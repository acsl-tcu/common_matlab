function R=CHECK_TRIGGER_NATIVE_UPGRADE_GATE(logger,agent)
% Disposable root-level EXPLICIT offline build + original-controller oracle.
% NEVER call during preflight/arming/takeoff/flight. It modifies ONLY the
% rebuilt MEX binary, if invoked by the user after a completed Flight.
% The already-saved old binary/source must be restorable from Git backup.
% Failure leaves the source pin FAIL-CLOSED and must not start a new Flight.
R=struct('status','FAIL_CLOSED_OPTIMIZED_NATIVE_AUDIT', ...
    'build_pass',false,'parity_pass',false, ...
    'pin_pass',false,'reason','','safe_to_commit',false);
try
    assert(nargin==2 && isobject(logger) && isobject(agent), ...
        'CHECK_TRIGGER_NATIVE_UPGRADE_GATE:Inputs', ...
        'Pass logger and agent from a completed, previously valid Flight.');
    folder=fileparts(which('TRIGGER_NATIVE_LOCAL_MEX'));
    assert(~isempty(folder), ...
        'CHECK_TRIGGER_NATIVE_UPGRADE_GATE:Path', ...
        'Add current trigger source folder to MATLAB path.');
    cpp=fullfile(folder,'TRIGGER_SYMBOLIC_NATIVE_CORE.cpp');
    native=fullfile(folder,['TRIGGER_SYMBOLIC_NATIVE_CORE.' mexext]);
    assert(isfile(cpp) && isfile(native), ...
        'CHECK_TRIGGER_NATIVE_UPGRADE_GATE:Sources', ...
        'Both original binary and new C++ source are required.');
    % Do not silently compare against an unrelated/older source tree.
    source=TRIGGER_NATIVE_MODEL_SOURCE_CHECK(false);
    assert(source.cpp_source_matches_verified && source.source_match, ...
        'CHECK_TRIGGER_NATIVE_UPGRADE_GATE:SourcePin', ...
        'Deployed optimized cpp hash or original model source mismatch.');
    assert(source.native_code_matches_verified || source.audit_pass, ...
        'CHECK_TRIGGER_NATIVE_UPGRADE_GATE:PreviousBinary', ...
        'Current binary is neither the known predecessor nor a pinned rebuild.');
    clear('TRIGGER_SYMBOLIC_NATIVE_CORE');
    clear mex
    mex('-R2018a','-O','-outdir',folder, ...
        '-output','TRIGGER_SYMBOLIC_NATIVE_CORE',cpp);
    rehash;
    R.build_pass=isfile(native);
    assert(R.build_pass, ...
        'CHECK_TRIGGER_NATIVE_UPGRADE_GATE:MissingMex', ...
        'Built production MEX not found.');
    A=CHECK_TRIGGER_NATIVE_MODEL_PARITY(logger,agent);
    R.parity_pass=isstruct(A) && isfield(A,'parity_pass') && ...
        isequal(A.parity_pass,true);
    assert(R.parity_pass, ...
        'CHECK_TRIGGER_NATIVE_UPGRADE_GATE:Parity', ...
        'Original controller/plant parity did not pass.');
    P=TRIGGER_NATIVE_SOURCE_PIN_CACHE('prepare');
    R.pin_pass=isstruct(P) && isfield(P,'passed') && ...
        isequal(P.passed,true);
    assert(R.pin_pass, ...
        'CHECK_TRIGGER_NATIVE_UPGRADE_GATE:Pin', ...
        'Fresh exact source + MEX SHA pin failed.');
    R.status='PASS_FRESH_ORIGINAL_MODEL_PARITY_AND_NATIVE_PIN__NOT_FLIGHT_SAFETY';
catch ME
    R.reason=[ME.identifier ' | ' ME.message];
end
save('TRIGGER_NATIVE_UPGRADE_RESULT.mat','R');
f=fopen('TRIGGER_NATIVE_UPGRADE_RESULT.txt','w');
if f>=0
    fprintf(f,'status=%s\nbuild=%d\nparity=%d\npin=%d\nreason=%s\n', ...
        R.status,R.build_pass,R.parity_pass,R.pin_pass,R.reason);
    fclose(f);
end
end
