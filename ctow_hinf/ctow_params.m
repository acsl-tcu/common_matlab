function P = ctow_params()
%CTOW_PARAMS  単機牽引（x軸, 6次チェーン）の共通パラメータと参照値
%   参照値は Python 版の解析（handoff_cooperative_transport.zip の analysis/）で計算したもの。
P.g        = 9.81;
P.dt       = 0.025;                 % 制御周期 [s]
P.tau_r    = 0.030;                 % FC 角速度ループの一次遅れ（公称）[s]
P.tau_list = [0.010 0.030 0.050];   % 評価に使う FC 遅れ [s]

% 比較用ゲイン（v = -K x, x = [p p' p'' p''' p'''' p''''']）
P.Q_lqr = diag([100 800 600 1000 1 1]);
P.K.G0 = [3162.2777 14831.6211 22132.3046 15162.9490 3153.3162 326.0470]; % 現行 LQR (R=1e-5)
P.K.G1 = [ 100.0000   476.9313   737.3171   536.3234  139.7111  19.4788]; % LQR R=1e-2（比較の基準）
P.K.G2 = [  35.6497   223.6648   530.0175   530.1459   93.6064  12.7857]; % 最適化静的ゲイン（25 ms 用）

% 参照値（dt = 25 ms、遅れ 1 サンプル。rho は tau_list の順）
P.ref.rho      = struct('G0',[2.9867 2.4168 2.1048], 'G1',[0.9908 0.9908 0.9908], 'G2',[0.9907 0.9907 0.9988]);
P.ref.zeta_min = struct('G1',0.0347, 'G2',0.0096);           % tau = 30 ms
P.ref.Twp_inf  = struct('G0',6.9961, 'G1',7.3703, 'G2',14.8607);
P.ref.Twth_inf = struct('G0',0.1387, 'G1',0.1406, 'G2',0.1434);
P.ref.minReGv  = struct('G0',-0.01533,'G1',-0.02582,'G2',-0.00545);

% 質量比 r = (想定担当質量)/(実際の有効質量) の不確かさ範囲
P.r_lo = 0.5; P.r_hi = 3.5;
P.r0 = (P.r_lo + P.r_hi)/2;
P.Wr = (P.r_hi - P.r_lo)/(P.r_hi + P.r_lo);
end
