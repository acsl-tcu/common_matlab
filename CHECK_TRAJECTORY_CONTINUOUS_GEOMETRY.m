function R=CHECK_TRAJECTORY_CONTINUOUS_GEOMETRY()
% Save test output in common_matlab root (never in the production folder).
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'reference','REPLANNING_SYSTEM');
addpath(fullfile(base,'TRAJECTORY_GENERATION'),fullfile(base,'OBSTACLE_INFORMATION'));
radius=struct('uav_m',0.02,'payload_m',0.02,'cable_m',0.005);
opt=struct('robust_tube_enabled',false,'max_subdivision_depth',3, ...
    'numerical_guard_m',1e-10);
% Near vertical/diagonal cable; a point in the AABB but far from cable.
U=repmat([0;0;0],1,24); L=repmat([sqrt(2);0;-sqrt(2)],1,24);
s=segment(U,L,0,3);
far=OBSTACLE_INFORMATION.define(21,'sphere',[sqrt(2) 0 0],0.05);
G=TRAJECTORY_CONTINUOUS_GEOMETRY_CERTIFICATE(s,far,radius,opt);
assert(G.certified && ~G.safe_to_commit && G.checks>0, ...
    'CHECK_TRAJECTORY:Diagonal','Stationary diagonal cable false alarm.');
% 12 different real primitive shapes, all away from the path; orientations
% are NOT axis-aligned for the ellipsoid, box, cylinder or other solids.
V=[0 0 0;1 0 0;0 1 0;0 0 1];
F=[1 3 2;1 2 4;1 4 3;2 3 4];
shapes={ ...
    OBSTACLE_INFORMATION.define(1,'sphere',[0 6 0],0.3), ...
    OBSTACLE_INFORMATION.define(2,'ellipsoid',[0 6 0],[0.5 1 2],'euler_deg',[20 40 50]), ...
    OBSTACLE_INFORMATION.define(3,'box',[0 6 0],[1 0.6 2],'euler_deg',[5 25 40]), ...
    OBSTACLE_INFORMATION.define(4,'cylinder',[0 6 0],[0.5 2],'euler_deg',[20 20 15]), ...
    OBSTACLE_INFORMATION.define(5,'capsule',[0 6 0],[0.3 1]), ...
    OBSTACLE_INFORMATION.define(6,'cone',[0 6 0],[0.5 2],'euler_deg',[10 20 30]), ...
    OBSTACLE_INFORMATION.define(7,'frustum',[0 6 0],[0.8 0.3 1]), ...
    OBSTACLE_INFORMATION.define(8,'pyramid',[0 6 0],[1 2]), ...
    OBSTACLE_INFORMATION.define(9,'regular_prism',[0 6 0],[6 0.7 1]), ...
    OBSTACLE_INFORMATION.define(10,'torus',[0 6 0],[1 0.2]), ...
    OBSTACLE_INFORMATION.define(11,'polygon_prism',[0 6 0], ...
        struct('outline',[-1 -1;1 -1;1 1;-1 1],'height',2)), ...
    OBSTACLE_INFORMATION.define(12,'polyhedron',[0 6 0], ...
        struct('vertices',V,'faces',F))};
all_shapes=[shapes{:}];
report=TRAJECTORY_CONTINUOUS_GEOMETRY_CERTIFICATE(s,all_shapes,radius,opt);
assert(report.certified&&numel(report.considered_obstacle_ids)==12, ...
    'CHECK_TRAJECTORY:AllShapes','Multiple arbitrary observed shapes failed.');
% Actual collision at time t=0 and whole period. UNKNOWN is required.
near=OBSTACLE_INFORMATION.define(22,'sphere',[0 0 0],0.1);
collision=TRAJECTORY_CONTINUOUS_GEOMETRY_CERTIFICATE(s,[far near],radius,opt);
assert(~collision.certified && ismember(22,collision.unresolved_obstacle_ids)&& ...
    ~collision.safe_to_commit, ...
    'CHECK_TRAJECTORY:Collision','Known collision was classified safe.');
% OFF vs ON uses externally supplied componentwise uncertainty radii.
center=OBSTACLE_INFORMATION.define(23,'sphere',[0.8 0 0],0.05);
s0=segment(repmat([0;0;0],1,2),repmat([0;0;-1],1,2),0,1);
nom=TRAJECTORY_CONTINUOUS_GEOMETRY_CERTIFICATE(s0,center,radius,opt);
assert(nom.certified,'CHECK_TRAJECTORY:Nominal','Nominal clearance expected.');
on=opt;on.robust_tube_enabled=true;
on.uncertainty_bounds_m=struct('uav_m',1,'payload_m',1,'cable_m',1);
robust=TRAJECTORY_CONTINUOUS_GEOMETRY_CERTIFICATE(s0,center,radius,on);
assert(~robust.certified && ...
    strcmp(robust.scope,'POLYNOMIAL_WITH_SUPPLIED_UNCERTAINTY_RADII'), ...
    'CHECK_TRAJECTORY:Tube','Uncertainty enabled without effect.');
% Continuous-time collision between endpoints, not detectable by a
% naive endpoint-only test. Quadratic apex at t=1 hits the sphere.
up=[-2 0 2;0 2 0;0 0 0];
lp=up-[zeros(2,3);ones(1,3)];
arc=segment(up,lp,0,2);
mid_obstacle=OBSTACLE_INFORMATION.define(24,'sphere',[0 1 0],0.05);
arc_test=TRAJECTORY_CONTINUOUS_GEOMETRY_CERTIFICATE(arc,mid_obstacle,radius,opt);
assert(~arc_test.certified && ismember(24,arc_test.unresolved_obstacle_ids), ...
    'CHECK_TRAJECTORY:Intersample','Interior collision was missed.');
% Kinematic convex-hull bound is continuous (not time sampled).
straight=repmat([0;0;0],1,24);
straight(1,:)=linspace(0,2,24);
ref=struct('t0_s',0,'duration_s',2,'control_points_m',straight);
limits=struct('derivative_norm_max',[2 1 1 1 1 1]);
kin=TRAJECTORY_KINEMATIC_CERTIFICATE(ref,limits,struct('max_subdivision_depth',2));
assert(kin.certified && abs(kin.upper_bounds(1)-1)<1e-10, ...
    'CHECK_TRAJECTORY:Kinematic','Nominal speed bound failed.');
limits.derivative_norm_max(1)=0.8;
kin_fast=TRAJECTORY_KINEMATIC_CERTIFICATE(ref,limits,struct('max_subdivision_depth',2));
assert(~kin_fast.certified, ...
    'CHECK_TRAJECTORY:Kinematic','Out-of-bound speed was accepted.');
% A pair of degree-23 pieces with identical endpoint 7-jets are C7;
% varying the free controls must alter the interior but not endpoint jets.
a=zeros(3,8);a(:,1)=[0;0;1];a(:,2)=[1;0;0];
b=a;b(:,1)=[2;0;1];b(:,2)=[1;0;0];
f=zeros(3,8);g=f;g(2,:)=0.4;
p=TRAJECTORY_C7_FREE_BERNSTEIN.build(0,2,a,b,f);
q=TRAJECTORY_C7_FREE_BERNSTEIN.build(0,2,a,b,g);
assert(isequal(size(p.control_points_m),[3 24]) && ...
    norm(TRAJECTORY_C7_FREE_BERNSTEIN.evaluate(p,0)-a,'fro')<1e-12 && ...
    norm(TRAJECTORY_C7_FREE_BERNSTEIN.evaluate(p,2)-b,'fro')<1e-6 && ...
    norm(TRAJECTORY_C7_FREE_BERNSTEIN.evaluate(q,0)-a,'fro')<1e-12 && ...
    norm(TRAJECTORY_C7_FREE_BERNSTEIN.evaluate(q,2)-b,'fro')<1e-6 && ...
    norm(TRAJECTORY_C7_FREE_BERNSTEIN.evaluate(q,1)- ...
         TRAJECTORY_C7_FREE_BERNSTEIN.evaluate(p,1),'fro')>1e-3, ...
    'CHECK_TRAJECTORY:FreeControls','Polynomial has no useful free controls.');
% Horizontal heading is C6 only if the whole-time speed never vanishes.
heading=TRAJECTORY_HEADING_CERTIFICATE(ref, ...
    struct('max_subdivision_depth',3,'numerical_guard_mps',1e-10));
assert(heading.certified,'CHECK_TRAJECTORY:Heading','Linear nonzero heading failed.');
stationary=ref;stationary.control_points_m=repmat([0;0;0],1,24);
heading_bad=TRAJECTORY_HEADING_CERTIFICATE(stationary, ...
    struct('max_subdivision_depth',2,'numerical_guard_mps',1e-10));
assert(~heading_bad.certified, ...
    'CHECK_TRAJECTORY:Heading','Stationary heading falsely certified.');
[ref28,yaw]=TRAJECTORY_C7_FREE_BERNSTEIN.reference28(p,0,0);
assert(all(isfinite(ref28))&&numel(ref28)==28&&numel(yaw)==7, ...
    'CHECK_TRAJECTORY:Reference28','HLC reference shape is wrong.');
% A new generator cannot falsely commit on a geometry-only certificate.
obj=TRAJECTORY_GENERATOR();
result=obj.certify_geometry(s0,far,radius,on);
assert(result.certified&&~result.safe_to_commit, ...
    'CHECK_TRAJECTORY:NotCommitted','Geometry falsely permitted commit.');
R=struct('status','PASS_CONTINUOUS_BERNSTEIN_GEOMETRY_12_SHAPES__DYNAMICS_NOT_CERTIFIED', ...
    'shape_count',12,'diagonal_clear',G.certified,'known_collision_rejected',~collision.certified, ...
    'robust_option_checked',~robust.certified,'intersample_collision_rejected',~arc_test.certified, ...
    'continuous_kinematics_checked',kin.certified, ...
    'heading_speed_certified',heading.certified, ...
    'degree23_free_controls',true, ...
    'HLC_connected',false,'full_dynamics_certified',false);
fid=fopen(fullfile(root,'TRAJECTORY_GEOMETRY_RESULT.txt'),'wt');
if fid>=0
    close_fid=onCleanup(@()fclose(fid)); %#ok<NASGU>
    fprintf(fid,'%s\n',R.status);
end
end
function s=segment(U,L,t0,T)
pu=struct('t0_s',t0,'duration_s',T,'control_points_m',U);
pl=struct('t0_s',t0,'duration_s',T,'control_points_m',L);
s=struct('uav',pu,'payload',pl);
end
