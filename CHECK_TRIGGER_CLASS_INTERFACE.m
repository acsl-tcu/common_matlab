function S=CHECK_TRIGGER_CLASS_INTERFACE(replanner_instance)
% Separate status/API audit, with no belief that a trace is a safety proof.
S=struct('status','NOT_COMPLETED_CLASS_INTERFACE','reason','', ...
    'active_core_file','','has_shadow_method',false, ...
    'has_status_method',false,'status_call_ok',false);
try
    assert(isobject(replanner_instance) && ...
        isprop(replanner_instance,'trigger_core') && ...
        ~isempty(replanner_instance.trigger_core), ...
        'CHECK_TRIGGER_CLASS_INTERFACE:Replanner');
    core=replanner_instance.trigger_core;
    S.active_core_file=which('FUTURE_COLLISION_TRIGGER');
    S.has_shadow_method=ismethod(core,'prepare_shadow_observed_static');
    S.has_status_method=ismethod(core,'shadow_observation_preparation_status');
    assert(S.has_shadow_method&&S.has_status_method, ...
        'CHECK_TRIGGER_CLASS_INTERFACE:MissingMethods', ...
        'An older or mismatched FUTURE_COLLISION_TRIGGER is active.');
    X=replanner_instance.get_status();
    assert(isstruct(X)&&isfield(X,'phase_shadow_geometry') && ...
        isstruct(X.phase_shadow_geometry)&& ...
        isfield(X.phase_shadow_geometry,'status'), ...
        'CHECK_TRIGGER_CLASS_INTERFACE:Status');
    S.status='PASS_CLASS_API_MATCH__NOT_FLIGHT_SAFETY';
    S.status_call_ok=true;
catch ME
    S.reason=[ME.identifier ' | ' ME.message];
end
fid=fopen('TRIGGER_CLASS_INTERFACE_RESULT.txt','w');
if fid>=0
    fprintf(fid,'status=%s\nreason=%s\nactive_core_file=%s\n', ...
        S.status,S.reason,S.active_core_file);
    fprintf(fid,'has_shadow=%d\nhas_status=%d\nstatus_call_ok=%d\n', ...
        S.has_shadow_method,S.has_status_method,S.status_call_ok);
    fclose(fid);
end
end
