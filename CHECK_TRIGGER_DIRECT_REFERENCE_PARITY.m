function D = CHECK_TRIGGER_DIRECT_REFERENCE_PARITY(agent)
% Post-Flight READ-ONLY source equivalence test. Never calls HLC, plant,
% sensor.observe or replanner.update. All future reference evaluations are
% performed only AFTER Flight for diagnostics, never before arming.
% Direct source path is used only if preflight purity audit permits it.
assert(isobject(agent)&&isscalar(agent)&&isprop(agent,'reference')&& ...
    isprop(agent,'parameter')&&isprop(agent,'plant'), ...
    'CHECK_TRIGGER_DIRECT_REFERENCE_PARITY:Agent', ...
    'Pass the actual completed Flight agent.');
nominal=agent.reference.timevarying;
assert(isa(nominal,'TIME_VARYING_REFERENCE') && ...
    isa(nominal.func,'function_handle') && isscalar(nominal.t) && ...
    isfinite(nominal.t), 'CHECK_TRIGGER_DIRECT_REFERENCE_PARITY:Source', ...
    'Completed Flight nominal source and epoch required.');
L=double(agent.parameter.get("cableL"));
dt=double(agent.plant.dt);
assert(isscalar(L)&&isfinite(L)&&L>0 && ...
    isscalar(dt)&&isfinite(dt)&&dt>0, ...
    'CHECK_TRIGGER_DIRECT_REFERENCE_PARITY:Runtime', ...
    'Actual physical parameters required.');
% The 4-s horizon here is a diagnostic only. No Flight state is modified.
N=ceil(4/dt);
query_times=double(nominal.t)+(0:N-1)*dt;
source_reference=@(tt) original_reference_semantics(nominal,tt,L);
original=zeros(28,N);
for k=1:N
    v=source_reference(query_times(k));
    assert(isnumeric(v)&&iscolumn(v)&&numel(v)>=4&&numel(v)<=28);
    original(1:numel(v),k)=v;
end
cache=TRIGGER_REFERENCE_WINDOW_CACHE();
audit=cache.audit_immutable_source(nominal.func);
[direct,report]=cache.evaluate(nominal,query_times,L, ...
    source_reference,source_reference(query_times(1)), ...
    'VERIFIED_F_PHASE_NOMINAL_Z_MINUS_CABLEL');
S=cache.get_status();
% isequal catches exact value differences including signed zero;
% the source function is evaluated on precisely the original time grid.
exact=isequal(original,direct);
D=struct('status','NOT_PASSED','matched',exact, ...
    'source_eligible',logical(audit.eligible), ...
    'direct_evaluations',S.direct_source_evaluations, ...
    'fallback_evaluations',S.direct_source_rejected, ...
    'checked_columns',N, ...
    'max_abs_error',max(abs(original(:)-direct(:))), ...
    'cache_report',report, ...
    'continuous_time_safe',false);
if exact && D.source_eligible && D.direct_evaluations>0
    D.status='PASS_DIRECT_REFERENCE_BITWISE_EQUIVALENCE__NOMINAL_ONLY';
elseif exact
    D.status='PASS_REFERENCE_VALUES__DIRECT_PATH_NOT_USED';
else
    D.status='FAIL_DIRECT_REFERENCE_DIFFERENCE__DO_NOT_USE';
end
folder=fileparts(mfilename('fullpath'));
save(fullfile(folder,'TRIGGER_DIRECT_REFERENCE_PARITY.mat'),'D');
fid=fopen(fullfile(folder,'TRIGGER_DIRECT_REFERENCE_PARITY.txt'),'wt');
if fid>=0
    cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
    fprintf(fid,'status=%s\nmatched=%d\nsource_eligible=%d\n', ...
        D.status,D.matched,D.source_eligible);
    fprintf(fid,'direct_evaluations=%d fallback_evaluations=%d checked_columns=%d\n', ...
        D.direct_evaluations,D.fallback_evaluations,D.checked_columns);
    fprintf(fid,'max_abs_error=%.17g\n',D.max_abs_error);
end
fprintf('[DIRECT REFERENCE] %s | checked=%d | max error=%.3g\n', ...
    D.status,D.checked_columns,D.max_abs_error);
end

function x=original_reference_semantics(nominal,absolute_time,L)
x=nominal.func(double(absolute_time)-double(nominal.t));
assert(isnumeric(x)&&isreal(x)&&iscolumn(x)&&numel(x)>=4 && ...
    numel(x)<=28&&all(isfinite(x)), ...
    'CHECK_TRIGGER_DIRECT_REFERENCE_PARITY:InvalidJet', ...
    'The active nominal func returned invalid jets.');
x=double(x);
x(3)=x(3)-double(L);
end
