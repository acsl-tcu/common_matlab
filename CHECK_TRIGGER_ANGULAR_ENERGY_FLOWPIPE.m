function A=CHECK_TRIGGER_ANGULAR_ENERGY_FLOWPIPE()
% Source-anchored rigid-body energy proof, independent of Picard wrapping.
% This audit verifies analytic exact solutions, nested bounds, adverse
% torques/inertias, source and time refusal, and existing triangular tests.
% It does NOT declare an actual Flight clearance certificate.
A=struct('status','FAIL_ANGULAR_ENERGY_SOURCE_CHAIN', ...
    'cases',0,'failures',0,'analytic_cases',0, ...
    'stress_cases',0,'source_pin',false, ...
    'triangular_handoff_cases',0,'signed_time_endpoint_cases',0,'reason','', ...
    'safe_to_commit',false);
try
    S=TRIGGER_TAUT_SOURCE_INVARIANTS();
    assert(S.source_bound_invariance && S.algebra_exact, ...
        'CHECK_TRIGGER_ANGULAR_ENERGY_FLOWPIPE:Source');
    A.source_pin=true;A.cases=A.cases+1;
    p=zeros(21,1);
    p(1)=1.2;p(6:8)=[0.05;0.08;0.05];
    p(9)=9.80665;p(20)=0.14;p(21)=2;
    x=zeros(24,1);x(15)=-2;x(19:21)=[0;0;-1];
    for k=1:24
        xx=x;
        w0=(-1)^k*0.015*k;
        xx(11)=w0;
        my=(-1)^k*(0.002+0.0007*k);
        u=[9;0;my;0];
        h=0.02+0.001*k;
        hl=0.3*h;
        D=fixture(xx,u,p,h,hl);
        E=TRIGGER_ORIGINAL_ANGULAR_ENERGY_TUBE(D);
        assert(E.energy_all_time_proven && E.source_pinned && ...
            E.constant_inertia_source_pinned && ~E.safe_to_commit && ...
            ~E.conditional_strict_inclusion && ...
            all(isfinite([E.tube_lower;E.tube_upper; ...
                E.endpoint_lower;E.endpoint_upper])) && ...
            all(E.tube_lower<=E.tube_upper) && ...
            all(E.endpoint_lower<=E.endpoint_upper), ...
            'CHECK_TRIGGER_ANGULAR_ENERGY_FLOWPIPE:Energy', ...
            'Analytic case %d: %s',k,E.reason);
        % Because Jx=Jz and w1=w3=Mx=Mz=0, original Euler ODE has
        % exact omega(t)=[0;w0+My*t/Jy;0] for all t.
        times=[0 hl (h+hl)/2 h];
        for j=1:numel(times)
            wt=w0+my*times(j)/p(7);
            tol=128*eps(max(1,abs(wt)));
            assert(E.tube_lower(2)<=wt+tol && ...
                E.tube_upper(2)>=wt-tol && ...
                E.tube_lower(1)<=tol && E.tube_upper(1)>=-tol && ...
                E.tube_lower(3)<=tol && E.tube_upper(3)>=-tol, ...
                'CHECK_TRIGGER_ANGULAR_ENERGY_FLOWPIPE:AnalyticTime');
            if times(j)>=hl
                assert(E.endpoint_lower(2)<=wt+tol && ...
                    E.endpoint_upper(2)>=wt-tol, ...
                    'CHECK_TRIGGER_ANGULAR_ENERGY_FLOWPIPE:AnalyticEnd');
            end
        end
        A.cases=A.cases+1;A.analytic_cases=A.analytic_cases+1;
    end
    % Huge torque / tiny inertia -> energy still provides a finite
    % all-time angular guarantee, even when strict 3D Picard may fail.
    for k=1:32
        pp=p;pp(6:8)=([0.005;0.009;0.013])*(1+0.05*k);
        xx=x;xx(10:12)=[0.13*k;-0.07*k;0.04*k];
        u=[15;0.03*sin(k);0.04*cos(k);0.02*sin(k/2)];
        D=fixture(xx,u,pp,0.002*k,0.001*k);
        E=TRIGGER_ORIGINAL_ANGULAR_ENERGY_TUBE(D);
        assert(E.energy_all_time_proven && ~E.safe_to_commit && ...
            all(E.tube_lower<=xx(10:12)) && ...
            all(E.tube_upper>=xx(10:12)) && ...
            E.energy_norm_upper>=0 && ...
            E.torque_energy_rate_upper>=0, ...
            'CHECK_TRIGGER_ANGULAR_ENERGY_FLOWPIPE:Stress', ...
            'Case %d: %s',k,E.reason);
        A.cases=A.cases+1;A.stress_cases=A.stress_cases+1;
    end
    % A time-varying/incompletely specified inertia has an uncancelled
    % dJ/dt energy term, and must NEVER receive the constant-J theorem.
    D=fixture(x,[10;0;0;0],p,0.025,0.025);
    D.param_upper(7)=p(7)+0.001;
    E=TRIGGER_ORIGINAL_ANGULAR_ENERGY_TUBE(D);
    assert(~E.energy_all_time_proven && ~E.safe_to_commit, ...
        'CHECK_TRIGGER_ANGULAR_ENERGY_FLOWPIPE:VariableInertiaAccepted');
    A.cases=A.cases+1;
    D=fixture(x,[10;0;0;0],p,0.025,0.025);
    D.param_lower(6)=0;
    E=TRIGGER_ORIGINAL_ANGULAR_ENERGY_TUBE(D);
    assert(~E.energy_all_time_proven && ~E.safe_to_commit, ...
        'CHECK_TRIGGER_ANGULAR_ENERGY_FLOWPIPE:ZeroInertiaAccepted');
    A.cases=A.cases+1;
    D=fixture(x,[10;0;0;0],p,0.025,0.04);
    E=TRIGGER_ORIGINAL_ANGULAR_ENERGY_TUBE(D);
    assert(~E.energy_all_time_proven && ~E.safe_to_commit, ...
        'CHECK_TRIGGER_ANGULAR_ENERGY_FLOWPIPE:TimeAccepted');
    A.cases=A.cases+1;
    % Regression for a REAL mathematical bug: the original full 24D
    % Picard step previously used [h,h] even when binary64 time-difference
    % was only in [h_lower_s,h].  A negative velocity loses the upper
    % endpoint unless the lower duration is propagated.
    xx=x;xx(7)=-2;xx(1)=0;
    D=fixture(xx,[10;0;0;0],p,1e-4,0.5e-4);
    D.tube_lower=xx-0.1;D.tube_upper=xx+0.1;
    D.tube_lower(5)=-0.1;D.tube_upper(5)=0.1;
    C=TRIGGER_ORIGINAL_PLANT_PICARD_STEP(D);
    assert(isfield(C,'rhs') && C.rhs.outward_elementary_operations && ...
        isfinite(C.endpoint_lower(1)) && isfinite(C.endpoint_upper(1)) && ...
        C.endpoint_lower(1)<=-2*D.h_s+1e-12 && ...
        C.endpoint_upper(1)>=-2*D.h_lower_s-1e-12, ...
        'CHECK_TRIGGER_ANGULAR_ENERGY_FLOWPIPE:SignedPhysicalTime', ...
        '24D endpoint must cover the signed derivative at both times.');
    A.cases=A.cases+1;A.signed_time_endpoint_cases=A.signed_time_endpoint_cases+1;
    % Existing combined 3D+21D proof must remain fail-closed.  No need
    % to force heavy full Flight here: this is a small algebraic regression.
    D=fixture(x,[10;0;0.01;0],p,1e-6,0.9e-6);
    T=TRIGGER_ORIGINAL_PLANT_TRIANGULAR_PICARD(D);
    assert(T.success && ~T.safe_to_commit && ...
        ~isempty(T.angular_method) && ...
        all(isfinite(T.endpoint_lower)) && ...
        all(isfinite(T.endpoint_upper)) && ...
        all(T.endpoint_lower<=T.endpoint_upper), ...
        'CHECK_TRIGGER_ANGULAR_ENERGY_FLOWPIPE:Combined',T.reason);
    A.triangular_handoff_cases=A.triangular_handoff_cases+1;
    A.cases=A.cases+1;
    A.status='PASS_SOURCE_PINNED_EULER_ENERGY_AND_21D_HANDOFF__NOT_FLIGHT_SAFE';
    A.reason=['Original Euler inertia-energy cancellation provides an ' ...
        'independent all-time 3D enclosure; remaining 21-state Picard, ' ...
        'taut tension and true numerical model retain separate obligations.'];
catch ME
    A.failures=1;
    A.reason=[ME.identifier ' | ' ME.message];
end
try
    save('TRIGGER_ANGULAR_ENERGY_FLOWPIPE_RESULT.mat','A');
    fid=fopen('TRIGGER_ANGULAR_ENERGY_FLOWPIPE_RESULT.txt','w');
    if fid>0
        fprintf(fid,'%s\ncases=%d failures=%d analytic=%d stress=%d handoff=%d signed_time=%d\n%s\n', ...
            A.status,A.cases,A.failures,A.analytic_cases,A.stress_cases, ...
            A.triangular_handoff_cases,A.signed_time_endpoint_cases,A.reason);
        fclose(fid);
    end
catch
end
end

function D=fixture(x,u,p,h,hl)
D=struct('x0_lower',x,'x0_upper',x, ...
    'u_lower',u,'u_upper',u, ...
    'param_lower',p,'param_upper',p, ...
    'h_s',h,'h_lower_s',hl);
end
