function R=CHECK_TRIGGER_TYPED_PREPARED_CANDIDATE()
% Disposable common_matlab/ CHECK, no preflight scan, no future truth.
R=struct('status','CANDIDATE_NOT_VERIFIED','reason','', ...
    'typed_empty_schema_present',false,'original_sensor_guard_present',false, ...
    'safe_to_commit',false);
try
    p=which('REPLANNING_SYSTEM');
    assert(~isempty(p),'CHECK_TRIGGER_TYPED_PREPARED_CANDIDATE:Missing', ...
        'REPLANNING_SYSTEM.m missing.');
    s=fileread(p);
    R.typed_empty_schema_present=contains(s, ...
        'obj.sensor.observed_prepared_only(zeros(1,0))');
    R.original_sensor_guard_present=contains(s, ...
        'newly_learned=memory_result.newly_acquired_ids') && ...
        contains(s,'obj.sensor.observed_prepared_only(newly_learned)');
    assert(R.typed_empty_schema_present && R.original_sensor_guard_present, ...
        'CHECK_TRIGGER_TYPED_PREPARED_CANDIDATE:Source', ...
        'Typed empty schema or true-observation-only guard is missing.');
    R.status='PASS_TYPED_EMPTY_SOURCE_GUARD__NOT_FLIGHT_SAFETY';
catch ME
    R.reason=[ME.identifier ' | ' ME.message];
end
fprintf('%s\n',R.status);
end
