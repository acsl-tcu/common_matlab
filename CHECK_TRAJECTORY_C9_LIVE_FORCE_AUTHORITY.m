function R=CHECK_TRAJECTORY_C9_LIVE_FORCE_AUTHORITY()
% Source-referenced HLC 4-input limits and time-varying EKF mass contract.
% Does not run Flight or certify actual HLC tracking. No test-specific bound
% is injected into the production class. The lightweight agent below is an
% explicit fixture for state transitions; only the source limits are LIVE.
root=fileparts(mfilename('fullpath'));
assert(isfile(fullfile(root,'run_flight_headless.m')), ...
    'CHECK_C9_LIVE_FORCE:Root','CHECK must be in common_matlab.');
addpath(root,'-begin');
addpath(fullfile(root,'controller'),'-begin');
addpath(fullfile(root,'model'),'-begin');
addpath(fullfile(root,'reference','REPLANNING_SYSTEM', ...
    'TRAJECTORY_GENERATION'),'-begin');
R=struct('status','FAIL_NOT_RUN','source_file','', ...
    'hlc_limits_N',[NaN NaN], ...
    'hlc_input_lower',[NaN;NaN;NaN;NaN], ...
    'hlc_input_upper',[NaN;NaN;NaN;NaN], ...
    'real_source_four_channels',false, ...
    'source_changed_clamp_reflected',false, ...
    'source_wrong_channel_rejected',false, ...
    'first_mass_kg',NaN,'second_mass_kg',NaN, ...
    'fresh_mass_updated',false,'stale_mass_rejected',false, ...
    'mass_change_invalidates_certificate',false, ...
    'inertia_change_invalidates_certificate',false, ...
    'changed_HLC_gains_rejected',false, ...
    'changed_HLC_source_path_rejected',false, ...
    'flight_only',false,'certificate_headroom_checked',false, ...
    'reversed_certificate_rejected',false, ...
    'safe_to_commit',false,'only_fixture_states_used',true, ...
    'actual_flight_controller_tracking_certified',false);
try
    [lo,hi,f]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    [limits,ff]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_limits();
    R.source_file=f;
    R.hlc_limits_N=limits;
    R.hlc_input_lower=lo;
    R.hlc_input_upper=hi;
    R.real_source_four_channels=strcmp(f,ff)&& ...
        isequal(limits,[lo(1) hi(1)])&& ...
        all(lo<hi)&&lo(1)>=0&&isequal(size(lo),[4 1]);
    src=fileread(f);
    % This synthetic source text is NOT the authority used by bind().
    % Verify that changed numeric limits are parsed, not cached as 0..20.
    synthetic=['obj.result.input = [' ...
        'max(1,min(17,tmp(1)));' ...
        'max(-0.7,min(0.8,tmp(2)));' ...
        'max(-0.5,min(0.9,tmp(3)));' ...
        'max(-0.2,min(0.4,tmp(4)))];'];
    [flo,fhi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY. ...
        parse_input_limits_source(synthetic);
    R.source_changed_clamp_reflected= ...
        isequal(flo,[1;-0.7;-0.5;-0.2])&& ...
        isequal(fhi,[17;0.8;0.9;0.4]);
    try
        TRAJECTORY_C9_HLC_FORCE_AUTHORITY.parse_input_limits_source( ...
            strrep(synthetic,'tmp(3)','tmp(4)'));
    catch
        R.source_wrong_channel_rejected=true;
    end
    assert(contains(src,'classdef HLC_SUSPENDED_LOAD')&& ...
        R.real_source_four_channels&&R.source_changed_clamp_reflected&& ...
        R.source_wrong_channel_rejected, ...
        'CHECK_C9_LIVE_FORCE:Source', ...
        'The real controller 4-input source contract was not verified.');
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    P.set("loadmass",0.14);
    gains=struct('dt',0.025,'F1',zeros(1,2), ...
        'F2',zeros(1,6),'F3',zeros(1,6),'F4',zeros(1,2));
    hc=HLC_SUSPENDED_LOAD([],gains);
    agent=struct('cha','f','controller',struct('hlc_suspended',hc), ...
        'parameter',P,'estimator',struct('result',struct( ...
        'state',struct('mL',0.14))));
    time=struct('t',5,'dt',0.025);
    ext=struct('gravity_world_mps2',[0;0;-double(P.get("gravity"))], ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0);
    B=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.bind(agent,ext);
    a=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.current(B,agent,time);
    assert(a.valid && isequal(a.authority.thrust_limits_N,limits)&& ...
        isequal(a.authority.input_limits.lower,lo)&& ...
        isequal(a.authority.input_limits.upper,hi)&& ...
        isequal(a.authority.torque_limits_Nm,[lo(2:4) hi(2:4)]), ...
        'CHECK_C9_LIVE_FORCE:First', ...
        'First captured authority differs from actual source.');
    R.first_mass_kg=a.estimated_payload_mass_kg;
    time.t=5.025;
    agent.estimator.result.state.mL=0.19;
    P.set("loadmass",0.19);
    b=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.current(B,agent,time);
    R.second_mass_kg=b.estimated_payload_mass_kg;
    R.fresh_mass_updated=b.valid&& ...
        b.authority.payload_mass_kg==0.19&& ...
        a.authority.payload_mass_kg==0.14;
    R.mass_change_invalidates_certificate= ...
        ~TRAJECTORY_C9_HLC_FORCE_AUTHORITY.same_force_authority(a,b);
    % Live parameter inertia change must invalidate even if mL is same.
    old_jx=double(P.get("jx"));
    P.set("jx",old_jx*1.01);
    c=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.current(B,agent,time);
    R.inertia_change_invalidates_certificate=c.valid&& ...
        ~TRAJECTORY_C9_HLC_FORCE_AUTHORITY.same_force_authority(b,c);
    P.set("jx",old_jx);
    time.t=5.05;
    agent.estimator.result.state.mL=0.21;
    d=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.current(B,agent,time);
    R.stale_mass_rejected=~d.valid&& ...
        strcmp(d.status,'UNKNOWN_EKF_HLC_MASS_MISMATCH');
    agent.estimator.result.state.mL=0.19;
    hc.param.F2(1)=1;
    e=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.current(B,agent,time);
    R.changed_HLC_gains_rejected=~e.valid&& ...
        strcmp(e.status,'UNKNOWN_HLC_GAINS_CHANGED');
    hc.param.F2(1)=0;
    old_source=B.source_file;
    B.source_file=[old_source '.unknown'];
    e2=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.current(B,agent,time);
    R.changed_HLC_source_path_rejected=~e2.valid&& ...
        strcmp(e2.status,'UNKNOWN_HLC_SOURCE_BINDING_CHANGED');
    B.source_file=old_source;
    agent.cha='t';
    none=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.current(B,agent,time);
    R.flight_only=~none.valid&&strcmp(none.status,'UNKNOWN_NOT_FLIGHT');
    quarter_span=(limits(2)-limits(1))/4;
    C=struct('certified_continuous_thrust',true, ...
        'thrust_lower_bound_N',limits(1)+quarter_span, ...
        'thrust_upper_bound_N',limits(2)-quarter_span);
    H=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.certified_headroom(C, ...
        a.authority);
    R.certificate_headroom_checked=H.certified&& ...
        abs(H.minimum_headroom_N-quarter_span)<= ...
            32*eps(max(1,abs(quarter_span)));
    C.thrust_lower_bound_N=limits(2);
    C.thrust_upper_bound_N=limits(1);
    Hbad=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.certified_headroom(C, ...
        a.authority);
    R.reversed_certificate_rejected=~Hbad.certified;
    assert(R.fresh_mass_updated&&R.mass_change_invalidates_certificate&& ...
        R.inertia_change_invalidates_certificate&& ...
        R.stale_mass_rejected&&R.changed_HLC_gains_rejected&& ...
        R.changed_HLC_source_path_rejected&&R.flight_only&& ...
        R.certificate_headroom_checked&&R.reversed_certificate_rejected, ...
        'CHECK_C9_LIVE_FORCE:Failed', ...
        'Per-flight-tick source/physics invalidation audit failed.');
    R.status= ...
      'PASS_REAL_HLC_FOUR_ACTUATOR_LIMITS_AND_CURRENT_EKF_MASS__NO_HLC_COMMIT';
catch ME
    R.status='FAIL_C9_LIVE_FORCE_AUTHORITY';
    R.error_identifier=ME.identifier;
    R.error_message=ME.message;
end
save(fullfile(root,'TRAJECTORY_C9_LIVE_FORCE_AUTHORITY_RESULT.mat'),'R');
fid=fopen(fullfile(root,'TRAJECTORY_C9_LIVE_FORCE_AUTHORITY_RESULT.txt'),'wt');
if fid>0
    fprintf(fid,'status=%s\nsource=%s\n',R.status,R.source_file);
    fprintf(fid,'hlc_input_lower=%s\nhlc_input_upper=%s\n', ...
        mat2str(R.hlc_input_lower'),mat2str(R.hlc_input_upper'));
    fprintf(fid,'mass_first=%.12g\nmass_second=%.12g\n', ...
        R.first_mass_kg,R.second_mass_kg);
    fprintf(fid,'mass_updated=%d\nmismatch_rejected=%d\n', ...
        R.fresh_mass_updated,R.stale_mass_rejected);
    fprintf(fid,'inertia_invalidation=%d\ngains_rejection=%d\n', ...
        R.inertia_change_invalidates_certificate,R.changed_HLC_gains_rejected);
    fprintf(fid,'SOURCE_LIMITS_ARE_LIVE__TEST_STATES_ARE_FIXTURES=1\n');
    fprintf(fid,'REAL_HLC_TRACKING_CERTIFIED=0\n');
    if isfield(R,'error_identifier')
        fprintf(fid,'error_id=%s\nerror=%s\n', ...
            R.error_identifier,R.error_message);
    end
    fclose(fid);
end
end
