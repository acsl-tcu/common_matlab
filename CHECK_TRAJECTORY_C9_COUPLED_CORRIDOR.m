function R=CHECK_TRAJECTORY_C9_COUPLED_CORRIDOR()
% CHECK_TRAJECTORY_C9_COUPLED_CORRIDOR  Ideal-taut coupled C9 local corridor.
% Synthetic MATLAB regression ONLY. No Flight or HLC torque certificate.
% All test values below are synthetic, not production defaults.
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'reference','REPLANNING_SYSTEM');
addpath(fullfile(base,'TRAJECTORY_GENERATION'), ...
    fullfile(base,'OBSTACLE_INFORMATION'));
A=struct('cable_length_m',2,'uav_mass_kg',1.5, ...
    'payload_mass_kg',1,'gravity_world_mps2',[0;0;-9.80665], ...
    'thrust_limits_N',[0;100],'minimum_tension_N',0, ...
    'acceleration_guard_mps2',1e-10);
r=struct('uav_m',0.02,'payload_m',0.02,'cable_m',0.005);
opt=struct('robust_tube_enabled',false,'max_subdivision_depth',4, ...
    'max_node_count',63,'numerical_guard_m',1e-10);
copt=struct('min_separation_m',1e-3, ...
    'max_normal_iterations',48,'max_ray_iterations',38);
J=zeros(3,10);J(3,1)=-2;
H=TRAJECTORY_C9_FLAT_BERNSTEIN.build(0,1,J,J, ...
    repmat(J(:,1),1,4));
% Twelve different observed static shapes, including rotated ellipsoid,
% cylinder, prism, polygon and a nonconvex torus (conservative support).
V=[0 0 0;1 0 0;0 1 0;0 0 1];
F=[1 3 2;1 2 4;1 4 3;2 3 4];
shapes={ ...
    OBSTACLE_INFORMATION.define(1,'sphere',[0 6 0],0.3), ...
    OBSTACLE_INFORMATION.define(2,'ellipsoid',[0 6 0],[.5 1 2],'euler_deg',[20 40 50]), ...
    OBSTACLE_INFORMATION.define(3,'box',[0 6 0],[1 .6 2],'euler_deg',[5 25 40]), ...
    OBSTACLE_INFORMATION.define(4,'cylinder',[0 6 0],[.5 2],'euler_deg',[20 20 15]), ...
    OBSTACLE_INFORMATION.define(5,'capsule',[0 6 0],[.3 1]), ...
    OBSTACLE_INFORMATION.define(6,'cone',[0 6 0],[.5 2],'euler_deg',[10 20 30]), ...
    OBSTACLE_INFORMATION.define(7,'frustum',[0 6 0],[.8 .3 1]), ...
    OBSTACLE_INFORMATION.define(8,'pyramid',[0 6 0],[1 2]), ...
    OBSTACLE_INFORMATION.define(9,'regular_prism',[0 6 0],[6 .7 1]), ...
    OBSTACLE_INFORMATION.define(10,'torus',[0 6 0],[1 .2]), ...
    OBSTACLE_INFORMATION.define(11,'polygon_prism',[0 6 0], ...
        struct('outline',[-1 -1;1 -1;1 1;-1 1],'height',2)), ...
    OBSTACLE_INFORMATION.define(12,'polyhedron',[0 6 0], ...
        struct('vertices',V,'faces',F))};
near=OBSTACLE_INFORMATION.define(13,'sphere',[0.65 0 -1],0.06);
obs=[shapes{:},near];
G=TRAJECTORY_GENERATOR(struct('ROBUST_TUBE_ENABLED',false));
C=G.build_coupled_c9_corridor(H,obs,r,A,opt,copt);
assert(C.certified && numel(C.obstacle_ids)==13 && ...
    ~C.safe_to_commit && numel(C.leaves)>=1, ...
    'CHECK_C9_COUPLED:Build','Failed to construct valid ideal-taut corridor.');
target=H.control_points_m(:,11:14);
target(1,:)=1; % Deliberately toward observed obstacle; no bypass direction is prescribed.
Rray=G.refine_coupled_c9_corridor(C,target,obs,r,A,opt);
assert(Rray.candidate_available && ...
    Rray.certified_ideal_taut_geometry && ~Rray.safe_to_commit && ...
    isfinite(Rray.ray_fraction) && Rray.ray_fraction>0 && ...
    Rray.ray_fraction<1 && ...
    Rray.fullbody_certificate.certified && ...
    Rray.ray_evaluation_count>=2, ...
    'CHECK_C9_COUPLED:Ray', ...
    'Ray must progress strictly while preserving whole-time coupled safety.');
assert(isequal(Rray.piece.start_jets,H.start_jets) && ...
    isequal(Rray.piece.end_jets,H.end_jets), ...
    'CHECK_C9_COUPLED:C9','C9 endpoint connection must remain unchanged.');
for t=linspace(0,1,21)
    E=TRAJECTORY_TAUT_FLATNESS.evaluate(Rray.piece,t,A);
    assert(E.valid && E.tension_N>0 && ...
        abs(norm(E.uav_jets(:,1)-E.load_jets(:,1))-A.cable_length_m)<1e-10, ...
        'CHECK_C9_COUPLED:Taut','Physical taut model or cable length violated.');
end
% Goal already inside corridor returns alpha=1 and reproduces the guide.
same=G.refine_coupled_c9_corridor(C,H.control_points_m(:,11:14),obs,r,A,opt);
assert(same.candidate_available && same.ray_fraction==1, ...
    'CHECK_C9_COUPLED:Identity','An unchanged certified C9 must remain valid.');
% Do not reuse a safe corridor after observations or estimated mass change.
stale=obs;stale(end).id=99;
changed=G.refine_coupled_c9_corridor(C,target,stale,r,A,opt);
assert(~changed.candidate_available && ...
    strcmp(changed.status,'UNKNOWN_STALE_OBSTACLES_OR_PHYSICAL_AUTHORITY'), ...
    'CHECK_C9_COUPLED:Snapshot','A changed observed obstacle must invalidate corridor.');
A2=A;A2.payload_mass_kg=2;
changedmass=G.refine_coupled_c9_corridor(C,target,obs,r,A2,opt);
assert(~changedmass.candidate_available, ...
    'CHECK_C9_COUPLED:Mass','Live mass change must invalidate corridor.');
% Robust-mode bounds must be supplied and must alter the certificate.
on=opt;on.robust_tube_enabled=true;
on.uncertainty_bounds_m=struct('uav_m',0.01,'payload_m',0.01,'cable_m',0.01);
Gr=TRAJECTORY_GENERATOR(struct('ROBUST_TUBE_ENABLED',true));
Cr=Gr.build_coupled_c9_corridor(H,obs,r,A,on,copt);
assert(Cr.certified && Cr.safe_to_commit==false, ...
    'CHECK_C9_COUPLED:Tube','Robust ON should preserve explicit tubes and safety.');
% A cable-centre obstacle makes the nominal guide unsafe: never construct
% a certified corridor or claim a preapproved bypass.
blocked=OBSTACLE_INFORMATION.define(14,'sphere',[0 0 -1],0.08);
Cb=G.build_coupled_c9_corridor(H,blocked,r,A,opt,copt);
assert(~Cb.certified && ~Cb.safe_to_commit, ...
    'CHECK_C9_COUPLED:Collision','A colliding initial guide is not a safe seed.');
R=struct('status','PASS_COUPLED_C9_LOCAL_CORRIDOR_AND_RAY__HLC_NOT_CERTIFIED', ...
    'shape_count',12,'observed_count',numel(obs), ...
    'leaf_count',numel(C.leaves), ...
    'corridor_build_ms',C.elapsed_ms, ...
    'ray_refine_with_certificate_ms',Rray.elapsed_ms, ...
    'ray_fraction',Rray.ray_fraction, ...
    'ray_evaluation_count',Rray.ray_evaluation_count, ...
    'robust_tube_checked',Cr.certified, ...
    'stale_obstacle_rejected',~changed.candidate_available, ...
    'stale_mass_rejected',~changedmass.candidate_available, ...
    'unsafe_seed_rejected',~Cb.certified, ...
    'real_HLC_execution_certified',false,'safe_to_commit',false);
mat=fullfile(root,'TRAJECTORY_C9_COUPLED_CORRIDOR_RESULT.mat');
txt=fullfile(root,'TRAJECTORY_C9_COUPLED_CORRIDOR_RESULT.txt');
save(mat,'R');
fid=fopen(txt,'wt');
assert(fid>0,'CHECK_C9_COUPLED:Output','Cannot write audit result.');
fclose_cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',R.status);
fprintf(fid,'observed=%d shapes=%d leaves=%d\n', ...
    R.observed_count,R.shape_count,R.leaf_count);
fprintf(fid,'build_ms=%.6f ray_including_final_proof_ms=%.6f alpha=%.12g evaluations=%d\n', ...
    R.corridor_build_ms,R.ray_refine_with_certificate_ms, ...
    R.ray_fraction,R.ray_evaluation_count);
fprintf(fid,'HLC_ACTUATOR_TRACKING=NOT_CERTIFIED commit=FORBIDDEN\n');
clear fclose_cleanup
zip(fullfile(root,'TRAJECTORY_C9_COUPLED_CORRIDOR_RESULTS_FOR_CHATGPT.zip'), ...
    {'TRAJECTORY_C9_COUPLED_CORRIDOR_RESULT.mat', ...
     'TRAJECTORY_C9_COUPLED_CORRIDOR_RESULT.txt'},root);
delete(mat);delete(txt);
end
