function R=CHECK_TRAJECTORY_C9_TORQUE_BINOMIAL_AB()
% Development-only paired benchmark, same REAL HLC source limits.
% ON and OFF execute identical interval arithmetic and must produce the
% same all-time nominal torque result. Neither proves HLC tracking, mass
% evolution, numerical directed rounding, nor permits trajectory COMMIT.
% Files are saved under common_matlab regardless of current pwd.
root=fileparts(mfilename('fullpath'));
name='TRAJECTORY_C9_TORQUE_BINOMIAL_AB_RESULT';
R=struct('status','FAIL_C9_TORQUE_BINOMIAL_AB','stage','START', ...
 'error_identifier','','error_message','','error_stack',{{}}, ...
 'scene_names',{{'SMOOTH_NOMINAL','SPHERE_ELLIPSOID_CERTIFIED_GUIDE'}}, ...
 'status_fast',{{}},'status_baseline',{{}}, ...
 'proof_nodes_fast',NaN(1,2),'proof_nodes_baseline',NaN(1,2), ...
 'accepted_leaves_fast',NaN(1,2),'accepted_leaves_baseline',NaN(1,2), ...
 'detailed_nodes_fast',NaN(1,2),'detailed_nodes_baseline',NaN(1,2), ...
 'fast_norm_nodes_fast',NaN(1,2),'fast_norm_nodes_baseline',NaN(1,2), ...
 'all_torque_bounds_identical',false(1,2), ...
 'whole_result_status_identical',false(1,2), ...
 'median_ms_fast',NaN(1,2),'median_ms_baseline',NaN(1,2), ...
 'p95_ms_fast',NaN(1,2),'p95_ms_baseline',NaN(1,2), ...
 'max_ms_fast',NaN(1,2),'max_ms_baseline',NaN(1,2), ...
 'search_status','NOT_CALLED','search_elapsed_ms',NaN, ...
 'search_independent_proof_calls',NaN, ...
 'repetitions',7,'safe_to_commit',false, ...
 'scope','NOMINAL_RIGID_BODY_TORQUE_AB__NO_HLC_OR_ROUNDING_PROOF', ...
 'zip_path',fullfile(root,[name '_FOR_CHATGPT.zip']));
try
 R.stage='READ_AUTHORITY_AND_BUILD_MATCHING_C9_FIXTURES';
 addpath(fullfile(root,'controller'),fullfile(root,'model'),'-begin');
 addpath(fullfile(root,'reference','REPLANNING_SYSTEM', ...
     'TRAJECTORY_GENERATION'), ...
     fullfile(root,'reference','REPLANNING_SYSTEM', ...
     'OBSTACLE_INFORMATION'),'-begin');
 [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
 P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
 P.set("loadmass",0.14); % CHECK fixture only, not production mass
 d=double(P.get(["mass","jx","jy","jz","gravity","cableL","loadmass"]));
 d=d(:);lo=double(lo(:));hi=double(hi(:));
 assert(numel(d)==7&&all(isfinite(d))&&all(d>0)&& ...
    numel(lo)==4&&numel(hi)==4&&all(hi>lo), ...
    'CHECK_C9_TORQUE:Authority', ...
    'Cannot read current controller/plant source authority.');
 a=struct('uav_mass_kg',d(1),'payload_mass_kg',d(7), ...
   'cable_length_m',d(6),'uav_inertia_kgm2',d(2:4), ...
   'gravity_world_mps2',[0;0;-d(5)], ...
   'thrust_limits_N',[lo(1),hi(1)], ...
   'torque_limits_Nm',[lo(2:4),hi(2:4)], ...
   'minimum_tension_N',0,'acceleration_guard_mps2',0);
 topt=struct('max_subdivision_depth',8,'max_node_count',511, ...
    'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
    'torque_guard_Nm',zeros(3,1), ...
    'enable_fast_norm_sufficient_bound',true);
 J0=zeros(3,10);J1=zeros(3,10);
 J0(:,1)=[-2;0;3];J1(:,1)=[2;0;3];
 J0(1,2)=0.4;J1(1,2)=0.4;
 nominal=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,10,J0,J1, ...
   repmat([0;0;3],1,4));
 R.stage='CREATE_REAL_MULTIOBSTACLE_GUIDE_WITHOUT_TORQUE_GATE';
 theta=0.34;Q=[cos(theta) -sin(theta) 0; ...
                 sin(theta) cos(theta) 0;0 0 1];
 observed=[OBSTACLE_INFORMATION.define(21,'sphere',[0 0.1 3],0.2), ...
   OBSTACLE_INFORMATION.define(33,'ellipsoid',[0.6 -0.16 3], ...
   [0.32 0.19 0.4],'rotation',Q)];
 gopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
   'numerical_guard_m',0,'robust_tube_enabled',false, ...
   'trajectory_phase','f');
 fopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
   'force_guard_N',0);
 sopt=struct('probe_count',13,'max_outer_iterations',4, ...
   'max_projection_sweeps',100,'projection_tolerance_m',1e-8, ...
   'min_separation_m',1e-5, ...
   'lazy_initial_proof_on_violated_plane',false, ...
   'payload_hull_witness_policy','off', ...
   'embed_taut_bernstein_halfspaces',false, ...
   'accept_first_certified_minimum_qp',false, ...
   'enable_connected_group_topology',true, ...
   'enable_point_intersection_prefilter',true);
 req=struct('t0_s',8,'duration_s',10,'flight_interval_s',[8 30], ...
   'start_jets',J0,'end_jets',J1, ...
   'nominal_free',nominal.control_points_m(:,11:14), ...
   'observed',observed, ...
   'radii',struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1), ...
   'authority',a,'geometry_options',gopt, ...
   'force_options',fopt,'search_options',sopt);
 S=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(req);
 R.search_status=S.status;
 R.search_elapsed_ms=S.elapsed_ms;
 R.search_independent_proof_calls=S.independent_proof_calls;
 assert(S.candidate_available&&S.final_certificate.certified && ...
    ~S.safe_to_commit, 'CHECK_C9_TORQUE:Guide', ...
    ['Multishape C9 guide was not independently proved. ' S.status]);
 pieces={nominal,S.candidate_piece};
 R.stage='PAIR_OLD_NEW_IDENTICAL_MATH_AND_TIMING';
 R.status_fast=cell(1,2);R.status_baseline=cell(1,2);
 for j=1:2
    on=topt;on.use_precomputed_binomial=true;
    off=topt;off.use_precomputed_binomial=false;
    A=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL(pieces{j},a,on);
    B=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL(pieces{j},a,off);
    R.status_fast{j}=A.status;R.status_baseline{j}=B.status;
    R.proof_nodes_fast(j)=A.checked_nodes;
    R.proof_nodes_baseline(j)=B.checked_nodes;
    R.accepted_leaves_fast(j)=A.accepted_leaves;
    R.accepted_leaves_baseline(j)=B.accepted_leaves;
    R.detailed_nodes_fast(j)=A.detailed_interval_checked_nodes;
    R.detailed_nodes_baseline(j)=B.detailed_interval_checked_nodes;
    R.fast_norm_nodes_fast(j)=A.fast_norm_checked_nodes;
    R.fast_norm_nodes_baseline(j)=B.fast_norm_checked_nodes;
    R.all_torque_bounds_identical(j)=isequaln( ...
       A.torque_bounds_Nm,B.torque_bounds_Nm);
    R.whole_result_status_identical(j)=strcmp(A.status,B.status)&& ...
       isequal(A.conditional_nominal_all_time_torque_proven, ...
               B.conditional_nominal_all_time_torque_proven)&& ...
       isequal(A.checked_nodes,B.checked_nodes)&& ...
       isequal(A.accepted_leaves,B.accepted_leaves)&& ...
       isequal(A.fast_norm_accepted_leaves,B.fast_norm_accepted_leaves)&& ...
       isequal(A.detailed_interval_checked_nodes, ...
               B.detailed_interval_checked_nodes)&& ...
       isequaln(A.unresolved_interval_s,B.unresolved_interval_s)&& ...
       ~A.safe_to_commit&&~B.safe_to_commit;
    assert(R.all_torque_bounds_identical(j)&& ...
       R.whole_result_status_identical(j), ...
       'CHECK_C9_TORQUE:Parity', ...
       'Fast coefficients must have EXACT identical proof results.');
    tf=zeros(1,R.repetitions);tb=tf;
    for k=1:R.repetitions
       if mod(k,2)==1
          X=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL(pieces{j},a,on);
          Y=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL(pieces{j},a,off);
       else
          Y=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL(pieces{j},a,off);
          X=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL(pieces{j},a,on);
       end
       assert(strcmp(X.status,A.status)&&strcmp(Y.status,B.status)&& ...
           isequaln(X.torque_bounds_Nm,Y.torque_bounds_Nm), ...
           'CHECK_C9_TORQUE:TimingParity','Proof changed between runs.');
       tf(k)=X.elapsed_ms;tb(k)=Y.elapsed_ms;
    end
    R.median_ms_fast(j)=median(tf);
    R.median_ms_baseline(j)=median(tb);
    z=sort(tf);R.p95_ms_fast(j)=z(ceil(.95*numel(z)));
    z=sort(tb);R.p95_ms_baseline(j)=z(ceil(.95*numel(z)));
    R.max_ms_fast(j)=max(tf);R.max_ms_baseline(j)=max(tb);
 end
 R.status='PASS_C9_TORQUE_BINOMIAL_AB__HLC_UNCERTIFIED';
 R.stage='COMPLETE';
catch ME
 R.error_identifier=ME.identifier;
 R.error_message=ME.message;
 R.error_stack=arrayfun(@(e)sprintf('%s:%d',e.name,e.line), ...
    ME.stack,'UniformOutput',false);
end
save(fullfile(root,[name '.mat']),'R');
fid=fopen(fullfile(root,[name '.txt']),'w');
if fid>=0
 fprintf(fid,'status=%s\nstage=%s\nerror=%s | %s\n', ...
    R.status,R.stage,R.error_identifier,R.error_message);
 for j=1:numel(R.error_stack)
    fprintf(fid,'stack_%d=%s\n',j,R.error_stack{j});
 end
 fprintf(fid,'search_status=%s | search_ms=%.6f | proof_calls=%g\n', ...
    R.search_status,R.search_elapsed_ms,R.search_independent_proof_calls);
 for j=1:2
    if numel(R.status_fast)<j,break;end
    fprintf(fid,['scene=%s | fast=%s | baseline=%s | ', ...
       'bounds_identical=%d | proof_identical=%d | ', ...
       'nodes=%g,%g | detailed_nodes=%g,%g | ', ...
       'median_ms=%.6f,%.6f | p95_ms=%.6f,%.6f | max_ms=%.6f,%.6f\n'], ...
       R.scene_names{j},R.status_fast{j},R.status_baseline{j}, ...
       R.all_torque_bounds_identical(j),R.whole_result_status_identical(j), ...
       R.proof_nodes_fast(j),R.proof_nodes_baseline(j), ...
       R.detailed_nodes_fast(j),R.detailed_nodes_baseline(j), ...
       R.median_ms_fast(j),R.median_ms_baseline(j), ...
       R.p95_ms_fast(j),R.p95_ms_baseline(j), ...
       R.max_ms_fast(j),R.max_ms_baseline(j));
 end
 fclose(fid);
end
zip(R.zip_path,{[name '.mat'],[name '.txt']},root);
fprintf('[C9 TORQUE BINOMIAL] %s | %s\n',R.status,R.zip_path);
end
