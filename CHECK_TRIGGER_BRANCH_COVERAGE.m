function A=CHECK_TRIGGER_BRANCH_COVERAGE(replanner_instance)
% Disposable common_matlab/ diagnostic. Real Flight preflight status only.
A=struct('status','NOT_CHECKED','passed',false,'reason','', ...
    'direct_native_calls',0,'preflight_sensor_steps',0, ...
    'verified_appends',0,'outer_appends',0,'narrow_cases',0, ...
    'outer_authority_calls',0,'outer_authority_status','');
try
    S=replanner_instance.get_status();
    A.direct_native_calls=double(S.isolated_direct_native_calls);
    A.preflight_sensor_steps=double(S.isolated_sensor_event_prepare_steps);
    A.verified_appends=double(S.isolated_direct_native_verified_appends);
    A.outer_appends=double(S.isolated_direct_native_outer_appends);
    A.narrow_cases=double(S.isolated_near_geometry_cases);
    A.outer_authority_calls=double(S.isolated_outer_authority_calls);
    A.outer_authority_status=S.isolated_outer_authority_status;
    assert(strcmp(S.isolated_direct_native_status, ...
        'SYNTHETIC_DIRECT_NATIVE_ACQUIRE_APPEND_REUSE_PASS__NO_JIT_GUARANTEE'), ...
        'CHECK_TRIGGER_BRANCH_COVERAGE:Native', ...
        'The isolated native append path has not passed all 8 actual transitions.');
    assert(A.direct_native_calls==24 && ...
        A.preflight_sensor_steps==40 && ...
        A.verified_appends==8 && A.outer_appends==8 && ...
        A.narrow_cases==32 && ...
        A.outer_authority_calls==8 && ...
        strcmp(A.outer_authority_status, ...
            'SYNTHETIC_ACTUAL_AUTHORITY_CURRENT_AND_REFERENCE_PATH_PASS') && ...
        strcmp(S.isolated_near_geometry_status, ...
            'SYNTHETIC_NONZERO_SUPPORT_AND_DISTANCE_EXERCISED'), ...
        'CHECK_TRIGGER_BRANCH_COVERAGE:Counts', ...
        'Preflight expected 8 acquisition + 8 append + 8 reuse, and 40 sensor transitions.');
    A.passed=true;
    A.status='PASS_ISOLATED_EIGHT_REAL_APPEND_BRANCHES__NOT_JIT_GUARANTEE';
catch ME
    A.status='NOT_COMPLETED_ISOLATED_COVERAGE';
    A.reason=[ME.identifier ' | ' ME.message];
end
save('TRIGGER_BRANCH_COVERAGE_RESULT.mat','A');
f=fopen('TRIGGER_BRANCH_COVERAGE_RESULT.txt','w');
if f>=0
    fprintf(f,'status=%s\npassed=%d\nnative_calls=%d\nsensor_steps=%d\nverified_appends=%d\nouter_appends=%d\nnarrow_cases=%d\nouter_authority_calls=%d\nouter_authority_status=%s\nreason=%s\n', ...
        A.status,A.passed,A.direct_native_calls, ...
        A.preflight_sensor_steps,A.verified_appends, ...
        A.outer_appends,A.narrow_cases,A.outer_authority_calls, ...
        A.outer_authority_status,A.reason);
    fclose(f);
end
end
