function R=CHECK_TRAJECTORY_C9_QP_PROBE_ALGEBRA()
% CHECK_TRAJECTORY_C9_QP_PROBE_ALGEBRA
% One development-only A/B audit of the WHOLE simultaneous C9 pipeline.
% Only the local QP probe algebra toggles; the independent continuous-time
% geometry/tension/thrust, C7/yaw and nominal torque proofs are identical.
% Synthetic fixtures are NOT live EKF certification or an HLC commit.
root=fileparts(mfilename('fullpath'));
R=struct('status','FAIL_C9_QP_PROBE_ALGEBRA','stage','START', ...
    'error_identifier','','error_message','','error_stack',{{}}, ...
    'algebra_max_scaled_error',NaN,'algebra_test_count',0, ...
    'case_names',{{'sphere_collision','sphere_rotated_ellipsoid'}}, ...
    'status_fast',{{'NOT_RUN','NOT_RUN'}}, ...
    'status_baseline',{{'NOT_RUN','NOT_RUN'}}, ...
    'status_parity',false(1,2),'candidate_parity_max_abs_m',NaN(1,2), ...
    'proof_call_parity',false(1,2),'QP_plane_count_parity',false(1,2), ...
    'no_unsafe_commit',false, 'repetitions',8, ...
    'full_fast_median_ms',NaN(1,2),'full_baseline_median_ms',NaN(1,2), ...
    'full_fast_p95_ms',NaN(1,2),'full_baseline_p95_ms',NaN(1,2), ...
    'full_fast_max_ms',NaN(1,2),'full_baseline_max_ms',NaN(1,2), ...
    'QP_planes_fast_median_ms',NaN(1,2), ...
    'QP_planes_baseline_median_ms',NaN(1,2), ...
        'median_total_ratio_baseline_over_fast',NaN(1,2), ...
    'fast_total_trials_ms',NaN(2,8), ...
    'baseline_total_trials_ms',NaN(2,8), ...
    'fast_planes_trials_ms',NaN(2,8), ...
    'baseline_planes_trials_ms',NaN(2,8), ...
    'fast_proof_trials_ms',NaN(2,8), ...
    'baseline_proof_trials_ms',NaN(2,8), ...
    'fast_qp_trials_ms',NaN(2,8), ...
    'baseline_qp_trials_ms',NaN(2,8), ...
    'fast_heading_trials_ms',NaN(2,8), ...
    'baseline_heading_trials_ms',NaN(2,8), ...
    'fast_torque_trials_ms',NaN(2,8), ...
    'baseline_torque_trials_ms',NaN(2,8), ...
    'zip_path',fullfile(root,'TRAJECTORY_C9_QP_PROBE_ALGEBRA_RESULT_FOR_CHATGPT.zip'));
try
    R.stage='PATHS';
    addpath(fullfile(root,'controller'),'-begin');
    addpath(fullfile(root,'model'),'-begin');
    addpath(fullfile(root,'reference','REPLANNING_SYSTEM','TRAJECTORY_GENERATION'), ...
        fullfile(root,'reference','REPLANNING_SYSTEM','OBSTACLE_INFORMATION'),'-begin');
    assert(isfile(fullfile(root,'run_flight_headless.m')), ...
        'CHECK_C9_QP:Root','Run from common_matlab project root.');
    R.stage='ALGEBRA_IDENTITY_RANDOM_3D';
    % Exact real-arithmetic identity of the whitened 12D linearization:
    % (n*b'' + c*(n-q(q''n))*d'')/U = n*(b''/U)+c*(n-q(q''n))*(d''/U).
    % The CHECK does not change the random stream of the flight runtime.
    previous_rng=rng;
    cleanup_rng=onCleanup(@()rng(previous_rng)); %#ok<NASGU>
    rng(9061,'twister');
    maxerr=0;
    for k=1:1500
        U=triu(randn(4));
        U(1:5:end)=U(1:5:end)+5;
        q=randn(3,1);q=q/norm(q);
        n=randn(3,1);n=n/norm(n);
        fb=randn(4,1);d2b=randn(4,1);
        c=randn(1);
        r=n-q*(q.'*n);
        baseline=reshape((n*fb.'+c*r*d2b.')/U,12,1);
        fast=reshape(n*(fb.'/U)+c*r*(d2b.'/U),12,1);
        maxerr=max(maxerr,max(abs(baseline-fast))/max(1,max(abs(baseline))));
    end
    R.algebra_test_count=1500;
    R.algebra_max_scaled_error=maxerr;
    assert(maxerr<2e-12,'CHECK_C9_QP:AlgebraParity', ...
        'Whitened row assembly is not algebraically equivalent.');
    R.stage='READ_ONE_FLIGHT_PARAMETER_FIXTURE';
    [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    P.set("loadmass",0.14); % CHECK fixture only; never Flight hardcode
    d=double(P.get(["mass","jx","jy","jz", ...
        "gravity","cableL","loadmass"]));
    d=d(:);lo=lo(:);hi=hi(:);
    assert(numel(d)==7&&all(isfinite(d))&&all(d>0)&& ...
        numel(lo)==4&&numel(hi)==4,'CHECK_C9_QP:Authority', ...
        'Read the active model and HLC before constructing the fixture.');
    A=struct('uav_mass_kg',d(1),'payload_mass_kg',d(7), ...
        'cable_length_m',d(6),'uav_inertia_kgm2',d(2:4), ...
        'gravity_world_mps2',[0;0;-d(5)], ...
        'thrust_limits_N',[lo(1),hi(1)], ...
        'torque_limits_Nm',[lo(2:4),hi(2:4)], ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0);
    gopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'numerical_guard_m',0,'robust_tube_enabled',false, ...
        'trajectory_phase','f');
    fopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'force_guard_N',0);
    sopt=struct('probe_count',13,'max_outer_iterations',4, ...
        'max_projection_sweeps',100, ...
        'projection_tolerance_m',1e-8,'min_separation_m',1e-5);
    hopt=struct('max_subdivision_depth',8,'max_node_count',511, ...
        'horizontal_velocity_guard_mps',0,'w_guard_mps2',0, ...
        'payload_jet_tolerance',1e-7*ones(3,10), ...
        'uav_jet_tolerance',1e-7*ones(3,8), ...
        'yaw_jet_tolerance',1e-7*ones(1,7));
    topt=struct('max_subdivision_depth',8,'max_node_count',511, ...
        'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
        'torque_guard_Nm',zeros(3,1), ...
        'enable_fast_norm_sufficient_bound',true);
    start=zeros(3,10);finish=zeros(3,10);
    start(:,1)=[-2;0;3];finish(:,1)=[2;0;3];
    start(1,2)=0.4;finish(1,2)=0.4;
    piece=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,10,start,finish, ...
        repmat([0;0;3],1,4));
    req=struct('t0_s',8,'duration_s',10,'flight_interval_s',[8 30], ...
        'start_jets',start,'end_jets',finish, ...
        'nominal_free',piece.control_points_m(:,11:14), ...
        'observed',struct([]), ...
        'radii',struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1), ...
        'authority',A,'geometry_options',gopt,'force_options',fopt, ...
        'search_options',sopt,'heading_options',hopt, ...
        'nominal_torque_options',topt);
    sphere=OBSTACLE_INFORMATION.define(21,'sphere',[0 0.1 3],0.2);
    ax=0.34;ay=-0.26;az=0.4;
    Rx=[1 0 0;0 cos(ax) -sin(ax);0 sin(ax) cos(ax)];
    Ry=[cos(ay) 0 sin(ay);0 1 0;-sin(ay) 0 cos(ay)];
    Rz=[cos(az) -sin(az) 0;sin(az) cos(az) 0;0 0 1];
    ellipsoid=OBSTACLE_INFORMATION.define(33,'ellipsoid', ...
        [0.6 -0.16 3],[0.32 0.19 0.4], ...
        'rotation',Rz*Ry*Rx);
    scenes={sphere,[sphere ellipsoid]};
    R.stage='PROFILE_PAIRED_ENTIRE_PIPELINE';
    good=true;
    for scene=1:2
        req.observed=scenes{scene};
        fast=req;fast.search_options.fast_probe_algebra=true;
        baseline=req;baseline.search_options.fast_probe_algebra=false;
        % Both paths warm up before any timing comparison.
        F=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(fast);
        B=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(baseline);
        R.status_fast{scene}=F.status;
        R.status_baseline{scene}=B.status;
        R.status_parity(scene)=strcmp(F.status,B.status)&& ...
            strcmp(F.search_status,B.search_status);
        R.proof_call_parity(scene)=F.proof_calls==B.proof_calls;
        R.QP_plane_count_parity(scene)= ...
            F.search_result.linear_constraints_generated== ...
            B.search_result.linear_constraints_generated;
        if F.candidate_available&&B.candidate_available
            R.candidate_parity_max_abs_m(scene)=max(abs( ...
                F.candidate_piece.control_points_m(:)- ...
                B.candidate_piece.control_points_m(:)));
        end
        good=good&&R.status_parity(scene)&& ...
            R.proof_call_parity(scene)&&R.QP_plane_count_parity(scene);
        good=good&&~F.safe_to_commit&&~B.safe_to_commit;
        for rep=1:R.repetitions
            % Interleave ordering so the first/second path does not gain
            % a systematic warm-cache advantage.
            if mod(rep,2)==1
                F=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(fast);
                B=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(baseline);
            else
                B=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(baseline);
                F=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(fast);
            end
            R.fast_total_trials_ms(scene,rep)=F.total_elapsed_ms;
            R.baseline_total_trials_ms(scene,rep)=B.total_elapsed_ms;
            R.fast_planes_trials_ms(scene,rep)=F.separation_planes_ms;
            R.baseline_planes_trials_ms(scene,rep)=B.separation_planes_ms;
            R.fast_proof_trials_ms(scene,rep)=F.joint_geometry_force_proof_ms;
            R.baseline_proof_trials_ms(scene,rep)=B.joint_geometry_force_proof_ms;
            R.fast_qp_trials_ms(scene,rep)=F.joint_QP_ms;
            R.baseline_qp_trials_ms(scene,rep)=B.joint_QP_ms;
            R.fast_heading_trials_ms(scene,rep)=F.heading_join_ms;
            R.baseline_heading_trials_ms(scene,rep)=B.heading_join_ms;
            R.fast_torque_trials_ms(scene,rep)=F.nominal_torque_ms;
            R.baseline_torque_trials_ms(scene,rep)=B.nominal_torque_ms;
            good=good&&strcmp(F.status,B.status)&& ...
                F.proof_calls==B.proof_calls&& ...
                ~F.safe_to_commit&&~B.safe_to_commit;
        end
        ft=R.fast_total_trials_ms(scene,:);
        bt=R.baseline_total_trials_ms(scene,:);
        R.full_fast_median_ms(scene)=median(ft);
        R.full_baseline_median_ms(scene)=median(bt);
        R.full_fast_p95_ms(scene)=local_p95(ft);
        R.full_baseline_p95_ms(scene)=local_p95(bt);
        R.full_fast_max_ms(scene)=max(ft);
        R.full_baseline_max_ms(scene)=max(bt);
        R.QP_planes_fast_median_ms(scene)=median(R.fast_planes_trials_ms(scene,:));
        R.QP_planes_baseline_median_ms(scene)=median(R.baseline_planes_trials_ms(scene,:));
        R.median_total_ratio_baseline_over_fast(scene)= ...
            median(bt)/median(ft);
    end
    R.no_unsafe_commit=good;
    if good
        R.status='PASS_QP_ALGEBRA_AND_PAIRED_WHOLE_PIPELINE__HLC_PENDING';
    else
        R.status='FAIL_QP_ALGEBRA_OR_WHOLE_PIPELINE_PARITY';
    end
    R.stage='DONE';
catch ME
    R.status='FAIL_C9_QP_PROBE_ALGEBRA';
    R.error_identifier=ME.identifier;
    R.error_message=ME.message;
    R.error_stack=cell(1,numel(ME.stack));
    for k=1:numel(ME.stack)
        R.error_stack{k}=sprintf('%s:%d',ME.stack(k).name,ME.stack(k).line);
    end
end
save(fullfile(root,'TRAJECTORY_C9_QP_PROBE_ALGEBRA_RESULT.mat'),'R');
fid=fopen(fullfile(root,'TRAJECTORY_C9_QP_PROBE_ALGEBRA_RESULT.txt'),'w');
if fid>=0
    fprintf(fid,'status=%s\nstage=%s\nerror=%s | %s\n', ...
        R.status,R.stage,R.error_identifier,R.error_message);
    fprintf(fid,'algebra_test_count=%d\nmax_scaled_error=%.12g\n', ...
        R.algebra_test_count,R.algebra_max_scaled_error);
    for j=1:2
        fprintf(fid, ...
          'scene=%s | fast=%s | baseline=%s | status_parity=%d | proof_parity=%d | planes_parity=%d\n', ...
          R.case_names{j},R.status_fast{j},R.status_baseline{j}, ...
          R.status_parity(j),R.proof_call_parity(j),R.QP_plane_count_parity(j));
        fprintf(fid, ...
          'median_whole_ms_fast=%.6f | baseline=%.6f | ratio=%.3f | median_plane_ms_fast=%.6f | baseline=%.6f\n', ...
          R.full_fast_median_ms(j),R.full_baseline_median_ms(j), ...
          R.median_total_ratio_baseline_over_fast(j), ...
          R.QP_planes_fast_median_ms(j),R.QP_planes_baseline_median_ms(j));
        fprintf(fid, ...
          'p95_whole_ms_fast=%.6f | baseline=%.6f | max_whole_ms_fast=%.6f | baseline=%.6f\n', ...
          R.full_fast_p95_ms(j),R.full_baseline_p95_ms(j), ...
          R.full_fast_max_ms(j),R.full_baseline_max_ms(j));
        fprintf(fid,'fast_breakdown_median_ms_proof=%.6f | planes=%.6f | QP=%.6f | heading=%.6f | torque=%.6f\n', ...
          median(R.fast_proof_trials_ms(j,:)), ...
          median(R.fast_planes_trials_ms(j,:)), ...
          median(R.fast_qp_trials_ms(j,:)), ...
          median(R.fast_heading_trials_ms(j,:)), ...
          median(R.fast_torque_trials_ms(j,:)));
        fprintf(fid,'baseline_breakdown_median_ms_proof=%.6f | planes=%.6f | QP=%.6f | heading=%.6f | torque=%.6f\n', ...
          median(R.baseline_proof_trials_ms(j,:)), ...
          median(R.baseline_planes_trials_ms(j,:)), ...
          median(R.baseline_qp_trials_ms(j,:)), ...
          median(R.baseline_heading_trials_ms(j,:)), ...
          median(R.baseline_torque_trials_ms(j,:)));
    end
    fclose(fid);
end
try
    zip(R.zip_path,{fullfile(root,'TRAJECTORY_C9_QP_PROBE_ALGEBRA_RESULT.mat'), ...
        fullfile(root,'TRAJECTORY_C9_QP_PROBE_ALGEBRA_RESULT.txt')});
catch ME
    warning('CHECK_C9_QP:Zip','Result ZIP creation failed: %s',ME.message);
end
fprintf('[C9 QP PROBE] %s | %s\n',R.status,R.zip_path);
end

function y=local_p95(x)
x=sort(double(x(:)));
p=1+(numel(x)-1)*0.95;
i=floor(p);j=ceil(p);
y=x(i)+(p-i)*(x(j)-x(i));
end
