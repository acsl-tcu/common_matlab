function A=CHECK_TRIGGER_TWO_TO_THREE_PREFLIGHT(replanner_instance)
% Disposable after-Flight audit of PRE-ARM synthetic path coverage.
% No fixed Flight start, no fixed real obstacle IDs, no expectation of
% speed improvement or continuous safety. Works with any live trajectory.
A=struct('status','NOT_RUN_DISCARDED_PREFLIGHT_AUDIT','reason','', ...
  'preflight_status','','native_calls',0,'verified_appends',0, ...
  'outer_appends',0,'safe_to_commit',false);
try
    assert(nargin==1 && isa(replanner_instance,'REPLANNING_SYSTEM'), ...
        'CHECK_TRIGGER_TWO_TO_THREE_PREFLIGHT:Replanner', ...
        'An already completed Flight replanner is required.');
    S=replanner_instance.get_status();
    A.preflight_status=S.isolated_direct_native_status;
    A.native_calls=S.isolated_direct_native_calls;
    A.verified_appends=S.isolated_direct_native_verified_appends;
    A.outer_appends=S.isolated_direct_native_outer_appends;
    assert(strcmp(A.preflight_status, ...
        'PASS_DISCARDED_TWO_TO_THREE_REAL_SENSOR_NATIVE__NO_JIT_GUARANTEE') && ...
        A.native_calls==24 && A.verified_appends==8 && ...
        A.outer_appends==8, ...
        'CHECK_TRIGGER_TWO_TO_THREE_PREFLIGHT:Coverage', ...
        'True-schema pre-ARM synthetic 2->3 paths did not all complete.');
    A.status='PASS_DISCARDED_TWO_TO_THREE_BRANCH_COVERAGE__NOT_JIT_PROOF';
catch ME
    A.reason=[ME.identifier ' | ' ME.message];
end
save('TRIGGER_TWO_TO_THREE_PREFLIGHT_RESULT.mat','A');
f=fopen('TRIGGER_TWO_TO_THREE_PREFLIGHT_RESULT.txt','w');
if f>=0
 fprintf(f,'status=%s\npreflight_status=%s\nnative_calls=%d\nverified_appends=%d\nouter_appends=%d\nreason=%s\n', ...
     A.status,A.preflight_status,A.native_calls, ...
     A.verified_appends,A.outer_appends,A.reason);
 fclose(f);
end
end
