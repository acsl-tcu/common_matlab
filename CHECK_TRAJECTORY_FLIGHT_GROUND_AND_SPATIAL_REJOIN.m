function R=CHECK_TRAJECTORY_FLIGHT_GROUND_AND_SPATIAL_REJOIN()
% CHECK_TRAJECTORY_FLIGHT_GROUND_AND_SPATIAL_REJOIN
% Synthetic regression tests, no change to Flight/HLC/EKF/plant/sensor/trigger.
% Run from any pwd. Outputs MAT/TXT in common_matlab/.
root=fileparts(mfilename('fullpath'));
mod=fullfile(root,'reference','REPLANNING_SYSTEM');
addpath(fullfile(root,'controller'),'-begin');
[hlc_force_limits,~]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_limits();
addpath(fullfile(mod,'TRAJECTORY_GENERATION'), ...
    fullfile(mod,'OBSTACLE_INFORMATION'),'-begin');
R=struct('status','FAIL_NOT_RUN','previous_ground_audit',false, ...
    'phase_flags_correct',false,'conservative_missing_phase',false, ...
    'invalid_phase_rejected',false,'flight_ground_rejected',false, ...
    'nonflight_ground_omitted',false, ...
    'c9_flight_ground_rejected',false, ...
    'c9_cable_radius_ground_rejected',false, ...
    'c9_thin_cable_ground_certified',false, ...
    'c9_nonflight_joint_certified',false, ...
    'c9_nonflight_pipeline_certified',false, ...
    'phase_switch_stale_corridor_rejected',false, ...
    'spatial_return_geometry_certified',false, ...
    'spatial_return_not_clock_tethered',false, ...
    'spatial_progress_respected',false, ...
    'reference28_sixth_order_join_checked',false, ...
    'reference28_mismatch_rejected',false, ...
    'safe_to_commit_any',false, ...
    'error_identifier','','error_message','');
try
    % Prior user supplied report: DO NOT fabricate a new MATLAB result.
    prev=fullfile(root,'GROUND_INFORMATION_SEPARATE_RESULT.mat');
    if isfile(prev)
        S=load(prev,'R');
        R.previous_ground_audit= ...
            isfield(S,'R')&&isfield(S.R,'status')&& ...
            strcmp(S.R.status, ...
              'PASS_GROUND_INFORMATION_SEPARATE_ALL_TIME_BODY_GEOMETRY');
    end

    flags='atfl';actual=false(1,4);
    for k=1:4
        [actual(k),phase]=TRAJECTORY_GROUND_SCOPE( ...
            struct('trajectory_phase',flags(k)));
        assert(strcmp(phase,flags(k)), ...
            'CHECK_FLIGHT_GROUND:Scope','Phase label mismatch.');
    end
    R.phase_flags_correct=isequal(actual,logical([0 0 1 0]));
    [on,phase]=TRAJECTORY_GROUND_SCOPE(struct());
    R.conservative_missing_phase=on&& ...
        strcmp(phase,'UNSPECIFIED_CONSERVATIVE');
    try
        TRAJECTORY_GROUND_SCOPE(struct('trajectory_phase','flight'));
    catch ME
        R.invalid_phase_rejected= ...
            strcmp(ME.identifier,'TRAJECTORY_GROUND_SCOPE:Phase');
    end
    assert(R.phase_flags_correct&&R.conservative_missing_phase&& ...
        R.invalid_phase_rejected,'CHECK_FLIGHT_GROUND:Scope', ...
        'Only explicit whole-piece non-f phase may disable ground.');

    % Finite synthetic fixture is intentionally in the occupied z<=0
    % halfspace during a/t/l. This should be allowed ONLY for the
    % phase-specific ground exemption (no finite obstacles are observed).
    U=struct('control_points_m',repmat([0;0;0],1,16), ...
        't0_s',0,'duration_s',1);
    L=struct('control_points_m',repmat([0;0;-2],1,16), ...
        't0_s',0,'duration_s',1);
    seg=struct('uav',U,'payload',L);
    r=struct('uav_m',0.5,'payload_m',0.5,'cable_m',0);
    op=struct('robust_tube_enabled',false, ...
        'max_subdivision_depth',0,'numerical_guard_m',0, ...
        'trajectory_phase','f');
    flight=TRAJECTORY_CONTINUOUS_GEOMETRY_CERTIFICATE( ...
        seg,struct([]),r,op);
    R.flight_ground_rejected=~flight.certified&& ...
        flight.ground_checked&&~flight.ground_certified;
    op.trajectory_phase='t';
    takeoff=TRAJECTORY_CONTINUOUS_GEOMETRY_CERTIFICATE( ...
        seg,struct([]),r,op);
    R.nonflight_ground_omitted=takeoff.certified&& ...
        ~takeoff.ground_checked&&~takeoff.ground_certified&& ...
        strcmp(takeoff.ground_status,'NOT_APPLICABLE_OUTSIDE_FLIGHT');
    assert(R.flight_ground_rejected&&R.nonflight_ground_omitted&& ...
        ~takeoff.safe_to_commit,'CHECK_FLIGHT_GROUND:Geometry', ...
        'Ground must be mandatory for f, not required for t.');

    % C9 ideal taut-load: constant load below ground, UAV at z=0.
    % Tests the same entire-time force/tension+geometry proof as the real
    % shared pipeline, and verifies its phase-specific ground contract.
    jets=zeros(3,10);jets(3,1)=-2;
    free=repmat([0;0;-2],1,4);
    piece=TRAJECTORY_C9_FLAT_BERNSTEIN.build(0,1,jets,jets,free);
    auth=struct('cable_length_m',2,'payload_mass_kg',0.2, ...
        'uav_mass_kg',1.0,'gravity_world_mps2',[0;0;-9.80665], ...
        'thrust_limits_N',hlc_force_limits, ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0);
    g=struct('max_subdivision_depth',0,'max_node_count',32, ...
        'numerical_guard_m',0,'robust_tube_enabled',false, ...
        'trajectory_phase','f');
    f=struct('max_subdivision_depth',0,'max_node_count',32, ...
        'force_guard_N',0);
    fail=TRAJECTORY_C9_JOINT_FAST_CERTIFICATE(piece, ...
        struct([]),r,auth,g,f);
    R.c9_flight_ground_rejected=~fail.certified&& ...
        fail.ground_checked;
    % Regression for the formerly reversed payload/cable radii in the
    % joint ground check. The original CHECK accidentally put the load at
    % z=2.3 m, so even a 0.5 m cable was ABOVE ground (1.8 m clearance).
    % That fixture could NOT be expected to fail. Use z=0.3 m instead:
    % payload clearance=+0.25 m, UAV clearance=+2.2 m, cable with r=0.5
    % has clearance=-0.2 m. This isolates CABLE thickness as the reason
    % to reject the proof, without weakening the production certificate.
    near_ground_jets=zeros(3,10);
    near_ground_jets(3,1)=0.3;
    near_ground_piece=TRAJECTORY_C9_FLAT_BERNSTEIN.build( ...
        0,1,near_ground_jets,near_ground_jets, ...
        repmat([0;0;0.3],1,4));
    rad_thin=struct('uav_m',0.1,'payload_m',0.05,'cable_m',0.0);
    rad_thick=rad_thin;rad_thick.cable_m=0.5;
    thin_proof=TRAJECTORY_C9_JOINT_FAST_CERTIFICATE( ...
        near_ground_piece,struct([]),rad_thin,auth,g,f);
    thick_proof=TRAJECTORY_C9_JOINT_FAST_CERTIFICATE( ...
        near_ground_piece,struct([]),rad_thick,auth,g,f);
    R.c9_thin_cable_ground_certified=thin_proof.certified&& ...
        thin_proof.ground_checked&& ...
        strcmp(thin_proof.ground_status,'CERTIFIED_ALL_TIME_ABOVE_GROUND');
    R.c9_cable_radius_ground_rejected= ...
        R.c9_thin_cable_ground_certified&& ...
        ~thick_proof.certified&&thick_proof.ground_checked&& ...
        strcmp(thick_proof.ground_status, ...
            'UNKNOWN_GROUND_CLEARANCE_NOT_PROVEN');
    g.trajectory_phase='a';
    pass=TRAJECTORY_C9_JOINT_FAST_CERTIFICATE(piece, ...
        struct([]),r,auth,g,f);
    R.c9_nonflight_joint_certified=pass.certified&& ...
        ~pass.ground_checked&&strcmp(pass.ground_status, ...
        'NOT_APPLICABLE_OUTSIDE_FLIGHT');
    c=struct('min_separation_m',1e-6, ...
        'max_normal_iterations',2,'max_ray_iterations',2);
    pipeline=TRAJECTORY_C9_FAST_TOTAL_PIPELINE(piece, ...
        free,struct([]),r,auth,g,f,c);
    R.c9_nonflight_pipeline_certified=pipeline.candidate_available&& ...
        ~pipeline.safe_to_commit&& ...
        ~pipeline.corridor.ground_applicable&& ...
        ~pipeline.candidate.fullbody_certificate.ground_checked;
    changed=g;changed.trajectory_phase='f';
    stale=TRAJECTORY_C9_TAUT_CORRIDOR_RAY( ...
        pipeline.corridor,free,struct([]),r,auth,changed,f);
    R.phase_switch_stale_corridor_rejected= ...
        ~stale.candidate_available&& ...
        strcmp(stale.status,'UNKNOWN_STALE_OBSTACLES_OR_PHYSICAL_AUTHORITY');
    assert(R.c9_flight_ground_rejected&& ...
        R.c9_thin_cable_ground_certified&& ...
        R.c9_cable_radius_ground_rejected&& ...
        R.c9_nonflight_joint_certified&& ...
        R.c9_nonflight_pipeline_certified&& ...
        R.phase_switch_stale_corridor_rejected, ...
        'CHECK_FLIGHT_GROUND:C9', ...
        sprintf(['C9 scope/regression flags: flight=%d, ' ...
            'thin_cable_safe=%d, thick_cable_rejected=%d, ' ...
            'nonflight_joint=%d, nonflight_pipeline=%d, stale_ray=%d. ' ...
            'Joint statuses: flight=%s, thin=%s, thick=%s, ' ...
            'nonflight=%s, pipeline=%s, stale_ray=%s.'], ...
            R.c9_flight_ground_rejected, ...
            R.c9_thin_cable_ground_certified, ...
            R.c9_cable_radius_ground_rejected, ...
            R.c9_nonflight_joint_certified, ...
            R.c9_nonflight_pipeline_certified, ...
            R.phase_switch_stale_corridor_rejected, ...
            fail.status,thin_proof.status,thick_proof.status, ...
            pass.status,pipeline.status,stale.status));

    % Spatial search: the source nominal is a geometric curve. It has
    % no wall-clock return time and the chosen parameter never decreases
    % below the externally supplied forward-progress bound.
    curve=[linspace(0,10,9);zeros(1,9);ones(1,9)];
    x=[7;3;1];
    policy=struct('position_tolerance_m',1e-3, ...
        'max_node_count',1024,'numerical_guard_m',0);
    target=TRAJECTORY_SPATIAL_REJOIN_TARGET(curve,x,0.2,policy);
    R.spatial_return_geometry_certified=target.certified_spatial_nearest&& ...
        target.candidate_available&& ...
        abs(target.distance_upper_bound_m-3)<1e-3&& ...
        norm(target.spatial_target_m-[7;0;1])<1e-2;
    R.spatial_return_not_clock_tethered=isempty(target.target_time_s)&& ...
        strcmp(target.rejoin_timing_policy,'FREE_TIME_SPATIAL_ONLY')&& ...
        ~target.safe_to_commit;
    R.spatial_progress_respected=target.curve_parameter_u>=0.2&& ...
        target.curve_parameter_u<=1;
    assert(R.spatial_return_geometry_certified&& ...
        R.spatial_return_not_clock_tethered&& ...
        R.spatial_progress_respected, ...
        'CHECK_FLIGHT_GROUND:Spatial','Spatial-only return contract failed.');

    % Actual original TIME_VARYING_REFERENCE supplies ref28 0..6. Build
    % a linear moving C9 test piece with nonzero horizontal speed, then
    % check all original 28 values at a spatial-only return station.
    sj=zeros(3,10);ej=zeros(3,10);
    sj(:,1)=[0;0;3];ej(:,1)=[3;0;3];
    sj(1,2)=3;ej(1,2)=3;
    controls=[linspace(0,3,24);zeros(1,24);3*ones(1,24)];
    moving=TRAJECTORY_C9_FLAT_BERNSTEIN.build( ...
        0,1,sj,ej,controls(:,11:14));
    first=TRAJECTORY_TAUT_FLATNESS.reference28(moving,0,auth,0);
    last=TRAJECTORY_TAUT_FLATNESS.reference28(moving,1,auth,0);
    spatial=TRAJECTORY_SPATIAL_REJOIN_TARGET( ...
        [linspace(0,3,9);zeros(1,9);5*ones(1,9)], ...
        [3;0;5],1,policy);
    match=TRAJECTORY_C9_REFERENCE_JOIN_AUDIT( ...
        moving,auth,first,last,spatial,zeros(28,1));
    R.reference28_sixth_order_join_checked= ...
        match.endpoint_ref28_matched&& ...
        match.position_d0_to_d6_matched&& ...
        match.yaw_d0_to_d6_matched&& ...
        ~match.strict_C7_join_certified&& ...
        ~match.safe_to_commit&&isempty(match.return_target_time_s);
    mismatched=last;mismatched(10)=mismatched(10)+1;
    reject=TRAJECTORY_C9_REFERENCE_JOIN_AUDIT( ...
        moving,auth,first,mismatched,spatial,zeros(28,1));
    R.reference28_mismatch_rejected=~reject.endpoint_ref28_matched;
    assert(R.reference28_sixth_order_join_checked&& ...
        R.reference28_mismatch_rejected, ...
        'CHECK_FLIGHT_GROUND:Join', ...
        'Original ref28 d0..d6 must be checked at spatial return.');

    R.safe_to_commit_any=flight.safe_to_commit|| ...
        takeoff.safe_to_commit||fail.safe_to_commit|| ...
        pass.safe_to_commit||pipeline.safe_to_commit|| ...
        target.safe_to_commit;
    assert(~R.safe_to_commit_any,'CHECK_FLIGHT_GROUND:Commit', ...
        'No partial proof may authorize HLC.');
    R.status='PASS_FLIGHT_ONLY_GROUND_AND_TIME_FREE_SPATIAL_TARGET__HLC_PENDING';
catch ME
    R.status='FAIL_FLIGHT_ONLY_GROUND_AND_SPATIAL_TARGET';
    R.error_identifier=ME.identifier;
    R.error_message=ME.message;
    write_result(root,R);
    rethrow(ME)
end
write_result(root,R);
end

function write_result(root,R)
name='TRAJECTORY_FLIGHT_GROUND_SPATIAL_RESULT';
save(fullfile(root,[name '.mat']),'R');
fid=fopen(fullfile(root,[name '.txt']),'wt');
if fid<0,error('CHECK_FLIGHT_GROUND:IO','Cannot write audit output.');end
cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\n',R.status);
keys=fieldnames(R);
for k=1:numel(keys)
    key=keys{k};
    if strcmp(key,'status'),continue;end
    val=R.(key);
    if (islogical(val)||isnumeric(val))&&isscalar(val)
        fprintf(fid,'%s=%d\n',key,val);
    elseif ischar(val)&&~isempty(val)
        fprintf(fid,'%s=%s\n',key,val);
    end
end
% Flush and close TXT before packaging it (onCleanup closes the handle).
clear cleanup
% Keep audit artifacts together for sharing with the next verification.
% MATLAB zip is used only after the CHECK finishes/fails; no runtime code
% calls this and it does NOT unzip/install/change production sources.
try
    zip(fullfile(root,[name '_FOR_CHATGPT.zip']), ...
        {[name '.mat'],[name '.txt']},root);
catch zip_error
    warning('CHECK_FLIGHT_GROUND:ZIP', ...
        'Results MAT/TXT saved, but could not make ZIP: %s', ...
        zip_error.message);
end
end
