function R=CHECK_TRIGGER_FINAL()
% Run regression checks for the final sampled collision trigger.
% Purely synthetic; does NOT simulate a real Flight or certify WCET/safety.
% Results and temporary CHECK_* files live only in common_matlab/.
root=fileparts(mfilename('fullpath'));
A=CHECK_TRIGGER_COLLISION_ONLY();
B=CHECK_TRIGGER_EARLY_CONTACT_FINAL();
assert(startsWith(string(A.status),'PASS_TRIGGER_COLLISION_ONLY_') && ...
    startsWith(string(B.status),'PASS_EARLY_CONTACT_PREFIX_'), ...
    'CHECK_TRIGGER_FINAL:Failure','One trigger regression did not pass.');
R=struct('status','PASS_TRIGGER_COLLISION_ONLY_AND_EARLY_STOP__SYNTHETIC_ONLY', ...
    'existing_cases',A.cases,'new_cases',B.cases, ...
    'failures',A.failures+B.failures,'existing',A,'early_stop',B, ...
    'real_flight_tested',false,'wcet_proven',false, ...
    'continuous_time_physical_safety_proven',false);
save(fullfile(root,'TRIGGER_FINAL_RESULT.mat'),'R');
fid=fopen(fullfile(root,'TRIGGER_FINAL_RESULT.txt'),'w');
assert(fid>0,'CHECK_TRIGGER_FINAL:Output','Output write failed.');
c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\nexisting=%d new=%d failures=%d\n', ...
    R.status,R.existing_cases,R.new_cases,R.failures);
fprintf(fid,'real_flight=0 WCET=0 continuous_time_physical_proof=0\n');
end
