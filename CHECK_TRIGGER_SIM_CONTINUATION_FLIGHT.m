function A=CHECK_TRIGGER_SIM_CONTINUATION_FLIGHT(replanner_instance)
% After ONE unmodified original Flight with TRIGGER_SIM_TRUE_SET_CHAIN=1.
% Captures the first inductive break rather than hiding it behind PASS.
A=struct('status','UNKNOWN_SIM_CONTINUATION_FLIGHT', ...
    'reason','','history_ticks',0,'future_calls',0, ...
    'last_time_s',NaN,'last_history_status','', ...
    'last_future_status','', ...
    'first_failure_time_s',NaN, ...
    'first_failure_prior_time_s',NaN, ...
    'first_failure_stage','', ...
    'first_failure_reason','', ...
    'first_failure_advance_status','', ...
    'first_failure_advance_reason','', ...
    'first_failure_refinements_tried',0, ...
    'first_failure_substeps_completed',0, ...
    'full_sim_safety_proven',false, ...
    'safe_to_commit',false);
try
    assert(isa(replanner_instance,'REPLANNING_SYSTEM') && ...
        replanner_instance.sim_true_set_chain_enabled && ...
        ~isempty(replanner_instance.sim_true_set_chain), ...
        'CHECK_TRIGGER_SIM_CONTINUATION_FLIGHT:Disabled', ...
        'Turn on TRIGGER_SIM_TRUE_SET_CHAIN=1 BEFORE constructing replanner.');
    chain=replanner_instance.sim_true_set_chain;
    S=chain.brief();
    A.history_ticks=S.real_history_ticks;
    A.future_calls=chain.forecast_count;
    A.last_time_s=S.time_s;
    A.last_history_status=S.status;
    A.reason=S.reason;
    A.first_failure_time_s=S.first_failure_time_s;
    A.first_failure_prior_time_s=S.first_failure_prior_time_s;
    A.first_failure_stage=S.first_failure_stage;
    A.first_failure_reason=S.first_failure_reason;
    A.first_failure_advance_status=S.first_failure_advance_status;
    A.first_failure_advance_reason=S.first_failure_advance_reason;
    if isstruct(chain.last_advance) && ...
            isfield(chain.last_advance,'plant_interval') && ...
            isstruct(chain.last_advance.plant_interval)
        I=chain.last_advance.plant_interval;
        if isfield(I,'refinements_tried')
            A.first_failure_refinements_tried=I.refinements_tried;
        end
        if isfield(I,'slabs_completed_in_last_trial')
            A.first_failure_substeps_completed=I.slabs_completed_in_last_trial;
        end
    end
    if isstruct(replanner_instance.last_trigger_result) && ...
            isfield(replanner_instance.last_trigger_result,'true_set_4s_status')
        A.last_future_status= ...
            replanner_instance.last_trigger_result.true_set_4s_status;
    end
    if chain.initialized && chain.completed_real_ticks>0 && ...
            chain.forecast_count>0
        A.status='CONDITIONAL_SIM_T0_NOW_AND_FUTURE_CALLED__NOT_PHYSICAL_PROOF';
        A.reason=[S.reason ' | Last 4s result: ' A.last_future_status];
    elseif chain.failure_latched
        A.status='UNKNOWN_ORIGINAL_PLANT_INTERVAL_CHAIN_STOPPED';
        A.reason=sprintf(['First failure t=%.17g s after successful ' ...
            't=%.17g s | stage=%s | %s | advance=%s | %s'], ...
            A.first_failure_time_s,A.first_failure_prior_time_s, ...
            A.first_failure_stage,A.first_failure_reason, ...
            A.first_failure_advance_status,A.first_failure_advance_reason);
    else
        A.status='UNKNOWN_NO_COMPLETE_ONLINE_CHAIN';
    end
catch ME
    A.reason=[ME.identifier ' | ' ME.message];
end
try
    save('TRIGGER_SIM_CONTINUATION_FLIGHT_RESULT.mat','A');
    fid=fopen('TRIGGER_SIM_CONTINUATION_FLIGHT_RESULT.txt','w');
    if fid>0
        fprintf(fid,['%s\nhistory_ticks=%d future_calls=%d ' ...
            'last_success_time=%.17g\nfirst_failure_time=%.17g ' ...
            'stage=%s\nrefinements=%d last_completed=%d\n%s\n'], ...
            A.status,A.history_ticks,A.future_calls,A.last_time_s, ...
            A.first_failure_time_s,A.first_failure_stage, ...
            A.first_failure_refinements_tried, ...
            A.first_failure_substeps_completed,A.reason);
        fclose(fid);
    end
catch
end
end
