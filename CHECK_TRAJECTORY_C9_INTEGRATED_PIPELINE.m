function R=CHECK_TRAJECTORY_C9_INTEGRATED_PIPELINE()
% CHECK_TRAJECTORY_C9_INTEGRATED_PIPELINE
% Profiles the *entire candidate-side nominal pipeline* in one call:
% simultaneous C9 obstacle search, shared joint full-time proof,
% C7/yaw C6 and all-time nominal rigid-body torque.
% NO HLC/plant/tracking theorem, numerical directed rounding or COMMIT.
% All scenario masses/geometries are EXPLICIT CHECK FIXTURES, not Flight EKF.
% Actual HLC input clamps and model parameters are read from active code.
root=fileparts(mfilename('fullpath'));
module=fullfile(root,'reference','REPLANNING_SYSTEM', ...
    'TRAJECTORY_GENERATION');
R=struct('status','FAIL_NOT_STARTED','stage','INIT', ...
    'error_identifier','','error_message','', 'error_stack',{{}}, ...
    'case_names',{{}},'case_status',{{}}, ...
    'case_count',0,'evaluated_case_count',0, ...
    'nominal_complete_count',0, ...
    'case_nominal_complete',[], 'case_search_status',{{}}, ...
    'case_heading_status',{{}},'case_torque_status',{{}}, ...
    'case_total_ms',[],'case_search_ms',[], ...
    'case_joint_proof_ms',[], 'case_planes_ms',[], ...
    'case_qp_ms',[],'case_search_other_ms',[], ...
    'case_heading_ms',[], 'case_torque_ms',[], ...
    'case_overhead_ms',[], 'case_proof_calls',[], ...
    'case_geometry_cache_hits',[], ...
    'case_geometry_prepare_ms',[], ...
    'case_initial_shapes_shared',[], ...
    'case_fixed_basis_cache_hits',[], ...
    'case_proof_status_history',{{}}, ...
    'case_proof_failure_times_s',{{}}, ...
    'case_proof_failure_ids',{{}}, ...
    'case_qp_status',{{}}, ...
    'snapshot_regression_pass',false, ...
    'initial_shape_share_matches_canonical',false, ...
    'snapshot_cache_reuse_pass',false, ...
    'snapshot_pose_change_invalidated',false, ...
    'snapshot_rotation_invalidated',false, ...
    'snapshot_dimensions_invalidated',false, ...
    'snapshot_count_invalidated',false, ...
    'snapshot_order_change_invalidated',false, ...
    'case_shared_proof_used',[], 'no_unsafe_commit',false, ...
    'safe_nominal_control_pass',false, ...
    'heading_helper_identity_pass',false, ...
    'heading_helper_test_times_s',[], ...
    'invalid_time_rejected',false, ...
    'time_translation_invariance_pass',false, ...
    'case_error_identifier',{{}}, 'case_failure_detail',{{}}, ...
    'old_endpoint_redundancy_avoided',false, ...
    'endpoint_actual_jet_evaluation_parity',false, ...
    'runtime_median_ms',NaN,'runtime_p95_ms',NaN, ...
    'runtime_max_ms',NaN, 'actual_HLC_tracking_proven',false, ...
    'repeated_trial_count',0, ...
    'repeated_case_times_ms',[], ...
    'repeated_case_median_ms',[], 'repeated_case_p95_ms',[], ...
    'repeated_case_max_ms',[], 'repeated_all_median_ms',NaN, ...
    'repeated_all_p95_ms',NaN, 'repeated_all_max_ms',NaN, ...
    'repeated_case_status',{{}}, ...
    'source_policy','HLC_LIMITS_AND_DRONE_PARAMETER_FROM_ACTIVE_SOURCE', ...
    'fixture_policy','SYNTHETIC_TEST_GEOMETRY_NOT_LIVE_FLIGHT_EKF', ...
    'zip_path',fullfile(root, ...
        'TRAJECTORY_C9_INTEGRATED_PIPELINE_RESULT_FOR_CHATGPT.zip'));
try
    R.stage='CHECK_REAL_PROJECT_LAYOUT';
    assert(isfolder(module)&& ...
        isfile(fullfile(root,'run_flight_headless.m')), ...
        'CHECK_C9_INTEGRATED:ProjectRoot', ...
        'Put this CHECK in the common_matlab project root.');
    addpath(fullfile(root,'controller'),'-begin');
    addpath(fullfile(root,'model'),'-begin');
    addpath(module,fullfile(root,'reference','REPLANNING_SYSTEM', ...
        'OBSTACLE_INFORMATION'),'-begin');

    R.stage='READ_REAL_HLC_AND_DRONE_PARAMETER';
    [lower,upper]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    P.set("loadmass",0.14); % explicit CHECK fixture, NEVER Flight authority
    % No mutation of the actual Flight program's parameter.
    d=double(P.get(["mass","jx","jy","jz", ...
        "gravity","cableL","loadmass"]));
    assert(numel(d)==7&&all(isfinite(d(:)))&&all(d(:)>0), ...
        'CHECK_C9_INTEGRATED:CurrentParameter', ...
        'Current parameter fixture must be physically valid.');
    d=d(:);lower=double(lower(:));upper=double(upper(:));
    A=struct('uav_mass_kg',d(1), ...
        'payload_mass_kg',d(7),'cable_length_m',d(6), ...
        'uav_inertia_kgm2',d(2:4), ...
        'gravity_world_mps2',[0;0;-d(5)], ...
        'thrust_limits_N',[lower(1),upper(1)], ...
        'torque_limits_Nm',[lower(2:4),upper(2:4)], ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0);
    R.hlc_input_lower=lower;R.hlc_input_upper=upper;
    R.parameter_source=which('DRONE_PARAM_SUSPENDED_LOAD');
    R.hlc_source=which('HLC_SUSPENDED_LOAD');

    R.stage='BUILD_ONE_COMMON_C9_PROBLEM';
    radii=struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1);
    geometry=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'numerical_guard_m',0,'robust_tube_enabled',false, ...
        'trajectory_phase','f');
    force=struct('max_subdivision_depth',6, ...
        'max_node_count',127,'force_guard_N',0);
    search=struct('probe_count',13,'max_outer_iterations',4, ...
        'max_projection_sweeps',100, ...
        'projection_tolerance_m',1e-8,'min_separation_m',1e-5);
    heading=struct('max_subdivision_depth',8,'max_node_count',511, ...
        'horizontal_velocity_guard_mps',0,'w_guard_mps2',0, ...
        'payload_jet_tolerance',1e-7*ones(3,10), ...
        'uav_jet_tolerance',1e-7*ones(3,8), ...
        'yaw_jet_tolerance',1e-7*ones(1,7));
    torque=struct('max_subdivision_depth',8,'max_node_count',511, ...
        'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
        'torque_guard_Nm',zeros(3,1), ...
        'enable_fast_norm_sufficient_bound',true);
    start=zeros(3,10);finish=zeros(3,10);
    start(:,1)=[-2;0;3];finish(:,1)=[2;0;3];
    start(1,2)=0.4;finish(1,2)=0.4;
    nominal=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,10, ...
        start,finish,repmat([0;0;3],1,4));
    req=struct('t0_s',8,'duration_s',10, ...
        'flight_interval_s',[8 30],'start_jets',start, ...
        'end_jets',finish, ...
        'nominal_free',nominal.control_points_m(:,11:14), ...
        'observed',struct([]),'radii',radii,'authority',A, ...
        'geometry_options',geometry,'force_options',force, ...
        'search_options',search,'heading_options',heading, ...
        'nominal_torque_options',torque);

    % Proven-safe reference control, identical to the previously passing
    % affine torque fixture; no obstacle and zero nominal angular velocity.
    s0=zeros(3,10);s1=zeros(3,10);
    s0(:,1)=[0;0;3];s1(:,1)=[1;0;3];
    s0(1,2)=0.5;s1(1,2)=0.5;
    affine_free=repmat(s0(:,1),1,4)+s0(:,2)*((2/23)*(10:13));
    safe_piece=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,2,s0,s1,affine_free);
    safe_req=req;safe_req.t0_s=8;safe_req.duration_s=2;
    safe_req.start_jets=s0;safe_req.end_jets=s1;
    safe_req.nominal_free=safe_piece.control_points_m(:,11:14);

    R.stage='VERIFY_EXACT_YAW_RECURRENCE_IDENTITY';
    % All evaluate/reference28 inputs use ABSOLUTE Flight time, not
    % zero-relative local time. The nominal piece lives on [8,18] s;
    % calling reference28(nominal,0,...) used to abort this entire CHECK
    % before a single candidate was measured.
    R.heading_helper_test_times_s=nominal.t0_s+ ...
        nominal.duration_s*[0 .5 1];
    same=true;
    for ti=R.heading_helper_test_times_s
        [~,oldyaw,Es]=TRAJECTORY_TAUT_FLATNESS.reference28( ...
            nominal,ti,A,0);
        newyaw=TRAJECTORY_TAUT_FLATNESS.yaw_from_uav_jets( ...
            Es.uav_jets,0);
        same=same&&isequal(oldyaw,newyaw);
    end
    R.heading_helper_identity_pass=same;
    assert(same,'CHECK_C9_INTEGRATED:YawParity', ...
        'Shared endpoint jets must preserve all seven yaw derivatives.');
    % A constant shift of the clock origin MUST NOT alter any jets or
    % heading values for the same relative position on the same polynomial.
    shifted=nominal;
    shifted.t0_s=nominal.t0_s+16;
    shift_ok=true;
    for ti=R.heading_helper_test_times_s
        [base_reference,base_yaw]=TRAJECTORY_TAUT_FLATNESS.reference28( ...
            nominal,ti,A,0);
        [shift_reference,shift_yaw]=TRAJECTORY_TAUT_FLATNESS.reference28( ...
            shifted,ti+16,A,0);
        shift_ok=shift_ok&&isequal(base_reference,shift_reference)&& ...
            isequal(base_yaw,shift_yaw);
    end
    R.time_translation_invariance_pass=shift_ok;
    assert(shift_ok,'CHECK_C9_INTEGRATED:ClockOrigin', ...
        'Changing the absolute Flight time must not alter the same C9 curve.');
    % A negative test, so the fix MUST NOT be implemented by allowing
    % extrapolation or silently clipping time to the piece's interval.
    try
        TRAJECTORY_TAUT_FLATNESS.reference28( ...
            nominal,nominal.t0_s-1,A,0);
    catch ME
        R.invalid_time_rejected=strcmp(ME.identifier, ...
            'TRAJECTORY_C9_FLAT:Domain');
    end
    assert(R.invalid_time_rejected, ...
        'CHECK_C9_INTEGRATED:DomainGuard', ...
        'Outside-piece evaluation must still fail closed.');
    R.old_endpoint_redundancy_avoided=true;
    % Exact endpoint regression: reusing the already verified real
    % derivative polygons must give the identical pointwise taut model
    % (including 3x8 UAV jets and all force outputs) as the standard
    % polynomial-evaluation entry. This is NOT a safety proof by sampling.
    actualD=TRAJECTORY_C9_FLAT_BERNSTEIN.actual_derivative_controls(safe_piece);
    R.endpoint_actual_jet_evaluation_parity=true;
    for endpoint=1:2
        if endpoint==1, tt=safe_piece.t0_s;else
            tt=safe_piece.t0_s+safe_piece.duration_s;
        end
        J=zeros(3,10);
        for ord=1:10
            if endpoint==1,J(:,ord)=actualD{ord}(:,1);else
                J(:,ord)=actualD{ord}(:,end);
            end
        end
        original=TRAJECTORY_TAUT_FLATNESS.evaluate(safe_piece,tt,A);
        reused=TRAJECTORY_TAUT_FLATNESS.evaluate_jet_matrix(J,A);
        R.endpoint_actual_jet_evaluation_parity= ...
            R.endpoint_actual_jet_evaluation_parity&&isequaln(original,reused);
    end
    assert(R.endpoint_actual_jet_evaluation_parity, ...
        'CHECK_C9_INTEGRATED:EndpointJetParity', ...
        'Actual polynomial endpoints and shared jet reconstruction differ.');


    R.stage='PROFILE_FULL_NOMINAL_PIPELINE';
    sphere=OBSTACLE_INFORMATION.define(21,'sphere',[0 0.1 3],0.2);
    ax=0.34;ay=-0.26;az=0.4;
    Rx=[1 0 0;0 cos(ax) -sin(ax);0 sin(ax) cos(ax)];
    Ry=[cos(ay) 0 sin(ay);0 1 0;-sin(ay) 0 cos(ay)];
    Rz=[cos(az) -sin(az) 0;sin(az) cos(az) 0;0 0 1];
    Q=Rz*Ry*Rx;
    ellipsoid=OBSTACLE_INFORMATION.define(33,'ellipsoid', ...
        [0.6 -0.16 3],[0.32 0.19 0.4],'rotation',Q);
    patterns={struct([]),sphere,[sphere ellipsoid]};
    labels={'uncollided_nominal','collision_start_single_sphere', ...
        'collision_start_sphere_and_rotated_ellipsoid'};
    count=numel(patterns);
    R.case_count=count;R.case_names=labels;
    R.case_status=repmat({'NOT_EVALUATED'},1,count);
    R.case_search_status=repmat({'NOT_EVALUATED'},1,count);
    R.case_heading_status=repmat({'NOT_EVALUATED'},1,count);
    R.case_torque_status=repmat({'NOT_EVALUATED'},1,count);
    R.case_error_identifier=repmat({''},1,count);
    R.case_failure_detail=repmat({''},1,count);
    fields={'case_total_ms','case_search_ms','case_joint_proof_ms', ...
        'case_planes_ms','case_qp_ms','case_search_other_ms', ...
        'case_heading_ms','case_torque_ms','case_overhead_ms', ...
        'case_proof_calls','case_shared_proof_used', ...
        'case_geometry_cache_hits','case_geometry_prepare_ms', ...
        'case_nominal_complete','case_initial_shapes_shared', ...
        'case_fixed_basis_cache_hits'};
    for i=1:numel(fields),R.(fields{i})=NaN(1,count);end
    R.case_shared_proof_used=zeros(1,count);
    R.case_nominal_complete=zeros(1,count);
    R.case_proof_status_history=repmat({{}},1,count);
    R.case_proof_failure_times_s=repmat({zeros(0,2)},1,count);
    R.case_proof_failure_ids=repmat({{}},1,count);
    R.case_qp_status=repmat({''},1,count);
    R.no_unsafe_commit=true;
    for k=1:count
        if k==1,v=safe_req;else,v=req;end
        v.observed=patterns{k};
        measured_clock=tic;
        try
            out=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(v);
        catch ME
            R.case_status{k}='UNKNOWN_CHECK_CASE_EXCEPTION';
            R.case_error_identifier{k}=ME.identifier;
            R.case_failure_detail{k}=ME.message;
            R.case_total_ms(k)=1000*toc(measured_clock);
            R.evaluated_case_count=k;
            continue
        end
        R.case_status{k}=out.status;
        R.case_failure_detail{k}=out.failure_detail;
        R.case_search_status{k}=out.search_status;
        R.case_heading_status{k}=out.heading_status;
        R.case_torque_status{k}=out.torque_status;
        R.case_total_ms(k)=out.total_elapsed_ms;
        R.case_search_ms(k)=out.search_elapsed_ms;
        R.case_joint_proof_ms(k)=out.joint_geometry_force_proof_ms;
        R.case_planes_ms(k)=out.separation_planes_ms;
        R.case_qp_ms(k)=out.joint_QP_ms;
        R.case_search_other_ms(k)=out.search_other_ms;
        R.case_heading_ms(k)=out.heading_join_ms;
        R.case_torque_ms(k)=out.nominal_torque_ms;
        R.case_overhead_ms(k)=out.integration_overhead_ms;
        R.case_proof_calls(k)=out.proof_calls;
        R.case_shared_proof_used(k)=out.joint_proof_reused_from_this_search;
        R.case_geometry_cache_hits(k)=out.geometry_snapshot_cache_hits;
        R.case_geometry_prepare_ms(k)=out.geometry_snapshot_prepare_ms_total;
        R.case_nominal_complete(k)=out.nominal_model_complete;
        if isstruct(out.search_result)&&isfield(out.search_result,'proof_status_history')
            h=out.search_result;
            R.case_proof_status_history{k}=h.proof_status_history;
            R.case_proof_failure_times_s{k}=h.proof_unresolved_time_history_s;
            R.case_proof_failure_ids{k}=h.proof_unresolved_obstacle_id_history;
            R.case_qp_status{k}=h.joint_qp_status;
            R.case_initial_shapes_shared(k)=double(h.initial_shapes_shared_from_proof);
            R.case_fixed_basis_cache_hits(k)=h.fixed_probe_basis_cache_hits;
        end
        R.evaluated_case_count=k;
        R.no_unsafe_commit=R.no_unsafe_commit&& ...
            ~out.safe_to_commit&&~out.actual_HLC_tracking_proven&& ...
            ~out.closed_loop_actuator_limits_proven;
        if out.nominal_model_complete
            assert(out.nominal_geometry_tension_thrust_proven&& ...
                out.C7_yaw_C6_all_time_and_join_proven&& ...
                out.nominal_three_axis_torque_proven&& ...
                out.joint_proof_reused_from_this_search, ...
                'CHECK_C9_INTEGRATED:AllGates', ...
                'Nominal completion requires ALL three independent gates.');
        end
    end
    R.nominal_complete_count=sum(R.case_nominal_complete);
    R.safe_nominal_control_pass=R.case_nominal_complete(1)>0;
    % The three different scene times are useful for profiling, but
    % their median is not a statistically meaningful same-problem runtime.
    % Repeated identical-case timings below separately expose P95/max.
    t=sort(R.case_total_ms(isfinite(R.case_total_ms)));
    if ~isempty(t)
        R.runtime_median_ms=median(t);
        R.runtime_p95_ms=t(max(1,ceil(.95*numel(t))));
        R.runtime_max_ms=max(t);
    end
    R.stage='PROFILE_REPEATED_COMPLETE_PIPELINE';
    repeats=20; R.repeated_trial_count=repeats;
    R.repeated_case_times_ms=NaN(count,repeats);
    repeated_parity=true;
    R.repeated_case_status=repmat({'NOT_EVALUATED'},count,repeats);
    for k=1:count
        if k==1,v=safe_req;else,v=req;end
        v.observed=patterns{k};
        for trial=1:repeats
            trial_clock=tic;
            try
                out=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(v);
                R.repeated_case_times_ms(k,trial)=out.total_elapsed_ms;
                R.repeated_case_status{k,trial}=out.status;
                % Repeated requests must preserve the same strict COMMIT
                % prohibition and proof-result status as the first run.
                repeated_parity=repeated_parity && ...
                    ~out.safe_to_commit && ...
                    strcmp(out.status,R.case_status{k});
            catch ME
                R.repeated_case_times_ms(k,trial)=1000*toc(trial_clock);
                R.repeated_case_status{k,trial}= ...
                    ['UNKNOWN_CHECK_REPEAT_' ME.identifier];
                repeated_parity=false;
            end
        end
    end
    R.repeated_case_median_ms=median(R.repeated_case_times_ms,2);
    ordered=sort(R.repeated_case_times_ms,2);
    R.repeated_case_p95_ms=ordered(:,ceil(.95*repeats));
    R.repeated_case_max_ms=max(R.repeated_case_times_ms,[],2);
    samples=sort(R.repeated_case_times_ms(:));
    R.repeated_all_median_ms=median(samples);
    R.repeated_all_p95_ms=samples(max(1,ceil(.95*numel(samples))));
    R.repeated_all_max_ms=max(samples);
    assert(repeated_parity, 'CHECK_C9_INTEGRATED:RepeatedParity', ...
        'Repeated full-pipeline status or COMMIT policy changed.');
    assert(R.no_unsafe_commit&&R.safe_nominal_control_pass&& ...
        R.case_shared_proof_used(1), ...
        'CHECK_C9_INTEGRATED:NominalRegression', ...
        'Safe nominal baseline must pass all gates without HLC COMMIT.');
    R.stage='VERIFY_IMMUTABLE_OBSTACLE_SNAPSHOT';
    % Cold/hot proof must be identical except timing and cache metadata.
    % Vary centre and obstacle ordering: neither is a detection-mask lookup.
    ob1=OBSTACLE_INFORMATION.define(9101,'sphere',[100 0 3],0.2);
    ob2=OBSTACLE_INFORMATION.define(9102,'ellipsoid', ...
        [101 1 4],[0.3 0.2 0.4]);
    [cp0,prepared_at_proof]=TRAJECTORY_C9_JOINT_FAST_CERTIFICATE( ...
        safe_piece,[ob1 ob2],radii,A,geometry,force);
    % The returned prepared shapes must be identical to the
    % independently validated canonical scene. These are never
    % externally asserted to be certified collision-free.
    R.initial_shape_share_matches_canonical=isequaln( ...
        prepared_at_proof,TRAJECTORY_OBSTACLE_SUPPORT.prepare([ob1 ob2]));
    cp1=TRAJECTORY_C9_JOINT_FAST_CERTIFICATE( ...
        safe_piece,[ob1 ob2],radii,A,geometry,force);
    R.snapshot_cache_reuse_pass=~cp0.geometry_snapshot_cache_hit&& ...
        cp1.geometry_snapshot_cache_hit;
    R.snapshot_regression_pass=proof_outcomes_equal(cp0,cp1);
    ob2move=OBSTACLE_INFORMATION.define(9102,'ellipsoid', ...
        [101.1 1 4],[0.3 0.2 0.4]);
    moved=TRAJECTORY_C9_JOINT_FAST_CERTIFICATE( ...
        safe_piece,[ob1 ob2move],radii,A,geometry,force);
    R.snapshot_pose_change_invalidated=~moved.geometry_snapshot_cache_hit;
    angle=0.37;
    Rz=[cos(angle) -sin(angle) 0;sin(angle) cos(angle) 0;0 0 1];
    ob2rot=OBSTACLE_INFORMATION.define(9102,'ellipsoid', ...
        [101.1 1 4],[0.3 0.2 0.4],'rotation',Rz);
    rotation_probe=TRAJECTORY_C9_JOINT_FAST_CERTIFICATE( ...
        safe_piece,[ob1 ob2rot],radii,A,geometry,force);
    R.snapshot_rotation_invalidated= ...
        ~rotation_probe.geometry_snapshot_cache_hit;
    ob2dim=OBSTACLE_INFORMATION.define(9102,'ellipsoid', ...
        [101.1 1 4],[0.35 0.2 0.4],'rotation',Rz);
    dimension_probe=TRAJECTORY_C9_JOINT_FAST_CERTIFICATE( ...
        safe_piece,[ob1 ob2dim],radii,A,geometry,force);
    R.snapshot_dimensions_invalidated= ...
        ~dimension_probe.geometry_snapshot_cache_hit;
    count_probe=TRAJECTORY_C9_JOINT_FAST_CERTIFICATE( ...
        safe_piece,ob1,radii,A,geometry,force);
    R.snapshot_count_invalidated=~count_probe.geometry_snapshot_cache_hit;
    changed_order=TRAJECTORY_C9_JOINT_FAST_CERTIFICATE( ...
        safe_piece,[ob2move ob1],radii,A,geometry,force);
    R.snapshot_order_change_invalidated=~changed_order.geometry_snapshot_cache_hit;
    R.snapshot_regression_pass=R.snapshot_regression_pass && ...
        R.initial_shape_share_matches_canonical && ...
        R.snapshot_cache_reuse_pass && ...
        R.snapshot_pose_change_invalidated && ...
        R.snapshot_rotation_invalidated && ...
        R.snapshot_dimensions_invalidated && ...
        R.snapshot_count_invalidated && ...
        R.snapshot_order_change_invalidated;
    if R.snapshot_regression_pass
        R.status='PASS_INTEGRATED_NOMINAL_PIPELINE_AUDIT__HLC_UNCERTIFIED';
    else
        R.status='FAIL_GEOMETRY_CACHE_REGRESSION__PIPELINE_MEASUREMENTS_RECORDED';
    end
    R.stage='COMPLETE';
catch ME
    R.status='FAIL_C9_INTEGRATED_PIPELINE';
    R.error_identifier=ME.identifier;
    R.error_message=ME.message;
    R.error_stack=arrayfun(@(f)sprintf('%s:%d',f.name,f.line), ...
        ME.stack,'UniformOutput',false);
end
% Persist even if one of the CHECK stages fails. Runtime measurements are
% not presented as proof of HLC tracking or flight authorization.
base='TRAJECTORY_C9_INTEGRATED_PIPELINE_RESULT';
matFile=fullfile(root,[base '.mat']);
txtFile=fullfile(root,[base '.txt']);
save(matFile,'R');
fid=fopen(txtFile,'w');
if fid>=0
    fprintf(fid,'status=%s\nstage=%s\nerror_identifier=%s\n', ...
        R.status,R.stage,R.error_identifier);
    fprintf(fid,'error_message=%s\n',R.error_message);
    for q=1:numel(R.error_stack)
        fprintf(fid,'error_stack_%d=%s\n',q,R.error_stack{q});
    end
    fprintf(fid,'scope=C9_SEARCH_AND_NOMINAL_PROOFS__NO_CLOSED_LOOP_HLC\n');
    fprintf(fid,'fixture=%s\n',R.fixture_policy);
    fprintf(fid,'source=%s\n',R.source_policy);
    fprintf(fid,['case_count=%d\nevaluated_case_count=%d\n', ...
        'nominal_complete_count=%d\n'], ...
        R.case_count,R.evaluated_case_count,R.nominal_complete_count);
    for k=1:R.case_count
        fprintf(fid,['case=%s | status=%s | search=%s | heading=%s | ', ...
            'torque=%s | total=%.6f ms | search=%.6f ms | ', ...
            'joint_proof=%.6f ms | planes=%.6f ms | qp=%.6f ms | ', ...
            'heading=%.6f ms | torque=%.6f ms | proof_calls=%.0f\n'], ...
            R.case_names{k},R.case_status{k},R.case_search_status{k}, ...
            R.case_heading_status{k},R.case_torque_status{k}, ...
            R.case_total_ms(k),R.case_search_ms(k), ...
            R.case_joint_proof_ms(k),R.case_planes_ms(k), ...
            R.case_qp_ms(k),R.case_heading_ms(k),R.case_torque_ms(k), ...
            R.case_proof_calls(k));
        if k<=numel(R.case_proof_status_history)&& ...
                ~isempty(R.case_proof_status_history{k})
            for h=1:numel(R.case_proof_status_history{k})
                times=R.case_proof_failure_times_s{k};
                ids=R.case_proof_failure_ids{k};
                fprintf(fid,['case_%d_proof_%d=%s | interval=[%.9g %.9g] | ', ...
                    'unresolved_ids=%s\n'], ...
                    k,h,R.case_proof_status_history{k}{h}, ...
                    times(h,1),times(h,2),mat2str(ids{h}));
            end
            fprintf(fid,['case_%d_qp=%s | initial_shapes_shared=%d | ', ...
                'fixed_probe_basis_cache_hits=%.0f\n'],k, ...
                R.case_qp_status{k},R.case_initial_shapes_shared(k), ...
                R.case_fixed_basis_cache_hits(k));
        end
    end
    fprintf(fid,['yaw_identity_inside_domain=%d\n', ...
        'outside_domain_rejected=%d\nclock_origin_invariance=%d\n'], ...
        R.heading_helper_identity_pass,R.invalid_time_rejected, ...
        R.time_translation_invariance_pass);
    for k=1:numel(R.case_error_identifier)
        fprintf(fid,'case_error_%d=%s | reason=%s\n',k, ...
            R.case_error_identifier{k},R.case_failure_detail{k});
    end
    for k=1:numel(R.repeated_case_median_ms)
        fprintf(fid,['repeated_case_%d_median_ms=%.6f | ', ...
            'p95_ms=%.6f | max_ms=%.6f\n'],k, ...
            R.repeated_case_median_ms(k),R.repeated_case_p95_ms(k), ...
            R.repeated_case_max_ms(k));
    end
    fprintf(fid,'endpoint_real_jet_parity=%d\n', ...
        R.endpoint_actual_jet_evaluation_parity);
    fprintf(fid,'shape_share_canonical_parity=%d\n', ...
        R.initial_shape_share_matches_canonical);
    fprintf(fid,['snapshot_cache_reuse=%d | proof_parity=%d | ', ...
        'pose_invalidated=%d | rotation_invalidated=%d | ', ...
        'dimensions_invalidated=%d | count_invalidated=%d | ', ...
        'order_invalidated=%d\n'], ...
        R.snapshot_cache_reuse_pass,R.snapshot_regression_pass, ...
        R.snapshot_pose_change_invalidated, ...
        R.snapshot_rotation_invalidated,R.snapshot_dimensions_invalidated, ...
        R.snapshot_count_invalidated,R.snapshot_order_change_invalidated);
    for k=1:numel(R.case_geometry_cache_hits)
        fprintf(fid,['geometry_snapshot_case_%d_cache_hits=%.0f | ', ...
            'preparation_ms=%.6f\n'],k, ...
            R.case_geometry_cache_hits(k),R.case_geometry_prepare_ms(k));
    end
    fprintf(fid,'repeat_trials_per_case=%d\n',R.repeated_trial_count);
    fprintf(fid,['repeated_all_median_ms=%.6f\n', ...
        'repeated_all_p95_ms=%.6f\n', ...
        'repeated_all_max_ms=%.6f\n'], ...
        R.repeated_all_median_ms,R.repeated_all_p95_ms, ...
        R.repeated_all_max_ms);
    fprintf(fid,'median_ms=%.6f\np95_ms=%.6f\nmax_ms=%.6f\n', ...
        R.runtime_median_ms,R.runtime_p95_ms,R.runtime_max_ms);
    fclose(fid);
end
try
    zip(R.zip_path,{[base '.mat'],[base '.txt']},root);
    assert(isfile(R.zip_path), ...
        'CHECK_C9_INTEGRATED:Export','Results ZIP was not created.');
catch ME
    warning('CHECK_C9_INTEGRATED:Export','Result ZIP: %s',ME.message);
end
fprintf('[C9 FULL PIPELINE AUDIT] %s | %s\n',R.status,R.zip_path);
end

