function T=CHECK_FUTURE_COLLISION_TRIGGER_CONTRACT()
% Pure contract/geometry tests ONLY. This is NOT a live-HLC prediction test.
% Does not read the real obstacle map or run any Flight/plant/controller code.
root=fileparts(mfilename('fullpath'));
module_root=fullfile(root,'reference','REPLANNING_SYSTEM');
module=fullfile(module_root,'FUTURE_COLLISION_TRIGGER');
addpath(module,'-begin');
addpath(fullfile(module_root,'OBSTACLE_INFORMATION'),'-begin');
addpath(fullfile(module_root,'SIMULATED_OBSTACLE_SENSOR'),'-begin');
% Only named, original supporting modules are added. No genpath shadowing.
assert(exist('OBSTACLE_INFORMATION','class')==8, ...
    'Add the existing REPLANNING_SYSTEM/OBSTACLE_INFORMATION folder to the MATLAB path.');
assert(exist('OBSTACLE_GEOMETRY_QUERY','class')==8, ...
    'Add the existing SIMULATED_OBSTACLE_SENSOR folder to the MATLAB path.');

cfg=struct('horizon_s',4,'sample_dt_s',0.025, ...
    'r_uav_m',0.15,'r_payload_m',0.10,'r_cable_m',0.01, ...
    'cable_length_m',2);
g=FUTURE_COLLISION_TRIGGER(struct('horizon_s',cfg.horizon_s));
e=struct('p',[0;0;2],'q',[0;0;0],'v',[0;0;0], ...
    'w',[0;0;0],'pL',[0;0;0],'vL',[0;0;0], ...
    'pT',[0;0;-1],'wL',[0;0;0]);
a=struct('payload_mass_kg',0.14,'reference_at',@(t)t, ...
    'runtime',rmfield(cfg,'horizon_s'));
empty_obj=OBSTACLE_INFORMATION.define(101,'ellipsoid',[0 0 1],[0.5 0.4 0.5]);
empty_obj=empty_obj([]);
frame=@(obs) struct('time_s',0,'uav_position_ekf_m',e.p, ...
    'detected_obstacles',obs,'detected_ids',reshape([obs.id],1,[]), ...
    'detected_count',numel(obs));
R0=g.evaluate(0,e,frame(empty_obj),a);
assert(strcmp(R0.status,'NO_CURRENTLY_DETECTED_OBSTACLES') && ...
    R0.considered_count==0 && ~R0.numeric_request && ...
    ~R0.continuous_observed_set_safe);
g.set_horizon(6.13);
a.runtime.sample_dt_s=0.031; % External dt may change between ticks.
R1=g.evaluate(0,e,frame(empty_obj),a);
assert(R1.horizon_s==6.13 && R1.sample_dt_s==0.031 && ...
    R1.considered_count==0 && R1.runtime_authority_refreshed);
obs=OBSTACLE_INFORMATION.define(101,'ellipsoid',[0 0 1],[0.5 0.4 0.5]);
R2=g.evaluate(0,e,frame(obs),a);
assert(strcmp(R2.status,'UNKNOWN_MODEL_NOT_BOUND') && ...
    ~R2.prediction_available && ~R2.continuous_observed_set_safe && ...
    ~R2.numeric_request && isequal(R2.possible_risk_ids,101));
% SYNTHETIC callback only tests module interface and centerline geometry.
% Its constant 'future' has no claim of actual physical closed-loop behavior.
a.predictor=@synthetic_not_dynamics;
R3=g.evaluate(0,e,frame(obs),a);
assert(strcmp(R3.status,'PREDICTED_SAMPLED_GEOMETRIC_CONTACT') && ...
    R3.sampled_collision && isequal(R3.sampled_collision_ids,101) && ...
    R3.first_sampled_collision_ttc_s==0 && ...
    strcmp(R3.first_sampled_collision_component,'CABLE_CENTERLINE') && ...
    R3.numeric_request && ~R3.safe_to_commit);
R4=g.evaluate(0,e,frame(obs),a);
assert(R4.duplicate_suppressed && ~R4.numeric_request && ~R4.new_event);
% A currently invisible source object must never enter the future check.
R5=g.evaluate(0,e,frame(empty_obj),a);
assert(R5.considered_count==0 && isempty(R5.possible_risk_ids));
R6=g.evaluate(0,e,frame(obs),a);
assert(R6.numeric_request && R6.new_event); % after re-detection
% Incorrect model initial state is fail-closed, not treated as safe.
a.predictor=@invalid_initial_state;
R7=g.evaluate(0,e,frame(obs),a);
assert(strcmp(R7.status,'UNKNOWN_PREDICTOR_ERROR') && ...
    ~R7.continuous_observed_set_safe && ~R7.safe_to_commit);
T=struct('status','PASS_TRIGGER_RUNTIME_CONTRACT_ONLY__NO_LIVE_DYNAMICS', ...
    'checks',8,'horizon_changed_to_s',g.horizon_s, ...
    'no_future_sensing',true,'missing_model_fails_closed',true, ...
    'synthetic_collision_test',true,'no_real_hlc_plant_execution',true);
disp(T.status);

    function out=synthetic_not_dynamics(req)
        n=numel(req.sample_times_s);
        out=struct('sample_times_s',req.sample_times_s, ...
            'uav_m',repmat(req.ekf_now.p,1,n), ...
            'payload_m',repmat(req.ekf_now.pL,1,n), ...
            'model_description','SYNTHETIC_TEST_ONLY_NOT_PHYSICAL');
    end
    function out=invalid_initial_state(req)
        out=synthetic_not_dynamics(req);
        out.uav_m(:,1)=out.uav_m(:,1)+[1;0;0];
    end
end
