function R=CHECK_TRAJECTORY_C9_27_NOMINAL_CHAIN()
% CHECK only. Stored and logged under common_matlab/ (not CWD).
% Degrees 23 and 27 are physically ONE C9 piece, never multiple stages.
% This is NOT an HLC/tube-B/online-planner acceptance test.
root=fileparts(mfilename('fullpath'));
R=struct('status','FAIL_C9_27_NOMINAL_CHAIN','error_message','', ...
    'degree27_exact_line_error',NaN, ...
    'degree27_end_jet_error',NaN, ...
    'tampered_cache_rejected',false, ...
    'degree27_geometry_pass',false, ...
    'degree27_heading_pass',false, ...
    'degree27_torque_pass',false, ...
    'degree27_nominal_chain_pass',false, ...
    'degree27_hlc_execution_proven',false, ...
    'intlab_input_lemma_status','NOT_RUN', ...
    'intlab_input_lemma_pass',false, ...
    'intlab_singularity_rejected',false, ...
    'safe_to_commit',false, ...
    'degree27_total_ms',NaN(1,5), ...
    'degree27_median_ms',NaN, ...
    'degree27_p95_ms',NaN, ...
    'degree27_max_ms',NaN, ...
    'degree27_torque_native_status','NOT_RUN', ...
    'degree27_native_preflight_status','NOT_RUN', ...
    'degree27_native_whole_proven',false, ...
    'certificate_status','NOT_RUN');
try
    N=TRAJECTORY_C9_TORQUE_WHOLE_27_PREFLIGHT(false);
    R.degree27_native_preflight_status=N.status;
    assert(N.ready,'Degree-27 whole-time torque MEX must be explicitly preflight-built.');
    n=27;T=27;v=1;
    Pexact=[zeros(1,n+1);(0:n);3*ones(1,n+1)];
    J0=zeros(3,10);J1=zeros(3,10);
    J0(:,1)=[0;0;3];J1(:,1)=[0;v*T;3];
    J0(:,2)=[0;v;0];J1(:,2)=[0;v;0];
    piece=TRAJECTORY_C9_FLAT_BERNSTEIN.build27( ...
        0,T,J0,J1,Pexact(:,11:18));
    R.degree27_exact_line_error=max(abs(piece.control_points_m(:)-Pexact(:)));
    assert(R.degree27_exact_line_error==0, ...
        'Exact integer-coefficient linear degree27 fixture changed');
    D=TRAJECTORY_C9_FLAT_BERNSTEIN.actual_derivative_controls(piece);
    Jleft=zeros(3,10);Jright=zeros(3,10);
    for k=1:10
        Jleft(:,k)=D{k}(:,1);
        Jright(:,k)=D{k}(:,end);
    end
    R.degree27_end_jet_error=max(abs([Jleft(:)-J0(:);Jright(:)-J1(:)]));
    assert(R.degree27_end_jet_error==0,'Endpoint physical C9 jets changed');
    bad=piece;
    bad.derivative_controls{3}(1,1)=1;
    observed=[OBSTACLE_INFORMATION.define(701,'sphere',[8,5,5],0.5), ...
        OBSTACLE_INFORMATION.define(702,'ellipsoid',[-8,12,5],[0.7,1.1,0.8], ...
          'euler_deg',[13,29,41])];
    a=struct('cable_length_m',2,'payload_mass_kg',0.14, ...
        'uav_mass_kg',1.1,'gravity_world_mps2',[0;0;-9.80665], ...
        'thrust_limits_N',[0;20], ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0, ...
        'uav_inertia_kgm2',[0.012;0.013;0.022], ...
        'torque_limits_Nm',[-1 1;-1 1;-1 1]);
    radii=struct('uav_m',0.3,'cable_m',0.01,'payload_m',0.2);
    g=struct('max_subdivision_depth',8,'max_node_count',900, ...
        'numerical_guard_m',0,'robust_tube_enabled',false, ...
        'trajectory_phase','f','use_exact_direction_cone_support',true, ...
        'use_native_support_separator',false);
    force=struct('max_subdivision_depth',8,'max_node_count',900, ...
        'force_guard_N',0);
    h=struct('max_subdivision_depth',8,'max_node_count',900, ...
        'horizontal_velocity_guard_mps',0,'w_guard_mps2',0, ...
        'payload_jet_tolerance',zeros(3,10), ...
        'uav_jet_tolerance',zeros(3,8), ...
        'yaw_jet_tolerance',zeros(1,7));
    torque=struct('max_subdivision_depth',8,'max_node_count',900, ...
        'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
        'torque_guard_Nm',zeros(3,1), ...
        'use_native_whole_torque_kernel',true);
    B=TRAJECTORY_C9_27_NOMINAL_CHAIN( ...
        bad,observed,radii,a,g,force,h,torque);
    R.tampered_cache_rejected=strcmp(B.status, ...
        'UNKNOWN_C9_27_DERIVATIVE_CACHE_UNBOUND')&&~B.nominal_chain_proven;
    assert(R.tampered_cache_rejected,'Tampered 27 degree cache was accepted');
    for k=1:5
        C=TRAJECTORY_C9_27_NOMINAL_CHAIN( ...
            piece,observed,radii,a,g,force,h,torque);
        R.degree27_total_ms(k)=C.elapsed_ms;
        if k==5
            R.certificate_status=C.status;
            R.degree27_geometry_pass= ~isempty(fieldnames(C.geometry_force)) ...
                && C.geometry_force.certified;
            R.degree27_heading_pass= ~isempty(fieldnames(C.heading)) ...
                && C.heading.certified;
            R.degree27_torque_pass= ~isempty(fieldnames(C.torque)) ...
                && C.torque.conditional_nominal_all_time_torque_proven;
            if ~isempty(fieldnames(C.torque))
                R.degree27_torque_native_status=C.torque.native_whole_torque_status;
                R.degree27_native_whole_proven=C.torque.native_whole_torque_certified;
            end
            R.degree27_nominal_chain_pass=C.nominal_chain_proven;
        end
    end
    sorted=sort(R.degree27_total_ms);
    R.degree27_median_ms=sorted(3);
    R.degree27_p95_ms=sorted(5); % ceil(0.95*5)=5
    R.degree27_max_ms=sorted(5);
    assert(R.degree27_geometry_pass&&R.degree27_heading_pass&& ...
        R.degree27_torque_pass&&R.degree27_nominal_chain_pass&& ...
        R.degree27_native_whole_proven&& ...
        all(isfinite(R.degree27_total_ms))&& ...
        ~C.safe_to_commit&&~C.actual_HLC_tracking_proven, ...
        'Ideal C9 degree-27 nominal chain not completely proven');
    % Separate conditional directed-interval HLC lemma. It never grants
    % state reachability, and may be unavailable without INTLAB.
    if exist('infsup','file')==2 && exist('intval','file')==2
        B=infsup(eye(3),eye(3));
        rhs=infsup(zeros(3,1),zeros(3,1));
        uf=infsup(1,1);
        liveLow=[0;-1;-1;-1];liveHigh=[20;1;1;1];
        H=TRAJECTORY_C9_HLC_FOUR_INPUT_INTERVAL_INTLAB( ...
            liveLow,liveHigh,B,rhs,uf);
        R.intlab_input_lemma_status=H.status;
        R.intlab_input_lemma_pass=H.conditional_4input_bound_proven;
        Bbad=B;Bbad(1,1)=infsup(-1,1);
        Hbad=TRAJECTORY_C9_HLC_FOUR_INPUT_INTERVAL_INTLAB( ...
            liveLow,liveHigh,Bbad,rhs,uf);
        R.intlab_singularity_rejected= ...
            ~Hbad.conditional_4input_bound_proven && ...
            strcmp(Hbad.status,'UNKNOWN_HLC_INTERVAL_BETA2_SINGULARITY');
        assert(R.intlab_input_lemma_pass && R.intlab_singularity_rejected, ...
            'INTLAB conditional 4-input lemma or singularity rejection failed');
    else
        R.intlab_input_lemma_status='UNKNOWN_INTLAB_NOT_INSTALLED';
    end
    R.status='PASS_DEGREE27_NOMINAL_GEOMETRY_C7_YAW_TORQUE__HLC_B_PENDING';
catch ME
    R.error_message=getReport(ME,'extended','hyperlinks','off');
end
% Save regardless of success, with exact project-root output paths.
matfile=fullfile(root,'TRAJECTORY_C9_27_NOMINAL_CHAIN_RESULT.mat');
txtfile=fullfile(root,'TRAJECTORY_C9_27_NOMINAL_CHAIN_RESULT.txt');
zipfile=fullfile(root,'TRAJECTORY_C9_27_NOMINAL_CHAIN_RESULT_FOR_CHATGPT.zip');
save(matfile,'R');
fid=fopen(txtfile,'w');
if fid>=0
    fprintf(fid,'status=%s\n',R.status);
    fprintf(fid,'error_message=%s\n',R.error_message);
    fprintf(fid,'degree27_exact_line_error=%.17g\n',R.degree27_exact_line_error);
    fprintf(fid,'degree27_end_jet_error=%.17g\n',R.degree27_end_jet_error);
    fprintf(fid,'tampered_cache_rejected=%d\n',R.tampered_cache_rejected);
    fprintf(fid,'geometry=%d heading=%d torque=%d chain=%d\n', ...
        R.degree27_geometry_pass,R.degree27_heading_pass, ...
        R.degree27_torque_pass,R.degree27_nominal_chain_pass);
    fprintf(fid,'nominal_chain_timing_ms=%s\n',mat2str(R.degree27_total_ms,7));
    fprintf(fid,'median=%.6g p95=%.6g max=%.6g\n', ...
        R.degree27_median_ms,R.degree27_p95_ms,R.degree27_max_ms);
    fprintf(fid,'torque_native_status=%s\n',R.degree27_torque_native_status);
    fprintf(fid,'preflight_status=%s\n',R.degree27_native_preflight_status);
    fprintf(fid,'intlab_status=%s exact=%d singular_reject=%d\n', ...
        R.intlab_input_lemma_status,R.intlab_input_lemma_pass, ...
        R.intlab_singularity_rejected);
    fprintf(fid,'certificate_status=%s\n',R.certificate_status);
    fclose(fid);
end
try
    if exist(zipfile,'file'),delete(zipfile);end
    zip(zipfile,{'TRAJECTORY_C9_27_NOMINAL_CHAIN_RESULT.mat', ...
        'TRAJECTORY_C9_27_NOMINAL_CHAIN_RESULT.txt'},root);
catch
end
end
