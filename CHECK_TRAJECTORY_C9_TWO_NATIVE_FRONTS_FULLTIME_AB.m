function R=CHECK_TRAJECTORY_C9_TWO_NATIVE_FRONTS_FULLTIME_AB()
% 3 scenes x 4 MATLAB/native combinations x 5 full-time pipeline repeats.
% Only full independent all-time nominal certificates can count as success.
% QP plane support/gradients are compared against legacy construction.
% Proof of tracking, real-HLC inputs, hard WCET and directed roundoff: NONE.
root=fileparts(mfilename('fullpath'));
mod=fullfile(root,'reference','REPLANNING_SYSTEM','TRAJECTORY_GENERATION');
addpath(fullfile(root,'controller'),fullfile(root,'model'),'-begin');
addpath(mod,fullfile(root,'reference','REPLANNING_SYSTEM','OBSTACLE_INFORMATION'),'-begin');
R=struct('status','NOT_RUN','error_message','','completed_trials',zeros(3,4), ...
    'setup_completed',false,'scenario_names',{{'clear_affine','sphere_13D','sphere_ellipsoid_13D'}}, ...
    'mode_names',{{'MATLAB_BOTH','NATIVE_TORQUE','NATIVE_SEPARATOR','NATIVE_BOTH'}}, ...
    'elapsed_ms',NaN(3,4,5),'geometry_ms',NaN(3,4,5), ...
    'planes_ms',NaN(3,4,5),'qp_ms',NaN(3,4,5), ...
    'nominal',false(3,4,5),'errors',{cell(3,4,5)}, ...
    'search_statuses',{cell(3,4,5)},'search_failure_reasons',{cell(3,4,5)}, ...
    'last_oracle_statuses',{cell(3,4,5)}, ...
    'independent_proof_calls',NaN(3,4,5), ...
    'statuses',{cell(3,4,5)},'median_ms',NaN(3,4), ...
    'p95_ms',NaN(3,4),'max_ms',NaN(3,4),'jitter_ms',NaN(3,4), ...
    'success_by_mode',NaN(1,4),'nominal_regressions',NaN, ...
    'batch_executed_count',0,'batch_rows_count',0, ...
    'native_batch_qp_uses',0,'native_separator_proposals',0, ...
    'separator_positive_parity',false,'separator_test_count',0, ...
    'native_batch_ms',NaN(3,4,5), ...
    'torque_jacobian_parity',false,'torque_jacobian_max_relative_error',NaN, ...
    'torque_status_parity',false,'native_preflight','NOT_RUN', ...
    'separator_preflight','NOT_RUN', ...
    'support_tests',0,'support_max_relative_difference',NaN, ...
    'qp_parity_checked',0,'qp_max_relative_difference',NaN, ...
    'safe_to_commit',false,'real_HLC_proven',false);
try
    PF=TRAJECTORY_C9_13D_TORQUE_BATCH_PREFLIGHT(false);
    R.native_preflight=PF.status;
    assert(PF.ready,'C9_NATIVE_13D_AB:Preflight', ...
        'Build MEX before the audit: TRAJECTORY_C9_13D_TORQUE_BATCH_PREFLIGHT(true).');
    PS=TRAJECTORY_C9_SEPARATOR_NATIVE_PREFLIGHT(false);
    R.separator_preflight=PS.status;
    assert(PS.ready,'C9_NATIVE_SEPARATOR_AB:Preflight', ...
        'Build MEX before the audit: TRAJECTORY_C9_SEPARATOR_NATIVE_PREFLIGHT(true).');
    [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    v=double(P.get(["mass","jx","jy","jz","gravity","cableL"]));
    v=v(:);lo=double(lo(:));hi=double(hi(:));
    assert(numel(v)==6&&numel(lo)==4&&numel(hi)==4&&all(v>0), ...
        'C9_NATIVE_13D_AB:Authority','No valid real controller authority fixture.');
    authority=struct('uav_mass_kg',v(1),'payload_mass_kg',0.14, ...
        'cable_length_m',v(6),'uav_inertia_kgm2',v(2:4), ...
        'gravity_world_mps2',[0;0;-v(5)], ...
        'thrust_limits_N',[lo(1) hi(1)], ...
        'torque_limits_Nm',[lo(2:4) hi(2:4)], ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0);
    rad=struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1);
    geometry=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'numerical_guard_m',0,'robust_tube_enabled',false,'trajectory_phase','f');
    force=struct('max_subdivision_depth',6,'max_node_count',127,'force_guard_N',0);
    search=struct('probe_count',13,'max_outer_iterations',4, ...
        'max_projection_sweeps',100,'projection_tolerance_m',1e-8, ...
        'min_separation_m',1e-5, ...
        'enable_13d_variable_time_joint_search',1, ...
        'enable_13d_reuse_nominal_torque_certificate',1, ...
        'use_shared_13d_duration_cache',1, ...
        'enable_13d_shared_jet_kernel',1, ...
        'enable_13d_certificate_leaf_hull_cuts',1, ...
        'enable_13d_physical_leaf_duration_tangent',1, ...
        'enable_13d_payload_witness_leaf_gate',1, ...
        'enable_13d_oracle_body_time_qp_rows',0, ...
        'enable_13d_oracle_body_time_outer_guard',0, ...
        'enable_13d_witness_transverse_plane',0, ...
        'enable_13d_coherent_cable_corridor',0);
    heading=struct('max_subdivision_depth',8,'max_node_count',511, ...
        'horizontal_velocity_guard_mps',0,'w_guard_mps2',0, ...
        'payload_jet_tolerance',1e-7*ones(3,10), ...
        'uav_jet_tolerance',1e-7*ones(3,8), ...
        'yaw_jet_tolerance',1e-7*ones(1,7));
    torque=struct('max_subdivision_depth',8,'max_node_count',511, ...
        'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
        'torque_guard_Nm',zeros(3,1), ...
        'enable_fast_norm_sufficient_bound',true);
    j0=zeros(3,10);j1=j0;
    j0(:,1)=[-2;0;3];j1(:,1)=[2;0;3];
    j0(1,2)=0.4;j1(1,2)=0.4;
    piece=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,10,j0,j1, ...
        repmat([0;0;3],1,4));
    req=struct('t0_s',8,'duration_s',10,'flight_interval_s',[8 30], ...
        'start_jets',j0,'end_jets',j1, ...
        'nominal_free',piece.control_points_m(:,11:14), ...
        'observed',struct([]),'radii',rad,'authority',authority, ...
        'geometry_options',geometry,'force_options',force, ...
        'search_options',search,'heading_options',heading, ...
        'nominal_torque_options',torque,'torque_options',torque);
    a=zeros(3,10);b=a;
    a(:,1)=[0;0;3];b(:,1)=[1;0;3];a(1,2)=0.5;b(1,2)=0.5;
    free=repmat(a(:,1),1,4)+a(:,2)*((2/23)*(10:13));
    cp=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,2,a,b,free);
    clearReq=req;clearReq.duration_s=2;
    clearReq.start_jets=a;clearReq.end_jets=b;
    clearReq.nominal_free=cp.control_points_m(:,11:14);
    sphere=OBSTACLE_INFORMATION.define(21,'sphere',[0 0.1 3],0.2);
    ax=0.34;ay=-0.26;az=0.4;
    Rx=[1 0 0;0 cos(ax) -sin(ax);0 sin(ax) cos(ax)];
    Ry=[cos(ay) 0 sin(ay);0 1 0;-sin(ay) 0 cos(ay)];
    Rz=[cos(az) -sin(az) 0;sin(az) cos(az) 0;0 0 1];
    ell=OBSTACLE_INFORMATION.define(33,'ellipsoid', ...
        [0.6 -0.16 3],[0.32 0.19 0.4],'rotation',Rz*Ry*Rx);
    observed={struct([]),sphere,[sphere ell]};
    TRAJECTORY_C9_STATIC_KERNEL_PREFLIGHT();
    % Exact SAME support function for nonzero and nonunit directions.
    [ncheck,maxerr,nsep]=c9_all12_support_parity();
    R.support_tests=ncheck;R.support_max_relative_difference=maxerr;
    R.separator_test_count=R.separator_test_count+nsep;
    assert(ncheck>=2000&&maxerr<1e-12, ...
        'C9_BATCH_AB:SupportParity','Prepared true-shape support mismatch.');
    % Independently compare the FULL physical local 13D search rows.
    testReq=req;testReq.observed=[sphere ell];
    ss=TRAJECTORY_OBSTACLE_SUPPORT.prepare(testReq.observed);
    ph=(1-cos(pi*(0:12)/12))/2;
    [ga,~]=TRAJECTORY_GROUND_SCOPE(testReq.geometry_options);
    R0=TRAJECTORY_C9_13D_NATURAL_QP(testReq,ss,ph, ...
        [rad.uav_m rad.cable_m rad.payload_m],ga,struct(),0);
    testReq.search_options.enable_13d_batched_geometry_planes=1;
    R1=TRAJECTORY_C9_13D_NATURAL_QP(testReq,ss,ph, ...
        [rad.uav_m rad.cable_m rad.payload_m],ga,struct(),0);
    assert(R0.solved&&R1.solved, ...
        'C9_BATCH_AB:QPModelFixture', ...
        'Both local 13D QPs must be constructed for valid row parity testing.');
    if R0.solved&&R1.solved
        assert(isequal(size(R0.raw_A),size(R1.raw_A))&& ...
            isequal(size(R0.raw_b),size(R1.raw_b)), ...
            'C9_BATCH_AB:QPShapeParity','QP row counts mismatch.');
        dx=max(abs(R0.raw_A(:)-R1.raw_A(:))./(1+abs(R0.raw_A(:))));
        db=max(abs(R0.raw_b(:)-R1.raw_b(:))./(1+abs(R0.raw_b(:))));
        R.qp_max_relative_difference=max(dx,db);R.qp_parity_checked=1;
        assert(R.qp_max_relative_difference<1e-10, ...
            'C9_BATCH_AB:QPValueParity','13D local QP rows changed.');
    end
    % The EXACT same C9 fixture and runtime authority as in the QP.
    % Native outputs are optimization tangents, never a proof.
    testPiece=TRAJECTORY_C9_FLAT_BERNSTEIN.build( ...
        testReq.t0_s,testReq.duration_s,testReq.start_jets, ...
        testReq.end_jets,testReq.nominal_free);
    oldopts=testReq.torque_options;
    oldopts.use_native_13d_torque_batch_kernel=0;
    newopts=oldopts;
    newopts.use_native_13d_torque_batch_kernel=1;
    Z0=TRAJECTORY_C9_TORQUE_FORWARD_JACOBIAN_13D( ...
        testPiece,authority,oldopts,ph);
    Z1=TRAJECTORY_C9_TORQUE_FORWARD_JACOBIAN_13D( ...
        testPiece,authority,newopts,ph);
    R.torque_status_parity=strcmp(Z0.status,Z1.status)&& ...
        isequal(Z0.valid,Z1.valid);
    assert(R.torque_status_parity&&any(Z0.valid)&& ...
        Z1.native_torque_batch_executed, ...
        'C9_NATIVE_13D_AB:StatusParity', ...
        'Native pointwise torque statuses differ from MATLAB.');
    tv=Z0.valid;
    D0=Z0.gradient_Nm_per_physical(:,:,tv);
    D1=Z1.gradient_Nm_per_physical(:,:,tv);
    t0=Z0.torque_Nm(:,tv);t1=Z1.torque_Nm(:,tv);
    errD=max(abs(D0(:)-D1(:))./(1+abs(D0(:))));
    errT=max(abs(t0(:)-t1(:))./(1+abs(t0(:))));
    R.torque_jacobian_max_relative_error=max(errD,errT);
    assert(isfinite(R.torque_jacobian_max_relative_error)&& ...
        R.torque_jacobian_max_relative_error<1e-9, ...
        'C9_NATIVE_13D_AB:ValueParity', ...
        'Native 13D point Jacobian differs from the MATLAB formulas.');
    R.torque_jacobian_parity=true;
    % Native separator can propose normals, but MATLAB MUST independently
    % validate using the SAME canonical support predicate for every shape.
    Ssh=TRAJECTORY_OBSTACLE_SUPPORT.prepare([sphere ell]);
    H=[2.4 2.5 2.35;1.4 1.35 1.48;3 3.01 3.04];
    for j=1:numel(Ssh)
        [baseOK,~,~,~,~,baseUsed]=TRAJECTORY_C9_SUPPORT_SEPARATOR( ...
            H,Ssh(j),0.01,mean(H,2),64,false);
        [nativeOK,normal,~,~,~,nativeUsed]=TRAJECTORY_C9_SUPPORT_SEPARATOR( ...
            H,Ssh(j),0.01,mean(H,2),64,true);
        assert(baseOK==nativeOK&&nativeUsed&&~baseUsed, ...
            'C9_NATIVE_SEPARATOR_AB:NormalParity', ...
            'Native separator unexpectedly changed proven separation status.');
        if nativeOK
            assert(min(normal.'*H)> ...
                TRAJECTORY_OBSTACLE_SUPPORT.value(Ssh(j),normal)+0.01, ...
                'C9_NATIVE_SEPARATOR_AB:IndependentProof', ...
                'Native proposal was not independently certified.');
        end
        R.separator_test_count=R.separator_test_count+1;
    end
    R.separator_positive_parity=true;
    R.setup_completed=true;
    for scene=1:3
        if scene==1,base=clearReq;else,base=req;end
        base.observed=observed{scene};
        for mode=1:4
            base.search_options.enable_13d_batched_geometry_planes=1;
            base.torque_options.use_native_13d_torque_batch_kernel= ...
                ismember(mode,[2 4]);
            base.geometry_options.use_native_support_separator= ...
                ismember(mode,[3 4]);
            % Prepare both JIT paths before any timed samples.
            try,TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(base);catch, end
            for trial=1:5
                start=tic;
                try
                    V=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(base);
                    R.elapsed_ms(scene,mode,trial)=V.total_elapsed_ms;
                    R.geometry_ms(scene,mode,trial)=V.joint_geometry_force_proof_ms;
                    R.planes_ms(scene,mode,trial)=V.separation_planes_ms;
                    R.qp_ms(scene,mode,trial)=V.joint_QP_ms;
                    R.nominal(scene,mode,trial)=V.nominal_model_complete;
                    R.statuses{scene,mode,trial}=V.status;
                    R.search_statuses{scene,mode,trial}=V.search_status;
                    R.independent_proof_calls(scene,mode,trial)=V.proof_calls;
                    if isfield(V.search_result,'failure_reason')
                        R.search_failure_reasons{scene,mode,trial}= ...
                            V.search_result.failure_reason;
                    end
                    if isfield(V.search_result,'duration_13d_last_oracle_status')
                        R.last_oracle_statuses{scene,mode,trial}= ...
                            V.search_result.duration_13d_last_oracle_status;
                    end
                    R.completed_trials(scene,mode)=R.completed_trials(scene,mode)+1;
                    R.batch_executed_count=R.batch_executed_count+V.batched_geometry_qp_uses;
                    R.batch_rows_count=R.batch_rows_count+V.batched_geometry_qp_rows;
                    R.native_batch_qp_uses=R.native_batch_qp_uses+ ...
                        V.native_torque_batch_qp_uses;
                    R.native_separator_proposals= ...
                        R.native_separator_proposals+V.native_separator_proposals;
                    R.native_batch_ms(scene,mode,trial)=V.native_torque_batch_qp_ms;
                    assert(~V.safe_to_commit&&~V.actual_HLC_tracking_proven, ...
                        'C9_BATCH_AB:UnsafeCommit','Nominal-only proof cannot COMMIT.');
                catch ME
                    R.elapsed_ms(scene,mode,trial)=1000*toc(start);
                    R.errors{scene,mode,trial}=[ME.identifier ' | ' ME.message];
                    R.statuses{scene,mode,trial}='MATLAB_EXCEPTION_NOT_PROVEN';
                end
            end
            t=reshape(R.elapsed_ms(scene,mode,:),[],1);
            R.median_ms(scene,mode)=median(t);t=sort(t);
            R.p95_ms(scene,mode)=t(ceil(.95*numel(t)));
            R.max_ms(scene,mode)=max(t);
            R.jitter_ms(scene,mode)=max(t)-min(t);
        end
    end
    good=false(3,4);
    for scene=1:3
        for mode=1:4
            good(scene,mode)=R.completed_trials(scene,mode)==5 && ...
                all(reshape(R.nominal(scene,mode,:),[],1));
        end
    end
    R.success_by_mode=sum(good,1);
    R.nominal_regressions=nnz(repmat(good(:,1),1,3)&~good(:,2:4));
    if any(R.completed_trials(:)~=5)||R.nominal_regressions>0 || ...
            R.batch_executed_count==0||R.native_batch_qp_uses==0|| ...
            ~R.separator_positive_parity|| ...
            any(~cellfun(@isempty,R.errors(:)))
        R.status='DO_NOT_ENABLE_NATIVE_13D__PARITY_REGRESSION_OR_EXCEPTION';
    else
        R.status='PASS_TWO_NATIVE_FRONTS__MODEL_HLC_WCET_PENDING';
    end
catch ME
    R.status='FAIL_NATIVE_13D_SETUP_OR_PARITY';
    R.error_message=ME.getReport('extended','hyperlinks','off');
end
base='TRAJECTORY_C9_TWO_NATIVE_FRONTS_FULLTIME_AB_RESULT';
matPath=fullfile(root,[base '.mat']);txtPath=fullfile(root,[base '.txt']);
zipPath=fullfile(root,[base '_FOR_CHATGPT.zip']);
save(matPath,'R');fid=fopen(txtPath,'w');
if fid<0,error('C9_BATCH_AB:CannotSave','Result path cannot be opened.');end
fprintf(fid,'status=%s\nerror=%s\n',R.status,R.error_message);
fprintf(fid,'native_preflight=%s jac_parity=%d max_relative=%.12g native_uses=%d\n', ...
    R.native_preflight,R.torque_jacobian_parity, ...
    R.torque_jacobian_max_relative_error,R.native_batch_qp_uses);
fprintf(fid,'separator_preflight=%s independent_sep_parity=%d tests=%d native_proposals=%d\n', ...
    R.separator_preflight,R.separator_positive_parity, ...
    R.separator_test_count,R.native_separator_proposals);
fprintf(fid,'support_tests=%d max_rel=%.12g\n',R.support_tests, ...
    R.support_max_relative_difference);
fprintf(fid,'QP_checked=%d qp_max_rel=%.12g\n', ...
    R.qp_parity_checked,R.qp_max_relative_difference);
fprintf(fid,'completed=%s successes=%s regressions=%g\n', ...
    mat2str(R.completed_trials),mat2str(R.success_by_mode),R.nominal_regressions);
fprintf(fid,'batch_qp_calls=%d rows=%d\n', ...
    R.batch_executed_count,R.batch_rows_count);
for scene=1:3
    for mode=1:4
        fprintf(fid,'scene=%s mode=%s median=%.7f p95=%.7f max=%.7f jitter=%.7f\n', ...
            R.scenario_names{scene},R.mode_names{mode}, ...
            R.median_ms(scene,mode),R.p95_ms(scene,mode), ...
            R.max_ms(scene,mode),R.jitter_ms(scene,mode));
        % Failed scenes are differentiated by the ACTUAL search and oracle
    % statuses, not guessed from the final integrated UNKNOWN label.
    for trial=1:5
        if ~R.nominal(scene,mode,trial)
            fprintf(fid,'failure scene=%s mode=%s trial=%d search=%s oracle=%s reason=%s\n', ...
                R.scenario_names{scene},R.mode_names{mode},trial, ...
                scalar_text(R.search_statuses{scene,mode,trial}), ...
                scalar_text(R.last_oracle_statuses{scene,mode,trial}), ...
                scalar_text(R.search_failure_reasons{scene,mode,trial}));
        end
    end
    end
end
fclose(fid);
if exist(zipPath,'file')==2,delete(zipPath);end
zip(zipPath,{matPath,txtPath});
end


function [num,maxerr,nsep]=c9_all12_support_parity()
% Independent MATLAB scalar-versus-batch oracle for ALL supported kinds.
% The prepared representative shapes are test fixtures, not sensed data or
% a precomputed obstacle layout for online Flight.
a=0.7;z=0.6;
Vpy=[a a -z;a -a -z;-a a -z;-a -a -z;0 0 z];
theta=2*pi*(0:6).'/7;
Vrp=[0.9*cos(theta),0.9*sin(theta)];
Vrp=[Vrp,-0.5*ones(7,1);Vrp,0.5*ones(7,1)];
Vpo=[-0.7 -0.1;0.1 -0.7;0.8 -0.2;0.5 0.7;-0.6 0.5];
Vpr=[Vpo,-0.5*ones(size(Vpo,1),1); ...
    Vpo,0.5*ones(size(Vpo,1),1)];
Vph=[0 0 0.8;0.7 0 0;0 0.6 0;-0.7 0 0;0 -0.6 0;0 0 -0.8];
K={'sphere','ellipsoid','box','cylinder','capsule','cone', ...
    'frustum','torus','pyramid','regular_prism','polygon_prism','polyhedron'};
D={0.6,[0.7 0.8 0.9],[0.7 0.8 0.9],[0.6 1.2], ...
    [0.6 1.2],[0.6 1.2],[0.6 0.2 1.2],[0.6 0.2], ...
    [2*a 2*z],[7 0.9 1.0],struct('outline',Vpo,'height',1.0), ...
    struct('vertices',Vph)};
Vs={[],[],[],[],[],[],[],[],Vpy,Vrp,Vpr,Vph};
num=0;maxerr=0;nsep=0;
for shape_id=1:12
    angle=shape_id*0.09;
    ax=[1 0 0;0 cos(angle) -sin(angle);0 sin(angle) cos(angle)];
    ay=[cos(angle/2) 0 sin(angle/2);0 1 0;-sin(angle/2) 0 cos(angle/2)];
    az=[cos(angle/3) -sin(angle/3) 0;sin(angle/3) cos(angle/3) 0;0 0 1];
    % Match TRAJECTORY_OBSTACLE_SUPPORT.prepare's canonical 0x3 empty
    % vertex matrix (rather than MATLAB [] / 0x0 fixture shorthand).
    V=Vs{shape_id};
    if isempty(V), V=zeros(0,3); end
    S=struct('id',shape_id,'kind',K{shape_id},'dim',D{shape_id}, ...
        'center',[0.1;-0.2;0.3],'R',az*ay*ax, ...
        'local_vertices',V);
    for j=1:11
        n=randn(3,20);
        batched=TRAJECTORY_C9_SUPPORT_BATCH(S,n);
        for k=1:20
            single=TRAJECTORY_OBSTACLE_SUPPORT.value(S,n(:,k));
            err=abs(single-batched(k))/(1+abs(single));
            maxerr=max(maxerr,err);
            num=num+1;
        end
    end
    % Every canonical shape, including vertex hulls and rotated bodies:
    % native proposes a normal; MATLAB independently proves its margin.
    H=S.center+[5 5.1 4.9;0.1 0.14 0.08;0 0.03 -0.02];
    % Call the MEX directly before wrapper parity.  Wrapper failure is
    % intentionally fail-closed to MATLAB and otherwise hides a MEX input
    % rejection behind native_used=false; direct call identifies the shape.
    try
        [directNormal,directProposed,~,~]= ...
            TRAJECTORY_C9_SEPARATOR_NORMAL_NATIVE(H,S,0.01,mean(H,2),64);
    catch ME
        error('C9_NATIVE_SEPARATOR_AB:DirectMEXShape', ...
            'Canonical shape %d (%s): native call failed: %s | %s', ...
            shape_id,K{shape_id},ME.identifier,ME.message);
    end
    assert(directProposed&&isequal(size(directNormal),[3 1])&& ...
        all(isfinite(directNormal))&& ...
        min(directNormal.'*H)> ...
        TRAJECTORY_OBSTACLE_SUPPORT.value(S,directNormal)+0.01, ...
        'C9_NATIVE_SEPARATOR_AB:DirectMEXProof', ...
        'Native proposal for shape %d (%s) failed independent support.', ...
        shape_id,K{shape_id});
    [baseOK,~,~,~,~,baseUsed]=TRAJECTORY_C9_SUPPORT_SEPARATOR( ...
        H,S,0.01,mean(H,2),64,false);
    [nativeOK,normal,~,~,~,nativeUsed]=TRAJECTORY_C9_SUPPORT_SEPARATOR( ...
        H,S,0.01,mean(H,2),64,true);
    % A proved cheap MATLAB normal may now return BEFORE native proposal.
    % This is intentional: no MEX is needed once the original support
    % function already certifies strict separation. Direct native
    % acceptance was independently audited just above.
    if ~(baseOK&&nativeOK&&~baseUsed)
        error('C9_NATIVE_SEPARATOR_AB:AllShapes', ...
            ['Shape %d (%s): MATLAB_ok=%d candidate_ok=%d ' ...
             'native_invoked=%d baseline_native=%d; parity failure.'], ...
            shape_id,K{shape_id},baseOK,nativeOK,nativeUsed,baseUsed);
    end
    assert(min(normal.'*H)> ...
        TRAJECTORY_OBSTACLE_SUPPORT.value(S,normal)+0.01, ...
        'C9_NATIVE_SEPARATOR_AB:AllShapesProof', ...
        'Unverified native proposal on rotated canonical shape.');
    nsep=nsep+1;
end
