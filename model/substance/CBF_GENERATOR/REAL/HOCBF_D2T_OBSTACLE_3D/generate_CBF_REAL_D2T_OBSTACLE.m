function result=generate_CBF_REAL_D2T_OBSTACLE()
% Recreate isolated generated evaluators ONLY under this scheme folder.
% Follows the original REAL/XY's source-to-GENERATED copying convention.
root=fileparts(mfilename('fullpath'));destDir=fullfile(root,'GENERATED');
if ~isfolder(destDir),mkdir(destDir);end
pairs={ ...
 'CBF_REAL_D2T_JET_SOURCE.m','CBF_REAL_D2T_JET.m'; ...
 'CBF_REAL_D2T_OBSTACLE_EVAL_SOURCE.m','CBF_REAL_D2T_OBSTACLE_EVAL.m'; ...
 'CBF_REAL_D2T_SAMPLED_EVAL_SOURCE.m','CBF_REAL_D2T_SAMPLED_EVAL.m'};
result=struct('sourceDir',root,'files',{{}},'order',4, ...
 'extendedStateDimension',21,'barrierMemoryDimensionPerObstacle',4, ...
 'controlledInputIndices',[1;2;3], ...
 'controlNames',{{'Delta2T_N','tauX','tauY'}}, ...
 'physicalStateDimension',19,'discreteThrustSecondDifference',true,'discreteBarrierStages',4, ...
 'groundConstraints',false, ...
 'bodyTiltConstraints',false,'cableTiltConstraints',false, ...
 'thrustIsZOH',true,'generatedDiscreteMap',true,'runtimeEvaluator','CBF_REAL_D2T_SAMPLED_EVAL', ...
 'fourGainsUsed',true,'objectiveNormalizedByInputRanges',true, ...
 'realTimeCertified',false,'intersampleCertified',false);
for k=1:size(pairs,1)
    src=fullfile(root,pairs{k,1});dest=fullfile(destDir,pairs{k,2});
    assert(isfile(src),'CBFD2T:MissingSource','Missing %s',src);
    txt=fileread(src);old=erase(pairs{k,1},'.m');new=erase(pairs{k,2},'.m');
    if isempty(regexp(txt,['(?m)^function\s+\w+\s*=\s*' old '\('],'once'))
        error('CBFD2T:Signature','Unexpected source signature %s',src);
    end
    txt=strrep(txt,old,new);
    f=fopen(dest,'w');
    if f<0,error('CBFD2T:Write','Cannot write %s',dest);end
    c=onCleanup(@()fclose(f));fprintf(f,'%s',txt);clear c
    result.files{end+1}=dest; %#ok<AGROW>
    fprintf('[CBF D2T GENERATE] %s\n',dest);
end
rehash
end
