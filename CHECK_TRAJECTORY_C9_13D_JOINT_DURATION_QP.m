function R=CHECK_TRAJECTORY_C9_13D_JOINT_DURATION_QP()
% Temporary, removable CHECK. This is NOT an HLC flight certificate.
% 13D torque Jacobian is compared at FIXED NORMALIZED PHASE while T varies.
% Result files are saved next to this CHECK in common_matlab (pwd-independent).
root=fileparts(mfilename('fullpath'));
name='TRAJECTORY_C9_13D_JOINT_DURATION_QP_RESULT';
R=struct('status','FAIL_NOT_STARTED','stage','INIT', ...
    'error_identifier','','error_message','','error_stack',{{}}, ...
    'max_torque_value_error_Nm',NaN, ...
    'max_free_torque_jacobian_relative_error',NaN, ...
    'max_duration_torque_jacobian_relative_error',NaN, ...
    'H_min_eigenvalue',NaN,'H_condition',NaN, ...
    'QP_duration_increment_s',NaN, ...
    'QP_primal_residual',NaN, ...
    'shape_plane_count',0,'ground_plane_count',0, ...
    'torque_plane_count',0, ...
    'qp_model_time_ms',NaN,'gradient_time_ms',NaN, ...
    'smoke_13d_search_status','NOT_RUN', ...
    'smoke_13d_search_ms',NaN,'smoke_safe_to_commit',false, ...
    'safe_to_commit',false,'actual_HLC_tracking_proven',false, ...
    'scope','13D_LOCAL_QP_AND_NOMINAL_TORQUE_JACOBIAN_PARITY__NOT_ALL_TIME_OR_HLC', ...
    'zip_path',fullfile(root,[name '_FOR_CHATGPT.zip']));
try
    addpath(fullfile(root,'reference','REPLANNING_SYSTEM', ...
        'TRAJECTORY_GENERATION'),'-begin');
    addpath(fullfile(root,'reference','REPLANNING_SYSTEM', ...
        'OBSTACLE_INFORMATION'),'-begin');
    R.stage='CANONICAL_C9_FIXED_PHYSICAL_ENDPOINT_JETS';
    J0=zeros(3,10);J1=zeros(3,10);
    J0(:,1)=[0;0;5];J1(:,1)=[6;1.2;5];
    J0(:,2)=[1;0.2;0];J1(:,2)=[1;0.2;0];
    T=6;t0=4;
    k=10:13;
    free=[6*k/23;1.2*k/23+[0.04 -0.06 0.05 -0.03]; ...
          [5.015 4.980 5.010 5.000]];
    p=TRAJECTORY_C9_FLAT_BERNSTEIN.build(t0,T,J0,J1,free);
    u=[0.17 0.31 0.57 0.83];
    authority=struct('gravity_world_mps2',[0;0;-9.80665], ...
        'cable_length_m',2,'uav_mass_kg',1.5, ...
        'payload_mass_kg',0.18, ...
        'uav_inertia_kgm2',[0.020;0.030;0.040], ...
        'torque_limits_Nm',[-1 1;-1 1;-1 1]);
    o=struct('minimum_force_z_N',0, ...
        'minimum_planar_speed_mps',0, ...
        'torque_guard_Nm',zeros(3,1), ...
        'use_vectorized_bernstein_point_jets',true);
    R.stage='13D_NOMINAL_TORQUE_POINT_JACOBIAN';
    tic;Z=TRAJECTORY_C9_TORQUE_FORWARD_JACOBIAN_13D( ...
        p,authority,o,u);R.gradient_time_ms=1000*toc;
    assert(all(Z.valid), ...
        'C9_13D_CHECK:TorqueSingular',Z.status);
    ref=TRAJECTORY_C9_TORQUE_POINT_EVALUATE( ...
        p,authority,o,t0+T*u);
    assert(all(ref.valid), 'C9_13D_CHECK:PointModel',ref.status);
    R.max_torque_value_error_Nm= ...
        max(abs(Z.torque_Nm-ref.torque_Nm),[],'all');
    assert(R.max_torque_value_error_Nm<1e-7, ...
        'C9_13D_CHECK:TorqueValueParity','Nominal torque model mismatch.');
    maxF=0;maxT=0;
    for j=[1 3 6 9 12 13]
        h=1e-5;
        Fplus=free;Fminus=free;Tp=T;Tm=T;
        if j<=12
            d=zeros(3,4);d(j)=h;
            Fplus=free+d;Fminus=free-d;
        else
            h=1e-4*T;Tp=T+h;Tm=T-h;
        end
        plus=TRAJECTORY_C9_FLAT_BERNSTEIN.build( ...
            t0,Tp,J0,J1,Fplus);
        minus=TRAJECTORY_C9_FLAT_BERNSTEIN.build( ...
            t0,Tm,J0,J1,Fminus);
        Pp=TRAJECTORY_C9_TORQUE_POINT_EVALUATE( ...
            plus,authority,o,t0+Tp*u);
        Pm=TRAJECTORY_C9_TORQUE_POINT_EVALUATE( ...
            minus,authority,o,t0+Tm*u);
        assert(all(Pp.valid)&&all(Pm.valid), ...
            'C9_13D_CHECK:FDPointSingularity','Finite-difference fixture singular.');
        df=(Pp.torque_Nm-Pm.torque_Nm)/(2*h);
        target=squeeze(Z.gradient_Nm_per_physical(:,j,:));
        rel=max(abs(df-target),[],'all')/max(1,max(abs(target),[],'all'));
        if j==13,maxT=max(maxT,rel);else,maxF=max(maxF,rel);end
    end
    R.max_free_torque_jacobian_relative_error=maxF;
    R.max_duration_torque_jacobian_relative_error=maxT;
    assert(maxF<1e-3&&maxT<1e-3, ...
        'C9_13D_CHECK:Gradient','13D analytic torque gradient mismatch.');
    R.stage='13D_ONE_QP_ALL_SHAPES_AND_GROUND';
    a=struct('id',1,'type','sphere','dimensions',0.35, ...
        'center0',[3;0.6;5], 'is_stationary',true, ...
        'rotation',eye(3));
    b=struct('id',2,'type','ellipsoid','dimensions',[0.45 0.25 0.65], ...
        'center0',[4;0.4;5.2], 'is_stationary',true, ...
        'rotation',eye(3));
    shapes=TRAJECTORY_OBSTACLE_SUPPORT.prepare([a b]);
    req=struct('t0_s',t0,'duration_s',T, ...
        'start_jets',J0,'end_jets',J1,'nominal_free',free, ...
        'authority',authority,'flight_interval_s',[t0-2,t0+15], ...
        'geometry_options',struct('numerical_guard_m',0, ...
            'robust_tube_enabled',0,'trajectory_phase','f'), ...
        'search_options',struct('min_separation_m',0.01, ...
            'projection_tolerance_m',1e-7, ...
            'max_projection_sweeps',50,'probe_count',5), ...
        'torque_options',o);
    tic;Q=TRAJECTORY_C9_13D_NATURAL_QP( ...
        req,shapes,u,[0.12 0.01 0.15],true);
    R.qp_model_time_ms=1000*toc;
    assert(Q.solved,'C9_13D_CHECK:QPModel',Q.status);
    R.shape_plane_count=Q.obstacle_plane_count;
    R.ground_plane_count=Q.ground_plane_count;
    R.torque_plane_count=Q.torque_search_plane_count;
    assert(Q.obstacle_plane_count>=numel(shapes)*numel(u)*3, ...
        'C9_13D_CHECK:Shapes','Not all shapes and bodies represented.');
    assert(Q.ground_plane_count==3*numel(u), ...
        'C9_13D_CHECK:Ground','Missing ground body constraints.');
    assert(Q.torque_search_plane_count==6*numel(u), ...
        'C9_13D_CHECK:Torques','Missing three-axis point constraints.');
    H=0.5*(Q.H+Q.H.');
    ev=eig(H);R.H_min_eigenvalue=min(ev);
    R.H_condition=cond(H);
    assert(all(ev>0)&&all(isfinite(ev)), ...
        'C9_13D_CHECK:Metric','Natural physical metric not positive definite.');
    % A manufactured duration inequality tests the EXISTING QP projection
    % in 13 dimensions. No pointwise test is a safety certificate.
    grad=zeros(13,1);grad(13)=1;
    Aw=Q.chol_upper.'\grad;
    [zz,qp]=TRAJECTORY_C9_JOINT_SCREENED_PROJECTION( ...
        Aw,0.25,200,1e-8);
    assert(qp.solved,'C9_13D_CHECK:Projection',qp.status);
    dx=Q.chol_upper\zz;
    R.QP_duration_increment_s=dx(13);
    R.QP_primal_residual=qp.maximum_primal_violation;
    assert(dx(13)>=0.25-1e-7, ...
        'C9_13D_CHECK:Duration','13D QP cannot update duration.');
    % One short synthetic end-to-end entry smoke check. It is deliberately
    % not a Flight performance benchmark or a real HLC proof. A failed
    % nominal certificate is reported as UNKNOWN, never hidden as PASS.
    R.stage='SINGLE_13D_SEARCH_BRANCH_SMOKE';
    u0=zeros(3,10);u1=zeros(3,10);
    u0(:,1)=[0;0;5];u1(:,1)=[2;0;5];
    u0(1,2)=1;u1(1,2)=1;
    f0=[(10:13)*2/23;zeros(1,4);5*ones(1,4)];
    smoke=req;smoke.t0_s=4;smoke.duration_s=2;
    smoke.flight_interval_s=[4 10];
    smoke.start_jets=u0;smoke.end_jets=u1;
    smoke.nominal_free=f0;
    smoke.observed=struct([]);
    smoke.radii=struct('uav_m',0.12,'cable_m',0.01,'payload_m',0.15);
    smoke.geometry_options.max_subdivision_depth=6;
    smoke.geometry_options.max_node_count=127;
    smoke.force_options=struct('max_subdivision_depth',6, ...
        'max_node_count',127,'force_guard_N',0);
    smoke.authority.thrust_limits_N=[0 20];
    smoke.authority.minimum_tension_N=0;
    smoke.authority.acceleration_guard_mps2=0;
    smoke.torque_options.max_subdivision_depth=6;
    smoke.torque_options.max_node_count=127;
    smoke.search_options.max_outer_iterations=1;
    smoke.search_options.enable_13d_variable_time_joint_search=1;
    tic;Zsmoke=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(smoke);
    R.smoke_13d_search_ms=1000*toc;
    R.smoke_13d_search_status=Zsmoke.status;
    R.smoke_safe_to_commit=Zsmoke.safe_to_commit;
    assert(~R.smoke_safe_to_commit, ...
        'C9_13D_CHECK:Commit','Nominal 13D branch must never COMMIT.');
    R.status='PASS_LOCAL_13D_TIME_AND_TORQUE_QP__NOT_ALL_TIME_NOT_HLC';
catch ME
    R.status='FAIL_13D_QP';
    R.error_identifier=ME.identifier;
    R.error_message=ME.message;
    R.error_stack=arrayfun(@(x)sprintf('%s:%d',x.name,x.line), ...
        ME.stack,'UniformOutput',false);
end
save(fullfile(root,[name '.mat']),'R');
fid=fopen(fullfile(root,[name '.txt']),'w');
if fid>=0
    fprintf(fid,'status=%s stage=%s error=%s %s\n', ...
        R.status,R.stage,R.error_identifier,R.error_message);
    fprintf(fid,'torque_point_value_Nm_error=%.12g\n', ...
        R.max_torque_value_error_Nm);
    fprintf(fid,'jacobian_free_rel=%.12g duration_rel=%.12g\n', ...
        R.max_free_torque_jacobian_relative_error, ...
        R.max_duration_torque_jacobian_relative_error);
    fprintf(fid,'H_min_eigen=%.12g condition=%.12g\n', ...
        R.H_min_eigenvalue,R.H_condition);
    fprintf(fid,'shape=%d ground=%d torque=%d\n', ...
        R.shape_plane_count,R.ground_plane_count,R.torque_plane_count);
    fprintf(fid,'QP_duration_step=%.12g primal=%.12g\n', ...
        R.QP_duration_increment_s,R.QP_primal_residual);
    fprintf(fid,'smoke_status=%s smoke_ms=%.9f smoke_commit=%d\n', ...
        R.smoke_13d_search_status,R.smoke_13d_search_ms,R.smoke_safe_to_commit);
    fprintf(fid,'model_ms=%.9f gradient_ms=%.9f\n', ...
        R.qp_model_time_ms,R.gradient_time_ms);
    for i=1:numel(R.error_stack),fprintf(fid,'stack=%s\n',R.error_stack{i});end
    fprintf(fid,'safe_to_commit=%d actual_HLC_tracking_proven=%d\n', ...
        R.safe_to_commit,R.actual_HLC_tracking_proven);
    fclose(fid);
end
zip(R.zip_path,{[name '.mat'],[name '.txt']},root);
fprintf('[C9 13D JOINT] %s\n',R.status);
end
