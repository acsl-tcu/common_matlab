function R=CHECK_TRAJECTORY_CANDIDATE_FEASIBILITY()
% Integration regression for IN-NLP reference constraints (not real solver).
% Put at common_matlab/; write result there. No HLC reference is changed.
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'reference','REPLANNING_SYSTEM');
addpath(fullfile(base,'TRAJECTORY_GENERATION'), ...
    fullfile(base,'OBSTACLE_INFORMATION'));
assert(exist('TRAJECTORY_C7_NLP_FEASIBILITY','file')==2&& ...
    exist('TRAJECTORY_C7_ENTRY_CONSISTENCY','file')==2, ...
    'CHECK_CANDIDATE_FEASIBILITY:Install', ...
    'Modified trajectory files not installed.');
% Synthetic exactly linear, positive horizontal velocity and taut initial
% cable. This is NOT a standalone UAV/load dynamics experiment.
U=zeros(3,8);L=zeros(3,8);L(3,1)=-2;
U(1,2)=1;L(1,2)=1;
V=U;W=L;V(1,1)=2;W(1,1)=2;
q=struct('t0_s',0,'duration_s',2, ...
    'start_jets',struct('uav',U,'payload',L), ...
    'end_jets',struct('uav',V,'payload',W), ...
    'nominal_free',struct('uav',zeros(3,8), ...
        'payload',zeros(3,8)), ...
    'observed',[ ...
        OBSTACLE_INFORMATION.define(41,'sphere',[0 4 0],0.2), ...
        OBSTACLE_INFORMATION.define(43,'box',[0 -4 0],[0.4 0.6 1], ...
            'euler_deg',[15 28 52])], ...
    'physical_radii',struct('uav_m',0.05, ...
        'payload_m',0.05,'cable_m',0.01), ...
    'proof_options',struct('robust_tube_enabled',false, ...
        'min_separation_m',0.02,'numerical_guard_m',1e-10, ...
        'max_subdivision_depth',3), ...
    'search_options',struct('time_leaf_depth',1, ...
        'max_constraint_rows',1000,'max_leaf_count',2, ...
        'feasibility_tolerance',1e-8,'endpoint_jet_tolerance',1e-7), ...
    'solver_options',struct(),'solver_function',@identity_solver);
% In exact degree-23 linear motion the free controls are x=2*i/23,
% i=8...15 (MATLAB control indices 9...16).
for j=1:8
    q.nominal_free.uav(1,j)=2*(j+7)/23;
    q.nominal_free.payload(:,j)=q.nominal_free.uav(:,j)+[0;0;-2];
end
limits=struct('uav',struct('derivative_norm_max', ...
    [2 1 1 10 100 1000]), ...
    'payload',struct('derivative_norm_max',[2 1 1 10 100 1000]));
entry=struct('ekf_now',struct('p',U(:,1),'v',U(:,2), ...
    'pL',L(:,1),'vL',L(:,2)), 'cable_length_m',2, ...
    'position_tolerance_m',1e-8, ...
    'velocity_tolerance_mps',1e-8, ...
    'cable_length_tolerance_m',1e-8, ...
    'cable_length_rate_tolerance_mps',1e-8);
q.candidate_feasibility=struct('derivative_limits',limits, ...
    'entry',entry,'heading_options',struct( ...
    'max_subdivision_depth',2,'numerical_guard_mps',1e-10));
G=TRAJECTORY_GENERATOR(struct('ROBUST_TUBE_ENABLED',false));
A=G.search_reference_feasible_candidate(q);
assert(A.candidate_available&&A.certified_geometry&& ...
    A.candidate_kinematics_enforced&& ...
    A.kinematic_certificate.uav.certified&& ...
    A.kinematic_certificate.payload.certified&& ...
    A.heading_certificate.certified&& ...
    A.kinematic_inequality_count==492&& ...
    A.geometry_inequality_count==384&& ...
    A.inequality_count==876&&~A.safe_to_commit, ...
    'CHECK_CANDIDATE_FEASIBILITY:Good', ...
    'In-solve derivative constraints not enforced/certified.');
% A limit that the known motion violates must be exposed to the solver as
% an inequality violation, not silently fixed in post-check.
bad=q;
bad.candidate_feasibility.derivative_limits.uav.derivative_norm_max(1)=0.5;
B=G.search_reference_feasible_candidate(bad);
assert(~B.candidate_available && ~B.safe_to_commit && ...
    B.kinematic_inequality_count==492, ...
    'CHECK_CANDIDATE_FEASIBILITY:Speed', ...
    'Live over-speed bound not imposed on the solver.');
% A live EKF mismatch must stop BEFORE any NLP iteration.
mismatch=q;
mismatch.candidate_feasibility.entry.ekf_now.p(1)=0.2;
C=G.search_reference_feasible_candidate(mismatch);
assert(strcmp(C.status,'REJECT_ENTRY_STATE_NOT_CONSISTENT')&& ...
    ~C.candidate_available&&~C.safe_to_commit, ...
    'CHECK_CANDIDATE_FEASIBILITY:Now', ...
    'EKF-now mismatch did not fail closed before optimization.');
% A taut cable's initial radial speed must vanish as well. This case
% matches the EKF endpoint jets exactly yet violates the cable constraint.
radial=q;
radial.start_jets.payload(3,2)=0.1;
radial.candidate_feasibility.entry.ekf_now.vL(3)=0.1;
E=G.search_reference_feasible_candidate(radial);
assert(strcmp(E.status,'REJECT_ENTRY_STATE_NOT_CONSISTENT')&& ...
    E.entry_consistency.cable_radial_velocity_error_mps>0.09&& ...
    ~E.safe_to_commit, ...
    'CHECK_CANDIDATE_FEASIBILITY:TautRate', ...
    'A taut cable radial velocity contradiction was silently accepted.');
% Geometry-only legacy adapter remains intact (and cannot commit).
legacy=rmfield(q,'candidate_feasibility');
D=G.search_geometric_candidate(legacy);
assert(D.candidate_available && ~D.candidate_kinematics_enforced&& ...
    ~D.safe_to_commit, ...
    'CHECK_CANDIDATE_FEASIBILITY:Legacy', ...
    'Existing geometry-only regression was broken.');
R=struct('status', ...
    'PASS_IN_SOLVE_REFERENCE_DERIVATIVE_LIMITS__DYNAMICS_PENDING', ...
    'cases',5,'live_entry_guard',true, ...
    'all_time_reference_limits',true,'heading_certified',true, ...
    'nonlinear_constraints_in_solve',A.inequality_count, ...
    'real_fmincon_tested',false,'native_hlc_plant_tested',false, ...
    'hlc_commit_allowed',false,'wcet_proven',false);
fid=fopen(fullfile(root,'TRAJECTORY_CANDIDATE_FEASIBILITY_RESULT.txt'),'wt');
assert(fid>0,'CHECK_CANDIDATE_FEASIBILITY:Output','Unable to save result.');
g=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\n',R.status);
fprintf(fid,'cases=%d total_nlp_inequalities=%d (geometry=%d reference=%d)\n', ...
    R.cases,A.inequality_count,A.geometry_inequality_count, ...
    A.kinematic_inequality_count);
fprintf(fid,'native=NOT_TESTED real_solver=NOT_TESTED commit=FORBIDDEN\n');
end
function [z,exitflag,out]=identity_solver(~,z0,G,~)
[c,ceq]=G(z0);
z=z0;
exitflag=1;
if ~(all(isfinite(c))&&all(c<=1e-8)&& ...
        all(isfinite(ceq))&&all(abs(ceq)<=1e-8))
    exitflag=-2;
end
out=struct('adapter','NO_OPTIMIZATION_FEASIBILITY_TEST');
end
