function R=CHECK_TRAJECTORY_C9_CONTINUOUS_THRUST()
% CHECK_TRAJECTORY_C9_CONTINUOUS_THRUST
% Single-run model-only regression, no physical/HLC commit.
% All numeric values are SYNTHETIC TEST INPUTS, not production fallbacks.
root=fileparts(mfilename('fullpath'));
addpath(fullfile(root,'reference','REPLANNING_SYSTEM','TRAJECTORY_GENERATION'));
A=struct('cable_length_m',2,'uav_mass_kg',1.5, ...
    'payload_mass_kg',1,'gravity_world_mps2',[0;0;-9.80665], ...
    'thrust_limits_N',[0;100], ...
    'minimum_tension_N',0,'acceleration_guard_mps2',1e-12);
options=struct('max_subdivision_depth',6,'max_node_count',127, ...
    'force_guard_N',1e-10);
% Exact uniform-velocity load path: nonzero heading, zero load acceleration.
J0=zeros(3,10);J0(1,2)=1;J0(3,1)=-2;
J1=J0;J1(1,1)=1;
free=zeros(3,4);free(1,:)=(10:13)/23;free(3,:)=-2;
p=TRAJECTORY_C9_FLAT_BERNSTEIN.build(0,1,J0,J1,free);
G=TRAJECTORY_GENERATOR(struct('ROBUST_TUBE_ENABLED',false));
t=tic;C=G.certify_c9_continuous_nominal_force(p,A,options);
elapsed_ms=toc(t)*1000;
expected=(A.uav_mass_kg+A.payload_mass_kg)*norm(A.gravity_world_mps2);
assert(C.certified&&C.certified_continuous_tension&& ...
    C.certified_continuous_thrust&&~C.safe_to_commit&& ...
    abs(C.thrust_lower_bound_N-expected)<1e-6&& ...
    abs(C.thrust_upper_bound_N-expected)<1e-6&& ...
    C.minimum_tension_lower_bound_N>0, ...
    'CHECK_C9_THRUST:Steady','Uniform flight must be certified with exact force.');
% A perturbed 23rd-degree C9 load moves its cable direction; actual flat
% force at ALL test times must lie inside our certificate. Dense sampling
% is used ONLY as an independent regression; proof uses Bernstein hulls.
p2free=free;
p2free(2,:)=1e-7*[1 -1 1 -1];
p2=TRAJECTORY_C9_FLAT_BERNSTEIN.build(0,1,J0,J1,p2free);
C2=G.certify_c9_continuous_nominal_force(p2,A,options);
assert(C2.certified && C2.thrust_upper_bound_N>=C2.thrust_lower_bound_N, ...
    'CHECK_C9_THRUST:Dynamic','Small coupled C9 perturbation not certified.');
for t=linspace(0,1,121)
    E=TRAJECTORY_TAUT_FLATNESS.evaluate(p2,t,A);
    assert(E.valid&& E.tension_N>=C2.minimum_tension_lower_bound_N-1e-6 && ...
        E.thrust_N>=C2.thrust_lower_bound_N-1e-6 && ...
        E.thrust_N<=C2.thrust_upper_bound_N+1e-6, ...
        'CHECK_C9_THRUST:Bound','Pointwise flatness violates all-time bound.');
end
% Changed latest payload mass must change bound immediately (no cache).
Aheavy=A;Aheavy.payload_mass_kg=2;
Cheavy=G.certify_c9_continuous_nominal_force(p,Aheavy,options);
assert(Cheavy.certified&&Cheavy.thrust_lower_bound_N> ...
    C.thrust_lower_bound_N+norm(A.gravity_world_mps2)/2 && ...
    Cheavy.authority_snapshot.payload_mass_kg==2, ...
    'CHECK_C9_THRUST:Mass','Current payload mass ignored.');
% Infeasible thrust max is UNKNOWN, never a safe commit.
Alimit=A;Alimit.thrust_limits_N=[0;20];
Cbad=G.certify_c9_continuous_nominal_force(p,Alimit,options);
assert(~Cbad.certified&&~Cbad.safe_to_commit && ...
    startsWith(Cbad.status,'UNKNOWN_'), ...
    'CHECK_C9_THRUST:Limits','Insufficient thrust must not be certified.');
% SO(3) coordinate covariance: transform gravity, trajectory and all jets.
a=0.47;b=0.83;
Q=[cos(a) -sin(a) 0;sin(a) cos(a) 0;0 0 1]* ...
  [cos(b) 0 sin(b);0 1 0;-sin(b) 0 cos(b)];
Ar=A;Ar.gravity_world_mps2=Q*A.gravity_world_mps2;
pr=TRAJECTORY_C9_FLAT_BERNSTEIN.build(0,1,Q*J0,Q*J1,Q*free);
Cr=G.certify_c9_continuous_nominal_force(pr,Ar,options);
assert(Cr.certified&&abs(Cr.thrust_upper_bound_N-C.thrust_upper_bound_N)<1e-6, ...
    'CHECK_C9_THRUST:SO3','Full-time force bound depends on world-axis direction.');
% Proof budget exhaustion never certifies thrust.
tiny=options;tiny.max_subdivision_depth=0;
Cfail=G.certify_c9_continuous_nominal_force(p,Alimit,tiny);
assert(~Cfail.certified,'CHECK_C9_THRUST:Budget','No proof may become safe.');
R=struct('status', ...
    'PASS_C9_IDEAL_TAUT_ALL_TIME_THRUST_TENSION__TORQUE_HLC_PENDING', ...
    'steady_force_N',expected, ...
    'dynamic_thrust_lower_N',C2.thrust_lower_bound_N, ...
    'dynamic_thrust_upper_N',C2.thrust_upper_bound_N, ...
    'proof_leaves',C2.checked_leaf_count, ...
    'steady_certifier_ms',elapsed_ms, ...
    'failed_limit_rejected',~Cbad.certified, ...
    'mass_change_checked',Cheavy.certified, ...
    'SO3_checked',Cr.certified, ...
    'sample_count',121,'real_HLC_certified',false,'torques_certified',false);
save(fullfile(root,'TRAJECTORY_C9_THRUST_RESULT.mat'),'R');
fid=fopen(fullfile(root,'TRAJECTORY_C9_THRUST_RESULT.txt'),'wt');
assert(fid>0,'CHECK_C9_THRUST:Write','Cannot write result.');
g=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',R.status);
fprintf(fid,'steady_force_N=%.9g dynamic_bound_N=[%.9g, %.9g] leaves=%d\n', ...
    R.steady_force_N,R.dynamic_thrust_lower_N,R.dynamic_thrust_upper_N, ...
    R.proof_leaves);
fprintf(fid,'steady_certificate_ms=%.6f SO3=1 mass_updated=1 torque=NOT_CERTIFIED HLC=FORBIDDEN\n', ...
    R.steady_certifier_ms);
clear g
zip(fullfile(root,'TRAJECTORY_C9_THRUST_RESULTS_FOR_CHATGPT.zip'), ...
    {'TRAJECTORY_C9_THRUST_RESULT.mat', ...
     'TRAJECTORY_C9_THRUST_RESULT.txt'},root);
delete(fullfile(root,'TRAJECTORY_C9_THRUST_RESULT.mat'));
delete(fullfile(root,'TRAJECTORY_C9_THRUST_RESULT.txt'));
end
