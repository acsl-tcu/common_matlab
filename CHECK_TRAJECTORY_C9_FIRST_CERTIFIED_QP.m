function R=CHECK_TRAJECTORY_C9_FIRST_CERTIFIED_QP()
% Development-only, minimal whole-pipeline comparison of a first certified
% minimum-QP solution with the historical certificate-checked shortening.
% No Flight runner modifications, no motor allocation, and no HLC COMMIT.
root=fileparts(mfilename('fullpath'));
names={'sphere','sphere_rotated_ellipsoid','box_cylinder'};
R=struct('status','FAIL_FIRST_CERTIFIED_QP_CHECK','stage','START', ...
    'error_identifier','','error_message','','error_stack',{{}}, ...
    'scene_names',{names},'fast_status',{{}},'original_status',{{}}, ...
    'fast_model_complete',false(1,3), ...
    'original_model_complete',false(1,3), ...
    'fast_first_hit_accepted',false(1,3), ...
    'fast_strict_qp_solved',false(1,3), ...
    'fast_proof_calls',NaN(1,3),'original_proof_calls',NaN(1,3), ...
    'fast_shortening_proofs',NaN(1,3), ...
    'original_shortening_proofs',NaN(1,3), ...
    'fast_median_ms',NaN(1,3),'original_median_ms',NaN(1,3), ...
    'fast_p95_ms',NaN(1,3),'original_p95_ms',NaN(1,3), ...
    'fast_max_ms',NaN(1,3),'original_max_ms',NaN(1,3), ...
    'fast_proof_median_ms',NaN(1,3), ...
    'original_proof_median_ms',NaN(1,3), ...
    'fast_payload_deviation_control_bound_m',NaN(1,3), ...
    'original_payload_deviation_control_bound_m',NaN(1,3), ...
    'fast_integral_accel_change',NaN(1,3), ...
    'original_integral_accel_change',NaN(1,3), ...
    'controller_source_limits_read',false, ...
    'no_uncertified_commit',true, ...
    'repetitions',7, ...
    'zip_path',fullfile(root,'TRAJECTORY_C9_FIRST_CERTIFIED_QP_RESULT_FOR_CHATGPT.zip'));
try
    R.stage='LOAD_CURRENT_MATLAB_PRODUCTION_CLASSES';
    addpath(fullfile(root,'controller'),'-begin');
    addpath(fullfile(root,'model'),'-begin');
    addpath(fullfile(root,'reference','REPLANNING_SYSTEM','TRAJECTORY_GENERATION'), ...
        fullfile(root,'reference','REPLANNING_SYSTEM','OBSTACLE_INFORMATION'),'-begin');
    assert(isfile(fullfile(root,'run_flight_headless.m')), ...
        'CHECK_C9_FIRSTHIT:Root','Run from common_matlab root.');
    R.stage='BUILD_REAL_PARAMETER_FIXTURE_NOT_HARDCODED_FLIGHT';
    [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    Psys=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    Psys.set("loadmass",0.14); % Development fixture, NOT a Flight constant
    d=double(Psys.get(["mass","jx","jy","jz", ...
        "gravity","cableL","loadmass"]));
    d=d(:);lo=lo(:);hi=hi(:);
    assert(numel(d)==7&&all(isfinite(d))&&all(d>0)&& ...
        numel(lo)==4&&numel(hi)==4&&all(hi>lo), ...
        'CHECK_C9_FIRSTHIT:Authority', ...
        'Could not read actual class and four source limits.');
    R.controller_source_limits_read=true;
    authority=struct('uav_mass_kg',d(1),'payload_mass_kg',d(7), ...
        'cable_length_m',d(6),'uav_inertia_kgm2',d(2:4), ...
        'gravity_world_mps2',[0;0;-d(5)], ...
        'thrust_limits_N',[lo(1),hi(1)], ...
        'torque_limits_Nm',[lo(2:4),hi(2:4)], ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0);
    gopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'numerical_guard_m',0,'robust_tube_enabled',false, ...
        'trajectory_phase','f');
    fopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'force_guard_N',0);
    sopt=struct('probe_count',13,'max_outer_iterations',4, ...
        'max_projection_sweeps',100, ...
        'projection_tolerance_m',1e-8,'min_separation_m',1e-5, ...
        'lazy_initial_proof_on_violated_plane',false, ...
        'payload_hull_witness_policy','off', ...
        'embed_taut_bernstein_halfspaces',false);
    hopt=struct('max_subdivision_depth',8,'max_node_count',511, ...
        'horizontal_velocity_guard_mps',0,'w_guard_mps2',0, ...
        'payload_jet_tolerance',1e-7*ones(3,10), ...
        'uav_jet_tolerance',1e-7*ones(3,8), ...
        'yaw_jet_tolerance',1e-7*ones(1,7));
    topt=struct('max_subdivision_depth',8,'max_node_count',511, ...
        'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
        'torque_guard_Nm',zeros(3,1), ...
        'enable_fast_norm_sufficient_bound',true);
    start=zeros(3,10);finish=zeros(3,10);
    start(:,1)=[-2;0;3];finish(:,1)=[2;0;3];
    start(1,2)=0.4;finish(1,2)=0.4;
    initial=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,10,start,finish, ...
        repmat([0;0;3],1,4));
    req=struct('t0_s',8,'duration_s',10,'flight_interval_s',[8 30], ...
        'start_jets',start,'end_jets',finish, ...
        'nominal_free',initial.control_points_m(:,11:14), ...
        'observed',struct([]),'radii', ...
        struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1), ...
        'authority',authority,'geometry_options',gopt, ...
        'force_options',fopt,'search_options',sopt, ...
        'heading_options',hopt,'nominal_torque_options',topt);
    sphere=OBSTACLE_INFORMATION.define(21,'sphere',[0 0.1 3],0.2);
    angle=0.34;rot=[cos(angle),-sin(angle),0; ...
        sin(angle),cos(angle),0;0,0,1];
    ellipsoid=OBSTACLE_INFORMATION.define(33,'ellipsoid', ...
        [0.6 -0.16 3],[0.32 0.19 0.4],'rotation',rot);
    box=OBSTACLE_INFORMATION.define(34,'box',[0 0.15 3], ...
        [0.35 0.3 0.7],'rotation',rot);
    cylinder=OBSTACLE_INFORMATION.define(35,'cylinder', ...
        [0.65 -0.15 3],[0.27 0.5],'rotation',rot);
    scenes={sphere,[sphere ellipsoid],[box cylinder]};
    R.fast_status=cell(1,3);R.original_status=cell(1,3);
    R.stage='PAIRED_FIRST_CERTIFIED_QP_WHOLE_PIPELINE';
    for case_index=1:3
        req.observed=scenes{case_index};
        fast=req;fast.search_options.accept_first_certified_minimum_qp=true;
        old=req;old.search_options.accept_first_certified_minimum_qp=false;
        a=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(fast);
        b=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(old);
        R.fast_status{case_index}=a.status;
        R.original_status{case_index}=b.status;
        R.fast_model_complete(case_index)=a.nominal_model_complete;
        R.original_model_complete(case_index)=b.nominal_model_complete;
        R.fast_first_hit_accepted(case_index)= ...
            a.search_result.first_hit_minimum_qp_accepted;
        R.fast_strict_qp_solved(case_index)= ...
            a.search_result.first_hit_strict_qp_solved;
        R.fast_proof_calls(case_index)=a.proof_calls;
        R.original_proof_calls(case_index)=b.proof_calls;
        R.fast_shortening_proofs(case_index)= ...
            a.search_result.certified_shortening_trials;
        R.original_shortening_proofs(case_index)= ...
            b.search_result.certified_shortening_trials;
        R.no_uncertified_commit=R.no_uncertified_commit&& ...
            ~a.safe_to_commit&&~b.safe_to_commit&& ...
            ~a.actual_HLC_tracking_proven&&~b.actual_HLC_tracking_proven;
        assert(R.no_uncertified_commit, ...
            'CHECK_C9_FIRSTHIT:UnsafeCommit','Uncertified HLC commit.');
        assert(a.proof_calls<=sopt.max_outer_iterations+1&& ...
            b.proof_calls<=sopt.max_outer_iterations+1, ...
            'CHECK_C9_FIRSTHIT:Budget','Proof call cap exceeded.');
        verify_result(a);verify_result(b);
        if a.search_result.first_hit_minimum_qp_accepted
            assert(a.search_result.search_iterations==1&& ...
                a.search_result.first_hit_strict_qp_solved&& ...
                a.search_result.certified_shortening_trials==0&& ...
                a.search_result.final_certificate.certified, ...
                'CHECK_C9_FIRSTHIT:Policy','First-hit acceptance predicate invalid.');
        end
        R.fast_payload_deviation_control_bound_m(case_index)= ...
            detour_bound(a,initial);
        R.original_payload_deviation_control_bound_m(case_index)= ...
            detour_bound(b,initial);
        R.fast_integral_accel_change(case_index)= ...
            a.search_result.integrated_squared_acceleration_change_m2ps3;
        R.original_integral_accel_change(case_index)= ...
            b.search_result.integrated_squared_acceleration_change_m2ps3;
        % Warm up both variants before timing; alternate order to avoid
        % systematic advantage from JIT, caches or thermal conditions.
        ft=zeros(1,R.repetitions);bt=ft;fp=ft;bp=ft;
        for rep=1:R.repetitions
            if mod(rep,2)==1
                A=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(fast);
                B=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(old);
            else
                B=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(old);
                A=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(fast);
            end
            assert(strcmp(A.status,a.status)&&strcmp(B.status,b.status)&& ...
                A.proof_calls==a.proof_calls&&B.proof_calls==b.proof_calls, ...
                'CHECK_C9_FIRSTHIT:Unstable','Timed certification result changed.');
            ft(rep)=A.total_elapsed_ms;bt(rep)=B.total_elapsed_ms;
            fp(rep)=A.joint_geometry_force_proof_ms;
            bp(rep)=B.joint_geometry_force_proof_ms;
        end
        R.fast_median_ms(case_index)=median(ft);
        R.original_median_ms(case_index)=median(bt);
        values=sort(ft);R.fast_p95_ms(case_index)= ...
            values(ceil(.95*numel(values)));
        values=sort(bt);R.original_p95_ms(case_index)= ...
            values(ceil(.95*numel(values)));
        R.fast_max_ms(case_index)=max(ft);
        R.original_max_ms(case_index)=max(bt);
        R.fast_proof_median_ms(case_index)=median(fp);
        R.original_proof_median_ms(case_index)=median(bp);
    end
    R.stage='COMPLETE';
    if any(R.fast_first_hit_accepted)
        R.status='PASS_FIRST_CERTIFIED_MINIMUM_QP_PAIRS__HLC_UNCERTIFIED';
    else
        R.status='PASS_POLICY_SAFE_BUT_FIRST_HIT_NOT_EXERCISED__HLC_UNCERTIFIED';
    end
catch ME
    R.error_identifier=ME.identifier;R.error_message=ME.message;
    R.error_stack=arrayfun(@(e)sprintf('%s:%d',e.name,e.line), ...
        ME.stack,'UniformOutput',false);
end
name='TRAJECTORY_C9_FIRST_CERTIFIED_QP_RESULT';
save(fullfile(root,[name '.mat']),'R');
fid=fopen(fullfile(root,[name '.txt']),'w');
if fid>=0
    fprintf(fid,'status=%s\nstage=%s\nerror=%s | %s\n', ...
        R.status,R.stage,R.error_identifier,R.error_message);
    for j=1:numel(R.error_stack)
        fprintf(fid,'stack_%d=%s\n',j,R.error_stack{j});
    end
    for j=1:3
        if numel(R.fast_status)>=j
            fprintf(fid,['scene=%s | first_hit=%d | fast=%s | old=%s | ', ...
                'proof_calls=%g vs %g | extra_shrink=%g vs %g | ', ...
                'median_ms=%.5f vs %.5f | p95_ms=%.5f vs %.5f | ', ...
                'proof_ms=%.5f vs %.5f | payload_detour_bound_m=%.5f vs %.5f\n'], ...
                R.scene_names{j},R.fast_first_hit_accepted(j), ...
                R.fast_status{j},R.original_status{j}, ...
                R.fast_proof_calls(j),R.original_proof_calls(j), ...
                R.fast_shortening_proofs(j),R.original_shortening_proofs(j), ...
                R.fast_median_ms(j),R.original_median_ms(j), ...
                R.fast_p95_ms(j),R.original_p95_ms(j), ...
                R.fast_proof_median_ms(j),R.original_proof_median_ms(j), ...
                R.fast_payload_deviation_control_bound_m(j), ...
                R.original_payload_deviation_control_bound_m(j));
        end
    end
    fclose(fid);
end
files={[name '.mat'],[name '.txt']};
zip(R.zip_path,files,root);
fprintf('[C9 FIRST CERTIFIED QP] %s | %s\n',R.status,R.zip_path);
end

function verify_result(A)
S=A.search_result;
assert(~S.candidate_available|| ...
    (isstruct(S.final_certificate)&& ...
     isfield(S.final_certificate,'certified')&& ...
     isequal(S.final_certificate.certified,true)), ...
    'CHECK_C9_FIRSTHIT:UncertifiedCandidate', ...
    'A candidate without an independent all-time proof was returned.');
end

function b=detour_bound(A,original)
b=NaN;
if ~A.search_result.candidate_available,return;end
p=double(A.search_result.candidate_piece.control_points_m);
q=double(original.control_points_m);
assert(isequal(size(p),[3 24])&&isequal(size(q),[3 24]), ...
    'CHECK_C9_FIRSTHIT:ControlSize','Wrong polynomial degree.');
delta=p-q;
b=max(sqrt(sum(delta.^2,1)));
% All-time payload deviation is <= this bound by Bernstein convexity.
% No sampling claim of safety is needed.
end
