function R=CHECK_TRIGGER_DEADLINE_WORST_CASE(target_ms)
% Diagnose 3 IDENTICAL software/configuration Flight captures, not three
% different methods. Online and off-line clock semantics are distinguished.
% This check analyzes ALL frames, including non-Flight startup, plus the
% 4-second predictor-active subset. Not a deterministic Windows/MATLAB WCET.
root=fileparts(mfilename('fullpath'));
R=struct('status','UNKNOWN_THREE_FLIGHT_WORST_CASE', ...
    'target_ms',NaN,'runs',struct([]),'failures',0, ...
    'prediction_masks_same',false,'repeat_over_target_k',[], ...
    'reason','','wall_clock_only',true,'physical_certificate',false);
try
    assert(nargin==1&&isnumeric(target_ms)&&isscalar(target_ms) && ...
        isreal(target_ms)&&isfinite(target_ms)&&target_ms>0, ...
        'CHECK_DEADLINE:Target','Supply the intended real-time target explicitly in ms.');
    R.target_ms=double(target_ms);
    over=[];masks=[];
    for run=1:3
        file=fullfile(root,sprintf('TRIGGER_DIAG_RUN_%02d.mat',run));
        assert(isfile(file),'CHECK_DEADLINE:Missing', ...
            'All three saved captures are required: %s',file);
        V=load(file,'C');assert(isfield(V,'C')&&isstruct(V.C));C=V.C;
        required={'replanner_ms','trigger_ms','sensor_ms','memory_ms', ...
            'predicted','detail'};
        assert(all(isfield(C,required)), ...
            'CHECK_DEADLINE:Fields','Raw saved Flight clock data missing.');
        update=reshape(double(C.replanner_ms),1,[]);
        trigger=reshape(double(C.trigger_ms),1,[]);
        inner_sensor=reshape(double(C.sensor_ms),1,[]);
        pred=reshape(logical(C.predicted),1,[]);
        n=numel(update);
        d=double(C.detail);
        if isequal(size(d),[n 6]),d=d.';end
        assert(isequal(size(d),[6 n]) && all(isfinite(update)) && ...
            all(isfinite(trigger))&&all(isfinite(inner_sensor)) && ...
            numel(trigger)==n&&numel(inner_sensor)==n && ...
            numel(pred)==n&&all(isfinite(d(:))) && all(d(:)>=0), ...
            'CHECK_DEADLINE:Layout','Invalid clocks or stage dimensions.');
        assert(all(abs(trigger-d(4,:)) <= 1e-9*max(1,abs(trigger))), ...
            'CHECK_DEADLINE:Nested','Trigger attribution mismatch.');
        blue=update-trigger;
        % The sensor-internal clock excludes constructor/dispatch/result
        % return and possible thread pauses outside its boundaries.
        sensor_outer=d(1,:);
        sensor_outer_minus_inner=sensor_outer-inner_sensor;
        if run==1
            over=false(3,n);masks=false(3,n);
        else
            assert(numel(update)==size(over,2), ...
                'CHECK_DEADLINE:Runs','All three runs need the same frame count.');
        end
        over(run,:)=update>target_ms;
        masks(run,:)=pred;
        U=struct('run',run,'frames',n, ...
           'prediction_count',nnz(pred), ...
           'update_max_ms',max(update), ...
           'predicted_update_max_ms',max(update(pred)), ...
           'yellow_max_ms',max(trigger), ...
           'blue_max_ms',max(blue), ...
           'sensor_outer_max_ms',max(sensor_outer), ...
           'sensor_inner_max_ms',max(inner_sensor), ...
           'sensor_outer_minus_inner_max_ms',max(sensor_outer_minus_inner), ...
           'all_over_target',nnz(over(run,:)), ...
           'predicted_over_target',nnz(over(run,:)&pred), ...
           'top_update',local_top(update,trigger,blue,sensor_outer,inner_sensor,12), ...
           'top_yellow',local_top(trigger,trigger,blue,sensor_outer,inner_sensor,12), ...
           'top_blue',local_top(blue,trigger,blue,sensor_outer,inner_sensor,12), ...
           'top_sensor_outer',local_top(sensor_outer,trigger,blue,sensor_outer,inner_sensor,12), ...
           'top_sensor_gap',local_top(sensor_outer_minus_inner,trigger,blue,sensor_outer,inner_sensor,12));
        if isempty(R.runs),R.runs=U;else,R.runs(end+1)=U;end %#ok<AGROW>
    end
    R.prediction_masks_same=all(all(masks==masks(1,:)));
    R.repeat_over_target_k=find(sum(over & masks,1)>=2);
    if any(over(:))
        R.status='PERFORMANCE_TARGET_EXCEEDED__NOT_WCET_CERTIFIED';
    else
        R.status='NO_RECORDED_OVERRUN__NOT_WCET_CERTIFIED';
    end
    R.reason=['Recorder measures wall-clock durations, not strict WCET. ' ...
        'A sensor_outer-inner gap alone cannot isolate scheduler, JIT or copy.'];
catch ME
    R.failures=R.failures+1;
    R.reason=[ME.identifier ' | ' ME.message];
end
save(fullfile(root,'TRIGGER_DEADLINE_WORST_CASE_RESULT.mat'),'R');
f=fopen(fullfile(root,'TRIGGER_DEADLINE_WORST_CASE_RESULT.txt'),'w');
if f>=0
    fprintf(f,'status=%s\nfailures=%d\ntarget_ms=%.6f\n', ...
        R.status,R.failures,R.target_ms);
    fprintf(f,'prediction_masks_same=%d\nrepeat_predicted_over_target_k=%s\n', ...
        R.prediction_masks_same,mat2str(R.repeat_over_target_k));
    fprintf(f,'reason=%s\n',R.reason);
    for k=1:numel(R.runs)
        U=R.runs(k);
        fprintf(f,['run=%d frames=%d predicted=%d update_max=%.6f ' ...
            'flight_update_max=%.6f yellow_max=%.6f blue_max=%.6f ' ...
            'sensor_outer_max=%.6f sensor_inner_max=%.6f ' ...
            'sensor_outer_gap_max=%.6f exceed_all=%d exceed_predicted=%d\n'], ...
            U.run,U.frames,U.prediction_count,U.update_max_ms, ...
            U.predicted_update_max_ms,U.yellow_max_ms,U.blue_max_ms, ...
            U.sensor_outer_max_ms,U.sensor_inner_max_ms, ...
            U.sensor_outer_minus_inner_max_ms, ...
            U.all_over_target,U.predicted_over_target);
        kinds={'top_update','top_yellow','top_blue','top_sensor_outer','top_sensor_gap'};
        for j=1:numel(kinds)
            fprintf(f,'%s columns=k,score,yellow,blue,sensor_outer,sensor_inner\n', ...
                kinds{j});
            M=U.(kinds{j});
            for p=1:size(M,1)
                fprintf(f,'%.6f,%.6f,%.6f,%.6f,%.6f,%.6f\n',M(p,:));
            end
        end
    end
    fclose(f);
end
end
function top=local_top(score,trigger,blue,sensor_outer,inner_sensor,N)
    [~,ix]=sort(score,'descend');ix=ix(1:min(N,numel(ix)));
    top=[ix(:),score(ix).',trigger(ix).',blue(ix).', ...
        sensor_outer(ix).',inner_sensor(ix).'];
end
