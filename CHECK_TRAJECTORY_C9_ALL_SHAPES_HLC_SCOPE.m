function R=CHECK_TRAJECTORY_C9_ALL_SHAPES_HLC_SCOPE()
% CHECK_TRAJECTORY_C9_ALL_SHAPES_HLC_SCOPE
% 12 canonical static obstacle families in ONE simultaneous scene.
% Checks original shape support, 3-D rotation, continuous ideal-taut
% certificate, integrated nominal gates and explicit NO_HLC_COMMIT.
% No run_flight_headless, HLC, EKF, plant, sensor, trigger modification.
% Test fixtures are not Flight-authoritative parameters or tubes.
root=fileparts(mfilename('fullpath'));
R=struct('status','FAIL_NOT_STARTED','stage','START', ...
    'error_identifier','','error_message','','error_stack',{{}}, ...
    'family_names',{{}},'family_count',0,'shape_support_value_pass',false, ...
    'rotated_world_support_parity',false,'all_family_ids_preserved',false, ...
    'all_family_joint_geometry_status','NOT_EVALUATED', ...
    'all_family_joint_geometry_proven',false, ...
    'all_family_shape_support_calls',NaN, ...
    'all_family_near_leaf_checks',NaN, ...
    'all_family_outer_rejections',NaN, ...
    'near_shape_family_checks',0, ...
    'near_shape_family_support_calls',zeros(1,12), ...
    'near_shape_family_unknown_status',{{}}, ...
    'all_family_integrated_status','NOT_EVALUATED', ...
    'all_family_nominal_complete',false, ...
    'all_family_elapsed_ms',NaN, ...
    'all_family_joint_proof_ms',NaN, ...
    'collision_mixed_shapes_status','NOT_EVALUATED', ...
    'collision_mixed_shapes_failure_reason','', ...
    'collision_mixed_shapes_elapsed_ms',NaN, ...
    'collision_mixed_shapes_obstacle_ids',[], ...
    'hlc_input_lower',NaN(4,1),'hlc_input_upper',NaN(4,1), ...
    'source_limits_read',false, ...
    'actual_HLC_tracking_proven',false, ...
    'actual_HLC_preclamp_proven',false, ...
    'safe_to_commit',false, ...
    'source_scope','C9_NOMINAL_ONLY__NO_CLOSED_LOOP_HLC_CERTIFICATE', ...
    'elapsed_ms',NaN);
t0=tic;
try
    R.stage='SOURCE_PATH';
    src=fullfile(root,'reference','REPLANNING_SYSTEM');
    assert(isfolder(src),'CHECK_C9_ALL_SHAPES:Path', ...
        'Extract ZIP to common_matlab root first.');
    addpath(genpath(src),'-begin');
    addpath(fullfile(root,'controller'),fullfile(root,'model'),'-begin');

    R.stage='READ_CURRENT_HLC_LIMITS_AND_TEST_FIXTURE';
    [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    lo=double(lo(:));hi=double(hi(:));
    assert(isequal(size(lo),[4 1])&&isequal(size(hi),[4 1])&& ...
        all(lo<hi),'CHECK_C9_ALL_SHAPES:Limits','Invalid live HLC input limits.');
    R.hlc_input_lower=lo;R.hlc_input_upper=hi;
    R.source_limits_read=true;
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    P.set("loadmass",0.14); % Fixture only; actual Flight must use EKF each tick.
    d=double(P.get(["mass","jx","jy","jz", ...
        "gravity","cableL","loadmass"]));
    d=d(:);
    assert(numel(d)==7&&all(isfinite(d))&&all(d>0), ...
        'CHECK_C9_ALL_SHAPES:Parameter','Invalid parameter fixture.');
    A=struct('uav_mass_kg',d(1),'payload_mass_kg',d(7), ...
        'cable_length_m',d(6),'uav_inertia_kgm2',d(2:4), ...
        'gravity_world_mps2',[0;0;-d(5)], ...
        'thrust_limits_N',[lo(1),hi(1)], ...
        'torque_limits_Nm',[lo(2:4),hi(2:4)], ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0);
    radii=struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1);
    geom=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'numerical_guard_m',0,'robust_tube_enabled',false, ...
        'trajectory_phase','f');
    force=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'force_guard_N',0);
    search=struct('probe_count',13,'max_outer_iterations',4, ...
        'max_projection_sweeps',100, ...
        'projection_tolerance_m',1e-8,'min_separation_m',1e-5);
    heading=struct('max_subdivision_depth',8,'max_node_count',511, ...
        'horizontal_velocity_guard_mps',0,'w_guard_mps2',0, ...
        'payload_jet_tolerance',1e-7*ones(3,10), ...
        'uav_jet_tolerance',1e-7*ones(3,8), ...
        'yaw_jet_tolerance',1e-7*ones(1,7));
    torque=struct('max_subdivision_depth',8,'max_node_count',511, ...
        'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
        'torque_guard_Nm',zeros(3,1), ...
        'enable_fast_norm_sufficient_bound',true);
    j0=zeros(3,10);j1=zeros(3,10);
    j0(:,1)=[0;0;3];j1(:,1)=[1;0;3];
    j0(1,2)=0.5;j1(1,2)=0.5;
    free=repmat(j0(:,1),1,4)+j0(:,2)*((2/23)*(10:13));
    piece=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,2,j0,j1,free);
    req=struct('t0_s',8,'duration_s',2, ...
        'flight_interval_s',[8 30], ...
        'start_jets',j0,'end_jets',j1,'nominal_free', ...
        piece.control_points_m(:,11:14), ...
        'observed',struct([]),'radii',radii,'authority',A, ...
        'geometry_options',geom,'force_options',force, ...
        'search_options',search,'heading_options',heading, ...
        'nominal_torque_options',torque);

    R.stage='DEFINE_ALL_12_CANONICAL_SHAPES';
    % All placement directions and SO(3) orientations are test-scene data;
    % they are NOT candidate avoidance directions or special planner cases.
    polys=struct('outline',[0 0;.26 0;.26 .08;.08 .08;.08 .26;0 .26], ...
        'height',0.27);
    poly=struct('vertices',[0 0 0;.24 0 0;0 .24 0;0 0 .24], ...
        'faces',[1 3 2;1 2 4;1 4 3;2 3 4]);
    names={'sphere','ellipsoid','box','cylinder','capsule', ...
        'cone','frustum','pyramid','regular_prism','torus', ...
        'polygon_prism','polyhedron'};
    dims={0.18,[0.2 0.12 0.23],[0.28 0.35 0.34], ...
        [0.20 0.40],[0.12 0.23],[0.20 0.40], ...
        [0.20 0.10 0.37],[0.35 0.40],[6 0.20 0.36], ...
        [0.24 0.07],polys,poly};
    objects=struct([]);
    support_ok=true;rotation_ok=true;
    for k=1:numel(names)
        rx=0.11*k;ry=-0.07*k;rz=0.09*k;
        X=[1 0 0;0 cos(rx) -sin(rx);0 sin(rx) cos(rx)];
        Y=[cos(ry) 0 sin(ry);0 1 0;-sin(ry) 0 cos(ry)];
        Z=[cos(rz) -sin(rz) 0;sin(rz) cos(rz) 0;0 0 1];
        Q=Z*Y*X;
        pos=[0.45+0.035*cos(k);1.50+0.03*sin(k);4.0];
        item=OBSTACLE_INFORMATION.define(1000+k,names{k},pos, ...
            dims{k},'rotation',Q);
        objects=[objects item]; %#ok<AGROW>
        support=TRAJECTORY_OBSTACLE_SUPPORT.prepare(item);
        for v={[1;2;3],[-2;1;0.5],[0;0;1]}
            n=v{1};
            [h,p]=TRAJECTORY_OBSTACLE_SUPPORT.value_and_point(support,n);
            hv=TRAJECTORY_OBSTACLE_SUPPORT.value(support,n);
            scale=max([1,abs(h),abs(hv)]);
            support_ok=support_ok&&isfinite(h)&&isfinite(hv)&& ...
                abs(h-hv)<=2e-12*scale&& ...
                abs(h-n.'*p)<=2e-12*scale;
            % World-to-local support identity for the exact recorded R.
            base=support;base.center=zeros(3,1);base.R=eye(3);
            local=TRAJECTORY_OBSTACLE_SUPPORT.value(base,Q.'*n);
            rotation_ok=rotation_ok&& ...
                abs(h-(n.'*pos+local))<=2e-12*scale;
        end
    end
    R.family_names=names;R.family_count=numel(objects);
    R.shape_support_value_pass=support_ok;
    R.rotated_world_support_parity=rotation_ok;
    R.all_family_ids_preserved=isequal([objects.id],1001:1012);
    assert(R.family_count==12&&support_ok&&rotation_ok&& ...
        R.all_family_ids_preserved,'CHECK_C9_ALL_SHAPES:Support', ...
        'Canonical 12-shape support/SO(3)/IDs mismatch.');

    R.stage='PROVE_ALL_12_SHAPES_IN_ONE_SCENE';
    % Independent continuous geometry and forces for the SAME actual C9
    % polynomial. The original all-time proof decides, not samples.
    G=TRAJECTORY_C9_JOINT_FAST_CERTIFICATE( ...
        piece,objects,radii,A,geom,force);
    R.all_family_joint_geometry_status=G.status;
    R.all_family_joint_geometry_proven=G.certified;
    R.all_family_shape_support_calls=G.shape_support_calls;
    R.all_family_near_leaf_checks=G.near_obstacle_leaf_checks;
    R.all_family_outer_rejections=G.outer_rejections;
    R.all_family_ids_preserved=R.all_family_ids_preserved&& ...
        isequal(sort(G.considered_obstacle_ids),1001:1012);
    % Far obstacles are CORRECTLY rejected before expensive support tests.
    % Requiring 12 exact support calls here would turn a performance
    % optimization into an erroneous audit failure. Count all obstacles
    % accounted for by a proven outer rejection OR exact near check.
    assert(G.certified&&G.checked_leaf_count>=1&& ...
        (G.outer_rejections+G.near_obstacle_leaf_checks)>=12&& ...
        R.all_family_ids_preserved, ...
        'CHECK_C9_ALL_SHAPES:JointProof', ...
        'All-family scene was not actually evaluated and certified.');
    R.stage='PROBE_EACH_SHAPE_NEAR_THE_REAL_PAYLOAD_PATH';
    % Exercise the NEAR stage for every family, without requiring a fixed
    % number of exact support calls: analytical broad/separation tests may
    % legitimately prove some families without that expensive subroutine.
    % The sphere through polyhedron use the SAME production geometry oracle.
    % Move only a COPY of each observed shape, not the obstacle source.
    near_status=cell(1,numel(objects));
    support_counts=zeros(1,numel(objects));
    for ii=1:numel(objects)
        near_shape=objects(ii);
        near_shape.position=[0.5;0;3];
        near_shape.initial_position=near_shape.position;
        NG=TRAJECTORY_C9_JOINT_FAST_CERTIFICATE( ...
            piece,near_shape,radii,A,geom,force);
        near_status{ii}=NG.status;
        support_counts(ii)=NG.shape_support_calls;
        assert(NG.near_obstacle_leaf_checks>0 && ...
            isequal(NG.considered_obstacle_ids,double(near_shape.id)), ...
            'CHECK_C9_ALL_SHAPES:NearShapeOracle', ...
            'Near-shape test did not reach the original shape oracle.');
        % The first shape is a sphere centred ON the payload path. A
        % sound all-time certificate must never claim this path is safe.
        if ii==1
            assert(~NG.certified, ...
                'CHECK_C9_ALL_SHAPES:IntersectingSphere', ...
                'A sphere directly intersecting the payload was certified.');
        end
    end
    R.near_shape_family_checks=numel(objects);
    R.near_shape_family_support_calls=support_counts;
    R.near_shape_family_unknown_status=near_status;
    R.stage='INTEGRATED_ALL_12_SHAPE_SCENE';
    req.observed=objects;
    integrated=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(req);
    R.all_family_integrated_status=integrated.status;
    R.all_family_nominal_complete=integrated.nominal_model_complete;
    R.all_family_elapsed_ms=integrated.total_elapsed_ms;
    R.all_family_joint_proof_ms=integrated.joint_geometry_force_proof_ms;
    assert(integrated.nominal_model_complete&& ...
        ~integrated.safe_to_commit&& ...
        ~integrated.actual_HLC_tracking_proven&& ...
        ~integrated.closed_loop_actuator_limits_proven, ...
        'CHECK_C9_ALL_SHAPES:Integrated', ...
        'Do not confuse conditional nominal certification with HLC safety.');

    R.stage='MIXED_TRUE_SHAPE_COLLISION_SEARCH';
    % This may return UNKNOWN: iteration budget and nonconvexity are
    % fundamental; no failure is relabelled as a safe result.
    box=OBSTACLE_INFORMATION.define(2001,'box', ...
        [0.5 0 4],[0.40 0.35 0.4],'rotation', ...
        objects(3).rotation);
    cyl=OBSTACLE_INFORMATION.define(2002,'cylinder', ...
        [0.55 0.22 4],[0.30 0.75], 'rotation', ...
        objects(4).rotation);
    req.observed=[box cyl];
    trial=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(req);
    R.collision_mixed_shapes_status=trial.status;
    R.collision_mixed_shapes_failure_reason=trial.failure_detail;
    R.collision_mixed_shapes_elapsed_ms=trial.total_elapsed_ms;
    R.collision_mixed_shapes_obstacle_ids=[box.id,cyl.id];
    assert(~trial.safe_to_commit&& ...
        ~trial.actual_HLC_tracking_proven&& ...
        ~trial.closed_loop_actuator_limits_proven, ...
        'CHECK_C9_ALL_SHAPES:HLC','No conditional candidate may be committed.');
    R.status='PASS_12_SHAPE_SIMULTANEOUS_AND_EXPLICIT_HLC_GAP';
    R.stage='COMPLETE';
catch ME
    R.status='FAIL_C9_12_SHAPE_AND_HLC_AUDIT';
    R.error_identifier=ME.identifier;R.error_message=ME.message;
    R.error_stack=arrayfun(@(f)sprintf('%s:%d',f.name,f.line), ...
        ME.stack,'UniformOutput',false);
end
R.elapsed_ms=1000*toc(t0);
% Audit files are always in common_matlab (CHECK location), never pwd.
name='TRAJECTORY_C9_ALL_SHAPES_HLC_SCOPE_RESULT';
matFile=fullfile(root,[name '.mat']);
txtFile=fullfile(root,[name '.txt']);
zipFile=fullfile(root,[name '_FOR_CHATGPT.zip']);
save(matFile,'R');
fid=fopen(txtFile,'w');
if fid>=0
    fprintf(fid,'status=%s\nstage=%s\nerror_identifier=%s\nerror_message=%s\n', ...
        R.status,R.stage,R.error_identifier,R.error_message);
    for j=1:numel(R.error_stack)
        fprintf(fid,'stack_%d=%s\n',j,R.error_stack{j});
    end
    fprintf(fid,'families=%s\ncount=%d\n',strjoin(R.family_names,','), ...
        R.family_count);
    fprintf(fid,'shape_support=%d\nSO3_support=%d\nIDs_preserved=%d\n', ...
        R.shape_support_value_pass,R.rotated_world_support_parity, ...
        R.all_family_ids_preserved);
    fprintf(fid,'all_shape_joint=%s\nnear_checks=%.0f\nsupport_calls=%.0f\nouter_rejections=%.0f\n', ...
        R.all_family_joint_geometry_status,R.all_family_near_leaf_checks, ...
        R.all_family_shape_support_calls,R.all_family_outer_rejections);
    fprintf(fid,'near_shape_family_checks=%d\nsupport_calls_each=%s\n', ...
        R.near_shape_family_checks,mat2str(R.near_shape_family_support_calls));
    fprintf(fid,'all_shape_integrated=%s\nall_shape_ms=%.6f\n', ...
        R.all_family_integrated_status,R.all_family_elapsed_ms);
    fprintf(fid,'mixed_search=%s\nreason=%s\nmixed_ms=%.6f\n', ...
        R.collision_mixed_shapes_status,R.collision_mixed_shapes_failure_reason, ...
        R.collision_mixed_shapes_elapsed_ms);
    fprintf(fid,['HLC_SCOPE=C9_NOMINAL_ONLY__NOT_CLOSED_LOOP_PROVEN\n', ...
        'HLC_PRECLAMP_ALL_TIME=NOT_PROVEN\n', ...
        'HLC_TRACKING_ALL_TIME=NOT_PROVEN\n', ...
        'HLC_COMMIT=FORBIDDEN\n', ...
        'fixture_mass_is_NOT_EKF_kg=0.14\n']);
    fprintf(fid,'CHECK_elapsed_ms=%.6f\n',R.elapsed_ms);
    fclose(fid);
end
if isfile(zipFile),delete(zipFile);end
zip(zipFile,{matFile,txtFile});
fprintf('[C9 12 SHAPES] %s | %s\n',R.status,zipFile);
end
