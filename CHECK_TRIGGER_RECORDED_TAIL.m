function R=CHECK_TRIGGER_RECORDED_TAIL()
% Offline audit of the THREE previously captured Flight runs.
% All input/output files are under common_matlab/, not the current pwd.
% NO Flight execution, no scheduler-causality or WCET claim.
root=fileparts(mfilename('fullpath'));
R=struct('status','FAIL_RECORDED_TAIL_AUDIT', ...
    'runs',struct([]),'reason','', ...
    'mat_path',fullfile(root,'TRIGGER_RECORDED_TAIL_RESULT.mat'), ...
    'txt_path',fullfile(root,'TRIGGER_RECORDED_TAIL_RESULT.txt'));
try
    result=cell(1,3);
    for i=1:3
        p=fullfile(root,sprintf('TRIGGER_DIAG_RUN_%02d.mat',i));
        assert(exist(p,'file')==2, ...
            'CHECK_TRIGGER_RECORDED_TAIL:Missing', ...
            'Missing captured Flight data: %s',p);
        S=load(p,'C');
        assert(isfield(S,'C')&&isstruct(S.C)&&isscalar(S.C), ...
            'CHECK_TRIGGER_RECORDED_TAIL:Struct','Capture C absent.');
        C=S.C;
        required={'replanner_ms','trigger_ms','sensor_ms','memory_ms', ...
            'predictor_ms','geometry_ms','reference_ms','rhs_evals', ...
            'predicted','time_s','duplicate','sensor_stage','geometry_stage'};
        assert(all(isfield(C,required)), ...
            'CHECK_TRIGGER_RECORDED_TAIL:Schema', ...
            'Three runs require the same detailed capture schema.');
        u=reshape(double(C.replanner_ms),1,[]);
        tr=reshape(double(C.trigger_ms),1,[]);
        n=numel(u);
        assert(n>0&&numel(tr)==n&&all(isfinite(u)) && ...
            all(u>=0) && numel(C.predicted)==n, ...
            'CHECK_TRIGGER_RECORDED_TAIL:Time','Invalid wall-clock arrays.');
        pflag=reshape(logical(C.predicted),1,[]);
        assert(any(pflag), ...
            'CHECK_TRIGGER_RECORDED_TAIL:Prediction','No prediction ticks.');
        [~,order]=sort(u,'descend');
        [~,rel_index]=max(u(pflag));
        ticks=find(pflag);
        ix=ticks(rel_index);
        maxix=order(1);
        T=struct('run',i,'cycles',n,'predicted',nnz(pflag), ...
            'update_median_ms',median(u), ...
            'update_p95_ms',rank_percentile(u,0.95), ...
            'update_p99_ms',rank_percentile(u,0.99), ...
            'update_max_ms',u(maxix), ...
            'update_max_cycle',maxix, ...
            'prediction_tick_max_ms',u(ix), ...
            'prediction_tick_max_cycle',ix, ...
            'prediction_tick_max_time_s',double(C.time_s(ix)), ...
            'prediction_tick_max_trigger_ms',tr(ix), ...
            'prediction_tick_max_sensor_ms',double(C.sensor_ms(ix)), ...
            'prediction_tick_max_memory_ms',double(C.memory_ms(ix)), ...
            'prediction_tick_max_geometry_ms',double(C.geometry_ms(ix)), ...
            'prediction_tick_max_reference_ms',double(C.reference_ms(ix)), ...
            'prediction_tick_max_rhs_evals',double(C.rhs_evals(ix)), ...
            'prediction_tick_over_4_ms',nnz(u(pflag)>4), ...
            'max_geometry_ms',max(double(C.geometry_ms(isfinite(C.geometry_ms)))), ...
            'top_cycles',order(1:min(10,n)), ...
            'top_update_ms',u(order(1:min(10,n))), ...
            'safe_to_commit',false);
        result{i}=T;
    end
    R.runs=[result{:}];
    R.status='PASS_THREE_RUN_DECOMPOSITION__NOT_CAUSAL_OR_WCET_PROOF';
    R.reason=['The counts and wall-clock components are factual. ' ...
        'No scheduler, GC, JIT or mathematical WCET attribution is made.'];
catch ME
    R.reason=[ME.identifier ' | ' ME.message];
end
% Output even on failure, retaining the source folder for complete cleanup.
try
    fid=fopen(R.txt_path,'wt');
    if fid<0,error('CHECK_TRIGGER_RECORDED_TAIL:Write','Cannot write TXT.');end
    cl=onCleanup(@()fclose(fid));
    fprintf(fid,'status=%s\nreason=%s\n',R.status,R.reason);
    for i=1:numel(R.runs)
        T=R.runs(i);
        fprintf(fid,['run=%d frames=%d predicted=%d median=%.6f ' ...
            'p95=%.6f p99=%.6f all_max=%.6f all_max_k=%d ' ...
            'prediction_max=%.6f prediction_max_k=%d t=%.6f ' ...
            'prediction_max_rhs=%.0f over_4ms_predicted=%d ' ...
            'geometry_peak=%.6f\n'], ...
            T.run,T.cycles,T.predicted,T.update_median_ms, ...
            T.update_p95_ms,T.update_p99_ms,T.update_max_ms, ...
            T.update_max_cycle,T.prediction_tick_max_ms, ...
            T.prediction_tick_max_cycle,T.prediction_tick_max_time_s, ...
            T.prediction_tick_max_rhs_evals, ...
            T.prediction_tick_over_4_ms,T.max_geometry_ms);
        for j=1:numel(T.top_cycles)
            fprintf(fid,'  top[%d] k=%d update=%.6f\n', ...
                j,T.top_cycles(j),T.top_update_ms(j));
        end
    end
    clear cl
    save(R.mat_path,'R');
catch ME
    warning('CHECK_TRIGGER_RECORDED_TAIL:Save','%s',ME.message);
end
end

function v=rank_percentile(x,q)
% Pure MATLAB, deterministic empirical rank (no Statistics Toolbox).
xs=sort(reshape(double(x),1,[]));
v=xs(max(1,min(numel(xs),ceil(numel(xs)*q))));
end
