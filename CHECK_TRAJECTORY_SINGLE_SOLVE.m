function R=CHECK_TRAJECTORY_SINGLE_SOLVE()
%CHECK_TRAJECTORY_SINGLE_SOLVE  One-solve geometry/corridor adapter regression.
% Uses a transparent identity solver ADAPTER for known safe geometries;
% this is NOT an fmincon convergence or 5-ms performance test.
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'reference','REPLANNING_SYSTEM');
addpath(fullfile(base,'TRAJECTORY_GENERATION'), ...
    fullfile(base,'OBSTACLE_INFORMATION'));
assert(exist('TRAJECTORY_SIMULTANEOUS_C7_SEARCH','file')==2 && ...
    exist('TRAJECTORY_OBSTACLE_SUPPORT','class')==8, ...
    'CHECK_TRAJECTORY_SINGLE_SOLVE:Path','Solver or support source missing.');
% Four 7-jets are externally supplied, including position and zero higher
% derivatives for a stationary synthetic test (not a flight trajectory).
U=zeros(3,8);L=zeros(3,8);L(3,1)=-2;
input=struct();
input.t0_s=0;input.duration_s=2;
input.start_jets=struct('uav',U,'payload',L);
input.end_jets=input.start_jets;
input.nominal_free=struct('uav',repmat(U(:,1),1,8), ...
    'payload',repmat(L(:,1),1,8));
input.observed=[ ...
    OBSTACLE_INFORMATION.define(41,'sphere',[0 4 0],0.2), ...
    OBSTACLE_INFORMATION.define(43,'box',[0 -4 0],[0.4 0.6 1], ...
        'euler_deg',[15 28 52])];
input.physical_radii=struct('uav_m',0.05,'payload_m',0.05,'cable_m',0.01);
input.proof_options=struct('robust_tube_enabled',false, ...
    'min_separation_m',0.02,'numerical_guard_m',1e-10, ...
    'max_subdivision_depth',3);
input.search_options=struct('time_leaf_depth',1, ...
    'max_constraint_rows',1000,'max_leaf_count',2, ...
    'feasibility_tolerance',1e-8,'endpoint_jet_tolerance',1e-7);
input.solver_options=struct();
input.solver_function=@identity_solver;
G=TRAJECTORY_GENERATOR(struct('ROBUST_TUBE_ENABLED',false));
X=G.search_geometric_candidate(input);
assert(X.candidate_available&&X.certified_geometry&& ...
    ~X.safe_to_commit&&X.corridor.certified&& ...
    numel(X.considered_obstacle_ids)==2&& ...
    X.minimum_plane_slack_m>0&& ...
    X.maximum_endpoint_jet_error<=1e-7, ...
    'CHECK_TRAJECTORY_SINGLE_SOLVE:Safe', ...
    'Feasible full-body corridor was not recovered.');
% Real uncertainty bounds ON must enlarge each component separately.
robust=input;
robust.proof_options.robust_tube_enabled=true;
robust.proof_options.uncertainty_bounds_m=struct( ...
    'uav_m',0.04,'payload_m',0.03,'cable_m',0.02);
GR=TRAJECTORY_GENERATOR(struct('ROBUST_TUBE_ENABLED',true));
XR=GR.search_geometric_candidate(robust);
assert(XR.certified_geometry && strcmp(XR.corridor.scope, ...
    'POLYNOMIAL_WITH_SUPPLIED_UNCERTAINTY_RADII') && ...
    ~XR.safe_to_commit, ...
    'CHECK_TRAJECTORY_SINGLE_SOLVE:Tube', ...
    'Robust tube external bounds were not carried into certificate.');
K=TRAJECTORY_CORRIDOR_LINEAR_CONSTRAINTS(X.corridor,2000);
xx=[X.pieces.uav.control_points_m(:); ...
    X.pieces.payload.control_points_m(:)];
assert(all(K.Aineq*xx<=K.bineq+1e-8), ...
    'CHECK_TRAJECTORY_SINGLE_SOLVE:Linear', ...
    'Solver-extracted corridor failed linear inequality check.');
% A nearby obstacle intersecting the static cable must NEVER be certified.
bad=input;
bad.observed=OBSTACLE_INFORMATION.define(42,'sphere',[0 0 -1],0.3);
Y=G.search_geometric_candidate(bad);
assert(~Y.safe_to_commit && ~Y.certified_geometry, ...
    'CHECK_TRAJECTORY_SINGLE_SOLVE:Collision', ...
    'Penetrating obstacle was certified.');
% All 12 shapes with arbitrary SO(3) pose: support homogeneity and the
% tested plane itself rotate with the scene, with no +Y/+Z preference.
shapes=all_shapes();
S=TRAJECTORY_OBSTACLE_SUPPORT.prepare(shapes);
angles=[12 29 46;-46 18 106;61 -22 -14];
count=0;
for j=1:numel(S)
    for i=1:size(angles,1)
        n=[0.4;-0.2;0.9];
        Q=rotation_matrix(angles(i,:));
        Si=S(j);Si.R=Q*S(j).R;Si.center=Q*S(j).center;
        a=TRAJECTORY_OBSTACLE_SUPPORT.value(S(j),n);
        b=TRAJECTORY_OBSTACLE_SUPPORT.value(Si,Q*n);
        assert(abs(a-b)<1e-8*(1+abs(a)), ...
            'CHECK_TRAJECTORY_SINGLE_SOLVE:Rotation', ...
            'World rotation changed support value.');
        m=TRAJECTORY_OBSTACLE_SUPPORT.value(S(j),2*n);
        assert(abs(m-2*a)<1e-8*(1+abs(a)), ...
            'CHECK_TRAJECTORY_SINGLE_SOLVE:Homogeneity', ...
            'Obstacle support is not positively homogeneous.');
        count=count+1;
    end
end
% The generator must still have no certified path to HLC commit.
try
    G.commit(X);
    error('CHECK_TRAJECTORY_SINGLE_SOLVE:Commit','Unsafe commit accepted.');
catch ME
    if strcmp(ME.identifier,'CHECK_TRAJECTORY_SINGLE_SOLVE:Commit')
        rethrow(ME)
    end
    assert(strcmp(ME.identifier,'TRAJECTORY_GENERATOR:CommitNotCertified'), ...
        'CHECK_TRAJECTORY_SINGLE_SOLVE:Commit','Unexpected commit behaviour.');
end
R=struct('status', ...
    'PASS_SINGLE_SOLVE_GEOMETRIC_TRANSCRIPTION__DYNAMICS_NOT_CERTIFIED', ...
    'shape_rotation_checks',count,'identity_safe',X.certified_geometry, ...
    'penetrating_shape_rejected',~Y.certified_geometry, ...
    'hlc_commit_blocked',true, ...
    'real_fmincon_convergence_tested',false, ...
    'real_flight_tested',false,'max_runtime_proven',false);
fid=fopen(fullfile(root,'TRAJECTORY_SINGLE_SOLVE_RESULT.txt'),'wt');
assert(fid>0,'CHECK_TRAJECTORY_SINGLE_SOLVE:Output','Cannot save audit.');
cleaner=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\n',R.status);
fprintf(fid,'12-shape rotation checks=%d; real solver=NOT_TESTED\n',count);
end
function [z,exitflag,output]=identity_solver(~,z0,G,~)
% Deliberately no optimisation: tests only exact one-solve plumbing.
[c,ceq]=G(z0);
z=z0;
if all(c<=0)&&all(abs(ceq)<1e-10)
    exitflag=1;
else
    exitflag=-2;
end
output=struct('adapter','IDENTITY_FEASIBILITY_REGRESSION');
end
function Q=rotation_matrix(a)
x=a(1)*pi/180;y=a(2)*pi/180;z=a(3)*pi/180;
Rx=[1 0 0;0 cos(x) -sin(x);0 sin(x) cos(x)];
Ry=[cos(y) 0 sin(y);0 1 0;-sin(y) 0 cos(y)];
Rz=[cos(z) -sin(z) 0;sin(z) cos(z) 0;0 0 1];
Q=Rz*Ry*Rx;
end
function o=all_shapes()
v=[0 0 0;1 0 0;0 1 0;0 0 1];
f=[1 3 2;1 2 4;1 4 3;2 3 4];
a={ ...
OBSTACLE_INFORMATION.define(1,'sphere',[0 6 0],0.3), ...
OBSTACLE_INFORMATION.define(2,'ellipsoid',[0 6 0],[0.5 1 2],'euler_deg',[20 40 50]), ...
OBSTACLE_INFORMATION.define(3,'box',[0 6 0],[1 0.6 2],'euler_deg',[5 25 40]), ...
OBSTACLE_INFORMATION.define(4,'cylinder',[0 6 0],[0.5 2],'euler_deg',[20 20 15]), ...
OBSTACLE_INFORMATION.define(5,'capsule',[0 6 0],[0.3 1]), ...
OBSTACLE_INFORMATION.define(6,'cone',[0 6 0],[0.5 2],'euler_deg',[10 20 30]), ...
OBSTACLE_INFORMATION.define(7,'frustum',[0 6 0],[0.8 0.3 1]), ...
OBSTACLE_INFORMATION.define(8,'pyramid',[0 6 0],[1 2]), ...
OBSTACLE_INFORMATION.define(9,'regular_prism',[0 6 0],[6 0.7 1]), ...
OBSTACLE_INFORMATION.define(10,'torus',[0 6 0],[1 0.2]), ...
OBSTACLE_INFORMATION.define(11,'polygon_prism',[0 6 0], ...
        struct('outline',[-1 -1;1 -1;1 1;-1 1],'height',2)), ...
OBSTACLE_INFORMATION.define(12,'polyhedron',[0 6 0], ...
        struct('vertices',v,'faces',f)) ...
};
o=[a{:}];
end
