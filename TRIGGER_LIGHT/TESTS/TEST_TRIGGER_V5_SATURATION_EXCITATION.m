function R=TEST_TRIGGER_V5_SATURATION_EXCITATION()
%TEST_TRIGGER_V5_SATURATION_EXCITATION Original HLC at deliberately perturbed
% physically taut INITIAL estimated states. No flight truth is passed to
% controller. This is ONE-STEP saturation discovery, NOT a 4s rollout.
% Do not claim saturation coverage unless a VALID taut case is observed.
agent=DRONE();
agent.parameter=DRONE_PARAM_SUSPENDED_LOAD('DIATONE');
agent.parameter.set("cableL",struct('cableL',2.0));
agent.parameter.set("loadmass",struct('loadmass',.01)); % stale model field
L=agent.parameter.get("cableL");
agent.plant=struct('name','V5_STRESS_TEST_ONLY');
mhat=.14; % V4 EKF test state; not plant truth
P=Controller_HL_Suspended_Load(.025,agent);
agent.reference.set_function_class('waypoint', ...
    WAYPOINT_REFERENCE(agent,{'gen_wp_straight',{'speed',1.5},6}));
xd=agent.reference.waypoint.generator.evaluate(0);
xd(3)=xd(3)-L;
refProxy=STATE_CLASS(struct('state_list',"xd",'num_list',28));
refProxy.set_state('xd',xd);
physicalNames={'mass','Lx','Ly','lx','ly','jx','jy','jz','gravity', ...
    'km1','km2','km3','km4','k1','k2','k3','k4','rotor_r', ...
    'Length','loadmass','cableL'};
p=agent.parameter.get('all','row');p=reshape(p,1,[]);
assert(numel(p)==21,'Original parameter layout changed');
p(20)=mhat;
values=cell2struct(num2cell(p),physicalNames,2);
params=WP_TRIGGER_PARAMETER_VIEW(values);
models=struct('caseName',{},'lateralOffset_m',{}, ...
    'cableAngle_rad',{},'cableAngularRate_rad_s',{}, ...
    'initialDroneVelocity_m_s',{},'saturationMagnitude',{}, ...
    'initialModeledTension_N',{},'tautPositiveAtStart',{}, ...
    'saturationObserved',{},'errorText',{});
for off=[0,1,2,4,6]
    for theta=[0,.15,.30,.45]
        for omega=[0,.6,1.2]
            for vx=[0,2]
                st=struct('p',[off;0;3], 'q',[0;0;0], ...
                    'v',[vx;0;0], 'w',[0;0;0], ...
                    'pL',[0;0;0], 'vL',[0;0;0], ...
                    'pT',[sin(theta);0;-cos(theta)], ...
                    'wL',[0;omega;0],'mL',mhat);
                st.pL=st.p+L*st.pT;
                st.vL=st.v+L*cross(st.wL,st.pT);
                keys=["p","q","v","w","pL","vL","pT","wL","mL"];
                lens=[3,3,3,3,3,3,3,3,1];
                state=STATE_CLASS(struct('state_list',keys,'num_list',lens));
                state.set_state(st);
                proxy=struct('estimator',struct('result',struct('state',state)), ...
                    'reference',struct('result',struct('state',refProxy)), ...
                    'parameter',params);
                sat=NaN; tension=NaN; msg='';
                try
                    H=HLC_SUSPENDED_LOAD(proxy,P);
                    out=H.do();
                    clipped=out.input(:);raw=out.tmp(:);
                    sat=max(abs(clipped-raw));
                    md=p(1);ml=p(20);g=p(9); %#ok<NASGU>
                    b=[0;0;1];q=st.pT;w=st.wL;
                    tension=(md*ml/(md+ml))*L*norm(cross(w,q))^2 ...
                        -(ml/(md+ml))*clipped(1)*dot(q,b);
                catch ME
                    msg=ME.message;
                end
                models(end+1)=struct('caseName','single_step_probe', ...
                    'lateralOffset_m',off,'cableAngle_rad',theta, ...
                    'cableAngularRate_rad_s',omega, ...
                    'initialDroneVelocity_m_s',vx, ...
                    'saturationMagnitude',sat, ...
                    'initialModeledTension_N',tension, ...
                    'tautPositiveAtStart',isfinite(tension)&&tension>0, ...
                    'saturationObserved',isfinite(sat)&&sat>1e-9, ...
                    'errorText',msg); %#ok<AGROW>
            end
        end
    end
end
valid=[models.tautPositiveAtStart] & [models.saturationObserved];
R=struct('status','ONE_STEP_SATURATION_NOT_YET_FOUND', ...
    'n',numel(models),'cases',models, ...
    'validTautSaturatedCount',nnz(valid), ...
    'saturationActuallyObserved',any(valid), ...
    'estimatedLoadMassUsed',mhat,'plantTrueLoadMassRead',false, ...
    'fullFourSecondSaturatedRolloutTested',false, ...
    'safeForOnline',false);
if any(valid)
    R.status='VALID_TAUT_ONE_STEP_SATURATION_FOUND__FOUR_SECOND_UNTESTED';
    R.firstValidSaturatedCase=models(find(valid,1,'first'));
end
end
