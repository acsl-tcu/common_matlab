function R=BENCH_TRIGGER_V8_FULL_SELECTED_MEX(repeats)
%BENCH_TRIGGER_V8_FULL_SELECTED_MEX End-to-end C one-mode A/B after build.
% Compare full: latest EKF snapshot + 4s PV forecast + ONE C x ellipsoid
% geometry. The compiled kernel only accelerates C's 36-part preclear.
% Always compare classification/parity before accepting timings.
if nargin<1,repeats=60;end
R=struct('status','MEX_NOT_FOUND','meanings','NOMINAL_ONLY', ...
    'matlabMedianMs',NaN,'mexMedianMs',NaN, ...
    'matlabP95Ms',NaN,'mexP95Ms',NaN, ...
    'matlabMaxMs',NaN,'mexMaxMs',NaN, ...
    'classificationAgrees',false);
if exist('wp_six_trigger_C_chain_numeric_mex_v8','file')~=3
    return
end
base=fullfile(fileparts(mfilename('fullpath')),'BASELINE_TRACES', ...
    'PURE_TRIGGER_V6_CAUSAL_AUDIT_20261113_013957.mat');
Q=load(base,'R');c=Q.R.original6.results(4);tr=c.nominalTrace;
T=reshape(tr.time,1,[]);
k0=find(abs(T-1)<1e-10,1);past=k0-40:k0;future=k0:k0+160;
settings=tr.governorSettings;
a=DRONE();a.parameter=DRONE_PARAM_SUSPENDED_LOAD('DIATONE');
a.plant=struct('name','TEST_ONLY');
ctrl=Controller_HL_Suspended_Load(.025,a);
K=wp_six_trigger_pv_cache_prepare( ...
    struct('F1',ctrl.F1,'F2',ctrl.F2,'F3',ctrl.F3), ...
    -1:.025:0,settings.filterTime,.1);
C=wp_six_trigger_route_cache_prepare_v8( ...
    gen_wp_straight('speed',1.5),0:.025:8);
dp=ppval(C.ppDP,reshape(tr.governorTau(past),1,[]));
H=struct('pastTimes',T(past)-1,'pastLoad',tr.pLoad(:,past), ...
    'pastVelocity',tr.vLoad(:,past), ...
    'pastRefLoad',tr.refLoad(:,past), ...
    'pastRefVelocity',dp.*repmat(tr.governorRateState(6,past),3,1), ...
    'tauNow',tr.governorTau(k0), ...
    'rateNow',tr.governorRateState(:,k0), ...
    'heldCommandNow',tr.governorHeldCommand(k0), ...
    'estimatedML',c.modelEstimatedMass, ...
    'cableLength',c.modelCableLength, ...
    'gravity',c.modelGravity, ...
    'slowdownStart',settings.slowdownStart, ...
    'slowdownFull',settings.slowdownFull, ...
    'minScale',settings.minScale, ...
    'filterTime',settings.filterTime);
centers=zeros(3,36);axes=repmat([.12;.12;.12],1,36);
for m=1:36
    index=1+4*mod(m-1,40);
    centers(:,m)=tr.pLoad(:,future(index)) + ...
        [.85+.08*cos(m);.2*sin(m);.04*cos(2*m)];
end
[~,world]=six_test_fixture(centers,axes,false);
known=wp_six_trigger_prepare(world,'multiple_ellipsoids');
cfg=wp_six_trigger_config('C','multiple_ellipsoids', ...
    wp_system_geometry_config('C'), ...
    struct('loadMass',c.modelEstimatedMass, ...
    'cableLength',c.modelCableLength));
agent=struct();agent.parameter=DRONE_PARAM_SUSPENDED_LOAD('DIATONE');
agent.parameter.set("cableL",struct('cableL',c.modelCableLength));
agent.parameter.set("loadmass",struct('loadmass',999));
agent.estimator.result.state=struct('pL',H.pastLoad(:,end), ...
    'vL',H.pastVelocity(:,end),'mL',c.modelEstimatedMass);
CM=cfg;CM.useMexCChainPreclear=false;
CX=cfg;CX.useMexCChainPreclear=true;
for k=1:8
    A=wp_six_trigger_selected_nominal_v8(agent,H,K,C,known,CM);
    B=wp_six_trigger_selected_nominal_v8(agent,H,K,C,known,CX);
end
R.classificationAgrees=strcmp(A.status,B.status) && ...
    strcmp(A.rawNominalGeometryStatus,B.rawNominalGeometryStatus) && ...
    ~B.safeToCommit && ~A.safeToCommit;
if ~R.classificationAgrees
    R.status='FAIL_MEX_FULL_CLASSIFICATION';return
end
mt=nan(1,repeats);xt=mt;
for k=1:repeats
    if mod(k,2)
        AA=wp_six_trigger_selected_nominal_v8(agent,H,K,C,known,CM);
        BB=wp_six_trigger_selected_nominal_v8(agent,H,K,C,known,CX);
    else
        BB=wp_six_trigger_selected_nominal_v8(agent,H,K,C,known,CX);
        AA=wp_six_trigger_selected_nominal_v8(agent,H,K,C,known,CM);
    end
    mt(k)=AA.totalMs;xt(k)=BB.totalMs;
end
assert(all(isfinite([mt,xt])) && all(mt>0) && all(xt>0));
ms=sort(mt);xs=sort(xt);
R.matlabMedianMs=median(mt);R.mexMedianMs=median(xt);
R.matlabP95Ms=ms(ceil(.95*repeats));
R.mexP95Ms=xs(ceil(.95*repeats));
R.matlabMaxMs=max(mt);R.mexMaxMs=max(xt);
R.status='PASS_FULL_ONE_MODE_MEX_AB__NOMINAL_ONLY';
end
