function R=TEST_TRIGGER_V7_PV_AND_SELECTED_GEOMETRY()
%TEST_TRIGGER_V7_PV_AND_SELECTED_GEOMETRY Reuse SAVED 6s original HLC trace.
% 4 cases x 2 starts; causally estimate modes from past 1s EKF pL/vL.
% Compare with future original HLC trace AFTER forecasting only.
% One selected system and one obstacle approximation per call; 6 choices
% are BENCHMARKED SEPARATELY, not combined in an online tick.
% No claim of physical prediction bound / true collision certification.
base=fullfile(fileparts(mfilename('fullpath')),'BASELINE_TRACES', ...
    'PURE_TRIGGER_V6_CAUSAL_AUDIT_20261113_013957.mat');
if ~isfile(base),error('V7:Trace','Saved V6.1 six-second baseline missing');end
S=load(base,'R');R6=S.R.original6;
assert(R6.allSucceeded && numel(R6.results)==4);
agent0=DRONE();agent0.parameter=DRONE_PARAM_SUSPENDED_LOAD('DIATONE');
agent0.plant=struct('name','TEST_ONLY_NOMINAL_NO_TRUE_PLANT');
ctrl=Controller_HL_Suspended_Load(.025,agent0);
gains=struct('F1',ctrl.F1,'F2',ctrl.F2,'F3',ctrl.F3);
routeCache=wp_six_trigger_route_cache_prepare(gen_wp_straight('speed',1.5),0:.025:8);
historyTimes=-1:.025:0;
settings=R6.results(1).nominalTrace.governorSettings;
K=wp_six_trigger_pv_cache_prepare(gains,historyTimes,settings.filterTime,.1);
modes={'C','B','D'};
covers={'multiple_spheres','multiple_ellipsoids'};
recs=struct('caseName',{},'startTime_s',{}, ...
    'maxLoadError_m',{},'maxDroneError_m',{},'maxCableAngleError_deg',{}, ...
    'maxGovernorTimeError_s',{},'forecastMedianMs',{}, ...
    'fitCondition',{},'originalSaturated',{});
noise=struct('caseName',{},'startTime_s',{}, ...
    'testPositionNoiseSigma_m',{},'testVelocityNoiseSigma_mps',{}, ...
    'noiseRepetitions',{},'medianMaxLoadError_m',{},'worstMaxLoadError_m',{});
geo=struct('caseName',{},'startTime_s',{},'mode',{},'cover',{}, ...
    'scenario',{},'nominalPredictorStatus',{},'originalBaselineStatus',{}, ...
    'classificationAgrees',{},'medianTotalMs',{},'p95TotalMs',{}, ...
    'maxTotalMs',{},'medianForecastMs',{},'medianGeometryMs',{}, ...
    'massFromEKF',{},'safeCertified',{},'errorText',{}, ...
    'baselineReason',{},'baselineProjectionMax_m',{},'timingSamples',{});
rng(20261113,'twister');
for ci=1:4
    c=R6.results(ci);tr=c.nominalTrace;
    t=reshape(tr.time,1,[]);
    for t0=[1,2]
        k0=find(abs(t-t0)<1e-10,1);
        past=k0-40:k0;future=k0:k0+160;
        assert(past(1)>0 && future(end)<=numel(t));
        tauPast=reshape(tr.governorTau(past),1,[]);
        dp=interp1(routeCache.tauGrid',routeCache.dp',tauPast','pchip')';
        pastRefVelocity=dp.*repmat(tr.governorRateState(6,past),3,1);
        H=struct('pastTimes',t(past)-t0, ...
            'pastLoad',tr.pLoad(:,past),'pastVelocity',tr.vLoad(:,past), ...
            'pastRefLoad',tr.refLoad(:,past), ...
            'pastRefVelocity',pastRefVelocity, ...
            'tauNow',tr.governorTau(k0), ...
            'rateNow',tr.governorRateState(:,k0), ...
            'heldCommandNow',tr.governorHeldCommand(k0), ...
            'estimatedML',c.modelEstimatedMass, ...
            'cableLength',c.modelCableLength,'gravity',c.modelGravity, ...
            'slowdownStart',settings.slowdownStart, ...
            'slowdownFull',settings.slowdownFull,'minScale',settings.minScale, ...
            'filterTime',settings.filterTime);
        pred=wp_six_trigger_pv_forecast(H,K,routeCache);
        assert(~pred.futureReferenceOracleUsed && ~pred.futureHlcUsed && ...
            ~pred.isEligibleForSafeClear && pred.notCertified);
        difL=vecnorm(pred.pLoad-tr.pLoad(:,future),2,1);
        difD=vecnorm(pred.pDrone-tr.pDrone(:,future),2,1);
        qdot=sum(pred.predCableDirection.*tr.pT(:,future),1);
        ang=acos(max(-1,min(1,qdot)))*180/pi;
        times=zeros(1,20);
        for j=1:numel(times)
            v=wp_six_trigger_pv_forecast(H,K,routeCache);times(j)=v.timeMs;
        end
        recs(end+1)=struct('caseName',char(c.caseName),'startTime_s',t0, ...
            'maxLoadError_m',max(difL),'maxDroneError_m',max(difD), ...
            'maxCableAngleError_deg',max(ang), ...
            'maxGovernorTimeError_s',max(abs(pred.virtualTime- ...
                 tr.governorTau(future))), ...
            'forecastMedianMs',median(times),'fitCondition',max(K.condition), ...
            'originalSaturated',logical(c.saturationSeen)); %#ok<AGROW>
        nn=zeros(1,8);
        for j=1:8
            noisy=H;
            noisy.pastLoad=H.pastLoad+.001*randn(size(H.pastLoad));
            noisy.pastVelocity=H.pastVelocity+.01*randn(size(H.pastVelocity));
            ff=wp_six_trigger_pv_forecast(noisy,K,routeCache);
            nn(j)=max(vecnorm(ff.pLoad-tr.pLoad(:,future),2,1));
        end
        noise(end+1)=struct('caseName',char(c.caseName), ...
            'startTime_s',t0,'testPositionNoiseSigma_m',.001, ...
            'testVelocityNoiseSigma_mps',.01, ...
            'noiseRepetitions',8,'medianMaxLoadError_m',median(nn), ...
            'worstMaxLoadError_m',max(nn)); %#ok<AGROW>
        fprintf('V7 PV %-18s t0 %.1fs: max Load %.4gm, Drone %.4gm, t %.3fms\n', ...
            c.caseName,t0,max(difL),max(difD),median(times));
        % Geometry: compare pred and ORIGINAL baseline using the SAME
        % piecewise-linear 41 knots. No invented physical rho/acc bounds.
        ids=1:4:161;
        % The original 24-state integrator can drift very slightly from
        % norm(pLoad-pDrone)==L. Its raw sampled positions therefore fail
        % a STRICT zero-tube geometry API with UNKNOWN. This comparison is
        % explicitly NOMINAL ONLY: project the baseline drone endpoint
        % along the original endpoint vector. This is the MINIMUM
        % position correction enforcing the known nominal L. Record the
        % correction (never silently pass an arbitrary physical error tube).
        [baselineDrone,projection]=wp_v7_nominal_baseline_taut_projection( ...
            tr.pLoad(:,future(ids)),tr.pDrone(:,future(ids)), ...
            tr.pT(:,future(ids)),c.modelCableLength);
        B=struct('timeOffsets',(0:40)*.1, ...
            'pDrone',baselineDrone, ...
            'pLoad',tr.pLoad(:,future(ids)), ...
            'rhoDrone',zeros(1,41),'rhoLoad',zeros(1,41), ...
            'accDrone',zeros(1,40),'accLoad',zeros(1,40), ...
            'modelLoadMass',c.modelEstimatedMass);
        % One actual-known part placed along baseline at ~1 second.
        touchCenter=tr.pLoad(:,future(41));
        for scene=1:2
            if scene==1
                % 36 nearby but deliberately offset parts; may still
                % be overconservative for some geometry combinations.
                centers=zeros(3,36);axes=repmat([.12;.12;.12],1,36);
                for m=1:36
                    index=1+4*mod(m-1,40);
                    centers(:,m)=tr.pLoad(:,future(index))+ ...
                        [.85+.08*cos(m); .20*sin(m);.04*cos(2*m)];
                end
                sceneName='near_offset_36';
            else
                centers=touchCenter;axes=[.16;.16;.16];
                sceneName='baseline_load_contact';
            end
            [ws,we]=six_test_fixture(centers,axes,false);
            for im=1:3
                mode=modes{im};external=wp_system_geometry_config(mode);
                for ic=1:2
                    cover=covers{ic};world=ws;
                    if ic==2,world=we;end
                    known=wp_six_trigger_prepare(world,cover);
                    model=struct('loadMass',c.modelEstimatedMass, ...
                        'cableLength',c.modelCableLength);
                    cfg=wp_six_trigger_config(mode,cover,external,model);
                    truth=wp_six_trigger_evaluate_fast_v4(known,cfg,B);
                    % Test-only agent with stale parameter.loadmass=999.
                    % The selected tick must use state.mL instead.
                    agent=struct();
                    agent.parameter=DRONE_PARAM_SUSPENDED_LOAD('DIATONE');
                    agent.parameter.set("cableL",struct('cableL',c.modelCableLength));
                    agent.parameter.set("loadmass",struct('loadmass',999));
                    agent.estimator.result.state=struct('pL',H.pastLoad(:,end), ...
                        'vL',H.pastVelocity(:,end),'mL',c.modelEstimatedMass);
                    % Warm-up is excluded from timing; no cache preparation in tick.
                    for warm=1:5
                        wp_six_trigger_selected_nominal_v7(agent,H,K,routeCache,known,cfg);
                    end
                    % All timing samples MUST be measured, never zeros.
                    nTimed=40;
                    bench=nan(1,nTimed);pf=nan(1,nTimed);gm=nan(1,nTimed);
                    for k=1:nTimed
                        Rtick=wp_six_trigger_selected_nominal_v7( ...
                            agent,H,K,routeCache,known,cfg);
                        bench(k)=Rtick.totalMs;pf(k)=Rtick.forecastMs;gm(k)=Rtick.geometryMs;
                    end
                    % Match only the underlying nominal polyline status;
                    % neither status is a physical true-state guarantee.
                    agrees=strcmp(Rtick.rawNominalGeometryStatus,truth.status);
                    assert(~Rtick.safeToCommit && ~Rtick.physicalClearCertified);
                    assert(abs(Rtick.modelLoadMassUsed-c.modelEstimatedMass)<1e-12);
                    assert(abs(agent.parameter.get("loadmass")-999)<1e-12);
                    assert(all(isfinite(bench)) && all(bench>0), ...
                        'V7:TimingSamples','Invalid/unmeasured total tick time');
                    assert(all(isfinite(pf)) && all(pf>0));
                    assert(all(isfinite(gm)) && all(gm>=0));
                    [v,~]=sort(bench);
                    geo(end+1)=struct('caseName',char(c.caseName), ...
                        'startTime_s',t0,'mode',mode,'cover',cover, ...
                        'scenario',sceneName, ...
                        'nominalPredictorStatus',Rtick.rawNominalGeometryStatus, ...
                        'originalBaselineStatus',truth.status, ...
                        'classificationAgrees',agrees, ...
                        'medianTotalMs',median(bench), ...
                        'p95TotalMs',v(ceil(.95*numel(v))), ...
                        'maxTotalMs',max(bench), ...
                        'medianForecastMs',median(pf), ...
                        'medianGeometryMs',median(gm), ...
                        'massFromEKF',Rtick.modelLoadMassUsed, ...
                        'safeCertified',Rtick.safeToCommit, ...
                        'errorText',Rtick.reason, ...
                        'baselineReason',truth.reason, ...
                        'baselineProjectionMax_m',projection.maxCorrection_m, ...
                        'timingSamples',nTimed); %#ok<AGROW>
                end
            end
        end
    end
end
nUnknown=sum(strcmp({geo.originalBaselineStatus},'UNKNOWN'));
nDisagree=sum(~[geo.classificationAgrees]);
if nUnknown>0
    auditStatus='INVALID_NOMINAL_BASELINE_UNKNOWN__NO_SAFETY_CLAIM';
elseif nDisagree>0
    auditStatus='NOMINAL_CLASSIFICATION_MISMATCH__NO_SAFETY_CLAIM';
else
    auditStatus='NOMINAL_GEOMETRY_AGREEMENT__NOT_SAFETY_QUALIFIED';
end
R=struct('status',auditStatus, ...
    'forecastRecords',recs,'noiseRecords',noise, ...
    'geometryRecords',geo,'selectedModePerCall',true, ...
    'futurePlantOrReferenceOracleUsed',false, ...
    'EKFCurrentMassOnly',true,'plantMassErrorSweepSkippedAsRequested',true, ...
    'physicalPredictionErrorCertified',false, ...
    'continuousTimeCollisionCertified',false, ...
    'flight25msMeasured',false, ...
    'nominalBaselineUnknownCount',nUnknown, ...
    'nominalClassificationDisagreements',nDisagree, ...
    'total2msMeasuredMedPassFraction',mean([geo.medianTotalMs]<=2), ...
    'total2msMeasuredP95PassFraction',mean([geo.p95TotalMs]<=2), ...
    'maxBaselineProjection_m',max([geo.baselineProjectionMax_m]), ...
    'timingSamplesPerCase',40, ...
    'fullProductionIntegrationDone',false);
end
