function R=TEST_TRIGGER_V8_FASTPATH_AND_STREAM(repeats)
%TEST_TRIGGER_V8_FASTPATH_AND_STREAM One-mode V7 vs V8 parity/timing.
% Uses SAVED original 6-second HLC baselines, no 300ms HLC rollout.
% Tests 4 original HLC conditions x 2 starts x 6 independent geometry
% choices x 2 observed obstacle scenes (96). Each selection is a separate
% call; never OR six modes. Tests ORIGINAL EKF stream buffer; current mL
% is read every tick (and parameter.loadmass is deliberately wrong).
% No claim of true physical/contact certification.
if nargin<1,repeats=30;end
base=fullfile(fileparts(mfilename('fullpath')),'BASELINE_TRACES', ...
    'PURE_TRIGGER_V6_CAUSAL_AUDIT_20261113_013957.mat');
S0=load(base,'R');R6=S0.R.original6;
assert(R6.allSucceeded && numel(R6.results)==4);
agent0=DRONE();agent0.parameter=DRONE_PARAM_SUSPENDED_LOAD('DIATONE');
agent0.plant=struct('name','TEST_ONLY_NO_TRUE_PLANT');
ctrl=Controller_HL_Suspended_Load(.025,agent0);
gains=struct('F1',ctrl.F1,'F2',ctrl.F2,'F3',ctrl.F3);
routeCache=wp_six_trigger_route_cache_prepare_v8( ...
    gen_wp_straight('speed',1.5),0:.025:8);
settings=R6.results(1).nominalTrace.governorSettings;
K=wp_six_trigger_pv_cache_prepare(gains,-1:.025:0,settings.filterTime,.1);
recs=struct('caseName',{},'startTime_s',{},'mode',{},'cover',{}, ...
    'scenario',{},'statusV7',{},'statusV8',{},'parity',{}, ...
    'validClearRefinement',{},'noInvalidNewClear',{}, ...
    'medianV7Ms',{},'medianV8Ms',{},'P95V8Ms',{},'maxV8Ms',{}, ...
    'medianForecastV8Ms',{},'medianGeometryV8Ms',{}, ...
    'v8CPrecleared',{},'massFromLatestEKF',{});
rt={'C','B','D'};coverNames={'multiple_spheres','multiple_ellipsoids'};
for ci=1:4
    c=R6.results(ci);tr=c.nominalTrace;
    tt=reshape(tr.time,1,[]);
    for t0=[1,2]
        k0=find(abs(tt-t0)<1e-10,1);
        past=(k0-40):k0;future=k0:(k0+160);
        tauPast=reshape(tr.governorTau(past),1,[]);
        dp=ppval(routeCache.ppDP,tauPast);
        pastRefVelocity=dp.*repmat(tr.governorRateState(6,past),3,1);
        H=struct('pastTimes',tt(past)-t0, ...
            'pastLoad',tr.pLoad(:,past),'pastVelocity',tr.vLoad(:,past), ...
            'pastRefLoad',tr.refLoad(:,past), ...
            'pastRefVelocity',pastRefVelocity, ...
            'tauNow',tr.governorTau(k0), ...
            'rateNow',tr.governorRateState(:,k0), ...
            'heldCommandNow',tr.governorHeldCommand(k0), ...
            'estimatedML',c.modelEstimatedMass, ...
            'cableLength',c.modelCableLength,'gravity',c.modelGravity, ...
            'slowdownStart',settings.slowdownStart, ...
            'slowdownFull',settings.slowdownFull,'minScale',settings.minScale, ...
            'filterTime',settings.filterTime);
        P7=wp_six_trigger_pv_forecast(H,K,routeCache);
        P8=wp_six_trigger_pv_forecast_v8(H,K,routeCache);
        eqD=max(abs(P7.pDrone(:)-P8.pDrone(:)));
        eqL=max(abs(P7.pLoad(:)-P8.pLoad(:)));
        eqT=max(abs(P7.virtualTime(:)-P8.virtualTime(:)));
        assert(max([eqD,eqL,eqT])<2e-9, ...
            'V8:PCHIP','Precomputed PCHIP changed V7 nominal trajectory');
        % Same trajectory; only the geometry preclear changes.
        touch=tr.pLoad(:,future(41));
        for scene=1:2
            if scene==1
                centers=zeros(3,36);axes=repmat([.12;.12;.12],1,36);
                for m=1:36
                    index=1+4*mod(m-1,40);
                    centers(:,m)=tr.pLoad(:,future(index)) + ...
                        [.85+.08*cos(m);.20*sin(m);.04*cos(2*m)];
                end
                sceneName='near_offset_36';
            else
                centers=touch;axes=[.16;.16;.16];
                sceneName='baseline_load_contact';
            end
            [ws,we]=six_test_fixture(centers,axes,false);
            for im=1:3
                mode=rt{im};external=wp_system_geometry_config(mode);
                for ic=1:2
                    cover=coverNames{ic};world=ws;
                    if ic==2,world=we;end
                    known=wp_six_trigger_prepare(world,cover);
                    cfg=wp_six_trigger_config(mode,cover,external, ...
                        struct('loadMass',c.modelEstimatedMass, ...
                               'cableLength',c.modelCableLength));
                    agent=struct();
                    agent.parameter=DRONE_PARAM_SUSPENDED_LOAD('DIATONE');
                    agent.parameter.set("cableL", ...
                        struct('cableL',c.modelCableLength));
                    agent.parameter.set("loadmass",struct('loadmass',999));
                    agent.estimator.result.state=struct( ...
                        'pL',H.pastLoad(:,end),'vL',H.pastVelocity(:,end), ...
                        'mL',c.modelEstimatedMass);
                    V7=wp_six_trigger_selected_nominal_v7( ...
                        agent,H,K,routeCache,known,cfg);
                    V8=wp_six_trigger_selected_nominal_v8( ...
                        agent,H,K,routeCache,known,cfg);
                    same=strcmp(V7.rawNominalGeometryStatus, ...
                        V8.rawNominalGeometryStatus) && ...
                        strcmp(V7.status,V8.status);
                    refined=strcmp(V7.rawNominalGeometryStatus,'POSSIBLE_CONTACT') && ...
                        strcmp(V8.rawNominalGeometryStatus,'CLEAR_CONDITIONAL') && ...
                        mode=='C' && isfield(V8,'nominalGeometry') && ...
                        isfield(V8.nominalGeometry,'v8ChainExtraCleared') && ...
                        V8.nominalGeometry.v8ChainExtraCleared>0;
                    % POSSIBLE means unresolved, not a proven collision.
                    % A new CLEAR is permitted ONLY if new C chain strict
                    % sufficient separation provides the certificate.
                    pass=(same || refined) && ~V8.safeToCommit && ...
                        ~V8.physicalClearCertified && ...
                        ~strcmp(V8.rawNominalGeometryStatus,'UNKNOWN');
                    assert(pass,'V8:Parity', ...
                        'Mode %s cover %s scene %s: invalid nominal regression', ...
                        mode,cover,sceneName);
                    % Alternate A/B, warm up both. Never include missing
                    % values or unmeasured entries in timing statistics.
                    for warm=1:5
                        wp_six_trigger_selected_nominal_v7( ...
                            agent,H,K,routeCache,known,cfg);
                        wp_six_trigger_selected_nominal_v8( ...
                            agent,H,K,routeCache,known,cfg);
                    end
                    m7=nan(1,repeats);m8=nan(1,repeats);
                    f8=m8;g8=m8;
                    for rep=1:repeats
                        if mod(rep,2)==1
                            A=wp_six_trigger_selected_nominal_v7( ...
                                agent,H,K,routeCache,known,cfg);
                            B=wp_six_trigger_selected_nominal_v8( ...
                                agent,H,K,routeCache,known,cfg);
                        else
                            B=wp_six_trigger_selected_nominal_v8( ...
                                agent,H,K,routeCache,known,cfg);
                            A=wp_six_trigger_selected_nominal_v7( ...
                                agent,H,K,routeCache,known,cfg);
                        end
                        m7(rep)=A.totalMs;m8(rep)=B.totalMs;
                        f8(rep)=B.forecastMs;g8(rep)=B.geometryMs;
                    end
                    assert(all(isfinite([m7,m8,f8,g8])));
                    v=sort(m8);
                    extra=0;
                    if isfield(V8,'nominalGeometry') && ...
                            isfield(V8.nominalGeometry,'v8ChainExtraCleared')
                        extra=V8.nominalGeometry.v8ChainExtraCleared;
                    end
                    recs(end+1)=struct('caseName',char(c.caseName), ...
                        'startTime_s',t0,'mode',mode,'cover',cover, ...
                        'scenario',sceneName,'statusV7',V7.status, ...
                        'statusV8',V8.status,'parity',same, ...
                        'validClearRefinement',refined, ...
                        'noInvalidNewClear',pass, ...
                        'medianV7Ms',median(m7), ...
                        'medianV8Ms',median(m8), ...
                        'P95V8Ms',v(ceil(.95*repeats)), ...
                        'maxV8Ms',max(m8), ...
                        'medianForecastV8Ms',median(f8), ...
                        'medianGeometryV8Ms',median(g8), ...
                        'v8CPrecleared',extra, ...
                        'massFromLatestEKF',V8.modelLoadMassUsed); %#ok<AGROW>
                end
            end
        end
    end
end
stream=TEST_TRIGGER_V8_EKF_STREAM();
R=struct('status','PASS_V8_NO_INVALID_NOMINAL_REGRESSION__NOT_PHYSICAL_CERTIFICATION', ...
    'records',recs,'stream',stream, ...
    'oneSelectedModePerCall',true,'nominalOnly',true, ...
    'exactAgreementFraction',mean([recs.parity]), ...
    'validClearRefinements',nnz([recs.validClearRefinement]), ...
    'originalPlantTruthUsedInPredictor',false, ...
    'futureReferenceOracleUsed',false, ...
    'physicalPredictionErrorBoundCertified',false, ...
    'flight25msMeasured',false,'actualEkfErrorKnown',false, ...
    'median2msPassFraction',mean([recs.medianV8Ms]<=2), ...
    'p95_2msPassFraction',mean([recs.P95V8Ms]<=2), ...
    'maxTotalMs',max([recs.maxV8Ms]));
end
