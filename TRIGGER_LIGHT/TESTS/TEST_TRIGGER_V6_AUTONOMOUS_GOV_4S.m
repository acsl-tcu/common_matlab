function R=TEST_TRIGGER_V6_AUTONOMOUS_GOV_4S(R6)
%TEST_TRIGGER_V6_AUTONOMOUS_GOV_4S Causal 4s modal+governor audit.
% At t0=1 and 2s use ONLY source-known route, t<=t0 HLC history, t0 EKF-like
% estimated mL & governor state. No future actual reference, HLC or plant
% values are passed to candidate. The future original trace is used ONLY
% AFTER prediction to calculate error and test time.
assert(isfield(R6,'results') && numel(R6.results)==4);
assert(all(strcmp({R6.results.status},'NOMINAL_COMPLETED')));
required={'gen_wp_straight','Controller_HL_Suspended_Load','DRONE', ...
    'DRONE_PARAM_SUSPENDED_LOAD'};
for i=1:numel(required),assert(~isempty(which(required{i})));end
agent=DRONE();agent.parameter=DRONE_PARAM_SUSPENDED_LOAD('DIATONE');
agent.plant=struct('name','V5_OFFLINE_COMPARE_ONLY');
ctrl=Controller_HL_Suspended_Load(.025,agent);
gains=struct('F1',ctrl.F1,'F2',ctrl.F2,'F3',ctrl.F3);
% The original V4 baseline used gen_wp_straight(speed=1.5) and virtual
% time 0 at flight start. This is KNOWN ROUTE, not future physical truth.
generator=gen_wp_straight('speed',1.5);
routeCache=wp_v5_route_table_prepare(generator,0:.025:8);
rng(20261113,'twister');
noiseRecords=struct('caseName',{},'startTime_s',{},'assumedPastLoadNoiseSigma_m',{}, ...
    'repetitions',{},'medianMaxLoadError_m',{},'worstMaxLoadError_m',{});
records=struct('caseName',{},'startTime_s',{},'forecastHorizon_s',{}, ...
    'maxLoadError_m',{},'rmsLoadError_m',{}, ...
    'maxDroneError_m',{},'rmsDroneError_m',{}, ...
    'maxGovernorTauError_s',{},'maxGovernorCommandError',{}, ...
    'maxReferencePositionError_m',{}, ...
    'maxCableDirectionError_rad',{}, ...
    'candidateElapsedMs',{},'benchmarkMedianMs',{}, ...
    'originalSaturationSeen',{},'futureOracleUsed',{}, ...
    'modalHistoryCondition',{},'stageModalFitMs',{}, ...
    'stageModalGovernorMs',{},'stageRouteInterpMs',{}, ...
    'stageTautReconstructMs',{},'predictorUsedFullEKFState',{});
for i=1:4
    c=R6.results(i);tr=c.nominalTrace;
    t=reshape(tr.time,1,[]);
    assert(isfield(tr,'governorRateState') && ...
        isfield(tr,'governorHeldCommand') && ...
        isfield(tr,'governorSettings'), ...
        'Run modified ORIGINAL HLC 6s reference: governor state missing');
    for tStart=[1,2]
    k0=find(abs(t-tStart)<1e-10,1,'first');
    assert(~isempty(k0) && k0+160<=numel(t));
    past=find(t>=tStart-1-1e-9 & t<=tStart+1e-9);
    assert(past(end)==k0);
    settings=tr.governorSettings;
    H=struct('pastTimes',t(past)-tStart, ...
        'pastLoad',tr.pLoad(:,past), ...
        'pastRefLoad',tr.refLoad(:,past), ...
        'tauNow',tr.governorTau(k0), ...
        'rateNow',tr.governorRateState(:,k0), ...
        'heldCommandNow',tr.governorHeldCommand(k0), ...
        'estimatedML',c.modelEstimatedMass, ...
        'cableLength',c.modelCableLength, ...
        'gravity',c.modelGravity, ...
        'slowdownStart',settings.slowdownStart, ...
        'slowdownFull',settings.slowdownFull, ...
        'minScale',settings.minScale, ...
        'filterTime',settings.filterTime);
    cache=wp_v5_modal_cache_prepare(gains,H.pastTimes,H.filterTime);
    candidate=wp_v5_modal_gov_forecast_candidate(H,gains,routeCache,cache);
    assert(~candidate.futureReferenceOracleUsed && ...
        ~candidate.futurePlantUsed && ~candidate.isEligibleForSafeClear);
    truthIdx=k0:k0+160;
    ld=vecnorm(candidate.pLoad-tr.pLoad(:,truthIdx),2,1);
    dd=vecnorm(candidate.pDrone-tr.pDrone(:,truthIdx),2,1);
    qd=sum(candidate.predCableDirection.*tr.pT(:,truthIdx),1);
    qd=acos(max(-1,min(1,qd)));
    % Reference output is path at predicted tau + predicted mode error.
    refPred=candidate.pLoad-candidate.predTrackingError;
    rd=vecnorm(refPred-tr.refLoad(:,truthIdx),2,1);
    nBench=20; timings=zeros(1,nBench);
    for j=1:nBench
        cb=wp_v5_modal_gov_forecast_candidate(H,gains,routeCache,cache);
        timings(j)=cb.timeMs;
    end
    records(end+1)=struct('caseName',char(c.caseName), ...
        'startTime_s',tStart, 'forecastHorizon_s',4, ...
        'maxLoadError_m',max(ld), ...
        'rmsLoadError_m',sqrt(mean(ld.^2)), ...
        'maxDroneError_m',max(dd), ...
        'rmsDroneError_m',sqrt(mean(dd.^2)), ...
        'maxGovernorTauError_s',max(abs(candidate.virtualTime- ...
            tr.governorTau(truthIdx))), ...
        'maxGovernorCommandError',max(abs(candidate.governorHeldCommand- ...
            tr.governorHeldCommand(truthIdx))), ...
        'maxReferencePositionError_m',max(rd), ...
        'maxCableDirectionError_rad',max(qd), ...
        'candidateElapsedMs',candidate.timeMs, ...
        'benchmarkMedianMs',median(timings), ...
        'originalSaturationSeen',logical(c.saturationSeen), ...
        'futureOracleUsed',false, ...
        'modalHistoryCondition',max(cellfun(@cond,cache.HP)), ...
        'stageModalFitMs',candidate.stageMs.modalFit, ...
        'stageModalGovernorMs',candidate.stageMs.modalAndGovernor160, ...
        'stageRouteInterpMs',candidate.stageMs.routeInterpolation, ...
        'stageTautReconstructMs',candidate.stageMs.tautReconstruction, ...
        'predictorUsedFullEKFState',false); %#ok<AGROW>
    for sigma=[.0001,.001]
        nNoise=12;maxLoadErrors=zeros(nNoise,1);
        for v=1:nNoise
            Hn=H;
            Hn.pastLoad=H.pastLoad+sigma*randn(size(H.pastLoad));
            noisy=wp_v5_modal_gov_forecast_candidate(Hn,gains,routeCache,cache);
            maxLoadErrors(v)=max(vecnorm(noisy.pLoad- ...
                tr.pLoad(:,truthIdx),2,1));
        end
        noiseRecords(end+1)=struct('caseName',char(c.caseName), ...
            'startTime_s',tStart,'assumedPastLoadNoiseSigma_m',sigma, ...
            'repetitions',nNoise, ...
            'medianMaxLoadError_m',median(maxLoadErrors), ...
            'worstMaxLoadError_m',max(maxLoadErrors)); %#ok<AGROW>
    end
    fprintf('V6 %-18s t0=%.1fs modalGov 4s: load max %.4gm drone max %.4gm governor max %.4gs; median %.3fms\n', ...
        c.caseName,tStart,max(ld),max(dd), ...
        records(end).maxGovernorTauError_s,median(timings));
    end % tStart
end % i
R=struct('status','FOUR_SECOND_NO_FUTURE_ORACLE_NOMINAL_AUDIT_COMPLETED', ...
    'records',records,'noiseRecords',noiseRecords, ...
    'originalRouteUsed',true,'futureReferenceOracleUsed',false, ...
    'originalHlcCalledPerForecast',false, ...
    'original24StateOdeCalledPerForecast',false, ...
    'currentEKFMassUsedFromTrace',true, ...
    'sourceIsNominalSimulatedEstimatorNotLiveEKF',true, ...
    'fullEKF24StateUsedToInitializeModalState',false, ...
    'fullFourSecondsEvaluated',true, ...
    'currentTimeInOriginalTrace_s',[1,2], ...
    'historyDuration_s',1, ...
    'currentGovernorStateSupplied',true, ...
    'routeTablePrecomputed',true, ...
    'inputSaturationQualification',false, ...
    'actualFlightCompared',false, ...
    'syntheticNoiseStressRun',true, ...
    'actualEKFErrorBoundKnown',false, ...
    'noiseQualification',false, ...
    'geometricInterSampleBoundsCertified',false, ...
    'physicalPredictionErrorCertified',false, ...
    'oneToTwoMsTotalQualified',false, ...
    'productionIntegrationComplete',false);
end
