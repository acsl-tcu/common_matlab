function R=TEST_TRIGGER_V7_1_AUDIT_CONTRACT()
% Fail if original-trajectory projection cannot satisfy strict nominal L.
p=fullfile(fileparts(mfilename('fullpath')),'BASELINE_TRACES', ...
    'PURE_TRIGGER_V6_CAUSAL_AUDIT_20261113_013957.mat');
S=load(p,'R');c=S.R.original6.results;
rows=struct('caseName',{},'rawLengthResidual_m',{}, ...
    'projectionCorrection_m',{},'projectedLengthResidual_m',{});
for k=1:numel(c)
    tr=c(k).nominalTrace;
    [~,m]=wp_v7_nominal_baseline_taut_projection( ...
        tr.pLoad,tr.pDrone,tr.pT,c(k).modelCableLength);
    assert(m.maxProjectedTautResidual_m < 128*eps(max(1,c(k).modelCableLength)), ...
        'V7:NominalTautProjection','Projection did not satisfy strict L');
    assert(abs(m.maxCorrection_m-m.maxOriginalTautResidual_m) < ...
        128*eps(max(1,c(k).modelCableLength)), ...
        'V7:NominalTautProjection','Projection unexpectedly changed lateral geometry');
    rows(end+1)=struct('caseName',char(c(k).caseName), ...
        'rawLengthResidual_m',m.maxOriginalTautResidual_m, ...
        'projectionCorrection_m',m.maxCorrection_m, ...
        'projectedLengthResidual_m',m.maxProjectedTautResidual_m); %#ok<AGROW>
end
R=struct('status','PASS_NUMERIC_NOMINAL_PROJECTION_ONLY', ...
    'results',rows,'physicalBoundCertified',false);
end
