function A=CHECK_TRIGGER_SIM_REFINED_TRUTH()
% Source-connected mathematical regression for real hold-time propagation.
% This does not claim that MATLAB ode15s (nor hardware) is rigorously
% contained by the ideal 24-state vector field in finite precision.
A=struct('status','FAIL_SIM_REFINED_TRUTH_AUDIT', ...
    'reason','','cases',0,'failures',0, ...
    'time_endpoint_cases',0,'rejected_cases',0, ...
    'refined_hold_attempted',false,'refined_hold_pass',false, ...
    'model_class_physical_dt_pinned',false, ...
    'cumulative_clock_not_physical_dt',false, ...
    'latch_stability_pass',false,'safe_to_commit',false);
try
    % Regression: the Picard terminal state must use [h_lower,h_upper],
    % whereas the all-time fixed-point tube uses [0,h_upper].
    x=zeros(24,1);
    x(3)=2; x(7)=1; x(8)=-1; x(16)=1; x(17)=-1;
    x(13:15)=[0;0;0]; x(19:21)=[0;0;-1];
    p=zeros(21,1);
    p(1)=1;p(6:8)=[0.05;0.05;0.08];p(9)=9.80665;
    p(20)=0.5;p(21)=2;
    u=[14.709975;0;0;0];
    % The distinct lower/upper clock values make the old error visible
    % without relying on the tiny size of a one-ULP difference.
    D=struct('x0_lower',x,'x0_upper',x, ...
        'tube_lower',x-0.01,'tube_upper',x+0.01, ...
        'u_lower',u,'u_upper',u, ...
        'param_lower',p,'param_upper',p, ...
        'h_s',1e-6,'h_lower_s',0.75e-6);
    Q=TRIGGER_ORIGINAL_PLANT_PICARD_STEP(D);
    assert(isstruct(Q.rhs) && isfield(Q.rhs,'outward_elementary_operations') && ...
        Q.rhs.outward_elementary_operations && ...
        all(isfinite([Q.endpoint_lower;Q.endpoint_upper])), ...
        'CHECK_TRIGGER_SIM_REFINED_TRUTH:EndpointFixture', ...
        'Original 24-state interval RHS cannot produce an endpoint fixture: %s',Q.reason);
    for j=1:24
        f=TRIGGER_OUTWARD_INTERVAL(Q.rhs.rhs_lower(j),Q.rhs.rhs_upper(j));
        initial=TRIGGER_OUTWARD_INTERVAL(x(j),x(j));
        endpoint=initial + TRIGGER_OUTWARD_INTERVAL( ...
            D.h_lower_s,D.h_s).*f;
        assert(Q.endpoint_lower(j)<=endpoint.lo && ...
            Q.endpoint_upper(j)>=endpoint.hi, ...
            'CHECK_TRIGGER_SIM_REFINED_TRUTH:WrongEndpointTime', ...
            'Component %d omitted one end of the elapsed-time interval.',j);
        A.cases=A.cases+1;
        A.time_endpoint_cases=A.time_endpoint_cases+1;
    end
    % Source-pinned physical integration span is the actual MODEL_CLASS dt;
    % accumulated runner timestamps can differ by many binary64 ulps.
    scope=TRIGGER_SIM_RUNNER_ORDER_PROOF();
    assert(scope.physical_hold_duration_from_solver_proven, ...
        'CHECK_TRIGGER_SIM_REFINED_TRUTH:SolverTimeNotPinned', ...
        'MODEL_CLASS physical hold source verification failed: %s',scope.reason);
    A.model_class_physical_dt_pinned=true;A.cases=A.cases+1;
    dt=0.025;t=0;mismatch=false;
    for it=1:20
        tnew=t+dt;
        mismatch=mismatch || (tnew-t ~= dt);
        t=tnew;
    end
    assert(mismatch,'CHECK_TRIGGER_SIM_REFINED_TRUTH:ClockFixture');
    A.cumulative_clock_not_physical_dt=true;A.cases=A.cases+1;
    % Both signs must occur in the actual original-plant RHS fixture;
    % otherwise the test could pass without exercising the old mistake.
    assert(Q.rhs.rhs_lower(1)>0 && Q.rhs.rhs_upper(2)<0, ...
        'CHECK_TRIGGER_SIM_REFINED_TRUTH:NontrivialSigns', ...
        'Need both strictly signed true physical derivative intervals.');
    A.cases=A.cases+1;
    % Even when [t_left,t_right] differs from dt, the source-verified
    % MODEL_CLASS solver hold duration must be used by every proof slab.
    tick_t0=0.05;tick_t1=tick_t0+dt;
    assert(tick_t1-tick_t0~=dt, ...
        'CHECK_TRIGGER_SIM_REFINED_TRUTH:NontrivialSimClock');
    physical=TRIGGER_ORIGINAL_HELD_SUBSTEP_CHAIN(struct( ...
        't_left_s',tick_t0,'t_right_s',tick_t1, ...
        'verified_hold_duration_s',dt, ...
        'x0_lower',x,'x0_upper',x, ...
        'u_lower',u,'u_upper',u, ...
        'param_lower',p,'param_upper',p));
    assert(strcmp(physical.duration_source, ...
        'ORIGINAL_MODEL_CLASS_SOLVER_HOLD_DT') && ...
        physical.physical_hold_duration_s==dt && ...
        ~physical.safe_to_commit, ...
        'CHECK_TRIGGER_SIM_REFINED_TRUTH:WrongPhysicalDuration');
    A.cases=A.cases+1;
    % A single invalid interval cannot be accepted by refinement.
    bad=TRIGGER_ORIGINAL_HELD_SUBSTEP_CHAIN(struct( ...
        't_left_s',0,'t_right_s',0.025, ...
        'x0_lower',x,'x0_upper',x, ...
        'u_lower',zeros(3,1),'u_upper',zeros(3,1), ...
        'param_lower',p,'param_upper',p));
    assert(~bad.conditional_strict_inclusion && ~bad.safe_to_commit, ...
        'CHECK_TRIGGER_SIM_REFINED_TRUTH:InvalidInputAccepted');
    A.cases=A.cases+1;A.rejected_cases=A.rejected_cases+1;
    % A valid physical fixture uses exactly the SAME hold actuator input
    % on every candidate proof slab. This may conservatively fail Picard
    % or tension, but it must NEVER certify an invalid set or use truth.
    good=TRIGGER_ORIGINAL_HELD_SUBSTEP_CHAIN(struct( ...
        't_left_s',0,'t_right_s',1e-6, ...
        'x0_lower',x,'x0_upper',x, ...
        'u_lower',u,'u_upper',u, ...
        'param_lower',p,'param_upper',p));
    A.refined_hold_attempted=true;
    A.refined_hold_pass=good.conditional_strict_inclusion;
    if A.refined_hold_pass
        assert(good.substeps>=1 && ...
            isequal(size(good.endpoint_lower),[24 1]) && ...
            all(good.endpoint_lower<=good.endpoint_upper) && ...
            all(good.tube_lower<=good.tube_upper) && ...
            isfinite(good.minimum_tension_lower_N) && ...
            good.minimum_tension_lower_N>0 && ~good.safe_to_commit, ...
            'CHECK_TRIGGER_SIM_REFINED_TRUTH:RefinementInvalid');
    else
        assert(startsWith(good.status,'UNKNOWN_') && ~good.safe_to_commit, ...
            'CHECK_TRIGGER_SIM_REFINED_TRUTH:UnknownPromotedToSafe');
    end
    A.cases=A.cases+1;
    % A failed provenance check is latched with its ORIGINAL reason, even
    % if invoked thousands of times. No re-seeding with a future EKF value.
    L=TRIGGER_SIM_TRUE_SET_CONTINUATION();
    e=L.observe(NaN,struct());
    assert(e.failure_latched && ...
        contains(e.first_failure_reason, ...
            'TRIGGER_SIM_TRUE_SET_CONTINUATION:Time'), ...
        'CHECK_TRIGGER_SIM_REFINED_TRUTH:FirstFailure');
    first_reason=e.first_failure_reason;
    e=L.observe(0,struct());
    assert(e.failure_latched && ...
        strcmp(e.first_failure_reason,first_reason) && ...
        strcmp(e.first_failure_reason,e.reason) && ...
        ~e.conditional_true_set_ready && ~e.safe_to_commit, ...
        'CHECK_TRIGGER_SIM_REFINED_TRUTH:LatchedReasonChanged');
    A.latch_stability_pass=true;A.cases=A.cases+1;
    A.status='PASS_TIME_ENDPOINT_AND_REFINED_HOLD_FAILCLOSED__NOT_PHYSICAL_PROOF';
    A.reason=['24 original endpoint interval components, signed RHS, ' ...
        'invalid physical input refusal, adaptive full-hold proof path ' ...
        'and unchanged initial failure evidence checked.'];
catch ME
    A.failures=1;
    A.reason=[ME.identifier ' | ' ME.message];
end
try
    save('TRIGGER_SIM_REFINED_TRUTH_RESULT.mat','A');
    fid=fopen('TRIGGER_SIM_REFINED_TRUTH_RESULT.txt','w');
    if fid>0
        fprintf(fid,'%s\ncases=%d failures=%d endpoints=%d refined_attempted=%d refined_pass=%d\n%s\n', ...
            A.status,A.cases,A.failures,A.time_endpoint_cases, ...
            A.refined_hold_attempted,A.refined_hold_pass,A.reason);
        fclose(fid);
    end
catch
end
end
