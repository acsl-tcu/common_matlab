function R=CHECK_TRAJECTORY_C9_CERTIFICATE_HULL_CUTS()
% Development-only test of interval hull cuts and paired WHOLE C9 pipeline.
% Never interprets sampled points or a local QP as a flight certificate.
root=fileparts(mfilename('fullpath'));
R=struct('status','FAIL_CERTIFICATE_HULL_CUTS','stage','START', ...
    'error_identifier','','error_message','','error_stack',{{}}, ...
    'interval_identity_cases',0,'interval_max_scaled_error',NaN, ...
    'affine_cut_count',0,'affine_max_scaled_error',0, ...
    'scene_names',{{'sphere','sphere_rotated_ellipsoid','box_cylinder'}}, ...
    'status_on',{{}},'status_off',{{}}, ...
    'proof_calls_on',NaN(1,3),'proof_calls_off',NaN(1,3), ...
        'proof_calls_adaptive',NaN(1,3), ...
        'status_adaptive',{{}}, ...
        'adaptive_invocations',NaN(1,3), ...
        'adaptive_skipped_existing_planes',NaN(1,3), ...
        'adaptive_skipped_no_diagnostic_id',NaN(1,3), ...
        'adaptive_skipped_not_payload',NaN(1,3), ...
        'body_diagnostic_valid',true, ...
        'adaptive_target_ids',{{}}, ...
        'default_policy_equivalence_pass',false, ...
        'optional_taut_embedding_default_off',false, ...
    'hull_cuts_on',NaN(1,3), ...
    'whole_median_ms_on',NaN(1,3), ...
    'whole_median_ms_off',NaN(1,3), ...
        'whole_median_ms_adaptive',NaN(1,3), ...
        'whole_p95_ms_adaptive',NaN(1,3), ...
        'whole_max_ms_adaptive',NaN(1,3), ...
        'proof_median_ms_adaptive',NaN(1,3), ...
        'qp_median_ms_adaptive',NaN(1,3), ...
    'whole_p95_ms_on',NaN(1,3), ...
    'whole_p95_ms_off',NaN(1,3), ...
    'whole_max_ms_on',NaN(1,3), ...
    'whole_max_ms_off',NaN(1,3), ...
    'proof_median_ms_on',NaN(1,3), ...
    'proof_median_ms_off',NaN(1,3), ...
    'qp_median_ms_on',NaN(1,3), ...
    'qp_median_ms_off',NaN(1,3), ...
    'repetitions',6,'no_unsafe_commit',false, ...
        'baseline_nominal_pass',false, ...
        'lazy_case_names',{{'sphere','sphere_rotated_ellipsoid','box_cylinder'}}, ...
        'lazy_status_on',{{}},'lazy_status_off',{{}}, ...
        'lazy_proof_calls_on',NaN(1,3), ...
        'lazy_proof_calls_off',NaN(1,3), ...
        'lazy_initial_proof_deferred',false(1,3), ...
        'lazy_fallback_used',false(1,3), ...
        'lazy_same_certification_result',false(1,3), ...
        'lazy_median_ms_on',NaN(1,3), ...
        'lazy_median_ms_off',NaN(1,3), ...
        'lazy_p95_ms_on',NaN(1,3), ...
        'lazy_p95_ms_off',NaN(1,3), ...
        'lazy_total_proof_median_ms_on',NaN(1,3), ...
        'lazy_total_proof_median_ms_off',NaN(1,3), ...
        'lazy_repetitions',5, ...
        'hlc_closed_loop_source_paths',{{}}, ...
        'hlc_closed_loop_source_status','NOT_COLLECTED', ...
    'zip_path',fullfile(root,'TRAJECTORY_C9_CERTIFICATE_HULL_RESULT_FOR_CHATGPT.zip'));
try
    R.stage='PATH';
    addpath(fullfile(root,'controller'),'-begin');
    addpath(fullfile(root,'model'),'-begin');
    addpath(fullfile(root,'reference','REPLANNING_SYSTEM','TRAJECTORY_GENERATION'), ...
        fullfile(root,'reference','REPLANNING_SYSTEM','OBSTACLE_INFORMATION'),'-begin');
    assert(isfile(fullfile(root,'run_flight_headless.m')), ...
        'CHECK_C9_HULL:Root','Run from common_matlab root.');
    oldrng=rng; restore_rng=onCleanup(@()rng(oldrng)); %#ok<NASGU>
    rng(81711,'twister');
    R.stage='BERNSTEIN_SUBINTERVAL_EXACT_IDENTITY';
    err=0;
    for k=1:250
        P=randn(3,24);
        u0=rand*0.85;u1=u0+(1-u0)*(0.15+0.85*rand);
        [Q,C]=TRAJECTORY_C9_BERNSTEIN_SUBINTERVAL_CONTROLS(P,u0,u1);
        err=max(err,max(abs(Q(:)-reshape(P*C,[],1)))/ ...
            max(1,max(abs(Q(:)))));
        err=max(err,max(abs(sum(C,1)-1)));
        for z=[0,0.13,0.5,0.83,1]
            direct=P*local_bernstein_basis(23,u0+(u1-u0)*z);
            restricted=Q*local_bernstein_basis(23,z);
            err=max(err,max(abs(direct-restricted))/max(1,max(abs(direct))));
        end
        R.interval_identity_cases=R.interval_identity_cases+1;
    end
    R.interval_max_scaled_error=err;
    assert(err<1e-11,'CHECK_C9_HULL:Interval', ...
        'Restricted polynomial differs from original on a subinterval.');
    R.stage='AFFINE_QP_CUT_IDENTITY';
    P=repmat([0;0;3],1,24);
    piece=struct('control_points_m',P,'t0_s',8,'duration_s',10);
    shape=OBSTACLE_INFORMATION.define(21,'sphere',[0.2 0 3],0.2);
    shapes=TRAJECTORY_OBSTACLE_SUPPORT.prepare(shape);
    U=diag([1.2,2.3,3.1,4.1]);
    [A0,b0,D]=TRAJECTORY_C9_CERTIFICATE_HULL_CUTS( ...
        piece,shapes,0.1,1e-5,U,[12 14],1e-10);
    assert(numel(b0)>0&&D.plane_count==numel(b0), ...
        'CHECK_C9_HULL:NotActivated','Expected an active hull cut.');
    R.affine_cut_count=numel(b0);
    df=0.001*randn(3,4);
    x=reshape(df*U.',12,1);
    shifted=P;shifted(:,11:14)=shifted(:,11:14)+df;
    [Q,~]=TRAJECTORY_C9_BERNSTEIN_SUBINTERVAL_CONTROLS( ...
        shifted,0.4,0.6);
    for i=1:numel(b0)
        n=D.cut_normals_world(:,i);
        idx=D.control_indices(i);
        new_deficit=TRAJECTORY_OBSTACLE_SUPPORT.value(shapes,n)+ ...
            0.1+1e-5-n.'*Q(:,idx);
        R.affine_max_scaled_error=max([0,R.affine_max_scaled_error, ...
            abs(new_deficit-(b0(i)-A0(:,i).'*x))]);
    end
    if isnan(R.affine_max_scaled_error)
        error('CHECK_C9_HULL:Affine','Uninitialized affine error.');
    end
    assert(R.affine_max_scaled_error<1e-10, ...
        'CHECK_C9_HULL:Affine','C9-QP Bernstein hull cut is not affine.');
    R.stage='READ_REAL_HLC_AND_MODEL_FIXTURE';
    [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    Psys=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    Psys.set("loadmass",0.14); % test fixture ONLY; never Flight hardcode
    d=double(Psys.get(["mass","jx","jy","jz", ...
        "gravity","cableL","loadmass"]));
    d=d(:);lo=lo(:);hi=hi(:);
    assert(numel(d)==7&&all(isfinite(d))&&all(d>0)&& ...
        numel(lo)==4&&numel(hi)==4, ...
        'CHECK_C9_HULL:Authority','Could not read actual HLC and model.');
    auth=struct('uav_mass_kg',d(1),'payload_mass_kg',d(7), ...
        'cable_length_m',d(6),'uav_inertia_kgm2',d(2:4), ...
        'gravity_world_mps2',[0;0;-d(5)], ...
        'thrust_limits_N',[lo(1),hi(1)], ...
        'torque_limits_Nm',[lo(2:4),hi(2:4)], ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0);
    gopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'numerical_guard_m',0,'robust_tube_enabled',false, ...
        'trajectory_phase','f');
    fopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'force_guard_N',0);
    sopt=struct('probe_count',13,'max_outer_iterations',4, ...
        'max_projection_sweeps',100, ...
        'projection_tolerance_m',1e-8,'min_separation_m',1e-5);
    hopt=struct('max_subdivision_depth',8,'max_node_count',511, ...
        'horizontal_velocity_guard_mps',0,'w_guard_mps2',0, ...
        'payload_jet_tolerance',1e-7*ones(3,10), ...
        'uav_jet_tolerance',1e-7*ones(3,8), ...
        'yaw_jet_tolerance',1e-7*ones(1,7));
    topt=struct('max_subdivision_depth',8,'max_node_count',511, ...
        'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
        'torque_guard_Nm',zeros(3,1), ...
        'enable_fast_norm_sufficient_bound',true);
    start=zeros(3,10);finish=zeros(3,10);
    start(:,1)=[-2;0;3];finish(:,1)=[2;0;3];
    start(1,2)=0.4;finish(1,2)=0.4;
    base=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,10,start,finish, ...
        repmat([0;0;3],1,4));
    req=struct('t0_s',8,'duration_s',10,'flight_interval_s',[8 30], ...
        'start_jets',start,'end_jets',finish, ...
        'nominal_free',base.control_points_m(:,11:14), ...
        'observed',struct([]),'radii', ...
        struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1), ...
        'authority',auth,'geometry_options',gopt,'force_options',fopt, ...
        'search_options',sopt,'heading_options',hopt, ...
        'nominal_torque_options',topt);
    sphere=OBSTACLE_INFORMATION.define(21,'sphere',[0 0.1 3],0.2);
    ang=0.34;Rz=[cos(ang) -sin(ang) 0;sin(ang) cos(ang) 0;0 0 1];
    ellipsoid=OBSTACLE_INFORMATION.define(33,'ellipsoid', ...
        [0.6 -0.16 3],[0.32 0.19 0.4],'rotation',Rz);
    box=OBSTACLE_INFORMATION.define(34,'box',[0 0.15 3],[0.35 0.3 0.7], ...
        'rotation',Rz);
    cylinder=OBSTACLE_INFORMATION.define(35,'cylinder', ...
        [0.65 -0.15 3],[0.27 0.5],'rotation',Rz);
    scenes={sphere,[sphere ellipsoid],[box cylinder]};
    R.stage='PAIRED_COMPLETE_C9_NOMINAL_PIPELINE';
    R.status_on=cell(1,3);R.status_off=cell(1,3);
    R.status_adaptive=cell(1,3);
    R.adaptive_target_ids=cell(1,3);
    R.no_unsafe_commit=true;
    for scene=1:3
        req.observed=scenes{scene};
        on=req;on.search_options.enable_payload_hull_witness_planes=true;
        off=req;off.search_options.enable_payload_hull_witness_planes=false;
        adaptive=req;
        adaptive.search_options.payload_hull_witness_policy='adaptive';
        % Read all THREE methods once before timed repetitions.
        Y=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(on);
        Z=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(off);
        W=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(adaptive);
        R.status_on{scene}=Y.status;R.status_off{scene}=Z.status;
        R.status_adaptive{scene}=W.status;
        R.proof_calls_on(scene)=Y.proof_calls;
        R.proof_calls_off(scene)=Z.proof_calls;
        R.proof_calls_adaptive(scene)=W.proof_calls;
        R.hull_cuts_on(scene)=Y.search_result.hull_witness_plane_count;
        R.adaptive_invocations(scene)=W.search_result.hull_witness_invocations;
        R.adaptive_skipped_existing_planes(scene)= ...
            W.search_result.hull_witness_skipped_existing_planes;
        R.adaptive_skipped_no_diagnostic_id(scene)= ...
            W.search_result.hull_witness_skipped_no_diagnostic_id;
        R.adaptive_target_ids{scene}=W.search_result.hull_witness_target_ids;
        R.adaptive_skipped_not_payload(scene)= ...
            W.search_result.hull_witness_skipped_not_payload;
        for candidate={Y,Z,W}
            pre=candidate{1}.search_result.initial_certificate;
            R.body_diagnostic_valid=R.body_diagnostic_valid&& ...
                isfield(pre,'unresolved_body_indices')&& ...
                all(ismember(pre.unresolved_body_indices,[1 2 3]));
        end
        assert(R.body_diagnostic_valid, ...
            'CHECK_C9_HULL:BodyDiagnostic','Proof body IDs must be valid.');
        R.no_unsafe_commit=R.no_unsafe_commit&& ...
            ~Y.safe_to_commit&&~Z.safe_to_commit&&~W.safe_to_commit;
        timing_on=zeros(1,R.repetitions);timing_off=timing_on;
        timing_adaptive=timing_on;
        proof_on=timing_on;proof_off=timing_on;
        proof_adaptive=timing_on;
        qp_on=timing_on;qp_off=timing_on;
        qp_adaptive=timing_on;
        for trial=1:R.repetitions
            % Rotate execution order so JIT/cache advantage is not reserved
            % for one policy; always measure COMPLETE integrated pipeline.
            if mod(trial,3)==1
                Y=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(on);
                Z=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(off);
                W=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(adaptive);
            elseif mod(trial,3)==2
                Z=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(off);
                W=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(adaptive);
                Y=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(on);
            else
                W=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(adaptive);
                Y=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(on);
                Z=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(off);
            end
            timing_on(trial)=Y.total_elapsed_ms;
            timing_off(trial)=Z.total_elapsed_ms;
            timing_adaptive(trial)=W.total_elapsed_ms;
            proof_on(trial)=Y.joint_geometry_force_proof_ms;
            proof_off(trial)=Z.joint_geometry_force_proof_ms;
            proof_adaptive(trial)=W.joint_geometry_force_proof_ms;
            qp_on(trial)=Y.joint_QP_ms;
            qp_off(trial)=Z.joint_QP_ms;
            qp_adaptive(trial)=W.joint_QP_ms;
            R.no_unsafe_commit=R.no_unsafe_commit&& ...
                ~Y.safe_to_commit&&~Z.safe_to_commit&&~W.safe_to_commit;
            assert(strcmp(R.status_on{scene},Y.status)&& ...
                strcmp(R.status_off{scene},Z.status)&& ...
                strcmp(R.status_adaptive{scene},W.status), ...
                'CHECK_C9_HULL:Unstable','Repeated per-method status changed.');
        end
        R.whole_median_ms_on(scene)=median(timing_on);
        R.whole_median_ms_off(scene)=median(timing_off);
        sorted=sort(timing_on);R.whole_p95_ms_on(scene)= ...
            sorted(ceil(.95*numel(sorted)));
        sorted=sort(timing_off);R.whole_p95_ms_off(scene)= ...
            sorted(ceil(.95*numel(sorted)));
        R.whole_max_ms_on(scene)=max(timing_on);
        R.whole_max_ms_off(scene)=max(timing_off);
        R.proof_median_ms_on(scene)=median(proof_on);
        R.proof_median_ms_off(scene)=median(proof_off);
        R.qp_median_ms_on(scene)=median(qp_on);
        R.qp_median_ms_off(scene)=median(qp_off);
        R.whole_median_ms_adaptive(scene)=median(timing_adaptive);
        sorted=sort(timing_adaptive);
        R.whole_p95_ms_adaptive(scene)=sorted(ceil(.95*numel(sorted)));
        R.whole_max_ms_adaptive(scene)=max(timing_adaptive);
        R.proof_median_ms_adaptive(scene)=median(proof_adaptive);
        R.qp_median_ms_adaptive(scene)=median(qp_adaptive);
    end
    R.stage='DEFAULT_POLICY_EQUALS_EXPLICIT_OFF';
    req.observed=scenes{2};
    if isfield(req.search_options,'enable_payload_hull_witness_planes')
        req.search_options=rmfield(req.search_options, ...
            'enable_payload_hull_witness_planes');
    end
    if isfield(req.search_options,'payload_hull_witness_policy')
        req.search_options=rmfield(req.search_options, ...
            'payload_hull_witness_policy');
    end
    default_result=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(req);
    req.search_options.payload_hull_witness_policy='off';
    explicit_result=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(req);
    R.optional_taut_embedding_default_off= ...
        ~default_result.search_result.taut_qp_embedding_enabled;
    R.default_policy_equivalence_pass=strcmp( ...
        default_result.status,explicit_result.status)&& ...
        isequal(default_result.search_result.hull_witness_plane_count, ...
                explicit_result.search_result.hull_witness_plane_count)&& ...
        strcmp(default_result.search_result.hull_witness_policy,'off');
    assert(R.default_policy_equivalence_pass && ...
        R.optional_taut_embedding_default_off && ...
        ~default_result.safe_to_commit && ~explicit_result.safe_to_commit, ...
        'CHECK_C9_HULL:DefaultPolicy','Default and explicit OFF differ.');
    R.stage='BASELINE_NO_OBSTACLES';
    req.observed=struct([]);
    req.search_options.enable_payload_hull_witness_planes=true;
    clean=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(req);
    R.baseline_nominal_pass=clean.nominal_model_complete&&~clean.safe_to_commit;
    assert(R.no_unsafe_commit&&R.baseline_nominal_pass&& ...
        R.body_diagnostic_valid, ...
        'CHECK_C9_HULL:Safety','No-obstacle nominal baseline or safety gate failed.');
    % Production-critical paired measurement: defer the INITIAL expensive
    % oracle only when the original polynomial has violated sampled joint
    % planes. This is LAZY PROOF SCHEDULING, NOT safety certification.
    % The original is still certified as a bounded fallback when required.
    R.stage='PAIRED_LAZY_INITIAL_PROOF_SCHEDULING';
    R.lazy_status_on=cell(1,3);R.lazy_status_off=cell(1,3);
    for scene=1:3
        base_req=req;
        base_req.observed=scenes{scene};
        base_req.search_options.payload_hull_witness_policy='off';
        lazy=base_req;lazy.search_options.lazy_initial_proof_on_violated_plane=true;
        eager=base_req;eager.search_options.lazy_initial_proof_on_violated_plane=false;
        one=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(lazy);
        two=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(eager);
        R.lazy_status_on{scene}=one.status;
        R.lazy_status_off{scene}=two.status;
        R.lazy_proof_calls_on(scene)=one.proof_calls;
        R.lazy_proof_calls_off(scene)=two.proof_calls;
        R.lazy_initial_proof_deferred(scene)= ...
            one.search_result.initial_proof_deferred;
        R.lazy_fallback_used(scene)= ...
            one.search_result.initial_proof_fallback_executed;
        R.lazy_same_certification_result(scene)= ...
            one.nominal_model_complete==two.nominal_model_complete;
        % Never treat either a probe or a QP result as execution safety.
        assert(~one.safe_to_commit&&~two.safe_to_commit&& ...
            ~one.actual_HLC_tracking_proven&& ...
            ~two.actual_HLC_tracking_proven, ...
            'CHECK_C9_HULL:UnsafeCommit','A noncertified HLC path was accepted.');
        assert(one.proof_calls<=base_req.search_options.max_outer_iterations+1, ...
            'CHECK_C9_HULL:Budget','Lazy branch exceeded the original proof-call cap.');
        assert(~one.search_result.candidate_available || ...
            one.search_result.final_certificate.certified, ...
            'CHECK_C9_HULL:UnprovedCandidate', ...
            'Candidate returned without independent all-time certificate.');
        t1=zeros(1,R.lazy_repetitions);t2=t1;p1=t1;p2=t1;
        for trial=1:R.lazy_repetitions
            if mod(trial,2)==1
                one=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(lazy);
                two=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(eager);
            else
                two=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(eager);
                one=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(lazy);
            end
            t1(trial)=one.total_elapsed_ms;t2(trial)=two.total_elapsed_ms;
            p1(trial)=one.joint_geometry_force_proof_ms;
            p2(trial)=two.joint_geometry_force_proof_ms;
            assert(strcmp(one.status,R.lazy_status_on{scene}) && ...
                strcmp(two.status,R.lazy_status_off{scene}), ...
                'CHECK_C9_HULL:LazyUnstable','Lazy result changed across repeats.');
        end
        R.lazy_median_ms_on(scene)=median(t1);
        R.lazy_median_ms_off(scene)=median(t2);
        z=sort(t1);R.lazy_p95_ms_on(scene)=z(ceil(.95*numel(z)));
        z=sort(t2);R.lazy_p95_ms_off(scene)=z(ceil(.95*numel(z)));
        R.lazy_total_proof_median_ms_on(scene)=median(p1);
        R.lazy_total_proof_median_ms_off(scene)=median(p2);
    end
    % DEVELOPMENT ONLY: capture the exact four source files required to
    % derive the *existing* HLC/EKF/plant closed-loop equations next.
    % No motor allocation/input-transform source is used or requested.
    % This never runs in a Flight event or changes an original source.
    names={'HLC_SUSPENDED_LOAD','Controller_HL_Suspended_Load', ...
        'Model_Suspended_Load','Estimator_EKF_SuspendedLoad'};
    paths=cell(1,0);
    for source_index=1:numel(names)
        file=which(names{source_index});
        if ~isempty(file)&&isfile(file) && ...
                strncmpi(file,[root filesep],numel(root)+1)
            paths{end+1}=file(numel(root)+2:end); %#ok<AGROW>
        end
    end
    R.hlc_closed_loop_source_paths=paths;
    R.hlc_closed_loop_source_status=sprintf('%d_OF_4_SOURCES_AVAILABLE', ...
        numel(paths));
    R.stage='DONE';
    R.status='PASS_PROOF_ORDER_BENCHMARK_AND_DEFAULT_UNUSED_CUTS_OFF__HLC_UNCERTIFIED';
catch ME
    R.error_identifier=ME.identifier;R.error_message=ME.message;
    R.error_stack=arrayfun(@(f)sprintf('%s:%d',f.name,f.line), ...
        ME.stack,'UniformOutput',false);
end
name='TRAJECTORY_C9_CERTIFICATE_HULL_RESULT';
save(fullfile(root,[name '.mat']),'R');
fid=fopen(fullfile(root,[name '.txt']),'w');
if fid>=0
    fprintf(fid,'status=%s\nstage=%s\nerror=%s | %s\n', ...
        R.status,R.stage,R.error_identifier,R.error_message);
    for k=1:numel(R.error_stack)
        fprintf(fid,'stack_%d=%s\n',k,R.error_stack{k});
    end
    fprintf(fid,'interval_tests=%d max_error=%.12g\n', ...
        R.interval_identity_cases,R.interval_max_scaled_error);
    fprintf(fid,'affine_cuts=%d max_error=%.12g\n', ...
        R.affine_cut_count,R.affine_max_scaled_error);
    for k=1:3
