function b=local_bernstein_basis(n,u)
% Used only for independent mathematical identity regression.
b=zeros(n+1,1);
if u==0,b(1)=1;return;end
if u==1,b(end)=1;return;end
b(1)=(1-u)^n;
for i=1:n
    b(i+1)=b(i)*(n-i+1)/i*u/(1-u);
end
end
