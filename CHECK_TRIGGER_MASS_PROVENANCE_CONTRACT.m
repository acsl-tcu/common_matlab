function A=CHECK_TRIGGER_MASS_PROVENANCE_CONTRACT()
% Disposable synthetic consistency tests; no real payload-mass theorem.
A=struct('status','NOT_RUN_MASS_CONTRACT','reason','', ...
    'point_sources_distinguished',false, ...
    'wrong_estimator_allowed_but_not_certified',false, ...
    'plant_outside_rejected',false,'variable_dt_accepted',false, ...
    'safe_to_commit',false);
try
    C=struct('time_grid_s',[13.7 13.724 13.752], ...
        'true_mass_lower_kg',[0.4 0.35], ...
        'true_mass_upper_kg',[0.6 0.68], ...
        'estimator_mass_kg',0.9, ...
        'hlc_parameter_mass_kg',0.95, ...
        'sim_plant_parameter_mass_kg',0.5);
    M=TRIGGER_MASS_PROVENANCE_CONTRACT(C);
    A.point_sources_distinguished=~M.estimator_matches_plant_mass && ...
        M.estimator_mass_kg~=M.hlc_mass_kg && ...
        M.hlc_mass_kg~=M.sim_plant_mass_kg;
    A.wrong_estimator_allowed_but_not_certified= ...
        M.conditional_current_snapshot_consistent && ...
        ~M.estimator_mass_in_current_true_interval && ...
        ~M.hlc_mass_in_current_true_interval && ...
        ~M.true_mass_evolution_proven && ~M.safe_to_commit;
    A.variable_dt_accepted=isequal(M.time_grid_s,C.time_grid_s);
    C.sim_plant_parameter_mass_kg=0.8;
    Z=TRIGGER_MASS_PROVENANCE_CONTRACT(C);
    A.plant_outside_rejected= ...
        ~Z.conditional_current_snapshot_consistent && ...
        ~Z.safe_to_commit && ...
        strcmp(Z.status,'UNKNOWN_CURRENT_SIM_PLANT_VS_DECLARED_TRUE_MASS');
    assert(A.point_sources_distinguished && ...
        A.wrong_estimator_allowed_but_not_certified && ...
        A.plant_outside_rejected && A.variable_dt_accepted, ...
        'CHECK_TRIGGER_MASS_PROVENANCE_CONTRACT:Failed', ...
        'The mass source distinction/physical interval semantics were lost.');
    A.status='PASS_SYNTHETIC_MASS_ROLE_SEPARATION__NOT_TRUE_MASS_PROOF';
catch ME
    A.reason=[ME.identifier ' | ' ME.message];
end
save('TRIGGER_MASS_PROVENANCE_RESULT.mat','A');
f=fopen('TRIGGER_MASS_PROVENANCE_RESULT.txt','w');
if f>=0
    fprintf(f,['status=%s\npoint_sources_distinguished=%d\n' ...
        'wrong_estimator_allowed_but_not_certified=%d\n' ...
        'plant_outside_rejected=%d\nvariable_dt_accepted=%d\nreason=%s\n'], ...
        A.status,A.point_sources_distinguished, ...
        A.wrong_estimator_allowed_but_not_certified, ...
        A.plant_outside_rejected,A.variable_dt_accepted,A.reason);
    fclose(f);
end
end
