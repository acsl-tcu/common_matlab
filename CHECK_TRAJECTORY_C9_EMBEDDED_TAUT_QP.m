function R=CHECK_TRAJECTORY_C9_EMBEDDED_TAUT_QP()
% One compact development-only CHECK: exact affine row algebra, rotation
% covariance, then SAME full integrated C9 pipeline with embedding ON/OFF.
% All numerical physics below are CHECK fixtures, NEVER production Flight
% defaults. Original HLC bounds still come directly from active source.
root=fileparts(mfilename('fullpath'));
module=fullfile(root,'reference','REPLANNING_SYSTEM','TRAJECTORY_GENERATION');
R=struct('status','FAIL_C9_TAUT_EMBEDDING','stage','INIT', ...
  'error_identifier','','error_message','', 'error_stack',{{}}, ...
  'affine_identity_pass',false,'rotation_covariance_pass',false, ...
  'noncertifying_skip_pass',false,'whole_time_cone_implication_pass',false, ...
  'algebra_max_abs_residual_mps2',Inf, ...
  'case_names',{{'safe_affine','collision_sphere','collision_sphere_ellipsoid'}}, ...
  'case_status_on',{{}},'case_status_off',{{}}, ...
  'case_nominal_pass_on',false(1,3),'case_nominal_pass_off',false(1,3), ...
  'case_embedded_rows',zeros(1,3),'case_QP_ms_on',NaN(1,3), ...
  'case_QP_ms_off',NaN(1,3),'case_proof_calls_on',NaN(1,3), ...
  'case_proof_calls_off',NaN(1,3), ...
  'case_median_ms_on',NaN(1,3),'case_median_ms_off',NaN(1,3), ...
  'case_p95_ms_on',NaN(1,3),'case_p95_ms_off',NaN(1,3), ...
  'case_max_ms_on',NaN(1,3),'case_max_ms_off',NaN(1,3), ...
  'sample_count',7,'safe_to_commit',false, ...
  'source_limits_directly_read',false, ...
  'HLC_closed_loop_proven',false, ...
  'output_zip',fullfile(root,'TRAJECTORY_C9_EMBEDDED_TAUT_QP_RESULT_FOR_CHATGPT.zip'));
try
    assert(isfolder(module),'C9_EMBED_CHECK:Path','Missing production module');
    addpath(module,fullfile(root,'reference','REPLANNING_SYSTEM', ...
      'OBSTACLE_INFORMATION'),fullfile(root,'controller'), ...
      fullfile(root,'model'),'-begin');
    R.stage='MATHEMATICAL_AFFINE_ROW_IDENTITY';
    T=2;P=zeros(3,24);v=[.5;0;0];g=[0;0;-9.80665];
    for j=1:24
        P(:,j)=[0;0;3]+v*(T*(j-1)/23);
    end
    testpiece=struct('control_points_m',P,'duration_s',T);
    a=struct('gravity_world_mps2',g,'payload_mass_kg',.14, ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0);
    U=chol([4 1 .3 .1;1 3 .1 0;.3 .1 2 .5;.1 0 .5 2],'upper');
    [C,b,S]=TRAJECTORY_C9_TAUT_BERNSTEIN_QP_ROWS(testpiece,a,U);
    assert(S.current_common_cone_valid&&size(C,2)==6&&numel(b)==6, ...
        'C9_EMBED_CHECK:SixRows','Expected six movable acceleration controls');
    k=23*22/T^2;
    maxerror=0;
    for trial=1:240
        dF=.001*reshape(sin((1:12)'*(trial/31)),3,4);
        x=reshape(dF*U.',12,1);
        next=P;next(:,11:14)=next(:,11:14)+dF;
        wnew=repmat(g,1,22)-k*diff(next,2,2);
        rhs=(S.normal.'*wnew(:,9:14)).'- ...
            S.required_acceleration_lower_bound_mps2;
        residual=max(abs(C.'*x-b-rhs));
        maxerror=max(maxerror,residual);
        assert(residual <= 1e-9*max(1,max(abs(rhs))), ...
            'C9_EMBED_CHECK:Affine','QP rows do not match exact C9 controls');
    end
    R.algebra_max_abs_residual_mps2=maxerror;
    R.affine_identity_pass=true;
    R.stage='ROTATION_COVARIANCE';
    theta=.41;phi=-.32;
    Q=[cos(theta) -sin(theta) 0;sin(theta) cos(theta) 0;0 0 1]* ...
        [cos(phi) 0 sin(phi);0 1 0;-sin(phi) 0 cos(phi)];
    rp=testpiece;rp.control_points_m=Q*P;
    ar=a;ar.gravity_world_mps2=Q*g;
    [Cr,br,Sr]=TRAJECTORY_C9_TAUT_BERNSTEIN_QP_ROWS(rp,ar,U);
    dx=.0001*reshape(cos((1:12)'),3,4);
    x=reshape(dx*U.',12,1);xr=reshape((Q*dx)*U.',12,1);
    R.rotation_covariance_pass=norm(Sr.normal-Q*S.normal)<1e-12 && ...
        norm(Cr.'*xr-br-(C.'*x-b))<1e-8;
    assert(R.rotation_covariance_pass,'C9_EMBED_CHECK:SO3', ...
        'SO(3) transformation must preserve constraints');
    a_invalid=a;a_invalid.gravity_world_mps2=[0;0;0];
    zero_piece=testpiece;zero_piece.control_points_m(:)=0;
    [Ce,be,Se]=TRAJECTORY_C9_TAUT_BERNSTEIN_QP_ROWS( ...
        zero_piece,a_invalid,U);
    R.noncertifying_skip_pass=isempty(Ce)&&isempty(be)&& ...
        ~Se.current_common_cone_valid;
    assert(R.noncertifying_skip_pass,'C9_EMBED_CHECK:Skip', ...
        'Ambiguous cone must not be certified or constrained arbitrarily');
    R.whole_time_cone_implication_pass= ...
        all(S.normal.'*(repmat(g,1,22)-k*diff(P,2,2)) > ...
            S.required_acceleration_lower_bound_mps2);
    assert(R.whole_time_cone_implication_pass, ...
        'C9_EMBED_CHECK:Hull','Expected strict whole-time convex-hull cone');
    R.stage='REAL_HLC_LIMITS_AND_LIVE_MODEL_FIXTURE';
    [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    assert(isequal(size(lo(:)),[4 1])&&isequal(size(hi(:)),[4 1])&& ...
        all(isfinite([lo(:);hi(:)]))&&all(lo(:)<hi(:)), ...
        'C9_EMBED_CHECK:HLC','Actual HLC source limits unavailable');
    R.source_limits_directly_read=true;
    p=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    p.set("loadmass",.14); % only a TEST fixture
    d=double(p.get(["mass","jx","jy","jz","gravity","cableL","loadmass"]));
    d=d(:);assert(numel(d)==7&&all(isfinite(d))&&all(d>0), ...
        'C9_EMBED_CHECK:Plant','Actual parameter fixture unavailable');
    auth=struct('uav_mass_kg',d(1),'uav_inertia_kgm2',d(2:4), ...
        'payload_mass_kg',d(7),'cable_length_m',d(6), ...
        'gravity_world_mps2',[0;0;-d(5)], ...
        'thrust_limits_N',[lo(1) hi(1)], ...
        'torque_limits_Nm',[lo(2:4) hi(2:4)], ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0);
    geom=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'numerical_guard_m',0,'robust_tube_enabled',false,'trajectory_phase','f');
    force=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'force_guard_N',0);
    search=struct('probe_count',13,'max_outer_iterations',4, ...
        'max_projection_sweeps',100, ...
        'projection_tolerance_m',1e-8,'min_separation_m',1e-5);
    heading=struct('max_subdivision_depth',8,'max_node_count',511, ...
        'horizontal_velocity_guard_mps',0,'w_guard_mps2',0, ...
        'payload_jet_tolerance',1e-7*ones(3,10), ...
        'uav_jet_tolerance',1e-7*ones(3,8), ...
        'yaw_jet_tolerance',1e-7*ones(1,7));
    torque=struct('max_subdivision_depth',8,'max_node_count',511, ...
        'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
        'torque_guard_Nm',zeros(3,1),'enable_fast_norm_sufficient_bound',true);
    s0=zeros(3,10);s1=s0;
    s0(:,1)=[0;0;3];s1(:,1)=[1;0;3];
    s0(1,2)=.5;s1(1,2)=.5;
    sf=repmat(s0(:,1),1,4)+s0(:,2)*((2/23)*(10:13));
    safe=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,2,s0,s1,sf);
    start=zeros(3,10);finish=start;
    start(:,1)=[-2;0;3];finish(:,1)=[2;0;3];
    start(1,2)=.4;finish(1,2)=.4;
    nominal=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,10, ...
        start,finish,repmat([0;0;3],1,4));
    req=struct('t0_s',8,'duration_s',10,'flight_interval_s',[8 30], ...
        'start_jets',start,'end_jets',finish, ...
        'nominal_free',nominal.control_points_m(:,11:14), ...
        'observed',struct([]), ...
        'radii',struct('uav_m',.1,'cable_m',.02,'payload_m',.1), ...
        'authority',auth,'geometry_options',geom, ...
        'force_options',force,'search_options',search, ...
        'heading_options',heading,'nominal_torque_options',torque);
    sphere=OBSTACLE_INFORMATION.define(21,'sphere',[0 .1 3],.2);
    angle=.4;Qz=[cos(angle) -sin(angle) 0;sin(angle) cos(angle) 0;0 0 1];
    ellipsoid=OBSTACLE_INFORMATION.define(33,'ellipsoid', ...
        [.6 -.16 3],[.32 .19 .4],'rotation',Qz);
    cases={struct([]),sphere,[sphere ellipsoid]};
    R.stage='MEASURE_COMPLETE_C9_PIPELINE_ON_OFF';
    for ci=1:numel(cases)
        case_req=req;
        if ci==1
            case_req.duration_s=2;
            case_req.start_jets=s0;case_req.end_jets=s1;
            case_req.nominal_free=safe.control_points_m(:,11:14);
        end
        case_req.observed=cases{ci};
        % Warm both choices before timing and interleave their execution.
        % This prevents compile/cache-first effects from being incorrectly
        % attributed to the embedding option. No warm-up in live Flight.
        for mode=0:1
            case_req.search_options.embed_taut_bernstein_halfspaces=logical(mode);
            TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(case_req);
        end
        timings=NaN(2,R.sample_count);
        last=cell(1,2);
        for trial=1:R.sample_count
            if mod(trial,2)==0,order=[1 0];else,order=[0 1];end
            for mode=order
                case_req.search_options.embed_taut_bernstein_halfspaces=logical(mode);
                out=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(case_req);
                timings(mode+1,trial)=out.total_elapsed_ms;
                last{mode+1}=out;
                assert(~out.safe_to_commit&&~out.actual_HLC_tracking_proven, ...
                    'C9_EMBED_CHECK:Commit','Nominal-only candidate must never COMMIT');
            end
        end
        for mode=0:1
            out=last{mode+1};elapsed=timings(mode+1,:);
            sorted=sort(elapsed);
            if mode
                R.case_status_on{ci}=out.status;
                R.case_nominal_pass_on(ci)=out.nominal_model_complete;
                R.case_median_ms_on(ci)=median(elapsed);
                R.case_p95_ms_on(ci)=sorted(ceil(.95*numel(sorted)));
                R.case_max_ms_on(ci)=max(elapsed);
                R.case_proof_calls_on(ci)=out.proof_calls;
                R.case_QP_ms_on(ci)=out.joint_QP_ms;
                if isstruct(out.search_result)&& ...
                        isfield(out.search_result,'taut_qp_embedded_rows')
                    R.case_embedded_rows(ci)=out.search_result.taut_qp_embedded_rows;
                end
            else
                R.case_status_off{ci}=out.status;
                R.case_nominal_pass_off(ci)=out.nominal_model_complete;
                R.case_median_ms_off(ci)=median(elapsed);
                R.case_p95_ms_off(ci)=sorted(ceil(.95*numel(sorted)));
                R.case_max_ms_off(ci)=max(elapsed);
                R.case_proof_calls_off(ci)=out.proof_calls;
                R.case_QP_ms_off(ci)=out.joint_QP_ms;
            end
        end
    end
    assert(R.case_nominal_pass_on(1)&&R.case_nominal_pass_off(1), ...
        'C9_EMBED_CHECK:SafeRegression', ...
        'An already certified nominal path must remain certified');
    R.status='PASS_EMBEDDED_TAUT_QP_ALGEBRA_AND_FULL_NOMINAL_AB_TEST__HLC_PENDING';
    R.stage='COMPLETE';
catch ME
    R.status='FAIL_C9_EMBEDDED_TAUT_QP';
    R.error_identifier=ME.identifier;
    R.error_message=ME.message;
    R.error_stack=arrayfun(@(s)sprintf('%s:%d',s.name,s.line), ...
        ME.stack,'UniformOutput',false);
end
base='TRAJECTORY_C9_EMBEDDED_TAUT_QP_RESULT';
save(fullfile(root,[base '.mat']),'R');
fid=fopen(fullfile(root,[base '.txt']),'w');
if fid>=0
 fprintf(fid,'status=%s\nstage=%s\nexception=%s | %s\n', ...
     R.status,R.stage,R.error_identifier,R.error_message);
 fprintf(fid,'affine=%d | rotation=%d | skip=%d | hull=%d | max_residual=%.9g\n', ...
     R.affine_identity_pass,R.rotation_covariance_pass, ...
     R.noncertifying_skip_pass,R.whole_time_cone_implication_pass, ...
     R.algebra_max_abs_residual_mps2);
 fprintf(fid,'actual_HLC_limits_read=%d | closed_loop_proven=%d | safe_to_commit=%d\n', ...
     R.source_limits_directly_read,R.HLC_closed_loop_proven,R.safe_to_commit);
 for ci=1:numel(R.case_names)
   if numel(R.case_status_on)>=ci && numel(R.case_status_off)>=ci
     fprintf(fid,['case=%s | on=%s | off=%s | rows=%.0f | ', ...
          'on_median=%.6f | off_median=%.6f | on_P95=%.6f | off_P95=%.6f | ', ...
          'on_proofs=%.0f | off_proofs=%.0f | on_QP=%.6f | off_QP=%.6f\n'], ...
          R.case_names{ci},R.case_status_on{ci},R.case_status_off{ci}, ...
          R.case_embedded_rows(ci), ...
          R.case_median_ms_on(ci),R.case_median_ms_off(ci), ...
          R.case_p95_ms_on(ci),R.case_p95_ms_off(ci), ...
          R.case_proof_calls_on(ci),R.case_proof_calls_off(ci), ...
          R.case_QP_ms_on(ci),R.case_QP_ms_off(ci));
   end
 end
 for j=1:numel(R.error_stack)
   fprintf(fid,'stack_%d=%s\n',j,R.error_stack{j});
 end
 fclose(fid);
end
try
    zip(R.output_zip,{[base '.mat'],[base '.txt']},root);
catch ME
    warning('C9_EMBED_CHECK:Export','%s',ME.message);
end
fprintf('[C9 EMBEDDED TAUT QP] %s | %s\n',R.status,R.output_zip);
end
