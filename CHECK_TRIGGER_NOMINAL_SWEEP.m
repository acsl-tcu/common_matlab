function R=CHECK_TRIGGER_NOMINAL_SWEEP()
%CHECK_TRIGGER_NOMINAL_SWEEP User-runnable exact-scope regression.
% Tests the nominal interpolant sweep ONLY, not true physics, EKF error,
% continuous ODE numerical error or deterministic Flight execution time.
root=fileparts(mfilename('fullpath'));
core=fullfile(root,'reference','REPLANNING_SYSTEM', ...
    'FUTURE_COLLISION_TRIGGER');
addpath(core);
assert(contains(fileread(fullfile(core,'FUTURE_COLLISION_TRIGGER.m')), ...
    'TRIGGER_NOMINAL_SWEPT_INTERVALS('), ...
    'CHECK_TRIGGER_NOMINAL_SWEEP:Wiring','Production core is not updated.');
T=[0 1];
U=[-1 1;0 0;0 0];L=U-[0 0;0 0;2 2];
a=make_sphere(41,[0;0;0],.1);
f=make_sphere(42,[4;0;0],.1);
R1=TRIGGER_NOMINAL_SWEPT_INTERVALS(U,L,T,a,.01,.01,.005,[],[]);
assert(R1.continuous_linear_interpolant_may_intersect && ...
    isequal(R1.new_obstacle_ids,41) && R1.new_ttc_s==0 && ...
    isequal(R1.new_time_bracket_s,[0 1]) && ...
    ~R1.real_plant_continuous_safety_proven, ...
    'CHECK_TRIGGER_NOMINAL_SWEEP:MissedBetweenSamples', ...
    'A 100%% between-samples crossing was not detected.');
R2=TRIGGER_NOMINAL_SWEPT_INTERVALS(U,L,T,f,.01,.01,.005,[],[]);
assert(~R2.continuous_linear_interpolant_may_intersect && ...
    isempty(R2.new_obstacle_ids), ...
    'CHECK_TRIGGER_NOMINAL_SWEEP:Far','Far obstacle produced a false candidate.');
R3=TRIGGER_NOMINAL_SWEPT_INTERVALS(U,L,T,[f a],.01,.01,.005,[],[]);
assert(isequal(R3.new_obstacle_ids,41), ...
    'CHECK_TRIGGER_NOMINAL_SWEEP:Order','Obstacle order matters.');
R4=TRIGGER_NOMINAL_SWEPT_INTERVALS(U,L,T,a,.01,.01,.005,41,[]);
assert(isempty(R4.new_obstacle_ids) && ...
    isequal(R4.first_obstacle_ids,41), ...
    'CHECK_TRIGGER_NOMINAL_SWEEP:Duplicate','Announced ID triggered again.');
R5=TRIGGER_NOMINAL_SWEPT_INTERVALS(U,L,T,a,.01,.01,.005,[],41);
assert(isempty(R5.new_obstacle_ids), ...
    'CHECK_TRIGGER_NOMINAL_SWEEP:Sampled','Confirmed sampled hit was not excluded.');
U2=[0 2;0 0;0 0];L2=U2-[0 0;0 0;2 2];
c=make_sphere(43,[1;0;-1],.05);
R6=TRIGGER_NOMINAL_SWEPT_INTERVALS(U2,L2,T,c,.01,.01,.01,[],[]);
assert(R6.continuous_linear_interpolant_may_intersect && ...
    isequal(R6.new_obstacle_ids,43) && ...
    strcmp(R6.new_parts{1},'CABLE'), ...
    'CHECK_TRIGGER_NOMINAL_SWEEP:Cable', ...
    'A between-samples straight-cable crossing was missed.');
d=make_sphere(44,[0;0;0],.1);
R7=TRIGGER_NOMINAL_SWEPT_INTERVALS(U,L,T,[d a],.01,.01,.005,[],[]);
assert(isequal(sort(R7.first_obstacle_ids),[41 44]) && ...
    isequal(sort(R7.new_obstacle_ids),[41 44]), ...
    'CHECK_TRIGGER_NOMINAL_SWEEP:Tie', ...
    'Simultaneous earliest intersample events were not preserved.');
R8=TRIGGER_NOMINAL_SWEPT_INTERVALS(U,L,T,[d a],.01,.01,.005,41,[]);
assert(isequal(R8.new_obstacle_ids,44), ...
    'CHECK_TRIGGER_NOMINAL_SWEEP:NewBehindOld', ...
    'Previously announced obstacle hid a new event.');
R=struct('status','PASS_NOMINAL_LINEAR_SWEEP_REGRESSION__NOT_PHYSICAL_CERTIFICATE', ...
    'cases',8,'failures',0, ...
    'between_samples_uav_detected',true, ...
    'between_samples_cable_detected',true, ...
    'physical_continuous_time_proven',false, ...
    'real_flight_tested',false,'wcet_proven',false);
save(fullfile(root,'TRIGGER_NOMINAL_SWEEP_RESULT.mat'),'R');
fid=fopen(fullfile(root,'TRIGGER_NOMINAL_SWEEP_RESULT.txt'),'w');
assert(fid>0,'CHECK_TRIGGER_NOMINAL_SWEEP:Log','Cannot write result.');
clean=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\ncases=8 failures=0\n',R.status);
fprintf(fid,'physical_continuous_time_proven=0 real_flight_tested=0 WCET_proven=0\n');
end

function s=make_sphere(id,c,r)
s=struct('id',id,'center0',c,'is_stationary',true, ...
    'bounding_radius_m',r,'rotation',eye(3),'dimensions',r, ...
    'type','sphere');
end
