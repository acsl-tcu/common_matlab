function R=CHECK_TRAJECTORY_C9_POINT_INPUT_CAUSE()
% Development-only diagnosis of a geometry-certified C9 candidate.
% Checks its actual Bernstein polynomial at explicitly selected times.
% Point probes are NOT all-time torque certificates and cannot COMMIT.
% No flight runner, HLC, estimator, or planner production policy is edited.
root=fileparts(mfilename('fullpath'));
name='TRAJECTORY_C9_POINT_INPUT_CAUSE_RESULT';
R=struct('status','FAIL_C9_POINT_INPUT_CAUSE', ...
    'stage','START','error_identifier','','error_message','', ...
    'error_stack',{{}},'search_status','NOT_RUN', ...
    'search_elapsed_ms',NaN,'search_independent_proof_calls',NaN, ...
    'search_oracle_time_total_ms',NaN, ...
    'search_plane_time_total_ms',NaN, ...
    'search_joint_qp_time_total_ms',NaN, ...
    'search_point_prefilter_time_ms',NaN, ...
    'baseline_status','NOT_RUN','baseline_ms',NaN, ...
    'baseline_nodes',NaN,'baseline_detailed_nodes',NaN, ...
    'baseline_unknown_interval_s',[NaN NaN], ...
    'baseline_unknown_depth',NaN,'baseline_unknown_bounds_Nm',NaN(3,2), ...
    'depth10_status','NOT_RUN','depth10_ms',NaN, ...
    'depth10_unknown_interval_s',[NaN NaN], ...
    'depth10_unknown_bounds_Nm',NaN(3,2), ...
    'point_count',0,'point_valid_count',0, ...
    'point_outside_count',0,'point_first_outside_s',NaN, ...
    'point_max_margin_violation_Nm',NaN, ...
    'point_probe_elapsed_ms',NaN, ...
    'point_mz_range_Nm',[NaN NaN], ...
    'point_worst_time_s',NaN, ...
    'point_times_s',zeros(1,0), ...
    'point_torque_lower_Nm',zeros(3,0), ...
    'point_torque_upper_Nm',zeros(3,0), ...
    'point_valid',false(1,0), ...
    'point_outside',false(1,0), ...
    'interpretation','NO_DIAGNOSTIC_YET', ...
    'safe_to_commit',false, ...
    'scope','POINT_DIAGNOSTICS_ONLY__NOT_ALL_TIME_OR_HLC_OR_ROUNDING_CERT', ...
    'zip_path',fullfile(root,[name '_FOR_CHATGPT.zip']));
try
    R.stage='AUTHORITATIVE_HLC_LIMITS_AND_FIXTURE';
    addpath(fullfile(root,'controller'),fullfile(root,'model'),'-begin');
    addpath(fullfile(root,'reference','REPLANNING_SYSTEM', ...
      'TRAJECTORY_GENERATION'), ...
      fullfile(root,'reference','REPLANNING_SYSTEM', ...
      'OBSTACLE_INFORMATION'),'-begin');
    [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    P.set("loadmass",0.14); % CHECK-only fixture; never production default.
    d=double(P.get(["mass","jx","jy","jz","gravity","cableL","loadmass"]));
    d=d(:);lo=double(lo(:));hi=double(hi(:));
    assert(numel(d)==7&&all(isfinite(d))&&all(d>0)&& ...
        numel(lo)==4&&numel(hi)==4&&all(hi>lo), ...
        'C9_POINT:Authority','Current HLC authority unavailable');
    a=struct('uav_mass_kg',d(1),'payload_mass_kg',d(7), ...
      'cable_length_m',d(6),'uav_inertia_kgm2',d(2:4), ...
      'gravity_world_mps2',[0;0;-d(5)], ...
      'thrust_limits_N',[lo(1),hi(1)], ...
      'torque_limits_Nm',[lo(2:4),hi(2:4)], ...
      'minimum_tension_N',0,'acceleration_guard_mps2',0);
    opt=struct('max_subdivision_depth',8,'max_node_count',511, ...
      'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
      'torque_guard_Nm',zeros(3,1), ...
      'enable_fast_norm_sufficient_bound',true, ...
      'use_precomputed_binomial',true, ...
      'use_factored_diagonal_gyro',true, ...
      'enable_infeasible_leaf_early_exit',true, ...
      'use_symmetric_unit_jet_kernel',true, ...
      'use_cancellation_attitude_jet',true, ...
      'use_structural_torque_intersection',false);
    J0=zeros(3,10);J1=zeros(3,10);
    J0(:,1)=[-2;0;3];J1(:,1)=[2;0;3];
    J0(1,2)=0.4;J1(1,2)=0.4;
    nominal=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,10,J0,J1, ...
      repmat([0;0;3],1,4));
    theta=0.34;Q=[cos(theta) -sin(theta) 0; ...
                     sin(theta) cos(theta) 0;0 0 1];
    observed=[OBSTACLE_INFORMATION.define(21,'sphere',[0 0.1 3],0.2), ...
      OBSTACLE_INFORMATION.define(33,'ellipsoid',[0.6 -0.16 3], ...
      [0.32 0.19 0.4],'rotation',Q)];
    gopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
      'numerical_guard_m',0,'robust_tube_enabled',false, ...
      'trajectory_phase','f');
    fopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
      'force_guard_N',0);
    sopt=struct('probe_count',13,'max_outer_iterations',4, ...
      'max_projection_sweeps',100,'projection_tolerance_m',1e-8, ...
      'min_separation_m',1e-5, ...
      'lazy_initial_proof_on_violated_plane',false, ...
      'payload_hull_witness_policy','off', ...
      'embed_taut_bernstein_halfspaces',false, ...
      'accept_first_certified_minimum_qp',false, ...
      'enable_connected_group_topology',true, ...
      'enable_point_intersection_prefilter',true);
    req=struct('t0_s',8,'duration_s',10,'flight_interval_s',[8 30], ...
      'start_jets',J0,'end_jets',J1, ...
      'nominal_free',nominal.control_points_m(:,11:14), ...
      'observed',observed, ...
      'radii',struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1), ...
      'authority',a,'geometry_options',gopt, ...
      'force_options',fopt,'search_options',sopt);
    R.stage='ONE_GEOMETRY_CERTIFIED_GUIDE';
    S=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(req);
    R.search_status=S.status;
    R.search_elapsed_ms=S.elapsed_ms;
    R.search_independent_proof_calls=S.independent_proof_calls;
    R.search_oracle_time_total_ms=S.independent_proof_time_total_ms;
    R.search_plane_time_total_ms=S.plane_construction_time_total_ms;
    R.search_joint_qp_time_total_ms=S.joint_qp_time_total_ms;
    R.search_point_prefilter_time_ms=S.point_intersection_time_total_ms;
    assert(S.candidate_available&&S.final_certificate.certified&& ...
      ~S.safe_to_commit, 'C9_POINT:Guide', ...
      ['No geometry-certified fixture: ' S.status]);
    piece=S.candidate_piece;
    R.stage='BASELINE_TORQUE_PROOF';
    Z=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL(piece,a,opt);
    R.baseline_status=Z.status;
    R.baseline_ms=Z.elapsed_ms;
    R.baseline_nodes=Z.checked_nodes;
    R.baseline_detailed_nodes=Z.detailed_interval_checked_nodes;
    R.baseline_unknown_interval_s=Z.unresolved_interval_s;
    R.baseline_unknown_depth=Z.unresolved_depth;
    R.baseline_unknown_bounds_Nm=Z.unresolved_torque_bounds_Nm;
    assert(~Z.safe_to_commit && ~Z.actual_HLC_tracking_proven && ...
      ~Z.numerically_directed_rounding_proven, ...
      'C9_POINT:Commit','Nominal proof improperly authorizes COMMIT');
    % One deeper diagnosis to localize an unresolved torque interval.
    R.stage='DEPTH10_LOCALIZATION_ONLY';
    o=opt;o.max_subdivision_depth=10;
    D=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL(piece,a,o);
    R.depth10_status=D.status;
    R.depth10_ms=D.elapsed_ms;
    R.depth10_unknown_interval_s=D.unresolved_interval_s;
    R.depth10_unknown_bounds_Nm=D.unresolved_torque_bounds_Nm;
    % Offline point probes. They can refute a candidate numerically,
    % but NEVER certify a safe continuous-time trajectory.
    R.stage='POINT_WITNESS_PROBES_DIAGNOSTIC_ONLY';
    t0=piece.t0_s;t1=t0+piece.duration_s;
    global_times=linspace(t0,t1,161);
    leaf=D.unresolved_interval_s;
    if any(~isfinite(leaf)), leaf=Z.unresolved_interval_s;end
    if all(isfinite(leaf))
        width=leaf(2)-leaf(1);
        nearby=linspace(max(t0,leaf(1)-4*width), ...
                        min(t1,leaf(2)+4*width),129);
    else
        nearby=[];
    end
    times=unique([global_times nearby]);
    o=opt;o.diagnostic_point_probe_times_s=times;
    X=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL(piece,a,o);
    assert(strcmp(X.status,Z.status)&& ...
      X.checked_nodes==Z.checked_nodes && ...
      X.detailed_interval_checked_nodes==Z.detailed_interval_checked_nodes && ...
      ~X.safe_to_commit && ~X.actual_HLC_tracking_proven && ...
      ~X.numerically_directed_rounding_proven, ...
      'C9_POINT:ProofDrift','Diagnostics changed all-time proof');
    R.point_times_s=X.diagnostic_point_probe_times_s;
    R.point_torque_lower_Nm=X.diagnostic_point_torque_lower_Nm;
    R.point_torque_upper_Nm=X.diagnostic_point_torque_upper_Nm;
    R.point_valid=X.diagnostic_point_valid;
    R.point_outside=X.diagnostic_point_outside_limits_unrounded;
    R.point_count=numel(times);
    R.point_valid_count=sum(R.point_valid);
    R.point_outside_count=sum(R.point_outside);
    R.point_first_outside_s=X.diagnostic_point_first_outside_time_s;
    R.point_max_margin_violation_Nm= ...
      X.diagnostic_point_max_margin_violation_Nm;
    R.point_probe_elapsed_ms=X.diagnostic_point_elapsed_ms;
    if any(R.point_valid)
        R.point_mz_range_Nm=[min(R.point_torque_lower_Nm(3,R.point_valid)), ...
                           max(R.point_torque_upper_Nm(3,R.point_valid))];
        valid_idx=find(R.point_valid);
        [~,local_idx]=max(R.point_torque_upper_Nm(3,valid_idx));
        R.point_worst_time_s=times(valid_idx(local_idx));
    end
    if R.point_outside_count>0
        R.interpretation= ...
          'POINT_OUTSIDE_UNROUNDED__REVISE_C9_INPUT_FEASIBILITY__NOT_FORMAL_WITNESS';
    elseif R.point_valid_count==R.point_count
        R.interpretation= ...
          'NO_POINT_OUTSIDE__STILL_UNKNOWN_CONTINUOUS_TIME__TIGHTEN_CERTIFICATE';
    else
        R.interpretation= ...
          'POINTS_DEGENERATE_OR_UNEVALUATED__INVESTIGATE_SINGULARITY';
    end
    R.stage='COMPLETE';
    R.status='PASS_C9_POINT_DIAGNOSTIC_SCOPE__HLC_UNCERTIFIED';
catch ME
    R.error_identifier=ME.identifier;R.error_message=ME.message;
    R.error_stack=arrayfun(@(e)sprintf('%s:%d',e.name,e.line), ...
      ME.stack,'UniformOutput',false);
end
save(fullfile(root,[name '.mat']),'R');
fid=fopen(fullfile(root,[name '.txt']),'w');
if fid>=0
    fprintf(fid,'status=%s | stage=%s\n',R.status,R.stage);
    fprintf(fid,'error=%s | %s\n',R.error_identifier,R.error_message);
    for k=1:numel(R.error_stack)
        fprintf(fid,'stack_%d=%s\n',k,R.error_stack{k});
    end
    fprintf(fid,'guide=%s | search_ms=%.6f | geometry_proofs=%g\n', ...
      R.search_status,R.search_elapsed_ms,R.search_independent_proof_calls);
    fprintf(fid,['guide_stage_ms: oracle=%.6f | planes=%.6f | ', ...
      'qp=%.6f | point_prefilter=%.6f\n'], ...
      R.search_oracle_time_total_ms,R.search_plane_time_total_ms, ...
      R.search_joint_qp_time_total_ms, ...
      R.search_point_prefilter_time_ms);
    fprintf(fid,'baseline=%s | ms=%.6f | nodes=%.0f | detailed=%.0f\n', ...
      R.baseline_status,R.baseline_ms,R.baseline_nodes, ...
      R.baseline_detailed_nodes);
    fprintf(fid,'baseline_unresolved=[%.12g %.12g] depth=%.0f | Mz=[%.12g %.12g]\n', ...
      R.baseline_unknown_interval_s,R.baseline_unknown_depth, ...
      R.baseline_unknown_bounds_Nm(3,1),R.baseline_unknown_bounds_Nm(3,2));
    fprintf(fid,'depth10=%s | ms=%.6f | interval=[%.12g %.12g] | Mz=[%.12g %.12g]\n', ...
      R.depth10_status,R.depth10_ms,R.depth10_unknown_interval_s, ...
      R.depth10_unknown_bounds_Nm(3,1), ...
      R.depth10_unknown_bounds_Nm(3,2));
    fprintf(fid,'point_count=%d | valid=%d | outside_unrounded=%d | point_elapsed_ms=%.6f\n', ...
      R.point_count,R.point_valid_count,R.point_outside_count, ...
      R.point_probe_elapsed_ms);
    fprintf(fid,'first_outside_s=%.12g | max_nominal_margin_violation_Nm=%.12g\n', ...
      R.point_first_outside_s,R.point_max_margin_violation_Nm);
    fprintf(fid,'point_mz_range=[%.12g %.12g] | peak_mz_time=%.12g\n', ...
      R.point_mz_range_Nm,R.point_worst_time_s);
    fprintf(fid,'interpretation=%s\n',R.interpretation);
    fprintf(fid,'scope=%s | safe_to_commit=%d\n',R.scope,R.safe_to_commit);
    fclose(fid);
end
zip(R.zip_path,{[name '.mat'],[name '.txt']},root);
fprintf('[C9 POINT INPUT CAUSE] %s | %s\n',R.status,R.zip_path);
end
