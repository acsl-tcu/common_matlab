function A = CHECK_TRIGGER_THREE_RUN_STAGE_CAUSES()
% Additional read-only analysis of the 3 saved TRIGGER_DIAG_V1 matrices.
% No reliance on fixed Flight time, obstacle IDs, path, or shape.
% No real-time code changed. Each cost is a WALL-CLOCK attribution,
% NOT proof of its underlying cause (JIT/GC/OS/preemption).
files = {'TRIGGER_DIAG_RUN_01.mat', ...
         'TRIGGER_DIAG_RUN_02.mat', ...
         'TRIGGER_DIAG_RUN_03.mat'};
A = struct('status','THREE_RUN_STAGE_CAUSES__NO_WCET_OR_CAUSAL_PROOF', ...
    'reason','', 'update_max_ms',nan(1,3), ...
    'reference_max_ms',nan(1,3), ...
    'memory_max_ms',nan(1,3), ...
    'sensor_max_ms',nan(1,3), ...
    'geometry_max_ms',nan(1,3), ...
    'peaks_over_5ms',zeros(1,3), ...
    'non_event_peaks_over_5ms',zeros(1,3));
fid = fopen('TRIGGER_DIAG_THREE_RUN_STAGE_CAUSES.txt','w');
assert(fid >= 0,'CHECK_TRIGGER_THREE_RUN_STAGE_CAUSES:File');
fid_cleaner=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'status=%s\n',A.status);
fprintf(fid,'All data from actual saved MAT files, not a guessed scenario.\n');
fprintf(fid,'Nested timers may overlap. No subtraction is proof of GC/JIT/OS cause.\n');
fprintf(fid,'One large timer reading can include OS preemption during that function.\n');
fprintf(fid,'Timestamp coincidence without cache miss counters cannot prove a cache reset.\n');
for r = 1:3
    assert(isfile(files{r}), ...
        'CHECK_TRIGGER_THREE_RUN_STAGE_CAUSES:MissingRun', ...
        'Missing %s',files{r});
    W=load(files{r},'C');
    assert(isfield(W,'C') && strcmp(W.C.version,'TRIGGER_DIAG_V1'), ...
        'CHECK_TRIGGER_THREE_RUN_STAGE_CAUSES:Version');
    C=W.C;
    assert(C.run_id==r && numel(C.replanner_ms)==C.n, ...
        'CHECK_TRIGGER_THREE_RUN_STAGE_CAUSES:RunOrder');
    names={'replanner_ms','trigger_ms','sensor_ms','memory_ms', ...
        'reference_ms','predictor_ms','geometry_ms','trigger_outer_ms', ...
        'rhs_evals','rejected_steps','detected_changed','acquired', ...
        'new_event','duplicate'};
    assert(all(isfield(C,names)), ...
        'CHECK_TRIGGER_THREE_RUN_STAGE_CAUSES:MissingFields');
    A.update_max_ms(r)=finite_max(C.replanner_ms);
    A.reference_max_ms(r)=finite_max(C.reference_ms);
    A.memory_max_ms(r)=finite_max(C.memory_ms);
    A.sensor_max_ms(r)=finite_max(C.sensor_ms);
    A.geometry_max_ms(r)=finite_max(C.geometry_ms);
    event = logical(C.acquired(:)) | logical(C.detected_changed(:)) | ...
        logical(C.new_event(:));
    % A transition may have its costly continuation on the FOLLOWING tick.
    event_or_next = event;
    event_or_next(2:end)=event_or_next(2:end)|event(1:end-1);
    over5 = isfinite(C.replanner_ms(:)) & C.replanner_ms(:)>5;
    A.peaks_over_5ms(r)=nnz(over5);
    A.non_event_peaks_over_5ms(r)=nnz(over5 & ~event_or_next);
    fprintf(fid,'\n=== RUN %d ===\n',r);
    fprintf(fid,'frames=%d first_prediction_index=%.0f\n',C.n,C.first_prediction);
    fprintf(fid,'update_median_ms=%.6f update_p95_ms=%.6f update_max_ms=%.6f\n', ...
        quant(C.replanner_ms,0.5),quant(C.replanner_ms,0.95),A.update_max_ms(r));
    fprintf(fid,'peaks_over_5ms=%d non_event_or_next_peaks_over_5ms=%d\n', ...
        A.peaks_over_5ms(r),A.non_event_peaks_over_5ms(r));
    fprintf(fid,'max_sensor=%.6f max_memory=%.6f max_reference=%.6f max_geometry=%.6f\n', ...
        A.sensor_max_ms(r),A.memory_max_ms(r),A.reference_max_ms(r),A.geometry_max_ms(r));
    fprintf(fid,'run,k,time_s,update_ms,trigger_ms,sensor_ms,memory_ms,reference_ms,geometry_ms,predictor_ms,outer_ms,rhs,reject,acquired,det_changed,new_event,duplicate,same_or_next_event,dominant_timer\n');
    valid=find(isfinite(C.replanner_ms(:)));
    [~,ind]=sort(C.replanner_ms(valid),'descend');
    n_top=min(numel(valid),40);
    selected=valid(ind(1:n_top));
    for k=reshape(selected,1,[])
        component=[C.sensor_ms(k),C.memory_ms(k),C.reference_ms(k), ...
             C.geometry_ms(k),C.predictor_ms(k),C.trigger_outer_ms(k)];
        labels={'SENSOR','MEMORY','REFERENCE','GEOMETRY', ...
             'PREDICTOR_WALL','TRIGGER_OUTER'};
        component(~isfinite(component))=-Inf;
        [large,where]=max(component);
        if ~isfinite(large) || large < 0.25*C.replanner_ms(k)
            dom='UNATTRIBUTED_IN_AVAILABLE_TIMERS';
        else
            dom=labels{where};
        end
        fprintf(fid,['%d,%d,%.9f,%.6f,%.6f,%.6f,%.6f,%.6f,' ...
            '%.6f,%.6f,%.6f,%.0f,%.0f,%d,%d,%d,%d,%d,%s\n'], ...
            r,k,C.time_s(k),C.replanner_ms(k),C.trigger_ms(k), ...
            C.sensor_ms(k),C.memory_ms(k),C.reference_ms(k), ...
            C.geometry_ms(k),C.predictor_ms(k),C.trigger_outer_ms(k), ...
            C.rhs_evals(k),C.rejected_steps(k), ...
            C.acquired(k),C.detected_changed(k),C.new_event(k), ...
            C.duplicate(k),event_or_next(k),dom);
    end
    fprintf(fid,'\nEVENT TRANSITIONS AND FOLLOWING TICKS\n');
    boundary=find(event);
    for index=reshape(boundary,1,[])
        k0=index;
        for k=k0:min(C.n,k0+1)
            fprintf(fid,['k=%d t=%.9f update=%.4f sensor=%.4f ' ...
               'memory=%.4f trigger=%.4f new=%d changed=%d ' ...
               'new_event=%d duplicate=%d\n'], ...
                k,C.time_s(k),C.replanner_ms(k),C.sensor_ms(k), ...
                C.memory_ms(k),C.trigger_ms(k), ...
                C.acquired(k),C.detected_changed(k), ...
                C.new_event(k),C.duplicate(k));
        end
    end
    fprintf(fid,'\nNUMERICAL WORKLOAD BASELINE (PREDICTED TICKS)\n');
    p=logical(C.predicted(:));
    fprintf(fid,'rhs_median=%.0f reject_median=%.0f rhs_max=%.0f reject_max=%.0f\n', ...
        quant(C.rhs_evals(p),.5),quant(C.rejected_steps(p),.5), ...
        finite_max(C.rhs_evals(p)),finite_max(C.rejected_steps(p)));
end
fprintf(fid,'\nINTERPRETATION\n');
fprintf(fid,'REFERENCE spikes alone do not prove 160 scalar cache misses.\n');
fprintf(fid,'MEMORY spikes alone do not prove structure copies or OS quantum.\n');
fprintf(fid,'GEOMETRY spikes without exact-query growth do not prove distance-loop workload.\n');
fprintf(fid,'RHS/rejected counters must be compared before modifying native solver.\n');
fprintf(fid,'Tracking error/continuous safety are NOT certified by these timing logs.\n');
save('TRIGGER_DIAG_THREE_RUN_STAGE_CAUSES.mat','A','-v7.3');
fprintf('Stage cause report: TRIGGER_DIAG_THREE_RUN_STAGE_CAUSES.txt\n');
end
function y=finite_max(x)
x=x(isfinite(x));
if isempty(x),y=NaN;else,y=max(x);end
end
function y=quant(x,q)
x=sort(x(isfinite(x)));
if isempty(x),y=NaN;else,y=x(max(1,ceil(q*numel(x))));end
end
