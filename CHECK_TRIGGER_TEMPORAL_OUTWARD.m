function A=CHECK_TRIGGER_TEMPORAL_OUTWARD()
% Dyadic-exact mathematical oracle for the final temporal inequality.
% All test operands are exact binary fractions: an ordinary double can
% represent the REAL reference inequality without a symbolic toolbox.
% Does not claim the preceding plant/Picard/shape oracles are certified.
root=fileparts(mfilename('fullpath'));
A=struct('status','FAIL_TEMPORAL_OUTWARD_ARITHMETIC', ...
    'cases',0,'failures',0,'positive',0,'near_boundary',0, ...
    'overflow_refusals',0,'reason','');
try
    for k=1:2400
        % 0..~32, exact dyadics; no rounding in the reference sums.
        aa=mod(k*37,257); bb=mod(k*53,251);
        cc=mod(k*71,283);
        d0=aa/16;d1=bb/16;
        v=cc/16;h=0.25;
        expected=(d0+d1-v*h)/2;
        C=struct('time_grid_s',[0,h], ...
            'observed_ids',k+70000, ...
            'sample_clearance_lower_m',[d0 d1], ...
            'speed_upper_mps',v);
        R=TRIGGER_TAUT_TEMPORAL_CLEARANCE_WITNESS(C);
        assert(isfinite(R.clearance_lower_m) && ...
            R.clearance_lower_m<=expected && ...
            R.interval_duration_upper_s>=h && ...
            isequal(R.separated_intervals,expected>0) && ...
            isequal(R.safe_to_commit,false), ...
            'CHECK_TRIGGER_TEMPORAL_OUTWARD:UnderApproximation', ...
            'Outward interval result disagrees with exact dyadic oracle.');
        if expected>0,A.positive=A.positive+1;end
        if expected==0,A.near_boundary=A.near_boundary+1;end
        A.cases=A.cases+1;
    end
    % Multiple simultaneously unproved IDs must survive the reduction.
    C=struct('time_grid_s',[0 0.25 0.5], ...
        'observed_ids',[7 19], ...
        'sample_clearance_lower_m',[1 1 1;0 0 0], ...
        'speed_upper_mps',[0 0]);
    R=TRIGGER_TAUT_TEMPORAL_CLEARANCE_WITNESS(C);
    assert(isequal(R.possible_risk_ids,19) && ...
        isequal(R.separated_intervals,[true true;false false]) && ...
        ~R.safe_to_commit);
    A.cases=A.cases+1;
    % Do not silently certify near overflow/Inf arithmetic.
    C=struct('time_grid_s',[0 1], ...
        'observed_ids',13, ...
        'sample_clearance_lower_m',[realmax realmax], ...
        'speed_upper_mps',realmax);
    R=TRIGGER_TAUT_TEMPORAL_CLEARANCE_WITNESS(C);
    assert(~R.conditional_clearance && ~R.safe_to_commit && ...
        ~isempty(strfind(R.status,'UNKNOWN'))); %#ok<STREMP>
    A.overflow_refusals=1;
    A.cases=A.cases+1;
    A.status='PASS_DIRECTED_TEMPORAL_BINARY64__INPUT_PROOF_MISSING';
catch ME
    A.failures=A.failures+1;
    A.reason=[ME.identifier ' | ' ME.message];
end
save(fullfile(root,'TRIGGER_TEMPORAL_OUTWARD_RESULT.mat'),'A');
fid=fopen(fullfile(root,'TRIGGER_TEMPORAL_OUTWARD_RESULT.txt'),'wt');
if fid>=0
    fprintf(fid,'status=%s\ncases=%d\nfailures=%d\n', ...
        A.status,A.cases,A.failures);
    fprintf(fid,'positive=%d\nnear_boundary=%d\noverflow_refusals=%d\nreason=%s\n', ...
        A.positive,A.near_boundary,A.overflow_refusals,A.reason);
    fclose(fid);
end
end
