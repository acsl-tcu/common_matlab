function R=CHECK_TRAJECTORY_C9_NOMINAL_INPUT_AWARE_QP()
% CHECK-only: identify physical nominal input deficiency vs interval inflation;
% compare old geometry-only guide with 12-variable joint torque-aware QP.
% NEVER claim continuous-time torque, numerical outward rounding, actual HLC
% closed-loop tracking, sensor tube, or physical COMMIT from these probes.
root=fileparts(mfilename('fullpath'));
name='TRAJECTORY_C9_NOMINAL_INPUT_AWARE_QP_RESULT';
R=struct('status','FAIL_C9_NOMINAL_INPUT_AWARE_QP', ...
    'error_identifier','','error_message','','error_stack',{{}}, ...
    'baseline_guide_status','NOT_RUN', ...
    'new_guide_status','NOT_RUN', ...
    'new_failure_reason','', ...
    'baseline_guide_available',false,'new_guide_available',false, ...
    'torque_value_parity_max_error_Nm',NaN, ...
    'torque_gradient_max_relative_error',NaN, ...
    'fixture_point_violation_count',NaN, ...
    'fixture_point_peak_violation_Nm',NaN, ...
    'fixture_min_heading_speed_mps',NaN, ...
    'fixture_peak_abs_mz_time_s',NaN, ...
    'fixture_heading_speed_at_peak_mps',NaN, ...
    'fixture_force_z_at_peak_N',NaN, ...
    'fixture_mz_inertial_at_peak_Nm',NaN, ...
    'fixture_mz_gyro_at_peak_Nm',NaN, ...
    'new_point_preoracle_skips',NaN, ...
    'new_point_torque_joint_cuts',NaN, ...
    'new_point_torque_jacobian_evaluations',NaN, ...
    'new_point_torque_ms',NaN, ...
    'new_independent_proofs',NaN, ...
    'new_independent_proof_ms',NaN, ...
    'new_plane_ms',NaN,'new_qp_ms',NaN, ...
    'new_point_torque_max_violation_Nm',NaN, ...
    'old_elapsed_ms',NaN(1,3),'new_elapsed_ms',NaN(1,3), ...
    'median_ms_old',NaN,'median_ms_new',NaN, ...
    'p95_ms_old',NaN,'p95_ms_new',NaN, ...
    'max_ms_old',NaN,'max_ms_new',NaN, ...
    'new_nominal_proof_status','NOT_RUN', ...
    'scope','SEARCH_OPTIMIZATION_AUDIT_ONLY__NOT_FULL_TIME_HLC_CERT', ...
    'safe_to_commit',false,'zip_path',fullfile(root,[name '_FOR_CHATGPT.zip']));
try
    addpath(fullfile(root,'controller'),fullfile(root,'model'),'-begin');
    addpath(fullfile(root,'reference','REPLANNING_SYSTEM', ...
        'TRAJECTORY_GENERATION'), ...
        fullfile(root,'reference','REPLANNING_SYSTEM', ...
        'OBSTACLE_INFORMATION'),'-begin');
    [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    P.set("loadmass",0.14); % CHECK-only fixture, never production fallback.
    d=double(P.get(["mass","jx","jy","jz", ...
         "gravity","cableL","loadmass"]));
    d=d(:);lo=double(lo(:));hi=double(hi(:));
    assert(numel(d)==7&&all(isfinite(d))&&all(d>0)&& ...
        numel(lo)==4&&numel(hi)==4&&all(hi>lo), ...
        'C9_INPUT_QP:Authority','HLC or physical authority unavailable');
    a=struct('uav_mass_kg',d(1),'payload_mass_kg',d(7), ...
      'cable_length_m',d(6),'uav_inertia_kgm2',d(2:4), ...
      'gravity_world_mps2',[0;0;-d(5)], ...
      'thrust_limits_N',[lo(1),hi(1)], ...
      'torque_limits_Nm',[lo(2:4),hi(2:4)], ...
      'minimum_tension_N',0,'acceleration_guard_mps2',0);
    topt=struct('max_subdivision_depth',8,'max_node_count',511, ...
      'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
      'torque_guard_Nm',zeros(3,1), ...
      'enable_fast_norm_sufficient_bound',true, ...
      'use_precomputed_binomial',true, ...
      'use_factored_diagonal_gyro',true, ...
      'enable_infeasible_leaf_early_exit',true, ...
      'use_symmetric_unit_jet_kernel',true, ...
      'use_cancellation_attitude_jet',true, ...
      'use_structural_torque_intersection',false);
    J0=zeros(3,10);J1=zeros(3,10);
    J0(:,1)=[-2;0;3];J1(:,1)=[2;0;3];
    J0(1,2)=0.4;J1(1,2)=0.4;
    nominal=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,10,J0,J1, ...
        repmat([0;0;3],1,4));
    theta=0.34;Q=[cos(theta) -sin(theta) 0; ...
                       sin(theta) cos(theta) 0;0 0 1];
    observed=[OBSTACLE_INFORMATION.define(21,'sphere',[0 0.1 3],0.2), ...
      OBSTACLE_INFORMATION.define(33,'ellipsoid',[0.6 -0.16 3], ...
      [0.32 0.19 0.4],'rotation',Q)];
    gopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
      'numerical_guard_m',0,'robust_tube_enabled',false, ...
      'trajectory_phase','f');
    fopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
      'force_guard_N',0);
    sopt=struct('probe_count',13,'max_outer_iterations',4, ...
      'max_projection_sweeps',100,'projection_tolerance_m',1e-8, ...
      'min_separation_m',1e-5, ...
      'lazy_initial_proof_on_violated_plane',false, ...
      'payload_hull_witness_policy','off', ...
      'embed_taut_bernstein_halfspaces',false, ...
      'accept_first_certified_minimum_qp',false, ...
      'enable_connected_group_topology',true, ...
      'enable_point_intersection_prefilter',true);
    req=struct('t0_s',8,'duration_s',10,'flight_interval_s',[8 30], ...
      'start_jets',J0,'end_jets',J1, ...
      'nominal_free',nominal.control_points_m(:,11:14), ...
      'observed',observed, ...
      'radii',struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1), ...
      'authority',a,'geometry_options',gopt,'force_options',fopt, ...
      'search_options',sopt,'torque_options',topt);
    S0=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(req);
    R.baseline_guide_status=S0.status;
    R.baseline_guide_available=S0.candidate_available;
    assert(S0.candidate_available&&S0.final_certificate.certified&& ...
        ~S0.safe_to_commit, 'C9_INPUT_QP:Fixture', ...
        'No geometry-certified reference for comparison');
    piece=S0.candidate_piece;
    % Real source candidate, caller-independent normalized probe schedule.
    ts=piece.t0_s+piece.duration_s*(0:32)/32;
    point=TRAJECTORY_C9_TORQUE_POINT_EVALUATE(piece,a,topt,ts);
    assert(all(point.valid)&&~point.safe_to_commit, ...
        'C9_INPUT_QP:Points','Fast point evaluator not valid');
    R.fixture_point_violation_count=sum(point.outside_limits);
    R.fixture_point_peak_violation_Nm=point.maximum_point_violation_Nm;
    R.fixture_min_heading_speed_mps=min(point.heading_speed_mps);
    [~,peak_idx]=max(abs(real(point.torque_Nm(3,:))));
    R.fixture_peak_abs_mz_time_s=ts(peak_idx);
    R.fixture_heading_speed_at_peak_mps= ...
        point.heading_speed_mps(peak_idx);
    R.fixture_force_z_at_peak_N=point.force_z_N(peak_idx);
    R.fixture_mz_inertial_at_peak_Nm= ...
        real(point.inertial_torque_Nm(3,peak_idx));
    R.fixture_mz_gyro_at_peak_Nm= ...
        real(point.gyroscopic_torque_Nm(3,peak_idx));
    % Independent implementation of the same physics: old interval
    % box evaluated on zero-width Bernstein jets at exactly these times.
    o=topt;o.diagnostic_point_probe_times_s=ts;
    ref=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL(piece,a,o);
    assert(all(ref.diagnostic_point_valid), ...
        'C9_INPUT_QP:Reference','Original point diagnostics failed');
    refM=ref.diagnostic_point_torque_lower_Nm;
    R.torque_value_parity_max_error_Nm= ...
        max(abs(point.torque_Nm-refM),[],'all');
    assert(R.torque_value_parity_max_error_Nm<= ...
        2e-7*max(1,max(abs(refM),[],'all')), ...
        'C9_INPUT_QP:Parity','Independent point inverse-dynamics mismatch');
    % Complex-step Jacobian must agree with a distinct central-difference
    % directional derivative; neither numerical derivative is a proof.
    U=[2 0.3 0 0;0 3 0.2 0;0 0 4 0.4;0 0 0 5];
    C=TRAJECTORY_C9_TORQUE_LOCAL_CUTS(piece,a,topt,ts,U);
    assert(C.cut_count>=1 && size(C.A,1)==12 && ...
        all(C.b>0)&&~C.safe_to_commit, ...
        'C9_INPUT_QP:Cuts','No torque cuts found from known violation');
    direction=sin((1:12)'*sqrt(2));
    direction=direction/norm(direction);
    fd=1e-6;
    physical=reshape(direction,3,4)/U.';
    plus=piece;minus=piece;
    plus.control_points_m(:,11:14)= ...
        piece.control_points_m(:,11:14)+fd*physical;
    minus.control_points_m(:,11:14)= ...
        piece.control_points_m(:,11:14)-fd*physical;
    R.torque_gradient_max_relative_error=0;
    for k=1:C.cut_count
        tp=C.cut_times_s(k);
        p1=TRAJECTORY_C9_TORQUE_POINT_EVALUATE(plus,a,topt,tp);
        p0=TRAJECTORY_C9_TORQUE_POINT_EVALUATE(minus,a,topt,tp);
        assert(all(p1.valid)&&all(p0.valid), ...
            'C9_INPUT_QP:GradientPoint','Degenerate gradient probe');
        ax=C.cut_axes(k);
        observed_d=(p1.torque_Nm(ax)-p0.torque_Nm(ax))/(2*fd);
        expected_d=C.cut_gradients_Nm_per_qp(:,k).'*direction;
        error=abs(observed_d-expected_d)/max([1,abs(observed_d),abs(expected_d)]);
        R.torque_gradient_max_relative_error= ...
            max(R.torque_gradient_max_relative_error,error);
    end
    assert(R.torque_gradient_max_relative_error<=1e-3, ...
        'C9_INPUT_QP:GradientParity','Local QP torque derivative mismatch');
    % A/B three runs each, with full independent geometry oracle counted.
    on=req;on.search_options.enable_torque_aware_joint_search=true;
    on.search_options.torque_probe_count=33;
    for k=1:3
        old=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(req);
        R.old_elapsed_ms(k)=old.elapsed_ms;
        new=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(on);
        R.new_elapsed_ms(k)=new.elapsed_ms;
    end
    R.new_guide_status=new.status;
    R.new_guide_available=new.candidate_available;
    R.new_failure_reason=new.failure_reason;
    R.new_point_preoracle_skips=new.point_torque_preoracle_skips;
    R.new_point_torque_joint_cuts=new.point_torque_local_cuts;
    R.new_point_torque_jacobian_evaluations= ...
        new.point_torque_local_jacobian_evaluations;
    R.new_point_torque_ms=new.point_torque_time_total_ms;
    R.new_point_torque_max_violation_Nm= ...
        new.point_torque_max_violation_Nm;
    R.new_independent_proofs=new.independent_proof_calls;
    R.new_independent_proof_ms=new.independent_proof_time_total_ms;
    R.new_plane_ms=new.plane_construction_time_total_ms;
    R.new_qp_ms=new.joint_qp_time_total_ms;
    R.median_ms_old=median(R.old_elapsed_ms);
    R.median_ms_new=median(R.new_elapsed_ms);
    R.p95_ms_old=prctile(R.old_elapsed_ms,95);
    R.p95_ms_new=prctile(R.new_elapsed_ms,95);
    R.max_ms_old=max(R.old_elapsed_ms);
    R.max_ms_new=max(R.new_elapsed_ms);
    assert(~new.safe_to_commit && ...
        (~new.candidate_available || new.final_certificate.certified), ...
        'C9_INPUT_QP:Safety','Geometry or COMMIT invariant broken');
    if new.candidate_available
        np=TRAJECTORY_C9_TORQUE_POINT_EVALUATE( ...
            new.candidate_piece,a,topt,ts);
        assert(all(np.valid)&&~any(np.outside_limits), ...
            'C9_INPUT_QP:PointScreen','Returned a point-violating guide');
        cert=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL( ...
            new.candidate_piece,a,topt);
        R.new_nominal_proof_status=cert.status;
        assert(~cert.safe_to_commit&&~cert.actual_HLC_tracking_proven, ...
            'C9_INPUT_QP:Commit','Nominal proof implies actual HLC COMMIT');
    end
    R.status='PASS_C9_INPUT_AWARE_SEARCH_INVARIANTS__HLC_UNCERTIFIED';
catch ME
    R.error_identifier=ME.identifier;
    R.error_message=ME.message;
    R.error_stack=arrayfun(@(s)sprintf('%s:%d',s.name,s.line), ...
        ME.stack,'UniformOutput',false);
end
save(fullfile(root,[name '.mat']),'R');
fid=fopen(fullfile(root,[name '.txt']),'w');
if fid>=0
    fprintf(fid,'status=%s error=%s %s\n',R.status,R.error_identifier,R.error_message);
    for j=1:numel(R.error_stack)
        fprintf(fid,'stack%d=%s\n',j,R.error_stack{j});
    end
    fprintf(fid,'fixture=%s | sample_violation=%g | max_excess_Nm=%.9f\n', ...
        R.baseline_guide_status,R.fixture_point_violation_count, ...
        R.fixture_point_peak_violation_Nm);
    fprintf(fid,['peak_abs_Mz_at_s=%.9f | heading_speed_mps=%.9f | ', ...
        'Fz_N=%.9f | inertial_Mz_Nm=%.9f | gyro_Mz_Nm=%.9f | ', ...
        'minimum_heading_speed_mps=%.9f\n'], ...
        R.fixture_peak_abs_mz_time_s, ...
        R.fixture_heading_speed_at_peak_mps, ...
        R.fixture_force_z_at_peak_N, ...
        R.fixture_mz_inertial_at_peak_Nm, ...
        R.fixture_mz_gyro_at_peak_Nm, ...
        R.fixture_min_heading_speed_mps);
    fprintf(fid,'parity_point_err_Nm=%g | gradient_relative_err=%g\n', ...
        R.torque_value_parity_max_error_Nm, ...
        R.torque_gradient_max_relative_error);
    fprintf(fid,'old_median_ms=%.6f p95_ms=%.6f max_ms=%.6f\n', ...
        R.median_ms_old,R.p95_ms_old,R.max_ms_old);
    fprintf(fid,'new_median_ms=%.6f p95_ms=%.6f max_ms=%.6f\n', ...
        R.median_ms_new,R.p95_ms_new,R.max_ms_new);
    fprintf(fid,'new=%s | available=%d | failure=%s\n', ...
        R.new_guide_status,R.new_guide_available,R.new_failure_reason);
    fprintf(fid,'new_preoracle_skips=%g cuts=%g jac_evals=%g torque_time_ms=%g\n', ...
        R.new_point_preoracle_skips,R.new_point_torque_joint_cuts, ...
        R.new_point_torque_jacobian_evaluations, ...
        R.new_point_torque_ms);
    fprintf(fid,'new_proofs=%g proof_ms=%g planes_ms=%g qp_ms=%g\n', ...
        R.new_independent_proofs,R.new_independent_proof_ms, ...
        R.new_plane_ms,R.new_qp_ms);
    fprintf(fid,'new_nominal_proof=%s | safe_to_commit=%d\n', ...
        R.new_nominal_proof_status,R.safe_to_commit);
    fclose(fid);
end
zip(R.zip_path,{[name '.mat'],[name '.txt']},root);
fprintf('[C9 INPUT AWARE QP] %s | %s\n',R.status,R.zip_path);
end
