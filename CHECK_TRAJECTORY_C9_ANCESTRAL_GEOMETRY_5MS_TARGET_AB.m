function R=CHECK_TRAJECTORY_C9_ANCESTRAL_GEOMETRY_5MS_TARGET_AB()
% Compare the IDENTICAL single-C9 pipeline, 15 scenes + repeat scenes:
% tight hull/outer-ball only versus tight + mathematically inherited
% per-obstacle, parent-cell, all-time geometry certificates.
% Nothing is terminated at 5ms/7ms. No new safety COMMIT is authorized.
root=fileparts(mfilename('fullpath'));
name='TRAJECTORY_C9_ANCESTRAL_GEOMETRY_5MS_TARGET_AB_RESULT';
R=struct('status','NOT_STARTED','stage','SETUP','error_message','', ...
    'safe_to_commit',false,'target_normal_ms',5,'target_heavy_ms',7, ...
    'no_time_cutoff_used',true,'no_stage_split_used',true, ...
    'property_test_count',0,'property_pass',false, ...
    'baseline_success',NaN,'inherited_success',NaN, ...
    'baseline_unknown',NaN,'inherited_unknown',NaN, ...
    'nominal_regressions',0,'new_nominal_successes',0, ...
    'certified_candidate_identity_pass',true, ...
    'baseline_median_ms',NaN,'inherited_median_ms',NaN, ...
    'baseline_p95_ms',NaN,'inherited_p95_ms',NaN, ...
    'baseline_max_ms',NaN,'inherited_max_ms',NaN, ...
    'baseline_repeat_max_ms',NaN(2,1), ...
    'inherited_repeat_max_ms',NaN(2,1), ...
    'baseline_repeat_p95_ms',NaN(2,1), ...
    'inherited_repeat_p95_ms',NaN(2,1), ...
    'baseline_repeat_jitter_ms',NaN(2,1), ...
    'inherited_repeat_jitter_ms',NaN(2,1), ...
    'baseline_geometry_ms',NaN(15,1), ...
    'inherited_geometry_ms',NaN(15,1), ...
    'baseline_planes_ms',NaN(15,1), ...
    'inherited_planes_ms',NaN(15,1), ...
    'baseline_full_ms',NaN(15,1), ...
    'inherited_full_ms',NaN(15,1), ...
    'baseline_case_status',{cell(15,1)}, ...
    'inherited_case_status',{cell(15,1)}, ...
    'inherited_shape_node_checks_avoided',0, ...
    'inherited_parent_shape_certs',0, ...
    'inherited_parent_outer_certs',0, ...
    'hlc_unproven_stays_unproven',false, ...
    'p95_under_7ms',false,'max_under_7ms',false, ...
    'result_zip',fullfile(root,[name '_FOR_CHATGPT.zip']));
try
    % Independent geometric monotonicity of the Bernstein convex hull:
    % a subdivision cell's controls are convex combinations of its parent.
    % The all-time 3D support certificate remains true on every child.
    R.stage='PARENT_TO_CHILD_ALL_TIME_CONTAINMENT';
    old_rng=rng;cleaner=onCleanup(@()rng(old_rng)); %#ok<NASGU>
    rng(271828,'twister');
    for k=1:2000
        P=randn(3,24);
        n=randn(3,1);n=n/norm(n);
        [L,U]=TRAJECTORY_C9_BERNSTEIN_MIDPOINT_SPLIT(P);
        parent_min=min(n.'*P);
        % Floating tolerance is used ONLY to assess this NUMERIC test.
        guard=512*eps(max(1,max(abs(P(:)))));
        assert(min(n.'*L)+guard>=parent_min && ...
               min(n.'*U)+guard>=parent_min, ...
            'C9_ANCESTRAL:ConvexHull','Subdivision escaped parent support');
        R.property_test_count=R.property_test_count+1;
    end
    R.property_pass=true;
    R.stage='BASELINE_15_AND_5_REPEAT';
    A=CHECK_TRAJECTORY_C9_WHOLE_FULL_PIPELINE_AUDIT('tight');
    assert(isempty(A.error_message) && startsWith(A.status,'PASS_'), ...
        'C9_ANCESTRAL:Baseline','Status=%s; Error=%s', ...
        A.status,A.error_message);
    R.stage='INHERITED_15_AND_5_REPEAT';
    B=CHECK_TRAJECTORY_C9_WHOLE_FULL_PIPELINE_AUDIT('inherited');
    assert(isempty(B.error_message) && startsWith(B.status,'PASS_') && ...
        A.matrix_count==15 && B.matrix_count==15, ...
        'C9_ANCESTRAL:Audit','Status=%s; Error=%s', ...
        B.status,B.error_message);
    R.baseline_success=A.matrix_nominal_complete_count;
    R.inherited_success=B.matrix_nominal_complete_count;
    R.baseline_unknown=A.matrix_unknown_count;
    R.inherited_unknown=B.matrix_unknown_count;
    R.baseline_median_ms=A.matrix_median_ms;
    R.inherited_median_ms=B.matrix_median_ms;
    R.baseline_p95_ms=A.matrix_p95_ms;
    R.inherited_p95_ms=B.matrix_p95_ms;
    R.baseline_max_ms=A.matrix_max_ms;
    R.inherited_max_ms=B.matrix_max_ms;
    R.baseline_repeat_max_ms=A.native_max_ms;
    R.inherited_repeat_max_ms=B.native_max_ms;
    R.baseline_repeat_p95_ms=A.native_p95_ms;
    R.inherited_repeat_p95_ms=B.native_p95_ms;
    R.baseline_repeat_jitter_ms=A.native_jitter_range_ms;
    R.inherited_repeat_jitter_ms=B.native_jitter_range_ms;
    R.inherited_shape_node_checks_avoided= ...
        B.matrix_ancestral_shape_skips_total;
    R.inherited_parent_shape_certs= ...
        B.matrix_ancestral_shape_certificates_total;
    R.inherited_parent_outer_certs= ...
        B.matrix_ancestor_outer_clearances_total;
    for i=1:15
        a=A.matrix_cases(i);b=B.matrix_cases(i);
        R.baseline_full_ms(i)=a.total_ms;
        R.inherited_full_ms(i)=b.total_ms;
        R.baseline_geometry_ms(i)=a.geometry_force_ms;
        R.inherited_geometry_ms(i)=b.geometry_force_ms;
        R.baseline_planes_ms(i)=a.plane_ms;
        R.inherited_planes_ms(i)=b.plane_ms;
        R.baseline_case_status{i}=a.status;
        R.inherited_case_status{i}=b.status;
        if a.nominal_complete && ~b.nominal_complete
            R.nominal_regressions=R.nominal_regressions+1;
        elseif ~a.nominal_complete && b.nominal_complete
            R.new_nominal_successes=R.new_nominal_successes+1;
        end
        if a.nominal_complete && b.nominal_complete && ...
                ~isequaln(a.certified_piece,b.certified_piece)
            R.certified_candidate_identity_pass=false;
        end
        assert(~a.safe_to_commit&&~b.safe_to_commit, ...
            'C9_ANCESTRAL:Commit','Unproven trajectory cannot be committed.');
    end
    R.hlc_unproven_stays_unproven= ...
        A.hlc_unbound_stays_unproven&&B.hlc_unbound_stays_unproven&& ...
        A.hlc_partial_binding_rejected&&B.hlc_partial_binding_rejected;
    R.p95_under_7ms=isfinite(R.inherited_p95_ms)&& ...
        R.inherited_p95_ms<=7;
    R.max_under_7ms=isfinite(R.inherited_max_ms)&& ...
        R.inherited_max_ms<=7;
    if R.nominal_regressions>0
        R.status='FAIL_CERTIFICATION_REGRESSION__DO_NOT_ENABLE_INHERITANCE';
    elseif ~R.hlc_unproven_stays_unproven
        R.status='FAIL_HLC_UNPROVEN_GATE_CHANGED';
    elseif R.inherited_parent_shape_certs==0 && ...
            R.inherited_shape_node_checks_avoided==0
        R.status='PASS_AB_NO_REGRESSION__INHERITANCE_NOT_EXERCISED';
    elseif R.max_under_7ms
        R.status='PASS_AB_15_CASES_UNDER_7MS__HLC_STILL_UNPROVEN';
    else
        R.status='PASS_AB_NO_REGRESSION__5_TO_7MS_AND_HLC_PENDING';
    end
    R.stage='FINAL_REVIEW';
catch ME
    R.status='FAIL_ANCESTRAL_GEOMETRY_AB';
    R.error_message=ME.message;
end
try
    save(fullfile(root,[name '.mat']),'R');
    fid=fopen(fullfile(root,[name '.txt']),'wt');
    assert(fid>0,'C9_ANCESTRAL:File','Unable to write result text');
    cleanup_text=onCleanup(@()fclose(fid)); %#ok<NASGU>
    fprintf(fid,'status=%s\nstage=%s\nerror=%s\n',R.status,R.stage,R.error_message);
    fprintf(fid,'TARGET normal=5ms heavy=7ms (NO TIME CUTOFF, NO STAGE SPLIT)\n');
    fprintf(fid,'nominal_success old=%g inherited=%g regressions=%d new=%d\n', ...
        R.baseline_success,R.inherited_success,R.nominal_regressions,R.new_nominal_successes);
    fprintf(fid,'median=%.6f %.6f  p95=%.6f %.6f  max=%.6f %.6f\n', ...
        R.baseline_median_ms,R.inherited_median_ms, ...
        R.baseline_p95_ms,R.inherited_p95_ms, ...
        R.baseline_max_ms,R.inherited_max_ms);
    fprintf(fid,'repeat_max_old=%s repeat_max_new=%s\n', ...
        mat2str(R.baseline_repeat_max_ms),mat2str(R.inherited_repeat_max_ms));
    fprintf(fid,'repeat_jitter_old=%s repeat_jitter_new=%s\n', ...
        mat2str(R.baseline_repeat_jitter_ms),mat2str(R.inherited_repeat_jitter_ms));
    fprintf(fid,'inherited_shape_skips=%g parent_shape_certificates=%g parent_outer_clearances=%g\n', ...
        R.inherited_shape_node_checks_avoided,R.inherited_parent_shape_certs, ...
        R.inherited_parent_outer_certs);
    fprintf(fid,'HLC_unproven=%d candidate_identity=%d property=%d\n', ...
        R.hlc_unproven_stays_unproven,R.certified_candidate_identity_pass,R.property_pass);
    for k=1:15
        fprintf(fid,'case%02d old=%.5f new=%.5f geom_old=%.5f geom_new=%.5f status_old=%s status_new=%s\n', ...
            k,R.baseline_full_ms(k),R.inherited_full_ms(k), ...
            R.baseline_geometry_ms(k),R.inherited_geometry_ms(k), ...
            R.baseline_case_status{k},R.inherited_case_status{k});
    end
    clear cleanup_text
    zip(R.result_zip,{[name '.mat'],[name '.txt']},root);
catch ME
    R.status='FAIL_ANCESTRAL_GEOMETRY_RESULT_WRITE';
    R.error_message=ME.message;
end
end
