function R=CHECK_TRIGGER_NOMINAL_COMPLETION()
%CHECK_TRIGGER_NOMINAL_COMPLETION One short completion regression.
% Guarantees scope: ALL times along the sampled piecewise-linear interpolant
% for observed static obstacles. It does NOT certify true ODE integration,
% state-estimation error, real tracking or worst-case runtime.
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'reference','REPLANNING_SYSTEM');
addpath(base,fullfile(base,'FUTURE_COLLISION_TRIGGER'), ...
    fullfile(base,'SIMULATED_OBSTACLE_SENSOR'), ...
    fullfile(base,'OBSTACLE_INFORMATION'));

% A contact at a SAMPLE does not justify omitting the same obstacle from
% the PRECEDING time interval: that would report a late triggering time.
t=[0 1 2];
u=[-1 0 1;0 0 0;0 0 0];
l=u-[0 0 0;0 0 0;2 2 2];
s=ball(901,[0;0;0],0.03);
w=TRIGGER_NOMINAL_SWEPT_INTERVALS(u,l,t,s,0.01,0.01,0.005,[],901);
assert(w.continuous_linear_interpolant_may_intersect && ...
    isequal(w.first_obstacle_ids,901) && w.first_ttc_s==0 && ...
    isequal(w.first_time_bracket_s,[0 1]) && w.all_sampled_ids_swept, ...
    'CHECK_TRIGGER_NOMINAL_COMPLETION:SkippedSampledID', ...
    'The sampled-contact obstacle was incorrectly skipped in the sweep.');
a=struct('first_obstacle_ids',901,'first_ttc_s',1, ...
    'first_sample_index',2,'first_components',{{'UAV'}}, ...
    'new_obstacle_ids',901,'new_ttc_s',1, ...
    'new_sample_index',2,'new_components',{{'UAV'}});
m=TRIGGER_MERGE_EARLIEST_NOMINAL_RISK(a,w,t);
assert(m.has_risk && m.has_new && ...
    isequal(m.selected.ids,901) && m.selected.ttc_s==0 && ...
    isequal(m.selected.bracket_s,[0 1]), ...
    'CHECK_TRIGGER_NOMINAL_COMPLETION:LateRisk', ...
    'A later sample hid an earlier possible contact interval.');

far=ball(902,[20;0;0],0.03);
w2=TRIGGER_NOMINAL_SWEPT_INTERVALS(u,l,t,far,0.01,0.01,0.005,[],[]);
assert(~w2.continuous_linear_interpolant_may_intersect && ...
    isempty(w2.first_obstacle_ids), ...
    'CHECK_TRIGGER_NOMINAL_COMPLETION:Far','False swept risk.');

% A repeating old ID must not hide a later new ID or activate twice.
b=ball(903,[0;0;0],0.03);
w3=TRIGGER_NOMINAL_SWEPT_INTERVALS(u,l,t,[s b],0.01,0.01,0.005,901,[]);
assert(isequal(w3.new_obstacle_ids,903) && ...
    isequal(sort(w3.first_obstacle_ids),[901 903]), ...
    'CHECK_TRIGGER_NOMINAL_COMPLETION:MultiID','Early tie/rearm regression.');

% Production evaluate integration, including changed committed trajectory.
o=OBSTACLE_INFORMATION.define(910,'sphere',[1 0 0],0.04);
zero=[0;0;0];
e=struct('p',zero,'q',zero,'v',zero,'w',zero, ...
    'pL',zero-[0;0;2],'vL',zero, ...
    'pT',[0;0;1],'wL',zero);
auth=struct('runtime',struct('sample_dt_s',0.2, ...
    'r_uav_m',0.01,'r_payload_m',0.01,'r_cable_m',0.005, ...
    'cable_length_m',2,'horizon_s',4), ...
    'payload_mass_kg',1, ...
    'reference_at',@(tt)zeros(28,1), ...
    'predictor',@(req)synthetic_predictor(req,1), ...
    'numeric_tolerances',[1e-7;1e-7]);
frame=struct('time_s',0,'uav_position_ekf_m',zero, ...
    'detected_obstacles',o,'detected_ids',910,'detected_count',1);
C=FUTURE_COLLISION_TRIGGER(struct('horizon_s',4));
x=C.evaluate(0,e,frame,auth);
assert(x.collision_risk_predicted && x.collision_predicted && ...
    x.sampled_collision && x.collision_possible_intersample && ...
    x.new_event && x.collision_obstacle_id==910 && ...
    abs(x.collision_ttc_s-0.8)<1e-11 && ...
    isequal(x.collision_time_bracket_s,[0.8 1]) && ...
    ~x.continuous_observed_set_safe && ~x.safe_to_commit, ...
    'CHECK_TRIGGER_NOMINAL_COMPLETION:Production', ...
    'Production selected the later sampled time or lost risk event.');
x2=C.evaluate(0,e,frame,auth);
assert(~x2.new_event && x2.duplicate_suppressed, ...
    'CHECK_TRIGGER_NOMINAL_COMPLETION:Repeat','Same plan retriggered.');
auth.predictor=@(req)synthetic_predictor(req,-1);
C.set_committed_plan_revision(uint64(1));
x3=C.evaluate(0,e,frame,auth);
assert(x3.prediction_complete && ~x3.collision_risk_predicted && ...
    x3.nominal_interpolant_observed_clear && ...
    strcmp(x3.collision_decision,'NO_CONTACT_IN_NOMINAL_LINEAR_SWEEP'), ...
    'CHECK_TRIGGER_NOMINAL_COMPLETION:ChangedPlan', ...
    'Changed trajectory reused previous trajectory risk.');

R=struct('status','PASS_NOMINAL_CONTINUOUS_INTERPOLANT_TRIGGER', ...
    'cases',6,'failures',0, ...
    'earliest_interval_s',x.collision_time_bracket_s, ...
    'observed_id',x.collision_obstacle_id, ...
    'nominal_interpolant_geometry_proven',true, ...
    'true_ode_continuous_collision_proven',false, ...
    'real_tracking_uncertainty_proven',false, ...
    'worst_case_runtime_proven',false);
save(fullfile(root,'TRIGGER_NOMINAL_COMPLETION_RESULT.mat'),'R');
fid=fopen(fullfile(root,'TRIGGER_NOMINAL_COMPLETION_RESULT.txt'),'w');
assert(fid>0,'CHECK_TRIGGER_NOMINAL_COMPLETION:Save','Cannot open result file.');
clean=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\ncases=%d failures=%d\n',R.status,R.cases,R.failures);
fprintf(fid,'nominal_interpolant=1 true_ODE=0 real_tracking=0 WCET=0\n');
end

function s=ball(id,c,r)
s=struct('id',id,'center0',c,'is_stationary',true, ...
    'bounding_radius_m',r,'rotation',eye(3), ...
    'dimensions',r,'type','sphere');
end

function P=synthetic_predictor(req,direction)
t=req.sample_times_s;
u=req.ekf_now.p+direction*[t;zeros(2,numel(t))];
l=u-[zeros(2,numel(t));repmat(req.cable_length_m,1,numel(t))];
P=struct('sample_times_s',t,'uav_m',u,'payload_m',l, ...
    'model_description','SYNTHETIC_ONLY');
end
