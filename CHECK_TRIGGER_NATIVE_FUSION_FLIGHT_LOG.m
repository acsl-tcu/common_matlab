function R=CHECK_TRIGGER_NATIVE_FUSION_FLIGHT_LOG(logger)
% Read-only, uses EXISTING Sim LOGGER. No sensor/plant/HLC/replanner calls.
assert(isobject(logger)&&isprop(logger,'Data')&& ...
    isfield(logger.Data,'agent')&& ...
    isfield(logger.Data.agent(1).reference,'result'), ...
    'CHECK_TRIGGER_NATIVE_FUSION_FLIGHT_LOG:Logger', ...
    'Pass the existing Sim LOGGER after a completed Flight.');
C=logger.Data.agent(1).reference.result;
if ~iscell(C),C=num2cell(C);end
n=min(double(logger.k),numel(C));
t=nan(n,1);elapsed=t;predwall=t;geomwall=t;refwall=t;
complete=false(n,1); fused=false(n,1);native_absent=false(n,1);
direct_native=false(n,1); legacy_callback=false(n,1);
for k=1:n
    x=C{k};
    if ~isstruct(x)||~isscalar(x),continue;end
    if isfield(x,'trigger_time_ms') && isnumeric(x.trigger_time_ms)
        elapsed(k)=double(x.trigger_time_ms);
    end
    if ~isfield(x,'future_collision_trigger') || ...
            ~isstruct(x.future_collision_trigger),continue;end
    p=x.future_collision_trigger;
    if isfield(p,'time_s'),t(k)=double(p.time_s);end
    if isfield(p,'predictor_dispatch')
        direct_native(k)=strcmp(char(p.predictor_dispatch),'DIRECT_NATIVE_VERIFIED_BINDING');
        legacy_callback(k)=strcmp(char(p.predictor_dispatch),'LEGACY_CALLBACK');
    end
    if isfield(p,'prediction_complete')
        complete(k)=isequal(p.prediction_complete,true);
    end
    if isfield(p,'geometry_native_broadphase_used')
        fused(k)=isequal(p.geometry_native_broadphase_used,true);
    else
        native_absent(k)=true;
    end
    if isfield(p,'predictor_wall_ms')&&isnumeric(p.predictor_wall_ms)
        predwall(k)=double(p.predictor_wall_ms);
    end
    if isfield(p,'predictor_reference_window_ms')&&isnumeric(p.predictor_reference_window_ms)
        refwall(k)=double(p.predictor_reference_window_ms);
    end
    if isfield(p,'geometry_wall_ms')&&isnumeric(p.geometry_wall_ms)
        geomwall(k)=double(p.geometry_wall_ms);
    end
end
R=struct('status','READ_ONLY_FUSION_EXECUTION_TIMING__NOT_SAFETY_PROOF', ...
    'records',n,'complete_prediction_count',nnz(complete), ...
    'direct_native_prediction_count',nnz(complete&direct_native), ...
    'legacy_callback_prediction_count',nnz(complete&legacy_callback), ...
    'missing_dispatch_count',nnz(complete&~direct_native&~legacy_callback), ...
    'native_fusion_used_count',nnz(fused), ...
    'complete_without_fusion_count',nnz(complete&~fused), ...
    'missing_instrumentation_count',nnz(native_absent), ...
    'all_predicting',quantiles(elapsed(complete)), ...
    'native_fused_predicting',quantiles(elapsed(complete&fused)), ...
    'unfused_predicting',quantiles(elapsed(complete&~fused)), ...
    'native_fused_predictor',quantiles(predwall(complete&fused)), ...
    'native_fused_geometry',quantiles(geomwall(complete&fused)), ...
    'future_reference_window',quantiles(refwall(complete)), ...
    'first_flight_sample',struct('time_s',NaN,'trigger_ms',NaN, ...
        'predictor_ms',NaN,'reference_ms',NaN,'geometry_ms',NaN, 'fused',false), ...
    'continuous_time_safe',false);
idx=find(t>=4.95 & complete,1,'first');
if ~isempty(idx)
    R.first_flight_sample=struct('time_s',t(idx), ...
        'trigger_ms',elapsed(idx),'predictor_ms',predwall(idx), ...
        'reference_ms',refwall(idx), ...
        'geometry_ms',geomwall(idx),'fused',fused(idx));
end
root=fileparts(mfilename('fullpath'));
save(fullfile(root,'TRIGGER_NATIVE_FUSION_FLIGHT_LOG.mat'),'R','-v7');
fid=fopen(fullfile(root,'TRIGGER_NATIVE_FUSION_FLIGHT_LOG.txt'),'wt');
if fid>=0
    c=onCleanup(@()fclose(fid)); %#ok<NASGU>
    fprintf(fid,'direct_native=%d legacy_callback=%d missing_dispatch=%d\n', ...
        R.direct_native_prediction_count,R.legacy_callback_prediction_count, ...
        R.missing_dispatch_count);
    fprintf(fid,'status=%s\ncomplete=%d fused=%d without_fusion=%d\n', ...
        R.status,R.complete_prediction_count,R.native_fusion_used_count, ...
        R.complete_without_fusion_count);
    names={'all_predicting','native_fused_predicting', ...
        'unfused_predicting','native_fused_predictor', ...
        'native_fused_geometry','future_reference_window'};
    for j=1:numel(names)
        a=R.(names{j});
        fprintf(fid,'%s n=%d median=%.6f p95=%.6f max=%.6f\n', ...
            names{j},a.n,a.median_ms,a.p95_ms,a.max_ms);
    end
    a=R.first_flight_sample;
    fprintf(fid,'first t=%.6f trigger=%.6f predictor=%.6f reference=%.6f geometry=%.6f fused=%d\n', ...
        a.time_s,a.trigger_ms,a.predictor_ms,a.reference_ms,a.geometry_ms,a.fused);
end
end
function Q=quantiles(a)
a=sort(a(isfinite(a)));
Q=struct('n',numel(a),'median_ms',NaN,'p95_ms',NaN,'max_ms',NaN);
if ~isempty(a)
    Q.median_ms=median(a);
    Q.p95_ms=a(max(1,ceil(.95*numel(a))));
    Q.max_ms=a(end);
end
end
