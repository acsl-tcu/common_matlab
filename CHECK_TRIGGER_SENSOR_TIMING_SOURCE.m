function A=CHECK_TRIGGER_SENSOR_TIMING_SOURCE()
% Fail if new collector and sensor source were not installed together.
A=struct('status','NOT_COMPLETED','reason','','source','');
try
    p=which('SIMULATED_OBSTACLE_SENSOR');
    assert(~isempty(p)&&isfile(p), ...
        'CHECK_TRIGGER_SENSOR_TIMING_SOURCE:Missing','No sensor source.');
    txt=fileread(p);
    assert(contains(txt,'diagnostic_sensor_stage_ms') && ...
        contains(txt,'diagnostic_sensor_exact_calls') && ...
        contains(txt,'REPLANNING_STAGE_TIMING') && ...
        contains(txt,'OBSTACLE_GEOMETRY_QUERY.distance'), ...
        'CHECK_TRIGGER_SENSOR_TIMING_SOURCE:WrongVersion', ...
        'Expected sensor stage instrumentation is not present.');
    q=which('CHECK_TRIGGER_CAPTURE_RUN');
    assert(~isempty(q)&&isfile(q) && ...
        contains(fileread(q),'TRIGGER_DIAG_V3_SENSOR'), ...
        'CHECK_TRIGGER_SENSOR_TIMING_SOURCE:CaptureWrongVersion', ...
        'Install the V3 three-run capture alongside the sensor.');
    A.status='PASS_SENSOR_STAGE_SOURCE_AND_V3_CAPTURE__NOT_RUNTIME';
    A.source=p;
catch ME
    A.status='FAIL_SENSOR_STAGE_SOURCE';
    A.reason=[ME.identifier ': ' ME.message];
end
fid=fopen('TRIGGER_SENSOR_STAGE_SOURCE_RESULT.txt','w');
assert(fid>=0);cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'status=%s\nreason=%s\nsource=%s\n', ...
    A.status,A.reason,A.source);
end
