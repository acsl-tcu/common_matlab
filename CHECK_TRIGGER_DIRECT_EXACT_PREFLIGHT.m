function A=CHECK_TRIGGER_DIRECT_EXACT_PREFLIGHT()
% Disposable common_matlab/ test: actual 7-argument MATLAB method callsite.
% No Flight epoch, no real obstacles, no EKF/plant/current HLC output.
A=struct('status','NOT_RUN','reason','', ...
    'calls',0,'direct_exact_windows',0,'direct_source_calls',0, ...
    'contract_rejections',0,'reused_exact_columns',0, ...
    'preserved_live_epoch',false);
try
    mock=struct('estimator',struct('result',struct('state',struct())));
    N=TIME_VARYING_REFERENCE(mock, ...
        {'TRIGGER_SOFTWARE_FIXTURE_REFERENCE_FACTORY',{}});
    fn=N.func;
    old_epoch=N.t;
    audit=TRIGGER_TIME_ONLY_PURITY(fn);
    assert(audit.eligible, ...
        'CHECK_TRIGGER_DIRECT_EXACT_PREFLIGHT:Purity', ...
        'Pre-arm synthetic source is not eligible.');
    P=TRIGGER_TIMEONLY_SOURCE_PREPARE(fn,audit, ...
        struct('nominal',N,'sample_dt_s',0.025,'horizon_s',4, ...
            'cable_length_m',2));
    A.calls=P.calls;
    A.direct_exact_windows=P.direct_exact_windows;
    A.direct_source_calls=P.direct_source_calls;
    A.contract_rejections=P.contract_rejections;
    A.reused_exact_columns=P.reused_exact_columns;
    A.preserved_live_epoch=isequaln(N.t,old_epoch) && ...
        ~P.used_flight_start && ~P.stored_reference_values;
    assert(startsWith(P.status,'PASS_REAL_SOURCE_DIRECT_EXACT') && ...
        A.calls==8 && A.direct_exact_windows==16 && ...
        A.direct_source_calls>0 && A.contract_rejections==0 && ...
        A.reused_exact_columns>0 && A.preserved_live_epoch, ...
        'CHECK_TRIGGER_DIRECT_EXACT_PREFLIGHT:Coverage', ...
        'The production direct-exact reference path was not fully covered.');
    A.status='PASS_PRODUCTION_SIGNATURE_DIRECT_EXACT_SYNTHETIC__NOT_JIT_PROOF';
catch ME
    A.status='NOT_COMPLETED_PRODUCTION_SIGNATURE_DIRECT_EXACT';
    A.reason=[ME.identifier ' | ' ME.message];
end
save('TRIGGER_DIRECT_EXACT_PREFLIGHT_RESULT.mat','A');
f=fopen('TRIGGER_DIRECT_EXACT_PREFLIGHT_RESULT.txt','w');
if f>=0
    fprintf(f,'status=%s\ncalls=%d\ndirect_windows=%d\ndirect_source_calls=%d\nrejections=%d\nreused_columns=%d\nlive_epoch_untouched=%d\nreason=%s\n', ...
        A.status,A.calls,A.direct_exact_windows,A.direct_source_calls, ...
        A.contract_rejections,A.reused_exact_columns, ...
        A.preserved_live_epoch,A.reason);
    fclose(f);
end
end
