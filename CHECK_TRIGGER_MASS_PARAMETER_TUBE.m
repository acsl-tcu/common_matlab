function A=CHECK_TRIGGER_MASS_PARAMETER_TUBE()
% Synthetic indexing and arbitrary hold-timing test, not a mass proof.
A=struct('status','NOT_RUN_MASS_PARAMETER_TUBE','reason','', ...
    'mass_index20_correct',false,'other_parameters_unchanged',false, ...
    'variable_hold_duration_accepted',false,'no_safety_grant',false);
try
    t=[9.173 9.190 9.221 9.261];n=numel(t)-1;
    lo=repmat((1:21).',1,n);hi=lo;
    lo(20,:)=NaN;hi(20,:)=NaN; % no point-mass fallback
    C=struct('time_grid_s',t,'true_mass_lower_kg',[0.35 0.4 0.45], ...
        'true_mass_upper_kg',[0.5 0.6 0.7], ...
        'other_param_lower',lo,'other_param_upper',hi);
    Q=TRIGGER_MASS_PARAMETER_TUBE(C);
    A.mass_index20_correct=Q.conditional_parameter_box && ...
        isequal(Q.parameter_lower(20,:),C.true_mass_lower_kg) && ...
        isequal(Q.parameter_upper(20,:),C.true_mass_upper_kg);
    idx=[1:19 21];
    A.other_parameters_unchanged= ...
        isequal(Q.parameter_lower(idx,:),lo(idx,:)) && ...
        isequal(Q.parameter_upper(idx,:),hi(idx,:));
    A.variable_hold_duration_accepted=any(diff(t)~=diff(t(1:2)));
    A.no_safety_grant=~Q.safe_to_commit && ...
        ~Q.true_mass_source_proven && ~Q.future_parameter_refresh_proven;
    assert(A.mass_index20_correct&&A.other_parameters_unchanged&& ...
        A.variable_hold_duration_accepted && A.no_safety_grant, ...
        'CHECK_TRIGGER_MASS_PARAMETER_TUBE:WrongContract');
    A.status='PASS_PER_HOLD_MASS_PARAM20_MAPPING__NOT_PHYSICAL_PROOF';
catch ME
    A.reason=[ME.identifier ' | ' ME.message];
end
save('TRIGGER_MASS_PARAMETER_TUBE_RESULT.mat','A');
f=fopen('TRIGGER_MASS_PARAMETER_TUBE_RESULT.txt','w');
if f>=0
    fprintf(f,'status=%s\nmass_index20_correct=%d\nother_parameters_unchanged=%d\nvariable_hold_duration_accepted=%d\nno_safety_grant=%d\nreason=%s\n', ...
        A.status,A.mass_index20_correct,A.other_parameters_unchanged, ...
        A.variable_hold_duration_accepted,A.no_safety_grant,A.reason);
    fclose(f);
end
end
