function R=CHECK_TRAJECTORY_ANALYTIC_SOLVER(run_real_solver)
%CHECK_TRAJECTORY_ANALYTIC_SOLVER Analytic NLP derivative + real fmincon audit.
% Place at common_matlab root. Does NOT modify HLC, plant, trigger or flight.
% run_real_solver defaults true. Pass false to check derivatives only.
% All distances, actuator-independent bounds and samples below are SYNTHETIC
% TEST FIXTURE VALUES, never defaults for the flight planner.
if nargin<1,run_real_solver=true;end
assert(isscalar(run_real_solver)&& ...
    (islogical(run_real_solver)||isnumeric(run_real_solver))&& ...
    (run_real_solver==0||run_real_solver==1), ...
    'CHECK_TRAJECTORY_ANALYTIC_SOLVER:Argument','Use 0 or 1.');
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'reference','REPLANNING_SYSTEM');
addpath(fullfile(base,'TRAJECTORY_GENERATION'), ...
    fullfile(base,'OBSTACLE_INFORMATION'));
assert(exist('TRAJECTORY_C7_NLP_ANALYTIC','file')==2&& ...
    exist('TRAJECTORY_SIMULTANEOUS_C7_SEARCH','file')==2, ...
    'CHECK_TRAJECTORY_ANALYTIC_SOLVER:Source','Install the patched source first.');
% A moving, straight, taut synthetic segment is feasible; nonlinear
% constraint gradients are tested at slightly perturbed free controls.
q=fixture();
q.candidate_feasibility.derivative_limits.uav.derivative_norm_max= ...
    [5 100 1000 1e6 1e8 1e10];
q.candidate_feasibility.derivative_limits.payload.derivative_norm_max= ...
    [5 100 1000 1e6 1e8 1e10];
% Capture the exact synthetic fixture, not a mutable closure of q.
q_for_audit=q;
q.solver_function=@(F,z0,N,opts)gradient_adapter(F,z0,N,opts,q_for_audit);
G=TRAJECTORY_GENERATOR(struct('ROBUST_TUBE_ENABLED',false));
A=G.search_reference_feasible_candidate(q);
assert(strcmp(A.status,'UNKNOWN_OPTIMIZER_FAILED')&&~A.safe_to_commit&& ...
    isfield(A.solve_output,'gradient_rel_error')&& ...
    isfield(A.solve_output,'support_checks'), ...
    'CHECK_TRAJECTORY_ANALYTIC_SOLVER:Adapter','Gradient adapter not reached.');
assert(A.solve_output.gradient_rel_error<2e-3 && ...
    A.solve_output.objective_rel_error<1e-6 && ...
    A.solve_output.support_max_error<1e-8, ...
    'CHECK_TRAJECTORY_ANALYTIC_SOLVER:Gradient', ...
    ['Differentiable analytic Jacobian failed: geometry=%.6g, ' ...
     'kinematics=%.6g, unit normals=%.6g; objective=%.6g.'], ...
    A.solve_output.geometry_rel_error, ...
    A.solve_output.kinematic_rel_error, ...
    A.solve_output.equality_rel_error, ...
    A.solve_output.objective_rel_error);
R=struct('status','PASS_ANALYTIC_GRADIENTS__REAL_SOLVER_NOT_RUN', ...
    'gradient_rel_error',A.solve_output.gradient_rel_error, ...
    'objective_rel_error',A.solve_output.objective_rel_error, ...
    'support_max_error',A.solve_output.support_max_error, ...
    'support_checks',A.solve_output.support_checks, ...
    'geometry_rel_error',A.solve_output.geometry_rel_error, ...
    'kinematic_rel_error',A.solve_output.kinematic_rel_error, ...
    'equality_rel_error',A.solve_output.equality_rel_error, ...
    'nonsmooth_rows_excluded',A.solve_output.nonsmooth_rows_excluded, ...
    'geometry_rows',A.geometry_inequality_count, ...
    'derivative_rows',A.kinematic_inequality_count, ...
    'real_solver_status','NOT_RUN', 'real_solver_ms',NaN, ...
    'real_solver_exitflag',NaN, ...
    'real_safe_case_certified',false,'real_collision_case_certified',false, ...
    'collision_search_status','NOT_RUN', ...
    'collision_search_ms',NaN,'safe_to_commit',false);
if run_real_solver
    if exist('fmincon','file')~=2
        R.real_solver_status='FMINCON_NOT_AVAILABLE';
    else
        q=rmfield(q,'solver_function');
        % Real Optimization Toolbox is called, NOT an identity adapter.
        q.solver_options=optimoptions('fmincon','Algorithm','sqp', ...
            'Display','off','MaxIterations',30, ...
            'MaxFunctionEvaluations',1000);
        result=G.search_reference_feasible_candidate(q);
        R.real_solver_status=result.status;
        R.real_solver_ms=result.elapsed_ms;
        R.real_solver_exitflag=result.solve_exitflag;
        R.real_safe_case_certified=result.certified_geometry && ...
            result.candidate_available && ~result.safe_to_commit;
        % Report a second genuinely colliding original, not a scripted
        % success. This can FAIL: nonconvex local NLP is not globally
        % complete, nor is any result dynamics certified.
        q.observed=OBSTACLE_INFORMATION.define(71,'sphere',[1;0;-1],0.19);
        result2=G.search_reference_feasible_candidate(q);
        R.collision_search_status=result2.status;
        R.collision_search_ms=result2.elapsed_ms;
        R.real_collision_case_certified=result2.certified_geometry && ...
            result2.candidate_available && ~result2.safe_to_commit;
    end
end
if run_real_solver
    if strcmp(R.real_solver_status,'FMINCON_NOT_AVAILABLE')
        R.status='PASS_GRADIENTS__REAL_FMINCON_NOT_AVAILABLE';
    else
        if R.real_safe_case_certified
            R.status='PASS_GRADIENTS_AND_REAL_SAFE_NLP__DYNAMICS_PENDING';
        else
            R.status='PASS_GRADIENTS__REAL_FMINCON_FAILED_SAFE_CASE';
        end
    end
end
save(fullfile(root,'TRAJECTORY_ANALYTIC_SOLVER_RESULT.mat'),'R');
fid=fopen(fullfile(root,'TRAJECTORY_ANALYTIC_SOLVER_RESULT.txt'),'wt');
assert(fid>0,'CHECK_TRAJECTORY_ANALYTIC_SOLVER:Output','Unable to save audit.');
cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\n',R.status);
fprintf(fid,'analytic gradient relative error=%.6g objective=%.6g support=%.6g (%d shape checks)\n', ...
    R.gradient_rel_error,R.objective_rel_error, ...
    R.support_max_error,R.support_checks);
fprintf(fid,'rows: geometry=%d kinematics=%d\n', ...
    R.geometry_rows,R.derivative_rows);
fprintf(fid,'gradient breakdown: geometry=%.6g kinematics=%.6g normals=%.6g, nonsmooth rows=%d\n', ...
    R.geometry_rel_error,R.kinematic_rel_error, ...
    R.equality_rel_error,R.nonsmooth_rows_excluded);
fprintf(fid,'real fmincon: %s | elapsed=%.6g ms | exitflag=%.6g\n', ...
    R.real_solver_status,R.real_solver_ms,R.real_solver_exitflag);
fprintf(fid,'real safe-case accepted=%d | colliding-original certified=%d\n', ...
    R.real_safe_case_certified,R.real_collision_case_certified);
fprintf(fid,'colliding original: %s | elapsed=%.6g ms\n', ...
    R.collision_search_status,R.collision_search_ms);
fprintf(fid,'HLC commit: FORBIDDEN; dynamics: NOT CERTIFIED\n');
end
function q=fixture()
U=zeros(3,8);L=zeros(3,8);L(3,1)=-2;
U(1,2)=1;L(1,2)=1;
V=U;W=L;V(1,1)=2;W(1,1)=2;
q=struct('t0_s',0,'duration_s',2, ...
    'start_jets',struct('uav',U,'payload',L), ...
    'end_jets',struct('uav',V,'payload',W), ...
    'nominal_free',struct('uav',zeros(3,8), ...
        'payload',zeros(3,8)), ...
    'observed',[ ...
        OBSTACLE_INFORMATION.define(41,'sphere',[0 4 0],0.2), ...
        OBSTACLE_INFORMATION.define(43,'ellipsoid',[0 -4 0],[0.3 0.6 1], ...
            'euler_deg',[15 28 52])], ...
    'physical_radii',struct('uav_m',0.05, ...
        'payload_m',0.05,'cable_m',0.01), ...
    'proof_options',struct('robust_tube_enabled',false, ...
        'min_separation_m',0.02,'numerical_guard_m',1e-10, ...
        'max_subdivision_depth',3), ...
    'search_options',struct('time_leaf_depth',1, ...
        'max_constraint_rows',1000,'max_leaf_count',2, ...
        'feasibility_tolerance',1e-7,'endpoint_jet_tolerance',1e-6), ...
    'solver_options',struct());
for j=1:8
    q.nominal_free.uav(1,j)=2*(j+7)/23;
    q.nominal_free.payload(:,j)=q.nominal_free.uav(:,j)+[0;0;-2];
end
entry=struct('ekf_now',struct('p',U(:,1),'v',U(:,2), ...
    'pL',L(:,1),'vL',L(:,2)), 'cable_length_m',2, ...
    'position_tolerance_m',1e-8, ...
    'velocity_tolerance_mps',1e-8, ...
    'cable_length_tolerance_m',1e-8, ...
    'cable_length_rate_tolerance_mps',1e-8);
q.candidate_feasibility=struct('derivative_limits',struct( ...
    'uav',struct('derivative_norm_max',[5 10 100 1000 1e5 1e7]), ...
    'payload',struct('derivative_norm_max',[5 10 100 1000 1e5 1e7])), ...
    'entry',entry,'heading_options',struct( ...
    'max_subdivision_depth',2,'numerical_guard_mps',1e-10));
end
function [z,exitflag,output]=gradient_adapter(F,z0,G,~,request)
% Check ALL optimization variables, including 3D separating planes.
% The prior audit differentiated c = ||D|| - limit. In this fixture,
% limit(6) is 1e10, so differences of two nearly equal 1e10 numbers
% lose significant digits; the ~1e-6 finite difference was NOT a valid
% reference for the analytic Jacobian. Keep the production function and
% feasibility limits unchanged. Verify the unshifted norms independently
% by complex-step differentiation at smooth points.
z=z0(:);
z(2)=z(2)+0.14;z(6)=z(6)+0.04;
z(28)=z(28)+0.09;z(42)=z(42)-0.06;
% Generic test-only perturbation avoids many accidental zero-norm kinks.
i=(1:48).';
z(1:48)=z(1:48)+0.005*sin(0.73*i)+0.003*cos(0.19*i);
[f,g]=F(z); %#ok<ASGLU>
[c,ceq,GC,GE]=G(z);
assert(isequal(size(GC),[numel(z),numel(c)])&& ...
    isequal(size(GE),[numel(z),numel(ceq)])&& ...
    all(isfinite([c(:);ceq(:);GC(:);GE(:);g(:)])), ...
    'CHECK_TRAJECTORY_ANALYTIC_SOLVER:Shape', ...
    'Jacobian dimensions/nonfinite values.');
% Shape support point / support value identity for all 12 types.
obs=all_shapes();S=TRAJECTORY_OBSTACLE_SUPPORT.prepare(obs);
n=[0.43;-0.71;0.92];sh_error=0;
for j=1:numel(S)
    [h,p]=TRAJECTORY_OBSTACLE_SUPPORT.value_and_point(S(j),n);
    ref=TRAJECTORY_OBSTACLE_SUPPORT.value(S(j),n);
    sh_error=max(sh_error,abs(h-ref));
    sh_error=max(sh_error,abs(h-n.'*p));
end

ngeo=96*numel(request.observed)*2^request.search_options.time_leaf_depth;
assert(ngeo<numel(c) && numel(ceq)== ...
    3*numel(request.observed)*2^request.search_options.time_leaf_depth, ...
    'CHECK_TRAJECTORY_ANALYTIC_SOLVER:Layout', ...
    'Unexpected constraint layout: audit needs updating.');
[baseU,baseL]=audit_base_controls(request);
leaf_maps=audit_leaf_maps(request.search_options.time_leaf_depth);
[unshifted,limit_vector]=audit_kinematic_raw(z,baseU,baseL, ...
    leaf_maps,request.duration_s,request.candidate_feasibility.derivative_limits);
assert(numel(unshifted)==numel(c)-ngeo && ...
    numel(limit_vector)==numel(unshifted) && ...
    all(isfinite(unshifted(:))) && ...
    max(abs(c(ngeo+1:end)-(unshifted-limit_vector))./ ...
        max(1,abs(limit_vector)))<1e-12, ...
    'CHECK_TRAJECTORY_ANALYTIC_SOLVER:RawNorm', ...
    'Independent raw kinematic values disagree with solver constraints.');

% Norm is nondifferentiable at zero. Only differentiable nonzero points
% have a unique derivative; at zero, the solver uses a valid subgradient.
% Verify all of those zero-point Jacobian rows are exactly zero in this
% fixture (their free-control coefficients vanish at constrained ends).
smooth=real(unshifted)>1e-6;  % TEST-ONLY threshold, not a flight/solver bound
if any(~smooth)
    assert(max(max(abs(GC(:,ngeo+find(~smooth)))))<1e-7, ...
        'CHECK_TRAJECTORY_ANALYTIC_SOLVER:ZeroNorm', ...
        'Unexpected nonzero derivative at zero-norm test rows.');
end
err_geometry=0;err_kinematic=0;err_equalities=0;err_objective=0;
for v=1:numel(z)
    % Only geometry and unit-normal equalities use ordinary central FD:
    % their magnitudes are of order metres, not 1e10-offset controls.
    step=1e-6*max(1,abs(z(v)));
    plus=z;minus=z;plus(v)=plus(v)+step;minus(v)=minus(v)-step;
    [cp,eqp]=G(plus);[cm,eqm]=G(minus);
    num_geo=(cp(1:ngeo)-cm(1:ngeo))/(2*step);
    num_eq=(eqp-eqm)/(2*step);
    err_geometry=max(err_geometry,max(abs(GC(v,1:ngeo).'-num_geo)./ ...
        max(1,abs(num_geo))));
    err_equalities=max(err_equalities,max(abs(GE(v,:).'-num_eq)./ ...
        max(1,abs(num_eq))));
    [fp,~]=F(plus);[fm,~]=F(minus);
    err_objective=max(err_objective,abs(g(v)-(fp-fm)/(2*step))/ ...
        max(1,abs(g(v))));

    % Complex-step of the UN-SUBTRACTED kinematic norm; no 1e10
    % cancellation and no differencing of two near-identical large bounds.
    % sqrt(sum(D.^2)) is the analytic extension of Euclidean norm when
    % D is real and nonzero; do not use norm(), which conjugates D.
    complex_z=complex(z);
    complex_step=1e-20;
    complex_z(v)=complex_z(v)+1i*complex_step;
    raw_plus=audit_kinematic_raw(complex_z,baseU,baseL, ...
        leaf_maps,request.duration_s, ...
        request.candidate_feasibility.derivative_limits);
    num_kin=imag(raw_plus)/complex_step;
    a_kin=GC(v,ngeo+1:end).';
    if any(smooth)
        err_kinematic=max(err_kinematic,max( ...
            abs(a_kin(smooth)-num_kin(smooth))./ ...
            max(1,abs(num_kin(smooth)))));
    end
end
err=max([err_geometry,err_kinematic,err_equalities]);
output=struct('gradient_rel_error',err, ...
    'geometry_rel_error',err_geometry, ...
    'kinematic_rel_error',err_kinematic, ...
    'equality_rel_error',err_equalities, ...
    'nonsmooth_rows_excluded',sum(~smooth), ...
    'objective_rel_error',err_objective, ...
    'support_max_error',sh_error,'support_checks',numel(S), ...
    'raw_constraint_count',numel(c),'identity_solver',false);
exitflag=-2; % Test adapter NEVER returns a candidate for HLC commitment.
end

function [U,L]=audit_base_controls(q)
% Independent construction of fixed endpoint controls for the test case.
U=TRAJECTORY_C7_FREE_BERNSTEIN.build(q.t0_s,q.duration_s, ...
    q.start_jets.uav,q.end_jets.uav,q.nominal_free.uav);
L=TRAJECTORY_C7_FREE_BERNSTEIN.build(q.t0_s,q.duration_s, ...
    q.start_jets.payload,q.end_jets.payload,q.nominal_free.payload);
U=U.control_points_m;L=L.control_points_m;
end

function leaves=audit_leaf_maps(depth)
% de Casteljau subdivision matrices, evaluated independently in the test.
leaves={eye(24)};
for d=1:depth
    nxt=cell(1,2*numel(leaves));
    for k=1:numel(leaves)
        Q=leaves{k};A=zeros(size(Q));B=zeros(size(Q));
        width=size(Q,2);A(:,1)=Q(:,1);B(:,end)=Q(:,end);
        for j=2:width
            Q=0.5*Q(:,1:end-1)+0.5*Q(:,2:end);
            A(:,j)=Q(:,1);B(:,width-j+1)=Q(:,end);
        end
        nxt{2*k-1}=A;nxt{2*k}=B;
    end
    leaves=nxt;
end
end

function [raw,bound]=audit_kinematic_raw(z,baseU,baseL,leaf_maps,T,limits)
% Numeric fixture evaluator without subtracting the large upper limits.
% Supports a complex z ONLY for complex-step gradient checking.
U=complex(baseU);L=complex(baseL);
U(:,9:16)=reshape(z(1:24),3,8);
L(:,9:16)=reshape(z(25:48),3,8);
raw=complex(zeros(246*numel(leaf_maps),1));
bound=zeros(numel(raw),1);idx=0;
for k=1:numel(leaf_maps)
    M=leaf_maps{k};dt=T/numel(leaf_maps);
    for b=1:2
        if b==1
            D=U*M; maxima=limits.uav.derivative_norm_max(:);
        else
            D=L*M; maxima=limits.payload.derivative_norm_max(:);
        end
        for order=1:6
            D=((24-order)/dt)*diff(D,1,2);
            mag=sqrt(sum(D.^2,1)); % NONCONJUGATE for complex-step
            ids=idx+(1:numel(mag));
            raw(ids)=mag(:);
            bound(ids)=maxima(order);
            idx=idx+numel(mag);
        end
    end
end
assert(idx==numel(raw),'CHECK_TRAJECTORY_ANALYTIC_SOLVER:Rows', ...
    'Kinematic row mismatch.');
end
