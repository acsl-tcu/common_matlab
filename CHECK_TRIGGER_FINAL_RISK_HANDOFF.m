function R=CHECK_TRIGGER_FINAL_RISK_HANDOFF()
% Dynamic, observed-only risk/events regression. No physical SAFE is faked.
R=struct('status','FAIL_FINAL_RISK_HANDOFF','cases',0,'failures',0, ...
    'unresolved_witnesses',0,'duplicate_suppression_witnesses',0, ...
    'revision_rearm_witnesses',0,'reason','');
try
    S=struct('plan_revision',uint64(0),'announced_ids',zeros(1,0));
    n=struct('status','UNKNOWN_CONTINUOUS_INTERVAL_OR_MODEL', ...
        'new_event_ids',zeros(1,0), ...
        'first_sampled_collision_ttc_s',NaN, ...
        'safe_to_commit',true); % Attempted proof-by-boolean must fail.
    [a,S]=TRIGGER_UNRESOLVED_EVENT_HANDOFF([],n,S,4,true,true);
    check(strcmp(a.status,'NO_OBSERVED_OBSTACLES__UNSEEN_WORLD_UNKNOWN') ...
        && ~a.safe_to_commit && ~a.physical_4s_clear_certified && ...
        ~a.request_trajectory_candidate, 'empty observed set');
    [a,S]=TRIGGER_UNRESOLVED_EVENT_HANDOFF([8 3],n,S,4,true,true);
    check(isequal(a.new_candidate_request_ids,[8 3]) && ...
        isequal(a.possibly_at_risk_ids,[8 3]) && ...
        isequal(a.possible_ttc_interval_s,[0 4]) && ...
        ~a.safe_to_commit && a.request_trajectory_candidate, ...
        'first observed unknown not notified');
    R.unresolved_witnesses=R.unresolved_witnesses+2;
    [a,S]=TRIGGER_UNRESOLVED_EVENT_HANDOFF([8 3],n,S,4,true,true);
    check(~a.request_trajectory_candidate && ...
        isequal(S.announced_ids,[8 3]),'unknown duplicate');
    R.duplicate_suppression_witnesses=R.duplicate_suppression_witnesses+1;
    n.new_event_ids=3;n.first_sampled_collision_ttc_s=1.75;
    [a,S]=TRIGGER_UNRESOLVED_EVENT_HANDOFF([8 3],n,S,4,true,true);
    check(isequal(a.new_nominal_event_ids,3) && ...
        isequal(a.nominal_escalation_ids,3) && ...
        ~a.request_trajectory_candidate && ...
        isequal(a.nominal_first_sampled_ttc_s,1.75), ...
        'nominal escalation should not replan same ID and revision');
    n.new_event_ids=[];n.first_sampled_collision_ttc_s=NaN;
    [a,S]=TRIGGER_UNRESOLVED_EVENT_HANDOFF([8 3 17],n,S,4,true,true);
    check(isequal(a.new_candidate_request_ids,17) && ...
        isequal(a.possibly_at_risk_ids,[8 3 17]), ...
        'new detected ID must be emitted independently');
    S.plan_revision=uint64(1);S.announced_ids=zeros(1,0);
    [a,S]=TRIGGER_UNRESOLVED_EVENT_HANDOFF([8 3 17],n,S,4,true,true);
    check(isequal(a.new_candidate_request_ids,[8 3 17]) && ...
        a.plan_revision==uint64(1),'new plan revision must rearm same IDs');
    R.revision_rearm_witnesses=R.revision_rearm_witnesses+3;
    [a,S2]=TRIGGER_UNRESOLVED_EVENT_HANDOFF([8 3 17],n,S,4,false,true);
    check(~a.request_trajectory_candidate && ...
        isequal(S,S2),'nonflight must not change history');
    [a,S2]=TRIGGER_UNRESOLVED_EVENT_HANDOFF([8 3 17],n,S,4,true,false);
    check(~a.request_trajectory_candidate && ...
        ~a.safe_to_commit && isequal(S,S2), ...
        'disabled sensor must fail closed and not issue geometry event');
    [a,S2]=TRIGGER_UNRESOLVED_EVENT_HANDOFF([8 8],n,S,4,true,true);
    check(strcmp(a.status,'UNKNOWN_HANDOFF_INVALID_INPUT') && ...
        ~a.safe_to_commit && ~a.request_trajectory_candidate && ...
        isequal(S,S2), 'duplicate sensor ID must fail closed');
    [a,S2]=TRIGGER_UNRESOLVED_EVENT_HANDOFF([8 3], ...
        struct('new_event_ids',77),S,4,true,true);
    check(strcmp(a.status,'UNKNOWN_HANDOFF_INVALID_INPUT') && ...
        isequal(S,S2) && ~a.safe_to_commit, ...
        'nonobserved nominal ID must fail closed');
    rng(148221,'twister');
    for k=1:800
        % Different observation sequences; never precompute ID masks.
        ids=randperm(400,randi([1 20]));
        n=struct('new_event_ids',zeros(1,0),'status','UNKNOWN');
        S0=struct('plan_revision',uint64(k), ...
            'announced_ids',zeros(1,0));
        [a,S1]=TRIGGER_UNRESOLVED_EVENT_HANDOFF(ids,n,S0,4,true,true);
        check(isequal(a.possibly_at_risk_ids,ids) && ...
            isequal(a.new_candidate_request_ids,ids) && ...
            isequal(S1.announced_ids,ids) && ...
            ~a.physical_4s_clear_certified && ~a.safe_to_commit, ...
            'random actual observed IDs');
        [b,S2]=TRIGGER_UNRESOLVED_EVENT_HANDOFF(ids,n,S1,4,true,true);
        check(~b.request_trajectory_candidate && ...
            isequal(S1,S2) && ...
            isequal(b.possibly_at_risk_ids,ids), ...
            'random stable repeated frame');
    end
    R.status='PASS_OBSERVED_ONLY_CONSERVATIVE_HANDOFF__PHYSICAL_SAFE_NOT_PROVEN';
    R.reason=['New ID and plan-revision candidate requests deduplicated; ' ...
        'nominal sample-contact escalation preserved without replan loops; ' ...
        'UNKNOWN never upgraded to SAFE or authorized to commit.'];
catch ME
    R.failures=R.failures+1;
    R.reason=[ME.identifier ' | ' ME.message];
end
    try
        save('TRIGGER_FINAL_RISK_HANDOFF_RESULT.mat','R');
        f=fopen('TRIGGER_FINAL_RISK_HANDOFF_RESULT.txt','w');
        if f>=0
            fprintf(f,'%s\ncases=%d failures=%d\n%s\n', ...
                R.status,R.cases,R.failures,R.reason);
            fclose(f);
        end
    catch
    end
    function check(ok,description)
        R.cases=R.cases+1;
        assert(ok,'CHECK_TRIGGER_FINAL_RISK_HANDOFF:Parity',description);
    end
end
