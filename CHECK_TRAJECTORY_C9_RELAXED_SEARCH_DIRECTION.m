function R=CHECK_TRAJECTORY_C9_RELAXED_SEARCH_DIRECTION()
% Pure mathematical audit: this module is NOT an obstacle certificate.
% No external obstacle, geometry or trajectory fixture is used to tune
% the search direction. Contradictory local halfspaces exercise a genuine
% failure mode of the original hard-QP search.
A=zeros(12,3);A(1,1)=1;A(1,2)=-1;A(2,3)=1;
b=[1;0.4;1];
[x,S]=TRAJECTORY_C9_RELAXED_SEARCH_DIRECTION(A,b,100);
% For 0.4 >=? The x1 constraints are x1>=1 and x1<=-0.4:
% least-squares residual optimum x1=(1-0.4)/2=0.3, x2=1.
R=struct('status','FAIL_MATH', ...
    'contradictory_hard_planes_tested',true, ...
    'constrained_QP_not_claimed',~S.linearized_feasibility_proven, ...
    'relaxed_search_direction_found',S.direction_available, ...
    'analytic_solution_max_abs_error',max(abs(x(1:2)-[0.3;1])), ...
    'untrusted_trajectory_status',~S.safe_to_commit, ...
    'permutation_max_abs_error',NaN, ...
    'rotation_max_abs_error',NaN, ...
    'no_improvement_returns_unknown',false, ...
    'no_fixed_obstacle_directions',true);
[perm,~]=TRAJECTORY_C9_RELAXED_SEARCH_DIRECTION( ...
    A(:,[3 1 2]),b([3 1 2]),100);
R.permutation_max_abs_error=max(abs(x-perm));
angle=0.47;
Q=eye(12);Q(1:2,1:2)=[cos(angle) -sin(angle);sin(angle) cos(angle)];
[xrot,~]=TRAJECTORY_C9_RELAXED_SEARCH_DIRECTION(Q*A,b,100);
R.rotation_max_abs_error=max(abs(xrot-Q*x));
[zero,Z]=TRAJECTORY_C9_RELAXED_SEARCH_DIRECTION( ...
    zeros(12,2),[1;2],20);
R.no_improvement_returns_unknown= ...
    ~Z.direction_available&&~Z.safe_to_commit&&all(zero==0);
assert(R.constrained_QP_not_claimed&&R.relaxed_search_direction_found&& ...
    R.analytic_solution_max_abs_error<1e-8&& ...
    R.permutation_max_abs_error<1e-8&& ...
    R.rotation_max_abs_error<1e-8&& ...
    R.no_improvement_returns_unknown&&R.untrusted_trajectory_status, ...
    'CHECK_C9_RELAXED:Math', ...
    'A relaxed search direction is not a full-time certificate.');
R.status='PASS_RELAXED_CONVEX_PROBE_MATH__NOT_TRAJECTORY_PROOF';
end
