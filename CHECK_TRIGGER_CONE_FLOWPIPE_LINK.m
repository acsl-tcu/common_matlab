function A=CHECK_TRIGGER_CONE_FLOWPIPE_LINK()
% Disposable root CHECK. Synthetic fixture for geometry only.
% Does NOT replace an audited plant/EKF/controller proof.
A=struct('status','NOT_RUN','reason','', ...
    'far_separated',false,'near_rejected',false, ...
    'invalid_mass_rejected',false,'intervals',0, ...
    'safe_to_commit',false);
try
    K=2;
    F=struct('conditional_chain_pass',true, ...
        'completed_intervals',K,'tension_lower_N',ones(1,K), ...
        'conditional_tension_positive_all_intervals',true, ...
        'manifold_compatible_intervals',true(1,K), ...
        'tube_lower',zeros(24,K), ...
        'tube_upper',zeros(24,K), ...
        'endpoint_lower',zeros(24,K+1), ...
        'endpoint_upper',zeros(24,K+1));
    F.tube_lower(19:21,:) = repmat([0;0;-1],1,K);
    F.tube_upper(19:21,:) = F.tube_lower(19:21,:);
    F.endpoint_lower(19:21,:) = repmat([0;0;-1],1,K+1);
    F.endpoint_upper(19:21,:) = F.endpoint_lower(19:21,:);
    F.tube_lower(13:15,:)=repmat([0;0;-2],1,K);
    F.tube_upper(13:15,:)=F.tube_lower(13:15,:);
    F.endpoint_lower(13:15,:)=repmat([0;0;-2],1,K+1);
    F.endpoint_upper(13:15,:)=F.endpoint_lower(13:15,:);
    P=zeros(21,K);P(20,:)=0.5;P(21,:)=2;
    sh=struct('id',70001,'center0',[9;0;0], ...
        'rotation',eye(3),'dimensions',0.5, ...
        'type','sphere','is_stationary',true);
    sh2=sh;
    sh2.id=70002;
    sh2.center0=[7;4;0];
    sh2.dimensions=[1;0.5;0.8];
    sh2.type='ellipsoid';
    phi=pi/6;
    sh2.rotation=[cos(phi) -sin(phi) 0; ...
                  sin(phi) cos(phi) 0;0 0 1];
    C=struct('flowpipe',F,'time_grid_s',[0 0.025 0.05], ...
        'param_lower',P,'param_upper',P, ...
        'observed_prepared_shapes',[sh sh2], ...
        'observed_ids',[70001 70002], ...
        'body',struct('r_uav_m',0.2,'r_cable_m',0.02, ...
                      'r_payload_m',0.15));
    D=TRIGGER_TAUT_CONE_FLOWPIPE_GATE(C);
    A.far_separated=D.conditional_geometry_pass && ...
        isequal(size(D.separated_intervals),[2 K]) && ...
        ~D.safe_to_commit && all(D.direction_cap_upper_rad==0);
    A.intervals=D.interval_count;
    sh.center0=[0;0;-1];
    C.observed_prepared_shapes=sh;
    C.observed_ids=70001;
    N=TRIGGER_TAUT_CONE_FLOWPIPE_GATE(C);
    A.near_rejected=~N.conditional_geometry_pass && ...
        ~N.safe_to_commit && ~isempty(N.possible_risk_ids);
    C.param_lower(21,:)=0;
    X=TRIGGER_TAUT_CONE_FLOWPIPE_GATE(C);
    A.invalid_mass_rejected=~X.conditional_geometry_pass && ...
        ~X.safe_to_commit;
    assert(A.far_separated&&A.near_rejected&&A.invalid_mass_rejected, ...
        'CHECK_TRIGGER_CONE_FLOWPIPE_LINK:Fixture', ...
        'Full-time cone fixture or fail-closed condition was not satisfied.');
    A.status='PASS_SYNTHETIC_CONE_FLOWPIPE_LINK__NOT_FLIGHT_SAFETY';
catch ME
    A.status='NOT_COMPLETED_CONE_FLOWPIPE_LINK';
    A.reason=[ME.identifier ' | ' ME.message];
end
fid=fopen('TRIGGER_CONE_FLOWPIPE_LINK_RESULT.txt','w');
if fid>=0
    fprintf(fid,'status=%s\nfar_separated=%d\nnear_rejected=%d\ninvalid_length_rejected=%d\nintervals=%d\nreason=%s\n', ...
        A.status,A.far_separated,A.near_rejected, ...
        A.invalid_mass_rejected,A.intervals,A.reason);
    fclose(fid);
end
save('TRIGGER_CONE_FLOWPIPE_LINK_RESULT.mat','A');
end
