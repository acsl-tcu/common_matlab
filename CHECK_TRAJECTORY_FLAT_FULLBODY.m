function R=CHECK_TRAJECTORY_FLAT_FULLBODY()
% CHECK_TRAJECTORY_FLAT_FULLBODY  Independent model-scope whole-time regression.
% Run at common_matlab root. No handoff TXT is read or needed.
% All parameters here are SYNTHETIC TEST VALUES and never source defaults.
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'reference','REPLANNING_SYSTEM');
addpath(fullfile(base,'TRAJECTORY_GENERATION'), ...
    fullfile(base,'OBSTACLE_INFORMATION'));
A=struct('cable_length_m',2,'uav_mass_kg',1.5, ...
    'payload_mass_kg',1,'gravity_world_mps2',[0;0;-9.80665], ...
    'thrust_limits_N',[0;100],'minimum_tension_N',0, ...
    'acceleration_guard_mps2',1e-10);
r=struct('uav_m',0.02,'payload_m',0.02,'cable_m',0.005);
opt=struct('robust_tube_enabled',false,'max_subdivision_depth',4, ...
    'max_node_count',63,'numerical_guard_m',1e-10);
J=zeros(3,10);J(3,1)=-2;
H=TRAJECTORY_C9_FLAT_BERNSTEIN.build(0,1,J,J, ...
    repmat(J(:,1),1,4));
V=[0 0 0;1 0 0;0 1 0;0 0 1];
F=[1 3 2;1 2 4;1 4 3;2 3 4];
shapes={ ...
    OBSTACLE_INFORMATION.define(1,'sphere',[0 6 0],0.3), ...
    OBSTACLE_INFORMATION.define(2,'ellipsoid',[0 6 0],[.5 1 2],'euler_deg',[20 40 50]), ...
    OBSTACLE_INFORMATION.define(3,'box',[0 6 0],[1 .6 2],'euler_deg',[5 25 40]), ...
    OBSTACLE_INFORMATION.define(4,'cylinder',[0 6 0],[.5 2],'euler_deg',[20 20 15]), ...
    OBSTACLE_INFORMATION.define(5,'capsule',[0 6 0],[.3 1]), ...
    OBSTACLE_INFORMATION.define(6,'cone',[0 6 0],[.5 2],'euler_deg',[10 20 30]), ...
    OBSTACLE_INFORMATION.define(7,'frustum',[0 6 0],[.8 .3 1]), ...
    OBSTACLE_INFORMATION.define(8,'pyramid',[0 6 0],[1 2]), ...
    OBSTACLE_INFORMATION.define(9,'regular_prism',[0 6 0],[6 .7 1]), ...
    OBSTACLE_INFORMATION.define(10,'torus',[0 6 0],[1 .2]), ...
    OBSTACLE_INFORMATION.define(11,'polygon_prism',[0 6 0], ...
        struct('outline',[-1 -1;1 -1;1 1;-1 1],'height',2)), ...
    OBSTACLE_INFORMATION.define(12,'polyhedron',[0 6 0], ...
        struct('vertices',V,'faces',F))};
observed=[shapes{:}];
clear_case=TRAJECTORY_TAUT_FULLBODY_CERTIFICATE(H,observed,r,A,opt);
assert(clear_case.certified && ~clear_case.safe_to_commit && ...
    numel(clear_case.considered_obstacle_ids)==12 && ...
    clear_case.checked_leaf_count>0 && ...
    clear_case.minimum_model_tension_lower_bound_N>0 && ...
    clear_case.maximum_cable_cone_padding_m<1e-10, ...
    'CHECK_TRAJECTORY_FLAT_FULLBODY:Clear', ...
    'Static vertical cable or 12 observed shapes wrongly handled.');
% The cable midpoint is the COLLISION, even though both endpoints clear.
mid=OBSTACLE_INFORMATION.define(13,'sphere',[0 0 -1],0.05);
contact=TRAJECTORY_TAUT_FULLBODY_CERTIFICATE(H,mid,r,A,opt);
assert(~contact.certified && ~contact.safe_to_commit && ...
    ismember(13,contact.unresolved_obstacle_ids), ...
    'CHECK_TRAJECTORY_FLAT_FULLBODY:Cable', ...
    'Obstacle intersecting the cable midpoint was declared safe.');
% Explicit caller-controlled robust tube, not a fixed hidden margin.
side=OBSTACLE_INFORMATION.define(14,'sphere',[0.6 0 -1],0.05);
nominal=TRAJECTORY_TAUT_FULLBODY_CERTIFICATE(H,side,r,A,opt);
on=opt;on.robust_tube_enabled=true;
on.uncertainty_bounds_m=struct('uav_m',0.8,'payload_m',0.8,'cable_m',0.8);
robust=TRAJECTORY_TAUT_FULLBODY_CERTIFICATE(H,side,r,A,on);
assert(nominal.certified && ~robust.certified && ~robust.safe_to_commit, ...
    'CHECK_TRAJECTORY_FLAT_FULLBODY:Tube', ...
    'Supplied uncertainty was ignored or nominal geometry false alarmed.');
% C9 cubic load x=t+0.1*t^3, y=0, z=-2. Its derived UAV position is
% NOT generally polynomial: verify the cone bound independently at samples.
left=J;left(1,2)=1;left(1,4)=0.6;
right=left;right(1,1)=1.1;right(1,2)=1.3;right(1,3)=0.6;
n=23;control=zeros(3,24);control(3,:)=-2;
for i=0:n
    control(1,i+1)=i/n+0.1*i*(i-1)*(i-2)/(n*(n-1)*(n-2));
end
X=TRAJECTORY_C9_FLAT_BERNSTEIN.build(0,1,left,right,control(:,11:14));
assert(max(abs(X.control_points_m(:)-control(:)))<1e-9, ...
    'CHECK_TRAJECTORY_FLAT_FULLBODY:C9','Synthetic C9 construction differs.');
dynamic=TRAJECTORY_TAUT_FULLBODY_CERTIFICATE(X,observed,r,A,opt);
assert(dynamic.certified && dynamic.maximum_cable_cone_padding_m>0 && ...
    ~dynamic.safe_to_commit, ...
    'CHECK_TRAJECTORY_FLAT_FULLBODY:Dynamic','Moving taut cable failed full-time proof.');
for t=linspace(0,1,33)
    E=TRAJECTORY_TAUT_FLATNESS.evaluate(X,t,A);
    assert(E.valid,'CHECK_TRAJECTORY_FLAT_FULLBODY:Evaluate','Invalid synthetic load.');
    idx=find(arrayfun(@(p) t>=p.time_interval_s(1)-1e-12 && ...
        t<=p.time_interval_s(2)+1e-12,dynamic.leaf_proofs),1);
    assert(~isempty(idx),'CHECK_TRAJECTORY_FLAT_FULLBODY:Leaves', ...
        'Time not covered by certificate.');
    leaf=dynamic.leaf_proofs(idx);
    proxy=E.load_jets(:,1)-A.cable_length_m*leaf.cable_direction_center;
    assert(norm(E.uav_jets(:,1)-proxy)<= ...
        leaf.additional_position_enclosure_m+5e-10, ...
        'CHECK_TRAJECTORY_FLAT_FULLBODY:Cone', ...
        'True model-derived UAV escaped directional cone enclosure.');
end
% External payload mass changes model tension bounds; no local mass default.
heavy=A;heavy.payload_mass_kg=1.7;
Rh=TRAJECTORY_TAUT_FULLBODY_CERTIFICATE(H,observed,r,heavy,opt);
assert(Rh.certified && abs( ...
    Rh.minimum_model_tension_lower_bound_N/ ...
    clear_case.minimum_model_tension_lower_bound_N-1.7)<1e-11, ...
    'CHECK_TRAJECTORY_FLAT_FULLBODY:Mass','Live load mass ignored.');
% Zero-tension/freefall is UNKNOWN even with no obstacles.
freeP=zeros(3,24);
for i=0:23
    freeP(:,i+1)=A.gravity_world_mps2*0.5*i*(i-1)/(23*22);
end
freefall=struct('t0_s',0,'duration_s',1,'control_points_m',freeP);
freeR=TRAJECTORY_TAUT_FULLBODY_CERTIFICATE(freefall,observed([]),r,A,opt);
assert(~freeR.certified && ~freeR.safe_to_commit && ...
    strcmp(freeR.status,'UNKNOWN_TAUT_TENSION_CONE'), ...
    'CHECK_TRAJECTORY_FLAT_FULLBODY:Tension', ...
    'Freefall was incorrectly certified as taut.');
short=opt;short.max_node_count=1;
budget=TRAJECTORY_TAUT_FULLBODY_CERTIFICATE(H,mid,r,A,short);
assert(~budget.certified && ~budget.safe_to_commit && ...
    strcmp(budget.status,'UNKNOWN_PROOF_NODE_BUDGET'), ...
    'CHECK_TRAJECTORY_FLAT_FULLBODY:Budget', ...
    'Exhausted proof budget was considered safe.');
% Public generator boundary: never permits unverified HLC commit.
G=TRAJECTORY_GENERATOR(struct('ROBUST_TUBE_ENABLED',false));
wrapper=G.certify_taut_fullbody(X,observed,r,A,opt);
assert(wrapper.certified && ~wrapper.safe_to_commit && ...
    isequal(wrapper.considered_obstacle_ids,dynamic.considered_obstacle_ids), ...
    'CHECK_TRAJECTORY_FLAT_FULLBODY:Generator', ...
    'Generator did not honor the coupled certificate.');
R=struct('status','PASS_C9_TAUT_CONTINUOUS_FULLBODY_12_SHAPES__HLC_PENDING', ...
    'shape_count',12,'dynamic_cone_padding_m',dynamic.maximum_cable_cone_padding_m, ...
    'dynamic_checked_leaves',dynamic.checked_leaf_count, ...
    'dynamic_certificate_ms',dynamic.elapsed_ms, ...
    'taut_tension_bound_N',dynamic.minimum_model_tension_lower_bound_N, ...
    'cable_collision_rejected',~contact.certified, ...
    'robust_flag_proven',~robust.certified, ...
    'freefall_rejected',~freeR.certified, ...
    'HLC_actuator_tracking_certified',false,'safe_to_commit',false);
mat=fullfile(root,'TRAJECTORY_FLAT_FULLBODY_RESULT.mat');
txt=fullfile(root,'TRAJECTORY_FLAT_FULLBODY_RESULT.txt');
save(mat,'R');
fid=fopen(txt,'wt');
assert(fid>0,'CHECK_TRAJECTORY_FLAT_FULLBODY:Output','Cannot write result.');
clearer=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',R.status);
fprintf(fid,'shapes=%d dynamic_leaves=%d padding_m=%.12g\n', ...
    R.shape_count,R.dynamic_checked_leaves,R.dynamic_cone_padding_m);
fprintf(fid,'certificate_ms=%.6f tension_bound_N=%.12g\n', ...
    R.dynamic_certificate_ms,R.taut_tension_bound_N);
fprintf(fid,'HLC_actuator_tracking=NOT_CERTIFIED commit=FORBIDDEN\n');
clear clearer;
zip(fullfile(root,'TRAJECTORY_FLAT_FULLBODY_RESULTS_FOR_CHATGPT.zip'), ...
    {'TRAJECTORY_FLAT_FULLBODY_RESULT.mat', ...
    'TRAJECTORY_FLAT_FULLBODY_RESULT.txt'},root);
delete(mat);delete(txt);
end
