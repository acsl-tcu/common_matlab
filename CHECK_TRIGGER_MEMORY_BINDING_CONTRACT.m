function A = CHECK_TRIGGER_MEMORY_BINDING_CONTRACT()
% Integration regression: OBSERVED_OBSTACLE_MEMORY MUST implement the
% exact method invoked by REPLANNING_SYSTEM for all Flight trigger ticks.
% Uses only synthetic OBSERVED frames. No source-world obstacle access.
A=struct('status','FAIL','reason','','cases',0,'known_ids',[], ...
         'retained_ids',[],'trigger_method_available',false, ...
         'replanner_calls_trigger_method',false);
try
    p=which('REPLANNING_SYSTEM');
    m=which('OBSERVED_OBSTACLE_MEMORY');
    assert(~isempty(p)&&~isempty(m), ...
        'CHECK_TRIGGER_MEMORY_BINDING:Path', ...
        'Both the replanner and the memory class must be on the MATLAB path.');
    source=fileread(p);
    A.replanner_calls_trigger_method=contains(source, ...
        'obj.observed_memory.known_frame_for_trigger(');
    A.trigger_method_available=any(strcmp( ...
        methods('OBSERVED_OBSTACLE_MEMORY'),'known_frame_for_trigger'));
    assert(A.trigger_method_available && A.replanner_calls_trigger_method, ...
        'CHECK_TRIGGER_MEMORY_BINDING:MissingMethod', ...
        'Current replanner and memory class API do not match.');
    % A minimal real-schema source for an ID and static geometry, without
    % any future observations. Only the sensed data may enter the memory.
    o=struct('id',1,'motion','static','position',[1;0;0]);
    M=OBSERVED_OBSTACLE_MEMORY(reshape(o([]),1,[]));
    f=struct('time_s',1.0,'uav_position_ekf_m',zeros(3,1), ...
        'detected_ids',1,'detected_count',1, ...
        'detected_obstacles',o,'detected_distances_m',0.6);
    U=M.update(f);
    K=M.known_frame_for_trigger(f);
    assert(isequal(K.detected_ids,1) && ...
        K.detected_count==1 && isequal(K.detected_obstacles.id,1) && ...
        isequal(U.newly_acquired_ids,1) && ...
        ~isfield(K,'detected_distances_m') && ...
        strcmp(K.observation_provenance,'ACTUAL_SENSOR_HISTORY_ONLY'), ...
        'CHECK_TRIGGER_MEMORY_BINDING:Initial', ...
        'Initial observed-only trigger packet is inconsistent.');
    A.cases=A.cases+1;
    % Detect nothing on a later tick: ID=1 MUST remain known, but none is
    % currently detected. Do not fabricate a current range measurement.
    f.time_s=2.0;
    f.detected_ids=zeros(1,0);
    f.detected_count=0;
    f.detected_obstacles=reshape(o([]),1,[]);
    f.detected_distances_m=zeros(1,0);
    U=M.update(f);
    K=M.known_frame_for_trigger(f);
    assert(isequal(K.detected_ids,1) && ...
        isempty(K.currently_detected_ids) && ...
        isequal(K.retained_only_ids,1) && ...
        isempty(U.newly_acquired_ids) && ~isfield(K,'detected_distances_m'), ...
        'CHECK_TRIGGER_MEMORY_BINDING:Retained', ...
        'Retained obstacle must remain available to Flight trigger.');
    A.cases=A.cases+1;
    % A second genuinely observed shape, irrespective of shape/type/order.
    o2=struct('id',2,'motion','static','position',[4;0;0]);
    f.time_s=3.0;f.detected_ids=2;f.detected_count=1;
    f.detected_obstacles=o2;f.detected_distances_m=3.6;
    U=M.update(f);
    K=M.known_frame_for_trigger(f);
    assert(isequal(K.detected_ids,[1 2]) && ...
        isequal(K.currently_detected_ids,2) && ...
        isequal(K.retained_only_ids,1) && ...
        isequal(U.newly_acquired_ids,2) && ...
        isa(K.memory_version,'uint64') && ...
        numel(K.detected_obstacles)==2, ...
        'CHECK_TRIGGER_MEMORY_BINDING:Incremental', ...
        'Incremental acquisition must preserve the full observed history.');
    A.cases=A.cases+1;
    f.time_s=4.0;f.detected_ids=zeros(1,0);f.detected_count=0;
    f.detected_obstacles=reshape(o([]),1,[]);
    f.detected_distances_m=zeros(1,0);
    M.update(f);
    K=M.known_frame_for_trigger(f);
    assert(isequal(K.detected_ids,[1 2]) && ...
        isempty(K.currently_detected_ids) && ...
        isequal(K.retained_only_ids,[1 2]), ...
        'CHECK_TRIGGER_MEMORY_BINDING:AllRetained', ...
        'A zero-detection scan must not erase observed obstacles.');
    A.cases=A.cases+1;
    A.known_ids=K.detected_ids;
    A.retained_ids=K.retained_only_ids;
    A.status='PASS_TRIGGER_MEMORY_ADAPTER__FLIGHT_NOT_YET_VERIFIED';
catch ME
    A.reason=sprintf('%s: %s',ME.identifier,ME.message);
end
fid=fopen('TRIGGER_MEMORY_BINDING_CONTRACT_RESULT.txt','w');
if fid>=0
    cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
    fprintf(fid,'status=%s\nreason=%s\ncases=%d\n', ...
        A.status,A.reason,A.cases);
    fprintf(fid,'trigger_method_available=%d\nreplanner_calls_trigger_method=%d\n', ...
        A.trigger_method_available,A.replanner_calls_trigger_method);
end
end
