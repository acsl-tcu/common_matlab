function R=CHECK_TRAJECTORY_SAFE_CORRIDOR()
% CHECK_TRAJECTORY_SAFE_CORRIDOR  Small fail-closed corridor regression.
% Place in common_matlab root. Writes one small result .txt there only.
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'reference','REPLANNING_SYSTEM');
addpath(fullfile(base,'TRAJECTORY_GENERATION'), ...
    fullfile(base,'OBSTACLE_INFORMATION'));
r=struct('uav_m',0.02,'payload_m',0.02,'cable_m',0.005);
opt=struct('robust_tube_enabled',false,'min_separation_m',0.01, ...
    'numerical_guard_m',1e-10,'max_subdivision_depth',4, ...
    'max_leaf_count',64,'max_normal_iterations',20);
% (1) Diagonal cable, where a crude AABB reports a false collision.
U=repmat([0;0;0],1,24);L=repmat([sqrt(2);0;-sqrt(2)],1,24);
S=seg(U,L,0,2);
far=OBSTACLE_INFORMATION.define(22,'sphere',[sqrt(2) 0 0],0.05);
C=TRAJECTORY_SAFE_CORRIDOR(S,far,r,opt);
assert(C.certified&&~C.safe_to_commit&&C.leaf_count==1, ...
    'CHECK_TRAJECTORY_CORRIDOR:Diagonal','Diagonal cable wrongly excluded.');
K=TRAJECTORY_CORRIDOR_LINEAR_CONSTRAINTS(C,2000);
x=[U(:);L(:)];
assert(size(K.Aineq,2)==numel(x)&&all(K.Aineq*x<=K.bineq)&& ...
    ~K.safe_to_commit, ...
    'CHECK_TRAJECTORY_CORRIDOR:Linear','Seed violates own linear constraints.');
V=TRAJECTORY_CORRIDOR_VALIDATE_CANDIDATE(C,S,far,r,opt,2000);
assert(V.corridor_constraints_satisfied&& ...
    V.continuous_geometry_certified&&~V.safe_to_commit, ...
    'CHECK_TRAJECTORY_CORRIDOR:Independent','Independent proof failed.');
% (2) Cable collides mid-span, even though both end spheres are clear.
Lc=repmat([0;0;-2],1,24);
Sc=seg(U,Lc,0,2);
collision=OBSTACLE_INFORMATION.define(44,'sphere',[0 0 -1],0.10);
Cc=TRAJECTORY_SAFE_CORRIDOR(Sc,collision,r,opt);
assert(~Cc.certified&&~Cc.safe_to_commit, ...
    'CHECK_TRAJECTORY_CORRIDOR:Cable','Cable collision accepted.');
% (3) Multiple obstacle planes simultaneously, with different sides.
left=OBSTACLE_INFORMATION.define(30,'sphere',[-1 0 0],0.1);
right=OBSTACLE_INFORMATION.define(31,'sphere',[2 0 0],0.1);
M=TRAJECTORY_SAFE_CORRIDOR(S,[left right far],r,opt);
assert(M.certified&&size(M.leaves(1).cable_normals,2)==3, ...
    'CHECK_TRAJECTORY_CORRIDOR:Multi','Multiple obstacles not simultaneous.');
% (4) Twelve canonical shapes, including arbitrary SO(3) rotations.
vertices=[0 0 0;1 0 0;0 1 0;0 0 1];
faces=[1 3 2;1 2 4;1 4 3;2 3 4];
shapes={ ...
    OBSTACLE_INFORMATION.define(1,'sphere',[0 6 0],0.3), ...
    OBSTACLE_INFORMATION.define(2,'ellipsoid',[0 6 0],[0.5 1 2],'euler_deg',[20 40 50]), ...
    OBSTACLE_INFORMATION.define(3,'box',[0 6 0],[1 0.6 2],'euler_deg',[5 25 40]), ...
    OBSTACLE_INFORMATION.define(4,'cylinder',[0 6 0],[0.5 2],'euler_deg',[20 20 15]), ...
    OBSTACLE_INFORMATION.define(5,'capsule',[0 6 0],[0.3 1]), ...
    OBSTACLE_INFORMATION.define(6,'cone',[0 6 0],[0.5 2],'euler_deg',[10 20 30]), ...
    OBSTACLE_INFORMATION.define(7,'frustum',[0 6 0],[0.8 0.3 1]), ...
    OBSTACLE_INFORMATION.define(8,'pyramid',[0 6 0],[1 2]), ...
    OBSTACLE_INFORMATION.define(9,'regular_prism',[0 6 0],[6 0.7 1]), ...
    OBSTACLE_INFORMATION.define(10,'torus',[0 6 0],[1 0.2]), ...
    OBSTACLE_INFORMATION.define(11,'polygon_prism',[0 6 0], ...
        struct('outline',[-1 -1;1 -1;1 1;-1 1],'height',2)), ...
    OBSTACLE_INFORMATION.define(12,'polyhedron',[0 6 0], ...
        struct('vertices',vertices,'faces',faces))};
allshapes=[shapes{:}];
C12=TRAJECTORY_SAFE_CORRIDOR(S,allshapes,r,opt);
assert(C12.certified&&numel(C12.observed_obstacle_ids)==12&& ...
    size(C12.leaves(1).uav_normals,2)==12, ...
    'CHECK_TRAJECTORY_CORRIDOR:Shapes','Twelve-shape corridor failed.');
% (5) A 23rd-order Bezier maintains the same linear-control semantics.
K12=TRAJECTORY_CORRIDOR_LINEAR_CONSTRAINTS(C12,3000);
assert(all(K12.Aineq*[U(:);L(:)]<=K12.bineq), ...
    'CHECK_TRAJECTORY_CORRIDOR:Shapes','All-shape guide not feasible.');
% (6) A changing control polygon must be constrained, not sampled.
Y=U;Y(2,:)=6;xx=[Y(:);L(:)];
assert(any(K12.Aineq*xx>K12.bineq), ...
    'CHECK_TRAJECTORY_CORRIDOR:Candidate','Corridor does not restrict control points.');
% (7) Robust tube changes feasibility with supplied radii only.
on=opt;on.robust_tube_enabled=true;
on.uncertainty_bounds_m=struct('uav_m',3,'payload_m',3,'cable_m',3);
Cb=TRAJECTORY_SAFE_CORRIDOR(S,far,r,on);
assert(~Cb.certified,'CHECK_TRAJECTORY_CORRIDOR:Tube','Tube bounds ignored.');
% (8) Subdivision improves a safe curved path's hull (not AABB inflation).
curve=[-2 0 2;0 3 0;0 0 0];
load=curve-[zeros(2,3);2*ones(1,3)];
arc=seg(curve,load,0,2);
near_arc=OBSTACLE_INFORMATION.define(50,'sphere',[0 0 -1],0.10);
D=TRAJECTORY_SAFE_CORRIDOR(arc,near_arc,r,opt);
assert(D.certified&&D.leaf_count>1, ...
    'CHECK_TRAJECTORY_CORRIDOR:Subdivision','Safe arc needs time-leaf corridor.');
KD=TRAJECTORY_CORRIDOR_LINEAR_CONSTRAINTS(D,3000);
assert(all(KD.Aineq*[curve(:);load(:)]<=KD.bineq), ...
    'CHECK_TRAJECTORY_CORRIDOR:Subdivision','Subdivision maps wrong.');
% (9) Same ID with different geometry MUST NOT reuse old corridor.
changed=OBSTACLE_INFORMATION.define(22,'sphere',[0 0 -1],0.15);
Q=TRAJECTORY_CORRIDOR_VALIDATE_CANDIDATE(C,S,changed,r,opt,2000);
assert(~Q.corridor_constraints_satisfied&& ...
    strcmp(Q.status,'UNKNOWN_OBSERVATION_CHANGED'), ...
    'CHECK_TRAJECTORY_CORRIDOR:Snapshot','Geometry changed under same ID.');
% (10) Generator exposes geometry-only interface, no HLC commit.
G=TRAJECTORY_GENERATOR(struct('ROBUST_TUBE_ENABLED',false));
Cg=G.build_corridor(S,far,r,opt);
assert(Cg.certified&&~Cg.safe_to_commit, ...
    'CHECK_TRAJECTORY_CORRIDOR:Generator','Generator integrated incorrectly.');
% (11) A known collision may never be CERTIFIED by larger budgets.
opt2=opt;opt2.max_subdivision_depth=0;
Bad=TRAJECTORY_SAFE_CORRIDOR(Sc,collision,r,opt2);
assert(~Bad.certified,'CHECK_TRAJECTORY_CORRIDOR:FailClosed','False safe.');
% (12) Missing shape knowledge creates no invented obstacle halfspaces.
Empty=TRAJECTORY_SAFE_CORRIDOR(S,allshapes([]),r,opt);
assert(Empty.certified&&Empty.halfspace_count==0, ...
    'CHECK_TRAJECTORY_CORRIDOR:ObservedOnly','Invented unknown obstacle.');
R=struct('status','PASS_FULL_BODY_POLYHEDRAL_CORRIDOR_12_SHAPES__NO_DYNAMICS_COMMIT', ...
    'cases',12,'shape_count',12,'separate_body_and_cable',true, ...
    'curved_path_subdivision',D.leaf_count, ...
    'linear_rows_12_shapes',K12.rows,'full_dynamics_certified',false, ...
    'generator_connected_to_HLC',false);
fid=fopen(fullfile(root,'TRAJECTORY_CORRIDOR_RESULT.txt'),'wt');
if fid>=0
    cleaner=onCleanup(@()fclose(fid)); %#ok<NASGU>
    fprintf(fid,'%s\n',R.status);
    fprintf(fid,'cases=%d shape_count=%d subdivided_leaves=%d rows=%d\n', ...
        R.cases,R.shape_count,R.curved_path_subdivision,R.linear_rows_12_shapes);
end
end
function s=seg(U,L,t,T)
u=struct('control_points_m',U,'t0_s',t,'duration_s',T);
l=struct('control_points_m',L,'t0_s',t,'duration_s',T);
s=struct('uav',u,'payload',l);
end
