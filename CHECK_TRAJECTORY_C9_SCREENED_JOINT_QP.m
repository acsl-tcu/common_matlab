function R=CHECK_TRAJECTORY_C9_SCREENED_JOINT_QP()
% Audit EXACT full-QP equivalence of monotone constraint generation.
% All initial-satisfied constraints are reconsidered after EVERY solve.
A=zeros(12,52);b=-4*ones(52,1);
A(1,1)=1;b(1)=1;
A(1,2)=-1;A(2,2)=1;b(2)=-0.4;
% The second plane is SATISFIED at zero but VIOLATED after x1>=1.
% Fill with nonbinding but nonzero, deterministic 12-D 3D-covariant rows.
for j=3:52
    a=sin((1:12)'*(j+.3))+cos((1:12)'*.17*j);
    A(:,j)=a/norm(a);
end
[x,S]=TRAJECTORY_C9_JOINT_SCREENED_PROJECTION(A,b,100,1e-10);
[y,F]=TRAJECTORY_C9_JOINT_PROJECTION(A,b,100,1e-10);
R=struct('status','FAIL_C9_SCREENED_JOINT_QP', ...
    'same_full_optimum',false,'full_feasibility_checked',false, ...
    'initially_satisfied_plane_added',false, ...
    'permutation_invariant',false,'rotation_invariant',false, ...
    'contradictory_planes_fail_closed',false, ...
    'zero_solution_on_all_satisfied',false, ...
    'working_plane_count',S.working_plane_count, ...
    'full_plane_count',S.full_plane_count, ...
    'passes',S.constraint_generation_passes, ...
    'pivots',S.pivots,'safe_to_commit',false);
assert(S.solved&&F.solved, 'CHECK_C9_QP:Full', ...
    'Both hard solvers must solve the same feasible strictly convex QP.');
R.same_full_optimum=norm(x-y,inf)<1e-8;
R.full_feasibility_checked=max(b-A.'*x)<=1e-10;
R.initially_satisfied_plane_added=S.constraint_generation_passes>=2&& ...
    x(2)>0.59&&S.working_plane_count>=2;
perm=52:-1:1;
[xp,sp]=TRAJECTORY_C9_JOINT_SCREENED_PROJECTION( ...
    A(:,perm),b(perm),100,1e-10);
R.permutation_invariant=sp.solved&&norm(xp-x,inf)<1e-8;
Q=eye(12);angle=0.37;
Q(1:2,1:2)=[cos(angle),-sin(angle);sin(angle),cos(angle)];
[xr,sr]=TRAJECTORY_C9_JOINT_SCREENED_PROJECTION( ...
    Q*A,b,100,1e-10);
R.rotation_invariant=sr.solved&&norm(xr-Q*x,inf)<1e-8;
conflict=zeros(12,2);conflict(1,:)=[1 -1];
[~,bad]=TRAJECTORY_C9_JOINT_SCREENED_PROJECTION( ...
    conflict,[1;0.2],100,1e-10);
R.contradictory_planes_fail_closed=~bad.solved;
[zero,z]=TRAJECTORY_C9_JOINT_SCREENED_PROJECTION( ...
    A,-4*ones(52,1),100,1e-10);
R.zero_solution_on_all_satisfied=z.solved&&all(zero==0);
assert(R.same_full_optimum&&R.full_feasibility_checked&& ...
    R.initially_satisfied_plane_added&&R.permutation_invariant&& ...
    R.rotation_invariant&&R.contradictory_planes_fail_closed&& ...
    R.zero_solution_on_all_satisfied&&~R.safe_to_commit, ...
    'CHECK_C9_QP:Invariant', ...
    'Constraint-generation QP must retain EVERY original halfspace.');
R.status='PASS_EXACT_JOINT_QP_CONSTRAINT_GENERATION__NOT_SAFETY_PROOF';
end
