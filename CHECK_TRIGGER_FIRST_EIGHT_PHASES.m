function D=CHECK_TRIGGER_FIRST_EIGHT_PHASES(replanner_instance)
% Disposable diagnostic under common_matlab/.  Shows *measured* phases,
% not a post hoc assumption that MATLAB JIT compiled on a particular tick.
D=struct('status','NOT_CAPTURED','records',0,'rows',zeros(0,15), ...
    'append_flags',false(0,2),'reason','');
try
    S=replanner_instance.get_status();
    a=S.first_flight_traces;
    assert(isstruct(a)&&numel(a)>=8, ...
        'CHECK_TRIGGER_FIRST_EIGHT_PHASES:NoTrace', ...
        'Enable TRIGGER_FIRST_FLIGHT_TRACE=1 before a fresh Flight.');
    D.records=8;
    D.rows=nan(8,15);
    D.append_flags=false(8,2);
    f=fopen('TRIGGER_FIRST_EIGHT_PHASES_RESULT.txt','w');
    assert(f>=0,'CHECK_TRIGGER_FIRST_EIGHT_PHASES:Open', ...
        'Could not create diagnostic report in common_matlab/.');
    c=onCleanup(@()fclose(f)); %#ok<NASGU>
    fprintf(f,['time known refnow authority core preverify outer_build ' ...
        'predwrap refwin pred_validate mex geomprep narrow geom_total ' ...
        'append_verify append_outer\n']);
    for k=1:8
        q=a(k);p=q.core_trace;
        D.rows(k,:)=[q.time_s,q.known_frame_ms,q.reference_now_ms, ...
            q.authority_current_ms,q.core_wall_ms, ...
            p.prepared_verify_ms,p.native_outer_build_ms, ...
            p.predictor_wrapped_wall_ms,p.reference_window_ms, ...
            p.predictor_validation_ms,p.mex_native_call_ms, ...
            p.geometry_prepare_ms,p.geometry_narrow_loop_ms, ...
            p.geometry_wall_ms,double(p.known_shape_count)];
        D.append_flags(k,:)=[logical(p.incremental_verify_taken), ...
            logical(p.incremental_outer_taken)];
        fprintf(f,'%.9f %.5f %.5f %.5f %.5f %.5f %.5f %.5f %.5f %.5f %.5f %.5f %.5f %.5f %d %d %d\n', ...
            D.rows(k,:),D.append_flags(k,1),D.append_flags(k,2));
    end
    D.status='PASS_SOURCE_PHASE_TIMING_CAPTURED__JIT_CAUSE_NOT_YET_INDEPENDENTLY_PROVED';
catch ME
    D.reason=[ME.identifier ' | ' ME.message];
    % A result is still saved for failed instrumentation / missing trace.
end
save('TRIGGER_FIRST_EIGHT_PHASES_RESULT.mat','D');
end
