function R=CHECK_TRAJECTORY_C9_PER_FLIGHT_MASS_CONTRACT()
% Flight-to-Flight parameter changes + within-Flight mass changes.
% All objects in this CHECK are TEST FIXTURES except the currently resolved
% HLC saturation source. No Flight or continuous HLC tracking is certified.
% Save even after failure. Run from common_matlab root; no saved MAT input.
root=fileparts(mfilename('fullpath'));
R=struct('status','FAIL_C9_PER_FLIGHT_NOT_EXECUTED', ...
    'error_identifier','','error_message','', ...
    'flight_one_bound',false,'live_mass_changed_within_flight',false, ...
    'nonmass_change_rejected',false,'tube_change_rejected',false, ...
    'session_change_rejected',false,'envelope_expiry_rejected',false, ...
    'mass_outside_external_range_rejected',false, ...
    'new_flight_parameters_rebound',false,'old_flight_contract_rejected',false, ...
    'missing_future_mass_envelope_not_invented',false, ...
    'mass_interval_force_pass',false,'mass_interval_short_validity_rejected',false, ...
    'mass_interval_high_variation_rejected',false, ...
    'current_hlc_limits_source_verified',false, ...
    'continuous_hlc_torque_tracking_certified',false, ...
    'safe_to_commit',false);
try
    root=fullfile(root);
    assert(isfile(fullfile(root,'run_flight_headless.m')), ...
        'CHECK_C9_FLIGHT:Root','CHECK must be in common_matlab.');
    addpath(fullfile(root,'controller'),'-begin');
    addpath(fullfile(root,'model'),'-begin');
    addpath(fullfile(root,'reference','REPLANNING_SYSTEM', ...
        'TRAJECTORY_GENERATION'),'-begin');
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    P.set("loadmass",0.14);
    gains=struct('dt',0.025,'F1',zeros(1,2), ...
        'F2',zeros(1,6),'F3',zeros(1,6),'F4',zeros(1,2));
    hc=HLC_SUSPENDED_LOAD([],gains);
    agent=struct('cha','f','controller',struct('hlc_suspended',hc), ...
        'parameter',P,'estimator',struct('result',struct( ...
        'state',struct('mL',0.14))));
    time=struct('t',5,'dt',gains.dt);
    ext=struct('gravity_world_mps2',[0;0;-double(P.get("gravity"))], ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0);
    B=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.bind(agent,ext);
    [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    R.current_hlc_limits_source_verified= ...
        isequal(B.input_lower,lo)&&isequal(B.input_upper,hi);
    req=struct();
    req.flight_session_id='CHECK_ONLY_FIRST_FLIGHT';
    req.radii=struct('uav_m',0.1,'cable_m',0.015,'payload_m',0.08);
    req.geometry_options=struct('robust_tube_enabled',true, ...
        'uncertainty_bounds_m',struct('uav_m',0.04, ...
            'cable_m',0.03,'payload_m',0.05), ...
        'numerical_guard_m',0,'trajectory_phase','f');
    req.force_options=struct('force_guard_N',0);
    req.future_mass_envelope=struct('lower_kg',0.10,'upper_kg',0.21, ...
        'valid_from_s',5,'valid_until_s',12, ...
        'source','EXTERNAL_TEST_ONLY__NOT_ESTIMATOR_GUARANTEE');
    C=TRAJECTORY_C9_FLIGHT_PARAMETER_CONTRACT.begin(B,agent,time,req);
    R.flight_one_bound=C.valid;
    time.t=5.025;
    P.set("loadmass",0.16);agent.estimator.result.state.mL=0.16;
    S=TRAJECTORY_C9_FLIGHT_PARAMETER_CONTRACT.check(C,B,agent,time,req);
    R.live_mass_changed_within_flight=S.valid&& ...
        abs(S.estimated_payload_mass_kg-0.16)<eps;
    oldL=double(P.get("cableL"));
    P.set("cableL",oldL*1.02);
    bad=TRAJECTORY_C9_FLIGHT_PARAMETER_CONTRACT.check(C,B,agent,time,req);
    R.nonmass_change_rejected=~bad.valid&& ...
        strcmp(bad.status,'UNKNOWN_NONMASS_PHYSICS_CHANGED_WITHIN_FLIGHT');
    P.set("cableL",oldL);
    badreq=req;
    badreq.geometry_options.uncertainty_bounds_m.payload_m=0.25;
    bad=TRAJECTORY_C9_FLIGHT_PARAMETER_CONTRACT.check(C,B,agent,time,badreq);
    R.tube_change_rejected=~bad.valid&& ...
        strcmp(bad.status,'UNKNOWN_GEOMETRY_OR_TUBE_CHANGED_WITHIN_FLIGHT');
    sessionreq=req;
    sessionreq.flight_session_id='CHECK_ONLY_FORGED_OTHER_FLIGHT';
    bad=TRAJECTORY_C9_FLIGHT_PARAMETER_CONTRACT.check(C,B,agent,time,sessionreq);
    R.session_change_rejected=~bad.valid&& ...
        strcmp(bad.status,'UNKNOWN_FLIGHT_SESSION_ID_CHANGED');
    time.t=12.025;
    bad=TRAJECTORY_C9_FLIGHT_PARAMETER_CONTRACT.check(C,B,agent,time,req);
    R.envelope_expiry_rejected=~bad.valid&& ...
        strcmp(bad.status,'UNKNOWN_LIVE_MASS_OUTSIDE_EXTERNAL_ENVELOPE');
    time.t=5.025;
    agent.estimator.result.state.mL=0.26;P.set("loadmass",0.26);
    bad=TRAJECTORY_C9_FLIGHT_PARAMETER_CONTRACT.check(C,B,agent,time,req);
    R.mass_outside_external_range_rejected=~bad.valid&& ...
        strcmp(bad.status,'UNKNOWN_LIVE_MASS_OUTSIDE_EXTERNAL_ENVELOPE');
    % Second Flight: legitimate new values must be allowed by FRESH bind.
    agent.estimator.result.state.mL=0.12;P.set("loadmass",0.12);
    P.set("cableL",oldL*1.1);
    time.t=8;
    B2=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.bind(agent,ext);
    req2=req;
    req2.flight_session_id='CHECK_ONLY_SECOND_FLIGHT';
    req2.radii.payload_m=0.12;
    req2.geometry_options.uncertainty_bounds_m.payload_m=0.07;
    req2.future_mass_envelope=struct('lower_kg',0.11, ...
        'upper_kg',0.18,'valid_from_s',8,'valid_until_s',18, ...
        'source','EXTERNAL_SECOND_FLIGHT_TEST_ONLY');
    C2=TRAJECTORY_C9_FLIGHT_PARAMETER_CONTRACT.begin(B2,agent,time,req2);
    R.new_flight_parameters_rebound=C2.valid;
    stale=TRAJECTORY_C9_FLIGHT_PARAMETER_CONTRACT.check(C,B2,agent,time,req2);
    R.old_flight_contract_rejected=~stale.valid;
    req3=rmfield(req2,'future_mass_envelope');
    C3=TRAJECTORY_C9_FLIGHT_PARAMETER_CONTRACT.begin(B2,agent,time,req3);
    R.missing_future_mass_envelope_not_invented=C3.valid&& ...
        ~C3.has_future_mass_envelope;
    % Analytic static taut-load fixture with internally consistent bounds.
    % It does NOT claim an independent geometry or HLC certificate existed.
    m0=double(P.get("loadmass"));
    mu=double(P.get("mass"));
    gg=double(P.get("gravity"));
    pc=zeros(3,24);pc(3,:)=3; % stationary, w = [0,0,-g]
    piece=struct('t0_s',8,'duration_s',2,'control_points_m',pc);
    nomf=(mu+m0)*gg;
    Tnom=m0*gg;
    N=struct('certified_continuous_geometry',true, ...
        'certified_continuous_thrust',true, ...
        'certified_continuous_tension',true, ...
        'thrust_lower_bound_N',nomf,'thrust_upper_bound_N',nomf, ...
        'minimum_tension_lower_bound_N',Tnom);
    A=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.current(B2,agent,time);
    assert(A.valid,'CHECK_C9_FLIGHT:Fresh','Live authority fixture invalid.');
    tight=req2.future_mass_envelope;
    tight.lower_kg=m0-0.001;tight.upper_kg=m0+0.001;
    good=TRAJECTORY_C9_VARIABLE_MASS_FORCE_CERTIFICATE( ...
        piece,N,A.authority,tight,0);
    R.mass_interval_force_pass=good.conditional_ideal_taut_force_proven&& ...
        abs(good.w_upper_bound_mps2-gg)<=32*eps(max(1,gg))&& ...
        ~good.safe_to_commit;
    early=tight;early.valid_until_s=9;
    bad=TRAJECTORY_C9_VARIABLE_MASS_FORCE_CERTIFICATE( ...
        piece,N,A.authority,early,0);
    R.mass_interval_short_validity_rejected= ...
        ~bad.conditional_ideal_taut_force_proven&& ...
        strcmp(bad.status,'UNKNOWN_MASS_ENVELOPE_DOES_NOT_COVER_ENTIRE_PIECE');
    huge=tight;huge.upper_kg=m0+2;
    bad=TRAJECTORY_C9_VARIABLE_MASS_FORCE_CERTIFICATE( ...
        piece,N,A.authority,huge,0);
    R.mass_interval_high_variation_rejected= ...
        ~bad.conditional_ideal_taut_force_proven&& ...
        strcmp(bad.status,'UNKNOWN_VARIABLE_MASS_FORCE_BOUNDS_NOT_FEASIBLE');
    keys={'flight_one_bound','live_mass_changed_within_flight', ...
        'nonmass_change_rejected','tube_change_rejected', ...
        'session_change_rejected','envelope_expiry_rejected', ...
        'mass_outside_external_range_rejected','new_flight_parameters_rebound', ...
        'old_flight_contract_rejected', ...
        'missing_future_mass_envelope_not_invented', ...
        'mass_interval_force_pass','mass_interval_short_validity_rejected', ...
        'mass_interval_high_variation_rejected', ...
        'current_hlc_limits_source_verified'};
    for k=1:numel(keys)
        assert(R.(keys{k}),'CHECK_C9_FLIGHT:Case', ...
            'Failed per-Flight authority case: %s',keys{k});
    end
    R.status='PASS_PER_FLIGHT_AUTHORITY_AND_CONDITIONAL_MASS_INTERVAL__NO_HLC_COMMIT';
catch ME
    R.status='FAIL_C9_PER_FLIGHT_AUTHORITY';
    R.error_identifier=ME.identifier;
    R.error_message=ME.message;
end
base='TRAJECTORY_C9_PER_FLIGHT_MASS_RESULT';
save(fullfile(root,[base '.mat']),'R');
fid=fopen(fullfile(root,[base '.txt']),'wt');
assert(fid>0,'CHECK_C9_FLIGHT:Write','Cannot write TXT.');
clean=onCleanup(@()fclose(fid));
for k=fieldnames(R)'
    name=k{1};v=R.(name);
    if islogical(v),fprintf(fid,'%s=%d\n',name,v);
    elseif ischar(v),fprintf(fid,'%s=%s\n',name,v);end
end
fprintf(fid,'ALL_FLIGHT_DATA_FIXTURES=1\n');
fprintf(fid,'ALL_TIME_HLC_TRACKING_AND_TORQUE_PROVED=0\n');
clear clean
out=fullfile(root,[base '_FOR_CHATGPT.zip']);
if isfile(out),delete(out);end
zip(out,{[base '.mat'],[base '.txt']},root);
assert(isfile(out)&&dir(out).bytes>100, ...
    'CHECK_C9_FLIGHT:Export','Cannot verify result ZIP.');
fprintf('[C9 PER-FLIGHT] %s\nOutput: %s\n',R.status,out);
end
