function V=obs_box_vertices(lo,hi)
% 8 local vertices of an axis-aligned closed box.
lo=reshape(lo,1,3); hi=reshape(hi,1,3);
V=[lo(1) lo(2) lo(3); hi(1) lo(2) lo(3); ...
   hi(1) hi(2) lo(3); lo(1) hi(2) lo(3); ...
   lo(1) lo(2) hi(3); hi(1) lo(2) hi(3); ...
   hi(1) hi(2) hi(3); lo(1) hi(2) hi(3)];
end
