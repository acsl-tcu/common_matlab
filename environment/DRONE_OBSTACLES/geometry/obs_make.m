function o = obs_make(type, name, position, params, rpyDeg)
% Common obstacle definition. position=[x y z], rpyDeg=[roll pitch yaw] in degrees.
if nargin < 5 || isempty(rpyDeg), rpyDeg=[0 0 0]; end
validateattributes(position,{'numeric'},{'vector','numel',3,'real','finite'});
validateattributes(rpyDeg,{'numeric'},{'vector','numel',3,'real','finite'});
o = struct('name',char(name),'type',char(type), ...
    'position',reshape(double(position),1,3), ...
    'rpyDeg',reshape(double(rpyDeg),1,3), ...
    'R',obs_rpy_matrix(rpyDeg),'params',params,'approxMethod','', ...
    'isDynamic',false,'motion',struct('type','static'));

end
