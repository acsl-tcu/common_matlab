function R=CHECK_TRAJECTORY_C9_FACTORED_GYRO_AB()
% Development-only REAL-ARITHMETIC nominal rigid-body torque A/B test.
% Does not certify numerical directed rounding, the actual HLC closed loop,
% or future payload mass evolution; every tested result is non-COMMIT.
% Results and ZIP always go into common_matlab, independent of pwd.
root=fileparts(mfilename('fullpath'));
name='TRAJECTORY_C9_FACTORED_GYRO_AB_RESULT';
R=struct('status','FAIL_C9_FACTORED_GYRO_AB','stage','START', ...
 'error_identifier','','error_message','','error_stack',{{}}, ...
 'scene_names',{{'SMOOTH_NOMINAL','SPHERE_ELLIPSOID_CERTIFIED_GUIDE'}}, ...
 'mode_names',{{'BASELINE','FACTORED','FACTORED_AND_LIMIT_WITNESS'}}, ...
 'status_by_mode',{{}}, ...
 'nodes_by_mode',NaN(3,2),'detailed_nodes_by_mode',NaN(3,2), ...
 'fast_norm_leaves_by_mode',NaN(3,2), ...
 'torque_limit_witness_by_mode',NaN(3,2), ...
 'torque_bounds_by_mode',{{}}, ...
 'median_ms_by_mode',NaN(3,2),'p95_ms_by_mode',NaN(3,2), ...
 'max_ms_by_mode',NaN(3,2), ...
 'algebra_trials',0,'algebra_inclusion_pass',false, ...
 'search_status','NOT_CALLED','search_elapsed_ms',NaN, ...
 'search_independent_proof_calls',NaN, ...
 'repetitions',7,'safe_to_commit',false, ...
 'scope','CONDITIONAL_NOMINAL_TORQUE__NOT_HLC_TRACKING_OR_NUMERIC_ROUNDING', ...
 'zip_path',fullfile(root,[name '_FOR_CHATGPT.zip']));
try
    R.stage='DIAGONAL_EULER_IDENTITY_AND_INTERVAL_TEST';
    % Random trials are an independent test of the Euler identity and
    % factorized interval inclusion, not a floating-point safety proof.
    trials=3000;
    previous_rng=rng;
    cleanup_rng=onCleanup(@()rng(previous_rng));
    rng(211,'twister');
    for it=1:trials
        J=10.^(-6+5*rand(3,1));
        cc=40*rand(3,1)-20;
        rr=20*rand(3,1);
        omega_lo=cc-rr;omega_hi=cc+rr;
        cyc=[2 3;3 1;1 2];
        for ax=1:3
            j=cyc(ax,1);k=cyc(ax,2);
            a=[omega_lo(j) omega_hi(j)];
            b=[omega_lo(k) omega_hi(k)];
            prods=[a(1)*b(1) a(1)*b(2) a(2)*b(1) a(2)*b(2)];
            dp=J(k)-J(j);
            factor_corners=dp*prods;
            exact_lo=min(factor_corners);exact_hi=max(factor_corners);
            % Legacy interval evaluation of wi*Jk*wk - wk*Jj*wi.
            old1=[a(1)*J(k)*b(1) a(1)*J(k)*b(2) ...
                  a(2)*J(k)*b(1) a(2)*J(k)*b(2)];
            old2=[b(1)*J(j)*a(1) b(1)*J(j)*a(2) ...
                  b(2)*J(j)*a(1) b(2)*J(j)*a(2)];
            % This test tolerates small ordinary floating-point roundoff;
            % production does NOT claim directed rounding from this.
            epsw=1e-11*max(1,max(abs([old1 old2 factor_corners])));
            assert(exact_lo>=min(old1)-max(old2)-epsw && ...
                   exact_hi<=max(old1)-min(old2)+epsw, ...
                   'C9_FACTORED_GYRO:Inclusion', ...
                   'Factored Euler bound exceeds generic cross interval.');
            wb=sum(max(abs(omega_lo),abs(omega_hi)).^2);
            assert(max(abs([exact_lo exact_hi]))<=0.5*abs(dp)*wb+epsw, ...
                'C9_FACTORED_GYRO:QuickBound', ...
                'Norm-sufficient Euler gyro inequality failed.');
        end
    end
    R.algebra_trials=trials;
    R.algebra_inclusion_pass=true;
    clear cleanup_rng

    R.stage='READ_REAL_HLC_LIMITS_AND_CREATE_C9';
    addpath(fullfile(root,'controller'),fullfile(root,'model'),'-begin');
    addpath(fullfile(root,'reference','REPLANNING_SYSTEM', ...
      'TRAJECTORY_GENERATION'), ...
      fullfile(root,'reference','REPLANNING_SYSTEM', ...
      'OBSTACLE_INFORMATION'),'-begin');
    [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    P.set("loadmass",0.14); % Only the CHECK fixture; never a production default.
    d=double(P.get(["mass","jx","jy","jz","gravity","cableL","loadmass"]));
    d=d(:);lo=double(lo(:));hi=double(hi(:));
    assert(numel(d)==7&&all(isfinite(d))&&all(d>0)&& ...
        numel(lo)==4&&numel(hi)==4&&all(hi>lo), ...
        'C9_FACTORED_GYRO:Authority','Cannot read source HLC/plant limits.');
    a=struct('uav_mass_kg',d(1),'payload_mass_kg',d(7), ...
      'cable_length_m',d(6),'uav_inertia_kgm2',d(2:4), ...
      'gravity_world_mps2',[0;0;-d(5)], ...
      'thrust_limits_N',[lo(1),hi(1)], ...
      'torque_limits_Nm',[lo(2:4),hi(2:4)], ...
      'minimum_tension_N',0,'acceleration_guard_mps2',0);
    opt=struct('max_subdivision_depth',8,'max_node_count',511, ...
      'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
      'torque_guard_Nm',zeros(3,1), ...
      'enable_fast_norm_sufficient_bound',true, ...
      'use_precomputed_binomial',true);
    J0=zeros(3,10);J1=zeros(3,10);
    J0(:,1)=[-2;0;3];J1(:,1)=[2;0;3];
    J0(1,2)=0.4;J1(1,2)=0.4;
    nominal=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,10,J0,J1, ...
      repmat([0;0;3],1,4));
    R.stage='FIND_GUIDE_ONCE_NOT_PER_BENCHMARK_MODE';
    theta=0.34;Q=[cos(theta) -sin(theta) 0; ...
                   sin(theta) cos(theta) 0;0 0 1];
    observed=[OBSTACLE_INFORMATION.define(21,'sphere',[0 0.1 3],0.2), ...
      OBSTACLE_INFORMATION.define(33,'ellipsoid',[0.6 -0.16 3], ...
      [0.32 0.19 0.4],'rotation',Q)];
    gopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
      'numerical_guard_m',0,'robust_tube_enabled',false, ...
      'trajectory_phase','f');
    fopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
      'force_guard_N',0);
    sopt=struct('probe_count',13,'max_outer_iterations',4, ...
      'max_projection_sweeps',100,'projection_tolerance_m',1e-8, ...
      'min_separation_m',1e-5, ...
      'lazy_initial_proof_on_violated_plane',false, ...
      'payload_hull_witness_policy','off', ...
      'embed_taut_bernstein_halfspaces',false, ...
      'accept_first_certified_minimum_qp',false, ...
      'enable_connected_group_topology',true, ...
      'enable_point_intersection_prefilter',true);
    req=struct('t0_s',8,'duration_s',10,'flight_interval_s',[8 30], ...
      'start_jets',J0,'end_jets',J1, ...
      'nominal_free',nominal.control_points_m(:,11:14), ...
      'observed',observed, ...
      'radii',struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1), ...
      'authority',a,'geometry_options',gopt, ...
      'force_options',fopt,'search_options',sopt);
    S=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(req);
    R.search_status=S.status;
    R.search_elapsed_ms=S.elapsed_ms;
    R.search_independent_proof_calls=S.independent_proof_calls;
    assert(S.candidate_available&&S.final_certificate.certified && ...
      ~S.safe_to_commit,'C9_FACTORED_GYRO:Guide', ...
      ['The multishape candidate lacks a nominal geometry proof: ' S.status]);
    pieces={nominal,S.candidate_piece};
    modes=[false false;true false;true true];
    R.status_by_mode=cell(3,2);R.torque_bounds_by_mode=cell(3,2);
    R.stage='A_B_THREE_MODES_AND_7_REPEATS';
    for scene=1:2
        mode_options=cell(3,1);reference=cell(3,1);
        for mode=1:3
            o=opt;
            o.use_factored_diagonal_gyro=modes(mode,1);
            o.enable_infeasible_leaf_early_exit=modes(mode,2);
            mode_options{mode}=o;
            Z=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL(pieces{scene},a,o);
            assert(~Z.safe_to_commit && ~Z.actual_HLC_tracking_proven && ...
                ~Z.numerically_directed_rounding_proven, ...
                'C9_FACTORED_GYRO:NoCommit','Nominal check claimed real HLC safety.');
            reference{mode}=Z;
            R.status_by_mode{mode,scene}=Z.status;
            R.nodes_by_mode(mode,scene)=Z.checked_nodes;
            R.detailed_nodes_by_mode(mode,scene)=Z.detailed_interval_checked_nodes;
            R.fast_norm_leaves_by_mode(mode,scene)=Z.fast_norm_accepted_leaves;
            R.torque_limit_witness_by_mode(mode,scene)= ...
                Z.nominal_torque_limit_witness_nodes;
            R.torque_bounds_by_mode{mode,scene}=Z.torque_bounds_Nm;
        end
        tt=NaN(3,R.repetitions);
        for k=1:R.repetitions
            % Rotate mode order on every repeat to control warm-up bias.
            for pos=1:3
                mode=mod(pos+k-2,3)+1;
                X=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL( ...
                    pieces{scene},a,mode_options{mode});
                Z=reference{mode};
                assert(strcmp(X.status,Z.status)&& ...
                    X.checked_nodes==Z.checked_nodes&& ...
                    isequaln(X.torque_bounds_Nm,Z.torque_bounds_Nm), ...
                    'C9_FACTORED_GYRO:Determinism', ...
                    'Repeated evaluation changed the certificate.');
                tt(mode,k)=X.elapsed_ms;
            end
        end
        for mode=1:3
            R.median_ms_by_mode(mode,scene)=median(tt(mode,:));
            sorted=sort(tt(mode,:));
            R.p95_ms_by_mode(mode,scene)= ...
                sorted(ceil(.95*numel(sorted)));
            R.max_ms_by_mode(mode,scene)=sorted(end);
        end
        % A stronger interval enclosure may turn UNKNOWN into a success;
        % never accept the opposite or an unproven baseline as COMMIT.
        if strcmp(R.status_by_mode{1,scene}, ...
           'CONDITIONAL_NOMINAL_RIGID_BODY_TORQUE_ALL_TIME__HLC_TRACKING_PENDING')
            assert(all(strcmp(R.status_by_mode{2,scene}, ...
              'CONDITIONAL_NOMINAL_RIGID_BODY_TORQUE_ALL_TIME__HLC_TRACKING_PENDING'))&& ...
              all(strcmp(R.status_by_mode{3,scene}, ...
              'CONDITIONAL_NOMINAL_RIGID_BODY_TORQUE_ALL_TIME__HLC_TRACKING_PENDING')), ...
              'C9_FACTORED_GYRO:Monotonicity', ...
              'Factored torque certificate unexpectedly lost a baseline proof.');
        end
    end
    R.status='PASS_C9_FACTORED_GYRO_AB__HLC_UNCERTIFIED';
    R.stage='COMPLETE';
catch ME
    R.error_identifier=ME.identifier;
    R.error_message=ME.message;
    R.error_stack=arrayfun(@(e)sprintf('%s:%d',e.name,e.line), ...
      ME.stack,'UniformOutput',false);
end
save(fullfile(root,[name '.mat']),'R');
fid=fopen(fullfile(root,[name '.txt']),'w');
if fid>=0
    fprintf(fid,'status=%s\nstage=%s\nerror=%s | %s\n', ...
        R.status,R.stage,R.error_identifier,R.error_message);
    for i=1:numel(R.error_stack)
        fprintf(fid,'stack_%d=%s\n',i,R.error_stack{i});
    end
    fprintf(fid,'random_euler_inclusion_trials=%d | PASS=%d\n', ...
        R.algebra_trials,R.algebra_inclusion_pass);
    fprintf(fid,'search=%s | search_ms=%.6f | independent_calls=%g\n', ...
        R.search_status,R.search_elapsed_ms,R.search_independent_proof_calls);
    for sc=1:2
        for mo=1:3
            if numel(R.status_by_mode)<(mo+(sc-1)*3),continue;end
            fprintf(fid,['scene=%s | mode=%s | status=%s | ', ...
                'nodes=%g | detailed=%g | quick_accepted=%g | ', ...
                'exclusion_witness=%g | median_ms=%.6f | ', ...
                'p95_ms=%.6f | max_ms=%.6f\n'], ...
                R.scene_names{sc},R.mode_names{mo}, ...
                R.status_by_mode{mo,sc},R.nodes_by_mode(mo,sc), ...
                R.detailed_nodes_by_mode(mo,sc), ...
                R.fast_norm_leaves_by_mode(mo,sc), ...
                R.torque_limit_witness_by_mode(mo,sc), ...
                R.median_ms_by_mode(mo,sc), ...
                R.p95_ms_by_mode(mo,sc),R.max_ms_by_mode(mo,sc));
        end
    end
    fprintf(fid,'scope=%s | safe_to_commit=%d\n',R.scope,R.safe_to_commit);
    fclose(fid);
end
zip(R.zip_path,{[name '.mat'],[name '.txt']},root);
fprintf('[C9 FACTORED GYRO] %s | %s\n',R.status,R.zip_path);
end
