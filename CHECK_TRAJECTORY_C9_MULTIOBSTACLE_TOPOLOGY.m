function R=CHECK_TRAJECTORY_C9_MULTIOBSTACLE_TOPOLOGY()
% Development-only: paired whole-pipeline comparison of a DATA-DERIVED
% connected-obstacle QP search direction with unchanged baseline search.
% The original independently certified geometry/tension/thrust, yaw,
% torque and HLC NO-COMMIT policy are NOT bypassed. No Flight runner edits.
root=fileparts(mfilename('fullpath'));
R=struct('status','FAIL_C9_CONNECTED_GROUP_TOPOLOGY','stage','START', ...
 'error_identifier','','error_message','','error_stack',{{}}, ...
 'scene_names',{{'sphere','sphere_rotated_ellipsoid','box_cylinder'}}, ...
 'status_on',{{}},'status_off',{{}}, ...
 'proof_calls_on',NaN(1,3),'proof_calls_off',NaN(1,3), ...
 'groups_used',NaN(1,3),'group_attempts',NaN(1,3), ...
 'group_graph_pair_tests',NaN, ...
 'group_ids',{{}},'group_normal',NaN(3,3), ...
 'group_search_status',{{}}, ...
 'prefilter_collision_witness_pass',false, ...
 'prefilter_noncollision_not_rejected',false, ...
 'prefilter_rejected_candidates_on',NaN(1,3), ...
 'prefilter_time_ms_on',NaN(1,3), ...
 'proof_status_history_on',{{}},'proof_status_history_off',{{}}, ...
 'unresolved_ids_on',{{}},'unresolved_ids_off',{{}}, ...
 'median_ms_on',NaN(1,3),'median_ms_off',NaN(1,3), ...
 'p95_ms_on',NaN(1,3),'p95_ms_off',NaN(1,3), ...
 'max_ms_on',NaN(1,3),'max_ms_off',NaN(1,3), ...
 'geometry_group_rotation_covariance',false, ...
 'gravity_collinear_bypass_pass',false, ...
 'gravity_collinear_SO3_covariance',false, ...
 'gravity_collinear_without_vector_unknown',false, ...
 'geometry_group_nonconnected_rejected',false, ...
 'no_unproven_candidate_accepted',false, ...
 'conditional_hlc_virtual_lemma_pass',false, ...
 'hlc_nonlinear_methods_found',false(1,5), ...
 'hlc_nonlinear_method_paths',{{}}, ...
 'repetitions',7, ...
 'stage_timing_names',{{'joint_proof','search_planes','joint_QP', ...
   'heading_join','nominal_torque','remaining_overhead'}}, ...
 'stage_median_ms_on',NaN(6,3),'stage_median_ms_off',NaN(6,3), ...
 'scope','C9_SAME_JOINT_QP__HLC_NOT_PROVED', ...
 'zip_path',fullfile(root,'TRAJECTORY_C9_MULTIOBSTACLE_TOPOLOGY_RESULT_FOR_CHATGPT.zip'));
try
 R.stage='READ_REAL_FLIGHT_AUTHORITY_FOR_DEVELOPMENT_FIXTURE';
 addpath(fullfile(root,'controller'),'-begin');
 addpath(fullfile(root,'model'),'-begin');
 addpath(fullfile(root,'reference','REPLANNING_SYSTEM','TRAJECTORY_GENERATION'), ...
     fullfile(root,'reference','REPLANNING_SYSTEM','OBSTACLE_INFORMATION'),'-begin');
 [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
 P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
 P.set("loadmass",0.14); % fixture only, never production constant
 d=double(P.get(["mass","jx","jy","jz","gravity","cableL","loadmass"]));
 d=d(:);lo=double(lo(:));hi=double(hi(:));
 assert(numel(d)==7&&all(isfinite(d))&&all(d>0)&& ...
   numel(lo)==4&&numel(hi)==4&&all(hi>lo), ...
   'CHECK_C9_GROUP:Authority','Current MATLAB source authority unavailable.');
 authority=struct('uav_mass_kg',d(1),'payload_mass_kg',d(7), ...
   'cable_length_m',d(6),'uav_inertia_kgm2',d(2:4), ...
   'gravity_world_mps2',[0;0;-d(5)], ...
   'thrust_limits_N',[lo(1) hi(1)], ...
   'torque_limits_Nm',[lo(2:4) hi(2:4)], ...
   'minimum_tension_N',0,'acceleration_guard_mps2',0);
 gopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
   'numerical_guard_m',0,'robust_tube_enabled',false,'trajectory_phase','f');
 fopt=struct('max_subdivision_depth',6,'max_node_count',127,'force_guard_N',0);
 sopt=struct('probe_count',13,'max_outer_iterations',4, ...
   'max_projection_sweeps',100,'projection_tolerance_m',1e-8, ...
   'min_separation_m',1e-5, ...
   'lazy_initial_proof_on_violated_plane',false, ...
   'payload_hull_witness_policy','off', ...
   'embed_taut_bernstein_halfspaces',false, ...
   'accept_first_certified_minimum_qp',false);
 hopt=struct('max_subdivision_depth',8,'max_node_count',511, ...
   'horizontal_velocity_guard_mps',0,'w_guard_mps2',0, ...
   'payload_jet_tolerance',1e-7*ones(3,10), ...
   'uav_jet_tolerance',1e-7*ones(3,8), ...
   'yaw_jet_tolerance',1e-7*ones(1,7));
 topt=struct('max_subdivision_depth',8,'max_node_count',511, ...
   'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
   'torque_guard_Nm',zeros(3,1), ...
   'enable_fast_norm_sufficient_bound',true);
 J0=zeros(3,10);J1=zeros(3,10);
 J0(:,1)=[-2;0;3];J1(:,1)=[2;0;3];
 J0(1,2)=0.4;J1(1,2)=0.4;
 nominal=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,10,J0,J1, ...
   repmat([0;0;3],1,4));
 req=struct('t0_s',8,'duration_s',10,'flight_interval_s',[8 30], ...
   'start_jets',J0,'end_jets',J1, ...
   'nominal_free',nominal.control_points_m(:,11:14), ...
   'observed',struct([]),'radii', ...
   struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1), ...
   'authority',authority,'geometry_options',gopt, ...
   'force_options',fopt,'search_options',sopt, ...
   'heading_options',hopt,'nominal_torque_options',topt);
 sphere=OBSTACLE_INFORMATION.define(21,'sphere',[0 0.1 3],0.2);
 theta=0.34;rot=[cos(theta) -sin(theta) 0; ...
                    sin(theta) cos(theta) 0;0 0 1];
 ellipsoid=OBSTACLE_INFORMATION.define(33,'ellipsoid', ...
   [0.6 -0.16 3],[0.32 0.19 0.4],'rotation',rot);
 box=OBSTACLE_INFORMATION.define(34,'box', ...
   [0 0.15 3],[0.35 0.3 0.7],'rotation',rot);
 cylinder=OBSTACLE_INFORMATION.define(35,'cylinder', ...
   [0.65 -0.15 3],[0.27 0.5],'rotation',rot);
 scenes={sphere,[sphere ellipsoid],[box cylinder]};
 R.stage='PROVE_3D_GROUP_ROTATION_AND_DISCONNECTED_REGRESSION';
 shapes=TRAJECTORY_OBSTACLE_SUPPORT.prepare([sphere ellipsoid]);
 failing=struct('unresolved_time_interval_s',[12.21875 12.375], ...
   'unresolved_obstacle_ids',21,'unresolved_body_indices',3);
 G=TRAJECTORY_C9_CONFLICT_GROUP_GUIDE(nominal,shapes,failing,0.1,1e-5);
 assert(G.active&&G.group_size==2&&numel(G.ids)==2&& ...
   all(isfinite(G.normal))&&abs(norm(G.normal)-1)<1e-12, ...
   'CHECK_C9_GROUP:Cluster','Failing obstacle group not found.');
 Q=[cos(0.43) -sin(0.43) 0;sin(0.43) cos(0.43) 0;0 0 1];
 rotated=shapes;
 for j=1:numel(rotated)
   rotated(j).center=Q*shapes(j).center;
   rotated(j).R=Q*shapes(j).R;
 end
 rotated_piece=nominal;
 rotated_piece.control_points_m=Q*nominal.control_points_m;
 G2=TRAJECTORY_C9_CONFLICT_GROUP_GUIDE( ...
   rotated_piece,rotated,failing,0.1,1e-5);
 R.geometry_group_rotation_covariance=G2.active && ...
   isequal(G.ids,G2.ids) && norm(Q*G.normal-G2.normal)<1e-9;
 assert(R.geometry_group_rotation_covariance, ...
   'CHECK_C9_GROUP:SO3','Candidate group direction not covariant.');
 % Do not assume an obstacle struct storage field: move its WORLD pose
 % using the same original definitional constructor, not a cached record.
 far=OBSTACLE_INFORMATION.define(33,'ellipsoid', ...
   [100 100 100],[0.32 0.19 0.4],'rotation',rot);
 separated=TRAJECTORY_OBSTACLE_SUPPORT.prepare([sphere far]);
 Gfar=TRAJECTORY_C9_CONFLICT_GROUP_GUIDE( ...
   nominal,separated,failing,0.1,1e-5);
 R.geometry_group_nonconnected_rejected=~Gfar.active;
 % Two true spheres collinear with the C9 velocity have no transverse
 % direction from obstacle centres alone. An actual Flight gravity vector
 % defines a transverse PLANE (not a preferred side): both signs are
 % checked by the same group-plane search. This never certifies a path.
 S1=OBSTACLE_INFORMATION.define(151,'sphere',[-0.12 0 3],0.15);
 S2=OBSTACLE_INFORMATION.define(152,'sphere',[+0.12 0 3],0.15);
 C=TRAJECTORY_OBSTACLE_SUPPORT.prepare([S1 S2]);
 failcol=struct('unresolved_time_interval_s',[12.21875 12.375], ...
   'unresolved_obstacle_ids',151,'unresolved_body_indices',3);
 Gno=TRAJECTORY_C9_CONFLICT_GROUP_GUIDE( ...
   nominal,C,failcol,0.1,1e-5);
 Gg=TRAJECTORY_C9_CONFLICT_GROUP_GUIDE( ...
   nominal,C,failcol,0.1,1e-5,authority.gravity_world_mps2);
 R.gravity_collinear_without_vector_unknown=~Gno.active;
 R.gravity_collinear_bypass_pass=Gg.active && ...
    abs(norm(Gg.normal)-1)<1e-12 && ...
    abs(Gg.normal.'*[1;0;0])<1e-10;
 assert(R.gravity_collinear_without_vector_unknown && ...
    R.gravity_collinear_bypass_pass,'CHECK_C9_GROUP:GravityCollinear', ...
    'Gravity-assisted covariant transverse plane failed.');
 % Transform ALL geometry vectors and real gravity by the same SO(3).
 % This test is frame-covariance, not an obstacle-specific flight rule.
 axis3=[0.37;0.64;-0.19];axis3=axis3/norm(axis3);
 K=[0 -axis3(3) axis3(2);axis3(3) 0 -axis3(1); ...
    -axis3(2) axis3(1) 0];
 angle3=0.57;
 Q3=eye(3)+sin(angle3)*K+(1-cos(angle3))*(K*K);
 C3=C;
 for k=1:numel(C)
    C3(k).center=Q3*C(k).center;
    C3(k).R=Q3*C(k).R;
 end
 rotated_collinear=nominal;
 rotated_collinear.control_points_m=Q3*nominal.control_points_m;
 Gg3=TRAJECTORY_C9_CONFLICT_GROUP_GUIDE(rotated_collinear, ...
   C3,failcol,0.1,1e-5,Q3*authority.gravity_world_mps2);
 R.gravity_collinear_SO3_covariance=Gg3.active && ...
   norm(Q3*Gg.normal-Gg3.normal)<1e-9;
 assert(R.gravity_collinear_SO3_covariance, ...
   'CHECK_C9_GROUP:GravitySO3', ...
   'Live-gravity collinear fallback is not SO(3)-equivariant.');
 % The 12-shape support oracle returns a genuine shape point, never an
 % arbitrary convex-hull interior proxy. One such point in an inflated
 % payload sphere proves this candidate cannot meet robust separation.
 W=TRAJECTORY_C9_POINT_INTERSECTION_PREFILTER( ...
   nominal,shapes,failing,[0.1 0.02 0.1], ...
   authority.gravity_world_mps2,authority.cable_length_m);
 R.prefilter_collision_witness_pass=W.definite_intersection && ...
   W.obstacle_id==21 && W.body_index==3;
 assert(R.prefilter_collision_witness_pass, ...
   'CHECK_C9_GROUP:PrefilterPositive', ...
   'Known payload-sphere overlap must reject the candidate.');
 far_sphere=OBSTACLE_INFORMATION.define(21,'sphere',[100 100 100],0.2);
 far_for_filter=TRAJECTORY_OBSTACLE_SUPPORT.prepare(far_sphere);
 Wfar=TRAJECTORY_C9_POINT_INTERSECTION_PREFILTER( ...
   nominal,far_for_filter,failing,[0.1 0.02 0.1], ...
   authority.gravity_world_mps2,authority.cable_length_m);
 R.prefilter_noncollision_not_rejected=~Wfar.definite_intersection;
 assert(R.prefilter_noncollision_not_rejected, ...
   'CHECK_C9_GROUP:PrefilterNegative', ...
   'Far shape must not cause false rejection.');
 assert(R.geometry_group_nonconnected_rejected, ...
   'CHECK_C9_GROUP:Disconnected','Unrelated far shape was grouped.');
 % One connected chain of spheres: closure must reach all obstacles
 % without retesting the same unordered pair on every group iteration.
 chain=OBSTACLE_INFORMATION.define(201,'sphere',[-0.7 0 3],0.16);
 for k=2:8
   chain(end+1)=OBSTACLE_INFORMATION.define(200+k,'sphere', ...
      [-0.7+(k-1)*0.2 0 3],0.16); %#ok<AGROW>
 end
 chain_shapes=TRAJECTORY_OBSTACLE_SUPPORT.prepare(chain);
 chain_fail=struct('unresolved_time_interval_s',[12.21875 12.375], ...
     'unresolved_obstacle_ids',201,'unresolved_body_indices',3);
 chain_group=TRAJECTORY_C9_CONFLICT_GROUP_GUIDE( ...
     nominal,chain_shapes,chain_fail,0.1,1e-5, ...
     authority.gravity_world_mps2);
 R.group_graph_pair_tests=chain_group.adjacency_pair_tests;
 assert(chain_group.active&&chain_group.group_size==8 && ...
     chain_group.adjacency_pair_tests<=8*7/2, ...
     'CHECK_C9_GROUP:GraphClosure', ...
     'Connected-cluster closure must be bounded by unordered pairs.');
 R.stage='READ_HLC_NONLINEAR_METHOD_CLOSURE_FOR_THEORY';
 % A one-time development-time source-availability check, NEVER in Flight.
 % HLC.do calls these five nonlinear methods. The class wrapper alone does
 % NOT prove exact virtual feedback linearization or actuator headroom.
 required_methods={'Vfd_SuspendedLoadxyDst','Vs_SuspendedLoadxyDst', ...
   'Uf_SuspendedLoadxyDst','Beta2_SuspendedLoadxyDst', ...
   'V2_alpha2_SuspendedLoadxyDst'};
 R.hlc_nonlinear_method_paths=cell(1,numel(required_methods));
 try
   actual_methods=methods('HLC_SUSPENDED_LOAD');
   for k=1:numel(required_methods)
     R.hlc_nonlinear_methods_found(k)= ...
       ismember(required_methods{k},actual_methods);
     if R.hlc_nonlinear_methods_found(k)
       R.hlc_nonlinear_method_paths{k}= ...
         which(['HLC_SUSPENDED_LOAD/' required_methods{k}]);
     end
   end
 catch
   % This is diagnostic, not an artificial failure of the trajectory
   % optimization or the conditional linear Lyapunov lemma.
 end
 R.stage='VERIFY_HLC_VIRTUAL_ERROR_LEMMA_NOT_PHYSICAL_HLC';
 % Mathematical unit test: gains here are stable virtual-chain fixtures,
 % not the real Flight gains or a certified EKF disturbance bound.
 lemma2=TRAJECTORY_C9_HLC_VIRTUAL_ERROR_ENVELOPE( ...
   [1 2],0.1,0.02,4);
 lemma6=TRAJECTORY_C9_HLC_VIRTUAL_ERROR_ENVELOPE( ...
   [1 6 15 20 15 6],0.1,0.02,4);
 R.conditional_hlc_virtual_lemma_pass= ...
   startsWith(lemma2.status,'CONDITIONAL_VIRTUAL_ERROR_ENVELOPE')&& ...
   startsWith(lemma6.status,'CONDITIONAL_VIRTUAL_ERROR_ENVELOPE')&& ...
   ~lemma2.safe_to_commit&&~lemma6.safe_to_commit&& ...
   ~lemma2.physical_HLC_input_certified&& ...
   ~lemma6.physical_HLC_input_certified;
 assert(R.conditional_hlc_virtual_lemma_pass, ...
   'CHECK_C9_GROUP:VirtualLemma','Conditional error lemma invalid.');
 R.stage='PAIR_ALL_TIME_PROVEN_ON_OFF_WHOLE_PIPELINE';
 R.status_on=cell(1,3);R.status_off=cell(1,3);
 R.group_ids=cell(1,3);R.group_search_status=cell(1,3);
 R.proof_status_history_on=cell(1,3);R.proof_status_history_off=cell(1,3);
 R.unresolved_ids_on=cell(1,3);R.unresolved_ids_off=cell(1,3);
 R.no_unproven_candidate_accepted=true;
 for j=1:3
   req.observed=scenes{j};
   on=req;on.search_options.enable_connected_group_topology=true;
   on.search_options.enable_point_intersection_prefilter=true;
   off=req;off.search_options.enable_connected_group_topology=false;
   off.search_options.enable_point_intersection_prefilter=false;
   A=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(on);
   B=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(off);
   R.status_on{j}=A.status;R.status_off{j}=B.status;
   R.proof_calls_on(j)=A.proof_calls;
   R.proof_calls_off(j)=B.proof_calls;
   Sa=A.search_result;Sb=B.search_result;
   R.groups_used(j)=Sa.topology_group_active;
   R.group_attempts(j)=Sa.topology_group_attempts;
   R.group_ids{j}=Sa.topology_group_ids;
   R.group_normal(:,j)=Sa.topology_group_normal;
   R.group_search_status{j}=Sa.topology_group_status;
   R.prefilter_rejected_candidates_on(j)= ...
      Sa.point_intersection_skipped_full_proofs;
   R.prefilter_time_ms_on(j)=Sa.point_intersection_time_total_ms;
   R.proof_status_history_on{j}=Sa.proof_status_history;
   R.proof_status_history_off{j}=Sb.proof_status_history;
   R.unresolved_ids_on{j}=Sa.proof_unresolved_obstacle_id_history;
   R.unresolved_ids_off{j}=Sb.proof_unresolved_obstacle_id_history;
   assert(~Sa.candidate_available||Sa.final_certificate.certified, ...
     'CHECK_C9_GROUP:Unchecked','Unproven C9 candidate returned.');
   assert(~Sb.candidate_available||Sb.final_certificate.certified, ...
     'CHECK_C9_GROUP:Unchecked','Unproven baseline C9 returned.');
   R.no_unproven_candidate_accepted= ...
     R.no_unproven_candidate_accepted && ~A.safe_to_commit && ...
     ~B.safe_to_commit && ~A.actual_HLC_tracking_proven && ...
     ~B.actual_HLC_tracking_proven;
   assert(R.no_unproven_candidate_accepted, ...
     'CHECK_C9_GROUP:Commit','HLC closed-loop not proven.');
   onms=zeros(1,R.repetitions);offms=onms;
   onstages=zeros(6,R.repetitions);offstages=onstages;
   for rep=1:R.repetitions
     if mod(rep,2)==1
       a=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(on);
       b=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(off);
     else
       b=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(off);
       a=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(on);
     end
     assert(strcmp(a.status,A.status)&&strcmp(b.status,B.status), ...
       'CHECK_C9_GROUP:Nondeterminism','Status changed during timings.');
     onms(rep)=a.total_elapsed_ms;offms(rep)=b.total_elapsed_ms;
     onstages(:,rep)=[a.joint_geometry_force_proof_ms; ...
         a.separation_planes_ms;a.joint_QP_ms; ...
         a.heading_join_ms;a.nominal_torque_ms; ...
         max(0,a.total_elapsed_ms-(a.joint_geometry_force_proof_ms + ...
         a.separation_planes_ms+a.joint_QP_ms+ ...
         a.heading_join_ms+a.nominal_torque_ms))];
     offstages(:,rep)=[b.joint_geometry_force_proof_ms; ...
         b.separation_planes_ms;b.joint_QP_ms; ...
         b.heading_join_ms;b.nominal_torque_ms; ...
         max(0,b.total_elapsed_ms-(b.joint_geometry_force_proof_ms + ...
         b.separation_planes_ms+b.joint_QP_ms+ ...
         b.heading_join_ms+b.nominal_torque_ms))];
   end
   R.stage_median_ms_on(:,j)=median(onstages,2);
   R.stage_median_ms_off(:,j)=median(offstages,2);
   R.median_ms_on(j)=median(onms);R.median_ms_off(j)=median(offms);
   x=sort(onms);R.p95_ms_on(j)=x(ceil(.95*numel(x)));
   x=sort(offms);R.p95_ms_off(j)=x(ceil(.95*numel(x)));
   R.max_ms_on(j)=max(onms);R.max_ms_off(j)=max(offms);
 end
 assert(R.groups_used(1)==0, ...
   'CHECK_C9_GROUP:SphereRegression','Grouping single shape is forbidden.');
 R.status='PASS_MULTIOBSTACLE_GROUP_A_B_AUDIT__HLC_UNCERTIFIED';
 R.stage='COMPLETE';
catch ME
 R.error_identifier=ME.identifier;R.error_message=ME.message;
 R.error_stack=arrayfun(@(e)sprintf('%s:%d',e.name,e.line), ...
   ME.stack,'UniformOutput',false);
end
name='TRAJECTORY_C9_MULTIOBSTACLE_TOPOLOGY_RESULT';
save(fullfile(root,[name '.mat']),'R');
fid=fopen(fullfile(root,[name '.txt']),'w');
if fid>=0
 fprintf(fid,'status=%s\nstage=%s\nerror=%s | %s\n', ...
   R.status,R.stage,R.error_identifier,R.error_message);
 for j=1:numel(R.error_stack)
   fprintf(fid,'stack_%d=%s\n',j,R.error_stack{j});
 end
 fprintf(fid,'gravity_collinear_direction=%d\n', ...
    R.gravity_collinear_bypass_pass);
 fprintf(fid,'gravity_collinear_SO3=%d\n', ...
    R.gravity_collinear_SO3_covariance);
 fprintf(fid,'gravity_without_authority_unknown=%d\n', ...
    R.gravity_collinear_without_vector_unknown);
 fprintf(fid,'chain_adjacency_pair_tests=%g\n',R.group_graph_pair_tests);
 for j=1:numel(R.scene_names)
   if numel(R.status_on)<j,continue;end
   fprintf(fid,['scene=%s | on=%s | off=%s | group=%g | ', ...
     'group_ids=%s | early_rejections=%g | calls=%g vs %g | ', ...
     'median_ms=%.6f vs %.6f | p95_ms=%.6f vs %.6f\n'], ...
     R.scene_names{j},R.status_on{j},R.status_off{j}, ...
     R.groups_used(j),mat2str(R.group_ids{j}), ...
     R.prefilter_rejected_candidates_on(j),R.proof_calls_on(j),R.proof_calls_off(j), ...
     R.median_ms_on(j),R.median_ms_off(j), ...
     R.p95_ms_on(j),R.p95_ms_off(j));
   fprintf(fid,'stage_median_ms_names=%s\n', ...
      strjoin(R.stage_timing_names,','));
   fprintf(fid,'stage_median_ms_on=%s | off=%s\n', ...
      mat2str(R.stage_median_ms_on(:,j).',6), ...
      mat2str(R.stage_median_ms_off(:,j).',6));
 end
 fclose(fid);
end
zip(R.zip_path,{[name '.mat'],[name '.txt']},root);
fprintf('[C9 GROUP TOPOLOGY] %s | %s\n',R.status,R.zip_path);
end
