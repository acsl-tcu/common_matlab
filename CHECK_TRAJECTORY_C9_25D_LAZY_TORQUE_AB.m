function R=CHECK_TRAJECTORY_C9_25D_LAZY_TORQUE_AB()
%CHECK_TRAJECTORY_C9_25D_LAZY_TORQUE_AB Research root-only audit.
% Full 27-degree C9/25D integrated solver; old QP vs evidence-driven
% torque-row activation. Always independently certifies all-time geometry,
% tension, thrust, heading and nominal torque. No fake HLC B PASS.
root=fileparts(mfilename('fullpath'));
R=struct('status','FAIL_C9_25D_LAZY_TORQUE_AB', ...
    'error_message','','modes',{{'baseline','certificate_driven'}}, ...
    'completed_pairs',0,'nominal_success',false(2,5), ...
    'search_status',{{}},'failure_reason',{{}}, ...
    'whole_ms',NaN(2,5),'proof_ms',NaN(2,5), ...
    'QP_construction_ms',NaN(2,5),'QP_solve_ms',NaN(2,5), ...
    'torque_jacobian_ms',NaN(2,5), ...
    'nominal_torque_proof_ms',NaN(2,5), ...
    'heading_ms',NaN(2,5), ...
    'QP_count',NaN(2,5), ...
    'lazy_torque_skips',NaN(2,5), ...
    'torque_proof_failure_witnesses',NaN(2,5), ...
    'median_ms',NaN(2,1),'p95_ms',NaN(2,1), ...
    'max_ms',NaN(2,1),'minimum_ms',NaN(2,1), ...
    'nominal_regressions',NaN,'HLC_B_proven',false, ...
    'safe_to_commit',false, ...
    'directed_body_tick_status','NOT_RUN', ...
    'directed_body_tick_distant_pass',false, ...
    'directed_body_tick_near_reject',false);
try
    N=TRAJECTORY_C9_TORQUE_WHOLE_27_PREFLIGHT(false);
    assert(N.ready,['27 degree torque preflight: ' N.status]);
    T=27;speed=1;
    J0=zeros(3,10);J1=zeros(3,10);
    J0(:,1)=[0;0;3];J1(:,1)=[0;T*speed;3];
    J0(:,2)=[0;speed;0];J1(:,2)=[0;speed;0];
    free23=[zeros(1,4);(10:13)*T/23;3*ones(1,4)];
    a=struct('cable_length_m',2,'payload_mass_kg',0.14, ...
        'uav_mass_kg',1.1,'gravity_world_mps2',[0;0;-9.80665], ...
        'thrust_limits_N',[0;20],'minimum_tension_N',0, ...
        'acceleration_guard_mps2',0, ...
        'uav_inertia_kgm2',[0.012;0.013;0.022], ...
        'torque_limits_Nm',[-1 1;-1 1;-1 1]);
    radius=struct('uav_m',0.3,'cable_m',0.01,'payload_m',0.2);
    geo=struct('max_subdivision_depth',8,'max_node_count',900, ...
        'numerical_guard_m',0,'robust_tube_enabled',false, ...
        'trajectory_phase','f','use_exact_direction_cone_support',true, ...
        'use_native_support_separator',false);
    force=struct('max_subdivision_depth',8,'max_node_count',900, ...
        'force_guard_N',0);
    heading=struct('max_subdivision_depth',8,'max_node_count',900, ...
        'horizontal_velocity_guard_mps',0,'w_guard_mps2',0, ...
        'payload_jet_tolerance',zeros(3,10), ...
        'uav_jet_tolerance',zeros(3,8), ...
        'yaw_jet_tolerance',zeros(1,7));
    torque=struct('max_subdivision_depth',8,'max_node_count',900, ...
        'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
        'torque_guard_Nm',zeros(3,1), ...
        'use_native_whole_torque_kernel',true);
    opt=struct('probe_count',5,'max_outer_iterations',2, ...
        'max_projection_sweeps',800, ...
        'projection_tolerance_m',1e-8,'min_separation_m',1e-3, ...
        'enable_degree27_25d_joint_search',1, ...
        'enable_25d_nominal_torque_local_rows',1, ...
        'enable_13d_variable_time_joint_search',0);
    req=struct('t0_s',0,'duration_s',T, ...
        'flight_interval_s',[0 40], ...
        'start_jets',J0,'end_jets',J1,'nominal_free',free23, ...
        'nominal_free27',[zeros(1,8);(10:17);3*ones(1,8)], ...
        'observed',OBSTACLE_INFORMATION.define(801,'sphere', ...
            [0.22,13,3],0.8), ...
        'radii',radius,'authority',a, ...
        'geometry_options',geo,'force_options',force, ...
        'heading_options',heading,'torque_options',torque, ...
        'nominal_torque_options',torque,'search_options',opt);
    % Alternate order between repetitions to reduce warm-cache bias.
    R.search_status=cell(2,5);R.failure_reason=cell(2,5);
    for k=1:5
        order=[1 2];if mod(k,2)==0,order=[2 1];end
        for mi=order
            request=req;
            request.search_options.enable_25d_certificate_driven_torque_rows=double(mi==2);
            V=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(request);
            R.whole_ms(mi,k)=V.total_elapsed_ms;
            R.nominal_success(mi,k)=V.nominal_model_complete;
            R.search_status{mi,k}=V.search_status;
            R.failure_reason{mi,k}=V.failure_detail;
            assert(~V.safe_to_commit && ~V.actual_HLC_tracking_proven, ...
                'An unproved future HLC B must never permit Flight.');
            if isfield(V,'search_result') && isstruct(V.search_result)
                S=V.search_result;
                R.proof_ms(mi,k)=getnumber(S,'duration_25d_proof_ms');
                R.QP_construction_ms(mi,k)=getnumber(S,'duration_25d_plane_ms');
                R.QP_solve_ms(mi,k)=getnumber(S,'duration_25d_qp_ms');
                R.torque_jacobian_ms(mi,k)=getnumber(S,'duration_25d_torque_tangent_ms');
                R.nominal_torque_proof_ms(mi,k)=getnumber(S,'duration_25d_torque_ms');
                R.heading_ms(mi,k)=getnumber(S,'duration_25d_heading_ms');
                R.QP_count(mi,k)=getnumber(S,'duration_25d_qp_count');
                R.lazy_torque_skips(mi,k)=getnumber(S,'duration_25d_lazy_torque_skipped_qps');
                R.torque_proof_failure_witnesses(mi,k)= ...
                    getnumber(S,'duration_25d_torque_failure_witnesses');
            end
        end
        R.completed_pairs=k;
    end
    R.nominal_regressions=nnz(R.nominal_success(1,:)&~R.nominal_success(2,:));
    for mi=1:2
        v=sort(R.whole_ms(mi,:));
        R.median_ms(mi)=median(v);
        R.p95_ms(mi)=interp1(1:5,v,4.8,'linear');
        R.max_ms(mi)=v(end);
        R.minimum_ms(mi)=v(1);
    end
    % Source-reach body lemma: independent optional proof fixture; does
    % not claim it was computed by the actual Flight plant integrator.
    Y=zeros(24,2);
    Y(1:3,:)=repmat([0;0;5],1,2);
    Y(13:15,:)=repmat([0;0;3],1,2);
    far=[OBSTACLE_INFORMATION.define(901,'sphere',[20,5,8],0.7), ...
         OBSTACLE_INFORMATION.define(902,'ellipsoid', ...
             [12,18,6],[0.7 0.8 0.9],'euler_deg',[13 29 41])];
    F=TRAJECTORY_C9_HLC_TICK_BODY_SEPARATION_INTLAB(Y,far,radius);
    R.directed_body_tick_status=F.status;
    if exist('infsup','file')==2 && exist('intval','file')==2
        R.directed_body_tick_distant_pass=F.conditional_alltime_body_separation;
        assert(R.directed_body_tick_distant_pass, ...
            ['INTLAB distant source-body geometry failed: ' F.status]);
        near=OBSTACLE_INFORMATION.define(903,'sphere',[0,0,3],0.5);
        N=TRAJECTORY_C9_HLC_TICK_BODY_SEPARATION_INTLAB(Y,near,radius);
        R.directed_body_tick_near_reject=~N.conditional_alltime_body_separation;
        assert(R.directed_body_tick_near_reject, ...
            'Near payload collision must never be certified separate.');
    end
    if R.nominal_regressions>0
        R.status='UNKNOWN_LAZY_TORQUE_NOMINAL_REGRESSION__NO_COMMIT';
    elseif all(R.nominal_success(:))
        R.status='PASS_LAZY_TORQUE_25D_NOMINAL_AB__HLC_B_AND_5MS_PENDING';
    else
        R.status='UNKNOWN_LAZY_TORQUE_25D_COMPARISON__NO_COMMIT';
    end
catch ME
    R.error_message=getReport(ME,'extended','hyperlinks','off');
end
save(fullfile(root,'TRAJECTORY_C9_25D_LAZY_TORQUE_AB_RESULT.mat'),'R');
log=fullfile(root,'TRAJECTORY_C9_25D_LAZY_TORQUE_AB_RESULT.txt');
fid=fopen(log,'w');
if fid>=0
    fprintf(fid,'status=%s\nerror=%s\n',R.status,R.error_message);
    fprintf(fid,'completed_pairs=%d regressions=%g\n', ...
        R.completed_pairs,R.nominal_regressions);
    fprintf(fid,'success=%s\n',mat2str(R.nominal_success));
    fprintf(fid,'whole_ms=%s\n',mat2str(R.whole_ms,6));
    fprintf(fid,'proof_ms=%s\n',mat2str(R.proof_ms,6));
    fprintf(fid,'QP_construction_ms=%s\n',mat2str(R.QP_construction_ms,6));
    fprintf(fid,'torque_jacobian_ms=%s\n',mat2str(R.torque_jacobian_ms,6));
    fprintf(fid,'QP_solve_ms=%s\n',mat2str(R.QP_solve_ms,6));
    fprintf(fid,'median_ms=%s p95_ms=%s max_ms=%s\n', ...
        mat2str(R.median_ms,6),mat2str(R.p95_ms,6),mat2str(R.max_ms,6));
    fprintf(fid,'lazy_torque_skips=%s\n',mat2str(R.lazy_torque_skips));
    fprintf(fid,'body_tick=%s distant=%d near_reject=%d\n', ...
        R.directed_body_tick_status, ...
        R.directed_body_tick_distant_pass, ...
        R.directed_body_tick_near_reject);
    for i=1:2
        for k=1:5
            fprintf(fid,'mode=%d repeat=%d status=%s reason=%s\n', ...
                i,k,c9_text(R.search_status{i,k}),c9_text(R.failure_reason{i,k}));
        end
    end
    fclose(fid);
end
out=fullfile(root,'TRAJECTORY_C9_25D_LAZY_TORQUE_AB_RESULT_FOR_CHATGPT.zip');
try
    if exist(out,'file'),delete(out);end
    zip(out,{'TRAJECTORY_C9_25D_LAZY_TORQUE_AB_RESULT.mat', ...
        'TRAJECTORY_C9_25D_LAZY_TORQUE_AB_RESULT.txt'},root);
catch
end
end

function v=getnumber(S,key)
v=NaN;
if isfield(S,key) && isnumeric(S.(key))&&isscalar(S.(key))
    v=double(S.(key));
end
end

function str=c9_text(x)
if isempty(x),str='';
elseif ischar(x),str=x;
elseif isstring(x)&&isscalar(x),str=char(x);
else,str='NOT_TEXT';end
end
