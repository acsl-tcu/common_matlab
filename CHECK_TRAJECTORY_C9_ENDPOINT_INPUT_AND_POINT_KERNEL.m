function R=CHECK_TRAJECTORY_C9_ENDPOINT_INPUT_AND_POINT_KERNEL()
% CHECK-only: mathematical fixed-endpoint torque necessity and O(Nprobe)
% duplicate derivative construction elimination. Never certifies all-time
% torque, physical tracking, or floating-point outward rounding.
% All generated artifacts are saved in common_matlab regardless of pwd.
root=fileparts(mfilename('fullpath'));
name='TRAJECTORY_C9_ENDPOINT_INPUT_AND_POINT_KERNEL_RESULT';
R=struct('status','FAIL_CHECK_NOT_STARTED','stage','INIT', ...
    'error_identifier','','error_message','','error_stack',{{}}, ...
    'endpoints_numerically_outside',false, ...
    'endpoints_unchanged_by_12_free_variables',false, ...
    'fixed_endpoint_gate_status','NOT_RUN', ...
    'zero_payload_mass_taut_gate_status','NOT_RUN', ...
    'fixed_endpoint_gate_witness_Nm',NaN(3,2), ...
    'fixed_endpoint_gate_proof_calls',NaN, ...
    'fixed_endpoint_gate_qp_ms',NaN, ...
    'valid_mask_equal',false,'point_max_abs_difference_Nm',NaN, ...
    'angular_rate_max_abs_difference',NaN, ...
    'median_ms_old',NaN,'median_ms_precomputed',NaN, ...
    'p95_ms_old',NaN,'p95_ms_precomputed',NaN, ...
    'safe_to_commit',false,'actual_hlc_tracking_proven',false, ...
    'scope','NUMERIC_NECESSARY_ENDPOINT_WITNESS_AND_POINT_AB__NOT_ALL_TIME', ...
    'zip_path',fullfile(root,[name '_FOR_CHATGPT.zip']));
try
    addpath(fullfile(root,'controller'),fullfile(root,'model'),'-begin');
    addpath(fullfile(root,'reference','REPLANNING_SYSTEM', ...
        'TRAJECTORY_GENERATION'), ...
        fullfile(root,'reference','REPLANNING_SYSTEM', ...
        'OBSTACLE_INFORMATION'),'-begin');
    R.stage='READ_ACTUAL_HLC_AND_FLIGHT_FIXTURE_PARAMETERS';
    [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    P.set("loadmass",0.14);  % CHECK fixture, never a production default.
    d=double(P.get(["mass","jx","jy","jz", ...
        "gravity","cableL","loadmass"]));
    d=d(:);lo=double(lo(:));hi=double(hi(:));
    assert(numel(d)==7&&all(isfinite(d))&&all(d>0)&& ...
        numel(lo)==4&&numel(hi)==4&&all(hi>lo), ...
        'C9_ENDPOINT_AB:Authority','Missing fixture authority.');
    a=struct('uav_mass_kg',d(1),'payload_mass_kg',d(7), ...
        'cable_length_m',d(6),'uav_inertia_kgm2',d(2:4), ...
        'gravity_world_mps2',[0;0;-d(5)], ...
        'thrust_limits_N',[lo(1) hi(1)], ...
        'torque_limits_Nm',[lo(2:4) hi(2:4)], ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0);
    topt=struct('max_subdivision_depth',8,'max_node_count',511, ...
        'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
        'torque_guard_Nm',zeros(3,1));

    R.stage='COMPARE_TWO_POINT_JET_EVALUATORS';
    L=zeros(3,10);E=zeros(3,10);
    L(:,1)=[-1;0;3];E(:,1)=[1;0;3];
    L(1,2)=0.5;E(1,2)=0.5;
    free=[-1+(10:13)*2/23;zeros(1,4);3*ones(1,4)];
    guide=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,6,L,E,free);
    ts=guide.t0_s+guide.duration_s*linspace(0,1,33);
    old=topt;old.use_precomputed_point_derivative_polygons=false;
    fast=topt;fast.use_precomputed_point_derivative_polygons=true;
    U=TRAJECTORY_C9_TORQUE_POINT_EVALUATE(guide,a,old,ts);
    V=TRAJECTORY_C9_TORQUE_POINT_EVALUATE(guide,a,fast,ts);
    assert(isequal(U.valid,V.valid)&&isequal(U.outside_limits,V.outside_limits), ...
        'C9_ENDPOINT_AB:Validity','Point valid/outside mask changed.');
    R.valid_mask_equal=true;
    assert(any(U.valid),'C9_ENDPOINT_AB:Fixture','No valid comparison points.');
    e=abs(U.torque_Nm(:,U.valid)-V.torque_Nm(:,U.valid));
    R.point_max_abs_difference_Nm=max(e(:));
    o=abs(U.angular_velocity_body_radps(:,U.valid)- ...
        V.angular_velocity_body_radps(:,U.valid));
    R.angular_rate_max_abs_difference=max(o(:));
    assert(R.point_max_abs_difference_Nm<= ...
        1e-10*max(1,max(abs(U.torque_Nm(:,U.valid)),[],'all')) && ...
        R.angular_rate_max_abs_difference<= ...
        1e-10*max(1,max(abs(U.angular_velocity_body_radps(:,U.valid)),[],'all')), ...
        'C9_ENDPOINT_AB:Parity','Point torque or angular rate changed.');
    N=7;told=zeros(1,N);tnew=zeros(1,N);
    for rep=1:N
        if mod(rep,2)
            t=tic;TRAJECTORY_C9_TORQUE_POINT_EVALUATE(guide,a,old,ts);
            told(rep)=1000*toc(t);
            t=tic;TRAJECTORY_C9_TORQUE_POINT_EVALUATE(guide,a,fast,ts);
            tnew(rep)=1000*toc(t);
        else
            t=tic;TRAJECTORY_C9_TORQUE_POINT_EVALUATE(guide,a,fast,ts);
            tnew(rep)=1000*toc(t);
            t=tic;TRAJECTORY_C9_TORQUE_POINT_EVALUATE(guide,a,old,ts);
            told(rep)=1000*toc(t);
        end
    end
    R.median_ms_old=median(told);R.median_ms_precomputed=median(tnew);
    so=sort(told);sn=sort(tnew);
    R.p95_ms_old=so(ceil(0.95*N));
    R.p95_ms_precomputed=sn(ceil(0.95*N));

    R.stage='IMMUTABLE_ENDPOINT_NOMINAL_TORQUE_WITNESS';
    % The jerk-to-higher-jet fixture is deliberately extreme to exercise
    % an early necessary rejection, not a real flight or tuning parameter.
    L(2,6)=1e6;  % payload fifth derivative at the START endpoint.
    bad=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,6,L,E,free);
    bad2=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,6,L,E, ...
        free+[2 -3 4 -5;3 -2 1 5;1 2 3 4]);
    tt=[8 14];
    badProbe=TRAJECTORY_C9_TORQUE_POINT_EVALUATE(bad,a,fast,tt);
    alteredProbe=TRAJECTORY_C9_TORQUE_POINT_EVALUATE(bad2,a,fast,tt);
    R.endpoints_numerically_outside=any(badProbe.valid & badProbe.outside_limits);
    assert(R.endpoints_numerically_outside && all(badProbe.valid), ...
        'C9_ENDPOINT_AB:NoWitness','Expected fixed-endpoint numerical violation unavailable.');
    R.endpoints_unchanged_by_12_free_variables= ...
        all(alteredProbe.valid==badProbe.valid) && ...
        max(abs(alteredProbe.torque_Nm(:)-badProbe.torque_Nm(:)))<1e-7;
    assert(R.endpoints_unchanged_by_12_free_variables, ...
        'C9_ENDPOINT_AB:FixedJets','Changing 12 interior controls changed endpoint torque.');

    R.stage='ZERO_ESTIMATED_PAYLOAD_MASS_IS_UNKNOWN_TAUT_NOT_EXCEPTION';
    aZero=a;aZero.payload_mass_kg=0;
    zz=TRAJECTORY_C9_ENDPOINT_FORCE_NECESSITY( ...
        L,E,aZero,struct('force_guard_N',0));
    R.zero_payload_mass_taut_gate_status=zz.status;
    assert(~zz.possible && strcmp(zz.status, ...
        'UNKNOWN_FIXED_ENDPOINT_TENSION_LIMIT'), ...
        'C9_ENDPOINT_AB:ZeroMass','Zero mass must be UNKNOWN tautness, not an exception.');

    R.stage='EARLY_EXIT_BEFORE_GEOMETRY_OR_QP';
    observed=OBSTACLE_INFORMATION.define(13,'sphere',[0 0 3],0.15);
    sopt=struct('probe_count',5,'max_outer_iterations',2, ...
        'max_projection_sweeps',16,'projection_tolerance_m',1e-8, ...
        'min_separation_m',1e-5, ...
        'enable_torque_aware_joint_search',true, ...
        'torque_probe_count',3, ...
        'enable_fixed_endpoint_torque_necessity',true);
    gopt=struct('max_subdivision_depth',4,'max_node_count',31, ...
        'numerical_guard_m',0,'robust_tube_enabled',false, ...
        'trajectory_phase','f');
    fopt=struct('max_subdivision_depth',4,'max_node_count',31, ...
        'force_guard_N',0);
    req=struct('t0_s',8,'duration_s',6,'flight_interval_s',[8 24], ...
        'start_jets',L,'end_jets',E,'nominal_free',free, ...
        'observed',observed, ...
        'radii',struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1), ...
        'authority',a,'geometry_options',gopt,'force_options',fopt, ...
        'search_options',sopt,'torque_options',fast);
    G=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(req);
    R.fixed_endpoint_gate_status=G.status;
    R.fixed_endpoint_gate_witness_Nm=G.fixed_endpoint_torque_values_Nm;
    R.fixed_endpoint_gate_proof_calls=G.independent_proof_calls;
    R.fixed_endpoint_gate_qp_ms=G.joint_qp_time_total_ms;
    assert(strcmp(G.status,'UNKNOWN_FIXED_ENDPOINT_NOMINAL_TORQUE_LIMIT') && ...
        ~G.candidate_available&&~G.safe_to_commit&& ...
        G.fixed_endpoint_torque_gate_enabled&& ...
        any(G.fixed_endpoint_torque_outside_limits)&& ...
        G.independent_proof_calls==0&&G.joint_qp_time_total_ms==0, ...
        'C9_ENDPOINT_AB:Gate','Endpoint violation must bypass all expensive proof/QP calls.');
    R.status='PASS_FIXED_ENDPOINT_TORQUE_NECESSITY_AND_FAST_POINT_AB__HLC_UNCERTIFIED';
catch ME
    R.status='FAIL_C9_ENDPOINT_TORQUE_AND_POINT_AB';
    R.error_identifier=ME.identifier;R.error_message=ME.message;
    R.error_stack=arrayfun(@(x)sprintf('%s:%d',x.name,x.line), ...
        ME.stack,'UniformOutput',false);
end
save(fullfile(root,[name '.mat']),'R');
fid=fopen(fullfile(root,[name '.txt']),'w');
if fid>=0
    fprintf(fid,'status=%s stage=%s error=%s %s\n', ...
        R.status,R.stage,R.error_identifier,R.error_message);
    for j=1:numel(R.error_stack), fprintf(fid,'stack=%s\n',R.error_stack{j});end
    fprintf(fid,'endpoint_outside=%d endpoint_fixed_free_invariant=%d\n', ...
        R.endpoints_numerically_outside,R.endpoints_unchanged_by_12_free_variables);
    fprintf(fid,'zero_mass_taut_status=%s\n',R.zero_payload_mass_taut_gate_status);
    fprintf(fid,'gate=%s full_geometry_proofs=%g QP_ms=%g\n', ...
        R.fixed_endpoint_gate_status,R.fixed_endpoint_gate_proof_calls, ...
        R.fixed_endpoint_gate_qp_ms);
    fprintf(fid,'valid_mask_equal=%d torque_error_Nm=%.12g omega_error=%.12g\n', ...
        R.valid_mask_equal,R.point_max_abs_difference_Nm, ...
        R.angular_rate_max_abs_difference);
    fprintf(fid,'point_eval_33_samples_old/new_median_ms=%.9f %.9f\n', ...
        R.median_ms_old,R.median_ms_precomputed);
    fprintf(fid,'point_eval_33_samples_old/new_p95_ms=%.9f %.9f\n', ...
        R.p95_ms_old,R.p95_ms_precomputed);
    fprintf(fid,'safe_to_commit=%d actual_hlc_tracking_proven=%d\n', ...
        R.safe_to_commit,R.actual_hlc_tracking_proven);
    fclose(fid);
end
zip(R.zip_path,{[name '.mat'],[name '.txt']},root);
fprintf('[C9 ENDPOINT INPUT & POINT KERNEL] %s\n',R.status);
end
