function R=CHECK_TRAJECTORY_C9_VECTOR_INTERVAL_AB()
% Development-only A/B: current vectorized interval dot/cross vs frozen
% previous scalar-loop certificate (CHECK_C9_TORQUE_SCALAR_REFERENCE).
% All results stay in common_matlab, independent of current working folder.
% This is NOT a closed-loop HLC or directed-rounding certificate.
root=fileparts(mfilename('fullpath'));
name='TRAJECTORY_C9_VECTOR_INTERVAL_AB_RESULT';
R=struct('status','FAIL_C9_VECTOR_INTERVAL_AB','stage','START', ...
    'error_identifier','','error_message','','error_stack',{{}}, ...
    'scene_names',{{'SMOOTH_NOMINAL','SPHERE_ELLIPSOID_CERTIFIED_GUIDE'}}, ...
    'mode_names',{{'SCALAR_REFERENCE','VECTOR_KERNEL'}}, ...
    'status_by_mode',{{}},'nodes_by_mode',NaN(2,2), ...
    'detailed_nodes_by_mode',NaN(2,2), ...
    'quick_leaves_by_mode',NaN(2,2), ...
    'witness_nodes_by_mode',NaN(2,2), ...
    'max_torque_bound_difference_Nm',NaN(1,2), ...
    'unknown_interval_s',NaN(1,2), ...
    'unknown_interval_bounds_Nm',NaN(3,2), ...
    'unknown_interval_valid',false, ...
    'unknown_interval_headroom_Nm',NaN, ...
    'unknown_leaf_reason','NOT_EVALUATED', ...
    'median_ms_by_mode',NaN(2,2),'p95_ms_by_mode',NaN(2,2), ...
    'max_ms_by_mode',NaN(2,2), ...
    'random_kernel_trials',0,'random_kernel_pass',false, ...
    'search_status','NOT_CALLED','search_elapsed_ms',NaN, ...
    'search_independent_proof_calls',NaN, ...
    'repetitions',7,'safe_to_commit',false, ...
    'scope','REAL_ARITHMETIC_NOMINAL_TORQUE_ONLY__HLC_AND_ROUNDING_NOT_PROVEN', ...
    'zip_path',fullfile(root,[name '_FOR_CHATGPT.zip']));
try
    R.stage='RANDOM_INTERVAL_DOT_CROSS_PARITY';
    previous_rng=rng;
    cleanup_rng=onCleanup(@()rng(previous_rng));
    rng(419,'twister');
    for k=1:2000
        na=0.1+2*rand(3,1); nb=0.1+2*rand(3,1);
        ca=20*rand(3,1)-10;cb=20*rand(3,1)-10;
        alo=ca-na;ahi=ca+na;blo=cb-nb;bhi=cb+nb;
        [dr0,dr1]=local_dot_scalar(alo,ahi,blo,bhi);
        [dv0,dv1]=local_dot_vector(alo,ahi,blo,bhi);
        [cr0,cr1]=local_cross_scalar(alo,ahi,blo,bhi);
        [cv0,cv1]=local_cross_vector(alo,ahi,blo,bhi);
        vals=[dr0;dr1;dv0;dv1;cr0;cr1;cv0;cv1];
        tol=2e-13*max(1,max(abs(vals(:))));
        assert(abs(dr0-dv0)<=tol&&abs(dr1-dv1)<=tol&& ...
          all(abs(cr0-cv0)<=tol)&&all(abs(cr1-cv1)<=tol), ...
          'C9_INTERVAL_AB:KernelParity','Interval corner bounds differ.');
    end
    R.random_kernel_trials=2000;
    R.random_kernel_pass=true;
    clear cleanup_rng

    R.stage='CURRENT_REAL_HLC_LIMITS_AND_C9_FIXTURES';
    addpath(fullfile(root,'controller'),fullfile(root,'model'),'-begin');
    addpath(fullfile(root,'reference','REPLANNING_SYSTEM', ...
      'TRAJECTORY_GENERATION'), ...
      fullfile(root,'reference','REPLANNING_SYSTEM', ...
      'OBSTACLE_INFORMATION'),'-begin');
    [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    P.set("loadmass",0.14); % CHECK fixture only; no production default.
    d=double(P.get(["mass","jx","jy","jz","gravity","cableL","loadmass"]));
    d=d(:);lo=double(lo(:));hi=double(hi(:));
    assert(numel(d)==7&&all(isfinite(d))&&all(d>0)&& ...
      numel(lo)==4&&numel(hi)==4&&all(hi>lo), ...
      'C9_INTERVAL_AB:Authority','Cannot read current HLC/plant bounds.');
    a=struct('uav_mass_kg',d(1),'payload_mass_kg',d(7), ...
      'cable_length_m',d(6),'uav_inertia_kgm2',d(2:4), ...
      'gravity_world_mps2',[0;0;-d(5)], ...
      'thrust_limits_N',[lo(1),hi(1)], ...
      'torque_limits_Nm',[lo(2:4),hi(2:4)], ...
      'minimum_tension_N',0,'acceleration_guard_mps2',0);
    opt=struct('max_subdivision_depth',8,'max_node_count',511, ...
      'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
      'torque_guard_Nm',zeros(3,1), ...
      'enable_fast_norm_sufficient_bound',true, ...
      'use_precomputed_binomial',true, ...
      'use_factored_diagonal_gyro',true, ...
      'enable_infeasible_leaf_early_exit',true);
    J0=zeros(3,10);J1=zeros(3,10);
    J0(:,1)=[-2;0;3];J1(:,1)=[2;0;3];
    J0(1,2)=0.4;J1(1,2)=0.4;
    nominal=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,10,J0,J1, ...
      repmat([0;0;3],1,4));
    R.stage='GENERATE_CERTIFIED_GUIDE_ONCE';
    theta=0.34;Q=[cos(theta) -sin(theta) 0; ...
                     sin(theta) cos(theta) 0;0 0 1];
    observed=[OBSTACLE_INFORMATION.define(21,'sphere',[0 0.1 3],0.2), ...
      OBSTACLE_INFORMATION.define(33,'ellipsoid',[0.6 -0.16 3], ...
      [0.32 0.19 0.4],'rotation',Q)];
    gopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
      'numerical_guard_m',0,'robust_tube_enabled',false, ...
      'trajectory_phase','f');
    fopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
      'force_guard_N',0);
    sopt=struct('probe_count',13,'max_outer_iterations',4, ...
      'max_projection_sweeps',100,'projection_tolerance_m',1e-8, ...
      'min_separation_m',1e-5, ...
      'lazy_initial_proof_on_violated_plane',false, ...
      'payload_hull_witness_policy','off', ...
      'embed_taut_bernstein_halfspaces',false, ...
      'accept_first_certified_minimum_qp',false, ...
      'enable_connected_group_topology',true, ...
      'enable_point_intersection_prefilter',true);
    req=struct('t0_s',8,'duration_s',10,'flight_interval_s',[8 30], ...
      'start_jets',J0,'end_jets',J1, ...
      'nominal_free',nominal.control_points_m(:,11:14), ...
      'observed',observed, ...
      'radii',struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1), ...
      'authority',a,'geometry_options',gopt, ...
      'force_options',fopt,'search_options',sopt);
    S=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(req);
    R.search_status=S.status;
    R.search_elapsed_ms=S.elapsed_ms;
    R.search_independent_proof_calls=S.independent_proof_calls;
    assert(S.candidate_available&&S.final_certificate.certified&& ...
      ~S.safe_to_commit, 'C9_INTERVAL_AB:Guide', ...
      ['No geometry-certified fixture: ' S.status]);
    pieces={nominal,S.candidate_piece};
    fun={@CHECK_C9_TORQUE_SCALAR_REFERENCE, ...
         @TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL};
    R.status_by_mode=cell(2,2);
    R.stage='CERTIFICATE_AB_7_REPEATS';
    for sc=1:2
        ref=cell(2,1);
        for m=1:2
            Z=fun{m}(pieces{sc},a,opt);
            assert(~Z.safe_to_commit&&~Z.actual_HLC_tracking_proven&& ...
              ~Z.numerically_directed_rounding_proven, ...
              'C9_INTERVAL_AB:NoCommit','Nominal results claimed closed-loop safety.');
            ref{m}=Z;
            R.status_by_mode{m,sc}=Z.status;
            R.nodes_by_mode(m,sc)=Z.checked_nodes;
            R.detailed_nodes_by_mode(m,sc)=Z.detailed_interval_checked_nodes;
            R.quick_leaves_by_mode(m,sc)=Z.fast_norm_accepted_leaves;
            R.witness_nodes_by_mode(m,sc)=Z.nominal_torque_limit_witness_nodes;
        end
        b=ref{1};v=ref{2};
        assert(strcmp(b.status,v.status)&&b.checked_nodes==v.checked_nodes&& ...
          b.accepted_leaves==v.accepted_leaves&& ...
          b.detailed_interval_checked_nodes==v.detailed_interval_checked_nodes&& ...
          isequaln(b.unresolved_interval_s,v.unresolved_interval_s), ...
          'C9_INTERVAL_AB:CertificateParity', ...
          'Vectorized kernel changed proof status or subdivision tree.');
        x=b.torque_bounds_Nm;y=v.torque_bounds_Nm;
        good=isnan(x)&isnan(y);
        gap=abs(x-y);gap(good)=0;
        finite_bounds=[x(~isnan(x));y(~isnan(y))];
        scale=1;
        if ~isempty(finite_bounds)
            scale=max(1,max(abs(finite_bounds)));
        end
        assert(all(good(:)|(isfinite(gap(:))&gap(:)<=1e-11*scale)), ...
          'C9_INTERVAL_AB:TorqueBoundParity', ...
          'Vectorized bound differs from frozen scalar certificate.');
        R.max_torque_bound_difference_Nm(sc)=max(gap(:));
        if sc==2
            R.unknown_interval_s=v.unresolved_interval_s;
            R.unknown_interval_bounds_Nm=v.unresolved_torque_bounds_Nm;
            R.unknown_interval_valid=v.unresolved_torque_interval_valid;
            R.unknown_interval_headroom_Nm=v.unresolved_torque_interval_headroom_Nm;
            R.unknown_leaf_reason=v.last_leaf_reason;
        end
        t=NaN(2,R.repetitions);
        for k=1:R.repetitions
            for pos=1:2
                m=mod(pos+k-2,2)+1;
                Z=fun{m}(pieces{sc},a,opt);
                assert(strcmp(Z.status,ref{m}.status)&& ...
                  Z.checked_nodes==ref{m}.checked_nodes, ...
                  'C9_INTERVAL_AB:Determinism','Repeated certificate differs.');
                t(m,k)=Z.elapsed_ms;
            end
        end
        for m=1:2
            R.median_ms_by_mode(m,sc)=median(t(m,:));
            u=sort(t(m,:));
            R.p95_ms_by_mode(m,sc)=u(ceil(.95*numel(u)));
            R.max_ms_by_mode(m,sc)=u(end);
        end
    end
    R.status='PASS_C9_VECTOR_INTERVAL_AB__HLC_UNCERTIFIED';
    R.stage='COMPLETE';
catch ME
    R.error_identifier=ME.identifier;
    R.error_message=ME.message;
    R.error_stack=arrayfun(@(e)sprintf('%s:%d',e.name,e.line), ...
      ME.stack,'UniformOutput',false);
end
save(fullfile(root,[name '.mat']),'R');
fid=fopen(fullfile(root,[name '.txt']),'w');
if fid>=0
    fprintf(fid,'status=%s\nstage=%s\nerror=%s | %s\n', ...
      R.status,R.stage,R.error_identifier,R.error_message);
    for k=1:numel(R.error_stack)
        fprintf(fid,'stack_%d=%s\n',k,R.error_stack{k});
    end
    fprintf(fid,'random_kernel_trials=%d | pass=%d\n', ...
       R.random_kernel_trials,R.random_kernel_pass);
    fprintf(fid,'search=%s | elapsed_ms=%.6f | independent_calls=%g\n', ...
       R.search_status,R.search_elapsed_ms,R.search_independent_proof_calls);
    for sc=1:2
        for m=1:2
            if numel(R.status_by_mode)<m+2*(sc-1),continue;end
            fprintf(fid,['scene=%s | mode=%s | status=%s | nodes=%g | ', ...
              'detailed=%g | median_ms=%.6f | p95_ms=%.6f | max_ms=%.6f\n'], ...
              R.scene_names{sc},R.mode_names{m},R.status_by_mode{m,sc}, ...
              R.nodes_by_mode(m,sc),R.detailed_nodes_by_mode(m,sc), ...
              R.median_ms_by_mode(m,sc),R.p95_ms_by_mode(m,sc), ...
              R.max_ms_by_mode(m,sc));
        end
    end
    fprintf(fid,'unresolved_time_s=[%.12g %.12g] | valid_box=%d | ', ...
      R.unknown_interval_s,R.unknown_interval_valid);
    fprintf(fid,'reason=%s | interval_headroom=%.12g\n', ...
      R.unknown_leaf_reason,R.unknown_interval_headroom_Nm);
    fprintf(fid,'unresolved_M_Nm=[%.12g %.12g; %.12g %.12g; %.12g %.12g]\n', ...
      R.unknown_interval_bounds_Nm.');
    fprintf(fid,'scope=%s | safe_to_commit=%d\n',R.scope,R.safe_to_commit);
    fclose(fid);
end
zip(R.zip_path,{[name '.mat'],[name '.txt']},root);
fprintf('[C9 VECTOR INTERVAL] %s | %s\n',R.status,R.zip_path);
end

function [z0,z1]=local_dot_scalar(a0,a1,b0,b1)
z0=0;z1=0;
for j=1:numel(a0)
    v=[a0(j)*b0(j),a0(j)*b1(j),a1(j)*b0(j),a1(j)*b1(j)];
    z0=z0+min(v);z1=z1+max(v);
end
end
function [z0,z1]=local_dot_vector(a0,a1,b0,b1)
v=[a0.*b0,a0.*b1,a1.*b0,a1.*b1];
z0=sum(min(v,[],2));z1=sum(max(v,[],2));
end
function [z0,z1]=local_cross_scalar(a0,a1,b0,b1)
z0=zeros(3,1);z1=zeros(3,1);
for i=1:3
    j=mod(i,3)+1;k=mod(i+1,3)+1;
    p=[a0(j)*b0(k),a0(j)*b1(k),a1(j)*b0(k),a1(j)*b1(k)];
    q=[a0(k)*b0(j),a0(k)*b1(j),a1(k)*b0(j),a1(k)*b1(j)];
    z0(i)=min(p)-max(q);z1(i)=max(p)-min(q);
end
end
function [z0,z1]=local_cross_vector(a0,a1,b0,b1)
j=[2;3;1];k=[3;1;2];
p=[a0(j).*b0(k),a0(j).*b1(k),a1(j).*b0(k),a1(j).*b1(k)];
q=[a0(k).*b0(j),a0(k).*b1(j),a1(k).*b0(j),a1(k).*b1(j)];
z0=min(p,[],2)-max(q,[],2);
z1=max(p,[],2)-min(q,[],2);
end
