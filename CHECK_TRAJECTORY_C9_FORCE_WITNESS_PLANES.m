function R=CHECK_TRAJECTORY_C9_FORCE_WITNESS_PLANES()
% Mathematical audit of local C9 force-witness gradients. No safety claim.
% This is intentionally independent of the eight geometry fixtures.
% Compare full analytic gradients with central differences of the SAME
% entire Bernstein-leaf sufficient-force upper bound, in NONIDENTITY
% QP whitening coordinates. Also verify thrust/tension inequalities create
% local search planes and retain the explicit no-COMMIT designation.
root=fileparts(mfilename('fullpath'));
addpath(fullfile(root,'controller'),'-begin');
[hlc_force_limits,~]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_limits();
P=zeros(3,24);
k=0:23;
P(1,:)=-2+4*k/23;
P(2,:)=0.19*sin(0.23*k)+0.08*cos(0.56*k);
P(3,:)=3+0.15*cos(0.34*k)+0.03*sin(0.74*k);
base=struct('control_points_m',P,'duration_s',10,'t0_s',0);
auth=struct('cable_length_m',2,'payload_mass_kg',0.2, ...
    'uav_mass_kg',1,'gravity_world_mps2',[0;0;-9.80665], ...
    'thrust_limits_N',[0,11.82],'minimum_tension_N',0, ...
    'acceleration_guard_mps2',0);
fopt=struct('force_guard_N',0);
M=[4.0 .7 .3 0;.7 2.3 -.2 .1;.3 -.2 3.1 .4;0 .1 .4 1.8];
U=chol(M,'upper');
intervals={[0 10],[2.1875 2.34375],[3.4375 3.59375]};
R=struct('status','FAIL_C9_FORCE_WITNESS_MATH', ...
    'cases_checked',numel(intervals), ...
    'maximum_whitened_gradient_error_N_per_m',0, ...
    'lower_gradient_max_error_N_per_m',0, ...
    'upper_plane_detected',false,'tension_plane_detected',false, ...
    'whole_interval_zero_sensitivity_rejected',false, ...
    'actual_interior_force_limit_violated',false, ...
    'endpoint_impossible_force_gate_rejected',false, ...
    'endpoint_valid_force_gate_accepted',false, ...
    'nonidentity_whitening_used',true,'no_safety_claim',true);
% A cap below the fixed-endpoint force is intentionally impossible to
% repair by the 4 free controls. A full-interval Bernstein upper bound can
% have ZERO gradient even if it violates the cap; NEVER invent a plane.
% Test the fail-closed case separately rather than demanding a fictitious
% plane for every proof-failing interval.
lowcap=auth;lowcap.thrust_limits_N=[0,8];
[Ap,bp,root]=TRAJECTORY_C9_FORCE_WITNESS_PLANE( ...
    base,lowcap,fopt,U,intervals{1}); %#ok<ASGLU>
R.whole_interval_zero_sensitivity_rejected= ...
    isempty(Ap)&&isempty(bp)&&root.immovable_violation&& ...
    root.zero_first_order_sensitivity&&root.planes==0&& ...
    strcmp(root.status,'UNKNOWN_UPPER_THRUST_LINEARIZATION_IMMOVABLE')&& ...
    root.upper_bound_N>8&&~root.safe_to_commit;
assert(R.whole_interval_zero_sensitivity_rejected, ...
    'CHECK_C9_FORCE:NoGradient', ...
    'A zero-gradient violated leaf must fail closed, not invent a plane.');
% Confirm that the shorter witness contains an ACTUAL model thrust deficit,
% not only a loose sufficient Bernstein upper bound.
D=cell(1,10);D{1}=P;
for j=1:9,D{j+1}=(24-j)/base.duration_s*diff(D{j},1,2);end
modelpiece=struct('control_points_m',P,'duration_s',10, ...
    't0_s',0,'degree',23,'derivative_controls',{D});
E=TRAJECTORY_TAUT_FLATNESS.evaluate(modelpiece,2.30,auth);
R.actual_interior_force_limit_violated= ...
    E.valid&&E.thrust_N>auth.thrust_limits_N(2)&& ...
    E.sampled_tension_above_minimum;
assert(R.actual_interior_force_limit_violated, ...
    'CHECK_C9_FORCE:PhysicalWitness', ...
    'Short-leaf force witness must have a genuine pointwise model deficit.');
% Actual C9 start/end jets are fixed, hence a force-incompatible endpoint
% cannot be repaired by changing 3x4 interior Bernstein controls.
Dstart=zeros(3,10);Dend=zeros(3,10);
for j=1:10
    Dstart(:,j)=D{j}(:,1);
    Dend(:,j)=D{j}(:,end);
end
impossible=TRAJECTORY_C9_ENDPOINT_FORCE_NECESSITY( ...
    Dstart,Dend,lowcap,fopt);
reasonable=auth;reasonable.thrust_limits_N=hlc_force_limits;
% The artificial [0 11.82] and [0 8] values above are deliberate
% gradient/failure fixtures, NEVER inferred HLC actuator limits.
possible=TRAJECTORY_C9_ENDPOINT_FORCE_NECESSITY( ...
    Dstart,Dend,reasonable,fopt);
R.endpoint_impossible_force_gate_rejected= ...
    ~impossible.possible&&~impossible.safe_to_commit&& ...
    strcmp(impossible.status,'UNKNOWN_FIXED_ENDPOINT_THRUST_LIMIT');
R.endpoint_valid_force_gate_accepted= ...
    possible.possible&&~possible.safe_to_commit&& ...
    strcmp(possible.status, ...
        'PASS_ENDPOINT_NECESSARY_FORCE_AND_TENSION__NOT_TRAJECTORY_PROOF');
assert(R.endpoint_impossible_force_gate_rejected&& ...
    R.endpoint_valid_force_gate_accepted, ...
    'CHECK_C9_FORCE:FixedJets','Endpoint necessary gate must be exact.');
% Endpoint-free controls are columns 11:14. Each perturbed whitening vector
% x maps to actual 3x4 free-control shift DeltaF=X/U'.
x=[0.7;-0.2;0.3; 0.1;-0.4;0.2; -0.5;0.1;0.8; 0.3;0.4;-0.2];
x=x/norm(x);
epsstep=3e-3;
physical=reshape(x,3,4)/U.';
for c=2:numel(intervals)
    tspan=intervals{c};
    [planes,deficit,ref]=TRAJECTORY_C9_FORCE_WITNESS_PLANE( ...
        base,auth,fopt,U,tspan); %#ok<ASGLU>
    assert(strcmp(ref.status, ...
        'FORCE_WITNESS_PLANES_AVAILABLE__INDEPENDENT_PROOF_REQUIRED') && ...
        ~ref.safe_to_commit&&ref.planes>=1&&all(isfinite(planes(:)))&& ...
        all(deficit>=0)&&ref.force_gradient_upper_norm_N_per_m>0, ...
        'CHECK_C9_FORCE:Plane', ...
        'An actionable short-leaf thrust deficit must create a search plane.');
    R.upper_plane_detected=true;
    % Short Bernstein leaves amplify floating-point cancellation in fourth
    % differences; use a larger, still-local central-difference step.
    plus=base;minus=base;
    plus.control_points_m(:,11:14)=P(:,11:14)+epsstep*physical;
    minus.control_points_m(:,11:14)=P(:,11:14)-epsstep*physical;
    [~,~,rp]=TRAJECTORY_C9_FORCE_WITNESS_PLANE( ...
        plus,auth,fopt,U,tspan);
    [~,~,rm]=TRAJECTORY_C9_FORCE_WITNESS_PLANE( ...
        minus,auth,fopt,U,tspan);
    finite=(rp.upper_bound_N-rm.upper_bound_N)/(2*epsstep);
    analytic=reshape(ref.force_gradient_upper_N_per_m/U,12,1).'*x;
    R.maximum_whitened_gradient_error_N_per_m=max( ...
        R.maximum_whitened_gradient_error_N_per_m,abs(finite-analytic));
    finite_lower=(rp.lower_bound_N-rm.lower_bound_N)/(2*epsstep);
    analytic_lower=reshape(ref.force_gradient_lower_N_per_m/U,12,1).'*x;
    R.lower_gradient_max_error_N_per_m=max( ...
        R.lower_gradient_max_error_N_per_m,abs(finite_lower-analytic_lower));
end
% An externally imposed tension limit above the actual leaf bound is a
% geometrically meaningful constraint: never silently delete it.
auth2=reasonable;auth2.minimum_tension_N=2.0;
[~,~,rt]=TRAJECTORY_C9_FORCE_WITNESS_PLANE( ...
    base,auth2,fopt,U,intervals{2});
R.tension_plane_detected=rt.planes>=1&&~rt.safe_to_commit&& ...
    ~rt.immovable_violation&&rt.tension_lower_bound_N<2.0;
assert(R.maximum_whitened_gradient_error_N_per_m<5e-4&& ...
    R.lower_gradient_max_error_N_per_m<5e-4&& ...
    R.upper_plane_detected&&R.tension_plane_detected&& ...
    R.whole_interval_zero_sensitivity_rejected&& ...
    R.actual_interior_force_limit_violated&& ...
    R.endpoint_impossible_force_gate_rejected&& ...
    R.endpoint_valid_force_gate_accepted&& ...
    R.no_safety_claim&&R.nonidentity_whitening_used, ...
    'CHECK_C9_FORCE:Derivative', ...
    'True 12-D QP gradients must match leaf-bound finite differences.');
R.status='PASS_C9_FORCE_WITNESS_ANALYTIC_GRADIENT__NOT_TRAJECTORY_PROOF';
end
