function R=CHECK_TRAJECTORY_NATIVE_MODEL_BRIDGE()
%CHECK_TRAJECTORY_NATIVE_MODEL_BRIDGE Model-connection regression only.
% A synthetic predictor tests 28-jet wiring, limits, time-grid and the
% failure-closed gate. It does NOT certify HLC/plant numerical parity.
% Real Flight uses the pinned TRIGGER_HLC_PLANT_PREDICTOR by default.
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'reference','REPLANNING_SYSTEM');
addpath(fullfile(base,'TRAJECTORY_GENERATION'), ...
    fullfile(base,'FUTURE_COLLISION_TRIGGER'), ...
    fullfile(base,'OBSTACLE_INFORMATION'));
U=zeros(3,8);U(1,1)=-1;U(1,2)=1;
V=U;V(1,1)=1;
ctrl=zeros(3,24);ctrl(1,:)=-1+2*(0:23)/23;
p=TRAJECTORY_C7_FREE_BERNSTEIN.build(0,2,U,V,ctrl(:,9:16));
E=U;F=V;E(3,1)=-2;F(3,1)=-2;
L=ctrl;L(3,:)=-2;
q=TRAJECTORY_C7_FREE_BERNSTEIN.build(0,2,E,F,L(:,9:16));
C=TRAJECTORY_POLYNOMIAL_CABLE_COMPATIBILITY(p,q,2,1e-8);
assert(C.polynomial_taut_length_compatible, ...
    'CHECK_TRAJECTORY_NATIVE_MODEL_BRIDGE:ConstantOffset', ...
    'Constant two-meter offset must pass necessary representation test.');
L(2,10)=0.5;
q2=TRAJECTORY_C7_FREE_BERNSTEIN.build(0,2,E,F,L(:,9:16));
D=TRAJECTORY_POLYNOMIAL_CABLE_COMPATIBILITY(p,q2,2,1e-8);
assert(~D.polynomial_taut_length_compatible, ...
    'CHECK_TRAJECTORY_NATIVE_MODEL_BRIDGE:NonconstantOffset', ...
    'Independent swing-like polynomial must not be called exact taut.');
req=struct();
req.piece=p;
req.time_s=0;
req.ekf_now=struct('p',U(:,1),'q',zeros(3,1), ...
    'v',U(:,2),'w',zeros(3,1),'pL',E(:,1), ...
    'vL',U(:,2),'pT',[0;0;1],'wL',zeros(3,1));
req.latest_payload_mass_kg=0.8;
req.native_binding=struct('audit_adapter_only',true);
req.relative_sample_times_s=[0 0.5 1 1.5 2];
req.numeric_tolerances=[1e-8 1e-8];
req.yaw_anchor_rad=0;
req.input_limits=struct('lower',[0;-1;-1;-1], ...
    'upper',[20;1;1;1]);
req.physical_parameters=struct('cable_length_m',2);
req.tolerances=struct('cable_length_abs_m',1e-8, ...
    'input_abs',1e-8,'tracking_abs_m',1e-8, ...
    'initial_position_abs_m',1e-8);
req.heading_options=struct('max_subdivision_depth',2, ...
    'numerical_guard_mps',0);
req.derivative_limits=struct('derivative_norm_max', ...
    [4 4 4 4 4 4]);
req.kinematic_options=struct('max_subdivision_depth',2);
req.observed=struct([]);
req.physical_radii=struct('uav_m',0.05, ...
    'payload_m',0.05,'cable_m',0.01);
req.proof_options=struct('robust_tube_enabled',false, ...
    'max_subdivision_depth',0,'numerical_guard_m',1e-10);
req.predictor_function=@(n,b)line_model_oracle(n,p,2,9); %#ok<INUSD>
G=TRAJECTORY_GENERATOR(struct('ROBUST_TUBE_ENABLED',false));
X=G.preview_c7_with_existing_model(req);
assert(X.screen_pass && X.prediction_complete && ...
    strcmp(X.status,'PASS_PINNED_MODEL_SAMPLED_SCREEN__NOT_PHYSICAL_CERTIFICATE') && ...
    ~X.safe_to_commit && ~X.physical_continuous_time_certified && ...
    isequal(size(X.reference_matrix_28),[28 4]) && ...
    all(abs(X.reference_matrix_28(4,:))<1e-10) && ...
    X.cable_length_error_max_m<1e-8 && ...
    X.tracking_error_max_m<1e-8, ...
    'CHECK_TRAJECTORY_NATIVE_MODEL_BRIDGE:Happy', ...
    'Real 28-jet bridge / synthetic sample screen mismatch.');
% Reject a thrust limit violation without permitting a commit.
req.predictor_function=@(n,b)line_model_oracle(n,p,2,25); %#ok<INUSD>
Y=G.preview_c7_with_existing_model(req);
assert(~Y.screen_pass && ~Y.safe_to_commit && ...
    strcmp(Y.status,'REJECT_SAMPLED_ACTUATOR_LIMIT'), ...
    'CHECK_TRAJECTORY_NATIVE_MODEL_BRIDGE:Limits', ...
    'A native-reported over-limit force must be rejected.');
% The model-readiness gate cannot be bypassed by a bad adapter.
req.predictor_function=@(n,b)error('AUDIT:NotReady','not ready'); %#ok<INUSD>
Z=G.preview_c7_with_existing_model(req);
assert(~Z.screen_pass && ~Z.safe_to_commit && ...
    strcmp(Z.status,'UNKNOWN_PINNED_HLC_PLANT_PREDICTION_FAILED'), ...
    'CHECK_TRAJECTORY_NATIVE_MODEL_BRIDGE:Readiness', ...
    'Failed native predictor may not turn into a nominal model pass.');
try
    G.commit(X);
    error('CHECK_TRAJECTORY_NATIVE_MODEL_BRIDGE:UnexpectedCommit', ...
        'Model-only preview was erroneously committed.');
catch ME
    if strcmp(ME.identifier, ...
            'CHECK_TRAJECTORY_NATIVE_MODEL_BRIDGE:UnexpectedCommit')
        rethrow(ME)
    end
    assert(strcmp(ME.identifier,'TRAJECTORY_GENERATOR:CommitNotCertified'));
end
R=struct('status','PASS_C7_NATIVE_MODEL_PREVIEW_WIRING__NO_PHYSICAL_COMMIT', ...
    'reference_size',size(X.reference_matrix_28), ...
    'model_pass',X.screen_pass,'actuator_rejection',~Y.screen_pass, ...
    'readiness_failure_closed',~Z.screen_pass, ...
    'nonconstant_polynomial_cable_rejected',~D.polynomial_taut_length_compatible, ...
    'real_native_tested',false,'real_ode_continuous_bound',false, ...
    'safe_to_commit',false);
fid=fopen(fullfile(root,'TRAJECTORY_NATIVE_MODEL_BRIDGE_RESULT.txt'),'w');
assert(fid>0,'CHECK_TRAJECTORY_NATIVE_MODEL_BRIDGE:File', ...
    'Unable to write result.');
closefile=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\n',R.status);
fprintf(fid,['Synthetic preview=PASS input violation=REJECT ' ...
    'native failure=UNKNOWN\n']);
fprintf(fid,'Real native HLC/plant run=NOT_TESTED; HLC commit=FORBIDDEN\n');
end
function P=line_model_oracle(req,p,L,thrust)
ts=req.sample_times_s;
U=zeros(3,numel(ts));
for k=1:numel(ts)
    J=TRAJECTORY_C7_FREE_BERNSTEIN.evaluate(p,p.t0_s+ts(k));
    U(:,k)=J(:,1);
end
V=U;V(3,:)=V(3,:)-L;
P=struct('uav_m',U,'payload_m',V, ...
    'sample_times_s',ts,'input_thrust_torque', ...
    repmat([thrust;0;0;0],1,numel(ts)-1), ...
    'prediction_complete',true);
end
