function R=CHECK_TRAJECTORY_SEARCH_PROGRESSION()
% CHECK_TRAJECTORY_SEARCH_PROGRESSION
% Verify certified corridor-ray refinement, with nonlinear fallback if needed.
% Install at common_matlab/ root. Final result is ONE ZIP in that root.
% Test values below are synthetic fixtures, not physical defaults.
% Does not change flight, HLC, plant, sensor, or accepted references.
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'reference','REPLANNING_SYSTEM');
addpath(fullfile(base,'TRAJECTORY_GENERATION'), ...
        fullfile(base,'OBSTACLE_INFORMATION'));
assert(exist('TRAJECTORY_SIMULTANEOUS_C7_SEARCH','file')==2, ...
    'CHECK_TRAJECTORY_SEARCH_PROGRESSION:Path','Production search not found.');
q=fixture();
% This original is mathematically safe and has J=0. The optimizer cannot
% improve on zero integrated squared trajectory deviation, so it MUST NOT
% be launched and no modified corridor/trajectory should be fabricated.
A=TRAJECTORY_SIMULTANEOUS_C7_SEARCH(q);
assert(A.nominal_fast_path_used && ~A.solver_called && ...
    A.nominal_global_deviation_minimum_proven && ...
    A.certified_geometry && A.candidate_available && ...
    ~A.safe_to_commit && isempty(A.corridor) && ...
    A.independent_geometry.certified && ...
    A.kinematic_certificate.uav.certified && ...
    A.kinematic_certificate.payload.certified && ...
    A.heading_certificate.certified, ...
    'CHECK_TRAJECTORY_SEARCH_PROGRESSION:NoSolve', ...
    'Provably safe unchanged reference incorrectly invokes NLP or lacks a proof.');
% This observed obstacle intersects the nominal cable near the centre;
% it MUST NOT be incorrectly claimed safe by the no-NLP path.
q.observed=OBSTACLE_INFORMATION.define(71,'sphere',[1;0;-1],0.19);
% Verify the closed-form fixed-corridor intersection independently.
T=TRAJECTORY_C7_CORRIDOR_RAY([-0.2;-0.3;-1], ...
    [0.8;-0.1;-1],2,[0;0],[1;1]);
assert(T.available && abs(T.fraction-0.2)<1e-12 && ...
    all(abs(T.free_controls-0.2)<1e-12) && ...
    abs(T.integrated_deviation_reduction_proportion-0.36)<1e-12, ...
    'CHECK_TRAJECTORY_SEARCH_PROGRESSION:RayMath', ...
    'Certified fixed-normal ray does not obey exact linear inequalities.');
assert(exist('fmincon','file')==2, ...
    'CHECK_TRAJECTORY_SEARCH_PROGRESSION:Fmincon', ...
    'The fallback nonlinear solver requires Optimization Toolbox.');
% Prove the colliding test is not intrinsically infeasible: a known
% smooth, lateral degree-23 reference with identical displacement of both
% endpoints has a geometric certificate. This is ONLY a synthetic oracle
% used by the auditor. It is NEVER handed to the online optimizer and is
% not a hardcoded real-flight bypass direction.
q_witness=q;
q_witness.nominal_free.uav(2,:)=0.3;
q_witness.nominal_free.payload(2,:)=0.3;
wu=TRAJECTORY_C7_FREE_BERNSTEIN.build(q.t0_s,q.duration_s, ...
    q.start_jets.uav,q.end_jets.uav,q_witness.nominal_free.uav);
wl=TRAJECTORY_C7_FREE_BERNSTEIN.build(q.t0_s,q.duration_s, ...
    q.start_jets.payload,q.end_jets.payload,q_witness.nominal_free.payload);
pr=q.physical_radii;
pr.uav_m=pr.uav_m+q.proof_options.min_separation_m;
pr.payload_m=pr.payload_m+q.proof_options.min_separation_m;
pr.cable_m=pr.cable_m+q.proof_options.min_separation_m;
wopt=q.proof_options;
wopt.max_subdivision_depth=6; % Test-only proof budget, not a flight default.
W=TRAJECTORY_CONTINUOUS_GEOMETRY_CERTIFICATE( ...
    struct('uav',wu,'payload',wl),q.observed,pr,wopt);
kwu=TRAJECTORY_KINEMATIC_CERTIFICATE( ...
    wu,q.candidate_feasibility.derivative_limits.uav, ...
    struct('max_subdivision_depth',2));
kwl=TRAJECTORY_KINEMATIC_CERTIFICATE( ...
    wl,q.candidate_feasibility.derivative_limits.payload, ...
    struct('max_subdivision_depth',2));
wh=TRAJECTORY_HEADING_CERTIFICATE( ...
    wu,q.candidate_feasibility.heading_options);
assert(W.certified && kwu.certified && kwl.certified && wh.certified, ...
    'CHECK_TRAJECTORY_SEARCH_PROGRESSION:Witness', ...
    ['A synthetic C7 detour known to exist cannot be independently ' ...
     'certified. Check geometry and kinematic budgets.']);
% These are TEST-only iteration/normal budgets, NOT physical constants.
% A bad nominal initial point must be displaced using observed geometry
% before a possible nonlinear fallback, with no fixed-world direction.
q.search_options.geometric_warm_start=struct( ...
    'enabled',true,'max_attempts',8,'max_normal_iterations',64);
q.solver_options=optimoptions('fmincon','Algorithm','sqp', ...
    'Display','off','MaxIterations',30, ...
    'MaxFunctionEvaluations',1000);
B=TRAJECTORY_SIMULTANEOUS_C7_SEARCH(q);
assert(~B.nominal_fast_path_used && ...
    (B.solver_called || B.certified_corridor_ray_selected || ...
     B.warm_start_candidate_selected) && ~B.safe_to_commit, ...
    'CHECK_TRAJECTORY_SEARCH_PROGRESSION:Colliding', ...
    'Colliding nominal was incorrectly skipped or solver residuals missing.');
% A failed warm start must still produce a full result ZIP for diagnosis.
% It is NOT allowed to be declared PASS without a verified warm start.
if B.candidate_available
    assert(B.certified_geometry && ...
        B.independent_geometry.certified && ...
        (B.solver_point_feasible || B.warm_start_candidate_selected || ...
         B.certified_corridor_ray_selected) && ...
        B.kinematic_certificate.uav.certified && ...
        B.kinematic_certificate.payload.certified && ...
        B.heading_certificate.certified, ...
        'CHECK_TRAJECTORY_SEARCH_PROGRESSION:FalseAccept', ...
        'Uncertified collision candidate was accepted.');
else
    assert(~B.certified_geometry, ...
        'CHECK_TRAJECTORY_SEARCH_PROGRESSION:FalseGeometry', ...
        'Failed candidate cannot be labelled geometrically certified.');
end
if B.candidate_available && B.certified_corridor_ray_selected
    assert(~B.solver_called && B.warm_start_used && ...
        isfinite(B.corridor_ray_fraction) && ...
        B.corridor_ray_fraction>=0 && B.corridor_ray_fraction<=1 && ...
        B.corridor_ray_deviation_reduction>=0 && ...
        B.corridor.certified, ...
        'CHECK_TRAJECTORY_SEARCH_PROGRESSION:CertifiedRay', ...
        'Refinement must be independently certified without launching NLP.');
    overall='PASS_CERTIFIED_COLLISION_RAY_NO_NLP__DYNAMICS_PENDING';
elseif B.candidate_available && B.warm_start_candidate_selected
    overall='PASS_CERTIFIED_COLLISION_GEOMETRIC_SEED__SOLVER_FAILED__DYNAMICS_PENDING';
elseif B.candidate_available
    overall='PASS_CERTIFIED_WARM_START_AND_COLLISION_GEOMETRIC_SOLVE__DYNAMICS_PENDING';
elseif B.warm_start_used
    overall='PASS_FEASIBLE_WARM_START__SOLVER_DID_NOT_CERTIFY_FINAL';
else
    overall='UNKNOWN_NO_CERTIFIED_WARM_START';
end
R=struct('status',overall, ...
    'safe_nominal_status',A.status,'safe_nominal_ms',A.elapsed_ms, ...
    'safe_nominal_solver_called',A.solver_called, ...
    'synthetic_feasible_detour_witness_certified',W.certified, ...
    'collision_status',B.status, ...
    'warm_start_status',B.warm_start_status, ...
    'warm_start_used',B.warm_start_used, ...
    'warm_start_attempts',B.warm_start_attempts, ...
    'warm_start_ms',B.warm_start_ms, ...
    'warm_start_geometry_violation_m',B.warm_start_geometry_violation_m, ...
    'warm_start_fallback_selected',B.warm_start_candidate_selected, ...
    'certified_corridor_ray_selected',B.certified_corridor_ray_selected, ...
    'corridor_ray_fraction',B.corridor_ray_fraction, ...
    'corridor_ray_deviation_reduction',B.corridor_ray_deviation_reduction, ...
    'corridor_ray_ms',B.corridor_ray_ms, ...
    'collision_solver_called',B.solver_called, ...
    'collision_candidate_certified',B.candidate_available, ...
    'collision_ms',B.elapsed_ms, ...
    'safe_nominal_certificate_ms',A.nominal_independent_certificate_ms, ...
    'collision_ray_constraint_stage_ms',B.ray_constraint_stage_ms, ...
    'collision_ray_independent_certificate_ms',B.ray_independent_certificate_ms, ...
    'collision_ray_corridor_certificate_ms',B.ray_corridor_certificate_ms, ...
    'collision_exitflag',B.solve_exitflag, ...
    'collision_initial_geometry_violation_m', ...
        B.initial_max_geometry_violation_m, ...
    'collision_final_geometry_violation_m', ...
        B.final_max_geometry_violation_m, ...
    'collision_initial_derivative_residual', ...
        B.initial_max_derivative_constraint_violation, ...
    'collision_final_derivative_residual', ...
        B.final_max_derivative_constraint_violation, ...
    'collision_final_normal_equality_error', ...
        B.final_max_normal_equality_violation, ...
    'collision_termination_message',B.solver_termination_message, ...
    'collision_reason',B.reason,'physical_dynamics_certified',false, ...
    'safe_to_commit',false);
% Preserve detailed solver.output in MAT only (no private state is read).
solve_output=B.solve_output;
mat=fullfile(root,'TRAJECTORY_SEARCH_PROGRESSION_RESULT.mat');
txt=fullfile(root,'TRAJECTORY_SEARCH_PROGRESSION_RESULT.txt');
archive=fullfile(root,'TRAJECTORY_C7_RAY_REFINEMENT_RESULTS_FOR_CHATGPT.zip');
save(mat,'R','solve_output');
fid=fopen(txt,'wt');
assert(fid>0,'CHECK_TRAJECTORY_SEARCH_PROGRESSION:Save','Text log open failed.');
g=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',R.status);
fprintf(fid,'unchanged reference=%s | no_NLP=%d | %.8g ms\n', ...
    R.safe_nominal_status,~R.safe_nominal_solver_called,R.safe_nominal_ms);
fprintf(fid,'synthetic feasible detour independently certified=%d\n', ...
    R.synthetic_feasible_detour_witness_certified);
fprintf(fid,'warm start: %s | used=%d | attempts=%d | %.9g ms | initial geometry=%.12g m\n', ...
    R.warm_start_status,R.warm_start_used,R.warm_start_attempts, ...
    R.warm_start_ms,R.warm_start_geometry_violation_m);
fprintf(fid,'geometric fallback selected=%d (NOT dynamics / NOT globally optimized)\n', ...
    R.warm_start_fallback_selected);
fprintf(fid,['certified ray selected=%d | solver called=%d | ' ...
    'fraction=%.12g | J reduction=%.12g | ray=%.8g ms\n'], ...
    R.certified_corridor_ray_selected,R.collision_solver_called, ...
    R.corridor_ray_fraction,R.corridor_ray_deviation_reduction, ...
    R.corridor_ray_ms);
fprintf(fid,'colliding case=%s | certified=%d | %.8g ms | exitflag=%g\n', ...
    R.collision_status,R.collision_candidate_certified, ...
    R.collision_ms,R.collision_exitflag);
fprintf(fid,['ray phase times (ms): necessary G=%.8g | ' ...
    'independent proof=%.8g | corridor proof=%.8g\n'], ...
    R.collision_ray_constraint_stage_ms, ...
    R.collision_ray_independent_certificate_ms, ...
    R.collision_ray_corridor_certificate_ms);
fprintf(fid,'safe nominal independent proof=%.8g ms\n', ...
    R.safe_nominal_certificate_ms);
fprintf(fid,'geometry violation (m): initial=%.12g final=%.12g\n', ...
    R.collision_initial_geometry_violation_m, ...
    R.collision_final_geometry_violation_m);
fprintf(fid,'derivative constraint residual (mixed units): initial=%.12g final=%.12g\n', ...
    R.collision_initial_derivative_residual, ...
    R.collision_final_derivative_residual);
fprintf(fid,'normal equality residual=%.12g\n', ...
    R.collision_final_normal_equality_error);
fprintf(fid,'solver message: %s\nreason: %s\n', ...
    strrep(R.collision_termination_message,sprintf('\n'),' '),R.collision_reason);
fprintf(fid,'HLC commit=FORBIDDEN; coupled dynamics=NOT CERTIFIED\n');
clear g
% Audit results depend only on numerical checks and their output files.
% The next-chat HANDOFF_TRAJECTORY.txt is documentation, not an audit input.
zip(archive,{'TRAJECTORY_SEARCH_PROGRESSION_RESULT.mat', ...
    'TRAJECTORY_SEARCH_PROGRESSION_RESULT.txt'},root);
assert(isfile(archive),'CHECK_TRAJECTORY_SEARCH_PROGRESSION:Save', ...
    'Result ZIP creation failed.');
delete(mat);delete(txt);
end

function q=fixture()
U=zeros(3,8);L=zeros(3,8);L(3,1)=-2;
U(1,2)=1;L(1,2)=1;
V=U;W=L;V(1,1)=2;W(1,1)=2;
q=struct('t0_s',0,'duration_s',2, ...
    'start_jets',struct('uav',U,'payload',L), ...
    'end_jets',struct('uav',V,'payload',W), ...
    'nominal_free',struct('uav',zeros(3,8), ...
        'payload',zeros(3,8)), ...
    'observed',[ ...
        OBSTACLE_INFORMATION.define(41,'sphere',[0;4;0],0.2), ...
        OBSTACLE_INFORMATION.define(43,'ellipsoid',[0;-4;0], ...
            [0.3 0.6 1],'euler_deg',[15 28 52])], ...
    'physical_radii',struct('uav_m',0.05, ...
        'payload_m',0.05,'cable_m',0.01), ...
    'proof_options',struct('robust_tube_enabled',false, ...
        'min_separation_m',0.02,'numerical_guard_m',1e-10, ...
        'max_subdivision_depth',3), ...
    'search_options',struct('time_leaf_depth',1, ...
        'max_constraint_rows',1000,'max_leaf_count',2, ...
        'feasibility_tolerance',1e-7,'endpoint_jet_tolerance',1e-6), ...
    'solver_options',struct());
for j=1:8
    q.nominal_free.uav(1,j)=2*(j+7)/23;
    q.nominal_free.payload(:,j)=q.nominal_free.uav(:,j)+[0;0;-2];
end
entry=struct('ekf_now',struct('p',U(:,1),'v',U(:,2), ...
    'pL',L(:,1),'vL',L(:,2)), 'cable_length_m',2, ...
    'position_tolerance_m',1e-8, ...
    'velocity_tolerance_mps',1e-8, ...
    'cable_length_tolerance_m',1e-8, ...
    'cable_length_rate_tolerance_mps',1e-8);
q.candidate_feasibility=struct('derivative_limits',struct( ...
    'uav',struct('derivative_norm_max',[5 100 1000 1e6 1e8 1e10]), ...
    'payload',struct('derivative_norm_max',[5 100 1000 1e6 1e8 1e10])), ...
    'entry',entry,'heading_options',struct( ...
    'max_subdivision_depth',2,'numerical_guard_mps',1e-10));
end
