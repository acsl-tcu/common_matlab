function S=CHECK_TRIGGER_DEEP_INSTRUMENTATION_SOURCE()
% Static API/source check only. Does NOT certify Flight performance or safety.
paths={which('TRIGGER_REFERENCE_WINDOW_CACHE'), ...
       which('OBSERVED_OBSTACLE_MEMORY'), ...
       which('TRIGGER_UNIVERSAL_SAMPLED_GEOMETRY'), ...
       which('FUTURE_COLLISION_TRIGGER'),which('CHECK_TRIGGER_CAPTURE_RUN')};
assert(all(~cellfun(@isempty,paths)), ...
 'CHECK_TRIGGER_DEEP_INSTRUMENTATION_SOURCE:Missing', ...
 'The patched reference, memory, geometry, core and capture files must all be on path.');
expected={'source_loop_ms','diagnostic_stage_ms','diagnostic_stage_ms', ...
          'reference_cache_source_loop_ms','TRIGGER_DIAG_V2'};
for k=1:numel(paths)
    assert(contains(fileread(paths{k}),expected{k}), ...
        'CHECK_TRIGGER_DEEP_INSTRUMENTATION_SOURCE:OldClass', ...
        'Old module detected: %s',paths{k});
end
S=struct('status','PASS_DEEP_LOGGING_SOURCES__NOT_RUNTIME_OR_SAFETY', ...
         'reason','','files',{paths});
fid=fopen('TRIGGER_DEEP_INSTRUMENTATION_SOURCE_RESULT.txt','w');
assert(fid>=0,'CHECK_TRIGGER_DEEP_INSTRUMENTATION_SOURCE:Write');
clean=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'status=%s\n',S.status);
for k=1:numel(paths),fprintf(fid,'%d: %s\n',k,paths{k});end
end
