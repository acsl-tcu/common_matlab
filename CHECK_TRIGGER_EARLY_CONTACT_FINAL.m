function R=CHECK_TRIGGER_EARLY_CONTACT_FINAL()
% CHECK_TRIGGER_EARLY_CONTACT_FINAL: independent synthetic integration audit.
% No fake claim about real Flight, mathematical continuous-time safety or WCET.
% Run from common_matlab; output MAT/TXT goes to this script's directory.
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'reference','REPLANNING_SYSTEM');
addpath(base,fullfile(base,'FUTURE_COLLISION_TRIGGER'), ...
    fullfile(base,'SIMULATED_OBSTACLE_SENSOR'), ...
    fullfile(base,'OBSTACLE_INFORMATION'));
checks=0;
counts=zeros(1,0);
direction=1;
C=FUTURE_COLLISION_TRIGGER(struct('horizon_s',4));
obs=OBSTACLE_INFORMATION.define(801,'sphere',[1 0 0],0.04);
e=ekf_at(0);
a=struct('runtime',struct('sample_dt_s',0.2, ...
    'r_uav_m',0.01,'r_payload_m',0.01, ...
    'r_cable_m',0.005,'cable_length_m',2,'horizon_s',4), ...
    'payload_mass_kg',1,'reference_at',@(t)zeros(28,1), ...
    'predictor',@synthetic_predictor, ...
    'numeric_tolerances',[1e-7;1e-7]);

% Full first prediction: first collision is detected and published exactly once.
counts=[];
A=C.evaluate(0,e,make_frame(0,e,obs),a);
assert(A.prediction_complete && A.full_horizon_evaluated && ...
    ~A.prediction_early_stopped && A.new_event && ...
    A.collision_obstacle_id==801 && abs(A.collision_ttc_s-1)<1e-12 && ...
    isequal(counts,21), 'CHECK_TRIGGER_EARLY_CONTACT_FINAL:First');
checks=checks+1;

% Subsequent unchanged trajectory: 4-s native prediction is NOT required
% after the already-announced collision is reconfirmed in a shorter prefix.
e=ekf_at(0.2);
counts=[];
B=C.evaluate(0.2,e,make_frame(0.2,e,obs),a);
assert(B.collision_predicted && ~B.new_event && ...
    B.prediction_early_stopped && ~B.prediction_complete && ...
    ~B.full_horizon_evaluated && B.collision_prediction_resolved && ...
    ~B.prefix_probe_retried_full && B.duplicate_suppressed && ...
    B.completed_prediction_horizon_s<4 && ...
    abs(B.collision_ttc_s-0.8)<1e-12 && ...
    isequal(counts,B.completed_prediction_samples) && ...
    all(counts<21), 'CHECK_TRIGGER_EARLY_CONTACT_FINAL:Prefix');
checks=checks+1;

% A changed live path without a revision is not assumed to collide:
% a prefix MISS must rerun full 4 s from the same current EKF state.
direction=-1;
counts=[];
D=C.evaluate(0.4,ekf_at(0.4),make_frame(0.4,ekf_at(0.4),obs),a);
assert(~D.collision_predicted && ~D.new_event && ...
    D.prediction_complete && D.full_horizon_evaluated && ...
    D.prefix_probe_attempted && D.prefix_probe_retried_full && ...
    ~D.prediction_early_stopped && numel(counts)==2 && ...
    counts(1)<21 && counts(2)==21 && ...
    strcmp(D.collision_decision,'NO_CONTACT_IN_NUMERIC_SAMPLES'), ...
    'CHECK_TRIGGER_EARLY_CONTACT_FINAL:Fallback');
checks=checks+1;

% A committed, different trajectory rearms the same obstacle ID.
direction=1;
C.set_committed_plan_revision(uint64(1));
counts=[];
E=C.evaluate(0.6,ekf_at(0.6),make_frame(0.6,ekf_at(0.6),obs),a);
assert(E.collision_predicted && E.new_event && ...
    E.plan_revision==uint64(1) && E.prediction_complete && ...
    ~E.prefix_probe_attempted && isequal(counts,21) && ...
    E.collision_obstacle_id==801 && ...
    abs(E.collision_ttc_s-0.4)<1e-12, ...
    'CHECK_TRIGGER_EARLY_CONTACT_FINAL:Revision');
checks=checks+1;

% An additional observed obstacle must disable the old prefix optimisation:
% the earlier already-announced contact cannot mask a NEW later contact.
far=OBSTACLE_INFORMATION.define(802,'sphere',[3 0 0],0.04);
new_obs=[obs;far];
counts=[];
F=C.evaluate(0.8,ekf_at(0.8),make_frame(0.8,ekf_at(0.8),new_obs),a);
assert(F.prediction_complete && ~F.prefix_probe_attempted && ...
    isequal(counts,21) && F.new_event && ...
    F.collision_obstacle_id==802 && ...
    abs(F.collision_ttc_s-2.2)<1e-12, ...
    'CHECK_TRIGGER_EARLY_CONTACT_FINAL:NewObstacle');
checks=checks+1;

% A shortened output never impersonates verified full 4-s clearance.
counts=[];
G=C.evaluate(1.0,ekf_at(1.0),make_frame(1.0,ekf_at(1.0),new_obs),a);
assert(G.collision_predicted && G.prediction_early_stopped && ...
    ~G.prediction_complete && ~G.full_horizon_evaluated && ...
    G.collision_prediction_resolved && ~G.new_event && ...
    G.collision_time_s>=1.0 && ...
    G.collision_ttc_s>=0, ...
    'CHECK_TRIGGER_EARLY_CONTACT_FINAL:NoFalseFull');
checks=checks+1;

R=struct('status','PASS_EARLY_CONTACT_PREFIX_AND_FULL_FALLBACK__SYNTHETIC_ONLY', ...
    'cases',checks,'failures',0, ...
    'first_ttc_s',A.collision_ttc_s, ...
    'repeat_prefix_horizon_s',B.completed_prediction_horizon_s, ...
    'repeat_prefix_sample_count',B.completed_prediction_samples, ...
    'fallback_full_horizon_s',D.completed_prediction_horizon_s, ...
    'new_obstacle_id',F.collision_obstacle_id, ...
    'mathematical_continuous_safety_proven',false, ...
    'real_flight_tested',false,'wcet_proven',false);
save(fullfile(root,'TRIGGER_EARLY_CONTACT_FINAL_RESULT.mat'),'R');
fid=fopen(fullfile(root,'TRIGGER_EARLY_CONTACT_FINAL_RESULT.txt'),'w');
assert(fid>0,'CHECK_TRIGGER_EARLY_CONTACT_FINAL:Write','Cannot open output.');
c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\ncases=%d failures=%d\n',R.status,R.cases,R.failures);
fprintf(fid,'first_ttc_s=%.9g prefix_horizon_s=%.9g prefix_samples=%d\n', ...
    R.first_ttc_s,R.repeat_prefix_horizon_s,R.repeat_prefix_sample_count);
fprintf(fid,'fallback_full_horizon_s=%.9g new_obstacle_id=%.0f\n', ...
    R.fallback_full_horizon_s,R.new_obstacle_id);
fprintf(fid,'continuous_safety=0 real_flight=0 WCET=0\n');

    function P=synthetic_predictor(req)
        t=reshape(double(req.sample_times_s),1,[]);
        counts(end+1)=numel(t);
        u=req.ekf_now.p+direction*[t;zeros(2,numel(t))];
        l=u-[zeros(2,numel(t));repmat(req.cable_length_m,1,numel(t))];
        P=struct('sample_times_s',t,'uav_m',u,'payload_m',l, ...
            'model_description','SYNTHETIC_EXACT_LINE_ORACLE');
    end
end

function e=ekf_at(x)
p=[x;0;0];
e=struct('p',p,'q',zeros(3,1),'v',zeros(3,1), ...
    'w',zeros(3,1),'pL',p-[0;0;2],'vL',zeros(3,1), ...
    'pT',[0;0;1],'wL',zeros(3,1));
end

function f=make_frame(t,e,obs)
ids=reshape(double([obs.id]),1,[]);
f=struct('time_s',double(t),'uav_position_ekf_m',e.p, ...
    'detected_obstacles',obs,'detected_ids',ids,'detected_count',numel(ids));
end
