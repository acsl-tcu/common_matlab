function R=CHECK_TRIGGER_SCOPE_AND_REVISION()
% CHECK_TRIGGER_SCOPE_AND_REVISION  Prediction-only trigger regression.
% Put this temporary CHECK_* in common_matlab/ (not reference/).
% Synthetic 4-s oracle: proves event wiring / revision semantics ONLY.
% It is NOT a real Flight, a physical HLC/plant parity test, or a
% continuous-time trajectory safety certificate.

root=fileparts(mfilename('fullpath'));
base=fullfile(root,'reference','REPLANNING_SYSTEM');
addpath(base,fullfile(base,'FUTURE_COLLISION_TRIGGER'), ...
    fullfile(base,'OBSTACLE_INFORMATION'), ...
    fullfile(base,'SIMULATED_OBSTACLE_SENSOR'));

O=OBSTACLE_INFORMATION.definitions();
assert(~isempty(O),'CHECK_TRIGGER_SCOPE_AND_REVISION:Obstacle', ...
    'At least one actual obstacle definition must be present.');
O=O(1); % Read-only source shape, used as a fixture; no sensor spoof in Flight.
id=double(O.id);
p=double(O.initial_position(:));
assert(isequal(size(p),[3 1]) && all(isfinite(p)));
e=struct('p',p,'q',zeros(3,1),'v',zeros(3,1), ...
    'w',zeros(3,1),'pL',p-[0;0;2], ...
    'vL',zeros(3,1),'pT',[0;0;1],'wL',zeros(3,1));
f=struct('time_s',0,'uav_position_ekf_m',p, ...
    'detected_obstacles',O,'detected_ids',id,'detected_count',1);
a=struct('runtime',struct('sample_dt_s',0.2, ...
    'r_uav_m',0.1,'r_payload_m',0.1,'r_cable_m',0, ...
    'cable_length_m',2,'horizon_s',4), ...
    'payload_mass_kg',1, 'reference_at',@(t)zeros(28,1), ...
    'predictor',@synthetic_oracle, 'numeric_tolerances',[1e-7;1e-7]);

C=FUTURE_COLLISION_TRIGGER(struct('horizon_s',4));
X1=C.evaluate(0,e,f,a);
X2=C.evaluate(0,e,f,a);
assert(X1.prediction_complete && X2.prediction_complete && ...
    X1.new_event && isequal(X1.new_event_ids,id) && ...
    X2.duplicate_suppressed && ~X2.new_event && ...
    isequal(X1.first_sampled_collision_ttc_s,0) && ...
    isequal(X1.sampled_collision_ids,id), ...
    'CHECK_TRIGGER_SCOPE_AND_REVISION:Duplicate', ...
    'One nominal event should be emitted per observed ID/plan.');
assert(~X1.safe_to_commit && ~X2.safe_to_commit && ...
    ~X1.continuous_observed_set_safe && ~X2.continuous_observed_set_safe, ...
    'CHECK_TRIGGER_SCOPE_AND_REVISION:Proof', ...
    'Nominal prediction must not publish a physical safety certificate.');

C.set_committed_plan_revision(uint64(1));
X3=C.evaluate(0,e,f,a);
assert(X3.new_event && isequal(X3.new_event_ids,id) && ...
    isequal(C.committed_plan_revision,uint64(1)), ...
    'CHECK_TRIGGER_SCOPE_AND_REVISION:Rearm', ...
    'Same observed ID must rearm only after a committed new plan.');
C.set_committed_plan_revision(uint64(1));
X4=C.evaluate(0,e,f,a);
assert(~X4.new_event && X4.duplicate_suppressed, ...
    'CHECK_TRIGGER_SCOPE_AND_REVISION:SameRevision', ...
    'Repeating the same revision cannot rearm an event.');
assert(throws_plan_revision(C,uint64(0)), ...
    'CHECK_TRIGGER_SCOPE_AND_REVISION:Monotonicity', ...
    'Plan revision must reject decreases.');

src=fileread(fullfile(base,'REPLANNING_SYSTEM.m'));
assert(~contains(src,'TRIGGER_UNRESOLVED_EVENT_HANDOFF(') && ...
    ~contains(src,'trigger_result.candidate_request_event=') && ...
    contains(src,'obj.trigger_core.set_committed_plan_revision(v);'), ...
    'CHECK_TRIGGER_SCOPE_AND_REVISION:Scope', ...
    'Production path still emits candidate requests or lacks rearm wiring.');

R=struct('status','PASS_TRIGGER_SCOPE_AND_REVISION__NOT_PHYSICAL_CERTIFICATE', ...
    'cases',5,'failures',0,'observed_fixture_id',id, ...
    'first_event',X1.new_event, 'duplicate_suppressed',X2.duplicate_suppressed, ...
    'committed_plan_rearms',X3.new_event, ...
    'same_plan_still_suppressed',X4.duplicate_suppressed, ...
    'decreasing_revision_rejected',true, ...
    'physical_collision_certified',false, ...
    'worst_case_execution_time_certified',false);
save(fullfile(root,'TRIGGER_SCOPE_AND_REVISION_RESULT.mat'),'R');
fid=fopen(fullfile(root,'TRIGGER_SCOPE_AND_REVISION_RESULT.txt'),'w');
assert(fid>0,'CHECK_TRIGGER_SCOPE_AND_REVISION:Output','Cannot open result log.');
cleaner=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\n',R.status);
fprintf(fid,'cases=%d failures=%d observed_fixture_id=%.0f\n', ...
    R.cases,R.failures,R.observed_fixture_id);
fprintf(fid,'same_obstacle_first_event=1 duplicate_suppressed=1 committed_plan_rearms=1 same_plan_still_suppressed=1\n');
fprintf(fid,'continuous_physical_safety_proven=0 real_flight_executed=0 WCET_proven=0\n');
end

function P=synthetic_oracle(req)
t=req.sample_times_s;
P=struct('sample_times_s',t, ...
    'uav_m',repmat(req.ekf_now.p,1,numel(t)), ...
    'payload_m',repmat(req.ekf_now.pL,1,numel(t)), ...
    'model_description','SYNTHETIC_STATIONARY_ORACLE_NOT_FLIGHT_MODEL');
end

function bad=throws_plan_revision(obj,revision)
bad=false;
try
    obj.set_committed_plan_revision(revision);
catch ME
    bad=strcmp(ME.identifier,'FUTURE_COLLISION_TRIGGER:PlanRevision');
end
end
