function R = RA_AUDIT_SOURCE_PROVENANCE(module)
% Conservative static audit of direct dependencies, not a formal taint proof.
files={...
 'TRIGGER/ENTRY_AND_OBSERVATION/wp_six_trigger_tick_v8.m',...
 'TRIGGER/ENTRY_AND_OBSERVATION/wp_six_trigger_selected_nominal_v8.m',...
 'TRIGGER/ENTRY_AND_OBSERVATION/wp_six_trigger_model_snapshot.m',...
 'TRIGGER/FOUR_SECOND_PREDICTION/wp_six_trigger_pv_forecast_v8.m',...
 'TRIGGER/FOUR_SECOND_PREDICTION/wp_six_trigger_route_cache_prepare.m',...
 'TRIGGER/FOUR_SECOND_PREDICTION/wp_six_trigger_pv_cache_prepare.m'};
paths=cell(numel(files),1);violations={};
for k=1:numel(files)
 paths{k}=fullfile(module,strrep(files{k},'/',filesep));
 if ~isfile(paths{k}), violations{end+1}=['MISSING ' files{k}];continue;end %#ok<AGROW>
 source=fileread(paths{k});
 source=regexprep(source,'(?m)^\s*%[^\n]*','');
 % Catch direct truth/sensor or future-flight reads inside forecasting chain.
 patterns={'\bagent\s*\.\s*plant\b','\bplant\s*\.\s*state\b',...
     '\bmotive\s*\.','\blogger\s*\.\s*data\b', ...
     '\btruth\s*\.','\bfuturePlant\s*\('};
 for i=1:numel(patterns)
   if ~isempty(regexp(source,patterns{i},'once'))
     violations{end+1}=sprintf('%s : %s',files{k},patterns{i}); %#ok<AGROW>
   end
 end
end
R=struct('status','PASS_STATIC_SOURCE_CHECK','violations',{violations},...
 'inspectedFiles',{files},'resolvedPaths',{paths},...
 'formalProof',false,'sensorUsesTrueDroneCenterByDesign',true,...
 'futureReferenceKnownRouteIsAllowed',true);
if ~isempty(violations),R.status='FAIL_STATIC_SOURCE_CHECK';end
end
