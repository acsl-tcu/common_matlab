function Q=RA_AUDIT_SAVED_HLC_TRACES(root)
% Re-evaluate original-HLC 6s traces using the CURRENT V8 forecast code.
% IMPORTANT: historical nominal truth is used as a SYNTHETIC perfect EKF
% history in this test ONLY. Not evidence of live EKF forecast accuracy.
p=fullfile(root,'REFERENCE_OBSTACLE_AVOIDANCE_TESTS',...
    '06_ORIGINAL_TRACE_REPLAY','BASELINE_TRACES',...
    'PURE_TRIGGER_V6_CAUSAL_AUDIT_20261113_013957.mat');
if ~isfile(p)
 Q=struct('status','SKIPPED_BASELINE_MAT_NOT_FOUND','path',p);
 return;
end
L=load(p,'R');records=L.R.original6.results;
agent=DRONE();agent.parameter=DRONE_PARAM_SUSPENDED_LOAD('DIATONE');
core=Controller_HL_Suspended_Load(.025,agent);
gains=struct('F1',core.F1,'F2',core.F2,'F3',core.F3);
route=wp_six_trigger_route_cache_prepare_v8(gen_wp_straight('speed',1.5),0:.025:12);
rows=struct('caseName',{},'start_s',{},'status',{},'maxLoad_m',{},...
    'maxDrone_m',{},'initialLoad_m',{},'initialDrone_m',{},...
    'modalCondition',{},'failure',{});
for s=1:numel(records)
 c=records(s);tr=c.nominalTrace;tt=tr.time;
 gs=tr.governorSettings;
 K=wp_six_trigger_pv_cache_prepare(gains,-1:.025:0,gs.filterTime,.1);
 for t0=[1 2]
  z=struct('caseName',char(c.caseName),'start_s',t0,'status','FAIL',...
     'maxLoad_m',NaN,'maxDrone_m',NaN,'initialLoad_m',NaN, ...
     'initialDrone_m',NaN,'modalCondition',K.condition,'failure','');
  try
   i=find(abs(tt-t0)<1e-9,1);
   if isempty(i),error('RAAudit:Time','Missing start time');end
   hist=i-40:i;
   tau=tr.governorTau(hist);
   velRef=zeros(3,numel(hist));
   for k=1:numel(hist)
     velRef(:,k)=ppval(route.ppDP,tau(k))*tr.governorRateState(6,hist(k));
   end
   H=struct('pastTimes',K.pastRelativeTimes,...
     'pastLoad',tr.pLoad(:,hist), ...
     'pastVelocity',tr.vLoad(:,hist), ...
     'pastRefLoad',tr.refLoad(:,hist), ...
     'pastRefVelocity',velRef,...
     'tauNow',tr.governorTau(i), ...
     'rateNow',tr.governorRateState(:,i), ...
     'heldCommandNow',tr.governorHeldCommand(i),...
     'estimatedML',c.modelEstimatedMass,...
     'cableLength',c.modelCableLength,'gravity',c.modelGravity,...
     'slowdownStart',gs.slowdownStart, ...
     'slowdownFull',gs.slowdownFull, ...
     'minScale',gs.minScale,'filterTime',gs.filterTime);
   F=wp_six_trigger_pv_forecast_v8(H,K,route);
   future=i:i+160;
   z.maxLoad_m=max(vecnorm(F.pLoad-tr.pLoad(:,future),2,1));
   z.maxDrone_m=max(vecnorm(F.pDrone-tr.pDrone(:,future),2,1));
   z.initialLoad_m=norm(F.pLoad(:,1)-tr.pLoad(:,i));
   z.initialDrone_m=norm(F.pDrone(:,1)-tr.pDrone(:,i));
   z.status='PASS_NOMINAL_COMPARE';
  catch ME
   z.failure=[ME.identifier ' ' ME.message];
  end
  rows(end+1)=z; %#ok<AGROW>
 end
end
Q=struct('status','PASS_EIGHT_ORIGINAL_HLC_NOMINAL_REPLAYS',...
    'records',rows,'source',p,'liveEKFUsed',false,...
    'historicalNominalTruthUsedAsSyntheticEKF',true,...
    'futureTruthUsedOnlyForScoring',true,...
    'physicalSafetyCertified',false);
if any(~strcmp({rows.status},'PASS_NOMINAL_COMPARE'))
 Q.status='FAIL_SAVED_REPLAY';
end
end
