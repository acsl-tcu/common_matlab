function ref = gen_wp_ra_audit_line_curve(opts)
% Test-only known C6 route: straight start -> smooth lateral bend -> straight.
% It uses the ORIGINAL waypoint smooth generator; no Flight production edit.
arguments
    opts.speed (1,1) double {mustBePositive} = 0.65
end
pointsXYZ = [ ...
    0.0  0.0  3.0; ...
    0.0  0.8  3.0; ...
    0.0  1.6  3.0; ...
    0.0  2.4  3.0; ...
    0.3  3.2  3.0; ...
    1.0  4.0  3.0; ...
    1.8  4.8  3.0; ...
    2.6  5.6  3.0; ...
    3.0  6.4  3.0];
ref = gen_ref_waypoint_smooth('pointsXYZ',pointsXYZ, ...
    'speed',opts.speed,'blendRadius',0.35);
ref.routeName = 'audit_line_curve';
end
