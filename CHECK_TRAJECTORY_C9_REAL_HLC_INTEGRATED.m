function R=CHECK_TRAJECTORY_C9_REAL_HLC_INTEGRATED()
% Preflight source-bound 4-clamp + minimal per-event EKF/C9 integrated nominal.
% No Flight runner/plant/HLC mutation. Synthetic state IS A FIXTURE; HLC
% class and DRONE_PARAM_SUSPENDED_LOAD are actual installed project classes.
% This is NOT real HLC closed-loop trajectory execution certification.
root=fileparts(mfilename('fullpath'));
R=struct('status','FAIL_NOT_STARTED','stage','START', ...
    'error_identifier','','error_message','','error_stack',{{}}, ...
    'real_HLC_source_file','','hlc_lower_4',NaN(4,1), ...
    'hlc_upper_4',NaN(4,1),'direct_limits_revalidated',false, ...
    'flight_source_limits_bound',false, ...
    'forged_preflight_limits_rejected',false, ...
    'caller_fake_authority_ignored',false, ...
    'current_EKF_mass_used',false, ...
    'flight_contract_checked',false, ...
    'integrated_nominal_4input_pass',false, ...
    'live_entry_pass',false, ...
    'stale_mass_rejected_before_optimizer',false, ...
    'changed_nonmass_flight_physics_rejected',false, ...
    'missing_flight_contract_rejected',false, ...
    'within_flight_EKF_mass_update_pass',false, ...
    'changed_mass_used_kg',NaN, ...
    'first_event_pipeline_breakdown_ms',NaN(1,6), ...
    'source_four_input_box_headroom',NaN(4,2), ...
    'hlc_feedback_admissible_lower_4',NaN(4,1), ...
    'hlc_feedback_admissible_upper_4',NaN(4,1), ...
    'hlc_feedback_allowance_identity_pass',false, ...
    'source_read_ms',NaN, ...
    'preflight_bind_ms',NaN, ...
    'event_source_read_count',NaN, ...
    'event_current_capture_count',NaN, ...
    'event_entry_gate_count',NaN, ...
    'event_flight_check_count',NaN, ...
    'warm_event_times_ms',NaN(1,9), ...
    'warm_event_median_ms',NaN,'warm_event_p95_ms',NaN, ...
    'warm_event_max_ms',NaN, ...
    'valid_integrated_ms',NaN,'integrated_status','NOT_RUN', ...
    'integrated_failure_detail','', ...
    'integrated_search_status','NOT_RUN', ...
    'integrated_heading_status','NOT_RUN', ...
    'integrated_torque_status','NOT_RUN', ...
    'total_elapsed_ms',NaN, ...
    'motor_allocation_proven',false, ...
    'closed_loop_HLC_tracking_proven',false, ...
    'safe_to_commit',false);
watch=tic;
try
    R.stage='PATH_AND_REAL_HLC_SOURCE';
    addpath(fullfile(root,'controller'),'-begin');
    addpath(fullfile(root,'model'),'-begin');
    addpath(genpath(fullfile(root,'reference','REPLANNING_SYSTEM')),'-begin');
    [lo,hi,source]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    lo=double(lo(:)); hi=double(hi(:));
    assert(numel(lo)==4&&numel(hi)==4&&all(lo<hi), ...
        'C9_REAL_INPUT_CHECK:Source','Real HLC must expose exactly 4 bounds.');
    R.real_HLC_source_file=source;
    R.hlc_lower_4=lo;R.hlc_upper_4=hi;
    R.stage='BUILD_REAL_CLASSES_WITH_TEST_ONLY_INITIAL_STATE';
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    % TEST fixture mass, never the production Flight mass or a fallback.
    P.set("loadmass",0.14);
    par=struct('dt',0.025,'F1',zeros(1,2), ...
        'F2',zeros(1,6),'F3',zeros(1,6),'F4',zeros(1,2));
    hc=HLC_SUSPENDED_LOAD([],par);
    d=double(P.get(["mass","gravity","cableL"]));
    d=d(:);
    assert(numel(d)==3&&all(isfinite(d))&&all(d>0), ...
        'C9_REAL_INPUT_CHECK:Parameter','Real DRONE parameter fixture invalid.');
    L=d(3);gravity=[0;0;-d(2)];
    start=zeros(3,10);finish=zeros(3,10);
    start(:,1)=[0;0;3];finish(:,1)=[1;0;3];
    start(1,2)=.5;finish(1,2)=.5;
    pL=start(:,1);q=[0;0;-1];
    e=struct('pL',pL,'vL',start(:,2),'pT',q, ...
        'p',pL-L*q,'mL',0.14);
    agent=struct('cha','f','controller',struct('hlc_suspended',hc), ...
        'parameter',P,'estimator',struct('result',struct('state',e)));
    time=struct('t',8,'dt',par.dt);
    opts=struct('gravity_world_mps2',gravity, ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0);
    preflight_clock=tic;
    binding=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.bind(agent,opts);
    R.preflight_bind_ms=1000*toc(preflight_clock);
    assert(isequal(binding.input_lower,lo)&& ...
           isequal(binding.input_upper,hi), ...
           'C9_REAL_INPUT_CHECK:RealBound','Flight binding not derived from source.');
    R.stage='BUILD_CURRENT_FLIGHT_C9_TEST_REQUEST';
    T=2;
    free=repmat(start(:,1),1,4)+start(:,2)*((2/23)*(10:13));
    piece=TRAJECTORY_C9_FLAT_BERNSTEIN.build(time.t,T,start,finish,free);
    req=struct('t0_s',time.t,'duration_s',T, ...
        'flight_interval_s',[time.t time.t+T], ...
        'start_jets',start,'end_jets',finish, ...
        'nominal_free',piece.control_points_m(:,11:14), ...
        'observed',struct([]), ...
        'radii',struct('uav_m',.1,'cable_m',.02,'payload_m',.1), ...
        'authority',struct('payload_mass_kg',999,'thrust_limits_N',[-1 999], ...
             'torque_limits_Nm',repmat([-999 999],3,1)), ...
        'geometry_options',struct('max_subdivision_depth',6, ...
             'max_node_count',127,'numerical_guard_m',0, ...
             'robust_tube_enabled',false,'trajectory_phase','f'), ...
        'force_options',struct('max_subdivision_depth',6, ...
             'max_node_count',127,'force_guard_N',0), ...
        'search_options',struct('probe_count',13, ...
             'max_outer_iterations',4,'max_projection_sweeps',100, ...
             'projection_tolerance_m',1e-8,'min_separation_m',1e-5), ...
        'heading_options',struct('max_subdivision_depth',8, ...
             'max_node_count',511,'horizontal_velocity_guard_mps',0, ...
             'w_guard_mps2',0, ...
             'payload_jet_tolerance',1e-7*ones(3,10), ...
             'uav_jet_tolerance',1e-7*ones(3,8), ...
             'yaw_jet_tolerance',1e-7*ones(1,7)), ...
        'nominal_torque_options',struct('max_subdivision_depth',8, ...
             'max_node_count',511,'minimum_force_z_N',0, ...
             'minimum_planar_speed_mps',0, ...
             'torque_guard_Nm',zeros(3,1), ...
             'enable_fast_norm_sufficient_bound',true), ...
        'entry_tolerances',struct('payload_position_m',1e-8, ...
             'payload_velocity_mps',1e-8,'cable_direction_rad',1e-8, ...
             'uav_position_m',1e-8), ...
        'flight_session_id','CHECK_ONLY_SINGLE_FLIGHT');
    C=TRAJECTORY_C9_FLIGHT_PARAMETER_CONTRACT.begin(binding,agent,time,req);
    assert(C.valid,'C9_REAL_INPUT_CHECK:Contract','Valid Flight contract not bound.');
    req.flight_parameter_contract=C;
    R.stage='REAL_4INPUT_AND_INTEGRATED_NOMINAL';
    A=TRAJECTORY_C9_REAL_HLC_INTEGRATED_CANDIDATE(req,binding,time,agent);
    R.integrated_status=A.status;
    if isstruct(A.integrated_result)&& ...
            isfield(A.integrated_result,'status')
        R.integrated_search_status=A.integrated_result.search_status;
        R.integrated_heading_status=A.integrated_result.heading_status;
        R.integrated_torque_status=A.integrated_result.torque_status;
        R.integrated_failure_detail=A.integrated_result.failure_detail;
    end
    % Source clamps have been directly captured by begin-of-Flight bind.
    % Per-event SOURCE rescanning is intentionally removed (not a proof).
    R.direct_limits_revalidated=A.source_limits_revalidated;
    R.flight_source_limits_bound=A.source_limits_bound_this_flight&& ...
        ~A.source_read_performed_this_event&& ...
        isequal(A.source_read_elapsed_ms,0)&& ...
        isequal(A.input_lower_4,lo)&&isequal(A.input_upper_4,hi);
    R.caller_fake_authority_ignored= ...
        isequal(A.presearch_snapshot.authority.thrust_limits_N,[lo(1),hi(1)])&& ...
        isequal(A.presearch_snapshot.authority.torque_limits_Nm,[lo(2:4),hi(2:4)])&& ...
        A.presearch_snapshot.authority.payload_mass_kg==e.mL;
    R.current_EKF_mass_used=A.live_EKF_mass_used_kg==e.mL;
    R.flight_contract_checked=A.flight_parameter_contract_checked;
    R.live_entry_pass=A.entry_necessary_pass;
    R.integrated_nominal_4input_pass= ...
        A.nominal_model_complete&&A.candidate_available&& ...
        A.nominal_4_input_within_live_software_limits&&~A.safe_to_commit;
    R.source_four_input_box_headroom=A.nominal_wrench_headroom_4x2;
    % The actual pre-clamp controller correction, if ever certified from
    % real HLC equations and state/error reachable sets, MUST lie inside
    % these remaining four input margins. This is an algebraic condition,
    % not a controller theorem or an execution authorization.
    R.hlc_feedback_admissible_lower_4= ...
        A.admissible_HLC_preclamp_correction_lower_4;
    R.hlc_feedback_admissible_upper_4= ...
        A.admissible_HLC_preclamp_correction_upper_4;
    R.hlc_feedback_allowance_identity_pass= ...
        isequal(R.hlc_feedback_admissible_lower_4, ...
            -A.nominal_wrench_headroom_4x2(:,1)) && ...
        isequal(R.hlc_feedback_admissible_upper_4, ...
             A.nominal_wrench_headroom_4x2(:,2)) && ...
        ~A.HLC_feedback_correction_enclosed && ...
        ~A.future_HLC_preclamp_inputs_proven;
    R.source_read_ms=A.source_read_elapsed_ms;
    R.event_source_read_count=double(A.source_read_performed_this_event);
    R.event_current_capture_count=A.current_authority_capture_count;
    R.event_entry_gate_count=A.entry_gate_count;
    R.event_flight_check_count=A.flight_contract_check_count;
    R.valid_integrated_ms=A.total_elapsed_ms;
    Z=A.integrated_result;
    R.first_event_pipeline_breakdown_ms=[Z.joint_geometry_force_proof_ms, ...
        Z.separation_planes_ms,Z.joint_QP_ms,Z.search_other_ms, ...
        Z.heading_join_ms,Z.nominal_torque_ms];
    assert(R.flight_source_limits_bound&&~R.direct_limits_revalidated&& ...
        R.caller_fake_authority_ignored&& ...
        R.current_EKF_mass_used&&R.flight_contract_checked&& ...
        R.live_entry_pass&&R.integrated_nominal_4input_pass&& ...
        R.hlc_feedback_allowance_identity_pass&& ...
        R.event_current_capture_count==1&& ...
        R.event_entry_gate_count==1&& ...
        R.event_flight_check_count==1&& ...
        R.event_source_read_count==0, ...
        'C9_REAL_INPUT_CHECK:LiveIntegrated', ...
        ['Current HLC/EKF binding did not produce minimal nominal pass: ' ...
        A.status ' | ' A.error_identifier ' ' A.error_message]);
    R.stage='MEASURE_WARM_MINIMAL_EVENTS';
    % Benchmark a finished CHECK-only fixture. No Flight tick, logger,
    % sensor, or actual flight execution is changed by this benchmark.
    for rep=1:numel(R.warm_event_times_ms)
        B=TRAJECTORY_C9_REAL_HLC_INTEGRATED_CANDIDATE(req,binding,time,agent);
        R.warm_event_times_ms(rep)=B.total_elapsed_ms;
        assert(B.nominal_model_complete&&B.candidate_available&& ...
            ~B.safe_to_commit&&B.current_authority_capture_count==1&& ...
            B.flight_contract_check_count==1&&B.entry_gate_count==1&& ...
            ~B.source_read_performed_this_event&& ...
            isequal(B.nominal_wrench_headroom_4x2, ...
                    A.nominal_wrench_headroom_4x2), ...
            'C9_REAL_INPUT_CHECK:WarmEvent','Warm event changed proof or did redundant work.');
    end
    temp=sort(R.warm_event_times_ms);
    R.warm_event_median_ms=median(temp);
    % Match standard nearest-rank P95 over a small explicit sample.
    R.warm_event_p95_ms=temp(ceil(.95*numel(temp)));
    R.warm_event_max_ms=temp(end);
    R.stage='REJECT_FORGED_4INPUT_BINDING_BEFORE_SEARCH';
    forged=binding;
    forged.input_upper(1)=forged.input_upper(1)+1;
    forged.limits_N(2)=forged.limits_N(2)+1;
    F=TRAJECTORY_C9_REAL_HLC_INTEGRATED_CANDIDATE(req,forged,time,agent);
    R.forged_preflight_limits_rejected= ...
        strcmp(F.status, ...
        'UNKNOWN_HLC_BINDING_CHANGED_SINCE_FLIGHT_START')&& ...
        ~F.candidate_available;
    R.stage='REJECT_STALE_ESTIMATOR_MASS_BEFORE_OPTIMIZER';
    agent.estimator.result.state.mL=0.17;
    E=TRAJECTORY_C9_REAL_HLC_INTEGRATED_CANDIDATE(req,binding,time,agent);
    R.stale_mass_rejected_before_optimizer= ...
        strcmp(E.status,'UNKNOWN_EKF_HLC_MASS_MISMATCH')&& ...
        ~E.candidate_available&&isempty(fieldnames(E.integrated_result));
    agent.estimator.result.state.mL=0.14;
    R.stage='REJECT_CHANGED_NONMASS_PHYSICS';
    old_jx=double(P.get("jx"));
    P.set("jx",old_jx*1.01);
    E=TRAJECTORY_C9_REAL_HLC_INTEGRATED_CANDIDATE(req,binding,time,agent);
    R.changed_nonmass_flight_physics_rejected= ...
        strcmp(E.status,'UNKNOWN_NONMASS_PHYSICS_CHANGED_WITHIN_FLIGHT')&& ...
        ~E.candidate_available;
    P.set("jx",old_jx);
    R.stage='REJECT_MISSING_CURRENT_FLIGHT_CONTRACT';
    bad=rmfield(req,'flight_parameter_contract');
    E=TRAJECTORY_C9_REAL_HLC_INTEGRATED_CANDIDATE(bad,binding,time,agent);
    R.missing_flight_contract_rejected= ...
        strcmp(E.status,'UNKNOWN_MISSING_LIVE_FLIGHT_CONTRACT_OR_START')&& ...
        ~E.candidate_available;
    assert(R.forged_preflight_limits_rejected&& ...
           R.stale_mass_rejected_before_optimizer&& ...
           R.changed_nonmass_flight_physics_rejected&& ...
           R.missing_flight_contract_rejected, ...
        'C9_REAL_INPUT_CHECK:Negative','Invalid live source/mass/Flight was accepted.');
    R.stage='ACCEPT_FRESH_EKF_MASS_WITHIN_THE_SAME_FLIGHT';
    % Production must accept a NEW EKF mass at the next event, provided
    % the original HLC parameter has received that same mass. Unlike the
    % four input clamp and UAV inertia, this value is NOT Flight-static.
    next_estimated_mass_kg=0.16; % CHECK-only perturbation, not a Flight default.
    P.set("loadmass",next_estimated_mass_kg);
    agent.estimator.result.state.mL=next_estimated_mass_kg;
    B=TRAJECTORY_C9_REAL_HLC_INTEGRATED_CANDIDATE(req,binding,time,agent);
    R.changed_mass_used_kg=B.live_EKF_mass_used_kg;
    R.within_flight_EKF_mass_update_pass= ...
        B.flight_parameter_contract_checked&&B.entry_necessary_pass&& ...
        B.nominal_model_complete&&B.nominal_4_input_within_live_software_limits&& ...
        B.candidate_available&&~B.safe_to_commit&& ...
        isequal(B.live_EKF_mass_used_kg,next_estimated_mass_kg)&& ...
        B.current_authority_capture_count==1&& ...
        B.flight_contract_check_count==1&& ...
        B.entry_gate_count==1;
    assert(R.within_flight_EKF_mass_update_pass, ...
        'C9_REAL_INPUT_CHECK:MassRefresh', ...
        ['Updated EKF/HLC mass failed to refresh C9 authority: ' B.status]);
    R.stage='COMPLETE';
    R.status='PASS_REAL_HLC_SOURCE_4INPUT_LIVE_EKF_TO_FULL_NOMINAL_PIPELINE__HLC_UNCERTIFIED';
catch ME
    R.status='FAIL_REAL_HLC_LIVE_INTEGRATED_AUDIT';
    R.error_identifier=ME.identifier;R.error_message=ME.message;
    R.error_stack=arrayfun(@(f)sprintf('%s:%d',f.name,f.line), ...
        ME.stack,'UniformOutput',false);
end
R.total_elapsed_ms=1000*toc(watch);
base='TRAJECTORY_C9_REAL_HLC_INTEGRATED_RESULT';
matname=fullfile(root,[base '.mat']);
txtname=fullfile(root,[base '.txt']);
zipname=fullfile(root,[base '_FOR_CHATGPT.zip']);
save(matname,'R');
fid=fopen(txtname,'wt');
if fid>=0
    fprintf(fid,'status=%s\nstage=%s\nerror=%s | %s\n', ...
        R.status,R.stage,R.error_identifier,R.error_message);
    for k=1:numel(R.error_stack)
        fprintf(fid,'stack_%d=%s\n',k,R.error_stack{k});
    end
    fprintf(fid,'real_HLC_source=%s\nsource_lower_4=%s\nsource_upper_4=%s\n', ...
        R.real_HLC_source_file,mat2str(R.hlc_lower_4.'),mat2str(R.hlc_upper_4.'));
    keys={'flight_source_limits_bound','direct_limits_revalidated', ...
        'forged_preflight_limits_rejected', ...
        'caller_fake_authority_ignored','current_EKF_mass_used', ...
        'flight_contract_checked','integrated_nominal_4input_pass', ...
        'live_entry_pass','stale_mass_rejected_before_optimizer', ...
        'changed_nonmass_flight_physics_rejected', ...
        'missing_flight_contract_rejected', ...
        'within_flight_EKF_mass_update_pass','motor_allocation_proven', ...
        'closed_loop_HLC_tracking_proven','safe_to_commit'};
    for k=1:numel(keys)
        key=keys{k};fprintf(fid,'%s=%d\n',key,R.(key));
    end
    fprintf(fid,'integrated=%s\nsearch=%s\nheading=%s\ntorque=%s\ndetail=%s\n', ...
        R.integrated_status,R.integrated_search_status, ...
        R.integrated_heading_status,R.integrated_torque_status, ...
        R.integrated_failure_detail);
    fprintf(fid,'first_event_pipeline_breakdown_ms=%s\n', ...
        mat2str(R.first_event_pipeline_breakdown_ms));
    fprintf(fid,'new_EKF_mass_used_kg=%.9g\n',R.changed_mass_used_kg);
    fprintf(fid,'feedback_admissible_lower_4=%s\nfeedback_admissible_upper_4=%s\nfeedback_allowance_identity=%d\n', ...
        mat2str(R.hlc_feedback_admissible_lower_4), ...
        mat2str(R.hlc_feedback_admissible_upper_4), ...
        R.hlc_feedback_allowance_identity_pass);
    fprintf(fid,'4input_headroom=%s\npreflight_bind_ms=%.6f\n', ...
        mat2str(R.source_four_input_box_headroom),R.preflight_bind_ms);
    fprintf(fid,'event_source_read_count=%d\nevent_current_capture_count=%d\n', ...
        R.event_source_read_count,R.event_current_capture_count);
    fprintf(fid,'event_entry_gate_count=%d\nevent_flight_check_count=%d\n', ...
        R.event_entry_gate_count,R.event_flight_check_count);
    fprintf(fid,'warm_event_median_ms=%.6f\nwarm_event_p95_ms=%.6f\nwarm_event_max_ms=%.6f\n', ...
        R.warm_event_median_ms,R.warm_event_p95_ms,R.warm_event_max_ms);
    fprintf(fid,'valid_integrated_ms=%.6f\ntotal_audit_ms=%.6f\n', ...
        R.valid_integrated_ms,R.total_elapsed_ms);
    fclose(fid);
end
if isfile(zipname),delete(zipname);end
zip(zipname,{matname,txtname});
fprintf('[C9 REAL HLC FULL NOMINAL] %s | %s\n',R.status,zipname);
end
