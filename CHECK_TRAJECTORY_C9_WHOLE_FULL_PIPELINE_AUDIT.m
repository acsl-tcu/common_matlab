function R=CHECK_TRAJECTORY_C9_WHOLE_FULL_PIPELINE_AUDIT(mode)
% Exact current-source 15-case pipeline timing, plus 2 proven scenes x5
% repeated LEAF-vs-WHOLE native full-pipeline comparisons.
% Flight-loop integration and live EKF/HLC execution proof are NOT simulated.
% A/B parity and conditional nominal certificates never authorize COMMIT.
if nargin==0,mode='baseline';end
if isstring(mode)&&isscalar(mode),mode=char(mode);end
assert(ischar(mode)&&isrow(mode)&&any(strcmp(mode,{'baseline','tight','inherited'})), ...
    'C9_FULL:ABMode','Only baseline/tight/inherited modes are permitted');
root=fileparts(mfilename('fullpath'));
if strcmp(mode,'inherited')
    name='TRAJECTORY_C9_WHOLE_FULL_PIPELINE_INHERITED_RESULT';
elseif strcmp(mode,'tight')
    name='TRAJECTORY_C9_WHOLE_FULL_PIPELINE_TIGHT_RESULT';
else
    name='TRAJECTORY_C9_WHOLE_FULL_PIPELINE_RESULT';
end
R=struct('mode',mode, ...
    'status','NOT_STARTED','stage','SETUP','error_message','', ...
    'error_report','','safe_to_commit',false, ...
    'whole_native_preflight_status','NOT_CHECKED', ...
    'leaf_native_preflight_status','NOT_CHECKED', ...
    'old_negative_controls_status','NOT_RUN', ...
    'old_negative_controls',struct(), ...
    'baseline_full_ms',NaN(2,5),'native_full_ms',NaN(2,5), ...
    'baseline_search_ms',NaN(2,5),'native_search_ms',NaN(2,5), ...
    'baseline_torque_in_search_ms',NaN(2,5), ...
    'native_torque_in_search_ms',NaN(2,5), ...
    'baseline_heading_ms',NaN(2,5),'native_heading_ms',NaN(2,5), ...
    'baseline_post_torque_ms',NaN(2,5), ...
    'native_post_torque_ms',NaN(2,5), ...
    'baseline_integration_overhead_ms',NaN(2,5), ...
    'native_integration_overhead_ms',NaN(2,5), ...
    'baseline_joint_proof_ms',NaN(2,5),'native_joint_proof_ms',NaN(2,5), ...
    'baseline_plane_ms',NaN(2,5),'native_plane_ms',NaN(2,5), ...
    'baseline_qp_ms',NaN(2,5),'native_qp_ms',NaN(2,5), ...
    'baseline_other_ms',NaN(2,5),'native_other_ms',NaN(2,5), ...
    'native_hlc_ms',NaN(2,5),'native_hlc_status',{cell(2,5)}, ...
    'baseline_status',{cell(2,5)},'native_status',{cell(2,5)}, ...
    'baseline_certified',false(2,5),'native_certified',false(2,5), ...
    'native_whole_used_inside_search',false(2,5), ...
    'full_pipeline_status_parity',true, ...
    'full_pipeline_candidate_parity',true, ...
    'full_pipeline_proof_regressions',0, ...
    'baseline_p95_ms',NaN(2,1),'native_p95_ms',NaN(2,1), ...
    'baseline_max_ms',NaN(2,1),'native_max_ms',NaN(2,1), ...
    'baseline_jitter_range_ms',NaN(2,1), ...
    'native_jitter_range_ms',NaN(2,1), ...
    'matrix_count',0,'matrix_nominal_complete_count',0, ...
    'matrix_unknown_count',0,'matrix_native_oracle_use_count',0, ...
    'matrix_max_ms',NaN,'matrix_p95_ms',NaN, ...
    'matrix_median_ms',NaN, ...
    'matrix_ancestral_shape_skips_total',0, ...
    'matrix_ancestral_shape_certificates_total',0, ...
    'matrix_ancestor_outer_clearances_total',0, ...
    'matrix_cases',{repmat( ...
        struct('path','','scene',0,'total_ms',NaN, ...
        'status','','search_ms',NaN,'search_torque_ms',NaN, ...
        'geometry_force_ms',NaN,'plane_ms',NaN,'qp_ms',NaN, ...
        'heading_ms',NaN,'post_torque_ms',NaN, ...
        'hlc_ms',NaN,'hlc_status','', ...
        'inherited_shape_skips',0,'parent_shape_certificates',0, ...
        'parent_outer_clearances',0,'certified_piece',struct(), ...
        'native_search_certificate',false, ...
        'qp_outer_ball_groups_tested',0, ...
        'qp_outer_ball_groups_skipped',0, ...
        'cable_envelope_axis_evaluations',0, ...
        'cable_envelope_strictly_improved',0, ...
        'nominal_complete',false,'safe_to_commit',false, ...
        'search_status','','search_failure_detail',''),1,15)}, ...
    'hlc_unbound_stays_unproven',false, ...
    'hlc_partial_binding_rejected',false, ...
    'hlc_partial_binding_status','NOT_TESTED', ...
    'overall_elapsed_ms',NaN, ...
    'result_zip',fullfile(root,[name '_FOR_CHATGPT.zip']));
clock=tic;
try
    module_dir=fullfile(root,'reference','REPLANNING_SYSTEM','TRAJECTORY_GENERATION');
    addpath(fullfile(root,'model'),fullfile(root,'controller'),module_dir, ...
        fullfile(root,'reference','REPLANNING_SYSTEM','OBSTACLE_INFORMATION'),'-begin');
    source=which('TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE');
    assert(strcmpi(source,fullfile(module_dir,'TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE.m')), ...
        'C9_FULL:Shadowed','Integrated pipeline source path is shadowed');
    assert(contains(fileread(source),'hlc_bridge_status'), ...
        'C9_FULL:OldPipeline','Apply the integrated HLC/whole-pipeline patch first');
    W=TRAJECTORY_C9_TORQUE_WHOLE_PREFLIGHT(false);
    L=TRAJECTORY_C9_NATIVE_TORQUE_PREFLIGHT(false);
    R.whole_native_preflight_status=W.status;
    R.leaf_native_preflight_status=L.status;
    assert(W.ready && L.ready, 'C9_FULL:NativeMissing', ...
        'Prepare both leaf MEX and whole MEX before Flight/A-B audit');
    % The known negative fixtures fail safely; do not rerun the preceding
    % CHECK automatically because that would multiply setup overhead.
    R.stage='DIRECT_WHOLE_NATIVE_NEGATIVE_CONTROLS';
    Pzero=[zeros(2,24);3*ones(1,24)];
    phys=[1;0.12;0.12;2;0;0;-9.80665;0.01;0.01;0.02;0;0];
    limits=[-1 1;-1 1;-1 1];
    [~,yes,~,~,code]=TRAJECTORY_C9_TORQUE_WHOLE_NATIVE( ...
        Pzero,8,phys,[1;1;1],limits,zeros(3,1),[8;511]);
    negStationary=~yes;
    R.old_negative_controls=struct('stationary_rejected',negStationary, ...
        'budget_rejected',false,'reason_stationary',code, ...
        'reason_budget',NaN);
    assert(negStationary, 'C9_FULL:NegativeControl', ...
        'Whole MEX must not certify singular heading');
    R.old_negative_controls_status='STATIONARY_REJECTED__BUDGET_PENDING';
    [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    lo=double(lo(:));hi=double(hi(:));
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    d=double(P.get(["mass","jx","jy","jz","gravity","cableL"]));d=d(:);
    A=struct('uav_mass_kg',d(1),'payload_mass_kg',0.12, ...
        'uav_inertia_kgm2',d(2:4), ...
        'gravity_world_mps2',[0;0;-d(5)], ...
        'cable_length_m',d(6), ...
        'thrust_limits_N',[lo(1) hi(1)], ...
        'torque_limits_Nm',[lo(2:4) hi(2:4)], ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0);
    catalog=c9_matrix_catalog();
    scenarios=[2 4];
    paths=[1 1];
    for j=1:2
        req=c9_matrix_request(A,paths(j),scenarios(j),catalog);
        req=rmfield(req,'audit_pose_angles_deg');
        req.search_options.enable_13d_oracle_focused_qp_shapes=1;
        req.search_options.enable_13d_reuse_nominal_torque_certificate=1;
        req=c9_select_geometry_ab(req,mode);
        for rep=1:5
            R.stage=sprintf('FULL_AB_SCENE_%d_REP_%d',scenarios(j),rep);
            reqLeaf=c9_native_request(req,false);
            reqWhole=c9_native_request(req,true);
            if mod(j+rep,2),order=[1 0];else,order=[0 1];end
            z=cell(1,2);
            for native_mode=order
                if native_mode==0,trial=reqLeaf;else,trial=reqWhole;end
                z{native_mode+1}=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(trial);
                assert(~z{native_mode+1}.safe_to_commit, ...
                    'C9_FULL:UnsafeCommit','No Flight execution proof may be claimed');
            end
            b=z{1};n=z{2};
            R.baseline_full_ms(j,rep)=b.total_elapsed_ms;
            R.native_full_ms(j,rep)=n.total_elapsed_ms;
            R.baseline_search_ms(j,rep)=b.search_elapsed_ms;
            R.native_search_ms(j,rep)=n.search_elapsed_ms;
            R.baseline_joint_proof_ms(j,rep)=b.joint_geometry_force_proof_ms;
            R.native_joint_proof_ms(j,rep)=n.joint_geometry_force_proof_ms;
            R.baseline_plane_ms(j,rep)=b.separation_planes_ms;
            R.native_plane_ms(j,rep)=n.separation_planes_ms;
            R.baseline_qp_ms(j,rep)=b.joint_QP_ms;
            R.native_qp_ms(j,rep)=n.joint_QP_ms;
            R.baseline_other_ms(j,rep)=b.search_other_ms;
            R.native_other_ms(j,rep)=n.search_other_ms;
            R.baseline_heading_ms(j,rep)=b.heading_join_ms;
            R.native_heading_ms(j,rep)=n.heading_join_ms;
            R.baseline_post_torque_ms(j,rep)=b.nominal_torque_ms;
            R.native_post_torque_ms(j,rep)=n.nominal_torque_ms;
            R.baseline_integration_overhead_ms(j,rep)= ...
                b.integration_overhead_ms;
            R.native_integration_overhead_ms(j,rep)= ...
                n.integration_overhead_ms;
            R.baseline_torque_in_search_ms(j,rep)= ...
                c9_search_torque_time(b.search_result);
            R.native_torque_in_search_ms(j,rep)= ...
                c9_search_torque_time(n.search_result);
            R.native_hlc_ms(j,rep)=n.hlc_bridge_elapsed_ms;
            R.native_hlc_status{j,rep}=n.hlc_bridge_status;
            R.baseline_status{j,rep}=b.status;
            R.native_status{j,rep}=n.status;
            R.baseline_certified(j,rep)=b.nominal_model_complete;
            R.native_certified(j,rep)=n.nominal_model_complete;
            R.native_whole_used_inside_search(j,rep)= ...
                c9_search_whole_proved(n.search_result);
            if ~strcmp(b.status,n.status)
                R.full_pipeline_status_parity=false;
            end
            if b.nominal_model_complete && ~n.nominal_model_complete
                R.full_pipeline_proof_regressions= ...
                    R.full_pipeline_proof_regressions+1;
            end
            if b.nominal_model_complete && n.nominal_model_complete && ...
                    ~isequaln(b.candidate_piece,n.candidate_piece)
                R.full_pipeline_candidate_parity=false;
            end
        end
        R.baseline_p95_ms(j)=percentile(R.baseline_full_ms(j,:),0.95);
        R.native_p95_ms(j)=percentile(R.native_full_ms(j,:),0.95);
        R.baseline_max_ms(j)=max(R.baseline_full_ms(j,:));
        R.native_max_ms(j)=max(R.native_full_ms(j,:));
        R.baseline_jitter_range_ms(j)=max(R.baseline_full_ms(j,:))- ...
            min(R.baseline_full_ms(j,:));
        R.native_jitter_range_ms(j)=max(R.native_full_ms(j,:))- ...
            min(R.native_full_ms(j,:));
    end
    % Use the REAL certified complex scene for proof-budget rejection.
    % A trivial straight line may already certify at the root node.
    phys=[double(A.uav_mass_kg);double(A.payload_mass_kg); ...
        double(A.payload_mass_kg);double(A.cable_length_m); ...
        double(A.gravity_world_mps2(:));double(A.uav_inertia_kgm2(:));0;0];
    [~,yesBudget,~,~,codeBudget]=TRAJECTORY_C9_TORQUE_WHOLE_NATIVE( ...
        double(n.candidate_piece.control_points_m), ...
        double(n.candidate_piece.duration_s),phys,[1;1;1], ...
        double(A.torque_limits_Nm),zeros(3,1),[0;1]);
    R.old_negative_controls.budget_rejected=~yesBudget;
    R.old_negative_controls.reason_budget=codeBudget;
    assert(~yesBudget && any(codeBudget==[2 4]), ...
        'C9_FULL:BudgetControl', ...
        'Complex certified fixture must not prove within one root node');
    R.old_negative_controls_status='PASS_NEGATIVES_FIVE_OUTPUT_MEX_SIGNATURE';
    % Actual 15-condition coverage is measured as one-run per condition.
    % Conditions are not artificially counted as 15 repeated Flight cycles.
    ncase=0;
    for pathid=1:3
        for scene=1:5
            ncase=ncase+1;
            R.stage=sprintf('MATRIX_PATH_%d_SCENE_%d',pathid,scene);
            req=c9_matrix_request(A,pathid,scene,catalog);
            req=rmfield(req,'audit_pose_angles_deg');
            req.search_options.enable_13d_oracle_focused_qp_shapes=1;
            req.search_options.enable_13d_reuse_nominal_torque_certificate=1;
            req=c9_select_geometry_ab(req,mode);
            req=c9_native_request(req,true);
            G=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(req);
            assert(~G.safe_to_commit && ~G.hlc_actual_execution_proven, ...
                'C9_FULL:MatrixSafety','Unexpected Flight execution proof');
            E=R.matrix_cases(ncase);
            E.path={'straight','arc','saddle'};
            E.path=E.path{pathid};
            E.scene=scene;
            E.total_ms=G.total_elapsed_ms;
            E.status=G.status;
            E.search_ms=G.search_elapsed_ms;
            E.search_torque_ms=c9_search_torque_time(G.search_result);
            E.geometry_force_ms=G.joint_geometry_force_proof_ms;
            E.plane_ms=G.separation_planes_ms;
            E.qp_ms=G.joint_QP_ms;
            E.heading_ms=G.heading_join_ms;
            E.post_torque_ms=G.nominal_torque_ms;
            E.hlc_ms=G.hlc_bridge_elapsed_ms;
            E.hlc_status=G.hlc_bridge_status;
            E.native_search_certificate=c9_search_whole_proved(G.search_result);
            E.qp_outer_ball_groups_tested=G.qp_outer_ball_groups_tested;
            E.qp_outer_ball_groups_skipped=G.qp_outer_ball_groups_skipped;
            E.cable_envelope_axis_evaluations=G.cable_envelope_axis_evaluations;
            E.cable_envelope_strictly_improved=G.cable_envelope_strictly_improved;
            E.nominal_complete=G.nominal_model_complete;
            E.inherited_shape_skips=G.inherited_shape_skips_total;
            E.parent_shape_certificates=G.parent_shape_certificates_total;
            E.parent_outer_clearances=G.parent_outer_clearances_total;
            if G.nominal_model_complete
                E.certified_piece=G.candidate_piece;
            end
            R.matrix_ancestral_shape_skips_total= ...
                R.matrix_ancestral_shape_skips_total+E.inherited_shape_skips;
            R.matrix_ancestral_shape_certificates_total= ...
                R.matrix_ancestral_shape_certificates_total+ ...
                E.parent_shape_certificates;
            R.matrix_ancestor_outer_clearances_total= ...
                R.matrix_ancestor_outer_clearances_total+ ...
                E.parent_outer_clearances;
            E.safe_to_commit=G.safe_to_commit;
            E.search_status=G.search_status;
            E.search_failure_detail=G.failure_detail;
            R.matrix_cases(ncase)=E;
            R.matrix_count=ncase;
            R.matrix_nominal_complete_count=R.matrix_nominal_complete_count + ...
                double(E.nominal_complete);
            R.matrix_unknown_count=R.matrix_unknown_count + ...
                double(~E.nominal_complete);
            R.matrix_native_oracle_use_count=R.matrix_native_oracle_use_count+ ...
                double(E.native_search_certificate);
        end
    end
    T=[R.matrix_cases.total_ms];
    R.matrix_median_ms=median(T);
    R.matrix_p95_ms=percentile(T,0.95);
    R.matrix_max_ms=max(T);
    R.hlc_unbound_stays_unproven=all(strcmp(R.native_hlc_status(:), ...
        'NOT_BOUND_TO_LIVE_HLC'))&&all(isfinite(R.native_hlc_ms(:)))&& ...
        all(R.native_hlc_ms(:)==0);
    % Negative binding check (only after nominal success; never input proof).
    R.stage='HLC_PARTIAL_BINDING_REJECTED';
    req=c9_matrix_request(A,1,2,catalog);
    req=rmfield(req,'audit_pose_angles_deg');
    req.search_options.enable_13d_oracle_focused_qp_shapes=1;
    req.search_options.enable_13d_reuse_nominal_torque_certificate=1;
    req=c9_select_geometry_ab(req,mode);
    req=c9_native_request(req,true);
    req.live_hlc_execution=struct('not_a_valid_binding',true);
    Z=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(req);
    R.hlc_partial_binding_status=Z.hlc_bridge_status;
    R.hlc_partial_binding_rejected=Z.nominal_model_complete&& ...
        strcmp(Z.hlc_bridge_status,'UNKNOWN_LIVE_HLC_BINDING_INCOMPLETE')&& ...
        ~Z.hlc_tube_B_model_conditional_proven&&~Z.safe_to_commit;
    if R.matrix_count==15 && ...
            R.full_pipeline_status_parity && R.full_pipeline_candidate_parity && ...
            R.full_pipeline_proof_regressions==0 && ...
            all(R.native_certified(:)) && ...
            all(R.native_whole_used_inside_search(:)) && ...
            R.hlc_unbound_stays_unproven && R.hlc_partial_binding_rejected
        R.status='PASS_WHOLE_NATIVE_PROVEN_FIXTURES_AUDITED__15_UNKNOWN_POSSIBLE__HLC_WCET_PENDING';
    else
        R.status='REVIEW_FULL_PIPELINE_PARITY_OR_HLC_GATE';
    end
catch ME
    R.status='FAIL_WHOLE_FULL_PIPELINE_AUDIT';
    R.error_message=[ME.identifier ' | ' ME.message];
    R.error_report=getReport(ME,'extended','hyperlinks','off');
end
R.overall_elapsed_ms=1000*toc(clock);
try
    save(fullfile(root,[name '.mat']),'R');
    fid=fopen(fullfile(root,[name '.txt']),'w');
    if fid>=0
        fprintf(fid,'status=%s\nmode=%s\nstage=%s\nerror=%s\n', ...
            R.status,R.mode,R.stage,R.error_message);
        fprintf(fid,'whole_preflight=%s leaf_preflight=%s\n', ...
            R.whole_native_preflight_status,R.leaf_native_preflight_status);
        fprintf(fid,'negative_controls=%s\n',R.old_negative_controls_status);
        fprintf(fid,'full_baseline_ms=%s\nfull_native_ms=%s\n', ...
            mat2str(R.baseline_full_ms,6),mat2str(R.native_full_ms,6));
        fprintf(fid,'full_p95_old=%s full_p95_native=%s\n', ...
            mat2str(R.baseline_p95_ms,6),mat2str(R.native_p95_ms,6));
        fprintf(fid,'full_max_old=%s full_max_native=%s\n', ...
            mat2str(R.baseline_max_ms,6),mat2str(R.native_max_ms,6));
        fprintf(fid,'jitter_range_old=%s jitter_range_native=%s\n', ...
            mat2str(R.baseline_jitter_range_ms,6), ...
            mat2str(R.native_jitter_range_ms,6));
        fprintf(fid,'whole_used_inside_search=%s\n', ...
            mat2str(R.native_whole_used_inside_search));
        fprintf(fid,'native_search_torque_ms=%s\nnative_post_torque_ms=%s\n', ...
            mat2str(R.native_torque_in_search_ms,6), ...
            mat2str(R.native_post_torque_ms,6));
        fprintf(fid,'native_geometry_ms=%s\nnative_plane_ms=%s\nnative_qp_ms=%s\n', ...
            mat2str(R.native_joint_proof_ms,6), ...
            mat2str(R.native_plane_ms,6),mat2str(R.native_qp_ms,6));
        fprintf(fid,'native_integration_overhead_ms=%s\n', ...
            mat2str(R.native_integration_overhead_ms,6));
        fprintf(fid,'full_parity=%d candidate_parity=%d regressions=%d\n', ...
            R.full_pipeline_status_parity, ...
            R.full_pipeline_candidate_parity,R.full_pipeline_proof_regressions);
        fprintf(fid,'matrix_15_done=%d nominal_success=%d unknown=%d native_uses=%d\n', ...
            R.matrix_count,R.matrix_nominal_complete_count, ...
            R.matrix_unknown_count,R.matrix_native_oracle_use_count);
        fprintf(fid,'matrix_median=%.7f p95=%.7f max=%.7f\n', ...
            R.matrix_median_ms,R.matrix_p95_ms,R.matrix_max_ms);
        for i=1:R.matrix_count
            C=R.matrix_cases(i);
            fprintf(fid,'case=%02d path=%s scene=%d full=%.5f search=%.5f ', ...
                i,C.path,C.scene,C.total_ms,C.search_ms);
            fprintf(fid,'geometry=%.5f plane=%.5f qp=%.5f ', ...
                C.geometry_force_ms,C.plane_ms,C.qp_ms);
            fprintf(fid,'search_torque=%.5f heading=%.5f post_torque=%.5f ', ...
                C.search_torque_ms,C.heading_ms,C.post_torque_ms);
            fprintf(fid,'hlc=%.5f nominal=%d native=%d status=%s failure=%s\n', ...
                C.hlc_ms,C.nominal_complete,C.native_search_certificate, ...
                C.status,C.search_failure_detail);
        end
        fprintf(fid,'hlc_unbound_rejected=%d hlc_partial_rejected=%d status=%s\n', ...
            R.hlc_unbound_stays_unproven,R.hlc_partial_binding_rejected, ...
            R.hlc_partial_binding_status);
        if ~isempty(R.error_report),fprintf(fid,'%s\n',R.error_report);end
        fclose(fid);
    end
    zip(R.result_zip,{fullfile(root,[name '.mat']),fullfile(root,[name '.txt'])});
catch ME
    if isempty(R.error_message)
        R.error_message=['ZIP: ' ME.message];
    end
end
R.safe_to_commit=false;
end

function req=c9_native_request(req,whole)
req.nominal_torque_options.enable_fast_norm_sufficient_bound=1;
req.nominal_torque_options.use_cancellation_attitude_jet=1;
req.nominal_torque_options.use_bernstein_force_vector_hull=0;
req.nominal_torque_options.use_bernstein_force_support_lower=0;
req.nominal_torque_options.use_native_torque_leaf_kernel=double(~whole);
req.nominal_torque_options.use_native_whole_torque_kernel=double(whole);
req.torque_options=req.nominal_torque_options;
end

function v=c9_search_torque_time(s)
v=NaN;
if isstruct(s)&&isfield(s,'duration_13d_torque_ms')
    v=double(s.duration_13d_torque_ms);
end
end

function tf=c9_search_whole_proved(s)
tf=false;
if ~isstruct(s)||~isfield(s,'duration_13d_nominal_torque_proof_bundle')
    return
end
b=s.duration_13d_nominal_torque_proof_bundle;
if isstruct(b)&&isscalar(b)&&isfield(b,'proof')&&isstruct(b.proof)&& ...
        isfield(b.proof,'native_whole_torque_certified')
    tf=isequal(b.proof.native_whole_torque_certified,true);
end
end

function v=percentile(x,p)
x=sort(x(:));k=1+(numel(x)-1)*p;
i=floor(k);j=ceil(k);
v=x(i)+(k-i)*(x(j)-x(i));
end

