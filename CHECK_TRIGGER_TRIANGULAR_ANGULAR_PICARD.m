function A=CHECK_TRIGGER_TRIANGULAR_ANGULAR_PICARD()
% Verify a SOURCE-BOUND angular 3D Picard certificate and 21D handoff.
% Analytic cases use exact rigid-body angular solutions (not samples alone).
% Passing this test does NOT certify the actual Flight for 4 seconds.
A=struct('status','FAIL_TRIANGULAR_ANGULAR_PICARD', ...
    'cases',0,'failures',0,'analytic_endpoint_cases',0, ...
    'nontrivial_inertia_cases',0,'triangular_handoff_attempts',0, ...
    'triangular_handoff_successes',0, ...
    'source_pin_pass',false,'reason','','safe_to_commit',false);
try
    S=TRIGGER_TAUT_SOURCE_INVARIANTS();
    assert(S.source_bound_invariance && S.algebra_exact, ...
        'CHECK_TRIGGER_TRIANGULAR_ANGULAR_PICARD:Source', ...
        'Current original RHS/mirror source is not pinned.');
    A.source_pin_pass=true;A.cases=A.cases+1;
    p=zeros(21,1);
    p(1)=1.2;p(6:8)=[0.05;0.08;0.05];
    p(9)=9.80665;p(20)=0.14;p(21)=2;
    x=zeros(24,1);x(19:21)=[0;0;-1];x(15)=-2;
    % When Jx=Jz and Mx=Mz=0, omega1=omega3=0 is exact
    % (not merely approximate), omega2(t)=omega2(0)+My*t/Jy.
    % Both signs and a nonzero time-width are essential regression cases.
    for k=1:14
        sgn=1;
        if mod(k,2)==0,sgn=-1;end
        my=sgn*(0.008+0.002*k);
        u=[10;0;my;0];
        h=0.0001*(1+0.1*mod(k,3));
        hl=0.75*h;
        D=fixture(x,u,p,h,hl);
        R=TRIGGER_ORIGINAL_ANGULAR_STRICT_TUBE(D);
        assert(R.conditional_strict_inclusion && R.source_pinned && ...
            R.subslabs>=1 && R.minimum_margin>0 && ...
            ~R.safe_to_commit && ...
            all(isfinite([R.tube_lower;R.tube_upper; ...
                R.endpoint_lower;R.endpoint_upper])) && ...
            all(R.tube_lower<=R.tube_upper) && ...
            all(R.endpoint_lower<=R.endpoint_upper), ...
            'CHECK_TRIGGER_TRIANGULAR_ANGULAR_PICARD:AngularTube', ...
            'Case %d failed strict 3D source-pinned tube: %s',k,R.reason);
        % Use a slightly widened comparison tolerance only for arithmetic
        % in the AUDIT witness; this does not affect proof acceptance.
        v0=0;
        vLo=v0+my*hl/p(7);
        vHi=v0+my*h/p(7);
        exactLo=min(vLo,vHi);exactHi=max(vLo,vHi);
        tol=128*eps(max(1,abs(exactHi)));
        assert(R.endpoint_lower(2)<=exactLo+tol && ...
            R.endpoint_upper(2)>=exactHi-tol && ...
            all(R.tube_lower<=tol) && ...
            all(R.tube_upper>=-tol), ...
            'CHECK_TRIGGER_TRIANGULAR_ANGULAR_PICARD:EndpointSigns', ...
            'Case %d lost a true signed angular endpoint.',k);
        A.cases=A.cases+1;
        A.analytic_endpoint_cases=A.analytic_endpoint_cases+1;
    end
    % Genuine nonlinear coupling of all three omega coordinates.
    p(8)=0.095;
    for k=1:8
        xx=x;
        xx(10:12)=[0.02*k;-0.013*k;0.007*k];
        u=[10;0.008*sin(k);0.014*cos(k);0.009*sin(k/2)];
        D=fixture(xx,u,p,5e-5,4.8e-5);
        R=TRIGGER_ORIGINAL_ANGULAR_STRICT_TUBE(D);
        assert(R.conditional_strict_inclusion && R.source_pinned && ...
            R.minimum_margin>0 && ~R.safe_to_commit, ...
            'CHECK_TRIGGER_TRIANGULAR_ANGULAR_PICARD:NonlinearOmega', ...
            'Coupled angular proof %d failed: %s',k,R.reason);
        A.cases=A.cases+1;
        A.nontrivial_inertia_cases=A.nontrivial_inertia_cases+1;
    end
    % The public combined theorem may run independently of the legacy
    % AUTO_PICARD search. Its success is permitted ONLY when the separate
    % angular and 21D strict proofs both succeeded.
    p(8)=0.05;
    for k=1:3
        u=[10;0;0.01*k;0];
        D=fixture(x,u,p,1e-6,0.9e-6);
        T=TRIGGER_ORIGINAL_PLANT_TRIANGULAR_PICARD(D);
        A.cases=A.cases+1;
        A.triangular_handoff_attempts=A.triangular_handoff_attempts+1;
        assert(~T.safe_to_commit, ...
            'CHECK_TRIGGER_TRIANGULAR_ANGULAR_PICARD:UnauthorizedSafety');
        if T.success
            assert(T.angular_subslabs>=1 && ...
                isfinite(T.angular_margin)&&T.angular_margin>0 && ...
                isfinite(T.residual_margin)&&T.residual_margin>0 && ...
                all(isfinite([T.tube_lower;T.tube_upper; ...
                    T.endpoint_lower;T.endpoint_upper])) && ...
                isequal(size(T.tube_lower),[24 1]) && ...
                isequal(size(T.endpoint_lower),[24 1]) && ...
                all(T.tube_lower<T.tube_upper) && ...
                all(T.endpoint_lower<=T.endpoint_upper), ...
                'CHECK_TRIGGER_TRIANGULAR_ANGULAR_PICARD:FalseCombinedProof');
            A.triangular_handoff_successes= ...
                A.triangular_handoff_successes+1;
        else
            assert(~isempty(T.reason), ...
                'CHECK_TRIGGER_TRIANGULAR_ANGULAR_PICARD:NoFailureExplanation');
        end
    end
    % Reject physically impossible inertia and an inconsistent time span.
    pp=p;pp(7)=0;
    R=TRIGGER_ORIGINAL_ANGULAR_STRICT_TUBE( ...
        fixture(x,[10;0;0;0],pp,0.001,0.001));
    assert(~R.conditional_strict_inclusion && ~R.safe_to_commit, ...
        'CHECK_TRIGGER_TRIANGULAR_ANGULAR_PICARD:BadInertiaAccepted');
    A.cases=A.cases+1;
    D=fixture(x,[10;0;0;0],p,0.001,0.002);
    R=TRIGGER_ORIGINAL_ANGULAR_STRICT_TUBE(D);
    assert(~R.conditional_strict_inclusion && ~R.safe_to_commit, ...
        'CHECK_TRIGGER_TRIANGULAR_ANGULAR_PICARD:BadClockAccepted');
    A.cases=A.cases+1;
    A.status='PASS_SOURCE_PINNED_3D_ANGULAR_TRIANGULAR_PROOF__FLIGHT_NOT_VALIDATED';
    A.reason=['Strict 3D all-time angular Picard, exact signed endpoint ' ...
        'witnesses, coupled nonlinear dynamics and 21D theorem handoff ' ...
        'checked. A 4-second Flight safety grant was NOT made.'];
catch ME
    A.failures=1;
    A.reason=[ME.identifier ' | ' ME.message];
end
try
    save('TRIGGER_TRIANGULAR_ANGULAR_RESULT.mat','A');
    fid=fopen('TRIGGER_TRIANGULAR_ANGULAR_RESULT.txt','w');
    if fid>0
        fprintf(fid,['%s\ncases=%d failures=%d analytic=%d coupled=%d' ...
            ' handoffs=%d successes=%d source_pin=%d\n%s\n'], ...
            A.status,A.cases,A.failures,A.analytic_endpoint_cases, ...
            A.nontrivial_inertia_cases,A.triangular_handoff_attempts, ...
            A.triangular_handoff_successes,A.source_pin_pass,A.reason);
        fclose(fid);
    end
catch
end
end

function D=fixture(x,u,p,h,hl)
D=struct('x0_lower',x,'x0_upper',x, ...
    'u_lower',u,'u_upper',u, ...
    'param_lower',p,'param_upper',p, ...
    'h_s',h,'h_lower_s',hl);
end
