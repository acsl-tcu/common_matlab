            R.p95_ms_by_mode(mode,sc)=t(ceil(.95*numel(t)));
            R.max_ms_by_mode(mode,sc)=t(end);
        end
    end
    R.stage='NON_CERTIFYING_MIDPOINT_DIAGNOSTIC';
    o=opt;
    o.use_structural_torque_intersection=true;
    o.enable_unknown_midpoint_diagnostic=true;
    Z=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL(pieces{2},a,o);
    R.midpoint_s=Z.unresolved_midpoint_s;
    R.midpoint_valid=Z.unresolved_midpoint_valid;
    R.midpoint_torque_bounds_Nm=Z.unresolved_midpoint_torque_bounds_Nm;
    R.midpoint_inside_limits_unrounded= ...
      Z.unresolved_midpoint_inside_limits_unrounded;
    % One diagnostic-only depth probe, not in the online certificate.
    % The candidate remains uncommittable regardless of its result.
    R.stage='DEPTH_10_UNRESOLVED_CAUSE_PROBE';
    o.max_subdivision_depth=10;
    o.max_node_count=511;
    D=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL(pieces{2},a,o);
    R.depth_10_probe_status=D.status;
    R.depth_10_probe_ms=D.elapsed_ms;
    R.depth_10_probe_nodes=D.checked_nodes;
    R.depth_10_probe_detailed=D.detailed_interval_checked_nodes;
    R.depth_10_probe_unknown_interval_s=D.unresolved_interval_s;
    R.depth_10_probe_unknown_bounds_Nm=D.unresolved_torque_bounds_Nm;
    assert(~D.safe_to_commit && ~D.actual_HLC_tracking_proven && ...
      ~D.numerically_directed_rounding_proven, ...
      'C9_STRUCTURAL:ProbeCommit','Depth probe changed COMMIT.');
    assert(~Z.safe_to_commit && ~Z.actual_HLC_tracking_proven && ...
      ~Z.numerically_directed_rounding_proven, ...
      'C9_ATTITUDE:DiagnosticCommit','A point diagnostic changed COMMIT.');
    if R.baseline_proof_regressions==0
        R.status='PASS_C9_STRUCTURAL_TORQUE_AB__HLC_UNCERTIFIED';
    else
        R.status='FAIL_C9_STRUCTURAL_TORQUE_PROOF_REGRESSION';
    end
    R.stage='COMPLETE';
catch ME
    R.error_identifier=ME.identifier;
    R.error_message=ME.message;
    R.error_stack=arrayfun(@(e)sprintf('%s:%d',e.name,e.line), ...
      ME.stack,'UniformOutput',false);
end
save(fullfile(root,[name '.mat']),'R');
fid=fopen(fullfile(root,[name '.txt']),'w');
if fid>=0
    fprintf(fid,'status=%s\nstage=%s\nerror=%s | %s\n', ...
      R.status,R.stage,R.error_identifier,R.error_message);
    for k=1:numel(R.error_stack)
        fprintf(fid,'stack_%d=%s\n',k,R.error_stack{k});
    end
    fprintf(fid,'attitude_second_derivative_tests=%d | max_error=%.12g\n', ...
      R.point_identity_trials,R.point_identity_max_error);
    fprintf(fid,'guide=%s | search_ms=%.6f | proof_calls=%g\n', ...
      R.search_status,R.search_elapsed_ms,R.search_independent_proof_calls);
    for sc=1:2
      for m=1:2
        if numel(R.status_by_mode)<m+2*(sc-1),continue;end
        fprintf(fid,['scene=%s | mode=%s | status=%s | nodes=%g | detailed=%g ', ...
          '| median_ms=%.6f | p95_ms=%.6f | max_ms=%.6f\n'], ...
          R.scene_names{sc},R.mode_names{m},R.status_by_mode{m,sc}, ...
          R.nodes_by_mode(m,sc),R.detailed_nodes_by_mode(m,sc), ...
          R.median_ms_by_mode(m,sc),R.p95_ms_by_mode(m,sc), ...
          R.max_ms_by_mode(m,sc));
      end
    end
    fprintf(fid,'structural_attempts=[%d %d] | tightened=[%d %d] | rescued=[%d %d]\n', ...
      R.structural_attempts_by_mode(2,1),R.structural_attempts_by_mode(2,2), ...
      R.structural_tighten_by_mode(2,1),R.structural_tighten_by_mode(2,2), ...
      R.structural_rescues_by_mode(2,1),R.structural_rescues_by_mode(2,2));
    fprintf(fid,'structural_unusable=[%d %d] | exceptions=[%d %d]\n', ...
      R.structural_unusable_by_mode(2,1),R.structural_unusable_by_mode(2,2), ...
      R.structural_exception_by_mode(2,1),R.structural_exception_by_mode(2,2));
    fprintf(fid,'unresolved_depth_baseline=%.0f | unresolved_depth_new=%.0f | reason=%s\n', ...
      R.unknown_depth_by_mode(1,2),R.unknown_depth_by_mode(2,2), ...
      R.unknown_reason_by_mode{2,2});
    fprintf(fid,'depth10_status=%s | nodes=%.0f | detailed=%.0f | ms=%.6f\n', ...
      R.depth_10_probe_status,R.depth_10_probe_nodes, ...
      R.depth_10_probe_detailed,R.depth_10_probe_ms);
    fprintf(fid,'depth10_interval=[%.12g %.12g] | Mz=[%.12g %.12g] Nm\n', ...
      R.depth_10_probe_unknown_interval_s, ...
      R.depth_10_probe_unknown_bounds_Nm(3,1), ...
      R.depth_10_probe_unknown_bounds_Nm(3,2));
    fprintf(fid,'proof_regressions=%d | proof_improvements=%d\n', ...
      R.baseline_proof_regressions,R.new_proof_improvements);
    fprintf(fid,'new_midpoint_s=%.12g | valid=%d | inside_unrounded=%d\n', ...
      R.midpoint_s,R.midpoint_valid, ...
      R.midpoint_inside_limits_unrounded);
    fprintf(fid,'scope=%s | safe_to_commit=%d\n',R.scope,R.safe_to_commit);
    fclose(fid);
end
zip(R.zip_path,{[name '.mat'],[name '.txt']},root);
fprintf('[C9 STRUCTURAL TORQUE] %s | %s\n',R.status,R.zip_path);
end

function U=c9_att_unit(X)
% Exact point jet through derivative order 2, independent of production.
a=X(:,1);ad=X(:,2);add=X(:,3);
n=norm(a);nd=dot(a,ad)/n;
ndd=(dot(ad,ad)+dot(a,add)-nd^2)/n;
u=a/n;
ud=(ad-nd*u)/n;
udd=(add-2*nd*ud-ndd*u)/n;
U=[u,ud,udd];
end
function C=c9_att_cross(A,B)
C=[cross(A(:,1),B(:,1)), ...
   cross(A(:,2),B(:,1))+cross(A(:,1),B(:,2)), ...
   cross(A(:,3),B(:,1))+2*cross(A(:,2),B(:,2))+ ...
     cross(A(:,1),B(:,3))];
end
function L=c9_att_lat(A)
L=[-A(2,:);A(1,:);zeros(1,size(A,2))];
end

function [w,al]=c9_att_structural_point(F,A)
% Independent exact-point derivation; no access to production interval code.
f=F(:,1);f1=F(:,2);f2=F(:,3);
a=A(:,1);a1=A(:,2);a2=A(:,3);
n=norm(f);m=norm(a);C=cross(f,a);
kF=dot(f,f1)/n^2;kA=dot(a,a1)/m^2;
N1=dot(C,f1);N2=dot(a,f1);N3=dot(C,a1);
N1p=dot(cross(f,a1),f1)+dot(C,f2);
N2p=dot(a1,f1)+dot(a,f2);
N3p=dot(cross(f1,a),a1)+dot(C,a2);
w=[-N1/(n^2*m);N2/(n*m);N3/(n*m^2)];
al=[-(N1p-N1*(2*kF+kA))/(n^2*m); ...
     (N2p-N2*(kF+kA))/(n*m); ...
     (N3p-N3*(kF+2*kA))/(n*m^2)];
end
