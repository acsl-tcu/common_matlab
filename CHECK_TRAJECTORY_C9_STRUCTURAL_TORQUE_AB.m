function R=CHECK_TRAJECTORY_C9_STRUCTURAL_TORQUE_AB()
% Temporary development-only validation: structural omega/alpha interval
% extension for C9 NOMINAL torque proof; preserves continuous-time guards.
% Runtime benchmark compares the cancelled-normalization baseline and structural-invariant intersection.
% Neither branch proves HLC tracking or directed floating-point rounding.
root=fileparts(mfilename('fullpath'));
name='TRAJECTORY_C9_STRUCTURAL_TORQUE_AB_RESULT';
R=struct('status','FAIL_C9_STRUCTURAL_TORQUE_AB', ...
  'stage','START','error_identifier','','error_message','', ...
  'error_stack',{{}}, ...
  'scene_names',{{'SMOOTH_NOMINAL','SPHERE_ELLIPSOID_CERTIFIED_GUIDE'}}, ...
  'mode_names',{{'CANCELLED_NORMALIZATION_BASELINE', ...
                  'STRUCTURAL_OMEGA_ALPHA_INTERSECTION'}}, ...
  'status_by_mode',{{}},'nodes_by_mode',NaN(2,2), ...
  'detailed_nodes_by_mode',NaN(2,2), ...
  'accepted_leaves_by_mode',NaN(2,2), ...
  'structural_attempts_by_mode',NaN(2,2), ...
  'structural_tighten_by_mode',NaN(2,2), ...
  'structural_rescues_by_mode',NaN(2,2), ...
  'median_ms_by_mode',NaN(2,2), ...
  'p95_ms_by_mode',NaN(2,2), ...
  'max_ms_by_mode',NaN(2,2), ...
  'unknown_interval_s_by_mode',NaN(2,2), ...
  'unknown_depth_by_mode',NaN(2,2), ...
  'unknown_reason_by_mode',{{}}, ...
  'structural_unusable_by_mode',NaN(2,2), ...
  'structural_exception_by_mode',NaN(2,2), ...
  'unknown_bounds_Nm_by_mode',NaN(3,2,2), ...
  'point_identity_trials',0,'point_identity_max_error',NaN, ...
  'midpoint_s',NaN,'midpoint_valid',false, ...
  'midpoint_torque_bounds_Nm',NaN(3,2), ...
  'midpoint_inside_limits_unrounded',false, ...
  'search_status','NOT_CALLED','search_elapsed_ms',NaN, ...
  'search_independent_proof_calls',NaN, ...
  'depth_10_probe_status','NOT_RUN','depth_10_probe_ms',NaN, ...
  'depth_10_probe_nodes',NaN, 'depth_10_probe_detailed',NaN, ...
  'depth_10_probe_unknown_interval_s',[NaN NaN], ...
  'depth_10_probe_unknown_bounds_Nm',NaN(3,2), ...
  'baseline_proof_regressions',0,'new_proof_improvements',0, ...
  'safe_to_commit',false,'repetitions',7, ...
  'scope','REAL_ARITHMETIC_NOMINAL_ONLY__HLC_AND_ROUNDING_UNCERTIFIED', ...
  'zip_path',fullfile(root,[name '_FOR_CHATGPT.zip']));
try
    R.stage='VALUE_AND_SECOND_DERIVATIVE_IDENTITY';
    oldrng=rng; clean_rng=onCleanup(@()rng(oldrng));
    rng(911,'twister');
    maxerr=0;
    for q=1:1000
        v=[1.5;1;0]+[0.8*randn(2,1);0];
        vjet=[v, [0.3*randn(2,1);0], [0.3*randn(2,1);0]];
        fjet=[randn(2,1);2+6*rand];
        fjet=[fjet,randn(3,1),randn(3,1)];
        older=c9_att_unit(c9_att_cross(c9_att_lat( ...
            c9_att_unit(vjet)),c9_att_unit(fjet)));
        newer=c9_att_unit(c9_att_cross(c9_att_lat(vjet),fjet));
        e=max(abs(older(:)-newer(:)));
        maxerr=max(maxerr,e);
        assert(e<=5e-10*max(1,max(abs(older(:)))), ...
          'C9_ATTITUDE:DerivativeIdentity', ...
          'Cancelled second-order attitude jet differs from original.');
    end
    % Independent point-jet identity test for the new scalar-invariant
    % omega/alpha formulas. This is not a sampled safety certificate.
    for q=1:1000
        vjet=[1.0+randn(2,1);0];
        vjet=[vjet,[0.3*randn(2,1);0],[0.3*randn(2,1);0]];
        fjet=[[randn(2,1);2+6*rand],randn(3,1),randn(3,1)];
        ajet=c9_att_cross(c9_att_lat(vjet),fjet);
        b1=c9_att_unit(ajet);
        b3=c9_att_unit(fjet);
        b2=c9_att_cross(b3,b1);
        omega=[dot(b3(:,1),b2(:,2));dot(b1(:,1),b3(:,2)); ...
               dot(b2(:,1),b1(:,2))];
        alpha=[dot(b3(:,2),b2(:,2))+dot(b3(:,1),b2(:,3)); ...
               dot(b1(:,2),b3(:,2))+dot(b1(:,1),b3(:,3)); ...
               dot(b2(:,2),b1(:,2))+dot(b2(:,1),b1(:,3))];
        [w2,a2]=c9_att_structural_point(fjet,ajet);
        e=max(abs([omega-w2;alpha-a2]));
        maxerr=max(maxerr,e);
        assert(e<1e-9*max(1,max(abs(alpha))), ...
           'C9_STRUCTURAL:PointIdentity', ...
           'Structural invariant angular velocity or acceleration mismatch.');
    end
    R.point_identity_trials=2000;
    R.point_identity_max_error=maxerr;
    clear clean_rng

    R.stage='LIVE_HLC_LIMITS_AND_C9_FIXTURES';
    addpath(fullfile(root,'controller'),fullfile(root,'model'),'-begin');
    addpath(fullfile(root,'reference','REPLANNING_SYSTEM', ...
      'TRAJECTORY_GENERATION'), ...
      fullfile(root,'reference','REPLANNING_SYSTEM', ...
      'OBSTACLE_INFORMATION'),'-begin');
    [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    P.set("loadmass",0.14); % CHECK fixture only. Never production default.
    d=double(P.get(["mass","jx","jy","jz","gravity","cableL","loadmass"]));
    d=d(:);lo=double(lo(:));hi=double(hi(:));
    assert(numel(d)==7&&all(isfinite(d))&&all(d>0)&& ...
      numel(lo)==4&&numel(hi)==4&&all(hi>lo), ...
      'C9_ATTITUDE:Authority','Real HLC source bounds unavailable.');
    a=struct('uav_mass_kg',d(1),'payload_mass_kg',d(7), ...
      'cable_length_m',d(6),'uav_inertia_kgm2',d(2:4), ...
      'gravity_world_mps2',[0;0;-d(5)], ...
      'thrust_limits_N',[lo(1),hi(1)], ...
      'torque_limits_Nm',[lo(2:4),hi(2:4)], ...
      'minimum_tension_N',0,'acceleration_guard_mps2',0);
    opt=struct('max_subdivision_depth',8,'max_node_count',511, ...
      'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
      'torque_guard_Nm',zeros(3,1), ...
      'enable_fast_norm_sufficient_bound',true, ...
      'use_precomputed_binomial',true, ...
      'use_factored_diagonal_gyro',true, ...
      'enable_infeasible_leaf_early_exit',true, ...
      'use_symmetric_unit_jet_kernel',true, ...
      'use_cancellation_attitude_jet',true, ...
      'use_structural_torque_intersection',false);
    J0=zeros(3,10);J1=zeros(3,10);
    J0(:,1)=[-2;0;3];J1(:,1)=[2;0;3];
    J0(1,2)=0.4;J1(1,2)=0.4;
    nominal=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,10,J0,J1, ...
      repmat([0;0;3],1,4));

    R.stage='GENERATE_GEOMETRY_CERTIFIED_GUIDE_ONCE';
    theta=0.34;Q=[cos(theta) -sin(theta) 0; ...
                     sin(theta) cos(theta) 0;0 0 1];
    observed=[OBSTACLE_INFORMATION.define(21,'sphere',[0 0.1 3],0.2), ...
      OBSTACLE_INFORMATION.define(33,'ellipsoid',[0.6 -0.16 3], ...
      [0.32 0.19 0.4],'rotation',Q)];
    gopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
      'numerical_guard_m',0,'robust_tube_enabled',false, ...
      'trajectory_phase','f');
    fopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
      'force_guard_N',0);
    sopt=struct('probe_count',13,'max_outer_iterations',4, ...
      'max_projection_sweeps',100,'projection_tolerance_m',1e-8, ...
      'min_separation_m',1e-5, ...
      'lazy_initial_proof_on_violated_plane',false, ...
      'payload_hull_witness_policy','off', ...
      'embed_taut_bernstein_halfspaces',false, ...
      'accept_first_certified_minimum_qp',false, ...
      'enable_connected_group_topology',true, ...
      'enable_point_intersection_prefilter',true);
    req=struct('t0_s',8,'duration_s',10,'flight_interval_s',[8 30], ...
      'start_jets',J0,'end_jets',J1, ...
      'nominal_free',nominal.control_points_m(:,11:14), ...
      'observed',observed, ...
      'radii',struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1), ...
      'authority',a,'geometry_options',gopt, ...
      'force_options',fopt,'search_options',sopt);
    S=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(req);
    R.search_status=S.status;R.search_elapsed_ms=S.elapsed_ms;
    R.search_independent_proof_calls=S.independent_proof_calls;
    assert(S.candidate_available&&S.final_certificate.certified&& ...
      ~S.safe_to_commit, 'C9_ATTITUDE:Guide', ...
      ['No geometry-certified fixture: ' S.status]);
    pieces={nominal,S.candidate_piece};
    R.status_by_mode=cell(2,2);
    R.unknown_reason_by_mode=cell(2,2);
    R.stage='CONTINUOUS_TIME_PROOF_AB_7_REPEATS';
    for sc=1:2
        reference=cell(2,1);
        for mode=1:2
            o=opt;
            o.use_structural_torque_intersection=(mode==2);
            Z=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL(pieces{sc},a,o);
            assert(~Z.safe_to_commit && ~Z.actual_HLC_tracking_proven && ...
              ~Z.numerically_directed_rounding_proven && ...
              Z.structural_torque_intersection_enabled==(mode==2) && ...
              Z.cancellation_attitude_jet_enabled, ...
              'C9_ATTITUDE:Scope','Nominal certificate changed COMMIT status.');
            reference{mode}=Z;
            R.status_by_mode{mode,sc}=Z.status;
            R.nodes_by_mode(mode,sc)=Z.checked_nodes;
            R.detailed_nodes_by_mode(mode,sc)=Z.detailed_interval_checked_nodes;
            R.accepted_leaves_by_mode(mode,sc)=Z.accepted_leaves;
            R.structural_attempts_by_mode(mode,sc)= ...
               Z.structural_torque_attempted_nodes;
            R.structural_tighten_by_mode(mode,sc)= ...
               Z.structural_torque_tightened_nodes;
            R.structural_rescues_by_mode(mode,sc)= ...
               Z.structural_torque_certified_leaves;
            R.structural_unusable_by_mode(mode,sc)= ...
               Z.structural_torque_unusable_nodes;
            R.structural_exception_by_mode(mode,sc)= ...
               Z.structural_torque_exception_nodes;
            R.unknown_depth_by_mode(mode,sc)=Z.unresolved_depth;
            R.unknown_reason_by_mode{mode,sc}=Z.last_leaf_reason;
            if sc==2
                R.unknown_interval_s_by_mode(mode,:)=Z.unresolved_interval_s;
                R.unknown_bounds_Nm_by_mode(:,:,mode)=Z.unresolved_torque_bounds_Nm;
            end
        end
        if reference{1}.conditional_nominal_all_time_torque_proven && ...
            ~reference{2}.conditional_nominal_all_time_torque_proven
            R.baseline_proof_regressions=R.baseline_proof_regressions+1;
