               reference{2}.conditional_nominal_all_time_torque_proven
            R.new_proof_improvements=R.new_proof_improvements+1;
        end
        time_ms=NaN(2,R.repetitions);
        for rep=1:R.repetitions
            for position=1:2
                mode=mod(rep+position-2,2)+1;
                o=opt;
                o.use_structural_torque_intersection=(mode==2);
                Z=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL(pieces{sc},a,o);
