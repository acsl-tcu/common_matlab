function R=CHECK_TRAJECTORY_C9_ENTRY_STATE_AND_HLC_LIMITS()
% Offline NECESSARY EKF-to-C9 start consistency + real HLC four-clamp audit.
% Does NOT certify high C7 derivatives, current HLC feedback, motor mixer,
% or any future collision-free closed-loop execution. No run/HLC changes.
root=fileparts(mfilename('fullpath'));
R=struct('status','FAIL_NOT_STARTED','stage','START', ...
    'error_identifier','','error_message','','error_stack',{{}}, ...
    'source_four_input_bounds_read',false, ...
    'software_lower',NaN(4,1),'software_upper',NaN(4,1), ...
    'hardware_motor_feasibility_proven',false, ...
    'valid_entry_necessary_pass',false, ...
    'stale_mass_rejected',false,'stale_position_rejected',false, ...
    'bad_cable_direction_rejected',false, ...
    'bad_uav_position_rejected',false, ...
    'stale_velocity_rejected',false, ...
    'missing_tolerance_rejected',false, ...
    'unbound_high_order_and_HLC_forbidden',false, ...
    'integrated_stale_live_start_rejected_before_search',false, ...
    'elapsed_ms',NaN);
t0=tic;
try
    R.stage='PATH';
    addpath(genpath(fullfile(root,'reference','REPLANNING_SYSTEM')),'-begin');
    R.stage='FOUR_REAL_HLC_SOFTWARE_BOUNDS';
    [lo,hi,source]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    lo=double(lo(:));hi=double(hi(:));
    R.software_lower=lo;R.software_upper=hi;
    assert(isfile(source)&&isequal(size(lo),[4 1])&& ...
        isequal(size(hi),[4 1])&&all(isfinite([lo;hi]))&& ...
        all(lo<hi)&&lo(1)>=0, ...
        'CHECK_C9_ENTRY:HLCBounds','The actual four-channel HLC software bound is invalid.');
    R.source_four_input_bounds_read=true;
    R.stage='VALID_CURRENT_EKF_ENTRY_NECESSARY';
    gravity=[0;0;-9.80665]; % TEST FIXTURE only, never Flight fallback.
    mL=.11;L=2.2; 
    j=zeros(3,10);j(:,1)=[3;2;4];j(:,2)=[.8;-.3;0];
    % Consistent taut cable: q=(gravity-j(:,3))/||...|| = [0;0;-1].
    q=[0;0;-1];
    ekf=struct('pL',j(:,1),'vL',j(:,2), ...
        'pT',q,'p',j(:,1)-L*q,'mL',mL);
    a=struct('payload_mass_kg',mL,'cable_length_m',L, ...
        'gravity_world_mps2',gravity);
    req=struct('t0_s',12.345,'start_jets',j,'authority',a);
    % Test-only near-rounding tolerances; production requires external
    % per-Flight physics/estimator bounds, NEVER these fixture numbers.
    tol=struct('payload_position_m',1e-10, ...
        'payload_velocity_mps',1e-10, ...
        'cable_direction_rad',1e-10,'uav_position_m',1e-10);
    E=TRAJECTORY_C9_ENTRY_STATE_GATE(req,ekf,tol);
    R.valid_entry_necessary_pass=E.necessary_conditions_met;
    R.unbound_high_order_and_HLC_forbidden=E.necessary_conditions_met&& ...
        ~E.safe_to_commit&&~E.C7_high_order_join_proven&& ...
        ~E.HLC_tracking_and_preclamp_proven;
    assert(R.valid_entry_necessary_pass&& ...
        R.unbound_high_order_and_HLC_forbidden, ...
        'CHECK_C9_ENTRY:EntryValid','Valid EKF entry was rejected or falsely committed.');
    R.stage='NEGATIVE_ENTRY_CONSISTENCY_TESTS';
    r=req;r.authority.payload_mass_kg=.12;
    M=TRAJECTORY_C9_ENTRY_STATE_GATE(r,ekf,tol);
    R.stale_mass_rejected=~M.necessary_conditions_met&& ...
        strcmp(M.status,'UNKNOWN_ENTRY_STALE_EKF_PAYLOAD_MASS');
    e=ekf;e.pL=e.pL+[.1;0;0];
    M=TRAJECTORY_C9_ENTRY_STATE_GATE(req,e,tol);
    R.stale_position_rejected=~M.necessary_conditions_met&& ...
        strcmp(M.status,'UNKNOWN_ENTRY_PAYLOAD_POSITION_MISMATCH');
    e=ekf;e.vL=e.vL+[0;.1;0];
    M=TRAJECTORY_C9_ENTRY_STATE_GATE(req,e,tol);
    R.stale_velocity_rejected=~M.necessary_conditions_met&& ...
        strcmp(M.status,'UNKNOWN_ENTRY_PAYLOAD_VELOCITY_MISMATCH');
    e=ekf;e.pT=[1;0;0];
    M=TRAJECTORY_C9_ENTRY_STATE_GATE(req,e,tol);
    R.bad_cable_direction_rejected=~M.necessary_conditions_met&& ...
        strcmp(M.status,'UNKNOWN_ENTRY_CABLE_DIRECTION_MISMATCH');
    e=ekf;e.p=e.p+[.1;0;0];
    M=TRAJECTORY_C9_ENTRY_STATE_GATE(req,e,tol);
    R.bad_uav_position_rejected=~M.necessary_conditions_met&& ...
        strcmp(M.status,'UNKNOWN_ENTRY_UAV_POSITION_MISMATCH');
    M=TRAJECTORY_C9_ENTRY_STATE_GATE(req,ekf,struct());
    R.missing_tolerance_rejected=~M.necessary_conditions_met&& ...
        strcmp(M.status,'UNKNOWN_ENTRY_REQUIRED_LIVE_FIELDS_MISSING');
    assert(R.stale_mass_rejected&&R.stale_position_rejected&& ...
        R.stale_velocity_rejected&&R.bad_cable_direction_rejected&& ...
        R.bad_uav_position_rejected&&R.missing_tolerance_rejected, ...
        'CHECK_C9_ENTRY:NegativeTests','Stale or misaligned EKF entry was not rejected.');
    R.stage='CHECK_INTEGRATED_BEFORE_OPTIMIZER';
    r=req;
    r.authority=struct('payload_mass_kg',.12, ...
        'cable_length_m',L,'gravity_world_mps2',gravity, ...
        'uav_inertia_kgm2',[.01;.01;.02], ...
        'torque_limits_Nm',[lo(2:4),hi(2:4)], ...
        'thrust_limits_N',[lo(1),hi(1)]);
    r.geometry_options=struct('trajectory_phase','f');
    r.observed=struct([]);
    r.heading_options=struct();
    r.nominal_torque_options=struct();
    r.current_ekf_state=ekf;r.entry_tolerances=tol;
    I=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(r);
    R.integrated_stale_live_start_rejected_before_search= ...
        ~I.live_EKF_entry_necessary_pass&& ...
        strcmp(I.status,'UNKNOWN_CURRENT_EKF_TO_C9_ENTRY_INCONSISTENT')&& ...
        strcmp(I.live_EKF_entry_status,'UNKNOWN_ENTRY_STALE_EKF_PAYLOAD_MASS')&& ...
        strcmp(I.search_status,'NOT_CALLED')&&~I.safe_to_commit;
    assert(R.integrated_stale_live_start_rejected_before_search, ...
        'CHECK_C9_ENTRY:Integrated','Old EKF mass reached the optimizer.');
    R.status='PASS_EKF_C9_ENTRY_NECESSARY_AND_REAL_4_HLC_CLAMPS__NOT_COMMIT';
    R.stage='COMPLETE';
catch ME
    R.status='FAIL_EKF_C9_ENTRY_AND_HLC_LIMITS';
    R.error_identifier=ME.identifier;R.error_message=ME.message;
    R.error_stack=arrayfun(@(f)sprintf('%s:%d',f.name,f.line), ...
        ME.stack,'UniformOutput',false);
end
R.elapsed_ms=1000*toc(t0);
name='TRAJECTORY_C9_ENTRY_STATE_AND_HLC_LIMITS_RESULT';
mfile=fullfile(root,[name '.mat']);
tfile=fullfile(root,[name '.txt']);
zfile=fullfile(root,[name '_FOR_CHATGPT.zip']);
save(mfile,'R');
fid=fopen(tfile,'w');
if fid>=0
    fprintf(fid,'status=%s\nstage=%s\nerror_identifier=%s\nerror_message=%s\n', ...
        R.status,R.stage,R.error_identifier,R.error_message);
    for k=1:numel(R.error_stack)
        fprintf(fid,'stack_%d=%s\n',k,R.error_stack{k});
    end
    fprintf(fid,'HLC_SOFTWARE_LO=%s\nHLC_SOFTWARE_HI=%s\n', ...
        mat2str(R.software_lower.'),mat2str(R.software_upper.'));
    fprintf(fid,'HW_MOTOR_ALLOCATION_CERTIFIED=%d\n',R.hardware_motor_feasibility_proven);
    for k={'valid_entry_necessary_pass','stale_mass_rejected', ...
            'stale_position_rejected','stale_velocity_rejected', ...
            'bad_cable_direction_rejected','bad_uav_position_rejected', ...
            'missing_tolerance_rejected', ...
            'integrated_stale_live_start_rejected_before_search'}
        key=k{1};fprintf(fid,'%s=%d\n',key,R.(key));
    end
    fprintf(fid,'elapsed_ms=%.6f\n',R.elapsed_ms);
    fclose(fid);
end
if isfile(zfile),delete(zfile);end
zip(zfile,{mfile,tfile});
fprintf('[C9 ENTRY+HLC 4 INPUTS] %s | %s\n',R.status,zfile);
end
