function report = CHECK_SENSOR_PREFLIGHT_WARMUP()
% CHECK_SENSOR_PREFLIGHT_WARMUP  飛行前の初回準備と本番センサ状態非汚染の検証。
% 一時検証用。正常なFlightの代わりにはならない。
options=struct('ENABLE_SENSOR',true,'ENABLE_ALL_LOG',true, ...
    'LOG_SENSOR',true,'LOG_OBSTACLES',true,'LOG_REPLANNER',true, ...
    'SENSOR_RANGE_M',20);
r=REPLANNING_SYSTEM(options);
s=r.get_status();
assert(s.preflight_warmup_ready, '初回準備が完了していません。');
assert(isfinite(s.preflight_warmup_ms) && s.preflight_warmup_ms>=0, ...
    '初回準備の時間が不正です。');
assert(s.sensor_status.scan_count==0 && s.sensor_status.timing_count==0, ...
    '初回準備が本番センサの計測回数を進めています。');
assert(isempty(s.sensor_status.last_detected_ids), ...
    '初回準備が本番の検知状態を汚染しています。');
assert(s.preflight_warmup_distance_checks==2*numel(r.obstacles), ...
    '幾何計算の事前実行件数が不正です。');
p=[0;0;0];t=0;
actual=r.observe_sensor(t,p);
reference=SIMULATED_OBSTACLE_SENSOR(r.obstacles,options.SENSOR_RANGE_M,true);
expected=reference.observe(t,p);
fields={'detected_ids','newly_detected_ids','left_range_ids', ...
        'detected_count','detected_distances_m','candidates_checked', ...
        'obstacles_screened','detected_obstacles'};
for k=1:numel(fields)
    f=fields{k};
    a=actual.(f);b=expected.(f);
    if isnumeric(a) && isnumeric(b) && isempty(a) && isempty(b)
        continue
    end
    assert(isequaln(a,b), '初回検知が基準センサと一致しません: %s',f);
end
s=r.get_status();
assert(s.sensor_status.scan_count==1 && s.sensor_status.timing_count==1, ...
    '本番センサの初回カウンタが不正です。');
report=struct('status','PASS_SENSOR_PREFLIGHT_WARMUP', ...
    'preflight_ms',s.preflight_warmup_ms, ...
    'preflight_geometry_checks',s.preflight_warmup_distance_checks, ...
    'first_detected_ids',actual.detected_ids, ...
    'first_newly_detected_ids',actual.newly_detected_ids, ...
    'first_scan_count',s.sensor_status.scan_count, ...
    'first_scan_elapsed_ms',actual.elapsed_ms);
fprintf('[PREFLIGHT] %s | warmup=%.4f ms | geometry checks=%d | first new IDs=%s\n', ...
    report.status,report.preflight_ms,report.preflight_geometry_checks, ...
    mat2str(report.first_newly_detected_ids));
fprintf('[PREFLIGHT] real first scan=%.4f ms\n',report.first_scan_elapsed_ms);
end
