function R=CHECK_TRIGGER_THREAD_THREE_RUNS()
% Three runs, SAME source and settings. Compare peaks in thread CPU & wall.
% A gap may be preemption, waiting, MATLAB runtime stalls, etc. NOT causal
% proof, and not a scheduling or worst-case execution time (WCET) bound.
root=fileparts(mfilename('fullpath'));
labels={'sensor_memory_prepared','nonflight_shadow','yellow_trigger','blue_results_log'};
R=struct('status','FAIL_THREAD_THREE_RUNS','reason','', ...
    'labels',{labels},'runs',struct([]), ...
    'physical_safety_certified',false,'wcet_certified',false);
try
    baseline_flags=[];
    for j=1:3
        p=fullfile(root,sprintf('TRIGGER_THREAD_RUN_%02d.mat',j));
        assert(exist(p,'file')==2,'CHECK_TRIGGER_THREAD:MissingRun', ...
            'Capture all three real Flights with CPU clock enabled.');
        Z=load(p,'C');C=Z.C;
        assert(C.run==j && C.valid_count==C.count && C.count>0, ...
            'CHECK_TRIGGER_THREAD:CaptureIncomplete', ...
            'Run %d is incomplete (valid %d/%d).',j,C.valid_count,C.count);
        if j==1
            baseline_flags=C.flags;
        else
            assert(isequal(C.flags,baseline_flags), ...
                'CHECK_TRIGGER_THREAD:FlagsChanged', ...
                'Three Flights must run with the SAME flags.');
        end
        W=C.segments_wall_ms;T=C.segments_cpu_ms;
        assert(isfield(C,'segments_thread_cycles') && ...
            C.cycle_valid_count==C.count, ...
            'CHECK_TRIGGER_THREAD:CycleSeriesMissing', ...
            'Rebuild the cycle-clock MEX and recapture all three Flights.');
        cycles=C.segments_thread_cycles;
        [~,ix]=max(W,[],1);
        % GetThreadTimes is quantized at roughly 15.625ms on this system;
        % wall - coarse CPU milliseconds is NOT a valid few-ms latency split.
        % Keep the legacy field only for readers, explicitly UNAVAILABLE.
        gap=nan(size(W));
        D=struct('run',j,'frames',C.count, ...
            'max_thread_wall_ms',max(W,[],1), ...
            'max_thread_cpu_ms',max(T,[],1), ...
            'max_wall_minus_cpu_ms',max(gap,[],1), ...
            'top_wall_k',reshape(ix,1,[]), ...
            'max_thread_cycles',max(cycles,[],1), ...
            'cycles_at_wall_peak',reshape(cycles(sub2ind(size(cycles),ix,1:4)),1,[]), ...
            'max_update_wall_ms',max(C.update_wall_ms), ...
            'max_yellow_wall_ms',max(C.trigger_wall_ms), ...
            'max_sensor_inner_wall_ms',max(C.sensor_inner_ms), ...
            'max_sensor_memory_wall_ms',max(W(:,1)));
        if isempty(R.runs),R.runs=D;else,R.runs(end+1)=D;end %#ok<AGROW>
    end
    R.status='PASS_THREE_RUN_CYCLE_AND_WALL_RECORDED__NO_WCET';
    R.reason=['Thread CPU milliseconds are QUANTIZED (often 15.625 ms). ' ...
        'Use raw thread cycles as a workload proxy only; frequency/core changes ' ...
        'prevent conversion to deterministic CPU time or a WCET guarantee.'];
catch ME
    R.reason=[ME.identifier ' | ' ME.message];
end
save(fullfile(root,'TRIGGER_THREAD_THREE_RUNS_RESULT.mat'),'R');
f=fopen(fullfile(root,'TRIGGER_THREAD_THREE_RUNS_RESULT.txt'),'w');
if f>=0
    fprintf(f,'status=%s\nreason=%s\n',R.status,R.reason);
    fprintf(f,'stage_labels=%s\n',strjoin(labels,','));
    for j=1:numel(R.runs)
        x=R.runs(j);
        fprintf(f,['run=%d frames=%d max_update_ms=%.6f ' ...
            'max_yellow_ms=%.6f max_sensor_inner_ms=%.6f ' ...
            'max_sensor_memory_wall_ms=%.6f\n'], ...
            x.run,x.frames,x.max_update_wall_ms,x.max_yellow_wall_ms, ...
            x.max_sensor_inner_wall_ms,x.max_sensor_memory_wall_ms);
        fprintf(f,'peak_stage_wall_ms=%s\n',mat2str(x.max_thread_wall_ms,8));
        fprintf(f,'peak_stage_cpu_ms=%s\n',mat2str(x.max_thread_cpu_ms,8));
        fprintf(f,'peak_stage_wall_minus_cpu_ms=%s\n',mat2str(x.max_wall_minus_cpu_ms,8));
        fprintf(f,'peak_stage_k=%s\n',mat2str(x.top_wall_k));
        fprintf(f,'max_thread_cycles=%s\n',mat2str(x.max_thread_cycles,14));
        fprintf(f,'cycles_at_wall_peak=%s\n',mat2str(x.cycles_at_wall_peak,14));
    end
    fclose(f);
end
end
