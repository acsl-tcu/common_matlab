function R=CHECK_TRAJECTORY_C9_FORWARD_JACOBIAN_AB()
% CHECK-only. Same C9 fixture, same obstacle search, SAME nominal torque.
% 12-coordinate real forward sensitivities vs 12 complex-step evaluations.
% No sampling, witness or local QP authorizes a flight COMMIT.
root=fileparts(mfilename('fullpath'));
name='TRAJECTORY_C9_FORWARD_JACOBIAN_AB_RESULT';
R=struct('status','FAIL_C9_FORWARD_JACOBIAN_AB', ...
 'error_identifier','','error_message','','error_stack',{{}}, ...
 'reference_guide_status','NOT_RUN', ...
 'forward_point_parity_Nm',NaN, ...
 'forward_jacobian_parity_max_rel',NaN, ...
 'qp_cut_A_parity_max_rel',NaN,'qp_cut_b_parity_max_rel',NaN, ...
 'cut_count',NaN,'selected_witness_times_s',zeros(1,0), ...
 'reference_sample_peak_excess_Nm',NaN, ...
 'jacobian_median_ms_complex',NaN, ...
 'jacobian_median_ms_forward',NaN, ...
 'jacobian_p95_ms_complex',NaN, ...
 'jacobian_p95_ms_forward',NaN, ...
 'old_search_status','NOT_RUN','new_search_status','NOT_RUN', ...
 'old_search_failure_reason','','new_search_failure_reason','', ...
 'old_search_median_ms',NaN,'new_search_median_ms',NaN, ...
 'old_search_p95_ms',NaN,'new_search_p95_ms',NaN, ...
 'old_search_max_ms',NaN,'new_search_max_ms',NaN, ...
 'old_torque_total_ms',NaN,'new_torque_total_ms',NaN, ...
 'old_jacobian_evaluations',NaN,'new_jacobian_evaluations',NaN, ...
 'old_independent_proofs',NaN,'new_independent_proofs',NaN, ...
 'old_qp_ms',NaN,'new_qp_ms',NaN, ...
 'old_point_witness_skips',NaN,'new_point_witness_skips',NaN, ...
 'old_nominal_torque_status','NOT_RUN', ...
 'new_nominal_torque_status','NOT_RUN', ...
 'scope','NOMINAL_SEARCH_JACOBIAN_AB_ONLY__ACTUAL_HLC_UNCERTIFIED', ...
 'safe_to_commit',false,'zip_path',fullfile(root,[name '_FOR_CHATGPT.zip']));
try
 addpath(fullfile(root,'controller'),fullfile(root,'model'),'-begin');
 addpath(fullfile(root,'reference','REPLANNING_SYSTEM', ...
    'TRAJECTORY_GENERATION'), ...
    fullfile(root,'reference','REPLANNING_SYSTEM', ...
    'OBSTACLE_INFORMATION'),'-begin');
 [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
 P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
 P.set("loadmass",0.14); % CHECK fixture only, not a production fallback.
 d=double(P.get(["mass","jx","jy","jz", ...
      "gravity","cableL","loadmass"]));
 d=d(:);lo=double(lo(:));hi=double(hi(:));
 assert(numel(d)==7&&all(isfinite(d))&&all(d>0)&& ...
    numel(lo)==4&&numel(hi)==4&&all(hi>lo), ...
    'C9_FORWARD_AB:Authority','Live fixture authority unavailable');
 a=struct('uav_mass_kg',d(1),'payload_mass_kg',d(7), ...
   'cable_length_m',d(6),'uav_inertia_kgm2',d(2:4), ...
   'gravity_world_mps2',[0;0;-d(5)], ...
   'thrust_limits_N',[lo(1),hi(1)], ...
   'torque_limits_Nm',[lo(2:4),hi(2:4)], ...
   'minimum_tension_N',0,'acceleration_guard_mps2',0);
 topt=struct('max_subdivision_depth',8,'max_node_count',511, ...
   'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
   'torque_guard_Nm',zeros(3,1), ...
   'enable_fast_norm_sufficient_bound',true, ...
   'use_precomputed_binomial',true, ...
   'use_factored_diagonal_gyro',true, ...
   'enable_infeasible_leaf_early_exit',true, ...
   'use_symmetric_unit_jet_kernel',true, ...
   'use_cancellation_attitude_jet',true, ...
   'use_structural_torque_intersection',false);
 J0=zeros(3,10);J1=zeros(3,10);
 J0(:,1)=[-2;0;3];J1(:,1)=[2;0;3];
 J0(1,2)=0.4;J1(1,2)=0.4;
 nominal=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,10,J0,J1, ...
     repmat([0;0;3],1,4));
 theta=0.34;Q=[cos(theta) -sin(theta) 0; ...
     sin(theta) cos(theta) 0;0 0 1];
 observed=[OBSTACLE_INFORMATION.define(21,'sphere',[0 0.1 3],0.2), ...
   OBSTACLE_INFORMATION.define(33,'ellipsoid',[0.6 -0.16 3], ...
   [0.32 0.19 0.4],'rotation',Q)];
 gopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
   'numerical_guard_m',0,'robust_tube_enabled',false, ...
   'trajectory_phase','f');
 fopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
   'force_guard_N',0);
 sopt=struct('probe_count',13,'max_outer_iterations',4, ...
   'max_projection_sweeps',100,'projection_tolerance_m',1e-8, ...
   'min_separation_m',1e-5, ...
   'lazy_initial_proof_on_violated_plane',false, ...
   'payload_hull_witness_policy','off', ...
   'embed_taut_bernstein_halfspaces',false, ...
   'accept_first_certified_minimum_qp',false, ...
   'enable_connected_group_topology',true, ...
   'enable_point_intersection_prefilter',true);
 req=struct('t0_s',8,'duration_s',10,'flight_interval_s',[8 30], ...
   'start_jets',J0,'end_jets',J1, ...
   'nominal_free',nominal.control_points_m(:,11:14), ...
   'observed',observed, ...
   'radii',struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1), ...
   'authority',a,'geometry_options',gopt,'force_options',fopt, ...
   'search_options',sopt,'torque_options',topt);
 S=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(req);
 R.reference_guide_status=S.status;
 assert(S.candidate_available&&S.final_certificate.certified&& ...
   ~S.safe_to_commit,'C9_FORWARD_AB:Fixture', ...
   'Missing geometry-certified nominal-unsafe comparison candidate');
 piece=S.candidate_piece;
 times=piece.t0_s+piece.duration_s*(0:32)/32;
 U=[2 0.3 0 0;0 3 0.2 0;0 0 4 0.4;0 0 0 5];
 point=TRAJECTORY_C9_TORQUE_POINT_EVALUATE(piece,a,topt,times);
 assert(all(point.valid)&&any(point.outside_limits), ...
   'C9_FORWARD_AB:FixturePoint','Need real torque-violating sample');
 R.reference_sample_peak_excess_Nm=point.maximum_point_violation_Nm;
 o=topt;o.use_forward_torque_jacobian=false;
 n=topt;n.use_forward_torque_jacobian=true;
 K0=TRAJECTORY_C9_TORQUE_LOCAL_CUTS(piece,a,o,times,U);
 K1=TRAJECTORY_C9_TORQUE_LOCAL_CUTS(piece,a,n,times,U);
 assert(strcmp(K0.status,'TORQUE_POINT_LOCAL_CUTS__FULL_CERTIFICATE_REQUIRED')&& ...
   strcmp(K1.status,K0.status)&&K0.cut_count==K1.cut_count&& ...
   K0.cut_count>=1&&isequal(K0.cut_axes,K1.cut_axes)&& ...
   isequal(K0.cut_sides,K1.cut_sides)&& ...
   isequal(K0.cut_times_s,K1.cut_times_s), ...
   'C9_FORWARD_AB:Cuts','Different active torque cuts');
 R.cut_count=K0.cut_count;
 R.selected_witness_times_s=K0.cut_times_s;
 R.qp_cut_A_parity_max_rel=max(abs(K0.A(:)-K1.A(:)) ...
   ./max(1,abs(K0.A(:))));
 R.qp_cut_b_parity_max_rel=max(abs(K0.b(:)-K1.b(:)) ...
   ./max(1,abs(K0.b(:))));
 R.forward_jacobian_parity_max_rel= ...
   max(abs(K0.cut_gradients_Nm_per_qp(:)- ...
   K1.cut_gradients_Nm_per_qp(:)) ...
   ./max(1,abs(K0.cut_gradients_Nm_per_qp(:))));
 uniqueTimes=unique(K0.cut_times_s);
 F=TRAJECTORY_C9_TORQUE_FORWARD_JACOBIAN( ...
   piece,a,n,uniqueTimes,U);
 P0=TRAJECTORY_C9_TORQUE_POINT_EVALUATE( ...
   piece,a,topt,uniqueTimes);
 assert(all(F.valid)&&all(P0.valid)&&~F.safe_to_commit, ...
   'C9_FORWARD_AB:Point','Invalid forward evaluator');
 R.forward_point_parity_Nm=max(abs(F.torque_Nm(:)-P0.torque_Nm(:)));
 assert(R.qp_cut_A_parity_max_rel<1e-7&& ...
   R.qp_cut_b_parity_max_rel<1e-7&& ...
   R.forward_jacobian_parity_max_rel<1e-7&& ...
   R.forward_point_parity_Nm<1e-7, ...
   'C9_FORWARD_AB:Parity','Value/Jacobian is not equal to reference');
 % Repeated LOCAL-CUT timing, with matching witness points and whitening.
 t0=zeros(1,7);t1=zeros(1,7);
 for k=1:7
   if mod(k,2)
      A0=TRAJECTORY_C9_TORQUE_LOCAL_CUTS(piece,a,o,times,U);
      A1=TRAJECTORY_C9_TORQUE_LOCAL_CUTS(piece,a,n,times,U);
   else
      A1=TRAJECTORY_C9_TORQUE_LOCAL_CUTS(piece,a,n,times,U);
      A0=TRAJECTORY_C9_TORQUE_LOCAL_CUTS(piece,a,o,times,U);
   end
   assert(A0.cut_count==A1.cut_count&& ...
      strcmp(A0.status,A1.status), ...
      'C9_FORWARD_AB:Repeat','Local cuts inconsistent');
   t0(k)=A0.elapsed_ms;t1(k)=A1.elapsed_ms;
 end
 R.jacobian_median_ms_complex=median(t0);
 R.jacobian_median_ms_forward=median(t1);
 R.jacobian_p95_ms_complex=prctile(t0,95);
 R.jacobian_p95_ms_forward=prctile(t1,95);
 % The same single-C9 simultaneous-obstacle search, 3x paired end-to-end.
 req.search_options.enable_torque_aware_joint_search=true;
 req.search_options.torque_probe_count=33;
 A=req;A.torque_options.use_forward_torque_jacobian=false;
 B=req;B.torque_options.use_forward_torque_jacobian=true;
 oldms=zeros(1,3);newms=zeros(1,3);
 for k=1:3
   if mod(k,2)
      old=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(A);
      new=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(B);
   else
      new=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(B);
      old=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(A);
   end
   assert(~old.safe_to_commit&&~new.safe_to_commit&& ...
      (~old.candidate_available||old.final_certificate.certified)&& ...
      (~new.candidate_available||new.final_certificate.certified), ...
      'C9_FORWARD_AB:NoCommit','Certification invariant broken');
   oldms(k)=old.elapsed_ms;newms(k)=new.elapsed_ms;
 end
 R.old_search_status=old.status;R.new_search_status=new.status;
 R.old_search_failure_reason=old.failure_reason;
 R.new_search_failure_reason=new.failure_reason;
 R.old_search_median_ms=median(oldms);
 R.new_search_median_ms=median(newms);
 R.old_search_p95_ms=prctile(oldms,95);
 R.new_search_p95_ms=prctile(newms,95);
 R.old_search_max_ms=max(oldms);
 R.new_search_max_ms=max(newms);
 R.old_torque_total_ms=old.point_torque_time_total_ms;
 R.new_torque_total_ms=new.point_torque_time_total_ms;
 R.old_jacobian_evaluations=old.point_torque_local_jacobian_evaluations;
 R.new_jacobian_evaluations=new.point_torque_local_jacobian_evaluations;
 R.old_independent_proofs=old.independent_proof_calls;
 R.new_independent_proofs=new.independent_proof_calls;
 R.old_qp_ms=old.joint_qp_time_total_ms;
 R.new_qp_ms=new.joint_qp_time_total_ms;
 R.old_point_witness_skips=old.point_torque_preoracle_skips;
 R.new_point_witness_skips=new.point_torque_preoracle_skips;
 if old.candidate_available
   oldcert=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL( ...
       old.candidate_piece,a,topt);
   R.old_nominal_torque_status=oldcert.status;
   assert(~oldcert.safe_to_commit, ...
     'C9_FORWARD_AB:OldCertificate','Unexpected COMMIT');
 end
 if new.candidate_available
   newcert=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL( ...
       new.candidate_piece,a,topt);
   R.new_nominal_torque_status=newcert.status;
   assert(~newcert.safe_to_commit, ...
     'C9_FORWARD_AB:NewCertificate','Unexpected COMMIT');
 end
 R.status='PASS_FORWARD_JACOBIAN_PARITY_AND_AUDIT__HLC_UNCERTIFIED';
catch ME
 R.error_identifier=ME.identifier;
 R.error_message=ME.message;
 R.error_stack=arrayfun(@(s)sprintf('%s:%d',s.name,s.line), ...
     ME.stack,'UniformOutput',false);
end
save(fullfile(root,[name '.mat']),'R');
fid=fopen(fullfile(root,[name '.txt']),'w');
if fid>=0
 fprintf(fid,'status=%s error=%s %s\n',R.status,R.error_identifier,R.error_message);
 for k=1:numel(R.error_stack)
    fprintf(fid,'stack%d=%s\n',k,R.error_stack{k});
 end
 fprintf(fid,'parity value=%g gradient=%g cut_A=%g cut_b=%g\n', ...
   R.forward_point_parity_Nm,R.forward_jacobian_parity_max_rel, ...
   R.qp_cut_A_parity_max_rel,R.qp_cut_b_parity_max_rel);
 fprintf(fid,'cut_count=%g peak_excess_Nm=%g\n', ...
   R.cut_count,R.reference_sample_peak_excess_Nm);
 fprintf(fid,'local_cuts_median_ms old=%g new=%g p95_old=%g p95_new=%g\n', ...
   R.jacobian_median_ms_complex,R.jacobian_median_ms_forward, ...
   R.jacobian_p95_ms_complex,R.jacobian_p95_ms_forward);
 fprintf(fid,'search_median_ms old=%g new=%g p95_old=%g p95_new=%g max_old=%g max_new=%g\n', ...
   R.old_search_median_ms,R.new_search_median_ms, ...
   R.old_search_p95_ms,R.new_search_p95_ms, ...
   R.old_search_max_ms,R.new_search_max_ms);
 fprintf(fid,'old_search=%s new_search=%s\n', ...
    R.old_search_status,R.new_search_status);
 fprintf(fid,'old_torque_ms=%g new_torque_ms=%g old_deriv_points=%g new_deriv_points=%g\n', ...
   R.old_torque_total_ms,R.new_torque_total_ms, ...
   R.old_jacobian_evaluations,R.new_jacobian_evaluations);
 fprintf(fid,'old_proofs=%g new_proofs=%g old_qp_ms=%g new_qp_ms=%g skips=%g/%g\n', ...
   R.old_independent_proofs,R.new_independent_proofs, ...
   R.old_qp_ms,R.new_qp_ms, ...
   R.old_point_witness_skips,R.new_point_witness_skips);
 fprintf(fid,'old_nominal_torque=%s new_nominal_torque=%s safe_to_commit=%d\n', ...
   R.old_nominal_torque_status,R.new_nominal_torque_status,R.safe_to_commit);
 fclose(fid);
end
zip(R.zip_path,{[name '.mat'],[name '.txt']},root);
fprintf('[C9 FORWARD JAC A/B] %s | %s\n',R.status,R.zip_path);
end
