function R=CHECK_TRIGGER_LIPSCHITZ_CONTACT_WINDOW()
% COMMON_ROOT disposable mathematical input oracle for the narrow
% possible-contact time window. It is NOT true-EKF physical validation.
root=fileparts(mfilename('fullpath'));
R=struct('status','FAIL_LIPSCHITZ_CONTACT_WINDOW','cases',0, ...
    'failures',0,'reason','','safe_to_commit',false);
old=rng;
restore_rng=onCleanup(@()rng(old)); %#ok<NASGU>
try
    rng(40017,'twister');
    C=struct('sample_times_s',[0 1], 'observed_ids',[5 2 33], ...
        'nominal_clearance_lower_m',[0.2 0.2;0 0.5;2 2], ...
        'full_body_endpoint_error_upper_m',[0 0], ...
        'whole_body_speed_upper_mps',1);
    X=TRIGGER_EKF_INTERVAL_RISK_DECISION(C);
    assert(isequal(X.earliest_possible_ids,[5 2]) && ...
        X.first_interval_index==1 && ...
        X.first_possible_narrow_left_s<=0 && ...
        X.first_possible_narrow_right_s>=0.8 && ...
        X.first_possible_narrow_right_s<=1 && ...
        X.narrow_window_conditional_only && ~X.safe_to_commit, ...
        'CHECK_TRIGGER_LIPSCHITZ_CONTACT_WINDOW:Multiple', ...
        'Concurrent observed-ID narrow risk window not conservative.');
    R.cases=R.cases+1;
    C.observed_ids=7;
    C.nominal_clearance_lower_m=[0 0];
    C.whole_body_speed_upper_mps=0;
    X=TRIGGER_EKF_INTERVAL_RISK_DECISION(C);
    assert(X.first_possible_narrow_left_s==0 && ...
        X.first_possible_narrow_right_s==1 && ~X.safe_to_commit, ...
        'CHECK_TRIGGER_LIPSCHITZ_CONTACT_WINDOW:Zero', ...
        'Zero velocity with zero lower clearance must remain UNKNOWN.');
    R.cases=R.cases+1;
    C.nominal_clearance_lower_m=[1 1];
    X=TRIGGER_EKF_INTERVAL_RISK_DECISION(C);
    assert(~X.conditional_replan_required && ...
        isnan(X.first_possible_narrow_left_s) && ~X.safe_to_commit, ...
        'CHECK_TRIGGER_LIPSCHITZ_CONTACT_WINDOW:Separated', ...
        'Separated case must not fabricate a collision time.');
    R.cases=R.cases+1;
    for k=1:1500
        v=0.01+15*rand;h=0.001+4*rand;
        contact=h*rand; p0=v*contact*rand; p1=v*(h-contact)*rand;
        err0=rand*0.5;err1=rand*0.5;
        n=randi([1 10]);chosen=randi(n);
        ids=100+randperm(1000,n);
        dl=2*v*h+10*ones(n,2);
        dl(chosen,:)=[p0+err0,p1+err1];
        C=struct('sample_times_s',[0 h], ...
            'observed_ids',ids,'nominal_clearance_lower_m',dl, ...
            'full_body_endpoint_error_upper_m',[err0 err1], ...
            'whole_body_speed_upper_mps',v);
        X=TRIGGER_EKF_INTERVAL_RISK_DECISION(C);
        a=X.first_possible_narrow_left_s;
        b=X.first_possible_narrow_right_s;
        if ~(X.conditional_replan_required && ...
                isequal(X.earliest_possible_ids,ids(chosen)) && ...
                isfinite(a)&&isfinite(b) && a>=0&&b<=h&&a<=contact&& ...
                contact<=b && ~X.safe_to_commit)
            error('CHECK_TRIGGER_LIPSCHITZ_CONTACT_WINDOW:Random', ...
                'A true admissible zero at %.12g is excluded by case %d.', ...
                contact,k);
        end
        R.cases=R.cases+1;
    end
    C.observed_ids=[];
    C.nominal_clearance_lower_m=zeros(0,2);
    X=TRIGGER_EKF_INTERVAL_RISK_DECISION(C);
    assert(~X.conditional_replan_required && ...
        isempty(X.earliest_possible_ids) && ...
        isnan(X.first_possible_narrow_left_s) && ~X.safe_to_commit, ...
        'CHECK_TRIGGER_LIPSCHITZ_CONTACT_WINDOW:Empty', ...
        'Unknown world must not produce clearance certification.');
    R.cases=R.cases+1;
    R.status='PASS_CONDITIONAL_LIPSCHITZ_NARROW_WINDOW__NOT_FLIGHT_PROOF';
catch ME
    R.failures=R.failures+1;
    R.reason=[ME.identifier ' | ' ME.message];
end
save(fullfile(root,'TRIGGER_LIPSCHITZ_CONTACT_WINDOW_RESULT.mat'),'R');
fp=fopen(fullfile(root,'TRIGGER_LIPSCHITZ_CONTACT_WINDOW_RESULT.txt'),'w');
if fp>=0
    fprintf(fp,'status=%s\ncases=%d\nfailures=%d\nreason=%s\n', ...
        R.status,R.cases,R.failures,R.reason);fclose(fp);
end
end
