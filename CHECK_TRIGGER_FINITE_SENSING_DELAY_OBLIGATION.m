function R=CHECK_TRIGGER_FINITE_SENSING_DELAY_OBLIGATION()
% Disposable mathematical fixture; NOT a Flight safety certificate.
R=struct('status','NOT_COMPLETED_RANGE_DELAY_FIXTURES', ...
    'pass_positive_case',false,'pass_short_range_rejection',false, ...
    'pass_occlusion_rejection',false,'pass_missing_input_rejection',false, ...
    'reason','');
try
    % ALL numbers below are SYNTHETIC test values, NEVER Flight defaults.
    C=struct('sensor_range_m',20,'cable_length_upper_m',2, ...
        'uav_radius_m',0.3,'cable_radius_m',0.02, ...
        'payload_radius_m',0.25, ...
        'true_uav_speed_upper_mps',3, ...
        'true_cable_angular_speed_upper_radps',0.5, ...
        'elapsed_since_last_complete_scan_upper_s',0.025, ...
        'compute_and_actuation_delay_upper_s',0.05, ...
        'sensor_complete_without_occlusion',true);
    a=TRIGGER_FINITE_SENSING_DELAY_OBLIGATION(C);
    assert(a.conditional_no_contact_until_reaction && ...
        ~a.safe_to_commit && ~a.full_flight_safety_proven && ...
        abs(a.body_extent_m-2.25)<1e-10, ...
        'CHECK_TRIGGER_FINITE_SENSING_DELAY_OBLIGATION:Positive');
    R.pass_positive_case=true;
    C.sensor_range_m=2;
    b=TRIGGER_FINITE_SENSING_DELAY_OBLIGATION(C);
    assert(~b.conditional_no_contact_until_reaction && ...
        ~b.safe_to_commit, ...
        'CHECK_TRIGGER_FINITE_SENSING_DELAY_OBLIGATION:ShortRange');
    R.pass_short_range_rejection=true;
    C.sensor_range_m=20;
    C.sensor_complete_without_occlusion=false;
    c=TRIGGER_FINITE_SENSING_DELAY_OBLIGATION(C);
    assert(strcmp(c.status, ...
        'UNKNOWN_OCCLUSION_OR_SENSOR_COMPLETENESS'), ...
        'CHECK_TRIGGER_FINITE_SENSING_DELAY_OBLIGATION:Occluded');
    R.pass_occlusion_rejection=true;
    C=rmfield(C,'true_uav_speed_upper_mps');
    d=TRIGGER_FINITE_SENSING_DELAY_OBLIGATION(C);
    assert(~d.conditional_no_contact_until_reaction && ...
        ~d.safe_to_commit, ...
        'CHECK_TRIGGER_FINITE_SENSING_DELAY_OBLIGATION:Missing');
    R.pass_missing_input_rejection=true;
    R.status='PASS_CONDITIONAL_FINITE_RANGE_DELAY_FIXTURES__NOT_FLIGHT_SAFETY';
catch ME
    R.reason=[ME.identifier ' | ' ME.message];
end
fid=fopen('TRIGGER_FINITE_RANGE_DELAY_RESULT.txt','w');
if fid>=0
    fprintf(fid,'status=%s\npositive=%d\nshort_rejected=%d\n', ...
        R.status,R.pass_positive_case,R.pass_short_range_rejection);
    fprintf(fid,'occlusion_rejected=%d\nmissing_rejected=%d\nreason=%s\n', ...
        R.pass_occlusion_rejection,R.pass_missing_input_rejection,R.reason);
    fclose(fid);
end
save('TRIGGER_FINITE_RANGE_DELAY_RESULT.mat','R');
end
