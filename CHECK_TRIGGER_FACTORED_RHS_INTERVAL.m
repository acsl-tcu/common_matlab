function A=CHECK_TRIGGER_FACTORED_RHS_INTERVAL()
% Exercise exact-algebra interval extension against the unchanged source RHS.
% Results are NUMERIC witnesses plus a source-pinned algebraic identity;
% this is NOT itself a verified solver, closed-loop or physical certificate.
A=struct('status','FAIL_FACTORED_INTERVAL_RHS', ...
    'cases',0,'failures',0,'point_witnesses',0, ...
    'box_witnesses',0,'source_pin_pass',false, ...
    'worst_old_pitch_width',NaN,'new_pitch_width',NaN, ...
    'interval_narrowing_ratio',NaN, ...
    'singular_chart_rejected',false,'negative_inertia_rejected',false, ...
    'reason','','safe_to_commit',false);
try
    S=TRIGGER_TAUT_SOURCE_INVARIANTS();
    assert(S.source_bound_invariance && S.algebra_exact, ...
        'CHECK_TRIGGER_FACTORED_RHS_INTERVAL:SourcePin', ...
        'The ORIGINAL 24-state physical source or factored interval mirror is not pinned: %s',S.reason);
    A.source_pin_pass=true;A.cases=A.cases+1;
    P=zeros(21,1);P(1)=1.2;P(6:8)=[0.05;0.08;0.05];
    P(9)=9.80665;P(20)=0.14;P(21)=2;
    U=[10;0;0;0];
    X=zeros(24,1);X(19:21)=[0;0;-1];X(15)=-2;
    % Deliberately correlated o1/o3 intervals. The source has jx==jz,
    % so the EXACT second-axis nonlinear inertial torque vanishes.
    % Independent interval copies of jx*o1*o3 - jz*o1*o3 do not vanish.
    LO=X;HI=X;
    LO(10)=-15;HI(10)=15;
    LO(12)=-15;HI(12)=15;
    R=TRIGGER_ORIGINAL_PLANT_INTERVAL_RHS( ...
        struct('lower',LO,'upper',HI), ...
        struct('lower',U,'upper',U), ...
        struct('lower',P,'upper',P));
    assert(R.outward_elementary_operations, ...
        'CHECK_TRIGGER_FACTORED_RHS_INTERVAL:WideAngularRHS', ...
        'The broad torque interval was rejected: %s',R.reason);
    jx=TRIGGER_OUTWARD_INTERVAL(P(6),P(6));
    jy=TRIGGER_OUTWARD_INTERVAL(P(7),P(7));
    jz=TRIGGER_OUTWARD_INTERVAL(P(8),P(8));
    o1=TRIGGER_OUTWARD_INTERVAL(LO(10),HI(10));
    o3=TRIGGER_OUTWARD_INTERVAL(LO(12),HI(12));
    u3=TRIGGER_OUTWARD_INTERVAL(0,0);
    old=(u3-(jx.*o1.*o3-jz.*o1.*o3))./jy;
    A.worst_old_pitch_width=old.hi-old.lo;
    A.new_pitch_width=R.rhs_upper(11)-R.rhs_lower(11);
    A.interval_narrowing_ratio=A.new_pitch_width/A.worst_old_pitch_width;
    assert(A.worst_old_pitch_width>1 && ...
        A.new_pitch_width>=0 && ...
        A.interval_narrowing_ratio<1e-4 && ...
        R.rhs_lower(11)<=0 && R.rhs_upper(11)>=0, ...
        'CHECK_TRIGGER_FACTORED_RHS_INTERVAL:DependencyReduction', ...
        'Unnecessary interval dependency in rigid-body axis 2 was not removed.');
    A.cases=A.cases+1;
    % Fixed-seed deterministic coverage; no RNG state changes to Flight.
    for j=1:48
        x=X;
        x(4:6)=[sin(0.7*j);cos(0.35*j);sin(0.23*j)]*0.65;
        x(7:9)=[sin(0.11*j);cos(0.17*j);sin(0.31*j)];
        x(10:12)=[6*sin(0.41*j);4*cos(0.19*j);5*sin(0.13*j)];
        x(16:18)=[sin(0.14*j);cos(0.2*j);sin(0.37*j)];
        x(22:24)=[sin(0.31*j);cos(0.27*j);sin(0.15*j)];
        p=P;
        p(6:8)=[0.03+0.001*mod(j,7);0.045+0.0007*mod(j,9); ...
                0.03+0.001*mod(j,7)];
        u=[9+mod(j,8);0.04*sin(j);0.03*cos(j);0.05*sin(j/3)];
        Q=TRIGGER_ORIGINAL_PLANT_INTERVAL_RHS( ...
            struct('lower',x,'upper',x), ...
            struct('lower',u,'upper',u), ...
            struct('lower',p,'upper',p));
        assert(Q.outward_elementary_operations && ...
            all(isfinite(Q.rhs_lower))&&all(isfinite(Q.rhs_upper)), ...
            'CHECK_TRIGGER_FACTORED_RHS_INTERVAL:PointRHS', ...
            'Sample %d rejected by the interval extension: %s',j,Q.reason);
        % The ORIGINAL generated plant reads in3(:,21), in3(:,20), ...:
        % its 21 physical parameters MUST form a 1x21 ROW vector.
        % The interval wrapper instead takes a 21x1 COLUMN bound by design.
        % Converting only this numeric oracle argument preserves both APIs.
        physicalParameterRow=p(:).';
        assert(isequal(size(physicalParameterRow),[1 21]), ...
            'CHECK_TRIGGER_FACTORED_RHS_INTERVAL:PlantParameterLayout', ...
            'Original generated plant requires its physical parameters as a 1x21 row.');
        exactSource=with_load_model_euler_for_HL(x,u,physicalParameterRow);
        assert(isnumeric(exactSource)&&isequal(size(exactSource),[24 1]) && ...
            all(isfinite(exactSource)), ...
            'CHECK_TRIGGER_FACTORED_RHS_INTERVAL:PlantSource', ...
            'Original physical source returned invalid dimensions.');
        % The ordinary generated double expression is ONLY a numerical
        % regression witness; its numerical roundoff is not ground truth.
        tol=1024*eps(max(1,abs(exactSource)));
        assert(all(Q.rhs_lower<=exactSource+tol) && ...
            all(Q.rhs_upper>=exactSource-tol), ...
            'CHECK_TRIGGER_FACTORED_RHS_INTERVAL:PointContainment', ...
            'Source witness escaped interval extension in fixture %d.',j);
        A.point_witnesses=A.point_witnesses+1;
        A.cases=A.cases+1;
        if mod(j,4)==0
            pad=zeros(24,1);pad(4:6)=0.015;
            pad(10:12)=0.2;pad(19:21)=0.01;pad(22:24)=0.04;
            Y=TRIGGER_ORIGINAL_PLANT_INTERVAL_RHS( ...
                struct('lower',x-pad,'upper',x+pad), ...
                struct('lower',u,'upper',u), ...
                struct('lower',p,'upper',p));
            assert(Y.outward_elementary_operations && ...
                all(Y.rhs_lower<=exactSource+tol) && ...
                all(Y.rhs_upper>=exactSource-tol), ...
                'CHECK_TRIGGER_FACTORED_RHS_INTERVAL:BoxContainment', ...
                'Source witness escaped interval box in fixture %d.',j);
            A.box_witnesses=A.box_witnesses+1;
            A.cases=A.cases+1;
        end
    end
    xx=X;xx(5)=1.4;up=xx;up(5)=1.8;
    bad=TRIGGER_ORIGINAL_PLANT_INTERVAL_RHS( ...
        struct('lower',xx,'upper',up), ...
        struct('lower',U,'upper',U), ...
        struct('lower',P,'upper',P));
    assert(~bad.outward_elementary_operations, ...
        'CHECK_TRIGGER_FACTORED_RHS_INTERVAL:ChartUnsafe', ...
        'Crossing cos(pitch)=0 must refuse this Euler chart.');
    A.singular_chart_rejected=true;A.cases=A.cases+1;
    pp=P;pp(7)=-1;
    bad=TRIGGER_ORIGINAL_PLANT_INTERVAL_RHS( ...
        struct('lower',X,'upper',X), ...
        struct('lower',U,'upper',U), ...
        struct('lower',pp,'upper',pp));
    assert(~bad.outward_elementary_operations, ...
        'CHECK_TRIGGER_FACTORED_RHS_INTERVAL:NegativeInertia', ...
        'Physically invalid inertia must refuse certification.');
    A.negative_inertia_rejected=true;A.cases=A.cases+1;
    A.status='PASS_FACTOR_ROTATION_INTERVAL_SOURCE_PARITY__FLIGHT_OPEN';
    A.reason=['Original source pins and rigid-body algebra match; ' ...
        'real-point witnesses and broad boxes included. Picard Flight ' ...
        'recovery, positive tension and complete physics remain unverified.'];
catch ME
    A.failures=1;
    A.reason=[ME.identifier ' | ' ME.message];
end
try
    save('TRIGGER_FACTORED_RHS_INTERVAL_RESULT.mat','A');
    fid=fopen('TRIGGER_FACTORED_RHS_INTERVAL_RESULT.txt','w');
    if fid>0
        fprintf(fid,['%s\ncases=%d failures=%d point=%d boxes=%d' ...
            ' source_pin=%d old_pitch_width=%.17g new_pitch_width=%.17g' ...
            ' ratio=%.17g chart_rejected=%d inertia_rejected=%d\n%s\n'], ...
            A.status,A.cases,A.failures,A.point_witnesses,A.box_witnesses, ...
            A.source_pin_pass,A.worst_old_pitch_width,A.new_pitch_width, ...
            A.interval_narrowing_ratio,A.singular_chart_rejected, ...
            A.negative_inertia_rejected,A.reason);
        fclose(fid);
    end
catch
end
end
