function obs = ENVIRONMENT_OBSTACLE_ELLIPSOID()
% ENVIRONMENT_OBSTACLE_ELLIPSOID 障害物の配置情報（楕円体対応）
% 
% コントローラや描画用クラスから呼び出され、
% 任意の姿勢 R_obs と軸長 Q_obs を持つ楕円体障害物を定義します。

    %% =========================================================================
    %  1. 障害物1 (縦長の楕円体として定義)
    %  =========================================================================
    obs(1).type = 'ellipsoid';
    obs(1).p_obs = [-0.3; 7.5; 1.5]; % 中心座標
    obs(1).R_obs = eye(3);           % 傾きなし
    obs(1).Q_obs = diag([0.5, 0.5, 1.5]); % X半径0.5, Y半径0.5, Z半径1.5 の縦長楕円体
    obs(1).d_margin = 0.5;           % コントローラ側で距離に上乗せできるマージン
    
    %% =========================================================================
    %  2. 障害物2 (真上の回避テスト用)
    %  =========================================================================
    obs(2).type = 'ellipsoid';
    obs(2).p_obs = [0.3; 0.3; 10.0]; % 上空10m
    obs(2).R_obs = eye(3);
    obs(2).Q_obs = diag([2.0, 1.0, 0.5]); % X,Yに広くZに薄いパンケーキ型（天井）
    obs(2).d_margin = 0.5;
end
