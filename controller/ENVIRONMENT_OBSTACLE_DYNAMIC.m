function obs = ENVIRONMENT_OBSTACLE_DYNAMIC(time)
% ENVIRONMENT_OBSTACLE_DYNAMIC 動的障害物の配置情報
% 引数 time (現在のシミュレーション時間構造体) を受け取り、
% 時間に応じて移動する障害物の現在位置と速度を返します。

    t = 0;
    if nargin > 0 && isprop(time, 't')
        t = time.t;
    end

    %% =========================================================================
    %  1. 動的障害物: 横切る障害物 (Cross-Traffic)
    %  ドローンの経路(Y軸進行)に対して、X軸方向から横切るように突進してくる
    %  =========================================================================
    obs(1).type = 'ellipsoid';
    
    % 初期位置と速度ベクトル
    p_start_1 = [5.0; 7.5; 3.0]; % X=5 からスタート
    v_obs_1   = [-1.5; 0.0; 0.0]; % X軸マイナス方向へ 1.5 m/s で移動
    
    obs(1).p_obs = p_start_1 + v_obs_1 * t; % 現在位置を計算
    obs(1).v_obs = v_obs_1;                 % 相対速度計算用に速度も渡す
    
    obs(1).R_obs = eye(3);
    obs(1).Q_obs = diag([0.6, 0.6, 0.6]);   % 球体近似
    obs(1).d_margin = 0.5;

    %% =========================================================================
    %  2. 動的障害物: 正面衝突コース (Head-on Collision)
    %  ドローンと真っ向からぶつかるように移動してくる
    %  =========================================================================
    obs(2).type = 'ellipsoid';
    
    p_start_2 = [0.0; 15.0; 3.0]; % ゴール付近からスタート
    v_obs_2   = [0.0; -1.0; 0.0]; % Y軸マイナス方向へ 1.0 m/s で移動 (ドローンに向かってくる)
    
    obs(2).p_obs = p_start_2 + v_obs_2 * t;
    obs(2).v_obs = v_obs_2;
    
    obs(2).R_obs = eye(3);
    obs(2).Q_obs = diag([0.8, 0.8, 1.5]); % 縦長の障害物
    obs(2).d_margin = 0.5;
end
