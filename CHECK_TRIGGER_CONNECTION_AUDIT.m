function R=CHECK_TRIGGER_CONNECTION_AUDIT(replanner_instance)
% Offline, read-only inspection of the CURRENT source and flight status.
% Separates proof CONNECTED from proof MISSING. No flight modification.
R=struct('status','NOT_RUN','reason','', ...
    'shadow_frame_calls',0,'shadow_authority_calls',0, ...
    'preflight_reference_status','', ...
    'preflight_mcos_status','', 'preflight_mcos_calls',0, ...
    'preflight_mcos_reason','', 'source_matched',false, ...
    'flight_predictor_warmed_in_shadow',false, ...
    'actual_EKF_error_proven',false, ...
    'actual_HLC_held_input_range_proven',false, ...
    'future_mass_variation_proven',false, ...
    'taut_hybrid_mode_proven',false, ...
    'rigorous_rounding_proven',false, ...
    'continuous_closed_loop_safe',false, ...
    'safe_to_commit',false);
try
    assert(isobject(replanner_instance)&& ...
        ismethod(replanner_instance,'get_status'), ...
        'CHECK_TRIGGER_CONNECTION_AUDIT:Input', ...
        'Pass the real completed-Flight replanner object.');
    S=replanner_instance.get_status();
    path=which('REPLANNING_SYSTEM');
    src=fileread(path);
    R.source_matched=~isempty(strfind(src,'prepare_nonflight_shadow')) && ...
        ~isempty(strfind(src,'TRIGGER_TIMEONLY_SOURCE_PREPARE'));
    if isfield(S,'phase_shadow_frame_calls')
        R.shadow_frame_calls=double(S.phase_shadow_frame_calls);
    end
    if isfield(S,'phase_shadow_authority_calls')
        R.shadow_authority_calls=double(S.phase_shadow_authority_calls);
    end
    if isfield(S,'preflight_timeonly_reference_status')
        R.preflight_reference_status=char(S.preflight_timeonly_reference_status);
    end
    if isfield(S,'isolated_mcos_current_prepare_status')
        R.preflight_mcos_status=char(S.isolated_mcos_current_prepare_status);
    end
    if isfield(S,'isolated_mcos_current_prepare_calls')
        R.preflight_mcos_calls=double(S.isolated_mcos_current_prepare_calls);
    end
    if isfield(S,'isolated_mcos_current_prepare_reason')
        R.preflight_mcos_reason=char(S.isolated_mcos_current_prepare_reason);
    end
    % Do not mark missing obligations true from sampled nominal parity,
    % synthetic fixture passes or source hashes. They need independent,
    % externally justified mathematical bounds before Flight certification.
    assert(R.source_matched, ...
        'CHECK_TRIGGER_CONNECTION_AUDIT:Version', ...
        'Main source is not the intended phase-shadow reference candidate.');
    R.status='SOURCE_AND_SHADOW_INSPECTED__FLIGHT_SAFETY_UNPROVEN';
    R.reason=['Non-Flight shadow runs current frame + authority only; ' ...
       'it does NOT execute full future core/geometry. EKF error, ' ...
       'held HLC output, future mass, taut mode and rigorous rounding ' ...
       'remain unverified.'];
catch ME
    R.status='CONNECTION_AUDIT_NOT_COMPLETED';
    R.reason=[ME.identifier ' | ' ME.message];
end
fid=fopen('TRIGGER_CONNECTION_AUDIT_RESULT.txt','w');
if fid>=0
    fprintf(fid,'status=%s\nsource_matched=%d\nshadow_frame_calls=%d\n', ...
        R.status,R.source_matched,R.shadow_frame_calls);
    fprintf(fid,'shadow_authority_calls=%d\npreflight_reference_status=%s\n', ...
        R.shadow_authority_calls,R.preflight_reference_status);
    fprintf(fid,'preflight_mcos_status=%s\npreflight_mcos_calls=%d\n', ...
        R.preflight_mcos_status,R.preflight_mcos_calls);
    fprintf(fid,'preflight_mcos_reason=%s\n',R.preflight_mcos_reason);
    fprintf(fid,'full_predictor_warmed_in_shadow=%d\n', ...
        R.flight_predictor_warmed_in_shadow);
    fprintf(fid,'actual_EKF_error_proven=%d\n',R.actual_EKF_error_proven);
    fprintf(fid,'actual_HLC_held_input_range_proven=%d\n', ...
        R.actual_HLC_held_input_range_proven);
    fprintf(fid,'future_mass_variation_proven=%d\n',R.future_mass_variation_proven);
    fprintf(fid,'taut_hybrid_mode_proven=%d\n',R.taut_hybrid_mode_proven);
    fprintf(fid,'rigorous_rounding_proven=%d\n',R.rigorous_rounding_proven);
    fprintf(fid,'safe_to_commit=%d\nreason=%s\n',R.safe_to_commit,R.reason);
    fclose(fid);
end
save('TRIGGER_CONNECTION_AUDIT_RESULT.mat','R');
end
