function R=CHECK_TRIGGER_COLLISION_ONLY()
% CHECK_TRIGGER_COLLISION_ONLY  Standalone software integration regression.
% Place at common_matlab/ root. Results also saved at common_matlab/.
% Uses SYNTHETIC predictor only; does NOT claim Flight/WCET/continuous safety.
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'reference','REPLANNING_SYSTEM');
addpath(base,fullfile(base,'FUTURE_COLLISION_TRIGGER'), ...
    fullfile(base,'SIMULATED_OBSTACLE_SENSOR'), ...
    fullfile(base,'OBSTACLE_INFORMATION'));

% Catch the exact prior missing-method error before running any scenario.
methods_core=methods('FUTURE_COLLISION_TRIGGER');
assert(any(strcmp(methods_core,'set_committed_plan_revision')), ...
    'CHECK_TRIGGER_COLLISION_ONLY:StaleClass', ...
    ['Missing set_committed_plan_revision. Extract the whole ZIP at ' ...
     'common_matlab/ and execute clear classes; rehash.']);
assert(any(strcmp(methods('TRIGGER_REFERENCE_WINDOW_CACHE'), ...
    'reset_for_committed_plan')), ...
    'CHECK_TRIGGER_COLLISION_ONLY:StaleCache', ...
    'Reference cache implementation was not replaced.');
sys=fileread(fullfile(base,'REPLANNING_SYSTEM.m'));
core=fileread(fullfile(base,'FUTURE_COLLISION_TRIGGER', ...
    'FUTURE_COLLISION_TRIGGER.m'));
assert(contains(sys,'obj.trigger_reference_cache.reset_for_committed_plan();') && ...
    contains(sys,'obj.trigger_core.set_committed_plan_revision(v);') && ...
    ~contains(sys,'TRIGGER_UNRESOLVED_EVENT_HANDOFF(') && ...
    ~contains(sys,'sim_true_set_chain') && ...
    contains(core,'TRIGGER_EARLIEST_SAMPLED_CONTACT(') && ...
    contains(core,'native_sampled_outer_excluded'), ...
    'CHECK_TRIGGER_COLLISION_ONLY:ProductionWiring', ...
    'Production system still contains stale trigger paths.');

% Real obstacle definitions, synthetic flight state and predictor ONLY.
far=OBSTACLE_INFORMATION.define(791,'sphere',[3 0 0],0.04);
near=OBSTACLE_INFORMATION.define(792,'sphere',[1 0 0],0.04);
tie=OBSTACLE_INFORMATION.define(793,'sphere',[1 0 0],0.04);
q=[0;0;0];
e=struct('p',q,'q',zeros(3,1),'v',zeros(3,1), ...
    'w',zeros(3,1),'pL',q-[0;0;2],'vL',zeros(3,1), ...
    'pT',[0;0;1],'wL',zeros(3,1));
a=struct('runtime',struct('sample_dt_s',0.2, ...
    'r_uav_m',0.01,'r_payload_m',0.01, ...
    'r_cable_m',0.005,'cable_length_m',2,'horizon_s',4), ...
    'payload_mass_kg',1,'reference_at',@(t)zeros(28,1), ...
    'predictor',@(r)line_oracle(r,1), ...
    'numeric_tolerances',[1e-7;1e-7]);
f=frame([far;near],q);
C=FUTURE_COLLISION_TRIGGER(struct('horizon_s',4));
X=C.evaluate(0,e,f,a);
assert(X.prediction_complete && X.collision_predicted && ...
    isequal(X.collision_obstacle_id,792) && ...
    isequal(X.collision_obstacle_ids,792) && ...
    abs(X.collision_ttc_s-1)<1e-12 && ...
    abs(X.collision_time_s-1)<1e-12 && ...
    X.new_event && X.numeric_request && ...
    ~X.continuous_observed_set_safe && ~X.safe_to_commit, ...
    'CHECK_TRIGGER_COLLISION_ONLY:Earliest', ...
    'The earliest contact must win, independently of input obstacle order.');
% An older repeated collision at t=1 must NOT mask a NEW one at t=3.
X2=C.evaluate(0,e,f,a);
assert(X2.collision_predicted && X2.new_event && ...
    X2.duplicate_suppressed && ...
    X2.collision_obstacle_id==791 && abs(X2.collision_ttc_s-3)<1e-12 && ...
    isequal(X2.new_event_ids,791), ...
    'CHECK_TRIGGER_COLLISION_ONLY:LaterNewObstacle', ...
    'A repeated old obstacle masked a new collision later in the horizon.');
Xd=C.evaluate(0,e,f,a);
assert(Xd.collision_predicted && ~Xd.new_event && ...
    Xd.duplicate_suppressed, ...
    'CHECK_TRIGGER_COLLISION_ONLY:Duplicate', ...
    'An unchanged plan must not retrigger already announced IDs.');

% A different COMMITTED plan must rearm; repeating its revision must not.
C.set_committed_plan_revision(uint64(1));
X3=C.evaluate(0,e,f,a);
assert(X3.new_event && X3.plan_revision==uint64(1), ...
    'CHECK_TRIGGER_COLLISION_ONLY:RevisionRearm', ...
    'A new committed trajectory should rearm an observed collision.');
C.set_committed_plan_revision(uint64(1));
X4=C.evaluate(0,e,f,a);
assert(X4.new_event && isequal(X4.new_event_ids,791), ...
    'CHECK_TRIGGER_COLLISION_ONLY:SecondObstacleAfterRevision', ...
    'No revision change must still allow a different new obstacle.');
X4b=C.evaluate(0,e,f,a);
assert(~X4b.new_event && X4b.duplicate_suppressed, ...
    'CHECK_TRIGGER_COLLISION_ONLY:SameRevision', ...
    'Repeating the same plan revision must not rearm announced IDs.');
try
    C.set_committed_plan_revision(uint64(0));
    error('CHECK_TRIGGER_COLLISION_ONLY:Monotone', ...
        'Decreasing the plan revision should be rejected.');
catch ME
    if strcmp(ME.identifier,'CHECK_TRIGGER_COLLISION_ONLY:Monotone')
        rethrow(ME)
    end
    assert(strcmp(ME.identifier,'FUTURE_COLLISION_TRIGGER:PlanRevision'), ...
        'CHECK_TRIGGER_COLLISION_ONLY:RevisionError', ...
        'Unexpected error for decreasing revision.');
end

% The latest plan may change direction: no stale future prediction may be reused.
a.predictor=@(r)line_oracle(r,-1);
C.set_committed_plan_revision(uint64(2));
X5=C.evaluate(0,e,f,a);
assert(X5.prediction_complete && ~X5.collision_predicted && ...
    strcmp(X5.collision_decision,'NO_CONTACT_IN_NUMERIC_SAMPLES') && ...
    isnan(X5.collision_obstacle_id) && isnan(X5.collision_ttc_s), ...
    'CHECK_TRIGGER_COLLISION_ONLY:ChangedReference', ...
    'Changed future trajectory must alter the collision result.');
a.predictor=@(r)line_oracle(r,1);
C.set_committed_plan_revision(uint64(3));
X6=C.evaluate(0,e,f,a);
assert(X6.collision_predicted && X6.new_event && ...
    X6.collision_obstacle_id==792 && abs(X6.collision_ttc_s-1)<1e-12, ...
    'CHECK_TRIGGER_COLLISION_ONLY:Return', ...
    'Return/replanning must still detect the same ID.');

% Two obstacles sharing the earliest sample: both IDs must be reported.
f_tie=frame([far;near;tie],q);
Ct=FUTURE_COLLISION_TRIGGER(struct('horizon_s',4));
Xt=Ct.evaluate(0,e,f_tie,a);
assert(Xt.collision_predicted && ...
    isequal(sort(Xt.collision_obstacle_ids),[792 793]) && ...
    abs(Xt.collision_ttc_s-1)<1e-12, ...
    'CHECK_TRIGGER_COLLISION_ONLY:Tie', ...
    'Equal-time collisions must preserve both observed obstacle IDs.');

% A chronological early cutoff is valid only after comparing every ID.
Cs=FUTURE_COLLISION_TRIGGER(struct('horizon_s',4));
fs=frame([near;far],q);
Xs=Cs.evaluate(0,e,fs,a);
assert(Xs.collision_obstacle_id==792 && Xs.collision_ttc_s==1 && ...
    Xs.geometry_wall_ms>=0, ...
    'CHECK_TRIGGER_COLLISION_ONLY:OrderInvariant', ...
    'Obstacle iteration order changed the earliest contact.');

% No observed shape: never consult the hidden true obstacle set.
f_empty=frame(far([]),q);
Ce=FUTURE_COLLISION_TRIGGER(struct('horizon_s',4));
Xe=Ce.evaluate(0,e,f_empty,a);
assert(~Xe.collision_predicted && isnan(Xe.collision_obstacle_id) && ...
    ~Xe.prediction_available && isempty(Xe.considered_obstacle_ids), ...
    'CHECK_TRIGGER_COLLISION_ONLY:Unobserved', ...
    'An unobserved shape leaked into collision evaluation.');

% Trigger reference cache must invalidate when a generator COMMIT happens.
K=TRIGGER_REFERENCE_WINDOW_CACHE();
K.reset_for_committed_plan();
S=K.get_status();
assert(strcmp(S.takeoff_prime_status,'COMMITTED_PLAN_CHANGED'), ...
    'CHECK_TRIGGER_COLLISION_ONLY:CacheReset', ...
    'Cached future-reference columns were not invalidated.');

R=struct('status','PASS_TRIGGER_COLLISION_ONLY_SOFTWARE__NOT_CONTINUOUS_PROOF', ...
    'cases',12,'failures',0,'first_obstacle_id',X.collision_obstacle_id, ...
    'first_contact_ttc_s',X.collision_ttc_s, ...
    'same_plan_suppressed',Xd.duplicate_suppressed, ...
    'later_new_obstacle_detected',X2.new_event, ...
    'new_plan_rearmed',X3.new_event, ...
    'changed_trajectory_no_collision',~X5.collision_predicted, ...
    'return_trajectory_retriggers',X6.new_event, ...
    'simultaneous_earliest_ids',Xt.collision_obstacle_ids, ...
    'physical_continuous_time_safety_proven',false, ...
    'real_flight_tested',false,'wcet_proven',false);
save(fullfile(root,'TRIGGER_COLLISION_ONLY_RESULT.mat'),'R');
fid=fopen(fullfile(root,'TRIGGER_COLLISION_ONLY_RESULT.txt'),'w');
assert(fid>0,'CHECK_TRIGGER_COLLISION_ONLY:Output','Cannot open result log.');
g=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\n',R.status);
fprintf(fid,'cases=%d failures=%d first_obstacle_id=%.0f ttc=%.12g\n', ...
    R.cases,R.failures,R.first_obstacle_id,R.first_contact_ttc_s);
fprintf(fid,'continuous_physical_certificate=0 real_flight=0 WCET=0\n');
end

function f=frame(obstacles,p)
ids=reshape(double([obstacles.id]),1,[]);
f=struct('time_s',0,'uav_position_ekf_m',p, ...
    'detected_obstacles',obstacles, 'detected_ids',ids, ...
    'detected_count',numel(ids));
end

function P=line_oracle(req,direction)
t=req.sample_times_s;
u=req.ekf_now.p+direction*[t;zeros(2,numel(t))];
l=u-[zeros(2,numel(t));repmat(req.cable_length_m,1,numel(t))];
P=struct('sample_times_s',t,'uav_m',u,'payload_m',l, ...
    'model_description','SYNTHETIC_LINE_ORACLE_FOR_SOFTWARE_REGRESSION');
end
