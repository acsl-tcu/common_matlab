function R=CHECK_TRIGGER_DIRECTIONAL_FINAL()
%CHECK_TRIGGER_DIRECTIONAL_FINAL Short nominal geometry/wiring regression.
% Extract ZIP at common_matlab/ (this script MUST be at that root).
% Not a real-Flight benchmark, ODE proof or worst-case runtime certificate.
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'reference','REPLANNING_SYSTEM');
assert(exist(fullfile(base,'FUTURE_COLLISION_TRIGGER', ...
    'TRIGGER_NOMINAL_SWEPT_INTERVALS.m'),'file')==2, ...
    'CHECK_TRIGGER_DIRECTIONAL_FINAL:Root', ...
    'Extract ZIP at common_matlab root, not inside REPLANNING_SYSTEM.');
addpath(base,fullfile(base,'FUTURE_COLLISION_TRIGGER'), ...
    fullfile(base,'SIMULATED_OBSTACLE_SENSOR'), ...
    fullfile(base,'OBSTACLE_INFORMATION'));
sweep_source=fileread(fullfile(base,'FUTURE_COLLISION_TRIGGER', ...
    'TRIGGER_NOMINAL_SWEPT_INTERVALS.m'));
core_source=fileread(fullfile(base,'FUTURE_COLLISION_TRIGGER', ...
    'FUTURE_COLLISION_TRIGGER.m'));
assert(contains(sweep_source,'DIRECTIONAL_CONVEX_HULL_NOMINAL_SWEEP') && ...
    ~contains(sweep_source,'box_lo=') && ...
    contains(core_source,'sample_shapes=query_shapes(ismember(') && ...
    contains(core_source,'sweep=TRIGGER_NOMINAL_SWEPT_INTERVALS('), ...
    'CHECK_TRIGGER_DIRECTIONAL_FINAL:Wiring', ...
    'New single directional sweep + conditional sampled oracle not installed.');
passed=0;
% A 2-m stationary tilted cable. Old AABB includes [sqrt(2),0,0],
% which is a metre from the REAL cable. It must NOT cause a trigger.
a=[0;0;0];b=[sqrt(2);0;-sqrt(2)];
U=[a a];L=[b b]; t=[0 0.1];
far=shape(91,'sphere',[sqrt(2);0;0],0.03,eye(3));
x=TRIGGER_NOMINAL_SWEPT_INTERVALS(U,L,t,far,.04,.04,.005,[],[]);
assert(~x.continuous_linear_interpolant_may_intersect && ...
    isempty(x.first_obstacle_ids) && ...
    x.max_midpoint_sweep_bound_m==0, ...
    'CHECK_TRIGGER_DIRECTIONAL_FINAL:OldAABB', ...
    'A distant diagonal-cable AABB corner still triggers.');
passed=passed+1;
% Real contact with a stationary cable, sphere at cable midpoint.
hit=shape(92,'sphere',0.5*(a+b),.02,eye(3));
x=TRIGGER_NOMINAL_SWEPT_INTERVALS(U,L,t,hit,.04,.04,.005,[],[]);
assert(x.continuous_linear_interpolant_may_intersect && ...
    x.first_obstacle_ids==92 && x.first_ttc_s==0, ...
    'CHECK_TRIGGER_DIRECTIONAL_FINAL:RealHit','Real cable hit was lost.');
passed=passed+1;
% Intersample contact while BOTH endpoint samples are clear.
U=[[-1;0;0] [1;0;0]];L=U-[0 0;0 0;2 2];t=[0 1];
hit=shape(93,'sphere',[0;0;-1],.04,eye(3));
x=TRIGGER_NOMINAL_SWEPT_INTERVALS(U,L,t,hit,.01,.01,.005,[],[]);
assert(x.continuous_linear_interpolant_may_intersect && ...
    x.first_ttc_s==0 && isequal(x.first_time_bracket_s,[0 1]), ...
    'CHECK_TRIGGER_DIRECTIONAL_FINAL:Intersample', ...
    'Continuous intersample cable crossing was missed.');
passed=passed+1;
% Very tall, narrow cylinder: its centre ball is huge but its radial
% width is small. A cable 2m laterally away must be cleared.
U=[2 2;0 0;4 4];L=[2 2;0 0;2 2];
cyl=shape(94,'cylinder',[0;0;0],[.05 10],eye(3));
x=TRIGGER_NOMINAL_SWEPT_INTERVALS(U,L,[0 .1],cyl,.04,.04,.005,[],[]);
assert(~x.continuous_linear_interpolant_may_intersect, ...
    'CHECK_TRIGGER_DIRECTIONAL_FINAL:Cylinder', ...
    'Tall cylinder enclosing ball produced a false collision.');
passed=passed+1;
% Arbitrarily rotated, extremely slender ellipsoid well away sideways.
phi=pi/4;Q=[cos(phi) -sin(phi) 0; sin(phi) cos(phi) 0; 0 0 1];
U=[2 2;0 0;3 3];L=[2 2;0 0;1 1];
ell=shape(95,'ellipsoid',[0;0;0],[.04 .06 4.9],Q);
x=TRIGGER_NOMINAL_SWEPT_INTERVALS(U,L,[0 .1],ell,.03,.03,.005,[],[]);
assert(~x.continuous_linear_interpolant_may_intersect, ...
    'CHECK_TRIGGER_DIRECTIONAL_FINAL:Ellipsoid', ...
    'Rotated slender ellipsoid produced a far-field false hit.');
passed=passed+1;
% Different new ID after already-announced one; both in same interval.
U=[[-1;0;0] [1;0;0]];L=U-[0 0;0 0;2 2];
s1=shape(96,'sphere',[0;0;-1],.05,eye(3));
s2=shape(97,'sphere',[0;0;0],.05,eye(3));
x=TRIGGER_NOMINAL_SWEPT_INTERVALS(U,L,[0 1],[s1 s2],.02,.02,.005,96,[]);
assert(isequal(sort(x.first_obstacle_ids),[96 97]) && ...
    isequal(x.new_obstacle_ids,97), ...
    'CHECK_TRIGGER_DIRECTIONAL_FINAL:IDs','New ID suppressed by old ID.');
passed=passed+1;
% The old nominal completion contract (early time, event, rearm) stays.
assert(exist(fullfile(root,'CHECK_TRIGGER_NOMINAL_COMPLETION.m'),'file')==2, ...
    'CHECK_TRIGGER_DIRECTIONAL_FINAL:Prerequisite', ...
    'CHECK_TRIGGER_NOMINAL_COMPLETION.m from prior passing package missing.');
prev=CHECK_TRIGGER_NOMINAL_COMPLETION();
assert(strcmp(prev.status,'PASS_NOMINAL_CONTINUOUS_INTERPOLANT_TRIGGER'), ...
    'CHECK_TRIGGER_DIRECTIONAL_FINAL:LegacyRegression','Previous PASS regressed.');
passed=passed+1;
R=struct('status','PASS_DIRECTIONAL_NOMINAL_SWEEP_AND_INTEGRATION', ...
    'cases',passed,'failed',0,'removed_AABB_collision_surrogate',true, ...
    'full_sample_oracle_for_cleared_obstacles',false, ...
    'nominal_linear_interpolant_scope',true, ...
    'true_ode_or_tracking_error_proven',false, ...
    'flight_runtime_measured',false);
save(fullfile(root,'TRIGGER_DIRECTIONAL_FINAL_RESULT.mat'),'R');
fid=fopen(fullfile(root,'TRIGGER_DIRECTIONAL_FINAL_RESULT.txt'),'w');
assert(fid>0,'CHECK_TRIGGER_DIRECTIONAL_FINAL:Log','Cannot write result file.');
clean=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\ncases=%d failures=%d\n',R.status,R.cases,R.failed);
fprintf(fid,'nominal_linear_interpolant=1 true_ODE=0 Flight=0 WCET=0\n');
clear clean  % close the file before adding it to the result ZIP
names={'TRIGGER_DIRECTIONAL_FINAL_RESULT.mat', ...
       'TRIGGER_DIRECTIONAL_FINAL_RESULT.txt', ...
       'TRIGGER_NOMINAL_COMPLETION_RESULT.mat', ...
       'TRIGGER_NOMINAL_COMPLETION_RESULT.txt'};
zip(fullfile(root,'TRIGGER_DIRECTIONAL_FINAL_FOR_CHATGPT.zip'),names,root);
for j=1:numel(names),delete(fullfile(root,names{j}));end
end

function s=shape(id,type,c,d,R)
if strcmp(type,'sphere'),b=d;
elseif strcmp(type,'ellipsoid'),b=max(d);
elseif strcmp(type,'cylinder'),b=hypot(d(1),d(2)/2);
else,error('CHECK_TRIGGER_DIRECTIONAL_FINAL:Type','Unsupported fixture type');end
s=struct('id',id,'center0',c,'is_stationary',true, ...
    'bounding_radius_m',b,'rotation',R, ...
    'dimensions',d,'type',type);
end
