function OUT = AF7R36_HEADING_TOPOLOGY_R10B_INSTALL()
% AF7R36_HEADING_TOPOLOGY_R10B_INSTALL
%
% Emergency repair + bounded/theory-directed heading topology diagnostic.
%
% R10 exhaustive tree search can explode combinatorially. R10B DISABLES the
% old per-call R10 hook and replaces it with a non-exhaustive construction:
%
%   1) Run the existing fail-fast strict temporal tangent test.
%   2) If an endpoint has zero horizontal speed, certify a one-sided
%      nonzero-speed neighborhood from acceleration and the already certified
%      global jerk upper bound:
%
%      ||v(t0+h)|| >= ||a_xy(t0)|| h - 0.5*J*h^2.
%
%      Choosing h <= ||a_xy(t0)||/J gives
%
%      ||v(t0+h)|| >= 0.5 ||a_xy(t0)|| h > 0.
%
%      The same theorem is applied backward at t1.
%
%   3) Run the existing fail-fast continuous nonzero-speed certificate only
%      on the remaining closed interior interval.
%
% Results:
%   PASS_STRICT                 : temporal tangent nonzero on full interval
%   ENDPOINT_ONLY_PROVEN        : only zero-speed endpoints remain; adjacent
%                                 open neighborhoods + interior are certified
%   INTERIOR_OR_CORE_FAILURE    : trimmed interior still fails
%   ENDPOINT_DEPARTURE_OPEN     : endpoint zero exists but local departure
%                                 cannot be certified from a_xy and J
%
% This is diagnostic only. No production selection or hard safety/C7
% semantics are changed. ENDPOINT_ONLY_PROVEN is NOT by itself a production
% yaw-C6 acceptance: a C6 stop/hold time law must still be constructed.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 HEADING TOPOLOGY R10B INSTALL\n');
fprintf(' old exhaustive R10 hook disabled           = 1\n');
fprintf(' production selection modified              = 0\n');
fprintf(' hard safety/C7 semantics modified           = 0\n');
fprintf(' endpoint theorem uses certified jerk bound  = 1\n');
fprintf(' exhaustive branch tree                      = 0\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir)&&isfolder(refDir), ...
    '[HEADTOPO-R10B] Cannot resolve current reference directory.');

hpp=fullfile(refDir,'af7r36_core.hpp');
cpp=fullfile(refDir,'af7r36_single_core_mex.cpp');
assert(isfile(hpp),'[HEADTOPO-R10B] Missing %s',hpp);
assert(isfile(cpp),'[HEADTOPO-R10B] Missing %s',cpp);

hpp0=normlf(fileread(hpp));
cpp0=normlf(fileread(cpp));
hppNew=hpp0;cppNew=cpp0;

assert(contains(hpp0,'AF7_HEADING_TOPOLOGY_R10'), ...
    '[HEADTOPO-R10B] R10 core not installed.');
assert(contains(cpp0,'headtopo10_push(Q,R,t0,tm,searchEnd);'), ...
    '[HEADTOPO-R10B] Old R10 hook not found.');
assert(contains(hpp0,'static inline bool c7r7_heading_regular'), ...
    '[HEADTOPO-R10B] Existing fail-fast heading certificate missing.');
assert(~contains(hpp0,'AF7_HEADING_TOPOLOGY_R10B'), ...
    '[HEADTOPO-R10B] R10B already installed.');

try
    %% --------------------------------------------------------------------
    % 1) New theory-directed helper before plan().
    % ---------------------------------------------------------------------
    anchor='static inline PlanResult plan(const ActiveReference&ref,const Live&L,const SpeedCert&base,';
    helper=[ ...
        '// AF7_HEADING_TOPOLOGY_R10B' sprintf('\n') ...
        'struct HeadingTopoR10B {' sprintf('\n') ...
        '    int cls=0; // 1 strict, 2 endpoint-only proven, 3 interior/core fail, 4 endpoint departure open' sprintf('\n') ...
        '    bool strict=false,core=false,left_proven=false,right_proven=false;' sprintf('\n') ...
        '    double v0=NAN,v1=NAN,a0=NAN,a1=NAN,J=NAN,dl=0,dr=0,core0=NAN,core1=NAN;' sprintf('\n') ...
        '};' sprintf('\n') ...
        '' sprintf('\n') ...
        'static inline HeadingTopoR10B heading_topology_r10b(' sprintf('\n') ...
        '        const ActiveReference&ref,const Candidate&C,const SpeedCert&s,double ta,double tb){' sprintf('\n') ...
        '    HeadingTopoR10B R;' sprintf('\n') ...
        '    if(!(s.certified&&fin(s.J)&&s.J>=0&&fin(ta)&&fin(tb)&&tb>ta)){R.cls=4;return R;}' sprintf('\n') ...
        '    R.J=s.J;' sprintf('\n') ...
        '    if(c7r7_heading_regular(ref,C,s,ta,tb)){R.strict=true;R.core=true;R.cls=1;return R;}' sprintf('\n') ...
        '' sprintf('\n') ...
        '    auto A=candidate_eval(ref,C,ta),B=candidate_eval(ref,C,tb);' sprintf('\n') ...
        '    R.v0=std::hypot(A[1].x,A[1].y);R.v1=std::hypot(B[1].x,B[1].y);' sprintf('\n') ...
        '    R.a0=std::hypot(A[2].x,A[2].y);R.a1=std::hypot(B[2].x,B[2].y);' sprintf('\n') ...
        '    double scale=std::max({1.0,std::fabs(s.VL),std::fabs(s.VQ)});' sprintf('\n') ...
        '    double zguard=512*epsd()*scale;' sprintf('\n') ...
        '    bool z0=fin(R.v0)&&R.v0<=zguard,z1=fin(R.v1)&&R.v1<=zguard;' sprintf('\n') ...
        '    R.left_proven=!z0;R.right_proven=!z1;' sprintf('\n') ...
        '' sprintf('\n') ...
        '    const double T=tb-ta;' sprintf('\n') ...
        '    if(z0){' sprintf('\n') ...
        '        if(fin(R.a0)&&R.a0>zguard){' sprintf('\n') ...
        '            R.dl=(s.J>0)?std::min(T,R.a0/s.J):T;' sprintf('\n') ...
        '            R.left_proven=R.dl>0;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '    if(z1){' sprintf('\n') ...
        '        if(fin(R.a1)&&R.a1>zguard){' sprintf('\n') ...
        '            R.dr=(s.J>0)?std::min(T,R.a1/s.J):T;' sprintf('\n') ...
        '            R.right_proven=R.dr>0;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '' sprintf('\n') ...
        '    if(!R.left_proven||!R.right_proven){R.cls=4;return R;}' sprintf('\n') ...
        '' sprintf('\n') ...
        '    // Use half of each theorem-valid neighborhood for the closed core' sprintf('\n') ...
        '    // boundary. This leaves a strict positive analytical margin:' sprintf('\n') ...
        '    // ||v|| >= (3/8)*||a_xy||*delta when J>0.' sprintf('\n') ...
        '    double trimL=z0?0.5*R.dl:0.0;' sprintf('\n') ...
        '    double trimR=z1?0.5*R.dr:0.0;' sprintf('\n') ...
        '    R.core0=ta+trimL;R.core1=tb-trimR;' sprintf('\n') ...
        '    if(!(R.core1>R.core0)){' sprintf('\n') ...
        '        // Endpoint theorem neighborhoods overlap and cover the whole interval.' sprintf('\n') ...
        '        R.core=true;R.cls=(z0||z1)?2:1;return R;' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '    R.core=c7r7_heading_regular(ref,C,s,R.core0,R.core1);' sprintf('\n') ...
        '    if(!R.core){R.cls=3;return R;}' sprintf('\n') ...
        '    R.cls=(z0||z1)?2:1;return R;' sprintf('\n') ...
        '}' sprintf('\n') ...
        '' sprintf('\n') ...
        anchor];
    hppNew=replace_once(hppNew,anchor,helper,'R10B core helper');

    %% --------------------------------------------------------------------
    % 2) Add compact ring.
    % ---------------------------------------------------------------------
    anchor='static bool G_compiled=false;';
    ring=[anchor sprintf('\n') sprintf('\n') ...
        'struct HeadTopoMexR10B {' sprintf('\n') ...
        '    double seq=0,t0=NAN,tm=NAN,t1=NAN,ok=0,family=0,cls=0,strict=0,core=0,lp=0,rp=0;' sprintf('\n') ...
        '    double v0=NAN,v1=NAN,a0=NAN,a1=NAN,J=NAN,dl=NAN,dr=NAN,c0=NAN,c1=NAN;' sprintf('\n') ...
        '};' sprintf('\n') ...
        'static std::vector<HeadTopoMexR10B> G_headtopo10b;' sprintf('\n') ...
        'static double G_headtopo10b_seq=0;' sprintf('\n') ...
        'static void headtopo10b_push(const PlanResult&P,const ActiveReference&ref,double t0,double tm,double t1){' sprintf('\n') ...
        '    HeadTopoMexR10B d;d.seq=++G_headtopo10b_seq;d.t0=t0;d.tm=tm;d.t1=t1;d.ok=P.success?1:0;' sprintf('\n') ...
        '    if(P.success){auto H=heading_topology_r10b(ref,P.cand,P.speed,t0,t1);d.family=P.cand.family;d.cls=H.cls;' sprintf('\n') ...
        '        d.strict=H.strict?1:0;d.core=H.core?1:0;d.lp=H.left_proven?1:0;d.rp=H.right_proven?1:0;' sprintf('\n') ...
        '        d.v0=H.v0;d.v1=H.v1;d.a0=H.a0;d.a1=H.a1;d.J=H.J;d.dl=H.dl;d.dr=H.dr;d.c0=H.core0;d.c1=H.core1;}' sprintf('\n') ...
        '    if(G_headtopo10b.size()>=512)G_headtopo10b.erase(G_headtopo10b.begin());G_headtopo10b.push_back(d);' sprintf('\n') ...
        '}' sprintf('\n') ...
        'static mxArray* headtopo10b_matrix(){' sprintf('\n') ...
        '    const mwSize N=(mwSize)G_headtopo10b.size(),C=20;mxArray*M=mxCreateDoubleMatrix(N,C,mxREAL);double*p=mxGetPr(M);' sprintf('\n') ...
        '    for(mwSize i=0;i<N;++i){const auto&d=G_headtopo10b[i];double v[C]={' sprintf('\n') ...
        '        d.seq,d.t0,d.tm,d.t1,d.ok,d.family,d.cls,d.strict,d.core,d.lp,d.rp,d.v0,d.v1,d.a0,d.a1,d.J,d.dl,d.dr,d.c0,d.c1};' sprintf('\n') ...
        '        for(mwSize j=0;j<C;++j)p[i+N*j]=v[j];}return M;' sprintf('\n') ...
        '}'];
    cppNew=replace_once(cppNew,anchor,ring,'R10B ring');

    %% --------------------------------------------------------------------
    % 3) CRITICAL recovery: replace old exhaustive hook.
    % ---------------------------------------------------------------------
    cppNew=replace_once(cppNew, ...
        '            headtopo10_push(Q,R,t0,tm,searchEnd);', ...
        '            headtopo10b_push(Q,R,t0,tm,searchEnd);', ...
        'disable exhaustive R10 hook');

    %% --------------------------------------------------------------------
    % 4) op16 read / op17 clear.
    % ---------------------------------------------------------------------
    anchor='        if(op==3){';
    ops=[ ...
        '        if(op==16){' sprintf('\n') ...
        '            if(nrhs!=1||nlhs!=1)mexErrMsgIdAndTxt("AF7HEADTOPO10B:Arity","op16 -> matrix.");' sprintf('\n') ...
        '            plhs[0]=headtopo10b_matrix();return;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '        if(op==17){' sprintf('\n') ...
        '            if(nrhs!=1||nlhs>1)mexErrMsgIdAndTxt("AF7HEADTOPO10B:Arity","op17 clear.");' sprintf('\n') ...
        '            G_headtopo10b.clear();G_headtopo10b_seq=0;if(nlhs>0)plhs[0]=logicalScalar(true);return;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        anchor];
    cppNew=replace_once(cppNew,anchor,ops,'R10B ops');

    %% --------------------------------------------------------------------
    % 5) Audits.
    % ---------------------------------------------------------------------
    assert(count_exact(cppNew,'headtopo10_push(Q,R,t0,tm,searchEnd);')==0, ...
        '[HEADTOPO-R10B] Exhaustive R10 runtime hook still active.');
    assert(count_exact(cppNew,'headtopo10b_push(Q,R,t0,tm,searchEnd);')==1, ...
        '[HEADTOPO-R10B] R10B runtime hook count invalid.');
    assert(count_exact(hppNew,'AF7_HEADING_TOPOLOGY_R10B')==1, ...
        '[HEADTOPO-R10B] R10B core marker count invalid.');
    assert(contains(cppNew, ...
        'static const char* PLANNER_REV="AF7_REPLANNER_MIN_DEVIATION_V4_FIXED_T1";'), ...
        '[HEADTOPO-R10B] Planner identity changed unexpectedly.');

    %% --------------------------------------------------------------------
    % 6) Stage compile and atomic install.
    % ---------------------------------------------------------------------
    stageDir=tempname;
    [ok,msg]=mkdir(stageDir);
    assert(ok,'[HEADTOPO-R10B] Cannot create staging directory: %s',msg);
    stageCleanup=onCleanup(@()cleanup_stage(stageDir)); %#ok<NASGU>
    stagedHpp=fullfile(stageDir,'af7r36_core.hpp');
    stagedCpp=fullfile(stageDir,'af7r36_single_core_mex.cpp');
    write_text(stagedHpp,hppNew);write_text(stagedCpp,cppNew);

    fprintf('[HEADTOPO-R10B] Compiling staged repair MEX...\n');
    oldDir=pwd;
    cwdCleanup=onCleanup(@()cd(oldDir)); %#ok<NASGU>
    cd(stageDir);clear mex;
    mex('-R2018a','-O', ...
        'COMPFLAGS="$COMPFLAGS /std:c++17"', ...
        ['-I' stageDir], ...
        '-output','af7r36_single_core_mex', ...
        '-outdir',stageDir, ...
        stagedCpp);
    stagedMex=fullfile(stageDir,['af7r36_single_core_mex.' mexext]);
    assert(isfile(stagedMex),'[HEADTOPO-R10B] Staged MEX missing.');

    dstMex=fullfile(refDir,['af7r36_single_core_mex.' mexext]);
    oldMexTmp=fullfile(stageDir,['af7r36_single_core_mex_OLD.' mexext]);
    hadOldMex=isfile(dstMex);
    if hadOldMex
        [ok,msg]=copyfile(dstMex,oldMexTmp,'f');
        assert(ok,'[HEADTOPO-R10B] Cannot stage rollback MEX: %s',msg);
    end

    cd(oldDir);clear mex;
    wroteH=false;wroteC=false;installedMex=false;
    try
        write_text(hpp,hppNew);wroteH=true;
        write_text(cpp,cppNew);wroteC=true;
        [ok,msg]=copyfile(stagedMex,dstMex,'f');
        assert(ok,'[HEADTOPO-R10B] Cannot install staged MEX: %s',msg);
        installedMex=true;
        clear mex;rehash;
        assert(exist('af7r36_single_core_mex','file')==3, ...
            '[HEADTOPO-R10B] Installed MEX not visible.');
        try,af7r36_single_core_mex(7);catch,end
        try,af7r36_single_core_mex(11);catch,end
        try,af7r36_single_core_mex(13);catch,end
        try,af7r36_single_core_mex(15);catch,end
        af7r36_single_core_mex(17);
    catch ME2
        if wroteH,try,write_text(hpp,hpp0);catch,end,end
        if wroteC,try,write_text(cpp,cpp0);catch,end,end
        if installedMex&&hadOldMex,try,copyfile(oldMexTmp,dstMex,'f');catch,end,end
        clear mex;rehash;rethrow(ME2);
    end

    fprintf('[HEADTOPO-R10B] PASS.\n');
    fprintf('  exhaustive R10 runtime hook active         = 0\n');
    fprintf('  endpoint theorem diagnostic active          = 1\n');
    fprintf('  production selection unchanged             = 1\n');
    fprintf('  safety/C7 semantics unchanged              = 1\n');
    fprintf('  README created                              = 0\n');
    fprintf('  persistent backup files created             = 0\n');

    OUT=struct('pass',true, ...
        'revision','AF7_HEADING_TOPOLOGY_R10B', ...
        'exhaustive_R10_hook_active',false, ...
        'production_selection_modified',false, ...
        'hard_safety_modified',false, ...
        'C7_modified',false);
catch ME
    clear mex;rehash;
    fprintf(2,'[HEADTOPO-R10B] FAILED. No successful production install completed.\n');
    rethrow(ME);
end
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1, ...
    '[HEADTOPO-R10B] Anchor "%s" count=%d; expected 1.',label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end
function n=count_exact(txt,pat),n=numel(strfind(txt,pat));end
function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));s=strrep(s,sprintf('\r'),sprintf('\n'));
end
function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');assert(f>=0,'[HEADTOPO-R10B] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end
function cleanup_stage(d)
if isfolder(d),try,rmdir(d,'s');catch,end,end
end
