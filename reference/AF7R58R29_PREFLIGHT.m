function Q = AF7R58R29_PREFLIGHT()
% Source-bound check of a research-only R29 two-endpoint ZYX certificate.
% Does not enable commit, modify limits, or reconfigure the model.
root=fileparts(mfilename('fullpath'));
p=fullfile(root,'REPLANNING_SYSTEM.m');
assert(isfile(p),'[R29] REPLANNING_SYSTEM.m is missing.');
resolved=which('REPLANNING_SYSTEM');
assert(strcmpi(resolved,p),'[R29] MATLAB resolves a different REPLANNING_SYSTEM.m');
s=fileread(p);
required={ ...
    'function F = observer_r29_tighten_chart_two_endpoints', ...
    'F=obj.observer_r29_tighten_chart_two_endpoints(', ...
    'if F.closed', ...
    'F.r29_theta_two_end=theta2;', ...
    'assert(okPhi,', ...
    'assert(okPsi,', ...
    'ENABLE_LIGHT_RUNTIME_AUDIT = 1;', ...
    'r29_W_ub'};
for i=1:numel(required)
    assert(contains(s,required{i}), ...
        '[R29] source check missing: %s',required{i});
end
assert(contains(s,'R26_SIMULATION_ONLY_EXPERIMENT = false;'), ...
    '[R29] unexpected simulation commit default.');
% Reproduce the supplied R28 endpoint-witness arithmetic as a regression.
Iw=1.3549194795981234;
a0=abs(-0.01104655166042024)+7.656997627152384e-18;
a1=abs(-0.0021831171404281553)+2.2194728589282417e-18;
Theta=0.5*(Iw+a0+a1);
pad=64*eps(max([1,Theta,a0,a1,Iw]));
Theta2=Theta+pad;
D=Iw/cos(Theta2);
assert(Theta2<pi/2 && D<6.281482063079217, ...
    '[R29] supplied R28 witness does not close.');
Q=struct('source',p,'certified_two_endpoint_pitch',Theta2, ...
    'certified_roll_bound_before_rounding',D, ...
    'R28_alternative_lift_min',6.281482063079217, ...
    'observer_original_chart_required',true, ...
    'original_hard_gates_retained',true, ...
    'diagnostic_runtime_audit_on',true, ...
    'simulation_only_commit_setup_unchanged',true, ...
    'mex_rebuild_required',false, ...
    'matlab_real_run_verified',false);
fprintf('[R29] SOURCE PREFLIGHT PASS | 2-endpoint theorem, old chart guard retained\n');
fprintf('[R29] previous witness: theta=%.12g, rollUB=%.12g rad\n',Theta2,D);
end
