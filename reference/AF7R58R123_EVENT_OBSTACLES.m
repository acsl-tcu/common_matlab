function E=AF7R58R123_EVENT_OBSTACLES(C)
% SAME-EVENT sensor memory -> static oriented ellipsoids. No future/UNKNOWN items.
% Whole-body radii incorporate only existing event-time configured inflation.
assert(isstruct(C)&&isscalar(C)&&all(isfield(C, ...
    {'r76_packet','r76_known_mask','r76_radii_m','r76_d_margin_m', ...
     'reference_version','time_s','horizon_s','prediction_dt'})), ...
    'R123:FrozenR71EventRequired','Provide an actual frozen R71 event.');
P=C.r76_packet;
need={'C','R','Araw','ids','delta_uav_m','delta_cable_m', ...
      'delta_payload_m','reference_version'};
assert(isstruct(P)&&all(isfield(P,need)), ...
    'R123:FrozenObstaclePacketRequired','Missing frozen obstacle fields.');
ids=double(P.ids(:));M=numel(ids);mask=logical(C.r76_known_mask(:));
assert(numel(mask)==M && isequal(size(P.C),[3 M]) && ...
    isequal(size(P.R),[9 M]) && isequal(size(P.Araw),[3 M]) && ...
    isequal(double(P.reference_version),double(C.reference_version)) && ...
    numel(unique(ids))==M && all(ids>=1 & ids==fix(ids)) && ...
    all(isfinite([P.C(:);P.R(:);P.Araw(:);ids])) && ...
    all(P.Araw(:)>0), ...
    'R123:StaleOrMalformedFrozenObstacles', ...
    'Use the same-event sensor-known obstacle packet only.');
ix=find(mask);
obs=repmat(struct('id',NaN,'center',zeros(3,1), ...
    'R',eye(3),'axes',ones(3,1)),1,numel(ix));
for j=1:numel(ix)
    k=ix(j);R=reshape(double(P.R(:,k)),3,3);
    assert(norm(R'*R-eye(3),'fro')<1e-9 && abs(det(R)-1)<1e-9, ...
        'R123:InvalidSO3','Frozen obstacle orientation is invalid.');
    obs(j).id=ids(k);obs(j).center=double(P.C(:,k));
    obs(j).R=R;obs(j).axes=double(P.Araw(:,k));
end
r=double(C.r76_radii_m(:));d=double(C.r76_d_margin_m);
extra=double([P.delta_uav_m;P.delta_cable_m;P.delta_payload_m]);
assert(numel(r)==3&&all(isfinite([r;d;extra])) && ...
    all([r;d;extra]>=0), ...
    'R123:InvalidEventInflation','Live frozen radii are invalid.');
E=struct('obstacles',obs,'known_ids',ids(ix).', ...
    'radii_m',r+d+extra, ...
    'event_time_s',double(C.time_s), ...
    'reference_version',double(C.reference_version), ...
    'horizon_s',double(C.horizon_s), ...
    'dt_s',double(C.prediction_dt), ...
    'unknown_count',sum(~mask), ...
    'uses_unknown_obstacles',false, ...
    'external_inflation_order','UAV_CABLE_PAYLOAD');
end
