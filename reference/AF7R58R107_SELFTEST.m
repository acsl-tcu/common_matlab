function T=AF7R58R107_SELFTEST()
% Pure source events, no live Flight needed, no production mutation.
% Validate the real legacy packet even if its cached producer-status was
% rejected by the historic q/pT confusion or some later scalar check.
t=19.75;ver=3;L=2;
x=zeros(24,1);x(1:3)=[0;0;2];x(13:15)=[0;0;0];
x(4:6)=[0;0;0.4];x(19:21)=[0;0;-1];
P=struct('C',[3;0;0],'R',reshape(eye(3),9,1), ...
   'Araw',[1;1;1],'ids',1, 'delta_payload_m',0, ...
   'delta_uav_m',0,'delta_cable_m',0);
E=struct('available',false,'status','EKF_CAPTURE_FAILED__OLD_FLAG', ...
   'time_s',t,'reference_version',ver,'known_mask',true, ...
   'state_x24',x);
Z=struct('time_s',t,'reference_version',ver, ...
   'known_mask',true,'ekf_event',E,'cable_length_m',L, ...
   'obstacle_packet',P,'horizon_s',4,'prediction_dt_s',.025, ...
   'rL_m',.2,'rQ_m',.15,'rC_m',.1,'d_margin_m',.05, ...
   'estimated_mass_kg',.02);
[F,D]=AF7R58R106_SOURCE_EVENT(struct('r88_snapshots',Z),t,ver);
assert(D.authenticated && ~isempty(F)&&D.raw_state_present, ...
    'R107:IndependentRawEKFValidation');
Z.ekf_event.state_x24(19:21)=[1;0;0];
[F2,D2]=AF7R58R106_SOURCE_EVENT(struct('r88_snapshots',Z),t,ver);
assert(isempty(F2)&&~D2.authenticated&& ...
    strcmp(D2.status,'R106_EKF_CABLE_RESIDUAL_NEEDS_OBSERVER_TUBE'), ...
    'R107:PhysicalCableCannotBeMadeUp');
Z.ekf_event.state_x24=nan(24,1);
[F3,D3]=AF7R58R106_SOURCE_EVENT(struct('r88_snapshots',Z),t,ver);
assert(isempty(F3)&&~D3.authenticated,'R107:NoRawNoAuthority');
T=struct('status','PASS_R107_RAW_EKF_AND_UNPROVEN_TUBE_SEPARATED', ...
    'raw_recovered_with_independent_validation',true, ...
    'bad_geometry_rejected',true,'missing_raw_rejected',true, ...
    'production_trigger_switched',false, ...
    'production_generator_switched',false, ...
    'physical_closed_loop_certified',false);
end
