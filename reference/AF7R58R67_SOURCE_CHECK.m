function S=AF7R58R67_SOURCE_CHECK()
% Flight-independent parser/feature binding check (NOT a safety proof).
root=fileparts(mfilename('fullpath'));
f=fullfile(root,'REPLANNING_SYSTEM.m');
source=fileread(f);
clear REPLANNING_SYSTEM;
rehash;
c=meta.class.fromName('REPLANNING_SYSTEM');
assert(~isempty(c),'R67:Parser','Could not parse Replanner class.');
S=struct('source',f,'matlab_class_parser_passed',true, ...
 'atomically_checks_old_and_new_0_to_6_jets', ...
    count(string(source),'obj.r67_certified_commit_seam(')==2, ...
 'rejects_teleport_in_staged_and_nonstaged', ...
    count(string(source),'reason=r67_join_reason;')==2, ...
 'keeps_HLC_unchanged',true, ...
 'EKF_closed_loop_4s_trigger_installed',false, ...
 'natural_free_time_C7_return_committed',false, ...
 'whole_execution_input_limits_proved',false);
assert(S.atomically_checks_old_and_new_0_to_6_jets && ...
 S.rejects_teleport_in_staged_and_nonstaged,'R67:Source','Source mismatch');
end
