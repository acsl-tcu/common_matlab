function R14 = AF7R58R15_AUTO_RESULT()
% AF7R58R15: retrieve the latest numeric-only R14 snapshot without an agent
% variable. Works after clearvars / scripts that do not return a replanner.
% Diagnostic only. No effect on the reference trajectory or certificates.
key='AF7R58R15_LAST_STATUS';
if ~isappdata(0,key)
    error('AF7R58R15:NoSnapshot', [ ...
        'No R15 snapshot exists in this MATLAB process. ' ...
        'The R15 class must be loaded before the simulation, ' ...
        'both R58 and R14 diagnostic flags must be 1, ' ...
        'and a real native Stage1 must have run.']);
end
S=getappdata(0,key);
assert(isstruct(S)&&isscalar(S)&& ...
    isfield(S,'r15_source')&& ...
    strcmp(S.r15_source,'NATIVE_R14_POST_STAGE1_NUMERIC_ONLY'), ...
    'Invalid R15 native diagnostic snapshot.');
assert(isfield(S,'r58_shadow_ran')&&S.r58_shadow_ran==1, ...
    'Native R58 shadow did not run in the captured Stage1.');
assert(isfield(S,'r58r14_lowjet_seed_only')&& ...
    S.r58r14_lowjet_seed_only==1, ...
    'R14 low-jet mode was not active for the captured Stage1.');
R14=AF7R58R14_RESULT(S);
fprintf(' R15 workspace-independent capture: trigger = %.9g s\n', ...
    S.r15_trigger_time_s);
fprintf(' R15 snapshot is kept in MATLAB root appdata (not base workspace).\n');
end
