function T=AF7R58R84_SELFTEST()
% Source-independent tests of the reference FRAME shift and whole-interval
% sampled negative witness. No MEX, no Flight, no commits.
L=2;dt=0.025;H=4;N=round(H/dt)+1;
P=struct('C',[0;0;0],'R',reshape(eye(3),9,1), ...
    'Araw',[0.2;0.2;0.2],'ids',3,'delta_payload_m',0, ...
    'delta_uav_m',0,'delta_cable_m',0,'reference_version',1);
S=struct('time_s',0,'reference_version',1,'cable_length_m',L, ...
   'horizon_s',H,'prediction_dt',dt,'r76_known_mask',true, ...
   'r76_packet',P,'r76_radii_m',[0.05;0.05;0.05], ...
   'r76_d_margin_m',0,'r76_reference_pL',repmat([0;0;2.5],1,N), ...
   'r76_reference_q',repmat([0;0;-1],1,N), ...
   'r76_original_trigger',true,'r76_original_obstacle_id',3);
A=AF7R58R84_PACKET_FRAME_COMPARE(S,@r84_fake_hit);
assert(~A.raw_hit && A.hlc_hit && A.hlc_obstacle_id==3 && ...
    A.flight_to_HLC_z_shift_m==-2 && ~A.sampled_nohit_is_safety_proof, ...
    'R84:RawVsHLCFrameRegressionFailed');
B=AF7R58R84_FULL_INTERVAL_WITNESS( ...
    S,@r84_mock_flat,0,6,9.81,@r84_fake_hit);
assert(B.found_conservative_negative_witness&& ...
    B.first_hit_time_s>=5 && B.first_hit_time_s<5.1 && ...
    B.first_hit_obstacle_id==3 && ~B.continuous_time_proved, ...
    'R84:FullSupportNotCoveredBeyondH4');
% Test ID/version mismatch explicitly rejected.
S.r76_packet.reference_version=2;bad=false;
try,AF7R58R84_PACKET_FRAME_COMPARE(S,@r84_fake_hit);catch,bad=true;end
assert(bad,'R84:StalePacketNotRejected');
T=struct('status','PASS_R84_FRAME_SHIFT_AND_BEYOND_H4_SAMPLED_WITNESS', ...
    'raw_hit',A.raw_hit,'hlc_hit',A.hlc_hit, ...
    'witness_time_s',B.first_hit_time_s, ...
    'witness_beyond_four_seconds',B.first_hit_time_s>4, ...
    'stale_packet_rejected',bad, ...
    'production_modified',false,'continuous_safety_proved',false);
end
function X=r84_mock_flat(t)
X=zeros(28,1);
if t<5,X(3)=5;else,X(3)=2.5;end
end
function [hit,j,obs,comp]=r84_fake_hit(~,~,~,PL,~,~,~,~,~,ids,mask)
ix=find(PL(3,:)<1,1,'first');
hit=~isempty(ix);j=NaN;obs=NaN;comp=NaN;
if hit
    j=ix;ids=double(ids(:));ixKnown=find(logical(mask(:)),1,'first');
    obs=ids(ixKnown);comp=1;
end
end
