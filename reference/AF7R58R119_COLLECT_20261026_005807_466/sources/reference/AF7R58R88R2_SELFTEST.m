function T=AF7R58R88R2_SELFTEST()
% Source-bound structural checks only. Does not claim MATLAB live or Flight safety.
root=fileparts(mfilename('fullpath'));
patch=fileread(fullfile(root,'REPLANNING_SYSTEM_R88_PATCHED_SOURCE.txt'));
S=AF7R58R88R2_SOURCE_CHECK();
assert(S.patch_sha256_matches,'R88R2:PackagedPatchChecksum');
a='function r88_capture_one_version(obj,t,knownMask)';
b='function R=r88_replay_saved_version_reference_only(obj,t,opts)';
c='function R = r71_report_live_flight_frame(obj,tglobal)';
posA=strfind(patch,a);posB=strfind(patch,b);posC=strfind(patch,c);
assert(numel(posA)==1 && numel(posB)==1 && numel(posC)==1 && ...
    posA<posB && posB<posC,'R88R2:MissingOrAmbiguousBoundaries');
capture=patch(posA:posB-1);
replay=patch(posB:posC-1);
assert(contains(capture,'mL=double(obj.loadmass);') && ...
    contains(capture,"'estimated_mass_kg',mL"), ...
    'R88R2:FlightSnapshotMassMustBeBoundToLiveTick');
assert(contains(capture,"'reference_version'") && ...
    contains(capture,"'known_mask'") && ...
    contains(capture,"'time_s'"), ...
    'R88R2:SnapshotMustBindTimeVersionAndKnownMask');
assert(contains(replay,'AF7R58R88_SELECT_TIME(snaps,t)') && ...
    contains(replay,'Z.estimated_mass_kg') && ...
    contains(replay,'R88_NO_EXACT_TIME_BOUND_SNAPSHOT__NO_R81'), ...
    'R88R2:ReplayMustUseOnlyExactCapturedAuthority');
assert(~contains(replay,'obj.loadmass') && ...
    ~contains(replay,'obj.get_load_mass()') && ...
    ~contains(replay,'estimator.result.state.mL'), ...
    'R88R2:ReplayMustNotUsePostFlightMass');
assert(contains(replay,'R88:SavedModelNativeEvaluatorMismatch') && ...
    contains(replay,"'production_committed',false"), ...
    'R88R2:ReplayMustRetainSafetyGuards');
S0=struct('time_s',{13.325,19.675,19.75}, ...
    'reference_version',{1,2,3});
assert(isequal(AF7R58R88_SELECT_TIME(S0,19.75),3));
assert(isempty(AF7R58R88_SELECT_TIME(S0,19.725)));
assert(isempty(AF7R58R88_SELECT_TIME(S0,19.75001)));
assert(isempty(AF7R58R88_SELECT_TIME(S0([1 1]),13.325)));
fns=cell(1,8);
for k=1:8
    q=k;
    fns{k}=@(tau)[tau.^q;2*tau.^q;3*tau.^q];
end
J=AF7R58R88_NOMINAL_JETS(fns,5,6);
assert(isequal(size(J),[3 8]) && J(1,1)==1 && J(3,8)==3);
T=struct('status','PASS_R88R2_SOURCE_SCOPED_TEST', ...
    'previous_false_global_assert_removed',true, ...
    'flight_time_mass_bound',true, ...
    'historical_mass_not_read_after_flight',true, ...
    'unchanged_production_body_verified_by_packager',true, ...
    'runtime_matlab_test_performed',false, ...
    'trigger_switched',false, ...
    'trajectory_generator_modified',false, ...
    'continuous_closed_loop_safety_proved',false);
end
