function R=AF7R58R74_FROZEN_EVENT_PREVIEW(c)
% R74: reconstruct EVERY numeric control-model authority from a single
% immutable Flight event; never read end-of-flight physical parameters.
% No HLC, EKF, plant, runner or live parameter object is changed.
need={'time_s','estimated_mass_kg','cable_length_m','external_param', ...
    'parameter_order','parameter_class','controller_param', ...
    'plant_param','plant_dim','plant_method_fn','plant_solver_fn', ...
    'horizon_s','prediction_dt','state_x24','raw_reference_fn'};
assert(isstruct(c) && all(isfield(c,need)), ...
    '[R74] this is not an R74 event snapshot; rerun Flight using R74.');
order=string(c.parameter_order(:)); vals=double(c.external_param(:));
assert(numel(order)==numel(vals) && numel(order)>0 && ...
    all(isfinite(vals)) && numel(unique(order))==numel(order), ...
    '[R74] event parameter order and numeric values inconsistent.');
ix=find(strcmpi(order,'loadmass'));
assert(numel(ix)==1 && isfinite(c.estimated_mass_kg) && ...
    c.estimated_mass_kg>0 && ...
    abs(vals(ix)-double(c.estimated_mass_kg)) <= ...
    4096*eps(max([1,abs(vals(ix)),abs(double(c.estimated_mass_kg))])), ...
    ['[R74] event-time HLC mass does not match same-event EKF mL; ' ...
     'do not replay a different controller.']);
ixL=find(strcmpi(order,'cableL'));
assert(numel(ixL)==1 && vals(ixL)==double(c.cable_length_m), ...
    '[R74] event cable length authority mismatch.');
cls=char(c.parameter_class);
assert(strcmp(cls,'DRONE_PARAM_SUSPENDED_LOAD'), ...
    '[R74] unverified parameter class; no inferred constructor/fallback.');
% Constructor name is only an internal tag, NOT a physical setting.
% R74R2: type="row" is positional; event fields are name-value inputs.
params=AF7R58R74R2_REBUILD_PARAMS(cls,order,vals,'R74_EVENT_SHADOW');
assert(isa(c.plant_method_fn,'function_handle') && ...
    isa(c.plant_solver_fn,'function_handle') && ...
    isequal(size(c.state_x24),[24 1]) && ...
    numel(c.plant_dim)==3, ...
    '[R74] incomplete exact event plant authority.');
% Minimal struct graph: the real HLC class and real plant functions are
% invoked, but only via frozen parameters and independently owned states.
shadow=struct();
shadow.parameter=params;
shadow.plant=struct('method',c.plant_method_fn, ...
    'solver',c.plant_solver_fn,'dim',double(c.plant_dim(:).'), ...
    'param',double(c.plant_param(:).'));
shadow.controller=struct('hlc_suspended',struct('param',c.controller_param));
R=AF7R58R71_EXACT_HLC_PLANT_PREVIEW(shadow,c.raw_reference_fn, ...
    double(c.time_s),double(c.horizon_s),double(c.prediction_dt), ...
    double(c.estimated_mass_kg),double(c.state_x24));
R.event_parameter_order=order;
R.event_external_param=vals;
R.event_time_s=double(c.time_s);
R.postflight_params_read=false;
R.runtime_instanced_objects_mutated=false;
R.continuous_time_collision_proved=false;
R.safe_for_commit=false;
end
