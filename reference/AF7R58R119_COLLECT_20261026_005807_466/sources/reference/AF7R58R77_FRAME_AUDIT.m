function A = AF7R58R77_FRAME_AUDIT(c,P)
% R77 same-event, postflight-only comparison of THREE geometry authorities.
% The Flight adapter SUSPENDED_LOAD_REF_ADJUST sets the raw reference
% payload z to raw xd(3)-cableL. The R76 reference packet is PRE adapter.
% HLC / EKF / plant / runtime reference / trigger / commit remain untouched.
% This is a sampled comparison, never a continuous-time safety certificate.
req={'time_s','horizon_s','prediction_dt','cable_length_m', ...
    'reference_version','r76_packet','r76_known_mask', ...
    'r76_reference_pL','r76_reference_q','r76_original_trigger', ...
    'r76_radii_m','r76_d_margin_m','raw_reference_fn'};
assert(isstruct(c) && all(isfield(c,req)), ...
    '[R77] incomplete same-event snapshot; old R75 events cannot be upgraded.');
assert(isstruct(P) && all(isfield(P,{'t','pQ','pL','hlc_payload_xd'})), ...
    '[R77] independent HLC+plant same-event preview is required.');
L=double(c.cable_length_m);
t=double(P.t(:).'); N=numel(t);
raw=double(c.r76_reference_pL);q=double(c.r76_reference_q);
assert(isfinite(L) && L>0 && isequal(size(raw),[3 N]) && ...
    isequal(size(q),[3 N]) && all(isfinite(raw),'all') && ...
    all(isfinite(q),'all'), ...
    '[R77] raw reference packet does not match numeric rollout.');
assert(abs((t(end)-t(1))-double(c.horizon_s)) <= ...
    1e-8*max(1,double(c.horizon_s)) && ...
    abs(t(1)-double(c.time_s)) <= 1e-8*max(1,abs(t(1))), ...
    '[R77] comparing different event time/horizon is forbidden.');
% Source-bound Flight adapter is a CONSTANT z translation over Flight;
% derivatives remain unchanged, and the same q is well-defined.
shift=[0;0;L]; adjusted=raw-shift;
cmd=double(P.hlc_payload_xd);
assert(size(cmd,1)>=3 && size(cmd,2)==N && ...
    all(isfinite(cmd(1:3,:)),'all'), ...
    '[R77] Flight adapter target is absent in the physical preview.');
% Also require that the event-native flat evaluator is the same input source
% used to build the reference packet at the triggering instant.
source=double(c.raw_reference_fn(double(c.time_s)));source=source(:);
assert(numel(source)>=3 && all(isfinite(source(1:3))), ...
    '[R77] event native active flat evaluator is not available.');
matchScale=max([1,max(abs(raw(:))),max(abs(adjusted(:))),max(abs(cmd(1:3,:)),[],'all')]);
sourceErr=max(abs(source(1:3)-raw(:,1)));
cmdErr=max(abs(cmd(1:3,:)-adjusted),[],'all');
% The rollout evaluated all 161 times by the authoritative function, while
% cached pL_ref may use an independently maintained exact rolling packet.
% If they disagree beyond model-scale IEEE tolerance, do NOT silently
% substitute the two as identical trajectories.
tol=4096*eps(matchScale);
A=struct('status','NOT_RUN','event_time_s',double(c.time_s), ...
    'reference_version',double(c.reference_version), ...
    'sample_count',N,'adapter_offset_m',L, ...
    'source_at_event_error_m',sourceErr, ...
    'adapter_to_hlc_all_samples_error_m',cmdErr, ...
    'reference_packet_consistent',sourceErr<=tol && cmdErr<=tol, ...
    'reference_raw',struct(),'reference_hlc_frame',struct(), ...
    'physical_ekf_initial',struct(),'raw_reference_first_component','NONE', ...
    'corrected_reference_first_component','NONE', ...
    'raw_reference_first_time_s',NaN, ...
    'corrected_reference_first_time_s',NaN, ...
    'physical_first_time_s',NaN, ...
    'original_trigger',logical(c.r76_original_trigger), ...
    'initial_uav_tracking_gap_m',NaN, ...
    'initial_payload_tracking_gap_m',NaN, ...
    'continuous_time_certified',false, ...
    'eligible_for_production_trigger',false, ...
    'error_message','');
if ~A.reference_packet_consistent
    A.status='REFERENCE_PACKET_VS_ACTUAL_HLC_TARGET_MISMATCH__FAIL_CLOSED';
    A.error_message='Raw packet differs from event flat evaluator / HLC adapted target.';
    return;
end
B=AF7R58R76_COLLISION_AUDIT(c,P);
d=c;d.r76_reference_pL=adjusted;
D=AF7R58R76_COLLISION_AUDIT(d,P);
assert(B.packet_version_matches && D.packet_version_matches && ...
    B.samples==D.samples && ...
    isequal(B.physical_sample_outer_hit,D.physical_sample_outer_hit) && ...
    isequaln(B.physical_first_time_s,D.physical_first_time_s), ...
    '[R77] physical trajectory changed when only reference frame moved.');
A.reference_raw=B;
A.reference_hlc_frame=D;
A.physical_ekf_initial=struct( ...
    'hit',logical(B.physical_sample_outer_hit), ...
    'time_s',B.physical_first_time_s, ...
    'component',B.physical_first_component, ...
    'obstacle_id',B.physical_first_obstacle_id, ...
    'native_hit',B.native_physical_nonseparation, ...
    'native_index',B.native_physical_jhit);
A.raw_reference_first_time_s=B.reference_first_time_s;
A.corrected_reference_first_time_s=D.reference_first_time_s;
A.physical_first_time_s=B.physical_first_time_s;
A.raw_reference_first_component=B.reference_first_component;
A.corrected_reference_first_component=D.reference_first_component;
pQ0=double(P.pQ(:,1));pL0=double(P.pL(:,1));
refQ0=adjusted(:,1)-L*q(:,1);
A.initial_uav_tracking_gap_m=norm(pQ0-refQ0);
A.initial_payload_tracking_gap_m=norm(pL0-adjusted(:,1));
A.status='THREE_WAY_SAME_EVENT_SAMPLE_COMPARISON__NOT_CERTIFIED';
end
