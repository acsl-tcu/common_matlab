function D=AF7R58R96_KNOT_REACHABILITY_PREFLIGHT(W,times,L,vQmax)
% MATHEMATICALLY NECESSARY (not sufficient) cable/UAV travel inequality.
% For unknown intermediate cable directions q_i, ||q_i||=1:
% ||pQ_(i+1)-pQ_i|| >= max(0, ||pL_(i+1)-pL_i||-2L).
% If the UAV has speed <=vQmax then (distance-2L) <=vQmax*dt.
% This cheap test runs BEFORE constructing degree-15 trajectories.
assert(isnumeric(W)&&size(W,1)==3&&all(isfinite(W(:)))&& ...
 isnumeric(times)&&isrow(times)&&numel(times)==size(W,2)&& ...
 all(isfinite(times))&&all(diff(times)>0)&& ...
 isnumeric(L)&&isscalar(L)&&isfinite(L)&&L>0&& ...
 isnumeric(vQmax)&&isscalar(vQmax)&&isfinite(vQmax)&&vQmax>0, ...
 'R96:ReachabilityExternalAuthority', ...
 'Need valid knot positions/times, live cable length, UAV speed bound.');
dist=vecnorm(diff(double(W),1,2),2,1);
dt=diff(double(times));
needed=max(0,dist-2*double(L))./dt;
D=struct('status','NECESSARY_SPHERICAL_CABLE_REACHABILITY_PASS', ...
 'passes_necessary_condition',true, ...
 'required_average_uav_speed_lower_m_s',needed, ...
 'first_failed_segment',NaN,'not_sufficient_for_safety',true, ...
 'production_commit_authorized',false);
idx=find(needed>vQmax+128*eps(max([1,vQmax,needed])),1);
if ~isempty(idx)
 D.passes_necessary_condition=false;
 D.first_failed_segment=idx;
 D.status='NECESSARY_CABLE_UAV_TRAVEL_TIME_VIOLATION';
end
end
