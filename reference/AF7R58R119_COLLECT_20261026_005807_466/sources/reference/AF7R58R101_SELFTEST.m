function T=AF7R58R101_SELFTEST()
% Regression of the exact R100 failure: heterogeneous struct assignment.
% Does not require Flight replay and does not prove safety.
S=AF7R58R101_SOURCE_CHECK();
assert(strcmp(S.status,'PASS_R101_ALL_RUNTIME_DEPENDENCIES'), ...
    'R101:DependencyFailed','Source dependencies are missing or shadowed.');
% This call must construct the SOURCE_CHECK cell array without MATLAB vertcat.
assert(isempty(S.missing_dependencies) && ...
       isempty(S.different_source_directory), ...
       'R101:SourceCheckListNotScalarCell', ...
       'The source-check dependency list must be a one-row cell vector.');
E=AF7R58R101_SEED_RECORD();
assert(isfield(E,'retime_trials') && ...
       isfield(E,'timing_peak_before_m_s') && ...
       isfield(E,'timing_peak_after_m_s') && ...
       isfield(E,'interior_peak_sample_m_s') && ...
       isfield(E,'interior_peak_baseline_sample_m_s') && ...
       isfield(E,'speed_blend_alpha') && ...
       isfield(E,'internal_speed_trials') && ...
       isfield(E,'geometry_kinematics_heading_pass'), ...
       'R101:NewFieldsMissing','New R100 fields missing from common schema.');
producer=repmat(AF7R58R101_SEED_RECORD(),1,0);
collector=repmat(AF7R58R101_SEED_RECORD(),1,0);
E.index=1;
E.status='PREFILTER_ADAPTIVE_KNOT_TIME_UNRESOLVED';
E.reason='SYNTHETIC_EXPECTED_NOT_REAL_FLIGHT';
E.retime_trials=2;
E.interior_peak_sample_m_s=1.25;
producer(end+1)=orderfields(E,AF7R58R101_SEED_RECORD());
try
    error('R101:SyntheticFailClosed','Simulated failed candidate.');
catch ME
    F=AF7R58R101_SEED_RECORD();
    F.index=2;
    F.status='FAIL_CLOSED_SEED_EXCEPTION';
    F.error=ME.identifier;
    producer(end+1)=orderfields(F,AF7R58R101_SEED_RECORD());
end
for k=1:numel(producer)
    C=producer(k);C.attempt_index=11;
    collector(end+1)=orderfields(C,AF7R58R101_SEED_RECORD());
end
assert(numel(collector)==2 && ...
       collector(1).retime_trials==2 && ...
       collector(1).interior_peak_sample_m_s==1.25 && ...
       strcmp(collector(2).status,'FAIL_CLOSED_SEED_EXCEPTION') && ...
       strcmp(collector(2).error,'R101:SyntheticFailClosed'), ...
       'R101:StructAppendRegression', ...
       'Reproduced the heterogeneous-struct-assignment regression.');
% Confirm runtime source uses the same schema, not duplicate field lists.
srcRunner=fileread(which('AF7R58R101_RUN_SAVED_ROUTE'));
srcAdaptive=fileread(which('AF7R58R101_ADAPTIVE_SAVED_SEARCH'));
assert(contains(srcRunner,'R.seed_attempt_log=repmat(AF7R58R101_SEED_RECORD(),1,0)') && ...
       contains(srcRunner,'E=AF7R58R101_SEED_RECORD()') && ...
       contains(srcAdaptive,'seed_log'',repmat(AF7R58R101_SEED_RECORD(),1,0)') && ...
       ~contains(srcAdaptive,'B=AF7R58R100_RUN_SAVED_ROUTE'), ...
       'R101:RuntimeSchemaNotBound', ...
       'Runtime call path still refers to outdated seed schema.');
% Source-only tests must not be misinterpreted as closed-loop success.
T=struct('status','PASS_R101_SHARED_SEED_SCHEMA_APPEND_REGRESSION', ...
    'producer_and_collector_fields_match',true, ...
    'success_and_exception_seed_appended',true, ...
    'new_time_and_speed_fields_retained',true, ...
    'runtime_calls_pinned_r101_runner',true, ...
    'r100_optimizer_retained',true, ...
    'real_flight_snapshot_replayed',false, ...
    'production_modified',false, ...
    'physical_trigger_switched',false, ...
    'whole_body_closed_loop_or_ieee_proved',false);
end
