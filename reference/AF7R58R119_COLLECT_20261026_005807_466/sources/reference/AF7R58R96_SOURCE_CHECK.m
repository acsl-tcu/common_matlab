function S=AF7R58R96_SOURCE_CHECK()
% Check actual resolution AND source identity of the runtime call graph.
% Does not assert closed-loop mathematical safety or run SimHL.
base=fileparts(mfilename('fullpath'));
new={'AF7R58R96_ADAPTIVE_SAVED_SEARCH', ...
 'AF7R58R96_RUN_SAVED_ROUTE','AF7R58R96_CORRIDOR_PREFLIGHT', ...
 'AF7R58R96_C7_KNOT_SPEED_ROUTE', ...
 'AF7R58R96_C7_CORRIDOR_PROJECT', ...
 'AF7R58R96_KNOT_VQ_SCREEN', ...
 'AF7R58R96_KNOT_REACHABILITY_PREFLIGHT', ...
 'AF7R58R96_KNOT_DISPLACEMENT_SCREEN', ...
 'AF7R58R96_WRITE_REPORT','AF7R58R96_SELFTEST', ...
 'AF7R58R96_SOURCE_CHECK','AF7R58R96_SHA256_FILE'};
prior={'AF7R58R94_CERTIFY_ALL_SEGMENTS', ...
 'AF7R58R94_SUPPORT_SEED_ROUTES','AF7R58R92_C7_MINIMUM8_ROUTE', ...
 'AF7R58R83_BIND_R81_INPUTS','AF7R58R88_NOMINAL_JETS', ...
 'AF7R58R88_SELECT_TIME', ...
 'AF7R58R91_STABLE_KINEMATIC_CERT', ...
 'AF7R58R80_HEADING_C6_CERT', ...
 'AF7R58R80_CONTINUOUS_SEPARATE_BODY_CERT', ...
 'AF7R58R90_INPUT_ENVELOPE'};
names=[new,prior];files=cell(size(names));hashes=cell(size(names));
missing={};shadow={};
for i=1:numel(names)
    files{i}=which(names{i});
    if isempty(files{i})
        missing{end+1}=names{i}; %#ok<AGROW>
        hashes{i}='';continue;
    end
    if ~strcmp(fileparts(files{i}),base)
        shadow{end+1}=names{i}; %#ok<AGROW>
    end
    hashes{i}=AF7R58R96_SHA256_FILE(files{i});
end
S=struct('status','', ...
    'new_files_complete',isempty(missing)&&isempty(shadow), ...
    'missing_dependencies',{missing},'different_source_directory',{shadow}, ...
    'filenames',{names},'resolved_files',{files},'sha256',{hashes}, ...
    'new_package_source_count',numel(new), ...
    'production_modified',false,'production_commit_authorized',false, ...
    'full_closed_loop_safety_proved',false);
if isempty(missing)&&isempty(shadow)
 S.status='PASS_R96_PINNED_RUNTIME_DEPENDENCY_RESOLUTION';
else
 S.status='FAIL_R96_MISSING_OR_SHADOWED_DEPENDENCIES__NO_EXECUTION';
end
end
