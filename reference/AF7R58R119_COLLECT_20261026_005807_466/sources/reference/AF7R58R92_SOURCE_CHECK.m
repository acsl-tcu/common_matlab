function C=AF7R58R92_SOURCE_CHECK()
% Checks the R92 bundle and previously installed exact source-bound certifiers.
base=fileparts(mfilename('fullpath'));
required={'AF7R58R92_C7_MINIMUM8_ROUTE.m', ...
 'AF7R58R92_CERTIFY_ALL_SEGMENTS.m', ...
 'AF7R58R92_RUN_SAVED_ROUTE.m', ...
 'AF7R58R92_SUPPORT_SEED_ROUTES.m', ...
 'AF7R58R92_TRACKING_INFLATION.m', ...
 'AF7R58R92_ADAPTIVE_SAVED_SEARCH.m', ...
 'AF7R58R92_SELFTEST.m'};
for i=1:numel(required)
 assert(exist(fullfile(base,required{i}),'file')==2, ...
    'R92:MissingLocalSource:%s',required{i});
end
requiredPrev={'AF7R58R83_BIND_R81_INPUTS', ...
 'AF7R58R88_SELECT_TIME','AF7R58R88_NOMINAL_JETS', ...
 'AF7R58R91_STABLE_KINEMATIC_CERT', ...
 'AF7R58R80_HEADING_C6_CERT', ...
 'AF7R58R80_CONTINUOUS_SEPARATE_BODY_CERT', ...
 'AF7R58R90_INPUT_ENVELOPE'};
missing={};
for i=1:numel(requiredPrev)
 if exist(requiredPrev{i},'file')~=2
     missing{end+1}=requiredPrev{i}; %#ok<AGROW>
 end
end
C=struct('status','R92_SOURCE_CHECKED__NOT_PRODUCTION', ...
 'matlab_previous_dependencies_available',isempty(missing), ...
 'missing_dependencies',{missing},'flight_trigger_switched',false, ...
 'production_initial_generator_replaced',false, ...
 'full_closed_loop_safety_proved',false);
end
