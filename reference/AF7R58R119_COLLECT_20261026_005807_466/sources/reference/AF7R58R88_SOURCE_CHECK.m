function S=AF7R58R88_SOURCE_CHECK()
% Reject any non-R87 baseline, package corruption, or nonadditive edit.
root=fileparts(mfilename('fullpath'));
target=fullfile(root,'REPLANNING_SYSTEM.m');
patch=fullfile(root,'REPLANNING_SYSTEM_R88_PATCHED_SOURCE.txt');
assert(isfile(target)&&isfile(patch),'R88:MissingSources');
base='694fe9c440b780a4168d10cf3a4f53bb20e17222409151c91c22b175ecee4d7d';
after='7d9502ca5d8db06f089c534bcdffb07d184b731a29266ffc52a7859a0c3c8621';
h=AF7R58R88_SHA256_FILE(target);
assert(strcmp(h,base)||strcmp(h,after), ...
    'R88:UnknownCurrentSource_NoWrite');
assert(strcmp(AF7R58R88_SHA256_FILE(patch),after), ...
    'R88:PackagedPatchCorrupt');
P=fileread(patch);
assert(numel(strfind(P,'function r88_capture_one_version'))==1 && ...
    numel(strfind(P,'function R=r88_replay_saved_version_reference_only'))==1 && ...
    numel(strfind(P,'obj.r88_capture_one_version(double(time.t),active);'))==1 && ...
    contains(P,'estimated_mass_kg'',mL') && ...
    contains(P,'AF7R58R88_SELECT_TIME(snaps,t)') && ...
    contains(P,'R88_NO_EXACT_TIME_BOUND_SNAPSHOT__NO_R81') && ...
    contains(P,'R88:SavedModelNativeEvaluatorMismatch'), ...
    'R88:RequiredSafetyPathsMissing');
assert(numel(strfind(P,'function mL = get_load_mass(obj)'))==1 && ...
    contains(P,'mL=obj.self.estimator.result.state.mL;'), ...
    'R88:LiveMassGetterMustRemainUntouched');
S=struct('status','PASS_R88_R87_SOURCE_BOUND', ...
    'before_install',strcmp(h,base),'already_installed',strcmp(h,after), ...
    'source_sha256',h,'expected_patched_sha256',after, ...
    'live_mass_getter_untouched',true, ...
    'production_commit_changed',false, ...
    'closed_loop_proved',false);
end
