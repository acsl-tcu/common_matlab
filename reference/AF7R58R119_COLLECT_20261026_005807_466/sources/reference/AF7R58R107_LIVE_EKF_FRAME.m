function [F,D]=AF7R58R107_LIVE_EKF_FRAME(replanner,t,knownMask)
% Live no-history input to the physical trigger. Call only INSIDE the
% replanner's Flight do(), AFTER sensor memory and EKF update, at that tick.
% Never reads R88/R55/R63 historical rings; does not invoke any optimizer.
% Output authenticity covers the EKF event, NOT a 4-second plant reach tube.
F=struct([]);
D=struct('status','LIVE_EKF_EVENT_NOT_AUTHENTICATED', ...
    'raw_ekf_valid',false,'physical_geometry_valid',false, ...
    'physical_future_certified',false,'time_s',double(t), ...
    'reference_version',NaN,'no_extra_logging',true);
assert(isa(replanner,'REPLANNING_SYSTEM')&&isscalar(replanner), ...
    'R107:LiveOwner','Use live REPLANNING_SYSTEM, not a postflight proxy.');
assert(isnumeric(t)&&isscalar(t)&&isfinite(t),'R107:Time', ...
    'The Flight do() time is required.');
assert(islogical(knownMask)||isnumeric(knownMask), ...
    'R107:KnownMaskType','Sensor-known obstacle mask required.');
Z=replanner.obstacle_packet;
mask=logical(knownMask(:).');
if ~(isstruct(Z)&&isscalar(Z)&&all(isfield(Z, ...
        {'C','R','Araw','ids','delta_payload_m', ...
        'delta_uav_m','delta_cable_m'})))
    D.status='LIVE_OBSTACLE_PACKET_UNAVAILABLE';return;
end
M=numel(Z.ids);
if numel(mask)~=M || ~any(mask)
    D.status='NO_VALID_SENSOR_KNOWN_OBSTACLE';return;
end
% Exactly one copy of the current EKF state; no per-tick source lookup,
% disk I/O, recursion, debugging snapshot, controller or plant mutation.
ver=double(replanner.active_reference_version);
L=double(replanner.L_cable);
E=AF7R58R106_PACK_EKF(replanner.self.estimator.result.state, ...
    t,ver,mask,L);
D.reference_version=ver;
if ~(isnumeric(E.state_x24)&&numel(E.state_x24)==24&& ...
        all(isfinite(E.state_x24(:))))
    D.status='LIVE_EKF_FULL_24_STATE_UNAVAILABLE';return;
end
D.raw_ekf_valid=true;
x=double(E.state_x24(:));
r=norm(x(13:15)-x(1:3)-L*x(19:21));
qerr=abs(norm(x(19:21))-1);
if ~(r<=1e-5*max(1,L)&&qerr<=1e-5)
    D.status='LIVE_EKF_CONSTRAINT_RESIDUAL__OBSERVER_TUBE_NEEDED';return;
end
D.physical_geometry_valid=true;
C=double(Z.C);R=double(Z.R);A=double(Z.Araw);
if ~isequal(size(C),[3,M])||~isequal(size(R),[9,M])|| ...
        ~isequal(size(A),[3,M])||~all(isfinite([C(:);R(:);A(:)]))|| ...
        any(A(:)<=0)
    D.status='LIVE_ELLIPSOID_PACKET_INVALID';return;
end
Dcomp=[double(replanner.r_load)+double(replanner.d_margin)+ ...
       double(Z.delta_payload_m); ...
       double(replanner.r_drone)+double(replanner.d_margin)+ ...
       double(Z.delta_uav_m); ...
       double(replanner.r_cable)+double(replanner.d_margin)+ ...
       double(Z.delta_cable_m)];
if ~(numel(Dcomp)==3&&all(isfinite(Dcomp))&&all(Dcomp>=0))
    D.status='LIVE_INFLATION_INVALID';return;
end
F=struct('time_s',double(t),'reference_version',ver, ...
    'horizon_s',double(replanner.horizon_s), ...
    'dt_s',double(replanner.prediction_dt), ...
    'cable_length_m',L,'pL_EKF',x(13:15), ...
    'pQ_EKF',x(1:3),'q_EKF',x(19:21), ...
    'state_x24',x,'known_mask',mask, ...
    'C',C,'R',R,'Araw',A,'ids',double(Z.ids(:).'), ...
    'Dcomp',Dcomp,'source','LIVE_CURRENT_TICK_EKF_NO_HISTORY');
D.status='LIVE_EKF_AND_SENSOR_KNOWN_FRAME_AVAILABLE';
end
