function S=AF7R58R73_SOURCE_CHECK()
% R73 actual MATLAB class parsing and source-binding check.
p=which('REPLANNING_SYSTEM');
assert(~isempty(p)&&~isempty(meta.class.fromName('REPLANNING_SYSTEM')), ...
    '[R73] Replanner missing or MATLAB class parser failed');
s=fileread(p);
assert(contains(s,"AF7R58R73_REGISTRY('register',obj)") && ...
    contains(s,"AF7R58R73_REGISTRY('capture',obj)") && ...
    contains(s,'obj.r71r2_event_snapshots=captured;') && ...
    contains(s,'catch r73_capture_ME') && ...
    contains(s,'r73_capture_error_count'), ...
    '[R73] source-bound snapshot repair missing');
assert(exist('AF7R58R71_EXACT_HLC_PLANT_PREVIEW','file')==2 && ...
    exist('AF7R58R73_COLLECT','file')==2 && ...
    exist('AF7R58R73_REGISTRY','file')==2, ...
    '[R73] dependent MATLAB sources missing');
B=AF7R58R73_REGISTRY('status');
S=struct('source',p,'matlab_class_parser_passed',true, ...
    'first_event_full_struct_assignment',true, ...
    'diagnostic_snapshot_errors_do_not_abort_flight',true, ...
    'postflight_collector_first_event_fixed',true, ...
    'registry_before_flight',B, ...
    'hlc_ekf_plant_runner_unchanged',true, ...
    'reference_future_trigger_replaced',false, ...
    'natural_C7_return_committed',false, ...
    'continuous_time_safety_certified',false);
end
