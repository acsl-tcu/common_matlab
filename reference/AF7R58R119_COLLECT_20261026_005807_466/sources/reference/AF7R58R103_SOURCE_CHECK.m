function S=AF7R58R103_SOURCE_CHECK()
% Exact current integration boundary. Fail when native class differs from
% the R88R2 Flight source audited for this bridge. No replacement/write.
root=fileparts(mfilename('fullpath'));
need={ ...
    'AF7R58R103_SOURCE_CHECK', ...
    'AF7R58R103_SELFTEST', ...
    'AF7R58R103_SHA256_FILE', ...
    'AF7R58R103_EKF_HLC_TRIGGER', ...
    'AF7R58R103_FROM_R55_PACKET', ...
    'AF7R58R103_DUAL_STAGE', ...
    'AF7R58R103_ATOMIC_HANDOVER', ...
    'AF7R58R102_ADAPTIVE_SAVED_SEARCH', ...
    'AF7R58R88_SELECT_TIME' ...
    };
missing={};shadow={};
for k=1:numel(need)
    path=which(need{k});
    if isempty(path)
        missing{end+1}=need{k}; %#ok<AGROW>
    elseif ~strcmp(fileparts(path),root)
        shadow{end+1}=sprintf('%s -> %s',need{k},path); %#ok<AGROW>
    end
end
sourceFile=which('REPLANNING_SYSTEM');
expected='7d9502ca5d8db06f089c534bcdffb07d184b731a29266ffc52a7859a0c3c8621';
actual='';
if ~isempty(sourceFile)&&isfile(sourceFile)
    actual=AF7R58R103_SHA256_FILE(sourceFile);
end
sourceCorrect=strcmp(actual,expected);
S=struct('status','PASS_R103_DUAL_CONNECTION_SOURCES__NOT_FLIGHT_READY', ...
    'missing_dependencies',{missing}, ...
    'different_source_directory',{shadow}, ...
    'production_source_sha256',actual, ...
    'expected_r88r2_source_sha256',expected, ...
    'native_atomic_source_pinned',sourceCorrect, ...
    'physical_predictor_source_bound',false, ...
    'complete_hlc_closed_loop_certificate',false, ...
    'generator_production_certified',false, ...
    'production_modified',false, ...
    'physical_trigger_switched',false, ...
    'generator_switched',false, ...
    'handover_enabled',false);
if ~isempty(missing)||~isempty(shadow)||~sourceCorrect
    S.status='BLOCKED_MISSING_SHADOWED_OR_UNEXPECTED_PRODUCTION_CLASS';
end
end
