function I=AF7R58R86_INSTALL()
% One-time OFFLINE installation: single read-only native-jet method plus
% R83 adapter routing. Never invoke during Flight or with live agent handles.
root=fileparts(mfilename('fullpath'));
target=fullfile(root,'REPLANNING_SYSTEM.m');
patch=fullfile(root,'REPLANNING_SYSTEM_R86_PATCHED_SOURCE.txt');
S=AF7R58R86_SOURCE_CHECK();
assert(S.source_before_install, ...
    'R86:AlreadyPatchedOrSourceChanged_NoWrite');
% Back up source in this script's directory before changing anything.
backup=fullfile(root,['REPLANNING_SYSTEM_pre_AF7R58R86_' ...
    datestr(now,'yyyymmdd_HHMMSSFFF') '.m']);
[ok,msg]=copyfile(target,backup);assert(ok,'R86:BackupFailed:%s',msg);
try
    [ok,msg]=copyfile(patch,target,'f');
    if ~ok,error('R86:CopyError','%s',msg);end
    T=AF7R58R86_SOURCE_CHECK();
    assert(T.source_already_patched,'R86:PostwriteIntegrityFailed');
catch ME
    copyfile(backup,target,'f');
    error('R86:InstallRolledBack', ...
        'Original source restored; %s',ME.message);
end
I=struct('status','R86_LIVE_NATIVE_C7_AUTHORITY_INSTALLED__RESTART_MATLAB', ...
    'backup_file',backup, ...
    'original_sha256','57e60163d054c3c102573496cb9457c5ece155c4f59a6c47acd1dc6c9a4bbff5', ...
    'patched_sha256','e55452c44b4eb77fbf33f1f422422b9b223d2844f85a1666a57178f07670deaa', ...
    'flight_loop_changed',false, ...
    'reference_generator_changed',false, ...
    'controller_plant_estimator_changed',false, ...
    'production_safety_proved',false);
% Explicit restart required. No class clearing while agent handles exist.
end
