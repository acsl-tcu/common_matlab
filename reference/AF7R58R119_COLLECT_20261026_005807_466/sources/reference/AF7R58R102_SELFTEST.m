function T=AF7R58R102_SELFTEST()
% Tests actual C7 optimizer (not just file names), schema append and dependencies.
S=AF7R58R102_SOURCE_CHECK();
assert(strcmp(S.status,'PASS_R102_SOURCE_DEPENDENCIES'), ...
    'R102:Deps','All source functions must resolve from reference folder.');
J0=zeros(3,8);J1=zeros(3,8);
J0(:,1)=[0;0;0];J1(:,1)=[4;0;0];
t=[0 1 2];W=[J0(:,1),[2;1;0],J1(:,1)];
R=AF7R58R92_C7_MINIMUM8_ROUTE(t,W,J0,J1,0,2);
assert(R.reference_candidate_found, 'R102:SyntheticC7','C7 generation failed.');
P=struct('max_continuous_jet_steps',14, ...
    'jet_objective_samples_per_segment',11);
O=AF7R58R102_C7_CONTINUOUS_JET_OPT(R,9.81,2,5,P);
assert(isfinite(O.sampled_speed_before_m_s)&& ...
    isfinite(O.sampled_speed_after_m_s)&& ...
    O.sampled_speed_after_m_s<=O.sampled_speed_before_m_s+1e-9, ...
    'R102:SpeedObjective','Generator optimizer worsened its numeric objective.');
Z=O.route;
assert(isequaln(Z.knot_jets(:,:,1),J0)&& ...
    isequaln(Z.knot_jets(:,:,end),J1), ...
    'R102:BoundaryJets','Source or destination jets changed.');
maxRelativeResidual=0;
for i=1:Z.num_segments
    H=Z.segments(i);A=H.payload_cp;D=A;
    for k=0:7
        lhs=[D(:,1);D(:,end)];
        rhs=[Z.knot_jets(:,k+1,i);Z.knot_jets(:,k+1,i+1)];
        maxRelativeResidual=max(maxRelativeResidual, ...
            max(abs(lhs-rhs)./max(1,abs(rhs))));
        if k<7,D=(size(D,2)-1)/H.duration_s*diff(D,1,2);end
    end
end
assert(maxRelativeResidual<1e-5, 'R102:C7EndpointNumeric', ...
    'Bezier boundary jet reconstruction was inaccurate.');
E=AF7R58R102_SEED_RECORD();
assert(all(isfield(E,{'r102_jet_optimizer_status', ...
    'r102_jet_optimizer_iterations','r102_speed_before_m_s', ...
    'r102_speed_after_m_s'})), ...
    'R102:Schema','New optimizer diagnostic fields missing.');
Q=repmat(AF7R58R102_SEED_RECORD(),1,0);
E.r102_speed_after_m_s=O.sampled_speed_after_m_s;
Q(end+1)=orderfields(E,AF7R58R102_SEED_RECORD());
assert(numel(Q)==1&&isfinite(Q(1).r102_speed_after_m_s), ...
    'R102:Append','Shared schema append failed.');
T=struct('status','PASS_R102_CONTINUOUS_INTERNAL_JET_GENERATOR', ...
    'source_dependencies_complete',true, ...
    'baseline_sample_peak_m_s',O.sampled_speed_before_m_s, ...
    'selected_sample_peak_m_s',O.sampled_speed_after_m_s, ...
    'numeric_jet_optimizer_steps',O.iterations, ...
    'max_relative_endpoint_jet_residual',maxRelativeResidual, ...
    'source_and_target_jet07_unchanged',true, ...
    'shared_seed_schema_append_pass',true, ...
    'real_flight_snapshot_replayed',false, ...
    'closed_loop_and_ieee_proved',false, ...
    'production_modified',false);
end
