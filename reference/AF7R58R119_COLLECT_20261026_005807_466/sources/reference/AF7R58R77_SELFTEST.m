function T=AF7R58R77_SELFTEST()
% A general translated Flight reference, arbitrary heading and nonzero
% speed. Frame shift must change only reference geometry, not the EKF rollout.
B=AF7R58R76_SELFTEST();
assert(startsWith(B.status,'PASS_R76'),'[R77] inherited geometry test failed.');
L=2;Tvec=0:0.025:4;N=numel(Tvec);
y=1.5*Tvec;
pQ=[zeros(1,N);y;L*ones(1,N)];pL=pQ-[0;0;L];
raw=pL+[0;0;L];q=(pL-pQ)/L;
XD=zeros(28,N);XD(1:3,:)=pL;
P=struct('t',Tvec,'pQ',pQ,'pL',pL,'hlc_payload_xd',XD);
c=struct('time_s',0,'horizon_s',4,'prediction_dt',0.025, ...
  'cable_length_m',L,'reference_version',0, ...
  'r76_reference_pL',raw,'r76_reference_q',q, ...
  'r76_original_trigger',true,'r76_original_ttc_s',4, ...
  'r76_known_mask',true,'r76_radii_m',[0;0;0], ...
  'r76_d_margin_m',0,'raw_reference_fn',@(t)[0;1.5*t;L;zeros(25,1)]);
a=[0.3;0.4;0.5];center=[0;3;L];
c.r76_packet=struct('C',center,'R',reshape(eye(3),9,1), ...
 'Araw',a,'Apay',a,'Auav',a,'Acable',a, ...
 'ids',11,'reference_version',0,'delta_payload_m',0, ...
 'delta_uav_m',0,'delta_cable_m',0);
A=AF7R58R77_FRAME_AUDIT(c,P);
assert(contains(A.status,'THREE_WAY_SAME_EVENT') && ...
    A.reference_packet_consistent && ...
    A.initial_uav_tracking_gap_m < 1e-12 && ...
    A.initial_payload_tracking_gap_m < 1e-12 && ...
    A.reference_hlc_frame.reference_sample_outer_hit && ...
    A.physical_ekf_initial.hit && ...
    strcmp(A.reference_hlc_frame.reference_first_component,'UAV') && ...
    strcmp(A.reference_raw.reference_first_component,'PAYLOAD') && ...
    ~A.eligible_for_production_trigger, ...
    '[R77] reference/adapter/physical geometry not distinguished.');
% Proof of source binding refusal if the Flight adapter assumption is broken.
Pbad=P;Pbad.hlc_payload_xd(3,:)=Pbad.hlc_payload_xd(3,:)+L;
Z=AF7R58R77_FRAME_AUDIT(c,Pbad);
assert(strcmp(Z.status,'REFERENCE_PACKET_VS_ACTUAL_HLC_TARGET_MISMATCH__FAIL_CLOSED'), ...
    '[R77] invalid adapter mapping was silently admitted.');
T=struct('status','PASS_R77_THREE_FRAME_GEOMETRY_AND_FAIL_CLOSED', ...
 'sample_representations_distinct',true,'frame_preserves_physical',true, ...
 'wrong_adapter_mapping_rejected',true, ...
 'replan_trigger_replaced',false,'continuous_time_proved',false);
end
