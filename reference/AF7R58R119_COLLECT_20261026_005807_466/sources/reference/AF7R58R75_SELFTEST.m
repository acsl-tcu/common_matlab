function T=AF7R58R75_SELFTEST()
% Read-only parameter getter API regression test with original class.
% Uses an isolated constructor instance ONLY for testing. The produced
% physical predictor always reconstructs captured event parameters.
S=AF7R58R75_SOURCE_CHECK();
P=DRONE_PARAM_SUSPENDED_LOAD('R75_TEST_GET_STRING_SCALAR');
Q=AF7R58R74R2_REBUILD_PARAMS(class(P), ...
    string(P.parameter_order(:)),double(P.parameter(:)), ...
    'R75_TEST_FROZEN_PARAMS');
names=string(Q.parameter_order(:)); vals=double(Q.parameter(:));
for nm=["loadmass","cableL"]
    j=find(strcmp(names,nm));
    assert(numel(j)==1,'[R75] requested external parameter absent.');
    a=double(Q.get(nm));
    assert(isscalar(a)&&isfinite(a)&&isequaln(a,vals(j)), ...
        '[R75] string-scalar parameter accessor returned wrong value.');
end
assert(S.char_vector_parameter_getter_replaced);
T=struct('status','PASS_R75_ACTUAL_PARAMETER_GETTER_STRING_SCALARS', ...
    'source_parser_pass',S.matlab_class_parser_passed, ...
    'parameter_getter_pass',true, ...
    'frozen_parameter_instance_pass',true, ...
    'physical_four_second_future_proved',false, ...
    'physical_trigger_replaced',false);
end
