function T=AF7R58R104_SELFTEST()
% Pure non-production regressions: phase lag, strict R103 trigger,
% absence of supplied physical forecast, dependency closure.
S=AF7R58R104_SOURCE_CHECK();
assert(startsWith(S.status,'PASS_R104_'), ...
    'R104:SourceCheck','R104 source dependencies or native hash unavailable.');
T0=19.75;unit=sqrt(2/9.81);
P=AF7R58R104_PHASE_SCHEDULE(T0,unit,24,[]);
assert(numel(P)==24 && ...
    all([P.duration_s]>0) && all([P.phase_advance_s]>0) && ...
    all([P.phase_delay_s]>=0) && ...
    all([P.phase_advance_s]<=[P.duration_s]) && ...
    any([P.phase_delay_s]>0), ...
    'R104:NaturalPhase','Maneuver time and phase progress must be decoupled.');
for k=1:numel(P)
    X=P(k);
    assert(abs(X.nominal_phase_time_s-(T0+X.duration_s-X.phase_delay_s)) < ...
        256*eps(max([1,abs(T0),abs(X.nominal_phase_time_s)])), ...
        'R104:PhaseAlgebra','Nominal phase must equal physical endpoint less lag.');
end
% The last schedule item intentionally has ratio=1, so it can have
% zero lag even when its physical maneuver time is >4 s.  Check existence
% of a longer-than-horizon maneuver WITH lag instead of incorrectly
% requiring the final enumerated item to be delayed.
longDuration=[P.duration_s]>4;
positiveLag=[P.phase_delay_s]>0;
assert(any(longDuration & positiveLag), ...
    'R104:HorizonMustNotCapManeuverTime', ...
    'At least one delayed maneuver must be longer than the 4 s sensing horizon.');
assert(any(longDuration & ~positiveLag), ...
    'R104:ZeroLagIsAllowed', ...
    'Zero-lag alternatives must remain possible beyond the sensing horizon.');
assert(P(end).duration_s>4 && P(end).phase_delay_s==0, ...
    'R104:FinalRatioIsNotDelayed', ...
    'The final phase fraction of 1 legitimately produces zero phase lag.');
% A small computational budget is NOT a physical maneuver-time cap:
% this call need not contain a >4 s maneuver, and must still be valid.
Psmall=AF7R58R104_PHASE_SCHEDULE(T0,unit,3,[]);
assert(numel(Psmall)==3 && all([Psmall.duration_s]<4) && ...
    [Psmall(end).phase_delay_s]==0 && any([Psmall.phase_delay_s]>0), ...
    'R104:BudgetIsNotPhysicalHorizon', ...
    'Enumeration length must not be mistaken for a maneuver-time limit.');
% A caller may explicitly select a phase fraction of 1 only.  Zero lag
% is a legitimate option; it must not trigger a spurious test failure.
Pzero=AF7R58R104_PHASE_SCHEDULE(T0,unit,4,1);
assert(numel(Pzero)==4 && all([Pzero.phase_delay_s]==0) && ...
    all([Pzero.phase_advance_s]==[Pzero.duration_s]), ...
    'R104:LegitimateZeroLagSearch', ...
    'A zero-lag-only phase schedule must be valid.');
% SOURCE-only, not a generated physical prediction.
F=struct('time_s',T0,'reference_version',3,'horizon_s',4, ...
    'dt_s',0.025,'cable_length_m',2,'pL_EKF',[0;0;0], ...
    'pQ_EKF',[0;0;2],'known_mask',true, ...
    'C',[4;0;0],'R',reshape(eye(3),9,1), ...
    'Araw',[1;1;1],'ids',4,'Dcomp',[0.1;0.1;0.1]);
N=round(F.horizon_s/F.dt_s)+1;
ref=struct('time_s',T0,'reference_version',3, ...
    'pL',repmat(F.pL_EKF,1,N),'pQ',repmat(F.pQ_EKF,1,N), ...
    'source','ACTIVE_REFERENCE_ONLY');
refGate=AF7R58R103_EKF_HLC_TRIGGER(F,ref);
assert(strcmp(refGate.status,'BLOCKED_NOT_PHYSICAL_HLC_PLANT')&& ...
    ~refGate.request, 'R104:ReferenceNotPhysical', ...
    'Reference-only future must not masquerade as an HLC rollout.');
ref.source='LIVE_EKF_HLC_PLANT_ROLLOUT';ref.reference_version=4;
stale=AF7R58R103_EKF_HLC_TRIGGER(F,ref);
assert(strcmp(stale.status,'BLOCKED_STALE_HLC_PREVIEW'), ...
    'R104:StalePreviewAccepted','Wrong-reference future was accepted.');
assert(~S.safe_to_commit&&~S.flight_trigger_switched&& ...
    ~S.flight_generator_switched, ...
    'R104:UnsafeImplicitInstall','Offline test cannot switch Flight behavior.');
T=struct('status','PASS_R104_NATURAL_PHASE_AND_DUAL_STAGE_REGRESSION', ...
    'phase_search_attempts',numel(P), ...
    'longer_than_4s_lagged_candidates',sum(longDuration & positiveLag), ...
    'longer_than_4s_zero_lag_candidates',sum(longDuration & ~positiveLag), ...
    'short_budget_regression_passed',true, ...
    'zero_lag_only_regression_passed',true, ...
    'positive_lag_options',sum([P.phase_delay_s]>0), ...
    'longest_test_maneuver_s',max([P.duration_s]), ...
    'horizon_not_maneuver_duration',true, ...
    'reference_future_rejected',true,'stale_forecast_rejected',true, ...
    'physical_preview_helper_present',S.native_preview_implementation_found, ...
    'live_flight_generator_replaced',false, ...
    'live_flight_trigger_replaced',false, ...
    'full_closed_loop_certificate_proved',false);
end
