function S=AF7R58R104_SOURCE_CHECK()
% Dependency and exact native-class binding, not a proof of Flight readiness.
base=fileparts(mfilename('fullpath'));
need={ ...
    'AF7R58R104_SOURCE_CHECK', ...
    'AF7R58R104_SELFTEST', ...
    'AF7R58R104_PHASE_SCHEDULE', ...
    'AF7R58R104_NATURAL_RETURN_SEARCH', ...
    'AF7R58R104_LIVE_EVENT_PACKET', ...
    'AF7R58R104_PHYSICAL_PREDICTOR', ...
    'AF7R58R104_DUAL_EVENT_REPLAY', ...
    'AF7R58R104_WRITE_REPORT', ...
    'AF7R58R103_SOURCE_CHECK', ...
    'AF7R58R103_FROM_R55_PACKET', ...
    'AF7R58R103_EKF_HLC_TRIGGER', ...
    'AF7R58R102_SOURCE_CHECK', ...
    'AF7R58R102_RUN_SAVED_ROUTE', ...
    'AF7R58R102_SEED_RECORD', ...
    'AF7R58R102_LIVE_INPUT_AUTHORITY', ...
    'AF7R58R88_SELECT_TIME', ...
    'AF7R58R88_NOMINAL_JETS' ...
    };
missing={};shadow={};
for k=1:numel(need)
    p=which(need{k});
    if isempty(p)
        missing{end+1}=need{k}; %#ok<AGROW>
    elseif ~strcmpi(fileparts(p),base)
        shadow{end+1}=sprintf('%s -> %s',need{k},p); %#ok<AGROW>
    end
end
original=AF7R58R103_SOURCE_CHECK();
upstream=AF7R58R102_SOURCE_CHECK();
methodFound=false;
if isfile(which('REPLANNING_SYSTEM'))
    source=fileread(which('REPLANNING_SYSTEM'));
    methodFound=contains(source,'function R = r71_predict_live_hlc_future(obj,tglobal)');
end
helperFound=(exist('AF7R58R71_EXACT_HLC_PLANT_PREVIEW','file')==2);
S=struct('status','PASS_R104_SOURCE_AND_DUAL_EVENT_CONNECTORS__PREVIEW_OPEN', ...
    'missing_dependencies',{missing},'shadowed_dependencies',{shadow}, ...
    'native_class_pinned',logical(original.native_atomic_source_pinned), ...
    'native_preview_method_found',methodFound, ...
    'native_preview_implementation_found',helperFound, ...
    'physical_predictor_source_bound',methodFound&&helperFound, ...
    'complete_closed_loop_certificate',false, ...
    'generator_full_production_certified',false, ...
    'production_modified',false,'flight_trigger_switched',false, ...
    'flight_generator_switched',false, ...
    'safe_to_commit',false);
if ~isempty(missing)||~isempty(shadow)||~original.native_atomic_source_pinned|| ...
        ~strcmp(char(upstream.status),'PASS_R102_SOURCE_DEPENDENCIES')
    S.status='BLOCKED_MISSING_SHADOWED_OR_CHANGED_NATIVE_SOURCE';
elseif helperFound
    S.status='PASS_R104_SOURCE_AND_PREVIEW_ENTRY__PROOF_STILL_OPEN';
end
end
