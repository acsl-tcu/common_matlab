    'nv=double(af7r36_single_core_mex(2,packet,tglobal));', ...
    'correction7=double(af7r36_single_core_mex(25,packet,tglobal));', ...
    'F(:,8)=nominal7+correction7;', ...
    "status='R86_NATIVE_ACTIVE_MISMATCH__FAIL_CLOSED';", ...
    'if isfield(M,''phase_layers'')&&~isempty(M.phase_layers)', ...
    'A=obj.r63_live_c7_authority(tglobal);', ...
    'A=obj.r86_live_serialized_c7_authority(double(tglobal));', ...
    'A.r86_serialized_jet7_used=false;', ...
    '''production_commit_authorized'',false'};
for k=1:numel(requirements)
    assert(contains(Z,requirements{k}), ...
        'R86:MissingRequiredGuard: %d',k);
end
assert(~contains(Z,'R86_ALLOW_UNCERTIFIED_COMMIT'), ...
    'R86:ForbiddenCommitBypass');
T=struct('status','PASS_R86_SOURCE_INTEGRITY_AND_FAIL_CLOSED_JET_ADAPTER', ...
    'source_bound',true, ...
    'native_order_0_to_6_used',true, ...
    'native_correction_order_7_used',true, ...
    'source_specific_identity_phase_only',true, ...
    'phase_retimming_unchanged',true, ...
    'live_matlab_native_comparison_performed',false, ...
    'initial_avoidance_generator_changed',false, ...
    'continuous_closed_loop_safety_proved',false);
end
