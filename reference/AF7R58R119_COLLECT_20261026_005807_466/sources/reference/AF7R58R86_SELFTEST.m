function T=AF7R58R86_SELFTEST()
% Source-bound pre-install test. MATLAB SimHL and actual Flight are NOT run.
S=AF7R58R86_SOURCE_CHECK();
assert(strcmp(S.status,'PASS_R86_NATIVE_C7_SOURCE_BOUND'), ...
    'R86:SourceCheckFailed');
