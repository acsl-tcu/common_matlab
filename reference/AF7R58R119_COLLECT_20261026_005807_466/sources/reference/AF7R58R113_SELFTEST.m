function T=AF7R58R113_SELFTEST()
% Exactly dyadic straight-line C7 fixture (avoids spurious 7th-jet roundoff).
% Synthetic physical geometry. Demonstrates that a path rejected by a
% whole L-inflated payload BALL can safely fit beside an obstacle once
% UAV/payload spheres and the entire cable are separated individually.
L=2;g=9.81;rQ=0.12;rL=0.11;rC=0.03; margin=0.02;
S=struct('segments',repmat(struct('t0',0,'t1',0,'payload_cp', ...
 zeros(3,16),'trajectory_frame','HLC_PAYLOAD_WORLD'),1,2));
for k=1:2
 S.segments(k).t0=2*(k-1);S.segments(k).t1=2*k;
 P=zeros(3,16);P(2,:)=(k-1)*(15/16)+(0:15)/16;
 S.segments(k).payload_cp=P;
end
o=struct('center',[1.5;0.75;1], ...
 'R',eye(3),'axes',[0.3;0.3;0.3]);
live=struct('gravity_m_s2',g,'cable_length_m',L, ...
 'rQ_m',rQ,'rL_m',rL,'rC_m',rC,'d_margin_m',margin, ...
 'finite_sensing_vQ_limit_m_s',3.2, ...
 'robust_tracking_margin_enabled',false);
opts=struct('max_nodes_per_check',128);
A=AF7R58R113_SEPARATE_SWEPT_CORRIDORS(S,o,live,opts);
assert(A.reference_geometry_certified&&A.continuous_time&& ...
 ~A.whole_body_ball_used && A.production_commit_authorized==false, ...
 'R113:ReferenceFixture','Three-body exact sweep unexpectedly fails.');
assert(A.minimum_margin_m>0&&A.numeric_c7_seams_verified&& ...
 A.max_c7_seam_residual<1e-10, ...
 'R113:StrictSeparation', ...
 'Fixture sweep: status=%s, clearance=%.16g m, C7 residual=%.16g, nodes=%d.', ...
 A.status,A.minimum_margin_m,A.max_c7_seam_residual,A.nodes);
% R90 integration: actual nominal thrust/tension checks on the SAME route.
% Synthetic masses and actuator limits are TEST FIXTURES ONLY, never defaults
% applied to production or live Flight.
Ginput=live;
Ginput.vehicle_mass_kg=0.762;
Ginput.latest_EKF_mL_kg=0.0194;
Ginput.thrust_bounds_N=[0 20];
Ginput.torque_bounds_Nm=[-1 1;-1 1;-1 1];
Ginput.tension_max_N=1;
Q=AF7R58R113_INPUT_GATES(S,Ginput,opts);
assert(Q.nominal_thrust_tension_strength_pass && ...
    Q.nominal_thrust_upper_N<20 && ...
    ~Q.nominal_torque_certified && ...
    ~Q.production_commit_authorized, ...
    'R113 test: R90 nominal thrust/tension must pass; HLC torque must remain open.');
noRating=rmfield(Ginput,'tension_max_N');
X=AF7R58R113_INPUT_GATES(S,noRating,opts);
assert(~X.nominal_thrust_tension_strength_pass && ...
    X.nominal_thrust_certified && ~X.cable_strength_certified, ...
    'R113 test: cable rating cannot be inferred.');
missingAuthority=rmfield(Ginput,'torque_bounds_Nm');
Y=AF7R58R113_INPUT_GATES(S,missingAuthority,opts);
assert(~Y.nominal_thrust_tension_strength_pass && ...
    ~isempty(Y.missing_authorities), ...
    'R113 test: missing torque clamp authority must not be invented.');
lowThrust=Ginput;lowThrust.thrust_bounds_N=[0 2];
Z=AF7R58R113_INPUT_GATES(S,lowThrust,opts);
assert(~Z.nominal_thrust_tension_strength_pass && ...
    ~Z.production_commit_authorized, ...
    'R113 test: thrust bound violation must reject.');
% A disconnected payload path must NOT obtain a full-interval certificate.
Sbad=S;Sbad.segments(2).payload_cp(2,:)= ...
 Sbad.segments(2).payload_cp(2,:)+0.25;
J=AF7R58R113_SEPARATE_SWEPT_CORRIDORS(Sbad,o,live,opts);
assert(~J.reference_geometry_certified&& ...
 strcmp(J.status,'INCONCLUSIVE_C7_SEAM_MISMATCH'), ...
 'R113 failure - DisconnectedC7MustReject');
% Whole L ball fails: horizontal x distance 1.5 < 0.3+2+0.12+margin.
oldBigBallPass=(1.5 > (0.3+L+rQ+margin));
assert(~oldBigBallPass,'R113 failure - ExpectedConservatism');
% Multiple differently-oriented ellipsoids use exact support.
ang=0.37;rot=[cos(ang),-sin(ang),0;sin(ang),cos(ang),0;0,0,1];
o3=o;o3.center=[-1.5;1.2;1];o3.axes=[0.4;0.2;0.3];o3.R=rot;
M=AF7R58R113_SEPARATE_SWEPT_CORRIDORS(S,[o,o3],live,opts);
assert(M.reference_geometry_certified&&M.known_obstacle_count==2, ...
 'R113 failure - MultiOrientedEllipsoids');
% Geometrically COLLIDING obstacle must never receive geometry PASS.
o2=o;o2.center=[0.05;0.75;1];
B=AF7R58R113_SEPARATE_SWEPT_CORRIDORS(S,o2,live, ...
 struct('max_nodes_per_check',32));
assert(~B.reference_geometry_certified && ...
 ~B.production_commit_authorized,'R113 failure - CollisionFixture');
% Robust inflation ON without an authoritative tube must be rejected.
missingTube=live;missingTube.robust_tracking_margin_enabled=true;
rejectMissingTube=false;
try
 AF7R58R113_SEPARATE_SWEPT_CORRIDORS(S,o,missingTube,opts);
catch ME
 rejectMissingTube=strcmp(ME.identifier,'R113:MissingCertifiedTube');
end
assert(rejectMissingTube,'R113 failure - TubeAuthority');
% Supplying an actually larger tube must not accidentally improve clearance.
robust=live;robust.robust_tracking_margin_enabled=true;
robust.tracking_tube_m=0.2;
C=AF7R58R113_SEPARATE_SWEPT_CORRIDORS(S,o,robust,opts);
assert(C.reference_geometry_certified && ...
 C.minimum_margin_m<A.minimum_margin_m, ...
 'R113 failure - MonotoneInflation');
% Every accepted leaf is time continuous, with independently chosen planes.
for j=1:numel(A.cells)
 cellj=A.cells(j);
 assert(all(cellj.margin_Q_m>0)&&all(cellj.margin_L_m>0)&& ...
 all(cellj.margin_C_m>0) && ...
 isequal(size(cellj.normal_Q),[3 1]),'R113 failure - BadLeaf');
end
r92Tested=false;
% A true C7 payload route is generated from explicitly provided endpoint
% jets using the EXISTING R92 solver, not R112 and not a frozen test path.
if exist('AF7R58R92_C7_MINIMUM8_ROUTE','file')==2
 J0=zeros(3,8);J0(2,2)=0.5;
 J1=J0;J0(2,1)=0;J1(2,1)=2;
 spec=struct('times_s',[0 2 4], ...
  'waypoints',[0 0 0;0 1 2;0 0 0], ...
  'start_jets',J0,'end_jets',J1,'phase_delay_s',1);
 R=AF7R58R92_C7_MINIMUM8_ROUTE(spec.times_s,spec.waypoints, ...
    spec.start_jets,spec.end_jets,spec.phase_delay_s,L);
 assert(R.reference_candidate_found&&R.max_jet_residual<1e-6, ...
    'R113 failure - ExistingRealC7Generator');
 r92Tested=true;
 % IMPORTANT: the full heuristic corridor/waypoint search is NOT a selftest
 % invariant: it may fail to find a feasible candidate for a fixed work budget.
 % Test it separately against actual live Flight data; this short selftest
 % checks the R92 C7 route construction and the independent safety gates.

end
T=struct('status','PASS_R113_DYADIC_C7_GEOMETRY_AND_R90_INPUT_FIXTURES', ...
 'separate_geometry_pass',A.reference_geometry_certified, ...
 'old_whole_body_ball_rejected',~oldBigBallPass, ...
 'colliding_ellipsoid_rejected',~B.reference_geometry_certified, ...
 'robust_tube_authority_failclosed',rejectMissingTube, ...
 'minimum_reference_margin_m',A.minimum_margin_m, ...
 'input_nominal_thrust_upper_N',Q.nominal_thrust_upper_N, ...
 'input_nominal_tension_upper_N',Q.nominal_tension_upper_N, ...
 'r90_input_fixture_pass',Q.nominal_thrust_tension_strength_pass, ...
 'missing_cable_rating_rejected',~X.cable_strength_certified, ...
 'missing_torque_authority_rejected',~isempty(Y.missing_authorities), ...
 'thrust_limit_violation_rejected',~Z.nominal_thrust_tension_strength_pass, ...
 'certified_leaf_count',A.leaves, ...
 'r92_c7_generator_exercised',r92Tested, ...
 'heuristic_search_exercised',false, ...
 'real_flight_exercised',false,'production_modified',false);
end
