function T=AF7R58R100_SELFTEST()
% Verify the ACTUAL optimizer and the full function resolution contract.
S=AF7R58R100_SOURCE_CHECK();
assert(strcmp(S.status,'PASS_R100_ALL_RUNTIME_DEPENDENCIES'), ...
 'R100:BadFunctionDependency','Source binding failed.');
g=9.81;L=2;vmax=4;times=[0 4 8];
W=[0 2 4;0 1 0;0 0 0];
J0=zeros(3,8);J1=zeros(3,8);
J0(:,1)=W(:,1);J1(:,1)=W(:,end);
J0(:,2)=[.5;0;0];J1(:,2)=[.5;0;0];
opts=struct('max_internal_velocity_trials',9, ...
 'velocity_objective_samples_per_segment',13,'max_retime_trials',2);
base=AF7R58R96_C7_KNOT_SPEED_ROUTE(times,W,J0,J1,0,L,g,vmax);
assert(base.reference_candidate_found && base.knot_speed_necessary_pass, ...
 'R100:BaselineSample','Baseline C7 route should be constructible.');
P=AF7R58R100_C7_INTERIOR_SPEED_AWARE(times,W,J0,J1,0,L,g,vmax,opts);
assert(P.reference_candidate_found&&P.knot_speed_necessary_pass&& ...
 P.interior_peak_sample_m_s<=P.interior_peak_baseline_sample_m_s+1e-10&& ...
 ~P.production_commit_authorized&&~P.interior_peak_samples_are_safety_proof, ...
 'R100:InteriorSpeedObjective','Generator failed the non-worsening speed objective or fail-closed contract.');
K=AF7R58R96_KNOT_VQ_SCREEN(P,g,L,vmax);
assert(K.necessary_speed_pass,'R100:KnotSpeed','Internal knot velocity proof obligation failed.');
assert(isfinite(P.max_jet_residual) && P.max_jet_residual<1e-4, ...
 'R100:NumericalC7Continuity','Reconstructed C7 endpoint jets inconsistent.');
A=AF7R58R100_CO_DESIGN_TIMES(W,0,8,J0,J1,0,L,g,vmax,opts);
assert(A.feasible_necessary_time&&all(diff(A.times_s)>0)&& ...
 ~A.production_commit_authorized&& ...
 A.estimated_peak_after_m_s<=A.estimated_peak_before_m_s+1e-10, ...
 'R100:KnotTimeCoDesign','Time co-design violated the non-worsening objective or necessary reachability.');
T=struct('status','PASS_R100_NUMERIC_JET_AND_KNOT_TIME_GENERATION', ...
 'sections',P.num_segments, ...
 'baseline_sample_peak_m_s',P.interior_peak_baseline_sample_m_s, ...
 'chosen_sample_peak_m_s',P.interior_peak_sample_m_s, ...
 'numeric_0_to_7_endpoint_residual',P.max_jet_residual, ...
 'retiming_trials',A.retime_trials, ...
 'time_design_peak_before_m_s',A.estimated_peak_before_m_s, ...
 'time_design_peak_after_m_s',A.estimated_peak_after_m_s, ...
 'source_dependencies_complete',true, ...
 'real_snapshot_exercised',false, ...
 'sampled_speed_is_continuous_time_proof',false, ...
 'whole_body_or_closed_loop_proved',false, ...
 'production_modified',false,'trigger_switched',false);
end
