function D = AF7R58R116_POSTFLIGHT_AUDIT(P)
% AFTER-FLIGHT ONLY: read the existing R115 trigger/generator/commit state.
% No modifications to REPLANNING_SYSTEM, HLC, plant, MEX or simulator.
% Output is written beside THIS audit file, never to the project main root.
% Usage after simulation (same MATLAB process):
%   D = AF7R58R116_POSTFLIGHT_AUDIT();
% or:
%   D = AF7R58R116_POSTFLIGHT_AUDIT(replannerHandle);
%
% An earlier process's run cannot be reconstructed from a new handle.
if nargin < 1 || isempty(P)
    key = 'AF7R58R71R2_ACTIVE_REPLANNER';
    assert(isappdata(0,key), 'R116:NoLiveReplanner', ...
        ['The postflight REPLANNING_SYSTEM handle is unavailable in this ' ...
         'MATLAB process. Pass the original replanner handle or send ' ...
         'the existing saved Flight MAT data. Do not re-run just for this audit.']);
    P = getappdata(0,key);
end
assert(isa(P,'REPLANNING_SYSTEM') && isscalar(P), ...
    'R116:InvalidReplanner', 'Supply the original postflight R115 replanner handle.');

D = struct();
D.schema = 'AF7R58R116_POSTFLIGHT_READ_ONLY_V1';
D.timestamp = datestr(now, 'yyyy-mm-dd HH:MM:SS');
D.note = ['Postflight observed state only; not a physical preview, ' ...
    'continuity proof, or execution safety certificate.'];
D.file_authority = struct( ...
    'replanner_all',{which('REPLANNING_SYSTEM','-all')}, ...
    'single_core_mex_all',{which('af7r36_single_core_mex','-all')}, ...
    'physical_helper',which('AF7R58R71_EXACT_HLC_PLANT_PREVIEW'), ...
    'reference_adjust',which('SUSPENDED_LOAD_REF_ADJUST'));

D.pipeline = P.get_staged_pipeline_status();
D.last_replan = P.get_last_replan_status();
D.certificate = P.get_runtime_certificate_status();
D.avoidance = P.get_avoidance_mode_status();
D.sensor_memory = P.get_simulated_sensor_memory_status();
D.first_trigger = P.get_first_trigger_event();
D.last_trigger = P.get_last_trigger_event();

names = { ...
    'active_reference_mode','active_reference_version', ...
    'trigger_dist','horizon_s','prediction_dt', ...
    'r108_dual_engine_armed','r108_keep_postflight_event_copies', ...
    'r63_now_unsafe','r63_now_hit_cumulative', ...
    'r63_now_event_count','r63_now_event_ring', ...
    'r63_now_last_time_s','r63_now_known_count', ...
    'r64_no_safe_lead','r64_now_request_count','r64_abort_staged_count', ...
    'staged_replan_state','staged_replan_last_reason', ...
    'staged_replan_stage1_count','staged_replan_stage2_count', ...
    'staged_replan_commit_count','staged_replan_fail_count', ...
    'staged_replan_last_candidate_family', ...
    'reference_only_commit_count','execution_aware_commit_count', ...
    'R26_SIMULATION_ONLY_EXPERIMENT','r26_sim_commit_attempted', ...
    'r26_sim_commit_succeeded','generator_backend_locked_name', ...
    'generator_backend_selection_locked','r47_event_ring', ...
    'r47_event_ring_count','r47_event_ring_head', ...
    'r67_seam_ring','r67_seam_count', ...
    'r68_seam_detail_ring','r68_seam_detail_count', ...
    'r88_capture_enabled','r88_capture_failure_count', ...
    'r73_capture_error_count','r73_last_capture_error_message'};
D.live = struct();
for k = 1:numel(names)
    key = names{k};
    if isprop(P,key)
        val = P.(key);
        if isnumeric(val) || islogical(val) || ischar(val) || isstring(val)
            D.live.(key) = val;
        end
    end
end
% Save published postflight diagnostic numeric packets, if available.
D.published_capture_present = isappdata(0,'AF7R58R17_LAST_CAPTURE');
D.published = struct();
if D.published_capture_present
    Z = getappdata(0,'AF7R58R17_LAST_CAPTURE');
    if isstruct(Z) && isscalar(Z)
        keys = {'schema','events','native_connected','native_success', ...
            'native_family','native_speed_pass','native_heading_pass', ...
            'native_geometry_pass','commit_attempted','activation_confirmed', ...
            'r21_active_base_stage1_requests','r21_active_base_native_returns', ...
            'r54_stage_ring','r54_stage_ring_count','r54_stage_ring_head', ...
            'r55_trigger_ring','r55_trigger_ring_count', ...
            'r55_trigger_ring_head','r55_trigger_packets', ...
            'r63_now_event_ring','r63_now_event_count', ...
            'r63_now_hit_count','r64_now_request_count', ...
            'r64_abort_staged_count','r67_seam_ring','r68_seam_detail_ring'};
        for k = 1:numel(keys)
            key = keys{k};
            if isfield(Z,key)
                D.published.(key) = Z.(key);
            end
        end
    end
end

outDir = fileparts(mfilename('fullpath'));
assert(~isempty(outDir), 'R116:SourcePathUnavailable', ...
    'The audit function must be run from its own .m source file.');
fileName = ['AF7R58R116_POSTFLIGHT_' datestr(now,'yyyymmdd_HHMMSS_FFF') '.mat'];
outFile = fullfile(outDir,fileName);
save(outFile,'D','-v7.3');

fprintf('\n[R116] Read-only postflight audit saved: %s\n',outFile);
fprintf('[R116] source: %s\n',which('REPLANNING_SYSTEM'));
fprintf('[R116] R108 dual engines armed: %d\n',logical(P.r108_dual_engine_armed));
fprintf('[R116] active: mode=%s version=%g; policy=%s\n', ...
    char(P.active_reference_mode),double(P.active_reference_version), ...
    char(P.AVOIDANCE_COMMIT_POLICY));
fprintf('[R116] stage counts: S1=%g S2=%g commit=%g fail=%g\n', ...
    double(P.staged_replan_stage1_count),double(P.staged_replan_stage2_count), ...
    double(P.staged_replan_commit_count),double(P.staged_replan_fail_count));
fprintf('[R116] commit levels: REFERENCE_ONLY=%g EXECUTION_AWARE=%g\n', ...
    double(P.reference_only_commit_count),double(P.execution_aware_commit_count));
fprintf('[R116] candidate family: %s; last pipeline reason: %s\n', ...
    char(P.staged_replan_last_candidate_family),char(P.staged_replan_last_reason));
fprintf('[R116] EKF-now hits=%g, protective requests=%g, stage aborts=%g\n', ...
    double(P.r63_now_hit_cumulative),double(P.r64_now_request_count), ...
    double(P.r64_abort_staged_count));
fprintf('[R116] saved snapshot is NOT proof of actual safe flight.\n\n');
end
