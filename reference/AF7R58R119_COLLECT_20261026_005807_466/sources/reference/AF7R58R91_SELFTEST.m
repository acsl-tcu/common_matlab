function T=AF7R58R91_SELFTEST()
% Runs against the EXACT new implementation (under its temporary function name)
% before installer writes the historical R89 entrypoint.
g=9.81; L=2; lim=3.10559006211;
% Normal straight translation must be certified.
P=zeros(3,16);P(2,:)=linspace(0,1,16);
a=AF7R58R91_STABLE_KINEMATIC_CERT(mk(P,1,19.75),g,L,lim,512);
assert(a.certified&&a.uav_speed_upper_m_s<lim&& ...
       a.ieee754_outward_closed==false,'R91:LinearFalseFail');
% Positive tilted specific force: g-||a|| bound was too conservative.
P=zeros(3,16);h=0.1;acc=11;
for j=0:15
 P(1,j+1)=0.5*acc*h^2*j*(j-1)/(15*14);
end
b=AF7R58R91_STABLE_KINEMATIC_CERT(mk(P,h,19.75),g,L,lim,512);
assert(b.certified&&b.specific_force_lower_m_s2>0, ...
       'R91:TiltedFalseFail');
% Real endpoint speed violation must be rejected before any recursion.
P=zeros(3,16);P(1,:)=linspace(0,5,16);
c=AF7R58R91_STABLE_KINEMATIC_CERT(mk(P,1,19.75),g,L,lim,512);
assert(~c.certified&&strcmp(c.status, ...
       'NECESSARY_START_SPEED_LIMIT_VIOLATED'), 'R91:EndpointOverSpeed');
% Zero-specific-force degeneracy must be rejected.
P=zeros(3,16);
for j=0:15
 P(3,j+1)=-0.5*g*h^2*j*(j-1)/(15*14);
end
d=AF7R58R91_STABLE_KINEMATIC_CERT(mk(P,h,19.75),g,L,lim,512);
assert(~d.certified,'R91:ZeroSpecificForceAccepted');
% Interior-only large velocity; endpoints are zero and must not disguise it.
P=zeros(3,16);P(1,7:10)=[0 6 6 0];
e=AF7R58R91_STABLE_KINEMATIC_CERT(mk(P,1,19.75),g,L,lim,512);
assert(~e.certified,'R91:InteriorOverSpeedAccepted');
% Strict finite work budget; unconcluded never promoted to certificate.
f=AF7R58R91_STABLE_KINEMATIC_CERT(mk(P,1,19.75),g,L,lim,1);
assert(~f.certified&&(~isempty(strfind(f.status,'WORK_BUDGET')) || ...
  ~isempty(strfind(f.status,'VIOLATION'))), 'R91:BudgetBypass');
% Source uses derivative-CP subdivision, not leaf position differences
% or times which have lost representable midpoint resolution.
s=fileread(fullfile(fileparts(mfilename('fullpath')), ...
    'AF7R58R91_STABLE_KINEMATIC_CERT.m'));
assert(contains(s,'split_half(Z.V)')&& ...
    contains(s,'split_half(Z.A)')&&contains(s,'split_half(Z.J)')&& ...
    contains(s,'split_half(Z.S)')&& ...
    ~contains(s,'diff(Z.cp'), 'R91:LeafDifferenceRegression');
T=struct('status','PASS_R91_STABLE_NORMALIZED_DERIVATIVE_CP', ...
 'straight_reference_certified',a.certified, ...
 'tilted_specific_force_certified',b.certified, ...
 'real_endpoint_speed_rejected',~c.certified, ...
 'specific_force_zero_rejected',~d.certified, ...
 'interior_speed_excess_not_accepted',~e.certified, ...
 'finite_work_budget_fail_closed',~f.certified, ...
 'normalized_derivative_CP_method',true, ...
 'matlab_live_R88_replay_performed',false, ...
 'ieee_rounding_proof',false, ...
 'thrust_torque_tension_closed_loop_certified',false, ...
 'production_changed',false);
end
function C=mk(P,T,t0)
C=struct('payload_cp',P,'t0',t0,'t1',t0+T,'duration_s',T);
end
