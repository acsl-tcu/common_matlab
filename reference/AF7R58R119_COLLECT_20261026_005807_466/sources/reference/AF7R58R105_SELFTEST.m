function T=AF7R58R105_SELFTEST()
S=AF7R58R105_SOURCE_CHECK();
assert(startsWith(S.status,'PASS_R105_'), ...
    'R105:SourceDependencies','R104/R105 source dependencies not resolved.');
% Two C7 segments with a shared exact linear x velocity and a delayed
% nominal constant-velocity continuation. Checks 0..7 jets on both seams.
t0=2;ts=[2 3 4];x0=0;speed=15/16;
J=zeros(3,8,3);
for k=1:3
    J(1,1,k)=x0+speed*(ts(k)-t0);
    J(1,2,k)=speed;
end
P=zeros(3,16);
seg=repmat(struct('payload_cp',P,'duration_s',1),1,2);
for k=1:2
    for j=0:15
        seg(k).payload_cp(1,j+1)=J(1,1,k)+j/16;
    end
end
R=struct('num_segments',2,'segments',seg,'times_s',ts, ...
    'phase_delay_s',2,'knot_jets',J);
f=cell(1,8);
f{1}=@(t)[speed*t;0;2];
f{2}=@(t)[speed;0;0];
for k=3:8,f{k}=@(t)[0;0;0];end
Psrc=struct('nominal_derivative_fns',{f}, ...
    'flight_reference_time_origin',0,'nominal_table_tend',6, ...
    'cable_length_m',2);
Seam=AF7R58R105_C7_SEAM_AUDIT(R,Psrc);
assert(Seam.finite_nominal_source_matches_last_stored_knot && ...
    Seam.max_abs_jet_residual<1e-7, ...
    'R105:C7SeamRegression','All sections and phase continuation must agree.');
[J1,D1]=AF7R58R105_C7_TAIL_EVAL(R,Psrc,ts(2));
[J2,D2]=AF7R58R105_C7_TAIL_EVAL(R,Psrc,ts(end));
[J3,D3]=AF7R58R105_C7_TAIL_EVAL(R,Psrc,5);
[~,D4]=AF7R58R105_C7_TAIL_EVAL(R,Psrc,8.1);
assert(max(abs(J1-J(:,:,2)),[],'all')<1e-7 && ...
    max(abs(J2-J(:,:,3)),[],'all')<1e-7 && ...
    abs(J3(1,1)-3*speed)<1e-10 && ...
    D1.heading_nondegenerate_numeric && ...
    D2.heading_nondegenerate_numeric && ...
    strcmp(D3.part,'DELAYED_NOMINAL') && ...
    ~D4.inside_finite_source_domain && ...
    ~D3.production_commit_authorized, ...
    'R105:FiniteC7TailSemantics','C7 tail/seam regression failed.');
Rbad=R;Rbad.knot_jets(1,2,end)=2;
Bad=AF7R58R105_C7_SEAM_AUDIT(Rbad,Psrc);
assert(~Bad.finite_nominal_source_matches_last_stored_knot && ...
    strcmp(Bad.status,'DISCONTINUOUS_SOURCE_VS_TERMINAL_KNOT'), ...
    'R105:StalePhaseMismatchTest','Incorrect terminal jet must fail.');
% A cable strength rating is NEVER manufactured from nominal tension.
A=struct('partial_reference_found',false,'best_partial',struct([]), ...
    'reference_version',3,'snapshot_time_s',t0);
G=AF7R58R105_CLOSE_PARTIAL([],A,struct('max_nodes_per_check',64));
assert(strcmp(G.status,'R104_PARTIAL_NOT_AVAILABLE')&& ...
    ~G.production_commit_authorized, ...
    'R105:NoPartialMustFailClosed','Missing candidate was accepted.');
% Full source-bound event retrieval must survive absent R55 capture,
% accept an exact R71R2 EKF event, and NEVER synthesize a missing EKF frame
% from the reference-only R88 immutable snapshot.
te=19.75;ver=3;
Q=struct('C',[3;0;0],'R',reshape(eye(3),9,1), ...
    'Araw',[1;1;1],'ids',7, ...
    'delta_payload_m',0,'delta_uav_m',0,'delta_cable_m',0);
Z=struct('time_s',te,'reference_version',ver,'known_mask',true, ...
    'obstacle_packet',Q,'estimated_mass_kg',0.02, ...
    'rL_m',0.2,'rQ_m',0.15,'rC_m',0.1,'d_margin_m',0.05, ...
    'cable_length_m',2,'horizon_s',4,'prediction_dt_s',0.025);
Owner=struct('r88_snapshots',Z);
[F0,D0]=AF7R58R105_SOURCE_EVENT(Owner,te,ver);
assert(isempty(F0)&&~D0.ekf_frame_authenticated && ...
    strcmp(D0.r55_status,'R55_CAPTURE_PROPERTIES_NOT_ON_LIVE_OBJECT'), ...
    'R105:MissingEKF','R88 reference snapshot was incorrectly promoted to EKF.');
% Same 24-state field order as the live R71R2 captured source:
% [p;q;v;w;pL;vL;pT;wL]. Cable direction pT is x(19:21).
x=zeros(24,1);x(1:3)=[0;0;2];x(4:6)=[0;0;0.4];
x(13:15)=[0;0;0];x(19:21)=[0;0;-1];
Event=struct('time_s',te,'reference_version',ver,'state_x24',x, ...
    'r76_known_mask',true,'r76_packet',Q, ...
    'r76_radii_m',[0.2;0.15;0.1], ...
    'r76_d_margin_m',0.05,'horizon_s',4, ...
    'prediction_dt',0.025,'cable_length_m',2);
Owner.r71r2_event_snapshots=Event;
[F1,D1]=AF7R58R105_SOURCE_EVENT(Owner,te,ver);
assert(D1.ekf_frame_authenticated&& ...
    strcmp(D1.source,'R71R2_FULL_EKF_SAVED_EVENT')&& ...
    isequal(F1.pQ_EKF,[0;0;2])&& ...
    isequal(F1.pL_EKF,[0;0;0])&& ...
    norm(F1.Dcomp-[0.25;0.2;0.15],inf)<= ...
        16*eps(max(1,max(abs(F1.Dcomp))))&& ...
    ~D1.hlc_physical_future_proved, ...
    'R105:R71R2Event', ...
    'Exact R71R2 extraction failed: status=%s r71=%s id=%s detail=%s', ...
    D1.status,D1.r71r2_status,D1.error_identifier,D1.error_message);
% Bad physical cable pT must be rejected even if unrelated attitude q
% remains smooth. Test specifically against the earlier wrong q indexing.
Owner.r71r2_event_snapshots.state_x24(4:6)=[0;0;-1];
Owner.r71r2_event_snapshots.state_x24(19:21)=[1;0;0];
[Fq,Dq]=AF7R58R105_SOURCE_EVENT(Owner,te,ver);
assert(isempty(Fq)&&~Dq.ekf_frame_authenticated&& ...
    strcmp(Dq.r71r2_status,'R71R2_EKF_CABLE_DIRECTION_INCONSISTENT'), ...
    'R105:IncorrectQRejected', ...
    'Incorrect q index passed or failed for the wrong reason: %s', ...
    Dq.r71r2_status);
Owner.r71r2_event_snapshots.state_x24=x;
Owner.r71r2_event_snapshots.r76_known_mask=false;
[Fbad,Dbad]=AF7R58R105_SOURCE_EVENT(Owner,te,ver);
assert(isempty(Fbad)&&~Dbad.ekf_frame_authenticated, ...
    'R105:SensorKnownMismatch','An unknown/sensed mismatch was accepted.');
Owner.r71r2_event_snapshots=struct([]);
LA=struct('time_s',te,'reference_version',ver,'valid',true, ...
    'current_ekf_pL',[0;0;0],'current_ekf_pQ',[0;0;2], ...
    'current_ekf_q',[0;0;-1], ...
    'sensor_known_count',1,'estimated_mass_kg',0.02);
Owner.r63_live_authority=LA;
[F2,D2]=AF7R58R105_SOURCE_EVENT(Owner,te,ver);
assert(D2.ekf_frame_authenticated&& ...
    strcmp(D2.source,'R63_EKF_AND_R88_SAME_TICK')&& ...
    isequal(F2.known_mask,true)&& ...
    ~D2.hlc_physical_future_proved, ...
    'R105:R63R88SameTick','Exact R63/R88 event association failed.');
Owner.r63_live_authority=struct([]);
P=struct('pL_EKF',[0;0;0],'pQ_EKF',[0;0;2], ...
    'active',true,'centers',Q.C,'rotations',Q.R, ...
    'axes',Q.Araw,'ids',Q.ids,'radii',[0.2+0.05;0.15+0.05;0.1+0.05], ...
    'H',4,'dt',0.025,'L',2);
Owner.r55_trigger_ring=nan(2,29);
Owner.r55_trigger_ring(1,1:2)=[te,ver];
Owner.r55_trigger_packets={P;[]};
Owner.r55_trigger_ring_count=1;
[F3,D3]=AF7R58R105_SOURCE_EVENT(Owner,te,ver);
assert(D3.ekf_frame_authenticated&& ...
    strcmp(D3.source,'R55_EXACT_EKF_PACKET')&& ...
    isequal(F3.pQ_EKF,[0;0;2]), ...
    'R105:R55Direct','Exact R55 packet regression failed.');
[F4,D4]=AF7R58R105_SOURCE_EVENT(Owner,te,ver+1);
assert(isempty(F4)&&~D4.ekf_frame_authenticated, ...
    'R105:StaleVersion','A different reference version was accepted.');
T=struct('status','PASS_R105_FINITE_NATURAL_TAIL_AND_PARTIAL_GATE', ...
    'event_source_fallback_regressions_pass',true, ...
    'r55_absence_no_crash',true, ...
    'r71r2_ekf_frame_tested',true, ...
    'r71r2_physical_pT_index_19_to_21_regression_pass',true, ...
    'floating_point_compensated_radii_comparison_pass',true, ...
    'r63_r88_same_tick_tested',true, ...
    'unknown_mismatch_rejected',true, ...
    'no_historical_hlc_future_fabricated',true, ...
    'source_dependencies_complete',true, ...
    'connector_seams_tested',2, ...
    'highest_jet_order_tested',7, ...
    'delayed_nominal_phase_tested',true, ...
    'tail_source_expiration_enforced',true, ...
    'fake_cable_rating_introduced',false, ...
    'real_flight_snapshot_tested',false, ...
    'real_hlc_future_tested',false, ...
    'whole_body_closed_loop_certified',false, ...
    'production_modified',false);
end
