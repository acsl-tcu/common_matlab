function fname=AF7R58R102_WRITE_REPORT(A)
% Offline report beside source; never in Flight's 25-ms control loop.
assert(isstruct(A)&&isscalar(A)&&isfield(A,'seed_log'), ...
 'R99:ReportInput','Supply R97 search result.');
root=fileparts(mfilename('fullpath'));
fname=fullfile(root,'AF7R58R102_SEARCH_REPORT.txt');
fid=fopen(fname,'w');
assert(fid>0,'R99:ReportOpenFailure','Could not open audit file.');
c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'R102 FULL INTERIOR-JET GENERATOR / R100 TIME DESIGN, R99 INDEPENDENT CERT GATES\n');
fprintf(fid,'status=%s attempts=%d partial=%d full_ref=%d\n', ...
 A.status,A.attempts,A.partial_reference_found,A.candidate_found);
fprintf(fid,'source_t=%.17g reference_version=%.0f known_count=%d mL=%.17g\n', ...
 A.source_snapshot_time_s,A.reference_version, ...
 A.known_obstacle_count,A.estimated_mass_at_snapshot_kg);
fprintf(fid,'live_input_authority=%s\n', A.r102_live_input_authority_status);
fprintf(fid,'first_reason=%s\nfirst_exception=%s\n', ...
 A.first_failed_reason,A.first_exception);
if isfield(A,'last_failed_reason')
 fprintf(fid,'last_reason=%s\n',A.last_failed_reason);
end
for i=1:numel(A.seed_log)
 E=A.seed_log(i);
 fprintf(fid,'attempt=%d seed=%d segments=%d polyline=%.12g status=%s reason=%s k=%d yaw=%d geom=%d\n', ...
 E.attempt_index,E.index,E.num_segments,E.polyline_length_m, ...
 E.status,E.reason,E.kinematic_passed_segments, ...
 E.heading_passed_segments,E.geometry_passed_segments);
 fprintf(fid,' corridor=%s projection=%s knots=%s vQ_knot=%.9g\n', ...
 E.corridor_precheck,E.corridor_projection,E.knot_screen, ...
 E.knot_speed_max_m_s);
 fprintf(fid,' payload_chain=%s leaves=%d overlaps=%d overlap_margin=%.12g\n', ...
 E.adaptive_payload_corridor_status,E.adaptive_payload_leaves, ...
 E.overlap_count,E.minimum_overlap_margin_m);
 fprintf(fid,' multisize_knot=%s knot_margin=%.12g knot_time=%s necessary_T=%.12g\n', ...
 E.multi_size_knot_status,E.multi_size_support_margin_m, ...
 E.knot_time_allocation_status,E.necessary_total_time_s);
 fprintf(fid,' timedesign trials=%d baselinePeak=%.12g selectedPeak=%.12g\n', ...
 E.retime_trials,E.timing_peak_before_m_s,E.timing_peak_after_m_s);
 fprintf(fid,' jetdesign trials=%d alpha=%.12g baselinePeak=%.12g selectedPeak=%.12g [SAMPLES_NOT_PROOF]\n', ...
 E.internal_speed_trials,E.speed_blend_alpha, ...
 E.interior_peak_baseline_sample_m_s,E.interior_peak_sample_m_s);
 fprintf(fid,' R102 shape %s iterations=%d accepted=%d peak before=%.12g after=%.12g [OPTIMIZATION MESH, NOT SAFETY PROOF]\n', ...
 E.r102_jet_optimizer_status,E.r102_jet_optimizer_iterations, ...
 E.r102_jet_optimizer_accepted_steps,E.r102_speed_before_m_s,E.r102_speed_after_m_s);
end
fprintf(fid,'NO PROOF: full future, input torque/tension, HLC tracking tube, IEEE rounding, production trigger/commit.\n');
end
