function path=AF7R58R105_WRITE_REPORT(R)
% Write next to the script. Never expose a numeric nominal pass as flight proof.
assert(isstruct(R)&&isscalar(R)&&isfield(R,'partial_closure'), ...
    'R105:StageReplayRequired','Supply an R105 stage replay result.');
path=fullfile(fileparts(mfilename('fullpath')), ...
    'AF7R58R105_STAGE_REPORT.txt');
f=fopen(path,'wt');
assert(f>0,'R105:ReportWrite','Could not write report next to source.');
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fprintf(f,'R105 SAME-EVENT STAGING / NOT PRODUCTION AUTHORITY\n');
fprintf(f,'status=%s trigger_requested=%d commit_called=%d\n', ...
    char(R.status),logical(R.replan_requested),logical(R.native_commit_called));
if isstruct(R.source_event)&&isfield(R.source_event,'status')
    fprintf(f,'event=%s source=%s exact_EKF=%d\n', ...
        char(R.source_event.status),char(R.source_event.source), ...
        logical(R.source_event.ekf_frame_authenticated));
    fprintf(f,'R55=%s R71R2=%s R63=%s R88_exact=%d\n', ...
        char(R.source_event.r55_status),char(R.source_event.r71r2_status), ...
        char(R.source_event.r63_status), ...
        logical(R.source_event.r88_exact_snapshot));
    fprintf(f,'R55_ring_count=%.17g oldest=%.17g newest=%.17g\n', ...
        R.source_event.r55_ring_count, ...
        R.source_event.r55_oldest_time_s, ...
        R.source_event.r55_newest_time_s);
end
if isstruct(R.physical_predictor)&&isfield(R.physical_predictor,'status')
    fprintf(f,'predictor=%s\n',char(R.physical_predictor.status));
end
G=R.partial_closure;
if isstruct(G)&&isfield(G,'status')
    fprintf(f,'closure=%s rating_available=%d\n', ...
        char(G.status),logical(G.rating_source_supplied));
    fprintf(f,'reference_geom_heading_kin=%d reference_all=%d\n', ...
        logical(G.geometry_heading_kinematics_pass), ...
        logical(G.reference_conditions_pass));
    fprintf(f,'numeric_tension_upper_N=%.17g nominal_thrust_upper_N=%.17g\n', ...
        G.nominal_tension_upper_N,G.nominal_thrust_upper_N);
    fprintf(f,'nominal_c7_seam_error=%.17g finite_tail_end_s=%.17g\n', ...
        G.numeric_c7_tail_seam_error,G.finite_nominal_tail_until_s);
    if isstruct(G.reference_certifier)&&isfield(G.reference_certifier,'segments')
        for i=1:numel(G.reference_certifier.segments)
            X=G.reference_certifier.segments(i);
            fprintf(f,'segment=%d geometry=%d kinematics=%d yaw=%d input=%s reason=%s\n', ...
                i,local_pass(X.geometry),local_pass(X.kinematics), ...
                local_pass(X.heading),local_input(X.input),char(X.reason));
        end
    end
end
fprintf(f,['NOT PROVEN: real HLC torque/tracking/tube, cable rated ' ...
    'strength if not supplied, infinite tail, IEEE bounds, 25ms and native commit\n']);
end
function a=local_pass(x)
a=0;
if isstruct(x)&&isfield(x,'certified'),a=logical(x.certified);end
end
function s=local_input(x)
s='NOT_EVALUATED';
if isstruct(x)&&isfield(x,'status'),s=char(x.status);end
end
