function C = AF7R58R79_C7_NATURAL_CONNECTOR(t0,t1,old_payload_jets,delayed_nominal_payload_jets,phase_delay_s,cable_length_m)
% R79 - degree-15, exact (algebraic) 0..7 jet Hermite connection in the HLC PAYLOAD FRAME.
% No nominal same-clock terminal position: delayed endpoint is an explicit caller authority.
% NOT a collision/actuator certificate and NOT a production commit.
assert(isnumeric(t0)&&isscalar(t0)&&isfinite(t0) && ...
       isnumeric(t1)&&isscalar(t1)&&isfinite(t1)&&t1>t0, ...
       '[R79] positive finite connector interval required.');
assert(isnumeric(phase_delay_s)&&isscalar(phase_delay_s)&& ...
       isfinite(phase_delay_s)&&phase_delay_s>=0, ...
       '[R79] phase delay must be nonnegative and explicitly provided.');
assert(isnumeric(cable_length_m)&&isscalar(cable_length_m)&& ...
       isfinite(cable_length_m)&&cable_length_m>0, ...
       '[R79] live external cable length required.');
assert(isnumeric(old_payload_jets)&&isequal(size(old_payload_jets),[3,8])&& ...
       all(isfinite(old_payload_jets(:))) && ...
       isnumeric(delayed_nominal_payload_jets)&& ...
       isequal(size(delayed_nominal_payload_jets),[3,8])&& ...
       all(isfinite(delayed_nominal_payload_jets(:))), ...
       '[R79] physical-time payload position derivative jets 0..7 required.');
T=double(t1-t0);
assert(isfinite(T)&&T>0,'[R79] connector duration overflow/underflow.');
A=double(old_payload_jets); B=double(delayed_nominal_payload_jets);
% Degree 15: eight endpoint derivative constraints at each boundary.
% CP_{j} = sum_{r=0}^j choose(j,r) * T^r * jet_r/(15)_r,
% CP_{15-j} = sum_{r=0}^j (-1)^r choose(j,r) * T^r * jet_r/(15)_r.
P=zeros(3,16);
for j=0:7
    left=zeros(3,1);right=zeros(3,1);
    for r=0:j
        ff=prod(15:-1:(16-r)); % (15)_0=1 (MATLAB empty product)
        a=nchoosek(j,r)*(T^r)/ff;
        left=left+a*A(:,r+1);
        right=right+(-1)^r*a*B(:,r+1);
    end
    P(:,j+1)=left;
    P(:,16-j)=right;
end
% The Flight adapter converts a raw UAV-height reference to the HLC payload
% reference by subtracting cableL in world z.  Translate POSITIONS only.
rawP=P+[zeros(2,16);cable_length_m*ones(1,16)];
C=struct('schema','R79_C7_NATURAL_PAYLOAD_CONNECTOR_V1', ...
    't0',double(t0),'t1',double(t1),'duration_s',T, ...
    'phase_delay_s',double(phase_delay_s), ...
    'source_phase_at_end_s',double(t1-phase_delay_s), ...
    'payload_cp',P,'raw_flight_cp',rawP, ...
    'old_payload_jets',A,'delayed_nominal_payload_jets',B, ...
    'cable_length_m',double(cable_length_m), ...
    'continuity_order',7, ...
    'trajectory_frame','HLC_PAYLOAD_WORLD', ...
    'native_committed',false, ...
    'whole_body_certified',false, ...
    'closed_loop_certified',false);
end
