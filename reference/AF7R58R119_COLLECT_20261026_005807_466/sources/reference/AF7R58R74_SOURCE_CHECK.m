function S=AF7R58R74_SOURCE_CHECK()
% Parse the actual class with MATLAB and bind to new event-frozen replay.
p=which('REPLANNING_SYSTEM');
assert(~isempty(p)&&~isempty(meta.class.fromName('REPLANNING_SYSTEM')), ...
    '[R74] Replanner missing or class parser failed.');
s=fileread(p);
assert(contains(s,"AF7R58R74_REGISTRY('register',obj)") && ...
    contains(s,"AF7R58R74_REGISTRY('capture',obj)") && ...
    contains(s,"'controller_param',obj.self.controller.hlc_suspended.param") && ...
    contains(s,"'plant_method_fn',obj.self.plant.method") && ...
    contains(s,"'external_param',double(obj.self.parameter.parameter(:))") && ...
    contains(s,'obj.r71r2_event_snapshots=captured;'), ...
    '[R74] source binding incomplete.');
for n=["AF7R58R74_FROZEN_EVENT_PREVIEW", ...
       "AF7R58R74_REGISTRY","AF7R58R74_COLLECT", ...
       "AF7R58R74R2_REBUILD_PARAMS", ...
       "AF7R58R71_EXACT_HLC_PLANT_PREVIEW"]
    assert(exist(char(n),'file')==2,'[R74] missing MATLAB dependency');
end
fr=fileread(which('AF7R58R74_FROZEN_EVENT_PREVIEW'));
ft=fileread(which('AF7R58R74_SELFTEST'));
assert(contains(fr,'AF7R58R74R2_REBUILD_PARAMS(') && ...
    contains(ft,'AF7R58R74R2_REBUILD_PARAMS(') && ...
    ~contains(fr,'"row",P') && ~contains(ft,'"row",Q'), ...
    '[R74R2] frozen event/self-test constructor wiring is stale.');
src=fileread(which('AF7R58R74_COLLECT'));
assert(contains(src,'AF7R58R74_FROZEN_EVENT_PREVIEW(c)') && ...
    ~contains(src,'flight parameters changed after the captured event'), ...
    '[R74] postflight stale comparison still installed');
S=struct('source',p,'matlab_class_parser_passed',true, ...
    'event_parameters_gains_model_captured',true, ...
    'end_of_flight_parameter_equality_gate_removed',true, ...
    'shadow_parameter_reconstruction_bound',true, ...
    'named_argument_constructor_fixed_in_test_and_preview',true, ...
    'hlc_ekf_plant_runner_modified',false, ...
    'future_collision_trigger_replaced',false, ...
    'natural_C7_return_committed',false, ...
    'continuous_time_safety_proved',false);
end
