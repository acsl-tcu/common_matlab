function T=AF7R58R93_SELFTEST()
% Source integrity + synthetic R92 multisegment reference tests.
base=fileparts(mfilename('fullpath'));
active=which('AF7R58R92_RUN_SAVED_ROUTE');
assert(strcmp(fileparts(active),base),'R93:RunnerIsShadowed');
wanted='5aa99988805093fff9e82111c08321062e6f85a5919c634af6e8419863746e8c';
assert(strcmpi(AF7R58R93_SHA256_FILE(active),wanted), ...
    'R93:RunnerNotExactlyPatched');
S=AF7R58R92_SELFTEST();
assert(strcmp(S.status,'PASS_R92_MULTISEGMENT_C7_MIN8_AND_FAIL_CLOSED_REFERENCE_GATE'), ...
    'R93:PriorSyntheticContractRegressed');
src=fileread(active);
assert(contains(src,'R.seed_attempt_log')&& ...
    contains(src,'R.best_partial_assessment')&& ...
    contains(src,'all_segment_reference_conditions_pass')&& ...
    contains(src,'R.production_commit_authorized'), ...
    'R93:SourceDiagnosticContractMissing');
T=struct('status','PASS_R93_SEED_TRACE_SOURCE_AND_R92_SYNTHETIC_TEST', ...
    'source_hash_match',true,'prior_r92_synthetic_pass',true, ...
    'attempt_diagnostics_available',true, ...
    'missing_input_authority_never_assumed',true, ...
    'real_flight_replay_tested',false, ...
    'production_changed',false,'trigger_switched',false, ...
    'closed_loop_safety_proved',false);
end
