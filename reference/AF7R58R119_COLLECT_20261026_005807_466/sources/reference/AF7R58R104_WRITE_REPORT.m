function path=AF7R58R104_WRITE_REPORT(A)
% Output next to this script (not the caller's current work directory).
assert(isstruct(A)&&isscalar(A)&&isfield(A,'attempt_log'), ...
    'R104:SearchResultRequired','Pass a natural-phase search result.');
path=fullfile(fileparts(mfilename('fullpath')),'AF7R58R104_SEARCH_REPORT.txt');
f=fopen(path,'wt');
assert(f>0,'R104:ReportWrite','Cannot open report next to its script.');
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fprintf(f,'R104 NATURAL-PHASE C7 SEARCH / NOT A PRODUCTION SAFETY CERTIFICATE\n');
fprintf(f,'status=%s attempts=%d partial=%d reference=%d\n', ...
    char(A.status),A.attempts,A.partial_reference_found,A.candidate_found);
fprintf(f,'snapshot=%.17g version=%g known=%d mass=%.17g\n', ...
    A.snapshot_time_s,A.reference_version,A.known_obstacle_count,A.estimated_mass_kg);
fprintf(f,'HLC_cmd_source=%s\n',char(A.r102_live_input_authority_status));
fprintf(f,'first_reason=%s\nfirst_exception=%s\n', ...
    char(A.first_failed_reason),char(A.first_exception));
for i=1:numel(A.attempt_log)
    L=A.attempt_log(i);
    fprintf(f,'attempt=%d T=%.12g progress=%.12g lag=%.12g status=%s seeds=%d partial=%d full=%d reason=%s error=%s\n', ...
        L.attempt_index,L.duration_s,L.phase_advance_s,L.phase_delay_s, ...
        char(L.status),L.seed_count,L.partial_count,L.full_count, ...
        char(L.first_reason),char(L.exception));
end
for k=1:numel(A.seed_log)
    L=A.seed_log(k);
    fprintf(f,'seed attempt=%d index=%d status=%s reason=%s sampled_before=%.12g sampled_after=%.12g kinematic=%d heading=%d geometry=%d\n', ...
        L.attempt_index,L.index,char(L.status),char(L.reason), ...
        L.r102_speed_before_m_s,L.r102_speed_after_m_s, ...
        L.kinematic_passed_segments,L.heading_passed_segments,L.geometry_passed_segments);
end
fprintf(f,'NOT PROVEN: whole future, actuator torque, cable rating, HLC tube, IEEE rounding, Flight 25ms, native commit\n');
end
