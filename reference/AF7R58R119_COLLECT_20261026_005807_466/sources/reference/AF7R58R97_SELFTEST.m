function T=AF7R58R97_SELFTEST()
% Exercises new geometric functions, not merely source-code existence.
S=AF7R58R97_SOURCE_CHECK();
assert(strcmp(S.status,'PASS_R97_COMPLETE_FUNCTION_BINDING'), ...
 'R97:MissingRuntimeFunction','R97 dependencies missing or shadowed.');
a=0.37;Rz=[cos(a) -sin(a) 0;sin(a) cos(a) 0;0 0 1];
O=struct('center',[0;0;-2],'axes',[120;60;15],'R',Rz);
start=[-300;0;-2];finish=[300;0;-2];
bad=AF7R58R97_TIGHT_SUPPORT_CORRIDOR([start finish],O,1);
assert(~bad.feasible_corridor_family&&bad.first_bad_obstacle==1, ...
 'R97:ObstructedChordNotRejected','Known obstacle crossing was not found.');
visible=AF7R58R97_TIGHT_SUPPORT_CORRIDOR( ...
 [-300 -160;300 300;-2 -2],O,1);
assert(visible.feasible_corridor_family&& ...
 ~visible.production_commit_authorized, ...
 'R97:LargeOrientedEllipsoidVisibility','Clearly outside chord rejected.');
seed=AF7R58R97_SUPPORT_SEED_ROUTES(start,finish,O,1,8);
assert(~isempty(seed.routes)&&seed.chord_corridors_verified&& ...
 ~seed.reference_certified,'R97:LargeEllipsoidSeedFail', ...
 'No support-chord route found around a large rotated ellipsoid.');
for i=1:numel(seed.routes)
 way=seed.routes{i};
 test=AF7R58R97_TIGHT_SUPPORT_CORRIDOR( ...
     [start way finish],O,1);
 assert(test.feasible_corridor_family&& ...
   numel(test.corridors)==size(way,2)+1, ...
   'R97:ReturnedUnsafeSeed','A returned seed fails its own strict chord support.');
end
% Multiple obstacles are never removed from the final known set.
O2=O;O2.center=[230;160;-2];O2.axes=[12;8;6];
chk=AF7R58R97_TIGHT_SUPPORT_CORRIDOR( ...
 [-300 -160;300 300;-2 -2],[O O2],1);
assert(chk.known_obstacles_checked==2, ...
 'R97:KnownObstacleCount','Known obstacles were dropped.');
% Fixed endpoint inside an obstacle does not yield a false corridor.
inside=AF7R58R97_SUPPORT_SEED_ROUTES(O.center,finish,O,1,4);
assert(isempty(inside.routes)&&~inside.reference_certified, ...
 'R97:UnsafeStartAccepted','Known collision at fixed endpoint must fail closed.');
T=struct('status','PASS_R97_GEOMETRY_FIRST_TIGHT_SUPPORT_CHORDS', ...
 'large_rotated_axes_m',O.axes.', ...
 'large_rotated_ellipsoid_route_count',numel(seed.routes), ...
 'first_route_waypoints',size(seed.routes{1},2), ...
 'known_obstacle_count_preserved',chk.known_obstacles_checked, ...
 'fixed_endpoint_collision_rejected',isempty(inside.routes), ...
 'reference_only',true,'production_modified',false, ...
 'whole_body_certified',false,'ieee_proved',false, ...
 'physical_trigger_switched',false);
end
