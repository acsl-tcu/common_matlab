function T=AF7R58R106_SELFTEST()
% Synthetic actual-EKF-vs-reference guard tests; no producer flag bypass.
S=AF7R58R106_SOURCE_CHECK();
assert(startsWith(S.status,'PASS_R106_'), ...
    'R106:Sources','Pinned R88 class and dependencies required.');
% Make a sensor-known, oriented ellipsoid event with a physically consistent
% 24-state EKF vector from the same tick, plus immutable R88 geometry.
t0=19.75;version=3;L=2;
x=zeros(24,1);x(1:3)=[0;0;2];x(4:6)=[0;0;0.7];
x(13:15)=[0;0;0];x(19:21)=[0;0;-1];
P=struct('C',[3;0;0], 'R',reshape(eye(3),9,1), ...
    'Araw',[1;1;1],'ids',7, ...
    'delta_payload_m',0,'delta_uav_m',0,'delta_cable_m',0);
st=struct('p',x(1:3),'q',x(4:6),'v',x(7:9), ...
    'w',x(10:12),'pL',x(13:15),'vL',x(16:18), ...
    'pT',x(19:21),'wL',x(22:24));
E=AF7R58R106_PACK_EKF(st,t0,version,true,L);
assert(E.available&&strcmp(E.status,'AUTHENTIC_SAME_TICK_EKF_24'), ...
    'R106:ProducerEKF','The actual EKF serializer must authenticate.');
stBad=st;stBad.pT=[1;0;0];
Eb=AF7R58R106_PACK_EKF(stBad,t0,version,true,L);
assert(~Eb.available, 'R106:ProducerMustRejectBadQ', ...
    'Invalid physical cable must be rejected by real producer.');
Z=struct('time_s',t0,'reference_version',version, ...
    'known_mask',true,'ekf_event',E,'obstacle_packet',P, ...
    'cable_length_m',L,'horizon_s',4,'prediction_dt_s',0.025, ...
    'rL_m',0.2,'rQ_m',0.15,'rC_m',0.10, ...
    'd_margin_m',0.05,'estimated_mass_kg',0.02);
O=struct('r88_snapshots',Z);
[F,D]=AF7R58R106_SOURCE_EVENT(O,t0,version);
assert(D.authenticated&&numel(F.state_x24)==24 && ...
    strcmp(D.status,'EXACT_R88_EKF_KNOWN_SET_EVENT_AUTHENTICATED') && ...
    norm(F.q_EKF-[0;0;-1])==0 && ...
    norm(F.Dcomp-[.25;.20;.15],inf)<1e-14, ...
    'R106:AuthenticEKFTest','Same-tick EKF+known obstacle should pass.');
O.r88_snapshots.ekf_event=[];
[Fmissing,Dmissing]=AF7R58R106_SOURCE_EVENT(O,t0,version);
assert(isempty(Fmissing)&&~Dmissing.authenticated, ...
    'R106:NoFallback','Never fill missing EKF from nominal.');
O.r88_snapshots=Z;
O.r88_snapshots.ekf_event.state_x24(19:21)=[1;0;0];
[Fbad,Dbad]=AF7R58R106_SOURCE_EVENT(O,t0,version);
assert(isempty(Fbad)&&~Dbad.authenticated, ...
    'R106:CableDirection','Wrong EKF q must be rejected.');
% A previous real Flight may contain a complete EKF x24 with
% "available=false" solely because the old producer validated q instead
% of pT. Re-authenticate the stored raw x24; do not require new Flight.
O.r88_snapshots=Z;
O.r88_snapshots.ekf_event.available=false;
O.r88_snapshots.ekf_event.status='EKF_CABLE_GEOMETRY_MISMATCH';
[Fr,Dr]=AF7R58R106_SOURCE_EVENT(O,t0,version);
assert(Dr.authenticated && ~isempty(Fr) && ...
    strcmp(Dr.status,'EXACT_R88_EKF_RECOVERED_FROM_INCORRECT_Q_CLASSIFICATION'), ...
    'R106:RawEKFRecovery','Previously misclassified real EKF must be recoverable.');
O.r88_snapshots.ekf_event.status='EKF_CAPTURE_FAILED__UNKNOWN';
[Fblocked,Dblocked]=AF7R58R106_SOURCE_EVENT(O,t0,version);
assert(isempty(Fblocked)&&~Dblocked.authenticated, ...
    'R106:UntrustedCaptureRejected','Do not recover an unrelated failed EKF.');
O.r88_snapshots=Z;
O.r88_snapshots.ekf_event.known_mask=false;
[Fbad,Dbad]=AF7R58R106_SOURCE_EVENT(O,t0,version);
assert(isempty(Fbad)&&~Dbad.authenticated, ...
    'R106:KnownMaskMismatch','Sensor-known set must match.');
O.r88_snapshots=Z;
[Fbad,Dbad]=AF7R58R106_SOURCE_EVENT(O,t0,version+1);
assert(isempty(Fbad)&&~Dbad.authenticated, ...
    'R106:WrongVersion','Stale version must be rejected.');
O.r88_snapshots=Z;
[Fbad,Dbad]=AF7R58R106_SOURCE_EVENT(O,t0+0.025,version);
assert(isempty(Fbad)&&~Dbad.authenticated, ...
    'R106:WrongTime','Different Flight tick must be rejected.');
O.r88_snapshots=Z;
O.r88_snapshots.ekf_event.available=false;
[Fbad,Dbad]=AF7R58R106_SOURCE_EVENT(O,t0,version);
assert(isempty(Fbad)&&~Dbad.authenticated, ...
    'R106:InvalidCaptureStatus','Unavailable estimator is not authority.');
T=struct('status','PASS_R106_SAME_TICK_EKF_EVENT_AND_FAIL_CLOSED_REPLAY', ...
    'source_dependency_pass',true, ...
    'ekf24_capture_contract_pass',true, ...
    'missing_ekf_rejected',true, ...
    'wrong_q_rejected',true, ...
    'wrong_known_set_rejected',true, ...
    'wrong_time_and_version_rejected',true, ...
    'no_fabricated_hlc_future',true, ...
    'physical_future_replayed',false, ...
    'production_trigger_switched',false, ...
    'production_generator_switched',false, ...
    'closed_loop_safety_proved',false);
end
