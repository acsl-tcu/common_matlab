function T=AF7R58R103_SELFTEST()
% Exercise the actual input/schema/handover barriers without any actuation.
S=AF7R58R103_SOURCE_CHECK();
assert(strcmp(S.status,'PASS_R103_DUAL_CONNECTION_SOURCES__NOT_FLIGHT_READY'), ...
    'R103:SourceNotReady','R103 or baseline class source not recognized.');
% No known obstacle: never equate this with global continuous-time safety.
F=struct('time_s',19.75,'reference_version',3, ...
    'horizon_s',4,'dt_s',0.025,'cable_length_m',2, ...
    'pL_EKF',[0;0;0],'pQ_EKF',[0;0;2], ...
    'known_mask',false(1,0),'C',zeros(3,0), ...
    'R',zeros(9,0),'Araw',zeros(3,0), ...
    'ids',zeros(1,0),'Dcomp',[0.5;0.5;0.5]);
A=AF7R58R103_EKF_HLC_TRIGGER(F,[]);
assert(strcmp(A.status,'NO_SENSOR_KNOWN_OBSTACLE') && ...
    ~A.complete_preview&&~A.commit_authorized, ...
    'R103:EmptyMask','Unknown obstacles cannot be certified safe.');
% A sensed obstacle cannot be silently substituted with a reference packet.
F.known_mask=true(1,1); F.C=[4;0;0]; F.R=reshape(eye(3),9,1);
F.Araw=[1;1;1];F.ids=4;
B=AF7R58R103_EKF_HLC_TRIGGER(F,[]);
assert(strcmp(B.status,'BLOCKED_NO_EKF_INITIALIZED_HLC_PLANT_PREVIEW') && ...
    ~B.commit_authorized,'R103:MissingPhysicalPreview', ...
    'The four-second physical predictor is mandatory.');
P=struct('pL_EKF',F.pL_EKF,'pQ_EKF',F.pQ_EKF, ...
    'active',F.known_mask,'centers',F.C,'rotations',F.R, ...
    'axes',F.Araw,'ids',F.ids,'radii',F.Dcomp, ...
    'H',F.horizon_s,'dt',F.dt_s,'L',F.cable_length_m);
Q=AF7R58R103_FROM_R55_PACKET(P,F.time_s,F.reference_version);
assert(isequaln(Q,F),'R103:R55FrameMapping', ...
    'Existing R55 captured EKF/known-obstacle packet did not map exactly.');
N=round(F.horizon_s/F.dt_s)+1;
D=struct('time_s',F.time_s,'reference_version',F.reference_version, ...
    'source','ACTIVE_REFERENCE_ONLY', ...
    'pL',repmat(F.pL_EKF,1,N), ...
    'pQ',repmat(F.pQ_EKF,1,N));
C=AF7R58R103_EKF_HLC_TRIGGER(F,D);
assert(strcmp(C.status,'BLOCKED_NOT_PHYSICAL_HLC_PLANT') && ...
    ~C.commit_authorized,'R103:ReferencePreviewNotPhysical', ...
    'Reference-only horizon must not be called a physical HLC preview.');
D.source='LIVE_EKF_HLC_PLANT_ROLLOUT';
D.reference_version=4;
E=AF7R58R103_EKF_HLC_TRIGGER(F,D);
assert(strcmp(E.status,'BLOCKED_STALE_HLC_PREVIEW'), ...
    'R103:StalePreview','The HLC preview must bind exact active version.');
assert(~S.handover_enabled && ~S.production_modified && ...
    ~S.generator_switched && ~S.physical_trigger_switched, ...
    'R103:UnexpectedFlightMutation','Flight must remain untouched.');
T=struct('status','PASS_R103_EKF_TRIGGER_AND_GENERATOR_HANDOVER_CONTRACT', ...
    'live_source_pinned',true, ...
    'r55_exact_frame_mapping_passed',true, ...
    'reference_only_future_rejected_as_physical',true, ...
    'stale_physical_preview_rejected',true, ...
    'unknown_not_declared_safe',true, ...
    'no_trusting_uncertified_generation',true, ...
    'flight_original_trigger_unchanged',true, ...
    'production_committed',false, ...
    'true_live_hlc_future_exercised',false, ...
    'full_system_proved',false);
end
