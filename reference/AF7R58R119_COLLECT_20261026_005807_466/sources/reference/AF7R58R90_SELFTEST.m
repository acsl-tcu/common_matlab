function T=AF7R58R90_SELFTEST()
% Mathematical identity + fail-closed regression; does not touch Flight.
P=struct('gravity_m_s2',9.81,'cable_length_m',2, ...
    'vehicle_mass_kg',0.762,'latest_EKF_mL_kg',0.02, ...
    'thrust_bounds_N',[0 20], ...
    'torque_bounds_Nm',[-1 1;-1 1;-1 1]);
h=2;Q=zeros(3,16);Q(1,:)=linspace(0,1,16);
C=struct('t0',0,'t1',h,'duration_s',h,'payload_cp',Q);
R=AF7R58R90_INPUT_ENVELOPE(C,P,256);
hover=(P.vehicle_mass_kg+P.latest_EKF_mL_kg)*P.gravity_m_s2;
assert(R.nominal_thrust_certified&&R.taut_tension_positive_certified && ...
    ~R.nominal_torque_certified&&~R.closed_loop_input_certified&& ...
    abs(R.start_thrust_N-hover)<1e-10 && ...
    abs(R.end_thrust_N-hover)<1e-10 && ...
    ~R.production_commit_authorized,'R90:HoverForceTensionRegression');
P2=P;P2.thrust_bounds_N=[0 hover-1];
U=AF7R58R90_INPUT_ENVELOPE(C,P2,256);
assert(~U.nominal_thrust_certified && ...
    strcmp(U.status,'NECESSARY_ENDPOINT_THRUST_LIMIT_VIOLATED'), ...
    'R90:ThrustOverlimitMustReject');
P3=P;P3.tension_max_N=0.1;
V=AF7R58R90_INPUT_ENVELOPE(C,P3,256);
assert(~V.cable_strength_certified&& ...
    strcmp(V.status,'NECESSARY_ENDPOINT_CABLE_STRENGTH_LIMIT_VIOLATED'), ...
    'R90:CableStrengthOverlimitMustReject');
W=AF7R58R90_INPUT_ENVELOPE(C,P,1);
assert(~W.production_commit_authorized,'R90:WorkBudgetMustNotAuthorize');
T=struct('status','PASS_R90_TAUT_INPUT_ENVELOPE_REFERENCE_ONLY', ...
    'straight_taut_hover_thrust_N',R.start_thrust_N, ...
    'straight_taut_tension_N',R.start_tension_N, ...
    'overthrust_rejected',true,'overstrength_rejected',true, ...
    'torque_certified',false,'closed_loop_certified',false, ...
    'production_changed',false);
end
