function S=AF7R58R108_SOURCE_CHECK()
% Fast offline installer guard; no changes to the Flight controller or agent.
root=fileparts(mfilename('fullpath'));
target=fullfile(root,'REPLANNING_SYSTEM.m');
patch=fullfile(root,'REPLANNING_SYSTEM_R108_PATCHED_SOURCE.txt');
old='6d2e806a06d93265f771b2850d6911cd5106208a2c3fd40d1191e2906a6abedb';new='09025f4842af7f540ce24bbc286296e11048c6eae1948aa71135607c808f3720';
S=struct('status','SOURCE_NOT_READY','installable',false, ...
    'already_installed',false,'expected_R106_sha256',old, ...
    'patched_sha256',new,'current_sha256','', ...
    'snapshot_capture_default_disabled',false, ...
    'dual_engines_enabled_by_default',false, ...
    'full_hlc_physical_future_available',false, ...
    'fully_certified_live_c7_generator_available',false, ...
    'production_switched',false);
assert(isfile(target)&&isfile(patch), ...
    'R108:SourceMissing','Both source and main class must be present.');
assert(strcmp(AF7R58R108_HASH_FILE(patch),new), ...
    'R108:PatchChanged','Supplied patched class bytes changed.');
S.current_sha256=AF7R58R108_HASH_FILE(target);
S.already_installed=strcmp(S.current_sha256,new);
S.installable=strcmp(S.current_sha256,old);
if S.already_installed
    S.status='PASS_R108_ALREADY_INSTALLED';
elseif S.installable
    S.status='PASS_R108_R106_SOURCE_PINNED';
else
    S.status='REFUSE_UNKNOWN_PRODUCTION_SOURCE__NO_WRITE';
end
src=fileread(patch);
assert(contains(src,'r108_trigger_dispatch(active,pL_ref,q_ref,time.t') && ...
    contains(src,'r108_generator_dispatch(CTX)') && ...
    contains(src,'r108_keep_postflight_event_copies = false;') && ...
    contains(src,'r88_capture_enabled = false;') && ...
    contains(src,'r108_dual_engine_armed = false;'), ...
    'R108:SourceIntegrity','Expected in-class trigger and generator routes missing.');
S.snapshot_capture_default_disabled=true;
S.dual_engines_enabled_by_default=false;
end
