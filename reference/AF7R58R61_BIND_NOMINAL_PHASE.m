function OUT=AF7R58R61_BIND_NOMINAL_PHASE(IN)
% Bind actual R44R2 correction jets to the LIVE, EXTERNALLY SUPPLIED
% nominal trajectory authority, then call R60 generic C7 natural-time solver.
% Works with arbitrary actual nominal curve, NOT a built-in circle or straight line.
% Never generates a flight-safe or committable candidate by itself.
required={'snapshot_file','nominal_jets_fn','nominal_position_fn', ...
    'phase_slowdown_beta','search_max_trials','growth_factor'};
for i=1:numel(required)
    assert(isstruct(IN)&&isfield(IN,required{i}),'R61:Missing','Missing %s',required{i});
end
assert(isa(IN.nominal_jets_fn,'function_handle')&& ...
    isa(IN.nominal_position_fn,'function_handle'), ...
    'R61:Nominal','Supply current external nominal trajectory callbacks');
SH=AF7R58R61_REAL_OFFSET_REJOIN(IN.snapshot_file,IN.search_max_trials);
assert(SH.candidate_found,'R61:Shape','Real correction shape search incomplete');
S=load(IN.snapshot_file,'Snapshot');
assert(isfield(S.Snapshot,'phase_layers')&&isempty(S.Snapshot.phase_layers), ...
    'R61:PhaseAuthority', ...
    'This historical source must have no phase layers; nonempty live phase needs explicit jets');
t0=SH.real_source_t0_s;
F=double(IN.nominal_jets_fn(t0));
assert(isequal(size(F),[3 8])&&all(isfinite(F),'all'), ...
    'R61:NominalJets','Current actual nominal authority must provide 0..7 derivatives');
J=F+SH.real_source_offset_jets_0_to_7;
RI=struct('t0_s',t0,'initial_duration_s',SH.candidate.T_s, ...
    'phase_delay_s',0,'phase_slowdown_beta',IN.phase_slowdown_beta, ...
    'phase_start_jets_0_to_7',[t0 1 zeros(1,6)], ...
    'active_jets_0_to_7',J, ...
    'nominal_jets_fn',IN.nominal_jets_fn, ...
    'nominal_position_fn',IN.nominal_position_fn, ...
    'max_trials',IN.search_max_trials,'growth_factor',IN.growth_factor, ...
    'enforce_scalar_monotone',false);
R=AF7R58R60_C7_FREE_REJOIN(RI);
OUT=struct('schema','R61_SOURCE_BOUND_NOMINAL_BINDING_V1', ...
    'status','UNCERTIFIED','real_offset_source',SH, ...
    'nominal_authority_supplied',true,'source_historical_phase_identity',true, ...
    'candidate',R,'commit_allowed',false,'tracking_tube_installed',false, ...
    'full_yaw_c6_certified',false,'dynamic_certified',false, ...
    'wholebody_interval_certified',false);
if R.numerical_candidate_found
    OUT.status='REAL_OFFSET_PLUS_EXTERNAL_NOMINAL_PHASE_C7__UNPROVEN';
end
end
