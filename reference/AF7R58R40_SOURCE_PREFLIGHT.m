function Q=AF7R58R40_SOURCE_PREFLIGHT()
% Inspect installed source only. Does not mutate code, accept a plan or bypass
% deadlines. An unexpected source layout is a hard failure.
path=which('REPLANNING_SYSTEM');
assert(~isempty(path) && isfile(path),'[R40] REPLANNING_SYSTEM not found.');
s=fileread(path);
checks=struct();
checks.stage2_entered_diagnostic_only=contains(s, ...
  'obj.r17_capture(''STAGE2_ENTERED'',t_now,NaN,struct());');
checks.stage2_prepared_diagnostic_only=contains(s, ...
  'obj.r17_capture(''STAGE2_CERTIFIED_AND_PREPARED'',t_now,obj.staged_replan_last_stage2_ms,struct());');
checks.stage2_would_reject_diagnostic_only=contains(s, ...
  'obj.r17_capture(''STAGE2_25MS_WOULD_REJECT'',t_now,obj.staged_replan_last_stage2_ms,struct());');
checks.idle_pipeline_guard=contains(s, ...
  '~strcmp(char(obj.staged_replan_state),''IDLE'')');
checks.idle_original_noop=contains(s, ...
  sprintf('if strcmp(state,''IDLE'')\n                return;'));
checks.trigger_still_reference_origin=contains(s, ...
  'obj.trigger_core(active,pL_ref,q_ref,time.t)');
checks.stage3_atomic_commit_present=contains(s, ...
  'activate_staged_reference_only_bundle');
checks.sensor_memory_present=contains(s,'apply_simulated_sensor_memory');
checks.c7_candidate_present=contains(s,'BEZIER_D15_C7');
names=fieldnames(checks);
for i=1:numel(names)
    assert(checks.(names{i}),'[R40] Source condition failed: %s',names{i});
end
Q=struct('schema','AF7R58R40_SOURCE_PREFLIGHT_V1', ...
  'source',path,'checks',checks,'source_bound',true, ...
  'safety_gate_modified_by_r40',false, ...
  'trigger_origin_switched',false,'return_candidate_committed',false, ...
  'real_time_deadline_achieved_unverified',true, ...
  'mex_rebuild_required',false);
fprintf('[R40] Source preflight PASS: diagnostic stage reuse and IDLE no-op\n');
end
