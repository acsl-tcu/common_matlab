function OUT = AF7R36_OBSERVER_CHART_FAILURE_AUDIT_R18_INSTALL()
% AF7R36_OBSERVER_CHART_FAILURE_AUDIT_R18_INSTALL
%
% Diagnostic-only instrumentation for the exact observer chart theorem.
%
% The original fail-closed condition is preserved:
%   S.closed = pitchClosed && fullClosed
%
% No chart limit, support bound, observer estimate, controller, trajectory,
% certificate or commit decision is changed.
%
% R18 records the exact mathematical witnesses used by observer_one_step_support:
%   q0
%   Iw
%   Theta = q0_pitch + Iw
%   pitch margin = pi/2 - Theta
%   roll/yaw propagated margins
%   W0, WL0, VL0, tauNorm, Jmin/Jmax, held input
% and persists the first failed forward-support record before throwing the
% same fail-closed observer error.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 OBSERVER CHART FAILURE AUDIT R18 INSTALL\n');
fprintf(' observer theorem modified                  = 0\n');
fprintf(' Euler chart limits modified                = 0\n');
fprintf(' fail-closed behavior modified              = 0\n');
fprintf(' trajectory/controller modified             = 0\n');
fprintf(' exact chart-inequality witness capture     = 1\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir)&&isfolder(refDir), ...
    '[R18] Cannot resolve current reference directory.');
rps=fullfile(refDir,'REPLANNING_SYSTEM.m');
assert(isfile(rps),'[R18] Missing %s',rps);

src0=normlf(fileread(rps));
src=src0;

assert(contains(src0,'continuous hidden-state support left certified chart.'), ...
    '[R18] Current observer chart assertion not found.');
assert(contains(src0,'Theta=q0(2)+Iw;'), ...
    '[R18] Current Theta theorem line not found.');
assert(~contains(src0,'AF7R36 R18 exact chart-failure witness'), ...
    '[R18] R18 already installed.');

try
    %% 1) Extend forward-support result with theorem witnesses.
    old=[ ...
        '            S=struct();' sprintf('\n') ...
        '            S.closed=pitchClosed&&fullClosed; S.h=h; S.held_input=u;' sprintf('\n') ...
        '            S.Jdiag=Jd; S.w_norm_ub_end=WabsEnd;' sprintf('\n') ...
        '            S.q_abs_ub_interval=qAbs;' sprintf('\n') ...
        '            S.wL_accel_norm_ub=aWL; S.wL_norm_ub_end=WLEnd;' sprintf('\n') ...
        '            S.vL_accel_norm_ub=ALmax; S.vL_norm_ub_end=VLEnd; S.pT_norm_ub=Pnorm;' sprintf('\n') ...
        '            S.sampled_acceptance=false; S.guessed_bound=false;'];

    new=[ ...
        '            S=struct();' sprintf('\n') ...
        '            S.closed=pitchClosed&&fullClosed; S.h=h; S.held_input=u;' sprintf('\n') ...
        '            S.Jdiag=Jd; S.Jmin=Jmin; S.Jmax=Jmax;' sprintf('\n') ...
        '            S.w_norm_ub_start=W0; S.w_norm_ub_energy_start=Wabs0;' sprintf('\n') ...
        '            S.w_norm_ub_end=WabsEnd; S.torque_norm=tauNorm;' sprintf('\n') ...
        '            S.Iw=Iw; S.q_abs_start=q0; S.Theta=Theta;' sprintf('\n') ...
        '            S.pitch_margin_rad=pi/2-Theta;' sprintf('\n') ...
        '            S.pitch_closed=pitchClosed;' sprintf('\n') ...
        '            S.q_abs_ub_interval=qAbs;' sprintf('\n') ...
        '            if pitchClosed' sprintf('\n') ...
        '                S.roll_margin_rad=pi-qAbs(1);' sprintf('\n') ...
        '                S.yaw_margin_rad=pi-qAbs(3);' sprintf('\n') ...
        '            else' sprintf('\n') ...
        '                S.roll_margin_rad=-Inf;' sprintf('\n') ...
        '                S.yaw_margin_rad=-Inf;' sprintf('\n') ...
        '            end' sprintf('\n') ...
        '            S.full_closed=fullClosed;' sprintf('\n') ...
        '            if ~pitchClosed' sprintf('\n') ...
        '                S.closure_reason=''PITCH_SUPPORT_REACHES_ZYX_SINGULARITY'';' sprintf('\n') ...
        '            elseif qAbs(1)>=pi && qAbs(3)>=pi' sprintf('\n') ...
        '                S.closure_reason=''ROLL_AND_YAW_SUPPORT_REACH_ZYX_CHART_BOUNDARY'';' sprintf('\n') ...
        '            elseif qAbs(1)>=pi' sprintf('\n') ...
        '                S.closure_reason=''ROLL_SUPPORT_REACHES_ZYX_CHART_BOUNDARY'';' sprintf('\n') ...
        '            elseif qAbs(3)>=pi' sprintf('\n') ...
        '                S.closure_reason=''YAW_SUPPORT_REACHES_ZYX_CHART_BOUNDARY'';' sprintf('\n') ...
        '            else' sprintf('\n') ...
        '                S.closure_reason=''ZYX_CHART_SUPPORT_CLOSED'';' sprintf('\n') ...
        '            end' sprintf('\n') ...
        '            S.wL_norm_ub_start=WL0; S.vL_norm_ub_start=VL0;' sprintf('\n') ...
        '            S.wL_accel_norm_ub=aWL; S.wL_norm_ub_end=WLEnd;' sprintf('\n') ...
        '            S.vL_accel_norm_ub=ALmax; S.vL_norm_ub_end=VLEnd; S.pT_norm_ub=Pnorm;' sprintf('\n') ...
        '            S.sampled_acceptance=false; S.guessed_bound=false;'];

    src=replace_once(src,old,new,'observer forward-support result');

    %% 2) Preserve exact failed F before throwing. Same failure authority.
    old=[ ...
        '                F=obj.observer_one_step_support(h,uPrev,I);' sprintf('\n') ...
        '                assert(F.closed, ...' sprintf('\n') ...
        '                    ''[REPLANNER OBSERVER ERROR] continuous hidden-state support left certified chart.'');' sprintf('\n') ...
        '                K=obj.observer_contract_two_events(I.previous_measurement,C,F,xhat);'];

    new=[ ...
        '                F=obj.observer_one_step_support(h,uPrev,I);' sprintf('\n') ...
        '                if ~F.closed' sprintf('\n') ...
        '                    % AF7R36 R18 exact chart-failure witness.' sprintf('\n') ...
        '                    I.fail_count=I.fail_count+1;' sprintf('\n') ...
        '                    I.last_forward_failure=F;' sprintf('\n') ...
        '                    obj.observer_hard_support_internal=I;' sprintf('\n') ...
        '                    error([''[REPLANNER OBSERVER ERROR] continuous hidden-state support left certified chart: '' ...' sprintf('\n') ...
        '                        ''%s | pitchMargin=%+.15e rad | rollMargin=%+.15e rad | yawMargin=%+.15e rad | '' ...' sprintf('\n') ...
        '                        ''Theta=%.15e | Iw=%.15e | W0=%.15e | tau=%.15e''], ...' sprintf('\n') ...
        '                        char(F.closure_reason),double(F.pitch_margin_rad), ...' sprintf('\n') ...
        '                        double(F.roll_margin_rad),double(F.yaw_margin_rad), ...' sprintf('\n') ...
        '                        double(F.Theta),double(F.Iw), ...' sprintf('\n') ...
        '                        double(F.w_norm_ub_start),double(F.torque_norm));' sprintf('\n') ...
        '                end' sprintf('\n') ...
        '                K=obj.observer_contract_two_events(I.previous_measurement,C,F,xhat);'];

    src=replace_once(src,old,new,'observer chart assertion');

    %% 3) Expose persisted failed support through public status accessor.
    anchor=[ ...
        '            S.realized_error_comparison_required=false;' sprintf('\n') ...
        '            S.Q_R_covariance_are_not_hard_authority=true;'];

    repl=[ ...
        '            S.realized_error_comparison_required=false;' sprintf('\n') ...
        '            S.last_forward_failure=struct();' sprintf('\n') ...
        '            S.Q_R_covariance_are_not_hard_authority=true;'];
    src=replace_once(src,anchor,repl,'status default failed support');

    anchor=[ ...
        '                ''hlc_state_mass_bridge'',''runtime_last_ms'',''runtime_max_ms''};'];
    repl=[ ...
        '                ''hlc_state_mass_bridge'',''runtime_last_ms'',''runtime_max_ms'', ...' sprintf('\n') ...
        '                ''last_forward_failure''};'];
    src=replace_once(src,anchor,repl,'status field list');

    %% Structural audit
    assert(contains(src,'AF7R36 R18 exact chart-failure witness.'), ...
        '[R18] Failure witness marker missing.');
    assert(contains(src,'S.pitch_margin_rad=pi/2-Theta;'), ...
        '[R18] Pitch margin witness missing.');
    assert(contains(src,'S.roll_margin_rad=pi-qAbs(1);'), ...
        '[R18] Roll margin witness missing.');
    assert(contains(src,'S.yaw_margin_rad=pi-qAbs(3);'), ...
        '[R18] Yaw margin witness missing.');
    assert(contains(src,'I.last_forward_failure=F;'), ...
        '[R18] Failed support persistence missing.');

    write_text(rps,src);
    rehash

    fprintf('[R18] PASS.\n');
    fprintf('  original chart inequalities               = unchanged\n');
    fprintf('  failure still aborts observer update       = 1\n');
    fprintf('  exact theorem witness persisted            = 1\n');
    fprintf('  IMPORTANT: clear old objects/classes before next simulation.\n');

    OUT=struct('pass',true, ...
        'revision','AF7_OBSERVER_CHART_FAILURE_AUDIT_R18', ...
        'observer_theorem_modified',false, ...
        'fail_closed_modified',false);

catch ME
    try,write_text(rps,src0);catch,end
    rehash
    fprintf(2,'[R18] FAILED. REPLANNING_SYSTEM source rolled back.\n');
    fprintf(2,'[R18] ORIGINAL ERROR: %s | %s\n',ME.identifier,ME.message);
    rethrow(ME);
end
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1,'[R18] Anchor "%s" count=%d; expected 1.',label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end

function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));
s=strrep(s,sprintf('\r'),sprintf('\n'));
end

function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');
assert(f>=0,'[R18] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end
