function S=AF7R58R88R2_SOURCE_CHECK()
% Exact source-binding before overwriting the production MATLAB class.
root=fileparts(mfilename('fullpath'));
target=fullfile(root,'REPLANNING_SYSTEM.m');
patch=fullfile(root,'REPLANNING_SYSTEM_R88_PATCHED_SOURCE.txt');
assert(isfile(target)&&isfile(patch),'R88R2:RequiredFileMissing');
base='694fe9c440b780a4168d10cf3a4f53bb20e17222409151c91c22b175ecee4d7d';
after='7d9502ca5d8db06f089c534bcdffb07d184b731a29266ffc52a7859a0c3c8621';
p=AF7R58R88_SHA256_FILE(patch);
h=AF7R58R88_SHA256_FILE(target);
assert(strcmp(p,after),'R88R2:PatchCorruptedOrNotIntendedSource');
assert(strcmp(h,base)||strcmp(h,after), ...
    'R88R2:UnknownProductionVersionRefusingToOverwrite');
P=fileread(patch);
assert(numel(strfind(P,'function r88_capture_one_version'))==1 && ...
    numel(strfind(P,'function R=r88_replay_saved_version_reference_only'))==1 && ...
    numel(strfind(P,'obj.r88_capture_one_version(double(time.t),active);'))==1 && ...
    numel(strfind(P,'function mL = get_load_mass(obj)'))==1 && ...
    contains(P,'mL=obj.self.estimator.result.state.mL;'), ...
    'R88R2:ExactEntrypointsOrUnmodifiedLiveMassGetterMissing');
S=struct('status','R88R2_SOURCE_BOUND', ...
    'baseline_sha256',base,'patched_sha256',after, ...
    'current_source_sha256',h, ...
    'patch_sha256_matches',strcmp(p,after), ...
    'needs_install',strcmp(h,base), ...
    'already_installed',strcmp(h,after), ...
    'production_trigger_changed',false, ...
    'production_trajectory_generator_changed',false);
end
