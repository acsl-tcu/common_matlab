function T=AF7R58R111_SELFTEST()
% Static regression test; MATLAB Flight/HLC prediction not exercised.
S=AF7R58R111_SOURCE_CHECK();
assert(S.installable||S.already_installed, ...
    'R111:SourceMismatch','Current production class must match a pinned R110 variant.');
root=fileparts(mfilename('fullpath'));
a=fileread(fullfile(root,'REPLANNING_SYSTEM_R111_FROM_R110_FLAG0.txt'));
b=fileread(fullfile(root,'REPLANNING_SYSTEM_R111_FROM_R110_FLAG1.txt'));
marker0='ENABLE_AF7R58R17_DIAG_CONTINUE_LATE = 0; % R111 research capture/sim path; NOT a 25-ms cutoff';
marker1='ENABLE_AF7R58R17_DIAG_CONTINUE_LATE = 1; % R111 research capture/sim path; NOT a 25-ms cutoff';
assert(contains(a,marker0)&&contains(b,marker1) && ...
    strcmp(strrep(b,marker1,marker0),a), ...
    'R111:FlagVariantMismatch','The two supplied classes must differ by the user flag only.');
removed={'STAGE1_CONTROL_PERIOD_EXCEEDED', ...
    'STAGE2_CONTROL_PERIOD_EXCEEDED', ...
    'STAGED_ATOMIC_CONTROL_PERIOD_EXCEEDED', ...
    'STAGED_ATOMIC_CONTROL_PERIOD_WOULD_EXCEED', ...
    'R109_NO_STAGE1_BUDGET'};
for i=1:numel(removed)
    assert(~contains(a,removed{i})&&~contains(b,removed{i}), ...
        'R111:DeadlineGateSurvived','Time-only veto still present: %s',removed{i});
end
required={'R111: Stage1 elapsed computation time is audit-only', ...
    'R111: Stage2 elapsed computation time is audit-only', ...
    'R111: No rollback based only on measured compute time', ...
    'R111: No time-only precommit veto', ...
    'function start_staged_replan_pipeline', ...
    'function advance_staged_replan_pipeline', ...
    'function [ok,reason] = activate_staged_reference_only_bundle', ...
    'function [ok,reason] = r17_precommit_check', ...
    'function r25_publish_capture', ...
    'function candidate=r108_generator_dispatch', ...
    'STAGE2_REFERENCE_CERTIFICATE_REJECT', ...
    'STAGED_SOURCE_REFERENCE_STALE', ...
    'STAGED_DEPENDENCY_OR_MAP_STALE', ...
    'STAGE3_ACTIVATION_GRID_MISSED', ...
    'STAGED_ACTIVATION_TIME_MISMATCH', ...
    'r108_trigger_dispatch(obj,active'};
for i=1:numel(required)
    assert(contains(a,required{i}), ...
        'R111:RequiredProtectionMissing','Required source code missing: %s',required{i});
end
assert(contains(a,'obj.generator_last_cycle_critical_ms=1e3*toc(t_hard_cycle);') && ...
    contains(a,'obj.staged_replan_last_stage2_ms=1e3*toc(ts);'), ...
    'R111:TimingMetersMissing','Keep timing measurements to optimize later.');
T=struct('status','PASS_R111_TIME_ONLY_ABORTS_REMOVED__CERT_GATES_PRESERVED',...
    'source_variant',S.source_variant,...
    'time_only_veto_count_removed',5,...
    'deadline_measurement_retained',true,...
    'stage2_certificate_gates_retained',true,...
    'stage3_atomic_commit_retained',true,...
    'user_changed_flag_preserved',S.user_flag_preserved,...
    'matlab_flight_tested',false,...
    'new_engines_certified',false);
end
