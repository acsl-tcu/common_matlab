function OUT = AF7R36_PRIMARY_HEADING_AND_R7_MAP_R9_INSTALL()
% AF7R36_PRIMARY_HEADING_AND_R7_MAP_R9_INSTALL
%
% Diagnostic-only R9.
%
% 1) Repairs the R4C witness segment classifier for the R7 split-transition
%    layout. The old classifier assumed one transition segment:
%       ENTRY, UNSAFE, INTER, UNSAFE, ..., EXIT
%    but R7 uses:
%       ENTRY_A, ENTRY_B, UNSAFE,
%       INTER_A, INTER_B, UNSAFE, ...,
%       EXIT_A, EXIT_B.
%
% 2) Independently checks the ACTUALLY SELECTED production candidate for the
%    continuous nonzero-horizontal-speed condition required by exact
%    path-tangent yaw:
%
%       psi = atan2(y_dot,x_dot)
%
%    Translation is already structural C7 in the current degree-15 candidate
%    construction. If ||v_xy|| is continuously nonzero, exact tangent yaw is
%    C6 on that moving interval.
%
% 3) Keeps the R7B shadow from R8B unchanged and records corrected witness
%    segment IDs/classes next to the production heading result.
%
% Production trajectory selection and hard safety gates are NOT changed.
% No README and no persistent backup file.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 PRIMARY HEADING + R7 SEGMENT MAP R9 INSTALL\n');
fprintf(' production selection modified              = 0\n');
fprintf(' hard safety semantics modified             = 0\n');
fprintf(' translation structural C7 changed          = 0\n');
fprintf(' production heading regularity diagnosed    = 1\n');
fprintf(' R7 witness semantic map repaired            = 1\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir)&&isfolder(refDir), ...
    '[PHR7-R9] Cannot resolve current reference directory.');

hpp=fullfile(refDir,'af7r36_core.hpp');
cpp=fullfile(refDir,'af7r36_single_core_mex.cpp');
assert(isfile(hpp),'[PHR7-R9] Missing %s',hpp);
assert(isfile(cpp),'[PHR7-R9] Missing %s',cpp);

hpp0=normlf(fileread(hpp));
cpp0=normlf(fileread(cpp));
hppNew=hpp0;
cppNew=cpp0;

assert(contains(hpp0,'AF7_TOWING_C7_CONDENSED_C3_R7B'), ...
    '[PHR7-R9] R7B core not installed.');
assert(contains(cpp0,'AF7_R7_SHADOW_AUTHORITY_R8B_RING'), ...
    '[PHR7-R9] R8B shadow ring not installed.');
assert(~contains(hpp0,'AF7_PRIMARY_HEADING_R7_MAP_R9'), ...
    '[PHR7-R9] R9 core patch already installed.');
assert(~contains(cpp0,'AF7_PRIMARY_HEADING_R7_MAP_R9_RING'), ...
    '[PHR7-R9] R9 wrapper patch already installed.');

try
    %% --------------------------------------------------------------------
    % 1) Repair only the diagnostic family-3 segment classifier.
    % Primary/family-1 mapping remains exactly the R4C legacy mapping.
    % ---------------------------------------------------------------------
    old=[ ...
        '    int cls=0;' sprintf('\n') ...
        '    if(seg==0)cls=1;' sprintf('\n') ...
        '    else if(seg==nseg-1)cls=4;' sprintf('\n') ...
        '    else if((seg&1)==1)cls=2;' sprintf('\n') ...
        '    else cls=3;'];

    new=[ ...
        '    int cls=0;' sprintf('\n') ...
        '    // AF7_PRIMARY_HEADING_R7_MAP_R9: family-3 uses split C7 transitions.' sprintf('\n') ...
        '    if(family==3 && nseg>=5 && ((nseg-2)%3)==0){' sprintf('\n') ...
        '        int nc=(nseg-2)/3;' sprintf('\n') ...
        '        if(seg<=1)cls=1;                           // ENTRY_A / ENTRY_B' sprintf('\n') ...
        '        else if(seg>=3*nc)cls=4;                  // EXIT_A / EXIT_B' sprintf('\n') ...
        '        else if(((seg-2)%3)==0)cls=2;             // true UNSAFE_AFFINE' sprintf('\n') ...
        '        else cls=3;                               // INTER_A / INTER_B' sprintf('\n') ...
        '    }else{' sprintf('\n') ...
        '        if(seg==0)cls=1;' sprintf('\n') ...
        '        else if(seg==nseg-1)cls=4;' sprintf('\n') ...
        '        else if((seg&1)==1)cls=2;' sprintf('\n') ...
        '        else cls=3;' sprintf('\n') ...
        '    }'];
    hppNew=replace_once(hppNew,old,new,'R4C witness class map');

    %% --------------------------------------------------------------------
    % 2) Add a compact R9 wrapper ring.
    % c7r7_heading_regular() is a general continuous-time test and can be
    % applied to the selected primary/fallback candidate as well.
    % ---------------------------------------------------------------------
    anchor='static bool G_compiled=false;';
    ring=[anchor sprintf('\n') sprintf('\n') ...
        '// AF7_PRIMARY_HEADING_R7_MAP_R9_RING -- diagnostic only.' sprintf('\n') ...
        'struct PHR9Row {' sprintf('\n') ...
        '    double seq=0,t0=NAN,tm=NAN,t1=NAN,limit=NAN;' sprintf('\n') ...
        '    double prod_ok=0,prod_family=0,prod_heading=0,prod_env=NAN,prod_vq=NAN,prod_qdot=NAN;' sprintf('\n') ...
        '    double r7_ok=0,r7_reason=0,r7_cand=0,r7_speed=0,r7_rejoin=0,r7_geom=0,r7_heading=0;' sprintf('\n') ...
        '    double r7_env=NAN,r7_vq=NAN,r7_qdot=NAN;' sprintf('\n') ...
        '    double wc=0,wmin=NAN,wmint=NAN,wmins=NAN,wminc=NAN,wmax=NAN,wmaxt=NAN,wmaxs=NAN,wmaxc=NAN;' sprintf('\n') ...
        '};' sprintf('\n') ...
        'static std::vector<PHR9Row> G_phr9;' sprintf('\n') ...
        'static double G_phr9_seq=0;' sprintf('\n') ...
        'static void phr9_push(const PlanResult&P,const C7R8ShadowResult&Q7,' sprintf('\n') ...
        '                      const ActiveReference&ref,const Live&L,double t0,double tm,double t1){' sprintf('\n') ...
        '    PHR9Row d;d.seq=++G_phr9_seq;d.t0=t0;d.tm=tm;d.t1=t1;' sprintf('\n') ...
        '    double rho=std::max({L.rQ,L.L+L.rL,L.L+L.rC});d.limit=(L.sensor_range-rho)/(L.horizon+L.dt);' sprintf('\n') ...
        '    d.prod_ok=P.success?1:0;' sprintf('\n') ...
        '    if(P.success){' sprintf('\n') ...
        '        d.prod_family=P.cand.family;d.prod_env=P.cand.max_ctrl;d.prod_vq=P.speed.VQ;d.prod_qdot=P.speed.qdot;' sprintf('\n') ...
        '        d.prod_heading=c7r7_heading_regular(ref,P.cand,P.speed,t0,t1)?1:0;' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '    d.r7_ok=Q7.success?1:0;d.r7_reason=Q7.reason;d.r7_cand=Q7.candidate_count;d.r7_speed=Q7.speed_pass;' sprintf('\n') ...
        '    d.r7_rejoin=Q7.rejoin_pass;d.r7_geom=Q7.geom_pass;d.r7_heading=Q7.heading_pass;' sprintf('\n') ...
        '    if(Q7.success){d.r7_env=Q7.cand.max_ctrl;d.r7_vq=Q7.speed.VQ;d.r7_qdot=Q7.speed.qdot;}' sprintf('\n') ...
        '    const auto&W=G_towmap_towing_witness;d.wc=W.count;' sprintf('\n') ...
        '    d.wmin=std::isfinite(W.min_vq)?W.min_vq:NAN;d.wmint=W.min_t;d.wmins=W.min_seg;d.wminc=W.min_class;' sprintf('\n') ...
        '    d.wmax=std::isfinite(W.max_vq)?W.max_vq:NAN;d.wmaxt=W.max_t;d.wmaxs=W.max_seg;d.wmaxc=W.max_class;' sprintf('\n') ...
        '    if(G_phr9.size()>=512)G_phr9.erase(G_phr9.begin());G_phr9.push_back(d);' sprintf('\n') ...
        '}' sprintf('\n') ...
        'static mxArray* phr9_matrix(){' sprintf('\n') ...
        '    const mwSize N=(mwSize)G_phr9.size(),C=30;mxArray*M=mxCreateDoubleMatrix(N,C,mxREAL);double*p=mxGetPr(M);' sprintf('\n') ...
        '    for(mwSize i=0;i<N;++i){const auto&d=G_phr9[i];double v[C]={' sprintf('\n') ...
        '        d.seq,d.t0,d.tm,d.t1,d.limit,d.prod_ok,d.prod_family,d.prod_heading,d.prod_env,d.prod_vq,d.prod_qdot,' sprintf('\n') ...
        '        d.r7_ok,d.r7_reason,d.r7_cand,d.r7_speed,d.r7_rejoin,d.r7_geom,d.r7_heading,d.r7_env,d.r7_vq,d.r7_qdot,' sprintf('\n') ...
        '        d.wc,d.wmin,d.wmint,d.wmins,d.wminc,d.wmax,d.wmaxt,d.wmaxs,d.wmaxc};' sprintf('\n') ...
        '        for(mwSize j=0;j<C;++j)p[i+N*j]=v[j];' sprintf('\n') ...
        '    }return M;' sprintf('\n') ...
        '}'];
    cppNew=replace_once(cppNew,anchor,ring,'R9 wrapper ring');

    %% --------------------------------------------------------------------
    % 3) Append R9 row after R7 shadow evaluation, before witness reset.
    % ---------------------------------------------------------------------
    old=[ ...
        '            C7R8ShadowResult Q7=c7r8_shadow_plan(R,L,B,O,t0,tm,searchEnd);' sprintf('\n') ...
        '            r7shadow_push(Q7,L,t0,tm,searchEnd);' sprintf('\n') ...
        '            towmap_core_reset_witness();'];

    new=[ ...
        '            C7R8ShadowResult Q7=c7r8_shadow_plan(R,L,B,O,t0,tm,searchEnd);' sprintf('\n') ...
        '            r7shadow_push(Q7,L,t0,tm,searchEnd);' sprintf('\n') ...
        '            phr9_push(Q,Q7,R,L,t0,tm,searchEnd);' sprintf('\n') ...
        '            towmap_core_reset_witness();'];
    cppNew=replace_once(cppNew,old,new,'R9 per-call append');

    %% --------------------------------------------------------------------
    % 4) op12 read, op13 clear.
    % ---------------------------------------------------------------------
    anchor='        if(op==3){';
    ops=[ ...
        '        if(op==12){' sprintf('\n') ...
        '            if(nrhs!=1||nlhs!=1)mexErrMsgIdAndTxt("AF7PHR9:Arity","op12 -> matrix.");' sprintf('\n') ...
        '            plhs[0]=phr9_matrix();return;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '        if(op==13){' sprintf('\n') ...
        '            if(nrhs!=1||nlhs>1)mexErrMsgIdAndTxt("AF7PHR9:Arity","op13 clear.");' sprintf('\n') ...
        '            G_phr9.clear();G_phr9_seq=0;if(nlhs>0)plhs[0]=logicalScalar(true);return;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        anchor];
    cppNew=replace_once(cppNew,anchor,ops,'R9 diagnostic ops');

    %% --------------------------------------------------------------------
    % 5) Audits.
    % ---------------------------------------------------------------------
    assert(contains(cppNew, ...
        'static const char* PLANNER_REV="AF7_REPLANNER_MIN_DEVIATION_V4_FIXED_T1";'), ...
        '[PHR7-R9] Planner identity changed unexpectedly.');
    assert(count_exact(hppNew,'AF7_PRIMARY_HEADING_R7_MAP_R9')==1, ...
        '[PHR7-R9] R9 core classifier marker count invalid.');
    assert(count_exact(cppNew,'AF7_PRIMARY_HEADING_R7_MAP_R9_RING')==1, ...
        '[PHR7-R9] R9 ring marker count invalid.');
    assert(count_exact(cppNew,'phr9_push(Q,Q7,R,L,t0,tm,searchEnd);')==1, ...
        '[PHR7-R9] R9 append call count invalid.');
    assert(count_exact(hppNew,'if(family==3 && nseg>=5 && ((nseg-2)%3)==0)')==1, ...
        '[PHR7-R9] Split-segment classifier not installed exactly once.');

    %% --------------------------------------------------------------------
    % 6) Stage compile before production write.
    % ---------------------------------------------------------------------
    stageDir=tempname;
    [ok,msg]=mkdir(stageDir);
    assert(ok,'[PHR7-R9] Cannot create staging directory: %s',msg);
    stageCleanup=onCleanup(@()cleanup_stage(stageDir)); %#ok<NASGU>

    stagedHpp=fullfile(stageDir,'af7r36_core.hpp');
    stagedCpp=fullfile(stageDir,'af7r36_single_core_mex.cpp');
    write_text(stagedHpp,hppNew);write_text(stagedCpp,cppNew);

    fprintf('[PHR7-R9] Compiling staged diagnostic MEX...\n');
    oldDir=pwd;
    cwdCleanup=onCleanup(@()cd(oldDir)); %#ok<NASGU>
    cd(stageDir);clear mex;
    mex('-R2018a','-O', ...
        'COMPFLAGS="$COMPFLAGS /std:c++17"', ...
        ['-I' stageDir], ...
        '-output','af7r36_single_core_mex', ...
        '-outdir',stageDir, ...
        stagedCpp);

    stagedMex=fullfile(stageDir,['af7r36_single_core_mex.' mexext]);
    assert(isfile(stagedMex),'[PHR7-R9] Staged MEX missing.');

    dstMex=fullfile(refDir,['af7r36_single_core_mex.' mexext]);
    oldMexTmp=fullfile(stageDir,['af7r36_single_core_mex_OLD.' mexext]);
    hadOldMex=isfile(dstMex);
    if hadOldMex
        [ok,msg]=copyfile(dstMex,oldMexTmp,'f');
        assert(ok,'[PHR7-R9] Cannot stage rollback MEX: %s',msg);
    end

    cd(oldDir);clear mex;
    wroteH=false;wroteC=false;installedMex=false;
    try
        write_text(hpp,hppNew);wroteH=true;
        write_text(cpp,cppNew);wroteC=true;
        [ok,msg]=copyfile(stagedMex,dstMex,'f');
        assert(ok,'[PHR7-R9] Cannot install staged MEX: %s',msg);
        installedMex=true;
        clear mex;rehash;
        assert(exist('af7r36_single_core_mex','file')==3, ...
            '[PHR7-R9] Installed MEX not visible.');
        try,af7r36_single_core_mex(7);catch,end
        try,af7r36_single_core_mex(11);catch,end
        af7r36_single_core_mex(13);
    catch ME2
        if wroteH,try,write_text(hpp,hpp0);catch,end,end
        if wroteC,try,write_text(cpp,cpp0);catch,end,end
        if installedMex&&hadOldMex,try,copyfile(oldMexTmp,dstMex,'f');catch,end,end
        clear mex;rehash;rethrow(ME2);
    end

    fprintf('[PHR7-R9] PASS.\n');
    fprintf('  production selection unchanged             = 1\n');
    fprintf('  family-3 split witness mapping corrected   = 1\n');
    fprintf('  selected production heading check          = continuous-time\n');
    fprintf('  translation C7 requirement weakened        = 0\n');
    fprintf('  safety requirement weakened                = 0\n');
    fprintf('  README created                              = 0\n');
    fprintf('  persistent backup files created             = 0\n');

    OUT=struct('pass',true, ...
        'revision','AF7_PRIMARY_HEADING_R7_MAP_R9', ...
        'production_selection_modified',false, ...
        'hard_safety_modified',false, ...
        'translation_C7_modified',false, ...
        'r7_segment_map_repaired',true, ...
        'production_heading_diagnosed',true);

catch ME
    clear mex;rehash;
    fprintf(2,'[PHR7-R9] FAILED. No successful production install completed.\n');
    rethrow(ME);
end
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1, ...
    '[PHR7-R9] Anchor "%s" count=%d; expected 1.',label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end

function n=count_exact(txt,pat)
n=numel(strfind(txt,pat));
end

function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));
s=strrep(s,sprintf('\r'),sprintf('\n'));
end

function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');
assert(f>=0,'[PHR7-R9] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end

function cleanup_stage(d)
if isfolder(d)
    try,rmdir(d,'s');catch,end
end
end
