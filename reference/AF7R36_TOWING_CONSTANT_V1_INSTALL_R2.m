function OUT = AF7R36_TOWING_CONSTANT_V1_INSTALL_R2()
% AF7R36_TOWING_CONSTANT_V1_INSTALL_R2
% Adds a towing-specific constant-translation candidate between the existing
% minimum-deviation primary and the unchanged minimum-snap fallback.
%
% Safety:
%   - existing minimum-deviation branch remains first and unchanged;
%   - new branch is attempted only if that branch fails;
%   - new candidate uses the same corridor halfspaces;
%   - unsafe spans satisfy d_j(s)=a_j exactly (v_j=0);
%   - degree-15 C7 transition construction is unchanged;
%   - acceptance is unchanged:
%       speed certificate -> rejoin certificate -> continuous whole-body cert;
%   - historical minimum-snap fallback remains unchanged and last.
%
% No README / no persistent backup files are created.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 TOWING CONSTANT-TRANSLATION V1 R2 INSTALL\n');
fprintf(' hard safety certificate semantics modified = 0\n');
fprintf(' old certified fallback preserved            = 1\n');
fprintf('====================================================================================================\n');

NL=sprintf('\n');

refDir = fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir) && isfolder(refDir), ...
    '[TOWCONST-V1] Cannot resolve current reference directory.');

hpp = fullfile(refDir,'af7r36_core.hpp');
cpp = fullfile(refDir,'af7r36_single_core_mex.cpp');
assert(isfile(hpp),'[TOWCONST-V1] Missing %s',hpp);
assert(isfile(cpp),'[TOWCONST-V1] Missing %s',cpp);

hpp0 = normalize_lf(fileread(hpp));
cpp0 = normalize_lf(fileread(cpp));
hppNew = hpp0;
cppNew = cpp0;

assert(~contains(hpp0,'AF7_TOWING_CONSTANT_V1'), ...
    '[TOWCONST-V1] Core is already patched.');
assert(~contains(cpp0,'TOWING_CONSTANT_TRANSLATION'), ...
    '[TOWCONST-V1] MEX wrapper is already patched.');

productionTouched=false;
try
    %% 1) Candidate-family documentation.
    old = [ ...
        '    // family: 1 = exact minimum integrated squared deviation affine family,' NL ...
        '    //         2 = historical minimum-snap affine fallback.' NL];
    new = [ ...
        '    // family: 1 = exact minimum integrated squared deviation affine family,' NL ...
        '    //         2 = historical minimum-snap affine fallback,' NL ...
        '    //         3 = towing constant-translation minimum-deviation family.' NL];
    hppNew = replace_once(hppNew,old,new,'candidate family documentation');

    %% 2) Add towing-branch counters without touching existing diagnostics.
    old = [ ...
        '    int fallback_candidate_count=0;' NL ...
        '    int fallback_speed_pass=0;' NL ...
        '    int fallback_rejoin_pass=0;' NL ...
        '    int fallback_geom_tests=0;' NL];
    new = [old ...
        '    int towing_candidate_count=0;' NL ...
        '    int towing_speed_pass=0;' NL ...
        '    int towing_rejoin_pass=0;' NL ...
        '    int towing_geom_tests=0;' NL];
    hppNew = replace_once(hppNew,old,new,'towing counters');

    %% 3) Extend branch-local accounting only. Hard gates are unchanged.
    old = [ ...
        '        if(branch==1) R.primary_candidate_count+=(int)candidates.size();' NL ...
        '        else if(branch==2) R.fallback_candidate_count+=(int)candidates.size();' NL];
    new = [ ...
        '        if(branch==1) R.primary_candidate_count+=(int)candidates.size();' NL ...
        '        else if(branch==2) R.fallback_candidate_count+=(int)candidates.size();' NL ...
        '        else if(branch==3) R.towing_candidate_count+=(int)candidates.size();' NL];
    hppNew = replace_once(hppNew,old,new,'candidate branch accounting');

    old = '            if(branch==1) ++R.primary_speed_pass; else if(branch==2) ++R.fallback_speed_pass;';
    new = ['            if(branch==1) ++R.primary_speed_pass; ' ...
           'else if(branch==2) ++R.fallback_speed_pass; ' ...
           'else if(branch==3) ++R.towing_speed_pass;'];
    hppNew = replace_once(hppNew,old,new,'speed branch accounting');

    old = [ ...
        '            if(branch==1){++R.primary_rejoin_pass;++R.primary_geom_tests;}' NL ...
        '            else if(branch==2){++R.fallback_rejoin_pass;++R.fallback_geom_tests;}' NL];
    new = [ ...
        '            if(branch==1){++R.primary_rejoin_pass;++R.primary_geom_tests;}' NL ...
        '            else if(branch==2){++R.fallback_rejoin_pass;++R.fallback_geom_tests;}' NL ...
        '            else if(branch==3){++R.towing_rejoin_pass;++R.towing_geom_tests;}' NL];
    hppNew = replace_once(hppNew,old,new,'rejoin geometry branch accounting');

    %% 4) Insert towing-specific candidate AFTER the unchanged primary and
    %     BEFORE the unchanged historical fallback.
    anchor = [ ...
        '    // ------------------------------------------------------------------' NL ...
        '    // FALLBACK: exact previously flown affine/minimum-snap family.' NL];

    block = [ ...
        '    // ------------------------------------------------------------------' NL ...
        '    // AF7_TOWING_CONSTANT_V1' NL ...
        '    // TOWING-SPECIFIC SECONDARY FAMILY: constant correction on each' NL ...
        '    // certified nominal-unsafe component.' NL ...
        '    //' NL ...
        '    // The existing affine primary remains authoritative and is tried' NL ...
        '    // first. This branch is reached only when that primary cannot close' NL ...
        '    // the unchanged hard certificates.' NL ...
        '    //' NL ...
        '    // Here the unsafe-span correction is constrained to' NL ...
        '    //' NL ...
        '    //      d_j(s) = a_j, with zero correction velocity and acceleration,' NL ...
        '    //' NL ...
        '    // by eliminating every affine velocity variable v_j from the QP.' NL ...
        '    // This is a towing-specific effort objective: it introduces no' NL ...
        '    // correction-induced motion while the payload/cable is traversing' NL ...
        '    // the certified avoidance span. The entry/inter-component/exit' NL ...
        '    // segments are still the exact same degree-15 C7 jet transitions.' NL ...
        '    //' NL ...
        '    // Corridor feasibility remains exact because the original linear' NL ...
        '    // halfspaces are restricted to the convex subspace v_j=0. No safety' NL ...
        '    // gate is removed or relaxed. Every resulting candidate still passes' NL ...
        '    // the identical speed -> rejoin -> continuous whole-body stack.' NL ...
        '    // If this family fails, the historical minimum-snap fallback below' NL ...
        '    // remains bit-for-bit available as before.' NL ...
        '    // ------------------------------------------------------------------' NL ...
        '    ts=clk::now();' NL ...
        '    {' NL ...
        '        const auto Hfull=minimum_deviation_hessian(E.comp,t0,t1);' NL ...
        '        const int npos=3*Cn;' NL ...
        '        std::vector<int> pmap(npos,0);' NL ...
        '        for(int j=0;j<Cn;++j)for(int d=0;d<3;++d)' NL ...
        '            pmap[3*j+d]=3*(2*j)+d;' NL ...
        '' NL ...
        '        std::vector<double> Hpos(npos*npos,0.0);' NL ...
        '        for(int i=0;i<npos;++i)for(int j=0;j<npos;++j)' NL ...
        '            Hpos[i*npos+j]=Hfull[pmap[i]*nvar+pmap[j]];' NL ...
        '' NL ...
        '        std::vector<Base> BT;' NL ...
        '        std::vector<int> sg(Ne,1);' NL ...
        '        std::function<void(int)> rec=[&](int k){' NL ...
        '            if(k<Ne){sg[k]=1;rec(k+1);sg[k]=-1;rec(k+1);return;}' NL ...
        '            std::vector<Row> rows;' NL ...
        '            for(int e=0;e<Ne;++e){' NL ...
        '                const auto& src=(sg[e]>0)?OR[e].plus:OR[e].minus;' NL ...
        '                for(const auto& rf:src){' NL ...
        '                    Row rr;rr.a.assign(npos,0.0);rr.b=rf.b;' NL ...
        '                    for(int j=0;j<Cn;++j)for(int d=0;d<3;++d)' NL ...
        '                        rr.a[3*j+d]=rf.a[3*(2*j)+d];' NL ...
        '                    rows.push_back(std::move(rr));' NL ...
        '                }' NL ...
        '            }' NL ...
        '            QPSol q=solve_qp(Hpos,npos,rows);' NL ...
        '            if(!q.ok)return;' NL ...
        '            std::vector<double> z(nvar,0.0);' NL ...
        '            for(int j=0;j<Cn;++j)for(int d=0;d<3;++d)' NL ...
        '                z[3*(2*j)+d]=q.z[3*j+d];' NL ...
        '            BT.push_back({std::move(z),q.cost,q.slack,sg});' NL ...
        '        };' NL ...
        '        rec(0);' NL ...
        '' NL ...
        '        std::vector<Candidate> towing;' NL ...
        '        towing.reserve(BT.size());' NL ...
        '        for(auto&b:BT){' NL ...
        '            Candidate c=build_candidate(E.comp,t0,t1,b.z,b.c,b.sg,b.s,3);' NL ...
        '            c.constant_translation=true;' NL ...
        '            towing.push_back(std::move(c));' NL ...
        '        }' NL ...
        '        R.tim.qp+=std::chrono::duration<double,std::milli>(clk::now()-ts).count();' NL ...
        '        auto tc=clk::now();' NL ...
        '        if(certify_candidates(towing,true,3)){' NL ...
        '            R.tim.candidate_build+=std::chrono::duration<double,std::milli>(clk::now()-tc).count();' NL ...
        '            R.tim.synthesis=std::chrono::duration<double,std::milli>(clk::now()-a).count();' NL ...
        '            R.tim.candidate=R.tim.synthesis;' NL ...
        '            R.tim.total=std::chrono::duration<double,std::milli>(clk::now()-T0).count();' NL ...
        '            return R;' NL ...
        '        }' NL ...
        '        R.tim.candidate_build+=std::chrono::duration<double,std::milli>(clk::now()-tc).count();' NL ...
        '    }' NL ...
        '' NL];

    hppNew = insert_before_once(hppNew,anchor,block,'towing constant branch');

    %% 5) Expose new family/counters through the existing MEX result.
    old = [ ...
        '        "fallback_candidate_count","fallback_speed_pass_count",' NL ...
        '        "fallback_rejoin_pass_count","fallback_geometry_test_count",' NL];
    new = [ ...
        '        "fallback_candidate_count","fallback_speed_pass_count",' NL ...
        '        "fallback_rejoin_pass_count","fallback_geometry_test_count",' NL ...
        '        "towing_candidate_count","towing_speed_pass_count",' NL ...
        '        "towing_rejoin_pass_count","towing_geometry_test_count",' NL];
    cppNew = replace_once(cppNew,old,new,'MEX towing field names');

    old = [ ...
        '    set("fallback_candidate_count",dscalar(R.fallback_candidate_count));' NL ...
        '    set("fallback_speed_pass_count",dscalar(R.fallback_speed_pass));' NL ...
        '    set("fallback_rejoin_pass_count",dscalar(R.fallback_rejoin_pass));' NL ...
        '    set("fallback_geometry_test_count",dscalar(R.fallback_geom_tests));' NL];
    new = [old ...
        '    set("towing_candidate_count",dscalar(R.towing_candidate_count));' NL ...
        '    set("towing_speed_pass_count",dscalar(R.towing_speed_pass));' NL ...
        '    set("towing_rejoin_pass_count",dscalar(R.towing_rejoin_pass));' NL ...
        '    set("towing_geometry_test_count",dscalar(R.towing_geom_tests));' NL];
    cppNew = replace_once(cppNew,old,new,'MEX towing field assignments');

    old = [ ...
        '    const char* family=(R.cand.family==1)?"MINIMUM_DEVIATION_AFFINE":' NL ...
        '                       ((R.cand.family==2)?"MINIMUM_SNAP_FALLBACK":"NONE");' NL];
    new = [ ...
        '    const char* family=(R.cand.family==1)?"MINIMUM_DEVIATION_AFFINE":' NL ...
        '                       ((R.cand.family==2)?"MINIMUM_SNAP_FALLBACK":' NL ...
        '                       ((R.cand.family==3)?"TOWING_CONSTANT_TRANSLATION":"NONE"));' NL];
    cppNew = replace_once(cppNew,old,new,'candidate family string');

    cppNew = replace_once(cppNew, ...
        '    set("compact_constant_translation",logicalScalar(false));', ...
        '    set("compact_constant_translation",logicalScalar(R.cand.constant_translation));', ...
        'constant translation result flag');

    cppNew = replace_once(cppNew, ...
        'static const char* PLANNER_REV="AF7_REPLANNER_MIN_DEVIATION_V4_FIXED_T1";', ...
        'static const char* PLANNER_REV="AF7_TOWING_CONSTANT_V1_FIXED_T1";', ...
        'planner revision');

    %% 6) Stage the patched sources away from production first.
    stageDir=tempname;
    [ok,msg]=mkdir(stageDir);
    assert(ok,'[TOWCONST-V1-R2] Cannot create staging directory: %s',msg);
    stageCleanup=onCleanup(@()cleanup_stage(stageDir)); %#ok<NASGU>
    stagedHpp=fullfile(stageDir,'af7r36_core.hpp');
    stagedCpp=fullfile(stageDir,'af7r36_single_core_mex.cpp');
    write_text_lf(stagedHpp,hppNew);
    write_text_lf(stagedCpp,cppNew);

    %% 7) Compile the STAGED copy. Production source is still untouched here.
    fprintf('[TOWCONST-V1-R2] Staged source closed. Compiling staged MEX...\n');
    oldDir=pwd;
    cwdCleanup=onCleanup(@()cd(oldDir)); %#ok<NASGU>
    cd(stageDir);
    clear mex;
    mex('-R2018a','-O', ...
        'COMPFLAGS="$COMPFLAGS /std:c++17"', ...
        ['-I' stageDir], ...
        '-output','af7r36_single_core_mex', ...
        '-outdir',stageDir, ...
        stagedCpp);

    stagedMex=fullfile(stageDir,['af7r36_single_core_mex.' mexext()]);
    assert(isfile(stagedMex), ...
        '[TOWCONST-V1-R2] Staged MEX compile returned without an output binary.');

    %% 8) Only after staged compilation succeeds, atomically update production files.
    cd(oldDir);
    clear mex;

    productionTouched=true;
    write_text_lf(hpp,hppNew);
    write_text_lf(cpp,cppNew);

    dstMex=fullfile(refDir,['af7r36_single_core_mex.' mexext()]);
    [ok,msg]=copyfile(stagedMex,dstMex,'f');
    assert(ok,'[TOWCONST-V1-R2] Cannot install compiled MEX: %s',msg);

    clear mex;
    rehash;

    assert(exist('af7r36_single_core_mex','file')==3, ...
        '[TOWCONST-V1-R2] Installed MEX not visible.');

    fprintf('[TOWCONST-V1-R2] PASS.\n');
    fprintf('  staged compile before production write   = 1\n');
    fprintf('  primary unchanged                        = 1\n');
    fprintf('  towing constant branch installed         = 1\n');
    fprintf('  historical minimum-snap fallback kept    = 1\n');
    fprintf('  speed/rejoin/whole-body hard gates same  = 1\n');
    fprintf('  persistent backup files created          = 0\n');

    OUT=struct();
    OUT.pass=true;
    OUT.reference_dir=refDir;
    OUT.revision='AF7_TOWING_CONSTANT_V1_R2';
    OUT.hard_certificate_semantics_modified=false;
    OUT.old_fallback_preserved=true;
    OUT.readme_created=false;
    OUT.persistent_backup_created=false;

catch ME
    if productionTouched
        try, write_text_lf(hpp,hpp0); catch, end
        try, write_text_lf(cpp,cpp0); catch, end
    end
    clear mex;
    rehash;
    fprintf(2,'[TOWCONST-V1-R2] FAILED; production source restored if it had been touched.\n');
    rethrow(ME);
end
end

function s=normalize_lf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));
s=strrep(s,sprintf('\r'),sprintf('\n'));
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1, ...
    '[TOWCONST-V1] Anchor "%s" count=%d; expected exactly 1. No edit retained.', ...
    label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end

function txt=insert_before_once(txt,anchor,block,label)
h=strfind(txt,anchor);
assert(numel(h)==1, ...
    '[TOWCONST-V1] Anchor "%s" count=%d; expected exactly 1. No edit retained.', ...
    label,numel(h));
txt=[txt(1:h-1) block txt(h:end)];
end


function cleanup_stage(stageDir)
if isfolder(stageDir)
    try
        rmdir(stageDir,'s');
    catch
    end
end
end


function write_text_lf(path,txt)
f=fopen(path,'wt','n','UTF-8');
assert(f>=0,'[TOWCONST-V1] Cannot open %s for writing.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end
