function path=AF7R58R95_WRITE_REPORT(A)
assert(isstruct(A)&&isscalar(A)&&isfield(A,'seed_log')&& ...
    isfield(A,'attempt_log'),'R93:ActualSearchOutputRequired');
base=fileparts(mfilename('fullpath'));
path=fullfile(base,'AF7R58R95_SEARCH_REPORT.txt');
fid=fopen(path,'wt');assert(fid>0,'R93:CannotWriteReport');
cl=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'R95 CORRIDOR-FIRST C7 KNOT-SPEED REFERENCE-ONLY SEARCH - NEVER A PRODUCTION SAFETY PROOF\n');
fprintf(fid,'status=%s attempts=%d partial=%d candidate=%d\n', ...
    A.status,A.attempts,A.partial_reference_found,A.candidate_found);
fprintf(fid,'source_t=%.17g ver=%.0f estimated_mL_kg=%.17g known_count=%d\n', ...
    A.source_snapshot_time_s,A.reference_version, ...
    A.estimated_mass_at_snapshot_kg,A.known_obstacle_count);
fprintf(fid,'input_authority_supplied=%d tension_rating_supplied=%d\n', ...
    A.external_input_authority_supplied,A.external_tension_rating_supplied);
fprintf(fid,'best_partial_length=%.17g duration=%.17g phase_delay=%.17g\n', ...
    A.best_partial_polyline_length_m,A.best_partial_duration_s, ...
    A.best_partial_phase_delay_s);
fprintf(fid,'first_failed_reason=%s\nfirst_exception=%s\n', ...
    A.first_failed_reason,A.first_exception);
for i=1:numel(A.attempt_log)
 X=A.attempt_log(i);
 fprintf(fid,'attempt=%d T=%.17g delay=%.17g status=%s seeds=%d geo_heading_kin=%d full_ref=%d reason=%s error=%s\n', ...
 X.attempt_index,X.duration_s,X.phase_delay_s,X.status, ...
 X.seed_count,X.partial_seed_count,X.full_reference_seed_count, ...
 X.first_failed_reason,X.error);
end
for i=1:numel(A.seed_log)
 X=A.seed_log(i);
 fprintf(fid,'SEED attempt=%d seed=%d status=%s segments=%d polyline_m=%.17g kpass=%d hpass=%d gpass=%d full_geo=%d full_ref=%d reason=%s error=%s\n', ...
 X.attempt_index,X.index,X.status,X.num_segments, ...
 X.polyline_length_m,X.kinematic_passed_segments, ...
 X.heading_passed_segments,X.geometry_passed_segments, ...
 X.geometry_kinematics_heading_pass, ...
 X.all_segment_reference_conditions_pass,X.reason,X.error);
 fprintf(fid,'  prefilter corridor=%s knot=%s knot_speed=%.17g\n', ...
  X.corridor_precheck,X.knot_screen,X.knot_speed_max_m_s);
 fprintf(fid,'  numeric_C7_endpoint_residual=%.17g\n',X.c7_numeric_endpoint_residual);
end
fprintf(fid,'UNPROVEN: tail, torques/closed-loop, robust tube, IEEE directed rounding, production commit\n');
end
