function OUT = AF7R58ZB_ONEFILE_EXACT_CACHE_KEY_INSTALL()
% AF7R58ZB
% Production patch on top of AF7R58Z-R5.
%
% Purpose:
%   Replace R5's prepared-cache use of the ACTIVE-runtime reuse gate with a
%   dedicated, source-proved prepared-cache key.
%
% Safety:
%   - Active runtime reuse gate remains unchanged.
%   - Cache is still one-entry, non-authority, overwrite-only.
%   - Cache hit requires exact speed bounds + exact live numeric geometry /
%     sensor dependencies + exact static_obstacle_map equality.
%   - Active reference mode/version at cache-store time must still match.
%   - Cached sweep/sensor numeric contents are revalidated exactly.
%   - targetVersion remains metadata-only and is rebound through the already
%     proved reuse_reference_only_runtime_packet_exact method.
%   - runtime_dependency_signature is NOT promoted from cache on a hit:
%     it is recaptured from live state with
%     capture_runtime_dependency_signature_fast.
%   - Existing final assertions and both hard deadline gates remain unchanged.
%
% Exact pre-source:
%   3e1cd5df64bf893c0d9c4d4fd6502d8a26f395ada08b8ad32abd12d076c9f901

root=fileparts(mfilename('fullpath'));
outdir=tempname(root);
[ok,msg]=mkdir(outdir); assert(ok,'%s',msg);

report=fullfile(outdir,'AF7R58ZB_REPORT.txt');
f=fopen(report,'wt','n','UTF-8');
assert(f>=0,'[AF7R58ZB] cannot open report.');
c=onCleanup(@()fclose(f)); %#ok<NASGU>

say(f,'====================================================================================================');
say(f,' AF7R58ZB | EXACT PREPARED-CACHE KEY + LIVE DEPENDENCY RECAPTURE INSTALL');
say(f,'====================================================================================================');
say(f,'[AUTHORITY] sourceBound=1 | oneEntry=1 | nonAuthority=1 | rollbackOnFailure=1 | parseBeforeWrite=1');
say(f,'[SAFETY] activeReuseGateUnchanged=1 | exactCacheKey=1 | liveDepRecapture=1 | finalAssertionsPreserved=1');

OUT=struct();
OUT.schema='AF7R58ZB_EXACT_CACHE_KEY_INSTALL_V1';
OUT.production_modified=false;
OUT.rollback_performed=false;
OUT.status='OPEN';
OUT.error=struct();
OUT.output_directory=outdir;

pR=fullfile(root,'REPLANNING_SYSTEM.m');
expected='3e1cd5df64bf893c0d9c4d4fd6502d8a26f395ada08b8ad32abd12d076c9f901';

backupDir=tempname(root);
backupReady=false;
writesStarted=false;

try
    assert(isfile(pR),'[AF7R58ZB] REPLANNING_SYSTEM.m missing.');
    h0=file_hash(pR);

    say(f,'');
    say(f,'[A. EXACT R5 SOURCE BINDING]');
    say(f,' source SHA exact = %d | %s',strcmp(h0,expected),h0);
    assert(strcmp(h0,expected),'[AF7R58ZB] current production source is not exact R5.');

    [txt,eolStyle]=read_text_norm(pR);
    lines=reshape(regexp(txt,'\n','split'),1,[]);
    defs=discover_function_headers(lines);

    protected={ ...
        'can_reuse_reference_only_runtime_packet_exact', ...
        'reuse_reference_only_runtime_packet_exact', ...
        'build_trigger_sweep_for_target', ...
        'prepare_obstacle_packet_fast_target', ...
        'build_sensor_horizon_for_target'};

    protectedBefore=struct();
    say(f,'');
    say(f,'[B. PROTECTED FUNCTION HASHES -- BEFORE]');
    for k=1:numel(protected)
        [b,i0,i1,~]=method_block_by_name(lines,defs,protected{k});
        key=matlab.lang.makeValidName(protected{k});
        protectedBefore.(key)=text_hash(strjoin(b,newline));
        say(f,' %-48s L%d:L%d | %s',protected{k},i0,i1,protectedBefore.(key));
    end

    requiredTokens={ ...
        'reference_only_prepared_packet_cache_valid = false;', ...
        'reference_only_prepared_packet_cache_commit_count = 0;', ...
        'AF7R58Z_R5_ONE_ENTRY_PREPARED_PACKET_CACHE_V1', ...
        'reusePreparedPacketCache=false;', ...
        'preparedPacketWasRebuilt=false;'};
    for k=1:numel(requiredTokens)
        assert(count(txt,requiredTokens{k})>=1, ...
            '[AF7R58ZB] required R5 token missing: %s',requiredTokens{k});
    end

    forbiddenTokens={ ...
        'can_reuse_reference_only_prepared_packet_cache_exact', ...
        'reference_only_prepared_packet_cache_gate_pass_count', ...
        'reference_only_prepared_packet_cache_miss_reason_count'};
    for k=1:numel(forbiddenTokens)
        assert(count(txt,forbiddenTokens{k})==0, ...
            '[AF7R58ZB] ZB token already present: %s',forbiddenTokens{k});
    end

    % 1) fixed-size diagnostics
    pProp=find_unique_regex(lines, ...
        '^\s*reference_only_prepared_packet_cache_commit_count\s*=\s*0;\s*$');

    propCode={ ...
        '        reference_only_prepared_packet_cache_gate_pass_count = 0;'; ...
        '        reference_only_prepared_packet_cache_last_reason_code = 0;'; ...
        '        reference_only_prepared_packet_cache_miss_reason_count = zeros(1,16);'};
    lines=insert_after(lines,pProp,propCode);

    % 2) dedicated exact cache gate
    defs=discover_function_headers(lines);
    [~,reuse0,~,~]=method_block_by_name(lines,defs, ...
        'reuse_reference_only_runtime_packet_exact');

    gateMethod={ ...
'        function [tf,reason] = can_reuse_reference_only_prepared_packet_cache_exact(obj,C,newSC)'; ...
'            % AF7R58ZB: exact NON-AUTHORITY prepared-cache key.'; ...
'            % reason: 0 PASS'; ...
'            % 1 policy | 2 cache/schema | 3 newSC | 4 cachedSC'; ...
'            % 5 payload speed | 6 UAV speed | 7 key shape'; ...
'            % 8 active authority changed | 9 live numeric dependency changed'; ...
'            % 10 obstacle source changed | 11 sweep mismatch'; ...
'            % 12 packet invalid | 13 sensor mismatch | 14 dep invalid'; ...
'            tf=false;'; ...
'            reason=1;'; ...
'            if ~strcmpi(char(obj.AVOIDANCE_COMMIT_POLICY),''REFERENCE_ONLY'')'; ...
'                return;'; ...
'            end'; ...
''; ...
'            reason=2;'; ...
'            if ~(isstruct(C) && isscalar(C) && ...'; ...
'                    isfield(C,''schema'') && ...'; ...
'                    strcmp(char(C.schema),''AF7R58ZB_ONE_ENTRY_PREPARED_PACKET_CACHE_V2'') && ...'; ...
'                    isfield(C,''non_authority'') && isscalar(C.non_authority) && logical(C.non_authority) && ...'; ...
'                    isfield(C,''speed'') && isfield(C,''sweep'') && ...'; ...
'                    isfield(C,''packet'') && isfield(C,''sensor'') && ...'; ...
'                    isfield(C,''dep'') && isfield(C,''key''))'; ...
'                return;'; ...
'            end'; ...
''; ...
'            req={''payload_speed_UB_m_s'',''uav_speed_UB_m_s''};'; ...
'            reason=3;'; ...
'            if ~(isstruct(newSC) && isfield(newSC,''certified'') && logical(newSC.certified) && ...'; ...
'                    all(isfield(newSC,req)))'; ...
'                return;'; ...
'            end'; ...
'            reason=4;'; ...
'            oldSC=C.speed;'; ...
'            if ~(isstruct(oldSC) && isfield(oldSC,''certified'') && logical(oldSC.certified) && ...'; ...
'                    all(isfield(oldSC,req)))'; ...
'                return;'; ...
'            end'; ...
'            VL=double(newSC.payload_speed_UB_m_s);'; ...
'            VQ=double(newSC.uav_speed_UB_m_s);'; ...
'            if ~(isfinite(VL)&&VL>=0&&isfinite(VQ)&&VQ>=0)'; ...
'                reason=3; return;'; ...
'            end'; ...
'            reason=5;'; ...
'            if ~isequal(double(oldSC.payload_speed_UB_m_s),VL), return; end'; ...
'            reason=6;'; ...
'            if ~isequal(double(oldSC.uav_speed_UB_m_s),VQ), return; end'; ...
''; ...
'            reason=7;'; ...
'            K=C.key;'; ...
'            keyReq={''active_reference_mode'',''active_reference_version'', ...'; ...
'                ''dt'',''r_load'',''d_margin'',''r_drone'',''r_cable'', ...'; ...
'                ''horizon'',''sensor_range'',''cable_length'',''static_obstacle_map''};'; ...
'            if ~(isstruct(K)&&isscalar(K)&&all(isfield(K,keyReq)))'; ...
'                return;'; ...
'            end'; ...
''; ...
'            reason=8;'; ...
'            if ~(strcmpi(char(K.active_reference_mode),char(obj.active_reference_mode)) && ...'; ...
'                    isequal(double(K.active_reference_version),double(obj.active_reference_version)))'; ...
'                return;'; ...
'            end'; ...
''; ...
'            reason=9;'; ...
'            live=[double(obj.prediction_dt),double(obj.r_load),double(obj.d_margin), ...'; ...
'                double(obj.r_drone),double(obj.r_cable),double(obj.horizon_s), ...'; ...
'                double(obj.trigger_dist),double(obj.L_cable)];'; ...
'            stored=[double(K.dt),double(K.r_load),double(K.d_margin), ...'; ...
'                double(K.r_drone),double(K.r_cable),double(K.horizon), ...'; ...
'                double(K.sensor_range),double(K.cable_length)];'; ...
'            if ~(all(isfinite(live)) && all(isfinite(stored)) && isequal(stored,live))'; ...
'                return;'; ...
'            end'; ...
''; ...
'            reason=10;'; ...
'            if ~isequaln(K.static_obstacle_map,obj.static_obstacle_map)'; ...
'                return;'; ...
'            end'; ...
''; ...
'            dt=live(1);'; ...
'            pay=VL*dt/2;'; ...
'            uav=VQ*dt/2;'; ...
'            cab=max(VL,VQ)*dt/2;'; ...
'            S=C.sweep;'; ...
'            reason=11;'; ...
'            if ~(isstruct(S) && isfield(S,''certified'') && logical(S.certified) && ...'; ...
'                    isfield(S,''dt'') && isequal(double(S.dt),dt) && ...'; ...
'                    isfield(S,''payload_m'') && isequal(double(S.payload_m),pay) && ...'; ...
'                    isfield(S,''uav_m'') && isequal(double(S.uav_m),uav) && ...'; ...
'                    isfield(S,''cable_m'') && isequal(double(S.cable_m),cab) && ...'; ...
'                    isfield(S,''sensor_one_period_m'') && ...'; ...
'                        isequal(double(S.sensor_one_period_m),VQ*dt))'; ...
'                return;'; ...
'            end'; ...
''; ...
'            reason=12;'; ...
'            P=C.packet;'; ...
'            if ~(isstruct(P) && isscalar(P) && ~isempty(fieldnames(P)) && ...'; ...
'                    isfield(P,''reference_version''))'; ...
'                return;'; ...
'            end'; ...
''; ...
'            reason=13;'; ...
'            H=live(6); Rs=live(7); L=live(8);'; ...
'            rho=max([live(4),L+live(2),L+live(5)]);'; ...
'            horizonMargin=Rs-(rho+VQ*H);'; ...
'            dDetLB=Rs-VQ*dt;'; ...
'            safeClear=dDetLB-rho;'; ...
'            if VQ>0'; ...
'                collisionLead=safeClear/VQ;'; ...
'                beforeHorizon=collisionLead-H;'; ...
'            else'; ...
'                collisionLead=Inf;'; ...
'                beforeHorizon=Inf;'; ...
'            end'; ...
'            T=C.sensor;'; ...
'            if ~(isstruct(T) && isfield(T,''certified'') && logical(T.certified) && ...'; ...
'                    isfield(T,''VL'') && isequal(double(T.VL),VL) && ...'; ...
'                    isfield(T,''VQ'') && isequal(double(T.VQ),VQ) && ...'; ...
'                    isfield(T,''dt'') && isequal(double(T.dt),dt) && ...'; ...
'                    isfield(T,''sensor_range'') && isequal(double(T.sensor_range),Rs) && ...'; ...
'                    isfield(T,''horizon'') && isequal(double(T.horizon),H) && ...'; ...
'                    isfield(T,''rho_body'') && isequal(double(T.rho_body),rho) && ...'; ...
'                    isfield(T,''sensor_horizon_margin_m'') && ...'; ...
'                        isequal(double(T.sensor_horizon_margin_m),horizonMargin) && ...'; ...
'                    isfield(T,''first_detection_distance_LB_m'') && ...'; ...
'                        isequal(double(T.first_detection_distance_LB_m),dDetLB) && ...'; ...
'                    isfield(T,''first_collision_lead_LB_s'') && ...'; ...
'                        isequal(double(T.first_collision_lead_LB_s),collisionLead) && ...'; ...
'                    isfield(T,''before_horizon_entry_LB_s'') && ...'; ...
'                        isequal(double(T.before_horizon_entry_LB_s),beforeHorizon))'; ...
'                return;'; ...
'            end'; ...
''; ...
'            reason=14;'; ...
'            if ~isstruct(C.dep), return; end'; ...
''; ...
'            reason=0;'; ...
'            tf=true;'; ...
'        end'; ...
''};
    lines=insert_before(lines,reuse0,gateMethod);

    % 3) patch R5 commit cache gate
    defs=discover_function_headers(lines);
    [B,i0,i1,~]=method_block_by_name(lines,defs,'try_commit_reference_only_proposal');
    B=reshape(B,1,[]);

    gateStart=find_unique_contains(B,'reusePreparedPacketCache=false;');
    firstClear=find_first_contains_after(B, ...
        'obj.reference_only_prepared_packet_cache=struct();',gateStart);
    e1=find_first_exact_trim_after(B,'end',firstClear);
    e2=find_first_exact_trim_after(B,'end',e1);

    newGate={ ...
        '            reusePreparedPacketCache=false;'; ...
        '            preparedPacketCache=struct();'; ...
        '            preparedPacketWasRebuilt=false;'; ...
        '            cacheReason=0;'; ...
        '            if ~reuseRuntimePacket && ...'; ...
        '                    logical(obj.reference_only_prepared_packet_cache_valid)'; ...
        '                preparedPacketCache=obj.reference_only_prepared_packet_cache;'; ...
        '                [reusePreparedPacketCache,cacheReason]= ...'; ...
        '                    obj.can_reuse_reference_only_prepared_packet_cache_exact( ...'; ...
        '                        preparedPacketCache,SC);'; ...
        '                obj.reference_only_prepared_packet_cache_last_reason_code=double(cacheReason);'; ...
        '                if reusePreparedPacketCache'; ...
        '                    obj.reference_only_prepared_packet_cache_gate_pass_count= ...'; ...
        '                        obj.reference_only_prepared_packet_cache_gate_pass_count+1;'; ...
        '                else'; ...
        '                    idx=round(double(cacheReason));'; ...
        '                    if isfinite(idx) && idx>=1 && ...'; ...
        '                            idx<=numel(obj.reference_only_prepared_packet_cache_miss_reason_count)'; ...
        '                        obj.reference_only_prepared_packet_cache_miss_reason_count(idx)= ...'; ...
        '                            obj.reference_only_prepared_packet_cache_miss_reason_count(idx)+1;'; ...
        '                    end'; ...
        '                    obj.reference_only_prepared_packet_cache_valid=false;'; ...
        '                    obj.reference_only_prepared_packet_cache=struct();'; ...
        '                    obj.reference_only_prepared_packet_cache_invalidate_count= ...'; ...
        '                        obj.reference_only_prepared_packet_cache_invalidate_count+1;'; ...
        '                    preparedPacketCache=struct();'; ...
        '                end'; ...
        '            end'};
    B=replace_range_with_lines(B,gateStart,e2,newGate);

    % 4) cache hit: recapture full live dependency signature
    hitBranch=find_first_exact_trim_after(B,'elseif reusePreparedPacketCache',1);
    nextElse=find_first_exact_trim_after(B,'else',hitBranch);
    freshDepCode={ ...
        '                % AF7R58ZB: never promote cached full-system dependency state.'; ...
        '                depNew=obj.capture_runtime_dependency_signature_fast();'; ...
        '                depNew.reference_mode=''REPAIRED'';'; ...
        '                depNew.reference_version=double(targetVersion);'};
    B=insert_before(B,nextElse,freshDepCode);

    % 5) cache store: V2 schema + exact key snapshot
    storeStart=find_unique_contains(B, ...
        'obj.reference_only_prepared_packet_cache=struct( ...');
    storeEnd=find_first_contains_after(B,'''dep'',depNew);',storeStart);

    newStore={ ...
        '                    obj.reference_only_prepared_packet_cache=struct( ...'; ...
        '                        ''schema'',''AF7R58ZB_ONE_ENTRY_PREPARED_PACKET_CACHE_V2'', ...'; ...
        '                        ''non_authority'',true, ...'; ...
        '                        ''speed'',SC, ...'; ...
        '                        ''sweep'',sweepNew, ...'; ...
        '                        ''packet'',packetNew, ...'; ...
        '                        ''sensor'',sensorNew, ...'; ...
        '                        ''dep'',depNew, ...'; ...
        '                        ''key'',struct( ...'; ...
        '                            ''active_reference_mode'',char(obj.active_reference_mode), ...'; ...
        '                            ''active_reference_version'',double(obj.active_reference_version), ...'; ...
        '                            ''dt'',double(obj.prediction_dt), ...'; ...
        '                            ''r_load'',double(obj.r_load), ...'; ...
        '                            ''d_margin'',double(obj.d_margin), ...'; ...
        '                            ''r_drone'',double(obj.r_drone), ...'; ...
        '                            ''r_cable'',double(obj.r_cable), ...'; ...
        '                            ''horizon'',double(obj.horizon_s), ...'; ...
        '                            ''sensor_range'',double(obj.trigger_dist), ...'; ...
        '                            ''cable_length'',double(obj.L_cable), ...'; ...
        '                            ''static_obstacle_map'',obj.static_obstacle_map));'};
    B=replace_range_with_lines(B,storeStart,storeEnd,newStore);

    lines=replace_range_with_lines(lines,i0,i1,B);
    patched=strjoin(lines,newline);

    % static invariants
    patchedLines=reshape(regexp(patched,'\n','split'),1,[]);
    patchedDefs=discover_function_headers(patchedLines);

    inv=struct();
    inv.new_gate_exactly_one=count_exact_function_definitions( ...
        patchedDefs,'can_reuse_reference_only_prepared_packet_cache_exact')==1;
    inv.v2_schema_twice=count(patched, ...
        'AF7R58ZB_ONE_ENTRY_PREPARED_PACKET_CACHE_V2')==2;
    inv.live_dep_recapture_once=count(patched, ...
        '% AF7R58ZB: never promote cached full-system dependency state.')==1;
    inv.key_has_obstacle_map=count(patched, ...
        '''static_obstacle_map'',obj.static_obstacle_map')==1;
    inv.key_has_all_numeric=all(cellfun(@(t)contains(patched,t),{ ...
        '''dt'',double(obj.prediction_dt)', ...
        '''r_load'',double(obj.r_load)', ...
        '''d_margin'',double(obj.d_margin)', ...
        '''r_drone'',double(obj.r_drone)', ...
        '''r_cable'',double(obj.r_cable)', ...
        '''horizon'',double(obj.horizon_s)', ...
        '''sensor_range'',double(obj.trigger_dist)', ...
        '''cable_length'',double(obj.L_cable)'}));
    inv.reason_counter_fixed=count(patched, ...
        'reference_only_prepared_packet_cache_miss_reason_count = zeros(1,16);')==1;
    inv.no_append=~contains(patched,'reference_only_prepared_packet_cache(end+1)') && ...
        ~contains(patched,'reference_only_prepared_packet_cache{end+1}');
    inv.predeadline_reason_preserved=count(patched, ...
        'REFERENCE_ONLY_COMMIT_PREPARATION_DEADLINE_EXCEEDED')==1;
    inv.all=all(structfun(@(x)logical(x),inv));
    OUT.static_invariants=inv;

    say(f,'');
    say(f,'[C. STATIC PATCH INVARIANTS]');
    fn=fieldnames(inv);
    for k=1:numel(fn)
        say(f,' %-44s = %d',fn{k},logical(inv.(fn{k})));
    end
    assert(inv.all,'[AF7R58ZB] static patch invariant failed.');

    protectedAfter=struct();
    protectedEqual=true;
    say(f,'');
    say(f,'[D. PROTECTED FUNCTION HASHES -- PATCHED]');
    for k=1:numel(protected)
        [b,j0,j1,~]=method_block_by_name(patchedLines,patchedDefs,protected{k});
        key=matlab.lang.makeValidName(protected{k});
        protectedAfter.(key)=text_hash(strjoin(b,newline));
        same=strcmp(protectedBefore.(key),protectedAfter.(key));
        protectedEqual=protectedEqual && same;
        say(f,' %-48s unchanged=%d | L%d:L%d | %s', ...
            protected{k},same,j0,j1,protectedAfter.(key));
    end
    assert(protectedEqual,'[AF7R58ZB] protected active-reuse/builder method changed.');
    OUT.protected_unchanged=protectedEqual;

    [PB,pi0,~,~]=method_block_by_name(patchedLines,patchedDefs, ...
        'try_commit_reference_only_proposal');

    qGate=find_unique_contains(PB, ...
        'obj.can_reuse_reference_only_prepared_packet_cache_exact( ...');
    qHit=find_first_exact_trim_after(PB,'elseif reusePreparedPacketCache',qGate);
    qFresh=find_unique_contains(PB, ...
        'depNew=obj.capture_runtime_dependency_signature_fast();');
    qStore=find_unique_contains(PB, ...
        '''schema'',''AF7R58ZB_ONE_ENTRY_PREPARED_PACKET_CACHE_V2'', ...');
    qReason=find_unique_contains(PB, ...
        'REFERENCE_ONLY_COMMIT_PREPARATION_DEADLINE_EXCEEDED');
    qTry=find_first_exact_trim_after(PB,'try',qReason);
    qActive=find_unique_contains(PB,'obj.obstacle_packet=packetNew;');
    qAssert1=find_unique_contains(PB,'obj.assert_trigger_packet_certificate_current();');
    qAssert2=find_unique_contains(PB,'obj.assert_repaired_reference_current();');

    assert(qGate<qHit && qHit<qFresh && qFresh<qStore && qStore<qReason && ...
        qReason<qTry && qTry<qActive && qActive<qAssert1 && qAssert1<qAssert2, ...
        '[AF7R58ZB] patched safety topology invalid.');

    OUT.topology=struct( ...
        'cache_gate',pi0+qGate-1, ...
        'cache_hit_branch',pi0+qHit-1, ...
        'live_dep_recapture',pi0+qFresh-1, ...
        'cache_store',pi0+qStore-1, ...
        'predeadline_reason',pi0+qReason-1, ...
        'transactional_try',pi0+qTry-1, ...
        'active_packet_assignment',pi0+qActive-1, ...
        'final_assert_1',pi0+qAssert1-1, ...
        'final_assert_2',pi0+qAssert2-1);

    say(f,'');
    say(f,'[E. PATCHED SAFETY TOPOLOGY]');
    T=OUT.topology;
    say(f,' cache dedicated exact gate             L%d',T.cache_gate);
    say(f,' cache hit branch                       L%d',T.cache_hit_branch);
    say(f,' live dependency recapture              L%d',T.live_dep_recapture);
    say(f,' reject-only cache store                L%d',T.cache_store);
    say(f,' predeadline reject reason              L%d',T.predeadline_reason);
    say(f,' transactional try                      L%d',T.transactional_try);
    say(f,' active packet assignment               L%d',T.active_packet_assignment);
    say(f,' final assertions                       L%d / L%d',T.final_assert_1,T.final_assert_2);

    % full class parse before write
    preDir=fullfile(outdir,'AF7R58ZB_PREFLIGHT');
    [ok,msg]=mkdir(preDir); assert(ok,'%s',msg);
    parseName='AF7R58ZB_PARSE_REPLANNING_SYSTEM';
    parseText=strrep(patched,'classdef REPLANNING_SYSTEM < handle', ...
        ['classdef ' parseName ' < handle']);
    write_utf8(fullfile(preDir,[parseName '.m']),parseText);
    addpath(preDir,'-begin');
    cp=onCleanup(@()safe_rmpath_if_present(preDir)); %#ok<NASGU>
    eval(['clear ' parseName]);
    mc=meta.class.fromName(parseName);
    assert(~isempty(mc),'[AF7R58ZB] patched full class preflight parse failed.');
    eval(['clear ' parseName]);

    say(f,'');
    say(f,'[F. PREFLIGHT BEFORE WRITE]');
    say(f,' static invariants                       = 1');
    say(f,' protected active-reuse/builders         = 1');
    say(f,' safety topology                         = 1');
    say(f,' full patched class parse                = 1');
    say(f,' production writes                       = 0');

    [ok,msg]=mkdir(backupDir); assert(ok,'%s',msg);
    backupReady=true;
    OUT.backup_directory=backupDir;
    copyfile(pR,fullfile(backupDir,'REPLANNING_SYSTEM.m'));

    writesStarted=true;
    write_text_eol(pR,patched,eolStyle);
    rehash;

    h1=file_hash(pR);
