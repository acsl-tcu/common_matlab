function OUT = AF7R31_BUILD_SOURCE_BOUND_FLAT_BATCH_MEX(replanner)
clc;
fprintf('\n====================================================================================================\n');
fprintf(' AF7R31 | BUILD SOURCE-BOUND NOMINAL FLAT-JET BATCH MEX\n');
fprintf('====================================================================================================\n');
assert(isa(replanner,'REPLANNING_SYSTEM'),'[AF7R31] input must be REPLANNING_SYSTEM.');
F=replanner.nominal_flat_derivative_fn;
assert(iscell(F)&&numel(F)>=7&&all(cellfun(@(f)isa(f,'function_handle'),F(1:7))), ...
    '[AF7R31] nominal flat derivative handles unavailable.');
src=which('REPLANNING_SYSTEM'); root=fileparts(src);
fn='af7r31_nominal_flat_batch_codegen';
mexName='af7r31_nominal_flat_batch_mex';
mPath=fullfile(root,[fn '.m']);
mexPath=fullfile(root,[mexName '.' mexext]);
metaPath=fullfile(root,'AF7R31_FLAT_BATCH_META.mat');
S=cell(1,7); V=cell(1,7); E=cell(1,7);
for r=1:7
    S{r}=func2str(F{r});
    tok=regexp(S{r},'^@\(([A-Za-z]\w*)\)(.*)$','tokens','once');
    assert(~isempty(tok)&&numel(tok)==2, ...
        '[AF7R31] flat derivative handle %d is not a single-variable anonymous function.',r-1);
    V{r}=tok{1}; E{r}=tok{2};
    assert(~isempty(strtrim(E{r})),'[AF7R31] empty derivative expression.');
end
signature=sha256_text(strjoin(S,char(10)));

fid=fopen(mPath,'w');
assert(fid>=0,'[AF7R31] cannot create generated evaluator.');
c=onCleanup(@()fclose(fid));
fprintf(fid,'function Y=%s(tv)\n',fn);
fprintf(fid,'%% Auto-generated by AF7R31. Source signature: %s\n',signature);
fprintf(fid,'tv=double(tv(:).'' );\n');
fprintf(fid,'N=numel(tv);\n');
fprintf(fid,'Y=zeros(21,N);\n');
fprintf(fid,'for k=1:N\n');
for r=1:7
    fprintf(fid,'    %s=tv(k);\n',V{r});
    fprintf(fid,'    z=%s;\n',E{r});
    fprintf(fid,'    Y(%d:%d,k)=reshape(double(z),3,1);\n',3*r-2,3*r);
end
fprintf(fid,'end\n');
fprintf(fid,'end\n');
clear c;

assert(exist('codegen','file')==2, ...
    ['[AF7R31] MATLAB Coder/codegen is required for this stage. ' ...
     'No production source has been modified.']);
if isfile(mexPath), delete(mexPath); end
old=pwd; cleanup=onCleanup(@()cd(old)); cd(root);
cfg=coder.config('mex');
try, cfg.GenerateReport=false; catch, end
T=coder.typeof(0,[1 Inf],[0 1]);
codegen('-config',cfg,fn,'-args',{T},'-o',mexName);
clear cleanup; cd(old); rehash;
assert(isfile(mexPath),'[AF7R31] generated flat batch MEX not found.');
meta=struct('schema','AF7R31_FLAT_BATCH_META_V1','signature',signature, ...
    'handle_text',{S},'generated_m',mPath,'mex_path',mexPath);
save(metaPath,'meta');
addpath(root,'-begin');
af7r31_nominal_flat_batch_mex([0 0.125]);
OUT=struct('schema','AF7R31_BUILD_SOURCE_BOUND_FLAT_BATCH_MEX_V1', ...
    'signature',signature,'generated_m',mPath,'mex_path',mexPath, ...
    'meta_path',metaPath,'built',true);
assignin('base','AF7R31_BUILD_SOURCE_BOUND_FLAT_BATCH_MEX_OUT',OUT);
fprintf(' reference-source signature              = %s\n',signature);
fprintf(' generated evaluator                     = %s\n',mPath);
fprintf(' MEX                                     = %s\n',mexPath);
fprintf(' production source modified              = 0\n');
fprintf('====================================================================================================\n');
end

function h=sha256_text(s)
md=java.security.MessageDigest.getInstance('SHA-256');
md.update(uint8(unicode2native(char(s),'UTF-8')));
d=typecast(md.digest(),'uint8');
h=lower(reshape(dec2hex(d,2).',1,[]));
end
