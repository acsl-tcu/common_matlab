function S=AF7R58R78_SOURCE_CHECK()
% Source binding, no side effects. The MATLAB Flight itself is still the
% authority for C7/yaw C6 and whole-body safety verification.
file=which('REPLANNING_SYSTEM');
assert(~isempty(file),'[R78] REPLANNING_SYSTEM source not found.');
base=fileparts(file);
cpp=fullfile(base,'af7r36_single_core_mex.cpp');
hpp=fullfile(base,'af7r36_core.hpp');
assert(exist(cpp,'file')==2 && exist(hpp,'file')==2, ...
    '[R78] native MEX source files missing from active class directory.');
s=fileread(file);c=fileread(cpp);h=fileread(hpp);
assert(contains(s,'r78_native_jet7_packet') && ...
    contains(s,'25,P.r78_native_jet7_packet') && ...
    contains(c,'r78_correction_jet7_matrix') && ...
    contains(h,'r78_correction_jet7_identity'), ...
    '[R78] MEX, header, class revision mismatch.');
assert(contains(s,'r67_certified_commit_seam') && ...
    contains(s,'R67_ATOMIC_C6_JET_DISCONTINUITY__KEEP_OLD_REFERENCE'), ...
    '[R78] hard yaw-jet seam guard must remain active.');
S=struct('status','R78_SOURCE_BUNDLED_SEVENTH_JET_PATH_PRESENT', ...
    'source',file,'mex_source',cpp,'header',hpp, ...
    'mex_available',exist('af7r36_single_core_mex','file')==3, ...
    'old_trigger_unchanged',true, ...
    'stage2_seam_guard_unchanged',true, ...
    'whole_body_safety_proved_by_R78',false, ...
    'new_trigger_active',false, ...
    'HLC_EKF_plant_modified',false);
end
