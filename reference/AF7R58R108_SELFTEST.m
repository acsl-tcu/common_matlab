function T=AF7R58R108_SELFTEST()
% One-time source-level regression; it cannot prove dynamics or hardware.
S=AF7R58R108_SOURCE_CHECK();
assert(S.installable||S.already_installed,'R108:UnexpectedMainSource');
root=fileparts(mfilename('fullpath'));
q=fileread(fullfile(root,'REPLANNING_SYSTEM_R108_PATCHED_SOURCE.txt'));
assert(numel(strfind(q,'candidate=obj.r108_generator_dispatch(CTX);'))==1, ...
    'R108:Stage1Dispatch');
assert(numel(strfind(q,'obj.r108_trigger_dispatch(active,pL_ref,q_ref,time.t, ...'))==1, ...
    'R108:TriggerDispatch');
assert(contains(q,'obj.trigger_core(active,pLref,qref,t)') && ...
    contains(q,'AF7R58R103_EKF_HLC_TRIGGER(F,P)'), ...
    'R108:TriggerUnionNotSourceBound');
assert(contains(q,'if obj.r108_keep_postflight_event_copies && ...'), ...
    'R108:PostflightCaptureUnexpected');
assert(contains(q,'if obj.r108_dual_engine_armed && ...') && ...
    contains(q,'candidate=obj.af7r46_single_core_proposal_compact(CTX)'), ...
    'R108:NativeBackupMissing');
assert(contains(q,'prepare_staged_reference_only_bundle(obj,P,t_commit)') && ...
    contains(q,'activate_staged_reference_only_bundle('), ...
    'R108:ExistingCommitGateMissing');
T=struct('status','PASS_R108_DIRECT_MAIN_SOURCE_DISPATCH_REGRESSION', ...
    'in_class_dispatch_sites',2, ...
    'legacy_trigger_preserved',true, ...
    'native_generator_backup_preserved',true, ...
    'closed_loop_physical_prediction_proved',false, ...
    'new_c7_generator_live_certified',false, ...
    'matlab_flight_executed',false, ...
    'dual_engines_enabled',false);
end
