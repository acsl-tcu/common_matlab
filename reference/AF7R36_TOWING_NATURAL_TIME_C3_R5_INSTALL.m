function OUT = AF7R36_TOWING_NATURAL_TIME_C3_R5_INSTALL()
% AF7R36_TOWING_NATURAL_TIME_C3_R5_INSTALL
%
% Replaces ONLY the failed towing-constant secondary candidate family with
% a model-derived towing-aware quadratic objective:
%
%   tau^2 = L/g
%
%   J = integral [ tau^-2 ||d||^2
%                +          ||d_dot||^2
%                + tau^2    ||d_ddot||^2
%                + tau^4    ||d_jerk||^2 ] dt
%
% All four terms have the same physical units.  No arbitrary tuning weight
% is introduced; the only scaling comes from the cable natural time sqrt(L/g).
%
% Why these derivatives:
%   - d controls detour / ballooning,
%   - d_dot controls correction-induced translational speed,
%   - d_ddot affects cable direction through specific force,
%   - d_jerk affects cable angular rate qdot.
%
% Safety is unchanged:
%   candidate -> existing speed certificate -> rejoin certificate
%             -> continuous whole-body certificate.
%
% Existing primary stays first. Historical minimum-snap stays final fallback.
% R4C diagnostic instrumentation, if installed, is retained.
%
% No README and no persistent backup file is created.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 TOWING NATURAL-TIME C3 R5 INSTALL\n');
fprintf(' hard safety certificate semantics modified = 0\n');
fprintf(' primary minimum-deviation retained          = 1\n');
fprintf(' historical minimum-snap fallback retained   = 1\n');
fprintf(' arbitrary objective tuning weights          = 0\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir) && isfolder(refDir), ...
    '[TOWC3-R5] Cannot resolve current reference directory.');

hpp=fullfile(refDir,'af7r36_core.hpp');
cpp=fullfile(refDir,'af7r36_single_core_mex.cpp');
assert(isfile(hpp),'[TOWC3-R5] Missing %s',hpp);
assert(isfile(cpp),'[TOWC3-R5] Missing %s',cpp);

hpp0=normlf(fileread(hpp));
cpp0=normlf(fileread(cpp));
hppNew=hpp0;
cppNew=cpp0;

assert(contains(hpp0,'AF7_TOWING_CONSTANT_V1'), ...
    '[TOWC3-R5] Existing constant towing branch marker not found. No edit made.');
assert(contains(cpp0,'TOWING_CONSTANT_TRANSLATION'), ...
    '[TOWC3-R5] Existing constant-family wrapper output not found. No edit made.');
assert(~contains(hpp0,'AF7_TOWING_NATURAL_TIME_C3_R5'), ...
    '[TOWC3-R5] R5 core already installed.');
assert(~contains(cpp0,'TOWING_NATURAL_TIME_C3'), ...
    '[TOWC3-R5] R5 wrapper already installed.');
assert(contains(cpp0, ...
    'static const char* PLANNER_REV="AF7_REPLANNER_MIN_DEVIATION_V4_FIXED_T1";'), ...
    '[TOWC3-R5] Legacy planner identity is not restored. No edit made.');
assert(contains(cpp0, ...
    'set("compact_constant_translation",logicalScalar(false));'), ...
    '[TOWC3-R5] Legacy compact build-contract flag is not false. No edit made.');

try
    %% --------------------------------------------------------------------
    % 1) Add exact derivative-energy Hessian helpers.
    % ---------------------------------------------------------------------
    anchor='// ------------------------- exact convex QP ----------------------------------';
    helper=[ ...
        '// AF7_TOWING_NATURAL_TIME_C3_R5' sprintf('\n') ...
        '// Exact derivative-energy Hessian for the complete correction.' sprintf('\n') ...
        'static inline void add_transition_derivative_hessian(std::vector<double>&Hs,int nslot,' sprintf('\n') ...
        '                                          const std::vector<std::array<double,8>>&J0,' sprintf('\n') ...
        '                                          const std::vector<std::array<double,8>>&J1,' sprintf('\n') ...
        '                                          double T,int r,double weight){' sprintf('\n') ...
        '    if(!(fin(T)&&T>0&&fin(weight)&&weight>=0&&r>=1&&r<=6))' sprintf('\n') ...
        '        throw std::runtime_error("invalid towing derivative Hessian request");' sprintf('\n') ...
        '    std::vector<std::vector<double>> B(nslot);' sprintf('\n') ...
        '    double ff=1.0;for(int k=0;k<r;++k)ff*=double(15-k);' sprintf('\n') ...
        '    for(int k=0;k<nslot;++k){' sprintf('\n') ...
        '        auto P=scalar_control_from_jets(J0[k],J1[k],T);' sprintf('\n') ...
        '        auto d=diff_scalar(P,r);' sprintf('\n') ...
        '        double sc=ff/std::pow(T,r);' sprintf('\n') ...
        '        for(double&v:d)v*=sc;' sprintf('\n') ...
        '        B[k]=std::move(d);' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '    const int deg=15-r;' sprintf('\n') ...
        '    const int ncp=16-r;' sprintf('\n') ...
        '    for(int i=0;i<nslot;++i)for(int j=0;j<nslot;++j){' sprintf('\n') ...
        '        double v=0.0;' sprintf('\n') ...
        '        for(int a=0;a<ncp;++a)for(int b=0;b<ncp;++b)' sprintf('\n') ...
        '            v+=B[i][a]*gram(deg,a,b)*B[j][b];' sprintf('\n') ...
        '        Hs[i*nslot+j]+=weight*T*v;' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '}' sprintf('\n') ...
        '' sprintf('\n') ...
        'static inline std::vector<double> towing_natural_time_c3_hessian(' sprintf('\n') ...
        '        const std::vector<Component>&comp,double t0,double t1,double cableL,double gravity){' sprintf('\n') ...
        '    if(!(fin(cableL)&&cableL>0&&fin(gravity)&&gravity>0))' sprintf('\n') ...
        '        throw std::runtime_error("invalid towing natural-time parameters");' sprintf('\n') ...
        '    int C=(int)comp.size(),nslot=2*C;' sprintf('\n') ...
        '    std::vector<double>Hs(nslot*nslot,0.0);' sprintf('\n') ...
        '    std::vector<std::array<double,8>>J0,J1;' sprintf('\n') ...
        '    const double tau2=cableL/gravity;' sprintf('\n') ...
        '    const double w0=1.0/tau2;' sprintf('\n') ...
        '    const double w1=1.0;' sprintf('\n') ...
        '    const double w2=tau2;' sprintf('\n') ...
        '    const double w3=tau2*tau2;' sprintf('\n') ...
        '' sprintf('\n') ...
        '    auto add_transition=[&](double T){' sprintf('\n') ...
        '        add_transition_deviation_hessian(Hs,nslot,J0,J1,T);' sprintf('\n') ...
        '        // Convert the position term from weight 1 to weight g/L.' sprintf('\n') ...
        '        // Rebuild its contribution exactly by scaling a temporary copy.' sprintf('\n') ...
        '    };' sprintf('\n') ...
        '' sprintf('\n') ...
        '    auto add_all=[&](double T){' sprintf('\n') ...
        '        std::vector<double> Hp(nslot*nslot,0.0);' sprintf('\n') ...
        '        add_transition_deviation_hessian(Hp,nslot,J0,J1,T);' sprintf('\n') ...
        '        for(int i=0;i<nslot*nslot;++i)Hs[i]+=w0*Hp[i];' sprintf('\n') ...
        '        add_transition_derivative_hessian(Hs,nslot,J0,J1,T,1,w1);' sprintf('\n') ...
        '        add_transition_derivative_hessian(Hs,nslot,J0,J1,T,2,w2);' sprintf('\n') ...
        '        add_transition_derivative_hessian(Hs,nslot,J0,J1,T,3,w3);' sprintf('\n') ...
        '    };' sprintf('\n') ...
        '' sprintf('\n') ...
        '    scalar_endpoint_maps(comp,0,0,0,nslot,J0,J1);' sprintf('\n') ...
        '    add_all(comp[0].start-t0);' sprintf('\n') ...
        '    for(int j=0;j<C-1;++j){' sprintf('\n') ...
        '        scalar_endpoint_maps(comp,j,j+1,1,nslot,J0,J1);' sprintf('\n') ...
        '        add_all(comp[j+1].start-comp[j].end);' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '    scalar_endpoint_maps(comp,C-1,0,2,nslot,J0,J1);' sprintf('\n') ...
        '    add_all(t1-comp.back().end);' sprintf('\n') ...
        '' sprintf('\n') ...
        '    // Unsafe affine span d(s)=a+v*s:' sprintf('\n') ...
        '    // position term is exact; velocity term is D*||v||^2;' sprintf('\n') ...
        '    // acceleration and jerk are identically zero on the affine span.' sprintf('\n') ...
        '    for(int j=0;j<C;++j){' sprintf('\n') ...
        '        double D=comp[j].end-comp[j].start;' sprintf('\n') ...
        '        if(!(fin(D)&&D>0))throw std::runtime_error("nonpositive unsafe component duration");' sprintf('\n') ...
        '        int ip=2*j,iv=2*j+1;' sprintf('\n') ...
        '        Hs[ip*nslot+ip]+=w0*D;' sprintf('\n') ...
        '        Hs[ip*nslot+iv]+=w0*0.5*D*D;' sprintf('\n') ...
        '        Hs[iv*nslot+ip]+=w0*0.5*D*D;' sprintf('\n') ...
        '        Hs[iv*nslot+iv]+=w0*(D*D*D)/3.0;' sprintf('\n') ...
        '        Hs[iv*nslot+iv]+=w1*D;' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '' sprintf('\n') ...
        '    int n=3*nslot;std::vector<double>H(n*n,0.0);' sprintf('\n') ...
        '    for(int i=0;i<nslot;++i)for(int j=0;j<nslot;++j)for(int d=0;d<3;++d)' sprintf('\n') ...
        '        H[(3*i+d)*n+(3*j+d)]=Hs[i*nslot+j];' sprintf('\n') ...
        '    return H;' sprintf('\n') ...
        '}' sprintf('\n') ...
        '' sprintf('\n') ...
        anchor];
    hppNew=replace_once(hppNew,anchor,helper,'exact convex QP anchor');

    % Remove an intentionally unused lambda if present in helper text.
    hppNew=strrep(hppNew, ...
        ['    auto add_transition=[&](double T){' sprintf('\n') ...
         '        add_transition_deviation_hessian(Hs,nslot,J0,J1,T);' sprintf('\n') ...
         '        // Convert the position term from weight 1 to weight g/L.' sprintf('\n') ...
         '        // Rebuild its contribution exactly by scaling a temporary copy.' sprintf('\n') ...
         '    };' sprintf('\n') sprintf('\n')], ...
        '');

    %% --------------------------------------------------------------------
    % 2) Replace only the failed constant secondary family.
    % ---------------------------------------------------------------------
    startMarker='    // AF7_TOWING_CONSTANT_V1';
    endMarker=['    // ------------------------------------------------------------------' sprintf('\n') ...
               '    // FALLBACK: exact previously flown affine/minimum-snap family.'];

    newBranch=[ ...
        '    // AF7_TOWING_NATURAL_TIME_C3_R5' sprintf('\n') ...
        '    // TOWING-SPECIFIC SECONDARY FAMILY.' sprintf('\n') ...
        '    //' sprintf('\n') ...
        '    // tau^2=L/g, and the exact quadratic objective is' sprintf('\n') ...
        '    //' sprintf('\n') ...
        '    // J = integral [ tau^-2 |d|^2 + |d_dot|^2' sprintf('\n') ...
        '    //              + tau^2 |d_ddot|^2 + tau^4 |d_jerk|^2 ] dt.' sprintf('\n') ...
        '    //' sprintf('\n') ...
        '    // Every term has identical physical units. No tuning weight is used.' sprintf('\n') ...
        '    // The original affine unsafe structure and degree-15 C7 transitions' sprintf('\n') ...
        '    // are unchanged. This is synthesis preference only; hard acceptance' sprintf('\n') ...
        '    // remains speed -> rejoin -> continuous whole-body.' sprintf('\n') ...
        '    // ------------------------------------------------------------------' sprintf('\n') ...
        '    ts=clk::now();' sprintf('\n') ...
        '    {' sprintf('\n') ...
        '        auto Htow=towing_natural_time_c3_hessian(E.comp,t0,t1,L.L,L.g);' sprintf('\n') ...
        '        std::vector<Base> BT;' sprintf('\n') ...
        '        std::vector<int> sg(Ne,1);' sprintf('\n') ...
        '        std::function<void(int)> rec=[&](int k){' sprintf('\n') ...
        '            if(k<Ne){sg[k]=1;rec(k+1);sg[k]=-1;rec(k+1);return;}' sprintf('\n') ...
        '            std::vector<Row> rows;' sprintf('\n') ...
        '            for(int e=0;e<Ne;++e){' sprintf('\n') ...
        '                const auto& src=(sg[e]>0)?OR[e].plus:OR[e].minus;' sprintf('\n') ...
        '                rows.insert(rows.end(),src.begin(),src.end());' sprintf('\n') ...
        '            }' sprintf('\n') ...
        '            QPSol q=solve_qp(Htow,nvar,rows);' sprintf('\n') ...
        '            if(q.ok)BT.push_back({q.z,q.cost,q.slack,sg});' sprintf('\n') ...
        '        };' sprintf('\n') ...
        '        rec(0);' sprintf('\n') ...
        '' sprintf('\n') ...
        '        std::vector<Candidate> towing;' sprintf('\n') ...
        '        towing.reserve(BT.size());' sprintf('\n') ...
        '        for(auto&b:BT)' sprintf('\n') ...
        '            towing.push_back(build_candidate(E.comp,t0,t1,b.z,b.c,b.sg,b.s,3));' sprintf('\n') ...
        '        R.tim.qp+=std::chrono::duration<double,std::milli>(clk::now()-ts).count();' sprintf('\n') ...
        '        auto tc=clk::now();' sprintf('\n') ...
        '        if(certify_candidates(towing,true,3)){' sprintf('\n') ...
        '            R.tim.candidate_build+=std::chrono::duration<double,std::milli>(clk::now()-tc).count();' sprintf('\n') ...
        '            R.tim.synthesis=std::chrono::duration<double,std::milli>(clk::now()-a).count();' sprintf('\n') ...
        '            R.tim.candidate=R.tim.synthesis;' sprintf('\n') ...
        '            R.tim.total=std::chrono::duration<double,std::milli>(clk::now()-T0).count();' sprintf('\n') ...
        '            return R;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '        R.tim.candidate_build+=std::chrono::duration<double,std::milli>(clk::now()-tc).count();' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '' sprintf('\n') ...
        '    // ------------------------------------------------------------------' sprintf('\n')];

    hppNew=replace_between(hppNew,startMarker,endMarker,newBranch,'constant towing branch');

    % Update family documentation if present.
    hppNew=strrep(hppNew, ...
        '    //         3 = towing constant-translation minimum-deviation family.', ...
        '    //         3 = towing natural-time C3 quadratic family.');

    %% --------------------------------------------------------------------
    % 3) Wrapper name only. Build identity remains unchanged.
    % ---------------------------------------------------------------------
    cppNew=replace_once(cppNew, ...
        '"TOWING_CONSTANT_TRANSLATION"', ...
        '"TOWING_NATURAL_TIME_C3"', ...
        'candidate family string');

    assert(contains(cppNew, ...
        'static const char* PLANNER_REV="AF7_REPLANNER_MIN_DEVIATION_V4_FIXED_T1";'), ...
        '[TOWC3-R5] planner_native_revision changed unexpectedly.');
    assert(contains(cppNew, ...
        'set("compact_constant_translation",logicalScalar(false));'), ...
        '[TOWC3-R5] compact build-contract flag changed unexpectedly.');

    % Structural audits.
    assert(count_exact(hppNew,'AF7_TOWING_NATURAL_TIME_C3_R5')>=2, ...
        '[TOWC3-R5] R5 helper/branch markers incomplete.');
    assert(count_exact(hppNew,'AF7_TOWING_CONSTANT_V1')==0, ...
        '[TOWC3-R5] Old constant branch marker remains.');
    assert(count_exact(cppNew,'"TOWING_NATURAL_TIME_C3"')==1, ...
        '[TOWC3-R5] New candidate-family string count is not one.');
    assert(count_exact(cppNew,'"TOWING_CONSTANT_TRANSLATION"')==0, ...
        '[TOWC3-R5] Old family string remains.');

    %% --------------------------------------------------------------------
    % 4) Stage compile before touching production.
    % ---------------------------------------------------------------------
    stageDir=tempname;
    [ok,msg]=mkdir(stageDir);
    assert(ok,'[TOWC3-R5] Cannot create staging directory: %s',msg);
    stageCleanup=onCleanup(@()cleanup_stage(stageDir)); %#ok<NASGU>

    stagedHpp=fullfile(stageDir,'af7r36_core.hpp');
    stagedCpp=fullfile(stageDir,'af7r36_single_core_mex.cpp');
    write_text(stagedHpp,hppNew);
    write_text(stagedCpp,cppNew);

    fprintf('[TOWC3-R5] Compiling staged MEX...\n');
    oldDir=pwd;
    cwdCleanup=onCleanup(@()cd(oldDir)); %#ok<NASGU>
    cd(stageDir);
    clear mex;

    mex('-R2018a','-O', ...
        'COMPFLAGS="$COMPFLAGS /std:c++17"', ...
        ['-I' stageDir], ...
        '-output','af7r36_single_core_mex', ...
        '-outdir',stageDir, ...
        stagedCpp);

    stagedMex=fullfile(stageDir,['af7r36_single_core_mex.' mexext]);
    assert(isfile(stagedMex),'[TOWC3-R5] Staged MEX binary missing.');

    dstMex=fullfile(refDir,['af7r36_single_core_mex.' mexext]);
    oldMexTmp=fullfile(stageDir,['af7r36_single_core_mex_OLD.' mexext]);
    hadOldMex=isfile(dstMex);
    if hadOldMex
        [ok,msg]=copyfile(dstMex,oldMexTmp,'f');
        assert(ok,'[TOWC3-R5] Cannot stage rollback MEX: %s',msg);
    end

    cd(oldDir);
    clear mex;

    wroteH=false;wroteC=false;installedMex=false;
    try
        write_text(hpp,hppNew);wroteH=true;
        write_text(cpp,cppNew);wroteC=true;
        [ok,msg]=copyfile(stagedMex,dstMex,'f');
        assert(ok,'[TOWC3-R5] Cannot install staged MEX: %s',msg);
        installedMex=true;

        clear mex;
        rehash;
        assert(exist('af7r36_single_core_mex','file')==3, ...
            '[TOWC3-R5] Installed MEX not visible.');

        % If R4C diagnostic op exists, clear its ring before the next run.
        try
            af7r36_single_core_mex(7);
        catch
        end

    catch ME2
        if wroteH, try, write_text(hpp,hpp0); catch, end, end
        if wroteC, try, write_text(cpp,cpp0); catch, end, end
        if installedMex && hadOldMex
            try, copyfile(oldMexTmp,dstMex,'f'); catch, end
        end
        clear mex;rehash;
        rethrow(ME2);
    end

    fprintf('[TOWC3-R5] PASS.\n');
    fprintf('  family 1: minimum-deviation unchanged      = 1\n');
    fprintf('  family 3: towing natural-time C3            = 1\n');
    fprintf('  family 2: minimum-snap fallback unchanged   = 1\n');
    fprintf('  speed/rejoin/whole-body gates unchanged     = 1\n');
    fprintf('  planner build identity unchanged            = 1\n');
    fprintf('  README created                              = 0\n');
    fprintf('  persistent backup files created             = 0\n');

    OUT=struct();
    OUT.pass=true;
    OUT.reference_dir=refDir;
    OUT.revision='AF7_TOWING_NATURAL_TIME_C3_R5';
    OUT.hard_certificate_semantics_modified=false;
    OUT.primary_retained=true;
    OUT.minimum_snap_fallback_retained=true;
    OUT.arbitrary_objective_weights=false;
    OUT.readme_created=false;
    OUT.persistent_backup_created=false;

catch ME
    clear mex;rehash;
    fprintf(2,'[TOWC3-R5] FAILED. No successful production install completed.\n');
    rethrow(ME);
end
end

function txt=replace_between(txt,startPat,endPat,new,label)
a=strfind(txt,startPat);
assert(numel(a)==1,'[TOWC3-R5] %s start count=%d; expected 1.',label,numel(a));
bAll=strfind(txt,endPat);
b=bAll(find(bAll>a,1,'first'));
assert(~isempty(b),'[TOWC3-R5] %s end marker not found after start.',label);
txt=[txt(1:a-1) new txt(b:end)];
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1, ...
    '[TOWC3-R5] Anchor "%s" count=%d; expected exactly 1.',label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end

function n=count_exact(txt,pat)
n=numel(strfind(txt,pat));
end

function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));
s=strrep(s,sprintf('\r'),sprintf('\n'));
end

function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');
assert(f>=0,'[TOWC3-R5] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end

function cleanup_stage(d)
if isfolder(d)
    try, rmdir(d,'s'); catch, end
end
end
