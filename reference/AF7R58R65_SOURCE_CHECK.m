function S=AF7R58R65_SOURCE_CHECK()
root=fileparts(mfilename('fullpath'));
f=which('REPLANNING_SYSTEM');
assert(strcmpi(f,fullfile(root,'REPLANNING_SYSTEM.m')), ...
    '[R65] REPLANNING_SYSTEM is shadowed by another path.');
assert(~isempty(meta.class.fromName('REPLANNING_SYSTEM')), ...
    '[R65] class syntax parser failed.');
code=fileread(f);
keys={'r65_native_canonical_agreement', ...
    'R65_REFERENCE_JET_MISMATCH_ORDER_', ...
    'r63_live_now_gate'};
assert(all(cellfun(@(k)contains(code,k),keys)), ...
    '[R65] expected jet gate or EKF-now code absent.');
S=struct('source',f,'matlab_class_parser_passed',true, ...
    'native_canonical_jet_gate_installed',true, ...
    'hlc_source_unchanged',true, ...
    'closed_loop_4s_current_EKF_future_installed',false, ...
    'natural_C7_return_committed',false, ...
    'reference_only_wrong_jet_commit_prevented',true);
end
