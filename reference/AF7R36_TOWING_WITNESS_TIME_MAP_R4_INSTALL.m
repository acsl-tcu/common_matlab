function OUT = AF7R36_TOWING_WITNESS_TIME_MAP_R4_INSTALL()
% AF7R36_TOWING_WITNESS_TIME_MAP_R4_INSTALL
% Diagnostic-only instrumentation:
%   - captures exact Stage-B finite speed witness location/value
%     for PRIMARY and TOWING candidate families;
%   - records every fixed-t1 MEX planning call in a bounded in-MEX ring,
%     allowing the actual MATLAB adaptive rejoin search to be reconstructed.
%
% It does NOT change:
%   candidate generation, candidate ordering, speed threshold,
%   rejoin test, whole-body certificate, commit policy, or planner revision.
%
% No README and no persistent backup files are created.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 TOWING WITNESS + TIME MAP R4 INSTALL\n');
fprintf(' trajectory generation modified            = 0\n');
fprintf(' hard certificate semantics modified       = 0\n');
fprintf(' adaptive-search decision modified          = 0\n');
fprintf(' bounded diagnostic ring only               = 1\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir) && isfolder(refDir), ...
    '[TOWMAP-R4] Cannot resolve current reference directory.');

hpp=fullfile(refDir,'af7r36_core.hpp');
cpp=fullfile(refDir,'af7r36_single_core_mex.cpp');
assert(isfile(hpp),'[TOWMAP-R4] Missing %s',hpp);
assert(isfile(cpp),'[TOWMAP-R4] Missing %s',cpp);

hpp0=normlf(fileread(hpp));
cpp0=normlf(fileread(cpp));
hppNew=hpp0;
cppNew=cpp0;

% Required current architecture: towing branch already installed, legacy
% planner identity already restored by R3.
assert(contains(hpp0,'TOWING-SPECIFIC SECONDARY FAMILY') || ...
       contains(hpp0,'AF7_TOWING_CONSTANT_V1'), ...
    '[TOWMAP-R4] Current towing branch not found. No edit made.');
assert(contains(cpp0,'TOWING_CONSTANT_TRANSLATION'), ...
    '[TOWMAP-R4] Towing family output not found. No edit made.');
assert(contains(cpp0, ...
    'static const char* PLANNER_REV="AF7_REPLANNER_MIN_DEVIATION_V4_FIXED_T1";'), ...
    '[TOWMAP-R4] Legacy planner build identity is not restored. No edit made.');
assert(~contains(hpp0,'AF7_TOWMAP_R4_SPEED_WITNESS'), ...
    '[TOWMAP-R4] Core diagnostic instrumentation already present.');
assert(~contains(cpp0,'AF7_TOWMAP_R4_RING'), ...
    '[TOWMAP-R4] MEX diagnostic ring already present.');

try
    %% --------------------------------------------------------------------
    % 1) Add rejection-only witness storage to PlanResult.
    % ---------------------------------------------------------------------
    anchor='    int towing_geom_tests=0;';
    block=[anchor sprintf('\n') ...
        sprintf('\n') ...
        '    // AF7_TOWMAP_R4_SPEED_WITNESS: rejection-only diagnostics.' sprintf('\n') ...
        '    // class: 1=ENTRY_C7, 2=UNSAFE_AFFINE, 3=INTER_C7, 4=EXIT_REJOIN_C7.' sprintf('\n') ...
        '    int primary_finite_witness_count=0;' sprintf('\n') ...
        '    double primary_witness_min_vq=std::numeric_limits<double>::infinity();' sprintf('\n') ...
        '    double primary_witness_min_t=std::numeric_limits<double>::quiet_NaN();' sprintf('\n') ...
        '    int primary_witness_min_seg=-1,primary_witness_min_class=0;' sprintf('\n') ...
        '    double primary_witness_max_vq=-std::numeric_limits<double>::infinity();' sprintf('\n') ...
        '    double primary_witness_max_t=std::numeric_limits<double>::quiet_NaN();' sprintf('\n') ...
        '    int primary_witness_max_seg=-1,primary_witness_max_class=0;' sprintf('\n') ...
        '    int towing_finite_witness_count=0;' sprintf('\n') ...
        '    double towing_witness_min_vq=std::numeric_limits<double>::infinity();' sprintf('\n') ...
        '    double towing_witness_min_t=std::numeric_limits<double>::quiet_NaN();' sprintf('\n') ...
        '    int towing_witness_min_seg=-1,towing_witness_min_class=0;' sprintf('\n') ...
        '    double towing_witness_max_vq=-std::numeric_limits<double>::infinity();' sprintf('\n') ...
        '    double towing_witness_max_t=std::numeric_limits<double>::quiet_NaN();' sprintf('\n') ...
        '    int towing_witness_max_seg=-1,towing_witness_max_class=0;'];
    hppNew=replace_once(hppNew,anchor,block,'PlanResult towing counter anchor');

    %% --------------------------------------------------------------------
    % 2) Preserve exact Stage-B rejection witness coordinates.
    % ---------------------------------------------------------------------
    anchor='struct VLeaf {';
    block=[ ...
        '// AF7_TOWMAP_R4_SPEED_WITNESS' sprintf('\n') ...
        'struct SpeedWitness {' sprintf('\n') ...
        '    bool valid=false;' sprintf('\n') ...
        '    int seg=-1;' sprintf('\n') ...
        '    double t=std::numeric_limits<double>::quiet_NaN();' sprintf('\n') ...
        '    double vq=std::numeric_limits<double>::quiet_NaN();' sprintf('\n') ...
        '};' sprintf('\n') ...
        anchor];
    hppNew=replace_once(hppNew,anchor,block,'SpeedWitness declaration');

    old=['static inline SpeedCert stageB_speed(const ActiveReference&ref,const Live&L,const SpeedCert&base,' sprintf('\n') ...
         '                                     const Candidate&C,double lim,bool&finiteWitness,bool&repr){'];
    new=['static inline SpeedCert stageB_speed(const ActiveReference&ref,const Live&L,const SpeedCert&base,' sprintf('\n') ...
         '                                     const Candidate&C,double lim,bool&finiteWitness,bool&repr,' sprintf('\n') ...
         '                                     SpeedWitness* witnessDiag=nullptr){'];
    hppNew=replace_once(hppNew,old,new,'Stage-B signature');

    old='        for(auto&f:leaves)if(fin(f.wit)&&f.wit>=lim){finiteWitness=true;return {};}';
    new=[ ...
        '        for(auto&f:leaves)if(fin(f.wit)&&f.wit>=lim){' sprintf('\n') ...
        '            finiteWitness=true;' sprintf('\n') ...
        '            if(witnessDiag){' sprintf('\n') ...
        '                witnessDiag->valid=true;' sprintf('\n') ...
        '                witnessDiag->seg=f.seg;' sprintf('\n') ...
        '                witnessDiag->t=0.5*(f.ta+f.tb);' sprintf('\n') ...
        '                witnessDiag->vq=f.wit;' sprintf('\n') ...
        '            }' sprintf('\n') ...
        '            return {};' sprintf('\n') ...
        '        }'];
    hppNew=replace_once(hppNew,old,new,'Stage-B finite witness return');

    %% --------------------------------------------------------------------
    % 3) Record witness branch and segment class without altering rejection.
    % ---------------------------------------------------------------------
    anchor='    auto certify_candidates=[&](std::vector<Candidate>& candidates,bool envelopeOrder,int branch)->bool{';
    block=[ ...
        '    auto towmap_record_witness=[&](int branch,const SpeedWitness&w){' sprintf('\n') ...
        '        if(!w.valid||!fin(w.vq)||!fin(w.t))return;' sprintf('\n') ...
        '        int cls=0;' sprintf('\n') ...
        '        if(w.seg==0)cls=1;' sprintf('\n') ...
        '        else if(w.seg==2*Cn)cls=4;' sprintf('\n') ...
        '        else if((w.seg&1)==1)cls=2;' sprintf('\n') ...
        '        else cls=3;' sprintf('\n') ...
        '        if(branch==1){' sprintf('\n') ...
        '            ++R.primary_finite_witness_count;' sprintf('\n') ...
        '            if(w.vq<R.primary_witness_min_vq){R.primary_witness_min_vq=w.vq;R.primary_witness_min_t=w.t;R.primary_witness_min_seg=w.seg;R.primary_witness_min_class=cls;}' sprintf('\n') ...
        '            if(w.vq>R.primary_witness_max_vq){R.primary_witness_max_vq=w.vq;R.primary_witness_max_t=w.t;R.primary_witness_max_seg=w.seg;R.primary_witness_max_class=cls;}' sprintf('\n') ...
        '        }else if(branch==3){' sprintf('\n') ...
        '            ++R.towing_finite_witness_count;' sprintf('\n') ...
        '            if(w.vq<R.towing_witness_min_vq){R.towing_witness_min_vq=w.vq;R.towing_witness_min_t=w.t;R.towing_witness_min_seg=w.seg;R.towing_witness_min_class=cls;}' sprintf('\n') ...
        '            if(w.vq>R.towing_witness_max_vq){R.towing_witness_max_vq=w.vq;R.towing_witness_max_t=w.t;R.towing_witness_max_seg=w.seg;R.towing_witness_max_class=cls;}' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '    };' sprintf('\n') sprintf('\n') ...
        anchor];
    hppNew=replace_once(hppNew,anchor,block,'certify_candidates anchor');

    old='            if(!sc.certified){bool wit=false,rp=false;sc=stageB_speed(ref,L,base,cand,lim,wit,rp);}';
    new=[ ...
        '            if(!sc.certified){' sprintf('\n') ...
        '                bool wit=false,rp=false;SpeedWitness sw;' sprintf('\n') ...
        '                sc=stageB_speed(ref,L,base,cand,lim,wit,rp,&sw);' sprintf('\n') ...
        '                if(wit)towmap_record_witness(branch,sw);' sprintf('\n') ...
        '            }'];
    hppNew=replace_once(hppNew,old,new,'Stage-B call site');

    %% --------------------------------------------------------------------
    % 4) Add an in-MEX bounded call ring. No planner output contract changes.
    % ---------------------------------------------------------------------
    anchor='static bool G_compiled=false;';
    block=[anchor sprintf('\n') sprintf('\n') ...
        '// AF7_TOWMAP_R4_RING: diagnostic only; cleared by MEX reload/op7.' sprintf('\n') ...
        'struct TowMapEntry {' sprintf('\n') ...
        '    double seq=0,t0=NAN,tm=NAN,t1=NAN,limit=NAN;' sprintf('\n') ...
        '    double success=0,family=0,envelope=NAN,VQ=NAN,VL=NAN,A=NAN,J=NAN,sigma=NAN,qdot=NAN,total_ms=NAN;' sprintf('\n') ...
        '    double pc=0,ps=0,pr=0,pg=0,tc=0,ts=0,tr=0,tg=0,fc=0,fs=0,fr=0,fg=0;' sprintf('\n') ...
        '    double pwc=0,pwmin=NAN,pwmint=NAN,pwmins=NAN,pwminc=NAN,pwmax=NAN,pwmaxt=NAN,pwmaxs=NAN,pwmaxc=NAN;' sprintf('\n') ...
        '    double twc=0,twmin=NAN,twmint=NAN,twmins=NAN,twminc=NAN,twmax=NAN,twmaxt=NAN,twmaxs=NAN,twmaxc=NAN;' sprintf('\n') ...
        '};' sprintf('\n') ...
        'static std::vector<TowMapEntry> G_towmap;' sprintf('\n') ...
        'static double G_towmap_seq=0;' sprintf('\n') ...
        'static inline double finite_or_nan(double x){return std::isfinite(x)?x:NAN;}' sprintf('\n') ...
        'static void towmap_push(const PlanResult&Q,const Live&L,double t0,double tm,double t1){' sprintf('\n') ...
        '    TowMapEntry d;d.seq=++G_towmap_seq;d.t0=t0;d.tm=tm;d.t1=t1;' sprintf('\n') ...
        '    double rho=std::max({L.rQ,L.L+L.rL,L.L+L.rC});d.limit=(L.sensor_range-rho)/(L.horizon+L.dt);' sprintf('\n') ...
        '    d.success=Q.success?1.0:0.0;d.family=(double)Q.cand.family;' sprintf('\n') ...
        '    d.envelope=Q.success?Q.cand.max_ctrl:NAN;d.VQ=Q.success?Q.speed.VQ:NAN;d.VL=Q.success?Q.speed.VL:NAN;' sprintf('\n') ...
        '    d.A=Q.success?Q.speed.A:NAN;d.J=Q.success?Q.speed.J:NAN;d.sigma=Q.success?Q.speed.sigma:NAN;d.qdot=Q.success?Q.speed.qdot:NAN;d.total_ms=Q.tim.total;' sprintf('\n') ...
        '    d.pc=Q.primary_candidate_count;d.ps=Q.primary_speed_pass;d.pr=Q.primary_rejoin_pass;d.pg=Q.primary_geom_tests;' sprintf('\n') ...
        '    d.tc=Q.towing_candidate_count;d.ts=Q.towing_speed_pass;d.tr=Q.towing_rejoin_pass;d.tg=Q.towing_geom_tests;' sprintf('\n') ...
        '    d.fc=Q.fallback_candidate_count;d.fs=Q.fallback_speed_pass;d.fr=Q.fallback_rejoin_pass;d.fg=Q.fallback_geom_tests;' sprintf('\n') ...
        '    d.pwc=Q.primary_finite_witness_count;d.pwmin=finite_or_nan(Q.primary_witness_min_vq);d.pwmint=Q.primary_witness_min_t;d.pwmins=Q.primary_witness_min_seg;d.pwminc=Q.primary_witness_min_class;' sprintf('\n') ...
        '    d.pwmax=finite_or_nan(Q.primary_witness_max_vq);d.pwmaxt=Q.primary_witness_max_t;d.pwmaxs=Q.primary_witness_max_seg;d.pwmaxc=Q.primary_witness_max_class;' sprintf('\n') ...
        '    d.twc=Q.towing_finite_witness_count;d.twmin=finite_or_nan(Q.towing_witness_min_vq);d.twmint=Q.towing_witness_min_t;d.twmins=Q.towing_witness_min_seg;d.twminc=Q.towing_witness_min_class;' sprintf('\n') ...
        '    d.twmax=finite_or_nan(Q.towing_witness_max_vq);d.twmaxt=Q.towing_witness_max_t;d.twmaxs=Q.towing_witness_max_seg;d.twmaxc=Q.towing_witness_max_class;' sprintf('\n') ...
        '    if(G_towmap.size()>=512)G_towmap.erase(G_towmap.begin());G_towmap.push_back(d);' sprintf('\n') ...
        '}' sprintf('\n') ...
        'static mxArray* towmap_matrix(){' sprintf('\n') ...
        '    const mwSize N=(mwSize)G_towmap.size(),C=44;mxArray*M=mxCreateDoubleMatrix(N,C,mxREAL);double*p=mxGetPr(M);' sprintf('\n') ...
        '    for(mwSize i=0;i<N;++i){const auto&d=G_towmap[i];double v[C]={' sprintf('\n') ...
        '        d.seq,d.t0,d.tm,d.t1,d.limit,d.success,d.family,d.envelope,d.VQ,d.VL,d.A,d.J,d.sigma,d.qdot,d.total_ms,' sprintf('\n') ...
        '        d.pc,d.ps,d.pr,d.pg,d.tc,d.ts,d.tr,d.tg,d.fc,d.fs,d.fr,d.fg,' sprintf('\n') ...
        '        d.pwc,d.pwmin,d.pwmint,d.pwmins,d.pwminc,d.pwmax,d.pwmaxt,d.pwmaxs,d.pwmaxc,' sprintf('\n') ...
        '        d.twc,d.twmin,d.twmint,d.twmins,d.twminc,d.twmax,d.twmaxt,d.twmaxs,d.twmaxc};' sprintf('\n') ...
        '        for(mwSize j=0;j<C;++j)p[i+N*j]=v[j];' sprintf('\n') ...
        '    }return M;' sprintf('\n') ...
        '}'];
    cppNew=replace_once(cppNew,anchor,block,'MEX diagnostic ring globals');

    old='            PlanResult Q=plan(R,L,B,O,t0,tm,searchEnd);';
    new=[old sprintf('\n') ...
        '            towmap_push(Q,L,t0,tm,searchEnd);'];
    cppNew=replace_once(cppNew,old,new,'op1 ring capture');

    anchor='        if(op==3){';
    block=[ ...
        '        if(op==6){' sprintf('\n') ...
        '            if(nrhs!=1||nlhs!=1) mexErrMsgIdAndTxt("AF7TOWMAP:Arity","diag op: op -> matrix.");' sprintf('\n') ...
        '            plhs[0]=towmap_matrix();return;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '        if(op==7){' sprintf('\n') ...
        '            if(nrhs!=1||nlhs>1) mexErrMsgIdAndTxt("AF7TOWMAP:Arity","clear diag op: op.");' sprintf('\n') ...
        '            G_towmap.clear();G_towmap_seq=0;if(nlhs>0)plhs[0]=logicalScalar(true);return;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        anchor];
    cppNew=replace_once(cppNew,anchor,block,'diagnostic op insertion');

    % Explicitly verify forbidden compatibility changes are absent.
    assert(contains(cppNew, ...
        'static const char* PLANNER_REV="AF7_REPLANNER_MIN_DEVIATION_V4_FIXED_T1";'), ...
        '[TOWMAP-R4] Planner revision changed unexpectedly.');
    assert(contains(cppNew, ...
        'set("compact_constant_translation",logicalScalar(false));'), ...
        '[TOWMAP-R4] Legacy compact build flag changed unexpectedly.');

    %% --------------------------------------------------------------------
    % 5) Stage compile before production write.
    % ---------------------------------------------------------------------
    stageDir=tempname;
    [ok,msg]=mkdir(stageDir);
    assert(ok,'[TOWMAP-R4] Cannot create staging directory: %s',msg);
    stageCleanup=onCleanup(@()cleanup_stage(stageDir)); %#ok<NASGU>

    stagedHpp=fullfile(stageDir,'af7r36_core.hpp');
    stagedCpp=fullfile(stageDir,'af7r36_single_core_mex.cpp');
    write_text(stagedHpp,hppNew);
    write_text(stagedCpp,cppNew);

    fprintf('[TOWMAP-R4] Compiling staged diagnostic MEX...\n');
    oldDir=pwd;
    cwdCleanup=onCleanup(@()cd(oldDir)); %#ok<NASGU>
    cd(stageDir);
    clear mex;
    mex('-R2018a','-O', ...
        'COMPFLAGS="$COMPFLAGS /std:c++17"', ...
        ['-I' stageDir], ...
        '-output','af7r36_single_core_mex', ...
        '-outdir',stageDir, ...
        stagedCpp);

    stagedMex=fullfile(stageDir,['af7r36_single_core_mex.' mexext]);
    assert(isfile(stagedMex),'[TOWMAP-R4] Staged MEX binary missing.');

    cd(oldDir);
    clear mex;

    wroteH=false;wroteC=false;
    try
        write_text(hpp,hppNew);wroteH=true;
        write_text(cpp,cppNew);wroteC=true;
        dstMex=fullfile(refDir,['af7r36_single_core_mex.' mexext]);
        [ok,msg]=copyfile(stagedMex,dstMex,'f');
        assert(ok,'[TOWMAP-R4] Cannot install staged MEX: %s',msg);
        clear mex;
        rehash;
        assert(exist('af7r36_single_core_mex','file')==3, ...
            '[TOWMAP-R4] Installed MEX is not visible.');
        af7r36_single_core_mex(7); % clear ring before next simulation
    catch ME2
        if wroteH, try, write_text(hpp,hpp0); catch, end, end
        if wroteC, try, write_text(cpp,cpp0); catch, end, end
        clear mex;rehash;
        rethrow(ME2);
    end

    fprintf('[TOWMAP-R4] PASS.\n');
    fprintf('  witness location/value capture            = 1\n');
    fprintf('  fixed-t1 call ring capacity                = 512\n');
    fprintf('  trajectory generation modified             = 0\n');
    fprintf('  hard certificate semantics modified        = 0\n');
    fprintf('  planner build identity modified             = 0\n');
    fprintf('  README created                              = 0\n');
    fprintf('  persistent backup files created             = 0\n');
    fprintf('  NOTE: timing from this diagnostic run is not production timing.\n');

    OUT=struct('pass',true, ...
        'reference_dir',refDir, ...
        'revision','AF7_TOWMAP_R4', ...
        'ring_capacity',512, ...
        'trajectory_generation_modified',false, ...
        'hard_certificate_semantics_modified',false, ...
        'readme_created',false, ...
        'persistent_backup_created',false);

catch ME
    clear mex;
    rehash;
    fprintf(2,'[TOWMAP-R4] FAILED. Staged compile/write did not close.\n');
    rethrow(ME);
end
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1, ...
    '[TOWMAP-R4] Anchor "%s" count=%d; expected exactly 1.',label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end

function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));
s=strrep(s,sprintf('\r'),sprintf('\n'));
end

function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');
assert(f>=0,'[TOWMAP-R4] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end

function cleanup_stage(d)
if isfolder(d)
    try, rmdir(d,'s'); catch, end
end
end
