function T=AF7R58R83_SELFTEST()
% Standalone R83 adapter contract; not a substitute for real Flight results.
J=zeros(3,8);J(2,2)=0.7;L=2;
ids=[3,4];eye9=eye(3);P=struct('C',[5 100;0 0;1 1], ...
  'R',repmat(eye9(:),1,2), ...
  'Araw',repmat([0.2;0.2;0.2],1,2), ...
  'ids',ids,'reference_version',1,'reference_mode','REPAIRED', ...
  'delta_payload_m',0,'delta_uav_m',0,'delta_cable_m',0);
S=struct('active_raw_jets',J,'nominal_raw_jets_at',@(t)nominal_r83(t), ...
  'known_mask',logical([1 0]),'obstacle_packet',P, ...
  'reference_version',1,'reference_mode','REPAIRED', ...
  'gravity_m_s2',9.81,'cable_length_m',L, ...
  'rQ_m',0.5,'rC_m',0.5,'rL_m',0.5,'d_margin_m',0, ...
  'sensor_range_m',15,'horizon_s',4,'prediction_dt_s',0.025, ...
  'latest_EKF_mL_kg',0.015);
B=AF7R58R83_BIND_R81_INPUTS(S);
assert(numel(B.obstacles)==1 && isequal(B.known_ids,3), ...
  'R83:UnknownObstacleIncorrectlyUsed');
N=B.nominal_payload_jets_at(0);
assert(B.old_payload_jets(3,1)==-2 && N(3,1)==-2, ...
  'R83:AdapterZCorrectionWrong');
assert(abs(B.live.finite_sensing_vQ_limit_m_s-3.105590062111801)<1e-10, ...
  'R83:FiniteSensingSourceMismatch');
% Fail closed on stale packet.
S.reference_version=2;
failed=false;
try,AF7R58R83_BIND_R81_INPUTS(S);catch,failed=true;end
assert(failed,'R83:StalePacketNotRejected');
% Same obstacle ID in another reference version is a different episode;
% it must not be suppressed by a stale stored token.
S.obstacle_packet.reference_version=2;
B2=AF7R58R83_BIND_R81_INPUTS(S);
assert(B2.source_version==2 && isequal(B2.known_ids,3));
assert(~B.production_commit_authorized && ~B.physical_execution_certified);
T=struct('status','PASS_R83_LIVE_FRAME_KNOWN_MASK_AND_VERSION_BINDING', ...
   'frame_shift_z_m',B.raw_flight_to_HLC_payload_z_shift_m, ...
   'known_obstacles_used',numel(B.obstacles), ...
   'unseen_obstacle_rejected',true, ...
   'same_obstacle_new_version_allowed',true, ...
   'reference_only_no_commit',~B.production_commit_authorized, ...
   'production_safety_proved',false);
end
function J=nominal_r83(t)
J=zeros(3,8);J(2,1)=0.7*t;J(2,2)=0.7;
end
