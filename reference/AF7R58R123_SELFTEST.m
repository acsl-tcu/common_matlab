function T=AF7R58R123_SELFTEST()
% Pure tests: sensor mask, oriented ellipsoid, inflation order, provenance.
% No synthetic test can certify real HLC+plant or actual Flight commit.
P=struct('C',[3 0;0 5;0 0], ...
    'R',[reshape(eye(3),9,1),reshape(eye(3),9,1)], ...
    'Araw',[0.5 0.7;0.8 0.6;1.1 0.4], ...
    'ids',[11 12],'delta_uav_m',0.02, ...
    'delta_cable_m',0.03,'delta_payload_m',0.04, ...
    'reference_version',5);
C=struct('r76_packet',P,'r76_known_mask',[true false], ...
    'r76_radii_m',[0.2;0.05;0.1], ...
    'r76_d_margin_m',0.01,'reference_version',5, ...
    'time_s',8,'horizon_s',4,'prediction_dt',0.025);
E=AF7R58R123_EVENT_OBSTACLES(C);
assert(numel(E.obstacles)==1&&E.obstacles(1).id==11&& ...
    E.unknown_count==1 && ~E.uses_unknown_obstacles && ...
    max(abs(E.radii_m-[0.23;0.09;0.15]))<1e-12, ...
    'R123:MaskAndSeparateBodyInflationFailure', ...
    'Unknown must be excluded; separate radius order must be kept.');
P.reference_version=4;C.r76_packet=P;
rejected=false;
try
    AF7R58R123_EVENT_OBSTACLES(C);
catch ME
    rejected=strcmp(ME.identifier,'R123:StaleOrMalformedFrozenObstacles');
end
assert(rejected,'R123:StaleObstacleVersionAccepted', ...
    'A sensor packet with a different reference version was accepted.');
T=struct('status','PASS_R123_EVENT_SOURCE_AND_FAIL_CLOSED_GATES', ...
    'unknown_excluded',true,'separate_three_radii',true, ...
    'stale_packet_rejected',true,'old_trigger_called',false, ...
    'old_generator_called',false,'hlc28_unchanged',true, ...
    'actual_physical_reachability_proved',false, ...
    'production_commit_authorized',false);
fprintf('[R123] %s\n',T.status);
end
