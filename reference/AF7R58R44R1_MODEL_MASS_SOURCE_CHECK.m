function R=AF7R58R44R1_MODEL_MASS_SOURCE_CHECK()
% Read the R44R1 model-based shadow source and fail if old mass-binding bug remains.
f=which('AF7R58R44_CLOSED_LOOP_SHADOW');
assert(~isempty(f),'Shadow source missing.');
s=fileread(f);
R=struct('schema','AF7R58R44R1_MODEL_BINDING_AUDIT_V1', ...
 'shadow_source',f, ...
 'controller_mass_assigned_from_estimator',contains(s,'Pphys(6)=mLEst;'), ...
 'hlc_mass_equivalence_enforced',contains(s,'HLC mass authority differs'), ...
 'plant_mass_assigned_from_estimator',contains(s,'params(20)=mL;'), ...
 'production_trigger_switched',false);
assert(R.controller_mass_assigned_from_estimator && ...
       R.plant_mass_assigned_from_estimator && ...
       R.hlc_mass_equivalence_enforced, ...
       'Shadow uses inconsistent controller/plant payload mass; refuse test.');
end
