function [hit,ttc,tHit,body,pLhit,qHit,pQhit,jHit,id,component,called,ms] = ...
    AF7R58R172_STRICT_TRIGGER(obj,active,t,pQnow,pLnow)
% R172 actual STRICT native callsite (not shadow, no nominal fallback).
% Consumes current EKF, same-tick HLC/plant continuous reach producer and
% source obstacle ledger. No synthetic results grant a Flight authority.
% Unknown is a hard reject; caller's safety backup must be independent.
clock=tic;
hit=false;ttc=Inf;tHit=Inf;body='NONE';
pLhit=nan(3,1);qHit=nan(3,1);pQhit=nan(3,1);
jHit=0;id=NaN;component=0;called=false;ms=NaN;
assert(obj.r172_strict_replacement,'R172:NotStrict','STRICT mode is not active.');
assert(~isempty(obj.r172_reachability_provider_fn) && ...
       ~isempty(obj.r172_obstacle_ledger_fn) && ...
       ~isempty(obj.r172_execution_validator_fn), ...
       'R172:MissingLiveCertificateProducer','Missing same-tick HLC/plant proof producer.');
s=obj.self.estimator.result.state;
assert(isfinite(s.mL)&&s.mL>0 && ...
       isequal(double(s.mL),double(obj.self.parameter.get('loadmass'))), ...
       'R172:LatestMassMissingOrStale','EKF estimated load mass differs from controller parameter.');
t=double(t);pQnow=double(pQnow(:));pLnow=double(pLnow(:));
assert(numel(pQnow)==3&&numel(pLnow)==3 && ...
       all(isfinite([pQnow;pLnow])) && ...
       isequal(double(s.p(:)),pQnow) && ...
       isequal(double(s.pL(:)),pLnow), ...
       'R172:CurrentEKFEndpointsChanged','Position mismatch for same EKF tick.');
live=struct('t_s',t,'estimated_mL_kg',double(s.mL), ...
 'source_horizon_s',double(obj.horizon_s), ...
 'source_radii_m',double([obj.r_drone;obj.r_cable;obj.r_load]), ...
 'position_Q_m',pQnow,'position_L_m',pLnow, ...
 'live_physical_parameters_valid',true);
assert(isequal(live.source_horizon_s,4), ...
       'R172:FourSecondHorizonRequired','Fixed 4 second horizon is required.');
ledger=obj.r172_obstacle_ledger_fn(obj.self,obj,t,active);
if isempty(ledger)
 assert(~any(active), 'R172:KnownObstacleWithoutLedger', ...
   'Active known obstacle has no source ledger record.');
 called=true; ms=1e3*toc(clock);return;
end
pack=obj.r172_reachability_provider_fn(obj.self,obj,t,live,ledger);
assert(isstruct(pack)&&isscalar(pack) && ...
       all(isfield(pack,{'prediction','reach_proof'})), ...
       'R172:ProducerMustReturnPredictionAndReachProof','Missing prediction or proof.');
P=pack.prediction;proof=pack.reach_proof;
assert(isstruct(P)&&isscalar(P)&&isstruct(proof)&&isscalar(proof), ...
       'R172:BadProducerPacket','Invalid prediction and proof types.');
% The validator must verify SOURCE/PROOF, not merely a literal true flag.
assert(isequal(obj.r172_execution_validator_fn( ...
    obj.self,obj,P,proof,ledger,live),true), ...
       'R172:ExecutionReachAndSourceNotCertified','Independent certificate authority rejected reach tube.');
[T,newLatch]=AF7R58R171_INTERVAL_TRIGGER( ...
    P,ledger,live,proof,obj.r172_trigger_latch);
obj.r172_trigger_latch=newLatch;
assert(logical(T.proof_usable_conditional) && ...
       ~T.backup_or_reachability_proof_required || ...
       (logical(T.proof_usable_conditional)&&logical(T.request)), ...
       'R172:UnknownReachability','Not enough interval bounds for strict trigger.');
assert(~startsWith(char(T.status),'UNKNOWN_'), ...
       'R172:UnknownTriggerResult','Trigger result is UNKNOWN.');
obj.r172_last_strict_trigger=T;
called=true;
if T.request
    % The first unresolved interval is preventive, NOT a true collision TTC.
    assert(isfield(T,'first_risk_interval_index') && ...
           isfinite(T.first_risk_interval_index), ...
           'R172:RiskIntervalWitnessMissing','Earliest unresolved interval missing.');
    i=double(T.first_risk_interval_index);
    times=double(P.t_s(:));Q=double(P.Q_m);L=double(P.L_m);
    if size(Q,1)~=3,Q=Q';end
    if size(L,1)~=3,L=L';end
    assert(i>=1 && i<=numel(times) && ...
           size(Q,1)==3 && size(L,1)==3, ...
           'R172:WrongWitnessShape','Prediction witness shape invalid.');
    tHit=times(i);ttc=max(0,tHit-t);
    pQhit=Q(:,i);pLhit=L(:,i);
    qHit=(pLhit-pQhit)/double(obj.L_cable);
    assert(all(isfinite(qHit)) && ...
           abs(norm(qHit)-1)<=1e-4, ...
           'R172:NonTautReachWitness','Predicted cable endpoints not taut.');
    jHit=i;id=double(T.first_unresolved_obstacle_id);
    body=char(T.failed_component);
    switch body
        case 'PAYLOAD', component=1;
        case 'UAV',component=2;
        case 'CABLE',component=3;
        otherwise, error('R172:UnknownCollisionComponent');
    end
    hit=true;
end
ms=1e3*toc(clock);
end
