function candidate=AF7R58R172_STRICT_GENERATOR(CTX,obj)
% R186 STRICT Stage1: R170 3-D corridor/C7 construction -> 28-state
% analytically evaluated heading-exact C6 reference. No legacy generator.
% No certified full-system HLC/observer/tension/torque/tail implies NO commit.
% This is an honest native-interface bridge, not a replacement proof.
clock=tic;
assert(obj.r172_strict_replacement,'R186:StrictModeRequired');
assert(isstruct(CTX)&&isfield(CTX,'r109_live_ekf'),...
 'R186:MissingSameTickEKF');
E=CTX.r109_live_ekf;
assert(isstruct(E)&&isfield(E,'future_ekf_state_certified')&&...
 ~logical(E.future_ekf_state_certified)&&...
 isfield(E,'latest_estimated_load_mass_kg')&&...
 isequal(double(E.latest_estimated_load_mass_kg),...
 double(obj.self.estimator.result.state.mL)), 'R186:StaleEKFMass');
assert(isa(obj.r172_routes_provider_fn,'function_handle'),...
 'R186:MissingCurrentCorridorProducer');
G=obj.r172_routes_provider_fn(CTX,obj.self,obj);
assert(isstruct(G)&&isscalar(G)&&all(isfield(G,...
 {'routes','packet','speed_certificate','obstacles','jets','options'})),...
 'R186:BadRoutePacket');
assert(isfield(G.packet,'t_s')&&...
 isequal(double(G.packet.t_s),double(E.observed_time_s))&&...
 isfield(G.packet,'estimated_mL_kg')&&...
 isequal(double(G.packet.estimated_mL_kg),...
 double(E.latest_estimated_load_mass_kg)), 'R186:StaleRouteSource');
A=AF7R58R170_GENERATE(G.routes,G.packet,...
 G.speed_certificate,G.obstacles,G.jets,G.options);
obj.r172_last_strict_generator=A;
Q=struct('status','NO_C7_CONDITIONAL_CANDIDATE','bound',false);
if A.conditional_shortlist_count>0&&isstruct(A.selected_route)&&...
 isfield(A.selected_route,'C7')
 Q=AF7R58R186_BIND_C7(A.selected_route.C7,...
      double(E.activation_time_s));
end
% Unlike the old hard-coded fail, this returns the ACTUAL C7 reference
% packet, its analytic yaw jet and typed reason for missing execution proof.
% The standard native Stage2/3 format is not forged. FAIL CLOSED.
candidate=struct('success',false,'generated',logical(Q.bound),...
 't0',double(E.activation_time_s),...
 'r9_stage_timing',struct('total_internal_ms',1e3*toc(clock)),...
 'reason_code',-186,'candidate_family','R186_C7_QP_BOUND__NOT_COMMITTABLE',...
 'research_status',char(A.status),'reference_binding',Q,...
 'reference_only',true,'production_commit_authorized',false,...
 'missing_certificate','VALIDATED_HLC_EKF_REACH_TORQUE_RETURN_AND_BACKUP');
end
