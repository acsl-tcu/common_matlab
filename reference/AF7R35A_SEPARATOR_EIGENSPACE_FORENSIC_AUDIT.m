function OUT = AF7R35A_SEPARATOR_EIGENSPACE_FORENSIC_AUDIT(replanner)
clc;
fprintf('\n====================================================================================================\n');
fprintf(' AF7R35A | SEPARATOR EIGENSPACE / C++ JACOBI FORENSIC AUDIT\n');
fprintf('====================================================================================================\n');
fprintf('[AUTHORITY] readOnly=1 | synthesisForensicOnly=1 | safetyLogicUnchanged=1 | productionModification=0\n');

assert(isa(replanner,'REPLANNING_SYSTEM'));
assert(exist('af7r34_single_core_mex','file')==3,'[AF7R35A] R14 core MEX missing.');

P0=AF7R34_PRIME_SINGLE_CORE_REFERENCE(replanner);
assert(P0.closed,'[AF7R35A] nominal AST prime not closed.');

E=replanner.get_first_trigger_event();
assert(isstruct(E)&&isfield(E,'valid')&&logical(E.valid)&&logical(E.real_flight_request_edge), ...
    '[AF7R35A] no stored real trigger.');
CTX=af7r32_replay_context(replanner,E);

PL=replanner.builtin_bezier_d15_c7_proposal(CTX);
[PN,RN]=af7r34_single_core_proposal(replanner,CTX);
assert(logical(PL.success)&&logical(PN.success),'[AF7R35A] both proposals must succeed.');

EL=PL.unsafe_episode_certificate;
assert(double(EL.episode_count)==1&&double(EL.component_count)==1, ...
    '[AF7R35A] current forensic expects the true-trigger 1-episode case.');

ep=EL.episodes(1);
tca=double(ep.start_s); tcb=double(ep.end_s);
xa=double(PL.base_flat_eval_fn(tca)); xa=xa(:);
xb=double(PL.base_flat_eval_fn(tcb)); xb=xb(:);
progress=xb(1:3)-xa(1:3);
if norm(progress)<=128*eps(max(1,norm(xa(1:3))))
    xm=double(PL.base_flat_eval_fn(0.5*(tca+tcb))); xm=xm(:);
    progress=xm(5:7);
end

ii=double(ep.obstacle_index);
R=reshape(double(CTX.obstacles.rotations_flat(:,ii)),3,3);
a=double(CTX.obstacles.base_axes(:,ii));

Q=R*diag(1./(a.^2))*R.';
Q=0.5*(Q+Q.');

if norm(progress)>128*eps(max(1,norm(progress)))
    v=progress/norm(progress);
    Pm=eye(3)-v*v.';
    Qp=0.5*(Pm*Q*Pm + (Pm*Q*Pm).');
else
    v=[NaN;NaN;NaN];
    Pm=eye(3);
    Qp=Q;
end

nM=replanner.bezier_lateral_separator_normal(R,a,progress);
nM=double(nM(:))/norm(double(nM(:)));

% Exact MATLAB port of the AF7R34 C++ jacobi_sym3() update order.
[VC,DC]=cpp_jacobi_sym3_exact_port(Qp);
[~,ixC]=max(DC);
nC=VC(:,ixC);
if all(isfinite(v))
    nC=Pm*nC;
end
if norm(nC)>0
    nC=nC/norm(nC);
end

% MATLAB spectral authority for Qp.
[VM,DM]=eig(Qp,'vector');
[lam,ord]=sort(real(DM),'descend');
VM=real(VM(:,ord));
lam1=lam(1); lam2=lam(2);
spectralGap=lam1-lam2;
spectralScale=max([1;abs(lam(:));norm(Qp,'fro')]);
spectralGuard=4096*eps(spectralScale);
topDegenerate=spectralGap<=spectralGuard;

rayM=real(nM.'*Qp*nM);
rayC=real(nC.'*Qp*nC);
resM=norm(Qp*nM-rayM*nM);
resC=norm(Qp*nC-rayC*nC);
optGapM=lam1-rayM;
optGapC=lam1-rayC;

if all(isfinite(v))
    orthM=abs(nM.'*v);
    orthC=abs(nC.'*v);
else
    orthM=0; orthC=0;
end

angleAbs=abs(dot(nM,nC));
angleDeg=acosd(max(-1,min(1,angleAbs)));

% Test the native solution under corridor rows generated by the exact ported
% C++ separator direction. If this passes, we have identified the synthesis
% mismatch source directly.
nvar=6;
[AcP,bcP,okCP]=replanner.bezier_piecewise_episode_corridor_rows( ...
    PL,CTX,EL,1,nC,nvar);
[AcM,bcM,okCM]=replanner.bezier_piecewise_episode_corridor_rows( ...
    PL,CTX,EL,1,-nC,nvar);
assert(okCP&&okCM,'[AF7R35A] C++-direction MATLAB rows failed.');

zL=pack_z(PL);
zN=pack_z(PN);
[sNcp,pNcp,tNcp]=slack_test(AcP,bcP,zN);
[sNcm,pNcm,tNcm]=slack_test(AcM,bcM,zN);
nativeFitsCppPortedDirection=xor(pNcp,pNcm);

[sLcp,pLcp,~]=slack_test(AcP,bcP,zL);
[sLcm,pLcm,~]=slack_test(AcM,bcM,zL);

% Compare physical direction using common normal from previous audit too.
[AmP,bmP,okMP]=replanner.bezier_piecewise_episode_corridor_rows( ...
    PL,CTX,EL,1,nM,nvar);
[AmM,bmM,okMM]=replanner.bezier_piecewise_episode_corridor_rows( ...
    PL,CTX,EL,1,-nM,nvar);
assert(okMP&&okMM);
[~,pNmp,~]=slack_test(AmP,bmP,zN);
[~,pNmm,~]=slack_test(AmM,bmM,zN);

% Classification.
cppVectorIsTop=(resC<=spectralGuard && optGapC<=spectralGuard && orthC<=spectralGuard);
matlabVectorIsTop=(resM<=spectralGuard && optGapM<=spectralGuard && orthM<=spectralGuard);

if nativeFitsCppPortedDirection && cppVectorIsTop && topDegenerate
    classification='VALID_DEGENERATE_TOP_EIGENSPACE__NONCANONICAL_BASIS_CHOICE';
elseif nativeFitsCppPortedDirection && ~cppVectorIsTop
    classification='CPP_JACOBI_NOT_PRINCIPAL__IMPLEMENTATION_BUG';
elseif ~nativeFitsCppPortedDirection
    classification='NATIVE_CORRIDOR_MISMATCH_NOT_EXPLAINED_BY_SEPARATOR_EIGENVECTOR';
else
    classification='NONDEGENERATE_SEPARATOR_DIFFERENCE_REQUIRES_FURTHER_AUDIT';
end

closed=matlabVectorIsTop && nativeFitsCppPortedDirection && ...
    (cppVectorIsTop || strcmp(classification,'CPP_JACOBI_NOT_PRINCIPAL__IMPLEMENTATION_BUG'));

fprintf(' obstacle index / id                     = %d / %.17g\n',ii,double(CTX.obstacles.ids(ii)));
fprintf(' progress                                 = [%.17g %.17g %.17g]^T\n',progress);
fprintf(' MATLAB separator nM                      = [%.17g %.17g %.17g]^T\n',nM);
fprintf(' C++-Jacobi port separator nC             = [%.17g %.17g %.17g]^T\n',nC);
fprintf(' |nM''*nC| / unsigned angle [deg]          = %.17g / %.9g\n',angleAbs,angleDeg);
fprintf('\n[SPECTRAL FORENSICS]\n');
fprintf(' Qp eigenvalues descending                = [%.17g %.17g %.17g]\n',lam(1),lam(2),lam(3));
fprintf(' top spectral gap / guard                 = %.17g / %.17g\n',spectralGap,spectralGuard);
fprintf(' top eigenspace degenerate                = %d\n',topDegenerate);
fprintf(' MATLAB rayleigh / residual / opt gap     = %.17g / %.17g / %.17g\n',rayM,resM,optGapM);
fprintf(' C++port rayleigh / residual / opt gap    = %.17g / %.17g / %.17g\n',rayC,resC,optGapC);
fprintf(' MATLAB/C++port progress orthogonality    = %.17g / %.17g\n',orthM,orthC);
fprintf(' MATLAB vector is top eigendirection      = %d\n',matlabVectorIsTop);
fprintf(' C++port vector is top eigendirection     = %d\n',cppVectorIsTop);

fprintf('\n[NATIVE CANDIDATE UNDER C++-PORTED DIRECTION]\n');
fprintf(' native +nC / -nC pass                    = %d / %d\n',pNcp,pNcm);
fprintf(' native +nC / -nC min slack               = %.17g / %.17g\n',sNcp,sNcm);
fprintf(' native +nC / -nC tolerance               = %.3g / %.3g\n',tNcp,tNcm);
fprintf(' native fits exactly one C++ported side   = %d\n',nativeFitsCppPortedDirection);
fprintf(' legacy +nC / -nC pass                    = %d / %d\n',pLcp,pLcm);
fprintf(' native under MATLAB nM + / -             = %d / %d\n',pNmp,pNmm);

fprintf('\n classification                            = %s\n',classification);
fprintf(' forensic closed                          = %d\n',closed);
fprintf(' production source modified               = 0\n');
fprintf('====================================================================================================\n');

OUT=struct('schema','AF7R35A_SEPARATOR_EIGENSPACE_FORENSIC_AUDIT_V1', ...
    'closed',closed,'classification',classification, ...
    'n_matlab',nM,'n_cpp_port',nC,'eigenvalues',lam, ...
    'spectral_gap',spectralGap,'spectral_guard',spectralGuard, ...
    'top_degenerate',topDegenerate, ...
    'matlab_top',matlabVectorIsTop,'cpp_top',cppVectorIsTop, ...
    'native_fits_cpp_direction',nativeFitsCppPortedDirection, ...
    'native_cpp_plus_pass',pNcp,'native_cpp_minus_pass',pNcm);
assignin('base','AF7R35A_SEPARATOR_EIGENSPACE_FORENSIC_AUDIT_OUT',OUT);
end


function [V,d]=cpp_jacobi_sym3_exact_port(A)
A=double(A);
V=eye(3);
for it=1:40
    pairs=[1 2;1 3;2 3];
    vals=[abs(A(1,2));abs(A(1,3));abs(A(2,3))];
    [m,k]=max(vals);
    p=pairs(k,1); q=pairs(k,2);
    scale=max([1,abs(A(1,1)),abs(A(2,2)),abs(A(3,3))]);
    if m<=64*eps(scale), break; end
    app=A(p,p); aqq=A(q,q); apq=A(p,q);
    phi=0.5*atan2(2*apq,aqq-app);
    c=cos(phi); s=sin(phi);

    % Preserve the exact sequential update order in AF7R34 C++.
    for kk=1:3
        aik=A(kk,p); aiq=A(kk,q);
        A(kk,p)=c*aik-s*aiq;
        A(kk,q)=s*aik+c*aiq;
    end
    for kk=1:3
        apk=A(p,kk); aqk=A(q,kk);
        A(p,kk)=c*apk-s*aqk;
        A(q,kk)=s*apk+c*aqk;
    end
    A(p,q)=0; A(q,p)=0;

    for kk=1:3
        vip=V(kk,p); viq=V(kk,q);
        V(kk,p)=c*vip-s*viq;
        V(kk,q)=s*vip+c*viq;
    end
end
d=[A(1,1);A(2,2);A(3,3)];
end


function z=pack_z(P)
p=double(P.piecewise_component_position);
v=double(P.piecewise_component_velocity);
assert(size(p,2)==1&&size(v,2)==1);
z=[p(:,1);v(:,1)];
end


function [m,pass,tol]=slack_test(A,b,z)
A=double(A); b=double(b(:)); z=double(z(:));
q=A*z; sl=q-b;
scale=max([1;abs(q(:));abs(b(:))]);
tol=512*eps(scale);
m=min(sl);
pass=all(sl>=-tol);
end
