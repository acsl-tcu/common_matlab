function Q=AF7R58R41_PREFLIGHT()
% Inspect installed source without changing simulator/controller state.
src=which('REPLANNING_SYSTEM');
assert(~isempty(src),'[R41] REPLANNING_SYSTEM not on path.');
s=fileread(src);
checks={ ...
 'rfortyone_trace_flag', ...
 'r41_pre_sensor=1e3*toc(r41_clock)', ...
 'r41_pre_stage=1e3*toc(r41_clock)', ...
 'r41_post_stage=1e3*toc(r41_clock)', ...
 'r41_end=1e3*toc(r41_clock)', ...
 'st.rfortyone_closure_ms=r41_end-( ...', ...
 'obj.trigger_core(active,pL_ref,q_ref,time.t)', ...
 'obj.staged_replan_candidate=candidate', ...
 'obj.activate_staged_reference_only_bundle' ...
};
for j=1:numel(checks)
 assert(contains(s,checks{j}), ...
  '[R41] Source-bound check failed at %s.',checks{j});
end
% Numeric shape demo uses only mathematical test polygons and does not
% set or infer ANY runtime flight parameter.
P=repmat([1;0;0],1,16);
T=AF7R58R41_RETURN_SHAPE({P},[1;0;0]);
assert(T.one_sided_Bernstein_sufficient && ...
 ~T.signed_negative_midpoint_witness, ...
 '[R41] Signed Bezier test failed.');
Q=struct('source',src,'timing_source_bound',true, ...
 'bezier_shape_algebra_test_pass',true, ...
 'production_trigger_changed',false, ...
 'return_optimizer_committed',false, ...
 'safety_proof_modified',false, ...
 'matlab_flight_runtime_verified',false);
fprintf('[R41] PREFLIGHT PASS | event time closure installed | no safety/trigger/commit changes.\n');
end
