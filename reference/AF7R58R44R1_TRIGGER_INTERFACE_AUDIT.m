function R=AF7R58R44R1_TRIGGER_INTERFACE_AUDIT(P)
% Model/HLC authority check, including resolved live plant function handle.
% Does not roll out 160 numerical ODE steps or alter production trigger.
if nargin<1 || isempty(P)
    if evalin('base','exist(''replanner_instance'',''var'')==1')
        P=evalin('base','replanner_instance');
    else
        R=struct('schema','AF7R58R44R1_TRIGGER_AUDIT_V1', ...
          'status','NO_LIVE_REPLANNER','live_model_resolved',false, ...
          'production_trigger_switched',false);
        return;
    end
end
assert(isa(P,'REPLANNING_SYSTEM'));
S=P.self.estimator.result.state;
Plant=P.self.plant;
assert(isa(Plant,'MODEL_CLASS') && isa(Plant.method,'function_handle'), ...
    'Loaded actual plant RHS is required.');
R=struct('schema','AF7R58R44R1_TRIGGER_AUDIT_V1', ...
    'status','LIVE_MODEL_SOURCE_RESOLVED_BUT_TRIGGER_NOT_CONNECTED', ...
    'live_model_resolved',true, ...
    'plant_loaded_function',func2str(Plant.method), ...
    'plant_solver',func2str(Plant.solver), ...
    'mass_from_estimator_kg',double(S.mL), ...
    'mass_external_property_kg',double(P.self.parameter.loadmass), ...
    'prediction_dt_s',double(P.prediction_dt), ...
    'prediction_horizon_s',double(P.horizon_s), ...
    'sensor_range_m',double(P.trigger_dist), ...
    'production_trigger_switched',false, ...
    'closed_loop_numerical_shadow_verified',false, ...
    'continuous_time_collision_certified',false);
R.mass_live_vs_external_difference_kg= ...
    R.mass_from_estimator_kg-R.mass_external_property_kg;
R.controller_mass_authority_matches_estimator= ...
    abs(R.mass_live_vs_external_difference_kg)<= ...
    64*eps(max(1,abs(R.mass_from_estimator_kg)));
if ~R.controller_mass_authority_matches_estimator
    R.status='LIVE_HLC_MASS_AUTHORITY_MISMATCH__SHADOW_FAIL_CLOSED';
end
R.note=['HLC rollout must use estimator mL for BOTH plant parameter ' ...
    'slot 20 and HLC Pphys slot 6; a reference-only future is not valid.'];
end
