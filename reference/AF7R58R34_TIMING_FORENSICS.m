function R=AF7R58R34_TIMING_FORENSICS(logger,runtime_profile)
% Post-Flight, read-only. Uses the EXISTING LOGGER timing fields from R29-R33.
% No timing calls, file access or changes in the Flight path.
assert(isa(logger,'LOGGER'),'A live LOGGER object is required.');
assert(isstruct(runtime_profile) && isfield(runtime_profile,'t') && ...
    isfield(runtime_profile,'phase'), 'Missing runtime_profile.t/phase.');
phase=runtime_profile.phase(:);
mask=(phase=='f');
t=double(runtime_profile.t(mask));
t=t(:);
assert(~isempty(t) && all(diff(t)>0),'Invalid Flight timeline.');
N=numel(t);
names={ ...
  'reference_total_ms','replanner_e2e_ms','observer_ms', ...
  'stage_start_ms','stage_advance_ms','event_capture_ms', ...
  'spike_time_s','spike_total_ms', 'front_ms','loadmass_ms', ...
  'dependency_ms','base_cert_geom_ms','sensor_trigger_ms','output_state_ms', ...
  'base_ref_ms','flight_guard_ms','cert_guard_ms','active_ref_ms', ...
  'geometry_ms','state_handle_ms','write_active_output_ms', ...
  'state_basic_ms','trigger_scalar_ms','trigger_heavy_ms', ...
  'state_cert_ms','state_meta_ms', ...
  'stage1_ms','stage2_ms'};
paths={ ...
  'controller.result.r25_reference_ms', ...
  'reference.result.state.rtime_e_to_e_ms', ...
  'reference.result.state.rtime_observer_ms', ...
  'reference.result.state.rtime_stage_start_ms', ...
  'reference.result.state.rtime_stage_advance_ms', ...
  'reference.result.state.rtime_capture_ms', ...
  'reference.result.state.rt_spike_capture_time', ...
  'reference.result.state.rt_spike_total_ms', ...
  'reference.result.state.rt_spike_stage_front_ms', ...
  'reference.result.state.rt_spike_stage_loadmass_ms', ...
  'reference.result.state.rt_spike_stage_dependency_ms', ...
  'reference.result.state.rt_spike_stage_base_cert_geom_ms', ...
  'reference.result.state.rt_spike_stage_sensor_trigger_ms', ...
  'reference.result.state.rt_spike_stage_output_state_ms', ...
  'reference.result.state.rt_spike_base_ref_ms', ...
  'reference.result.state.rt_spike_flight_guard_ms', ...
  'reference.result.state.rt_spike_cert_guard_ms', ...
  'reference.result.state.rt_spike_active_ref_ms', ...
  'reference.result.state.rt_spike_geometry_ms', ...
  'reference.result.state.rt_spike_state_handle_ms', ...
  'reference.result.state.rt_spike_write_active_output_ms', ...
  'reference.result.state.rt_spike_state_basic_ms', ...
  'reference.result.state.rt_spike_state_trigger_scalar_ms', ...
  'reference.result.state.rt_spike_state_trigger_heavy_ms', ...
  'reference.result.state.rt_spike_state_cert_ms', ...
  'reference.result.state.rt_spike_state_meta_ms', ...
  'reference.result.state.rtime_stage_start_ms', ...
  'reference.result.state.rtime_stage_advance_ms'};
assert(numel(names)==numel(paths));
V=nan(N,numel(names));
errors=cell(0,2);
for j=1:numel(names)
    try
        [v,~]=logger.data(1,paths{j},'','phase','f');
        x=double(v);
        if numel(x)~=N
            error('AF7R58R34:LengthMismatch', ...
                 'LOGGER %s had %d instead of %d samples.', ...
                 paths{j},numel(x),N);
        end
        V(:,j)=x(:);
    catch ME
        errors(end+1,:)={names{j},ME.message}; %#ok<AGROW>
    end
end
D=array2table(V,'VariableNames',names);
D.time_s=t;
D=movevars(D,'time_s','Before',1);
D.wrapper_or_adjacent_ms=D.reference_total_ms-D.replanner_e2e_ms;
% rt_spike fields persist as state variables in the legacy LOGGER. Use
% only samples whose recorded capture timestamp equals this sample time.
valid=isfinite(D.spike_time_s) & ...
      abs(D.spike_time_s-t)<=64*eps(max(1,abs(t)));
spikeNames=names(8:26);
for j=1:numel(spikeNames)
    z=D.(spikeNames{j});
    z(~valid)=NaN;
    D.(spikeNames{j})=z;
end
D.spike_valid=valid;
D.spike_sum_ms=D.front_ms+D.loadmass_ms+D.dependency_ms+ ...
   D.base_cert_geom_ms+D.sensor_trigger_ms+D.output_state_ms;
D.spike_closure_error_ms=D.spike_total_ms-D.spike_sum_ms;
% Same-cycle top-level reference time, not percentile masking.
[~,order]=sort(D.reference_total_ms,'descend','MissingPlacement','last');
order=order(isfinite(D.reference_total_ms(order)));
T=D(order(1:min(25,numel(order))),:);
R=struct('schema','AF7R58R34_FULL_CLOCK_READONLY_V1', ...
   'cycle_count',N,'all_cycles',D,'worst_cycles',T, ...
   'missing_logger_fields',{errors}, ...
   'strict_same_cycle_spike_timestamp_enforced',true, ...
   'flight_runtime_changed',false);
disp('========== R34 EXACT-CYCLE SPIKES (ms) ==========');
show={'time_s','reference_total_ms','replanner_e2e_ms', ...
      'wrapper_or_adjacent_ms','observer_ms','stage_start_ms', ...
      'stage_advance_ms','base_cert_geom_ms','sensor_trigger_ms', ...
      'output_state_ms','spike_valid'};
disp(T(:,show));
if ~isempty(errors)
    disp('Some LOGGER fields are unavailable; those fields remain NaN:');
    disp(errors);
end
save('AF7R58R34_TIMING_FORENSICS.mat','R');
writetable(T,'AF7R58R34_TIMING_FORENSICS_TOP.csv');
end
