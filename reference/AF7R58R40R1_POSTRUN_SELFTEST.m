function V = AF7R58R40R1_POSTRUN_SELFTEST(currentMat,baselineMat)
% Source-bound A/B test: no separate guessed variables or mock data.
assert(nargin==2 && isfile(currentMat) && isfile(baselineMat), ...
    '[R40R1] Provide the current and prior Flight timing MAT paths.');
R=AF7R58R40_OFFLINE_SUMMARY(currentMat,baselineMat);
assert(R.backup_timing_available && R.event_match_verified && ...
    R.flight_time_grid_match_verified, ...
    '[R40R1] Flight timing and event identity not proved.');
assert(height(R.baseline_comparison)==height(R.current_stage_table), ...
    '[R40R1] Missing compared Stage event.');
assert(isfinite(R.current_full_closure_residual_ms) && ...
    R.current_full_closure_residual_ms<=1e-8, ...
    '[R40R1] Total-cycle measurement does not close.');
assert(~R.internal_timer_closure_verified && ...
    ~R.estimator_origin_trigger_switched && ...
    ~R.return_optimization_committed, ...
    '[R40R1] Diagnostic results must not claim unverified safety or activation.');
V=struct('schema','R40R1_POSTRUN_AUDIT', ...
    'stage_events_compared',height(R.baseline_comparison), ...
    'full_closure_ms',R.current_full_closure_residual_ms, ...
    'event_source_bound',true,'reference_before_max_ms',R.baseline_max_reference_ms, ...
    'reference_after_max_ms',R.current_max_reference_ms, ...
    'reference_after_p50_ms',R.current_p50_reference_ms, ...
    'post_commit_cycle_count',height(R.after_commit_followup), ...
    'internal_closure_unmeasured',~R.internal_timer_closure_verified, ...
    'trigger_not_switched',~R.estimator_origin_trigger_switched, ...
    'return_not_committed',~R.return_optimization_committed);
disp(V);
end
