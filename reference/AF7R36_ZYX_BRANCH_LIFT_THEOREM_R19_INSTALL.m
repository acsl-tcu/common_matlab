function OUT = AF7R36_ZYX_BRANCH_LIFT_THEOREM_R19_INSTALL()
% AF7R36_ZYX_BRANCH_LIFT_THEOREM_R19_INSTALL
%
% THEORY CORRECTION -- not a threshold relaxation.
%
% Current ZYX kinematics use
%
%   omega = E(phi,theta) qdot
%
% with det(E)=cos(theta). Therefore the continuous-time ZYX coordinate chart
% is singular only when |theta| reaches pi/2. Roll/yaw values +/-pi are NOT
% kinematic singularities; they are branch boundaries of a chosen principal
% atan2 representation.
%
% R18 showed:
%   pitch margin = +0.277 rad  (continuous chart CLOSED)
%   roll/yaw principal-box bounds exceeded pi.
%
% The old code conflated:
%   (A) continuous ZYX chart singularity, and
%   (B) principal 2*pi branch ambiguity used by two-event finite differences.
%
% R19 separates them rigorously.
%
% 1. Continuous chart theorem:
%      Theta = |theta_0|_UB + integral ||omega|| dt < pi/2.
%    This remains the hard fail-closed requirement.
%
% 2. Roll/yaw displacement theorem while pitch is closed:
%      |phi_dot| <= sec(Theta) ||omega||
%      |psi_dot| <= sec(Theta) ||omega||
%    because the Euclidean row norms of T_ZYX are both sec(theta).
%    Hence
%      Delta_phi_UB = sec(Theta) Iw
%      Delta_psi_UB = sec(Theta) Iw.
%
% 3. Principal-branch lifting:
%    The current endpoint measurement interval is lifted by 2*pi*k.  Integers
%    k are admissible only if the lifted endpoint interval intersects the
%    continuous reachable interval from the previous endpoint.  The lift is
%    used only when the admissible integer is UNIQUE.  Zero or multiple lifts
%    are fail-closed -- no guessed unwrap.
%
% 4. The uniquely lifted roll/yaw endpoint is then used by the EXISTING
%    two-event angular-rate contraction. The current-event measured error box
%    and HLC bridge continue to use the actual current measurement coordinates.
%
% No safety threshold, physical limit, trajectory, controller, or timing gate
% is changed.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 ZYX BRANCH-LIFT THEOREM R19 INSTALL\n');
fprintf(' continuous ZYX singularity condition       = cos(theta) != 0 only\n');
fprintf(' pitch pi/2 hard condition modified          = 0\n');
fprintf(' roll/yaw +/-pi treated as singularity       = 0 (mathematical correction)\n');
fprintf(' branch unwrap rule                          = unique 2*pi lift from certified reachable set\n');
fprintf(' ambiguous branch policy                     = FAIL CLOSED\n');
fprintf(' guessed unwrap / heuristic threshold        = 0\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir)&&isfolder(refDir), ...
    '[R19] Cannot resolve current reference directory.');
rps=fullfile(refDir,'REPLANNING_SYSTEM.m');
assert(isfile(rps),'[R19] Missing %s',rps);

src0=normlf(fileread(rps));
src=src0;

assert(contains(src0,'AF7R36 R18 exact chart-failure witness.'), ...
    '[R19] R18 witness patch is required.');
assert(contains(src0,'S.closed=pitchClosed&&fullClosed;'), ...
    '[R19] Old combined chart/principal-branch closure line not found.');
assert(contains(src0,'[REPLANNER OBSERVER ERROR] measured Euler box reaches chart boundary.'), ...
    '[R19] Old principal-box contraction guard not found.');
assert(~contains(src0,'AF7R36 R19 unique periodic branch lift'), ...
    '[R19] R19 already installed.');

try
    %% --------------------------------------------------------------------
    % A. Correct the chart theorem and coordinate displacement bounds.
    % ---------------------------------------------------------------------
    old=[ ...
        '            qAbs=[Inf;Theta;Inf]; fullClosed=false;' sprintf('\n') ...
        '            if pitchClosed' sprintf('\n') ...
        '                qAbs(1)=q0(1)+(1+tan(Theta))*Iw;' sprintf('\n') ...
        '                qAbs(3)=q0(3)+(1/cos(Theta))*Iw;' sprintf('\n') ...
        '                fullClosed=qAbs(1)<pi&&qAbs(3)<pi;' sprintf('\n') ...
        '            end'];

    new=[ ...
        '            qAbs=[Inf;Theta;Inf]; fullClosed=false;' sprintf('\n') ...
        '            dEuler=[Inf;Iw;Inf];' sprintf('\n') ...
        '            if pitchClosed' sprintf('\n') ...
        '                % AF7R36 R19: exact Euclidean row norms of the inverse' sprintf('\n') ...
        '                % ZYX kinematic map are sec(theta) for roll and yaw.' sprintf('\n') ...
        '                secTheta=1/cos(Theta);' sprintf('\n') ...
        '                dEuler(1)=secTheta*Iw;' sprintf('\n') ...
        '                dEuler(3)=secTheta*Iw;' sprintf('\n') ...
        '                qAbs(1)=q0(1)+dEuler(1);' sprintf('\n') ...
        '                qAbs(3)=q0(3)+dEuler(3);' sprintf('\n') ...
        '                % Diagnostic principal-box condition only.  It is NOT' sprintf('\n') ...
        '                % the continuous ZYX singularity condition.' sprintf('\n') ...
        '                fullClosed=qAbs(1)<pi&&qAbs(3)<pi;' sprintf('\n') ...
        '            end'];

    src=replace_once(src,old,new,'coordinate displacement theorem');

    old='            S.closed=pitchClosed&&fullClosed; S.h=h; S.held_input=u;';
    new=[ ...
        '            % AF7R36 R19: det(E_ZYX)=cos(theta). Continuous chart' sprintf('\n') ...
        '            % closure therefore requires pitch closure only.' sprintf('\n') ...
        '            S.closed=pitchClosed; S.h=h; S.held_input=u;'];
    src=replace_once(src,old,new,'continuous chart closure');

    anchor='            S.Iw=Iw; S.q_abs_start=q0; S.Theta=Theta;';
    repl=[anchor sprintf('\n') ...
        '            S.euler_coordinate_delta_abs_ub=dEuler;' sprintf('\n') ...
        '            S.principal_roll_yaw_box_closed=fullClosed;'];
    src=replace_once(src,anchor,repl,'R19 support fields');

    old=[ ...
        '            if ~pitchClosed' sprintf('\n') ...
        '                S.closure_reason=''PITCH_SUPPORT_REACHES_ZYX_SINGULARITY'';' sprintf('\n') ...
        '            elseif qAbs(1)>=pi && qAbs(3)>=pi' sprintf('\n') ...
        '                S.closure_reason=''ROLL_AND_YAW_SUPPORT_REACH_ZYX_CHART_BOUNDARY'';' sprintf('\n') ...
        '            elseif qAbs(1)>=pi' sprintf('\n') ...
        '                S.closure_reason=''ROLL_SUPPORT_REACHES_ZYX_CHART_BOUNDARY'';' sprintf('\n') ...
        '            elseif qAbs(3)>=pi' sprintf('\n') ...
        '                S.closure_reason=''YAW_SUPPORT_REACHES_ZYX_CHART_BOUNDARY'';' sprintf('\n') ...
        '            else' sprintf('\n') ...
        '                S.closure_reason=''ZYX_CHART_SUPPORT_CLOSED'';' sprintf('\n') ...
        '            end'];

    new=[ ...
        '            if ~pitchClosed' sprintf('\n') ...
        '                S.closure_reason=''PITCH_SUPPORT_REACHES_ZYX_SINGULARITY'';' sprintf('\n') ...
        '            elseif fullClosed' sprintf('\n') ...
        '                S.closure_reason=''ZYX_KINEMATIC_CHART_AND_PRINCIPAL_BOX_CLOSED'';' sprintf('\n') ...
        '            else' sprintf('\n') ...
        '                S.closure_reason=''ZYX_KINEMATIC_CHART_CLOSED__PRINCIPAL_ROLL_YAW_BOX_OPEN'';' sprintf('\n') ...
        '            end'];
    src=replace_once(src,old,new,'closure reason separation');

    %% --------------------------------------------------------------------
    % B. Replace principal +/-pi endpoint guard by unique periodic lifting.
    % ---------------------------------------------------------------------
    old=[ ...
        '            dq=(y1(iq)-y0(iq))/h;' sprintf('\n') ...
        '            rQdot=0.5*qddotUb*h+(norm(n0(iq))+norm(n1(iq)))/h;' sprintf('\n') ...
        '            lim=[pi;pi/2;pi];' sprintf('\n') ...
        '            assert(all(abs(y0(iq))+n0(iq)<lim)&&all(abs(y1(iq))+n1(iq)<lim), ...' sprintf('\n') ...
        '                ''[REPLANNER OBSERVER ERROR] measured Euler box reaches chart boundary.'');' sprintf('\n') ...
        '            Ey=obj.observer_euler_rate_inverse_ZYX(y1(iq));'];

    new=[ ...
        '            % AF7R36 R19 unique periodic branch lift.' sprintf('\n') ...
        '            % Pitch has no 2*pi branch in the certified ZYX strip and' sprintf('\n') ...
        '            % remains subject to the original strict pi/2 endpoint check.' sprintf('\n') ...
        '            assert(abs(y0(5))+n0(5)<pi/2 && abs(y1(5))+n1(5)<pi/2, ...' sprintf('\n') ...
        '                ''[REPLANNER OBSERVER ERROR] measured pitch box reaches ZYX singularity.'');' sprintf('\n') ...
        '            Dq=double(F.euler_coordinate_delta_abs_ub(:));' sprintf('\n') ...
        '            assert(numel(Dq)==3&&all(isfinite(Dq))&&all(Dq>=0), ...' sprintf('\n') ...
        '                ''[REPLANNER OBSERVER ERROR] R19 Euler displacement support invalid.'');' sprintf('\n') ...
        '            [okPhi,phi1,kPhi]=obj.observer_unique_2pi_lift( ...' sprintf('\n') ...
        '                y0(4),n0(4),y1(4),n1(4),Dq(1));' sprintf('\n') ...
        '            [okPsi,psi1,kPsi]=obj.observer_unique_2pi_lift( ...' sprintf('\n') ...
        '                y0(6),n0(6),y1(6),n1(6),Dq(3));' sprintf('\n') ...
        '            assert(okPhi, ...' sprintf('\n') ...
        '                ''[REPLANNER OBSERVER ERROR] roll 2*pi branch lift is not unique.'');' sprintf('\n') ...
        '            assert(okPsi, ...' sprintf('\n') ...
        '                ''[REPLANNER OBSERVER ERROR] yaw 2*pi branch lift is not unique.'');' sprintf('\n') ...
        '            y1Lift=y1(iq); y1Lift(1)=phi1; y1Lift(3)=psi1;' sprintf('\n') ...
        '            dq=(y1Lift-y0(iq))/h;' sprintf('\n') ...
        '            rQdot=0.5*qddotUb*h+(norm(n0(iq))+norm(n1(iq)))/h;' sprintf('\n') ...
        '            Ey=obj.observer_euler_rate_inverse_ZYX(y1Lift);'];

    src=replace_once(src,old,new,'principal branch lift');

    %% C. Persist lift diagnostics in contracted observer output.
    anchor=[ ...
        '            O=struct(); O.closed=true; O.h=h; O.measured_error=MEAS;'];
    repl=[ ...
        '            O=struct(); O.closed=true; O.h=h; O.measured_error=MEAS;' sprintf('\n') ...
        '            O.roll_lift_k=kPhi; O.yaw_lift_k=kPsi;' sprintf('\n') ...
        '            O.periodic_branch_lift_unique=true;' sprintf('\n') ...
        '            O.continuous_zyx_chart_closed=logical(F.closed);' sprintf('\n') ...
        '            O.principal_roll_yaw_box_closed=logical(F.principal_roll_yaw_box_closed);'];
    src=replace_once(src,anchor,repl,'contraction diagnostics');

    %% D. Add unique-lift helper before Euler inverse.
    anchor='        function E = observer_euler_rate_inverse_ZYX(~,q)';
    helper=[ ...
        '        function [ok,lifted,k] = observer_unique_2pi_lift(~,c0,r0,c1,r1,dmax)' sprintf('\n') ...
        '            % Certified periodic lift theorem.' sprintf('\n') ...
        '            % True endpoint 0 lies in [c0-r0,c0+r0].  Continuous' sprintf('\n') ...
        '            % displacement is bounded by dmax.  Endpoint 1 measurement' sprintf('\n') ...
        '            % represents [c1-r1+2*pi*k,c1+r1+2*pi*k].  A branch is' sprintf('\n') ...
        '            % accepted iff exactly one integer k has nonempty intersection.' sprintf('\n') ...
        '            vals=double([c0 r0 c1 r1 dmax]);' sprintf('\n') ...
        '            assert(all(isfinite(vals))&&r0>=0&&r1>=0&&dmax>=0, ...' sprintf('\n') ...
        '                ''[REPLANNER OBSERVER ERROR] periodic-lift inputs invalid.'');' sprintf('\n') ...
        '            P=2*pi;' sprintf('\n') ...
        '            lo=c0-r0-dmax; hi=c0+r0+dmax;' sprintf('\n') ...
        '            sc=max([1 abs(lo) abs(hi) abs(c1) r1 dmax P]);' sprintf('\n') ...
        '            % Outward numerical guard only; it enlarges the reachable' sprintf('\n') ...
        '            % and measurement sets and therefore cannot create a false' sprintf('\n') ...
        '            % uniqueness certificate.' sprintf('\n') ...
        '            gd=64*eps(sc);' sprintf('\n') ...
        '            lo=lo-gd; hi=hi+gd; rr=r1+gd;' sprintf('\n') ...
        '            kmin=ceil((lo-(c1+rr))/P);' sprintf('\n') ...
        '            kmax=floor((hi-(c1-rr))/P);' sprintf('\n') ...
        '            ok=isfinite(kmin)&&isfinite(kmax)&&kmin==kmax;' sprintf('\n') ...
        '            if ok' sprintf('\n') ...
        '                k=kmin; lifted=c1+P*k;' sprintf('\n') ...
        '            else' sprintf('\n') ...
        '                k=NaN; lifted=NaN;' sprintf('\n') ...
        '            end' sprintf('\n') ...
        '        end' sprintf('\n') ...
        '' sprintf('\n') ...
        anchor];
    src=replace_once(src,anchor,helper,'unique periodic lift helper');

    %% E. Static theorem audits.
    assert(contains(src,'S.closed=pitchClosed; S.h=h; S.held_input=u;'), ...
        '[R19] Pitch-only kinematic chart closure not installed.');
    assert(contains(src,'S.euler_coordinate_delta_abs_ub=dEuler;'), ...
        '[R19] Coordinate displacement theorem not exported.');
    assert(contains(src,'observer_unique_2pi_lift'), ...
        '[R19] Unique periodic lift helper missing.');
    assert(~contains(src,'measured Euler box reaches chart boundary.'), ...
        '[R19] Old roll/yaw principal-box-as-singularity guard survived.');
    assert(contains(src,'roll 2*pi branch lift is not unique.'), ...
        '[R19] Fail-closed roll ambiguity guard missing.');
    assert(contains(src,'yaw 2*pi branch lift is not unique.'), ...
        '[R19] Fail-closed yaw ambiguity guard missing.');
    assert(contains(src,'PITCH_SUPPORT_REACHES_ZYX_SINGULARITY'), ...
        '[R19] Original pitch singularity authority disappeared.');

    write_text(rps,src);
    rehash

    fprintf('[R19] PASS.\n');
    fprintf('  pitch singularity theorem preserved        = 1\n');
    fprintf('  roll/yaw +/-pi false singularity removed   = 1\n');
    fprintf('  periodic branch ambiguity guessed          = 0\n');
    fprintf('  ambiguous lift fail-closed                 = 1\n');
    fprintf('  IMPORTANT: clear old objects/classes before next simulation.\n');

    OUT=struct('pass',true, ...
        'revision','AF7_ZYX_BRANCH_LIFT_THEOREM_R19', ...
        'pitch_singularity_condition_modified',false, ...
        'roll_yaw_principal_boundary_reclassified',true, ...
        'ambiguous_lift_fail_closed',true, ...
        'heuristic_unwrap',false);

catch ME
    try,write_text(rps,src0);catch,end
    rehash
    fprintf(2,'[R19] FAILED. REPLANNING_SYSTEM source rolled back.\n');
    fprintf(2,'[R19] ORIGINAL ERROR: %s | %s\n',ME.identifier,ME.message);
    rethrow(ME);
end
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1,'[R19] Anchor "%s" count=%d; expected 1.',label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end

function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));
s=strrep(s,sprintf('\r'),sprintf('\n'));
end

function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');
assert(f>=0,'[R19] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end
