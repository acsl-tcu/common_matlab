function OUT = AF7R58R60_SELFTEST()
% Self-contained mathematical regression using an arbitrary non-circular
% moving nominal path. No sensor environment/vehicle parameters are assumed.
% All output files go beside THIS file, not into a new directory.
root=fileparts(mfilename('fullpath'));
% A general 3D quadratic example, used ONLY for a structural unit test.
nom_pos=@(tau) [tau+.04*tau^2; 2*tau-.01*tau^2; 3+.2*tau];
nom_jets=@(tau) [ [tau+.04*tau^2;2*tau-.01*tau^2;3+.2*tau], ...
                     [1+.08*tau;2-.02*tau;.2], ...
                     [.08;-.02;0],zeros(3,5) ];
t0=1.37;delta=0.33;
A=nom_jets(t0-delta);
% Distinct nonzero position/velocity/acceleration etc. at the join.
A(:,1)=A(:,1)+[-2;0;0];
A(:,2)=A(:,2)+[.16;0;0];
A(:,3)=A(:,3)+[.002;0;0];
IN=struct('t0_s',t0,'initial_duration_s',7, ...
    'phase_delay_s',delta,'phase_slowdown_beta',.7, ...
    'phase_start_jets_0_to_7',[t0-delta,1,zeros(1,6)], ...
    'active_jets_0_to_7',A, ...
    'nominal_jets_fn',nom_jets,'nominal_position_fn',nom_pos, ...
    'max_trials',6,'enforce_scalar_monotone',false);
R=AF7R58R60_C7_FREE_REJOIN(IN);
assert(R.numerical_candidate_found,'R60 self-test did not construct a candidate');
C=R.candidate;
assert(C.start_jet_error<1e-8 && C.end_jet_error<1e-8, ...
    'R60:Test','C7 endpoint jet regression failed');
assert(C.phase_delay_final_s>C.phase_delay_initial_s && ...
    C.no_same_clock_catchup && C.phase_rate_nonnegative, ...
    'R60:Test','No-catch-up phase law failed');
t=linspace(C.t0_s,C.t1_s,1001);
[p,s,d]=AF7R58R60_EVAL(C,t,nom_pos);
assert(all(isfinite(p),'all')&&all(diff(s)>0) && ...
    all(diff(s)<=diff(t)+1e-9),'R60:Test','Phase-rate regression failed');
assert(norm(d(:,end))<1e-9,'R60:Test','Terminal correction nonzero');
% Simulate replanning WHILE the previous phase is still slowing down.
% The precise previous phase physical-time jet is an explicit input,
% not reconstructed from nominal clock time or guessed from a position.
IN2=IN;
IN2.phase_start_jets_0_to_7=[t0-delta,.85,-.004,zeros(1,5)];
IN2.phase_slowdown_beta=.45;
R2=AF7R58R60_C7_FREE_REJOIN(IN2);
assert(R2.numerical_candidate_found, ...
    'R60:Test','In-avoidance phase replan construction failed');
assert(R2.candidate.start_jet_error<1e-8 && ...
    R2.candidate.phase_delay_final_s>=delta, ...
    'R60:Test','In-avoidance start phase or C7 failed');
G=AF7R58R60_EKF_WHOLEBODY_NOW(struct( ...
    'pQ',[0;0;2], 'pL',[0;0;0], 'q',[0;0;-1], ...
    'cable_length',2,'radii',[.2;.2;.02], ...
    'obstacles',struct('id',1,'center',[10;0;1], ...
    'rotation',eye(3),'axes',[1;2;3]), ...
    'geometry_tolerance',1e-10));
assert(strcmp(G.results(1).status,'NUMERIC_SEPARATING_PLANE_FOUND'), ...
    'R60:Test','EKF whole-body now support-plane regression failed');
OUT=struct('status','PASS_STRUCTURAL_ONLY__NOT_SAFE_FOR_COMMIT', ...
    'commit_allowed',false,'c7_join_error',C.start_jet_error, ...
    'c7_end_error',C.end_jet_error, ...
    'delay_start_s',C.phase_delay_initial_s, ...
    'delay_end_s',C.phase_delay_final_s, ...
    'duration_s',C.T_s,'mid_phase_replan',R2.candidate, ...
    'current_geometry_test',G, ...
    'x_samples',p,'tau_samples',s, ...
    'candidate',C);
mat_file=fullfile(root,'AF7R58R60_OUT.mat');
txt_file=fullfile(root,'AF7R58R60_REPORT.txt');
OUT.mat_file=mat_file;OUT.report_file=txt_file;
save(mat_file,'OUT','-v7');
fid=fopen(txt_file,'w');
if fid<0,error('R60:File','Report cannot be created');end
fcloseCleanup=onCleanup(@()fclose(fid));
fprintf(fid,'R60 C7 NATURAL TIME STRUCTURAL SELFTEST\n');
fprintf(fid,'status=%s\n',OUT.status);
fprintf(fid,'join_jet_error=%.17g end_offset_jet_error=%.17g\n', ...
    OUT.c7_join_error,OUT.c7_end_error);
fprintf(fid,'duration_s=%.17g delta_initial_s=%.17g delta_final_s=%.17g\n', ...
    C.T_s,C.phase_delay_initial_s,C.phase_delay_final_s);
fprintf(fid,'UNPROVEN: full physical HLC rollout, reference speed/yaw regularity,\n');
fprintf(fid,'whole-body continuous-time safety, controller input and tension bounds.\n');
fprintf(fid,'HLC SOURCE IS NEVER ALTERED. COMMIT ALLOWED=0.\n');
OUT.mat_file=mat_file;OUT.report_file=txt_file;
end
