function [out,state]=ra_sim_sensor_trigger_step( ...
    agent,worldNow,pDroneTrue,sensorCfg,systemMode,forecastPrepared,flightTime,state,preflightMex)
%RA_SIM_SENSOR_TRIGGER_STEP 25ms: true-position sensor -> ONE selected mode.
% This is a MONITOR only: it never changes the HLC/CBF/reference/input.
% The sensor reads ONLY current true drone position to determine visibility.
% The forecast reads ONLY latest EKF states and current estimated mL.
% Missing native C MEX never triggers compilation during control tick.
% The C/B/D system mode is distinct from the obstacle method taken from
% worldNow.approximation. No duplicate shape selector exists here.
if nargin<8 || ~isstruct(state),state=struct();end
if nargin<9 || ~isstruct(preflightMex)
    preflightMex=struct('available',false);
end
clock=tic;
[obs,report]=ra_sim_sensor_detect(worldNow,pDroneTrue,sensorCfg);
method=ra_obstacle_method_info(obs);
changed=~isfield(state,'lastParts') || ...
    ~isequaln(state.lastParts,obs.parts) || ...
    ~isfield(state,'method') || ~strcmp(state.method,method.method) || ...
    ~isfield(state,'systemMode') || ~strcmp(state.systemMode,upper(char(systemMode))) || ...
    ~isfield(state,'lastGround') || ~isequaln(state.lastGround,obs.ground);
if changed
    % Only the observed geometry enters the trigger; the full world stays
    % inside this sensor function's call and is not cached downstream.
    Q=reference_avoidance_prepare_observed(agent,systemMode,obs,[], ...
        struct('allowMexBuild',false));
    Q.cfg.useMexCChainPreclear=strcmpi(systemMode,'C') && ...
        isfield(preflightMex,'available') && preflightMex.available && ...
        exist('wp_six_trigger_C_chain_numeric_mex_v8','file')==3;
    Q.cfg.autoRebuildMexDuringTick=false;
    state.prepared=Q;
    state.lastParts=obs.parts;
    state.lastGround=obs.ground;
    state.method=method.method;
    state.systemMode=upper(char(systemMode));
    state.geometryRebuilds=getCount(state,'geometryRebuilds')+1;
end
if ~isfield(state,'history') || ~isstruct(state.history),state.history=struct();end
[R,state.history]=reference_avoidance_tick(agent,state.history, ...
    forecastPrepared.modalCache,forecastPrepared.routeCache, ...
    state.prepared.known,state.prepared.cfg,flightTime);
out=struct('status',R.status,'reason',R.reason, ...
    'sensor',report,'trigger',R,'systemMode',upper(char(systemMode)), ...
    'obstacleApproximation',method.method,'obstacleKind',method.kind, ...
    'detectedObjects',report.detectedObjectCount, ...
    'detectedParts',report.returnedPartCount, ...
    'geometryCacheRebuilt',changed, ...
    'currentEstimatedMass',R.estimatedMassUsed, ...
    'totalSensorTriggerMs',1000*toc(clock),'monitorOnly',true);
end
function x=getCount(s,name)
if isfield(s,name),x=s.(name);else,x=0;end
end
