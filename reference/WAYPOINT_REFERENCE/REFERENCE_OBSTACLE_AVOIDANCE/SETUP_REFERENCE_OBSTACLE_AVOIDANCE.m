function info=SETUP_REFERENCE_OBSTACLE_AVOIDANCE()
%SETUP_REFERENCE_OBSTACLE_AVOIDANCE Add only the new modules to MATLAB path.
% Run from any directory. Old SAFETY_PREVIEW_GEOMETRY/TRIGGER_LIGHT can
% coexist during migration; this setup prioritizes the NEW copies.
root=fileparts(mfilename('fullpath'));
leaf={ ...
    fullfile(root,'SYSTEM_APPROXIMATION','COMMON'), ...
    fullfile(root,'SYSTEM_APPROXIMATION','MODEL_C_MULTIPLE_SPHERES'), ...
    fullfile(root,'SYSTEM_APPROXIMATION','MODEL_B_SPHERE_CAPSULE'), ...
    fullfile(root,'SYSTEM_APPROXIMATION','MODEL_D_SPHERE_CABLE_ELLIPSOID'), ...
    fullfile(root,'TRIGGER','ENTRY_AND_OBSERVATION'), ...
    fullfile(root,'TRIGGER','FOUR_SECOND_PREDICTION'), ...
    fullfile(root,'TRIGGER','GEOMETRY_SCREENING'), ...
    fullfile(root,'TRIGGER','MEX_ACCELERATION'), ...
    fullfile(root,'PREVIEW_TOOLS'), ...
    fullfile(root,'SIMULATED_SENSOR')};
% addpath(...,'-begin') prepends; loop in reverse to preserve leaf order.
for k=numel(leaf):-1:1
    if ~isfolder(leaf{k})
        error('RefAvoidance:Installation','Missing folder: %s',leaf{k});
    end
    addpath(leaf{k},'-begin');
end
addpath(root,'-begin');
addpath(fileparts(root),'-end'); % Original WAYPOINT_REFERENCE utilities
important={'wp_system_geometry_config','wp_shape_C','wp_shape_B', ...
    'wp_shape_D','wp_six_trigger_tick_v8','wp_six_trigger_evaluate_fast_v8'};
resolved=cell(size(important));
for j=1:numel(important)
    resolved{j}=which(important{j});
    if ~startsWith(resolved{j},[root filesep])
        error('RefAvoidance:PathConflict', ...
            'MATLAB is resolving %s from %s instead of %s', ...
            important{j},resolved{j},root);
    end
end
info=struct('status','NEW_FOLDER_PATH_ACTIVE', ...
    'root',root,'importantFunctions',{important}, ...
    'resolvedPaths',{resolved},'legacyFoldersUnmodified',true, ...
    'sensorImplemented',true,'safetyCertified',false, ...
    'mexBuildIsAutomaticOnCPreparation',true, ...
    'simulatedSensorCurrentOnly',true, ...
    'simulatedSensorDefaultRadiusM',20);
end
