function Q=AF7R58R38_PREFLIGHT()
% R38 source-bound audit. Research / simulation only.
p=which('REPLANNING_SYSTEM');
assert(~isempty(p),'REPLANNING_SYSTEM unavailable.');
s=fileread(p);
a=strfind(s,'function r25_publish_capture(obj)');
b=strfind(s,'function r35_capture_completed_stage1_marker');
c=strfind(s,'function r17_capture(obj');
d=strfind(s,'function [ok,reason] = r17_precommit_check');
assert(numel(a)==1&&numel(b)==1&&numel(c)==1&&numel(d)==1&&a<b&&b<c&&c<d, ...
    '[R38] wrong source class / profile section.');
pub=s(a:b); capture=s(c:d);
assert(contains(pub,'D.r20_profile=struct(')&&contains(pub,'D.r22_profile=struct('), ...
    '[R38] after-Flight profile materialization not installed.');
assert(~contains(capture,'D.r20_profile=struct(')&& ...
       ~contains(capture,'D.r22_profile=struct('), ...
    '[R38] Flight-time redundant profile materialization remains.');
assert(contains(s,'ENABLE_LIGHT_RUNTIME_AUDIT = 0;') && ...
    contains(s,'start_staged_replan_pipeline') && ...
    contains(s,'STAGE3_SIM_ONLY_ATOMIC_COMMIT_PASS'), ...
    '[R38] R37 authority source prerequisite missing.');
Q=struct('schema','AF7R58R38_SOURCE_CHECK_V1','source',p, ...
    'after_flight_profile_materialization',true, ...
    'profile_rebuild_in_flight',false, ...
    'safety_and_commit_source_bodies_unmodified_by_R38',true, ...
    'real_flight_suitable',false, ...
    'mex_rebuild_required',false, ...
    'runtime_equivalence_matlab_verified',false, ...
    'trigger_switched_to_estimate',false, ...
    'return_auto_commit_enabled',false);
disp('[R38] PREFLIGHT PASS | source-bound post-Flight profiles | certified path unchanged.');
end
