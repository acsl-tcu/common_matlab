function A = AF7R55_BALANCED_PHASE_AUDIT
assert(evalin('base','exist(''D38'',''var'')==1'), ...
    'Run: D38 = AF7R38_SPEED_ROOTCAUSE_AUDIT; first.');
D38=evalin('base','D38');
P=D38.pipeline;

fprintf('\n====================================================================================================\n');
fprintf(' AF7R55 | BALANCED PHASE + MIXED ORIENTED-ELLIPSOID AUDIT\n');
fprintf('====================================================================================================\n');

F={ ...
 'predeadline_candidate_success','predeadline_candidate_family', ...
 'predeadline_payload_speed','predeadline_uav_speed','predeadline_qdot', ...
 'predeadline_c7_exact','predeadline_speed_pass_count', ...
 'predeadline_rejoin_pass_count','predeadline_geometry_test_count', ...
 'r55_phase_build_count','r55_phase_build_fail_count', ...
 'r55_phase_episode_pass_count','r55_phase_episode_empty_count', ...
 'r55_alpha','r55_delay_s','r55_source_unsafe_start_s','r55_source_unsafe_end_s', ...
 'r55_predicted_first_unsafe_t_s','r55_predicted_last_unsafe_t_s', ...
 'r55_pre_unsafe_slack_s','r55_post_unsafe_slack_s','r55_min_temporal_slack_s', ...
 'r55_phase_entry_transition_s','r55_phase_exit_transition_s', ...
 'r55_source_phase_at_rejoin_s','r55_rejoin_clock_delay_s', ...
 'r55_mixed_side_episode_count','r55_side_plus_count','r55_side_minus_count', ...
 'r55_side_onebranch_count','r55_side_both_failed_count','r55_corridor_row_count', ...
 'r55_obstacle_count','r55_min_ellipsoid_axis_m','r55_max_ellipsoid_axis_m', ...
 'r55_max_rotation_orth_error','r55_old_clock_binding_count', ...
 'r55_maneuver_horizon_coupling_count', ...
 'r37_spatial_qp_solutions','r37_exact_c7_candidates','r37_best_total_velocity_ub', ...
 'r37_best_accel_ub','r37_best_jerk_ub', ...
 'r24e_family_speed_pass','r24e_family_speed_fail', ...
 'r35_heading_candidate_count','r35_heading_pass_count','r35_heading_reject_count', ...
 'r52_selected_spatial_rejoin_s', ...
 'native_episode_ms','native_hessian_ms','native_corridor_ms','native_qp_ms', ...
 'native_candidate_build_ms','native_total_ms','last_stage1_ms','last_stage2_ms','last_stage3_ms'};

for k=1:numel(F)
    f=F{k};
    if isfield(P,f)
        v=P.(f);
        if isnumeric(v)||islogical(v)
            if isscalar(v)
                fprintf('%-64s = %.17g\n',f,double(v));
            else
                fprintf('%-64s = %s\n',f,mat2str(double(v),17));
            end
        else
            fprintf('%-64s = %s\n',f,char(string(v)));
        end
    else
        fprintf('%-64s = <NOT EXPOSED>\n',f);
    end
end

fprintf('\n[SOURCE CONTRACT]\n');
src=fileread(which('af7r36_core.hpp'));
p0=strfind(src,'AF7R55 PRIMARY:');
p1=strfind(src,'Single production theory: no alternative trajectory-family fallback.');
assert(~isempty(p0)&&~isempty(p1)&&p1(find(p1>p0(1),1))>p0(1),'R55 primary markers unavailable.');
blk=src(p0(1):p1(find(p1>p0(1),1)));

hasH=contains(blk,'L.horizon');
hasLiteral4=~isempty(regexp(blk,'(?<![A-Za-z0-9_])4\.0(?![A-Za-z0-9_])','once'));
hasR54Trials=contains(blk,'r54_phase_candidates')||contains(blk,'rejoinTrials');
hasOldClock=contains(blk,'ref.eval(tR)')||contains(blk,'ref.eval(t1)');
hasBalanced=contains(src,'r55_build_balanced_phase');
hasMixed=contains(src,'r55_choose_episode_rows');
hasExactSupport=contains(src,'r52_best_support_plane') && ...
                contains(src,'o.axes.x') && contains(src,'tmul(o.R');

fprintf(' R55 primary reads L.horizon                           = %d\n',hasH);
fprintf(' R55 primary contains literal 4.0                     = %d\n',hasLiteral4);
fprintf(' R55 primary contains R54 phase/rejoin enumeration    = %d\n',hasR54Trials);
fprintf(' R55 primary directly binds old reference at rejoin   = %d\n',hasOldClock);
fprintf(' balanced source-phase allocator present              = %d\n',hasBalanced);
fprintf(' episode-local mixed-side selector present            = %d\n',hasMixed);
fprintf(' oriented-ellipsoid exact-support machinery present   = %d\n',hasExactSupport);

closed=~hasH && ~hasLiteral4 && ~hasR54Trials && ~hasOldClock && ...
       hasBalanced && hasMixed && hasExactSupport && ...
       isfield(P,'r55_old_clock_binding_count') && P.r55_old_clock_binding_count==0 && ...
       isfield(P,'r55_maneuver_horizon_coupling_count') && P.r55_maneuver_horizon_coupling_count==0;
fprintf(' R55 GENERALITY / CLOCK-DECOUPLING CONTRACT CLOSED     = %d\n',closed);

fprintf('\nMeaning:\n');
fprintf(' - 4 s remains trigger/finite-sensing authority only.\n');
fprintf(' - spatial rejoin is to delayed source phase, not the old same-clock position.\n');
fprintf(' - ellipsoid orientation and all three semiaxes enter exact support directly.\n');
fprintf(' - different obstacle episodes may choose different bypass sides without 2^N enumeration.\n');
fprintf('====================================================================================================\n');

A=P;
assignin('base','R55A',A);
end
