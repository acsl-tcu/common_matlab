function OUT = AF7R36_TOWING_CONSTANT_V1_INSTALL()
% AF7R36_TOWING_CONSTANT_V1_INSTALL
% Adds a towing-specific constant-translation candidate between the existing
% minimum-deviation primary and the unchanged minimum-snap fallback.
%
% Safety:
%   - existing minimum-deviation branch remains first and unchanged;
%   - new branch is attempted only if that branch fails;
%   - new candidate uses the same corridor halfspaces;
%   - unsafe spans satisfy d_j(s)=a_j exactly (v_j=0);
%   - degree-15 C7 transition construction is unchanged;
%   - acceptance is unchanged:
%       speed certificate -> rejoin certificate -> continuous whole-body cert;
%   - historical minimum-snap fallback remains unchanged and last.
%
% No README / no persistent backup files are created.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 TOWING CONSTANT-TRANSLATION V1 INSTALL\n');
fprintf(' hard safety certificate semantics modified = 0\n');
fprintf(' old certified fallback preserved            = 1\n');
fprintf('====================================================================================================\n');

refDir = fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir) && isfolder(refDir), ...
    '[TOWCONST-V1] Cannot resolve current reference directory.');

hpp = fullfile(refDir,'af7r36_core.hpp');
cpp = fullfile(refDir,'af7r36_single_core_mex.cpp');
assert(isfile(hpp),'[TOWCONST-V1] Missing %s',hpp);
assert(isfile(cpp),'[TOWCONST-V1] Missing %s',cpp);

hpp0 = normalize_lf(fileread(hpp));
cpp0 = normalize_lf(fileread(cpp));
hppNew = hpp0;
cppNew = cpp0;

assert(contains(hpp0,'AF7_TOWING_DIAG_V1'), ...
    ['[TOWCONST-V1] Expected AF7_TOWING_DIAG_V1 core not found. ' ...
     'Install/use the currently tested diagnostic source first.']);
assert(~contains(hpp0,'AF7_TOWING_CONSTANT_V1'), ...
    '[TOWCONST-V1] Core is already patched.');
assert(~contains(cpp0,'TOWING_CONSTANT_TRANSLATION'), ...
    '[TOWCONST-V1] MEX wrapper is already patched.');

try
    %% 1) Candidate-family documentation.
    old = [ ...
        '    // family: 1 = exact minimum integrated squared deviation affine family,' newline ...
        '    //         2 = historical minimum-snap affine fallback.' newline];
    new = [ ...
        '    // family: 1 = exact minimum integrated squared deviation affine family,' newline ...
        '    //         2 = historical minimum-snap affine fallback,' newline ...
        '    //         3 = towing constant-translation minimum-deviation family.' newline];
    hppNew = replace_once(hppNew,old,new,'candidate family documentation');

    %% 2) Add towing-branch counters without touching existing diagnostics.
    old = [ ...
        '    int fallback_candidate_count=0;' newline ...
        '    int fallback_speed_pass=0;' newline ...
        '    int fallback_rejoin_pass=0;' newline ...
        '    int fallback_geom_tests=0;' newline];
    new = [old ...
        '    int towing_candidate_count=0;' newline ...
        '    int towing_speed_pass=0;' newline ...
        '    int towing_rejoin_pass=0;' newline ...
        '    int towing_geom_tests=0;' newline];
    hppNew = replace_once(hppNew,old,new,'towing counters');

    %% 3) Extend branch-local accounting only. Hard gates are unchanged.
    old = [ ...
        '        if(branch==1) R.primary_candidate_count+=(int)candidates.size();' newline ...
        '        else if(branch==2) R.fallback_candidate_count+=(int)candidates.size();' newline];
    new = [ ...
        '        if(branch==1) R.primary_candidate_count+=(int)candidates.size();' newline ...
        '        else if(branch==2) R.fallback_candidate_count+=(int)candidates.size();' newline ...
        '        else if(branch==3) R.towing_candidate_count+=(int)candidates.size();' newline];
    hppNew = replace_once(hppNew,old,new,'candidate branch accounting');

    old = '            if(branch==1) ++R.primary_speed_pass; else if(branch==2) ++R.fallback_speed_pass;';
    new = ['            if(branch==1) ++R.primary_speed_pass; ' ...
           'else if(branch==2) ++R.fallback_speed_pass; ' ...
           'else if(branch==3) ++R.towing_speed_pass;'];
    hppNew = replace_once(hppNew,old,new,'speed branch accounting');

    old = [ ...
        '            if(branch==1){++R.primary_rejoin_pass;++R.primary_geom_tests;}' newline ...
        '            else if(branch==2){++R.fallback_rejoin_pass;++R.fallback_geom_tests;}' newline];
    new = [ ...
        '            if(branch==1){++R.primary_rejoin_pass;++R.primary_geom_tests;}' newline ...
        '            else if(branch==2){++R.fallback_rejoin_pass;++R.fallback_geom_tests;}' newline ...
        '            else if(branch==3){++R.towing_rejoin_pass;++R.towing_geom_tests;}' newline];
    hppNew = replace_once(hppNew,old,new,'rejoin geometry branch accounting');

    %% 4) Insert towing-specific candidate AFTER the unchanged primary and
    %     BEFORE the unchanged historical fallback.
    anchor = [ ...
        '    // ------------------------------------------------------------------' newline ...
        '    // FALLBACK: exact previously flown affine/minimum-snap family.' newline];

    block = [ ...
        '    // ------------------------------------------------------------------' newline ...
        '    // AF7_TOWING_CONSTANT_V1' newline ...
        '    // TOWING-SPECIFIC SECONDARY FAMILY: constant correction on each' newline ...
        '    // certified nominal-unsafe component.' newline ...
        '    //' newline ...
        '    // The existing affine primary remains authoritative and is tried' newline ...
        '    // first. This branch is reached only when that primary cannot close' newline ...
        '    // the unchanged hard certificates.' newline ...
        '    //' newline ...
        '    // Here the unsafe-span correction is constrained to' newline ...
        '    //' newline ...
        '    //      d_j(s) = a_j,        d_j''(s)=0, d_j'(s)=0,' newline ...
        '    //' newline ...
        '    // by eliminating every affine velocity variable v_j from the QP.' newline ...
        '    // This is a towing-specific effort objective: it introduces no' newline ...
        '    // correction-induced motion while the payload/cable is traversing' newline ...
        '    // the certified avoidance span. The entry/inter-component/exit' newline ...
        '    // segments are still the exact same degree-15 C7 jet transitions.' newline ...
        '    //' newline ...
        '    // Corridor feasibility remains exact because the original linear' newline ...
        '    // halfspaces are restricted to the convex subspace v_j=0. No safety' newline ...
        '    // gate is removed or relaxed. Every resulting candidate still passes' newline ...
        '    // the identical speed -> rejoin -> continuous whole-body stack.' newline ...
        '    // If this family fails, the historical minimum-snap fallback below' newline ...
        '    // remains bit-for-bit available as before.' newline ...
        '    // ------------------------------------------------------------------' newline ...
        '    ts=clk::now();' newline ...
        '    {' newline ...
        '        const auto Hfull=minimum_deviation_hessian(E.comp,t0,t1);' newline ...
        '        const int npos=3*Cn;' newline ...
        '        std::vector<int> pmap(npos,0);' newline ...
        '        for(int j=0;j<Cn;++j)for(int d=0;d<3;++d)' newline ...
        '            pmap[3*j+d]=3*(2*j)+d;' newline ...
        '' newline ...
        '        std::vector<double> Hpos(npos*npos,0.0);' newline ...
        '        for(int i=0;i<npos;++i)for(int j=0;j<npos;++j)' newline ...
        '            Hpos[i*npos+j]=Hfull[pmap[i]*nvar+pmap[j]];' newline ...
        '' newline ...
        '        std::vector<Base> BT;' newline ...
        '        std::vector<int> sg(Ne,1);' newline ...
        '        std::function<void(int)> rec=[&](int k){' newline ...
        '            if(k<Ne){sg[k]=1;rec(k+1);sg[k]=-1;rec(k+1);return;}' newline ...
        '            std::vector<Row> rows;' newline ...
        '            for(int e=0;e<Ne;++e){' newline ...
        '                const auto& src=(sg[e]>0)?OR[e].plus:OR[e].minus;' newline ...
        '                for(const auto& rf:src){' newline ...
        '                    Row rr;rr.a.assign(npos,0.0);rr.b=rf.b;' newline ...
        '                    for(int j=0;j<Cn;++j)for(int d=0;d<3;++d)' newline ...
        '                        rr.a[3*j+d]=rf.a[3*(2*j)+d];' newline ...
        '                    rows.push_back(std::move(rr));' newline ...
        '                }' newline ...
        '            }' newline ...
        '            QPSol q=solve_qp(Hpos,npos,rows);' newline ...
        '            if(!q.ok)return;' newline ...
        '            std::vector<double> z(nvar,0.0);' newline ...
        '            for(int j=0;j<Cn;++j)for(int d=0;d<3;++d)' newline ...
        '                z[3*(2*j)+d]=q.z[3*j+d];' newline ...
        '            BT.push_back({std::move(z),q.cost,q.slack,sg});' newline ...
        '        };' newline ...
        '        rec(0);' newline ...
        '' newline ...
        '        std::vector<Candidate> towing;' newline ...
        '        towing.reserve(BT.size());' newline ...
        '        for(auto&b:BT){' newline ...
        '            Candidate c=build_candidate(E.comp,t0,t1,b.z,b.c,b.sg,b.s,3);' newline ...
        '            c.constant_translation=true;' newline ...
        '            towing.push_back(std::move(c));' newline ...
        '        }' newline ...
        '        R.tim.qp+=std::chrono::duration<double,std::milli>(clk::now()-ts).count();' newline ...
        '        auto tc=clk::now();' newline ...
        '        if(certify_candidates(towing,true,3)){' newline ...
        '            R.tim.candidate_build+=std::chrono::duration<double,std::milli>(clk::now()-tc).count();' newline ...
        '            R.tim.synthesis=std::chrono::duration<double,std::milli>(clk::now()-a).count();' newline ...
        '            R.tim.candidate=R.tim.synthesis;' newline ...
        '            R.tim.total=std::chrono::duration<double,std::milli>(clk::now()-T0).count();' newline ...
        '            return R;' newline ...
        '        }' newline ...
        '        R.tim.candidate_build+=std::chrono::duration<double,std::milli>(clk::now()-tc).count();' newline ...
        '    }' newline ...
        '' newline];

    hppNew = insert_before_once(hppNew,anchor,block,'towing constant branch');

    %% 5) Expose new family/counters through the existing MEX result.
    old = [ ...
        '        "fallback_candidate_count","fallback_speed_pass_count",' newline ...
        '        "fallback_rejoin_pass_count","fallback_geometry_test_count",' newline];
    new = [ ...
        '        "fallback_candidate_count","fallback_speed_pass_count",' newline ...
        '        "fallback_rejoin_pass_count","fallback_geometry_test_count",' newline ...
        '        "towing_candidate_count","towing_speed_pass_count",' newline ...
        '        "towing_rejoin_pass_count","towing_geometry_test_count",' newline];
    cppNew = replace_once(cppNew,old,new,'MEX towing field names');

    old = [ ...
        '    set("fallback_candidate_count",dscalar(R.fallback_candidate_count));' newline ...
        '    set("fallback_speed_pass_count",dscalar(R.fallback_speed_pass));' newline ...
        '    set("fallback_rejoin_pass_count",dscalar(R.fallback_rejoin_pass));' newline ...
        '    set("fallback_geometry_test_count",dscalar(R.fallback_geom_tests));' newline];
    new = [old ...
        '    set("towing_candidate_count",dscalar(R.towing_candidate_count));' newline ...
        '    set("towing_speed_pass_count",dscalar(R.towing_speed_pass));' newline ...
        '    set("towing_rejoin_pass_count",dscalar(R.towing_rejoin_pass));' newline ...
        '    set("towing_geometry_test_count",dscalar(R.towing_geom_tests));' newline];
    cppNew = replace_once(cppNew,old,new,'MEX towing field assignments');

    old = [ ...
        '    const char* family=(R.cand.family==1)?"MINIMUM_DEVIATION_AFFINE":' newline ...
        '                       ((R.cand.family==2)?"MINIMUM_SNAP_FALLBACK":"NONE");' newline];
    new = [ ...
        '    const char* family=(R.cand.family==1)?"MINIMUM_DEVIATION_AFFINE":' newline ...
        '                       ((R.cand.family==2)?"MINIMUM_SNAP_FALLBACK":' newline ...
        '                       ((R.cand.family==3)?"TOWING_CONSTANT_TRANSLATION":"NONE"));' newline];
    cppNew = replace_once(cppNew,old,new,'candidate family string');

    cppNew = replace_once(cppNew, ...
        '    set("compact_constant_translation",logicalScalar(false));', ...
        '    set("compact_constant_translation",logicalScalar(R.cand.constant_translation));', ...
        'constant translation result flag');

    cppNew = replace_once(cppNew, ...
        'static const char* PLANNER_REV="AF7_REPLANNER_MIN_DEVIATION_V4_FIXED_T1";', ...
        'static const char* PLANNER_REV="AF7_TOWING_CONSTANT_V1_FIXED_T1";', ...
        'planner revision');

    %% 6) Write only after every source-bound edit closed.
    write_text_lf(hpp,hppNew);
    write_text_lf(cpp,cppNew);

    %% 7) Rebuild. Source text is restored in-memory on any failure.
    fprintf('[TOWCONST-V1] Source patch closed. Rebuilding af7r36_single_core_mex...\n');
    oldDir=pwd;
    cdir=onCleanup(@()cd(oldDir)); %#ok<NASGU>
    cd(refDir);
    clear mex;
    mex('-R2018a','-O', ...
        'COMPFLAGS="$COMPFLAGS /std:c++17"', ...
        ['-I' refDir], ...
        '-output','af7r36_single_core_mex', ...
        '-outdir',refDir, ...
        cpp);
    clear mex;
    rehash;

    assert(exist('af7r36_single_core_mex','file')==3, ...
        '[TOWCONST-V1] Rebuilt MEX not visible.');

    fprintf('[TOWCONST-V1] PASS.\n');
    fprintf('  primary unchanged                       = 1\n');
    fprintf('  towing constant branch installed        = 1\n');
    fprintf('  historical minimum-snap fallback kept   = 1\n');
    fprintf('  speed/rejoin/whole-body hard gates same = 1\n');
    fprintf('  persistent backup files created         = 0\n');

    OUT=struct();
    OUT.pass=true;
    OUT.reference_dir=refDir;
    OUT.revision='AF7_TOWING_CONSTANT_V1';
    OUT.hard_certificate_semantics_modified=false;
    OUT.old_fallback_preserved=true;
    OUT.readme_created=false;
    OUT.persistent_backup_created=false;

catch ME
    try, write_text_lf(hpp,hpp0); catch, end
    try, write_text_lf(cpp,cpp0); catch, end
    clear mex;
    rehash;
    fprintf(2,'[TOWCONST-V1] FAILED; source text restored in-memory. No partial source patch retained.\n');
    rethrow(ME);
end
end

function s=normalize_lf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));
s=strrep(s,sprintf('\r'),sprintf('\n'));
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1, ...
    '[TOWCONST-V1] Anchor "%s" count=%d; expected exactly 1. No edit retained.', ...
    label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end

function txt=insert_before_once(txt,anchor,block,label)
h=strfind(txt,anchor);
assert(numel(h)==1, ...
    '[TOWCONST-V1] Anchor "%s" count=%d; expected exactly 1. No edit retained.', ...
    label,numel(h));
txt=[txt(1:h-1) block txt(h:end)];
end

function write_text_lf(path,txt)
f=fopen(path,'wt','n','UTF-8');
assert(f>=0,'[TOWCONST-V1] Cannot open %s for writing.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end
