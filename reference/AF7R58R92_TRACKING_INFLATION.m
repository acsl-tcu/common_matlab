function [V,D]=AF7R58R92_TRACKING_INFLATION(live,opts)
% Separate switch for EXTRA robust observer/tracking inflation only.
% OFF removes only these new margins, NEVER the physical body radii,
% baseline sensor/inflation margins, HLC dynamics or nominal constraints.
% No default uncertainty radius; absence of a source-bound tube means the
% reference-level geometric test can run, but execution safety is UNPROVED.
assert(isstruct(live)&&isscalar(live)&&isstruct(opts)&&isscalar(opts), ...
    'R92:RuntimeAndDiagnosticOptionsRequired');
on=1;backup=1;
if isfield(opts,'robust_tracking_inflation_on')
    on=opts.robust_tracking_inflation_on;
end
if isfield(opts,'failure_backup_on')
    backup=opts.failure_backup_on;
end
assert(isscalar(on)&&any(on==[0 1])&& ...
    isscalar(backup)&&any(backup==[0 1]), ...
    'R92:DiagnosticFlagsMustBeZeroOrOne');
V=live;
D=struct('robust_tracking_inflation_on',logical(on), ...
    'failure_backup_on',logical(backup), ...
    'additional_radii_applied_m',[0 0 0], ...
    'tube_data_authority_verified',false, ...
    'execution_robust_tube_mathematically_proved',false, ...
    'backup_executed',false, ...
    'status','ROBUST_TUBE_NOT_SUPPLIED__REFERENCE_ONLY');
if ~on
    D.status='EXTRA_TUBE_INFLATION_OFF__DIAGNOSTIC_ONLY';
    return;
end
if ~isfield(opts,'tracking_tube')
    return;
end
T=opts.tracking_tube;
need={'uav_position_error_m','cable_position_error_m', ...
    'payload_position_error_m','reference_version', ...
    'estimated_mass_kg','source_bound_certified'};
assert(isstruct(T)&&isscalar(T)&&all(isfield(T,need)), ...
    'R92:TrackingTubeMissingRequiredFields');
q=[T.uav_position_error_m,T.cable_position_error_m, ...
    T.payload_position_error_m];
assert(isnumeric(q)&&numel(q)==3&&all(isfinite(q))&&all(q>=0)&& ...
    isfield(live,'source_reference_version')&& ...
    isfield(live,'latest_EKF_mL_kg')&& ...
    double(T.reference_version)==double(live.source_reference_version)&& ...
    double(T.estimated_mass_kg)==double(live.latest_EKF_mL_kg)&& ...
    logical(T.source_bound_certified), ...
    'R92:UncertifiedOrStaleTrackingTube');
V.rQ_m=live.rQ_m+q(1);
V.rC_m=live.rC_m+q(2);
V.rL_m=live.rL_m+q(3);
D.additional_radii_applied_m=q;
D.tube_data_authority_verified=true;
D.status='EXTERNAL_VERSION_AND_MASS_BOUND_TUBE_APPLIED__PROOF_UNAUDITED';
% Caller flag cannot substitute the actual controller reachability theorem.
end
