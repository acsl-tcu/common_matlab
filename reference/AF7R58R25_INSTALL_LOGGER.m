function Q = AF7R58R25_INSTALL_LOGGER()
% R25: Source-bound, idempotent patch of the R23-instrumented Flight loop.
% Inserts LOGGER-visible scalar timings and a post-Flight diagnostic flush.
% It does NOT touch controller calls, reference commands or safety decisions.
runner = which('run_flight_headless');
if isempty(runner)
    p = which('REPLANNING_SYSTEM');
    assert(~isempty(p),'[R25] REPLANNING_SYSTEM not found.');
    runner = fullfile(fileparts(fileparts(p)), 'run_flight_headless.m');
end
assert(isfile(runner),'[R25] run_flight_headless.m not found.');
S = fileread(runner);
tag = '% AF7R58R25_LOGGER_INSTALLED';
if contains(S, tag)
    Q=struct('runner',runner,'already_installed',true,'patched',false);
    fprintf('[R25] Logger patch already installed.\n');
    return;
end
assert(contains(S,'% AF7R58R23_SPIKE_PROBE_INSTALLED'), ...
    '[R25] R23 full-loop probe is not installed. Run AF7R58R23_INSTALL_SPIKE_PROBE once first.');
loopStart='%% 8. Headless simulation loop';
loopEnd='% Trim preallocated timing arrays to actual logged length.';
a=strfind(S,loopStart); b=strfind(S,loopEnd);
assert(numel(a)==1 && numel(b)==1 && a<b, ...
    '[R25] Loop source anchors do not match. Nothing modified.');
head=S(1:a-1); loop=S(a:b-1); tail=S(b:end);
% Ensure the logger sees the same numeric fields from Arming onward,
% rather than adding new columns only in Flight.
armingOld='agent.controller.result.controllertime_total=control_plus_sim_plant_s;';
armingInit=[armingOld newline ...
    '%% R25 pre-create ordinary LOGGER scalar fields before first logging' newline ...
    'r25_fields={''r25_sensor_ms'',''r25_estimator_ms'',''r25_reference_ms'',''r25_controller_ms'',''r25_input_ms'',''r25_online_ms'',''r25_plant_ms'',''r25_stage1_ms'',''r25_stage2_ms''};' newline ...
    'for r25_idx=1:numel(r25_fields)' newline ...
    '    agent.controller.result.(r25_fields{r25_idx})=NaN;' newline ...
    'end'];
assert(numel(strfind(head,armingOld))==1, ...
    '[R25] Cannot locate Arming logger schema initialization.');
head=strrep(head,armingOld,armingInit);
% The r23 variables are populated immediately after each do_prop_local call.
old='    agent.controller.result.controllertime_total=control_plus_sim_plant_s;';
insert = [old newline ...
    '    % R25: ordinary LOGGER logging, no separate Flight file I/O.' newline ...
    '    % These values are in milliseconds and are observable like other' newline ...
    '    % controller.result fields. No safety decision reads them.' newline ...
    '    agent.controller.result.r25_sensor_ms=1e3*r23_sensor_s;' newline ...
    '    agent.controller.result.r25_estimator_ms=1e3*r23_estimator_s;' newline ...
    '    agent.controller.result.r25_reference_ms=1e3*r23_reference_s;' newline ...
    '    agent.controller.result.r25_controller_ms=1e3*r23_controller_s;' newline ...
    '    agent.controller.result.r25_input_ms=1e3*r23_input_s;' newline ...
    '    agent.controller.result.r25_online_ms=1e3*online_before_plant_s;' newline ...
    '    agent.controller.result.r25_plant_ms=1e3*simulation_plant_s;' newline ...
    '    agent.controller.result.r25_stage1_ms=NaN;' newline ...
    '    agent.controller.result.r25_stage2_ms=NaN;' newline ...
    '    if abs(double(replanner_instance.staged_replan_request_time)-double(time.t))<=32*eps(max(1,abs(double(time.t))))' newline ...
    '        agent.controller.result.r25_stage1_ms=double(replanner_instance.staged_replan_last_stage1_ms);' newline ...
    '    end' newline ...
    '    if abs(double(replanner_instance.staged_replan_request_time)+double(replanner_instance.prediction_dt)-double(time.t))<=32*eps(max(1,abs(double(time.t))))' newline ...
    '        agent.controller.result.r25_stage2_ms=double(replanner_instance.staged_replan_last_stage2_ms);' newline ...
    '    end' newline ...
    '    ' tag];
assert(numel(strfind(loop,old))==1, ...
    '[R25] Controller log entry expected once in Flight loop.');
loop=strrep(loop,old,insert);
% Only after the loop: publish the event snapshot, retaining R17 auto-result.
needle='AF7R58R23_SPIKE_REPORT(runtime_profile);';
assert(numel(strfind(tail,needle))==1, ...
    '[R25] R23 post-Flight report anchor not found.');
tail=strrep(tail,needle, ...
    ['replanner_instance.r25_publish_capture();' newline needle]);
patched=[head loop tail];
assert(numel(strfind(patched,tag))==1 && ...
    numel(strfind(patched,'r25_publish_capture();'))==1 && ...
    numel(strfind(patched,'r25_reference_ms='))==1, ...
    '[R25] Incomplete patch; nothing modified.');
backup=fullfile(tempdir, ...
    ['AF7R58R25_RUNNER_BACKUP_' datestr(now,'yyyymmdd_HHMMSS_FFF') '.m']);
[ok,msg]=copyfile(runner,backup);
assert(ok,'[R25] Backup failed: %s',msg);
fid=fopen(runner,'w','n','UTF-8');
assert(fid>=0,'[R25] Cannot write runner; backup: %s',backup);
fprintf(fid,'%s',patched);
fclose(fid);
rehash;
Q=struct('runner',runner,'backup',backup,'already_installed',false, ...
    'patched',true,'flight_file_io',false,'safety_logic_modified',false);
fprintf('[R25] LOGGER FIELDS INSTALLED | post-Flight diag flush active.\n');
fprintf('Runner: %s\nBackup: %s\n',runner,backup);
end
