function OUT = AF7R29_INSTALL_R11_NONCOMMIT_HOTPATH()
% AF7R29_INSTALL_R11_NONCOMMIT_HOTPATH
% =========================================================================
% R11 production hot-path cleanup.
%
% Motivation from AF7R28:
%   - failed proposal requests after 13.9 s have backend callback < 1 ms,
%     but SENSOR_TRIGGER/replan stage is 12--17 ms.
%   - successful-but-deadline-missed requests at 9.85--10.375 s also spend
%     substantial time after the backend callback on read-only diagnostics.
%
% Safety argument:
%   * a failed proposal can never commit;
%   * a deadline-missed proposal can never commit;
%   therefore reference-only / execution-aware theorem evaluation on those
%   two NONCOMMIT branches is diagnostic only and may be deferred outside
%   the production hot path without enlarging the commit set.
%
% Default:
%   ENABLE_NONCOMMIT_DIAGNOSTIC_EVAL = 0
%
% Set it to 1 only for dedicated forensic/theorem-diagnostic runs.
% =========================================================================

clc;
fprintf('\n');
fprintf('====================================================================================================\n');
fprintf(' AF7R29 | INSTALL R11 NONCOMMIT HOT-PATH DEFER\n');
fprintf('====================================================================================================\n');

src=which('REPLANNING_SYSTEM');
assert(~isempty(src)&&isfile(src),'[AF7R29] REPLANNING_SYSTEM.m not found.');
raw=fileread(src);
assert(contains(raw,'AF7R27-R10'),'[AF7R29] R10 marker missing.');
assert(~contains(raw,'AF7R29-R11'),'[AF7R29] R11 already installed.');

stamp=char(datetime('now','Format','yyyyMMdd_HHmmss'));
backup=fullfile(fileparts(src),['REPLANNING_SYSTEM_pre_R11_' stamp '.m']);
copyfile(src,backup);

% -------------------------------------------------------------------------
% Public switch, default OFF in production.
% -------------------------------------------------------------------------
old1=['        ENABLE_LIGHT_RUNTIME_AUDIT = 1; % 外側1個の軽量 wall timer のみ有効' newline];
new1=[old1 ...
'        ENABLE_NONCOMMIT_DIAGNOSTIC_EVAL = 0; % failed/deadline-missed proposal theorem diagnostics are deferred' newline];
raw=replace_once(raw,old1,new1,'public diagnostic switch');

% Constructor option.
old2=['            if isfield(opts,''ENABLE_LIGHT_RUNTIME_AUDIT'')' newline ...
      '                obj.ENABLE_LIGHT_RUNTIME_AUDIT=logical(opts.ENABLE_LIGHT_RUNTIME_AUDIT);' newline ...
      '            end' newline];
new2=[old2 ...
'            if isfield(opts,''ENABLE_NONCOMMIT_DIAGNOSTIC_EVAL'')' newline ...
'                obj.ENABLE_NONCOMMIT_DIAGNOSTIC_EVAL=logical(opts.ENABLE_NONCOMMIT_DIAGNOSTIC_EVAL);' newline ...
'            end' newline];
raw=replace_once(raw,old2,new2,'constructor diagnostic switch');

% -------------------------------------------------------------------------
% Fast return for failed candidate BEFORE expensive read-only theorem work.
% -------------------------------------------------------------------------
anchorFail=['                if ~(isfield(candidate,''success'') && logical(candidate.success))' newline ...
            '                    % Preserve the failed candidate as a read-only theorem' newline];

fastFail=[ ...
'                if ~(isfield(candidate,''success'') && logical(candidate.success)) && ...' newline ...
'                        ~obj.ENABLE_NONCOMMIT_DIAGNOSTIC_EVAL' newline ...
'                    obj.last_reference_only_evaluation=struct( ...' newline ...
'                        ''certified'',false, ...' newline ...
'                        ''full_system_authority'',false, ...' newline ...
'                        ''sampled_acceptance'',false, ...' newline ...
'                        ''reason'',''SKIPPED_FAILED_PROPOSAL_PRODUCTION_HOTPATH'');' newline ...
'                    obj.last_execution_aware_evaluation=struct( ...' newline ...
'                        ''certified'',false, ...' newline ...
'                        ''full_system_authority'',false, ...' newline ...
'                        ''sampled_acceptance'',false, ...' newline ...
'                        ''reason'',''SKIPPED_FAILED_PROPOSAL_PRODUCTION_HOTPATH'');' newline ...
'                    obj.generator_last_status_code=21;' newline ...
'                    obj.last_replan_status=struct( ...' newline ...
'                        ''requested'',true,''committed'',false, ...' newline ...
'                        ''reason'',''REFERENCE_PROPOSAL_NOT_CERTIFIED'', ...' newline ...
'                        ''proposal_reason_code'',double(candidate.reason_code), ...' newline ...
'                        ''proposal_reason'',obj.bezier_proposal_reason_text(candidate.reason_code), ...' newline ...
'                        ''proposal_generated'',obj.logical_struct_field(candidate,''generated''), ...' newline ...
'                        ''proposal_t0'',double(candidate.t0), ...' newline ...
'                        ''proposal_tm'',double(candidate.tm), ...' newline ...
'                        ''proposal_t1'',double(candidate.t1), ...' newline ...
'                        ''reference_certified'',false, ...' newline ...
'                        ''execution_certified'',false, ...' newline ...
'                        ''noncommit_diagnostics_deferred'',true, ...' newline ...
'                        ''cycle_ms'',cycle_ms, ...' newline ...
'                        ''deadline_ms'',1e3*double(obj.hard_modify_deadline_s), ...' newline ...
'                        ''commit_policy'',char(obj.AVOIDANCE_COMMIT_POLICY));' newline ...
'                    return;' newline ...
'                end' newline newline ...
anchorFail];
raw=replace_once(raw,anchorFail,fastFail,'failed candidate fast-return');

% -------------------------------------------------------------------------
% Fast return for successful candidate whose generator already missed the
% hard deadline. No read-only certificate evaluation can make it committable.
% -------------------------------------------------------------------------
anchorDeadline=[ ...
'                % -----------------------------------------------------' newline ...
'                % Evaluate BOTH safety layers on the SAME candidate.' newline];

fastDeadline=[ ...
'                if deadlineExceeded && ~obj.ENABLE_NONCOMMIT_DIAGNOSTIC_EVAL' newline ...
'                    obj.last_reference_only_evaluation=struct( ...' newline ...
'                        ''certified'',false, ...' newline ...
'                        ''full_system_authority'',false, ...' newline ...
'                        ''sampled_acceptance'',false, ...' newline ...
'                        ''reason'',''SKIPPED_DEADLINE_MISS_PRODUCTION_HOTPATH'');' newline ...
'                    obj.last_execution_aware_evaluation=struct( ...' newline ...
'                        ''certified'',false, ...' newline ...
'                        ''full_system_authority'',false, ...' newline ...
'                        ''sampled_acceptance'',false, ...' newline ...
'                        ''reason'',''SKIPPED_DEADLINE_MISS_PRODUCTION_HOTPATH'');' newline ...
'                    obj.generator_last_status_code=-20;' newline ...
'                    obj.last_replan_status=struct( ...' newline ...
'                        ''requested'',true,''committed'',false, ...' newline ...
'                        ''reason'',''GENERATOR_DEADLINE_EXCEEDED__DIAGNOSTICS_DEFERRED'', ...' newline ...
'                        ''commit_policy'',char(obj.AVOIDANCE_COMMIT_POLICY), ...' newline ...
'                        ''reference_certified'',false, ...' newline ...
'                        ''execution_certified'',false, ...' newline ...
'                        ''noncommit_diagnostics_deferred'',true, ...' newline ...
'                        ''cycle_ms'',cycle_ms, ...' newline ...
'                        ''deadline_ms'',1e3*double(obj.hard_modify_deadline_s));' newline ...
'                    return;' newline ...
'                end' newline newline ...
anchorDeadline];
raw=replace_once(raw,anchorDeadline,fastDeadline,'deadline miss fast-return');

% Header.
hdr='% AF7R27-R10: adaptive interval cover + projected corridor hull + active-set QP.';
assert(contains(raw,hdr),'[AF7R29] R10 header not found.');
raw=strrep(raw,hdr,[hdr newline ...
    '% AF7R29-R11: noncommittable proposal diagnostics deferred from production hot path.']);

% Static invariants.
assert(contains(raw,'SKIPPED_FAILED_PROPOSAL_PRODUCTION_HOTPATH'));
assert(contains(raw,'SKIPPED_DEADLINE_MISS_PRODUCTION_HOTPATH'));
assert(contains(raw,'ENABLE_NONCOMMIT_DIAGNOSTIC_EVAL = 0'));
assert(~contains(regexprep(raw,'\s+',''),'''sampled_acceptance'',true'), ...
    '[AF7R29] sampled acceptance true detected.');

fid=fopen(src,'w');
assert(fid>=0,'[AF7R29] cannot open source.');
c=onCleanup(@()fclose(fid));
fwrite(fid,raw,'char');
clear c;

OUT=struct();
OUT.schema='AF7R29_INSTALL_R11_NONCOMMIT_HOTPATH_V1';
OUT.source=src;
OUT.backup=backup;
OUT.installed=true;
OUT.commit_set_changed=false;
OUT.safety_acceptance_changed=false;
OUT.failed_branch_diagnostics_deferred=true;
OUT.deadline_miss_diagnostics_deferred=true;

fprintf(' source                                  = %s\n',src);
fprintf(' backup                                  = %s\n',backup);
fprintf(' failed proposal diagnostics deferred    = 1\n');
fprintf(' deadline-miss diagnostics deferred      = 1\n');
fprintf(' default diagnostic switch               = 0\n');
fprintf(' commit set changed                      = 0\n');
fprintf(' safety acceptance changed               = 0\n');
fprintf('====================================================================================================\n');
end


function out=replace_once(in,old,new,label)
idx=strfind(in,old);
assert(numel(idx)==1, ...
    '[AF7R29] Expected one "%s" target; found %d.',label,numel(idx));
out=[in(1:idx-1) new in(idx+length(old):end)];
end
