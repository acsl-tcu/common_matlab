function AF7R58ZZY_R22_INSTALL
% AF7R58ZZY-R22 accounting-only diagnostic installer.
% No performance optimization. Instruments the R21 path so the 9.85-10.025 s
% online excess can be reconciled from runner -> reference -> staged internals.

EXPECTED_SOURCE_SHA='310cfdd01f9554a80b71e8d90464816a721859709ad7c4b9137cdc0f3a6eaf49';
scriptDir=fileparts(mfilename('fullpath'));
srcPath=which('REPLANNING_SYSTEM'); runnerPath=which('run_flight_headless');
assert(~isempty(srcPath)&&isfile(srcPath),'[R22] REPLANNING_SYSTEM.m not found.');
assert(~isempty(runnerPath)&&isfile(runnerPath),'[R22] run_flight_headless.m not found.');
assert(strcmpi(sha256_file_r22(srcPath),EXPECTED_SOURCE_SHA),'[R22] production source SHA mismatch.');
root=fileparts(runnerPath);

% R22 is intentionally based on the current R21 behavior.
r21Anchor='replanner_instance = REPLANNING_SYSTEM_R21_BALANCED(agent,nominal_ref,replan_opts);';
r22Anchor='replanner_instance = REPLANNING_SYSTEM_R22_ACCOUNTING_DIAG(agent,nominal_ref,replan_opts);';
txt=fileread(runnerPath);
if contains(txt,r22Anchor)
    assert(count(txt,r22Anchor)==1,'[R22] R22 runner anchor is not unique.');
    mode='ALREADY_R22';
elseif contains(txt,r21Anchor)
    assert(count(txt,r21Anchor)==1,'[R22] R21 runner anchor is not unique.');
    mode='FROM_R21';
else
    error('[R22] Install R21 first. R22 is accounting-only and must diagnose the exact R21 behavior.');
end

% Copy exact R21/R19 support plus R22 diagnostic subclass/report.
files={ ...
 'REPLANNING_SYSTEM_R19_FAST.m', ...
 'REPLANNING_SYSTEM_R21_BALANCED.m', ...
 'REPLANNING_SYSTEM_R22_ACCOUNTING_DIAG.m', ...
 'af7r75_posaccel_batch_R19.m', ...
 'af7r75_posaccel_core_R19.m', ...
 'af7r72_posaccel_core_R16.m', ...
 'af7r73_posaccel_core_R17.m', ...
 'AF7R58ZZY_R22_REPORT.m'};
for k=1:numel(files)
    s=fullfile(scriptDir,files{k}); assert(isfile(s),'[R22] package file missing: %s',files{k});
    copyfile(s,fullfile(root,files{k}),'f');
end

% MEXes are R21/R19 numerical authority. Compile only if missing.
ensure_mex_r22(fullfile(scriptDir,'af7r70_observer_mex.cpp'),root,'af7r70_observer_mex');
ensure_mex_r22(fullfile(scriptDir,'af7r71_decasteljau_batch_mex.cpp'),root,'af7r71_decasteljau_batch_mex');
ensure_mex_r22(fullfile(scriptDir,'af7r75_correction_posaccel_mex.cpp'),root,'af7r75_correction_posaccel_mex');
addpath(root,'-begin'); rehash;
assert(exist('REPLANNING_SYSTEM_R22_ACCOUNTING_DIAG','class')==8,'[R22] diagnostic class parse/install failed.');

if strcmp(mode,'FROM_R21')
    backupPath=fullfile(root,'run_flight_headless.R22_PREINSTALL_BACKUP.m');
    assert(~isfile(backupPath),'[R22] R22 backup already exists; resolve before install.');
    copyfile(runnerPath,backupPath);

    % 1) Switch only the replanner class and enable built-in diagnostic timers.
    patched=strrep(txt,r21Anchor,r22Anchor);
    optAnchor='replan_opts.ENABLE_AUTO_REPLAN_COMMIT = ENABLE_AUTO_REPLAN_COMMIT;';
    assert(count(patched,optAnchor)==1,'[R22] option anchor changed.');
    optInsert=[optAnchor newline ...
        '% R22 ACCOUNTING DIAGNOSTIC ONLY -- no safety/control semantics changed.' newline ...
        'replan_opts.ENABLE_PROFILING = true;' newline ...
        'replan_opts.ENABLE_LIGHT_RUNTIME_AUDIT = true;' newline ...
        'replan_opts.SPIKE_CAPTURE_THRESHOLD_MS = 0.0;'];
    patched=strrep(patched,optAnchor,optInsert);

    % 2) Preallocate runner-level per-property timing channels.
    allocAnchor='runtime_profile.k = 0;';
    assert(count(patched,allocAnchor)==1,'[R22] runtime allocation anchor changed.');
    names={ ...
      'r22_sensor_prop_s','r22_estimator_prop_s','r22_replanner_s','r22_sload_s', ...
      'r22_reference_merge_s','r22_reference_prop_s','r22_diag_snapshot_s', ...
      'r22_controller_prop_s','r22_input_transform_prop_s', ...
      'r22_rt_light_e2e_ms','r22_rt_observer_ms','r22_rt_live_binding_ms','r22_rt_dependency_ms', ...
      'r22_rt_base_ref_ms','r22_rt_cert_guard_ms','r22_rt_geometry_eval_ms','r22_rt_reference_packet_ms', ...
      'r22_rt_sensor_ms','r22_rt_kernel_ms','r22_rt_trigger_ms','r22_rt_replan_status_ms', ...
      'r22_rt_output_write_ms','r22_rt_state_trigger_write_ms','r22_rt_state_cert_write_ms', ...
      'r22_rt_state_meta_write_ms','r22_rt_total_ms', ...
      'r22_spike_front_ms','r22_spike_loadmass_ms','r22_spike_dependency_ms','r22_spike_base_cert_geom_ms', ...
      'r22_spike_sensor_trigger_ms','r22_spike_output_state_ms','r22_spike_write_active_output_ms', ...
      'r22_trigger_event_capture_ms'};
    ins=allocAnchor;
    for k=1:numel(names)
        ins=[ins newline 'runtime_profile.' names{k} ' = nan(size(ts:dt:te));']; %#ok<AGROW>
    end
    patched=strrep(patched,allocAnchor,ins);

    % 3) Replace ONLY the Flight online call block by semantically identical
    % calls with boundary timers. Reference list is asserted to be exactly
    % [timevarying,sload], matching the current runner contract.
    block=[ ...
'    do_prop_local(time,cha,cha,logger,env,agent,"sensor",1,true);' newline ...
'    do_prop_local(time,cha,cha,logger,env,agent,"estimator",1,true);' newline ...
'    do_prop_local(time,cha,cha,logger,env,agent,"reference",1,true);' newline ...
'    do_prop_local(time,cha,cha,logger,env,agent,"controller",1,true);' newline ...
'    do_prop_local(time,cha,cha,logger,env,agent,"input_transform",1,true);'];
    assert(count(patched,block)==1,'[R22] Flight property-call block changed or not unique.');
    timed=[ ...
'    r22t=tic; do_prop_local(time,cha,cha,logger,env,agent,"sensor",1,true); r22_sensor_prop_s=toc(r22t);' newline ...
'    r22t=tic; do_prop_local(time,cha,cha,logger,env,agent,"estimator",1,true); r22_estimator_prop_s=toc(r22t);' newline ...
'' newline ...
'    % Exact expansion of do_prop_local for the fixed Flight reference list' newline ...
'    % ["timevarying","sload"], so replanner and SLOAD adjustment are separated.' newline ...
'    assert(isequal(agent.cha_allocation.f.reference,["timevarying","sload"]), ...' newline ...
'        ''[R22] Flight reference allocation changed.'');' newline ...
'    r22ref=tic;' newline ...
'    r22t=tic; agent.reference.result = agent.reference.timevarying.do(time,cha,logger,env,agent,1); r22_replanner_s=toc(r22t);' newline ...
'    r22t=tic; r22_sload_result = agent.reference.sload.do(time,cha,logger,env,agent,1); r22_sload_s=toc(r22t);' newline ...
'    r22t=tic; agent.reference.result = merge_result(agent.reference.result,r22_sload_result); r22_reference_merge_s=toc(r22t);' newline ...
'    r22_reference_prop_s=toc(r22ref);' newline ...
'' newline ...
'    % Snapshot scalar diagnostic channels; time this overhead explicitly.' newline ...
'    r22t=tic; r22st=replanner_instance.result.state;' newline ...
'    r22_rt_light_e2e_ms=double(r22st.rt_light_e2e_ms);' newline ...
'    r22_rt_observer_ms=double(r22st.rt_observer_ms);' newline ...
'    r22_rt_live_binding_ms=double(r22st.rt_live_binding_ms);' newline ...
'    r22_rt_dependency_ms=double(r22st.rt_dependency_ms);' newline ...
'    r22_rt_base_ref_ms=double(r22st.rt_base_ref_ms);' newline ...
'    r22_rt_cert_guard_ms=double(r22st.rt_cert_guard_ms);' newline ...
'    r22_rt_geometry_eval_ms=double(r22st.rt_geometry_eval_ms);' newline ...
'    r22_rt_reference_packet_ms=double(r22st.rt_reference_packet_ms);' newline ...
'    r22_rt_sensor_ms=double(r22st.rt_sensor_ms);' newline ...
'    r22_rt_kernel_ms=double(r22st.rt_kernel_ms);' newline ...
'    r22_rt_trigger_ms=double(r22st.rt_trigger_ms);' newline ...
'    r22_rt_replan_status_ms=double(r22st.rt_replan_status_ms);' newline ...
'    r22_rt_output_write_ms=double(r22st.rt_output_write_ms);' newline ...
'    r22_rt_state_trigger_write_ms=double(r22st.rt_state_trigger_write_ms);' newline ...
'    r22_rt_state_cert_write_ms=double(r22st.rt_state_cert_write_ms);' newline ...
'    r22_rt_state_meta_write_ms=double(r22st.rt_state_meta_write_ms);' newline ...
'    r22_rt_total_ms=double(r22st.rt_total_ms);' newline ...
'    r22_spike_front_ms=double(r22st.rt_spike_stage_front_ms);' newline ...
'    r22_spike_loadmass_ms=double(r22st.rt_spike_stage_loadmass_ms);' newline ...
'    r22_spike_dependency_ms=double(r22st.rt_spike_stage_dependency_ms);' newline ...
'    r22_spike_base_cert_geom_ms=double(r22st.rt_spike_stage_base_cert_geom_ms);' newline ...
'    r22_spike_sensor_trigger_ms=double(r22st.rt_spike_stage_sensor_trigger_ms);' newline ...
'    r22_spike_output_state_ms=double(r22st.rt_spike_stage_output_state_ms);' newline ...
'    r22_spike_write_active_output_ms=double(r22st.rt_spike_write_active_output_ms);' newline ...
'    r22_trigger_event_capture_ms=double(r22st.trigger_event_capture_ms);' newline ...
'    r22_diag_snapshot_s=toc(r22t);' newline ...
'' newline ...
'    r22t=tic; do_prop_local(time,cha,cha,logger,env,agent,"controller",1,true); r22_controller_prop_s=toc(r22t);' newline ...
'    r22t=tic; do_prop_local(time,cha,cha,logger,env,agent,"input_transform",1,true); r22_input_transform_prop_s=toc(r22t);'];
    patched=strrep(patched,block,timed);

    % 4) Store the new channels at the same rk after each Flight iteration.
    storeAnchor='    runtime_profile.full_iteration_s(rk)=full_iteration_s;';
    assert(count(patched,storeAnchor)>=1,'[R22] runtime storage anchor missing.');
    % Only the indented Flight occurrence is matched by the exact leading spaces.
    store=storeAnchor;
    scalarNames=names;
    for k=1:numel(scalarNames)
        nm=scalarNames{k};
        store=[store newline '    runtime_profile.' nm '(rk)=' nm ';']; %#ok<AGROW>
    end
    patched=strrep(patched,storeAnchor,store);

    % 5) Trim diagnostic arrays together with the existing profile.
    trimAnchor='runtime_profile.full_iteration_s=runtime_profile.full_iteration_s(1:Krt);';
    assert(count(patched,trimAnchor)==1,'[R22] runtime trim anchor changed.');
    trim=trimAnchor;
    for k=1:numel(names)
        trim=[trim newline 'runtime_profile.' names{k} '=runtime_profile.' names{k} '(1:Krt);']; %#ok<AGROW>
    end
    patched=strrep(patched,trimAnchor,trim);

    write_utf8_r22(runnerPath,patched);
end
rehash;
assert(strcmpi(sha256_file_r22(srcPath),EXPECTED_SOURCE_SHA),'[R22] production source changed during install.');
newtxt=fileread(runnerPath);
assert(count(newtxt,r22Anchor)==1,'[R22] runner class switch failed.');
assert(contains(newtxt,'r22_replanner_s=toc(r22t);'),'[R22] runner property accounting patch missing.');

fprintf('\n[R22] INSTALLED | mode=%s\n',mode);
fprintf('[R22] DIAGNOSTIC ONLY: no trajectory/certificate/controller/commit optimization added.\n');
fprintf('[R22] Built-in replanner profiling + runner property boundaries enabled.\n');
fprintf('[R22] Stage1/2/3 internals instrumented on exact R21 behavior.\n');
fprintf('[R22] Run: run_flight_headless\n');
fprintf('[R22] Then: AF7R58ZZY_R22_REPORT\n');
end

function ensure_mex_r22(cppPath,outDir,outName)
if exist(outName,'file')==3, return; end
assert(isfile(cppPath),'[R22] missing C++ source: %s',cppPath);
old=pwd; c=onCleanup(@()cd(old)); cd(outDir);
if ispc
    mex('-R2018a','COMPFLAGS=$COMPFLAGS /fp:strict',cppPath,'-output',outName,'-outdir',outDir);
else
    mex('-R2018a','CXXFLAGS=$CXXFLAGS -fno-fast-math -ffp-contract=off',cppPath,'-output',outName,'-outdir',outDir);
end
end

function h=sha256_file_r22(p)
fid=fopen(p,'rb'); assert(fid>=0,'[R22] cannot open %s.',p); c=onCleanup(@()fclose(fid)); b=fread(fid,Inf,'*uint8');
md=javaMethod('getInstance','java.security.MessageDigest','SHA-256'); md.update(typecast(b,'int8'));
h=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
function write_utf8_r22(p,s)
fid=fopen(p,'w','n','UTF-8'); assert(fid>=0,'[R22] cannot write %s.',p); c=onCleanup(@()fclose(fid)); fwrite(fid,s,'char');
end
