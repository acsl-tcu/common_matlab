function OUT = AF7R24_INSTALL_R9_SYNTHESIS_TIMING()
% AF7R24_INSTALL_R9_SYNTHESIS_TIMING
% =========================================================================
% Diagnostic-only instrumentation inside
% build_bezier_piecewise_towing_candidates().
%
% Measures:
%   Hessian construction
%   corridor-row construction
%   exact sign enumeration + QP solves
%   candidate control-point / derivative-bound assembly
%
% No synthesis/certificate/deadline logic is changed.
% =========================================================================

clc;
fprintf('\n');
fprintf('====================================================================================================\n');
fprintf(' AF7R24 | INSTALL R9 SYNTHESIS SUBSTAGE TIMING\n');
fprintf('====================================================================================================\n');

src=which('REPLANNING_SYSTEM');
assert(~isempty(src)&&isfile(src),'[AF7R24] REPLANNING_SYSTEM.m not found.');
raw=fileread(src);
assert(contains(raw,'AF7R21-R9'),'[AF7R24] R9 marker not found.');
assert(contains(raw,'AF7R23_STAGE_TIMING'),'[AF7R24] Install R23 first.');
assert(~contains(raw,'AF7R24_SYNTHESIS_TIMING'),'[AF7R24] already installed.');

stamp=char(datetime('now','Format','yyyyMMdd_HHmmss'));
backup=fullfile(fileparts(src),['REPLANNING_SYSTEM_pre_R24_' stamp '.m']);
copyfile(src,backup);

% 1) Properties.
old1=['        r9_stage_total_internal_ms              = NaN;' newline];
new1=[old1 ...
'        % AF7R24_SYNTHESIS_TIMING diagnostic-only mirrors' newline ...
'        r9_synth_hessian_ms                    = NaN;' newline ...
'        r9_synth_corridor_ms                   = NaN;' newline ...
'        r9_synth_qp_ms                         = NaN;' newline ...
'        r9_synth_candidate_build_ms            = NaN;' newline ...
'        r9_synth_row_count                     = NaN;' newline ...
'        r9_synth_episode_count                 = NaN;' newline ...
'        r9_synth_component_count               = NaN;' newline ...
'        r9_synth_sign_count                    = NaN;' newline];
raw=replace_once(raw,old1,new1,'properties');

% 2) Logger property list.
old2=['                "r9_stage_total_internal_ms", ...' newline ...
      '                "geometry_shadow_pass", ...'];
new2=['                "r9_stage_total_internal_ms", ...' newline ...
      '                "r9_synth_hessian_ms", ...' newline ...
      '                "r9_synth_corridor_ms", ...' newline ...
      '                "r9_synth_qp_ms", ...' newline ...
      '                "r9_synth_candidate_build_ms", ...' newline ...
      '                "r9_synth_row_count", ...' newline ...
      '                "r9_synth_episode_count", ...' newline ...
      '                "r9_synth_component_count", ...' newline ...
      '                "r9_synth_sign_count", ...' newline ...
      '                "geometry_shadow_pass", ...'];
raw=replace_once(raw,old2,new2,'logger list');

% 3) State mirrors.
old3=['            st.r9_stage_total_internal_ms=obj.r9_stage_total_internal_ms;' newline ...
      '            st.geometry_shadow_pass=logical(obj.geometry_shadow_pass);'];
new3=['            st.r9_stage_total_internal_ms=obj.r9_stage_total_internal_ms;' newline ...
      '            st.r9_synth_hessian_ms=obj.r9_synth_hessian_ms;' newline ...
      '            st.r9_synth_corridor_ms=obj.r9_synth_corridor_ms;' newline ...
      '            st.r9_synth_qp_ms=obj.r9_synth_qp_ms;' newline ...
      '            st.r9_synth_candidate_build_ms=obj.r9_synth_candidate_build_ms;' newline ...
      '            st.r9_synth_row_count=obj.r9_synth_row_count;' newline ...
      '            st.r9_synth_episode_count=obj.r9_synth_episode_count;' newline ...
      '            st.r9_synth_component_count=obj.r9_synth_component_count;' newline ...
      '            st.r9_synth_sign_count=obj.r9_synth_sign_count;' newline ...
      '            st.geometry_shadow_pass=logical(obj.geometry_shadow_pass);'];
raw=replace_all_at_least(raw,old3,new3,1,'state mirrors');

% 4) Reset timers at synthesis function entry after nvar is known.
old4=['            nslot=2*C;' newline ...
      '            nvar=3*nslot;' newline];
new4=[old4 ...
'            obj.r9_synth_hessian_ms=NaN;' newline ...
'            obj.r9_synth_corridor_ms=NaN;' newline ...
'            obj.r9_synth_qp_ms=NaN;' newline ...
'            obj.r9_synth_candidate_build_ms=NaN;' newline ...
'            obj.r9_synth_row_count=NaN;' newline ...
'            obj.r9_synth_episode_count=E;' newline ...
'            obj.r9_synth_component_count=C;' newline ...
'            obj.r9_synth_sign_count=2^E;' newline];
raw=replace_once(raw,old4,new4,'timer reset');

% 5) Hessian.
old5=['            Hs=obj.piecewise_minimum_snap_hessian(EPI.components, ...' newline ...
      '                double(P.t0),double(t1));' newline];
new5=['            r24tic=tic;' newline ...
      old5];
raw=replace_once(raw,old5,new5,'hessian start');

old6=['            H=kron(Hs,eye(3));' newline ...
      '            H=0.5*(H+H.'');' newline];
new6=[old6 ...
'            obj.r9_synth_hessian_ms=1e3*toc(r24tic);' newline];
raw=replace_once(raw,old6,new6,'hessian end');

% 6) Corridor loop.
old7=['            for ie=1:E' newline ...
      '                ep=EPI.episodes(ie);'];
new7=['            r24tic=tic;' newline ...
      old7];
raw=replace_once(raw,old7,new7,'corridor start');

old8=['            BASE=struct(''z'',{},''qp_cost'',{},''corridor_signs'',{}, ...' newline ...
      '                ''min_slack'',{});' newline];
new8=['            obj.r9_synth_corridor_ms=1e3*toc(r24tic);' newline ...
      '            rows24=0;' newline ...
      '            for ie24=1:numel(OR)' newline ...
      '                rows24=rows24+size(OR(ie24).rows_plus,1)+size(OR(ie24).rows_minus,1);' newline ...
      '            end' newline ...
      '            obj.r9_synth_row_count=rows24;' newline ...
      old8 ...
      '            r24tic=tic;' newline];
raw=replace_once(raw,old8,new8,'corridor end / qp start');

% 7) QP end.
old9=['            SYN.fixed_sign_qp_feasible_count=numel(BASE);' newline ...
      '            if isempty(BASE)' newline];
new9=['            SYN.fixed_sign_qp_feasible_count=numel(BASE);' newline ...
      '            obj.r9_synth_qp_ms=1e3*toc(r24tic);' newline ...
      '            if isempty(BASE)' newline];
raw=replace_once(raw,old9,new9,'qp end');

% 8) Candidate build.
old10=['            [~,ord]=sort([BASE.qp_cost]);' newline ...
       '            BASE=BASE(ord);' newline ...
       '            for ib=1:numel(BASE)' newline];
new10=['            [~,ord]=sort([BASE.qp_cost]);' newline ...
       '            BASE=BASE(ord);' newline ...
       '            r24tic=tic;' newline ...
       '            for ib=1:numel(BASE)' newline];
raw=replace_once(raw,old10,new10,'candidate build start');

old11=['            SYN.certified=~isempty(CANDS);' newline ...
       '        end' newline newline ...
       newline ...
       '        function [A,b,ok] = bezier_piecewise_episode_corridor_rows'];
new11=['            obj.r9_synth_candidate_build_ms=1e3*toc(r24tic);' newline ...
       '            SYN.certified=~isempty(CANDS);' newline ...
       '        end' newline newline ...
       newline ...
       '        function [A,b,ok] = bezier_piecewise_episode_corridor_rows'];
raw=replace_once(raw,old11,new11,'candidate build end');

% Marker.
oldH=['% AF7R23_STAGE_TIMING: diagnostic-only top-level R9 timing instrumentation.' newline];
newH=[oldH ...
'% AF7R24_SYNTHESIS_TIMING: diagnostic-only synthesis substage timing.' newline];
raw=replace_once(raw,oldH,newH,'header');

fid=fopen(src,'w');
assert(fid>=0,'[AF7R24] cannot open source.');
fwrite(fid,raw,'char');
fclose(fid);

OUT=struct('schema','AF7R24_INSTALL_R9_SYNTHESIS_TIMING_V1', ...
    'source',src,'backup',backup,'installed',true, ...
    'acceptance_logic_modified',false);
fprintf(' source                                  = %s\n',src);
fprintf(' backup                                  = %s\n',backup);
fprintf(' synthesis timing installed              = 1\n');
fprintf(' acceptance logic modified               = 0\n');
fprintf('====================================================================================================\n');
end


function out=replace_once(in,old,new,label)
idx=strfind(in,old);
assert(numel(idx)==1, ...
    '[AF7R24] Expected one "%s" target; found %d.',label,numel(idx));
out=[in(1:idx-1) new in(idx+length(old):end)];
end


function out=replace_all_at_least(in,old,new,nmin,label)
idx=strfind(in,old);
assert(numel(idx)>=nmin, ...
    '[AF7R24] Expected at least %d "%s" targets; found %d.',nmin,label,numel(idx));
out=strrep(in,old,new);
end
