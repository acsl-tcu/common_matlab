function Q = AF7R58R26_PREFLIGHT()
% Read-only provenance check before the simulation-only atomic commit trial.
cls=which('REPLANNING_SYSTEM');
assert(~isempty(cls)&&isfile(cls),'[R26] Class missing.');
s=fileread(cls);
need={ ...
 'function r26_materialize_deferred_diagnostics(obj)', ...
 'obj.r26_deferred_candidate=candidate;', ...
 'obj.r26_deferred_pending=true;', ...
 'obj.r26_materialize_deferred_diagnostics();', ...
 'function [ok,reason] = activate_staged_reference_only_bundle(', ...
 'obj.activate_staged_reference_only_bundle( ...', ...
 'STAGE3_SIM_ONLY_ATOMIC_COMMIT_PASS', ...
 'obj.r26_r15_status=snap15;', ...
 'ENABLE_AF7R58R17_DIAG_CONTINUE_LATE = 1', ...
 'ENABLE_AF7R58R16_REFERENCE_BRIDGE = 1'};
for k=1:numel(need)
    assert(contains(s,need{k}), ...
        '[R26] Required source marker absent: %s',need{k});
end
runner=which('run_flight_headless');
if isempty(runner)
    runner=fullfile(fileparts(fileparts(cls)),'run_flight_headless.m');
end
assert(isfile(runner),'[R26] Runner missing.');
r=fileread(runner);
assert(contains(r,'replan_opts.R26_SIMULATION_ONLY_EXPERIMENT = true;') && ...
    contains(r,'% AF7R58R25_LOGGER_INSTALLED') && ...
    contains(r,'replanner_instance.r25_publish_capture();'), ...
    '[R26] Headless sim-only opt-in or R25 logger is missing.');
assert(exist('af7r36_single_core_mex','file')==3, ...
    '[R26] Existing C++17 MEX binary missing.');
Q=struct('source',cls,'runner',runner, ...
    'diagnostics_lazily_materialized',true, ...
    'r15_status_buffered',true, ...
    'simulation_commit_opted_in',true, ...
    'plant_tracking_tube_complete',false, ...
    'actual_flight_acceptable',false, ...
    'deadline_proof_complete',false);
fprintf('[R26] PREFLIGHT SOURCE CHECK PASS. HEADLESS SIMULATION ONLY; NO REALTIME CLAIM.\n');
end
