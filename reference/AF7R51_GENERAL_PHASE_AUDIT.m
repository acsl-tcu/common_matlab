function A = AF7R51_GENERAL_PHASE_AUDIT
assert(evalin('base','exist(''D38'',''var'')==1'), ...
    'Run: D38 = AF7R38_SPEED_ROOTCAUSE_AUDIT; first.');
D38=evalin('base','D38');
assert(isstruct(D38)&&isfield(D38,'pipeline'));
P=D38.pipeline;

fprintf('\n====================================================================================================\n');
fprintf(' AF7R51 | GENERAL-C7 PHASE-WARPED TANGENT-CORRIDOR AUDIT\n');
fprintf('====================================================================================================\n');

F={ ...
 'predeadline_candidate_success','predeadline_candidate_family', ...
 'predeadline_t0','predeadline_t1','predeadline_payload_speed', ...
 'predeadline_uav_speed','predeadline_qdot','predeadline_c7_exact', ...
 'predeadline_speed_pass_count','predeadline_rejoin_pass_count', ...
 'predeadline_geometry_test_count', ...
 'r32_affine_base_detected','r47_active_base_replan_count', ...
 'r47_nonaffine_base_count','r47_heading_leaf_count','r47_heading_split_count', ...
 'r37_side_assignments','r37_spatial_qp_solutions','r37_exact_c7_candidates', ...
 'r37_support_start_s','r37_actual_rejoin_s','r37_best_total_velocity_ub', ...
 'r37_best_accel_ub','r37_best_jerk_ub', ...
 'r45_tangent_interval_count','r45_zero_offset_interval_count', ...
 'r45_convex_search_fallback_count','r45_best_fixed_peak_req_m', ...
 'r45_best_tangent_peak_req_m','r45_max_peak_relief_m', ...
 'r48_exit_monotone_row_count', ...
 'r51_phase_seed_count','r51_phase_seed_reject_count', ...
 'r51_tangent_candidate_count','r51_tangent_certified_count', ...
 'r51_phase_alpha','r51_phase_delay_s','r51_phase_exit_time_s', ...
 'r34_selected_delay_s','r34_selected_alpha', ...
 'native_episode_ms','native_hessian_ms','native_corridor_ms', ...
 'native_qp_ms','native_candidate_build_ms','native_total_ms', ...
 'last_stage1_ms','last_stage2_ms','last_stage3_ms'};

for k=1:numel(F)
    f=F{k};
    if isfield(P,f)
        v=P.(f);
        if isnumeric(v)||islogical(v)
            if isscalar(v)
                fprintf('%-55s = %.17g\n',f,double(v));
            else
                fprintf('%-55s = %s\n',f,mat2str(double(v),17));
            end
        else
            fprintf('%-55s = %s\n',f,char(string(v)));
        end
    else
        fprintf('%-55s = <NOT EXPOSED>\n',f);
    end
end

fprintf('\nInterpretation:\n');
fprintf(' phase_alpha in (0,1] and phase_delay_s >= 0 mean no schedule catch-up.\n');
fprintf(' tangent_certified_count > 0 means the R45/R47 tangent corridor survived all hard gates.\n');
fprintf(' nonaffine_base_count > 0 on a successful later replan demonstrates curved/repaired-base operation.\n');
fprintf(' After phase_exit_time the spatial correction is zero and the old spatial path is followed at delayed phase.\n');
fprintf('====================================================================================================\n');

A=P;
assignin('base','R51A',A);
end
