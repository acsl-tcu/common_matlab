function R=AF7R58R36_RETURN_SIGN_AUDIT(C,direction)
% Continuous-time sufficient sign certificate for a two-segment C7 candidate.
% Not an obstacle, yaw, thrust, or speed certificate, and sign is not necessary
% for feasible avoidance. Direction comes from physical scenario, not default.
assert(isstruct(C)&&isfield(C,'first')&&isfield(C,'second'), ...
 'Supply an existing C7 piecewise candidate.');
n=double(direction(:));
assert(numel(n)==3 && all(isfinite(n)) && norm(n)>0, ...
 'Physical correction direction must be a nonzero finite 3-vector.');
n=n/norm(n);
B1=double(C.first.control_points);B2=double(C.second.control_points);
assert(isequal(size(B1),[3 16])&&isequal(size(B2),[3 16]), ...
 'Requires both degree-15 Bernstein control-point blocks.');
V1=n.'*B1;V2=n.'*B2;
assert(all(isfinite([V1 V2])),'Nonfinite return coefficients.');
R=struct('schema','AF7R58R36_RETURN_SIGN_COMPARE_V1', ...
 'direction',n,'minimum_bernstein_control_projection',min([V1 V2]), ...
 'continuous_nonnegative_projection_proven',min([V1 V2])>=0, ...
 'continuous_negative_projection_proven',max([V1 V2])<0, ...
 'ambiguous_without_refinement',min([V1 V2])<0 && max([V1 V2])>=0, ...
 'fullbody_certificate',false,'speed_certificate',false,'yaw_certificate',false, ...
 'auto_commit',false,'fixed_rejoin_required',false);
end
