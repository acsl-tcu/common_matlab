function A=AF7R58R80_ASSESS_NATURAL_CONNECTOR(C,obstacles,g,L,rQ,rC,rL, ...
    finite_sensing_vQ_limit,max_nodes)
% R80 single entry point for an R79 C7 delayed connector's reference-level
% continuous-time checks. Prevents global-ball geometry from gating the path.
% ALWAYS refuses autonomous commit: input/torque/tension/robust tube and
% nominal continuation are not yet proved. No HLC/EKF/plant modifications.
G=AF7R58R80_CONTINUOUS_SEPARATE_BODY_CERT( ...
    C,obstacles,g,L,rQ,rC,rL,max_nodes);
Y=AF7R58R80_HEADING_C6_CERT(C,max_nodes);
K=AF7R58R79_CONTINUOUS_KINEMATIC_CERT( ...
    C,g,L,finite_sensing_vQ_limit);
pass=logical(G.certified&&Y.certified&&K.certified);
if pass
    status='REFERENCE_CONNECTOR_CHECKS_PASS__EXECUTION_NOT_CERTIFIED';
else
    status='REJECT_REFERENCE_CONNECTOR_CHECKS_INCOMPLETE';
end
A=struct('status',status, ...
    'reference_checks_pass',pass, ...
    'geometry',G,'heading',Y,'kinematics',K, ...
    'continuous_time_geometry_certified',G.certified, ...
    'continuous_time_yaw_c6_certified',Y.certified, ...
    'actuator_tension_robustness_certified',false, ...
    'nominal_continuation_certified',false, ...
    'ready_to_commit',false,'production_committed',false);
end
