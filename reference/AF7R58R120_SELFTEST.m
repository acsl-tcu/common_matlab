function O=AF7R58R120_SELFTEST()
% Source-only synthetic tests; NEVER modifies Flight, HLC, plant, MEX.
% Synthetic exact affine tail source is a known polynomial by construction.
J0=zeros(3,8);J0(1,2)=1;J0(3,1)=2;
J1=J0;J1(1,1)=5;
times=[0 5];waypoints=[J0(:,1),J1(:,1)];
seed=AF7R58R92_C7_MINIMUM8_ROUTE(times,waypoints, ...
    J0,J1,0,2);
assert(seed.reference_candidate_found,'R120Test:SeedRoute');
live=struct('rL_m',0.1,'rQ_m',0.1,'rC_m',0.05, ...
    'gravity_m_s2',9.81,'cable_length_m',2, ...
    'finite_sensing_vQ_limit_m_s',4);
solver=struct('max_iterations',100,'seed_segments',seed.segments);
% Payload is at z=2, vehicle is at z=4, cable spans [2,4].
% The plane z<=4.5 leaves ~0.4m all-body margin.
Cgood={struct('A',[0 0 1],'b',4.5)};
Q=AF7R58R120_WHOLEBODY_CORRIDOR_QP(times,waypoints, ...
    J0,J1,Cgood,live,solver);
assert(Q.reference_candidate_found && ...
    Q.minimum_whole_body_halfspace_margin_m>0 && ...
    Q.min_force_box_slack>=-1e-8, ...
    'R120Test:WholeBodyCorridorMustPass');
% Deliberately invalid z<=3 corridor: payload has 1m clearance but
% the UAV/cable intrude. Old payload-only QP accepts; R120 MUST reject.
Cbad={struct('A',[0 0 1],'b',3)};
oldPayload=AF7R58R118_CORRIDOR_C7_QP(times,waypoints, ...
    J0,J1,Cbad,struct('rL_m',live.rL_m), ...
    struct('max_iterations',100));
assert(oldPayload.reference_candidate_found, ...
    'R120Test:BaselinePayloadOnlyMustAcceptThisUnsafeConfiguration');
Qbad=AF7R58R120_WHOLEBODY_CORRIDOR_QP(times,waypoints, ...
    J0,J1,Cbad,live,solver);
assert(~Qbad.reference_candidate_found, ...
    'R120Test:RejectPayloadOnlyFalseSafety');
obs=struct('id',17,'center',[50;0;2],'R',eye(3), ...
    'axes',[1;1;1]);
tailJ1=J1;tailJ1(1,1)=7;
tail=AF7R58R92_C7_MINIMUM8_ROUTE([5 7], ...
    [J1(:,1),tailJ1(:,1)],J1,tailJ1,0,2);
assert(tail.reference_candidate_found,'R120Test:ExactAffineTail');
% This is a SYNTHETIC known exact-affine source. In production the source
% identity and polynomial enclosure MUST come from the real nominal source.
source=struct('verified',true,'reference_version',4, ...
    'exact_for_entire_domain',true,'finite_domain_end_s',7, ...
    'source_kind','EXACT_SOURCE_BOUND_BERNSTEIN');
A=struct('connector',Q,'tail_segments',tail.segments, ...
    'tail_source_certificate',source,'finite_tail_end_s',7, ...
    'nominal_source_domain_end_s',7,'nominal_shift_s',0, ...
    'reference_version',4,'known_obstacles',obs,'live',live, ...
    'radii_m',[0.1;0.05;0.1],'certificate_nodes',512);
T=AF7R58R120_FINITE_TAIL_CERT(A);
assert(T.finite_tail_reference_certified && ...
    T.connector_and_tail_c7 && T.connector_and_tail_yaw_c6 && ...
    ~T.production_commit_authorized, ...
    'R120Test:ExactSourceFiniteTailAndC7');
% Breaking source provenance invalidates the whole-tail certificate.
A.tail_source_certificate.verified=false;
Tbad=AF7R58R120_FINITE_TAIL_CERT(A);
assert(~Tbad.finite_tail_reference_certified, ...
    'R120Test:NoUnboundTailAcceptance');
% Exercise the complete new search/controller-independent planner against
% the synthetic straight nominal path and static far ellipsoid. A real
% source-bound tail representation was not provided to the planner, so its
% finite tail remains explicitly pending despite safe connector geometry.
fullLive=live;
fullLive.latest_EKF_mL_kg=0.14;
fullLive.vehicle_mass_kg=0.762;
fullLive.thrust_bounds_N=[0 20];
fullLive.torque_bounds_Nm=[-1 1;-1 1;-1 1];
plan=AF7R58R120_WHOLEBODY_PLANNER(struct( ...
    't0_s',0,'initial_reference_jets07',J0, ...
    'nominal_phase_start_s',0,'nominal_jets07_fn',@nominal, ...
    'obs',obs,'live',fullLive,'radii_m',[0.1;0.05;0.1], ...
    'work',struct('duration_trials',3,'branch_assignments',6, ...
       'corridor_nodes',256,'qp_iterations',500, ...
       'certificate_nodes',512), 'duration_scale_s',5));
assert(plan.reference_candidate_found && plan.position_c7 && ...
    plan.yaw_c6 && plan.continuous_uav_cable_payload && ...
    ~plan.full_finite_tail_reference_certified && ...
    ~plan.production_commit_authorized, ...
    'R120Test:IntegratedCorridorPlannerOrFalseTail');
% Unknown physical future cannot be promoted into proof by event state.
EKF=zeros(24,1);EKF(1:3)=[0;0;4];EKF(13:15)=[0;0;2];
t=(0:160)*0.025;
R71=struct('t',t,'pQ',repmat(EKF(1:3),1,161), ...
    'pL',repmat(EKF(13:15),1,161), ...
    'state',repmat(EKF,1,161),'estimated_mass_kg',0.14, ...
    'continuous_time_collision_proved',false);
E=struct('event_time_s',0,'reference_version',1, ...
    'EKF_x24',EKF,'EKF_mL',0.14,'horizon_s',4, ...
    'dt_s',0.025,'known_obstacles',obs, ...
    'radii_m',[0.1;0.05;0.1]);
physical=AF7R58R120_BIND_R71_TRIGGER(E,R71);
assert(physical.request && ~physical.proved_clear && ...
    ~physical.reference_trigger_used, ...
    'R120Test:NoPhysicalNumericFalseClear');
D=struct('event_id',17,'reference_version',1, ...
    'known_set_revision',4,'physical_status',physical, ...
    'active_plan_certified',false,'certified_plan_version',0, ...
    'event_resolved',false,'new_material_hazard',false);
[F,S]=AF7R58R120_EVENT_LATCH(D,[]);
assert(F.launch_generation,'R120Test:FirstEvent');
[G,S2]=AF7R58R120_EVENT_LATCH(D,S);
assert(~G.launch_generation && G.unresolved_protective, ...
    'R120Test:DuplicateEvent');
D.reference_version=2;
[H,~]=AF7R58R120_EVENT_LATCH(D,S2);
assert(H.launch_generation,'R120Test:MaterialReferenceChange');
O=struct('status','PASS_R120_WHOLEBODY_QP_TAIL_AND_EVENT_GATES', ...
    'positive_whole_body_margin_m', ...
     Q.minimum_whole_body_halfspace_margin_m, ...
    'payload_only_false_safe_rejected',true, ...
    'finite_tail_conditional_reference',T.status, ...
    'physical_without_reachability_proved_clear',physical.proved_clear, ...
    'duplicate_event_suppressed',true, ...
    'planner',plan.status, ...
    'installed_in_native_Flight',false, ...
    'real_MATLAB_executed',false);
fprintf('[R120] %s\n',O.status);
fprintf('[R120] full-body corridor margin %.6g m | tail = %s\n', ...
    O.positive_whole_body_margin_m,O.finite_tail_conditional_reference);
end
function J=nominal(t)
J=zeros(3,8);J(1,1)=t;J(1,2)=1;J(3,1)=2;
end
