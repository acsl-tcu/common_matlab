function R=AF7R58R41_LIVE_TRIGGER_READOUT(replanner)
% Read-only actual-estimator-origin vs reference-trigger authority.
% Does not invent a predictor or change trigger production.
assert(isa(replanner,'REPLANNING_SYSTEM'),'[R41] Live replanner object is required.');
S=replanner.self.estimator.result.state;
if isstruct(S)
    hasP=isfield(S,'p');hasQT=isfield(S,'pT');hasPL=isfield(S,'pL');
else
    hasP=isprop(S,'p');hasQT=isprop(S,'pT');hasPL=isprop(S,'pL');
end
assert(hasP && hasQT, ...
 '[R41] Estimator p/pT are required.');
pQ=double(S.p(:)); q=double(S.pT(:));
assert(numel(pQ)==3 && numel(q)==3 && all(isfinite([pQ;q])) && norm(q)>0, ...
 '[R41] Invalid measured p/pT.');
q=q/norm(q);
L=double(replanner.L_cable);
assert(isfinite(L)&&L>0,'[R41] Cable length missing.');
if hasPL && ~isempty(S.pL)
 pL=double(S.pL(:));
 pL_from_estimator=true;
else
 pL=pQ+L*q;
 pL_from_estimator=false;
end
assert(numel(pL)==3&&all(isfinite(pL)),'[R41] Invalid load position.');
R=struct('schema','AF7R58R41_LIVE_ORIGIN_V1', ...
 'pQ_est_m',pQ,'pL_est_m',pL,'q_est',q, ...
 'pL_directly_estimated',pL_from_estimator, ...
 'cable_length_m',L, ...
 'estimator_cable_residual_m',norm(pL-pQ-L*q), ...
 'active_mode',char(replanner.active_reference_mode), ...
 'active_version',double(replanner.active_reference_version), ...
 'collision_trigger_future_source','ACTIVE_REFERENCE_NOT_ESTIMATED_STATE', ...
 'model_consistent_closed_loop_predictor_connected',false, ...
 'production_trigger_changed',false, ...
 'wholebody_continuous_collision_certified',false);
end
