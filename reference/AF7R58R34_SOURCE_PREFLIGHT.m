function Q=AF7R58R34_SOURCE_PREFLIGHT()
% Source-bound preflight. No changes to simulation or controller settings.
p=which('REPLANNING_SYSTEM');
assert(~isempty(p),'REPLANNING_SYSTEM source not found.');
s=fileread(p);
assert(contains(s,'r34_mirror_reset_pending=true;'), ...
    'R34 Stage1 deferred-reset flag not found.');
assert(contains(s,'if obj.r34_mirror_reset_pending'), ...
    'R34 lazy diagnostic reset not found.');
assert(contains(s,'obj.r34_mirror_reset_pending=false;'), ...
    'R34 lazy diagnostic reset completion not found.');
assert(contains(s,'function S = get_staged_pipeline_status(obj)') && ...
    contains(s,'obj.r26_materialize_deferred_diagnostics();'), ...
    'Diagnostic status materialization path not found.');
assert(contains(s,'obj.r17_capture(''STAGE1_NATIVE_RETURNED'''), ...
    'R17 timing/capture path changed unexpectedly.');
assert(contains(s,'obj.activate_staged_reference_only_bundle('), ...
    'Existing atomic-commit path not detected.');
Q=struct('schema','AF7R58R34_SOURCE_PREFLIGHT_V1', ...
    'source',p, 'diagnostic_only_mirrors_deferred',385, ...
    'in_cycle_capture_mirrors_retained',4, ...
    'trajectory_or_safety_source_modified',false, ...
    'native_mex_rebuild_required',false, ...
    'MATLAB_runtime_equivalence_unverified',true, ...
    'measured_speedup_unverified',true, ...
    'return_candidate_autocommit',false);
fprintf('R34 SOURCE PREFLIGHT PASS | deferred diagnostic reset | NO SAFETY CHANGE.\n');
end
