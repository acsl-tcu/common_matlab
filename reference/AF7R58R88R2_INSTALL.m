function I=AF7R58R88R2_INSTALL()
% Direct bounded replacement of the existing class, with backup and rollback.
% Call AFTER ending Flight; restart MATLAB before creating the next agent.
T=AF7R58R88R2_SELFTEST(); %#ok<NASGU>
S=AF7R58R88R2_SOURCE_CHECK();
if S.already_installed
    I=struct('status','R88R2_ALREADY_INSTALLED__NO_WRITE', ...
        'production_modified',false, ...
        'trigger_switched',false, ...
        'full_execution_safety_proved',false);
    return;
end
root=fileparts(mfilename('fullpath'));
target=fullfile(root,'REPLANNING_SYSTEM.m');
patch=fullfile(root,'REPLANNING_SYSTEM_R88_PATCHED_SOURCE.txt');
backup=fullfile(root,['REPLANNING_SYSTEM_pre_AF7R58R88R2_' ...
    datestr(now,'yyyymmdd_HHMMSSFFF') '.m']);
[ok,msg]=copyfile(target,backup);
assert(ok,'R88R2:BackupFailed:%s',msg);
assert(strcmp(AF7R58R88_SHA256_FILE(backup),S.baseline_sha256), ...
    'R88R2:BackupIntegrityFailed');
try
    [ok,msg]=copyfile(patch,target,'f');
    if ~ok,error('R88R2:CopyFailed','%s',msg);end
    V=AF7R58R88R2_SOURCE_CHECK();
    assert(V.already_installed,'R88R2:PostWriteSHAFailure');
catch ME
    [ok,msg]=copyfile(backup,target,'f');
    assert(ok,'R88R2:RollbackFailed:%s',msg);
    assert(strcmp(AF7R58R88_SHA256_FILE(target),S.baseline_sha256), ...
        'R88R2:RollbackChecksumFailed');
    error('R88R2:RolledBack','Production source restored: %s',ME.message);
end
I=struct('status','R88R2_DIRECT_SOURCE_REPLACED__RESTART_MATLAB', ...
    'backup_file',backup, ...
    'original_sha256',S.baseline_sha256, ...
    'patched_sha256',S.patched_sha256, ...
    'flight_diagnostic_capture_added',true, ...
    'trigger_switched',false, ...
    'initial_generator_modified',false, ...
    'controller_plant_ekf_changed',false, ...
    'continuous_closed_loop_safety_proved',false);
end
