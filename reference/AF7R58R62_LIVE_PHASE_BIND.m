function OUT=AF7R58R62_LIVE_PHASE_BIND(IN)
% Bind actual committed C7 source to live nominal + phase jets WITHOUT
% assuming the historical nominal clock or requiring same-time catch-up.
% This is a candidate adapter, not a production install or safety proof.
required={'snapshot_file','active_reference_version','active_reference_jets_fn', ...
    'active_phase_jets_fn','nominal_jets_fn','nominal_position_fn', ...
    'phase_slowdown_beta','growth_factor','search_max_trials'};
for i=1:numel(required)
    assert(isstruct(IN)&&isfield(IN,required{i}), ...
        'R62:Missing','Missing external/live authority %s',required{i});
end
assert(isa(IN.active_reference_jets_fn,'function_handle') && ...
       isa(IN.active_phase_jets_fn,'function_handle') && ...
       isa(IN.nominal_jets_fn,'function_handle') && ...
       isa(IN.nominal_position_fn,'function_handle'), ...
       'R62:Authority','All nominal, active and phase callback handles are mandatory');
S=load(IN.snapshot_file,'Snapshot');
assert(isfield(S,'Snapshot')&&isfield(S.Snapshot,'version') && ...
    isequal(double(IN.active_reference_version),double(S.Snapshot.version)), ...
    'R62:Version','Live active reference differs from historical correction snapshot; never mix versions');
SH=AF7R58R61_REAL_OFFSET_REJOIN(IN.snapshot_file,IN.search_max_trials);
assert(SH.candidate_found,'R62:Shape','No real C7 source-correction candidate');
t0=SH.real_source_t0_s;
A=double(IN.active_reference_jets_fn(t0));
PH=double(IN.active_phase_jets_fn(t0));PH=PH(:).';
assert(isequal(size(A),[3 8])&&isequal(size(PH),[1 8]) && ...
       all(isfinite([A(:);PH(:)])),'R62:Jets','Real active position and phase jets 0..7 mandatory');
delay=t0-PH(1);
assert(delay>=0,'R62:Delay','Cannot impose catch-up or negative live phase delay');
RI=struct('t0_s',t0,'initial_duration_s',SH.candidate.T_s, ...
    'phase_delay_s',delay,'phase_slowdown_beta',IN.phase_slowdown_beta, ...
    'phase_start_jets_0_to_7',PH, ...
    'active_jets_0_to_7',A,'nominal_jets_fn',IN.nominal_jets_fn, ...
    'nominal_position_fn',IN.nominal_position_fn, ...
    'max_trials',IN.search_max_trials,'growth_factor',IN.growth_factor, ...
    'enforce_scalar_monotone',true);
P=AF7R58R60_C7_FREE_REJOIN(RI);
OUT=struct('status',P.status,'source',SH,'phase_candidate',P, ...
    'source_version_verified',true,'true_nominal_phase_authority_bound',true, ...
    'position_C7_structural_only',P.numerical_candidate_found, ...
    'yaw_C6_certified',false,'wholebody_certified',false, ...
    'hlc_execution_certified',false,'commit_allowed',false,'tube_installed',false);
end
