function OUT = AF7R36_R16B_PREDEADLINE_CANDIDATE_AUDIT_INSTALL()
% AF7R36_R16B_PREDEADLINE_CANDIDATE_AUDIT_INSTALL
%
% Diagnostic-only patch.
%
% R16 live result showed:
%   Stage1 count = 1
%   Stage1 wall time = 26.0779 ms
%   Stage2 count = 0
%   candidate family = blank
%
% Current staged pipeline increments Stage1 count and THEN checks
% CONTROL_PERIOD_EXCEEDED before storing staged_replan_candidate.
% Therefore the native candidate was returned, but its identity was discarded
% before the R16 family latch.
%
% R16B latches a compact read-only summary immediately BEFORE the timing gate.
% It does NOT:
%   - change the 25 ms timing gate,
%   - allow an over-budget candidate to proceed,
%   - change candidate generation,
%   - change C7/speed/rejoin/whole-body certificates,
%   - change commit policy.
%
% No MEX rebuild is required.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 R16B PRE-DEADLINE CANDIDATE AUDIT INSTALL\n');
fprintf(' planner mathematics modified               = 0\n');
fprintf(' hard safety gates modified                 = 0\n');
fprintf(' staged timing gate modified                = 0\n');
fprintf(' commit behavior modified                   = 0\n');
fprintf(' pre-deadline candidate summary latch       = 1\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir)&&isfolder(refDir), ...
    '[R16B] Cannot resolve current reference directory.');

rps=fullfile(refDir,'REPLANNING_SYSTEM.m');
assert(isfile(rps),'[R16B] Missing %s',rps);

rps0=normlf(fileread(rps));
rpsNew=rps0;

assert(contains(rps0,'staged_replan_last_candidate_family'), ...
    '[R16B] R16 family latch not found. Install R16 first.');
assert(~contains(rps0,'staged_replan_predeadline_candidate_family'), ...
    '[R16B] R16B already installed.');

try
    %% 1) Add diagnostic properties near R16 family latch.
    anchor='        staged_replan_last_candidate_family = ''''; % R16 diagnostic authority only';
    new=[anchor sprintf('\n') ...
        '        % R16B diagnostic-only pre-deadline native-candidate summary.' sprintf('\n') ...
        '        staged_replan_predeadline_candidate_seen = false;' sprintf('\n') ...
        '        staged_replan_predeadline_candidate_success = false;' sprintf('\n') ...
        '        staged_replan_predeadline_candidate_family = '''';' sprintf('\n') ...
        '        staged_replan_predeadline_reason_code = NaN;' sprintf('\n') ...
        '        staged_replan_predeadline_t0 = NaN;' sprintf('\n') ...
        '        staged_replan_predeadline_t1 = NaN;' sprintf('\n') ...
        '        staged_replan_predeadline_envelope_m = NaN;' sprintf('\n') ...
        '        staged_replan_predeadline_payload_speed = NaN;' sprintf('\n') ...
        '        staged_replan_predeadline_uav_speed = NaN;' sprintf('\n') ...
        '        staged_replan_predeadline_qdot = NaN;' sprintf('\n') ...
        '        staged_replan_predeadline_geometry_pass = false;' sprintf('\n') ...
        '        staged_replan_predeadline_speed_pass_count = NaN;' sprintf('\n') ...
        '        staged_replan_predeadline_rejoin_pass_count = NaN;' sprintf('\n') ...
        '        staged_replan_predeadline_geometry_test_count = NaN;' sprintf('\n') ...
        '        staged_replan_predeadline_constant_translation = false;'];
    rpsNew=replace_once(rpsNew,anchor,new,'R16 property anchor');

    %% 2) Latch candidate summary after Stage1 count increment, BEFORE timing gate.
    anchor=[ ...
        '            obj.staged_replan_stage1_count=obj.staged_replan_stage1_count+1;' sprintf('\n') ...
        '' sprintf('\n') ...
        '            if obj.generator_last_cycle_critical_ms>1e3*dt'];

    latch=[ ...
        '            obj.staged_replan_stage1_count=obj.staged_replan_stage1_count+1;' sprintf('\n') ...
        '' sprintf('\n') ...
        '            % AF7R36 R16B: diagnostic-only latch before the wall-time gate.' sprintf('\n') ...
        '            obj.staged_replan_predeadline_candidate_seen=true;' sprintf('\n') ...
        '            obj.staged_replan_predeadline_candidate_success= ...' sprintf('\n') ...
        '                isfield(candidate,''success'') && logical(candidate.success);' sprintf('\n') ...
        '            if isfield(candidate,''candidate_family'')' sprintf('\n') ...
        '                obj.staged_replan_predeadline_candidate_family=char(candidate.candidate_family);' sprintf('\n') ...
        '            else' sprintf('\n') ...
        '                obj.staged_replan_predeadline_candidate_family='''';' sprintf('\n') ...
        '            end' sprintf('\n') ...
        '            obj.staged_replan_predeadline_reason_code=field_scalar(candidate,''reason_code'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_t0=field_scalar(candidate,''t0'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_t1=field_scalar(candidate,''t1'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_envelope_m=field_scalar(candidate,''max_control_norm_m'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_payload_speed=field_scalar(candidate,''speed_payload'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_uav_speed=field_scalar(candidate,''speed_uav'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_qdot=field_scalar(candidate,''speed_qdot'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_geometry_pass= ...' sprintf('\n') ...
        '                isfield(candidate,''geometry_pass'') && logical(candidate.geometry_pass);' sprintf('\n') ...
        '            obj.staged_replan_predeadline_speed_pass_count=field_scalar(candidate,''speed_pass_count'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_rejoin_pass_count=field_scalar(candidate,''rejoin_pass_count'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_geometry_test_count=field_scalar(candidate,''geometry_test_count'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_constant_translation= ...' sprintf('\n') ...
        '                isfield(candidate,''compact_constant_translation'') && logical(candidate.compact_constant_translation);' sprintf('\n') ...
        '' sprintf('\n') ...
        '            if obj.generator_last_cycle_critical_ms>1e3*dt'];

    rpsNew=replace_once(rpsNew,anchor,latch,'pre-deadline latch insertion');

    %% 3) Expose through staged status.
    anchor='            S.last_candidate_family=char(obj.staged_replan_last_candidate_family);';
    expose=[anchor sprintf('\n') ...
        '            S.predeadline_candidate_seen=logical(obj.staged_replan_predeadline_candidate_seen);' sprintf('\n') ...
        '            S.predeadline_candidate_success=logical(obj.staged_replan_predeadline_candidate_success);' sprintf('\n') ...
        '            S.predeadline_candidate_family=char(obj.staged_replan_predeadline_candidate_family);' sprintf('\n') ...
        '            S.predeadline_reason_code=double(obj.staged_replan_predeadline_reason_code);' sprintf('\n') ...
        '            S.predeadline_t0=double(obj.staged_replan_predeadline_t0);' sprintf('\n') ...
        '            S.predeadline_t1=double(obj.staged_replan_predeadline_t1);' sprintf('\n') ...
        '            S.predeadline_envelope_m=double(obj.staged_replan_predeadline_envelope_m);' sprintf('\n') ...
        '            S.predeadline_payload_speed=double(obj.staged_replan_predeadline_payload_speed);' sprintf('\n') ...
        '            S.predeadline_uav_speed=double(obj.staged_replan_predeadline_uav_speed);' sprintf('\n') ...
        '            S.predeadline_qdot=double(obj.staged_replan_predeadline_qdot);' sprintf('\n') ...
        '            S.predeadline_geometry_pass=logical(obj.staged_replan_predeadline_geometry_pass);' sprintf('\n') ...
        '            S.predeadline_speed_pass_count=double(obj.staged_replan_predeadline_speed_pass_count);' sprintf('\n') ...
        '            S.predeadline_rejoin_pass_count=double(obj.staged_replan_predeadline_rejoin_pass_count);' sprintf('\n') ...
        '            S.predeadline_geometry_test_count=double(obj.staged_replan_predeadline_geometry_test_count);' sprintf('\n') ...
        '            S.predeadline_constant_translation=logical(obj.staged_replan_predeadline_constant_translation);'];
    rpsNew=replace_once(rpsNew,anchor,expose,'status exposure');

    %% 4) Add one local utility method if absent.
    %
    % Place immediately before reset_staged_replan_pipeline.
    anchor='        function reset_staged_replan_pipeline(obj,reason,retry)';
    helper=[ ...
        '        function v = field_scalar(~,S,name)' sprintf('\n') ...
        '            v=NaN;' sprintf('\n') ...
        '            if isstruct(S) && isfield(S,name)' sprintf('\n') ...
        '                q=S.(name);' sprintf('\n') ...
        '                if isnumeric(q) && isscalar(q) && isfinite(double(q))' sprintf('\n') ...
        '                    v=double(q);' sprintf('\n') ...
        '                end' sprintf('\n') ...
        '            end' sprintf('\n') ...
        '        end' sprintf('\n') ...
        '' sprintf('\n') ...
        anchor];
    % Calls above must be object-qualified in class method scope.
    rpsNew=strrep(rpsNew,'field_scalar(candidate,','obj.field_scalar(candidate,');
    rpsNew=replace_once(rpsNew,anchor,helper,'field_scalar helper');

    %% 5) Structural audit.
    assert(count_exact(rpsNew,'staged_replan_predeadline_candidate_family')>=3, ...
        '[R16B] Candidate family latch/exposure incomplete.');
    assert(count_exact(rpsNew,'AF7R36 R16B: diagnostic-only latch before the wall-time gate.')==1, ...
        '[R16B] Pre-deadline latch count invalid.');

    % Timing gate must remain exactly present and after the latch.
    pLatch=strfind(rpsNew,'AF7R36 R16B: diagnostic-only latch before the wall-time gate.');
    pGate=strfind(rpsNew,'if obj.generator_last_cycle_critical_ms>1e3*dt');
    assert(~isempty(pLatch)&&~isempty(pGate)&&pGate(1)>pLatch(1), ...
        '[R16B] Timing gate authority/order changed unexpectedly.');

    %% 6) Install source only. No class clear inside installer.
    write_text(rps,rpsNew);
    rehash

    fprintf('[R16B] PASS.\n');
    fprintf('  timing gate bypassed                       = 0\n');
    fprintf('  candidate safety/selection modified        = 0\n');
    fprintf('  pre-deadline summary persistence           = 1\n');
    fprintf('  IMPORTANT: clear old objects/classes before next simulation.\n');

    OUT=struct( ...
        'pass',true, ...
        'revision','AF7_R16B_PREDEADLINE_CANDIDATE_AUDIT', ...
        'timing_gate_modified',false, ...
        'planner_modified',false, ...
        'hard_safety_modified',false);

catch ME
    try,write_text(rps,rps0);catch,end
    rehash
    fprintf(2,'[R16B] FAILED. REPLANNING_SYSTEM source rolled back.\n');
    fprintf(2,'[R16B] ORIGINAL ERROR: %s | %s\n',ME.identifier,ME.message);
    rethrow(ME);
end
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1,'[R16B] Anchor "%s" count=%d; expected 1.',label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end

function n=count_exact(txt,pat)
n=numel(strfind(txt,pat));
end

function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));
s=strrep(s,sprintf('\r'),sprintf('\n'));
end

function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');
assert(f>=0,'[R16B] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end
