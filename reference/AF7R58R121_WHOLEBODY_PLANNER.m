function R=AF7R58R121_WHOLEBODY_PLANNER(A)
% R120 new generation research branch, NOT installed in native R115.
% The full 3-body safe corridor is imposed BEFORE the QP solve, through
% a Bernstein specific-force tube about a source-seed. Independent R80
% certification remains mandatory. This does not solve the HLC tracking
% reachable-set or native atomic packet schema.
% New trajectory GENERATION (not R115 native generator):
% seed branches -> knot whole-body support corridors -> 1 coupled C7
% corridor-constrained minimum p^(8)^2 QP -> independent all-time
% U/Q/cable, heading and kinematic proof -> natural-phase tail contract.
% Only sensor-known oriented static obstacles may be provided in A.obs.
% All physical authorities come from A.live, none are hard-coded.
required={'t0_s','initial_reference_jets07','nominal_phase_start_s', ...
    'nominal_jets07_fn','obs','live','radii_m', ...
    'work','duration_scale_s'};
for i=1:numel(required)
    assert(isfield(A,required{i}), 'R118:MissingLivePlannerParameter', ...
        'Missing planner input %s.',required{i});
end
assert(isa(A.nominal_jets07_fn,'function_handle'), ...
    'R118:ActualNominalDerivativeSourceRequired');
J0=A.initial_reference_jets07;
assert(isequal(size(J0),[3 8])&&all(isfinite(J0(:))), ...
    'R118:ExactActivationReferenceJets07Required');
W=A.work;
for q={'duration_trials','branch_assignments','corridor_nodes', ...
        'qp_iterations','certificate_nodes'}
    key=q{1};
    assert(isfield(W,key)&&isfinite(W.(key))&&W.(key)>=1&& ...
        fix(W.(key))==W.(key),'R118:ExternalSolverWorkBudgetRequired');
end
live=A.live;requiredLive={'cable_length_m','gravity_m_s2', ...
    'latest_EKF_mL_kg','vehicle_mass_kg','thrust_bounds_N', ...
    'torque_bounds_Nm','finite_sensing_vQ_limit_m_s'};
for i=1:numel(requiredLive)
    assert(isfield(live,requiredLive{i}), ...
        'R118:MissingPhysicalAuthority','Missing %s.',requiredLive{i});
end
L=live.cable_length_m;g=live.gravity_m_s2;
assert(isfinite(L)&&L>0&&isfinite(g)&&g>0&& ...
    isfinite(live.latest_EKF_mL_kg)&&live.latest_EKF_mL_kg>0, ...
    'R118:InvalidExternalDynamicsAuthority');
r=double(A.radii_m(:));
assert(isequal(size(r),[3 1])&&all(isfinite(r))&&all(r>=0), ...
    'R118:ExternalUavCableLoadRadii');
live.rQ_m=r(1);live.rC_m=r(2);live.rL_m=r(3);
R=struct('status','INCONCLUSIVE_NO_ALL_INTERVAL_CERTIFIED_ROUTE', ...
    'reference_candidate_found',false,'production_commit_authorized',false, ...
    'execution_certified',false,'position_c7',false,'yaw_c6',false, ...
    'continuous_uav_cable_payload',false, ...
    'corridor_constrained_during_generation',true, ...
    'whole_body_constrained_during_generation',true, ...
    'full_finite_tail_reference_certified',false, ...
    'return_solved_jointly',true,'duration_fixed_upper_limit',false, ...
    'attempts',0,'selected_duration_s',NaN, ...
    'nominal_phase_end_s',NaN,'nominal_time_shift_s',NaN, ...
    'active_obstacle_count',numel(A.obs), ...
    'route',struct([]),'certificate',struct([]));
assert(~isempty(A.obs),'R118:OnlyTriggerOnKnownObstacle');
assert(isfinite(A.t0_s)&&isfinite(A.nominal_phase_start_s)&& ...
    A.nominal_phase_start_s<=A.t0_s && ...
    A.duration_scale_s>0&&isfinite(A.duration_scale_s), ...
    'R118:NaturalTimeAndLiveTimeAuthority');
fractions=[1/4 1/2 1];
for attempt=1:W.duration_trials
    R.attempts=attempt;
    level=floor((attempt-1)/numel(fractions));
    f=fractions(mod(attempt-1,numel(fractions))+1);
    T=A.duration_scale_s*2^level;
    if ~isfinite(T)||~isfinite(A.t0_s+T),break;end
    phaseEnd=A.nominal_phase_start_s+f*T;
    Jend=double(A.nominal_jets07_fn(phaseEnd));
    if ~isequal(size(Jend),[3 8])||any(~isfinite(Jend(:)))
        R.status='BLOCKED_NOMINAL_EXACT_JETS_UNAVAILABLE';return;
    end
    seeds=AF7R58R92_SUPPORT_SEED_ROUTES(J0(:,1),Jend(:,1), ...
        A.obs,max(r),W.branch_assignments);
    for b=1:numel(seeds.routes)
        knots=[J0(:,1),seeds.routes{b},Jend(:,1)];
        lengths=vecnorm(diff(knots,1,2),2,1);
        if any(lengths<=0),continue;end
        times=A.t0_s+[0,cumsum(lengths)/sum(lengths)]*T;
        % R92 unconstrained curve used ONLY to initialize a topologically
        % valid whole-body knot corridor; it is NOT the delivered route.
        seed=AF7R58R92_C7_MINIMUM8_ROUTE(times,knots,J0,Jend, ...
            T*(1-f)+(A.t0_s-A.nominal_phase_start_s),L);
        if ~seed.reference_candidate_found,continue;end
        cells=AF7R58R99_MULTI_SIZE_KNOT_CORRIDOR(seed,A.obs,live);
        if ~cells.whole_body_knot_corridor_found,continue;end
        qp=AF7R58R120_WHOLEBODY_CORRIDOR_QP(times,knots,J0,Jend, ...
            cells.cells,live,struct('max_iterations',W.qp_iterations, ...
            'seed_segments',seed.segments));
        if ~qp.reference_candidate_found,continue;end
        % QP now includes a sufficient whole-body halfspace proof. Independently
        % certify all three bodies, speed and nonzero XY tangent for each
        % complete segment, including the return connector.
        details=repmat(struct('body',struct([]), ...
            'kinematics',struct([]),'heading',struct([])),1,qp.num_segments);
        passed=true;
        for s=1:qp.num_segments
            seg=qp.segments(s);
            C=AF7R58R80_CONTINUOUS_SEPARATE_BODY_CERT( ...
                seg,A.obs,g,L,r(1),r(2),r(3),W.certificate_nodes);
            K=AF7R58R91_STABLE_KINEMATIC_CERT( ...
                seg,g,L,live.finite_sensing_vQ_limit_m_s,W.certificate_nodes);
            H=AF7R58R118_HEADING_C6_CERT(seg,W.certificate_nodes);
            details(s)=struct('body',C,'kinematics',K,'heading',H);
            if ~(C.certified&&K.certified&&H.certified)
                passed=false;break;
            end
        end
        if ~passed,continue;end
        R.status='ALL_CONNECTOR_INTERVALS_NUMERIC_REFERENCE_CERTIFIED__TAIL_AND_EXECUTION_PENDING';
        R.reference_candidate_found=true;
        R.position_c7=true;R.yaw_c6=true;
        R.continuous_uav_cable_payload=true;
        R.selected_duration_s=T;
        R.nominal_phase_end_s=phaseEnd;
        R.nominal_time_shift_s=times(end)-phaseEnd;
        R.route=qp;
        R.certificate=struct('segments',details, ...
            'corridor_knot_initialization',cells.status, ...
            'payload_qp_margin_m',qp.min_payload_corridor_margin_m, ...
            'tail_after_connector_certified',false, ...
            'actuator_torque_certified',false, ...
            'tracking_tube_certified',false, ...
            'all_connector_segments_reference_certified',true);
        % Full-trajectory safety also requires EVERY interval AFTER the
        % connector, within the original nominal source's finite domain.
        % An unverified fit to nominal values is NEVER accepted as exact.
        % Calling code may attach a source-bound exact Bernstein tail
        % provider; no path-specific type or time horizon is assumed.
        R.certificate.tail_after_connector_certified=false;
        R.certificate.tail_source_status='EXACT_NOMINAL_TAIL_NOT_PROVIDED';
        if isfield(A,'exact_tail_source_fn') && ...
           isa(A.exact_tail_source_fn,'function_handle') && ...
           isfield(A,'nominal_source_domain_end_s') && ...
           isfield(A,'reference_version')
            tailData=A.exact_tail_source_fn(phaseEnd, ...
                A.nominal_source_domain_end_s, ...
                R.nominal_time_shift_s,A.reference_version);
            assert(isstruct(tailData)&& ...
                all(isfield(tailData,{'segments','source_certificate','knot_jets'})), ...
                'R120:NoSourceCertifiedNominalTailRepresentation');
            G=AF7R58R121_FINITE_TAIL_CERT(struct( ...
                'connector',qp,'tail_segments',tailData.segments, ...
                'tail_knot_jets',tailData.knot_jets, ...
                'tail_source_certificate',tailData.source_certificate, ...
                'finite_tail_end_s',A.nominal_source_domain_end_s+R.nominal_time_shift_s, ...
                'nominal_source_domain_end_s',A.nominal_source_domain_end_s, ...
                'nominal_shift_s',R.nominal_time_shift_s, ...
                'reference_version',A.reference_version, ...
                'known_obstacles',A.obs,'live',live, ...
                'radii_m',r, ...
                'certificate_nodes',W.certificate_nodes));
            R.certificate.tail_closure=G;
            R.certificate.tail_source_status=G.status;
            R.certificate.tail_after_connector_certified= ...
                G.finite_tail_reference_certified;
            R.full_finite_tail_reference_certified= ...
                G.finite_tail_reference_certified;
            if G.finite_tail_reference_certified
                R.status='FINITE_SOURCE_WHOLEBODY_REFERENCE_CERTIFIED__EXECUTION_PENDING';
            end
        end
        % An exact tail provider that rejects the proposed return point
        % means the WHOLE candidate is not certified. Try other branches
        % and natural times rather than silently promoting the connector.
        if isfield(A,'exact_tail_source_fn') && ...
           isa(A.exact_tail_source_fn,'function_handle') && ...
           ~R.full_finite_tail_reference_certified
            R.status=['INCONCLUSIVE_TAIL_' char(R.certificate.tail_source_status)];
            R.reference_candidate_found=false;
            continue;
        end
        % The research-only connector is useful for inspection if no
        % exact source-tail provider was supplied; no production commit.
        return;
    end
end
end
