function OUT=AF7R36_CURVED_C7_BELL_PRIMARY_R25B_INSTALL()
% AF7R36_CURVED_C7_BELL_PRIMARY_R25B_INSTALL
%
% Adds a new first-choice primary family:
%
%   CURVED_C7_ZERO_JET_BELL
%
% For every disconnected nominally-unsafe component j, choose one amplitude
% A_j in R^3 and a support [l_j,r_j] with peak p_j:
%
%   d_j(l_j)=0  -> d_j(p_j)=A_j -> d_j(r_j)=0.
%
% Each half is degree-15 Bezier:
%   UP   control polygon = [0 x8, A_j x8]
%   DOWN control polygon = [A_j x8, 0 x8]
%
% Therefore at every outer boundary and peak:
%   d^(r)_left == d^(r)_right exactly, r=0..7,
% because the first/last eight binary64 control points are identical.
% No equality of left/right segment durations is required.
%
% Amplitudes are synthesized by a fixed-sign convex QP. The half-space
% inequalities are only a synthesis guide. Final acceptance remains the
% unchanged finite-sensing speed, rejoin, and continuous whole-body
% certificates.
%
% Migration policy:
%   R25 tries family 6 first. Existing families remain temporarily after it
%   for A/B comparison. They are NOT declared final fallback. Once family 6
%   closes the regression set, old trapezoid families can be removed.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 CURVED EXACT-C7 ZERO-JET BELL PRIMARY R25B INSTALL\n');
fprintf(' new primary family                          = CURVED_C7_ZERO_JET_BELL\n');
fprintf(' internal plateau                            = 0\n');
fprintf(' exact C7 join tolerance                     = ZERO\n');
fprintf(' equal-half-duration requirement             = 0\n');
fprintf(' speed/rejoin/whole-body gates modified      = 0\n');
fprintf(' old families removed now                    = 0 (migration comparison only)\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir)&&isfolder(refDir),'[R25B] Cannot resolve reference directory.');
hpp=fullfile(refDir,'af7r36_core.hpp');
cpp=fullfile(refDir,'af7r36_single_core_mex.cpp');
rps=fullfile(refDir,'REPLANNING_SYSTEM.m');
assert(isfile(hpp)&&isfile(cpp)&&isfile(rps),'[R25B] Production sources missing.');

hpp0=normlf(fileread(hpp));
cpp0=normlf(fileread(cpp));
rps0=normlf(fileread(rps));
hppNew=hpp0;cppNew=cpp0;rpsNew=rps0;

assert(contains(hpp0,'AF7_EXACT_C7_DYADIC_LATTICE_R22C'), ...
    '[R25B] R22C exact-C7 layer missing.');
assert(contains(hpp0,'AF7R24E_FAMILY_DIAGNOSTICS'), ...
    '[R25B] R24E family diagnostics missing.');
assert(contains(hpp0,'bool exact_c7=false;'), ...
    '[R25B] Candidate exact_c7 authority missing.');
assert(~contains(hpp0,'AF7R25B_CURVED_C7_ZERO_JET_BELL'), ...
    '[R25B] R25B already installed.');
assert(~contains(hpp0,'AF7R25_CURVED_C7_ZERO_JET_BELL'), ...
    '[R25B] Unexpected partial R25 source detected; do not stack R25B.');

try
    %% -----------------------------------------------------------------
    % 1. New family helpers. Insert after QP/Hessian utilities and before
    %    candidate construction.
    % ------------------------------------------------------------------
    anchor='// -------------------- build candidate control polygons ---------------------';
    code=[ ...
'// AF7R25B_CURVED_C7_ZERO_JET_BELL' sprintf('\n') ...
'struct R25BellWin{double l=0,p=0,r=0;};' sprintf('\n') ...
'' sprintf('\n') ...
'static inline std::vector<R25BellWin> r25_windows(const std::vector<Component>&comp,double t0,double t1){' sprintf('\n') ...
'    const int C=(int)comp.size();std::vector<R25BellWin> W(C);' sprintf('\n') ...
'    if(C<1)return W;' sprintf('\n') ...
'    std::vector<double> cut(C+1);cut[0]=t0;cut[C]=t1;' sprintf('\n') ...
'    for(int j=1;j<C;++j)cut[j]=0.5*(comp[j-1].end+comp[j].start);' sprintf('\n') ...
'    for(int j=0;j<C;++j){' sprintf('\n') ...
'        W[j].l=cut[j];W[j].p=0.5*(comp[j].start+comp[j].end);W[j].r=cut[j+1];' sprintf('\n') ...
'        if(!(fin(W[j].l)&&fin(W[j].p)&&fin(W[j].r)&&' sprintf('\n') ...
'             W[j].l<comp[j].start&&comp[j].start<=W[j].p&&' sprintf('\n') ...
'             W[j].p<=comp[j].end&&comp[j].end<W[j].r))' sprintf('\n') ...
'            throw std::runtime_error("R25B invalid bell support");' sprintf('\n') ...
'    }' sprintf('\n') ...
'    return W;' sprintf('\n') ...
'}' sprintf('\n') ...
'' sprintf('\n') ...
'static inline double r25_casteljau_scalar(std::array<double,16>a,double u){' sprintf('\n') ...
'    u=std::max(0.0,std::min(1.0,u));' sprintf('\n') ...
'    for(int n=15;n>0;--n)for(int i=0;i<n;++i)a[i]=(1.0-u)*a[i]+u*a[i+1];' sprintf('\n') ...
'    return a[0];' sprintf('\n') ...
'}' sprintf('\n') ...
'' sprintf('\n') ...
'static inline double r25_beta(double t,const R25BellWin&w){' sprintf('\n') ...
'    if(t<=w.l||t>=w.r)return 0.0;' sprintf('\n') ...
'    if(t==w.p)return 1.0;' sprintf('\n') ...
'    std::array<double,16>b{};' sprintf('\n') ...
'    if(t<w.p){' sprintf('\n') ...
'        for(int k=8;k<16;++k)b[k]=1.0;' sprintf('\n') ...
'        return r25_casteljau_scalar(b,(t-w.l)/(w.p-w.l));' sprintf('\n') ...
'    }else{' sprintf('\n') ...
'        for(int k=0;k<8;++k)b[k]=1.0;' sprintf('\n') ...
'        return r25_casteljau_scalar(b,(t-w.p)/(w.r-w.p));' sprintf('\n') ...
'    }' sprintf('\n') ...
'}' sprintf('\n') ...
'' sprintf('\n') ...
'static inline std::vector<Row> r25_bell_rows(const ActiveReference&ref,const Live&L,' sprintf('\n') ...
'        const SpeedCert&base,const std::vector<Obstacle>&obs,const EpisodeCert&E,' sprintf('\n') ...
'        const std::vector<R25BellWin>&W,int ei,Vec3 n,int nvar){' sprintf('\n') ...
'    const auto&ep=E.ep[ei];const int jj=ep.comp;n=normalized(n);const auto&o=obs[ep.obs];' sprintf('\n') ...
'    Vec3 rn=tmul(o.R,n),ar{o.axes.x*rn.x,o.axes.y*rn.y,o.axes.z*rn.z};' sprintf('\n') ...
'    const double hObs=dot(n,o.c)+norm(ar),VC=std::max(base.VL,base.VQ);' sprintf('\n') ...
'    std::vector<Row>rows;double ta=ep.start,te=ep.end;' sprintf('\n') ...
'    while(ta<te-8*epsd()*std::max(1.0,std::fabs(te))){' sprintf('\n') ...
'        double tb=std::min(te,ta+L.dt);' sprintf('\n') ...
'        if(ta<W[jj].p&&tb>W[jj].p)tb=W[jj].p;' sprintf('\n') ...
'        if(!(tb>ta))throw std::runtime_error("R25B bell cell not representable");' sprintf('\n') ...
'        const double tc=0.5*(ta+tb),half=0.5*(tb-ta);auto x=ref.eval(tc);' sprintf('\n') ...
'        Vec3 pL=x[0],sf=x[2]+Vec3{0,0,L.g};double ns=norm(sf);' sprintf('\n') ...
'        if(!(fin(ns)&&ns>0))throw std::runtime_error("R25B corridor flatness singular");' sprintf('\n') ...
'        Vec3 q=sf*(-1.0/ns),pQ=pL-q*L.L;' sprintf('\n') ...
'        double rhoL=L.rL+L.dmargin+L.tracking+base.VL*half;' sprintf('\n') ...
'        double rhoQ=L.rQ+L.dmargin+L.tracking+base.VQ*half;' sprintf('\n') ...
'        double rhoC=L.rC+L.dmargin+L.tracking+VC*half;' sprintf('\n') ...
'        double req=std::max({hObs+rhoL-dot(n,pL),hObs+rhoQ-dot(n,pQ),' sprintf('\n') ...
'                            hObs+rhoC-std::min(dot(n,pQ),dot(n,pL))});' sprintf('\n') ...
'        req+=64*epsd()*std::max(1.0,std::fabs(req));' sprintf('\n') ...
'        double bl=std::min(r25_beta(ta,W[jj]),r25_beta(tb,W[jj]));' sprintf('\n') ...
'        bl-=128*epsd()*std::max(1.0,std::fabs(bl));' sprintf('\n') ...
'        if(!(fin(bl)&&bl>0))throw std::runtime_error("R25B bell support has zero lower bound on unsafe cell");' sprintf('\n') ...
'        Row R;R.a.assign(nvar,0.0);R.b=req/bl;' sprintf('\n') ...
'        R.b+=64*epsd()*std::max(1.0,std::fabs(R.b));' sprintf('\n') ...
'        R.a[3*jj+0]=n.x;R.a[3*jj+1]=n.y;R.a[3*jj+2]=n.z;' sprintf('\n') ...
'        rows.push_back(std::move(R));ta=tb;' sprintf('\n') ...
'    }' sprintf('\n') ...
'    return rows;' sprintf('\n') ...
'}' sprintf('\n') ...
'' sprintf('\n') ...
'static inline std::vector<double> r25_bell_hessian(const std::vector<R25BellWin>&W){' sprintf('\n') ...
'    const int C=(int)W.size(),n=3*C;std::vector<double>H(n*n,0.0);' sprintf('\n') ...
'    double I=0.0;for(int i=8;i<16;++i)for(int j=8;j<16;++j)I+=gram(15,i,j);' sprintf('\n') ...
'    if(!(fin(I)&&I>0))throw std::runtime_error("R25B bell L2 Gram invalid");' sprintf('\n') ...
'    for(int j=0;j<C;++j){' sprintf('\n') ...
'        double w=(W[j].r-W[j].l)*I;if(!(fin(w)&&w>0))throw std::runtime_error("R25B bell weight invalid");' sprintf('\n') ...
'        for(int d=0;d<3;++d)H[(3*j+d)*n+(3*j+d)]=w;' sprintf('\n') ...
'    }' sprintf('\n') ...
'    return H;' sprintf('\n') ...
'}' sprintf('\n') ...
'' sprintf('\n') ...
'static inline Poly r25_bell_segment(Vec3 A,bool up){' sprintf('\n') ...
'    Poly P(16);' sprintf('\n') ...
'    if(up){for(int k=0;k<8;++k)P[k]={0,0,0};for(int k=8;k<16;++k)P[k]=A;}' sprintf('\n') ...
'    else{for(int k=0;k<8;++k)P[k]=A;for(int k=8;k<16;++k)P[k]={0,0,0};}' sprintf('\n') ...
'    return P;' sprintf('\n') ...
'}' sprintf('\n') ...
'' sprintf('\n') ...
'static inline Candidate r25_build_bell(const std::vector<Component>&comp,' sprintf('\n') ...
'        const std::vector<R25BellWin>&W,const std::vector<double>&z,double cost,' sprintf('\n') ...
'        const std::vector<int>&signs,double minSlack){' sprintf('\n') ...
'    const int Cn=(int)comp.size();if((int)z.size()!=3*Cn)throw std::runtime_error("R25B bell z size");' sprintf('\n') ...
'    Candidate C;C.cost=cost;C.signs=signs;C.minSlack=minSlack;C.family=6;' sprintf('\n') ...
'    C.constant_translation=false;C.exact_c7=true;C.pos.resize(Cn);C.vel.assign(Cn,Vec3{0,0,0});' sprintf('\n') ...
'    for(int j=0;j<Cn;++j){' sprintf('\n') ...
'        Vec3 A{z[3*j],z[3*j+1],z[3*j+2]};C.pos[j]=A;' sprintf('\n') ...
'        C.seg0.push_back(W[j].l);C.seg1.push_back(W[j].p);C.cp.push_back(r25_bell_segment(A,true));' sprintf('\n') ...
'        C.seg0.push_back(W[j].p);C.seg1.push_back(W[j].r);C.cp.push_back(r25_bell_segment(A,false));' sprintf('\n') ...
'    }' sprintf('\n') ...
'    C.dub.fill(0);C.max_ctrl=0;' sprintf('\n') ...
'    for(size_t s=0;s<C.cp.size();++s){' sprintf('\n') ...
'        double T=C.seg1[s]-C.seg0[s];Poly D=C.cp[s];int deg=(int)D.size()-1;' sprintf('\n') ...
'        for(auto v:D)C.max_ctrl=std::max(C.max_ctrl,norm(v));' sprintf('\n') ...
'        for(int r=1;r<=6;++r){Poly E(D.size()-1);' sprintf('\n') ...
'            for(size_t i=0;i+1<D.size();++i)E[i]=(D[i+1]-D[i])*(double(deg)/T);' sprintf('\n') ...
'            D.swap(E);--deg;C.dub[r-1]=std::max(C.dub[r-1],poly_norm_ub(D));}' sprintf('\n') ...
'    }' sprintf('\n') ...
'    return C;' sprintf('\n') ...
'}' sprintf('\n') ...
'' sprintf('\n') ...
anchor];
    hppNew=replace_once(hppNew,anchor,code,'R25B bell helper insertion');

    %% 2. Preserve the selected lateral normal for R25 synthesis.
    old='    std::vector<OrientedRows> OR(Ne);';
    new=[old sprintf('\n') '    std::vector<Vec3> R25N(Ne);'];
    hppNew=replace_once_in_region(hppNew, ...
        'static inline PlanResult plan_fixed_scope(', ...
        'static inline PlanResult plan(', ...
        old,new,'R25B normal storage');

    old=[ ...
        '        Vec3 n=lateral_normal(obs[ep.obs].R,obs[ep.obs].axes,prog);' sprintf('\n') ...
        '        OR[e].plus=corridor_rows(ref,L,base,obs,E,e,n,nvar);'];
    new=[ ...
        '        Vec3 n=lateral_normal(obs[ep.obs].R,obs[ep.obs].axes,prog);' sprintf('\n') ...
        '        R25N[e]=n;' sprintf('\n') ...
        '        OR[e].plus=corridor_rows(ref,L,base,obs,E,e,n,nvar);'];
    hppNew=replace_once_in_region(hppNew, ...
        'static inline PlanResult plan_fixed_scope(', ...
        'static inline PlanResult plan(', ...
        old,new,'R25B normal capture');

    %% 3. Insert new first-choice primary before the old R36 primary.
    anchor=[ ...
        '    // ------------------------------------------------------------------' sprintf('\n') ...
        '    // PRIMARY R36 branch: exact minimum integrated squared deviation.'];

    branch=[ ...
        '    // ------------------------------------------------------------------' sprintf('\n') ...
        '    // PRIMARY R25B: CURVED_C7_ZERO_JET_BELL.' sprintf('\n') ...
        '    //' sprintf('\n') ...
        '    // Continuous half-space rows guide synthesis only. Every candidate' sprintf('\n') ...
        '    // is independently re-certified by the unchanged speed, rejoin,' sprintf('\n') ...
        '    // and continuous whole-body authorities before acceptance.' sprintf('\n') ...
        '    // ------------------------------------------------------------------' sprintf('\n') ...
        '    ts=clk::now();' sprintf('\n') ...
        '    {' sprintf('\n') ...
        '        auto W25=r25_windows(E.comp,t0,t1);const int nv25=3*Cn;' sprintf('\n') ...
        '        auto H25=r25_bell_hessian(W25);std::vector<Base>B25;' sprintf('\n') ...
        '        std::vector<int>sg25(Ne,1);' sprintf('\n') ...
        '        std::function<void(int)> rec25=[&](int k){' sprintf('\n') ...
        '            if(k<Ne){sg25[k]=1;rec25(k+1);sg25[k]=-1;rec25(k+1);return;}' sprintf('\n') ...
        '            std::vector<Row>rows;' sprintf('\n') ...
        '            try{' sprintf('\n') ...
        '                for(int e=0;e<Ne;++e){' sprintf('\n') ...
        '                    Vec3 n=sg25[e]>0?R25N[e]:R25N[e]*(-1.0);' sprintf('\n') ...
        '                    auto v=r25_bell_rows(ref,L,base,obs,E,W25,e,n,nv25);' sprintf('\n') ...
        '                    rows.insert(rows.end(),v.begin(),v.end());' sprintf('\n') ...
        '                }' sprintf('\n') ...
        '            }catch(const std::runtime_error&){return;}' sprintf('\n') ...
        '            QPSol q=solve_qp(H25,nv25,rows);if(q.ok)B25.push_back({q.z,q.cost,q.slack,sg25});' sprintf('\n') ...
        '        };' sprintf('\n') ...
        '        rec25(0);std::vector<Candidate>bell;bell.reserve(B25.size());' sprintf('\n') ...
        '        for(auto&b:B25)bell.push_back(r25_build_bell(E.comp,W25,b.z,b.c,b.sg,b.s));' sprintf('\n') ...
        '        R.tim.qp+=std::chrono::duration<double,std::milli>(clk::now()-ts).count();' sprintf('\n') ...
        '        auto tc25=clk::now();' sprintf('\n') ...
        '        if(certify_candidates(bell,true,3)){' sprintf('\n') ...
        '            R.tim.candidate_build+=std::chrono::duration<double,std::milli>(clk::now()-tc25).count();' sprintf('\n') ...
        '            R.tim.synthesis=std::chrono::duration<double,std::milli>(clk::now()-a).count();' sprintf('\n') ...
        '            R.tim.candidate=R.tim.synthesis;' sprintf('\n') ...
        '            R.tim.total=std::chrono::duration<double,std::milli>(clk::now()-T0).count();return R;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '        R.tim.candidate_build+=std::chrono::duration<double,std::milli>(clk::now()-tc25).count();' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '' sprintf('\n') ...
        anchor];
    hppNew=replace_once_in_region(hppNew, ...
        'static inline PlanResult plan_fixed_scope(', ...
        'static inline PlanResult plan(', ...
        anchor,branch,'R25B primary branch');

    %% 4. Candidate family name in native result.
    old='    set("candidate_family",mxCreateString(family));';
    new=[ ...
        '    if(R.cand.family==6)family="CURVED_C7_ZERO_JET_BELL";' sprintf('\n') ...
        old];
    cppNew=replace_once_in_region(cppNew, ...
        'static mxArray* result_struct(', ...
        'static mxArray* dcp_only_from_cp(', ...
        old,new,'R25B family name');

    %% 5. Correct metadata: family 6 is piecewise D15 exact-C7, but not the
    % affine-unsafe towing-corridor representation.
    old=[ ...
        '            if isfield(P,''representation_code'')&&double(P.representation_code)==2' sprintf('\n') ...
        '                smoothSource=''PIECEWISE_DEGREE15_BEZIER_C7_AFFINE_TOWING_CORRIDORS'';' sprintf('\n') ...
        '            end'];
    new=[old sprintf('\n') ...
        '            if isfield(P,''native_raw'')&&isstruct(P.native_raw)&& ...' sprintf('\n') ...
        '                    isfield(P.native_raw,''candidate_family'')&& ...' sprintf('\n') ...
        '                    strcmpi(char(P.native_raw.candidate_family),''CURVED_C7_ZERO_JET_BELL'')' sprintf('\n') ...
        '                smoothSource=''PIECEWISE_DEGREE15_BEZIER_C7_ZERO_JET_BELL'';' sprintf('\n') ...
        '            end'];
    rpsNew=replace_all_exact(rpsNew,old,new,2,'R25B smoothness metadata');

    %% 6. Static invariants.
    assert(count_exact(hppNew,'AF7R25B_CURVED_C7_ZERO_JET_BELL')==1);
    assert(count_exact(hppNew,'C.family=6;')==1);
    assert(count_exact(hppNew,'C.exact_c7=true;')>=2);
    assert(contains(hppNew,'r25_bell_rows'));
    assert(contains(hppNew,'r25_bell_hessian'));
    assert(contains(hppNew,'certify_candidates(bell,true,3)'));
    assert(contains(cppNew,'CURVED_C7_ZERO_JET_BELL'));
    assert(contains(rpsNew,'PIECEWISE_DEGREE15_BEZIER_C7_ZERO_JET_BELL'));
    assert(contains(hppNew,'tighten_stageA'));
    assert(contains(hppNew,'stageB_speed'));
    assert(contains(hppNew,'rejoin_safe'));
    assert(contains(hppNew,'wholebody'));

    %% 7. Stage compile MEX before writes.
    stage=tempname;[ok,msg]=mkdir(stage);assert(ok,'%s',msg);
    cleanup=onCleanup(@()cleanup_stage(stage)); %#ok<NASGU>
    sh=fullfile(stage,'af7r36_core.hpp');sc=fullfile(stage,'af7r36_single_core_mex.cpp');
    write_text(sh,hppNew);write_text(sc,cppNew);
    oldDir=pwd;cdguard=onCleanup(@()cd(oldDir)); %#ok<NASGU>
    cd(stage);clear mex
    fprintf('[R25B] Compiling staged MEX...\n');
    mex('-R2018a','-O','COMPFLAGS="$COMPFLAGS /std:c++17"', ...
        ['-I' stage],'-output','af7r36_single_core_mex','-outdir',stage,sc);
    sm=fullfile(stage,['af7r36_single_core_mex.' mexext]);assert(isfile(sm));
    cd(oldDir);clear mex

    %% 8. Transactional install.
    dstMex=fullfile(refDir,['af7r36_single_core_mex.' mexext]);
    oldMex=fullfile(stage,['af7r36_single_core_mex_OLD.' mexext]);
    hadMex=isfile(dstMex);if hadMex,[ok,msg]=copyfile(dstMex,oldMex,'f');assert(ok,'%s',msg);end

    wroteH=false;wroteC=false;wroteR=false;installed=false;
    try
        write_text(hpp,hppNew);wroteH=true;
        write_text(cpp,cppNew);wroteC=true;
        write_text(rps,rpsNew);wroteR=true;
        [ok,msg]=copyfile(sm,dstMex,'f');assert(ok,'%s',msg);installed=true;
        clear mex;rehash
        assert(exist('af7r36_single_core_mex','file')==3);
    catch ME2
        if wroteH,try,write_text(hpp,hpp0);catch,end,end
        if wroteC,try,write_text(cpp,cpp0);catch,end,end
        if wroteR,try,write_text(rps,rps0);catch,end,end
        if installed&&hadMex,try,copyfile(oldMex,dstMex,'f');catch,end,end
        clear mex;rehash;rethrow(ME2);
    end

    fprintf('[R25B] PASS.\n');
    fprintf('  new curved exact-C7 primary installed      = 1\n');
    fprintf('  plateau in family 6                        = 0\n');
    fprintf('  family 6 equal-duration dependency         = 0\n');
    fprintf('  hard safety recertification                = unchanged / mandatory\n');
    fprintf('  old families                               = retained only for migration comparison\n');

    OUT=struct('pass',true,'revision','AF7_CURVED_C7_ZERO_JET_BELL_R25B', ...
        'family_id',6,'exact_C7',true,'plateau',false, ...
        'hard_safety_modified',false,'old_families_removed',false);

catch ME
    clear mex;rehash
    fprintf(2,'[R25B] FAILED: %s | %s\n',ME.identifier,ME.message);
    rethrow(ME);
end
end

function txt=replace_once_in_region(txt,regionStart,regionEnd,old,new,label)
p0=strfind(txt,regionStart);
assert(numel(p0)==1,'[R25B] Region start "%s" count=%d; expected 1.',label,numel(p0));
tail=txt(p0:end);
p1=strfind(tail,regionEnd);
assert(~isempty(p1),'[R25B] Region end "%s" missing.',label);
stop=p0+p1(1)-2;
sub=txt(p0:stop);
q=strfind(sub,old);
assert(numel(q)==1,'[R25B] Anchor "%s" count=%d inside target region; expected 1.',label,numel(q));
a=p0+q(1)-1;
