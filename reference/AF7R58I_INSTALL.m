function [bitLegacy,bitFlat,maxLegacy,maxFlat,boundaryPass]=canonical_selftest()
rawfh=@synthetic_raw;
flatfh=cell(1,7);
for r=0:6
    rr=r;
    flatfh{r+1}=@(t)synthetic_flat(t,rr);
end

model=struct();
model.certified=true;
model.flight_reference_time_origin=0.25;
model.corrections=struct('t0',{},'t1',{},'segment_t0',{},'segment_t1',{},'control_points',{});

C1=synthetic_correction(1.00,2.00,0.03);
C2=synthetic_correction(1.50,2.50,-0.02);
model.corrections=[C1 C2];

times=[0.25 0.999999 1.0 1.2 1.5 1.75 2.0 2.2 2.5 2.500001 3.0];

bitLegacy=true;
bitFlat=true;
maxLegacy=0;
maxFlat=0;

for k=1:numel(times)
    t=times(k);

    yCanon=af7r58i_eval_canonical_reference(rawfh,flatfh,0.25,model,t,false);
    yOld=synthetic_recursive(rawfh,flatfh,0.25,model,t,false);
    maxLegacy=max(maxLegacy,max(abs(yCanon(:)-yOld(:))));
    bitLegacy=bitLegacy && isequal(typecast(yCanon(:),'uint64'),typecast(yOld(:),'uint64'));

    yCanonF=af7r58i_eval_canonical_reference(rawfh,flatfh,0.25,model,t,true);
    yOldF=synthetic_recursive(rawfh,flatfh,0.25,model,t,true);
    maxFlat=max(maxFlat,max(abs(yCanonF(:)-yOldF(:))));
    bitFlat=bitFlat && isequal(typecast(yCanonF(:),'uint64'),typecast(yOldF(:),'uint64'));
end

% At exact global correction boundaries both matching groups are zero by strict support.
base1=synthetic_recursive(rawfh,flatfh,0.25,struct( ...
    'corrections',struct('t0',{},'t1',{},'segment_t0',{},'segment_t1',{},'control_points',{})), ...
    1.0,false);
v1=af7r58i_eval_canonical_reference(rawfh,flatfh,0.25, ...
    struct('corrections',C1),1.0,false);
base2=synthetic_recursive(rawfh,flatfh,0.25,struct( ...
    'corrections',struct('t0',{},'t1',{},'segment_t0',{},'segment_t1',{},'control_points',{})), ...
    2.0,false);
v2=af7r58i_eval_canonical_reference(rawfh,flatfh,0.25, ...
    struct('corrections',C1),2.0,false);
boundaryPass=isequal(typecast(base1(:),'uint64'),typecast(v1(:),'uint64')) && ...
    isequal(typecast(base2(:),'uint64'),typecast(v2(:),'uint64'));
end


function y=synthetic_recursive(rawfh,flatfh,tf0,model,t,useFlat)
tau=t-tf0;
if tau<0, tau=0; end
y=double(rawfh(tau)); y=y(:);
if numel(y)<28, y=[y;zeros(28-numel(y),1)]; end
if useFlat
    for r=0:6
        z=double(flatfh{r+1}(tau)); z=z(:);
        y(4*r+(1:3))=z;
    end
end
for g=1:numel(model.corrections)
    D=synthetic_corr_derivatives(t,model.corrections(g),6);
    for r=0:6
        y(4*r+(1:3))=y(4*r+(1:3))+D(:,r+1);
    end
end
end


function y=synthetic_raw(t)
y=zeros(28,1);
for r=0:6
    y(4*r+(1:3))=[(r+1)+t; 2*(r+1)-0.5*t; -(r+1)+0.25*t];
    y(4*r+4)=0.1*(r+1)+0.01*t;
end
end


function z=synthetic_flat(t,r)
z=[(r+1)+t+0.001*(r+1); ...
   2*(r+1)-0.5*t-0.002*(r+1); ...
   -(r+1)+0.25*t+0.003*(r+1)];
end


function C=synthetic_correction(t0,t1,scale)
tm=(t0+t1)/2;
C=struct();
C.t0=t0;
C.t1=t1;
C.segment_t0=[t0 tm];
C.segment_t1=[tm t1];
C.control_points=cell(1,2);
for s=1:2
    A=zeros(3,16);
    for j=1:16
        A(:,j)=scale*[j; j^2/16; (-1)^j*j/8]*(1+0.1*s);
    end
    C.control_points{s}=A;
end
end


function DOUT=synthetic_corr_derivatives(t,C,maxOrder)
DOUT=zeros(3,maxOrder+1);
if t<=C.t0||t>=C.t1, return; end
s0=C.segment_t0(:);
s1=C.segment_t1(:);
is=find(t<=s1,1,'first');
if isempty(is), return; end
if t<s0(is)
    if is==1, return; end
    is=is-1;
end
T=s1(is)-s0(is);
u=(t-s0(is))/T;
u=max(0,min(1,u));
Q=double(C.control_points{is});
deg=15;
DOUT(:,1)=synthetic_decasteljau(Q,u);
for r=1:maxOrder
    Q=(deg/T)*diff(Q,1,2);
    deg=deg-1;
    DOUT(:,r+1)=synthetic_decasteljau(Q,u);
end
end


function y=synthetic_decasteljau(C,u)
while size(C,2)>1
    C=(1-u)*C(:,1:end-1)+u*C(:,2:end);
end
y=C(:,1);
end


