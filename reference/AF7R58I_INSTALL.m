function OUT = AF7R58I_ONEFILE_PRODUCTION_CANONICAL_RESOURCE_INSTALL()
% AF7R58I
% Transactional production install for:
%   (1) exact expired correction prune,
%   (2) finite live G/S resource theorem,
%   (3) explicit positive successive-commit spacing,
%   (4) nonrecursive canonical active evaluators.
%
% This installer is intentionally theory-preserving:
%   - no sampled safety acceptance is introduced;
%   - no obstacle geometry/count, trajectory instance, physical parameter,
%     actuator/input limit, or payload mass is hard-coded;
%   - payload mL is untouched and remains live-estimator authority for the
%     later tension/thrust/moment feasibility certificate;
%   - active reference valid_until is NOT artificially shortened.
%
% It edits current production source transactionally. Any failure after the
% first write restores all modified production files and deletes new helpers.
%
% RETURN:
%   AF7R58I_REPORT.txt
%   AF7R58I_OUT.mat

root=fileparts(mfilename('fullpath'));
outdir=tempname(root);
[ok,msg]=mkdir(outdir); assert(ok,'%s',msg);

f=fopen(fullfile(outdir,'AF7R58I_REPORT.txt'),'wt','n','UTF-8');
assert(f>=0,'[AF7R58I] cannot open report.');
cleanupFile=onCleanup(@()fclose(f)); %#ok<NASGU>

say(f,'====================================================================================================');
say(f,' AF7R58I | TRANSACTIONAL CANONICAL ACTIVE-REFERENCE RESOURCE INSTALL');
say(f,'====================================================================================================');
say(f,'[AUTHORITY] transactional=1 | rollbackOnFailure=1 | noFlight=1 | noSimulation=1 | noMexChange=1');
say(f,'[SAFETY] sampledSafetyAcceptance=0 | theoryWeakening=0 | hardcodedPhysicalParams=0 | mLFrozen=0');
say(f,' root = %s',root);

OUT=struct();
OUT.schema='AF7R58I_CANONICAL_RESOURCE_INSTALL_V1';
OUT.production_modified=false;
OUT.rollback_performed=false;
OUT.status='OPEN';
OUT.error=struct();
OUT.pre_audit=struct();
OUT.selftest=struct();
OUT.source_hash_before=struct();
OUT.source_hash_after=struct();
OUT.helper_hashes=struct();
OUT.backup_directory='';
OUT.output_directory=outdir;
OUT.required_return_files={'AF7R58I_REPORT.txt','AF7R58I_OUT.mat'};

pR=fullfile(root,'REPLANNING_SYSTEM.m');
pA33=fullfile(root,'af7r33_make_batch_model_from_proposal.m');

expectedR='223d34c49d7148b8ea14ff4ab9c420d409560c0650ac19e9b0f99318887090c9';
expectedA33='f0e9f487cd270430d191871366c84595be586b6da0fb7b93eb98f4dfc25b46fd';

helperNames={ ...
    'af7r58i_resource_contract.m', ...
    'af7r58i_commit_spacing_guard.m', ...
    'af7r58i_prune_batch_model_exact.m', ...
    'af7r58i_prepare_batch_model.m', ...
    'af7r58i_make_canonical_eval_handles.m', ...
    'af7r58i_eval_canonical_reference.m'};

backupDir=tempname(root);
backupReady=false;
writesStarted=false;

try
    assert(isfile(pR),'[AF7R58I] missing REPLANNING_SYSTEM.m');
    assert(isfile(pA33),'[AF7R58I] missing af7r33_make_batch_model_from_proposal.m');

    hR=file_hash(pR);
    hA33=file_hash(pA33);
    OUT.source_hash_before=struct('REPLANNING_SYSTEM',hR,'AF7R33_BUILDER',hA33);

    say(f,'');
    say(f,'[A. EXACT PRE-INSTALL SOURCE BINDING]');
    say(f,' REPLANNING_SYSTEM exact reviewed source = %d | %s',strcmp(hR,expectedR),hR);
    say(f,' AF7R33 builder exact reviewed source    = %d | %s',strcmp(hA33,expectedA33),hA33);

    assert(strcmp(hR,expectedR), ...
        '[AF7R58I] REPLANNING_SYSTEM.m differs from reviewed AF7R58G/H authority; no install.');
    assert(strcmp(hA33,expectedA33), ...
        '[AF7R58I] AF7R33 builder differs from reviewed authority; no install.');

    for k=1:numel(helperNames)
        assert(~isfile(fullfile(root,helperNames{k})), ...
            '[AF7R58I] helper already exists; refusing ambiguous overwrite: %s',helperNames{k});
    end

    [R,eolR]=read_text_norm(pR);
    [A33,eolA33]=read_text_norm(pA33);
    cR=compact_ws(R);

    % ---------------------------------------------------------------------
    % Source theorem pre-audit.
    % ---------------------------------------------------------------------
    tReq=contains(cR,'''time'',double(t_now)');
    tCommitCall=contains(cR, ...
        'obj.try_commit_reference_only_proposal(...candidate,double(t_now),t_hard_cycle)');
    if ~tCommitCall
        % Robust compact-source form after ellipsis/newline removal.
        tCommitCall=contains(cR, ...
            'obj.try_commit_reference_only_proposal(candidate,double(t_now),t_hard_cycle)');
    end
    tPacket=contains(fileread(fullfile(root,'af7r34_make_core_packet.m')), ...
        'P.t0=double(RQ.time);');
    coreText=fileread(fullfile(root,'af7r36_core.hpp'));
    strictSupport=contains(compact_ws(coreText),'if(!(t>C.t0&&t<C.t1))continue;');
    matlabStrict=contains(cR,'ift<=double(P.t0)||t>=double(P.t1)');

    recursiveCapture= ...
        contains(cR,'P.base_eval_fn=obj.snapshot_active_reference_eval_fn();') && ...
        contains(cR,'P.base_flat_eval_fn=obj.snapshot_active_reference_flat_eval_fn();') && ...
        contains(cR,'evalFn=@(tg)obj.evaluate_bezier_proposal_reference(tg,P);') && ...
        contains(cR,'flatEvalFn=@(tg)obj.evaluate_bezier_proposal_flat_reference(tg,P);');

    noOldSpacing=~contains(cR,'af7r58i_commit_spacing_guard');
    noOldCanonical=~contains(cR,'af7r58i_make_canonical_eval_handles');

    OUT.pre_audit=struct( ...
        'request_time_from_tnow',tReq, ...
        'reference_only_commit_uses_tnow',tCommitCall, ...
        'packet_t0_from_request',tPacket, ...
        'native_strict_support',strictSupport, ...
        'matlab_strict_support',matlabStrict, ...
        'recursive_capture_present',recursiveCapture, ...
        'fresh_spacing_install',noOldSpacing, ...
        'fresh_canonical_install',noOldCanonical);

    say(f,'');
    say(f,'[B. PRE-INSTALL THEORY / SOURCE FACTS]');
    say(f,' request.time = t_now                              = %d',tReq);
    say(f,' reference-only commit receives same t_now         = %d',tCommitCall);
    say(f,' packet t0 = request.time                          = %d',tPacket);
    say(f,' native correction support is strict t0<t<t1      = %d',strictSupport);
    say(f,' MATLAB correction support is strict t0<t<t1      = %d',matlabStrict);
    say(f,' recursive active-evaluator capture is present     = %d',recursiveCapture);
    say(f,' prior AF7R58I spacing install absent              = %d',noOldSpacing);
    say(f,' prior AF7R58I canonical install absent            = %d',noOldCanonical);

    assert(tReq&&tCommitCall&&tPacket&&strictSupport&&matlabStrict&& ...
        recursiveCapture&&noOldSpacing&&noOldCanonical, ...
        '[AF7R58I] exact production precondition not closed; no install.');

    % ---------------------------------------------------------------------
    % Backup before first write.
    % ---------------------------------------------------------------------
    [ok,msg]=mkdir(backupDir); assert(ok,'%s',msg);
    backupReady=true;
    OUT.backup_directory=backupDir;
    copyfile(pR,fullfile(backupDir,'REPLANNING_SYSTEM.m'));
    copyfile(pA33,fullfile(backupDir,'af7r33_make_batch_model_from_proposal.m'));

    % ---------------------------------------------------------------------
    % Patch 1: generic EXECUTION_AWARE commit also gets explicit spacing.
    % ---------------------------------------------------------------------
    old=blk({ ...
        '            obj.assert_hard_modify_deadline_limit();'; ...
        '            obj.validate_repaired_candidate(candidate,double(t_commit));'; ...
        ''});
    new=blk({ ...
        '            obj.assert_hard_modify_deadline_limit();'; ...
        '            [spacingOK,~,~,spacingReason]= ...'; ...
        '                af7r58i_commit_spacing_guard(obj,double(t_commit));'; ...
        '            assert(spacingOK, ...'; ...
        '                ''[REPLANNER ERROR] repaired commit spacing rejected: %s'', ...'; ...
        '                spacingReason);'; ...
        '            obj.validate_repaired_candidate(candidate,double(t_commit));'; ...
        ''});
    R=patch_once(R,old,new,'generic execution-aware commit spacing');

    % ---------------------------------------------------------------------
    % Patch 2: REFERENCE_ONLY commit spacing and no persistent recursive base.
    % ---------------------------------------------------------------------
    old=blk({ ...
        '            if ~(isstruct(P) && isfield(P,''success'') && logical(P.success))'; ...
        '                reason=''PROPOSAL_NOT_SUCCESSFUL'';'; ...
        '                return;'; ...
        '            end'; ...
        ''; ...
        '            P=obj.af7r46_materialize_candidate_evaluators(P);'; ...
        ''});
    new=blk({ ...
        '            if ~(isstruct(P) && isfield(P,''success'') && logical(P.success))'; ...
        '                reason=''PROPOSAL_NOT_SUCCESSFUL'';'; ...
        '                return;'; ...
        '            end'; ...
        ''; ...
        '            [spacingOK,~,~,spacingReason]= ...'; ...
        '                af7r58i_commit_spacing_guard(obj,double(t_commit));'; ...
        '            if ~spacingOK'; ...
        '                reason=spacingReason;'; ...
        '                return;'; ...
        '            end'; ...
        ''});
    R=patch_once(R,old,new,'reference-only spacing and recursive materialization removal');

    % ---------------------------------------------------------------------
    % Patch 3: build bounded canonical model BEFORE evaluator handles.
    % ---------------------------------------------------------------------
    old=blk({ ...
        '            evalFn=@(tg)obj.evaluate_bezier_proposal_reference(tg,P);'; ...
        '            flatEvalFn=@(tg)obj.evaluate_bezier_proposal_flat_reference(tg,P);'; ...
        ''});
    new=blk({ ...
        '            [resourceOK,resourceReason,batchModel,resourceMeta]= ...'; ...
        '                af7r58i_prepare_batch_model( ...'; ...
        '                    obj,P,targetVersion,double(t_commit));'; ...
        '            if ~resourceOK'; ...
        '                reason=resourceReason;'; ...
        '                return;'; ...
        '            end'; ...
        '            [evalFn,flatEvalFn]= ...'; ...
        '                af7r58i_make_canonical_eval_handles(obj,batchModel);'; ...
        ''});
    R=patch_once(R,old,new,'reference-only canonical evaluator creation');

    % ---------------------------------------------------------------------
    % Patch 4: store the already-pruned bounded canonical model, not append again.
    % ---------------------------------------------------------------------
    old=blk({ ...
        '                R.batch_flat_model=obj.make_batch_model_from_proposal_cached( ...'; ...
        '                    P,targetVersion);'; ...
        '                R.authority_split=struct( ...'});
    new=blk({ ...
        '                R.batch_flat_model=batchModel;'; ...
        '                R.resource_certificate=resourceMeta.contract;'; ...
        '                R.resource_state=resourceMeta;'; ...
        '                R.authority_split=struct( ...'});
    R=patch_once(R,old,new,'store canonical batch model once');

    % ---------------------------------------------------------------------
    % Patch 5: make the legacy cached builder bounded too, so no hidden path
    % can append without the same theorem.
    % ---------------------------------------------------------------------
    old=extract_function_block(R, ...
        '        function model = make_batch_model_from_proposal_cached(obj,P,targetVersion)', ...
        '        function sweep = build_trigger_sweep_for_target(obj,SC,targetVersion)');
    new=blk({ ...
        '        function model = make_batch_model_from_proposal_cached(obj,P,targetVersion)'; ...
        '            [ok,reason,model,~]=af7r58i_prepare_batch_model( ...'; ...
        '                obj,P,targetVersion,double(P.t0));'; ...
        '            assert(ok, ...'; ...
        '                ''[REPLANNER ERROR] canonical batch resource gate rejected: %s'', ...'; ...
        '                reason);'; ...
        '        end'; ...
        ''; ...
        ''; ...
        '        function sweep = build_trigger_sweep_for_target(obj,SC,targetVersion)'});
    R=patch_once(R,old,new,'cached batch builder canonicalization');

    % ---------------------------------------------------------------------
    % Patch external AF7R33 builder to same canonical resource path.
    % ---------------------------------------------------------------------
    A33=blk({ ...
        'function model = af7r33_make_batch_model_from_proposal(replanner,P,targetVersion)'; ...
        '% AF7R58I canonical bounded batch-model builder.'; ...
        '% No object state is modified here.'; ...
        ''; ...
        'assert(isa(replanner,''REPLANNING_SYSTEM''));'; ...
        '[ok,reason,model,~]=af7r58i_prepare_batch_model( ...'; ...
        '    replanner,P,targetVersion,double(P.t0));'; ...
        'assert(ok,''[AF7R33] canonical resource gate rejected: %s'',reason);'; ...
        'end'; ...
        ''});

    % ---------------------------------------------------------------------
    % Install production text and helpers transactionally.
    % ---------------------------------------------------------------------
    writesStarted=true;
    write_text_eol(pR,R,eolR);
    write_text_eol(pA33,A33,eolA33);

    write_utf8(fullfile(root,'af7r58i_resource_contract.m'),resource_contract_text());
    write_utf8(fullfile(root,'af7r58i_commit_spacing_guard.m'),spacing_guard_text());
    write_utf8(fullfile(root,'af7r58i_prune_batch_model_exact.m'),prune_text());
    write_utf8(fullfile(root,'af7r58i_prepare_batch_model.m'),prepare_model_text());
    write_utf8(fullfile(root,'af7r58i_make_canonical_eval_handles.m'),make_handles_text());
    write_utf8(fullfile(root,'af7r58i_eval_canonical_reference.m'),canonical_eval_text());

    say(f,'');
    say(f,'[C. TRANSACTIONAL PRODUCTION INSTALL]');
    say(f,' explicit positive commit-spacing guard installed        = 1');
    say(f,' exact expired prune installed                           = 1');
    say(f,' live source-derived Gmax/Smax theorem installed          = 1');
    say(f,' nonrecursive canonical active evaluator installed        = 1');
    say(f,' active valid_until artificially shortened                = 0');
    say(f,' MEX/core mathematical safety code modified               = 0');
    say(f,' payload mL touched/frozen                                = 0');

    % ---------------------------------------------------------------------
    % MATLAB syntax parse of modified files and helpers.
    % ---------------------------------------------------------------------
    clear af7r33_make_batch_model_from_proposal
    nargin('af7r33_make_batch_model_from_proposal');

    for k=1:numel(helperNames)
        fn=erase(helperNames{k},'.m');
        eval(['clear ' fn]);
        nargin(fn);
    end

    parseName='AF7R58I_PARSE_REPLANNING_SYSTEM';
    parseText=strrep(R,'classdef REPLANNING_SYSTEM < handle', ...
        ['classdef ' parseName ' < handle']);
    parseFile=fullfile(outdir,[parseName '.m']);
    write_utf8(parseFile,parseText);
    addpath(outdir,'-begin');
    cleanupPath=onCleanup(@()safe_rmpath(outdir)); %#ok<NASGU>
    mc=meta.class.fromName(parseName);
    assert(~isempty(mc),'[AF7R58I] modified REPLANNING_SYSTEM class parse failed.');
    eval(['clear ' parseName]);

    % ---------------------------------------------------------------------
    % Algebraic/canonical synthetic self-test.
    % Primary theorem is algebraic; this numerical test is supplementary.
    % ---------------------------------------------------------------------
    [bitwiseLegacy,bitwiseFlat,maxLegacy,maxFlat,boundaryPass]= ...
        canonical_selftest();

    assert(bitwiseLegacy && bitwiseFlat && boundaryPass, ...
        '[AF7R58I] canonical evaluator synthetic equivalence regression failed.');

    say(f,'');
    say(f,'[D. CANONICAL EVALUATOR SELF-TEST -- SUPPLEMENTARY]');
    say(f,' legacy recursive-vs-canonical bitwise identical          = %d',bitwiseLegacy);
    say(f,' flat recursive-vs-canonical bitwise identical            = %d',bitwiseFlat);
    say(f,' max legacy abs error                                      = %.17g',maxLegacy);
    say(f,' max flat abs error                                        = %.17g',maxFlat);
    say(f,' strict-support boundary zero semantics                    = %d',boundaryPass);
    say(f,' NOTE: this regression is not safety acceptance; the proof is additive correction algebra + strict support.');

    % ---------------------------------------------------------------------
    % Source post-audit.
    % ---------------------------------------------------------------------
    R2=fileread(pR);
    cR2=compact_ws(R2);
    postCanonical=contains(cR2,'af7r58i_make_canonical_eval_handles(obj,batchModel)');
    postStore=contains(cR2,'R.batch_flat_model=batchModel;');
    postNoRecursiveCommit=~contains(extract_between( ...
        R2, ...
        '        function [ok,reason] = try_commit_reference_only_proposal(obj,P,t_commit,t_hard_cycle)', ...
        '        function R = evaluate_reference_only_proposal_certificate'), ...
        'evalFn=@(tg)obj.evaluate_bezier_proposal_reference(tg,P);');
    postSpacing=contains(cR2,'af7r58i_commit_spacing_guard(obj,double(t_commit))');

    assert(postCanonical&&postStore&&postNoRecursiveCommit&&postSpacing, ...
        '[AF7R58I] post-install source invariant failed.');

    hR2=file_hash(pR);
    hA332=file_hash(pA33);
    OUT.source_hash_after=struct('REPLANNING_SYSTEM',hR2,'AF7R33_BUILDER',hA332);

    for k=1:numel(helperNames)
        fn=erase(helperNames{k},'.m');
        OUT.helper_hashes.(fn)=file_hash(fullfile(root,helperNames{k}));
    end

    OUT.selftest=struct( ...
        'matlab_helpers_parse',true, ...
        'modified_class_parse',true, ...
        'legacy_canonical_bitwise',bitwiseLegacy, ...
        'flat_canonical_bitwise',bitwiseFlat, ...
        'legacy_max_abs',maxLegacy, ...
        'flat_max_abs',maxFlat, ...
        'strict_boundary_pass',boundaryPass, ...
        'post_canonical_handle',postCanonical, ...
        'post_canonical_model_store',postStore, ...
        'post_no_recursive_commit_eval',postNoRecursiveCommit, ...
        'post_spacing_guard',postSpacing);

    OUT.production_modified=true;
    OUT.status='PRODUCTION_CANONICAL_RESOURCE_INSTALL_COMPLETE__RUNTIME_PACKET_AUDIT_NEXT';

    say(f,'');
    say(f,'[E. CLOSURE LEDGER AFTER INSTALL]');
    say(f,' t0=commit equality enforced at resource gate             = 1');
    say(f,' finite correction support retained                        = 1');
    say(f,' expired-prune semantics installed                         = 1');
    say(f,' recursive active evaluator removed from commit             = 1');
    say(f,' bounded canonical model is sole REFERENCE_ONLY history     = 1');
    say(f,' explicit positive Dcommit guard installed                  = 1');
    say(f,' live Gmax/Smax contract installed                          = 1');
    say(f,' ordinary reference-only return on resource excess          = 1');
    say(f,' full IEEE compiler/rounding environment closure            = 0');
    say(f,' end-to-end hard 4 ms re-validation                        = 0');
    say(f,' tension/thrust/moment feasibility with latest live mL      = 0');
    say(f,' final failure backup integration                           = 0');
    say(f,' production modified                                        = 1');

    say(f,'');
    say(f,'[F. NEXT REQUIRED AUDIT]');
    say(f,' Recreate REPLANNING_SYSTEM object from a clean run before testing.');
    say(f,' Return AF7R58I_REPORT.txt and AF7R58I_OUT.mat.');
    say(f,' Next: direct live-config resource packet audit + equivalence regression + hard-path 4-ms timing.');
    say(f,' Then: towing-specific tension/thrust/moment feasibility using external preflight config');
    say(f,'       and the latest in-flight payload-mass estimate; no fixed mL assumption.');

catch ME
    if backupReady && writesStarted
        rollback_install(root,backupDir,pR,pA33,helperNames);
        OUT.rollback_performed=true;
    end
    OUT.production_modified=false;
    OUT.status='INSTALL_FAILED__ROLLBACK_COMPLETE';
    OUT.error=struct('identifier',ME.identifier,'message',ME.message,'stack',{ME.stack});

    say(f,'');
    say(f,'[INSTALL FAILURE]');
    say(f,' identifier          = %s',ME.identifier);
    say(f,' message             = %s',ME.message);
    say(f,' rollback performed  = %d',OUT.rollback_performed);
    say(f,' production modified = 0');
end

OUT.output_directory=outdir;
save(fullfile(outdir,'AF7R58I_OUT.mat'),'OUT','-v7');
assignin('base','AF7R58I_OUT',OUT);

say(f,'');
say(f,'[RETURN THESE TWO FILES]');
say(f,' RETURN: %s',fullfile(outdir,'AF7R58I_REPORT.txt'));
say(f,' RETURN: %s',fullfile(outdir,'AF7R58I_OUT.mat'));
say(f,' status = %s',OUT.status);

end


