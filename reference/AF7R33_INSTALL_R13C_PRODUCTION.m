function OUT = AF7R33_INSTALL_R13C_PRODUCTION()
clc;
fprintf('\n====================================================================================================\n');
fprintf(' AF7R33 | INSTALL R13C REPEAT-SAFE BATCH + EXACT QP PRODUCTION PATH\n');
fprintf('====================================================================================================\n');
fprintf('[AUTHORITY] theoremUnchanged=1 | repeatedReplanModel=1 | sampledAcceptance=0 | deadlineUnchanged=1\n');

src=which('REPLANNING_SYSTEM');
assert(~isempty(src)&&isfile(src),'[AF7R33] REPLANNING_SYSTEM unresolved.');
root=fileparts(src); here=fileparts(mfilename('fullpath'));

tokPath=fullfile(root,'AF7R33_PREINSTALL_TOKEN.mat');
assert(isfile(tokPath),'[AF7R33] preinstall token missing. Run AF7R33C_PREINSTALL_GATE first.');
Q=load(tokPath,'token');
assert(isfield(Q,'token')&&isstruct(Q.token)&&isfield(Q.token,'closed')&&logical(Q.token.closed), ...
    '[AF7R33] preinstall token is not closed.');

reqFiles={ ...
    'af7r33_active_flat_jet_batch.m', ...
    'af7r33_nominal_batch_model.m', ...
    'af7r33_make_batch_model_from_proposal.m', ...
    'af7r33_flat_jet_batch_model.m', ...
    'af7r33_episode_batch_allobs.m', ...
    'af7r33_corridor_batch.m', ...
    'af7r33_candidate_position_accel_batch.m', ...
    'af7r33_wholebody_batch_certified.m'};
for k=1:numel(reqFiles)
    a=fullfile(here,reqFiles{k}); b=fullfile(root,reqFiles{k});
    assert(isfile(a),'[AF7R33] package helper missing: %s',reqFiles{k});
    if ~strcmpi(a,b)
        [ok,msg]=copyfile(a,b,'f'); assert(ok,'[AF7R33] copy failed: %s',msg);
    end
end

assert(exist('af7r33_episode_pair_mex','file')==3, ...
    '[AF7R33] paired episode MEX missing. Build it first.');
assert(exist('af7r31_geometry_batch_mex','file')==3, ...
    '[AF7R33] R13 geometry batch MEX missing.');
assert(exist('af7r32_exact_qp_mex','file')==3, ...
    '[AF7R33] exact QP MEX missing.');

raw=fileread(src);
assert(contains(raw,'AF7R27-R10')&&contains(raw,'AF7R29-R11')&&contains(raw,'AF7R30-R12'), ...
    '[AF7R33] expected R10/R11/R12 source not present.');
assert(~contains(raw,'AF7R33-R13C'), ...
    '[AF7R33] R13C marker already present; refusing duplicate install.');

stamp=datestr(now,'yyyymmdd_HHMMSS');
bak=fullfile(root,['REPLANNING_SYSTEM_pre_R13C_' stamp '.m']);
[ok,msg]=copyfile(src,bak,'f'); assert(ok,'[AF7R33] backup failed: %s',msg);

% Marker.
raw=strrep(raw,'classdef REPLANNING_SYSTEM < handle', ...
    sprintf('classdef REPLANNING_SYSTEM < handle\n\n%% AF7R33-R13C: repeat-safe active-flat batch + all-obstacle episode + exact-QP + batched whole-body.'));

% Episode production call.
old=sprintf(['            [EPI,okEpi]=obj.build_bezier_nominal_unsafe_episode_components( ...\n' ...
             '                OUT,CTX,searchEnd);']);
new=sprintf(['            [EPI,okEpi]=af7r33_episode_batch_allobs( ...\n' ...
             '                obj,OUT,CTX,searchEnd);']);
assert(count(raw,old)==1,'[AF7R33] episode anchor count mismatch.');
raw=strrep(raw,old,new);

% Corridor production calls.
old=sprintf(['                [Ap,bp,okp]=obj.bezier_piecewise_episode_corridor_rows( ...\n' ...
             '                    P,CTX,EPI,ie,n0,nvar);\n' ...
             '                [Am,bm,okm]=obj.bezier_piecewise_episode_corridor_rows( ...\n' ...
             '                    P,CTX,EPI,ie,-n0,nvar);']);
new=sprintf(['                [Ap,bp,okp]=af7r33_corridor_batch( ...\n' ...
             '                    obj,P,CTX,EPI,ie,n0,nvar);\n' ...
             '                [Am,bm,okm]=af7r33_corridor_batch( ...\n' ...
             '                    obj,P,CTX,EPI,ie,-n0,nvar);']);
assert(count(raw,old)==1,'[AF7R33] corridor anchor count mismatch.');
raw=strrep(raw,old,new);

% Store explicit repeated-replan flat model at reference-only commit.
old=sprintf(['                R.representation=struct( ...\n' ...
             '                    ''kind'',''BEZIER_D15_C7_TRANSLATION_BUMP'', ...\n' ...
             '                    ''t0'',double(P.t0),''tm'',double(P.tm),''t1'',double(P.t1), ...\n' ...
             '                    ''displacement'',double(P.displacement(:)));\n' ...
             '                R.authority_split=struct( ...']);
new=sprintf(['                R.representation=struct( ...\n' ...
             '                    ''kind'',''BEZIER_D15_C7_TRANSLATION_BUMP'', ...\n' ...
             '                    ''t0'',double(P.t0),''tm'',double(P.tm),''t1'',double(P.t1), ...\n' ...
             '                    ''displacement'',double(P.displacement(:)));\n' ...
             '                R.batch_flat_model=af7r33_make_batch_model_from_proposal( ...\n' ...
             '                    obj,P,targetVersion);\n' ...
             '                R.authority_split=struct( ...']);
assert(count(raw,old)==1,'[AF7R33] reference-only commit anchor mismatch.');
raw=strrep(raw,old,new);

% Native exact QP fast path.  Legacy quadprog remains as fallback if native
% is unavailable, non-SPD, errors, or reports no solution.
anchor=sprintf(['            H=0.5*(double(H)+double(H).'');\n' ...
                '            hs=max(abs(H(:)));\n' ...
                '            if ~(isfinite(hs)&&hs>0)\n' ...
                '                return;\n' ...
                '            end\n\n' ...
                '            Hsolve=H/hs;']);
insert=sprintf(['            H=0.5*(double(H)+double(H).'');\n' ...
                '            hs=max(abs(H(:)));\n' ...
                '            if ~(isfinite(hs)&&hs>0)\n' ...
                '                return;\n' ...
                '            end\n\n' ...
                '            if exist(''af7r32_exact_qp_mex'',''file'')==3\n' ...
                '                try\n' ...
                '                    [zn,cn,sn,on,~,~,spd]=af7r32_exact_qp_mex( ...\n' ...
                '                        H,double(A),double(b(:)));\n' ...
                '                    if logical(spd)&&logical(on)&&numel(zn)==size(H,1)&&all(isfinite(zn))\n' ...
                '                        AzN=double(A)*double(zn(:));\n' ...
                '                        slackN=AzN-double(b(:));\n' ...
                '                        tolN=512*eps(max([ones(size(slackN)),abs(double(b(:))),abs(AzN)],[],2));\n' ...
                '                        if all(slackN>=-tolN)&&isfinite(double(cn))&&isfinite(double(sn))\n' ...
                '                            z=double(zn(:));\n' ...
                '                            cost=0.5*z.''*H*z;\n' ...
                '                            minSlack=min(slackN);\n' ...
                '                            ok=isfinite(cost);\n' ...
                '                            if ok, return; end\n' ...
                '                        end\n' ...
                '                    end\n' ...
                '                catch\n' ...
                '                    %% Fall through to unchanged quadprog synthesis.\n' ...
                '                end\n' ...
                '            end\n\n' ...
                '            Hsolve=H/hs;']);
assert(count(raw,anchor)==1,'[AF7R33] QP anchor mismatch.');
raw=strrep(raw,anchor,insert);

% Whole-body production fast path at method entry. A well-formed returned
% certificate is authoritative; exceptions/malformed output fall back to
% the unchanged legacy theorem below.
anchor='        function G = build_static_continuous_wholebody_shadow_certificate(obj,CTX,P)';
assert(count(raw,anchor)==1,'[AF7R33] whole-body method anchor mismatch.');
new=[anchor newline ...
'            if exist(''af7r33_wholebody_batch_certified'',''file'')==2' newline ...
'                try' newline ...
'                    Gfast=af7r33_wholebody_batch_certified(obj,CTX,P);' newline ...
'                    if isstruct(Gfast)&&isfield(Gfast,''mathematical_pass'')&& ...' newline ...
'                            isfield(Gfast,''continuous_time'')&&logical(Gfast.continuous_time)&& ...' newline ...
'                            isfield(Gfast,''sampled_acceptance'')&&~logical(Gfast.sampled_acceptance)' newline ...
'                        G=Gfast;' newline ...
'                        return;' newline ...
'                    end' newline ...
'                catch' newline ...
'                    %% Fall through to the unchanged legacy theorem.' newline ...
'                end' newline ...
'            end'];
raw=strrep(raw,anchor,new);

% Warm source-bound flat batch before Flight.
anchor=sprintf(['            try\n' ...
                '                obj.assert_runtime_core_certificates_current();\n' ...
                '                xdP=obj.evaluate_active_reference_xd(double(tf),xd_nom);']);
new=sprintf(['            try\n' ...
             '                obj.assert_runtime_core_certificates_current();\n' ...
             '                af7r33_active_flat_jet_batch(obj,[double(tf) double(tf)+double(obj.prediction_dt)]);\n' ...
             '                xdP=obj.evaluate_active_reference_xd(double(tf),xd_nom);']);
assert(count(raw,anchor)>=1,'[AF7R33] tail-prime anchor missing.');
% Replace only the last occurrence region-specific by exact first occurrence
% inside r12 method: use rfind on substring before MATLAB write is unavailable,
% so unique local text count is required here.
idx=strfind(raw,anchor);
assert(numel(idx)==1,'[AF7R33] tail-prime exact anchor is not unique.');
raw=strrep(raw,anchor,new);

% Preserve no sampled-acceptance production marker.
compact=regexprep(raw,'\s+','');
needle=[char(39) 'sampled_acceptance' char(39) ',true'];
assert(~contains(compact,needle),'[AF7R33] sampled acceptance true detected.');

fid=fopen(src,'w'); assert(fid>=0,'[AF7R33] cannot open production source.');
c=onCleanup(@()fclose(fid)); fwrite(fid,raw,'char'); clear c;
rehash;

OUT=struct('schema','AF7R33_INSTALL_R13C_PRODUCTION_V1', ...
    'source',src,'backup',bak,'installed',true, ...
    'safety_theorem_modified',false,'deadline_modified',false);
assignin('base','AF7R33_INSTALL_R13C_PRODUCTION_OUT',OUT);
fprintf(' source                                  = %s\n',src);
fprintf(' backup                                  = %s\n',bak);
fprintf(' repeat-safe flat model installed        = 1\n');
fprintf(' all-obstacle episode batch installed    = 1\n');
fprintf(' batch corridor installed                = 1\n');
fprintf(' exact-QP native fast path installed     = 1\n');
fprintf(' whole-body batch authority installed    = 1\n');
fprintf(' legacy QP/whole-body fallbacks retained = 1\n');
fprintf(' safety/deadline thresholds modified     = 0\n');
fprintf('====================================================================================================\n');
end
