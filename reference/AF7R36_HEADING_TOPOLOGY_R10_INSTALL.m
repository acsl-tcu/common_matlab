function OUT = AF7R36_HEADING_TOPOLOGY_R10_INSTALL()
% AF7R36_HEADING_TOPOLOGY_R10_INSTALL
%
% Diagnostic only.
%
% R9B proved:
%   - production compact primary is C7 and hard-safe,
%   - the overly strong full-interval condition ||v_xy(t)||>0 fails.
%
% R10 localizes that failure without changing production:
%   1 = unresolved leaf touches t0 only
%   2 = unresolved leaf touches t1 only
%   3 = unresolved leaf is strictly interior
%   4 = unresolved leaves touch both endpoints
%
% It also records horizontal norms of derivatives 1..6 at the smallest
% unresolved leaf midpoint, plus exact endpoint horizontal speed norms.
%
% This is a topology diagnostic, not an acceptance certificate. It decides
% whether the next theory should be:
%   endpoint stop/hold extension, or
%   genuine PATH_TIME_SEPARATED redesign for an interior stop/singularity.
%
% No production selection/safety/smoothness semantics are modified.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 HEADING SINGULARITY TOPOLOGY R10 INSTALL\n');
fprintf(' production selection modified              = 0\n');
fprintf(' hard safety semantics modified             = 0\n');
fprintf(' C7 smoothness semantics modified            = 0\n');
fprintf(' heading failure topology localized          = 1\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir)&&isfolder(refDir), ...
    '[HEADTOPO-R10] Cannot resolve current reference directory.');

hpp=fullfile(refDir,'af7r36_core.hpp');
cpp=fullfile(refDir,'af7r36_single_core_mex.cpp');
assert(isfile(hpp),'[HEADTOPO-R10] Missing %s',hpp);
assert(isfile(cpp),'[HEADTOPO-R10] Missing %s',cpp);

hpp0=normlf(fileread(hpp));
cpp0=normlf(fileread(cpp));
hppNew=hpp0;cppNew=cpp0;

% Functional prerequisites, not cosmetic marker strings.
assert(contains(hpp0,'static inline bool c7r7_heading_regular') && ...
       contains(cpp0,'phr9_push(Q,Q7,R,L,t0,tm,searchEnd);') && ...
       contains(cpp0,'if(op==12){'), ...
    '[HEADTOPO-R10] R9B functional instrumentation is not installed.');
assert(~contains(hpp0,'AF7_HEADING_TOPOLOGY_R10'), ...
    '[HEADTOPO-R10] R10 core already installed.');
assert(~contains(cpp0,'AF7_HEADING_TOPOLOGY_R10_RING'), ...
    '[HEADTOPO-R10] R10 wrapper already installed.');

try
    %% --------------------------------------------------------------------
    % 1) Core topology diagnostic.
    % ---------------------------------------------------------------------
    anchor='static inline PlanResult plan(const ActiveReference&ref,const Live&L,const SpeedCert&base,';
    helper=[ ...
        '// AF7_HEADING_TOPOLOGY_R10' sprintf('\n') ...
        'struct HeadingTopoR10 {' sprintf('\n') ...
        '    bool strict_pass=false;' sprintf('\n') ...
        '    int location=0; // 0 pass, 1 t0, 2 t1, 3 interior, 4 both endpoints' sprintf('\n') ...
        '    double fail_t=NAN,fail_width=NAN,vxy=NAN,v0=NAN,v1=NAN;' sprintf('\n') ...
        '    std::array<double,6> hder{};' sprintf('\n') ...
        '    int unresolved=0,max_depth_hit=0;' sprintf('\n') ...
        '};' sprintf('\n') ...
        '' sprintf('\n') ...
        'static inline HeadingTopoR10 heading_topology_r10(' sprintf('\n') ...
        '        const ActiveReference&ref,const Candidate&C,const SpeedCert&s,double ta,double tb){' sprintf('\n') ...
        '    HeadingTopoR10 R;' sprintf('\n') ...
        '    if(!(s.certified&&fin(s.A)&&s.A>=0&&fin(ta)&&fin(tb)&&tb>ta))return R;' sprintf('\n') ...
        '    auto xa=candidate_eval(ref,C,ta),xb=candidate_eval(ref,C,tb);' sprintf('\n') ...
        '    R.v0=std::hypot(xa[1].x,xa[1].y);R.v1=std::hypot(xb[1].x,xb[1].y);' sprintf('\n') ...
        '    struct Leaf{double a,b;int d;bool lt,rt;};' sprintf('\n') ...
        '    std::vector<Leaf>st;st.push_back({ta,tb,0,true,true});' sprintf('\n') ...
        '    const int maxDepth=52;bool hitL=false,hitR=false,hitI=false;' sprintf('\n') ...
        '    double bestW=std::numeric_limits<double>::infinity();' sprintf('\n') ...
        '    while(!st.empty()){' sprintf('\n') ...
        '        Leaf f=st.back();st.pop_back();double tc=0.5*(f.a+f.b),h=0.5*(f.b-f.a);' sprintf('\n') ...
        '        if(!(tc>f.a&&tc<f.b)){++R.unresolved;if(f.lt)hitL=true;if(f.rt)hitR=true;if(!f.lt&&!f.rt)hitI=true;continue;}' sprintf('\n') ...
        '        auto x=candidate_eval(ref,C,tc);double v=std::hypot(x[1].x,x[1].y);' sprintf('\n') ...
        '        double lb=v-s.A*h;' sprintf('\n') ...
        '        if(fin(lb)&&lb>0)continue;' sprintf('\n') ...
        '        if(f.d>=maxDepth){' sprintf('\n') ...
        '            ++R.unresolved;++R.max_depth_hit;' sprintf('\n') ...
        '            if(f.lt)hitL=true;if(f.rt)hitR=true;if(!f.lt&&!f.rt)hitI=true;' sprintf('\n') ...
        '            double w=f.b-f.a;if(w<bestW){' sprintf('\n') ...
        '                bestW=w;R.fail_t=tc;R.fail_width=w;R.vxy=v;' sprintf('\n') ...
        '                for(int k=1;k<=6;++k)R.hder[k-1]=std::hypot(x[k].x,x[k].y);' sprintf('\n') ...
        '            }' sprintf('\n') ...
        '            continue;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '        st.push_back({tc,f.b,f.d+1,false,f.rt});' sprintf('\n') ...
        '        st.push_back({f.a,tc,f.d+1,f.lt,false});' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '    if(R.unresolved==0){R.strict_pass=true;R.location=0;return R;}' sprintf('\n') ...
        '    if(hitI)R.location=3;' sprintf('\n') ...
        '    else if(hitL&&hitR)R.location=4;' sprintf('\n') ...
        '    else if(hitL)R.location=1;' sprintf('\n') ...
        '    else if(hitR)R.location=2;' sprintf('\n') ...
        '    else R.location=3;' sprintf('\n') ...
        '    return R;' sprintf('\n') ...
        '}' sprintf('\n') ...
        '' sprintf('\n') ...
        anchor];
    hppNew=replace_once(hppNew,anchor,helper,'pre-plan topology helper');

    %% --------------------------------------------------------------------
    % 2) Wrapper ring.
    % ---------------------------------------------------------------------
    anchor='static bool G_compiled=false;';
    ring=[anchor sprintf('\n') sprintf('\n') ...
        '// AF7_HEADING_TOPOLOGY_R10_RING -- diagnostic only.' sprintf('\n') ...
        'struct HeadTopoMexR10 {' sprintf('\n') ...
        '    double seq=0,t0=NAN,tm=NAN,t1=NAN,ok=0,family=0,strict=0,loc=0;' sprintf('\n') ...
        '    double fail_t=NAN,width=NAN,vxy=NAN,v0=NAN,v1=NAN;' sprintf('\n') ...
        '    double d1=NAN,d2=NAN,d3=NAN,d4=NAN,d5=NAN,d6=NAN,unresolved=0,depthhit=0;' sprintf('\n') ...
        '};' sprintf('\n') ...
        'static std::vector<HeadTopoMexR10> G_headtopo10;' sprintf('\n') ...
        'static double G_headtopo10_seq=0;' sprintf('\n') ...
        'static void headtopo10_push(const PlanResult&P,const ActiveReference&ref,double t0,double tm,double t1){' sprintf('\n') ...
        '    HeadTopoMexR10 d;d.seq=++G_headtopo10_seq;d.t0=t0;d.tm=tm;d.t1=t1;d.ok=P.success?1:0;' sprintf('\n') ...
        '    if(P.success){' sprintf('\n') ...
        '        d.family=P.cand.family;auto H=heading_topology_r10(ref,P.cand,P.speed,t0,t1);' sprintf('\n') ...
        '        d.strict=H.strict_pass?1:0;d.loc=H.location;d.fail_t=H.fail_t;d.width=H.fail_width;d.vxy=H.vxy;d.v0=H.v0;d.v1=H.v1;' sprintf('\n') ...
        '        d.d1=H.hder[0];d.d2=H.hder[1];d.d3=H.hder[2];d.d4=H.hder[3];d.d5=H.hder[4];d.d6=H.hder[5];' sprintf('\n') ...
        '        d.unresolved=H.unresolved;d.depthhit=H.max_depth_hit;' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '    if(G_headtopo10.size()>=512)G_headtopo10.erase(G_headtopo10.begin());G_headtopo10.push_back(d);' sprintf('\n') ...
        '}' sprintf('\n') ...
        'static mxArray* headtopo10_matrix(){' sprintf('\n') ...
        '    const mwSize N=(mwSize)G_headtopo10.size(),C=21;mxArray*M=mxCreateDoubleMatrix(N,C,mxREAL);double*p=mxGetPr(M);' sprintf('\n') ...
        '    for(mwSize i=0;i<N;++i){const auto&d=G_headtopo10[i];double v[C]={' sprintf('\n') ...
        '        d.seq,d.t0,d.tm,d.t1,d.ok,d.family,d.strict,d.loc,d.fail_t,d.width,d.vxy,d.v0,d.v1,' sprintf('\n') ...
        '        d.d1,d.d2,d.d3,d.d4,d.d5,d.d6,d.unresolved,d.depthhit};' sprintf('\n') ...
        '        for(mwSize j=0;j<C;++j)p[i+N*j]=v[j];' sprintf('\n') ...
        '    }return M;' sprintf('\n') ...
        '}'];
    cppNew=replace_once(cppNew,anchor,ring,'R10 wrapper ring');

    %% --------------------------------------------------------------------
    % 3) Record after R9B/R7 diagnostic rows. Production is already fixed.
    % ---------------------------------------------------------------------
    anchor='            phr9_push(Q,Q7,R,L,t0,tm,searchEnd);';
    new=[anchor sprintf('\n') ...
        '            headtopo10_push(Q,R,t0,tm,searchEnd);'];
    cppNew=replace_once(cppNew,anchor,new,'R10 per-call append');

    %% --------------------------------------------------------------------
    % 4) op14 read, op15 clear.
    % ---------------------------------------------------------------------
    anchor='        if(op==3){';
    ops=[ ...
        '        if(op==14){' sprintf('\n') ...
        '            if(nrhs!=1||nlhs!=1)mexErrMsgIdAndTxt("AF7HEADTOPO10:Arity","op14 -> matrix.");' sprintf('\n') ...
        '            plhs[0]=headtopo10_matrix();return;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '        if(op==15){' sprintf('\n') ...
        '            if(nrhs!=1||nlhs>1)mexErrMsgIdAndTxt("AF7HEADTOPO10:Arity","op15 clear.");' sprintf('\n') ...
        '            G_headtopo10.clear();G_headtopo10_seq=0;if(nlhs>0)plhs[0]=logicalScalar(true);return;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        anchor];
    cppNew=replace_once(cppNew,anchor,ops,'R10 diagnostic ops');

    %% --------------------------------------------------------------------
    % 5) Audits.
    % ---------------------------------------------------------------------
    assert(contains(cppNew, ...
        'static const char* PLANNER_REV="AF7_REPLANNER_MIN_DEVIATION_V4_FIXED_T1";'), ...
        '[HEADTOPO-R10] Planner identity changed unexpectedly.');
    assert(count_exact(hppNew,'AF7_HEADING_TOPOLOGY_R10')==1, ...
        '[HEADTOPO-R10] Core marker count invalid.');
    assert(count_exact(cppNew,'AF7_HEADING_TOPOLOGY_R10_RING')==1, ...
        '[HEADTOPO-R10] Wrapper marker count invalid.');
    assert(count_exact(cppNew,'headtopo10_push(Q,R,t0,tm,searchEnd);')==1, ...
        '[HEADTOPO-R10] Per-call topology hook count invalid.');

    %% --------------------------------------------------------------------
    % 6) Stage compile.
    % ---------------------------------------------------------------------
    stageDir=tempname;
    [ok,msg]=mkdir(stageDir);
    assert(ok,'[HEADTOPO-R10] Cannot create staging directory: %s',msg);
    stageCleanup=onCleanup(@()cleanup_stage(stageDir)); %#ok<NASGU>

    stagedHpp=fullfile(stageDir,'af7r36_core.hpp');
    stagedCpp=fullfile(stageDir,'af7r36_single_core_mex.cpp');
    write_text(stagedHpp,hppNew);write_text(stagedCpp,cppNew);

    fprintf('[HEADTOPO-R10] Compiling staged diagnostic MEX...\n');
    oldDir=pwd;
    cwdCleanup=onCleanup(@()cd(oldDir)); %#ok<NASGU>
    cd(stageDir);clear mex;
    mex('-R2018a','-O', ...
        'COMPFLAGS="$COMPFLAGS /std:c++17"', ...
        ['-I' stageDir], ...
        '-output','af7r36_single_core_mex', ...
        '-outdir',stageDir, ...
        stagedCpp);

    stagedMex=fullfile(stageDir,['af7r36_single_core_mex.' mexext]);
    assert(isfile(stagedMex),'[HEADTOPO-R10] Staged MEX missing.');

    dstMex=fullfile(refDir,['af7r36_single_core_mex.' mexext]);
    oldMexTmp=fullfile(stageDir,['af7r36_single_core_mex_OLD.' mexext]);
    hadOldMex=isfile(dstMex);
    if hadOldMex
        [ok,msg]=copyfile(dstMex,oldMexTmp,'f');
        assert(ok,'[HEADTOPO-R10] Cannot stage rollback MEX: %s',msg);
    end

    cd(oldDir);clear mex;
    wroteH=false;wroteC=false;installedMex=false;
    try
        write_text(hpp,hppNew);wroteH=true;
        write_text(cpp,cppNew);wroteC=true;
        [ok,msg]=copyfile(stagedMex,dstMex,'f');
        assert(ok,'[HEADTOPO-R10] Cannot install staged MEX: %s',msg);
        installedMex=true;
        clear mex;rehash;
        assert(exist('af7r36_single_core_mex','file')==3, ...
            '[HEADTOPO-R10] Installed MEX not visible.');
        try,af7r36_single_core_mex(7);catch,end
        try,af7r36_single_core_mex(11);catch,end
        try,af7r36_single_core_mex(13);catch,end
        af7r36_single_core_mex(15);
    catch ME2
        if wroteH,try,write_text(hpp,hpp0);catch,end,end
        if wroteC,try,write_text(cpp,cpp0);catch,end,end
        if installedMex&&hadOldMex,try,copyfile(oldMexTmp,dstMex,'f');catch,end,end
        clear mex;rehash;rethrow(ME2);
    end

    fprintf('[HEADTOPO-R10] PASS.\n');
    fprintf('  production selection unchanged             = 1\n');
    fprintf('  safety/C7 semantics unchanged              = 1\n');
    fprintf('  heading unresolved topology ring installed = 1\n');
    fprintf('  README created                              = 0\n');
    fprintf('  persistent backup files created             = 0\n');

    OUT=struct('pass',true, ...
        'revision','AF7_HEADING_TOPOLOGY_R10', ...
        'production_selection_modified',false, ...
        'hard_safety_modified',false, ...
        'C7_modified',false);

catch ME
    clear mex;rehash;
    fprintf(2,'[HEADTOPO-R10] FAILED. No successful production install completed.\n');
    rethrow(ME);
end
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1, ...
    '[HEADTOPO-R10] Anchor "%s" count=%d; expected 1.',label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end

function n=count_exact(txt,pat)
n=numel(strfind(txt,pat));
end

function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));
s=strrep(s,sprintf('\r'),sprintf('\n'));
end

function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');
assert(f>=0,'[HEADTOPO-R10] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end

function cleanup_stage(d)
if isfolder(d)
    try,rmdir(d,'s');catch,end
end
end
