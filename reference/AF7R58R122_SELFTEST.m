function T=AF7R58R122_SELFTEST()
% Algebraic adapter tests only. No live Flight and no safety claim.
L=1.8;T0=2;tg=4;
fs=cell(1,8);
for r=0:7
    order=r;
    fs{r+1}=@(t)r122_poly_derivative(t,order);
end
J=AF7R58R122_NOMINAL_PAYLOAD_JETS(fs,T0,L,tg);
assert(isequal(size(J),[3 8]) && ...
    J(3,1)==3-L && J(3,2)==0 && J(3,8)==0 && ...
    J(1,8)==factorial(7) && J(2,2)==2, ...
    'R122:NominalTestFailed', 'Source derivatives or z-only offset wrong.');
% Degree-15 representation of an affine payload motion on [5,7].
seg=struct();seg.t0=5;seg.t1=7;seg.duration_s=2;
seg.trajectory_frame='HLC_PAYLOAD_WORLD';
a=[1;2;3];v=[2;0.5;-0.3];
seg.payload_cp=zeros(3,16);
for j=0:15
    seg.payload_cp(:,j+1)=a+(j/15)*seg.duration_s*v;
end
H=AF7R58R118_HEADING_C6_CERT(seg,64);
assert(H.certified,'R122:HeadingTestFailed', ...
    'Nonzero constant planar velocity should certify.');
R=AF7R58R122_C7_TO_RAW_XD28(seg,6,L,atan2(v(2),v(1)));
x=R.raw_xd28;
assert(isequal(size(x),[28 1])&& ...
    abs(x(1)-(a(1)+v(1)))<1e-12 && ...
    abs(x(2)-(a(2)+v(2)))<1e-12 && ...
    abs(x(3)-(a(3)+v(3)+L))<1e-12 && ...
    abs(x(7)-v(3))<1e-12 && ...
    abs(x(4)-atan2(v(2),v(1)))<1e-12 && ...
    norm(x(9:28))<1e-11 && ...
    norm(R.payload_jets07(:,8))<1e-11 && ...
    isequal(R.production_commit_authorized,false), ...
    'R122:RawPacketTestFailed', ...
    'HLC width, derivative slots or SLOAD altitude conversion incorrect.');
% Curved reference: x=t-5, y=(t-5)^2/2, so yaw'(5)=1 rad/s.
curve=seg;curve.payload_cp=zeros(3,16);
for j=0:15
    curve.payload_cp(:,j+1)=[2*j/15; ...
        2*j*(j-1)/(15*14);2];
end
HC=AF7R58R118_HEADING_C6_CERT(curve,64);
assert(HC.certified,'R122:CurveHeadingCertFailed', ...
    'Positive x velocity must certify entire curved interval.');
RC=AF7R58R122_C7_TO_RAW_XD28(curve,5,L,0);
assert(abs(RC.raw_xd28(4))<1e-12 && ...
    abs(RC.raw_xd28(8)-1)<1e-10 && ...
    abs(RC.raw_xd28(3)-(2+L))<1e-12, ...
    'R122:YawJetIndexing','Curved tangent yaw derivative must occupy slot 8.');
% An inappropriate 32-vector must NOT be generated as the HLC command.
% A nonexistent/invalid externally authoritative cable length is rejected.
rejected=false;
try
    AF7R58R122_C7_TO_RAW_XD28(seg,6,NaN,0);
catch ME
    rejected=strcmp(ME.identifier,'R122:LiveCableLRequired');
end
assert(rejected,'R122:MissingAuthorityNotRejected', ...
    'Missing runtime cable length must fail closed.');
T=struct('status','PASS_R122_C7_INTERNAL_VS_28_HLC_BRIDGE_ALGEBRA', ...
    'nominal_position_7th_Jx',J(1,8), ...
    'hlc_packet_width',numel(x),'hlc_packet_z_pre_adjust',x(3), ...
    'hlc_packet_z_post_adjust',R.payload_height_after_sload_m, ...
    'source_seventh_exact_fn_tested',true, ...
    'whole_body_safe_proved',false,'flight_installed',false, ...
    'real_hlc_called',false);
fprintf('[R122] %s\n',T.status);
end
function D=r122_poly_derivative(t,r)
if r>7 || r<0,error('R122:BadDerivative');end
D=zeros(3,1);
D(1)=factorial(7)/factorial(7-r)*t^(7-r);
if r==0
    D(2)=2*t+1;D(3)=3;
elseif r==1
    D(2)=2;
end
end
