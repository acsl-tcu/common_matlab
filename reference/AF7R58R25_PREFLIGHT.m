function Q = AF7R58R25_PREFLIGHT()
% Research-only: source sanity check; does not claim runtime certificate.
source=which('REPLANNING_SYSTEM');
assert(~isempty(source),'[R25] REPLANNING_SYSTEM not found.');
src=fileread(source);
assert(contains(src,'r25_event_capture_valid = false;') && ...
    contains(src,'function r25_publish_capture(obj)') && ...
    contains(src,'obj.r25_event_capture=D;'), ...
    '[R25] REPLANNING_SYSTEM missing event-buffer implementation.');
assert(~contains(src,'setappdata(0,key,D);'), ...
    '[R25] Old per-event setappdata still in R17 capture.');
assert(contains(src,'ENABLE_AF7R58R17_DIAG_CONTINUE_LATE = 1;'), ...
    '[R25] Expected research-only diagnostics not preconfigured.');
assert(contains(src,"AVOIDANCE_COMMIT_POLICY      = 'REFERENCE_ONLY'"), ...
    '[R25] Expected diagnostic-only commit policy changed.');
runner=which('run_flight_headless');
if isempty(runner),runner=fullfile(fileparts(fileparts(source)),'run_flight_headless.m');end
assert(isfile(runner),'[R25] Runner not found.');
txt=fileread(runner);
assert(contains(txt,'% AF7R58R25_LOGGER_INSTALLED') && ...
    contains(txt,'replanner_instance.r25_publish_capture();'), ...
    '[R25] Logger patch not installed.');
Q=struct('source',source,'runner',runner,'diagnostic_only',true, ...
    'logger_fields_enabled',true,'post_flight_flush',true, ...
    'mex_rebuild_required',false,'commit_allowed',false, ...
    'simulator_tested',false);
fprintf('[R25] PREFLIGHT SOURCE CHECK PASS | LOGGER + buffered events | NO COMMIT\n');
end
