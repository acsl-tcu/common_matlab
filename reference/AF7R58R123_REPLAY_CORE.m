function R=AF7R58R123_REPLAY_CORE(opts)
% End-to-end real source rehearsal OUTSIDE Flight.do(); never commits.
% Physical R71 event is frozen at its true EKF time; planning 0..7 jets
% are bound only if the CURRENT active reference VERSION matches event.
% Old trigger/generator are NEVER invoked here. Execution cert remains open.
if nargin<1,opts=struct();end
assert(isstruct(opts)&&isscalar(opts),'R123:OptionsStructRequired');
D=fileparts(mfilename('fullpath'));
R=struct('status','STARTED','error_identifier','', ...
    'error_message','','event_time_s',NaN,'reference_version',NaN, ...
    'physical',struct([]),'planning',struct([]), ...
    'actual_same_event_route_found',false, ...
    'all_required_authorities_bound',false, ...
    'source_version_matched',false, ...
    'physical_interval_certificate_closed',false, ...
    'return_tail_certified',false, ...
    'native_atomic_packet_available',false, ...
    'production_commit_authorized',false, ...
    'old_trigger_called',false,'old_generator_called',false, ...
    'source_code_version','R123_REAL_EVENT_REHEARSAL_V1');
try
    stack=dbstack;
    assert(~any(strcmp({stack.name},'REPLANNING_SYSTEM.do')), ...
        'R123:NotInFlightControlCallback','Postflight rehearsal only.');
    O=AF7R58R74_REGISTRY('get');
    assert(isa(O,'REPLANNING_SYSTEM')&&isscalar(O) && ...
        isstruct(O.r71r2_event_snapshots)&&~isempty(O.r71r2_event_snapshots), ...
        'R123:FrozenFlightEventsNotFound', ...
        'Run this in the SAME MATLAB session after a Flight with R71 event capture.');
    C=O.r71r2_event_snapshots;
    if isfield(opts,'event_index')
        j=double(opts.event_index);
    else
        j=numel(C);
    end
    assert(isscalar(j)&&isfinite(j)&&j==fix(j)&&j>=1&&j<=numel(C), ...
        'R123:InvalidCapturedEventIndex');
    E=C(j);R.event_time_s=double(E.time_s);
    R.reference_version=double(E.reference_version);
    R.physical=AF7R58R123_FROZEN_PHYSICAL_TRIGGER(E);
    R.physical_interval_certificate_closed= ...
        logical(R.physical.physical_clearance_certified);
    % NEVER use a present-day active source to invent the old historical
    % state of a DIFFERENT reference version.
    if double(O.active_reference_version)~=double(E.reference_version)
        R.status='PHYSICAL_REPLAY_DONE__HISTORICAL_ACTIVE_C7_VERSION_DIFFERS';
        return;
    end
    R.source_version_matched=true;
    % Native Stage1 targets atomic activation TWO prediction periods later.
    % This does not reuse the 4-s trigger H as the avoidance duration.
    activationTime=double(E.time_s)+2*double(E.prediction_dt);
    B=AF7R58R122_BIND_LIVE_C7(O,activationTime);
    assert(double(B.reference_version)==double(E.reference_version), ...
        'R123:PlannerSourceVersionChanged');
    Q=AF7R58R123_EVENT_OBSTACLES(E);
    if isempty(Q.obstacles)
        R.status='PHYSICAL_REPLAY_DONE__NO_SENSOR_KNOWN_PLANNING_TARGET';
        return;
    end
    % A vehicle mass/command authority read after Flight cannot be silently
    % substituted for its historical value. Only the frozen event mass can
    % be used for the event's payload mass.
    [I,stat]=AF7R58R102_LIVE_INPUT_AUTHORITY(O,[]);
    if ~stat.input_authorities_available
        R.status=['BLOCKED_ACTUATOR_AUTHORITY__' char(stat.status)];return;
    end
    order=string(E.parameter_order(:));values=double(E.external_param(:));
    kMass=find(strcmpi(order,'mass'));
    if numel(kMass)~=1 || ~isfinite(values(kMass)) || ...
       abs(double(I.vehicle_mass_kg)-values(kMass))> ...
          4096*eps(max([1,abs(values(kMass)),abs(I.vehicle_mass_kg)]))
       R.status='BLOCKED_EVENT_VEHICLE_MASS_AND_CURRENT_MISMATCH';return;
    end
    % Actual command limits/gains must remain unchanged since capture.
    if ~isequaln(O.self.controller.hlc_suspended.param, E.controller_param)
        R.status='BLOCKED_HISTORICAL_HLC_GAIN_MISMATCH';return;
    end
    L=double(E.cable_length_m);
    assert(L==B.live_cable_length_m && ...
        isfinite(E.horizon_s)&&isfinite(E.prediction_dt) && ...
        E.horizon_s>0&&E.prediction_dt>0, ...
        'R123:CurrentCableOrHorizonAuthorityMismatch');
    g=double(O.gravity);
    % No historical sensor-range fallback. A caller must bind the actual
    % event parameter explicitly, because the current O.trigger_dist may
    % have changed since this frozen R71 event.
    if ~isfield(opts,'event_sensor_range_m')
        R.status='BLOCKED_HISTORICAL_SENSOR_RANGE_AUTHORITY_REQUIRED';return;
    end
    sensorRange=double(opts.event_sensor_range_m);
    rho=max([double(E.r76_radii_m(1)), ...
        L+double(E.r76_radii_m(3)),L+double(E.r76_radii_m(2))]);
    vq=(sensorRange-rho)/(double(E.horizon_s)+double(E.prediction_dt));
    assert(all(isfinite([g;sensorRange;vq]))&&g>0&&vq>0, ...
        'R123:FiniteSensingAuthorityInvalid');
    V=struct('gravity_m_s2',g,'cable_length_m',L, ...
        'latest_EKF_mL_kg',double(E.estimated_mass_kg), ...
        'vehicle_mass_kg',double(I.vehicle_mass_kg), ...
        'thrust_bounds_N',I.thrust_bounds_N, ...
        'torque_bounds_Nm',I.torque_bounds_Nm, ...
        'finite_sensing_vQ_limit_m_s',vq);
    if isfield(opts,'work')
        W=opts.work;
    else
        % Internal solver work limits only; NEVER a physical duration cap.
        W=struct('duration_trials',6,'branch_assignments',6, ...
            'corridor_nodes',256,'qp_iterations',250, ...
            'certificate_nodes',512);
    end
    if isfield(opts,'duration_scale_s')
        scale=double(opts.duration_scale_s);
    else
        scale=sqrt(L/g); % physical cable natural time, not 4-s trigger.
    end
    A=struct('t0_s',activationTime, ...
        'reference_version',double(E.reference_version), ...
        'initial_reference_jets07',B.initial_reference_jets07, ...
        'nominal_phase_start_s',B.nominal_phase_start_s, ...
        'nominal_jets07_fn',B.nominal_jets07_fn, ...
        'obs',Q.obstacles,'live',V,'radii_m',Q.radii_m, ...
        'work',W,'duration_scale_s',scale);
    R.all_required_authorities_bound=true;
    G=AF7R58R121_WHOLEBODY_PLANNER(A);
    R.planning=struct('status',G.status,'attempts',G.attempts, ...
        'activation_time_s',activationTime, ...
        'reference_candidate_found',G.reference_candidate_found, ...
        'position_c7',G.position_c7,'yaw_c6',G.yaw_c6, ...
        'continuous_uav_cable_payload',G.continuous_uav_cable_payload, ...
        'full_finite_tail_reference_certified',G.full_finite_tail_reference_certified, ...
        'duration_s',G.selected_duration_s, ...
        'nominal_phase_end_s',G.nominal_phase_end_s, ...
        'nominal_time_shift_s',G.nominal_time_shift_s, ...
        'segment_count',numel(G.route));
    if G.reference_candidate_found
        R.actual_same_event_route_found=true;
        R.planning.segment_count=numel(G.route.segments);
        R.planning.first_segment=G.route.segments(1);
        R.planning.activation_seam=AF7R58R123_ACTIVATION_SEAM( ...
            O,G.route,E.reference_version,activationTime);
        if ~R.planning.activation_seam.certified
            R.actual_same_event_route_found=false;
            R.status='BLOCKED_PROPOSED_C7_ACTIVATION_SEAM';return;
        end
        R.planning.route_certificate=G.certificate;
        % Internal C7 -> unmodified legacy HLC 28 packet: no fake native
        % stage-3 candidate or fabricated execution certificate.
        Y=AF7R58R122_C7_TO_RAW_XD28( ...
            G.route.segments(1),activationTime,L, ...
            atan2(B.initial_reference_jets07(2,2), ...
                  B.initial_reference_jets07(1,2)));
        R.planning.first_raw_xd28=Y.raw_xd28;
    end
    if R.actual_same_event_route_found
        R.status='REAL_EVENT_C7_CONNECTOR_AND_HLC28__TAIL_EXECUTION_NOT_CERTIFIED';
    else
        R.status=['REAL_EVENT_PLANNER_INCONCLUSIVE__' char(G.status)];
    end
catch ME
    R.status='FAIL_CLOSED_INTEGRATION_REHEARSAL';
    R.error_identifier=char(ME.identifier);
    R.error_message=char(ME.message);
end
end
