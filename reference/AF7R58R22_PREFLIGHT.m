function Q=AF7R58R22_PREFLIGHT()
% Independent R22 source-bound read-only preflight. No setting changes.
source=which('REPLANNING_SYSTEM');
assert(~isempty(source),'[R22] REPLANNING_SYSTEM is not on MATLAB path.');
folder=fileparts(source);
header=fullfile(folder,'af7r36_core.hpp');
cpp=fullfile(folder,'af7r36_single_core_mex.cpp');
assert(isfile(header) && isfile(cpp),'[R22] Required C++ sources missing.');
S=fileread(source);
H=fileread(header);
assert(contains(S,'r22_shared_native_eval_packet') && ...
    contains(S,'r22_stage2_native_eval_ms') && ...
    contains(S,'obj.r22_stage2_cache_ms=1e3*toc(r22_cache_tic)'), ...
    '[R22] Source missing shared exact-eval-packet or timing profile.');
assert(contains(H,'r58r22_lowjet_hessian_direct') && ...
    contains(H,'r58r22_scalar_hessian') && ...
    contains(H,'r58r22_lowjet_hessian_direct(K58,L.L,L.g,EL58,lowJetIndices58)'), ...
    '[R22] Direct Hessian source missing.');
assert(contains(S,'ENABLE_AF7R58R17_DIAG_CONTINUE_LATE = 1;') && ...
    contains(S,"AVOIDANCE_COMMIT_POLICY      = 'REFERENCE_ONLY'"), ...
    '[R22] Expected no-commit diagnostic settings are missing.');
assert(exist('AF7R58R22_AUTO_RESULT','file')==2, ...
    '[R22] R22 result reporter not found.');
assert(exist('AF7R58R21_AUTO_RESULT','file')==2 && ...
    exist('AF7R58R20_AUTO_RESULT','file')==2, ...
    '[R22] R20/R21 report dependencies missing.');
mexPath=which('af7r36_single_core_mex');
assert(~isempty(mexPath) && exist('af7r36_single_core_mex','file')==3, ...
    '[R22] MEX binary missing; compile using /std:c++17.');
Q=struct('source',source,'native_mex',mexPath, ...
    'r22_source_revision','R22_DIRECT_LOWJET_HESSIAN_SHARED_PACKET', ...
    'diagnostic_only',true, ...
    'reference_activation_forbidden',true, ...
    'deadline_bypass_stages1_2',true, ...
    'deadline_unchanged_in_normal_mode',true, ...
    'mex_rebuild_required',true);
fprintf('AF7R58R22 PREFLIGHT PASS | NO COMMIT | DIAGNOSTIC ONLY\n');
end
