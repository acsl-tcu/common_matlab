function OUT = AF7R53_DEEP_AUDIT
assert(evalin('base','exist(''D38'',''var'')==1'), ...
    'Run: D38 = AF7R38_SPEED_ROOTCAUSE_AUDIT; first.');
D38=evalin('base','D38');
P=D38.pipeline;

fprintf('\n====================================================================================================\n');
fprintf(' AF7R53 | MOVING-NORMAL GENERAL-C7 + DEEP HARD-GATE AUDIT\n');
fprintf('====================================================================================================\n');

F={ ...
 'predeadline_candidate_success','predeadline_candidate_family', ...
 'predeadline_payload_speed','predeadline_uav_speed','predeadline_qdot', ...
 'r37_side_assignments','r37_spatial_qp_solutions','r37_exact_c7_candidates', ...
 'r37_best_total_velocity_ub','r37_best_accel_ub','r37_best_jerk_ub', ...
 'r51_phase_alpha','r51_phase_delay_s','r51_phase_exit_time_s', ...
 'r52_phase_episode_count','r52_corridor_row_count', ...
 'r52_spatial_qp_solution_count','r52_rejoin_time_trial_count', ...
 'r52_selected_spatial_rejoin_s', ...
 'r53_normal_bundle_node_count','r53_normal_bundle_row_count', ...
 'r53_normal_bundle_singular_count','r53_affine_reduction_count', ...
 'r24e_family_speed_pass','r24e_family_speed_fail', ...
 'r35_heading_candidate_count','r35_heading_pass_count','r35_heading_reject_count', ...
 'native_episode_ms','native_hessian_ms','native_corridor_ms','native_qp_ms', ...
 'native_candidate_build_ms','native_total_ms','last_stage1_ms'};

for k=1:numel(F)
    f=F{k};
    if isfield(P,f)
        v=P.(f);
        if isnumeric(v)||islogical(v)
            if isscalar(v)
                fprintf('%-60s = %.17g\n',f,double(v));
            else
                fprintf('%-60s = %s\n',f,mat2str(double(v),17));
            end
        else
            fprintf('%-60s = %s\n',f,char(string(v)));
        end
    else
        fprintf('%-60s = <NOT EXPOSED>\n',f);
    end
end

fprintf('\n[PER-CANDIDATE HARD GATES]\n');
M=af7r36_single_core_mex(20);
if isempty(M)
    fprintf(' diagnostic matrix is EMPTY\n');
    T=table();
else
    names={ ...
    'seq','family','exact_c7','max_ctrl_m','corr_vel_ub','corr_acc_ub','corr_jerk_ub', ...
    'phase_alpha','phase_delay_s','actual_rejoin_s', ...
    'VQ_limit','base_VL','base_A','base_J','base_sigma', ...
    'stageA_Uv','stageA_Ua','stageA_Uj','stageA_sigma','stageA_VQ', ...
    'stageA_cert','stageA_impossible','stageA_repr', ...
    'stageB_attempt','stageB_result','stageB_leaves','stageB_splits', ...
    'stageB_worst_VQ','stageB_worst_t','stageB_worst_seg','stageB_worst_VL', ...
    'stageB_worst_sigma','stageB_worst_qdot','stageB_worst_witness', ...
    'speed_pass','heading_attempt','heading_pass','heading_reason', ...
    'heading_min_g0','heading_min_lb','heading_leaves','heading_splits','heading_gamma', ...
    'rejoin_attempt','rejoin_pass','geometry_attempt','geometry_pass','geometry_min_margin','reserved'};
    assert(size(M,2)==numel(names),'[AF7R53] unexpected diagnostic matrix width.');
    T=array2table(M,'VariableNames',names);
    disp(T);
    fprintf(' candidates=%d | speed pass=%d | heading pass=%d | rejoin pass=%d | geometry pass=%d\n', ...
        height(T),sum(T.speed_pass==1),sum(T.heading_pass==1), ...
        sum(T.rejoin_pass==1),sum(T.geometry_pass==1));
end

fprintf('\nContract:\n');
fprintf(' - phase is the sole longitudinal/progress variable.\n');
fprintf(' - spatial correction uses the moving normal bundle of the actual C7 active reference.\n');
fprintf(' - affine reference reduces to historical R45/R47 e_perp semantics.\n');
fprintf(' - no alternative trajectory-family fallback; all hard certificates unchanged.\n');
fprintf('====================================================================================================\n');

OUT=struct('pipeline',P,'candidates',T);
assignin('base','R53A',OUT);
end
