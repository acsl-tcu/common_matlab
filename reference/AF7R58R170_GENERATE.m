function G=AF7R58R170_GENERATE(routes,packet,speedCert,sourceObstacles,jets,options)
% R170 directional-cable construction + yaw guarded research generator. ALL supplied topological corridor routes,
% not a fixed side/altitude, are considered BEFORE route selection.
% Runtime mL must come from AF7R58R166_LIVE_PACKET on EACH EKF update.
% No fallback to saved Flight mass, no nominal-only trigger authority.
% REQUIRE valid current start/end derivative jets 0..7 from system.
% Stage 1: initial C7 seed from route knots and SAME-EKF event jets;
% Stage 2: physics-derived derivative budgets + 3D corridor-QP;
% Stage 3: coupled taut wholebody/force/tension/source support guard.
% Unknown/torque/yaw/tail/observer tube => NEVER production commit.
G=struct('status','UNKNOWN_MISSING_LIVE_AUTHORITY_OR_JETS',...
 'routes_considered',0,'qp_success_count',0,'conditional_shortlist_count',0,...
 'selected_index',NaN,'selected_duration_s',NaN,'selected_route',struct(),...
 'trials',[],'production_commit_authorized',false,...
 'full_execution_certified',false,'torque_yaw_tail_certified',false);
if nargin<6||isempty(options),options=struct();end
if ~isfield(options,'max_trials'),options.max_trials=4;end
if ~isfield(options,'robust_tube_on'),options.robust_tube_on=true;end
if ~isfield(options,'duration_seed_s')||...
 ~isfield(options,'current_tick_time_s'),return;end
% Do not silently use a global obstacle map, future or occluded objects.
% Sensor handler must validate the supplied observed-only set at this event.
if ~isfield(options,'observed_only_sensor_set_validated')||...
 ~isequal(options.observed_only_sensor_set_validated,true),return;end
if ~isstruct(packet)||~isscalar(packet)||...
 ~isfield(packet,'live_physical_parameters_valid')||...
 ~isequal(packet.live_physical_parameters_valid,true)||...
 ~isfield(packet,'t_s')||~isscalar(packet.t_s)||~isfinite(packet.t_s)||...
 ~isstruct(speedCert)||~isscalar(speedCert)||...
 ~all(isfield(speedCert,{'source_time_s','VQ_limit_mps','bound_derived_from_live_sensing'}))||...
 ~isequal(speedCert.bound_derived_from_live_sensing,true)||...
 ~isequal(double(speedCert.source_time_s),double(packet.t_s))||...
 ~isfield(packet,'origin')||~strcmp(char(packet.origin),'CURRENT_EKF_STATE')||...
 ~isequal(double(options.current_tick_time_s),double(packet.t_s))||...
 ~isstruct(sourceObstacles)||isempty(sourceObstacles)||...
 ~isstruct(jets)||~isstruct(routes)||...
 ~isscalar(options.max_trials)||options.max_trials<1||...
 fix(options.max_trials)~=options.max_trials,return;end
n=numel(routes);T0=double(options.duration_seed_s);
if ~isfinite(T0)||~isscalar(T0)||T0<=0||...
 numel(jets)~=n,return;end
item=struct('route_index',0,'time_scale',NaN,'duration_s',NaN,...
 'budget_status','','qp_status','','physics_status','',...
 'qp_pass',false,'physical_reference_conditional',false,...
 'yaw_status','NOT_EVALUATED','fullbody_inner_status','NOT_EVALUATED');
logs=repmat(item,1,0);
G.routes_considered=n;
for r=1:n
 route=routes(r);j=jets(r);
 if ~all(isfield(j,{'source_time_s','start_jet','end_jet',...
 'source_current_ekf_valid','spatial_return_endpoint_valid'}))||...
 ~isequal(double(j.source_time_s),double(packet.t_s))||...
 ~isequal(j.source_current_ekf_valid,true)||...
 ~isequal(j.spatial_return_endpoint_valid,true)||...
 ~isequal(size(j.start_jet),[3,8])||...
 ~isequal(size(j.end_jet),[3,8])||...
 any(~isfinite([j.start_jet(:);j.end_jet(:)]))
  continue;
 end
 if ~all(isfield(packet,{'position_L_m','velocity_L_mps'}))||...
 numel(packet.position_L_m)~=3||numel(packet.velocity_L_mps)~=3
  continue;
 end
 p=double(packet.position_L_m(:));v=double(packet.velocity_L_mps(:));
 jp=double(j.start_jet(:,1));jv=double(j.start_jet(:,2));
 tol=1024*eps(max([1;abs(p);abs(v);abs(jp);abs(jv)]));
 if max(abs(p-jp))>tol||max(abs(v-jv))>tol,continue;end
 for k=1:options.max_trials
  factor=2^(k-1);T=T0*factor;
  if ~isfinite(T)||T<=0,continue;end
  seed=AF7R58R168_SEED_C7(route,j.start_jet,j.end_jet,T);
  if ~seed.feasible,continue;end
  rseed=route;rseed.C7=seed;
  % Seed is defined AT THIS proposed duration; no second dilation.
  budget=AF7R58R168_PHYSICAL_BUDGET(rseed,packet,speedCert,1);
  entry=item;entry.route_index=r;entry.time_scale=factor;entry.duration_s=T;
  entry.budget_status=budget.status;
  if budget.usable
   wb=AF7R58R170_DIRECTIONAL_C7QP(route,j.start_jet,j.end_jet,...
    seed.segment_durations_s,budget.limits_mps_mps2_mps3_mps4,packet,...
    struct('robust_tube_on',options.robust_tube_on));
   qp=wb.qp;entry.fullbody_inner_status=wb.status;
   entry.qp_status=wb.status;
   if wb.feasible
    entry.qp_pass=true;G.qp_success_count=G.qp_success_count+1;
    cand=wb.candidate;
    yaw=AF7R58R169_HEADING_C6(cand);
    entry.yaw_status=yaw.status;
    % Revalidate actual nonlinear model and original shapes, per candidate.
    guard=AF7R58R170_CANDIDATE_GATE(cand,packet,speedCert,sourceObstacles, ...
     struct('robust_tube_on',options.robust_tube_on));
    entry.physics_status=guard.status;
    if guard.candidate_shortlist_only&&yaw.heading_exact_C6_conditional&&...
     ~wb.robust_tube_missing
     entry.physical_reference_conditional=true;
     G.conditional_shortlist_count=G.conditional_shortlist_count+1;
     if isnan(G.selected_duration_s)||T<G.selected_duration_s
      G.selected_index=r;G.selected_duration_s=T;
      G.selected_route=cand;
     end
    end
   end
  end
  logs(end+1)=entry; %#ok<AGROW>
  % Finite computation budget; unexamined longer timings remain UNKNOWN.
 end
end
G.trials=logs;
if G.conditional_shortlist_count>0
 G.status='CONDITIONAL_DIRECTIONAL_CABLE_QP_AND_C6_SHORTLIST__TORQUE_TAIL_HLC_PENDING';
else
 G.status='NO_DIRECTIONAL_CABLE_AND_HEADING_C6_CONDITIONAL_ROUTE__FAIL_CLOSED';
end
end
