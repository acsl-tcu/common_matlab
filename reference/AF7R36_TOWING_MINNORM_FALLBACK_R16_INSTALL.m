function OUT = AF7R36_TOWING_MINNORM_FALLBACK_R16_INSTALL()
% AF7R36_TOWING_MINNORM_FALLBACK_R16_INSTALL
%
% Adds a NEW towing-specific fallback before the historical minimum-snap
% fallback. The historical branch is intentionally retained for this one
% migration/audit step only.
%
% New family:
%   TOWING_C7_MIN_NORM_CONSTANT
%
% On every certified nominal-unsafe component j:
%
%       d_j(t) = a_j
%       d_j^(r)(t) = 0, r >= 1
%
% The existing corridor inequalities have form
%
%       n' a_j + s n' v_j >= b.
%
% R16 restricts v_j = 0 and solves, per component,
%
%       minimize    1/2 ||a_j||^2
%       subject to  n_i' a_j >= b_i
%
% using the existing active-set QP solver with H = I_3.
%
% Consequences:
%   - no Schur complement;
%   - no minimum-snap Hessian;
%   - no arbitrary towing weights;
%   - only three unknowns per component;
%   - correction-induced velocity/acceleration/jerk are identically zero on
%     each unsafe span;
%   - entry/inter/exit transitions remain the existing degree-15 C7 jet
%     construction;
%   - every candidate is still accepted ONLY through the unchanged
%       finite-sensing speed -> rejoin -> continuous whole-body certificates.
%
% This installer DOES NOT remove the historical minimum-snap fallback yet.
% Removal is allowed only after this new family closes a real live hard case.
%
% No README. No persistent backup.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 TOWING MIN-NORM CONSTANT FALLBACK R16 INSTALL\n');
fprintf(' new family                                 = TOWING_C7_MIN_NORM_CONSTANT\n');
fprintf(' unsafe-span correction derivatives r>=1   = exactly zero\n');
fprintf(' fallback QP dimension                      = 3 per component\n');
fprintf(' arbitrary objective weights                = 0\n');
fprintf(' Schur regularization                       = 0\n');
fprintf(' hard safety gates modified                 = 0\n');
fprintf(' structural C7 construction modified        = 0\n');
fprintf(' historical minimum-snap removed now        = 0 (migration safety step)\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir)&&isfolder(refDir), ...
    '[R16] Cannot resolve current reference directory.');

hpp=fullfile(refDir,'af7r36_core.hpp');
cpp=fullfile(refDir,'af7r36_single_core_mex.cpp');
rps=fullfile(refDir,'REPLANNING_SYSTEM.m');
assert(isfile(hpp),'[R16] Missing %s',hpp);
assert(isfile(cpp),'[R16] Missing %s',cpp);
assert(isfile(rps),'[R16] Missing %s',rps);

hpp0=normlf(fileread(hpp));
cpp0=normlf(fileread(cpp));
rps0=normlf(fileread(rps));

hppNew=hpp0;
cppNew=cpp0;
rpsNew=rps0;

assert(contains(hpp0,'AF7_R7_FAILCLOSED_FALLTHROUGH_R15B'), ...
    '[R16] R15B fail-closed R7 transport is not installed.');
assert(count_exact(hpp0,'AF7_R15B_FALLBACK:')==1, ...
    '[R16] R15B fallback label count is not one.');
assert(contains(hpp0,'// FALLBACK: exact previously flown affine/minimum-snap family.'), ...
    '[R16] Historical fallback marker missing.');
assert(contains(hpp0,'static inline QPSol solve_qp'), ...
    '[R16] Existing exact small active-set QP solver missing.');
assert(contains(hpp0,'static inline Candidate build_candidate'), ...
    '[R16] Existing structural C7 candidate builder missing.');
assert(~contains(hpp0,'AF7_TOWING_MINNORM_CONSTANT_R16'), ...
    '[R16] R16 already installed.');

try
    %% --------------------------------------------------------------------
    % 1) Insert new family at the R15B fallback label.
    %    Thus an R7 Schur failure enters the NEW fallback first.
    % ---------------------------------------------------------------------
    anchor=[ ...
        'AF7_R15B_FALLBACK:' sprintf('\n') ...
        '    // ------------------------------------------------------------------' sprintf('\n') ...
        '    // FALLBACK: exact previously flown affine/minimum-snap family.'];

    block=[ ...
        'AF7_R15B_FALLBACK:' sprintf('\n') ...
        '    // ------------------------------------------------------------------' sprintf('\n') ...
        '    // AF7_TOWING_MINNORM_CONSTANT_R16' sprintf('\n') ...
        '    // NEW TOWING FALLBACK: componentwise minimum-norm constant offset.' sprintf('\n') ...
        '    //' sprintf('\n') ...
        '    // Restriction on every unsafe component j:' sprintf('\n') ...
        '    //     d_j(t)=a_j,  v_j=0.' sprintf('\n') ...
        '    // Therefore correction-induced derivatives of order >=1 vanish' sprintf('\n') ...
        '    // identically on the unsafe span.  The corridor rows reduce exactly' sprintf('\n') ...
        '    // from n''a_j+s n''v_j>=b to n''a_j>=b.' sprintf('\n') ...
        '    //' sprintf('\n') ...
        '    // Each component solves min 0.5||a_j||^2 with H=I3.  No arbitrary' sprintf('\n') ...
        '    // weights, no Schur complement and no minimum-snap Hessian are used.' sprintf('\n') ...
        '    // Candidate acceptance remains the unchanged hard certificate stack.' sprintf('\n') ...
        '    // ------------------------------------------------------------------' sprintf('\n') ...
        '    {' sprintf('\n') ...
        '        const auto tfb=clk::now();' sprintf('\n') ...
        '        std::vector<Candidate> calm;' sprintf('\n') ...
        '        std::vector<int> sg(Ne,1);' sprintf('\n') ...
        '        std::function<void(int)> rec16=[&](int k){' sprintf('\n') ...
        '            if(k<Ne){' sprintf('\n') ...
        '                sg[k]=1;rec16(k+1);' sprintf('\n') ...
        '                sg[k]=-1;rec16(k+1);' sprintf('\n') ...
        '                return;' sprintf('\n') ...
        '            }' sprintf('\n') ...
        '            std::vector<double> z(nvar,0.0);' sprintf('\n') ...
        '            double totalCost=0.0;' sprintf('\n') ...
        '            double minSlack=std::numeric_limits<double>::infinity();' sprintf('\n') ...
        '            bool ok=true;' sprintf('\n') ...
        '            for(int j=0;j<Cn && ok;++j){' sprintf('\n') ...
        '                std::vector<Row> r3;' sprintf('\n') ...
        '                for(int e=0;e<Ne;++e){' sprintf('\n') ...
        '                    if(E.ep[e].comp!=j)continue;' sprintf('\n') ...
        '                    const auto&src=(sg[e]>0)?OR[e].plus:OR[e].minus;' sprintf('\n') ...
        '                    for(const auto&rf:src){' sprintf('\n') ...
        '                        Row rr;rr.a.assign(3,0.0);rr.b=rf.b;' sprintf('\n') ...
        '                        const int pslot=2*j;' sprintf('\n') ...
        '                        rr.a[0]=rf.a[3*pslot+0];' sprintf('\n') ...
        '                        rr.a[1]=rf.a[3*pslot+1];' sprintf('\n') ...
        '                        rr.a[2]=rf.a[3*pslot+2];' sprintf('\n') ...
        '                        r3.push_back(std::move(rr));' sprintf('\n') ...
        '                    }' sprintf('\n') ...
        '                }' sprintf('\n') ...
        '                if(r3.empty()){ok=false;break;}' sprintf('\n') ...
        '                std::vector<double> H3(9,0.0);H3[0]=H3[4]=H3[8]=1.0;' sprintf('\n') ...
        '                QPSol q=solve_qp(H3,3,r3);' sprintf('\n') ...
        '                if(!q.ok||q.z.size()!=3){ok=false;break;}' sprintf('\n') ...
        '                const int pslot=2*j;' sprintf('\n') ...
        '                z[3*pslot+0]=q.z[0];' sprintf('\n') ...
        '                z[3*pslot+1]=q.z[1];' sprintf('\n') ...
        '                z[3*pslot+2]=q.z[2];' sprintf('\n') ...
        '                // velocity slot stays exactly zero.' sprintf('\n') ...
        '                totalCost+=q.cost;' sprintf('\n') ...
        '                minSlack=std::min(minSlack,q.slack);' sprintf('\n') ...
        '            }' sprintf('\n') ...
        '            if(!ok)return;' sprintf('\n') ...
        '            Candidate C=build_candidate(E.comp,t0,t1,z,totalCost,sg,minSlack,4);' sprintf('\n') ...
        '            C.constant_translation=true;' sprintf('\n') ...
        '            calm.push_back(std::move(C));' sprintf('\n') ...
        '        };' sprintf('\n') ...
        '        rec16(0);' sprintf('\n') ...
        '        R.tim.qp+=std::chrono::duration<double,std::milli>(clk::now()-tfb).count();' sprintf('\n') ...
        '        const auto tc16=clk::now();' sprintf('\n') ...
        '        if(certify_candidates(calm,true,4)){' sprintf('\n') ...
        '            R.tim.candidate_build+=std::chrono::duration<double,std::milli>(clk::now()-tc16).count();' sprintf('\n') ...
        '            R.tim.synthesis=std::chrono::duration<double,std::milli>(clk::now()-a).count();' sprintf('\n') ...
        '            R.tim.candidate=R.tim.synthesis;' sprintf('\n') ...
        '            R.tim.total=std::chrono::duration<double,std::milli>(clk::now()-T0).count();' sprintf('\n') ...
        '            return R;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '        R.tim.candidate_build+=std::chrono::duration<double,std::milli>(clk::now()-tc16).count();' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '' sprintf('\n') ...
        '    // ------------------------------------------------------------------' sprintf('\n') ...
        '    // FALLBACK: exact previously flown affine/minimum-snap family.'];

    hppNew=replace_once(hppNew,anchor,block,'R15B fallback entry');

    %% --------------------------------------------------------------------
    % 2) Native result naming for family 4.
    %    Keep any existing family-3/R7 mapping intact.
    % ---------------------------------------------------------------------
    famAnchor='    set("candidate_family",mxCreateString(family));';
    famInsert=[ ...
        '    if(R.cand.family==4)family="TOWING_C7_MIN_NORM_CONSTANT";' sprintf('\n') ...
        famAnchor];
    cppNew=replace_once(cppNew,famAnchor,famInsert,'candidate family serializer');

    % The existing result field can now truthfully identify this family.
    constAnchor='    set("compact_constant_translation",logicalScalar(false));';
    if count_exact(cppNew,constAnchor)==1
        cppNew=replace_once(cppNew,constAnchor, ...
            '    set("compact_constant_translation",logicalScalar(R.cand.family==4));', ...
            'constant-translation result flag');
    end

    %% --------------------------------------------------------------------
    % 3) Persist the last successfully generated candidate family across
    %    staged-pipeline reset, for postrun authority audit only.
    % ---------------------------------------------------------------------
    propAnchor='        staged_replan_last_reason = '''';';
    propInsert=[propAnchor sprintf('\n') ...
        '        staged_replan_last_candidate_family = ''''; % R16 diagnostic authority only'];
    rpsNew=replace_once(rpsNew,propAnchor,propInsert,'R16 family property');

    setAnchor='            obj.staged_replan_candidate=candidate;';
    setInsert=[setAnchor sprintf('\n') ...
        '            if isfield(candidate,''candidate_family'')' sprintf('\n') ...
        '                obj.staged_replan_last_candidate_family=char(candidate.candidate_family);' sprintf('\n') ...
        '            else' sprintf('\n') ...
        '                obj.staged_replan_last_candidate_family='''';' sprintf('\n') ...
        '            end'];
    rpsNew=replace_once(rpsNew,setAnchor,setInsert,'R16 Stage1 family latch');

    statusAnchor='            S.last_reason=char(obj.staged_replan_last_reason);';
    statusInsert=[statusAnchor sprintf('\n') ...
        '            S.last_candidate_family=char(obj.staged_replan_last_candidate_family);'];
    rpsNew=replace_once(rpsNew,statusAnchor,statusInsert,'R16 staged status family');

    %% --------------------------------------------------------------------
    % 4) Structural audits.
    % ---------------------------------------------------------------------
    assert(count_exact(hppNew,'AF7_TOWING_MINNORM_CONSTANT_R16')==1, ...
        '[R16] New fallback marker count invalid.');
    assert(count_exact(hppNew,'certify_candidates(calm,true,4)')==1, ...
        '[R16] New fallback hard-certificate call count invalid.');
    assert(count_exact(hppNew,'C.constant_translation=true;')==1, ...
        '[R16] Constant-translation semantic flag count invalid.');
    assert(count_exact(hppNew,'H3[0]=H3[4]=H3[8]=1.0;')==1, ...
        '[R16] Identity 3x3 fallback objective missing.');
    assert(count_exact(cppNew,'TOWING_C7_MIN_NORM_CONSTANT')==1, ...
        '[R16] Candidate family serializer count invalid.');

    % Historical fallback is intentionally still present for this migration step.
    assert(contains(hppNew,'minimum_snap_hessian(E.comp,t0,t1)'), ...
        '[R16] Historical fallback unexpectedly disappeared during migration.');

    % Unchanged hard gates remain.
    assert(contains(hppNew,'tighten_stageA'), ...
        '[R16] Stage-A finite-sensing gate disappeared.');
    assert(contains(hppNew,'stageB_speed'), ...
        '[R16] Stage-B finite-sensing gate disappeared.');
    assert(contains(hppNew,'rejoin_safe'), ...
        '[R16] Rejoin gate disappeared.');
    assert(contains(hppNew,'wholebody'), ...
        '[R16] Continuous whole-body gate disappeared.');

    %% --------------------------------------------------------------------
    % 5) Stage compile before production install.
    % ---------------------------------------------------------------------
    stageDir=tempname;
    [ok,msg]=mkdir(stageDir);
    assert(ok,'[R16] Cannot create staging directory: %s',msg);
    stageCleanup=onCleanup(@()cleanup_stage(stageDir)); %#ok<NASGU>

    stagedHpp=fullfile(stageDir,'af7r36_core.hpp');
    stagedCpp=fullfile(stageDir,'af7r36_single_core_mex.cpp');
    write_text(stagedHpp,hppNew);
    write_text(stagedCpp,cppNew);

    fprintf('[R16] Compiling staged MEX...\n');
    oldDir=pwd;
    cwdCleanup=onCleanup(@()cd(oldDir)); %#ok<NASGU>
    cd(stageDir);
    clear mex
    mex('-R2018a','-O', ...
        'COMPFLAGS="$COMPFLAGS /std:c++17"', ...
        ['-I' stageDir], ...
        '-output','af7r36_single_core_mex', ...
        '-outdir',stageDir, ...
        stagedCpp);

    stagedMex=fullfile(stageDir,['af7r36_single_core_mex.' mexext]);
    assert(isfile(stagedMex),'[R16] Staged MEX missing.');

    %% --------------------------------------------------------------------
    % 6) Install with temporary rollback copies. No clear classes here.
    % ---------------------------------------------------------------------
    dstMex=fullfile(refDir,['af7r36_single_core_mex.' mexext]);
    oldMexTmp=fullfile(stageDir,['af7r36_single_core_mex_OLD.' mexext]);
    hadOldMex=isfile(dstMex);
    if hadOldMex
        [ok,msg]=copyfile(dstMex,oldMexTmp,'f');
        assert(ok,'[R16] Cannot prepare temporary MEX rollback: %s',msg);
    end

    cd(oldDir);
    clear mex
    wroteH=false;wroteC=false;wroteR=false;installedMex=false;
    try
        write_text(hpp,hppNew);wroteH=true;
        write_text(cpp,cppNew);wroteC=true;
        write_text(rps,rpsNew);wroteR=true;

        [ok,msg]=copyfile(stagedMex,dstMex,'f');
        assert(ok,'[R16] Cannot install staged MEX: %s',msg);
        installedMex=true;
        clear mex
        rehash

        assert(exist('af7r36_single_core_mex','file')==3, ...
            '[R16] Installed MEX not visible.');
        assert(contains(normlf(fileread(hpp)),'AF7_TOWING_MINNORM_CONSTANT_R16'), ...
            '[R16] Installed core marker not visible.');
        assert(contains(normlf(fileread(rps)),'staged_replan_last_candidate_family'), ...
            '[R16] Installed family latch not visible.');
    catch ME2
        if wroteH,try,write_text(hpp,hpp0);catch,end,end
        if wroteC,try,write_text(cpp,cpp0);catch,end,end
        if wroteR,try,write_text(rps,rps0);catch,end,end
        if installedMex && hadOldMex
            try,copyfile(oldMexTmp,dstMex,'f');catch,end
        end
        clear mex
        rehash
        rethrow(ME2);
    end

    fprintf('[R16] PASS.\n');
    fprintf('  new towing min-norm fallback installed     = 1\n');
    fprintf('  legacy minimum-snap still behind it        = 1 (temporary migration guard)\n');
    fprintf('  safety/smoothness certificate weakening    = 0\n');
    fprintf('  IMPORTANT: clear old objects/classes before next simulation.\n');

    OUT=struct( ...
        'pass',true, ...
        'revision','AF7_TOWING_MINNORM_CONSTANT_R16', ...
        'new_family','TOWING_C7_MIN_NORM_CONSTANT', ...
        'legacy_fallback_temporarily_retained',true, ...
        'hard_safety_modified',false, ...
        'C7_modified',false);

catch ME
    clear mex
    rehash
    fprintf(2,'[R16] FAILED. No successful production install completed.\n');
    fprintf(2,'[R16] ORIGINAL ERROR: %s | %s\n',ME.identifier,ME.message);
    rethrow(ME);
end
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1,'[R16] Anchor "%s" count=%d; expected 1.',label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end

function n=count_exact(txt,pat)
n=numel(strfind(txt,pat));
end

function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));
s=strrep(s,sprintf('\r'),sprintf('\n'));
end

function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');
assert(f>=0,'[R16] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end

function cleanup_stage(d)
if isfolder(d)
    try,rmdir(d,'s');catch,end
end
end
