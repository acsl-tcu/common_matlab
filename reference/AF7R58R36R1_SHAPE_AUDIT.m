function A=AF7R58R36R1_SHAPE_AUDIT(spike_mat_path)
% Regression audit for R36R1; uses saved R23 MAT, not a new simulation.
if nargin<1 || isempty(spike_mat_path)
    spike_mat_path='AF7R58R23_SPIKE_REPORT.mat';
end
assert(isfile(spike_mat_path), 'R36R1:MissingFile', ...
    'Timing MAT not found: %s',char(spike_mat_path));
R=AF7R58R36_TIMING_CLOSE([],[],spike_mat_path);
N=R.flight_cycle_count;
assert(N>0 && iscolumn(R.time_s), 'R36R1:TimeShape');
fields={'outer_reference_ms','full_iteration_ms','full_component_sum_ms', ...
    'full_cycle_closure_ms','online_component_sum_ms','online_cycle_closure_ms', ...
    'internal_do_ms','wrapper_and_adjacent_ms'};
for j=1:numel(fields)
    assert(isequal(size(R.(fields{j})),[N 1]), ...
        'R36R1:Shape','Field %s is not Nx1.',fields{j});
end
assert(height(R.top_cycles)==min(30,N),'R36R1:TopCycleTable');
assert(all(isfinite(R.full_cycle_closure_ms)), 'R36R1:FullClosureFinite');
% The full iteration is partitioned by the instrumented R23 components.
assert(R.max_abs_full_cycle_closure_ms<=1e-6, ...
    'R36R1:FullClosure','Full-cycle closure must be numerically near zero.');
A=struct('pass',true,'flight_cycles',N,'reference_peak_ms', ...
    R.reference_max_ms,'full_cycle_closure_max_ms', ...
    R.max_abs_full_cycle_closure_ms,'online_cycle_closure_max_ms', ...
    R.max_abs_online_cycle_closure_ms,'top_cycle_rows',height(R.top_cycles), ...
    'logger_internal_timing_available',isfield(R.timings,'rtime_e_to_e_ms'));
fprintf('[R36R1] SHAPE / FULL-CYCLE CLOSURE AUDIT PASS | N=%d | max full residual=%.9g ms\n', ...
    N,A.full_cycle_closure_max_ms);
end
