function S=AF7R58R64_SOURCE_CHECK()
% Source-only check, no Flight or MEX mutation. R64 is not a safety proof.
root=fileparts(mfilename('fullpath'));
f=which('REPLANNING_SYSTEM');
assert(~isempty(f) && strcmpi(f,fullfile(root,'REPLANNING_SYSTEM.m')), ...
    'R64:ShadowedSource','A different REPLANNING_SYSTEM is on the MATLAB path');
% R64R2: Unlike a fileread/contains() check, meta.class.fromName
% forces MATLAB to parse/resolve the class BEFORE SimHL starts Flight.
% It does NOT construct a replanner instance or change HLC/EKF/plant.
try
    classMeta=meta.class.fromName('REPLANNING_SYSTEM');
catch ME
    fprintf(2,'R64R2 parser FAILED before Flight: %s\n',ME.message);
    rethrow(ME);
end
assert(~isempty(classMeta) && strcmp(char(classMeta.Name),'REPLANNING_SYSTEM'), ...
    'R64R2:ClassParse','MATLAB did not resolve REPLANNING_SYSTEM class');
s=fileread(f);
assert(contains(s,'''enforce_projected_no_overshoot'',true);') && ...
    ~contains(s,'''enforce_projected_no_overshoot'',true));'), ...
    'R64R2:OldSyntax','An unfixed double closing parenthesis is present');
assert(contains(s,'r64_no_safe_lead') && ...
    contains(s,'EKF_NOW_UNSEPARATED__NO_CERTIFIED_PRECOLLISION_LEAD') && ...
    contains(s,'ACTIVE_FLAT_JET_MISMATCH__REJOIN_BLOCKED') && ...
    contains(s,'enforce_projected_no_overshoot') && ...
    contains(s,'r63_live_now_gate') && contains(s,'r63_live_c7_authority'), ...
    'R64:Incomplete','Incomplete R64 class installation');
f60=fullfile(root,'AF7R58R60_C7_FREE_REJOIN.m');
assert(exist(f60,'file')==2 && ...
    contains(fileread(f60),'projected_no_overshoot_control_polygon'), ...
    'R64:MissingGenerator','Required C7 return candidate generator unavailable');
S=struct('source',f, 'source_loaded',true, ...
    'matlab_class_parser_passed',true, ...
    'r64_extra_closing_parenthesis_fixed',true, ...
    'original_sensor_detection_unchanged',true, ...
    'current_ekf_no_lead_alert_active',true, ...
    'unsafe_stage_commit_prevented',true, ...
    'natural_return_projected_no_overshoot_screen_installed',true, ...
    'incorrect_c7_jet_validity_fail_closed',true, ...
    'hlc_unchanged',true, ...
    'closed_loop_four_second_future_certified',false, ...
    'natural_return_committed',false, ...
    'robust_error_tube_installed',false);
disp(S);
end
