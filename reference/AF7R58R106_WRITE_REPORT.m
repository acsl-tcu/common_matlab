function path=AF7R58R106_WRITE_REPORT(C,U)
% Postflight only. Keep output next to the audit script, not project root.
if nargin<2,U=[];end
assert(isstruct(C)&&isscalar(C),'R106:CaptureReportSchema', ...
    'Pass AF7R58R106_CAPTURE_STATUS result.');
path=fullfile(fileparts(mfilename('fullpath')), ...
    'AF7R58R106_STAGE_REPORT.txt');
fid=fopen(path,'wt');
assert(fid>=0,'R106:ReportOpen','Cannot write report directory.');
c=onCleanup(@()fclose(fid));
fprintf(fid,'R106 ACTUAL EKF + KNOWN MASK SAME-EVENT AUDIT\n');
fprintf(fid,'status=%s snapshot_count=%d authenticated_count=%d\n', ...
    char(C.status),double(C.count),double(C.authenticated_count));
for k=1:C.count
    fprintf(fid,'event=%d time=%.17g version=%.0f known=%d ekf=%s ', ...
        k,C.event_times_s(k),C.reference_versions(k), ...
        C.known_counts(k),char(C.ekf_status{k}));
    fprintf(fid,'q_error=%.9g cable_error_m=%.9g\n', ...
        C.ekf_q_norm_error(k),C.ekf_cable_relation_error_m(k));
end
if ~isempty(U)
    fprintf(fid,'stage=%s source=%s trigger_preview_supplied=%d\n', ...
        char(U.status),char(U.source_event.status), ...
        double(U.physical_future_supplied));
    fprintf(fid,'partial_closure=%s reference_pass=%d\n', ...
        char(U.partial_closure.status), ...
        double(U.partial_closure.reference_conditions_pass));
end
fprintf(fid,['UNPROVEN: closed-loop HLC future, torque/tension strength, ' ...
    'tracking tube, infinite future, IEEE, 25ms, production atomic commit\n']);
end
