function S = AF7R58R58_SOURCE_CHECK()
% R58 source/MEX binding: no mutation of planning, controller or safety.
root=fileparts(mfilename('fullpath'));
files={'REPLANNING_SYSTEM.m','af7r36_core.hpp','af7r36_single_core_mex.cpp'};
for k=1:numel(files)
    assert(isfile(fullfile(root,files{k})),'R58:MissingFile', ...
        'Missing source: %s',fullfile(root,files{k}));
end
P=which('REPLANNING_SYSTEM');
assert(strcmpi(P,fullfile(root,'REPLANNING_SYSTEM.m')), ...
    'R58:Shadow','A different REPLANNING_SYSTEM is active: %s',P);
M=which('af7r36_single_core_mex');
assert(~isempty(M),'R58:NoMEX','Compile af7r36_single_core_mex.cpp with C++17 first.');
assert(strcmpi(fileparts(M),root),'R58:ShadowMEX', ...
    'A different MEX is active: %s',M);
a=fileread(P); b=fileread(fullfile(root,'af7r36_core.hpp'));
c=fileread(fullfile(root,'af7r36_single_core_mex.cpp'));
assert(contains(a,'r58_detail_diagnostic_enabled') && ...
    contains(b,'r58_decasteljau_fixed16') && ...
    contains(b,'if(collectRawQPDiag)') && ...
    contains(c,'r58_detail_diagnostic_enabled'),'R58:SourceMismatch', ...
    'R58 source files do not have the expected signatures.');
assert(contains(a,'ENABLE_AF7R58R16_REFERENCE_BRIDGE = 1') && ...
    contains(a,'ENABLE_AF7R57_DETAIL_RECORD = false'), ...
    'R58:ConfigurationMismatch','R58 bridge/diagnostic settings changed.');
me=dir(M); h=dir(fullfile(root,'af7r36_core.hpp'));
cc=dir(fullfile(root,'af7r36_single_core_mex.cpp'));
assert(me.datenum+1/86400>=max([h.datenum cc.datenum]), ...
    'R58:OldMEX','The MEX file predates C++ source; rebuild it with C++17.');
S=struct('source',P,'mex',M,'clean_details',true, ...
    'r58_bridge',true,'c7_numerical_equivalence_proved_by_matlab',false, ...
    'execution_tube_added',false,'return_modified',false,'trigger_modified',false);
fprintf('[R58 SOURCE] REPLANNING_SYSTEM = %s\n',P);
fprintf('[R58 SOURCE] compiled MEX      = %s\n',M);
fprintf('[R58 SOURCE] C7 numerical evaluator optimized; hard gates unchanged in source.\n');
fprintf('[R58 SOURCE] C++17 compiler required. No MATLAB same-run validation yet.\n');
end
