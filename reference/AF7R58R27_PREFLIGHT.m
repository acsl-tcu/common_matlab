       contains(s,'observer_unique_2pi_lift(') && ...
       contains(s,"assert(okPhi, ...") && ...
       contains(s,'R27_STAGE3_RUNTIME_SIM_FLAG_TRUE'), ...
       '[R27] class provenance not found.');
