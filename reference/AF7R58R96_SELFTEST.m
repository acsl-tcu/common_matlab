function T=AF7R58R96_SELFTEST()
% Synthetic fixtures only; no MATLAB Flight, HLC or IEEE proof.
req={'AF7R58R96_C7_KNOT_SPEED_ROUTE', ...
    'AF7R58R96_KNOT_DISPLACEMENT_SCREEN', ...
    'AF7R58R96_CORRIDOR_PREFLIGHT', ...
    'AF7R58R96_RUN_SAVED_ROUTE', ...
    'AF7R58R96_ADAPTIVE_SAVED_SEARCH', ...
    'AF7R58R96_C7_CORRIDOR_PROJECT', ...
    'AF7R58R96_SHA256_FILE', ...
    'AF7R58R96_KNOT_VQ_SCREEN', ...
    'AF7R58R96_KNOT_REACHABILITY_PREFLIGHT', ...
    'AF7R58R96_SOURCE_CHECK', ...
    'AF7R58R94_CERTIFY_ALL_SEGMENTS', ...
    'AF7R58R94_SUPPORT_SEED_ROUTES', ...
    'AF7R58R92_C7_MINIMUM8_ROUTE'};
root=fileparts(mfilename('fullpath'));
S96=AF7R58R96_SOURCE_CHECK();
assert(strcmp(S96.status,'PASS_R96_PINNED_RUNTIME_DEPENDENCY_RESOLUTION'), ...
 'R96:MissingRuntimeDependency', ...
 'Required dependency missing or loaded from another source directory.');
for k=1:numel(req)
    f=which(req{k});
    assert(~isempty(f)&&strcmp(fileparts(f),root), ...
        'R95:SourceShadowOrMissing', ...
        'Expected %s in the active reference directory; resolved %s', ...
        req{k},f);
end
w=[0 1.5 3;0 0 0;-2 -2 -2]; times=[0 1.5 3];
J0=zeros(3,8);J1=zeros(3,8);
J0(:,1)=w(:,1);J1(:,1)=w(:,end);
J0(1,2)=1;J1(1,2)=1;
R=AF7R58R96_C7_KNOT_SPEED_ROUTE( ...
    times,w,J0,J1,0.25,2,9.81,3.1);
assert(R.reference_candidate_found&&R.knot_speed_necessary_pass&& ...
    R.num_segments==2&&R.max_jet_residual<1e-7&& ...
    ~R.production_commit_authorized, ...
    'R95:SyntheticStraightC7KnotRegression', ...
    'Two-section synthetic straight C7 trajectory failed.');
S=AF7R58R96_KNOT_DISPLACEMENT_SCREEN(R,9.81,2,3.1);
assert(S.necessary_speed_pass && ~S.production_commit_authorized, ...
    'R95:KnotTravelRegression','Straight slow knot travel must pass.');
U=R;U.knot_jets(:,1,2)=[200;0;-2];
F=AF7R58R96_KNOT_DISPLACEMENT_SCREEN(U,9.81,2,3.1);
assert(~F.necessary_speed_pass && ...
    strcmp(F.status,'NECESSARY_UAV_KNOT_TRAVEL_TIME_VIOLATED'), ...
    'R95:KnotTravelNecessaryViolationNotDetected', ...
    'Impossible mid-knot displacement must fail.');
% Screen physically impossible waypoint/time combinations before
% constructing high-order Bezier polynomials. Do not assume q is fixed.
N=AF7R58R96_KNOT_REACHABILITY_PREFLIGHT( ...
    [zeros(3,1),[100;0;0]],[0 1],2,3.1);
assert(~N.passes_necessary_condition && ...
    strcmp(N.status,'NECESSARY_CABLE_UAV_TRAVEL_TIME_VIOLATION'), ...
    'R96:NecessaryTautCableTravelViolationNotRejected', ...
    'A 100 m payload displacement in one second cannot be achieved by this UAV.');
Y=AF7R58R96_KNOT_REACHABILITY_PREFLIGHT( ...
    [zeros(3,1),[1;0;0]],[0 1],2,3.1);
assert(Y.passes_necessary_condition,'R96:NonRestrictiveSphericalReachability', ...
    'The necessary cable travel screen must not invent a payload speed limit.');
% An arbitrarily large rotated ellipsoid is not filtered by size.
angle=0.35; rot=[cos(angle) -sin(angle) 0; ...
    sin(angle) cos(angle) 0;0 0 1];
O=struct('center',[0;0;-2],'R',rot, ...
    'axes',[120;60;15]);
far=AF7R58R96_CORRIDOR_PREFLIGHT( ...
    [-400 -200;300 300;-2 -2],O,0.3);
assert(far.feasible_corridor_family&& ...
    far.known_obstacles_checked==1, ...
    'R95:LargeEllipsoidIncorrectlyRejected', ...
    'A distant waypoint edge must support the large ellipsoid case.');
inside=AF7R58R96_CORRIDOR_PREFLIGHT( ...
    [-10 10;0 0;-2 -2],O,0.3);
assert(~inside.feasible_corridor_family&& ...
    ~inside.production_commit_authorized, ...
    'R95:ObviousIntersectingSeedAccepted', ...
    'Crossing a known large ellipsoid must not be admitted as a corridor family.');
% Exercise the actual new generator constraint insertion, not merely
% presence of a function. A deliberately unsafe control polygon must be
% repaired by SHARED C7 knot derivatives, preserving 0..7 boundary jets.
Jpert=R.knot_jets;
Jpert(2,2,2)=1;
Rpert=R;Rpert.knot_jets=Jpert;
for si=1:R.num_segments
    Rpert.segments(si).payload_cp=test_cp( ...
        Jpert(:,:,si),Jpert(:,:,si+1),times(si+1)-times(si));
end
planes=struct('A',[0 1 0;0 -1 0], ...
              'b',[0.002;0.002]);
[repaired,proj]=AF7R58R96_C7_CORRIDOR_PROJECT(Rpert, ...
    {planes,planes},struct('max_corridor_projection_sweeps',256));
assert(proj.control_point_contained&&proj.adjusted_internal_jets&& ...
    proj.endpoint_0_to_7_exact_input_preserved&& ...
    repaired.max_jet_residual<1e-6&& ...
    all(arrayfun(@(x) all(all(planes.A*x.payload_cp<= ...
      planes.b*ones(1,16))),repaired.segments)), ...
    'R96:CorridorConstraintsInGenerationRegression', ...
    'Shared jet projection failed to enforce a simple feasible corridor.');
fixBoundary=Rpert;
fixBoundary.knot_jets(2,1,1)=0.5;
fixBoundary.segments(1).payload_cp=test_cp( ...
 fixBoundary.knot_jets(:,:,1),fixBoundary.knot_jets(:,:,2),times(2)-times(1));
[~,unres]=AF7R58R96_C7_CORRIDOR_PROJECT(fixBoundary, ...
    {planes,planes},struct('max_corridor_projection_sweeps',256));
assert(~unres.control_point_contained&&~unres.production_commit_authorized, ...
    'R96:ImpossibleFixedEndpointMustBeRejected', ...
    'A fixed endpoint outside its corridor cannot be changed silently.');
sha=AF7R58R96_SHA256_FILE(which('AF7R58R96_ADAPTIVE_SAVED_SEARCH'));
assert(ischar(sha)&&numel(sha)==64,'R96:SHA256Independence', ...
    'Source integrity helper must be packaged locally.');
T=struct('status','PASS_R96_IN_GENERATOR_C7_CORRIDOR_AND_BUNDLE', ...
    'synthetic_c7_sections',R.num_segments, ...
    'internal_jet_corridor_projection_passed',proj.control_point_contained, ...
    'projection_sweeps',proj.projection_sweeps, ...
    'fixed_endpoint_unsafe_rejected',~unres.control_point_contained, ...
    'sha256_helper_packaged',true, ...
    'runtime_dependencies_same_folder',true, ...
    'synthetic_all_07_jets_residual',R.max_jet_residual, ...
    'speed_aware_knot_test_passed',R.knot_speed_necessary_pass, ...
    'necessary_displacement_rejected',~F.necessary_speed_pass, ...
    'spherical_cable_reachability_screen_tested', ...
       ~N.passes_necessary_condition&&Y.passes_necessary_condition, ...
    'large_rotated_ellipsoid_retained',far.known_obstacles_checked, ...
    'obvious_large_ellipsoid_crossing_rejected', ...
      ~inside.feasible_corridor_family, ...
    'real_snapshot_exercised',false, ...
    'flight_generator_changed',false,'trigger_changed',false, ...
    'whole_closed_loop_safety_proved',false, ...
    'production_commit_authorized',false);
end

function P=test_cp(A,B,T)
D=size(A,1);P=zeros(D,16);
for j=0:7
 x=zeros(D,1);y=zeros(D,1);
 for r=0:j
  falling=prod(15:-1:(16-r));
  f=nchoosek(j,r)*T^r/falling;
  x=x+f*A(:,r+1);y=y+(-1)^r*f*B(:,r+1);
 end
 P(:,j+1)=x;P(:,16-j)=y;
end
end
