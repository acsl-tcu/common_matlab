function S=AF7R58R72_SOURCE_CHECK()
% R72 requires ACTUAL MATLAB class parse plus source and registry checks.
p=which('REPLANNING_SYSTEM');
assert(~isempty(p)&&~isempty(meta.class.fromName('REPLANNING_SYSTEM')), ...
    '[R72] missing or unparseable Replanner');
s=fileread(p);
assert(contains(s,"AF7R58R72_REGISTRY('register',obj)") && ...
    contains(s,"AF7R58R72_REGISTRY('capture',obj)") && ...
    contains(s,'r71r2_event_snapshots'), ...
    '[R72] constructor/event persistent binding missing');
assert(exist('AF7R58R71_EXACT_HLC_PLANT_PREVIEW','file')==2, ...
    '[R72] physical predictor missing');
B=AF7R58R72_REGISTRY('status');
S=struct('source',p,'class_parser_passed',true, ...
    'constructor_registration_installed',true, ...
    'event_bound_registration_installed',true, ...
    'postflight_registry',B, ...
    'hlc_ekf_plant_runner_modified',false, ...
    'reference_trigger_replaced',false, ...
    'natural_C7_return_committed',false, ...
    'continuous_time_certificate',false);
end
