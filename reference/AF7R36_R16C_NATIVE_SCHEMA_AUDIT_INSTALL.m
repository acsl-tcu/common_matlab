function OUT = AF7R36_R16C_NATIVE_SCHEMA_AUDIT_INSTALL()
% AF7R36_R16C_NATIVE_SCHEMA_AUDIT_INSTALL
%
% Diagnostic-only correction to R16B.
%
% R16B read compact-proposal fields as if they were all top-level.
% Actual AF7R46 schema:
%   candidate.native_raw.candidate_family
%   candidate.displacement_norm_m
%   candidate.reference_speed_certificate.*
%   candidate.geometry_shadow_certificate.*
%   candidate.native_raw.{speed,rejoin,geometry}_pass_count
%
% R16C corrects ONLY the diagnostic latch before the unchanged Stage1 timing
% gate. Planner, C7, speed/rejoin/whole-body certificates, and commit behavior
% are unchanged.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 R16C NATIVE-SCHEMA PRE-DEADLINE AUDIT INSTALL\n');
fprintf(' planner mathematics modified               = 0\n');
fprintf(' hard safety gates modified                 = 0\n');
fprintf(' staged timing gate modified                = 0\n');
fprintf(' compact/native schema mapping corrected    = 1\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir)&&isfolder(refDir), ...
    '[R16C] Cannot resolve current reference directory.');

rps=fullfile(refDir,'REPLANNING_SYSTEM.m');
assert(isfile(rps),'[R16C] Missing %s',rps);

rps0=normlf(fileread(rps));
rpsNew=rps0;

assert(contains(rps0,'AF7R36 R16B: diagnostic-only latch before the wall-time gate.'), ...
    '[R16C] R16B pre-deadline latch not found.');
assert(contains(rps0,'staged_replan_predeadline_candidate_family'), ...
    '[R16C] R16B diagnostic properties not found.');
assert(~contains(rps0,'AF7R36 R16C: corrected compact/native schema latch.'), ...
    '[R16C] R16C already installed.');

try
    old = [ ...
        '            % AF7R36 R16B: diagnostic-only latch before the wall-time gate.' sprintf('\n') ...
        '            obj.staged_replan_predeadline_candidate_seen=true;' sprintf('\n') ...
        '            obj.staged_replan_predeadline_candidate_success= ...' sprintf('\n') ...
        '                isfield(candidate,''success'') && logical(candidate.success);' sprintf('\n') ...
        '            if isfield(candidate,''candidate_family'')' sprintf('\n') ...
        '                obj.staged_replan_predeadline_candidate_family=char(candidate.candidate_family);' sprintf('\n') ...
        '            else' sprintf('\n') ...
        '                obj.staged_replan_predeadline_candidate_family='''';' sprintf('\n') ...
        '            end' sprintf('\n') ...
        '            obj.staged_replan_predeadline_reason_code=obj.field_scalar(candidate,''reason_code'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_t0=obj.field_scalar(candidate,''t0'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_t1=obj.field_scalar(candidate,''t1'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_envelope_m=obj.field_scalar(candidate,''max_control_norm_m'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_payload_speed=obj.field_scalar(candidate,''speed_payload'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_uav_speed=obj.field_scalar(candidate,''speed_uav'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_qdot=obj.field_scalar(candidate,''speed_qdot'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_geometry_pass= ...' sprintf('\n') ...
        '                isfield(candidate,''geometry_pass'') && logical(candidate.geometry_pass);' sprintf('\n') ...
        '            obj.staged_replan_predeadline_speed_pass_count=obj.field_scalar(candidate,''speed_pass_count'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_rejoin_pass_count=obj.field_scalar(candidate,''rejoin_pass_count'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_geometry_test_count=obj.field_scalar(candidate,''geometry_test_count'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_constant_translation= ...' sprintf('\n') ...
        '                isfield(candidate,''compact_constant_translation'') && logical(candidate.compact_constant_translation);' ];

    new = [ ...
        '            % AF7R36 R16C: corrected compact/native schema latch.' sprintf('\n') ...
        '            obj.staged_replan_predeadline_candidate_seen=true;' sprintf('\n') ...
        '            obj.staged_replan_predeadline_candidate_success= ...' sprintf('\n') ...
        '                isfield(candidate,''success'') && logical(candidate.success);' sprintf('\n') ...
        '            obj.staged_replan_predeadline_candidate_family='''';' sprintf('\n') ...
        '            if isfield(candidate,''native_raw'') && isstruct(candidate.native_raw) && ...' sprintf('\n') ...
        '                    isfield(candidate.native_raw,''candidate_family'')' sprintf('\n') ...
        '                obj.staged_replan_predeadline_candidate_family= ...' sprintf('\n') ...
        '                    char(candidate.native_raw.candidate_family);' sprintf('\n') ...
        '            end' sprintf('\n') ...
        '            obj.staged_replan_predeadline_reason_code=obj.field_scalar(candidate,''reason_code'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_t0=obj.field_scalar(candidate,''t0'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_t1=obj.field_scalar(candidate,''t1'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_envelope_m=obj.field_scalar(candidate,''displacement_norm_m'');' sprintf('\n') ...
        '            obj.staged_replan_predeadline_payload_speed=NaN;' sprintf('\n') ...
        '            obj.staged_replan_predeadline_uav_speed=NaN;' sprintf('\n') ...
        '            obj.staged_replan_predeadline_qdot=NaN;' sprintf('\n') ...
        '            if isfield(candidate,''reference_speed_certificate'') && ...' sprintf('\n') ...
        '                    isstruct(candidate.reference_speed_certificate)' sprintf('\n') ...
        '                SC16=candidate.reference_speed_certificate;' sprintf('\n') ...
        '                obj.staged_replan_predeadline_payload_speed= ...' sprintf('\n') ...
        '                    obj.field_scalar(SC16,''payload_speed_UB_m_s'');' sprintf('\n') ...
        '                obj.staged_replan_predeadline_uav_speed= ...' sprintf('\n') ...
        '                    obj.field_scalar(SC16,''uav_speed_UB_m_s'');' sprintf('\n') ...
        '                obj.staged_replan_predeadline_qdot= ...' sprintf('\n') ...
        '                    obj.field_scalar(SC16,''qdot_UB_rad_s'');' sprintf('\n') ...
        '            end' sprintf('\n') ...
        '            obj.staged_replan_predeadline_geometry_pass=false;' sprintf('\n') ...
        '            if isfield(candidate,''geometry_shadow_certificate'') && ...' sprintf('\n') ...
        '                    isstruct(candidate.geometry_shadow_certificate)' sprintf('\n') ...
        '                G16=candidate.geometry_shadow_certificate;' sprintf('\n') ...
        '                if isfield(G16,''certified'')' sprintf('\n') ...
        '                    obj.staged_replan_predeadline_geometry_pass=logical(G16.certified);' sprintf('\n') ...
        '                end' sprintf('\n') ...
        '            end' sprintf('\n') ...
        '            obj.staged_replan_predeadline_speed_pass_count=NaN;' sprintf('\n') ...
        '            obj.staged_replan_predeadline_rejoin_pass_count=NaN;' sprintf('\n') ...
        '            obj.staged_replan_predeadline_geometry_test_count=NaN;' sprintf('\n') ...
        '            obj.staged_replan_predeadline_constant_translation=false;' sprintf('\n') ...
        '            if isfield(candidate,''native_raw'') && isstruct(candidate.native_raw)' sprintf('\n') ...
        '                NR16=candidate.native_raw;' sprintf('\n') ...
        '                obj.staged_replan_predeadline_speed_pass_count= ...' sprintf('\n') ...
        '                    obj.field_scalar(NR16,''speed_pass_count'');' sprintf('\n') ...
        '                obj.staged_replan_predeadline_rejoin_pass_count= ...' sprintf('\n') ...
        '                    obj.field_scalar(NR16,''rejoin_pass_count'');' sprintf('\n') ...
        '                obj.staged_replan_predeadline_geometry_test_count= ...' sprintf('\n') ...
        '                    obj.field_scalar(NR16,''geometry_test_count'');' sprintf('\n') ...
        '                if isfield(NR16,''compact_constant_translation'')' sprintf('\n') ...
        '                    obj.staged_replan_predeadline_constant_translation= ...' sprintf('\n') ...
        '                        logical(NR16.compact_constant_translation);' sprintf('\n') ...
        '                end' sprintf('\n') ...
        '            end' ];

    rpsNew=replace_once(rpsNew,old,new,'R16B shallow-schema latch');

    assert(contains(rpsNew,'AF7R36 R16C: corrected compact/native schema latch.'), ...
        '[R16C] Corrected latch marker missing.');
    assert(contains(rpsNew,'candidate.native_raw.candidate_family'), ...
        '[R16C] Native family path missing.');
    assert(contains(rpsNew,'candidate.reference_speed_certificate'), ...
        '[R16C] Speed-certificate path missing.');
    assert(contains(rpsNew,'candidate.geometry_shadow_certificate'), ...
        '[R16C] Geometry-certificate path missing.');

    % Timing gate must be untouched and remain after the latch.
    pLatch=strfind(rpsNew,'AF7R36 R16C: corrected compact/native schema latch.');
    pGate=strfind(rpsNew,'if obj.generator_last_cycle_critical_ms>1e3*dt');
    assert(~isempty(pLatch)&&~isempty(pGate)&&pGate(1)>pLatch(1), ...
        '[R16C] Stage1 timing-gate authority/order changed.');

    write_text(rps,rpsNew);
    rehash

    fprintf('[R16C] PASS.\n');
    fprintf('  candidate schema diagnostic corrected      = 1\n');
    fprintf('  timing gate bypassed                       = 0\n');
    fprintf('  planner/safety/commit behavior changed     = 0\n');
    fprintf('  IMPORTANT: clear old objects/classes before next simulation.\n');

    OUT=struct( ...
        'pass',true, ...
        'revision','AF7_R16C_NATIVE_SCHEMA_AUDIT', ...
        'timing_gate_modified',false, ...
        'planner_modified',false, ...
        'hard_safety_modified',false);

catch ME
    try,write_text(rps,rps0);catch,end
    rehash
    fprintf(2,'[R16C] FAILED. REPLANNING_SYSTEM source rolled back.\n');
    fprintf(2,'[R16C] ORIGINAL ERROR: %s | %s\n',ME.identifier,ME.message);
    rethrow(ME);
end
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1,'[R16C] Anchor "%s" count=%d; expected 1.',label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end

function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));
s=strrep(s,sprintf('\r'),sprintf('\n'));
end

function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');
assert(f>=0,'[R16C] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end
