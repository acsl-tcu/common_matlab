function S=AF7R58R80_SOURCE_CHECK()
% Verify ONLY geometry primitives present; no production commit is claimed.
names={'AF7R58R79_C7_NATURAL_CONNECTOR', ...
       'AF7R58R79_CONTINUOUS_BODY_CERT', ...
       'AF7R58R80_CONTINUOUS_SEPARATE_BODY_CERT', ...
       'AF7R58R80_HEADING_C6_CERT', ...
       'AF7R58R80_ASSESS_NATURAL_CONNECTOR','AF7R58R80_SELFTEST'};
for k=1:numel(names)
    p=which(names{k});
    assert(~isempty(p),'[R80] missing expected function: %s',names{k});
end
nativePath=fullfile(fileparts(mfilename('fullpath')),'af7r36_core.hpp');
nativeSep=false;
if isfile(nativePath)
    code=fileread(nativePath);
    nativeSep=contains(code,'segment_margin(pQ,pL,o')&& ...
        contains(code,'point_margin(pL,o')&& ...
        contains(code,'point_margin(pQ,o');
end
S=struct('status','R80_SOURCE_PRESENT_UNCOMMITTED', ...
    'separate_body_certifier',which('AF7R58R80_CONTINUOUS_SEPARATE_BODY_CERT'), ...
    'global_body_ball_used_by_R80',false, ...
    'native_source_checked',isfile(nativePath), ...
    'existing_native_wholebody_separate',nativeSep, ...
    'production_modified',false, 'actuator_proof',false, ...
    'natural_return_committed',false);
end
