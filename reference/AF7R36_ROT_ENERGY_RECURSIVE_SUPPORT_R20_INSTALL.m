function OUT = AF7R36_ROT_ENERGY_RECURSIVE_SUPPORT_R20_INSTALL()
% AF7R36_ROT_ENERGY_RECURSIVE_SUPPORT_R20_INSTALL
%
% THEOREM CORRECTION: recursively propagate rotational kinetic-energy support.
%
% Rigid-body dynamics:
%       J*w_dot = tau - w x Jw
%
% Lyapunov quantity:
%       V = 0.5*w'*J*w
%
% gives exactly
%       V_dot = w'*tau
%
% and therefore, with J >= Jmin I,
%
%       d/dt sqrt(V) <= ||tau|| / sqrt(2*Jmin).
%
% For held torque over h:
%
%       sqrt(V(t+h)) <= sqrt(V(t))
%                       + ||tau|| h / sqrt(2*Jmin).
%
% Hence
%
%       ||w(t)|| <= sqrt(2/Jmin) sqrt(V(t))
%
% and
%
%       integral ||w|| dt
%       <= sqrt(2/Jmin)*sqrt(V0)*h
%          + ||tau|| h^2/(2*Jmin).
%
% OLD recursion reconstructed V from the scalar norm support every event:
%
%       V0 <= 0.5*Jmax*W0^2
%
% then converted back through Jmin. This can multiply a merely scalar support
% by sqrt(Jmax/Jmin) every event even when tau=0.
%
% R20 stores sqrt(V_UB) as a recursive hard-support state instead.
%
% After the existing two-event contraction gives a certified Euclidean ball
%
%       w in B(c,r),
%
% an independent kinetic-energy support is
%
%       V <= 0.5*c'*J*c + r*||Jc|| + 0.5*Jmax*r^2.
%
% The next stored support is the intersection:
%
%       V_new_UB = min(V_forward_UB, V_ball_UB).
%
% This is a tighter theorem, not a relaxed threshold.
%
% R19 ZYX pitch singularity / unique periodic branch-lift theorem remains
% unchanged. No trajectory, controller, timing gate, physical limit, or
% observer measurement hard bound is modified.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 ROTATIONAL ENERGY RECURSIVE SUPPORT R20 INSTALL\n');
fprintf(' rigid-body energy identity used             = Vdot = omega^T tau\n');
fprintf(' recursive state                             = sqrt(V_UB)\n');
fprintf(' per-event Jmax/Jmin remapping removed       = 1\n');
fprintf(' contraction update                          = intersection of certified supports\n');
fprintf(' pitch singularity threshold modified        = 0\n');
fprintf(' branch-lift theorem modified                = 0\n');
fprintf(' heuristic / fitted coefficient              = 0\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir)&&isfolder(refDir), ...
    '[R20] Cannot resolve current reference directory.');
rps=fullfile(refDir,'REPLANNING_SYSTEM.m');
assert(isfile(rps),'[R20] Missing %s',rps);

src0=normlf(fileread(rps));
src=src0;

assert(contains(src0,'AF7R36 R19 unique periodic branch lift.'), ...
    '[R20] R19 branch-lift theorem is not installed.');
assert(contains(src0,'S.closed=pitchClosed; S.h=h; S.held_input=u;'), ...
    '[R20] R19 pitch-only ZYX chart theorem not found.');
assert(contains(src0,'V0=0.5*Jmax*W0^2;'), ...
    '[R20] Old rotational-energy reconstruction line not found.');
assert(~contains(src0,'AF7R36 R20 recursive rotational-energy support'), ...
    '[R20] R20 already installed.');

try
    %% --------------------------------------------------------------------
    % A. Replace repeated norm->energy reconstruction by recursive energy.
    % ---------------------------------------------------------------------
    old=[ ...
        '            V0=0.5*Jmax*W0^2;' sprintf('\n') ...
        '            sqrtVend=sqrt(V0)+tauNorm*h/sqrt(2*Jmin);' sprintf('\n') ...
        '            VwEnd=sqrtVend^2;' sprintf('\n') ...
        '            Wabs0=sqrt(2*V0/Jmin); WabsEnd=sqrt(2*VwEnd/Jmin);' sprintf('\n') ...
        '            Iw=Wabs0*h+tauNorm*h^2/(2*Jmin);'];

    new=[ ...
        '            % AF7R36 R20 recursive rotational-energy support.' sprintf('\n') ...
        '            if isfield(H,''w_sqrt_energy_ub'') && ...' sprintf('\n') ...
        '                    isscalar(H.w_sqrt_energy_ub) && ...' sprintf('\n') ...
        '                    isfinite(double(H.w_sqrt_energy_ub)) && ...' sprintf('\n') ...
        '                    double(H.w_sqrt_energy_ub)>=0' sprintf('\n') ...
        '                sqrtV0=double(H.w_sqrt_energy_ub);' sprintf('\n') ...
        '                energySeedFromBall=false;' sprintf('\n') ...
        '            else' sprintf('\n') ...
        '                % First recursive step only: derive kinetic-energy' sprintf('\n') ...
        '                % support directly from the certified omega ball.' sprintf('\n') ...
        '                wc0=double(H.w_center(:)); wr0=double(H.w_radius);' sprintf('\n') ...
        '                assert(numel(wc0)==3&&all(isfinite(wc0))&& ...' sprintf('\n') ...
        '                    isfinite(wr0)&&wr0>=0, ...' sprintf('\n') ...
        '                    ''[REPLANNER OBSERVER ERROR] omega support ball invalid.'');' sprintf('\n') ...
        '                Jwc0=Jd.*wc0;' sprintf('\n') ...
        '                V0ball=0.5*sum(wc0.*Jwc0)+wr0*norm(Jwc0)+0.5*Jmax*wr0^2;' sprintf('\n') ...
        '                V0ball=max(0,V0ball);' sprintf('\n') ...
        '                sqrtV0=sqrt(V0ball);' sprintf('\n') ...
        '                energySeedFromBall=true;' sprintf('\n') ...
        '            end' sprintf('\n') ...
        '            sqrtVend=sqrtV0+tauNorm*h/sqrt(2*Jmin);' sprintf('\n') ...
        '            VwEnd=sqrtVend^2;' sprintf('\n') ...
        '            Wabs0=sqrt(2/Jmin)*sqrtV0;' sprintf('\n') ...
        '            WabsEnd=sqrt(2/Jmin)*sqrtVend;' sprintf('\n') ...
        '            Iw=Wabs0*h+tauNorm*h^2/(2*Jmin);'];

    src=replace_once(src,old,new,'rotational energy recursion');

    %% B. Export theorem witnesses in forward-support record.
    anchor='            S.Jdiag=Jd; S.Jmin=Jmin; S.Jmax=Jmax;';
    repl=[anchor sprintf('\n') ...
        '            S.w_sqrt_energy_ub_start=sqrtV0;' sprintf('\n') ...
        '            S.w_sqrt_energy_ub_end=sqrtVend;' sprintf('\n') ...
        '            S.w_energy_ub_start=sqrtV0^2;' sprintf('\n') ...
        '            S.w_energy_ub_end=VwEnd;' sprintf('\n') ...
        '            S.energy_seed_from_ball=energySeedFromBall;'];
    src=replace_once(src,anchor,repl,'forward energy witness export');

    %% --------------------------------------------------------------------
    % C. After the existing two-event contraction, intersect the forward
    %    energy support with the contracted omega-ball energy support.
    % ---------------------------------------------------------------------
    anchor=[ ...
        '                I.hidden.w_center=K.w.center;' sprintf('\n') ...
        '                I.hidden.w_radius=K.w.radius;' sprintf('\n') ...
        '                I.hidden.w_norm_ub=K.w.true_norm_ub;'];

    repl=[ ...
        '                I.hidden.w_center=K.w.center;' sprintf('\n') ...
        '                I.hidden.w_radius=K.w.radius;' sprintf('\n') ...
        '                I.hidden.w_norm_ub=K.w.true_norm_ub;' sprintf('\n') ...
        '                % AF7R36 R20: intersect forward energy tube with' sprintf('\n') ...
        '                % the certified contracted Euclidean omega ball.' sprintf('\n') ...
        '                JdE=double(F.Jdiag(:)); JmaxE=max(JdE);' sprintf('\n') ...
        '                cwE=double(K.w.center(:)); rwE=double(K.w.radius);' sprintf('\n') ...
        '                assert(numel(cwE)==3&&all(isfinite(cwE))&& ...' sprintf('\n') ...
        '                    isfinite(rwE)&&rwE>=0, ...' sprintf('\n') ...
        '                    ''[REPLANNER OBSERVER ERROR] contracted omega ball invalid.'');' sprintf('\n') ...
        '                JcwE=JdE.*cwE;' sprintf('\n') ...
        '                VballE=0.5*sum(cwE.*JcwE)+rwE*norm(JcwE)+0.5*JmaxE*rwE^2;' sprintf('\n') ...
        '                VballE=max(0,VballE);' sprintf('\n') ...
        '                sqrtVballE=sqrt(VballE);' sprintf('\n') ...
        '                sqrtVforwardE=double(F.w_sqrt_energy_ub_end);' sprintf('\n') ...
        '                assert(isfinite(sqrtVforwardE)&&sqrtVforwardE>=0, ...' sprintf('\n') ...
        '                    ''[REPLANNER OBSERVER ERROR] forward omega energy support invalid.'');' sprintf('\n') ...
        '                I.hidden.w_sqrt_energy_ub=min(sqrtVforwardE,sqrtVballE);'];

    src=replace_once(src,anchor,repl,'contracted energy intersection');

    %% D. Preserve current support in public read-only status.
    anchor=[ ...
        '                ''hlc_state_mass_bridge'',''runtime_last_ms'',''runtime_max_ms'', ...' sprintf('\n') ...
        '                ''last_forward_failure''};'];
    if contains(src,anchor)
        repl=[ ...
            '                ''hlc_state_mass_bridge'',''runtime_last_ms'',''runtime_max_ms'', ...' sprintf('\n') ...
            '                ''last_forward_failure'',''last_forward_support''};'];
        src=replace_once(src,anchor,repl,'status forward-support exposure');
    end

    %% E. Structural theorem audits.
    assert(~contains(src,'V0=0.5*Jmax*W0^2;'), ...
        '[R20] Repeated Jmax norm->energy reconstruction survived.');
    assert(contains(src,'I.hidden.w_sqrt_energy_ub=min(sqrtVforwardE,sqrtVballE);'), ...
        '[R20] Energy-support intersection missing.');
    assert(contains(src,'V0ball=0.5*sum(wc0.*Jwc0)+wr0*norm(Jwc0)+0.5*Jmax*wr0^2;'), ...
        '[R20] Initial omega-ball energy theorem missing.');
    assert(contains(src,'S.closed=pitchClosed; S.h=h; S.held_input=u;'), ...
        '[R20] R19 pitch singularity theorem changed unexpectedly.');
    assert(contains(src,'observer_unique_2pi_lift'), ...
        '[R20] R19 periodic branch theorem disappeared.');

    write_text(rps,src);
    rehash

    fprintf('[R20] PASS.\n');
    fprintf('  recursive kinetic-energy hard support      = 1\n');
    fprintf('  repeated condition-number inflation        = removed\n');
    fprintf('  measurement contraction remains hard set   = 1\n');
    fprintf('  chart/branch safety theorem weakened        = 0\n');
    fprintf('  IMPORTANT: clear old objects/classes before next simulation.\n');

    OUT=struct('pass',true, ...
        'revision','AF7_ROT_ENERGY_RECURSIVE_SUPPORT_R20', ...
        'recursive_energy_support',true, ...
        'heuristic_coefficients',false, ...
        'chart_threshold_modified',false, ...
        'hard_safety_modified',false);

catch ME
    try,write_text(rps,src0);catch,end
    rehash
    fprintf(2,'[R20] FAILED. REPLANNING_SYSTEM source rolled back.\n');
    fprintf(2,'[R20] ORIGINAL ERROR: %s | %s\n',ME.identifier,ME.message);
    rethrow(ME);
end
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1,'[R20] Anchor "%s" count=%d; expected 1.',label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end

function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));
s=strrep(s,sprintf('\r'),sprintf('\n'));
end

function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');
assert(f>=0,'[R20] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end
