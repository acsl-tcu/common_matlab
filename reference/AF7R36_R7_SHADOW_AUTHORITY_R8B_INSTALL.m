function OUT = AF7R36_R7_SHADOW_AUTHORITY_R8B_INSTALL()
% AF7R36_R7_SHADOW_AUTHORITY_R8B_INSTALL
%
% Diagnostic-only authority repair for R7B.
%
% R7B is placed after the production primary family. Therefore when primary
% succeeds, R7B is not reached. A zero R7 candidate count in that situation
% means NOT-REACHED, not QP failure.
%
% R8 leaves production selection unchanged and evaluates R7B in a completely
% separate shadow path for EVERY fixed-t1 call. It records:
%   QP candidates, speed pass, rejoin pass, whole-body pass,
%   exact-heading regularity pass, certified metrics and finite speed witness.
%
% It also disables execution of the obsolete R6B homotopy diagnostic.
% R6B source helpers may remain compiled but are not run.
%
% No README and no persistent backup file.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 R7 SHADOW AUTHORITY R8B INSTALL\n');
fprintf(' production candidate selection modified    = 0\n');
fprintf(' hard safety semantics modified             = 0\n');
fprintf(' production primary/fallback order modified = 0\n');
fprintf(' R7 shadow forced on every fixed-t1 call     = 1\n');
fprintf(' obsolete R6B homotopy execution disabled   = 1\n');
fprintf(' early wrapper helper forward dependencies = 0\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir)&&isfolder(refDir), ...
    '[R7SHADOW-R8B] Cannot resolve current reference directory.');

hpp=fullfile(refDir,'af7r36_core.hpp');
cpp=fullfile(refDir,'af7r36_single_core_mex.cpp');
assert(isfile(hpp),'[R7SHADOW-R8B] Missing %s',hpp);
assert(isfile(cpp),'[R7SHADOW-R8B] Missing %s',cpp);

hpp0=normlf(fileread(hpp));
cpp0=normlf(fileread(cpp));
hppNew=hpp0;
cppNew=cpp0;

assert(contains(hpp0,'AF7_TOWING_C7_CONDENSED_C3_R7B'), ...
    '[R7SHADOW-R8B] R7B core is not installed.');
assert(contains(cpp0,'"TOWING_C7_CONDENSED_C3"'), ...
    '[R7SHADOW-R8B] R7B family wrapper is not installed.');
assert(contains(cpp0,'AF7_TOWMAP_R4C_RING'), ...
    '[R7SHADOW-R8B] R4C ring is required.');
assert(~contains(hpp0,'AF7_R7_SHADOW_AUTHORITY_R8B'), ...
    '[R7SHADOW-R8B] R8 core already installed.');
assert(~contains(cpp0,'AF7_R7_SHADOW_AUTHORITY_R8BB_RING'), ...
    '[R7SHADOW-R8B] R8 MEX ring already installed.');

try
    %% --------------------------------------------------------------------
    % 1) Add an independent R7-only shadow planner immediately before plan().
    % It never writes the production PlanResult.
    % ---------------------------------------------------------------------
    anchor='static inline PlanResult plan(const ActiveReference&ref,const Live&L,const SpeedCert&base,';
    shadow=[ ...
        '// AF7_R7_SHADOW_AUTHORITY_R8B' sprintf('\n') ...
        'struct C7R8ShadowResult {' sprintf('\n') ...
        '    bool success=false;' sprintf('\n') ...
        '    int reason=0,candidate_count=0,speed_pass=0,rejoin_pass=0,geom_pass=0,heading_pass=0;' sprintf('\n') ...
        '    Candidate cand;' sprintf('\n') ...
        '    SpeedCert speed;' sprintf('\n') ...
        '    double total_ms=0;' sprintf('\n') ...
        '};' sprintf('\n') ...
        '' sprintf('\n') ...
        'static inline C7R8ShadowResult c7r8_shadow_plan(' sprintf('\n') ...
        '        const ActiveReference&ref,const Live&L,const SpeedCert&base,' sprintf('\n') ...
        '        const std::vector<Obstacle>&obs,double t0,double tm,double t1){' sprintf('\n') ...
        '    using clk=std::chrono::steady_clock;const auto T0=clk::now();C7R8ShadowResult R;' sprintf('\n') ...
        '    if(!(fin(t0)&&fin(tm)&&fin(t1)&&t1>tm&&tm>t0&&L.dt>0)){R.reason=17;return R;}' sprintf('\n') ...
        '    EpisodeCert E=build_episode(ref,L,base,obs,t0,t1);' sprintf('\n') ...
        '    if(!E.ok||E.comp.empty()||E.ep.empty()){R.reason=22;return R;}' sprintf('\n') ...
        '    if(E.comp.front().start<=t0+8*epsd()*std::max(1.0,std::fabs(t0))){R.reason=14;return R;}' sprintf('\n') ...
        '    if(E.comp.back().end>=t1-8*epsd()*std::max(1.0,std::fabs(t1))){R.reason=17;return R;}' sprintf('\n') ...
        '' sprintf('\n') ...
        '    int Cn=(int)E.comp.size(),Ne=(int)E.ep.size(),nvar=6*Cn;' sprintf('\n') ...
        '    std::vector<OrientedRows> OR(Ne);' sprintf('\n') ...
        '    for(int e=0;e<Ne;++e){' sprintf('\n') ...
        '        auto ep=E.ep[e];auto xa=ref.eval(ep.start),xb=ref.eval(ep.end);Vec3 prog=xb[0]-xa[0];' sprintf('\n') ...
        '        if(norm(prog)<=128*epsd()*std::max(1.0,norm(xa[0])))prog=ref.eval(0.5*(ep.start+ep.end))[1];' sprintf('\n') ...
        '        Vec3 n=lateral_normal(obs[ep.obs].R,obs[ep.obs].axes,prog);' sprintf('\n') ...
        '        OR[e].plus=corridor_rows(ref,L,base,obs,E,e,n,nvar);' sprintf('\n') ...
        '        OR[e].minus=corridor_rows(ref,L,base,obs,E,e,n*(-1),nvar);' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '    double rhoBody=std::max({L.rQ,L.L+L.rL,L.L+L.rC});' sprintf('\n') ...
        '    double lim=(L.sensor_range-rhoBody)/(L.horizon+L.dt);' sprintf('\n') ...
        '    if(!(fin(lim)&&lim>0)){R.reason=16;return R;}' sprintf('\n') ...
        '' sprintf('\n') ...
        '    struct BaseR8{std::vector<double>z;double c=0,s=0;std::vector<int>sg;};' sprintf('\n') ...
        '    auto MR=c7r7_model(E.comp,t0,t1,L.L,L.g);' sprintf('\n') ...
        '    std::vector<BaseR8>B;std::vector<int>sg(Ne,1);' sprintf('\n') ...
        '    std::function<void(int)> rec=[&](int k){' sprintf('\n') ...
        '        if(k<Ne){sg[k]=1;rec(k+1);sg[k]=-1;rec(k+1);return;}' sprintf('\n') ...
        '        std::vector<Row>rows;' sprintf('\n') ...
        '        for(int e=0;e<Ne;++e){const auto&src=sg[e]>0?OR[e].plus:OR[e].minus;rows.insert(rows.end(),src.begin(),src.end());}' sprintf('\n') ...
        '        QPSol q=solve_qp(MR.H,nvar,rows);' sprintf('\n') ...
        '        if(q.ok)B.push_back({q.z,q.cost,q.slack,sg});' sprintf('\n') ...
        '    };rec(0);' sprintf('\n') ...
        '' sprintf('\n') ...
        '    std::vector<Candidate>C;' sprintf('\n') ...
        '    C.reserve(B.size());for(auto&b:B)C.push_back(build_candidate_c7r7(E.comp,t0,t1,b.z,b.c,b.sg,b.s,MR,3));' sprintf('\n') ...
        '    R.candidate_count=(int)C.size();' sprintf('\n') ...
        '    std::stable_sort(C.begin(),C.end(),candidate_envelope_less);' sprintf('\n') ...
        '' sprintf('\n') ...
        '    for(auto cand:C){' sprintf('\n') ...
        '        SpeedCert sc;auto tr=tighten_stageA(cand,base,L.L,lim);' sprintf('\n') ...
        '        if(tr.certified){' sprintf('\n') ...
        '            sc=stageA_speed(tr,base,L.L);' sprintf('\n') ...
        '            if(sc.certified&&sc.VQ<lim){cand.dub[0]=tr.U[0];cand.dub[1]=tr.U[1];cand.dub[2]=tr.U[2];}' sprintf('\n') ...
        '            else sc.certified=false;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '        if(!sc.certified){bool wit=false,rp=false;sc=stageB_speed(ref,L,base,cand,lim,wit,rp);}' sprintf('\n') ...
        '        if(!sc.certified)continue;' sprintf('\n') ...
        '        ++R.speed_pass;' sprintf('\n') ...
        '        if(!rejoin_safe(ref,L,obs,t1,sc))continue;' sprintf('\n') ...
        '        ++R.rejoin_pass;' sprintf('\n') ...
        '        auto G=wholebody(ref,L,obs,t0,tm,E.comp.back().end,t1,cand,sc);' sprintf('\n') ...
        '        if(!G.pass)continue;' sprintf('\n') ...
        '        ++R.geom_pass;' sprintf('\n') ...
        '        if(!c7r7_heading_regular(ref,cand,sc,t0,t1))continue;' sprintf('\n') ...
        '        ++R.heading_pass;' sprintf('\n') ...
        '        R.success=true;R.reason=0;R.cand=std::move(cand);R.speed=sc;' sprintf('\n') ...
        '        R.total_ms=std::chrono::duration<double,std::milli>(clk::now()-T0).count();return R;' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '    if(R.candidate_count==0)R.reason=23;' sprintf('\n') ...
        '    else if(R.speed_pass==0)R.reason=24;' sprintf('\n') ...
        '    else if(R.rejoin_pass==0)R.reason=25;' sprintf('\n') ...
        '    else if(R.geom_pass==0)R.reason=26;' sprintf('\n') ...
        '    else R.reason=27;' sprintf('\n') ...
        '    R.total_ms=std::chrono::duration<double,std::milli>(clk::now()-T0).count();return R;' sprintf('\n') ...
        '}' sprintf('\n') ...
        '' sprintf('\n') ...
        anchor];
    hppNew=replace_once(hppNew,anchor,shadow,'pre-plan R7 shadow helper');

    %% --------------------------------------------------------------------
    % 2) Disable obsolete R6B homotopy execution. Source helpers remain.
    % ---------------------------------------------------------------------
    old='    if(OUT.success)c7front_run(ref,L,base,obs,t0,tm,t1,E);';
    if contains(hppNew,old)
        new='    /* R8: obsolete R6B homotopy execution disabled; production result unchanged. */';
        hppNew=replace_once(hppNew,old,new,'disable R6B homotopy execution');
    end

    %% --------------------------------------------------------------------
    % 3) Add shadow ring to the MEX wrapper.
    % ---------------------------------------------------------------------
    anchor='static bool G_compiled=false;';
    ring=[anchor sprintf('\n') sprintf('\n') ...
        '// AF7_R7_SHADOW_AUTHORITY_R8BB_RING -- diagnostic only.' sprintf('\n') ...
        'struct C7R8MexRow {' sprintf('\n') ...
        '    double seq=0,t0=NAN,tm=NAN,t1=NAN,limit=NAN,success=0,reason=0;' sprintf('\n') ...
        '    double cand=0,speed=0,rejoin=0,geom=0,heading=0;' sprintf('\n') ...
        '    double env=NAN,VQ=NAN,VL=NAN,A=NAN,J=NAN,sigma=NAN,qdot=NAN,total_ms=NAN;' sprintf('\n') ...
        '    double wc=0,wmin=NAN,wmint=NAN,wmins=NAN,wminc=NAN,wmax=NAN,wmaxt=NAN,wmaxs=NAN,wmaxc=NAN;' sprintf('\n') ...
        '};' sprintf('\n') ...
        'static std::vector<C7R8MexRow> G_r7shadow;' sprintf('\n') ...
        'static double G_r7shadow_seq=0;' sprintf('\n') ...
        'static void r7shadow_push(const C7R8ShadowResult&Q,const Live&L,double t0,double tm,double t1){' sprintf('\n') ...
        '    C7R8MexRow d;d.seq=++G_r7shadow_seq;d.t0=t0;d.tm=tm;d.t1=t1;' sprintf('\n') ...
        '    double rho=std::max({L.rQ,L.L+L.rL,L.L+L.rC});d.limit=(L.sensor_range-rho)/(L.horizon+L.dt);' sprintf('\n') ...
        '    d.success=Q.success?1:0;d.reason=Q.reason;d.cand=Q.candidate_count;d.speed=Q.speed_pass;d.rejoin=Q.rejoin_pass;d.geom=Q.geom_pass;d.heading=Q.heading_pass;' sprintf('\n') ...
        '    if(Q.success){d.env=Q.cand.max_ctrl;d.VQ=Q.speed.VQ;d.VL=Q.speed.VL;d.A=Q.speed.A;d.J=Q.speed.J;d.sigma=Q.speed.sigma;d.qdot=Q.speed.qdot;}' sprintf('\n') ...
        '    d.total_ms=Q.total_ms;' sprintf('\n') ...
        '    const auto&W=G_towmap_towing_witness;d.wc=W.count;d.wmin=std::isfinite(W.min_vq)?W.min_vq:NAN;d.wmint=W.min_t;d.wmins=W.min_seg;d.wminc=W.min_class;' sprintf('\n') ...
        '    d.wmax=std::isfinite(W.max_vq)?W.max_vq:NAN;d.wmaxt=W.max_t;d.wmaxs=W.max_seg;d.wmaxc=W.max_class;' sprintf('\n') ...
        '    if(G_r7shadow.size()>=512)G_r7shadow.erase(G_r7shadow.begin());G_r7shadow.push_back(d);' sprintf('\n') ...
        '}' sprintf('\n') ...
        'static mxArray* r7shadow_matrix(){' sprintf('\n') ...
        '    const mwSize N=(mwSize)G_r7shadow.size(),C=29;mxArray*M=mxCreateDoubleMatrix(N,C,mxREAL);double*p=mxGetPr(M);' sprintf('\n') ...
        '    for(mwSize i=0;i<N;++i){const auto&d=G_r7shadow[i];double v[C]={' sprintf('\n') ...
        '        d.seq,d.t0,d.tm,d.t1,d.limit,d.success,d.reason,d.cand,d.speed,d.rejoin,d.geom,d.heading,' sprintf('\n') ...
        '        d.env,d.VQ,d.VL,d.A,d.J,d.sigma,d.qdot,d.total_ms,d.wc,d.wmin,d.wmint,d.wmins,d.wminc,d.wmax,d.wmaxt,d.wmaxs,d.wmaxc};' sprintf('\n') ...
        '        for(mwSize j=0;j<C;++j)p[i+N*j]=v[j];' sprintf('\n') ...
        '    }return M;' sprintf('\n') ...
        '}'];
    cppNew=replace_once(cppNew,anchor,ring,'R8 MEX ring globals');

    %% --------------------------------------------------------------------
    % 4) Run R7 shadow AFTER production result/rings are captured.
    % Production Q is already fixed before this call.
    % ---------------------------------------------------------------------
    anchor='            towmap_push(Q,L,t0,tm,searchEnd);';
    new=[anchor sprintf('\n') ...
        '            towmap_core_reset_witness();' sprintf('\n') ...
        '            C7R8ShadowResult Q7=c7r8_shadow_plan(R,L,B,O,t0,tm,searchEnd);' sprintf('\n') ...
        '            r7shadow_push(Q7,L,t0,tm,searchEnd);' sprintf('\n') ...
        '            towmap_core_reset_witness();'];
    cppNew=replace_once(cppNew,anchor,new,'per-call R7 shadow execution');

    %% --------------------------------------------------------------------
    % 5) op10 = read, op11 = clear.
    % ---------------------------------------------------------------------
    anchor='        if(op==3){';
    ops=[ ...
        '        if(op==10){' sprintf('\n') ...
        '            if(nrhs!=1||nlhs!=1)mexErrMsgIdAndTxt("AF7R7SHADOW:Arity","op10 -> matrix.");' sprintf('\n') ...
        '            plhs[0]=r7shadow_matrix();return;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '        if(op==11){' sprintf('\n') ...
        '            if(nrhs!=1||nlhs>1)mexErrMsgIdAndTxt("AF7R7SHADOW:Arity","op11 clear.");' sprintf('\n') ...
        '            G_r7shadow.clear();G_r7shadow_seq=0;' sprintf('\n') ...
        '            if(nlhs>0)plhs[0]=logicalScalar(true);return;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        anchor];
    cppNew=replace_once(cppNew,anchor,ops,'R8 diagnostic ops');

    %% --------------------------------------------------------------------
    % 6) Structural invariants.
    % ---------------------------------------------------------------------
    assert(contains(cppNew, ...
        'static const char* PLANNER_REV="AF7_REPLANNER_MIN_DEVIATION_V4_FIXED_T1";'), ...
        '[R7SHADOW-R8B] Planner revision changed unexpectedly.');
    assert(contains(cppNew,'"TOWING_C7_CONDENSED_C3"'), ...
        '[R7SHADOW-R8B] R7B family label disappeared.');
    assert(count_exact(hppNew,'AF7_R7_SHADOW_AUTHORITY_R8B')>=1, ...
        '[R7SHADOW-R8B] Core shadow marker missing.');
    assert(count_exact(cppNew,'AF7_R7_SHADOW_AUTHORITY_R8BB_RING')==1, ...
        '[R7SHADOW-R8B] MEX shadow marker count invalid.');
    assert(count_exact(cppNew,'C7R8ShadowResult Q7=c7r8_shadow_plan')==1, ...
        '[R7SHADOW-R8B] Shadow execution count invalid.');
    assert(count_exact(cppNew,'d.wmin=std::isfinite(W.min_vq)?W.min_vq:NAN;')==1 && ...
           count_exact(cppNew,'d.wmax=std::isfinite(W.max_vq)?W.max_vq:NAN;')==1, ...
        '[R7SHADOW-R8B] Self-contained witness finite conversion missing.');

    %% --------------------------------------------------------------------
    % 7) Stage compile before production write.
    % ---------------------------------------------------------------------
    stageDir=tempname;
    [ok,msg]=mkdir(stageDir);
    assert(ok,'[R7SHADOW-R8B] Cannot create staging directory: %s',msg);
    stageCleanup=onCleanup(@()cleanup_stage(stageDir)); %#ok<NASGU>

    stagedHpp=fullfile(stageDir,'af7r36_core.hpp');
    stagedCpp=fullfile(stageDir,'af7r36_single_core_mex.cpp');
    write_text(stagedHpp,hppNew);
    write_text(stagedCpp,cppNew);

    fprintf('[R7SHADOW-R8B] Compiling staged diagnostic MEX...\n');
    oldDir=pwd;
    cwdCleanup=onCleanup(@()cd(oldDir)); %#ok<NASGU>
    cd(stageDir);clear mex;
    mex('-R2018a','-O', ...
        'COMPFLAGS="$COMPFLAGS /std:c++17"', ...
        ['-I' stageDir], ...
        '-output','af7r36_single_core_mex', ...
        '-outdir',stageDir, ...
        stagedCpp);

    stagedMex=fullfile(stageDir,['af7r36_single_core_mex.' mexext]);
    assert(isfile(stagedMex),'[R7SHADOW-R8B] Staged MEX missing.');

    dstMex=fullfile(refDir,['af7r36_single_core_mex.' mexext]);
    oldMexTmp=fullfile(stageDir,['af7r36_single_core_mex_OLD.' mexext]);
    hadOldMex=isfile(dstMex);
    if hadOldMex
        [ok,msg]=copyfile(dstMex,oldMexTmp,'f');
        assert(ok,'[R7SHADOW-R8B] Cannot stage rollback MEX: %s',msg);
    end

    cd(oldDir);clear mex;
    wroteH=false;wroteC=false;installedMex=false;
    try
        write_text(hpp,hppNew);wroteH=true;
        write_text(cpp,cppNew);wroteC=true;
        [ok,msg]=copyfile(stagedMex,dstMex,'f');
        assert(ok,'[R7SHADOW-R8B] Cannot install staged MEX: %s',msg);
        installedMex=true;
        clear mex;rehash;
        assert(exist('af7r36_single_core_mex','file')==3, ...
            '[R7SHADOW-R8B] Installed MEX not visible.');
        try,af7r36_single_core_mex(7);catch,end
        try,af7r36_single_core_mex(9);catch,end
        af7r36_single_core_mex(11);
    catch ME2
        if wroteH,try,write_text(hpp,hpp0);catch,end,end
        if wroteC,try,write_text(cpp,cpp0);catch,end,end
        if installedMex&&hadOldMex,try,copyfile(oldMexTmp,dstMex,'f');catch,end,end
        clear mex;rehash;rethrow(ME2);
    end

    fprintf('[R7SHADOW-R8B] PASS.\n');
    fprintf('  production selection unchanged             = 1\n');
    fprintf('  R7 shadow executes even if primary passes  = 1\n');
    fprintf('  C7 + speed + rejoin + wholebody + heading  = shadow hard gates\n');
    fprintf('  obsolete R6B homotopy execution            = 0\n');
    fprintf('  README created                              = 0\n');
    fprintf('  persistent backup files created             = 0\n');
    fprintf('  NOTE: shadow runtime is diagnostic only.\n');

    OUT=struct('pass',true, ...
        'revision','AF7_R7_SHADOW_AUTHORITY_R8B', ...
        'production_selection_modified',false, ...
        'hard_safety_modified',false, ...
        'r7_shadow_every_fixed_t1',true, ...
        'r6b_homotopy_execution',false);

catch ME
    clear mex;rehash;
    fprintf(2,'[R7SHADOW-R8B] FAILED. No successful production install completed.\n');
    rethrow(ME);
end
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1, ...
    '[R7SHADOW-R8B] Anchor "%s" count=%d; expected 1.',label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end

function n=count_exact(txt,pat)
n=numel(strfind(txt,pat));
end

function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));
s=strrep(s,sprintf('\r'),sprintf('\n'));
end

function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');
assert(f>=0,'[R7SHADOW-R8B] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end

function cleanup_stage(d)
if isfolder(d)
    try,rmdir(d,'s');catch,end
end
end
