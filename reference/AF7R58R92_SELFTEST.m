function T=AF7R58R92_SELFTEST()
% Synthetic unit test ONLY: not a real Flight, real HLC/tube, or IEEE proof.
req={'AF7R58R91_STABLE_KINEMATIC_CERT', ...
    'AF7R58R80_HEADING_C6_CERT', ...
    'AF7R58R80_CONTINUOUS_SEPARATE_BODY_CERT', ...
    'AF7R58R90_INPUT_ENVELOPE'};
for k=1:numel(req)
    assert(exist(req{k},'file')==2, ...
        'R92:MissingPreviouslyInstalledCertifier:%s',req{k});
end
% The synthetic nominal follows a straight path with nonzero XY speed.
times=[0 1 2];wps=[0 1 2;0 0 0;-2 -2 -2];
A=zeros(3,8);B=zeros(3,8);
A(:,1)=wps(:,1);B(:,1)=wps(:,end);
A(1,2)=1;B(1,2)=1;
C=AF7R58R92_C7_MINIMUM8_ROUTE(times,wps,A,B,0.2,2);
assert(C.reference_candidate_found&&C.num_segments==2&& ...
    C.continuity_order==7&&~C.production_commit_authorized, ...
    'R92:GlobalC7ConstructionFailed');
% Algebraic exact C7: common knot jets 0..7 used by BOTH adjacent segments.
% Float evaluation differences are checked separately, never safety proof.
assert(isequal(C.segments(1).t1,C.segments(2).t0), ...
    'R92:NonadjacentSegments');
assert(max(abs(C.knot_jets(:,1,2)-wps(:,2)))==0, ...
    'R92:KnotDrift');
assert(all(isfinite(C.knot_jets(:,2,2))), ...
    'R92:NonfiniteInternalVelocity');
% All runtime physical inputs here are explicitly SYNTHETIC test values.
live=struct('gravity_m_s2',9.81,'cable_length_m',2, ...
    'rQ_m',0.1,'rC_m',0.1,'rL_m',0.1, ...
    'finite_sensing_vQ_limit_m_s',3.1, ...
    'vehicle_mass_kg',0.762,'latest_EKF_mL_kg',0.02, ...
    'thrust_bounds_N',[0 20], ...
    'torque_bounds_Nm',[-1 1;-1 1;-1 1], ...
    'tension_max_N',1);
obs=struct('center',[0;100;-2],'R',eye(3), ...
    'axes',[0.5;0.8;1]);
opts=struct('max_nodes_per_check',256, ...
    'operational_uav_speed_limit_m_s',1.5);
wide=struct('A',[eye(3);-eye(3)],'b',4*ones(6,1));
K=AF7R58R92_CERTIFY_ALL_SEGMENTS(C,obs,live,opts,{wide,wide});
assert(K.all_segment_reference_conditions_pass&& ...
    K.heading_c6_certified&&K.corridor_constraints_pass&& ...
    ~K.actual_hlc_torque_certified&&~K.production_commit_authorized, ...
    'R92:SyntheticStraightReferenceFailure');
% A corridor excluding the payload must never be silently accepted.
invalid=struct('A',[1 0 0],'b',-10);
D=AF7R58R92_CERTIFY_ALL_SEGMENTS(C,obs,live,opts,{invalid,wide});
assert(~D.all_segment_reference_conditions_pass&& ...
    ~D.segments(1).corridor_pass&& ...
    ~D.production_commit_authorized,'R92:UnsafeCorridorAccepted');
% Missing external input authority must fail closed, never guessed.
L=rmfield(live,'vehicle_mass_kg');
E=AF7R58R92_CERTIFY_ALL_SEGMENTS(C,obs,L,opts,{wide,wide});
assert(~E.all_segment_reference_conditions_pass&& ...
    ~E.input_authorities_available&&~E.production_commit_authorized, ...
    'R92:InputFallbackIntroduced');
% Analytic support-seed routes for an arbitrary SO(3) ellipsoid.
alpha=0.37;Rot=[cos(alpha) -sin(alpha) 0;sin(alpha) cos(alpha) 0;0 0 1];
o2=struct('center',[1;0;-2],'R',Rot,'axes',[0.3;0.8;0.5]);
Seeds=AF7R58R92_SUPPORT_SEED_ROUTES( ...
    [0;0;-2],[2;0;-2],o2,0.1,4);
assert(Seeds.assignments_considered==4&& ...
    numel(Seeds.routes)==4&& ...
    all(cellfun(@(x)isequal(size(x),[3 1]),Seeds.routes)), ...
    'R92:RotatedEllipsoidSeedFailure');
% Two independent switches: robust inflation affects ONLY added radii;
% backup status is independent and does not pretend an actual failsafe exists.
LV=live;LV.source_reference_version=7;
tube=struct('uav_position_error_m',0.03, ...
 'cable_position_error_m',0.02,'payload_position_error_m',0.01, ...
 'reference_version',7,'estimated_mass_kg',0.02, ...
 'source_bound_certified',true);
[V_on,D_on]=AF7R58R92_TRACKING_INFLATION( ...
 LV,struct('robust_tracking_inflation_on',1,'failure_backup_on',0, ...
           'tracking_tube',tube));
[V_off,D_off]=AF7R58R92_TRACKING_INFLATION( ...
 LV,struct('robust_tracking_inflation_on',0,'failure_backup_on',1, ...
           'tracking_tube',tube));
assert(abs(V_on.rQ_m-(LV.rQ_m+0.03))<1e-12&& ...
 abs(V_on.rC_m-(LV.rC_m+0.02))<1e-12&& ...
 V_off.rQ_m==LV.rQ_m&&V_off.rC_m==LV.rC_m&& ...
 ~D_on.failure_backup_on && D_off.failure_backup_on && ...
 ~D_on.execution_robust_tube_mathematically_proved, ...
 'R92:TwoIndependentDiagnosticSwitchesNotMaintained');
% Nonlinear 3D waypoints must still produce a C7 multi-segment curve.
w2=[0 1 2 4;0 1 -0.5 0;-2 -1.5 -2.5 -2];
j0=zeros(3,8);je=zeros(3,8);j0(:,1)=w2(:,1);je(:,1)=w2(:,end);
j0(1,2)=0.5;je(1,2)=0.5;
F=AF7R58R92_C7_MINIMUM8_ROUTE([0 2 4 8],w2,j0,je,1,2);
assert(F.reference_candidate_found&&F.num_segments==3&& ...
    F.continuity_order==7,'R92:Multi3DRouteFailed');
T=struct('status','PASS_R92_MULTISEGMENT_C7_MIN8_AND_FAIL_CLOSED_REFERENCE_GATE', ...
    'linear_test_sections',C.num_segments, ...
    'three_dimensional_test_sections',F.num_segments, ...
    'rotated_ellipsoid_seed_alternatives',numel(Seeds.routes), ...
    'synthetic_reference_geometry_kinematics_input_pass', ...
        K.all_segment_reference_conditions_pass, ...
    'unsafe_corridor_rejected',~D.all_segment_reference_conditions_pass, ...
    'missing_external_input_rejected',~E.all_segment_reference_conditions_pass, ...
    'separate_robust_and_backup_flags_tested',true, ...
    'continuity_0_to_7_algebraic',true, ...
    'path_tangent_yaw_c6_synthetic_test',K.heading_c6_certified, ...
    'real_flight_trigger_replaced',false, ...
    'full_closed_loop_and_ieee_proved',false, ...
    'production_modified',false);
end
