function OUT = AF7R38_INSTALL_10S_ATTRIBUTION_V3()
% Robust read-only timing attribution for the remaining 10 s path.
% Run AFTER corrected R38 V2 already succeeded.
% Safety/acceptance logic is unchanged. Added values are diagnostic only.

clc;
fprintf('\n====================================================================================================\n');
fprintf(' AF7R38 V3 | ROBUST 10 s POST-CALLBACK ATTRIBUTION INSTALL\n');
fprintf('====================================================================================================\n');
fprintf('[AUTHORITY] diagnosticOnly=1 | safetyLogicUnchanged=1 | hard4msUnchanged=1\n');

src=which('REPLANNING_SYSTEM');
if isempty(src)
    cand=fullfile(pwd,'REPLANNING_SYSTEM.m');
    assert(isfile(cand), ...
        '[AF7R38V3] REPLANNING_SYSTEM.m unresolved. cd to the reference folder first.');
    src=cand;
end
assert(isfile(src),'[AF7R38V3] source file missing.');
raw=fileread(src);

assert(contains(raw,'AF7R37-R14D-PRODUCTION'), ...
    '[AF7R38V3] R14D production marker missing.');
assert(contains(raw,'AF7R38-PREFLIGHT-POLICY-HOTPATH'), ...
    '[AF7R38V3] corrected R38 policy/preflight patch is not installed.');
assert(~contains(raw,'AF7R38V3-10S-ATTRIBUTION'), ...
    '[AF7R38V3] attribution patch already installed.');

root=fileparts(src);
stamp=datestr(now,'yyyymmdd_HHMMSS');
bak=fullfile(root,['REPLANNING_SYSTEM_pre_R38V3attr_' stamp '.m']);
[ok,msg]=copyfile(src,bak,'f');
assert(ok,'[AF7R38V3] backup failed: %s',msg);

% Marker.
raw=insert_after_unique(raw, ...
    'classdef\s+REPLANNING_SYSTEM\s*<\s*handle', ...
    sprintf('\n\n%% AF7R38V3-10S-ATTRIBUTION: read-only post-callback timing attribution.'));

% Diagnostic properties. Whitespace-tolerant anchor.
propAnchor='(?m)^[ \t]*postcallback_prime_candidate_found[ \t]*=[ \t]*false;[ \t]*$';
propText=sprintf([ ...
'\n        %% AF7R38V3 diagnostic-only timing fields\n' ...
'        r38_ref_eval_ms                  = NaN;\n' ...
'        r38_commit_prepare_ms            = NaN;\n' ...
'        r38_commit_rebuild_ms            = NaN;\n' ...
'        r38_commit_total_ms              = NaN;\n' ...
'        r38_commit_attempt_count         = 0;\n' ...
'        r38_commit_last_ok               = false;\n' ...
'        r38_commit_last_reason           = '''';']);
raw=insert_after_unique(raw,propAnchor,propText);

% REFERENCE_ONLY reference-certificate evaluation timing.
pat=[ ...
'(?m)^([ \t]*)case[ \t]+''REFERENCE_ONLY''[ \t]*\r?\n' ...
'\1[ \t]+if[ \t]+obj\.ENABLE_REFERENCE_ONLY_CERTIFICATE[ \t]*\r?\n' ...
'\1[ \t]+[ \t]*Rref=obj\.evaluate_reference_only_proposal_certificate\(candidate\);'];
[s,e,tok]=regexp(raw,pat,'start','end','tokens');
assert(numel(s)==1, ...
    '[AF7R38V3] REFERENCE_ONLY certificate anchor count mismatch (%d).',numel(s));
indent=tok{1}{1};
newBlock=sprintf([ ...
'%scase ''REFERENCE_ONLY''\n' ...
'%s    if obj.ENABLE_REFERENCE_ONLY_CERTIFICATE\n' ...
'%s        tr38_ref=tic;\n' ...
'%s        Rref=obj.evaluate_reference_only_proposal_certificate(candidate);\n' ...
'%s        obj.r38_ref_eval_ms=1e3*toc(tr38_ref);'], ...
indent,indent,indent,indent,indent);
raw=[raw(1:s-1) newBlock raw(e+1:end)];

% Commit function entrance timing.
pat=[ ...
'(?m)^([ \t]*)function[ \t]+\[ok,reason\][ \t]*=[ \t]*' ...
'try_commit_reference_only_proposal\(obj,P,t_commit,t_hard_cycle\)[ \t]*\r?\n' ...
'\1[ \t]+ok=false;[ \t]*\r?\n' ...
'\1[ \t]+reason='''';'];
[s,e,tok]=regexp(raw,pat,'start','end','tokens');
assert(numel(s)==1, ...
    '[AF7R38V3] commit function entrance anchor count mismatch (%d).',numel(s));
ind=tok{1}{1};
new=sprintf([ ...
'%sfunction [ok,reason] = try_commit_reference_only_proposal(obj,P,t_commit,t_hard_cycle)\n' ...
'%s    ok=false;\n' ...
'%s    reason='''';\n' ...
'%s    obj.r38_commit_attempt_count=obj.r38_commit_attempt_count+1;\n' ...
'%s    obj.r38_commit_last_ok=false;\n' ...
'%s    obj.r38_commit_last_reason='''';\n' ...
'%s    obj.r38_commit_prepare_ms=NaN;\n' ...
'%s    obj.r38_commit_rebuild_ms=NaN;\n' ...
'%s    obj.r38_commit_total_ms=NaN;\n' ...
'%s    tr38_total=tic;'], ...
ind,ind,ind,ind,ind,ind,ind,ind,ind,ind);
raw=[raw(1:s-1) new raw(e+1:end)];

% Commit prepare/evaluation interval.
pat='(?m)^([ \t]*)evalFn=@\(tg\)obj\.evaluate_bezier_proposal_reference\(tg,P\);[ \t]*$';
[s,e,tok]=regexp(raw,pat,'start','end','tokens');
assert(numel(s)==1, ...
    '[AF7R38V3] commit evalFn anchor count mismatch (%d).',numel(s));
ind2=tok{1}{1};
replacement=sprintf([ ...
'%str38_prepare=tic;\n' ...
'%sevalFn=@(tg)obj.evaluate_bezier_proposal_reference(tg,P);'],ind2,ind2);
raw=[raw(1:s-1) replacement raw(e+1:end)];

pat='(?m)^([ \t]*)old=struct\([ \t]*\.\.\.[ \t]*$';
[s,e,tok]=regexp(raw,pat,'start','end','tokens');
assert(numel(s)==1, ...
    '[AF7R38V3] commit rollback-snapshot anchor count mismatch (%d).',numel(s));
ind3=tok{1}{1};
replacement=sprintf([ ...
'%sobj.r38_commit_prepare_ms=1e3*toc(tr38_prepare);\n' ...
'%sold=struct( ...'],ind3,ind3);
raw=[raw(1:s-1) replacement raw(e+1:end)];

% Rebuild interval.
pat=[ ...
'(?m)^([ \t]*)obj\.validate_active_speed_certificate\(SC\);[ \t]*\r?\n' ...
'\1obj\.trigger_sweep_inflation='];
[s,e,tok]=regexp(raw,pat,'start','end','tokens');
assert(numel(s)==1, ...
    '[AF7R38V3] commit rebuild start anchor count mismatch (%d).',numel(s));
ind4=tok{1}{1};
old=raw(s:e);
needle2='obj.trigger_sweep_inflation=';
k=strfind(old,needle2);
assert(numel(k)==1);
new=[old(1:k-1) sprintf('tr38_rebuild=tic;\n%s',ind4) old(k:end)];
raw=[raw(1:s-1) new raw(e+1:end)];

pat=[ ...
'(?m)^([ \t]*)obj\.runtime_dependency_signature=[ \t]*\.\.\.[ \t]*\r?\n' ...
'\1[ \t]+obj\.capture_runtime_dependency_signature_fast\(\);'];
[s,e,tok]=regexp(raw,pat,'start','end','tokens');
assert(numel(s)==1, ...
    '[AF7R38V3] dependency signature anchor count mismatch (%d).',numel(s));
ind5=tok{1}{1};
old=raw(s:e);
new=[old sprintf('\n%sobj.r38_commit_rebuild_ms=1e3*toc(tr38_rebuild);',ind5)];
raw=[raw(1:s-1) new raw(e+1:end)];

% Success total/status.
pat=[ ...
'(?m)^([ \t]*)ok=true;[ \t]*\r?\n' ...
'\1reason=''REFERENCE_ONLY_COMMIT_CLOSED'';'];
[s,e,tok]=regexp(raw,pat,'start','end','tokens');
assert(numel(s)==1, ...
    '[AF7R38V3] commit success anchor count mismatch (%d).',numel(s));
ind6=tok{1}{1};
new=sprintf([ ...
'%sok=true;\n' ...
'%sreason=''REFERENCE_ONLY_COMMIT_CLOSED'';\n' ...
'%sobj.r38_commit_total_ms=1e3*toc(tr38_total);\n' ...
'%sobj.r38_commit_last_ok=true;\n' ...
'%sobj.r38_commit_last_reason=reason;'],ind6,ind6,ind6,ind6,ind6);
raw=[raw(1:s-1) new raw(e+1:end)];

% Rollback/catch total/status.
pat=[ ...
'(?m)^([ \t]*)obj\.last_replan_commit_time=old\.time;[ \t]*\r?\n' ...
'\1reason=ME\.message;'];
[s,e,tok]=regexp(raw,pat,'start','end','tokens');
assert(numel(s)==1, ...
    '[AF7R38V3] commit rollback tail anchor count mismatch (%d).',numel(s));
ind7=tok{1}{1};
new=sprintf([ ...
'%sobj.last_replan_commit_time=old.time;\n' ...
'%sreason=ME.message;\n' ...
'%sobj.r38_commit_total_ms=1e3*toc(tr38_total);\n' ...
'%sobj.r38_commit_last_ok=false;\n' ...
'%sobj.r38_commit_last_reason=reason;'],ind7,ind7,ind7,ind7,ind7);
raw=[raw(1:s-1) new raw(e+1:end)];

% Invariants.
compact=regexprep(raw,'\s+','');
needle=[char(39) 'sampled_acceptance' char(39) ',true'];
assert(~contains(compact,needle), ...
    '[AF7R38V3] sampled_acceptance=true detected.');
assert(contains(raw,'hard_modify_deadline_s<=4.0e-3'), ...
    '[AF7R38V3] hard 4 ms source contract disappeared.');
assert(contains(raw,'MIDPOINT_STATIC_SUPPORT_MINUS_SPEED_TIMES_HALFWIDTH'), ...
    '[AF7R38V3] whole-body theorem marker disappeared.');
assert(contains(raw,'R9_LOCAL_VECTOR_COUPLED_ADAPTIVE_BERNSTEIN_FLATNESS_SPEED'), ...
    '[AF7R38V3] R9 theorem marker disappeared.');

fid=fopen(src,'w');
assert(fid>=0,'[AF7R38V3] cannot open source for writing.');
cc=onCleanup(@()fclose(fid));
fwrite(fid,raw,'char');
clear cc;
rehash;

OUT=struct('schema','AF7R38_INSTALL_10S_ATTRIBUTION_V3', ...
    'installed',true,'source',src,'backup',bak, ...
    'diagnostic_only',true,'hard_deadline_modified',false, ...
    'safety_logic_modified',false);
assignin('base','AF7R38_INSTALL_10S_ATTRIBUTION_V3_OUT',OUT);

fprintf(' source                                  = %s\n',src);
fprintf(' backup                                  = %s\n',bak);
fprintf(' robust property insertion               = 1\n');
fprintf(' reference-cert timing                   = 1\n');
fprintf(' commit prepare/rebuild/total timing      = 1\n');
fprintf(' safety logic modified                   = 0\n');
fprintf(' hard deadline modified                  = 0\n');
fprintf('====================================================================================================\n');
end

function out=insert_after_unique(in,pat,addition)
[s,e]=regexp(in,pat,'start','end');
assert(numel(s)==1, ...
    '[AF7R38V3] regex anchor count mismatch (%d): %s',numel(s),pat);
out=[in(1:e) addition in(e+1:end)];
end
