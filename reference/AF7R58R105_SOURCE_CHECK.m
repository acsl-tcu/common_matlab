function S=AF7R58R105_SOURCE_CHECK()
% Fail early for source shadowing/missing path. Native pinned to R103/R104.
base=fileparts(mfilename('fullpath'));
need={ ...
    'AF7R58R105_SOURCE_CHECK', ...
    'AF7R58R105_SELFTEST', ...
    'AF7R58R105_CLOSE_PARTIAL', ...
    'AF7R58R105_C7_TAIL_EVAL', ...
    'AF7R58R105_C7_SEAM_AUDIT', ...
    'AF7R58R105_STAGE_REPLAY', ...
    'AF7R58R105_SOURCE_EVENT', ...
    'AF7R58R105_WRITE_REPORT', ...
    'AF7R58R104_SOURCE_CHECK', ...
    'AF7R58R104_NATURAL_RETURN_SEARCH', ...
    'AF7R58R104_LIVE_EVENT_PACKET', ...
    'AF7R58R104_PHYSICAL_PREDICTOR', ...
    'AF7R58R103_FROM_R55_PACKET', ...
    'AF7R58R103_EKF_HLC_TRIGGER', ...
    'AF7R58R102_LIVE_INPUT_AUTHORITY', ...
    'AF7R58R83_BIND_R81_INPUTS', ...
    'AF7R58R88_SELECT_TIME', ...
    'AF7R58R88_NOMINAL_JETS', ...
    'AF7R58R94_CERTIFY_ALL_SEGMENTS' ...
};
missing={};shadow={};
for j=1:numel(need)
    p=which(need{j});
    if isempty(p)
        missing{end+1}=need{j}; %#ok<AGROW>
    elseif ~strcmpi(fileparts(p),base)
        shadow{end+1}=sprintf('%s -> %s',need{j},p); %#ok<AGROW>
    end
end
up=AF7R58R104_SOURCE_CHECK();
S=struct('status','BLOCKED_MISSING_OR_SHADOWED_DEPENDENCY', ...
    'missing_dependencies',{missing},'different_source_directory',{shadow}, ...
    'r104_source_status',char(up.status), ...
    'hlc_plant_preview_helper_present', ...
       exist('AF7R58R71_EXACT_HLC_PLANT_PREVIEW','file')==2, ...
    'production_source_pinned',logical(up.native_class_pinned), ...
    'simulation_source_modified',false,'existing_hlc_replaced',false, ...
    'flight_trigger_switched',false,'flight_generator_switched',false, ...
    'full_future_certified',false,'production_commit_authorized',false, ...
    'event_sources_supported',{{'R55','R71R2','R63_PLUS_R88'}});
if isempty(missing)&&isempty(shadow)&&startsWith(char(up.status),'PASS_R104_')
    S.status='PASS_R105_REPLAY_REFERENCE_CLOSURE_DEPENDENCIES';
end
end
