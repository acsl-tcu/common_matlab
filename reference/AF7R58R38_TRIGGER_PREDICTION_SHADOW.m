function R=AF7R58R38_TRIGGER_PREDICTION_SHADOW(x0,t0,dt,H,L,mL,g,controllerAuthority,predictor)
% R38 SIMULATION / DIAGNOSTIC ONLY. NOT a certified trigger or a safety check.
% External ideal closed-loop prediction model MUST be supplied. No local
% substitute for the real HLC, state estimator or payload dynamics.
% x0 fields: pQ,pL,q (3x1), and other authoritative estimator/model states.
% predictor(x0,times,mL,L,g,controllerAuthority) -> struct containing
%   pL (3xN), q (3xN), pQ (3xN), and optionally model identity metadata.
% All positions/directions must correspond to one dynamic solution.
validateattributes(t0,{'double'},{'finite','real','scalar'});
validateattributes(dt,{'double'},{'real','finite','positive','scalar'});
validateattributes(H,{'double'},{'real','finite','positive','scalar'});
validateattributes(L,{'double'},{'real','finite','positive','scalar'});
validateattributes(mL,{'double'},{'real','finite','positive','scalar'});
validateattributes(g,{'double'},{'real','finite','positive','scalar'});
assert(isa(predictor,'function_handle'),'External ideal dynamics predictor is mandatory.');
assert(isstruct(x0)&&all(isfield(x0,{'pQ','pL','q'})), ...
    'Estimated full-body state needs pQ,pL,q.');
for f={'pQ','pL','q'}
    v=x0.(f{1});
    validateattributes(v,{'double'},{'real','finite','numel',3});
end
N=round(H/dt)+1;
assert(abs((N-1)*dt-H)<=32*eps(max(1,H))&&N>=2, ...
    'Prediction horizon and sampling period must agree exactly.');
times=t0+(0:(N-1))*dt;
assert(all(diff(times)>0),'Unrepresentable prediction grid.');
Y=predictor(x0,times,mL,L,g,controllerAuthority);
assert(isstruct(Y)&&all(isfield(Y,{'pL','q','pQ'})), ...
    'Predictor did not return whole-body pL,q,pQ trajectory.');
for f={'pL','q','pQ'}
    a=Y.(f{1});
    assert(isa(a,'double')&&isreal(a)&&isequal(size(a),[3 N])&&all(isfinite(a(:))), ...
        'Predictor returned an invalid trajectory field.');
end
% A trajectory must begin at the actual estimator state. The origin may
% not be nominally substituted. Report mismatch rather than patch the 1st sample.
origin=[norm(Y.pQ(:,1)-x0.pQ(:)), ...
        norm(Y.pL(:,1)-x0.pL(:)), norm(Y.q(:,1)-x0.q(:))];
qNorm=max(abs(vecnorm(Y.q)-1));
geo=max(vecnorm(Y.pQ-(Y.pL-L*Y.q)));
initialCableResidual=norm(x0.pQ(:)-(x0.pL(:)-L*x0.q(:)));
R=struct('schema','AF7R58R38_ESTIMATED_ORIGIN_SHADOW_V1', ...
    'time_s',times,'pL',Y.pL,'pQ',Y.pQ,'q',Y.q, ...
    'origin_residual',origin,'max_q_norm_residual',qNorm, ...
    'max_cable_geometry_residual',geo, ...
    'initial_estimated_cable_residual',initialCableResidual, ...
    'horizon_s',H,'current_mass_from_estimator',mL, ...
    'predictor_provided',true, ...
    'referenced_nominal_initial_state',false, ...
    'dynamics_equation_verified',false, ...
    'continuous_time_collision_certified',false, ...
    'future_trajectory_proven',false, ...
    'source_matched_certified_C7_candidate',false, ...
    'production_trigger_changed',false, ...
    'committable',false);
if isfield(Y,'model_identity'),R.model_identity=Y.model_identity;end
% No fail-open tolerances: downstream model authority must certify residuals
% and continuous-time dynamics with its own valid numerical bounds.
end
