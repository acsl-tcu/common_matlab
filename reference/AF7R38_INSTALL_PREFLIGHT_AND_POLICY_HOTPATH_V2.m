'                    obj.replan_request_component_code=sp.reqComp;\n' ...
'                    rethrow(MEpost);\n' ...
'                end\n' ...
'                obj.active_reference_mode=sp.mode;\n' ...
'                obj.active_reference_version=sp.version;\n' ...
'                obj.active_repaired_reference=sp.ref;\n' ...
'                obj.active_repaired_certificates=sp.cert;\n' ...
'                obj.active_speed_certificate=sp.speed;\n' ...
'                obj.trigger_sweep_inflation=sp.sweep;\n' ...
