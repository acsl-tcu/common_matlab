'                    ''mode'',obj.active_reference_mode, ...\n' ...
'                    ''version'',obj.active_reference_version, ...\n' ...
'                    ''ref'',obj.active_repaired_reference, ...\n' ...
'                    ''cert'',obj.active_repaired_certificates, ...\n' ...
