'                    obj.last_replan_commit_time=sp.time;\n' ...
'                    obj.last_replan_status=sp.status;\n' ...
'                    obj.replan_request_active=sp.reqActive;\n' ...
'                    obj.replan_request_reference_version=sp.reqVer;\n' ...
