raw=strrep(raw,anchor,insert);

% -------------------------------------------------------------------------
% Production hot path: under REFERENCE_ONLY, execution-aware is NOT the
% commit authority. Do not spend deadline budget on that diagnostic layer.
% Under EXECUTION_AWARE the previous dual evaluation remains unchanged.
% -------------------------------------------------------------------------
