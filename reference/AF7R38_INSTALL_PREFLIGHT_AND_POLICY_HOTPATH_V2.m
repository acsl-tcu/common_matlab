'            obj.generator_backend_kernel_prime_variants=nvar;\n' ...
'            obj.generator_backend_kernel_prime_done=true;']);

insert=sprintf([ ...
'            %% AF7R38: warm the REAL successful-candidate post-callback\n' ...
'            %% reference-only path without allowing synthetic setup state to\n' ...
'            %% survive. This is implementation/JIT priming only; no setup\n' ...
'            %% candidate becomes safety authority.\n' ...
'            obj.postcallback_prime_candidate_found=~isempty(primeCandidate);\n' ...
'            if ~isempty(primeCandidate) && ...\n' ...
'                    strcmpi(char(obj.AVOIDANCE_COMMIT_POLICY),''REFERENCE_ONLY'') && ...\n' ...
'                    obj.ENABLE_REFERENCE_ONLY_CERTIFICATE && obj.ENABLE_AUTO_REPLAN_COMMIT\n' ...
