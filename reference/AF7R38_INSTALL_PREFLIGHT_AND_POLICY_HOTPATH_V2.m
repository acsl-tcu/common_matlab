'                    ''reqObs'',obj.replan_request_obstacle_id, ...\n' ...
'                    ''reqComp'',obj.replan_request_component_code);\n' ...
'                tpost=tic;\n' ...
'                try\n' ...
'                    Rprime=obj.evaluate_reference_only_proposal_certificate(primeCandidate);\n' ...
'                    assert(isstruct(Rprime)&&isfield(Rprime,''certified'')&&logical(Rprime.certified), ...\n' ...
'                        ''[REPLANNER PRIME ERROR] successful native prime candidate failed reference-only certificate.'');\n' ...
'                    [okPrime,reasonPrime]=obj.try_commit_reference_only_proposal( ...\n' ...
'                        primeCandidate,double(t_now),[]);\n' ...
'                    assert(okPrime, ...\n' ...
'                        ''[REPLANNER PRIME ERROR] reference-only atomic plumbing prime failed: %%s'',reasonPrime);\n' ...
'                    obj.postcallback_prime_ms=1e3*toc(tpost);\n' ...
'                    obj.postcallback_prime_done=true;\n' ...
'                catch MEpost\n' ...
'                    obj.active_reference_mode=sp.mode;\n' ...
'                    obj.active_reference_version=sp.version;\n' ...
'                    obj.active_repaired_reference=sp.ref;\n' ...
'                    obj.active_repaired_certificates=sp.cert;\n' ...
'                    obj.active_speed_certificate=sp.speed;\n' ...
'                    obj.trigger_sweep_inflation=sp.sweep;\n' ...
'                    obj.obstacle_packet=sp.packet;\n' ...
'                    obj.sensor_horizon_certificate=sp.sensor;\n' ...
'                    obj.runtime_dependency_signature=sp.dep;\n' ...
'                    obj.certificate_stale=sp.stale;\n' ...
