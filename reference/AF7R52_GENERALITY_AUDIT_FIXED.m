function A = AF7R52_GENERALITY_AUDIT
assert(evalin('base','exist(''D38'',''var'')==1'), ...
    'Run: D38 = AF7R38_SPEED_ROOTCAUSE_AUDIT; first.');

D38 = evalin('base','D38');
P = D38.pipeline;

fprintf('\n====================================================================================================\n');
fprintf(' AF7R52 | GENERAL-C7 WORLD-3D PHASE / CORRIDOR AUDIT\n');
fprintf('====================================================================================================\n');

F = { ...
    'predeadline_candidate_success','predeadline_candidate_family', ...
    'predeadline_uav_speed','predeadline_payload_speed','predeadline_qdot', ...
    'predeadline_c7_exact','predeadline_speed_pass_count', ...
    'predeadline_rejoin_pass_count','predeadline_geometry_test_count', ...
    'r47_active_base_replan_count','r47_nonaffine_base_count', ...
    'r51_phase_alpha','r51_phase_delay_s','r51_phase_exit_time_s', ...
    'r52_phase_episode_count','r52_phase_episode_rebuild_fail_count', ...
    'r52_corridor_row_count','r52_support_plane_fail_count', ...
    'r52_spatial_qp_solution_count','r52_rejoin_time_trial_count', ...
    'r52_selected_spatial_rejoin_s', ...
    'r37_side_assignments','r37_spatial_qp_solutions','r37_exact_c7_candidates', ...
    'r51_tangent_certified_count', ...
    'r37_best_total_velocity_ub','r37_best_accel_ub','r37_best_jerk_ub', ...
    'r24e_family_seen','r24e_family_exact','r24e_family_speed_pass','r24e_family_speed_fail', ...
    'r35_heading_candidate_count','r35_heading_pass_count','r35_heading_reject_count', ...
    'r35_best_heading_gamma_m_s','r37_heading_pass_count', ...
    'r47_heading_leaf_count','r47_heading_split_count', ...
    'native_episode_ms','native_hessian_ms','native_corridor_ms','native_qp_ms', ...
    'native_candidate_build_ms','native_total_ms', ...
    'last_stage1_ms','last_stage2_ms','last_stage3_ms'};

for k = 1:numel(F)
    f = F{k};
    if isfield(P,f)
        v = P.(f);
        if isnumeric(v) || islogical(v)
            if isscalar(v)
                fprintf('%-58s = %.17g\n',f,double(v));
            else
                fprintf('%-58s = %s\n',f,mat2str(double(v),17));
            end
        else
            fprintf('%-58s = %s\n',f,char(string(v)));
        end
    else
        fprintf('%-58s = <NOT EXPOSED>\n',f);
    end
end

fprintf('\nContract:\n');
fprintf(' - unsafe episodes are rebuilt on the actual phase-composed reference.\n');
fprintf(' - spatial correction is world-3D C7; no straight/affine/fixed-lateral-plane assumption.\n');
fprintf(' - support-plane numerical failure fails closed; no alternative trajectory-family fallback.\n');
fprintf(' - phase delay preserves the old spatial path without same-clock catch-up.\n');
fprintf('====================================================================================================\n');

A = P;
assignin('base','R52A',A);
end
