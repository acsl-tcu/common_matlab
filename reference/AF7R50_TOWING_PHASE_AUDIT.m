function A = AF7R50_TOWING_PHASE_AUDIT
assert(evalin('base','exist(''D38'',''var'')==1'), ...
    'Run: D38 = AF7R38_SPEED_ROOTCAUSE_AUDIT; first.');
D38=evalin('base','D38');
P=D38.pipeline;

fprintf('\n====================================================================================================\n');
fprintf(' AF7R50 | TOWING-LATERAL / PHASE-DECOUPLED AUDIT\n');
fprintf('====================================================================================================\n');

F={ ...
 'predeadline_candidate_success','predeadline_candidate_family', ...
 'predeadline_t0','predeadline_t1','predeadline_payload_speed', ...
 'predeadline_uav_speed','predeadline_qdot', ...
 'r34_delay_candidate_count','r34_terminal_hold_exact_count', ...
 'r34_monotone_progress_count','r34_selected_delay_s', ...
 'r34_selected_hold_start_s','r34_selected_alpha', ...
 'r49_phase_timing_trial_count','r49_phase_gate_pass_count', ...
 'r49_hard_certificate_trial_count','r49_selected_Ke', ...
 'r49_selected_Kflow','r49_selected_Kx', ...
 'r50_spatial_side_solution_count', ...
 'r50_spatial_lateral_constraint_count', ...
 'r50_entry_candidate_count','r50_exit_candidate_count', ...
 'r50_best_spatial_velocity_norm', ...
 'r31_best_correction_speed_ub','r32_best_pre_speed_ub', ...
 'native_episode_ms','native_corridor_ms','native_qp_ms', ...
 'native_candidate_build_ms','native_total_ms', ...
 'last_stage1_ms','last_stage2_ms','last_stage3_ms'};

for k=1:numel(F)
    f=F{k};
    if isfield(P,f)
        v=P.(f);
        if isnumeric(v)||islogical(v)
            if isscalar(v)
                fprintf('%-54s = %.17g\n',f,double(v));
            else
                fprintf('%-54s = %s\n',f,mat2str(double(v),17));
            end
        else
            fprintf('%-54s = %s\n',f,char(string(v)));
        end
    else
        fprintf('%-54s = <NOT EXPOSED>\n',f);
    end
end

fprintf('\nInterpretation:\n');
fprintf(' spatial_velocity_norm is the unsafe-span lateral V chosen by the towing natural-time QP.\n');
fprintf(' phase_gate_pass>0 means continuous 0<=ds/dt<=1.\n');
fprintf(' selected_delay_s>0 means rejoin to the old spatial path with retained clock delay.\n');
fprintf('====================================================================================================\n');

A=P;
assignin('base','R50A',A);
end
