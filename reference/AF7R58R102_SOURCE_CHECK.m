function S=AF7R58R102_SOURCE_CHECK()
% R102 dependency/entrypoint audit. No script-side effects.
base=fileparts(mfilename('fullpath'));
need={ ...
    'AF7R58R102_SOURCE_CHECK', ...
    'AF7R58R102_SEED_RECORD', ...
    'AF7R58R102_RUN_SAVED_ROUTE', ...
    'AF7R58R102_ADAPTIVE_SAVED_SEARCH', ...
    'AF7R58R102_WRITE_REPORT', ...
    'AF7R58R102_SELFTEST', ...
    'AF7R58R102_C7_CONTINUOUS_JET_OPT', ...
    'AF7R58R102_LIVE_INPUT_AUTHORITY', ...
    'AF7R58R100_C7_INTERIOR_SPEED_AWARE', ...
    'AF7R58R100_CO_DESIGN_TIMES', ...
    'AF7R58R99_OVERLAP_LOCAL_CORRIDOR_CHAIN', ...
    'AF7R58R99_MULTI_SIZE_KNOT_CORRIDOR', ...
    'AF7R58R98_ALLOCATE_KNOT_TIMES', ...
    'AF7R58R97_TIGHT_SUPPORT_CORRIDOR', ...
    'AF7R58R97_SUPPORT_SEED_ROUTES', ...
    'AF7R58R96_C7_KNOT_SPEED_ROUTE', ...
    'AF7R58R96_KNOT_DISPLACEMENT_SCREEN', ...
    'AF7R58R96_KNOT_REACHABILITY_PREFLIGHT', ...
    'AF7R58R96_KNOT_VQ_SCREEN', ...
    'AF7R58R96_C7_CORRIDOR_PROJECT', ...
    'AF7R58R96_SHA256_FILE', ...
    'AF7R58R94_CERTIFY_ALL_SEGMENTS', ...
    'AF7R58R92_C7_MINIMUM8_ROUTE', ...
    'AF7R58R88_SELECT_TIME', ...
    'AF7R58R83_BIND_R81_INPUTS', ...
    'AF7R58R88_NOMINAL_JETS', ...
    'AF7R58R92_TRACKING_INFLATION', ...
    'AF7R58R91_STABLE_KINEMATIC_CERT', ...
    'AF7R58R80_HEADING_C6_CERT', ...
    'AF7R58R80_CONTINUOUS_SEPARATE_BODY_CERT', ...
    'AF7R58R90_INPUT_ENVELOPE' ...
};
missing={};shadow={};
for i=1:numel(need)
 f=which(need{i});
 if isempty(f)
  missing{end+1}=need{i}; %#ok<AGROW>
 elseif ~strcmp(fileparts(f),base)
  shadow{end+1}=sprintf('%s -> %s',need{i},f); %#ok<AGROW>
 end
end
S=struct('status','PASS_R102_SOURCE_DEPENDENCIES', ...
 'missing_dependencies',{missing},'different_source_directory',{shadow}, ...
 'production_modified',false,'trigger_switched',false, ...
 'closed_loop_safety_proved',false);
if ~isempty(missing)||~isempty(shadow)
 S.status='FAIL_R102_MISSING_OR_SHADOWED_DEPENDENCY';
end
end
