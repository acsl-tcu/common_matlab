function R=AF7R58R35_RETURN_OPTIONS_AUDIT(cases)
% Study whether staying on a chosen side is compatible with different C7
% boundary jets. Each case must supply t0,T,J0,JT,L,g,direction.
%
% IMPORTANT: a one-sided Bezier control-hull proof is a sufficient SHAPE
% condition for that direction, not a necessary condition for obstacle
% avoidance or proof that a return is physically possible. The safety
% certificate for the full UAV/cable/payload is NOT performed here.
% The times/directions are scenario inputs, never hard-coded limits.
assert(isstruct(cases) && ~isempty(cases), ...
    'Provide a nonempty struct array of physical input scenarios.');
fields={'t0','T','J0','JT','L','g','direction'};
assert(all(isfield(cases,fields)), ...
    'Each return scenario must supply t0,T,J0,JT,L,g,direction.');
rows=struct('case_index',{},'status',{},'unconstrained_cost',{}, ...
    'unconstrained_signed_control_min_m',{}, ...
    'unconstrained_one_side_proven',{}, ...
    'constrained_one_side_proven',{},'constrained_cost',{}, ...
    'endpoint_directionally_incompatible',{}, ...
    'fullbody_safety_certified',{},'committable',{});
for k=1:numel(cases)
    C=cases(k);
    validateattributes(C.J0,{'double'},{'real','finite','size',[3 8]});
    validateattributes(C.JT,{'double'},{'real','finite','size',[3 8]});
    validateattributes(C.direction,{'double'}, ...
        {'real','finite','numel',3});
    n=C.direction(:)/norm(C.direction(:));
    assert(all(isfinite(n)) && norm(n)>0,'Direction must be nonzero.');
    % Exact endpoint necessity for a NONNEGATIVE scalar projection,
    % as far as the supplied (double) endpoint jets can decide it.
    % A negative initial value, or first nonzero right-sided Taylor
    % coefficient, implies negative projection near t0. At t1 the
    % sign of the r-th derivative changes by (-1)^r.
    a0=n.'*C.J0;
    a1=n.'*C.JT;
    leftBad=local_endpoint_sign_bad(a0,1);
    rightBad=local_endpoint_sign_bad(a1,-1);
    shape=AF7R58R34_ONE_SIDED_C7_RETURN( ...
        C.t0,C.T,C.J0,C.JT,C.L,C.g,C.direction);
    rows(end+1)=struct( ...
        'case_index',k, 'status',char(shape.status), ...
        'unconstrained_cost',shape.unconstrained_integral_cost, ...
        'unconstrained_signed_control_min_m', ...
            shape.unconstrained_min_signed_control_m, ...
        'unconstrained_one_side_proven', ...
            logical(shape.unconstrained_algebraic_one_sided_proven), ...
        'constrained_one_side_proven', ...
            logical(shape.constrained_algebraic_one_sided_proven), ...
        'constrained_cost',shape.integral_cost, ...
        'endpoint_directionally_incompatible',leftBad || rightBad, ...
        'fullbody_safety_certified',false,'committable',false); %#ok<AGROW>
end
R=struct('schema','AF7R58R35_RETURN_OPTION_COMPARISON_V1', ...
    'rows',struct2table(rows), ...
    'limits','Projection condition is directional only; other directions and obstacles remain free.', ...
    'fullbody_certified',false,'auto_commit',false, ...
    'fixed_rejoin_time_forced',false);
disp(R.rows);
end

function bad=local_endpoint_sign_bad(jets,side)
% Exact polynomial coefficient sign as evaluated from supplied doubles;
% this is an algebraic necessary test, NOT a floating-point interval proof.
bad=false;
for k=1:numel(jets)
    v=jets(k)*side^(k-1);
    if v~=0
        bad=(v<0);
        return;
    end
end
end
