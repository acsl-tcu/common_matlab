function A = AF7R58R31_RETURN_SHAPE_AUDIT(t, nominalP, activeP)
% POST-RUN ONLY. Detect signed reversal of correction after its dominant peak.
% This is a trajectory QUALITY diagnostic, never a hard safety/rejoin gate.
validateattributes(t,{'double'},{'real','finite','vector'});
t=double(t(:).');
assert(ismatrix(nominalP) && size(nominalP,1)==3 && ...
    isequal(size(nominalP),size(activeP)) && size(nominalP,2)==numel(t) && ...
    all(isfinite(nominalP(:))) && all(isfinite(activeP(:))) && ...
    all(diff(t)>0), 'Need aligned finite 3xN positions and increasing time.');
D=double(activeP)-double(nominalP);
n=sqrt(sum(D.^2,1));
[nmax,idx]=max(n);
if nmax==0
    A=struct('has_deviation',false,'max_deviation_m',0, ...
        'signed_crossing_detected',false,'certified',false);
    return
end
axis=D(:,idx)/nmax;
projection=axis.'*D;
% A sign reversal is meaningful only relative to the actual peak offset.
post=idx:numel(t);
negative=post(projection(post)<0);
A=struct('has_deviation',true,'max_deviation_m',nmax, ...
    'peak_time_s',t(idx),'peak_axis',axis, ...
    'signed_correction_m',projection,'correction_norm_m',n, ...
    'signed_crossing_detected',~isempty(negative), ...
    'first_negative_time_s',NaN,'min_postpeak_projection_m',min(projection(post)), ...
    'continuous_time_no_overshoot_proven',false, ...
    'collision_safety_certified',false);
if ~isempty(negative), A.first_negative_time_s=t(negative(1)); end
end
