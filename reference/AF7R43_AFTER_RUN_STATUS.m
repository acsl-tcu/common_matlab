function OUT = AF7R43_AFTER_RUN_STATUS(replanner)
clc;
fprintf('\n====================================================================================================\n');
fprintf(' AF7R43B | HARD-PATH CLEANUP AFTER-RUN STATUS\n');
fprintf('====================================================================================================\n');
fprintf('[AUTHORITY] readOnly=1 | diagnosticOnly=1\n');

assert(isa(replanner,'REPLANNING_SYSTEM'));
fprintf(' nominal batch model cache valid          = %d\n', ...
    logical(replanner.nominal_batch_model_cache_valid));
fprintf(' trigger-event capture runtime [ms]       = %.6g\n', ...
    double(replanner.trigger_event_capture_ms));
fprintf(' active reference mode/version            = %s / %.0f\n', ...
    char(replanner.active_reference_mode),double(replanner.active_reference_version));
fprintf(' reference-only commit count              = %.0f\n', ...
    double(replanner.reference_only_commit_count));
fprintf(' generator last status                    = %.0f\n', ...
    double(replanner.generator_last_status_code));
fprintf(' generator last pre-generator [ms]        = %.6g\n', ...
    double(replanner.generator_last_elapsed_before_ms));
fprintf(' generator last callback [ms]             = %.6g\n', ...
    double(replanner.generator_last_callback_ms));
fprintf(' generator last cycle critical [ms]       = %.6g\n', ...
    double(replanner.generator_last_cycle_critical_ms));
fprintf('====================================================================================================\n');

OUT=struct('schema','AF7R43B_AFTER_RUN_STATUS_V1', ...
    'nominal_cache_valid',logical(replanner.nominal_batch_model_cache_valid), ...
    'commit_count',double(replanner.reference_only_commit_count), ...
    'last_status',double(replanner.generator_last_status_code), ...
    'last_pre_ms',double(replanner.generator_last_elapsed_before_ms), ...
    'last_callback_ms',double(replanner.generator_last_callback_ms), ...
    'last_cycle_ms',double(replanner.generator_last_cycle_critical_ms));
assignin('base','AF7R43_AFTER_RUN_STATUS_OUT',OUT);
end
