function OUT = AF7R39_AFTER_RUN_STATUS(replanner)
clc;
fprintf('\n====================================================================================================\n');
fprintf(' AF7R39B | AFTER-RUN R38/R14D STATUS\n');
fprintf('====================================================================================================\n');
fprintf('[AUTHORITY] readOnly=1 | diagnosticOnly=1 | safetyLogicUnchanged=1\n');

assert(isa(replanner,'REPLANNING_SYSTEM'));

req={'observer_preflight_prime_done','observer_preflight_prime_ms', ...
    'qpc_stamp_prime_done','postcallback_prime_candidate_found', ...
    'postcallback_prime_done','postcallback_prime_ms'};
for k=1:numel(req)
    assert(isprop(replanner,req{k}),'[AF7R39B] missing property %s.',req{k});
end

fprintf(' observer preflight prime done / ms       = %d / %.6g\n', ...
    logical(replanner.observer_preflight_prime_done), ...
    double(replanner.observer_preflight_prime_ms));
fprintf(' QPC stamp prime done                     = %d\n', ...
    logical(replanner.qpc_stamp_prime_done));
fprintf(' postcallback prime candidate/done/ms     = %d / %d / %.6g\n', ...
    logical(replanner.postcallback_prime_candidate_found), ...
    logical(replanner.postcallback_prime_done), ...
    double(replanner.postcallback_prime_ms));
fprintf(' active reference mode/version            = %s / %.0f\n', ...
    char(replanner.active_reference_mode),double(replanner.active_reference_version));
fprintf(' reference-only commit count              = %.0f\n', ...
    double(replanner.reference_only_commit_count));
fprintf(' generator last status                    = %.0f\n', ...
    double(replanner.generator_last_status_code));
fprintf(' generator last callback / cycle [ms]     = %.6g / %.6g\n', ...
    double(replanner.generator_last_callback_ms), ...
    double(replanner.generator_last_cycle_critical_ms));

S=replanner.get_last_replan_status();
reason='';
if isstruct(S)&&isfield(S,'reason'), reason=char(S.reason); end
fprintf(' last replan reason                       = %s\n',reason);
fprintf('====================================================================================================\n');

OUT=struct('schema','AF7R39_AFTER_RUN_STATUS_V1', ...
    'observer_prime_done',logical(replanner.observer_preflight_prime_done), ...
    'observer_prime_ms',double(replanner.observer_preflight_prime_ms), ...
    'qpc_prime_done',logical(replanner.qpc_stamp_prime_done), ...
    'postcallback_candidate',logical(replanner.postcallback_prime_candidate_found), ...
    'postcallback_done',logical(replanner.postcallback_prime_done), ...
    'postcallback_ms',double(replanner.postcallback_prime_ms), ...
    'active_mode',char(replanner.active_reference_mode), ...
    'active_version',double(replanner.active_reference_version), ...
    'reference_only_commit_count',double(replanner.reference_only_commit_count), ...
    'generator_last_status',double(replanner.generator_last_status_code), ...
    'last_reason',reason);
assignin('base','AF7R39_AFTER_RUN_STATUS_OUT',OUT);
end
