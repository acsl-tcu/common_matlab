function P=AF7R58R166_LIVE_PACKET(agent,replanner,time,A)
% Call at EVERY CONTROL TICK when integrated AFTER estimator and BEFORE HLC.
% Never cache estimated payload mass: always read state.mL anew.
% No modification of agent, replanner, EKF, HLC, plant or settings.
if nargin<4||isempty(A),A=AF7R58R166_SOURCE_AUDIT();end
P=struct('status','UNKNOWN_LIVE_SOURCE','t_s',NaN,'estimated_mL_kg',NaN, ...
 'controller_parameter_mL_kg',NaN,'same_tick_mass_match',false, ...
 'source_contract_status',A.status,'origin','CURRENT_EKF_STATE', ...
 'position_Q_m',nan(3,1),'position_L_m',nan(3,1), ...
 'velocity_Q_mps',nan(3,1),'velocity_L_mps',nan(3,1), ...
 'source_mass_kg',NaN,'source_gravity_mps2',NaN, ...
 'source_cable_length_m',NaN,'source_radii_m',nan(3,1), ...
 'source_sensing_range_m',NaN,'source_horizon_s',NaN, ...
 'source_prediction_dt_s',NaN, ...
 'thrust_bounds_N',A.source_thrust_bounds_N, ...
 'torque_bounds_Nm',A.source_torque_bounds_N, ...
 'live_physical_parameters_valid',false, ...
 'continuous_reachable_set_certified',false, ...
 'production_commit_authorized',false);
assert(isstruct(time)&&isfield(time,'t')&&isfinite(double(time.t)), ...
 'R166:MissingTimeAuthority');
P.t_s=double(time.t);
assert(strcmp(A.status,'PASS_STATIC_CURRENT_SOURCE_MASS_CHAIN_AND_ACTUATOR_LIMIT_PARSE__NO_FLIGHT_PROOF'), ...
 'R166:SourceContractChanged');
state=agent.estimator.result.state;
P.estimated_mL_kg=double(state.mL);
P.controller_parameter_mL_kg=double(agent.parameter.get('loadmass'));
P.same_tick_mass_match=isequal(P.estimated_mL_kg,P.controller_parameter_mL_kg);
P.position_Q_m=double(state.p(:));P.position_L_m=double(state.pL(:));
P.velocity_Q_mps=double(state.v(:));P.velocity_L_mps=double(state.vL(:));
P.source_mass_kg=double(agent.parameter.get('mass'));
P.source_gravity_mps2=double(agent.parameter.get('gravity'));
P.source_cable_length_m=double(agent.parameter.get('cableL'));
P.source_radii_m=double([replanner.r_drone;replanner.r_cable;replanner.r_load]);
P.source_sensing_range_m=double(replanner.trigger_dist);
P.source_horizon_s=double(replanner.horizon_s);
P.source_prediction_dt_s=double(replanner.prediction_dt);
x=[P.estimated_mL_kg;P.controller_parameter_mL_kg;P.position_Q_m; ...
 P.position_L_m;P.velocity_Q_mps;P.velocity_L_mps;P.source_mass_kg; ...
 P.source_gravity_mps2;P.source_cable_length_m;P.source_radii_m; ...
 P.source_sensing_range_m;P.source_horizon_s;P.source_prediction_dt_s; ...
 P.thrust_bounds_N;P.torque_bounds_Nm(:)];
P.live_physical_parameters_valid=all(isfinite(x))&&P.estimated_mL_kg>0 ...
 &&P.source_mass_kg>0&&P.source_gravity_mps2>0 ...
 &&P.source_cable_length_m>0&&all(P.source_radii_m>=0) ...
 &&P.source_sensing_range_m>0&&P.source_horizon_s==4 ...
 &&P.source_prediction_dt_s>0&&P.same_tick_mass_match;
if ~P.live_physical_parameters_valid
 P.status='FAIL_CLOSED_LIVE_SOURCE_OR_ESTIMATOR_MASS_MISMATCH';
else
 P.status='PASS_SAME_TICK_LIVE_PARAMETER_READ__NO_EXECUTION_CERTIFICATE';
end
end
