function R=AF7R58R87_PARAMETER_RUNTIME_PROBE(agent)
% Parameter authority live read using EXACT keys already used by production.
% This can run after SimHL; it has no side effects and does not replan.
assert(isobject(agent)&&isscalar(agent)&&isprop(agent,'parameter'), ...
    'R87:ExistingAgentWithParameterRequired');
L=double(agent.parameter.get("cableL"));
g=double(agent.parameter.get("gravity"));
assert(isscalar(L)&&isfinite(L)&&L>0 && ...
       isscalar(g)&&isfinite(g)&&g>0, ...
       'R87:ParameterAuthorityInvalid');
R=struct('status','PASS_R87_ACTUAL_RUNTIME_PARAMETER_STRING_KEYS', ...
    'live_cable_length_m',L,'live_gravity_m_s2',g, ...
    'production_modified',false, 'r81_candidate_certified',false);
end
