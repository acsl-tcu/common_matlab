function R=AF7R58R44R1_SELFTEST()
% Synthetic numerical validation of offline hull parser only (NOT safety proof).
Q=zeros(3,16);Q(1,:)=linspace(1,2,16);
C=struct('segment_t0',0,'segment_t1',2,'control_points',Q);
S=struct('schema','AF7R58R44R1_ACTIVE_SNAPSHOT_V1', ...
    'contains_committed_c7_control_points',true, ...
    'corrections',C,'phase_layers',struct([]));
A=AF7R58R44R1_RETURN_HULL_OFFLINE(S);
assert(A.theoretical_one_sided_sufficient_if_exact_control_points && ...
    abs(A.min_signed_cp_m-1)<1e-12 && ...
    abs(A.max_signed_cp_m-2)<1e-12);
R=struct('schema','AF7R58R44R1_SELFTEST_V1', ...
    'synthetic_hull_parser_pass',true, ...
    'live_trajectory_tested',false, ...
    'safety_certified',false, ...
    'no_workspace_instance_tested',false);
if evalin('base','exist(''replanner_instance'',''var'')~=1')
    B=AF7R58R44R1_POSTRUN_CAPTURE();
    assert(~B.captured && strcmp(B.status, ...
        'NO_LIVE_INSTANCE__RUN_HEADLESS_IN_THIS_WORKSPACE_FIRST'));
    R.no_workspace_instance_tested=true;
end
end
