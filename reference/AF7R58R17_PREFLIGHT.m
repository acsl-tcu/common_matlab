function Q = AF7R58R17_PREFLIGHT()
% AF7R58R17: non-instantiating source/flag check. No simulation state modified.
f=which('REPLANNING_SYSTEM');
assert(~isempty(f),'REPLANNING_SYSTEM source not on MATLAB path.');
s=fileread(f);
names={ ...
    'ENABLE_AF7R58_SHADOW_DIAGNOSTIC', ...
    'ENABLE_AF7R58R14_LOWJET_SEED_ONLY', ...
    'ENABLE_AF7R58R16_REFERENCE_BRIDGE', ...
    'ENABLE_AF7R58R17_DIAG_CONTINUE_LATE'};
for k=1:numel(names)
    tok=regexp(s,['(?m)^\s*' names{k} '\s*=\s*([01])\s*;'],'tokens','once');
    assert(~isempty(tok) && strcmp(tok{1},'1'), ...
        '[R17] Set %s = 1 in REPLANNING_SYSTEM.m before the simulation.',names{k});
end
policies={'AVOIDANCE_COMMIT_POLICY','AVOIDANCE_CERTIFICATE_MODE'};
for k=1:numel(policies)
    pat=['(?m)^\s*' policies{k} '\s*=\s*''REFERENCE_ONLY''\s*;'];
    assert(~isempty(regexp(s,pat,'once')), ...
        '[R17] Set %s = ''REFERENCE_ONLY'' in REPLANNING_SYSTEM.m.',policies{k});
end
assert(~isempty(strfind(s,'function r17_capture(')), ...
    '[R17] The active REPLANNING_SYSTEM.m lacks R17 source modifications.');
assert(exist('af7r36_single_core_mex','file')==3, ...
    '[R17] The R16 native MEX must be compiled and on the path.');
assert(exist('AF7R58R17_AUTO_RESULT','file')==2, ...
    '[R17] The R17 result function must be on the path.');
Q=struct('source',f,'native_mex',which('af7r36_single_core_mex'), ...
         'diagnostic_only',true,'atomic_activation_forbidden',true, ...
         'deadline_bypass_stage1_stage2',true, ...
         'flight_suitable',false);
fprintf('AF7R58R17 PREFLIGHT PASS (diagnostic only, reference activation BLOCKED)\n');
fprintf('source: %s\n',Q.source);
fprintf('MEX: %s\n',Q.native_mex);
end
