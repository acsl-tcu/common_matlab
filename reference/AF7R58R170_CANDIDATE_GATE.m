function G=AF7R58R170_CANDIDATE_GATE(route,packet,speedCert,shapes,opts)
% Same-tick geometry + taut force/speed reference screening.
% No approximate whole-cable L-radius sphere, no fixed-direction filter.
if nargin<5||isempty(opts),opts=struct();end
if ~isfield(opts,'robust_tube_on'),opts.robust_tube_on=true;end
G=struct('status','UNKNOWN','candidate_shortlist_only',false,...
 'geometry',struct(),'dynamics',struct(),...
 'source_time_s',NaN,'production_commit_authorized',false);
req={'t_s','estimated_mL_kg','live_physical_parameters_valid',...
 'source_mass_kg','source_cable_length_m','source_gravity_mps2',...
 'source_radii_m','thrust_bounds_N'};
if ~isstruct(packet)||~isscalar(packet)||~all(isfield(packet,req))||...
 ~isequal(packet.live_physical_parameters_valid,true)||...
 ~isstruct(speedCert)||~isscalar(speedCert)||...
 ~all(isfield(speedCert,{'source_time_s','bound_derived_from_live_sensing',...
 'VQ_limit_mps'}))||...
 ~isequal(double(speedCert.source_time_s),double(packet.t_s))||...
 ~isequal(speedCert.bound_derived_from_live_sensing,true)||...
 ~isscalar(speedCert.VQ_limit_mps)||...
 ~isfinite(speedCert.VQ_limit_mps)||speedCert.VQ_limit_mps<=0
 G.status='UNKNOWN_STALE_EKF_MASS_OR_SPEED_AUTHORITY';return;
end
G.source_time_s=double(packet.t_s);
G.geometry=AF7R58R170_STRAIGHT_CABLE_CERT(route,packet,shapes,opts);
if ~G.geometry.candidate_clear
 G.status=['UNKNOWN_DIRECTIONAL_FULLBODY_GEOMETRY_' G.geometry.status];return;
end
r=double(packet.source_radii_m(:));
model=struct('vehicle_mass_kg',packet.source_mass_kg,...
 'latest_EKF_mL_kg',packet.estimated_mL_kg,...
 'cable_length_m',packet.source_cable_length_m,...
 'gravity_m_s2',packet.source_gravity_mps2,...
 'thrust_bounds_N',packet.thrust_bounds_N,...
 'finite_sensing_vQ_limit_m_s',speedCert.VQ_limit_mps,...
 'rQ_m',r(1),'rC_m',r(2),'rL_m',r(3));
G.dynamics=AF7R58R164_FLAT_DYNAMICS(route,model,...
 struct('max_leaves',256,'samples_per_segment',41));
if G.dynamics.sample_rejected
 G.status='REJECT_TAUT_DYNAMICS_SAMPLE_VIOLATION';return;
end
if ~G.dynamics.conditional_sufficient_reference_bounds
 G.status='UNKNOWN_TAUT_FORCE_SPEED_CONTINUOUS_BOUND';return;
end
G.candidate_shortlist_only=true;
G.status='CONDITIONAL_REFERENCE_CABLE_AND_FORCE_SAFE__TORQUE_YAW_TAIL_HLC_PENDING';
end
