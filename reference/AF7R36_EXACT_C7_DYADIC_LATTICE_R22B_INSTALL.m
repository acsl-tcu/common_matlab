function OUT = AF7R36_EXACT_C7_DYADIC_LATTICE_R22B_INSTALL()
% AF7R36_EXACT_C7_DYADIC_LATTICE_R22B_INSTALL
%
% R21B proved:
%   production metadata              = C7
%   committed binary64 representation = exactly C1
%   first exact discontinuity         = derivative order 2
%
% Root cause:
%   R17 split midpoint jets were converted independently to the left/right
%   degree-15 Bezier control polygons. Binary64 rounding destroyed equality
%   of the nonzero midpoint jet representation beyond first derivative.
%
% R22B theorem:
%   Build the midpoint-side control points on an exact dyadic lattice
%
%       P_k = (I_p + k I_d) 2^e
%
%   with integer |I| < 2^52.  These stored doubles are exact dyadic rationals.
%   The last 8 control points of the left piece and the first 8 of the right
%   piece are a shared arithmetic progression about the same midpoint:
%
%       left : P_{15-k} = (I_p-k I_d) 2^e
%       right: P_k      = (I_p+k I_d) 2^e
%
%   for k=0..7.
%
%   If the two split durations are bitwise identical, then as exact real
%   polynomials:
%       d0 is identical,
%       d1 is identical,
%       d2..d7 are identically zero on both sides.
%
% Outer endpoints use 8 repeated control points, hence derivatives 1..7 are
% exactly zero there. Constant unsafe spans are repeated-point Beziers.
%
% SAFETY BINDING:
%   The exact stored control polygons are constructed BEFORE certification.
%   The unchanged Stage-A/B speed, rejoin, and continuous whole-body gates
%   certify those exact same polygons. No old certificate is transferred to
%   a modified trajectory.
%
% Candidate acceptance now requires Candidate.exact_c7=true.  R17 family 5
% and R16 constant family 4 are marked exact by construction. Historical
% primary/minimum-snap/R7 candidates are retained in source for comparison
% but cannot be accepted unless separately given an exact representation.
%
% No tolerance is introduced for C7. No hard safety gate is weakened.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 EXACT C7 DYADIC-LATTICE R22B INSTALL\n');
fprintf(' C7 tolerance                               = ZERO\n');
fprintf(' exact representation                       = integer * 2^e dyadic lattice\n');
fprintf(' certificate trajectory == executed traj    = 1\n');
fprintf(' speed/rejoin/whole-body gates modified     = 0\n');
fprintf(' historical minimum-snap acceptance         = disabled by exact-C7 gate\n');
fprintf(' heuristic smoothing / epsilon join accept  = 0\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir)&&isfolder(refDir),'[R22B] Cannot resolve reference directory.');

hpp=fullfile(refDir,'af7r36_core.hpp');
cpp=fullfile(refDir,'af7r36_single_core_mex.cpp');
rps=fullfile(refDir,'REPLANNING_SYSTEM.m');
assert(isfile(hpp)&&isfile(cpp)&&isfile(rps),'[R22B] Production sources missing.');

hpp0=normlf(fileread(hpp));
cpp0=normlf(fileread(cpp));
rps0=normlf(fileread(rps));
hppNew=hpp0; cppNew=cpp0; rpsNew=rps0;

assert(contains(hpp0,'AF7_TOWING_C7_SPEED_OPT_SPLIT_R17'), ...
    '[R22B] R17 split family is not installed.');
assert(contains(hpp0,'AF7_TOWING_MINNORM_CONSTANT_R16'), ...
    '[R22B] R16 constant family is not installed.');
assert(contains(rps0,'P.c7_exact=true;'), ...
    '[R22B] Current unconditional P.c7_exact declaration not found.');
assert(~contains(hpp0,'AF7_EXACT_C7_DYADIC_LATTICE_R22B'), ...
    '[R22B] R22B already installed.');

try
    %% 1. Candidate carries structural exactness authority.
    old=[ ...
        '    bool constant_translation=false;' sprintf('\n') ...
        '    std::vector<int> signs;'];
    new=[ ...
        '    bool constant_translation=false;' sprintf('\n') ...
        '    bool exact_c7=false;' sprintf('\n') ...
        '    std::vector<int> signs;'];
    hppNew=replace_once(hppNew,old,new,'Candidate exact_c7 field');

    %% 2. Replace R17 split construction by exact dyadic-lattice construction.
    old=[ ...
        'static inline void r17_append_split_transition(Candidate&C,Vec3 p0,Vec3 p1,' sprintf('\n') ...
        '                                               double ta,double tb,double alpha){' sprintf('\n') ...
        '    const double T=tb-ta;' sprintf('\n') ...
        '    if(!(fin(T)&&T>0&&fin(alpha)&&alpha>=15.0/8.0&&alpha<=2.0))' sprintf('\n') ...
        '        throw std::runtime_error("R17 invalid split transition");' sprintf('\n') ...
        '    const double tm=0.5*(ta+tb);' sprintf('\n') ...
        '    if(!(tm>ta&&tm<tb))throw std::runtime_error("R17 split midpoint unrepresentable");' sprintf('\n') ...
        '    std::array<Vec3,8> ja{},jm{},jb{};' sprintf('\n') ...
        '    ja[0]=p0;' sprintf('\n') ...
        '    jm[0]=(p0+p1)*0.5;' sprintf('\n') ...
        '    jm[1]=(p1-p0)*(alpha/T);' sprintf('\n') ...
        '    jb[0]=p1;' sprintf('\n') ...
        '    C.seg0.push_back(ta);C.seg1.push_back(tm);' sprintf('\n') ...
        '    C.cp.push_back(vector_control_from_jets(ja,jm,tm-ta));' sprintf('\n') ...
        '    C.seg0.push_back(tm);C.seg1.push_back(tb);' sprintf('\n') ...
        '    C.cp.push_back(vector_control_from_jets(jm,jb,tb-tm));' sprintf('\n') ...
        '}'];

    new=[ ...
        '// AF7_EXACT_C7_DYADIC_LATTICE_R22B' sprintf('\n') ...
        'struct R22AxisLattice{int e=0;long long p=0,d=0;};' sprintf('\n') ...
        'static inline R22AxisLattice r22_axis_lattice(double pm,double di){' sprintf('\n') ...
        '    if(!(fin(pm)&&fin(di)))throw std::runtime_error("R22B nonfinite lattice target");' sprintf('\n') ...
        '    const double scale=std::max({1.0,std::fabs(pm),7.0*std::fabs(di)});' sprintf('\n') ...
        '    const int es=std::ilogb(scale);' sprintf('\n') ...
        '    const int e=es-50;' sprintf('\n') ...
        '    const double ps=std::ldexp(pm,-e),ds=std::ldexp(di,-e);' sprintf('\n') ...
        '    if(!(fin(ps)&&fin(ds)&&std::fabs(ps)<4503599627370496.0&&std::fabs(ds)<4503599627370496.0))' sprintf('\n') ...
        '        throw std::runtime_error("R22B dyadic lattice integer range");' sprintf('\n') ...
        '    const long long ip=std::llround(ps),id=std::llround(ds);' sprintf('\n') ...
        '    const long long ap=ip<0?-ip:ip,ad=id<0?-id:id;' sprintf('\n') ...
        '    if(ap+7*ad>=4503599627370496LL)' sprintf('\n') ...
        '        throw std::runtime_error("R22B dyadic lattice exactness range");' sprintf('\n') ...
        '    return {e,ip,id};' sprintf('\n') ...
        '}' sprintf('\n') ...
        'static inline double r22_grid(long long q,int e){' sprintf('\n') ...
        '    if(q<=-4503599627370496LL||q>=4503599627370496LL)' sprintf('\n') ...
        '        throw std::runtime_error("R22B dyadic grid overflow");' sprintf('\n') ...
        '    const double x=std::ldexp((double)q,e);' sprintf('\n') ...
        '    if(!fin(x))throw std::runtime_error("R22B dyadic grid nonfinite");' sprintf('\n') ...
        '    return x;' sprintf('\n') ...
        '}' sprintf('\n') ...
        'static inline Vec3 r22_grid_vec(const R22AxisLattice&x,const R22AxisLattice&y,' sprintf('\n') ...
        '                              const R22AxisLattice&z,int k){' sprintf('\n') ...
        '    return {r22_grid(x.p+(long long)k*x.d,x.e),' sprintf('\n') ...
        '            r22_grid(y.p+(long long)k*y.d,y.e),' sprintf('\n') ...
        '            r22_grid(z.p+(long long)k*z.d,z.e)};' sprintf('\n') ...
        '}' sprintf('\n') ...
        'static inline void r17_append_split_transition(Candidate&C,Vec3 p0,Vec3 p1,' sprintf('\n') ...
        '                                               double ta,double tb,double alpha){' sprintf('\n') ...
        '    const double T=tb-ta;' sprintf('\n') ...
        '    if(!(fin(T)&&T>0&&fin(alpha)&&alpha>=15.0/8.0&&alpha<=2.0))' sprintf('\n') ...
        '        throw std::runtime_error("R17 invalid split transition");' sprintf('\n') ...
        '    double tm=ta+0.5*(tb-ta);' sprintf('\n') ...
        '    bool splitExact=false;double hL=0,hR=0;' sprintf('\n') ...
        '    if(tm>ta&&tm<tb){hL=tm-ta;hR=tb-tm;splitExact=(hL==hR&&fin(hL)&&hL>0);}' sprintf('\n') ...
        '    if(!splitExact){' sprintf('\n') ...
        '        double lo=tm,hi=tm;' sprintf('\n') ...
        '        for(int it=0;it<64&&!splitExact;++it){' sprintf('\n') ...
        '            lo=std::nextafter(lo,ta);' sprintf('\n') ...
        '            if(lo>ta&&lo<tb){hL=lo-ta;hR=tb-lo;if(hL==hR&&fin(hL)&&hL>0){tm=lo;splitExact=true;break;}}' sprintf('\n') ...
        '            hi=std::nextafter(hi,tb);' sprintf('\n') ...
        '            if(hi>ta&&hi<tb){hL=hi-ta;hR=tb-hi;if(hL==hR&&fin(hL)&&hL>0){tm=hi;splitExact=true;break;}}' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '    if(!splitExact)throw std::runtime_error("R22B split halves not exactly representable");' sprintf('\n') ...
        '    const Vec3 pm=(p0+p1)*0.5;' sprintf('\n') ...
        '    // Ideal midpoint Bezier increment is v_mid*h/15 = alpha*(p1-p0)/30.' sprintf('\n') ...
        '    // It is quantized only to an exact dyadic representability lattice;' sprintf('\n') ...
        '    // the resulting stored polygon itself is what the hard gates certify.' sprintf('\n') ...
        '    const Vec3 di=(p1-p0)*(alpha/30.0);' sprintf('\n') ...
        '    const auto ax=r22_axis_lattice(pm.x,di.x);' sprintf('\n') ...
        '    const auto ay=r22_axis_lattice(pm.y,di.y);' sprintf('\n') ...
        '    const auto az=r22_axis_lattice(pm.z,di.z);' sprintf('\n') ...
        '    Poly Lp(16),Rp(16);' sprintf('\n') ...
        '    for(int k=0;k<8;++k){Lp[k]=p0;Rp[15-k]=p1;}' sprintf('\n') ...
        '    for(int k=0;k<8;++k){' sprintf('\n') ...
        '        Lp[15-k]=r22_grid_vec(ax,ay,az,-k);' sprintf('\n') ...
        '        Rp[k]=r22_grid_vec(ax,ay,az,k);' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '    C.seg0.push_back(ta);C.seg1.push_back(tm);C.cp.push_back(std::move(Lp));' sprintf('\n') ...
        '    C.seg0.push_back(tm);C.seg1.push_back(tb);C.cp.push_back(std::move(Rp));' sprintf('\n') ...
        '}'];

    hppNew=replace_once(hppNew,old,new,'R17 split -> R22B exact dyadic split');

    %% 3. R17 family exact by construction.
    old='    C.family=5;C.constant_translation=true;';
    new='    C.family=5;C.constant_translation=true;C.exact_c7=true;';
    hppNew=replace_once(hppNew,old,new,'R17 exact C7 flag');

    %% 4. R16 constant family is exact C7: zero unsafe velocity, repeated
    % endpoint control values and a constant unsafe-span polynomial.
    old=[ ...
        '            Candidate C=build_candidate(E.comp,t0,t1,z,totalCost,sg,minSlack,4);' sprintf('\n') ...
        '            C.constant_translation=true;' sprintf('\n') ...
        '            const double aopt=r17_speed_opt_alpha(E.comp,t0,t1,C.pos,base,L);'];
    new=[ ...
        '            Candidate C=build_candidate(E.comp,t0,t1,z,totalCost,sg,minSlack,4);' sprintf('\n') ...
        '            C.constant_translation=true;' sprintf('\n') ...
        '            C.exact_c7=true; // zero-jet transitions + constant unsafe spans' sprintf('\n') ...
        '            const double aopt=r17_speed_opt_alpha(E.comp,t0,t1,C.pos,base,L);'];
    hppNew=replace_once(hppNew,old,new,'R16 exact C7 flag');

    %% 5. Nonrepresentable R22B split candidate is skipped, not planner-fatal.
    old=[ ...
        '            auto pushR17=[&](double av){' sprintf('\n') ...
        '                Candidate S=r17_build_split_constant(E.comp,t0,t1,z,totalCost,sg,minSlack,av);' sprintf('\n') ...
        '                calm.push_back(std::move(S));' sprintf('\n') ...
        '            };'];
    new=[ ...
        '            auto pushR17=[&](double av){' sprintf('\n') ...
        '                try{' sprintf('\n') ...
        '                    Candidate S=r17_build_split_constant(E.comp,t0,t1,z,totalCost,sg,minSlack,av);' sprintf('\n') ...
        '                    calm.push_back(std::move(S));' sprintf('\n') ...
        '                }catch(const std::runtime_error&e){' sprintf('\n') ...
        '                    const std::string m=e.what();' sprintf('\n') ...
        '                    if(m.rfind("R22B ",0)==0)return;' sprintf('\n') ...
        '                    throw;' sprintf('\n') ...
        '                }' sprintf('\n') ...
        '            };'];
    hppNew=replace_once(hppNew,old,new,'R17 representability fail-closed skip');

    %% 6. Exact C7 is a hard candidate gate before speed/rejoin/geometry.
    % Region-bound insertion: later diagnostics may change lines inside the
    % loop, so do not depend on the text immediately following the for line.
    hppNew=insert_after_in_region( ...
        hppNew, ...
        'auto certify_candidates=[&]', ...
        'return false;', ...
        '        for(auto cand:candidates){', ...
        sprintf('\n        if(!cand.exact_c7)continue;'), ...
        'exact C7 hard candidate gate');

    %% 7. Serialize exact representation authority.
    old='"spatial_envelope_priority","compact_constant_translation","minimum_deviation_primary",';
    new='"spatial_envelope_priority","compact_constant_translation","stored_c7_exact","minimum_deviation_primary",';
    cppNew=replace_once(cppNew,old,new,'MEX field list stored_c7_exact');

    anchor='    set("compact_constant_translation",logicalScalar(R.cand.family==4||R.cand.family==5));';
    new=[anchor sprintf('\n') ...
        '    set("stored_c7_exact",logicalScalar(R.cand.exact_c7));'];
    cppNew=replace_once(cppNew,anchor,new,'MEX exact C7 field value');

    %% 8. Proposal can no longer self-declare C7.
    old='            P.c7_exact=true;';
    new=[ ...
        '            assert(isfield(RAW,''stored_c7_exact''), ...' sprintf('\n') ...
        '                ''[AF7R46] native result lacks exact stored-C7 authority.'');' sprintf('\n') ...
        '            P.c7_exact=logical(RAW.stored_c7_exact);'];
    rpsNew=replace_once(rpsNew,old,new,'proposal exact C7 binding');

    %% 9. Extend predeadline audit latch if R16C instrumentation exists.
    if contains(rpsNew,'staged_replan_predeadline_constant_translation = false;') && ...
            ~contains(rpsNew,'staged_replan_predeadline_c7_exact = false;')
        rpsNew=replace_once(rpsNew, ...
            '        staged_replan_predeadline_constant_translation = false;', ...
            ['        staged_replan_predeadline_constant_translation = false;' sprintf('\n') ...
             '        staged_replan_predeadline_c7_exact = false;'], ...
            'R22B predeadline C7 property');
    end

    if contains(rpsNew,'obj.staged_replan_predeadline_constant_translation= ...') && ...
            ~contains(rpsNew,'obj.staged_replan_predeadline_c7_exact=')
        anchor=[ ...
            '                if isfield(NR16,''compact_constant_translation'')' sprintf('\n') ...
            '                    obj.staged_replan_predeadline_constant_translation= ...' sprintf('\n') ...
            '                        logical(NR16.compact_constant_translation);' sprintf('\n') ...
            '                end'];
        repl=[anchor sprintf('\n') ...
            '                if isfield(NR16,''stored_c7_exact'')' sprintf('\n') ...
            '                    obj.staged_replan_predeadline_c7_exact=logical(NR16.stored_c7_exact);' sprintf('\n') ...
            '                end'];
        rpsNew=replace_once(rpsNew,anchor,repl,'R22B predeadline C7 latch');
    end

    if contains(rpsNew,'S.predeadline_constant_translation=logical(obj.staged_replan_predeadline_constant_translation);') && ...
            ~contains(rpsNew,'S.predeadline_c7_exact=')
        anchor='            S.predeadline_constant_translation=logical(obj.staged_replan_predeadline_constant_translation);';
        repl=[anchor sprintf('\n') ...
            '            S.predeadline_c7_exact=logical(obj.staged_replan_predeadline_c7_exact);'];
        rpsNew=replace_once(rpsNew,anchor,repl,'R22B predeadline C7 status');
    end

    %% 10. Static invariants.
    assert(count_exact(hppNew,'AF7_EXACT_C7_DYADIC_LATTICE_R22B')==1);
    assert(count_exact(hppNew,'bool exact_c7=false;')==1);
    assert(count_exact(hppNew,'if(!cand.exact_c7)continue;')==1);
    assert(count_exact(hppNew,'C.family=5;C.constant_translation=true;C.exact_c7=true;')==1);
    assert(count_exact(hppNew,'R22B split halves not exactly equal')==1);
    assert(count_exact(cppNew,'"stored_c7_exact"')>=2);
    assert(~contains(rpsNew,'            P.c7_exact=true;'));
    assert(contains(rpsNew,'P.c7_exact=logical(RAW.stored_c7_exact);'));

    % Hard safety authority must remain.
    assert(contains(hppNew,'tighten_stageA'));
    assert(contains(hppNew,'stageB_speed'));
    assert(contains(hppNew,'rejoin_safe'));
    assert(contains(hppNew,'wholebody'));

    %% 11. Stage compile MEX.
    stageDir=tempname;
    [ok,msg]=mkdir(stageDir);assert(ok,'%s',msg);
    stageCleanup=onCleanup(@()cleanup_stage(stageDir)); %#ok<NASGU>
    stagedHpp=fullfile(stageDir,'af7r36_core.hpp');
    stagedCpp=fullfile(stageDir,'af7r36_single_core_mex.cpp');
    write_text(stagedHpp,hppNew);write_text(stagedCpp,cppNew);

    fprintf('[R22B] Compiling staged MEX...\n');
    oldDir=pwd; cwdCleanup=onCleanup(@()cd(oldDir)); %#ok<NASGU>
    cd(stageDir); clear mex
    mex('-R2018a','-O','COMPFLAGS="$COMPFLAGS /std:c++17"', ...
        ['-I' stageDir],'-output','af7r36_single_core_mex','-outdir',stageDir,stagedCpp);
    stagedMex=fullfile(stageDir,['af7r36_single_core_mex.' mexext]);
    assert(isfile(stagedMex),'[R22B] staged MEX missing.');

    %% 12. Transactional install.
    dstMex=fullfile(refDir,['af7r36_single_core_mex.' mexext]);
    oldMexTmp=fullfile(stageDir,['af7r36_single_core_mex_OLD.' mexext]);
    hadOldMex=isfile(dstMex);
    if hadOldMex
        [ok,msg]=copyfile(dstMex,oldMexTmp,'f');assert(ok,'%s',msg);
    end

    cd(oldDir); clear mex
    wroteH=false;wroteC=false;wroteR=false;installedMex=false;
    try
        write_text(hpp,hppNew);wroteH=true;
        write_text(cpp,cppNew);wroteC=true;
        write_text(rps,rpsNew);wroteR=true;
        [ok,msg]=copyfile(stagedMex,dstMex,'f');assert(ok,'%s',msg);installedMex=true;
        clear mex;rehash
        assert(exist('af7r36_single_core_mex','file')==3);
        assert(contains(normlf(fileread(hpp)),'AF7_EXACT_C7_DYADIC_LATTICE_R22B'));
        assert(contains(normlf(fileread(rps)),'P.c7_exact=logical(RAW.stored_c7_exact);'));
    catch ME2
        if wroteH,try,write_text(hpp,hpp0);catch,end,end
        if wroteC,try,write_text(cpp,cpp0);catch,end,end
        if wroteR,try,write_text(rps,rps0);catch,end,end
        if installedMex&&hadOldMex,try,copyfile(oldMexTmp,dstMex,'f');catch,end,end
        clear mex;rehash
        rethrow(ME2);
    end

    fprintf('[R22B] PASS.\n');
    fprintf('  exact binary64 C7 hard gate               = 1\n');
    fprintf('  R17 split dyadic lattice                  = 1\n');
    fprintf('  old minimum-snap can be accepted          = 0 unless separately exact-certified\n');
    fprintf('  hard safety recertification after shape   = unchanged and mandatory\n');
    fprintf('  IMPORTANT: clear old objects/classes before the next simulation.\n');

    OUT=struct('pass',true, ...
        'revision','AF7_EXACT_C7_DYADIC_LATTICE_R22B', ...
        'zero_tolerance_C7',true, ...
        'same_trajectory_recertified',true, ...
        'hard_safety_modified',false, ...
        'legacy_unverified_C7_acceptance_disabled',true);

catch ME
    clear mex;rehash
    fprintf(2,'[R22B] FAILED. No successful production install completed.\n');
    fprintf(2,'[R22B] ORIGINAL ERROR: %s | %s\n',ME.identifier,ME.message);
    rethrow(ME);
end
end

function txt=insert_after_in_region(txt,regionStart,regionEnd,anchor,insert,label)
p0=strfind(txt,regionStart);
assert(numel(p0)==1,'[R22B] Region start "%s" count=%d; expected 1.',label,numel(p0));
tail=txt(p0:end);
p1=strfind(tail,regionEnd);
assert(~isempty(p1),'[R22B] Region end "%s" not found.',label);
regionStop=p0+p1(1)-2;
pa=strfind(txt(p0:regionStop),anchor);
assert(numel(pa)==1,'[R22B] Anchor "%s" count=%d inside region; expected 1.',label,numel(pa));
q=p0+pa(1)-1+numel(anchor)-1;
txt=[txt(1:q) insert txt(q+1:end)];
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1,'[R22B] Anchor "%s" count=%d; expected 1.',label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end
function n=count_exact(txt,pat),n=numel(strfind(txt,pat));end
function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));s=strrep(s,sprintf('\r'),sprintf('\n'));
end
function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');assert(f>=0,'[R22B] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end
function cleanup_stage(d)
if isfolder(d),try,rmdir(d,'s');catch,end,end
end
