function B=AF7R58R179_BODY_SUPPORT(PQ,PL,radii,n)
% CANONICAL WHOLE BODY GEOMETRY, R179.
% UAV = closed ball(center=pQ,rQ), payload = ball(center=pL,rL).
% Cable = union_{lambda in [0,1]} ball(pL+lambda*(pQ-pL),rC).
% The finite-width cable is a CAPSULE, never a sphere of radius L.
% PQ, PL: 3-by-K control-point HULLS for the same time interval.
% If a source guarantees actual endpoint curves lie in conv(PQ) and
% conv(PL), each bound holds for every time and every cable fraction.
% In particular, the cable belongs to conv([PQ,PL])+Ball(rC).
% These formulae are exact over the convex hulls in real arithmetic;
% double results are NOT IEEE-outward-certified.
B=struct('valid',false,'status','INVALID_BODY_SUPPORT_INPUT',...
 'lower',nan(3,1),'upper',nan(3,1),...
 'full_lower',NaN,'full_upper',NaN,...
 'body_order','UAV_CABLE_PAYLOAD','cable_is_segment_capsule',true,...
 'uses_length_radius_sphere',false,'outward_rounded',false);
if nargin~=4||~isnumeric(PQ)||~isnumeric(PL)||...
 size(PQ,1)~=3||size(PL,1)~=3||...
 isempty(PQ)||isempty(PL)||~isnumeric(radii)||numel(radii)~=3||...
 ~isnumeric(n)||numel(n)~=3,return;end
PQ=double(PQ);PL=double(PL);r=double(radii(:));n=double(n(:));
if any(~isfinite([PQ(:);PL(:);r;n]))||any(r<0)||norm(n)==0,return;end
k=norm(n);hq=n'*PQ;hl=n'*PL;
B.lower=[min(hq)-r(1)*k;...
 min([hq hl])-r(2)*k;...
 min(hl)-r(3)*k];
B.upper=[max(hq)+r(1)*k;...
 max([hq hl])+r(2)*k;...
 max(hl)+r(3)*k];
B.full_lower=min(B.lower);B.full_upper=max(B.upper);
B.valid=true;B.status='REAL_ARITHMETIC_CONVEX_HULL_BOUND__NO_IEEE_CERT';
end
