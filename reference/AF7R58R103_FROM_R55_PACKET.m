function F=AF7R58R103_FROM_R55_PACKET(P,eventTime,referenceVersion)
% Build exact Flight trigger input from existing R55 event packet. The
% physical forecast must be supplied SEPARATELY; R55 contains references.
assert(isstruct(P)&&isscalar(P)&&isnumeric(eventTime)&& ...
    isscalar(eventTime)&&isfinite(eventTime)&& ...
    isnumeric(referenceVersion)&&isscalar(referenceVersion)&& ...
    isfinite(referenceVersion), ...
    'R103:PacketAndEventBinding','Provide captured R55 and its exact event/version.');
req={'pL_EKF','pQ_EKF','active','centers','rotations','axes', ...
    'ids','radii','H','dt','L'};
for k=1:numel(req)
    assert(isfield(P,req{k}),'R103:R55MissingSourceField', ...
        'Captured R55 packet is missing %s.',req{k});
end
F=struct('time_s',double(eventTime), ...
    'reference_version',double(referenceVersion), ...
    'horizon_s',double(P.H),'dt_s',double(P.dt), ...
    'cable_length_m',double(P.L), ...
    'pL_EKF',double(P.pL_EKF(:)), ...
    'pQ_EKF',double(P.pQ_EKF(:)), ...
    'known_mask',logical(P.active(:).'), ...
    'C',double(P.centers),'R',double(P.rotations), ...
    'Araw',double(P.axes),'ids',double(P.ids), ...
    'Dcomp',double(P.radii(:)));
% IMPORTANT: no physical prediction is synthesized from pL_ref/q_ref.
end
