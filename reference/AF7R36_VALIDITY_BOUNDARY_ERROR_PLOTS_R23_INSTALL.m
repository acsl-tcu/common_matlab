function OUT=AF7R36_VALIDITY_BOUNDARY_ERROR_PLOTS_R23_INSTALL()
% AF7R36_VALIDITY_BOUNDARY_ERROR_PLOTS_R23_INSTALL
%
% Two independent MATLAB-only corrections:
%
% (A) Staged activation / valid_from binary64 boundary
% Stage3 already accepts an activation instant when
%   |t_now-t_a| <= 64*eps(scale).
% The repaired evaluator previously required t_now>=valid_from with zero
% representational tolerance. Thus Stage3 could atomically activate at
% t_now=t_a-few-ULPs and immediately fail in the same cycle.
%
% R23 does NOT extend the repair certificate backward.
% If t_now<valid_from but lies inside the exact same Stage3 representational
% equivalence window, the output is the nominal reference. This is consistent
% with the canonical correction support theorem: correction is active only
% for strict t>t0. Any earlier time outside that ULP window remains fail-closed.
%
% (B) Headless error plotting
% The simulation exception is captured, partial logger/runtime data are
% plotted using the existing plotting code, drawnow is executed, then the
% ORIGINAL simulation exception is rethrown. No failure is hidden.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 VALIDITY-BOUNDARY + ERROR-PLOTS R23 INSTALL\n');
fprintf(' repair validity interval extended           = 0\n');
fprintf(' pre-validity repaired evaluation             = 0\n');
fprintf(' Stage3/evaluator floating-boundary aligned   = 1\n');
fprintf(' simulation errors suppressed                 = 0\n');
fprintf(' partial plots before rethrow                 = 1\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir)&&isfolder(refDir),'[R23] Cannot resolve reference directory.');
rps=fullfile(refDir,'REPLANNING_SYSTEM.m');
runner=which('run_flight_headless');
assert(isfile(rps),'[R23] Missing %s',rps);
assert(~isempty(runner)&&isfile(runner),'[R23] run_flight_headless.m not found.');

r0=normlf(fileread(rps));
h0=normlf(fileread(runner));
r=r0;h=h0;

assert(~contains(r0,'AF7R36 R23 certified-boundary nominal hold'), ...
    '[R23] validity patch already installed.');
assert(~contains(h0,'AF7R36 R23 partial-plot-on-error'), ...
    '[R23] runner patch already installed.');

try
    %% A. Replace only the active-reference validity test.
    old=[ ...
        '                    assert(isfield(R,''valid_from'') && isfield(R,''valid_until'') && ...' sprintf('\n') ...
        '                        isfinite(R.valid_from) && ...' sprintf('\n') ...
        '                        (isfinite(R.valid_until) || isinf(R.valid_until)) && ...' sprintf('\n') ...
        '                        double(t_now)>=double(R.valid_from) && ...' sprintf('\n') ...
        '                        double(t_now)<=double(R.valid_until), ...' sprintf('\n') ...
        '                        ''[REPLANNER ERROR] repaired reference queried outside certified validity interval.'');' sprintf('\n') ...
        '' sprintf('\n') ...
        '                    xd=R.eval_fn(double(t_now));'];

    new=[ ...
        '                    assert(isfield(R,''valid_from'') && isfield(R,''valid_until'') && ...' sprintf('\n') ...
        '                        isfinite(R.valid_from) && ...' sprintf('\n') ...
        '                        (isfinite(R.valid_until) || isinf(R.valid_until)), ...' sprintf('\n') ...
        '                        ''[REPLANNER ERROR] repaired reference validity metadata is invalid.'');' sprintf('\n') ...
        '                    tn=double(t_now); vf=double(R.valid_from); vu=double(R.valid_until);' sprintf('\n') ...
        '                    if tn<vf' sprintf('\n') ...
        '                        % AF7R36 R23 certified-boundary nominal hold.' sprintf('\n') ...
        '                        % Stage3 already treats this ULP-scale difference as' sprintf('\n') ...
        '                        % the same activation grid instant. Do NOT evaluate' sprintf('\n') ...
        '                        % repaired dynamics before vf; return nominal instead.' sprintf('\n') ...
        '                        sc=max([1,abs(tn),abs(vf)]);' sprintf('\n') ...
        '                        btol=64*eps(sc);' sprintf('\n') ...
        '                        assert(vf-tn<=btol, ...' sprintf('\n') ...
        '                            [''[REPLANNER ERROR] repaired reference queried before certified validity interval: '' ...' sprintf('\n') ...
        '                             ''t=%.17g valid_from=%.17g gap=%.17g tol=%.17g''], ...' sprintf('\n') ...
        '                            tn,vf,vf-tn,btol);' sprintf('\n') ...
        '                        xd=xd_nom(:);' sprintf('\n') ...
        '                        return;' sprintf('\n') ...
        '                    end' sprintf('\n') ...
        '                    assert(tn<=vu, ...' sprintf('\n') ...
        '                        [''[REPLANNER ERROR] repaired reference queried after certified validity interval: '' ...' sprintf('\n') ...
        '                         ''t=%.17g valid_until=%.17g''],tn,vu);' sprintf('\n') ...
        '' sprintf('\n') ...
        '                    xd=R.eval_fn(tn);'];

    r=replace_once(r,old,new,'active repaired validity boundary');

    %% B1. Open try/catch around simulation loop.
    old=[ ...
        'cha = ''t'';' sprintf('\n') ...
        '' sprintf('\n') ...
        'while time.t <= time.te'];
    new=[ ...
        'cha = ''t'';' sprintf('\n') ...
        '' sprintf('\n') ...
        '% AF7R36 R23 partial-plot-on-error: preserve the original failure.' sprintf('\n') ...
        'simulation_error=[];' sprintf('\n') ...
        'simulation_error_time=NaN;' sprintf('\n') ...
        'simulation_error_phase='''';' sprintf('\n') ...
        'try' sprintf('\n') ...
        'while time.t <= time.te'];
    h=replace_once(h,old,new,'simulation try open');

    %% B2. Close simulation try immediately after the while loop.
    old=[ ...
        '    if mod(time.t,5.0) < dt' sprintf('\n') ...
        '        fprintf(''Time: %.1f / %.1f sec (Phase: %s)\n'',time.t,time.te,cha);' sprintf('\n') ...
        '    end' sprintf('\n') ...
        'end' sprintf('\n') ...
        '' sprintf('\n') ...
        '% Trim preallocated timing arrays to actual logged length.'];
    new=[ ...
        '    if mod(time.t,5.0) < dt' sprintf('\n') ...
        '        fprintf(''Time: %.1f / %.1f sec (Phase: %s)\n'',time.t,time.te,cha);' sprintf('\n') ...
        '    end' sprintf('\n') ...
        'end' sprintf('\n') ...
        'catch ME_SIM' sprintf('\n') ...
        '    simulation_error=ME_SIM;' sprintf('\n') ...
        '    simulation_error_time=double(time.t);' sprintf('\n') ...
        '    simulation_error_phase=char(cha);' sprintf('\n') ...
        '    fprintf(2,''\n[HEADLESS] Simulation stopped at t=%.9g s, phase=%s.\n'', ...' sprintf('\n') ...
        '        simulation_error_time,simulation_error_phase);' sprintf('\n') ...
        '    fprintf(2,''[HEADLESS] Original error: %s | %s\n'',ME_SIM.identifier,ME_SIM.message);' sprintf('\n') ...
        'end' sprintf('\n') ...
        '' sprintf('\n') ...
        '% Trim preallocated timing arrays to actual logged length.'];
    h=replace_once(h,old,new,'simulation try close');

    %% B3. Change completion message and guard the plotting block.
    old='disp("Simulation complete! Drawing plots...");';
    new=[ ...
        'if isempty(simulation_error)' sprintf('\n') ...
        '    disp("Simulation complete! Drawing plots...");' sprintf('\n') ...
        'else' sprintf('\n') ...
        '    disp("Simulation interrupted. Drawing all available partial plots before rethrow...");' sprintf('\n') ...
        'end' sprintf('\n') ...
        'plot_error=[];' sprintf('\n') ...
        'try'];
    h=replace_once(h,old,new,'plot try open');

    %% B4. Close plotting, force draw, then rethrow ORIGINAL sim error.
    old=[ ...
        'drawnow;' sprintf('\n') ...
        '' sprintf('\n') ...
        '%% LOCAL FUNCTIONS'];
    new=[ ...
        'drawnow;' sprintf('\n') ...
        'catch ME_PLOT' sprintf('\n') ...
        '    plot_error=ME_PLOT;' sprintf('\n') ...
        '    fprintf(2,''[HEADLESS] Partial plotting error: %s | %s\n'',ME_PLOT.identifier,ME_PLOT.message);' sprintf('\n') ...
        '    drawnow;' sprintf('\n') ...
        'end' sprintf('\n') ...
        '' sprintf('\n') ...
        'if ~isempty(simulation_error)' sprintf('\n') ...
        '    fprintf(2,''[HEADLESS] Partial plots displayed through t=%.9g s. Rethrowing original simulation error.\n'', ...' sprintf('\n') ...
        '        simulation_error_time);' sprintf('\n') ...
        '    rethrow(simulation_error);' sprintf('\n') ...
        'end' sprintf('\n') ...
        'if ~isempty(plot_error)' sprintf('\n') ...
        '    rethrow(plot_error);' sprintf('\n') ...
        'end' sprintf('\n') ...
        '' sprintf('\n') ...
        '%% LOCAL FUNCTIONS'];
    h=replace_once(h,old,new,'plot try close/rethrow');

    %% Static invariants.
    assert(count_exact(r,'AF7R36 R23 certified-boundary nominal hold')==1);
    assert(contains(r,'assert(vf-tn<=btol'));
    assert(contains(r,'xd=xd_nom(:);'));
    assert(count_exact(h,'AF7R36 R23 partial-plot-on-error')==1);
    assert(contains(h,'rethrow(simulation_error);'));
    assert(contains(h,'Simulation interrupted. Drawing all available partial plots before rethrow...'));

    %% Transactional install.
    stage=tempname;
    [ok,msg]=mkdir(stage);assert(ok,'%s',msg);
    c=onCleanup(@()cleanup_stage(stage)); %#ok<NASGU>
    rb=fullfile(stage,'REPLANNING_SYSTEM.m');
    hb=fullfile(stage,'run_flight_headless.m');
    copyfile(rps,rb,'f'); copyfile(runner,hb,'f');

    wroteR=false;wroteH=false;
    try
        write_text(rps,r);wroteR=true;
        write_text(runner,h);wroteH=true;
        rehash
        assert(contains(normlf(fileread(rps)),'AF7R36 R23 certified-boundary nominal hold'));
        assert(contains(normlf(fileread(runner)),'AF7R36 R23 partial-plot-on-error'));
    catch ME2
        if wroteR,try,copyfile(rb,rps,'f');catch,end,end
        if wroteH,try,copyfile(hb,runner,'f');catch,end,end
        rehash
        rethrow(ME2);
    end

    fprintf('[R23] PASS.\n');
    fprintf('  repair evaluated before valid_from         = 0\n');
    fprintf('  ULP boundary returns nominal               = 1\n');
    fprintf('  earlier-than-boundary query fail-closed    = 1\n');
    fprintf('  interrupted simulation plots partial data  = 1\n');
    fprintf('  original simulation error rethrown         = 1\n');
    fprintf('  IMPORTANT: clear classes before next run.\n');

    OUT=struct('pass',true, ...
        'revision','AF7_VALIDITY_BOUNDARY_ERROR_PLOTS_R23', ...
        'validity_extended',false, ...
        'pre_validity_repaired_eval',false, ...
        'partial_plots_on_error',true, ...
        'original_error_rethrown',true);

catch ME
    fprintf(2,'[R23] FAILED. Production install not completed.\n');
    fprintf(2,'[R23] ORIGINAL ERROR: %s | %s\n',ME.identifier,ME.message);
    rethrow(ME);
end
end

function txt=replace_once(txt,old,new,label)
p=strfind(txt,old);
assert(numel(p)==1,'[R23] Anchor "%s" count=%d; expected 1.',label,numel(p));
txt=[txt(1:p-1) new txt(p+numel(old):end)];
end
function n=count_exact(txt,pat),n=numel(strfind(txt,pat));end
function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));s=strrep(s,sprintf('\r'),sprintf('\n'));
end
function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');assert(f>=0,'[R23] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end
function cleanup_stage(d)
if isfolder(d),try,rmdir(d,'s');catch,end,end
end
