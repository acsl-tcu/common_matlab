function T=AF7R58R120_BIND_R71_TRIGGER(event,R71)
% Bind R71's ACTUAL EKF/HLC/plant numerical rollout to the independent
% physical trigger. Do not fabricate a differential enclosure from its
% finite differences or from its solver's tolerances. Without an external
% VALIDATED speed/reachability bound, interval-clear remains UNKNOWN.
required={'event_time_s','reference_version','EKF_x24','EKF_mL', ...
    'horizon_s','dt_s','known_obstacles','radii_m'};
for k=1:numel(required)
 assert(isfield(event,required{k}), ...
   'R120:MissingSameEventInput','Missing %s',required{k});
end
T=struct('status','BLOCKED_R71_PHYSICAL_ROLLOUT_UNAVAILABLE', ...
    'request',true,'proved_clear',false,'sampled_risk_witness',false, ...
    'reference_trigger_used',false, 'native_commit_authorized',false);
if isempty(R71)
    return;
end
requiredR={'t','pQ','pL','state','estimated_mass_kg', ...
    'continuous_time_collision_proved'};
if ~isstruct(R71)||~isscalar(R71)||~all(isfield(R71,requiredR))
    T.status='BLOCKED_INVALID_ACTUAL_R71_SCHEMA';return;
end
x=double(event.EKF_x24(:));tt=double(R71.t(:).');
if numel(x)~=24 || any(~isfinite(x)) || numel(tt)<2 || ...
  size(R71.state,1)~=24 || size(R71.state,2)~=numel(tt) || ...
  ~isequal(size(R71.pQ),[3 numel(tt)]) || ...
  ~isequal(size(R71.pL),[3 numel(tt)]) || ...
  abs(double(R71.estimated_mass_kg)-double(event.EKF_mL))> ...
     1024*eps(max([1,abs(double(event.EKF_mL))])) || ...
  abs(tt(1)-double(event.event_time_s))> ...
     128*eps(max(1,abs(tt(1)))) || ...
  norm(R71.state(:,1)-x,Inf)> ...
     256*eps(max([1;abs(x)]))
    T.status='BLOCKED_R71_EVENT_MASS_OR_EKF_SEAM_MISMATCH';return;
end
P=struct('source','LIVE_EKF_HLC_PLANT_ROLLOUT', ...
    'time_s',double(event.event_time_s), ...
    'reference_version',double(event.reference_version), ...
    'EKF_mL',double(event.EKF_mL), ...
    'pQ',double(R71.pQ),'pL',double(R71.pL),'t_s',tt);
% R71 does NOT create this proof. If and only if a separate validated
% reachability engine supplies per-time-cell bounds do we pass them through.
if isfield(event,'validated_reachability') && ...
   isstruct(event.validated_reachability) && ...
   all(isfield(event.validated_reachability, ...
      {'interval_speed_upper_m_s','bound_certificate'}))
    P.interval_speed_upper_m_s= ...
       event.validated_reachability.interval_speed_upper_m_s;
    P.bound_certificate=event.validated_reachability.bound_certificate;
end
A=event;A.rollout=P;
T=AF7R58R118_EKF_TRIGGER(A);
T.r71_numerical_same_event_bound=true;
T.r71_closed_loop_reachability_proved=false;
if isfield(P,'bound_certificate')
    T.r71_closed_loop_reachability_proved= ...
        logical(T.physical_full_interval_proved);
end
T.native_commit_authorized=false;
end
