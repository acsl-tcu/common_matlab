function OUT = AF7R36_C7_HOMOTOPY_FRONTIER_R6_INSTALL()
% AF7R36_C7_HOMOTOPY_FRONTIER_R6_INSTALL
%
% DIAGNOSTIC ONLY. The selected production trajectory is NOT changed.
%
% Purpose:
%   For fixed-t1 calls that already have a certified production solution,
%   scan the convex continuation between
%
%       alpha=0 : AF7_TOWING_NATURAL_TIME_C3_R5 solution
%       alpha=1 : historical minimum-snap solution
%
%   for the SAME obstacle-side/sign assignment.
%
% For each alpha candidate:
%   - degree-15 / C7 construction is unchanged,
%   - existing speed certificate is applied,
%   - existing rejoin certificate is applied,
%   - existing continuous whole-body certificate is applied,
%   - continuous nonzero XY-tangent is separately certified for
%     heading-exact yaw regularity.
%
% The homotopy is diagnostic only. No sampled point grants safety.
% No README and no persistent backup file is created.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 C7 HOMOTOPY FRONTIER R6 INSTALL\n');
fprintf(' production candidate selection modified    = 0\n');
fprintf(' hard safety semantics modified             = 0\n');
fprintf(' translation structural continuity          = C7\n');
fprintf(' heading-exact yaw prerequisite diagnosed   = 1\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir) && isfolder(refDir), ...
    '[C7FRONT-R6] Cannot resolve current reference directory.');

hpp=fullfile(refDir,'af7r36_core.hpp');
cpp=fullfile(refDir,'af7r36_single_core_mex.cpp');
assert(isfile(hpp),'[C7FRONT-R6] Missing %s',hpp);
assert(isfile(cpp),'[C7FRONT-R6] Missing %s',cpp);

hpp0=normlf(fileread(hpp));
cpp0=normlf(fileread(cpp));
hppNew=hpp0;
cppNew=cpp0;

assert(contains(hpp0,'AF7_TOWING_NATURAL_TIME_C3_R5'), ...
    '[C7FRONT-R6] R5 towing natural-time core not found.');
assert(contains(cpp0,'TOWING_NATURAL_TIME_C3'), ...
    '[C7FRONT-R6] R5 family wrapper output not found.');
assert(contains(cpp0,'AF7_TOWMAP_R4C_RING'), ...
    '[C7FRONT-R6] R4C diagnostic ring is required for paired comparison.');
assert(~contains(hpp0,'AF7_C7_HOMOTOPY_FRONTIER_R6'), ...
    '[C7FRONT-R6] R6 core diagnostic already installed.');
assert(~contains(cpp0,'AF7_C7_HOMOTOPY_FRONTIER_R6_RING'), ...
    '[C7FRONT-R6] R6 wrapper diagnostic already installed.');
assert(contains(cpp0, ...
    'static const char* PLANNER_REV="AF7_REPLANNER_MIN_DEVIATION_V4_FIXED_T1";'), ...
    '[C7FRONT-R6] Planner build identity mismatch.');

try
    %% --------------------------------------------------------------------
    % 1) Core diagnostic types + exact candidate certification copy.
    % ---------------------------------------------------------------------
    anchor='// ---------------------------- top-level -------------------------------------';
    helper=[ ...
        '// AF7_C7_HOMOTOPY_FRONTIER_R6' sprintf('\n') ...
        '// Diagnostic-only continuation frontier. Never used for production selection.' sprintf('\n') ...
        'struct C7FrontRow {' sprintf('\n') ...
        '    double alpha=0;' sprintf('\n') ...
        '    int sign_code=0;' sprintf('\n') ...
        '    bool generated=false,speed=false,rejoin=false,geometry=false,heading=false;' sprintf('\n') ...
        '    double envelope=std::numeric_limits<double>::quiet_NaN();' sprintf('\n') ...
        '    double VL=std::numeric_limits<double>::quiet_NaN();' sprintf('\n') ...
        '    double A=std::numeric_limits<double>::quiet_NaN();' sprintf('\n') ...
        '    double J=std::numeric_limits<double>::quiet_NaN();' sprintf('\n') ...
        '    double sigma=std::numeric_limits<double>::quiet_NaN();' sprintf('\n') ...
        '    double qdot=std::numeric_limits<double>::quiet_NaN();' sprintf('\n') ...
        '    double VQ=std::numeric_limits<double>::quiet_NaN();' sprintf('\n') ...
        '    double heading_lb=std::numeric_limits<double>::quiet_NaN();' sprintf('\n') ...
        '    int heading_splits=0;' sprintf('\n') ...
        '};' sprintf('\n') ...
        'static std::vector<C7FrontRow> G_c7front_rows;' sprintf('\n') ...
        '' sprintf('\n') ...
        'struct HeadingRegularityCert {' sprintf('\n') ...
        '    bool pass=false;' sprintf('\n') ...
        '    double min_lb=std::numeric_limits<double>::infinity();' sprintf('\n') ...
        '    int splits=0;' sprintf('\n') ...
        '};' sprintf('\n') ...
        'static inline HeadingRegularityCert c7front_heading_regular(' sprintf('\n') ...
        '        const ActiveReference&ref,const Candidate&C,const SpeedCert&s,double ta,double tb){' sprintf('\n') ...
        '    HeadingRegularityCert R;' sprintf('\n') ...
        '    struct Leaf{double a,b;int d;};' sprintf('\n') ...
        '    std::vector<Leaf> st;' sprintf('\n') ...
        '    if(!(fin(ta)&&fin(tb)&&tb>ta&&s.certified&&fin(s.A)&&s.A>=0))return R;' sprintf('\n') ...
        '    st.push_back({ta,tb,0});' sprintf('\n') ...
        '    const int maxDepth=52;' sprintf('\n') ...
        '    while(!st.empty()){' sprintf('\n') ...
        '        Leaf f=st.back();st.pop_back();' sprintf('\n') ...
        '        double tc=0.5*(f.a+f.b),h=0.5*(f.b-f.a);' sprintf('\n') ...
        '        if(!(tc>f.a&&tc<f.b))return R;' sprintf('\n') ...
        '        auto x=candidate_eval(ref,C,tc);' sprintf('\n') ...
        '        double vxy=std::hypot(x[1].x,x[1].y);' sprintf('\n') ...
        '        double lb=vxy-s.A*h;' sprintf('\n') ...
        '        if(fin(lb)&&lb>0){R.min_lb=std::min(R.min_lb,lb);continue;}' sprintf('\n') ...
        '        if(f.d>=maxDepth)return R;' sprintf('\n') ...
        '        st.push_back({tc,f.b,f.d+1});' sprintf('\n') ...
        '        st.push_back({f.a,tc,f.d+1});' sprintf('\n') ...
        '        ++R.splits;' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '    if(fin(R.min_lb)&&R.min_lb>0)R.pass=true;' sprintf('\n') ...
        '    return R;' sprintf('\n') ...
        '}' sprintf('\n') ...
        '' sprintf('\n') ...
        'static inline C7FrontRow c7front_certify_one(' sprintf('\n') ...
        '        const ActiveReference&ref,const Live&L,const SpeedCert&base,' sprintf('\n') ...
        '        const std::vector<Obstacle>&obs,double t0,double tm,double hold,double t1,' sprintf('\n') ...
        '        Candidate cand,double lim,double alpha,int signCode){' sprintf('\n') ...
        '    C7FrontRow D;D.alpha=alpha;D.sign_code=signCode;D.generated=true;D.envelope=cand.max_ctrl;' sprintf('\n') ...
        '    SpeedCert sc;' sprintf('\n') ...
        '    auto tr=tighten_stageA(cand,base,L.L,lim);' sprintf('\n') ...
        '    if(tr.certified){' sprintf('\n') ...
        '        sc=stageA_speed(tr,base,L.L);' sprintf('\n') ...
        '        if(sc.certified&&sc.VQ<lim){' sprintf('\n') ...
        '            cand.dub[0]=tr.U[0];cand.dub[1]=tr.U[1];cand.dub[2]=tr.U[2];' sprintf('\n') ...
        '        }else sc.certified=false;' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '    if(!sc.certified){bool wit=false,rp=false;sc=stageB_speed(ref,L,base,cand,lim,wit,rp);}' sprintf('\n') ...
        '    if(!sc.certified)return D;' sprintf('\n') ...
        '    D.speed=true;D.VL=sc.VL;D.A=sc.A;D.J=sc.J;D.sigma=sc.sigma;D.qdot=sc.qdot;D.VQ=sc.VQ;' sprintf('\n') ...
        '    if(!rejoin_safe(ref,L,obs,t1,sc))return D;' sprintf('\n') ...
        '    D.rejoin=true;' sprintf('\n') ...
        '    auto G=wholebody(ref,L,obs,t0,tm,hold,t1,cand,sc);' sprintf('\n') ...
        '    if(!G.pass)return D;' sprintf('\n') ...
        '    D.geometry=true;' sprintf('\n') ...
        '    auto H=c7front_heading_regular(ref,cand,sc,t0,t1);' sprintf('\n') ...
        '    D.heading=H.pass;D.heading_lb=H.pass?H.min_lb:std::numeric_limits<double>::quiet_NaN();D.heading_splits=H.splits;' sprintf('\n') ...
        '    return D;' sprintf('\n') ...
        '}' sprintf('\n') ...
        '' sprintf('\n') ...
        'static inline void c7front_run(' sprintf('\n') ...
        '        const ActiveReference&ref,const Live&L,const SpeedCert&base,' sprintf('\n') ...
        '        const std::vector<Obstacle>&obs,double t0,double tm,double t1,const EpisodeCert&E){' sprintf('\n') ...
        '    G_c7front_rows.clear();' sprintf('\n') ...
        '    if(!E.ok||E.comp.empty()||E.ep.empty())return;' sprintf('\n') ...
        '    int Cn=(int)E.comp.size(),Ne=(int)E.ep.size(),nvar=6*Cn;' sprintf('\n') ...
        '    std::vector<OrientedRows> OR(Ne);' sprintf('\n') ...
        '    for(int e=0;e<Ne;++e){' sprintf('\n') ...
        '        auto ep=E.ep[e];auto xa=ref.eval(ep.start),xb=ref.eval(ep.end);' sprintf('\n') ...
        '        Vec3 prog=xb[0]-xa[0];' sprintf('\n') ...
        '        if(norm(prog)<=128*epsd()*std::max(1.0,norm(xa[0])))prog=ref.eval(0.5*(ep.start+ep.end))[1];' sprintf('\n') ...
        '        Vec3 n=lateral_normal(obs[ep.obs].R,obs[ep.obs].axes,prog);' sprintf('\n') ...
        '        OR[e].plus=corridor_rows(ref,L,base,obs,E,e,n,nvar);' sprintf('\n') ...
        '        OR[e].minus=corridor_rows(ref,L,base,obs,E,e,n*(-1),nvar);' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '    double rhoBody=std::max({L.rQ,L.L+L.rL,L.L+L.rC});' sprintf('\n') ...
        '    double lim=(L.sensor_range-rhoBody)/(L.horizon+L.dt);' sprintf('\n') ...
        '    if(!(fin(lim)&&lim>0))return;' sprintf('\n') ...
        '    auto Hc3=towing_natural_time_c3_hessian(E.comp,t0,t1,L.L,L.g);' sprintf('\n') ...
        '    auto Hsn=minimum_snap_hessian(E.comp,t0,t1);' sprintf('\n') ...
        '    std::vector<int>sg(Ne,1);int signCode=0;' sprintf('\n') ...
        '    std::function<void(int)> rec=[&](int k){' sprintf('\n') ...
        '        if(k<Ne){sg[k]=1;rec(k+1);sg[k]=-1;rec(k+1);return;}' sprintf('\n') ...
        '        std::vector<Row> rows;' sprintf('\n') ...
        '        for(int e=0;e<Ne;++e){const auto&v=sg[e]>0?OR[e].plus:OR[e].minus;rows.insert(rows.end(),v.begin(),v.end());}' sprintf('\n') ...
        '        QPSol qc=solve_qp(Hc3,nvar,rows),qs=solve_qp(Hsn,nvar,rows);' sprintf('\n') ...
        '        ++signCode;' sprintf('\n') ...
        '        if(!(qc.ok&&qs.ok)||qc.z.size()!=qs.z.size())return;' sprintf('\n') ...
        '        for(int kk=0;kk<=16;++kk){' sprintf('\n') ...
        '            double alpha=double(kk)/16.0;' sprintf('\n') ...
        '            std::vector<double>z(qc.z.size());' sprintf('\n') ...
        '            for(size_t i=0;i<z.size();++i)z[i]=(1.0-alpha)*qc.z[i]+alpha*qs.z[i];' sprintf('\n') ...
        '            Candidate C=build_candidate(E.comp,t0,t1,z,alpha,sg,0.0,4);' sprintf('\n') ...
        '            G_c7front_rows.push_back(c7front_certify_one(ref,L,base,obs,t0,tm,E.comp.back().end,t1,C,lim,alpha,signCode));' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '    };' sprintf('\n') ...
        '    rec(0);' sprintf('\n') ...
        '}' sprintf('\n') ...
        '' sprintf('\n') ...
        anchor];
    hppNew=replace_once(hppNew,anchor,helper,'top-level diagnostic helper anchor');

    %% --------------------------------------------------------------------
    % 2) Run diagnostic only AFTER ordinary fixed-t1 planner result exists,
    % and only when production already found a certified solution.
    % ---------------------------------------------------------------------
    old=['    OUT=plan_fixed_scope(ref,L,base,obs,t0,tm,t1,E);' sprintf('\n') ...
         '    OUT.search_end=t1;'];
    new=['    OUT=plan_fixed_scope(ref,L,base,obs,t0,tm,t1,E);' sprintf('\n') ...
         '    G_c7front_rows.clear();' sprintf('\n') ...
         '    if(OUT.success)c7front_run(ref,L,base,obs,t0,tm,t1,E);' sprintf('\n') ...
         '    OUT.search_end=t1;'];
    hppNew=replace_once(hppNew,old,new,'post-plan diagnostic invocation');

    %% --------------------------------------------------------------------
    % 3) Wrapper aggregation ring + op8 read/op9 clear.
    % ---------------------------------------------------------------------
    anchor='static bool G_compiled=false;';
    ring=[anchor sprintf('\n') sprintf('\n') ...
        '// AF7_C7_HOMOTOPY_FRONTIER_R6_RING -- diagnostic only.' sprintf('\n') ...
        'struct C7FrontMexRow {' sprintf('\n') ...
        '    double seq=0,t0=NAN,tm=NAN,t1=NAN,alpha=NAN,sign_code=0;' sprintf('\n') ...
        '    double generated=0,speed=0,rejoin=0,geometry=0,heading=0,c7=1;' sprintf('\n') ...
        '    double envelope=NAN,VL=NAN,A=NAN,J=NAN,sigma=NAN,qdot=NAN,VQ=NAN,heading_lb=NAN,heading_splits=0;' sprintf('\n') ...
        '};' sprintf('\n') ...
        'static std::vector<C7FrontMexRow> G_c7front_mex;' sprintf('\n') ...
        'static double G_c7front_seq=0;' sprintf('\n') ...
        'static void c7front_push(double t0,double tm,double t1){' sprintf('\n') ...
        '    for(const auto&r:G_c7front_rows){' sprintf('\n') ...
        '        C7FrontMexRow d;d.seq=++G_c7front_seq;d.t0=t0;d.tm=tm;d.t1=t1;d.alpha=r.alpha;d.sign_code=r.sign_code;' sprintf('\n') ...
        '        d.generated=r.generated?1:0;d.speed=r.speed?1:0;d.rejoin=r.rejoin?1:0;d.geometry=r.geometry?1:0;d.heading=r.heading?1:0;' sprintf('\n') ...
        '        d.envelope=r.envelope;d.VL=r.VL;d.A=r.A;d.J=r.J;d.sigma=r.sigma;d.qdot=r.qdot;d.VQ=r.VQ;d.heading_lb=r.heading_lb;d.heading_splits=r.heading_splits;' sprintf('\n') ...
        '        if(G_c7front_mex.size()>=2048)G_c7front_mex.erase(G_c7front_mex.begin());' sprintf('\n') ...
        '        G_c7front_mex.push_back(d);' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '}' sprintf('\n') ...
        'static mxArray* c7front_matrix(){' sprintf('\n') ...
        '    const mwSize N=(mwSize)G_c7front_mex.size(),C=21;' sprintf('\n') ...
        '    mxArray*M=mxCreateDoubleMatrix(N,C,mxREAL);double*p=mxGetPr(M);' sprintf('\n') ...
        '    for(mwSize i=0;i<N;++i){const auto&d=G_c7front_mex[i];double v[C]={' sprintf('\n') ...
        '        d.seq,d.t0,d.tm,d.t1,d.alpha,d.sign_code,d.generated,d.speed,d.rejoin,d.geometry,d.heading,d.c7,' sprintf('\n') ...
        '        d.envelope,d.VL,d.A,d.J,d.sigma,d.qdot,d.VQ,d.heading_lb,d.heading_splits};' sprintf('\n') ...
        '        for(mwSize j=0;j<C;++j)p[i+N*j]=v[j];' sprintf('\n') ...
        '    }return M;' sprintf('\n') ...
        '}'];
    cppNew=replace_once(cppNew,anchor,ring,'R6 MEX ring globals');

    % R4C currently pushes its own diagnostic immediately after plan.
    anchor='            towmap_push(Q,L,t0,tm,searchEnd);';
    new=[anchor sprintf('\n') ...
        '            c7front_push(t0,tm,searchEnd);'];
    cppNew=replace_once(cppNew,anchor,new,'R6 per-plan ring append');

    anchor='        if(op==3){';
    block=[ ...
        '        if(op==8){' sprintf('\n') ...
        '            if(nrhs!=1||nlhs!=1)mexErrMsgIdAndTxt("AF7C7FRONT:Arity","diag op8: op -> matrix.");' sprintf('\n') ...
        '            plhs[0]=c7front_matrix();return;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '        if(op==9){' sprintf('\n') ...
        '            if(nrhs!=1||nlhs>1)mexErrMsgIdAndTxt("AF7C7FRONT:Arity","diag op9: clear.");' sprintf('\n') ...
        '            G_c7front_mex.clear();G_c7front_seq=0;G_c7front_rows.clear();' sprintf('\n') ...
        '            if(nlhs>0)plhs[0]=logicalScalar(true);return;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        anchor];
    cppNew=replace_once(cppNew,anchor,block,'R6 diagnostic ops');

    % Compatibility invariants.
    assert(contains(cppNew, ...
        'static const char* PLANNER_REV="AF7_REPLANNER_MIN_DEVIATION_V4_FIXED_T1";'), ...
        '[C7FRONT-R6] Planner revision changed unexpectedly.');
    assert(contains(cppNew,'TOWING_NATURAL_TIME_C3'), ...
        '[C7FRONT-R6] Production R5 family changed unexpectedly.');
    assert(count_exact(hppNew,'AF7_C7_HOMOTOPY_FRONTIER_R6')>=1, ...
        '[C7FRONT-R6] Core marker missing.');
    assert(count_exact(cppNew,'AF7_C7_HOMOTOPY_FRONTIER_R6_RING')==1, ...
        '[C7FRONT-R6] Wrapper marker count wrong.');

    %% --------------------------------------------------------------------
    % 4) Stage compile before production write.
    % ---------------------------------------------------------------------
    stageDir=tempname;
    [ok,msg]=mkdir(stageDir);
    assert(ok,'[C7FRONT-R6] Cannot create staging directory: %s',msg);
    stageCleanup=onCleanup(@()cleanup_stage(stageDir)); %#ok<NASGU>

    stagedHpp=fullfile(stageDir,'af7r36_core.hpp');
    stagedCpp=fullfile(stageDir,'af7r36_single_core_mex.cpp');
    write_text(stagedHpp,hppNew);
    write_text(stagedCpp,cppNew);

    fprintf('[C7FRONT-R6] Compiling staged diagnostic MEX...\n');
    oldDir=pwd;
    cwdCleanup=onCleanup(@()cd(oldDir)); %#ok<NASGU>
    cd(stageDir);
    clear mex;
    mex('-R2018a','-O', ...
        'COMPFLAGS="$COMPFLAGS /std:c++17"', ...
        ['-I' stageDir], ...
        '-output','af7r36_single_core_mex', ...
        '-outdir',stageDir, ...
        stagedCpp);

    stagedMex=fullfile(stageDir,['af7r36_single_core_mex.' mexext]);
    assert(isfile(stagedMex),'[C7FRONT-R6] Staged MEX binary missing.');

    dstMex=fullfile(refDir,['af7r36_single_core_mex.' mexext]);
    oldMexTmp=fullfile(stageDir,['af7r36_single_core_mex_OLD.' mexext]);
    hadOldMex=isfile(dstMex);
    if hadOldMex
        [ok,msg]=copyfile(dstMex,oldMexTmp,'f');
        assert(ok,'[C7FRONT-R6] Cannot stage rollback MEX: %s',msg);
    end

    cd(oldDir);
    clear mex;

    wroteH=false;wroteC=false;installedMex=false;
    try
        write_text(hpp,hppNew);wroteH=true;
        write_text(cpp,cppNew);wroteC=true;
        [ok,msg]=copyfile(stagedMex,dstMex,'f');
        assert(ok,'[C7FRONT-R6] Cannot install staged MEX: %s',msg);
        installedMex=true;

        clear mex;rehash;
        assert(exist('af7r36_single_core_mex','file')==3, ...
            '[C7FRONT-R6] Installed MEX not visible.');
        try, af7r36_single_core_mex(7); catch, end
        af7r36_single_core_mex(9);

    catch ME2
        if wroteH, try, write_text(hpp,hpp0); catch, end, end
        if wroteC, try, write_text(cpp,cpp0); catch, end, end
        if installedMex && hadOldMex
            try, copyfile(oldMexTmp,dstMex,'f'); catch, end
        end
        clear mex;rehash;
        rethrow(ME2);
    end

    fprintf('[C7FRONT-R6] PASS.\n');
    fprintf('  production selection unchanged             = 1\n');
    fprintf('  production hard safety unchanged           = 1\n');
    fprintf('  diagnostic candidates structural C7        = 1\n');
    fprintf('  continuous XY-tangent lower-bound check    = 1\n');
    fprintf('  alpha diagnostic grid                       = k/16, k=0..16\n');
    fprintf('  README created                              = 0\n');
    fprintf('  persistent backup files created             = 0\n');
    fprintf('  NOTE: diagnostic runtime is NOT production timing.\n');

    OUT=struct();
    OUT.pass=true;
    OUT.reference_dir=refDir;
    OUT.revision='AF7_C7_HOMOTOPY_FRONTIER_R6';
    OUT.production_selection_modified=false;
    OUT.hard_safety_modified=false;
    OUT.translation_C7=true;
    OUT.heading_exact_yaw_prerequisite_diagnosed=true;
    OUT.alpha_resolution=1/16;
    OUT.readme_created=false;
    OUT.persistent_backup_created=false;

catch ME
    clear mex;rehash;
    fprintf(2,'[C7FRONT-R6] FAILED. No successful production install completed.\n');
    rethrow(ME);
end
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1, ...
    '[C7FRONT-R6] Anchor "%s" count=%d; expected exactly 1.',label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end

function n=count_exact(txt,pat)
n=numel(strfind(txt,pat));
end

function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));
s=strrep(s,sprintf('\r'),sprintf('\n'));
end

function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');
assert(f>=0,'[C7FRONT-R6] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end

function cleanup_stage(d)
if isfolder(d)
    try, rmdir(d,'s'); catch, end
end
end
