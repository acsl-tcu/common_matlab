function T=AF7R58R64_SELFTEST()
% Verify the source-bound real R44R2 correction's whole-control-polygon
% projected monotonicity + no increase beyond starting correction norm.
% This is a C7/shape QUALITY test, not obstacle or HLC safety certification.
root=fileparts(mfilename('fullpath'));
f=fullfile(root,'AF7R58R61_OUT.mat');
assert(exist(f,'file')==2,'R64:MissingRealSource', ...
    'Real R61 MAT supplied with this package is required.');
A=load(f,'R61');
P=double(A.R61.real_correction.candidate.control_points);
assert(isequal(size(P),[3,16]) && all(isfinite(P),'all'), ...
    'R64:InvalidCP','Actual degree-15 R61 control points invalid.');
a=P(:,1);n=norm(a);
assert(n>0,'R64:ZeroOffset','Test source has no starting offset');
lam=(a.'*P)/n^2;
rad=vecnorm(P,2,1);
tol=512*eps(max(1,n));
projectedPass=all(diff(lam)<=tol) && all(lam>=-tol) && ...
    all(lam<=1+tol);
noRadialExpansion=all(rad<=n+tol);
assert(projectedPass && noRadialExpansion, ...
    'R64:ActualRegression','Real R61 correction control polygon failed.');
% A deterministic adversarial zigzag is not allowed.
Pbad=P;
Pbad(:,8)=Pbad(:,7)+2*a;
lamBad=(a.'*Pbad)/n^2;
radBad=vecnorm(Pbad,2,1);
badPass=all(diff(lamBad)<=tol) && all(lamBad>=-tol) && ...
    all(lamBad<=1+tol) && all(radBad<=n+tol);
assert(~badPass,'R64:Regression','Overshooting correction was not rejected');
% R63 actual-world source inconsistency (different from R61 corrections)
% is an explicit fixture showing why valid=1 was unsafe to trust.
R63=load(fullfile(root,'AF7R58R63_OUT.mat'),'R63');
E=arrayfun(@(x)double(x.flat_active_jet_consistency_error), ...
    R63.R63.live_authorities);
assert(any(E>0.1),'R64:Evidence','Missing real repaired-source jet mismatch fixture');
T=struct('status','REAL_SOURCE_CONTROL_POLYGON_PASS__NOT_SAFETY_CERTIFIED', ...
    'actual_source_start_norm_m',n, ...
    'projection_min',min(lam),'projection_max',max(lam), ...
    'largest_projection_reverse_increment',max(diff(lam)), ...
    'largest_control_norm_m',max(rad), ...
    'projected_monotone',projectedPass, ...
    'no_radial_overshoot',noRadialExpansion, ...
    'overshoot_negative_control_rejected',~badPass, ...
    'r63_actual_jet_mismatch_max',max(E), ...
    'full_world_path_no_backtracking_proved',false, ...
    'physical_future_4s_proved',false, ...
    'wholebody_safety_proved',false, ...
    'commit_allowed',false);
T.mat_file=fullfile(root,'AF7R58R64_SELFTEST_OUT.mat');
T.report_file=fullfile(root,'AF7R58R64_SELFTEST_REPORT.txt');
save(T.mat_file,'T','-v7');
fid=fopen(T.report_file,'wt');
assert(fid>0,'R64:Save','Cannot write test report');
c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'R64 ACTUAL R61 C7 CONTROL-POLYGON QUALITY REGRESSION\n');
fprintf(fid,'status=%s\n',T.status);
fprintf(fid,'initial_offset_m=%.17g\n',n);
fprintf(fid,'projected_monotone=%d radial_nonexpansion=%d negative_rejected=%d\n', ...
    projectedPass,noRadialExpansion,~badPass);
fprintf(fid,'R63_measured_flat_jet_mismatch_max=%.17g\n',max(E));
fprintf(fid,'C7 candidate quality ONLY. Full world trajectory/obstacle/HLC certification NOT proved.\n');
end
