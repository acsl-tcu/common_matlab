function R=AF7R58R123_FROZEN_PHYSICAL_TRIGGER(C)
% Fully bound, real HLC+plant replay + independent 4-s EKF trigger.
% Deliberately returns UNKNOWN unless validated interval enclosure exists.
E=AF7R58R123_EVENT_OBSTACLES(C);
assert(isequal(size(C.state_x24),[24 1])&& ...
       isfinite(C.estimated_mass_kg)&&C.estimated_mass_kg>0, ...
       'R123:EKF24AndEstimatedMassRequired');
R=struct('status','NOT_RUN','event',E,'trigger',struct([]), ...
    'prediction',struct([]),'sampled_risk_witness',false, ...
    'physical_clearance_certified',false, ...
    'source_exact_same_event',true,'old_reference_trigger_used',false, ...
    'production_commit_authorized',false);
if isempty(E.obstacles)
    R.status='NO_KNOWN_OBSTACLES__NOT_GLOBAL_CLEAR';
    return;
end
P=AF7R58R74_FROZEN_EVENT_PREVIEW(C);
A=struct('event_time_s',E.event_time_s, ...
    'reference_version',E.reference_version, ...
    'EKF_x24',double(C.state_x24(:)), ...
    'EKF_mL',double(C.estimated_mass_kg), ...
    'horizon_s',E.horizon_s,'dt_s',E.dt_s, ...
    'known_obstacles',E.obstacles,'radii_m',E.radii_m);
T=AF7R58R120_BIND_R71_TRIGGER(A,P);
R.prediction=struct('status',P.status, ...
    'time_grid_count',numel(P.t), ...
    'max_cable_closure_residual_m',P.max_cable_closure_residual_m, ...
    'saturated_sample_count',P.saturated_sample_count);
R.trigger=T;R.status=char(T.status);
R.sampled_risk_witness=logical(T.sampled_risk_witness);
R.physical_clearance_certified=logical(T.proved_clear);
end
