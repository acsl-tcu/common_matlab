function OUT = AF7R36_TOWING_C7_SPEED_OPT_SPLIT_R17_INSTALL()
% AF7R36_TOWING_C7_SPEED_OPT_SPLIT_R17_INSTALL
%
% New towing-specific fallback candidate family:
%
%   TOWING_C7_SPEED_OPT_SPLIT
%
% Foundation:
%   R16 already solves the constant-offset corridor problem
%
%       min 1/2 ||a_j||^2
%       s.t. exact existing corridor halfspaces
%
%   independently per unsafe component, with zero correction velocity on the
%   unsafe spans.  R17 keeps those minimum-norm offsets and changes ONLY the
%   safe transition shape.
%
% Transition A -> B over duration T:
%   - two degree-15 Bezier pieces, each of duration T/2;
%   - outer endpoint derivatives 1...7 are zero;
%   - shared midpoint jets:
%
%         m0 = (A+B)/2
%         m1 = alpha (B-A)/T
%         m2 = ... = m7 = 0
%
%   so both pieces meet with identical jets 0...7: structural C7.
%
% For alpha in [15/8, 2], the scalar Bezier control coordinates remain in
% [0,1], so every transition lies in the line segment conv{A,B}; therefore
% the correction envelope cannot balloon beyond its endpoint offsets.
%
% Exact Bernstein derivative-control bounds on the whole transition are:
%
%   Uv = alpha * ||B-A|| / T
%   Ua = 28 (15-7 alpha) * ||B-A|| / T^2
%   Uj = 728(15-7 alpha) * ||B-A|| / T^3
%
% throughout alpha in [15/8,2].
%
% Let
%   A1=max ||Delta||/T, B2=max ||Delta||/T^2, C3=max ||Delta||/T^3.
% The same finite-sensing Stage-A sufficient expression is
%
%   F(alpha)=base.VL + alpha*A1
%       + L*(base.J + 728*h*C3)/(base.sigma - 28*h*B2),
%   h=15-7*alpha.
%
% Its stationary point has
%
%   base.sigma - 28*B2*h
%       = sqrt( 7*L*(728*C3*base.sigma + 28*B2*base.J)/A1 ).
%
% R17 uses the clamped analytic minimizer, plus the two theorem endpoints
% alpha=15/8 and alpha=2 as deterministic certified alternatives.
%
% IMPORTANT:
%   These formulas are SYNTHESIS only. Acceptance is still exclusively the
%   unchanged:
%       Stage-A/B finite-sensing speed
%       -> continuous rejoin
%       -> continuous whole-body
%   hard certificate stack.
%
% Historical minimum-snap remains behind R17 for this validation step only.
% If R17 closes the live hard case, the next revision removes minimum-snap
% from the production hierarchy.
%
% No README. No persistent backup.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 TOWING C7 SPEED-OPT SPLIT R17 INSTALL\n');
fprintf(' new family                                 = TOWING_C7_SPEED_OPT_SPLIT\n');
fprintf(' unsafe-span correction derivatives        = exactly zero\n');
fprintf(' transition continuity                     = structural C7 (jets 0..7)\n');
fprintf(' transition geometric overshoot            = prohibited by convex-segment construction\n');
fprintf(' alpha selection                            = analytic finite-sensing Stage-A bound minimizer\n');
fprintf(' arbitrary trajectory weights              = 0\n');
fprintf(' hard safety gates modified                 = 0\n');
fprintf(' historical minimum-snap removed now        = 0 (validation guard only)\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir)&&isfolder(refDir), ...
    '[R17] Cannot resolve current reference directory.');

hpp=fullfile(refDir,'af7r36_core.hpp');
cpp=fullfile(refDir,'af7r36_single_core_mex.cpp');
assert(isfile(hpp),'[R17] Missing %s',hpp);
assert(isfile(cpp),'[R17] Missing %s',cpp);

hpp0=normlf(fileread(hpp));
cpp0=normlf(fileread(cpp));
hppNew=hpp0;
cppNew=cpp0;

assert(contains(hpp0,'AF7_TOWING_MINNORM_CONSTANT_R16'), ...
    '[R17] R16 minimum-norm constant fallback is not installed.');
assert(contains(hpp0,'AF7_R7_FAILCLOSED_FALLTHROUGH_R15B'), ...
    '[R17] R15B R7 fail-closed transport is not installed.');
assert(contains(hpp0, ...
    'Candidate C=build_candidate(E.comp,t0,t1,z,totalCost,sg,minSlack,4);'), ...
    '[R17] R16 candidate construction anchor missing.');
assert(~contains(hpp0,'AF7_TOWING_C7_SPEED_OPT_SPLIT_R17'), ...
    '[R17] R17 already installed.');
assert(~contains(cpp0,'TOWING_C7_SPEED_OPT_SPLIT'), ...
    '[R17] R17 serializer already installed.');

try
    %% --------------------------------------------------------------------
    % 1) Add split-transition helpers before Stage A.
    % ---------------------------------------------------------------------
    anchor='// ---------------------------- Stage A ---------------------------------------';
    helper=[ ...
        '// ---------------------------------------------------------------------------' sprintf('\n') ...
        '// AF7_TOWING_C7_SPEED_OPT_SPLIT_R17' sprintf('\n') ...
        '// ---------------------------------------------------------------------------' sprintf('\n') ...
        'static inline void r17_append_split_transition(Candidate&C,Vec3 p0,Vec3 p1,' sprintf('\n') ...
        '                                               double ta,double tb,double alpha){' sprintf('\n') ...
        '    const double T=tb-ta;' sprintf('\n') ...
        '    if(!(fin(T)&&T>0&&fin(alpha)&&alpha>=15.0/8.0&&alpha<=2.0))' sprintf('\n') ...
        '        throw std::runtime_error("R17 invalid split transition");' sprintf('\n') ...
        '    const double tm=0.5*(ta+tb);' sprintf('\n') ...
        '    if(!(tm>ta&&tm<tb))throw std::runtime_error("R17 split midpoint unrepresentable");' sprintf('\n') ...
        '    std::array<Vec3,8> ja{},jm{},jb{};' sprintf('\n') ...
        '    ja[0]=p0;' sprintf('\n') ...
        '    jm[0]=(p0+p1)*0.5;' sprintf('\n') ...
        '    jm[1]=(p1-p0)*(alpha/T);' sprintf('\n') ...
        '    jb[0]=p1;' sprintf('\n') ...
        '    C.seg0.push_back(ta);C.seg1.push_back(tm);' sprintf('\n') ...
        '    C.cp.push_back(vector_control_from_jets(ja,jm,tm-ta));' sprintf('\n') ...
        '    C.seg0.push_back(tm);C.seg1.push_back(tb);' sprintf('\n') ...
        '    C.cp.push_back(vector_control_from_jets(jm,jb,tb-tm));' sprintf('\n') ...
        '}' sprintf('\n') ...
        '' sprintf('\n') ...
        'static inline void r17_finalize_candidate_bounds(Candidate&C){' sprintf('\n') ...
        '    C.dub.fill(0);C.max_ctrl=0;' sprintf('\n') ...
        '    for(size_t s=0;s<C.cp.size();++s){' sprintf('\n') ...
        '        const double T=C.seg1[s]-C.seg0[s];' sprintf('\n') ...
        '        if(!(fin(T)&&T>0))throw std::runtime_error("R17 nonpositive segment time");' sprintf('\n') ...
        '        Poly D=C.cp[s];int deg=15;' sprintf('\n') ...
        '        for(auto v:D)C.max_ctrl=std::max(C.max_ctrl,norm(v));' sprintf('\n') ...
        '        for(int r=1;r<=6;++r){' sprintf('\n') ...
        '            Poly E(D.size()-1);' sprintf('\n') ...
        '            for(size_t i=0;i+1<D.size();++i)' sprintf('\n') ...
        '                E[i]=(D[i+1]-D[i])*(double(deg)/T);' sprintf('\n') ...
        '            D.swap(E);--deg;' sprintf('\n') ...
        '            C.dub[r-1]=std::max(C.dub[r-1],poly_norm_ub(D));' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '}' sprintf('\n') ...
        '' sprintf('\n') ...
        'static inline Candidate r17_build_split_constant(const std::vector<Component>&comp,' sprintf('\n') ...
        '        double t0,double t1,const std::vector<double>&z,double cost,' sprintf('\n') ...
        '        const std::vector<int>&signs,double minSlack,double alpha){' sprintf('\n') ...
        '    Candidate C;C.cost=cost;C.signs=signs;C.minSlack=minSlack;' sprintf('\n') ...
        '    C.family=5;C.constant_translation=true;' sprintf('\n') ...
        '    const int nc=(int)comp.size(),nslot=2*nc;' sprintf('\n') ...
        '    if((int)z.size()!=3*nslot||nc<1)throw std::runtime_error("R17 candidate z size");' sprintf('\n') ...
        '    C.pos.resize(nc);C.vel.assign(nc,Vec3{});' sprintf('\n') ...
        '    for(int j=0;j<nc;++j){' sprintf('\n') ...
        '        C.pos[j]={z[3*(2*j)],z[3*(2*j)+1],z[3*(2*j)+2]};' sprintf('\n') ...
        '        const Vec3 vz{z[3*(2*j+1)],z[3*(2*j+1)+1],z[3*(2*j+1)+2]};' sprintf('\n') ...
        '        const double tv=4096*epsd()*std::max(1.0,norm(C.pos[j]));' sprintf('\n') ...
        '        if(norm(vz)>tv)throw std::runtime_error("R17 requires zero unsafe-span velocity");' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '    r17_append_split_transition(C,Vec3{},C.pos[0],t0,comp[0].start,alpha);' sprintf('\n') ...
        '    for(int j=0;j<nc;++j){' sprintf('\n') ...
        '        Poly p(16,C.pos[j]);' sprintf('\n') ...
        '        C.seg0.push_back(comp[j].start);C.seg1.push_back(comp[j].end);' sprintf('\n') ...
        '        C.cp.push_back(std::move(p));' sprintf('\n') ...
        '        if(j<nc-1)' sprintf('\n') ...
        '            r17_append_split_transition(C,C.pos[j],C.pos[j+1],' sprintf('\n') ...
        '                                        comp[j].end,comp[j+1].start,alpha);' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '    r17_append_split_transition(C,C.pos.back(),Vec3{},comp.back().end,t1,alpha);' sprintf('\n') ...
        '    r17_finalize_candidate_bounds(C);' sprintf('\n') ...
        '    return C;' sprintf('\n') ...
        '}' sprintf('\n') ...
        '' sprintf('\n') ...
        'static inline double r17_speed_opt_alpha(const std::vector<Component>&comp,' sprintf('\n') ...
        '        double t0,double t1,const std::vector<Vec3>&p,const SpeedCert&base,const Live&L){' sprintf('\n') ...
        '    double A1=0,B2=0,C3=0;' sprintf('\n') ...
        '    auto add=[&](Vec3 d,double T){' sprintf('\n') ...
        '        if(!(fin(T)&&T>0))throw std::runtime_error("R17 invalid transition duration");' sprintf('\n') ...
        '        const double D=norm(d);' sprintf('\n') ...
        '        A1=std::max(A1,D/T);' sprintf('\n') ...
        '        B2=std::max(B2,D/(T*T));' sprintf('\n') ...
        '        C3=std::max(C3,D/(T*T*T));' sprintf('\n') ...
        '    };' sprintf('\n') ...
        '    add(p[0],comp[0].start-t0);' sprintf('\n') ...
        '    for(size_t j=0;j+1<p.size();++j)' sprintf('\n') ...
        '        add(p[j+1]-p[j],comp[j+1].start-comp[j].end);' sprintf('\n') ...
        '    add(p.back()*(-1.0),t1-comp.back().end);' sprintf('\n') ...
        '    if(!(fin(A1)&&fin(B2)&&fin(C3))||A1<=0||B2<=0)return 2.0;' sprintf('\n') ...
        '    const double rad=7.0*L.L*(728.0*C3*base.sigma+28.0*B2*base.J)/A1;' sprintf('\n') ...
        '    if(!(fin(rad)&&rad>=0))return 2.0;' sprintf('\n') ...
        '    const double target=std::sqrt(rad);' sprintf('\n') ...
        '    double h=(base.sigma-target)/(28.0*B2);' sprintf('\n') ...
        '    h=std::max(1.0,std::min(15.0/8.0,h));' sprintf('\n') ...
        '    double alpha=(15.0-h)/7.0;' sprintf('\n') ...
        '    alpha=std::max(15.0/8.0,std::min(2.0,alpha));' sprintf('\n') ...
        '    return alpha;' sprintf('\n') ...
        '}' sprintf('\n') ...
        '' sprintf('\n') ...
        anchor];

    hppNew=replace_once(hppNew,anchor,helper,'Stage-A helper insertion');

    %% --------------------------------------------------------------------
    % 2) Extend R16 per-side candidate generation.
    %    Speed-opt split is inserted BEFORE the original single-transition
    %    constant family; historical minimum-snap remains later.
    % ---------------------------------------------------------------------
    old=[ ...
        '            Candidate C=build_candidate(E.comp,t0,t1,z,totalCost,sg,minSlack,4);' sprintf('\n') ...
        '            C.constant_translation=true;' sprintf('\n') ...
        '            calm.push_back(std::move(C));'];

    new=[ ...
        '            Candidate C=build_candidate(E.comp,t0,t1,z,totalCost,sg,minSlack,4);' sprintf('\n') ...
        '            C.constant_translation=true;' sprintf('\n') ...
        '            const double aopt=r17_speed_opt_alpha(E.comp,t0,t1,C.pos,base,L);' sprintf('\n') ...
        '            auto pushR17=[&](double av){' sprintf('\n') ...
        '                Candidate S=r17_build_split_constant(E.comp,t0,t1,z,totalCost,sg,minSlack,av);' sprintf('\n') ...
        '                calm.push_back(std::move(S));' sprintf('\n') ...
        '            };' sprintf('\n') ...
        '            pushR17(aopt);' sprintf('\n') ...
        '            if(std::fabs(aopt-15.0/8.0)>128*epsd())pushR17(15.0/8.0);' sprintf('\n') ...
        '            if(std::fabs(aopt-2.0)>128*epsd())pushR17(2.0);' sprintf('\n') ...
        '            calm.push_back(std::move(C));'];

    hppNew=replace_once(hppNew,old,new,'R16 candidate expansion');

    %% --------------------------------------------------------------------
    % 3) Serializer family 5 + constant-span flag.
    % ---------------------------------------------------------------------
    anchor='    if(R.cand.family==4)family="TOWING_C7_MIN_NORM_CONSTANT";';
    repl=[anchor sprintf('\n') ...
        '    if(R.cand.family==5)family="TOWING_C7_SPEED_OPT_SPLIT";'];
    cppNew=replace_once(cppNew,anchor,repl,'family-5 serializer');

    old='    set("compact_constant_translation",logicalScalar(R.cand.family==4));';
    if contains(cppNew,old)
        cppNew=replace_once(cppNew,old, ...
            '    set("compact_constant_translation",logicalScalar(R.cand.family==4||R.cand.family==5));', ...
            'constant-span serializer flag');
    end

    %% --------------------------------------------------------------------
    % 4) Static source audits.
    % ---------------------------------------------------------------------
    assert(count_exact(hppNew,'AF7_TOWING_C7_SPEED_OPT_SPLIT_R17')==1, ...
        '[R17] R17 marker count invalid.');
    assert(count_exact(hppNew,'C.family=5;C.constant_translation=true;')==1, ...
        '[R17] R17 family semantic marker missing.');
    assert(count_exact(hppNew,'const double aopt=r17_speed_opt_alpha')==1, ...
        '[R17] Analytic alpha selection missing.');
    assert(count_exact(hppNew,'pushR17(15.0/8.0);')==1 && ...
           count_exact(hppNew,'pushR17(2.0);')==1, ...
        '[R17] Theorem endpoint alternatives missing.');
    assert(count_exact(cppNew,'TOWING_C7_SPEED_OPT_SPLIT')==1, ...
        '[R17] Family serializer count invalid.');

    % R16 and historical fallback are still present for validation only.
    assert(contains(hppNew,'AF7_TOWING_MINNORM_CONSTANT_R16'), ...
        '[R17] R16 base corridor fallback disappeared.');
    assert(contains(hppNew,'minimum_snap_hessian(E.comp,t0,t1)'), ...
        '[R17] Historical validation guard unexpectedly disappeared.');

    % Unchanged hard acceptance authority.
    assert(contains(hppNew,'tighten_stageA'), ...
        '[R17] Stage-A finite-sensing certificate disappeared.');
    assert(contains(hppNew,'stageB_speed'), ...
        '[R17] Stage-B finite-sensing certificate disappeared.');
    assert(contains(hppNew,'rejoin_safe'), ...
        '[R17] Rejoin hard gate disappeared.');
    assert(contains(hppNew,'wholebody'), ...
        '[R17] Continuous whole-body gate disappeared.');

    %% --------------------------------------------------------------------
    % 5) Stage compile before production install.
    % ---------------------------------------------------------------------
    stageDir=tempname;
    [ok,msg]=mkdir(stageDir);
    assert(ok,'[R17] Cannot create staging directory: %s',msg);
    stageCleanup=onCleanup(@()cleanup_stage(stageDir)); %#ok<NASGU>

    stagedHpp=fullfile(stageDir,'af7r36_core.hpp');
    stagedCpp=fullfile(stageDir,'af7r36_single_core_mex.cpp');
    write_text(stagedHpp,hppNew);
    write_text(stagedCpp,cppNew);

    fprintf('[R17] Compiling staged MEX...\n');
    oldDir=pwd;
    cwdCleanup=onCleanup(@()cd(oldDir)); %#ok<NASGU>
    cd(stageDir);
    clear mex
    mex('-R2018a','-O', ...
        'COMPFLAGS="$COMPFLAGS /std:c++17"', ...
        ['-I' stageDir], ...
        '-output','af7r36_single_core_mex', ...
        '-outdir',stageDir, ...
        stagedCpp);

    stagedMex=fullfile(stageDir,['af7r36_single_core_mex.' mexext]);
    assert(isfile(stagedMex),'[R17] Staged MEX missing.');

    %% --------------------------------------------------------------------
    % 6) Install with temporary rollback only. No clear classes here.
    % ---------------------------------------------------------------------
    dstMex=fullfile(refDir,['af7r36_single_core_mex.' mexext]);
    oldMexTmp=fullfile(stageDir,['af7r36_single_core_mex_OLD.' mexext]);
    hadOldMex=isfile(dstMex);
    if hadOldMex
        [ok,msg]=copyfile(dstMex,oldMexTmp,'f');
        assert(ok,'[R17] Cannot prepare temporary MEX rollback: %s',msg);
    end

    cd(oldDir);
    clear mex
    wroteH=false;wroteC=false;installedMex=false;
    try
        write_text(hpp,hppNew);wroteH=true;
        write_text(cpp,cppNew);wroteC=true;
        [ok,msg]=copyfile(stagedMex,dstMex,'f');
        assert(ok,'[R17] Cannot install staged MEX: %s',msg);
        installedMex=true;
        clear mex
        rehash

        assert(exist('af7r36_single_core_mex','file')==3, ...
            '[R17] Installed MEX not visible.');
        assert(contains(normlf(fileread(hpp)),'AF7_TOWING_C7_SPEED_OPT_SPLIT_R17'), ...
            '[R17] Installed core marker not visible.');
    catch ME2
        if wroteH,try,write_text(hpp,hpp0);catch,end,end
        if wroteC,try,write_text(cpp,cpp0);catch,end,end
        if installedMex && hadOldMex
            try,copyfile(oldMexTmp,dstMex,'f');catch,end
        end
        clear mex
        rehash
        rethrow(ME2);
    end

    fprintf('[R17] PASS.\n');
    fprintf('  speed-opt split C7 family installed        = 1\n');
    fprintf('  unsafe-span correction derivative          = 0 exactly\n');
    fprintf('  transition endpoint-segment overshoot      = 0 by construction\n');
    fprintf('  hard certificate stack weakened            = 0\n');
    fprintf('  legacy minimum-snap retained only for validation = 1\n');
    fprintf('  IMPORTANT: clear old objects/classes before next simulation.\n');

    OUT=struct( ...
        'pass',true, ...
        'revision','AF7_TOWING_C7_SPEED_OPT_SPLIT_R17', ...
        'new_family','TOWING_C7_SPEED_OPT_SPLIT', ...
        'hard_safety_modified',false, ...
        'C7_modified',false, ...
        'legacy_validation_guard_present',true);

catch ME
    clear mex
    rehash
    fprintf(2,'[R17] FAILED. No successful production install completed.\n');
    fprintf(2,'[R17] ORIGINAL ERROR: %s | %s\n',ME.identifier,ME.message);
    rethrow(ME);
end
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1,'[R17] Anchor "%s" count=%d; expected 1.',label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end

function n=count_exact(txt,pat)
n=numel(strfind(txt,pat));
end

function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));
s=strrep(s,sprintf('\r'),sprintf('\n'));
end

function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');
assert(f>=0,'[R17] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end

function cleanup_stage(d)
if isfolder(d)
    try,rmdir(d,'s');catch,end
end
end
