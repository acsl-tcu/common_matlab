function T=AF7R58R81_SELFTEST()
% R81 regression: live-only inputs, adaptive duration without a time cap;
% separate-body corridor; endpoint C7; independent no-commit gate.
L=2;g=9.81;v=0.7;t0=0;
J=zeros(3,8);J(2,2)=v;
live=struct('gravity_m_s2',g,'cable_length_m',L, ...
    'rQ_m',0.15,'rC_m',0.05,'rL_m',0.15, ...
    'finite_sensing_vQ_limit_m_s',3.10559006211, ...
    'latest_EKF_mL_kg',0.015);
opts=struct('max_attempts',24,'max_nodes_per_check',512, ...
    'minimum_schedule_delay_s',0.2);
o=struct('center',[5;0;1],'R',eye(3),'axes',[0.2;0.2;0.2]);
R=AF7R58R81_ADAPTIVE_DELAYED_RETURN(t0,J, ...
    @(s)r81_linear_nominal(s,v),o,live,opts);
assert(R.reference_candidate_found&&R.continuous_time_reference_certified, ...
    '[R81] synthetic straight reference must admit a connector.');
assert(R.phase_delay_s>=opts.minimum_schedule_delay_s && R.phase_delay_s>0, ...
    '[R81] delayed nominal phase must be used, not same-clock forced.');
assert(~R.production_commit_authorized&&~R.input_torque_tension_certified&& ...
    ~R.tracking_observer_tube_certified&&~R.whole_future_certified, ...
    '[R81] reference-level tests must never authorize production.');
C=R.candidate;
P0=zeros(3,8);P1=zeros(3,8);
for r=0:7
    P0(:,r+1)=AF7R58R79_C7_EVAL(C,C.t0,r);
    P1(:,r+1)=AF7R58R79_C7_EVAL(C,C.t1,r);
end
J1=r81_linear_nominal(C.t1-R.phase_delay_s,v);
% Raw high derivatives of degree-15 polynomials amplify IEEE-754 noise.
% Each jet gets a scale-consistent roundoff bound, not a fixed tolerance.
tol=zeros(1,8);
cpScale=max(1,max(abs(C.payload_cp(:))));
for r=0:7
    falling=prod(15:-1:(16-r));
    tol(r+1)=1024*eps(cpScale)*falling/C.duration_s^r;
end
startDiff=max(abs(P0-J),[],1);endDiff=max(abs(P1-J1),[],1);
assert(all(startDiff<=tol),'[R81] start C7 endpoint jets');
assert(all(endDiff<=tol),'[R81] delayed end C7 endpoint jets');
% Force the finite work budget to end rather than pretending a safe plan.
unsafe=o;unsafe.center=[0;0;1];unsafe.axes=[0.5;0.5;0.5];
opts.max_attempts=1;opts.max_nodes_per_check=32;
F=AF7R58R81_ADAPTIVE_DELAYED_RETURN(t0,J, ...
    @(s)r81_linear_nominal(s,v),unsafe,live,opts);
assert(~F.reference_candidate_found&&~F.production_commit_authorized, ...
    '[R81] collision or lack of proof must never produce a candidate');
T=struct('status','PASS_R81_ADAPTIVE_C7_RETURN_REFERENCE_ONLY', ...
    'candidate_found',R.reference_candidate_found, ...
    'connector_duration_s',R.t1_s-R.t0_s, ...
    'delay_s',R.phase_delay_s, ...
    'endpoint07_max_error',max([startDiff,endDiff]), ...
    'endpoint07_max_normalized_error',max([startDiff./tol,endDiff./tol]), ...
    'geometry_certified',R.assessment.geometry.certified, ...
    'tangent_yaw_certified',R.assessment.heading.certified, ...
    'reference_kinematic_certified',R.assessment.kinematics.certified, ...
    'unsafe_case_rejected',~F.reference_candidate_found, ...
    'actuator_tension_proved',false, ...
    'nominal_tail_proved',false,'production_committed',false);
end
function J=r81_linear_nominal(s,v)
J=zeros(3,8);J(2,1)=v*s;J(2,2)=v;
end
