function O=AF7R58R117_SELFTEST()
% Run from the directory containing the R117 engine and four bundled R92/R80/R91 helpers.
% No production code is modified. No external Flight model is faked.
obs=struct('id',7,'center',[70;30;20],'R',eye(3),'axes',[3;1;2]);
A=struct('event_time_s',5,'reference_version',4, ...
    'EKF_x24',zeros(24,1),'EKF_mL',0.14, ...
    'horizon_s',4,'dt_s',0.025,'known_obstacles',obs, ...
    'radii_m',[0.2;0.03;0.2]);
A.EKF_x24(1:3)=[0;0;2];A.EKF_x24(13:15)=[0;0;0];
N=161;P=struct('source','LIVE_EKF_HLC_PLANT_ROLLOUT', ...
 'time_s',5,'reference_version',4,'EKF_mL',0.14, ...
 't_s',5+(0:160)*0.025,'pQ',repmat([0;0;2],1,N), ...
 'pL',repmat([0;0;0],1,N), ...
 'interval_speed_upper_m_s',zeros(2,N-1), ...
 'bound_certificate',struct('certified',true,'event_time_s',5, ...
 'reference_version',4,'method','EXACT_CONSTANT_TRAJECTORY_TEST_ONLY'));
A.rollout=P;
T=AF7R58R117_DUAL_REPLACEMENT('trigger',A);
assert(T.proved_safe && ~T.request && T.checked_interval_count==160, ...
 'R117SelfTest:FarObstacle','Far oriented ellipsoid must be certified clear.');
A.known_obstacles=struct('id',19,'center',[0;0;1], ...
 'R',eye(3),'axes',[0.4;0.3;0.3]);
T2=AF7R58R117_DUAL_REPLACEMENT('trigger',A);
assert(T2.request&&T2.obstacle_id==19&&strcmp(T2.body,'CABLE'), ...
 'R117SelfTest:CableHit','Cable intersection must not be ignored.');
A.rollout=rmfield(P,{'interval_speed_upper_m_s','bound_certificate'});
T3=AF7R58R117_DUAL_REPLACEMENT('trigger',A);
assert(~T3.proved_safe && ~T3.request && T3.unknown && ...
  ~T3.old_reference_trigger_used, ...
 'R117SelfTest:MissingProof','Missing continuous proof must NOT fall back.');
D=AF7R58R117_DUAL_REPLACEMENT('decide',struct( ...
 'physical_trigger',T,'active_plan_certificate', ...
 struct('still_feasible',true),'same_reference_version',true));
assert(D.keep_active && ~D.replan, 'R117SelfTest:DuplicateReplan');
D2=AF7R58R117_DUAL_REPLACEMENT('decide',struct( ...
 'physical_trigger',T2,'active_plan_certificate', ...
 struct('still_feasible',true),'same_reference_version',true));
assert(D2.replan, 'R117SelfTest:LegitimateSameObstacleReplan');
% Reference planner smoke test uses the actual R92/R80/R91 sources.
J=zeros(3,8);J(1,2)=1;
B=struct('time_s',0,'start_jets07',J, ...
 'nominal_jets07_fn',@nominal_jets, ...
 'known_obstacles',obs,'live', ...
 struct('cable_length_m',2,'gravity_m_s2',9.81, ...
 'latest_EKF_mL_kg',0.14,'vehicle_mass_kg',0.762, ...
 'thrust_bounds_N',[0,20], ...
 'torque_bounds_Nm',[-1,1;-1,1;-1,1]), ...
 'search_work_limit',3,'branch_work_limit',8, ...
 'certificate_work_limit',256,'duration_scale_s',2, ...
 'radii_m',[0.2;0.03;0.2],'max_uav_speed_m_s',3);
R=AF7R58R117_DUAL_REPLACEMENT('plan',B);
assert(R.continuity_order==7&&R.yaw_order==6&& ...
 ~R.production_commit_authorized && ~R.execution_certified, ...
 'R117SelfTest:PlannerAuthority','Reference plan must not claim full authority.');
O=struct('status','PASS_TRIGGER_ENCLOSURE_ARBITRATION_AND_PLANNER_AUTHORITY', ...
 'far_clear',T,'cable_unsafe',T2,'missing_bounds',T3, ...
 'duplicate_guard',D,'replan_guard',D2, ...
 'planner_status',R.status,'planner_found',R.found);
fprintf('[R117] %s\n',O.status);
fprintf('[R117] reference planner: %s\n',R.status);
end
function J=nominal_jets(t)
J=zeros(3,8);J(1,1)=t;J(1,2)=1;
end
