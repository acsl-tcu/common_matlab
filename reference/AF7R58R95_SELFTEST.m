function T=AF7R58R95_SELFTEST()
% Synthetic fixtures only; no MATLAB Flight, HLC or IEEE proof.
req={'AF7R58R95_C7_KNOT_SPEED_ROUTE', ...
    'AF7R58R95_KNOT_DISPLACEMENT_SCREEN', ...
    'AF7R58R95_CORRIDOR_PREFLIGHT', ...
    'AF7R58R95_RUN_SAVED_ROUTE', ...
    'AF7R58R95_ADAPTIVE_SAVED_SEARCH', ...
    'AF7R58R94_CERTIFY_ALL_SEGMENTS', ...
    'AF7R58R92_C7_MINIMUM8_ROUTE'};
root=fileparts(mfilename('fullpath'));
for k=1:numel(req)
    f=which(req{k});
    assert(~isempty(f)&&strcmp(fileparts(f),root), ...
        'R95:SourceShadowOrMissing', ...
        'Expected %s in the active reference directory; resolved %s', ...
        req{k},f);
end
w=[0 1.5 3;0 0 0;-2 -2 -2]; times=[0 1.5 3];
J0=zeros(3,8);J1=zeros(3,8);
J0(:,1)=w(:,1);J1(:,1)=w(:,end);
J0(1,2)=1;J1(1,2)=1;
R=AF7R58R95_C7_KNOT_SPEED_ROUTE( ...
    times,w,J0,J1,0.25,2,9.81,3.1);
assert(R.reference_candidate_found&&R.knot_speed_necessary_pass&& ...
    R.num_segments==2&&R.max_jet_residual<1e-7&& ...
    ~R.production_commit_authorized, ...
    'R95:SyntheticStraightC7KnotRegression', ...
    'Two-section synthetic straight C7 trajectory failed.');
S=AF7R58R95_KNOT_DISPLACEMENT_SCREEN(R,9.81,2,3.1);
assert(S.necessary_speed_pass && ~S.production_commit_authorized, ...
    'R95:KnotTravelRegression','Straight slow knot travel must pass.');
U=R;U.knot_jets(:,1,2)=[200;0;-2];
F=AF7R58R95_KNOT_DISPLACEMENT_SCREEN(U,9.81,2,3.1);
assert(~F.necessary_speed_pass && ...
    strcmp(F.status,'NECESSARY_UAV_KNOT_TRAVEL_TIME_VIOLATED'), ...
    'R95:KnotTravelNecessaryViolationNotDetected', ...
    'Impossible mid-knot displacement must fail.');
% An arbitrarily large rotated ellipsoid is not filtered by size.
angle=0.35; rot=[cos(angle) -sin(angle) 0; ...
    sin(angle) cos(angle) 0;0 0 1];
O=struct('center',[0;0;-2],'R',rot, ...
    'axes',[120;60;15]);
far=AF7R58R95_CORRIDOR_PREFLIGHT( ...
    [-400 -200;300 300;-2 -2],O,0.3);
assert(far.feasible_corridor_family&& ...
    far.known_obstacles_checked==1, ...
    'R95:LargeEllipsoidIncorrectlyRejected', ...
    'A distant waypoint edge must support the large ellipsoid case.');
inside=AF7R58R95_CORRIDOR_PREFLIGHT( ...
    [-10 10;0 0;-2 -2],O,0.3);
assert(~inside.feasible_corridor_family&& ...
    ~inside.production_commit_authorized, ...
    'R95:ObviousIntersectingSeedAccepted', ...
    'Crossing a known large ellipsoid must not be admitted as a corridor family.');
T=struct('status','PASS_R95_CORRIDOR_FIRST_C7_KNOT_PREFLIGHT', ...
    'synthetic_c7_sections',R.num_segments, ...
    'synthetic_all_07_jets_residual',R.max_jet_residual, ...
    'speed_aware_knot_test_passed',R.knot_speed_necessary_pass, ...
    'necessary_displacement_rejected',~F.necessary_speed_pass, ...
    'large_rotated_ellipsoid_retained',far.known_obstacles_checked, ...
    'obvious_large_ellipsoid_crossing_rejected', ...
      ~inside.feasible_corridor_family, ...
    'real_snapshot_exercised',false, ...
    'flight_generator_changed',false,'trigger_changed',false, ...
    'whole_closed_loop_safety_proved',false, ...
    'production_commit_authorized',false);
end
