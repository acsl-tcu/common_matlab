function OUT = AF7R25_INSTALL_HIGHRES_TIMING()
% AF7R25_INSTALL_HIGHRES_TIMING
% =========================================================================
% Diagnostic-only high-resolution timing instrumentation for R9/R23/R24.
%
% QPC wall times:
%   callback, episode, synthesis, QP enumeration
%
% Work counters:
%   current MATLAB thread cycles, whole MATLAB process cycles
%
% Every real generator request resets all R25 fields to NaN and binds them
% to generator_request_count, preventing stale values from later attempts.
%
% Acceptance, trajectory, safety certificate, solver, and 4-ms gate are
% NOT changed by this diagnostic patch.
% =========================================================================

clc;
fprintf('\n');
fprintf('====================================================================================================\n');
fprintf(' AF7R25 | INSTALL HIGH-RESOLUTION R9 TIMING\n');
fprintf('====================================================================================================\n');

src=which('REPLANNING_SYSTEM');
assert(~isempty(src)&&isfile(src),'[AF7R25] REPLANNING_SYSTEM.m not found.');
assert(~isempty(which('af7r25_stamp_mex')), ...
    '[AF7R25] af7r25_stamp_mex missing. Run AF7R25_BUILD_HIGHRES_TIMER first.');

raw=fileread(src);
assert(contains(raw,'AF7R21-R9'),'[AF7R25] R9 marker missing.');
assert(contains(raw,'AF7R23_STAGE_TIMING'),'[AF7R25] R23 marker missing.');
assert(contains(raw,'AF7R24_SYNTHESIS_TIMING'),'[AF7R25] R24 marker missing.');
assert(~contains(raw,'AF7R25_HIGHRES_TIMING'),'[AF7R25] already installed.');

stamp=char(datetime('now','Format','yyyyMMdd_HHmmss'));
backup=fullfile(fileparts(src),['REPLANNING_SYSTEM_pre_R25_' stamp '.m']);
copyfile(src,backup);

% -------------------------------------------------------------------------
% Properties.
% -------------------------------------------------------------------------
old1=['        r9_synth_sign_count                    = NaN;' newline];
new1=[old1 ...
'        % AF7R25_HIGHRES_TIMING diagnostic-only QPC/cycle counters' newline ...
'        r9_hr_request_seq                      = NaN;' newline ...
'        r9_hr_callback_wall_ms                 = NaN;' newline ...
'        r9_hr_callback_thread_cycles           = NaN;' newline ...
'        r9_hr_callback_process_cycles          = NaN;' newline ...
'        r9_hr_episode_wall_ms                  = NaN;' newline ...
'        r9_hr_episode_thread_cycles            = NaN;' newline ...
'        r9_hr_episode_process_cycles           = NaN;' newline ...
'        r9_hr_synthesis_wall_ms                = NaN;' newline ...
'        r9_hr_synthesis_thread_cycles          = NaN;' newline ...
'        r9_hr_synthesis_process_cycles         = NaN;' newline ...
'        r9_hr_qp_wall_ms                       = NaN;' newline ...
'        r9_hr_qp_thread_cycles                 = NaN;' newline ...
'        r9_hr_qp_process_cycles                = NaN;' newline];
raw=replace_once(raw,old1,new1,'properties');

% -------------------------------------------------------------------------
% Logger property names.
% -------------------------------------------------------------------------
old2=['                "r9_synth_sign_count", ...' newline ...
      '                "geometry_shadow_pass", ...'];
new2=['                "r9_synth_sign_count", ...' newline ...
      '                "r9_hr_request_seq", ...' newline ...
      '                "r9_hr_callback_wall_ms", ...' newline ...
      '                "r9_hr_callback_thread_cycles", ...' newline ...
      '                "r9_hr_callback_process_cycles", ...' newline ...
      '                "r9_hr_episode_wall_ms", ...' newline ...
      '                "r9_hr_episode_thread_cycles", ...' newline ...
      '                "r9_hr_episode_process_cycles", ...' newline ...
      '                "r9_hr_synthesis_wall_ms", ...' newline ...
      '                "r9_hr_synthesis_thread_cycles", ...' newline ...
      '                "r9_hr_synthesis_process_cycles", ...' newline ...
      '                "r9_hr_qp_wall_ms", ...' newline ...
      '                "r9_hr_qp_thread_cycles", ...' newline ...
      '                "r9_hr_qp_process_cycles", ...' newline ...
      '                "geometry_shadow_pass", ...'];
raw=replace_once(raw,old2,new2,'logger names');

% -------------------------------------------------------------------------
% State mirrors.
% -------------------------------------------------------------------------
old3=['            st.r9_synth_sign_count=obj.r9_synth_sign_count;' newline ...
      '            st.geometry_shadow_pass=logical(obj.geometry_shadow_pass);'];
new3=['            st.r9_synth_sign_count=obj.r9_synth_sign_count;' newline ...
      '            st.r9_hr_request_seq=obj.r9_hr_request_seq;' newline ...
      '            st.r9_hr_callback_wall_ms=obj.r9_hr_callback_wall_ms;' newline ...
      '            st.r9_hr_callback_thread_cycles=obj.r9_hr_callback_thread_cycles;' newline ...
      '            st.r9_hr_callback_process_cycles=obj.r9_hr_callback_process_cycles;' newline ...
      '            st.r9_hr_episode_wall_ms=obj.r9_hr_episode_wall_ms;' newline ...
      '            st.r9_hr_episode_thread_cycles=obj.r9_hr_episode_thread_cycles;' newline ...
      '            st.r9_hr_episode_process_cycles=obj.r9_hr_episode_process_cycles;' newline ...
      '            st.r9_hr_synthesis_wall_ms=obj.r9_hr_synthesis_wall_ms;' newline ...
      '            st.r9_hr_synthesis_thread_cycles=obj.r9_hr_synthesis_thread_cycles;' newline ...
      '            st.r9_hr_synthesis_process_cycles=obj.r9_hr_synthesis_process_cycles;' newline ...
      '            st.r9_hr_qp_wall_ms=obj.r9_hr_qp_wall_ms;' newline ...
      '            st.r9_hr_qp_thread_cycles=obj.r9_hr_qp_thread_cycles;' newline ...
      '            st.r9_hr_qp_process_cycles=obj.r9_hr_qp_process_cycles;' newline ...
      '            st.geometry_shadow_pass=logical(obj.geometry_shadow_pass);'];
raw=replace_all_at_least(raw,old3,new3,1,'state mirrors');

% -------------------------------------------------------------------------
% Reset on EVERY generator request. This fixes stale telemetry.
% -------------------------------------------------------------------------
old4=['            obj.generator_request_count=obj.generator_request_count+1;' newline];
new4=[old4 ...
'            obj.r9_hr_request_seq=double(obj.generator_request_count);' newline ...
'            obj.r9_hr_callback_wall_ms=NaN;' newline ...
'            obj.r9_hr_callback_thread_cycles=NaN;' newline ...
'            obj.r9_hr_callback_process_cycles=NaN;' newline ...
'            obj.r9_hr_episode_wall_ms=NaN;' newline ...
'            obj.r9_hr_episode_thread_cycles=NaN;' newline ...
'            obj.r9_hr_episode_process_cycles=NaN;' newline ...
'            obj.r9_hr_synthesis_wall_ms=NaN;' newline ...
'            obj.r9_hr_synthesis_thread_cycles=NaN;' newline ...
'            obj.r9_hr_synthesis_process_cycles=NaN;' newline ...
'            obj.r9_hr_qp_wall_ms=NaN;' newline ...
'            obj.r9_hr_qp_thread_cycles=NaN;' newline ...
'            obj.r9_hr_qp_process_cycles=NaN;' newline];
raw=replace_once(raw,old4,new4,'request reset');

% -------------------------------------------------------------------------
% Outer callback QPC.
% -------------------------------------------------------------------------
old5=['                    candidate=obj.generator_backend_locked_callback(CTX);' newline];
new5=['                    r25cb0=af7r25_stamp_mex();' newline ...
      old5 ...
      '                    r25cb1=af7r25_stamp_mex();' newline ...
      '                    obj.r9_hr_callback_wall_ms=1e3*double(r25cb1(1)-r25cb0(1))/double(r25cb0(2));' newline ...
      '                    obj.r9_hr_callback_thread_cycles=double(r25cb1(3)-r25cb0(3));' newline ...
      '                    obj.r9_hr_callback_process_cycles=double(r25cb1(4)-r25cb0(4));' newline];
raw=replace_once(raw,old5,new5,'callback QPC');

% -------------------------------------------------------------------------
% Episode stage QPC.
% -------------------------------------------------------------------------
old6=['            [EPI,okEpi]=obj.build_bezier_nominal_unsafe_episode_components( ...' newline ...
      '                OUT,CTX,searchEnd);' newline];
new6=['            r25ep0=af7r25_stamp_mex();' newline ...
      old6 ...
      '            r25ep1=af7r25_stamp_mex();' newline ...
      '            obj.r9_hr_episode_wall_ms=1e3*double(r25ep1(1)-r25ep0(1))/double(r25ep0(2));' newline ...
      '            obj.r9_hr_episode_thread_cycles=double(r25ep1(3)-r25ep0(3));' newline ...
      '            obj.r9_hr_episode_process_cycles=double(r25ep1(4)-r25ep0(4));' newline];
raw=replace_once(raw,old6,new6,'episode QPC');

% -------------------------------------------------------------------------
% Synthesis stage QPC.
% -------------------------------------------------------------------------
old7=['            [CANDS,SYN]=obj.build_bezier_piecewise_towing_candidates( ...' newline ...
      '                OUT,CTX,EPI,OUT.t1);' newline];
new7=['            r25sy0=af7r25_stamp_mex();' newline ...
      old7 ...
      '            r25sy1=af7r25_stamp_mex();' newline ...
      '            obj.r9_hr_synthesis_wall_ms=1e3*double(r25sy1(1)-r25sy0(1))/double(r25sy0(2));' newline ...
      '            obj.r9_hr_synthesis_thread_cycles=double(r25sy1(3)-r25sy0(3));' newline ...
      '            obj.r9_hr_synthesis_process_cycles=double(r25sy1(4)-r25sy0(4));' newline];
raw=replace_once(raw,old7,new7,'synthesis QPC');

% -------------------------------------------------------------------------
% QP enumeration QPC.
% -------------------------------------------------------------------------
old8=['            BASE=obj.enumerate_piecewise_sign_qp_recursive( ...' newline ...
      '                H,OR,1,zeros(E,1),BASE);' newline];
new8=['            r25qp0=af7r25_stamp_mex();' newline ...
      old8 ...
      '            r25qp1=af7r25_stamp_mex();' newline ...
      '            obj.r9_hr_qp_wall_ms=1e3*double(r25qp1(1)-r25qp0(1))/double(r25qp0(2));' newline ...
      '            obj.r9_hr_qp_thread_cycles=double(r25qp1(3)-r25qp0(3));' newline ...
      '            obj.r9_hr_qp_process_cycles=double(r25qp1(4)-r25qp0(4));' newline];
raw=replace_once(raw,old8,new8,'QP QPC');

% Header marker.
oldH=['% AF7R24_SYNTHESIS_TIMING: diagnostic-only synthesis substage timing.' newline];
newH=[oldH ...
'% AF7R25_HIGHRES_TIMING: QPC wall + thread/process cycle diagnostic timing.' newline];
raw=replace_once(raw,oldH,newH,'header');

fid=fopen(src,'w');
assert(fid>=0,'[AF7R25] cannot open source for writing.');
fwrite(fid,raw,'char');
fclose(fid);

OUT=struct('schema','AF7R25_INSTALL_HIGHRES_TIMING_V1', ...
    'source',src,'backup',backup,'installed',true, ...
    'acceptance_logic_modified',false,'deadline_logic_modified',false, ...
    'stale_telemetry_reset_added',true);

fprintf(' source                                  = %s\n',src);
fprintf(' backup                                  = %s\n',backup);
fprintf(' QPC/cycle instrumentation installed     = 1\n');
fprintf(' request-local stale reset installed     = 1\n');
fprintf(' acceptance logic modified               = 0\n');
fprintf(' deadline logic modified                 = 0\n');
fprintf('====================================================================================================\n');
end


function out=replace_once(in,old,new,label)
idx=strfind(in,old);
assert(numel(idx)==1, ...
    '[AF7R25] Expected one "%s" target; found %d.',label,numel(idx));
out=[in(1:idx-1) new in(idx+length(old):end)];
end

function out=replace_all_at_least(in,old,new,nmin,label)
idx=strfind(in,old);
assert(numel(idx)>=nmin, ...
    '[AF7R25] Expected at least %d "%s" targets; found %d.',nmin,label,numel(idx));
out=strrep(in,old,new);
end
