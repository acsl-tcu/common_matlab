function R=AF7R58R36_ESTIMATED_ORIGIN_AUDIT(EST,refPacket,predictor,tvec,OP,PHYS,knownMask)
% RESEARCH-ONLY current-estimate-origin trigger comparison. Never commit.
% predictor is the ACTUAL externally provided ideal closed-loop propagation:
%   pred=predictor(EST,tvec,refPacket,PHYS)
% It must return pL[3xN], q[3xN] and source description.
% A reference shifted in position is NOT a valid predictor.
assert(isa(predictor,'function_handle'),'A verified model callback is required; no fallback.');
assert(isstruct(EST)&&all(isfield(EST,{'p','pL','pT'})), ...
 'Estimator must provide UAV p, payload pL and cable pT.');
assert(isstruct(refPacket)&&all(isfield(refPacket,{'pL','q'})), ...
 'The active reference horizon packet must be provided.');
assert(isstruct(PHYS)&&all(isfield(PHYS,{'L_cable','H','dt','current_mL'})), ...
 'No guessed cable length, horizon, dt, or payload mass.');
assert(all(isfield(OP,{'C','R','Araw','ids','Dcomp'})), ...
 'Exact obstacle packet and three component radii must be supplied.');
tvec=double(tvec(:).');N=numel(tvec);
assert(N>1 && all(isfinite(tvec)) && all(diff(tvec)>0), 'Invalid forward clock.');
assert(abs(tvec(end)-tvec(1)-double(PHYS.H))<=64*eps(max(1,max(abs(tvec)))), ...
 'Grid horizon differs from external H.');
assert(all(abs(diff(tvec)-double(PHYS.dt))<=64*eps(max(1,max(abs(tvec))))), ...
 'Grid spacing differs from external dt.');
P=predictor(EST,tvec,refPacket,PHYS);
assert(isstruct(P)&&all(isfield(P,{'pL','q','model_source'})), ...
 'Forward propagation must provide complete model output.');
pL=double(P.pL);q=double(P.q);
assert(isequal(size(pL),[3,N]) && isequal(size(q),[3,N]) && ...
 all(isfinite(pL(:))) && all(isfinite(q(:))), ...
 'Current-state propagator returned invalid dimensions or nonfinite values.');
assert(isequal(size(refPacket.pL),[3,N]) && isequal(size(refPacket.q),[3,N]), ...
 'Reference packet shape mismatch.');
normerr=max(abs(vecnorm(q)-1));
assert(normerr<=1e-9,'Predicted cable unit-vector invariant failed.');
assert(all(isfinite([PHYS.L_cable PHYS.current_mL])) && ...
 PHYS.L_cable>0 && PHYS.current_mL>0, 'Invalid live physical parameters.');
initial_payload_res=norm(pL(:,1)-double(EST.pL(:)));
initial_cable_res=norm(q(:,1)-double(EST.pT(:))/norm(double(EST.pT(:))));
initial_geometry_res=norm(double(EST.pL(:))-double(EST.p(:))- ...
 PHYS.L_cable*double(EST.pT(:))/norm(double(EST.pT(:))));
% These are DIAGNOSTICS. Do not force them to zero by replacing a sample.
assert(initial_payload_res<1e-7 && initial_cable_res<1e-7, ...
 'Predictor does not start at the provided estimator state.');
assert(exist('g26_future_trigger_kernel_mex','file')==3, ...
 'The current native trigger MEX is required.');
knownMask=double(logical(knownMask));
[oldHit,oldIdx,oldId,oldComponent]=g26_future_trigger_kernel_mex( ...
 PHYS.H,PHYS.dt,PHYS.L_cable,refPacket.pL,refPacket.q, ...
 OP.C,OP.R,OP.Araw,OP.Dcomp,OP.ids,knownMask);
[newHit,newIdx,newId,newComponent]=g26_future_trigger_kernel_mex( ...
 PHYS.H,PHYS.dt,PHYS.L_cable,pL,q, ...
 OP.C,OP.R,OP.Araw,OP.Dcomp,OP.ids,knownMask);
R=struct('schema','AF7R58R36_ESTIMATED_ORIGIN_SHADOW_V1', ...
 'authority','READ_ONLY_SHADOW_NO_COMMIT', ...
 'current_estimate_forward_origin',true,'model_source',char(P.model_source), ...
 'reference_trigger',logical(oldHit),'reference_index',oldIdx, ...
 'reference_obstacle',oldId,'reference_component',oldComponent, ...
 'estimated_origin_trigger',logical(newHit),'estimated_index',newIdx, ...
 'estimated_obstacle',newId,'estimated_component',newComponent, ...
 'initial_payload_residual_m',initial_payload_res, ...
 'initial_q_residual',initial_cable_res, ...
 'estimator_geometry_residual_m',initial_geometry_res, ...
 'trigger_disagrees',logical(oldHit)~=logical(newHit), ...
 'ideal_propagator_verification_required',true, ...
 'reference_candidate_still_uses_reference_start',true, ...
 'certified_execution_safety',false,'auto_commit',false);
end
