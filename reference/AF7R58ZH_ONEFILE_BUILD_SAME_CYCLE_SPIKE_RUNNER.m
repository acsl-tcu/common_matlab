'    do_prop_local(time,cha,cha,logger,env,agent,"sensor",1,true);' newline ...
'    do_prop_local(time,cha,cha,logger,env,agent,"estimator",1,true);' newline ...
'    do_prop_local(time,cha,cha,logger,env,agent,"reference",1,true);' newline ...
'    do_prop_local(time,cha,cha,logger,env,agent,"controller",1,true);' newline ...
'    do_prop_local(time,cha,cha,logger,env,agent,"input_transform",1,true);' newline ...
'' newline ...
'    % Onboard-compute proxy:' newline ...
'    % connector acquisition + sensor + estimator + reference/replanner' newline ...
'    % + controller + input_transform.  Numerical plant is excluded.' newline ...
'    online_before_plant_s=toc(tIteration);'];

