    'runtime_profile.full_iteration_s(rk)=full_iteration_s;', ...
    'runtime_profile.full_iteration_s=runtime_profile.full_iteration_s(1:Krt);', ...
    'plot_runtime_profile(runtime_profile,10,11);', ...
