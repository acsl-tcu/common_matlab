loop=raw(loopPos:end);
loop=replace_once(loop,anchorStore,newStore,'flight-loop runtime_profile store');
raw=[prefix loop];

% --------------------------------------------------------------------------------------
% 4. Trim new arrays and auto-generate report before plotting.
% --------------------------------------------------------------------------------------
anchorTrim='runtime_profile.full_iteration_s=runtime_profile.full_iteration_s(1:Krt);';
newTrim=[anchorTrim newline ...
'runtime_profile.sensor_dispatch_s=runtime_profile.sensor_dispatch_s(1:Krt);' newline ...
'runtime_profile.estimator_s=runtime_profile.estimator_s(1:Krt);' newline ...
'runtime_profile.reference_s=runtime_profile.reference_s(1:Krt);' newline ...
'runtime_profile.controller_s=runtime_profile.controller_s(1:Krt);' newline ...
'runtime_profile.input_transform_s=runtime_profile.input_transform_s(1:Krt);' newline ...
'runtime_profile.online_residual_s=runtime_profile.online_residual_s(1:Krt);' newline ...
'runtime_profile.gen_request_delta=runtime_profile.gen_request_delta(1:Krt);' newline ...
