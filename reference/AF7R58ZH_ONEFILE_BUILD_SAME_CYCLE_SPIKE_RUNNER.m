'    runtime_profile.sensor_dispatch_s(rk)=sensor_dispatch_s;' newline ...
'    runtime_profile.estimator_s(rk)=estimator_s;' newline ...
'    runtime_profile.reference_s(rk)=reference_s;' newline ...
'    runtime_profile.controller_s(rk)=controller_s;' newline ...
'    runtime_profile.input_transform_s(rk)=input_transform_s;' newline ...
'    runtime_profile.online_residual_s(rk)=online_residual_s;' newline ...
'    runtime_profile.gen_request_delta(rk)=af7r58zh_req_delta;' newline ...
'    runtime_profile.gen_deadline_delta(rk)=af7r58zh_deadline_delta;' newline ...
'    runtime_profile.gen_commit_delta(rk)=af7r58zh_commit_delta;' newline ...
'    runtime_profile.cache_store_delta(rk)=af7r58zh_store_delta;' newline ...
'    runtime_profile.cache_hit_delta(rk)=af7r58zh_hit_delta;' newline ...
'    runtime_profile.cache_invalidate_delta(rk)=af7r58zh_invalidate_delta;' newline ...
'    runtime_profile.cache_reason(rk)=af7r58zh_prop(replanner_instance,''reference_only_prepared_packet_cache_last_reason_code'',NaN);' newline ...
'    runtime_profile.gen_last_callback_ms(rk)=af7r58zh_prop(replanner_instance,''generator_last_callback_ms'',NaN);' newline ...
'    runtime_profile.gen_last_critical_ms(rk)=af7r58zh_prop(replanner_instance,''generator_last_critical_ms'',NaN);' newline ...
'    runtime_profile.gen_last_cycle_critical_ms(rk)=af7r58zh_prop(replanner_instance,''generator_last_cycle_critical_ms'',NaN);' newline ...
'    runtime_profile.reference_version(rk)=af7r58zh_prop(replanner_instance,''active_reference_version'',NaN);'];

