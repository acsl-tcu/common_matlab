'        sensor_dispatch_s - estimator_s - reference_s - controller_s - input_transform_s;' newline ...
'' newline ...
'    % Snapshot cumulative replanner counters AFTER online timing has stopped.' newline ...
'    af7r58zh_req = af7r58zh_prop(replanner_instance,''generator_request_count'',af7r58zh_prev_req);' newline ...
'    af7r58zh_deadline = af7r58zh_prop(replanner_instance,''generator_deadline_fail_count'',af7r58zh_prev_deadline);' newline ...
'    af7r58zh_commit = af7r58zh_prop(replanner_instance,''replan_commit_count'',af7r58zh_prev_commit);' newline ...
'    af7r58zh_store = af7r58zh_prop(replanner_instance,''reference_only_prepared_packet_cache_store_count'',af7r58zh_prev_store);' newline ...
'    af7r58zh_hit = af7r58zh_prop(replanner_instance,''reference_only_prepared_packet_cache_hit_count'',af7r58zh_prev_hit);' newline ...
'    af7r58zh_invalidate = af7r58zh_prop(replanner_instance,''reference_only_prepared_packet_cache_invalidate_count'',af7r58zh_prev_invalidate);' newline ...
'    af7r58zh_req_delta=af7r58zh_req-af7r58zh_prev_req;' newline ...
'    af7r58zh_deadline_delta=af7r58zh_deadline-af7r58zh_prev_deadline;' newline ...
'    af7r58zh_commit_delta=af7r58zh_commit-af7r58zh_prev_commit;' newline ...
'    af7r58zh_store_delta=af7r58zh_store-af7r58zh_prev_store;' newline ...
'    af7r58zh_hit_delta=af7r58zh_hit-af7r58zh_prev_hit;' newline ...
'    af7r58zh_invalidate_delta=af7r58zh_invalidate-af7r58zh_prev_invalidate;' newline ...
'    af7r58zh_prev_req=af7r58zh_req;' newline ...
'    af7r58zh_prev_deadline=af7r58zh_deadline;' newline ...
'    af7r58zh_prev_commit=af7r58zh_commit;' newline ...
