function OUT = AF7R58ZH_ONEFILE_BUILD_SAME_CYCLE_SPIKE_RUNNER()
% AF7R58ZH
% Build a diagnostic COPY of the current run_flight_headless.m.
%
% The original run_flight_headless.m is NEVER modified.
%
% The copy measures, in the SAME control cycle:
%   sensor acquisition
%   sensor dispatch
%   estimator
%   reference / REPLANNING_SYSTEM
%   controller
%   input_transform
%   online residual
%   simulation plant
%   logger
%   full iteration
%
% It also snapshots REPLANNING_SYSTEM cumulative counters AFTER the online
% timer stops, so the counter reads do not contaminate online_before_plant_s.
%
% This is diagnostic-only. The added tic/toc stage probes have small
% measurement overhead and are NOT final 4-ms authority. Their purpose is to
% identify which same-cycle stage creates the observed 40--50 ms spike.
%
% Output copy:
%   <root>\run_flight_headless_AF7R58ZH_spike_audit.m
%
% Running that copy automatically creates:
%   AF7R58ZH_SPIKE_REPORT.txt
%   AF7R58ZH_SPIKE_OUT.mat
% in a temporary folder under the project root and prints their paths.

src=which('run_flight_headless');
assert(~isempty(src)&&isfile(src), ...
    '[AF7R58ZH] run_flight_headless.m is not on MATLAB path.');

root=fileparts(src);
dst=fullfile(root,'run_flight_headless_AF7R58ZH_spike_audit.m');

raw=fileread(src);
raw=strrep(raw,sprintf('\r\n'),sprintf('\n'));
raw=strrep(raw,sprintf('\r'),sprintf('\n'));

