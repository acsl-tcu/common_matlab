OUT.schema='AF7R58ZH_BUILD_SAME_CYCLE_SPIKE_RUNNER_V1';
OUT.source_path=src;
OUT.source_sha=file_hash(src);
OUT.output_path=dst;
OUT.production_modified=false;
OUT.status='OPEN';

fprintf('\n====================================================================================================\n');
fprintf(' AF7R58ZH | BUILD SAME-CYCLE SPIKE DECOMPOSITION RUNNER\n');
fprintf('====================================================================================================\n');
fprintf('[AUTHORITY] diagnosticCopyOnly=1 | originalModified=0 | sameCycleStages=1\n');
fprintf(' source = %s\n',src);
fprintf(' source SHA = %s\n',OUT.source_sha);

% --------------------------------------------------------------------------------------
% Exact current-source anchors.
% --------------------------------------------------------------------------------------
must={ ...
    'runtime_profile.full_iteration_s = nan(size(ts:dt:te));', ...
    'while time.t <= time.te', ...
    'do_prop_local(time,cha,cha,logger,env,agent,"sensor",1,true);', ...
    'do_prop_local(time,cha,cha,logger,env,agent,"estimator",1,true);', ...
    'do_prop_local(time,cha,cha,logger,env,agent,"reference",1,true);', ...
    'do_prop_local(time,cha,cha,logger,env,agent,"controller",1,true);', ...
