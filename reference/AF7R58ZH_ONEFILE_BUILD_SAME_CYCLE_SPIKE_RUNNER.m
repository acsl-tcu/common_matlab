'runtime_profile.gen_last_critical_ms=runtime_profile.gen_last_critical_ms(1:Krt);' newline ...
'runtime_profile.gen_last_cycle_critical_ms=runtime_profile.gen_last_cycle_critical_ms(1:Krt);' newline ...
'runtime_profile.reference_version=runtime_profile.reference_version(1:Krt);' newline ...
'' newline ...
'% AF7R58ZH automatic same-cycle spike report.' newline ...
'AF7R58ZH_SPIKE_OUT=af7r58zh_report(runtime_profile,replanner_instance);' newline ...
'assignin(''base'',''AF7R58ZH_SPIKE_OUT'',AF7R58ZH_SPIKE_OUT);'];

raw=replace_once(raw,anchorTrim,newTrim,'runtime_profile trim/report');

% --------------------------------------------------------------------------------------
% 5. Add stage-decomposition plot.
% --------------------------------------------------------------------------------------
anchorPlot='plot_runtime_profile(runtime_profile,10,11);';
