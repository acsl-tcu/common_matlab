'runtime_profile.gen_last_critical_ms = nan(size(ts:dt:te));' newline ...
'runtime_profile.gen_last_cycle_critical_ms = nan(size(ts:dt:te));' newline ...
'runtime_profile.reference_version = nan(size(ts:dt:te));' newline ...
'runtime_profile.k = 0;' newline ...
'' newline ...
'% Cumulative counter baselines. Reads occur outside the online timer.' newline ...
'af7r58zh_prev_req = af7r58zh_prop(replanner_instance,''generator_request_count'',0);' newline ...
'af7r58zh_prev_deadline = af7r58zh_prop(replanner_instance,''generator_deadline_fail_count'',0);' newline ...
