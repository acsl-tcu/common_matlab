function T=AF7R58R76_SELFTEST()
% Synthetic geometry tests, independent of a concrete flight or obstacle
% count/pose. This is not a closed-loop safety certificate.
t=0:0.025:4; N=numel(t); L=2;
y=linspace(0,2,N);
pQ=[zeros(1,N);y;2*ones(1,N)];
pL=[zeros(1,N);y;zeros(1,N)];
P=struct('t',t,'pQ',pQ,'pL',pL);
c=struct('time_s',0,'cable_length_m',L,'horizon_s',4, ...
 'prediction_dt',0.025,'reference_version',0, ...
 'r76_reference_pL',pL,'r76_reference_q',(pL-pQ)/L, ...
 'r76_original_trigger',true,'r76_original_ttc_s',2, ...
 'r76_known_mask',true,'r76_radii_m',[0;0;0], ...
 'r76_d_margin_m',0);
C=[0;1;1];R=eye(3);r=0.3*ones(3,1);
B=struct('C',C,'R',R(:),'Araw',r,'Apay',r, ...
 'Auav',r,'Acable',r,'ids',17,'reference_version',0, ...
 'delta_payload_m',0,'delta_uav_m',0,'delta_cable_m',0);
c.r76_packet=B;
A=AF7R58R76_COLLISION_AUDIT(c,P);
assert(A.physical_sample_outer_hit && ...
 strcmp(A.physical_first_component,'CABLE') && ...
 A.physical_first_obstacle_id==17 && ...
 ~A.inter_sample_safety_proved && ~A.eligible_for_trigger_replacement, ...
 '[R76] midpoint full-cable collision not found or falsely certified.');
c.r76_packet.C=[4;1;1];
Z=AF7R58R76_COLLISION_AUDIT(c,P);
assert(~Z.physical_sample_outer_hit && ~Z.reference_sample_outer_hit && ...
 ~Z.inter_sample_safety_proved,'[R76] clear sample rejected or overcertified.');
% The same geometry must independently catch each rigid component.
c.r76_packet=B;c.r76_packet.C=[0;1;2];
U=AF7R58R76_COLLISION_AUDIT(c,P);
assert(U.physical_sample_outer_hit && ...
    strcmp(U.physical_first_component,'UAV'), ...
    '[R76] missed UAV sphere collision.');
c.r76_packet.C=[0;1;0];
V=AF7R58R76_COLLISION_AUDIT(c,P);
assert(V.physical_sample_outer_hit && ...
    strcmp(V.physical_first_component,'PAYLOAD'), ...
    '[R76] missed payload sphere collision.');
c.r76_packet=B;
% The sensor-known mask, not all map obstacles, defines the query.
c.r76_known_mask=false;
H=AF7R58R76_COLLISION_AUDIT(c,P);
assert(H.known_count==0 && ~H.physical_sample_outer_hit, ...
    '[R76] unknown obstacle used before detection.');
c.r76_known_mask=true;
% Global rotation invariance, arbitrary oriented ellipsoid.
ang=0.43; Q=[cos(ang) -sin(ang) 0; sin(ang) cos(ang) 0;0 0 1];
c.r76_packet=B;c.r76_packet.C=Q*B.C;
c.r76_packet.R=Q*R;c.r76_packet.R=c.r76_packet.R(:);
P.pQ=Q*pQ;P.pL=Q*pL;
c.r76_reference_pL=Q*pL;c.r76_reference_q=Q*(pL-pQ)/L;
W=AF7R58R76_COLLISION_AUDIT(c,P);
assert(W.physical_sample_outer_hit && ...
 strcmp(W.physical_first_component,'CABLE') && ...
 abs(W.min_outer_normalized_clearance-A.min_outer_normalized_clearance)<1e-11, ...
 '[R76] SE(3) rotated cable geometry violated.');
old=rmfield(c,{'r76_packet','r76_known_mask'});
Y=AF7R58R76_COLLISION_AUDIT(old,P);
assert(contains(Y.status,'NO_SAME_EVENT_GEOMETRY'), ...
 '[R76] legacy R75 obstacle packet must not be invented.');
T=struct('status','PASS_R76_CABLE_ROTATION_AND_LEGACY_FAIL_CLOSED', ...
 'cable_midpoint_collision_found',true,'uav_hit',true, ...
 'payload_hit',true,'unknown_not_used',true, ...
 'separated_sample_pass',true,'rotation_invariant',true, ...
 'legacy_snapshot_refused',true, ...
 'full_four_second_future_certified',false, ...
 'trigger_replaced',false);
end
