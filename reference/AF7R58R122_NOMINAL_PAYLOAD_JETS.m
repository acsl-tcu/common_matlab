function J = AF7R58R122_NOMINAL_PAYLOAD_JETS(fns,flightT0,cableL,tGlobal)
% Exact nominal position 0..7 WORLD-TIME jets, in HLC PAYLOAD frame.
% fns are the eight source-derived functions already held by
% REPLANNING_SYSTEM.nominal_flat_derivative_fn; never differentiate sampled xd.
% Source nominal altitude is pre-SLOAD Flight raw z. SLOAD subtracts cableL
% ONCE from position z, not from derivatives of order 1..7.
assert(iscell(fns) && numel(fns)==8 && ...
    all(cellfun(@(f) isa(f,'function_handle'),fns)), ...
    'R122:NominalEightExactDerivativeHandlesRequired', ...
    'The source-derived nominal 0..7 derivative functions are required.');
assert(isnumeric(flightT0)&&isscalar(flightT0)&&isfinite(flightT0) && ...
    isnumeric(cableL)&&isscalar(cableL)&&isfinite(cableL)&&cableL>0 && ...
    isnumeric(tGlobal)&&isscalar(tGlobal)&&isfinite(tGlobal) && ...
    tGlobal>=flightT0, ...
    'R122:InvalidNominalPhysicalTimeOrCableAuthority', ...
    'Global query time must be inside Flight and cableL must be live.');
tau=double(tGlobal)-double(flightT0);
J=zeros(3,8);
for k=1:8
    v=double(fns{k}(tau));v=v(:);
    assert(isequal(size(v),[3 1]) && all(isfinite(v)), ...
        'R122:InvalidExactNominalJet', ...
        'The exact nominal derivative %d must be a finite 3-vector.',k-1);
    J(:,k)=v;
end
J(3,1)=J(3,1)-double(cableL);
end
