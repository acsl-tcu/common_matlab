function O=AF7R58R118_SELFTEST()
% All tests are independent and NEVER mutate REPLANNING_SYSTEM, HLC or plant.
% Validates nontrivial corridor QP and continuous all-interval certificates.
J0=zeros(3,8);J0(1,2)=1;J0(3,1)=2;
J1=J0;J1(1,1)=5;
times=[0 2 5];seed=[J0(:,1),[2;0.5;2],J1(:,1)];
live=struct('rL_m',0.05);
cell1=struct('A',[0 1 0;0 -1 0],'b',[1;1]);
C={cell1,cell1};
Q=AF7R58R118_CORRIDOR_C7_QP(times,seed,J0,J1,C,live, ...
    struct('max_iterations',2500));
assert(Q.reference_candidate_found,'R118Test:CorridorQP', ...
    'Strict constrained C7 QP should solve an ordinary feasible route.');
assert(Q.min_payload_corridor_margin_m>0,'R118Test:CorridorMargin');
assert(Q.max_c7_knot_residual<1e-5,'R118Test:C7Knot');
H=AF7R58R118_HEADING_C6_CERT(Q.segments(1),512);
assert(H.certified,'R118Test:YawC6');
Y=AF7R58R118_YAW_JETS_C6(Q.segments(1),0,0);
assert(abs(Y.yaw_jets06(1))<1e-7&& ...
    abs(Y.yaw_jets06(2))<1e-6, 'R118Test:AnalyticYawJets');
% Intentionally exclude the fixed start endpoint: never rescue an
% impossible corridor with a post-generation unchecked waypoint.
blocked=C;blocked{1}=struct('A',[0 1 0],'b',-2);
QB=AF7R58R118_CORRIDOR_C7_QP(times,seed,J0,J1,blocked,live, ...
    struct('max_iterations',100));
assert(~QB.reference_candidate_found,'R118Test:FixedEndpointFailClosed');
ob=struct('id',9,'center',[50;10;12], 'R',eye(3), 'axes',[1;2;3]);
params=struct('cable_length_m',2,'gravity_m_s2',9.81, ...
 'latest_EKF_mL_kg',0.14,'vehicle_mass_kg',0.762, ...
 'thrust_bounds_N',[0 20], ...
 'torque_bounds_Nm',[-1 1;-1 1;-1 1], ...
 'finite_sensing_vQ_limit_m_s',3);
A=struct('t0_s',0,'initial_reference_jets07',J0, ...
 'nominal_phase_start_s',0,'nominal_jets07_fn',@nominal, ...
 'obs',ob,'live',params,'radii_m',[0.1;0.03;0.1], ...
 'work',struct('duration_trials',3,'branch_assignments',8, ...
 'corridor_nodes',256,'qp_iterations',1000, ...
 'certificate_nodes',512),'duration_scale_s',2);
Z=AF7R58R118_C7_CORRIDOR_PLANNER(A);
assert(Z.reference_candidate_found && Z.position_c7 && Z.yaw_c6 && ...
    Z.continuous_uav_cable_payload && ~Z.production_commit_authorized, ...
    'R118Test:AllIntervalPlanner', ...
    'Full return connector must pass continuous reference certificates.');
assert(Z.return_solved_jointly && ...
    Z.nominal_time_shift_s>=0,'R118Test:NaturalPhase');
EKF=zeros(24,1);EKF(1:3)=[0;0;4];EKF(13:15)=[0;0;2];
P=struct('source','LIVE_EKF_HLC_PLANT_ROLLOUT', ...
 'time_s',0,'reference_version',1,'EKF_mL',0.14, ...
 'pQ',repmat([0;0;4],1,161), ...
 'pL',repmat([0;0;2],1,161), 't_s',(0:160)*0.025);
TR=AF7R58R118_EKF_TRIGGER(struct('event_time_s',0, ...
 'reference_version',1,'EKF_x24',EKF,'EKF_mL',0.14, ...
 'horizon_s',4,'dt_s',0.025, ...
 'known_obstacles',ob,'radii_m',[0.1;0.03;0.1], ...
 'rollout',P));
assert(TR.request && ~TR.proved_clear && ~TR.reference_trigger_used, ...
    'R118Test:NoNumericFalseSafety');
obClose=ob;obClose.center=[0;0;3];
TA=AF7R58R118_EKF_TRIGGER(struct('event_time_s',0, ...
 'reference_version',1,'EKF_x24',EKF,'EKF_mL',0.14, ...
 'horizon_s',4,'dt_s',0.025, ...
 'known_obstacles',obClose,'radii_m',[0.1;0.03;0.1], ...
 'rollout',P));
assert(TA.sampled_risk_witness && TA.request && ...
 ~TA.proved_clear,'R118Test:EKFPhysicalRisk');
O=struct('status','PASS_R118_CORRIDOR_QP_C7_AND_PHYSICAL_TRIGGER_GATES', ...
 'qp',Q.status,'qp_margin_m',Q.min_payload_corridor_margin_m, ...
 'planner',Z.status,'planner_duration_s',Z.selected_duration_s, ...
 'numeric_without_bound',TR.status, ...
 'risk',TA.status,'production_installed',false);
fprintf('[R118] %s\n',O.status);
fprintf('[R118] QP = %s | full-return planner = %s\n',O.qp,O.planner);
end
function J=nominal(t)
J=zeros(3,8);J(1,1)=t;J(1,2)=1;J(3,1)=2;
end
