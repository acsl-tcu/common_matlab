function S=AF7R58R71_SOURCE_CHECK()
% R71R2 static binding and MATLAB class parser gate.
p=which('REPLANNING_SYSTEM');
assert(~isempty(p)&&~isempty(meta.class.fromName('REPLANNING_SYSTEM')), ...
    '[R71R2] missing or unparseable replanner');
s=fileread(p);
assert(contains(s,'AF7R58R71R2_ACTIVE_REPLANNER') && ...
    contains(s,'r71r2_event_snapshots') && ...
    contains(s,'snapshot_active_reference_eval_fn'), ...
    '[R71R2] source does not implement Flight-local event snapshots');
assert(exist('AF7R58R71_EXACT_HLC_PLANT_PREVIEW','file')==2, ...
    '[R71R2] predictor missing');
S=struct('source',p,'parser_passed',true, ...
    'event_snapshot_capture_installed',true, ...
    'postflight_no_argument_collection_installed',true, ...
    'HLC_EKF_plant_runner_modified',false, ...
    'future_trigger_replaced',false,'natural_C7_return_committed',false, ...
    'continuous_time_safety_proved',false);
end
