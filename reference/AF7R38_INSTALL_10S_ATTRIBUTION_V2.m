function OUT = AF7R38_INSTALL_10S_ATTRIBUTION_V2()
% Read-only timing attribution for the remaining 10 s post-callback path.
% Timing fields never participate in a safety or acceptance decision.

src=which('REPLANNING_SYSTEM');
assert(~isempty(src)&&isfile(src),'[AF7R38ATTR] source unresolved.');
raw=fileread(src);
assert(contains(raw,'AF7R38-PREFLIGHT-POLICY-HOTPATH'), ...
    '[AF7R38ATTR] corrected R38 policy patch must be installed first.');
assert(~contains(raw,'AF7R38V2-10S-ATTRIBUTION'), ...
    '[AF7R38ATTR] attribution already installed.');

raw=replace_once(raw, ...
    'classdef REPLANNING_SYSTEM < handle', ...
    join_lines({'classdef REPLANNING_SYSTEM < handle', ...
                '', ...
                '%% AF7R38V2-10S-ATTRIBUTION: read-only reference-only post-callback timing.'}));

anchor='        postcallback_prime_candidate_found = false;';
insert=join_lines({anchor, ...
'        r38_ref_eval_ms                  = NaN;', ...
'        r38_commit_prepare_ms            = NaN;', ...
'        r38_commit_rebuild_ms            = NaN;', ...
'        r38_commit_total_ms              = NaN;', ...
'        r38_commit_attempt_count         = 0;', ...
'        r38_commit_last_ok               = false;', ...
'        r38_commit_last_reason           = '''';'});
raw=replace_once(raw,anchor,insert);

% REFERENCE_ONLY reference-certificate time.
old=join_lines({ ...
'                    case ''REFERENCE_ONLY''', ...
'                        if obj.ENABLE_REFERENCE_ONLY_CERTIFICATE', ...
'                            Rref=obj.evaluate_reference_only_proposal_certificate(candidate);', ...
'                            obj.reference_only_evaluation_count= ...'});
new=join_lines({ ...
'                    case ''REFERENCE_ONLY''', ...
'                        if obj.ENABLE_REFERENCE_ONLY_CERTIFICATE', ...
'                            tr38_ref=tic;', ...
'                            Rref=obj.evaluate_reference_only_proposal_certificate(candidate);', ...
'                            obj.r38_ref_eval_ms=1e3*toc(tr38_ref);', ...
'                            obj.reference_only_evaluation_count= ...'});
raw=replace_once(raw,old,new);

% Commit total timer.
old=join_lines({ ...
'        function [ok,reason] = try_commit_reference_only_proposal(obj,P,t_commit,t_hard_cycle)', ...
'            ok=false;', ...
'            reason='''';'});
new=join_lines({ ...
'        function [ok,reason] = try_commit_reference_only_proposal(obj,P,t_commit,t_hard_cycle)', ...
'            ok=false;', ...
'            reason='''';', ...
'            obj.r38_commit_attempt_count=obj.r38_commit_attempt_count+1;', ...
'            obj.r38_commit_last_ok=false;', ...
'            obj.r38_commit_last_reason='''';', ...
'            obj.r38_commit_prepare_ms=NaN;', ...
'            obj.r38_commit_rebuild_ms=NaN;', ...
'            obj.r38_commit_total_ms=NaN;', ...
'            tr38_total=tic;'});
raw=replace_once(raw,old,new);

% Prepare/eval region.
raw=replace_once(raw, ...
    '            evalFn=@(tg)obj.evaluate_bezier_proposal_reference(tg,P);', ...
    join_lines({'            tr38_prepare=tic;', ...
                '            evalFn=@(tg)obj.evaluate_bezier_proposal_reference(tg,P);'}));

old=join_lines({ ...
'                if ~(isfinite(norm(sf))&&norm(sf)>0)', ...
'                    reason=''REFERENCE_ONLY_FLATNESS_SINGULAR'';', ...
'                    return;', ...
'                end', ...
'            end', ...
'', ...
'            old=struct( ...'});
new=join_lines({ ...
'                if ~(isfinite(norm(sf))&&norm(sf)>0)', ...
'                    reason=''REFERENCE_ONLY_FLATNESS_SINGULAR'';', ...
'                    obj.r38_commit_prepare_ms=1e3*toc(tr38_prepare);', ...
'                    obj.r38_commit_total_ms=1e3*toc(tr38_total);', ...
'                    obj.r38_commit_last_reason=reason;', ...
'                    return;', ...
'                end', ...
'            end', ...
'            obj.r38_commit_prepare_ms=1e3*toc(tr38_prepare);', ...
'', ...
'            old=struct( ...'});
raw=replace_once(raw,old,new);

% Rebuild region.
old=join_lines({ ...
'                obj.active_speed_certificate=SC;', ...
'                obj.validate_active_speed_certificate(SC);', ...
'                obj.trigger_sweep_inflation= ...'});
new=join_lines({ ...
'                obj.active_speed_certificate=SC;', ...
'                obj.validate_active_speed_certificate(SC);', ...
'                tr38_rebuild=tic;', ...
'                obj.trigger_sweep_inflation= ...'});
raw=replace_once(raw,old,new);

old=join_lines({ ...
'                obj.runtime_dependency_signature= ...', ...
'                    obj.capture_runtime_dependency_signature_fast();', ...
'                obj.certificate_stale=obj.empty_certificate_stale_state();'});
new=join_lines({ ...
'                obj.runtime_dependency_signature= ...', ...
'                    obj.capture_runtime_dependency_signature_fast();', ...
'                obj.r38_commit_rebuild_ms=1e3*toc(tr38_rebuild);', ...
'                obj.certificate_stale=obj.empty_certificate_stale_state();'});
raw=replace_once(raw,old,new);

% Total and status on success.
old=join_lines({ ...
'                ok=true;', ...
'                reason=''REFERENCE_ONLY_COMMIT_CLOSED'';', ...
'            catch ME'});
new=join_lines({ ...
'                ok=true;', ...
'                reason=''REFERENCE_ONLY_COMMIT_CLOSED'';', ...
'                obj.r38_commit_total_ms=1e3*toc(tr38_total);', ...
'                obj.r38_commit_last_ok=true;', ...
'                obj.r38_commit_last_reason=reason;', ...
'            catch ME'});
raw=replace_once(raw,old,new);

% Total and status on failure/rollback.
old=join_lines({ ...
'                obj.last_replan_commit_time=old.time;', ...
'                reason=ME.message;', ...
'            end'});
new=join_lines({ ...
'                obj.last_replan_commit_time=old.time;', ...
'                reason=ME.message;', ...
'                obj.r38_commit_total_ms=1e3*toc(tr38_total);', ...
'                obj.r38_commit_last_ok=false;', ...
'                obj.r38_commit_last_reason=reason;', ...
'            end'});
raw=replace_once(raw,old,new);

compact=regexprep(raw,'\s+','');
needle=[char(39) 'sampled_acceptance' char(39) ',true'];
assert(~contains(compact,needle),'[AF7R38ATTR] sampled acceptance changed.');
assert(contains(raw,'hard_modify_deadline_s<=4.0e-3'), ...
    '[AF7R38ATTR] hard deadline contract lost.');

fid=fopen(src,'w');
assert(fid>=0,'[AF7R38ATTR] cannot write source.');
cc=onCleanup(@()fclose(fid));
fwrite(fid,raw,'char');
clear cc;
rehash;

OUT=struct('schema','AF7R38_INSTALL_10S_ATTRIBUTION_V2', ...
    'installed',true,'safety_logic_modified',false);
assignin('base','AF7R38_INSTALL_10S_ATTRIBUTION_V2_OUT',OUT);
end

function out=replace_once(in,old,new)
idx=strfind(in,old);
assert(numel(idx)==1, ...
    '[AF7R38ATTR] source anchor count mismatch (%d).',numel(idx));
out=[in(1:idx-1) new in(idx+numel(old):end)];
end

function s=join_lines(C)
s=strjoin(C,newline);
end
