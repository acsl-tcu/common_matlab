function OUT = AF7R36_TOWING_C7_CONDENSED_C3_R7_INSTALL()
% AF7R36_TOWING_C7_CONDENSED_C3_R7_INSTALL
%
% New towing-specific trajectory family:
%   TOWING_C7_CONDENSED_C3
%
% Core idea
% ---------
% The old family has one degree-15 Hermite transition from the current
% correction jets to the affine obstacle-avoidance span. With C7 endpoint
% matching that transition is unique, so changing only the outer objective
% cannot reshape the entry where the R4C witness actually occurs.
%
% R7 splits every safe transition into TWO degree-15 Bezier pieces and gives
% their common midpoint the full 0..7 derivative jet. C7 is therefore exact.
% Those 8 scalar midpoint jets are optimized analytically and eliminated by
% a Schur complement. Hence the OUTER QP dimension remains exactly 6*C, the
% same as the previous affine families.
%
% Natural cable time:
%       tau^2 = L/g
%
% Exact scalar transition objective:
%       int [ tau^-2 d^2 + d_dot^2
%            + tau^2 d_ddot^2 + tau^4 d_jerk^2 ] dt
%
% There are no arbitrary weighting coefficients.
%
% Acceptance remains:
%       speed certificate
%       -> rejoin certificate
%       -> continuous whole-body certificate
%       -> continuous nonzero XY tangent certificate
%
% The last gate is required because exact path-tangent yaw
%       psi = atan2(y_dot,x_dot)
% is C6 when x,y are C7 and ||v_xy|| is continuously nonzero.
%
% The legacy minimum-snap family is retained only as the existing development
% fail-safe while R7 is evaluated. R7 does not weaken any safety/smoothness
% requirement.
%
% No README and no persistent backup file.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 TOWING C7 CONDENSED C3 R7 INSTALL\n');
fprintf(' structural translation continuity          = C7\n');
fprintf(' exact-heading yaw regularity gate           = continuous ||v_xy|| > 0\n');
fprintf(' hard safety semantics modified              = 0\n');
fprintf(' outer QP dimension increased                = 0\n');
fprintf(' arbitrary tuning weights                    = 0\n');
fprintf('====================================================================================================\n');

