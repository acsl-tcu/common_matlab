        '            QPSol q=solve_qp(MR.H,nvar,rows);' sprintf('\n') ...
        '            if(q.ok)BT.push_back({q.z,q.cost,q.slack,sg});' sprintf('\n') ...
        '        };' sprintf('\n') ...
        '        rec(0);' sprintf('\n') ...
        '        std::vector<Candidate> towing;' sprintf('\n') ...
        '        towing.reserve(BT.size());' sprintf('\n') ...
        '        for(auto&b:BT)towing.push_back(build_candidate_c7r7(E.comp,t0,t1,b.z,b.c,b.sg,b.s,MR,3));' sprintf('\n') ...
        '        R.tim.qp+=std::chrono::duration<double,std::milli>(clk::now()-ts).count();' sprintf('\n') ...
        '        auto tc=clk::now();' sprintf('\n') ...
        '        if(certify_candidates(towing,true,3)){' sprintf('\n') ...
        '            R.tim.candidate_build+=std::chrono::duration<double,std::milli>(clk::now()-tc).count();' sprintf('\n') ...
        '            R.tim.synthesis=std::chrono::duration<double,std::milli>(clk::now()-a).count();' sprintf('\n') ...
        '            R.tim.candidate=R.tim.synthesis;' sprintf('\n') ...
        '            R.tim.total=std::chrono::duration<double,std::milli>(clk::now()-T0).count();' sprintf('\n') ...
        '            return R;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '        R.tim.candidate_build+=std::chrono::duration<double,std::milli>(clk::now()-tc).count();' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '' sprintf('\n') ...
        '    // ------------------------------------------------------------------' sprintf('\n')];

    hppNew=replace_between(hppNew,startMarker,endMarker,newBranch,'R5 family-3 branch');

    %% --------------------------------------------------------------------
    % 5) Wrapper label. Legacy build identity remains unchanged.
    % ---------------------------------------------------------------------
    cppNew=replace_once(cppNew, ...
        '"TOWING_NATURAL_TIME_C3"', ...
        '"TOWING_C7_CONDENSED_C3"', ...
        'family-3 wrapper string');

    assert(contains(cppNew, ...
        'static const char* PLANNER_REV="AF7_REPLANNER_MIN_DEVIATION_V4_FIXED_T1";'), ...
        '[TOWC7-R7] Planner revision changed unexpectedly.');
    assert(contains(cppNew, ...
        'set("compact_constant_translation",logicalScalar(false));'), ...
        '[TOWC7-R7] Legacy compact flag changed unexpectedly.');
    assert(count_exact(hppNew,'AF7_TOWING_C7_CONDENSED_C3_R7')>=3, ...
        '[TOWC7-R7] R7 core markers incomplete.');
    assert(count_exact(cppNew,'"TOWING_C7_CONDENSED_C3"')==1, ...
        '[TOWC7-R7] R7 family string count is not one.');
    assert(count_exact(hppNew,'AF7_TOWING_NATURAL_TIME_C3_R5')==0, ...
        '[TOWC7-R7] Old R5 family branch marker remains.');

    %% --------------------------------------------------------------------
    % 6) Stage compile before production write.
    % ---------------------------------------------------------------------
    stageDir=tempname;
    [ok,msg]=mkdir(stageDir);
    assert(ok,'[TOWC7-R7] Cannot create staging directory: %s',msg);
    stageCleanup=onCleanup(@()cleanup_stage(stageDir)); %#ok<NASGU>

    stagedHpp=fullfile(stageDir,'af7r36_core.hpp');
    stagedCpp=fullfile(stageDir,'af7r36_single_core_mex.cpp');
    write_text(stagedHpp,hppNew);
    write_text(stagedCpp,cppNew);

    fprintf('[TOWC7-R7] Compiling staged MEX...\n');
    oldDir=pwd;
    cwdCleanup=onCleanup(@()cd(oldDir)); %#ok<NASGU>
    cd(stageDir);
    clear mex;
    mex('-R2018a','-O', ...
        'COMPFLAGS="$COMPFLAGS /std:c++17"', ...
        ['-I' stageDir], ...
        '-output','af7r36_single_core_mex', ...
        '-outdir',stageDir, ...
        stagedCpp);

    stagedMex=fullfile(stageDir,['af7r36_single_core_mex.' mexext]);
    assert(isfile(stagedMex),'[TOWC7-R7] Staged MEX binary missing.');

    dstMex=fullfile(refDir,['af7r36_single_core_mex.' mexext]);
    oldMexTmp=fullfile(stageDir,['af7r36_single_core_mex_OLD.' mexext]);
    hadOldMex=isfile(dstMex);
    if hadOldMex
        [ok,msg]=copyfile(dstMex,oldMexTmp,'f');
        assert(ok,'[TOWC7-R7] Cannot stage rollback MEX: %s',msg);
    end

    cd(oldDir);
    clear mex;

    wroteH=false;wroteC=false;installedMex=false;
    try
        write_text(hpp,hppNew);wroteH=true;
        write_text(cpp,cppNew);wroteC=true;
        [ok,msg]=copyfile(stagedMex,dstMex,'f');
        assert(ok,'[TOWC7-R7] Cannot install staged MEX: %s',msg);
        installedMex=true;

        clear mex;rehash;
        assert(exist('af7r36_single_core_mex','file')==3, ...
            '[TOWC7-R7] Installed MEX not visible.');
        try, af7r36_single_core_mex(7); catch, end
        try, af7r36_single_core_mex(9); catch, end

    catch ME2
        if wroteH, try, write_text(hpp,hpp0); catch, end, end
        if wroteC, try, write_text(cpp,cpp0); catch, end, end
        if installedMex && hadOldMex
            try, copyfile(oldMexTmp,dstMex,'f'); catch, end
        end
        clear mex;rehash;
        rethrow(ME2);
    end

    fprintf('[TOWC7-R7] PASS.\n');
    fprintf('  family 3 = TOWING_C7_CONDENSED_C3         = 1\n');
    fprintf('  translation C7 structurally preserved      = 1\n');
    fprintf('  family-3 exact-heading C6 prerequisite gate= 1\n');
    fprintf('  outer QP dimension unchanged               = 1\n');
    fprintf('  speed/rejoin/whole-body gates unchanged    = 1\n');
    fprintf('  legacy minimum-snap retained as dev backup = 1\n');
    fprintf('  README created                              = 0\n');
    fprintf('  persistent backup files created             = 0\n');

    OUT=struct();
    OUT.pass=true;
    OUT.reference_dir=refDir;
    OUT.revision='AF7_TOWING_C7_CONDENSED_C3_R7';
    OUT.translation_C7=true;
    OUT.heading_exact_yaw_C6_gate=true;
    OUT.outer_qp_dimension_increased=false;
    OUT.hard_safety_modified=false;
    OUT.arbitrary_weights=false;
    OUT.legacy_fallback_retained_for_development=true;

catch ME
    clear mex;rehash;
    fprintf(2,'[TOWC7-R7] FAILED. No successful production install completed.\n');
    rethrow(ME);
end
end

function txt=replace_between(txt,startPat,endPat,new,label)
a=strfind(txt,startPat);
assert(numel(a)==1,'[TOWC7-R7] %s start count=%d; expected 1.',label,numel(a));
bAll=strfind(txt,endPat);
b=bAll(find(bAll>a,1,'first'));
assert(~isempty(b),'[TOWC7-R7] %s end marker not found.',label);
txt=[txt(1:a-1) new txt(b:end)];
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1, ...
    '[TOWC7-R7] Anchor "%s" count=%d; expected exactly 1.',label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end

function n=count_exact(txt,pat)
n=numel(strfind(txt,pat));
end

function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));
s=strrep(s,sprintf('\r'),sprintf('\n'));
end

function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');
assert(f>=0,'[TOWC7-R7] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end

function cleanup_stage(d)
if isfolder(d)
    try, rmdir(d,'s'); catch, end
end
