function R = AF7R58R84_PACKET_FRAME_COMPARE(S,kernel)
% R84 source-bound postflight REFERENCE packet diagnostic. Read-only.
% One event/one reference version, all SENSOR-KNOWN ellipsoids.
% Hit / conservative non-separation is a NEGATIVE WITNESS ONLY.
% Sampled no-hit does NOT certify continuous-time or closed-loop safety.
if nargin<2 || isempty(kernel)
    assert(exist('g26_future_trigger_kernel_mex','file')==3, ...
        '[R84] Current native future-trigger MEX is missing.');
    kernel=@g26_future_trigger_kernel_mex;
end
assert(isstruct(S)&&isscalar(S),'R84:EventSnapshotRequired');
req={'time_s','reference_version','cable_length_m','horizon_s', ...
    'prediction_dt','r76_known_mask','r76_packet','r76_radii_m', ...
    'r76_d_margin_m','r76_reference_pL','r76_reference_q', ...
    'r76_original_trigger','r76_original_obstacle_id'};
for k=1:numel(req)
    assert(isfield(S,req{k}), 'R84:SnapshotMissing:%s',req{k});
end
P=S.r76_packet;
reqP={'C','R','Araw','ids','delta_payload_m','delta_uav_m','delta_cable_m', ...
    'reference_version'};
for k=1:numel(reqP)
    assert(isfield(P,reqP{k}),'R84:SnapshotPacketMissing:%s',reqP{k});
end
assert(double(P.reference_version)==double(S.reference_version), ...
    'R84:EventVersionPacketMismatch');
ids=double(P.ids(:)); n=numel(ids);
assert(n>0&&numel(unique(ids))==n&&all(ids>0)&&all(ids==fix(ids))&& ...
    isequal(size(P.C),[3 n]) && isequal(size(P.R),[9 n]) && ...
    isequal(size(P.Araw),[3 n]) && all(P.Araw(:)>0) && ...
    all(isfinite([P.C(:);P.R(:);P.Araw(:)])), ...
    'R84:InvalidKnownObstaclePacket');
mask=logical(S.r76_known_mask(:).');
assert(numel(mask)==n&&any(mask),'R84:NoKnownObstacleCannotClaimSafe');
PL=double(S.r76_reference_pL); Q=double(S.r76_reference_q);
assert(size(PL,1)==3 && isequal(size(PL),size(Q)) && ...
    all(isfinite([PL(:);Q(:)])) && size(PL,2)>=1, ...
    'R84:InvalidSavedReferencePacket');
dt=double(S.prediction_dt); L=double(S.cable_length_m); H=double(S.horizon_s);
assert(all(isfinite([dt,L,H]))&&dt>0&&L>0&&H>=0 && ...
    abs((size(PL,2)-1)*dt-H)<1e-7*max(1,H), ...
    'R84:SavedPacketHorizonMismatch');
r=double(S.r76_radii_m(:)); dm=double(S.r76_d_margin_m);
assert(numel(r)==3&&all(isfinite(r))&&all(r>=0)&& ...
    isfinite(dm)&&dm>=0,'R84:InvalidBodyDimensions');
D=[r(1)+dm+double(P.delta_payload_m); ...
   r(2)+dm+double(P.delta_uav_m); ...
   r(3)+dm+double(P.delta_cable_m)];
assert(all(isfinite(D))&&all(D>=0),'R84:InvalidInflation');
[hitRaw,jRaw,obsRaw,compRaw]=kernel(H,dt,L,PL,Q, ...
    double(P.C),double(P.R),double(P.Araw),D,ids,double(mask));
PLtrue=PL;PLtrue(3,:)=PLtrue(3,:)-L;
[hitHLC,jHLC,obsHLC,compHLC]=kernel(H,dt,L,PLtrue,Q, ...
    double(P.C),double(P.R),double(P.Araw),D,ids,double(mask));
R=struct('status','R84_SAMPLED_REFERENCE_FRAME_DIFFERENCE__NOT_CERTIFIED', ...
    'event_time_s',double(S.time_s), ...
    'version',double(S.reference_version), ...
    'known_obstacle_ids',ids(mask).', ...
    'original_trigger',logical(S.r76_original_trigger), ...
    'original_obstacle_id',double(S.r76_original_obstacle_id), ...
    'raw_hit',logical(hitRaw),'raw_obstacle_id',double(obsRaw), ...
    'raw_component',double(compRaw),'raw_ttc_s',NaN, ...
    'hlc_hit',logical(hitHLC),'hlc_obstacle_id',double(obsHLC), ...
    'hlc_component',double(compHLC),'hlc_ttc_s',NaN, ...
    'flight_to_HLC_z_shift_m',-L, ...
    'raw_vs_HLC_hit_disagrees',logical(hitRaw)~=logical(hitHLC), ...
    'sampled_nohit_is_safety_proof',false, ...
    'physical_plant_predicted',false,'full_future_certified',false);
if logical(hitRaw)
    assert(isfinite(jRaw)&&jRaw>=1&&jRaw<=size(PL,2), ...
        'R84:RawNativeIndexInvalid');
    R.raw_ttc_s=(double(jRaw)-1)*dt;
end
if logical(hitHLC)
    assert(isfinite(jHLC)&&jHLC>=1&&jHLC<=size(PL,2), ...
        'R84:HLCNativeIndexInvalid');
    R.hlc_ttc_s=(double(jHLC)-1)*dt;
end
end
