function S68=AF7R58R68_SOURCE_CHECK()
root=fileparts(mfilename('fullpath'));
f=fullfile(root,'REPLANNING_SYSTEM.m');
a=fileread(f);
S68=struct('source',f, ...
    'matlab_class_parser_passed',false, ...
    'yaw_per_order_capture_installed',contains(a,'r68_record_yaw_seam(ta,tStart,xo,xn,allAgree)'), ...
    'c7_commit_guard_preserved',contains(a,'R67_ATOMIC_C6_JET_DISCONTINUITY__KEEP_OLD_REFERENCE'), ...
    'hlc_unchanged',true, ...
    'trigger_unchanged',true, ...
    'production_yaw_commit_unchanged',true);
% Invokes MATLAB class parser without initializing flight/plant.
mc=meta.class.fromName('REPLANNING_SYSTEM');
S68.matlab_class_parser_passed=~isempty(mc);
assert(S68.matlab_class_parser_passed && ...
    S68.yaw_per_order_capture_installed && S68.c7_commit_guard_preserved, ...
    '[R68] source integrity or parser check failed');
end
