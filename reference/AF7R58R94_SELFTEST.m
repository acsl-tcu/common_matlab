function T=AF7R58R94_SELFTEST()
% Contract/integration selftest, never a Flight or execution safety proof.
base=fileparts(mfilename('fullpath'));
req={'AF7R58R94_CERTIFY_ALL_SEGMENTS', ...
 'AF7R58R94_SUPPORT_SEED_ROUTES','AF7R58R94_RUN_SAVED_ROUTE', ...
 'AF7R58R94_ADAPTIVE_SAVED_SEARCH', ...
 'AF7R58R91_STABLE_KINEMATIC_CERT', ...
 'AF7R58R80_CONTINUOUS_SEPARATE_BODY_CERT', ...
 'AF7R58R80_HEADING_C6_CERT', ...
 'AF7R58R90_INPUT_ENVELOPE'};
for i=1:4
   src=which(req{i});
   if isempty(src)||~strcmp(fileparts(src),base)
      error('R94:WrongSourceResolved', ...
         'Expected %s in reference directory; got %s.',req{i},src);
   end
end
for i=5:numel(req)
   if exist(req{i},'file')~=2
      error('R94:RequiredPreviousCertifierMissing', ...
          'Missing %s.',req{i});
   end
end
T92=AF7R58R92_SELFTEST();
if ~strcmp(T92.status, ...
 'PASS_R92_MULTISEGMENT_C7_MIN8_AND_FAIL_CLOSED_REFERENCE_GATE')
  error('R94:Regression','Baseline R92 C7 selftest did not pass.');
end
times=[0 1 2]; way=[0 1 2;0 0 0;-2 -2 -2];
J0=zeros(3,8);J1=zeros(3,8);
J0(:,1)=way(:,1);J1(:,1)=way(:,end);
J0(1,2)=1;J1(1,2)=1;
route=AF7R58R92_C7_MINIMUM8_ROUTE(times,way,J0,J1,0.2,2);
if ~route.reference_candidate_found||route.num_segments~=2
  error('R94:ReferenceGeneration','Could not generate exact C7 fixture.');
end
% All values below are SYNTHETIC test inputs, NOT replanner fallback values.
live=struct('gravity_m_s2',9.81,'cable_length_m',2, ...
  'rQ_m',0.1,'rC_m',0.1,'rL_m',0.1, ...
  'finite_sensing_vQ_limit_m_s',3.1, ...
  'vehicle_mass_kg',0.762,'latest_EKF_mL_kg',0.02, ...
  'thrust_bounds_N',[0 20], ...
  'torque_bounds_Nm',[-1 1;-1 1;-1 1], ...
  'tension_max_N',1);
obs=struct('center',[0;100;-2],'R',eye(3), ...
 'axes',[0.5;0.8;1]);
opts=struct('max_nodes_per_check',256, ...
 'operational_uav_speed_limit_m_s',1.5);
G=AF7R58R94_CERTIFY_ALL_SEGMENTS(route,obs,live,opts,{});
contract={'segments','geometry_kinematics_heading_pass', ...
  'all_segment_reference_conditions_pass', ...
  'input_authorities_available','production_commit_authorized'};
if ~all(isfield(G,contract)) || ~G.geometry_kinematics_heading_pass || ...
        ~G.all_segment_reference_conditions_pass || G.production_commit_authorized
  error('R94:ContractWithInputFailed', ...
       'Pinned full-input certifier returned invalid data.');
end
missing=rmfield(live,{'vehicle_mass_kg','thrust_bounds_N','torque_bounds_Nm'});
F=AF7R58R94_CERTIFY_ALL_SEGMENTS(route,obs,missing,opts,{});
if ~all(isfield(F,contract)) || ~F.geometry_kinematics_heading_pass || ...
        F.all_segment_reference_conditions_pass || ...
        F.input_authorities_available || F.production_commit_authorized
  error('R94:MissingInputFailClosedContract', ...
        'Missing input must not suppress geometry results or permit commit.');
end
% Distinguish missing input from an unsafe geometric route.
unsafe=struct('center',[1;0;-2],'R',eye(3),'axes',[1;1;1]);
D=AF7R58R94_CERTIFY_ALL_SEGMENTS(route,unsafe,live,opts,{});
if D.geometry_kinematics_heading_pass || D.all_segment_reference_conditions_pass
  error('R94:GeometricExclusionNotDetected', ...
        'Synthetic obstacle intersecting the path must be rejected.');
end
% Size-independent route hypotheses: one very large oriented ellipsoid,
% several smaller ones, and endpoint-projection overlap.
a=0.41;rot=[cos(a) -sin(a) 0;sin(a) cos(a) 0;0 0 1];
big=struct('center',[0;0;-2],'R',rot,'axes',[40;17;6]);
seeds=AF7R58R94_SUPPORT_SEED_ROUTES( ...
    [-200;0;-2],[200;0;-2],big,0.2,8);
if numel(seeds.routes)<4 || seeds.known_obstacle_count~=1 || ...
        ~all(cellfun(@(W)isnumeric(W)&&size(W,1)==3 && ...
            all(isfinite(W(:))),seeds.routes))
    error('R94:LargeRotatedObstacleSeedsMissing', ...
       'Large ellipsoid must be represented without dimension cutoffs.');
end
idxbig=seeds.seed_relevant_known_indices;
if ~isequal(idxbig,1)
   error('R94:LargeEllipsoidFiltered','Near large ellipsoid was incorrectly filtered.');
end
% Multiple ellipsoids: finite CPU budget limits candidates, not their sizes.
obsMany=repmat(big,1,9);
for k=1:9
 obsMany(k).center=[-90+18*k;0;-2];
 obsMany(k).axes=[3+0.2*k;2;1];
end
M=AF7R58R94_SUPPORT_SEED_ROUTES( ...
     [-200;0;-2],[200;0;-2],obsMany,0.2,4);
if numel(M.routes)>4 || numel(M.seed_relevant_known_indices)~=9
    error('R94:MultiObstacleBudgetOrFiltering','Obstacle count was clipped or CPU budget ignored.');
end
T=struct('status','PASS_R94_PINNED_CERTIFICATE_SCHEMA_AND_GENERAL_SEEDS', ...
  'pinned_certifier_resolved',true, ...
  'geometry_heading_kinematic_with_missing_input_pass', ...
    F.geometry_kinematics_heading_pass, ...
  'missing_input_still_blocks_full_reference', ...
    ~F.all_segment_reference_conditions_pass, ...
  'unsafe_known_obstacle_rejected', ...
    ~D.geometry_kinematics_heading_pass, ...
  'large_rotated_ellipsoid_seed_count',numel(seeds.routes), ...
  'multiple_obstacles_kept',numel(M.seed_relevant_known_indices), ...
  'production_code_modified',false, ...
  'real_flight_snapshot_replayed',false, ...
  'torque_tube_tail_and_ieee_proved',false);
end
