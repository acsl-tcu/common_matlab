function S=AF7R58R63_SOURCE_CHECK()
% No Flight file I/O; verify exact class source selection before SimHL.
root=fileparts(mfilename('fullpath'));
f=which('REPLANNING_SYSTEM');
assert(strcmpi(f,fullfile(root,'REPLANNING_SYSTEM.m')), ...
    'R63:Path','MATLAB is resolving a different REPLANNING_SYSTEM class');
s=fileread(f);
assert(contains(s,'function A=r63_live_c7_authority') && ...
    contains(s,'function [hit,obs_id,component]=r63_live_now_gate') && ...
    contains(s,'r63_now_event_ring') && ...
    contains(s,'r63_live_natural_rejoin_candidate') && ...
    contains(s,'ENABLE_AF7R58R16_REFERENCE_BRIDGE'), ...
    'R63:Class','R63 live source patch is incomplete');
triggerMexReady=(exist('g26_future_trigger_kernel_mex','file')==3);
% Constructor/preflight may compile the kernel later; this source check is
% intentionally safe to run before the usual SimHL initialization.
S=struct('source',f,'source_loaded',true,'trigger_mex_present_now',triggerMexReady, ...
    'current_gate_installed',true, ...
    'live_c7_source_installed',true, ...
    'hlc_unchanged',true,'control_commit_unchanged',true, ...
    'real_4s_closed_loop_future_installed',false, ...
    'rejoin_commit_installed',false);
disp(S);
end
