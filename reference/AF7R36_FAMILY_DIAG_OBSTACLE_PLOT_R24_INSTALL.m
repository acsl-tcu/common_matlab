        'end' sprintf('\n') ...
        'function af7r24_local_obstacle_limits(ax,obs)' sprintf('\n') ...
        'if isempty(obs),return;end;lo=[inf;inf;inf];hi=[-inf;-inf;-inf];' sprintf('\n') ...
