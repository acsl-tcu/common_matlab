    runNew=replace_once(runNew,old,new,'R24 plot calls');

    anchor='function y = motive_output(obj,data)';
    helper=[ ...
        'function af7r24_overlay_obstacles(ax,obs)' sprintf('\n') ...
        'if isempty(obs),return;end' sprintf('\n') ...
        'hold(ax,''on'');' sprintf('\n') ...
        'for ii=1:numel(obs)' sprintf('\n') ...
        '    o=obs(ii);if ~isfield(o,''p_center''),continue;end' sprintf('\n') ...
        '    c=double(o.p_center(:));if numel(c)~=3||any(~isfinite(c)),continue;end' sprintf('\n') ...
        '    R=eye(3);if isfield(o,''R_obs'')&&isequal(size(o.R_obs),[3 3]),R=double(o.R_obs);end' sprintf('\n') ...
        '    typ='''';if isfield(o,''type''),typ=lower(char(o.type));end' sprintf('\n') ...
        '    rp=[];if isfield(o,''raw_param''),rp=double(o.raw_param(:));end' sprintf('\n') ...
        '    if strcmp(typ,''cylinder'')&&numel(rp)>=2,af7r24_draw_cylinder(ax,c,R,rp(1),rp(2));' sprintf('\n') ...
        '    elseif strcmp(typ,''sphere'')&&~isempty(rp),af7r24_draw_ellipsoid(ax,c,R,rp(1)*ones(3,1));' sprintf('\n') ...
        '    elseif strcmp(typ,''ellipsoid'')&&numel(rp)>=3,af7r24_draw_ellipsoid(ax,c,R,rp(1:3));' sprintf('\n') ...
        '    elseif strcmp(typ,''box'')&&numel(rp)>=3,af7r24_draw_box(ax,c,R,rp(1:3));' sprintf('\n') ...
        '    elseif isfield(o,''ellipsoid_radii'')&&numel(o.ellipsoid_radii)>=3,af7r24_draw_ellipsoid(ax,c,R,double(o.ellipsoid_radii(1:3)));end' sprintf('\n') ...
        '    id=ii;if isfield(o,''id''),id=double(o.id);end' sprintf('\n') ...
        '    text(ax,c(1),c(2),c(3),sprintf('' Obs %g'',id),''FontWeight'',''bold'',''Clipping'',''on'');' sprintf('\n') ...
        'end' sprintf('\n') ...
        'hold(ax,''off'');' sprintf('\n') ...
        'end' sprintf('\n') ...
        'function af7r24_draw_cylinder(ax,c,R,r,h)' sprintf('\n') ...
        'if ~(isfinite(r)&&r>0&&isfinite(h)&&h>0),return;end' sprintf('\n') ...
        '[X,Y,Z]=cylinder(r,48);Z=(Z-0.5)*h;[X,Y,Z]=af7r24_xform(X,Y,Z,c,R);' sprintf('\n') ...
        'surf(ax,X,Y,Z,''FaceAlpha'',0.22,''EdgeAlpha'',0.18,''HandleVisibility'',''off'');' sprintf('\n') ...
