        '            obj.staged_replan_predeadline_r24_family_finite_speed_witness=nan(1,8);' sprintf('\n') ...
        '            obj.staged_replan_predeadline_r24_split_representability_reject=NaN;'];
    rpsNew=replace_once(rpsNew,old,new,'R24 latch reset');

    old=[ ...
        '                if isfield(NR16,''stored_c7_exact'')' sprintf('\n') ...
        '                    obj.staged_replan_predeadline_c7_exact=logical(NR16.stored_c7_exact);' sprintf('\n') ...
        '                end'];
    new=[old sprintf('\n') ...
        '                if isfield(NR16,''r24_family_seen''),obj.staged_replan_predeadline_r24_family_seen=double(NR16.r24_family_seen(:).'' );end' sprintf('\n') ...
        '                if isfield(NR16,''r24_family_exact''),obj.staged_replan_predeadline_r24_family_exact=double(NR16.r24_family_exact(:).'' );end' sprintf('\n') ...
        '                if isfield(NR16,''r24_family_exact_reject''),obj.staged_replan_predeadline_r24_family_exact_reject=double(NR16.r24_family_exact_reject(:).'' );end' sprintf('\n') ...
        '                if isfield(NR16,''r24_family_speed_pass''),obj.staged_replan_predeadline_r24_family_speed_pass=double(NR16.r24_family_speed_pass(:).'' );end' sprintf('\n') ...
        '                if isfield(NR16,''r24_family_speed_fail''),obj.staged_replan_predeadline_r24_family_speed_fail=double(NR16.r24_family_speed_fail(:).'' );end' sprintf('\n') ...
        '                if isfield(NR16,''r24_family_finite_speed_witness''),obj.staged_replan_predeadline_r24_family_finite_speed_witness=double(NR16.r24_family_finite_speed_witness(:).'' );end' sprintf('\n') ...
        '                if isfield(NR16,''r24_split_representability_reject''),obj.staged_replan_predeadline_r24_split_representability_reject=double(NR16.r24_split_representability_reject);end'];
    rpsNew=replace_once(rpsNew,old,new,'R24 native latch');

    old='            S.predeadline_c7_exact=logical(obj.staged_replan_predeadline_c7_exact);';
    new=[old sprintf('\n') ...
        '            S.r24_family_seen=double(obj.staged_replan_predeadline_r24_family_seen);' sprintf('\n') ...
        '            S.r24_family_exact=double(obj.staged_replan_predeadline_r24_family_exact);' sprintf('\n') ...
        '            S.r24_family_exact_reject=double(obj.staged_replan_predeadline_r24_family_exact_reject);' sprintf('\n') ...
        '            S.r24_family_speed_pass=double(obj.staged_replan_predeadline_r24_family_speed_pass);' sprintf('\n') ...
        '            S.r24_family_speed_fail=double(obj.staged_replan_predeadline_r24_family_speed_fail);' sprintf('\n') ...
        '            S.r24_family_finite_speed_witness=double(obj.staged_replan_predeadline_r24_family_finite_speed_witness);' sprintf('\n') ...
        '            S.r24_split_representability_reject=double(obj.staged_replan_predeadline_r24_split_representability_reject);'];
    rpsNew=replace_once(rpsNew,old,new,'R24 status');

    %% Obstacle rendering in Figure 5/6 and local Figure 12.
    old=[ ...
        'plot_suspended_load_trajectory(logger,dt, ...' sprintf('\n') ...
        '    "figure_number",6, ...' sprintf('\n') ...
        '    "phase","f", ...' sprintf('\n') ...
        '    "title_text","UAV / Suspended Load / Reference Trajectory — Flight");'];
    new=[old sprintf('\n') ...
        '' sprintf('\n') ...
        '% AF7R24 obstacle-aware 3-D visualization.' sprintf('\n') ...
        'figure(5); af7r24_overlay_obstacles(gca,replanner_instance.static_obstacle_map);' sprintf('\n') ...
        'figure(6); af7r24_overlay_obstacles(gca,replanner_instance.static_obstacle_map);' sprintf('\n') ...
        'plot_suspended_load_trajectory(logger,dt, ...' sprintf('\n') ...
        '    "figure_number",12, ...' sprintf('\n') ...
        '    "phase","f", ...' sprintf('\n') ...
        '    "title_text","Obstacle-local 3-D: UAV / Load / Reference");' sprintf('\n') ...
        'figure(12); af7r24_overlay_obstacles(gca,replanner_instance.static_obstacle_map);' sprintf('\n') ...
        'af7r24_local_obstacle_limits(gca,replanner_instance.static_obstacle_map);' sprintf('\n') ...
