        'if strcmp(typ,''cylinder'')&&numel(rp)>=2,e=abs(R)*[rp(1);rp(1);rp(2)/2];elseif strcmp(typ,''sphere'')&&~isempty(rp),e=rp(1)*ones(3,1);' sprintf('\n') ...
        'elseif strcmp(typ,''ellipsoid'')&&numel(rp)>=3,e=abs(R)*rp(1:3);elseif strcmp(typ,''box'')&&numel(rp)>=3,e=abs(R)*(rp(1:3)/2);end' sprintf('\n') ...
