function OUT = AF7R36_TOWING_DIAG_CAPTURE_V3_INSTALL()
% AF7R36_TOWING_DIAG_CAPTURE_V3_INSTALL
% -------------------------------------------------------------------------
% Robust post-run diagnostic persistence patch for AF7_TOWING_DIAG_V1.
%
% PURPOSE
%   Persist ONLY the scalar towing/speed root-cause diagnostics from the
%   latest real runtime AF7R36 native planning request.  This removes the
%   need for a temporary workspace variable R after run_flight_headless.
%
% SAFETY / SEMANTICS
%   - trajectory synthesis              : unchanged
%   - candidate ordering                : unchanged
%   - speed certificate                 : unchanged
%   - rejoin certificate                : unchanged
%   - continuous whole-body certificate : unchanged
%   - adaptive-rejoin / commit logic    : unchanged
%   - diagnostic persistence only; never read by acceptance/commit code
%
% DIFFERENCE FROM V2
%   V2 used an exact multi-line source anchor.  V3 finds the unique native
%   planner call with a whitespace-tolerant regex, then inserts directly
%   after that call.  If the call is not unique, NO edit is made.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 TOWING DIAGNOSTIC CAPTURE V3 INSTALL\n');
fprintf(' trajectory/certificate semantics modified = 0\n');
fprintf(' robust source matching                     = 1\n');
fprintf('====================================================================================================\n');

rf = which('REPLANNING_SYSTEM');
assert(~isempty(rf) && isfile(rf),'[TOWDIAG-V3] REPLANNING_SYSTEM.m not resolved.');
refDir = fileparts(rf);
hpp = fullfile(refDir,'af7r36_core.hpp');
cpp = fullfile(refDir,'af7r36_single_core_mex.cpp');
assert(isfile(hpp) && isfile(cpp),'[TOWDIAG-V3] AF7R36 sources are missing.');

h = normalize_lf(fileread(hpp));
c = normalize_lf(fileread(cpp));
s = normalize_lf(fileread(rf));

assert(contains(h,'AF7_TOWING_DIAG_V1'), ...
    '[TOWDIAG-V3] V1 core diagnostics are not installed in af7r36_core.hpp.');
assert(contains(c,'towing_diag_revision'), ...
    '[TOWDIAG-V3] V1 MEX diagnostics are not installed in af7r36_single_core_mex.cpp.');

if contains(s,'AF7_TOWING_DIAG_CAPTURE_V3')
    fprintf('[TOWDIAG-V3] Already installed: %s\n',rf);
    OUT=struct('pass',true,'already_installed',true,'source',rf, ...
        'trajectory_semantics_modified',false,'certificate_semantics_modified',false);
    return;
end

% Match only the planner call itself. [ \t] is deliberately used instead of
% \s so the expression cannot consume neighboring lines.
pat = ['(?m)^([ \t]*)RAW[ \t]*=[ \t]*af7r36_single_core_mex[ \t]*' ...
       '\([ \t]*1[ \t]*,[ \t]*pkt[ \t]*\)[ \t]*;[ \t]*$'];
[st,en,tok] = regexp(s,pat,'start','end','tokens');
assert(numel(st)==1, ...
    '[TOWDIAG-V3] Native planner call count=%d; expected exactly 1. No edit made.',numel(st));
indent = tok{1}{1};

% Minimal scalar-only capture.  No control points / cells / compiled packet
% are copied into the persistent diagnostic state.
L = { ...
    '% AF7_TOWING_DIAG_CAPTURE_V3 -- scalar diagnostic persistence only.'; ...
    '% Never used by synthesis, certification, candidate selection or commit.'; ...
    'if isfield(RAW,''towing_diag_revision'') && ...'; ...
    '        ~obj.setup_exact_do_prime_active && ...'; ...
    '        ~obj.generator_integration_prime_active'; ...
    '    D=struct();'; ...
    '    D.capture_revision=''AF7_TOWING_DIAG_CAPTURE_V3'';'; ...
    '    D.candidate_family=RAW.candidate_family;'; ...
    '    D.t1=double(RAW.t1);'; ...
    '    D.finite_sensing_limit_m_s=double(RAW.finite_sensing_limit_m_s);'; ...
    '    D.speed_payload=double(RAW.speed_payload);'; ...
    '    D.speed_accel=double(RAW.speed_accel);'; ...
    '    D.speed_jerk=double(RAW.speed_jerk);'; ...
    '    D.speed_sigma=double(RAW.speed_sigma);'; ...
    '    D.speed_qdot=double(RAW.speed_qdot);'; ...
    '    D.speed_uav=double(RAW.speed_uav);'; ...
    '    D.max_control_norm_m=double(RAW.max_control_norm_m);'; ...
    '    D.primary_candidate_count=double(RAW.primary_candidate_count);'; ...
    '    D.primary_speed_pass_count=double(RAW.primary_speed_pass_count);'; ...
    '    D.primary_rejoin_pass_count=double(RAW.primary_rejoin_pass_count);'; ...
    '    D.primary_geometry_test_count=double(RAW.primary_geometry_test_count);'; ...
    '    D.fallback_candidate_count=double(RAW.fallback_candidate_count);'; ...
    '    D.fallback_speed_pass_count=double(RAW.fallback_speed_pass_count);'; ...
    '    D.primary_min_stageA_uav_speed_UB_m_s=double(RAW.primary_min_stageA_uav_speed_UB_m_s);'; ...
    '    D.primary_min_stageA_specific_force_LB_m_s2=double(RAW.primary_min_stageA_specific_force_LB_m_s2);'; ...
    '    D.primary_min_stageA_correction_speed_UB_m_s=double(RAW.primary_min_stageA_correction_speed_UB_m_s);'; ...
    '    D.primary_min_stageA_correction_accel_UB_m_s2=double(RAW.primary_min_stageA_correction_accel_UB_m_s2);'; ...
    '    D.primary_min_stageA_correction_jerk_UB_m_s3=double(RAW.primary_min_stageA_correction_jerk_UB_m_s3);'; ...
    '    D.primary_min_envelope_m=double(RAW.primary_min_envelope_m);'; ...
    '    D.primary_stageA_certified_count=double(RAW.primary_stageA_certified_count);'; ...
    '    D.primary_stageB_certified_count=double(RAW.primary_stageB_certified_count);'; ...
    '    D.primary_stageB_finite_witness_count=double(RAW.primary_stageB_finite_witness_count);'; ...
    '    D.primary_stageB_repr_fail_count=double(RAW.primary_stageB_repr_fail_count);'; ...
    '    D.towing_diag_revision=RAW.towing_diag_revision;'; ...
    '    obj.generator_last_status=D;'; ...
    'end' ...
    };

block = sprintf('\n');
for k=1:numel(L)
    block = [block indent L{k} sprintf('\n')]; %#ok<AGROW>
end

snew = [s(1:en) block s(en+1:end)];
assert(contains(snew,'AF7_TOWING_DIAG_CAPTURE_V3'), ...
    '[TOWDIAG-V3] Internal insertion verification failed. No edit made.');
assert(numel(regexp(snew,'AF7_TOWING_DIAG_CAPTURE_V3','match'))>=1, ...
    '[TOWDIAG-V3] Marker verification failed. No edit made.');

stamp=char(datetime('now','Format','yyyyMMdd_HHmmss'));
bak=[rf '.towdiag_capture_v3_backup_' stamp];
copyfile(rf,bak,'f');

try
    write_text_lf(rf,snew);
    verify=normalize_lf(fileread(rf));
    assert(contains(verify,'AF7_TOWING_DIAG_CAPTURE_V3'), ...
        '[TOWDIAG-V3] Written source marker not found.');
    fprintf('[TOWDIAG-V3] PASS: scalar post-run diagnostic persistence installed.\n');
    fprintf('[TOWDIAG-V3] REPLANNING_SYSTEM = %s\n',rf);
    fprintf('[TOWDIAG-V3] backup            = %s\n',bak);
    fprintf('[TOWDIAG-V3] Next: clear classes; clear mex; rehash; then rerun the same simulation.\n');
    OUT=struct('pass',true,'already_installed',false,'source',rf,'backup',bak, ...
        'trajectory_semantics_modified',false,'certificate_semantics_modified',false, ...
        'capture_scalar_only',true);
catch ME
    try, copyfile(bak,rf,'f'); catch, end
    fprintf(2,'[TOWDIAG-V3] FAILED; REPLANNING_SYSTEM restored from backup.\n');
    rethrow(ME);
end
end

function s=normalize_lf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));
s=strrep(s,sprintf('\r'),sprintf('\n'));
end

function write_text_lf(path,txt)
f=fopen(path,'wt','n','UTF-8');
assert(f>=0,'[TOWDIAG-V3] Cannot write %s',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end
