function OUT = AF7R38B_10S_POSTCALLBACK_ATTRIBUTION(replanner)
clc;
fprintf('\n====================================================================================================\n');
fprintf(' AF7R38B | 10 s POST-CALLBACK / REFERENCE-ONLY COMMIT ATTRIBUTION\n');
fprintf('====================================================================================================\n');
fprintf('[AUTHORITY] readOnly=1 | diagnosticOnly=1 | safetyLogicUnchanged=1\n');

assert(isa(replanner,'REPLANNING_SYSTEM'));
names={'observer_preflight_prime_done','observer_preflight_prime_ms', ...
    'qpc_stamp_prime_done','postcallback_prime_candidate_found', ...
    'postcallback_prime_done','postcallback_prime_ms', ...
    'r38_ref_eval_ms','r38_commit_prepare_ms','r38_commit_rebuild_ms', ...
    'r38_commit_total_ms','r38_commit_attempt_count', ...
    'r38_commit_last_ok','r38_commit_last_reason'};
for k=1:numel(names)
    assert(isprop(replanner,names{k}),'[AF7R38B] missing property %s.',names{k});
end

fprintf(' observer preflight prime done / ms        = %d / %.6g\n', ...
    logical(replanner.observer_preflight_prime_done),double(replanner.observer_preflight_prime_ms));
fprintf(' QPC stamp prime done                      = %d\n',logical(replanner.qpc_stamp_prime_done));
fprintf(' postcallback prime candidate/done/ms      = %d / %d / %.6g\n', ...
    logical(replanner.postcallback_prime_candidate_found), ...
    logical(replanner.postcallback_prime_done),double(replanner.postcallback_prime_ms));

fprintf('\n[LATEST REFERENCE_ONLY ATTEMPT]\n');
fprintf(' reference certificate eval [ms]           = %.6g\n',double(replanner.r38_ref_eval_ms));
fprintf(' commit prepare/eval [ms]                  = %.6g\n',double(replanner.r38_commit_prepare_ms));
fprintf(' commit rebuild [ms]                       = %.6g\n',double(replanner.r38_commit_rebuild_ms));
fprintf(' commit total [ms]                         = %.6g\n',double(replanner.r38_commit_total_ms));
other=double(replanner.r38_commit_total_ms) ...
    -finite0(double(replanner.r38_commit_prepare_ms)) ...
    -finite0(double(replanner.r38_commit_rebuild_ms));
fprintf(' commit remaining/other [ms]               = %.6g\n',other);
fprintf(' commit attempts / last ok                 = %.0f / %d\n', ...
    double(replanner.r38_commit_attempt_count),logical(replanner.r38_commit_last_ok));
fprintf(' last reason                               = %s\n',char(replanner.r38_commit_last_reason));
fprintf('====================================================================================================\n');

OUT=struct('schema','AF7R38B_10S_POSTCALLBACK_ATTRIBUTION_V1', ...
    'ref_eval_ms',double(replanner.r38_ref_eval_ms), ...
    'prepare_ms',double(replanner.r38_commit_prepare_ms), ...
    'rebuild_ms',double(replanner.r38_commit_rebuild_ms), ...
    'total_ms',double(replanner.r38_commit_total_ms), ...
    'other_ms',other,'last_ok',logical(replanner.r38_commit_last_ok), ...
    'last_reason',char(replanner.r38_commit_last_reason));
assignin('base','AF7R38B_10S_POSTCALLBACK_ATTRIBUTION_OUT',OUT);
end

function y=finite0(x)
if isfinite(x), y=x; else, y=0; end
end
