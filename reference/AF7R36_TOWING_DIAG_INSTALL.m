function OUT = AF7R36_TOWING_DIAG_INSTALL()
% AF7R36_TOWING_DIAG_INSTALL
% -------------------------------------------------------------------------
% Diagnostic-only source patch for the current AF7R36 fixed-t1 native core.
%
% PURPOSE
%   Explain why MINIMUM_DEVIATION_AFFINE candidates fail the unchanged
%   finite-sensing speed certificate before MINIMUM_SNAP_FALLBACK is used.
%
% SAFETY CONTRACT
%   * DOES NOT change candidate generation, ordering, acceptance, t1 search,
%     rejoin logic, or whole-body continuous certificate.
%   * DOES NOT turn sampled checks into acceptance.
%   * Adds rejection/upper-bound diagnostics only.
%   * Existing op=1 planning semantics remain unchanged.
%   * Installer is source-bound and fail-closed: every edit anchor must occur
%     exactly once.  On failure, source files are restored from backup.
%
% Run from MATLAB after putting this file anywhere on the MATLAB path:
%   OUT = AF7R36_TOWING_DIAG_INSTALL;
%
% Then rerun the exact same scenario/audit that produced
% MINIMUM_SNAP_FALLBACK and call:
%   AF7R36_TOWING_ROOTCAUSE_PRINT(R)
% where R is the returned RAW/native result (or a struct containing native_raw).

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 TOWING ROOT-CAUSE DIAGNOSTIC INSTALL\n');
fprintf(' selection/certificate semantics modified = 0\n');
fprintf('====================================================================================================\n');

refDir = fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir) && isfolder(refDir), ...
    '[TOWDIAG] Cannot resolve current reference directory from af7r34_make_core_packet.');

hpp = fullfile(refDir,'af7r36_core.hpp');
cpp = fullfile(refDir,'af7r36_single_core_mex.cpp');
assert(isfile(hpp),'[TOWDIAG] Missing %s',hpp);
assert(isfile(cpp),'[TOWDIAG] Missing %s',cpp);

% Refuse to patch an already-patched or structurally different source.
hpp0 = normalize_lf(fileread(hpp));
cpp0 = normalize_lf(fileread(cpp));
assert(~contains(hpp0,'AF7_TOWING_DIAG_V1'), ...
    '[TOWDIAG] af7r36_core.hpp already contains AF7_TOWING_DIAG_V1.');
assert(~contains(cpp0,'towing_diag_revision'), ...
    '[TOWDIAG] af7r36_single_core_mex.cpp already contains towing_diag_revision.');
assert(contains(hpp0,'MINIMUM_DEVIATION_AFFINE') || contains(cpp0,'MINIMUM_DEVIATION_AFFINE'), ...
    '[TOWDIAG] Expected current minimum-deviation planner not found.');
assert(contains(hpp0,'One exact hard-certificate attempt for a fixed maneuver scope and fixed t1.'), ...
    '[TOWDIAG] Expected fixed-t1 core contract not found.');

stamp = char(datetime('now','Format','yyyyMMdd_HHmmss'));
bakH = [hpp '.towdiag_backup_' stamp];
bakC = [cpp '.towdiag_backup_' stamp];
copyfile(hpp,bakH,'f');
copyfile(cpp,bakC,'f');

try
    %% --------------------------------------------------------------------
    % 1) Add diagnostic state to PlanResult.
    old = [ ...
        '    int fallback_candidate_count=0;' newline ...
        '    int fallback_speed_pass=0;' newline ...
        '    int fallback_rejoin_pass=0;' newline ...
        '    int fallback_geom_tests=0;' newline];
    new = [old ...
        newline ...
        '    // AF7_TOWING_DIAG_V1 -- diagnostic-only; never grants acceptance.' newline ...
        '    double finite_sensing_limit=std::numeric_limits<double>::quiet_NaN();' newline ...
        '    double primary_min_stageA_vq=std::numeric_limits<double>::infinity();' newline ...
        '    double primary_min_stageA_sigma=-std::numeric_limits<double>::infinity();' newline ...
        '    std::array<double,3> primary_min_stageA_U{{' ...
        'std::numeric_limits<double>::quiet_NaN(),' ...
        'std::numeric_limits<double>::quiet_NaN(),' ...
        'std::numeric_limits<double>::quiet_NaN()}};' newline ...
        '    double primary_min_envelope=std::numeric_limits<double>::infinity();' newline ...
        '    int primary_stageA_certified_count=0;' newline ...
        '    int primary_stageB_certified_count=0;' newline ...
        '    int primary_stageB_finite_witness_count=0;' newline ...
        '    int primary_stageB_repr_fail_count=0;' newline];
    hpp0 = replace_once(hpp0,old,new,'PlanResult diagnostic state');

    %% --------------------------------------------------------------------
    % 2) Record the exact finite-sensing limit used by the unchanged gate.
    old = [ ...
        '    if(!(fin(lim)&&lim>0)){' newline ...
        '        R.reason=16;R.tim.total=std::chrono::duration<double,std::milli>(clk::now()-T0).count();return R;' newline ...
        '    }' newline];
    new = [old ...
        '    R.finite_sensing_limit=lim; // AF7_TOWING_DIAG_V1' newline];
    hpp0 = replace_once(hpp0,old,new,'finite-sensing limit capture');

    %% --------------------------------------------------------------------
    % 3) Add branch-local rejection diagnostics around the existing speed
    %    certificate. No acceptance condition is changed.
    old = [ ...
        '        for(auto cand:candidates){' newline ...
        '            SpeedCert sc;' newline ...
        '            auto tr=tighten_stageA(cand,base,L.L,lim);' newline ...
        '            if(tr.certified){' newline ...
        '                sc=stageA_speed(tr,base,L.L);' newline ...
        '                if(sc.certified&&sc.VQ<lim){' newline ...
        '                    cand.dub[0]=tr.U[0];cand.dub[1]=tr.U[1];cand.dub[2]=tr.U[2];' newline ...
        '                }else sc.certified=false;' newline ...
        '            }' newline ...
        '            if(!sc.certified){bool wit=false,rp=false;sc=stageB_speed(ref,L,base,cand,lim,wit,rp);}' newline ...
        '            if(!sc.certified) continue;' newline];

    new = [ ...
        '        for(auto cand:candidates){' newline ...
        '            SpeedCert sc;' newline ...
        '            if(branch==1) R.primary_min_envelope=std::min(R.primary_min_envelope,cand.max_ctrl);' newline ...
        '            auto tr=tighten_stageA(cand,base,L.L,lim);' newline ...
        '            if(branch==1){' newline ...
        '                const double dsig=base.sigma-tr.U[1];' newline ...
        '                const double dvq=(dsig>0.0)?' newline ...
        '                    base.VL+tr.U[0]+L.L*(base.J+tr.U[2])/dsig:' newline ...
        '                    std::numeric_limits<double>::infinity();' newline ...
        '                if(fin(dvq) && dvq<R.primary_min_stageA_vq){' newline ...
        '                    R.primary_min_stageA_vq=dvq;' newline ...
        '                    R.primary_min_stageA_sigma=dsig;' newline ...
        '                    R.primary_min_stageA_U=tr.U;' newline ...
        '                }' newline ...
        '                if(tr.certified) ++R.primary_stageA_certified_count;' newline ...
        '            }' newline ...
        '            if(tr.certified){' newline ...
        '                sc=stageA_speed(tr,base,L.L);' newline ...
        '                if(sc.certified&&sc.VQ<lim){' newline ...
        '                    cand.dub[0]=tr.U[0];cand.dub[1]=tr.U[1];cand.dub[2]=tr.U[2];' newline ...
        '                }else sc.certified=false;' newline ...
        '            }' newline ...
        '            if(!sc.certified){' newline ...
        '                bool wit=false,rp=false;' newline ...
        '                sc=stageB_speed(ref,L,base,cand,lim,wit,rp);' newline ...
        '                if(branch==1){' newline ...
        '                    if(wit) ++R.primary_stageB_finite_witness_count;' newline ...
        '                    if(rp) ++R.primary_stageB_repr_fail_count;' newline ...
        '                    if(sc.certified) ++R.primary_stageB_certified_count;' newline ...
        '                }' newline ...
        '            }' newline ...
        '            if(!sc.certified) continue;' newline];
    hpp0 = replace_once(hpp0,old,new,'primary speed rejection instrumentation');

    %% --------------------------------------------------------------------
    % 4) Add diagnostic fields to the MEX result structure.
    old = [ ...
        '        "fallback_rejoin_pass_count","fallback_geometry_test_count",' newline ...
        '        "rejoin_search_ms","planner_native_revision"};' newline];
    new = [ ...
        '        "fallback_rejoin_pass_count","fallback_geometry_test_count",' newline ...
        '        "finite_sensing_limit_m_s","primary_min_stageA_uav_speed_UB_m_s",' newline ...
        '        "primary_min_stageA_specific_force_LB_m_s2",' newline ...
        '        "primary_min_stageA_correction_speed_UB_m_s",' newline ...
        '        "primary_min_stageA_correction_accel_UB_m_s2",' newline ...
        '        "primary_min_stageA_correction_jerk_UB_m_s3",' newline ...
        '        "primary_min_envelope_m","primary_stageA_certified_count",' newline ...
        '        "primary_stageB_certified_count","primary_stageB_finite_witness_count",' newline ...
        '        "primary_stageB_repr_fail_count","towing_diag_revision",' newline ...
        '        "rejoin_search_ms","planner_native_revision"};' newline];
    cpp0 = replace_once(cpp0,old,new,'MEX diagnostic field names');

    old = [ ...
        '    set("fallback_rejoin_pass_count",dscalar(R.fallback_rejoin_pass));' newline ...
        '    set("fallback_geometry_test_count",dscalar(R.fallback_geom_tests));' newline ...
        '    set("rejoin_search_ms",dscalar(R.tim.rejoin_search));' newline];
    new = [ ...
        '    set("fallback_rejoin_pass_count",dscalar(R.fallback_rejoin_pass));' newline ...
        '    set("fallback_geometry_test_count",dscalar(R.fallback_geom_tests));' newline ...
        '    set("finite_sensing_limit_m_s",dscalar(R.finite_sensing_limit));' newline ...
        '    set("primary_min_stageA_uav_speed_UB_m_s",dscalar(R.primary_min_stageA_vq));' newline ...
        '    set("primary_min_stageA_specific_force_LB_m_s2",dscalar(R.primary_min_stageA_sigma));' newline ...
        '    set("primary_min_stageA_correction_speed_UB_m_s",dscalar(R.primary_min_stageA_U[0]));' newline ...
        '    set("primary_min_stageA_correction_accel_UB_m_s2",dscalar(R.primary_min_stageA_U[1]));' newline ...
        '    set("primary_min_stageA_correction_jerk_UB_m_s3",dscalar(R.primary_min_stageA_U[2]));' newline ...
        '    set("primary_min_envelope_m",dscalar(R.primary_min_envelope));' newline ...
        '    set("primary_stageA_certified_count",dscalar(R.primary_stageA_certified_count));' newline ...
        '    set("primary_stageB_certified_count",dscalar(R.primary_stageB_certified_count));' newline ...
        '    set("primary_stageB_finite_witness_count",dscalar(R.primary_stageB_finite_witness_count));' newline ...
        '    set("primary_stageB_repr_fail_count",dscalar(R.primary_stageB_repr_fail_count));' newline ...
        '    set("towing_diag_revision",mxCreateString("AF7_TOWING_DIAG_V1"));' newline ...
        '    set("rejoin_search_ms",dscalar(R.tim.rejoin_search));' newline];
    cpp0 = replace_once(cpp0,old,new,'MEX diagnostic field assignment');

    % Write sources only after all source-bound replacements succeeded.
    write_text_lf(hpp,hpp0);
    write_text_lf(cpp,cpp0);

    %% --------------------------------------------------------------------
    % 5) Rebuild current MEX. If rebuild fails, restore source files.
    fprintf('[TOWDIAG] Source patch complete. Rebuilding MEX...\n');
    oldDir=pwd;
    cleanupDir=onCleanup(@()cd(oldDir)); %#ok<NASGU>
    cd(refDir);
    clear mex;
    mex('-R2018a','-O', ...
        'COMPFLAGS="$COMPFLAGS /std:c++17"', ...
        ['-I' refDir], ...
        '-output','af7r36_single_core_mex', ...
        '-outdir',refDir, ...
        cpp);
    clear mex;
    rehash;

    assert(exist('af7r36_single_core_mex','file')==3, ...
        '[TOWDIAG] rebuilt MEX not visible.');

    fprintf('[TOWDIAG] PASS: diagnostics installed. Planning semantics unchanged.\n');
    fprintf('[TOWDIAG] backup hpp = %s\n',bakH);
    fprintf('[TOWDIAG] backup cpp = %s\n',bakC);

    OUT=struct();
    OUT.pass=true;
    OUT.reference_dir=refDir;
    OUT.hpp=hpp;
    OUT.cpp=cpp;
    OUT.backup_hpp=bakH;
    OUT.backup_cpp=bakC;
    OUT.revision='AF7_TOWING_DIAG_V1';
    OUT.selection_semantics_modified=false;
    OUT.certificate_semantics_modified=false;
catch ME
    % Fail closed: restore sources exactly if any patch/build step fails.
    try, copyfile(bakH,hpp,'f'); catch, end
    try, copyfile(bakC,cpp,'f'); catch, end
    clear mex;
    rehash;
    fprintf(2,'[TOWDIAG] FAILED; source files restored from backup.\n');
    rethrow(ME);
end
end

function s=normalize_lf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));
s=strrep(s,sprintf('\r'),sprintf('\n'));
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1,'[TOWDIAG] Anchor "%s" count=%d (expected exactly 1).',label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end

function write_text_lf(path,txt)
f=fopen(path,'wt','n','UTF-8');
assert(f>=0,'[TOWDIAG] Cannot open %s for writing.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end
