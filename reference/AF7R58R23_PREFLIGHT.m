function Q=AF7R58R23_PREFLIGHT()
source=which('REPLANNING_SYSTEM');
assert(~isempty(source),'[R23] REPLANNING_SYSTEM is not on the MATLAB path.');
folder=fileparts(source);
S=fileread(source);
H=fileread(fullfile(folder,'af7r36_core.hpp'));
C=fileread(fullfile(folder,'af7r36_single_core_mex.cpp'));
assert(contains(S,'r23_prime_ok=af7r36_single_core_mex(24)') && ...
    contains(H,'r58r23_gram_table') && ...
    contains(H,'r58r23_binomial_table') && ...
    contains(C,'if(op==24)'), ...
    '[R23] R23 source/MEX prewarm revision mismatch.');
assert(exist('af7r36_single_core_mex','file')==3, ...
    '[R23] MEX missing; compile with /std:c++17.');
assert(exist('AF7R58R23_SPIKE_REPORT','file')==2 && ...
    exist('AF7R58R23_INSTALL_SPIKE_PROBE','file')==2, ...
    '[R23] Spike tools not on path.');
% The opcode only loads immutable coefficient tables. Does not plan, commit
% or accept a candidate, and can also be invoked before the runner starts.
ready=af7r36_single_core_mex(24);
assert(islogical(ready) && isscalar(ready) && ready, ...
    '[R23] Native constant coefficient prewarm returned invalid result.');
Q=struct('source',source,'native_mex',which('af7r36_single_core_mex'), ...
    'coefficient_preflight',true,'no_commit_diagnostic',true, ...
    'hard_safety_acceptance_modified',false);
fprintf('[R23] PREFLIGHT PASS: coefficient tables warmed; NO COMMIT.\n');
end
