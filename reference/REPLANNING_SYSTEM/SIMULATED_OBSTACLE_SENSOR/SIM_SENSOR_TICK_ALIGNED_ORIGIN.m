function [center,next]=SIM_SENSOR_TICK_ALIGNED_ORIGIN(prev,t,cha,postplant_p,dt)
% Time-align Sim sensor truth with the EKF's CURRENT runner tick.
% Runner order: EKF(t) -> HLC(t) -> plant advances [t,t+dt] -> update(t).
% The post-plant state at update(t) belongs to t+dt, NOT to t.
% Therefore scan at t using the previous update's post-plant truth.
% Arming at t=0 does not integrate the plant (MODEL_CLASS.do), seeding
% the true initial position before Takeoff first integrates the plant.
% No plant truth is used by the 4-s EKF-anchored trigger or tube prover.
assert(isnumeric(t)&&isscalar(t)&&isreal(t)&&isfinite(t) && ...
    isnumeric(dt)&&isscalar(dt)&&isreal(dt)&&isfinite(dt)&&dt>0 && ...
    isnumeric(postplant_p)&&isreal(postplant_p)&&numel(postplant_p)==3 && ...
    all(isfinite(postplant_p(:))), ...
    'SIM_SENSOR_TICK_ALIGNED_ORIGIN:Input', ...
    'Finite Sim tick, solver dt and post-step true position are required.');
assert((ischar(cha)||isstring(cha))&&isscalar(string(cha)), ...
    'SIM_SENSOR_TICK_ALIGNED_ORIGIN:Phase', ...
    'Actual Sim phase is required.');
postplant_p=double(postplant_p(:));
cha=char(cha);
if isempty(prev)||~isstruct(prev)||~isscalar(prev)|| ...
        ~isfield(prev,'ready')||~prev.ready
    % This is the only allowed seed; arming is prior to any integration.
    assert(t==0 && strcmp(cha,'a'), ...
        'SIM_SENSOR_TICK_ALIGNED_ORIGIN:NoArmingSeed', ...
        'Sim初期真値を観測できない場合は推定値に代替しません。');
    center=postplant_p;
    n=uint64(0);
else
    assert(isfield(prev,'last_time_s')&&isfield(prev,'center')&& ...
        isfield(prev,'next_plant_position'), ...
        'SIM_SENSOR_TICK_ALIGNED_ORIGIN:State','Sensor epoch state is incomplete.');
    prevt=double(prev.last_time_s);
    if t==prevt
        % First Arming and first Takeoff both use time.t==0.
        assert(strcmp(cha,'t') && strcmp(prev.last_phase,'a'), ...
            'SIM_SENSOR_TICK_ALIGNED_ORIGIN:DuplicateTick', ...
            'Only the documented Arming->Takeoff same-tick transition is valid.');
        center=prev.center;
    else
        delta=t-prevt;
        tolerance=32*eps(max(1,max(abs([t,prevt]))))+32*eps(dt);
        assert(delta>0 && abs(delta-dt)<=tolerance, ...
            'SIM_SENSOR_TICK_ALIGNED_ORIGIN:TickGap', ...
            'Exactly one original plant hold must separate sensor scans.');
        center=prev.next_plant_position;
    end
    n=prev.scan_epoch+1;
end
next=struct('ready',true,'last_time_s',double(t), ...
    'last_phase',cha,'center',center, ...
    'next_plant_position',postplant_p,'scan_epoch',n, ...
    'center_source','SIM_PLANT_TRUE_AT_RUNNER_TIME');
end
