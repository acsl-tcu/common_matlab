function p=SIM_SENSOR_READ_TRUE_POSITION(agent)
% Sensor-only access to the Sim plant truth, AFTER the current plant step.
% The caller must delay this physical snapshot by one runner tick to align
% with time.t. Do NOT call from prediction or proof state propagation.
assert(isobject(agent)&&isscalar(agent)&&isprop(agent,'plant'), ...
    'SIM_SENSOR_READ_TRUE_POSITION:NoPlant', ...
    'Sim真値を持つagent.plantが必要です。実機でEKFへ代替しません。');
plant=agent.plant;
assert(isa(plant,'MODEL_CLASS')&&isprop(plant,'state'), ...
    'SIM_SENSOR_READ_TRUE_POSITION:NotOriginalSimPlant', ...
    '原MODEL_CLASSのSim plantにのみ対応します。');
x=plant.state;
assert(isobject(x)&&isscalar(x)&&isprop(x,'p'), ...
    'SIM_SENSOR_READ_TRUE_POSITION:NoTruePosition', ...
    '現在Sim plantに機体真値pがありません。');
p=x.p;
assert(isnumeric(p)&&isreal(p)&&numel(p)==3&&all(isfinite(p(:))), ...
    'SIM_SENSOR_READ_TRUE_POSITION:InvalidTruth', ...
    '原Sim plantの位置pは有限な3次元実数でなければなりません。');
p=double(p(:));
end
