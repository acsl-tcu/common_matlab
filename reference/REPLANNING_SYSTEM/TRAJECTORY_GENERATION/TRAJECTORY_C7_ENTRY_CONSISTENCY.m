function R=TRAJECTORY_C7_ENTRY_CONSISTENCY(start_jets,entry)
%TRAJECTORY_C7_ENTRY_CONSISTENCY Validate NOW, BEFORE optimization.
% The taut cable is checked only at the current EKF snapshot. It does NOT
% assert that independent UAV/payload polynomials remain taut for all time.
% Every acceptance tolerance comes from the live caller; none is guessed.
required={'ekf_now','cable_length_m','position_tolerance_m', ...
    'velocity_tolerance_mps','cable_length_tolerance_m', ...
    'cable_length_rate_tolerance_mps'};
assert(isstruct(start_jets)&&isscalar(start_jets)&& ...
    all(isfield(start_jets,{'uav','payload'}))&& ...
    isequal(size(start_jets.uav),[3 8])&& ...
    isequal(size(start_jets.payload),[3 8])&& ...
    all(isfinite(start_jets.uav(:)))&& ...
    all(isfinite(start_jets.payload(:)))&& ...
    isstruct(entry)&&isscalar(entry)&&all(isfield(entry,required)), ...
    'TRAJECTORY_C7_ENTRY:Request', ...
    'Need authoritative endpoint jets, EKF state, cable and tolerances.');
e=entry.ekf_now;
assert(isstruct(e)&&all(isfield(e,{'p','v','pL','vL'})), ...
    'TRAJECTORY_C7_ENTRY:EKF','Missing EKF positions/velocities.');
for k={'p','v','pL','vL'}
    a=e.(k{1});
    assert(isnumeric(a)&&isreal(a)&&isequal(size(a),[3 1])&& ...
        all(isfinite(a)), ...
        'TRAJECTORY_C7_ENTRY:EKF','Invalid EKF vector.');
end
for k=required(2:end)
    a=entry.(k{1});
    assert(isnumeric(a)&&isreal(a)&&isscalar(a)&&isfinite(a)&&a>=0, ...
        'TRAJECTORY_C7_ENTRY:Authority','Invalid external parameter.');
end
assert(entry.cable_length_m>0,'TRAJECTORY_C7_ENTRY:Cable', ...
    'Current live cable length must be positive.');
pe=max(norm(start_jets.uav(:,1)-e.p), ...
    norm(start_jets.payload(:,1)-e.pL));
ve=max(norm(start_jets.uav(:,2)-e.v), ...
    norm(start_jets.payload(:,2)-e.vL));
D=e.p-e.pL;
actual_length=norm(D);
ce=abs(actual_length-entry.cable_length_m);
if actual_length>0
    % Necessary radial-velocity condition of a fixed-length taut cable:
    % d/dt ||pQ-pL|| = dot(d,vQ-vL)/||d|| = 0.
    cable_rate=abs(dot(D,e.v-e.vL)/actual_length);
else
    cable_rate=Inf;
end
pass=pe<=entry.position_tolerance_m&& ...
    ve<=entry.velocity_tolerance_mps&& ...
    ce<=entry.cable_length_tolerance_m&& ...
    cable_rate<=entry.cable_length_rate_tolerance_mps;
R=struct('passed',pass,'position_error_m',pe, ...
    'velocity_error_mps',ve,'current_cable_length_error_m',ce, ...
    'cable_radial_velocity_error_mps',cable_rate, ...
    'scope','INITIAL_EKF_SNAPSHOT_ONLY', ...
    'whole_time_cable_tension_certified',false, ...
    'reason','Current EKF/jets/cable are mutually consistent');
if ~pass
    R.reason='EKF/endpoint jets violate current fixed-length taut-cable constraints';
end
end
