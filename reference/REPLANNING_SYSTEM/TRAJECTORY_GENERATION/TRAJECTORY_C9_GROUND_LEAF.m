function [ok,lower]=TRAJECTORY_C9_GROUND_LEAF(P,q0,pad,L,rad,ground,guard)
% All-time sufficient bound for infinite occupied halfspace z<=0.
% pL in conv(P); q(t) in B(q0,pad/L), pU=pL-L*q,
% cable point pL-lambda*L*q, lambda in [0,1].
% Body occupancy: UAV sphere, payload sphere, cable capsule/line segment.
% A failed sufficient bound is UNKNOWN; never claim collision by itself.
assert(isnumeric(P)&&isreal(P)&&size(P,1)==3&& ...
    all(isfinite(P(:)))&&isnumeric(q0)&&isequal(size(q0),[3 1])&& ...
    all(isfinite(q0))&&isfinite(pad)&&pad>=0&&isfinite(L)&&L>0&& ...
    isnumeric(rad)&&numel(rad)==3&&all(isfinite(rad(:)))&& ...
    all(rad(:)>=0)&&isfinite(guard)&&guard>=0, ...
    'TRAJECTORY_C9_GROUND:Input','Invalid taut leaf enclosure.');
assert(isstruct(ground)&&strcmp(ground.type,'ground_halfspace')&& ...
    isequal(ground.normal_world,[0;0;1])&& ...
    isequal(ground.height_m,0)&& ...
    strcmp(ground.occupied_side,'negative')&& ...
    isequal(ground.always_known,true), ...
    'TRAJECTORY_C9_GROUND:Authority', ...
    'Ground must be the defined z=0 occupied half-space.');
minload=min(P(3,:));
uav_bottom=minload-L*q0(3)-pad;
% Cable segments interpolate between endpoints. Direction-cone error is
% <= lambda*pad; using full pad throughout is conservative and safe.
cable_bottom=min(minload,minload-L*q0(3))-pad;
lower=[uav_bottom,minload,cable_bottom]-ground.height_m- ...
    [rad(1),rad(2),rad(3)]-guard;
ok=all(isfinite(lower))&&all(lower>0);
end
