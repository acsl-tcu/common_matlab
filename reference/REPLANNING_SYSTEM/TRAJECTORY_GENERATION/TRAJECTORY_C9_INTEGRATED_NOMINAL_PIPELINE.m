function R=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(request)
% TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE
% One SAME C9 simultaneous-obstacle search, with a single all-time joint
% geometry/tension/thrust oracle and mandatory C7/yaw-C6 and nominal
% 3-axis torque tests. This is NOT a multi-stage trajectory generator.
%
% ALL search candidates are certified exclusively by the existing
% TRAJECTORY_C9_JOINT_FAST_CERTIFICATE inside the one search invocation.
% Its final proof is shared here only because this function itself invoked
% the search and has not mutated its result or the external inputs.
% An arbitrary externally supplied 'certified' struct is NEVER accepted.
%
% CONDITIONAL NOMINAL certification is NOT execution certification:
% continuous-time floating-point enclosure, current EKF-to-HLC tracking,
% closed-loop attainable set, torque saturation, mass uncertainty validity,
% and controller/observer error tube are not proven here. NEVER COMMIT.
%
% All authority, observed shapes, numerical guards, proof/search budgets,
% desired time, and C7/yaw join tolerances are supplied by the caller.
% In production use the currently bound Flight/EKF/HLC authority; this
% function never guesses a future payload mass or a controller limit.
timer=tic;
R=struct('status','UNKNOWN_INTEGRATED_NOT_STARTED', ...
    'nominal_model_complete',false,'safe_to_commit',false, ...
    'actual_HLC_tracking_proven',false, ...
    'closed_loop_actuator_limits_proven',false, ...
    'numerically_directed_rounding_proven',false, ...
    'future_mass_envelope_proven',false, ...
    'candidate_available',false, 'candidate_piece',struct(), ...
    'live_EKF_entry_supplied',false, ...
    'live_EKF_entry_necessary_pass',false, ...
    'live_EKF_entry_status','NOT_SUPPLIED_NOMINAL_ONLY', ...
    'live_EKF_entry_evaluation_ms',0, ...
    'search_status','NOT_CALLED','heading_status','NOT_CALLED', ...
    'torque_status','NOT_CALLED', ...
    'search_result',struct(), 'heading_certificate',struct(), ...
    'nominal_torque_certificate',struct(), ...
    'nominal_torque_reused_from_same_search',false, ...
    'nominal_torque_saved_call_ms',0, ...
    'nominal_torque_reuse_status','NOT_ATTEMPTED', ...
    'joint_proof_reused_from_this_search',false, ...
    'nominal_geometry_tension_thrust_proven',false, ...
    'C7_yaw_C6_all_time_and_join_proven',false, ...
    'nominal_three_axis_torque_proven',false, ...
    'nominal_flat_feedforward_four_within_limits',false, ...
    'nominal_four_input_bounds_N_Nm',NaN(4,2), ...
    'nominal_four_input_headroom_4_N_Nm',NaN(4,1), ...
    'nominal_four_input_status','NOT_EVALUATED', ...
    'candidate_duration_s',NaN, ...
    'proof_calls',0, 'obstacle_count',0, ...
    'total_elapsed_ms',NaN,'search_elapsed_ms',0, ...
    'joint_geometry_force_proof_ms',0, 'separation_planes_ms',0, ...
    'joint_QP_ms',0,'search_other_ms',0, ...
    'qp_outer_ball_groups_tested',0, ...
    'shared_jet_qp_uses',0,'native_torque_batch_qp_uses',0, ...
    'native_torque_batch_qp_ms',0,'native_separator_proposals',0,'certificate_leaf_qp_cuts',0, ...
    'batched_geometry_qp_uses',0,'batched_geometry_qp_ms',0, ...
    'batched_geometry_qp_rows',0, ...
    'body_time_focus_qp_uses',0, ...
    'body_time_outer_guard_uses',0, ...
    'body_time_outer_guard_rejections',0, ...
    'body_time_outer_guard_far_checks',0, ...
    'body_time_outer_guard_near_checks',0, ...
    'body_time_focus_skipped_shape_phase_groups',0, ...
    'body_time_focus_skipped_body_planes',0, ...
    'certificate_leaf_support_calls',0, ...
    'qp_outer_ball_groups_skipped',0, ...
    'cable_envelope_axis_evaluations',0, ...
    'cable_envelope_strictly_improved',0, ...
    'geometry_snapshot_cache_hits',0, ...
    'geometry_snapshot_prepare_ms_total',0, ...
    'inherited_shape_skips_total',0, ...
    'parent_shape_certificates_total',0, ...
    'parent_outer_clearances_total',0, ...
    'heading_join_ms',0,'nominal_torque_ms',0, ...
    'heading_reused_from_same_search',false, ...
    'heading_saved_call_ms',0, ...
    'integration_overhead_ms',0, ...
    'hlc_bridge_requested',false, ...
    'hlc_bridge_status','NOT_BOUND_TO_LIVE_HLC', ...
    'hlc_bridge_elapsed_ms',0, ...
    'hlc_bridge_result',struct(), ...
    'hlc_tube_B_model_conditional_proven',false, ...
    'hlc_actual_execution_proven',false, ...
    'full_time_including_hlc_ms',NaN, ...
    'measurement_scope', ...
    'C9_SEARCH_PLUS_INTERNAL_JOINT_PROOFS_PLUS_C7_YAW_PLUS_NOMINAL_TORQUE', ...
    'excluded_from_timing', ...
    'TRIGGER_SENSOR_FULL_CONTROLLER_SIM_LOGGER__HLC_BRIDGE_ONLY_IF_EXPLICIT', ...
    'failure_detail','');
try
    if ~(isstruct(request)&&isscalar(request)&& ...
            all(isfield(request,{'heading_options','nominal_torque_options', ...
                                 'authority','geometry_options','observed'})))
        R.status='UNKNOWN_REQUIRED_FULL_NOMINAL_OPTIONS_MISSING';
        finish();return
    end
    a=request.authority;
    if ~(isstruct(a)&&isscalar(a)&& ...
            all(isfield(a,{'uav_inertia_kgm2','torque_limits_Nm', ...
                           'payload_mass_kg','thrust_limits_N'})))
        R.status='UNKNOWN_CURRENT_HLC_TORQUE_AUTHORITY_MISSING';
        finish();return
    end
    if ~(isstruct(request.observed))
        R.status='UNKNOWN_OBSERVED_SHAPES_MALFORMED';
        finish();return
    end
    R.obstacle_count=numel(request.observed);
    % An optional real-EKF entry snapshot is a NECESSARY execution gate.
    % The nominal-only fixture API remains usable for offline research,
    % but never returns safe_to_commit. If either live binding field is
    % provided, BOTH are mandatory and the current mass/position/velocity/
    % cable/UAV entry must match before any expensive search begins.
    has_live_state=isfield(request,'current_ekf_state');
    has_live_tol=isfield(request,'entry_tolerances');
    if xor(has_live_state,has_live_tol)
        R.status='UNKNOWN_INCOMPLETE_LIVE_EKF_ENTRY_BINDING';
        finish();return
    end
    if has_live_state
        R.live_EKF_entry_supplied=true;
        te=tic;
        E=TRAJECTORY_C9_ENTRY_STATE_GATE( ...
            request,request.current_ekf_state,request.entry_tolerances);
        R.live_EKF_entry_evaluation_ms=1000*toc(te);
        R.live_EKF_entry_status=E.status;
        R.live_EKF_entry_necessary_pass=E.necessary_conditions_met;
        if ~E.necessary_conditions_met
            R.status='UNKNOWN_CURRENT_EKF_TO_C9_ENTRY_INCONSISTENT';
            R.failure_detail=E.status;
            finish();return
        end
    end
    % Avoid downstream repeated work if a required nominal proof option
    % is missing. Neither section is optional in this integrated entry.
    if ~(isstruct(request.heading_options)&& ...
            isstruct(request.nominal_torque_options))
        R.status='UNKNOWN_PROOF_OPTION_FORMAT';finish();return
    end
    S=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(request);
    R.search_result=S;
    if isfield(S,'duration_13d_native_separator_proposals')
        R.native_separator_proposals= ...
            S.duration_13d_native_separator_proposals;
    end
    if isfield(S,'duration_13d_inherited_shape_skips')
        R.inherited_shape_skips_total=S.duration_13d_inherited_shape_skips;
        R.parent_shape_certificates_total=S.duration_13d_parent_shape_certificates;
        R.parent_outer_clearances_total=S.duration_13d_parent_outer_clearances;
    end
    if isfield(S,'duration_13d_shared_jet_uses')
        R.shared_jet_qp_uses=S.duration_13d_shared_jet_uses;
        if isfield(S,'duration_13d_native_torque_batch_uses')
            R.native_torque_batch_qp_uses= ...
                S.duration_13d_native_torque_batch_uses;
            R.native_torque_batch_qp_ms= ...
                S.duration_13d_native_torque_batch_ms;
        end
        R.certificate_leaf_qp_cuts=S.duration_13d_certificate_leaf_cuts;
        R.certificate_leaf_support_calls= ...
            S.duration_13d_certificate_leaf_support_calls;
    end
    if isfield(S,'duration_13d_body_time_outer_guard_uses')
        R.body_time_outer_guard_uses= ...
            S.duration_13d_body_time_outer_guard_uses;
        R.body_time_outer_guard_rejections= ...
            S.duration_13d_body_time_outer_guard_rejections;
        R.body_time_outer_guard_far_checks= ...
            S.duration_13d_body_time_outer_guard_far_checks;
        R.body_time_outer_guard_near_checks= ...
            S.duration_13d_body_time_outer_guard_near_checks;
    end
    if isfield(S,'duration_13d_batched_qp_uses')
        R.batched_geometry_qp_uses=S.duration_13d_batched_qp_uses;
        R.batched_geometry_qp_ms=S.duration_13d_batched_qp_ms;
        R.batched_geometry_qp_rows=S.duration_13d_batched_qp_rows;
    end
    if isfield(S,'duration_13d_body_time_focus_qp_uses')
        R.body_time_focus_qp_uses=S.duration_13d_body_time_focus_qp_uses;
        R.body_time_focus_skipped_shape_phase_groups= ...
            S.duration_13d_body_time_focus_skipped_shape_phase_groups;
        R.body_time_focus_skipped_body_planes= ...
            S.duration_13d_body_time_focus_skipped_body_planes;
    end
    R.search_status=S.status;
    R.search_elapsed_ms=S.elapsed_ms;
    R.proof_calls=S.independent_proof_calls;
    R.joint_geometry_force_proof_ms=S.independent_proof_time_total_ms;
    R.separation_planes_ms=S.plane_construction_time_total_ms;
    R.joint_QP_ms=S.joint_qp_time_total_ms;
    if isfield(S,'duration_13d_qp_outer_ball_groups_tested')
        R.qp_outer_ball_groups_tested=S.duration_13d_qp_outer_ball_groups_tested;
        R.qp_outer_ball_groups_skipped=S.duration_13d_qp_outer_ball_groups_skipped;
    end
    if isfield(S,'final_certificate') && isstruct(S.final_certificate)
        C=S.final_certificate;
        if isfield(C,'cable_lambda_envelope_axis_evaluations')
            R.cable_envelope_axis_evaluations=C.cable_lambda_envelope_axis_evaluations;
            R.cable_envelope_strictly_improved=C.cable_lambda_envelope_strictly_improved;
        end
    end
    R.geometry_snapshot_cache_hits=S.geometry_snapshot_cache_hits;
    R.geometry_snapshot_prepare_ms_total=S.geometry_snapshot_prepare_ms_total;
    R.search_other_ms=max(0,R.search_elapsed_ms- ...
        (R.joint_geometry_force_proof_ms+R.separation_planes_ms+R.joint_QP_ms));
    if ~S.candidate_available
        R.status='UNKNOWN_C9_SEARCH_DID_NOT_CERTIFY_ALL_TIME';
        R.failure_detail=S.status;
        finish();return
    end
    % Never rerun the expensive joint proof for the SAME immutable
    % candidate already certified inside this search invocation.
    P=S.final_certificate;
    if ~(isstruct(P)&&isfield(P,'certified')&& ...
            isequal(P.certified,true)&& ...
            isequal(P.certified_continuous_geometry,true)&& ...
            isequal(P.certified_continuous_tension,true)&& ...
            isequal(P.certified_continuous_thrust,true)&& ...
            isequal(P.authority_snapshot,a)&& ...
            ~P.safe_to_commit&& ...
            isequal(P.trajectory_phase,'f')&& ...
            isequal(P.ground_checked, ...
                TRAJECTORY_GROUND_SCOPE(request.geometry_options))&& ...
            ~S.safe_to_commit)
        R.status='UNKNOWN_SEARCH_PROOF_BINDING_OR_SCOPE';
        finish();return
    end
    R.joint_proof_reused_from_this_search=true;
    R.nominal_geometry_tension_thrust_proven=true;
    piece=S.candidate_piece;
    % In 13D mode the WHOLE POINT is that the certified candidate may
    % have a different physical duration from the initial request.
    % Bind the accepted duration to THIS search's immutable piece and
    % reported duration; do not silently require the initial duration.
    variable_duration=false;
    if isfield(request,'search_options') && ...
            isstruct(request.search_options) && ...
            isfield(request.search_options,'enable_13d_variable_time_joint_search')
        variable_duration=isequal( ...
            request.search_options.enable_13d_variable_time_joint_search,1);
    end
    mode_25d=false;
    if isfield(request,'search_options')&&isstruct(request.search_options)&& ...
            isfield(request.search_options,'enable_degree27_25d_joint_search')
        mode_25d=isequal(request.search_options.enable_degree27_25d_joint_search,1);
    end
    variable_duration=variable_duration||mode_25d;
    duration_identity=isequal(piece.duration_s,request.duration_s);
    if variable_duration
        duration_identity=isfield(S,'duration_s') && ...
            isequal(piece.duration_s,S.duration_s) && ...
            isfield(request,'flight_interval_s') && ...
            isnumeric(request.flight_interval_s) && ...
            numel(request.flight_interval_s)==2 && ...
            piece.t0_s>=request.flight_interval_s(1) && ...
            piece.t0_s+piece.duration_s<=request.flight_interval_s(2);
    end
    if ~(isstruct(piece)&&isscalar(piece)&& ...
            isfield(piece,'control_points_m')&& ...
            (isequal(size(piece.control_points_m),[3,24])&&~mode_25d|| ...
             isequal(size(piece.control_points_m),[3,28])&&mode_25d)&& ...
            isfield(piece,'start_jets')&&isfield(piece,'end_jets')&& ...
            isequal(piece.start_jets,request.start_jets)&& ...
            isequal(piece.end_jets,request.end_jets)&& ...
            isequal(piece.t0_s,request.t0_s)&& ...
            isnumeric(piece.duration_s)&&isscalar(piece.duration_s)&& ...
            isfinite(piece.duration_s)&&piece.duration_s>0&& ...
            duration_identity)
        R.status='UNKNOWN_INTERNAL_CANDIDATE_IDENTITY';
        finish();return
    end
    R.candidate_duration_s=piece.duration_s;
    reuse_heading=false;
    if mode_25d && isfield(S,'duration_25d_heading_proof_bundle')
        HB=S.duration_25d_heading_proof_bundle;
        if isstruct(HB)&&isscalar(HB)&& ...
                all(isfield(HB,{'piece','authority','options', ...
                                'proof','proof_call_ms'}))&& ...
                isequaln(HB.piece,piece)&& ...
                isequaln(HB.authority,a)&& ...
                isequaln(HB.options,request.heading_options)&& ...
                isstruct(HB.proof)&&isscalar(HB.proof)&& ...
                isfield(HB.proof,'certified')&& ...
                isequal(HB.proof.certified,true)&& ...
                isfinite(HB.proof_call_ms)&&HB.proof_call_ms>=0
            reuse_heading=true;
        end
    end
    if reuse_heading
        H=HB.proof;
        R.heading_reused_from_same_search=true;
        R.heading_saved_call_ms=HB.proof_call_ms;
        R.heading_join_ms=0;
    else
        tHeading=tic;
        H=TRAJECTORY_C9_UAV_C7_YAW_C6_AUDIT( ...
            piece,a,request.heading_options);
        R.heading_join_ms=1000*toc(tHeading);
    end
    R.heading_certificate=H;
    R.heading_status=H.status;
    R.C7_yaw_C6_all_time_and_join_proven= ...
        H.certified&&H.continuous_horizontal_heading_proven&& ...
        H.derived_uav_C7_regular&&H.derived_yaw_C6_regular;
    if ~R.C7_yaw_C6_all_time_and_join_proven
        R.status='UNKNOWN_C7_YAW_C6_OR_JOIN_NOT_CERTIFIED';
        R.failure_detail=H.status;
        finish();return
    end
    % The 13D search has ALREADY called the expensive all-time torque
    % oracle for THIS nominal C9, using THIS authority and THESE options.
    % Reuse only the authenticated same-invocation evidence and only
    % after exact binding checks. Otherwise re-run the unchanged oracle.
    % This reduces duplicate work without skipping any mandatory proof.
    reuse_allowed=true;
    if isfield(request,'search_options') && ...
            isstruct(request.search_options) && ...
            isfield(request.search_options, ...
                    'enable_13d_reuse_nominal_torque_certificate')
        sw=request.search_options.enable_13d_reuse_nominal_torque_certificate;
        assert((islogical(sw)||isnumeric(sw))&&isscalar(sw)&& ...
            isreal(sw)&&isfinite(double(sw))&&any(double(sw)==[0 1]), ...
            'C9_INTEGRATED:TorqueReuseSwitch','Torque proof reuse must be 0/1');
        reuse_allowed=logical(sw);
    end
    use_evidence=false;
    if reuse_allowed && variable_duration && ...
            (isfield(S,'duration_13d_nominal_torque_proof_bundle')|| ...
             isfield(S,'duration_25d_nominal_torque_proof_bundle'))
        if mode_25d && isfield(S,'duration_25d_nominal_torque_proof_bundle')
            B=S.duration_25d_nominal_torque_proof_bundle;
        elseif isfield(S,'duration_13d_nominal_torque_proof_bundle')
            B=S.duration_13d_nominal_torque_proof_bundle;
        else
            B=struct();
        end
        if isstruct(B)&&isscalar(B)&& ...
                all(isfield(B,{'piece','authority','options','proof','proof_call_ms'}))&& ...
                isequaln(B.piece,piece)&&isequaln(B.authority,a)&& ...
                isfield(request,'torque_options')&& ...
                isequaln(B.options,request.torque_options)&& ...
                isequaln(B.options,request.nominal_torque_options)&& ...
                isstruct(B.proof)&&isscalar(B.proof)&& ...
                isfield(B.proof,'conditional_nominal_all_time_torque_proven')&& ...
                isfield(B.proof,'status')&& ...
                isequal(B.proof.conditional_nominal_all_time_torque_proven,true)&& ...
                isfield(B.proof,'payload_mass_snapshot_kg')&& ...
                isequal(B.proof.payload_mass_snapshot_kg,a.payload_mass_kg)&& ...
                isfield(B.proof,'safe_to_commit')&&~B.proof.safe_to_commit&& ...
                ((mode_25d&& ...
                  isfield(S,'duration_25d_conditional_nominal_torque_proven')&& ...
                  isequal(S.duration_25d_conditional_nominal_torque_proven,true)&& ...
                  isfield(S,'duration_25d_nominal_torque_status')&& ...
                  isequal(B.proof.status,S.duration_25d_nominal_torque_status))|| ...
                 (~mode_25d&& ...
                  isfield(S,'duration_13d_conditional_nominal_torque_proven')&& ...
                  isequal(S.duration_13d_conditional_nominal_torque_proven,true)&& ...
                  isfield(S,'duration_13d_nominal_torque_status')&& ...
                  isequal(B.proof.status,S.duration_13d_nominal_torque_status)))
            use_evidence=true;
        end
    end
    if use_evidence
        Q=B.proof;
        R.nominal_torque_reused_from_same_search=true;
        R.nominal_torque_reuse_status='EXACT_C9_AUTHORITY_OPTIONS_BOUND';
        R.nominal_torque_saved_call_ms=B.proof_call_ms;
        R.nominal_torque_ms=0; % No duplicate second oracle call.
    else
        tTorque=tic;
        Q=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL( ...
            piece,a,request.nominal_torque_options);
        R.nominal_torque_ms=1000*toc(tTorque);
        if ~reuse_allowed
            R.nominal_torque_reuse_status='EXPLICITLY_DISABLED_AB_BASELINE';
        else
            R.nominal_torque_reuse_status='NO_EXACT_MATCH_RECOMPUTED';
        end
    end
    R.nominal_torque_certificate=Q;
    R.torque_status=Q.status;
    R.nominal_three_axis_torque_proven= ...
        Q.conditional_nominal_all_time_torque_proven&& ...
        ~Q.actual_HLC_tracking_proven&&~Q.safe_to_commit;
    if ~R.nominal_three_axis_torque_proven
        R.status='UNKNOWN_NOMINAL_3_AXIS_TORQUE_NOT_CERTIFIED';
        R.failure_detail=Q.status;
        finish();return
    end
    % Assemble the exact SAME candidate's existing joint-force and
    % nominal-torque ALL-TIME sufficient bounds. This uses no point
    % samples, no extra proof oracle and no additional numerical guard.
    % The raw physical feedforward thrust/torques are the IDEAL-NOMINAL
    % quantities; equality to the actual HLC beta2\rhs and nonzero
    % tracking input are separate obligations. Never grant COMMIT here.
    if ~(isfield(P,'thrust_lower_bound_N')&& ...
            isfield(P,'thrust_upper_bound_N')&& ...
            isfield(Q,'torque_bounds_Nm')&& ...
            isfield(Q,'payload_mass_snapshot_kg')&& ...
            isequal(double(Q.payload_mass_snapshot_kg), ...
                double(a.payload_mass_kg))&& ...
            isequal(size(Q.torque_bounds_Nm),[3 2])&& ...
            isnumeric(P.thrust_lower_bound_N)&& ...
            isnumeric(P.thrust_upper_bound_N)&& ...
            isscalar(P.thrust_lower_bound_N)&& ...
            isscalar(P.thrust_upper_bound_N))
        R.status='UNKNOWN_NOMINAL_FOUR_INPUT_PROOF_BINDING';
        finish();return
    end
    full_interval=[ ...
        double([P.thrust_lower_bound_N,P.thrust_upper_bound_N]); ...
        double(Q.torque_bounds_Nm)];
    if ~isequal(size(full_interval),[4 2])|| ...
            any(~isfinite(full_interval(:)))|| ...
            any(full_interval(:,1)>full_interval(:,2))
        R.status='UNKNOWN_NOMINAL_FOUR_INPUT_BAD_INTERVAL';
        finish();return
    end
    live_lower=[double(a.thrust_limits_N(1)); ...
                double(a.torque_limits_Nm(:,1))];
    live_upper=[double(a.thrust_limits_N(2)); ...
                double(a.torque_limits_Nm(:,2))];
    I=TRAJECTORY_C9_HLC_NOMINAL_FOUR_INPUT_GATE( ...
        live_lower,live_upper,full_interval);
    R.nominal_four_input_status=['FLAT_FEEDFORWARD_ONLY_' I.status];
    R.nominal_four_input_bounds_N_Nm=I.conditional_raw_input_enclosure;
    R.nominal_four_input_headroom_4_N_Nm=min([ ...
        full_interval(:,1)-live_lower, ...
        live_upper-full_interval(:,2)],[],2);
    R.nominal_flat_feedforward_four_within_limits= ...
        I.conditional_headroom_all_positive;
    if ~R.nominal_flat_feedforward_four_within_limits
        R.status='UNKNOWN_NOMINAL_FLAT_FEEDFORWARD_LIMITS_NOT_PROVEN';
        R.failure_detail=I.status;
        finish();return
    end
    R.nominal_model_complete=true;
    R.candidate_available=true;
    R.candidate_piece=piece;
    R.status='CONDITIONAL_INTEGRATED_C9_C7_YAW_TORQUE_NOMINAL__HLC_PENDING';
    % Explicit optional bridge to the LIVE HLC proof interface. Never
    % invent a controller/EKF object or a model-error enclosure offline.
    % Not an extra planning stage and cannot authorize trajectory COMMIT.
    if isfield(request,'live_hlc_execution')
        bridge_live_hlc();
    end
catch ME
    R.status='UNKNOWN_INTEGRATED_EXCEPTION';
    R.failure_detail=[ME.identifier ' | ' ME.message];
end
finish();


    function bridge_live_hlc()
        R.hlc_bridge_requested=true;
        tBridge=tic;
        bridgeClockCleanup=onCleanup(@()set_hlc_elapsed(tBridge)); %#ok<NASGU>
        try
            L=request.live_hlc_execution;
            if ~isstruct(L)||~isscalar(L)|| ...
                    ~all(isfield(L,{'binding','agent','time_s','proof'}))|| ...
                    ~isstruct(L.proof)||~isscalar(L.proof)
                R.hlc_bridge_status='UNKNOWN_LIVE_HLC_BINDING_INCOMPLETE';
                return
            end
            if ~R.live_EKF_entry_supplied || ...
                    ~R.live_EKF_entry_necessary_pass
                R.hlc_bridge_status='UNKNOWN_LIVE_HLC_NEEDS_EKF_ENTRY_CERT';
                return
            end
            proof=L.proof;
            % A certified nominal input bound belongs to THIS current C9
            % candidate; the caller may not silently substitute another.
            if isfield(proof,'nominal_preclamp_input_interval_4x2') && ...
                    ~isequaln(proof.nominal_preclamp_input_interval_4x2, ...
                              R.nominal_four_input_bounds_N_Nm)
                R.hlc_bridge_status='UNKNOWN_LIVE_HLC_NOMINAL_INPUT_IDENTITY';
                return
            end
            proof.nominal_preclamp_input_interval_4x2= ...
                R.nominal_four_input_bounds_N_Nm;
            % A supplied corridor must cover EXACTLY this candidate,
            % currently observed IDs and physical authority. The bridge
            % itself rechecks all corridor leaves and execution tube.
            if isfield(proof,'shared_corridor')
                C=proof.shared_corridor;
                if ~isstruct(C)||~isscalar(C)|| ...
                        ~all(isfield(C,{'certified','guide_piece', ...
                            'authority','obstacle_ids','radii'}))|| ...
                        ~isequal(C.certified,true)|| ...
                        ~isequaln(C.guide_piece,piece)|| ...
                        ~isequaln(C.authority,a)|| ...
                        ~isequaln(C.radii,request.radii)
                    R.hlc_bridge_status='UNKNOWN_LIVE_HLC_CORRIDOR_BINDING_MISMATCH';
                    return
                end
                observedIDs=reshape([request.observed.id],1,[]);
                if ~isequal(sort(double(C.obstacle_ids(:))), ...
                             sort(double(observedIDs(:))))
                    R.hlc_bridge_status='UNKNOWN_LIVE_HLC_OBSTACLE_SET_CHANGED';
                    return
                end
            end
            E=TRAJECTORY_C9_HLC_EXECUTION_PROOF_BRIDGE( ...
                L.binding,L.agent,L.time_s,proof);
            R.hlc_bridge_result=E;
            R.hlc_bridge_status=E.status;
            % The exact same live current EKF mass/limits must be bound;
            % no asynchronous sampled estimate may masquerade as the
            % model's mass used to produce the candidate C9 certificate.
            lower=[double(a.thrust_limits_N(1)); ...
                   double(a.torque_limits_Nm(:,1))];
            upper=[double(a.thrust_limits_N(2)); ...
                   double(a.torque_limits_Nm(:,2))];
            if ~E.live_HLC_verified || ...
                    ~isequaln(E.latest_EKF_mass_kg,a.payload_mass_kg)|| ...
                    ~isequaln(double(E.input_lower(:)),lower)|| ...
                    ~isequaln(double(E.input_upper(:)),upper)
                R.hlc_bridge_status='UNKNOWN_LIVE_HLC_AUTHORITY_SNAPSHOT_CHANGED';
                return
            end
            % The bridge grants only MODEL-CONDITIONAL lemmas. Nominal A,
            % physical C and missing external enclosures never grant B.
            if isfield(E,'model_only_conditional_proven') && ...
                    isequal(E.model_only_conditional_proven,true) && ...
                    strcmp(E.guarantee_tier,'MODEL_TUBE') && ...
                    isequal(E.model_execution_tube_enabled,1)
                R.hlc_tube_B_model_conditional_proven=true;
            end
        catch ME
            R.hlc_bridge_status=['UNKNOWN_LIVE_HLC_BRIDGE_' ME.identifier];
        end
        R.hlc_bridge_elapsed_ms=1000*toc(tBridge);
        R.hlc_actual_execution_proven=false;
        R.safe_to_commit=false;
    end

    function set_hlc_elapsed(t0)
        R.hlc_bridge_elapsed_ms=1000*toc(t0);
    end

    function finish()
        R.total_elapsed_ms=1000*toc(timer);
        R.full_time_including_hlc_ms=R.total_elapsed_ms;
        R.integration_overhead_ms=max(0,R.total_elapsed_ms- ...
            R.search_elapsed_ms-R.heading_join_ms- ...
            R.nominal_torque_ms-R.hlc_bridge_elapsed_ms);
        % This API always returns candidates only. No physical controller
        % commit / HLC execution certificate exists here.
        R.safe_to_commit=false;
    end
end
