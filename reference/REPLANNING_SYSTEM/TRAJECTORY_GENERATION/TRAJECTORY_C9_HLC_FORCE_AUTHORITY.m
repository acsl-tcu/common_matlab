classdef TRAJECTORY_C9_HLC_FORCE_AUTHORITY
    % Source-verified FOUR HLC input clamps + current estimator/parameter values.
    % No guessed physical limits or frozen payload-mass fallback.
    % HLC source is inspected ONCE before Flight. If its saturation
    % expression changes, binding FAILS CLOSED rather than guessing bounds.
    % The existing controller/estimator/plant are never modified.
    methods (Static)
        function [limits,source_file]=source_limits()
            % Backward-compatible thrust-only API. NEVER a hard-coded 20 N.
            [lo,hi,source_file]= ...
                TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
            limits=[lo(1),hi(1)];
        end
        function [lower,upper,source_file]=source_input_limits()
            % Bind to the currently resolved HLC class file, before Flight.
            source_file=which('HLC_SUSPENDED_LOAD');
            assert(~isempty(source_file)&&isfile(source_file), ...
                'TRAJECTORY_C9_HLC_AUTHORITY:MissingHLCSource', ...
                'The actual HLC_SUSPENDED_LOAD source is required.');
            txt=fileread(source_file);
            assert(~isempty(regexp(txt, ...
                'classdef\s+HLC_SUSPENDED_LOAD\s*<\s*handle','once')), ...
                'TRAJECTORY_C9_HLC_AUTHORITY:SourceIdentity', ...
                'The resolved file is not the HLC class implementation.');
            [lower,upper]= ...
                TRAJECTORY_C9_HLC_FORCE_AUTHORITY.parse_input_limits_source(txt);
        end
        function [lower,upper]=parse_input_limits_source(txt)
            % Pure STRICT source recognizer, usable by independent audit.
            % Any changed or ambiguous HLC clamp requires code review.
            % This is necessary because HLC publishes actuator OUTPUTS but
            % has no public property exposing its internal saturation bounds.
            assert(ischar(txt)||isstring(txt), ...
                'TRAJECTORY_C9_HLC_AUTHORITY:SourceText', ...
                'The HLC source must be text.');
            txt=char(txt);
            assert(~contains(txt,'%{')&&~contains(txt,'%}'), ...
                'TRAJECTORY_C9_HLC_AUTHORITY:BlockComment', ...
                'Block comments require re-review of the HLC source.');
            % The current HLC has no quoted percent signs or block comments.
            % If its syntax changes, reject instead of guessing the bounds.
            active=regexprep(txt,'(?m)%[^\r\n]*','');
            lhs='obj\s*\.\s*result\s*\.\s*input\s*=';
            assignments=regexp(active,lhs,'match');
            token=regexp(active,[lhs '\s*\[([^\]]*)\]\s*;'], ...
                'tokens');
            assert(numel(assignments)==1&&numel(token)==1, ...
                'TRAJECTORY_C9_HLC_AUTHORITY:UnrecognizedHLCClamp', ...
                'The active controller must have one four-channel clamp assignment.');
            channels=regexp(token{1}{1},';','split');
            if ~isempty(channels)&&isempty(strtrim(channels{end}))
                channels(end)=[];
            end
            assert(numel(channels)==4, ...
                'TRAJECTORY_C9_HLC_AUTHORITY:InputChannels', ...
                'The real HLC must clamp thrust and all 3 torques.');
            number='([+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?)';
            lower=zeros(4,1);upper=zeros(4,1);
            for k=1:4
                pat=['^\s*max\(\s*' number '\s*,\s*min\(\s*' ...
                    number '\s*,\s*tmp\(\s*' num2str(k) ...
                    '\s*\)\s*\)\s*\)\s*$'];
                m=regexp(strtrim(channels{k}),pat,'tokens','once');
                assert(~isempty(m)&&numel(m)==2, ...
                    'TRAJECTORY_C9_HLC_AUTHORITY:UnrecognizedHLCClamp', ...
                    'Unrecognized clamp/order in the active HLC source.');
                lower(k)=str2double(m{1});upper(k)=str2double(m{2});
            end
            assert(all(isfinite([lower;upper]))&& ...
                all(lower<upper)&&lower(1)>=0, ...
                'TRAJECTORY_C9_HLC_AUTHORITY:InvalidHLCClamp', ...
                'Read HLC bounds are not physically valid.');
        end
        function B=bind(agent,opts)
            % Call before Flight, only after the real HLC was constructed.
            assert(isstruct(opts)&&isscalar(opts)&&all(isfield(opts, ...
                {'gravity_world_mps2','minimum_tension_N', ...
                 'acceleration_guard_mps2'})), ...
                'TRAJECTORY_C9_HLC_AUTHORITY:Physics', ...
                'Explicit externally-authoritative gravity and tension guards required.');
            has_controller=(isstruct(agent.controller)&& ...
                isfield(agent.controller,'hlc_suspended'))|| ...
                (isobject(agent.controller)&& ...
                isprop(agent.controller,'hlc_suspended'));
            assert(has_controller && ...
                isa(agent.controller.hlc_suspended,'HLC_SUSPENDED_LOAD'), ...
                'TRAJECTORY_C9_HLC_AUTHORITY:ActiveController', ...
                'The original HLC_SUSPENDED_LOAD must be active.');
            [input_lower,input_upper,source_file]= ...
                TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
            limits=[input_lower(1),input_upper(1)];
            g=double(opts.gravity_world_mps2(:));
            assert(isequal(size(g),[3 1])&&all(isfinite(g))&&norm(g)>0, ...
                'TRAJECTORY_C9_HLC_AUTHORITY:Gravity','Valid external world gravity required.');
            for k={'minimum_tension_N','acceleration_guard_mps2'}
                v=opts.(k{1});
                assert(isnumeric(v)&&isreal(v)&&isscalar(v)&& ...
                    isfinite(v)&&v>=0, ...
                    'TRAJECTORY_C9_HLC_AUTHORITY:Guards', ...
                    'Guards must come from external physics authority.');
            end
            controller=agent.controller.hlc_suspended;
            assert(isstruct(controller.param)&& ...
                isfield(controller.param,'dt')&& ...
                isscalar(controller.param.dt)&& ...
                isfinite(controller.param.dt)&&controller.param.dt>0, ...
                'TRAJECTORY_C9_HLC_AUTHORITY:ControllerDT','Real HLC dt required.');
            % Take the gains from the actual HLC instance (not a fixture
            % tuned here). A change requires explicit rebind/revalidation.
            gain_fields={'F1','F2','F3','F4'};
            gain_dims=[2 6 6 2];
            gains=struct();
            for k=1:numel(gain_fields)
                name=gain_fields{k};
                assert(isfield(controller.param,name), ...
                    'TRAJECTORY_C9_HLC_AUTHORITY:MissingLiveGains', ...
                    'Real HLC controller gains must be present.');
                v=controller.param.(name);
                assert(isnumeric(v)&&isreal(v)&& ...
                    numel(v)==gain_dims(k)&&all(isfinite(v(:))), ...
                    'TRAJECTORY_C9_HLC_AUTHORITY:InvalidLiveGains', ...
                    'Actual HLC gain dimensions/values are invalid.');
                gains.(name)=double(v(:));
            end
            B=struct('limits_N',limits,'source_file',source_file, ...
                'input_lower',input_lower,'input_upper',input_upper, ...
                'controller_gains',gains, ...
                'source_bytes',dir(source_file), ...
                'hlc_handle',controller,'parameter_handle',agent.parameter, ...
                'sample_dt_s',double(controller.param.dt), ...
                'gravity_world_mps2',g, ...
                'minimum_tension_N',double(opts.minimum_tension_N), ...
                'acceleration_guard_mps2',double(opts.acceleration_guard_mps2), ...
                'authority_policy','REAL_HLC_FOUR_CLAMPS_AND_GAINS__EACH_TICK_EKF_MASS', ...
                'safe_to_commit',false);
        end
        function S=current(B,agent,time)
            % Lightweight per-tick capture, after estimator/state-manager.
            % No file read, geometry search or source scan on the Flight tick.
            S=struct('valid',false,'status','UNKNOWN_NOT_CAPTURED', ...
                'safe_to_commit',false,'authority',struct(), ...
                'tick_time_s',NaN,'estimated_payload_mass_kg',NaN, ...
                'hlc_payload_mass_kg',NaN,'thrust_limits_N',B.limits_N, ...
                'torque_limits_Nm',[B.input_lower(2:4),B.input_upper(2:4)], ...
                'input_limits_lower',B.input_lower, ...
                'input_limits_upper',B.input_upper, ...
                'mass_consistent_with_hlc',false, ...
                'policy','CURRENT_ESTIMATOR_MASS__NO_CACHED_MASS');
            has_phase=(isstruct(agent)&&isfield(agent,'cha'))|| ...
                (isobject(agent)&&isprop(agent,'cha'));
            if ~has_phase || ~strcmp(char(agent.cha),'f')
                S.status='UNKNOWN_NOT_FLIGHT';return
            end
            if ~isequal(agent.controller.hlc_suspended,B.hlc_handle)|| ...
                    ~isequal(agent.parameter,B.parameter_handle)
                S.status='UNKNOWN_ACTIVE_HLC_CHANGED';return
            end
            if ~strcmpi(which('HLC_SUSPENDED_LOAD'),B.source_file)
                S.status='UNKNOWN_HLC_SOURCE_BINDING_CHANGED';return
            end
            cp=agent.controller.hlc_suspended.param;
            if ~isstruct(cp)||~isfield(cp,'dt')|| ...
                    ~isequal(double(cp.dt),B.sample_dt_s)
                S.status='UNKNOWN_HLC_DT_CHANGED';return
            end
            for k={'F1','F2','F3','F4'}
                name=k{1};
                if ~isfield(cp,name)
                    S.status='UNKNOWN_HLC_GAINS_CHANGED';return
                end
                live_gain=cp.(name);
                if ~isequal(double(live_gain(:)),B.controller_gains.(name))
                    S.status='UNKNOWN_HLC_GAINS_CHANGED';return
                end
            end
            has_time=(isstruct(time)&&isfield(time,'t')&&isfield(time,'dt'))|| ...
                (isobject(time)&&isprop(time,'t')&&isprop(time,'dt'));
            if ~(has_time&& ...
                 isscalar(time.t)&&isfinite(time.t)&& ...
                 isequal(double(time.dt),B.sample_dt_s))
                S.status='UNKNOWN_FLIGHT_TIME_OR_DT';return
            end
            S.tick_time_s=double(time.t);
            % The state manager updates this very estimator result BEFORE
            % the HLC; never read the takeoff preset or a cached estimate.
            state=agent.estimator.result.state;
            if isstruct(state)
                if ~isfield(state,'mL'),S.status='UNKNOWN_MISSING_EKF_MASS';return;end
                mL=state.mL;
            else
                if ~isprop(state,'mL'),S.status='UNKNOWN_MISSING_EKF_MASS';return;end
                mL=state.mL;
            end
            if ~(isnumeric(mL)&&isreal(mL)&&isscalar(mL)&& ...
                    isfinite(mL)&&mL>0)
                S.status='UNKNOWN_INVALID_CURRENT_EKF_MASS';return
            end
            S.estimated_payload_mass_kg=double(mL);
            p=double(agent.parameter.get( ...
                ["mass","cableL","gravity","loadmass","jx","jy","jz"]));
            if numel(p)~=7||~all(isfinite(p(:)))|| ...
                    any(p<=0)
                S.status='UNKNOWN_LIVE_PARAMETER_VALUES';return
            end
            p=reshape(p,1,7);
            S.hlc_payload_mass_kg=p(4);
            S.mass_consistent_with_hlc=isequal(double(mL),p(4));
            if ~S.mass_consistent_with_hlc
                S.status='UNKNOWN_EKF_HLC_MASS_MISMATCH';return
            end
            % This is equality of the same physical gravity magnitude,
            % allowing only a machine-rounding comparison, not a safety margin.
            grav=norm(B.gravity_world_mps2);
            if abs(p(3)-grav)>32*eps(max([1,abs(p(3)),grav]))
                S.status='UNKNOWN_HLC_GRAVITY_CHANGED';return
            end
            A=struct('cable_length_m',p(2), ...
                'payload_mass_kg',double(mL),'uav_mass_kg',p(1), ...
                'gravity_world_mps2',B.gravity_world_mps2, ...
                'thrust_limits_N',reshape(B.limits_N,1,2), ...
                'minimum_tension_N',B.minimum_tension_N, ...
                'acceleration_guard_mps2',B.acceleration_guard_mps2, ...
                'uav_inertia_kgm2',p(5:7), ...
                'torque_limits_Nm',[B.input_lower(2:4),B.input_upper(2:4)], ...
                'input_limits',struct('lower',B.input_lower, ...
                                      'upper',B.input_upper), ...
                'hlc_gains',B.controller_gains, ...
                'hlc_dt_s',B.sample_dt_s);
            S.authority=A;
            S.status='CURRENT_FLIGHT_EKF_MASS_AND_REAL_HLC_4_INPUT_LIMITS';
            S.valid=true;
        end
        function same=same_force_authority(previous,current)
            % On any changed mass/physical bound, old nominal certificates
            % may NOT be reused. This is intentionally an exact comparison.
            same=previous.valid&&current.valid&& ...
                isequaln(previous.authority,current.authority);
        end
        function H=certified_headroom(certificate,authority)
            % Report only sufficient all-time guaranteed magnitude margin.
            % Never enlarge or silently shrink the true HLC feasible range.
            H=struct('certified',false,'lower_headroom_N',NaN, ...
                'upper_headroom_N',NaN,'minimum_headroom_N',NaN, ...
                'source','INDEPENDENT_C9_ALL_TIME_THRUST_BOUNDS');
            if ~isstruct(certificate)|| ...
                    ~isfield(certificate,'certified_continuous_thrust')|| ...
                    ~certificate.certified_continuous_thrust|| ...
                    ~isfield(certificate,'thrust_lower_bound_N')|| ...
                    ~isfield(certificate,'thrust_upper_bound_N')
                return
            end
            limits=double(authority.thrust_limits_N(:));
            bound_lower=double(certificate.thrust_lower_bound_N);
            bound_upper=double(certificate.thrust_upper_bound_N);
            if ~(isscalar(bound_lower)&&isscalar(bound_upper)&& ...
                    isfinite(bound_lower)&&isfinite(bound_upper)&& ...
                    bound_lower<=bound_upper)
                return
            end
            H.lower_headroom_N=bound_lower-limits(1);
            H.upper_headroom_N=limits(2)-bound_upper;
            H.minimum_headroom_N=min(H.lower_headroom_N,H.upper_headroom_N);
            H.certified=isfinite(H.minimum_headroom_N)&&H.minimum_headroom_N>=0;
        end
    end
end
