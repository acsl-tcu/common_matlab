function [ineq,details]=TRAJECTORY_C7_NLP_FEASIBILITY(U,L,duration_s,limits,leaf_maps)
%TRAJECTORY_C7_NLP_FEASIBILITY Exact whole-time derivative hull inequalities.
% Given degree-23 UAV and payload Bernstein controls, impose
% norm(P^(k)_i)<= caller-owned limit(k), k=1..6, on EACH de Casteljau leaf.
% These are SUFFICIENT for the exact reference polynomial for every t,
% NOT actuator, cable-tension or HLC-tracking constraints.
% No fake flight constants; the external authority owns each limit.
assert(isnumeric(U)&&isreal(U)&&isequal(size(U),[3 24])&&all(isfinite(U(:)))&& ...
    isnumeric(L)&&isreal(L)&&isequal(size(L),[3 24])&&all(isfinite(L(:)))&& ...
    isnumeric(duration_s)&&isscalar(duration_s)&& ...
    isfinite(duration_s)&&duration_s>0, ...
    'TRAJECTORY_NLP_FEASIBILITY:Controls', ...
    'Need finite 3x24 controls and positive live duration.');
assert(isstruct(limits)&&isscalar(limits)&& ...
    all(isfield(limits,{'uav','payload'})), ...
    'TRAJECTORY_NLP_FEASIBILITY:Limits', ...
    'UAV and payload reference derivative limits are caller-owned.');
for name={'uav','payload'}
    q=limits.(name{1});
    assert(isstruct(q)&&isscalar(q)&&isfield(q,'derivative_norm_max')&& ...
        isnumeric(q.derivative_norm_max)&& ...
        numel(q.derivative_norm_max)==6&& ...
        all(isfinite(q.derivative_norm_max(:)))&& ...
        all(q.derivative_norm_max(:)>=0), ...
        'TRAJECTORY_NLP_FEASIBILITY:Limits', ...
        'Need six nonnegative external derivative limits per body.');
end
assert(iscell(leaf_maps)&&~isempty(leaf_maps), ...
    'TRAJECTORY_NLP_FEASIBILITY:Leaves','Require exact leaf maps.');
count=numel(leaf_maps);
for j=1:count
    assert(isnumeric(leaf_maps{j})&& ...
        isequal(size(leaf_maps{j}),[24 24])&& ...
        all(isfinite(leaf_maps{j}(:))), ...
        'TRAJECTORY_NLP_FEASIBILITY:Map','Invalid Bernstein leaf map.');
end
% 23+22+21+20+19+18 = 123 inequalities per leaf per body.
ineq=zeros(246*count,1);i=0;maxratio=0;
for leaf=1:count
    T=duration_s/count;
    M=leaf_maps{leaf};
    for b=1:2
        if b==1
            D=U*M;bound=double(limits.uav.derivative_norm_max(:));
        else
            D=L*M;bound=double(limits.payload.derivative_norm_max(:));
        end
        for k=1:6
            D=((24-k)/T)*diff(D,1,2);
            val=sqrt(sum(D.^2,1)).';
            N=numel(val);
            ineq(i+(1:N))=val-bound(k);
            i=i+N;
            if bound(k)>0
                maxratio=max(maxratio,max(val/bound(k)));
            elseif any(val>0)
                maxratio=Inf;
            end
        end
    end
end
assert(i==numel(ineq),'TRAJECTORY_NLP_FEASIBILITY:Rows', ...
    'Internal derivative inequality count mismatch.');
details=struct('inequality_count',i, ...
    'max_reference_derivative_ratio',maxratio, ...
    'scope','ENTIRE_UAV_AND_PAYLOAD_REFERENCE_POLYNOMIALS', ...
    'actuator_and_tension_certified',false);
end
