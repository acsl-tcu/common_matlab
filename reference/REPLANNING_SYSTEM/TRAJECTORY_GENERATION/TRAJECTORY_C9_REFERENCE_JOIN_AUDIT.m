function R=TRAJECTORY_C9_REFERENCE_JOIN_AUDIT(piece,authority, ...
    active_ref28,spatial_nominal_ref28,spatial_target,tolerance28)
% TRAJECTORY_C9_REFERENCE_JOIN_AUDIT
% Check ALL 28 values at BOTH ends of a proposed ideal-taut C9 piece.
% The active initial reference is the one used at the replanning boundary.
% The exit reference is the ORIGINAL reference EVALUATED AT THE CHOSEN
% SPATIAL RETURN STATION, NOT at the original wall-clock rejoin time.
% 28 values = 7 groups of [px,py,pz,yaw] for derivative orders 0..6.
% This preserves the actual original reference's sixth-order jets, instead
% of inventing seventh-order source data from a 28-reference interface.
% The candidate UAV is C7-capable from C9; mathematically strict C7 at
% the joint additionally requires an authoritative d7 of the nominal.
% This checker does NOT assert unknown d7 equality or full-time yaw lift,
% force, torque, obstacle safety, tracking or HLC commit authority.
start=tic;
req={'candidate_available','certified_spatial_nearest', ...
     'spatial_target_m','target_time_s','curve_parameter_u'};
assert(isstruct(spatial_target)&&isscalar(spatial_target)&& ...
    all(isfield(spatial_target,req))&& ...
    isempty(spatial_target.target_time_s)&& ...
    isequal(spatial_target.candidate_available,true)&& ...
    isequal(spatial_target.certified_spatial_nearest,true)&& ...
    isnumeric(spatial_target.spatial_target_m)&& ...
    isequal(size(spatial_target.spatial_target_m),[3 1])&& ...
    all(isfinite(spatial_target.spatial_target_m))&& ...
    isnumeric(spatial_target.curve_parameter_u)&& ...
    isscalar(spatial_target.curve_parameter_u)&& ...
    isfinite(spatial_target.curve_parameter_u)&& ...
    spatial_target.curve_parameter_u>=0&& ...
    spatial_target.curve_parameter_u<=1, ...
    'TRAJECTORY_C9_JOIN:Spatial', ...
    'Only a time-free certified spatial target is eligible for this audit.');
for v={active_ref28,spatial_nominal_ref28,tolerance28}
    a=v{1};
    assert(isnumeric(a)&&isreal(a)&&isequal(size(a),[28 1])&& ...
        all(isfinite(a)), ...
        'TRAJECTORY_C9_JOIN:Reference','Need 28 finite real values.');
end
assert(all(tolerance28>=0),'TRAJECTORY_C9_JOIN:Tolerance', ...
    'Caller must supply nonnegative 28-component tolerances.');
assert(isstruct(piece)&&isscalar(piece)&& ...
    all(isfield(piece,{'t0_s','duration_s'}))&& ...
    piece.duration_s>0, ...
    'TRAJECTORY_C9_JOIN:Piece','Require finite valid piece timing.');
R=struct('status','UNKNOWN_JOIN_NOT_PROVEN', ...
    'endpoint_ref28_matched',false, ...
    'spatial_endpoint_matches',false, ...
    'position_d0_to_d6_matched',false, ...
    'yaw_d0_to_d6_matched',false, ...
    'nominal_d7_available',false, ...
    'strict_C7_join_certified',false, ...
    'safe_to_commit',false, ...
    'initial_ref28_error',NaN(28,1), ...
    'spatial_return_ref28_error',NaN(28,1), ...
    'candidate_initial_ref28',NaN(28,1), ...
    'candidate_exit_ref28',NaN(28,1), ...
    'exit_spatial_station_u',spatial_target.curve_parameter_u, ...
    'return_target_time_s',[], ...
    'elapsed_ms',NaN, ...
    'meaning','Endpoint derivative 0..6 audit; no true d7 or physical tracking certificate');
try
    [start28,~,~]=TRAJECTORY_TAUT_FLATNESS.reference28( ...
        piece,piece.t0_s,authority,active_ref28(4));
    [end28,~,~]=TRAJECTORY_TAUT_FLATNESS.reference28( ...
        piece,piece.t0_s+piece.duration_s,authority, ...
        spatial_nominal_ref28(4));
catch ME
    R.status=['UNKNOWN_ENDPOINT_HEADING_OR_MODEL_' ME.identifier];
    R.elapsed_ms=toc(start)*1000;
    return
end
R.candidate_initial_ref28=start28;
R.candidate_exit_ref28=end28;
R.initial_ref28_error=start28-active_ref28;
R.spatial_return_ref28_error=end28-spatial_nominal_ref28;
matched=abs(R.initial_ref28_error)<=tolerance28 & ...
    abs(R.spatial_return_ref28_error)<=tolerance28;
position_mask=true(28,1);position_mask(4:4:28)=false;
yaw_mask=~position_mask;
R.position_d0_to_d6_matched=all(matched(position_mask));
R.yaw_d0_to_d6_matched=all(matched(yaw_mask));
R.spatial_endpoint_matches=all( ...
    abs(spatial_nominal_ref28(1:3)-spatial_target.spatial_target_m) ...
    <=tolerance28(1:3))&& ...
    all(abs(end28(1:3)-spatial_target.spatial_target_m) ...
    <=tolerance28(1:3));
R.endpoint_ref28_matched=all(matched)&&R.spatial_endpoint_matches;
if R.endpoint_ref28_matched
    R.status='CHECKED_28_ENDPOINT_JETS_TO_SPATIAL_STATION__D7_HLC_PENDING';
else
    R.status='UNKNOWN_ENDPOINT_28_JETS_OR_SPATIAL_STATION_MISMATCH';
end
R.elapsed_ms=toc(start)*1000;
end
