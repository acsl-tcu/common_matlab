function ok=TRAJECTORY_C9_DURATION_CACHE_MATCH(S,t0,T,left,right,free,phases)
% Guard for sharing analytic duration jets within ONE (free,T,phase) QP.
% Stale or mismatched derivative data are never accepted. This verifies
% exact source parameters; no sampled geometry / all-time claim is made.
ok=false;
if ~(isstruct(S)&&isscalar(S) && ...
        all(isfield(S,{'piece','phase_samples','duration_s', ...
        'physical_jets','dphysical_jets_dT_fixed_phase', ...
        'dphysical_jets_dT_fixed_time','dphysical_derivative_controls_dT'})))
    return
end
p=S.piece;
if ~(isstruct(p)&&isscalar(p)&&all(isfield(p, ...
        {'t0_s','duration_s','start_jets','end_jets','control_points_m'})))
    return
end
u=double(phases(:).');N=numel(u);
if ~(isequal(p.t0_s,double(t0))&& ...
        isequal(p.duration_s,double(T))&& ...
        isequal(S.duration_s,double(T))&& ...
        isequal(p.start_jets,double(left))&& ...
        isequal(p.end_jets,double(right))&& ...
        isequal(p.control_points_m(:,11:14),double(free))&& ...
        isequal(S.phase_samples,u)&& ...
        isequal(size(p.control_points_m),[3 24])&& ...
        size(S.physical_jets,1)==3&&size(S.physical_jets,2)==10&& ...
        size(S.physical_jets,3)==N&& ...
        size(S.dphysical_jets_dT_fixed_phase,1)==3&& ...
        size(S.dphysical_jets_dT_fixed_phase,2)==10&& ...
        size(S.dphysical_jets_dT_fixed_phase,3)==N&& ...
        size(S.dphysical_jets_dT_fixed_time,1)==3&& ...
        size(S.dphysical_jets_dT_fixed_time,2)==9&& ...
        size(S.dphysical_jets_dT_fixed_time,3)==N&& ...
        iscell(S.dphysical_derivative_controls_dT)&& ...
        numel(S.dphysical_derivative_controls_dT)>=7)
    return
end
for r=0:6
    if ~isequal(size(S.dphysical_derivative_controls_dT{r+1}),[3 24-r])
        return
    end
end
ok=true;
end
