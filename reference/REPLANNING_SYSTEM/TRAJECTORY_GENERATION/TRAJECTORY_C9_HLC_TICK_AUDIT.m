function R=TRAJECTORY_C9_HLC_TICK_AUDIT(piece,authority,log_input)
% TRAJECTORY_C9_HLC_TICK_AUDIT
% Compare a generated ideal-taut C9 -> UAV heading-exact 28 reference
% with the ACTUAL logged 28xN HLC-bound reference at each real Flight tick.
% No fabricated controller input or automatically assumed HLC behavior.
% log_input.actual_controller_ref28 must be read from the actual HLC input.
% 28 channels: [x y z yaw] for derivative orders 0..6, column per tick.
% Optional actual_input_thrust_torque (4xN), actual_uav_m (3xN),
% actual_payload_m (3xN) and their explicit bounds are sampled diagnostics.
% A passing sampled trace is NEVER a continuous-time HLC/ODE guarantee.
clock=tic;
required={'time_s','actual_controller_ref28','yaw_anchor_rad', ...
    'reference_tolerance28'};
assert(isstruct(log_input)&&isscalar(log_input)&& ...
    all(isfield(log_input,required)), ...
    'TRAJECTORY_C9_TICK:MissingLog', ...
    'Actual HLC-bound 28-channel log and caller tolerances are mandatory.');
t=reshape(double(log_input.time_s),1,[]);
N=numel(t);
actual=double(log_input.actual_controller_ref28);
tol=double(log_input.reference_tolerance28(:));
assert(N>=1&&all(isfinite(t))&&all(diff(t)>0)&& ...
    t(1)>=piece.t0_s&&t(end)<=piece.t0_s+piece.duration_s&& ...
    isequal(size(actual),[28 N])&&all(isfinite(actual(:)))&& ...
    isequal(size(tol),[28 1])&&all(isfinite(tol))&&all(tol>=0)&& ...
    isscalar(log_input.yaw_anchor_rad)&& ...
    isfinite(log_input.yaw_anchor_rad), ...
    'TRAJECTORY_C9_TICK:Input','Invalid tick grid, log or tolerance.');
R=struct('status','UNKNOWN_NOT_CHECKED','sampled_reference_match',false, ...
    'sampled_actuators_checked',false,'sampled_actuators_within_limits',false, ...
    'sampled_tracking_checked',false,'sampled_tracking_within_bounds',false, ...
    'expected_ref28',NaN(28,N),'actual_ref28',actual, ...
    'error_ref28',NaN(28,N),'maximum_channel_error',NaN(28,1), ...
    'time_s',t,'first_mismatch_index',NaN, ...
    'actual_actuator_4xN',zeros(4,0),'sampled_tracking_error_max_m',NaN, ...
    'sampled_payload_error_max_m',NaN, ...
    'physical_continuous_time_certified',false, ...
    'safe_to_commit',false,'elapsed_ms',NaN, ...
    'scope','TRUE_HLC_BOUND_TICK_LOG_DIAGNOSTIC_ONLY__NOT_TRACKING_PROOF');
yaw=double(log_input.yaw_anchor_rad);expected=zeros(28,N);
try
    for k=1:N
        [expected(:,k),yj]=TRAJECTORY_TAUT_FLATNESS.reference28( ...
            piece,t(k),authority,yaw);
        yaw=yj(1);
    end
catch ME
    R.status=['UNKNOWN_REFERENCE_GENERATION_' ME.identifier];
    R.elapsed_ms=1000*toc(clock);return
end
R.expected_ref28=expected;
R.error_ref28=actual-expected;
R.maximum_channel_error=max(abs(R.error_ref28),[],2);
within=all(abs(R.error_ref28)<=repmat(tol,1,N),1);
R.sampled_reference_match=all(within);
if ~R.sampled_reference_match
    R.first_mismatch_index=find(~within,1,'first');
    R.status='REJECT_ACTUAL_HLC_REFERENCE_MISMATCH';
else
    R.status='CHECKED_ALL_RECORDED_HLC_TICKS__PHYSICAL_HLC_PENDING';
end
if isfield(log_input,'actual_input_thrust_torque')
    assert(isfield(log_input,'input_limits')&& ...
        all(isfield(log_input.input_limits,{'lower','upper'})), ...
        'TRAJECTORY_C9_TICK:InputLimits','Live 4-axis bounds mandatory.');
    v=double(log_input.actual_input_thrust_torque);
    lo=double(log_input.input_limits.lower(:));
    hi=double(log_input.input_limits.upper(:));
    assert(isequal(size(v),[4 N])&&all(isfinite(v(:)))&& ...
        isequal(size(lo),[4 1])&&isequal(size(hi),[4 1])&& ...
        all(isfinite([lo;hi]))&&all(lo<=hi), ...
        'TRAJECTORY_C9_TICK:Actuators','Actual input and bounds invalid.');
    R.actual_actuator_4xN=v;
    R.sampled_actuators_checked=true;
    R.sampled_actuators_within_limits=all(all( ...
        v>=repmat(lo,1,N)&v<=repmat(hi,1,N)));
    if ~R.sampled_actuators_within_limits
        R.status='REJECT_SAMPLED_REAL_HLC_ACTUATOR_LIMIT';
    end
end
if isfield(log_input,'actual_uav_m')||isfield(log_input,'actual_payload_m')
    assert(all(isfield(log_input,{'actual_uav_m','actual_payload_m', ...
        'tracking_limits_m'}))&&all(isfield(log_input.tracking_limits_m, ...
        {'uav_m','payload_m'})), ...
        'TRAJECTORY_C9_TICK:Tracking','Both real positions and live bounds required.');
    u=double(log_input.actual_uav_m);p=double(log_input.actual_payload_m);
    assert(isequal(size(u),[3 N])&&isequal(size(p),[3 N])&& ...
        all(isfinite([u(:);p(:)]))&& ...
        isfinite(log_input.tracking_limits_m.uav_m)&& ...
        log_input.tracking_limits_m.uav_m>=0&& ...
        isfinite(log_input.tracking_limits_m.payload_m)&& ...
        log_input.tracking_limits_m.payload_m>=0, ...
        'TRAJECTORY_C9_TICK:Tracking','Invalid actual tracking log.');
    ep=zeros(1,N);eu=ep;
    for k=1:N
        E=TRAJECTORY_TAUT_FLATNESS.evaluate(piece,t(k),authority);
        assert(E.valid,'TRAJECTORY_C9_TICK:Flatness', ...
            'Valid ideal taut model needed for sample comparisons.');
        eu(k)=norm(u(:,k)-E.uav_jets(:,1));
        ep(k)=norm(p(:,k)-E.load_jets(:,1));
    end
    R.sampled_tracking_checked=true;
    R.sampled_tracking_error_max_m=max(eu);
    R.sampled_payload_error_max_m=max(ep);
    R.sampled_tracking_within_bounds= ...
        all(eu<=log_input.tracking_limits_m.uav_m)&& ...
        all(ep<=log_input.tracking_limits_m.payload_m);
    if ~R.sampled_tracking_within_bounds
        R.status='REJECT_SAMPLED_REAL_HLC_TRACKING_BOUND';
    end
end
R.elapsed_ms=1000*toc(clock);
end
