function decision=TRAJECTORY_OBSTACLE_RELEASE(known_ids,currently_detected_ids,context)
% TRAJECTORY_OBSTACLE_RELEASE  Fail-closed obstacle-retirement interface.
% No observed ID can be deleted simply because it is behind the UAV,
% outside sensor range or absent from the next 4-second collision horizon.
% A certified no-reentry / future-redetection-and-reaction theorem must be
% implemented before live release is permitted. This module changes NO data.
assert(isnumeric(known_ids)&&isreal(known_ids)&&isvector(known_ids)&& ...
    all(isfinite(known_ids(:)))&&all(known_ids(:)>0)&& ...
    all(known_ids(:)==fix(known_ids(:)))&& ...
    numel(unique(known_ids))==numel(known_ids), ...
    'TRAJECTORY_OBSTACLE_RELEASE:KnownIDs','Invalid observed ID set.');
assert(isnumeric(currently_detected_ids)&&isreal(currently_detected_ids)&& ...
    isvector(currently_detected_ids)&& ...
    all(ismember(currently_detected_ids,known_ids)), ...
    'TRAJECTORY_OBSTACLE_RELEASE:CurrentIDs','Current detections must be known.');
assert(isstruct(context)&&isscalar(context), ...
    'TRAJECTORY_OBSTACLE_RELEASE:Context','A scalar context is required.');
decision=struct('released_ids',zeros(1,0), ...
    'retained_ids',reshape(double(known_ids),1,[]), ...
    'status','HOLD_ALL_UNTIL_CERTIFIED_RELEASE', ...
    'automatic_release_enabled',false, ...
    'reason','No certified no-reentry policy, so retain every observed obstacle');
end
