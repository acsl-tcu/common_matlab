function G=TRAJECTORY_C9_ENDPOINT_FORCE_NECESSITY(start_jets,end_jets,authority,force_options)
% TRAJECTORY_C9_ENDPOINT_FORCE_NECESSITY
% Exact *necessary* thrust and taut-tension conditions at fixed C9 jets.
% Free Bernstein controls cannot change derivatives at either endpoint.
% This inexpensive invariant can reject futile searches before the expensive
% full-time certificate / one joint QP.  It NEVER certifies a trajectory.
% A failure is UNKNOWN for the requested fixed jets, not a collision claim.
% All quantities are taken from the live external authority. No flight
% phase, obstacle direction, reference shape or physical margin is invented.
required={'cable_length_m','payload_mass_kg','uav_mass_kg', ...
    'gravity_world_mps2','thrust_limits_N','minimum_tension_N', ...
    'acceleration_guard_mps2'};
assert(isnumeric(start_jets)&&isreal(start_jets)&& ...
    isequal(size(start_jets),[3 10])&&all(isfinite(start_jets(:)))&& ...
    isnumeric(end_jets)&&isreal(end_jets)&& ...
    isequal(size(end_jets),[3 10])&&all(isfinite(end_jets(:)))&& ...
    isstruct(authority)&&isscalar(authority)&& ...
    all(isfield(authority,required))&& ...
    isstruct(force_options)&&isscalar(force_options)&& ...
    isfield(force_options,'force_guard_N'), ...
    'TRAJECTORY_C9_ENDPOINT:Input','Valid C9 endpoint jets and live authority required.');
A=authority;
% A latest estimator mass of zero is admissible as DATA, but it cannot
% establish a positive taut-cable tension in the ideal point-load model.
% Report the subsequent UNKNOWN tension condition, not an input exception.
for f={'cable_length_m','uav_mass_kg'}
    v=A.(f{1});
    assert(isnumeric(v)&&isreal(v)&&isscalar(v)&&isfinite(v)&&v>0, ...
        'TRAJECTORY_C9_ENDPOINT:Authority','Positive UAV/cable authority required.');
end
v=A.payload_mass_kg;
assert(isnumeric(v)&&isreal(v)&&isscalar(v)&&isfinite(v)&&v>=0, ...
    'TRAJECTORY_C9_ENDPOINT:Authority', ...
    'Latest estimated payload mass must be finite and nonnegative.');
for f={'minimum_tension_N','acceleration_guard_mps2'}
    v=A.(f{1});
    assert(isnumeric(v)&&isreal(v)&&isscalar(v)&&isfinite(v)&&v>=0, ...
        'TRAJECTORY_C9_ENDPOINT:Authority','Nonnegative physical authority required.');
end
g=double(A.gravity_world_mps2(:));f=double(A.thrust_limits_N(:));
fguard=double(force_options.force_guard_N);
assert(isequal(size(A.gravity_world_mps2),[3 1])&& ...
    isnumeric(A.gravity_world_mps2)&&isreal(A.gravity_world_mps2)&& ...
    all(isfinite(g))&&norm(g)>0&& ...
    isnumeric(A.thrust_limits_N)&&isreal(A.thrust_limits_N)&& ...
    numel(f)==2&&all(isfinite(f))&&f(1)>=0&&f(2)>=f(1)&& ...
    isnumeric(fguard)&&isreal(fguard)&&isscalar(fguard)&& ...
    isfinite(fguard)&&fguard>=0, ...
    'TRAJECTORY_C9_ENDPOINT:Authority','Finite signed gravity and force limits required.');
G=struct('status','UNKNOWN_ENDPOINT_NOT_CHECKED','possible',false, ...
    'safe_to_commit',false,'checked_count',0, ...
    'thrust_at_endpoints_N',NaN(1,2), ...
    'tension_at_endpoints_N',NaN(1,2), ...
    'thrust_force_at_endpoints_world_N',NaN(3,2), ...
    'force_lower_limit_N',f(1)+fguard, ...
    'force_upper_limit_N',f(2)-fguard, ...
    'required_tension_N',double(A.minimum_tension_N)+ ...
       double(A.payload_mass_kg)*double(A.acceleration_guard_mps2), ...
    'scope','NECESSARY_FIXED_ENDPOINT_IDEAL_TAUT_CONDITION__NOT_FULL_TIME_PROOF');
if G.force_lower_limit_N>G.force_upper_limit_N
    G.status='UNKNOWN_ENDPOINT_EMPTY_FORCE_INTERVAL';return
end
J={start_jets,end_jets};
for k=1:2
    % w = g-pL'' and q = w/||w||; pU = pL-L*q.
    % The q'' formula follows by differentiating w=s*q twice.
    w=g-double(J{k}(:,3));
    w1=-double(J{k}(:,4));
    w2=-double(J{k}(:,5));
    s=norm(w);
    if ~(isfinite(s)&&s>0)
        G.status='UNKNOWN_FIXED_ENDPOINT_TAUT_SINGULARITY';return
    end
    q=w/s;
    sd=dot(q,w1);
    q1=(w1-q*sd)/s;
    sdd=dot(q,w2)+s*dot(q1,q1);
    q2=(w2-2*sd*q1-sdd*q)/s;
    F=-(double(A.uav_mass_kg)+double(A.payload_mass_kg))*w- ...
        double(A.uav_mass_kg)*double(A.cable_length_m)*q2;
    Ft=norm(F);Ten=double(A.payload_mass_kg)*s;
    G.thrust_at_endpoints_N(k)=Ft;
    G.tension_at_endpoints_N(k)=Ten;
    G.thrust_force_at_endpoints_world_N(:,k)=F;
    G.checked_count=k;
    if ~all(isfinite([Ft;Ten;F;q2]))
        G.status='UNKNOWN_FIXED_ENDPOINT_NONFINITE_MODEL';return
    end
    if ~(Ten>G.required_tension_N)
        G.status='UNKNOWN_FIXED_ENDPOINT_TENSION_LIMIT';return
    end
    if Ft<G.force_lower_limit_N||Ft>G.force_upper_limit_N
        G.status='UNKNOWN_FIXED_ENDPOINT_THRUST_LIMIT';return
    end
end
G.possible=true;
G.status='PASS_ENDPOINT_NECESSARY_FORCE_AND_TENSION__NOT_TRAJECTORY_PROOF';
end
