function log_row=TRAJECTORY_REFERENCE_TRACE(t_s,plan_revision,generated_ref28,actual_controller_ref28)
% TRAJECTORY_REFERENCE_TRACE  One-tick reference audit payload for Sim LOGGER.
% This is a pure transformer; the calling REPLANNING_SYSTEM must attach it
% to agent.reference.result once the exact HLC-bound 28-vector is identified.
% NEVER substitute the generated vector for an unobserved controller input.
assert(isnumeric(t_s)&&isreal(t_s)&&isscalar(t_s)&&isfinite(t_s), ...
    'TRAJECTORY_REFERENCE_TRACE:Time','Finite tick time required.');
assert((isa(plan_revision,'uint64')||isnumeric(plan_revision)) && ...
    isscalar(plan_revision)&&isreal(plan_revision)&& ...
    isfinite(double(plan_revision))&&double(plan_revision)>=0&& ...
    double(plan_revision)==fix(double(plan_revision)), ...
    'TRAJECTORY_REFERENCE_TRACE:Revision','Committed revision required.');
for v={generated_ref28,actual_controller_ref28}
    x=v{1};
    assert(isnumeric(x)&&isreal(x)&&isequal(size(x),[28 1])&& ...
        all(isfinite(x)), ...
        'TRAJECTORY_REFERENCE_TRACE:Reference', ...
        'Both generated and actually delivered HLC references must be finite 28x1 columns.');
end
log_row=struct('time_s',double(t_s), ...
    'plan_revision',uint64(plan_revision), ...
    'generated_ref28',generated_ref28, ...
    'actual_controller_ref28',actual_controller_ref28, ...
    'actual_minus_generated_ref28',actual_controller_ref28-generated_ref28, ...
    'exact_delivery_match',isequal(actual_controller_ref28,generated_ref28));
end
