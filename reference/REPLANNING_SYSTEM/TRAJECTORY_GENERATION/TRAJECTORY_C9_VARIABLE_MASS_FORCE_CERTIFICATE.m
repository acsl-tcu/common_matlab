function R=TRAJECTORY_C9_VARIABLE_MASS_FORCE_CERTIFICATE(piece,nominal,authority,envelope,acceleration_numeric_guard_mps2)
% SUFFICIENT interval-mass ideal taut-load thrust/tension certificate.
% This is NOT a torque/HLC tracking certificate. The future-mass envelope
% and numerical guard are supplied EXTERNALLY, never inferred from a past
% sampled estimator value. The mathematical result is conditional on those
% external bounds being valid throughout [t0,t0+T].
%
% w(t)=g-pL''(t), q=w/||w||, F(m,t)=F(m0,t)-(m-m0)*w(t).
% Bernstein hull bounds ||w(t)|| <= W, for ALL t in the piece.
% Delta=max(|m_min-m0|,|m_max-m0|), so
%   | ||F(m,t)|| - ||F(m0,t)|| | <= Delta*W.
% Tension(m,t) = m/m0 * Tension(m0,t), under the same taut model.
% Conservatively enlarge thrust magnitude bounds and shrink tension
% lower bound. No endpoint-only-force interpolation shortcut is used.
R=struct('status','UNKNOWN_VARIABLE_MASS_NOT_CERTIFIED', ...
    'conditional_ideal_taut_force_proven',false, ...
    'external_mass_envelope_assumed',false,'safe_to_commit',false, ...
    'w_upper_bound_mps2',NaN,'mass_delta_kg',NaN, ...
    'thrust_lower_bound_N',NaN,'thrust_upper_bound_N',NaN, ...
    'tension_lower_bound_N',NaN, ...
    'HLC_tracking_continuous_time_proven',false, ...
    'attitude_and_torque_continuous_time_proven',false);
needed={'certified_continuous_geometry','certified_continuous_thrust', ...
    'certified_continuous_tension','thrust_lower_bound_N', ...
    'thrust_upper_bound_N','minimum_tension_lower_bound_N'};
if ~isstruct(nominal)||~isscalar(nominal)||~all(isfield(nominal,needed))|| ...
        ~nominal.certified_continuous_geometry|| ...
        ~nominal.certified_continuous_thrust|| ...
        ~nominal.certified_continuous_tension
    R.status='UNKNOWN_BASE_CONTINUOUS_PROOF_MISSING';return
end
if ~isstruct(piece)||~isscalar(piece)||~all(isfield(piece, ...
        {'control_points_m','t0_s','duration_s'}))|| ...
        ~isequal(size(piece.control_points_m),[3 24])|| ...
        ~isnumeric(piece.control_points_m)||~isreal(piece.control_points_m)|| ...
        ~all(isfinite(piece.control_points_m(:)))|| ...
        ~isscalar(piece.duration_s)||~isfinite(piece.duration_s)||piece.duration_s<=0|| ...
        ~isscalar(piece.t0_s)||~isfinite(piece.t0_s)
    R.status='UNKNOWN_INVALID_C9_PIECE';return
end
if ~isstruct(authority)||~isscalar(authority)|| ...
        ~all(isfield(authority,{'payload_mass_kg','uav_mass_kg', ...
        'gravity_world_mps2','thrust_limits_N','minimum_tension_N'}))|| ...
        ~TRAJECTORY_C9_FLIGHT_PARAMETER_CONTRACT.valid_envelope(envelope)
    R.status='UNKNOWN_INVALID_EXTERNAL_MASS_OR_FORCE_AUTHORITY';return
end
m0=double(authority.payload_mass_kg);
g=double(authority.gravity_world_mps2(:));
lim=double(authority.thrust_limits_N(:));
if ~isscalar(m0)||~isfinite(m0)||m0<=0|| ...
        ~isscalar(authority.uav_mass_kg)||~isfinite(authority.uav_mass_kg)|| ...
        authority.uav_mass_kg<=0||numel(g)~=3||any(~isfinite(g))|| ...
        numel(lim)~=2||any(~isfinite(lim))||lim(2)<lim(1)||lim(1)<0|| ...
        ~isnumeric(acceleration_numeric_guard_mps2)|| ...
        ~isscalar(acceleration_numeric_guard_mps2)|| ...
        ~isfinite(acceleration_numeric_guard_mps2)|| ...
        acceleration_numeric_guard_mps2<0
    R.status='UNKNOWN_INVALID_FORCE_OR_NUMERIC_GUARD';return
end
if piece.t0_s<envelope.valid_from_s || ...
        piece.t0_s+piece.duration_s>envelope.valid_until_s || ...
        m0<envelope.lower_kg || m0>envelope.upper_kg
    R.status='UNKNOWN_MASS_ENVELOPE_DOES_NOT_COVER_ENTIRE_PIECE';return
end
b=[nominal.thrust_lower_bound_N,nominal.thrust_upper_bound_N, ...
    nominal.minimum_tension_lower_bound_N];
if any(~isfinite(b))||b(1)<0||b(2)<b(1)||b(3)<0|| ...
        ~isscalar(authority.minimum_tension_N)|| ...
        ~isfinite(authority.minimum_tension_N)||authority.minimum_tension_N<0
    R.status='UNKNOWN_INVALID_NOMINAL_FORCE_PROOF_BOUNDS';return
end
P=double(piece.control_points_m);
% Degree-23 Bernstein second derivative has 22 control points.
A=(23*22)/(double(piece.duration_s)^2)*diff(P,2,2);
Wmax=max(sqrt(sum((g-A).^2,1)));
Wmax=Wmax+double(acceleration_numeric_guard_mps2);
if ~isfinite(Wmax)||Wmax<0
    R.status='UNKNOWN_INVALID_W_BOUND';return
end
dm=max(abs(envelope.lower_kg-m0),abs(envelope.upper_kg-m0));
add=dm*Wmax;
lo=max(0,b(1)-add);
hi=b(2)+add;
tension=b(3)*(envelope.lower_kg/m0);
R.external_mass_envelope_assumed=true;
R.w_upper_bound_mps2=Wmax;
R.mass_delta_kg=dm;
R.thrust_lower_bound_N=lo;
R.thrust_upper_bound_N=hi;
R.tension_lower_bound_N=tension;
if lo<lim(1)||hi>lim(2)||tension<authority.minimum_tension_N
    R.status='UNKNOWN_VARIABLE_MASS_FORCE_BOUNDS_NOT_FEASIBLE';return
end
R.conditional_ideal_taut_force_proven=true;
R.status='CONDITIONAL_ALL_TIME_TAUT_FORCE_VALID_FOR_EXTERNAL_MASS_RANGE__NO_HLC_COMMIT';
end
