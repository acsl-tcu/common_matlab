function R=TRAJECTORY_POLYNOMIAL_CABLE_COMPATIBILITY(uav,payload,cable_length_m,tolerance_m)
%TRAJECTORY_POLYNOMIAL_CABLE_COMPATIBILITY Necessary taut-cable audit.
% Algebraic fact: if D(t)=payload(t)-uav(t) is a polynomial and its
% Euclidean norm is CONSTANT for every t in any nonempty time interval,
% then D(t) is constant. Proof: sum(D_i(t)^2)-L^2 is a polynomial identity.
% The leading coefficient of its largest even degree is a sum of squares,
% hence can vanish only if all leading vector coefficients vanish.
% Thus independent polynomial UAV and payload paths cannot represent a
% swinging exact-length taut cable. This only audits REPRESENTATION; it is
% not a dynamics/tension safety certificate. No guessed cable length.
assert(isstruct(uav)&&isstruct(payload)&& ...
    all(isfield(uav,{'control_points_m','t0_s','duration_s'}))&& ...
    all(isfield(payload,{'control_points_m','t0_s','duration_s'})), ...
    'TRAJECTORY_CABLE_COMPATIBILITY:Piece','Two Bernstein pieces required.');
U=uav.control_points_m;P=payload.control_points_m;
assert(isnumeric(U)&&isnumeric(P)&&isequal(size(U),size(P))&& ...
    size(U,1)==3&&size(U,2)>=2&&all(isfinite([U(:);P(:)]))&& ...
    isequal(uav.t0_s,payload.t0_s)&& ...
    isequal(uav.duration_s,payload.duration_s)&& ...
    uav.duration_s>0&&isfinite(uav.duration_s), ...
    'TRAJECTORY_CABLE_COMPATIBILITY:Time', ...
    'Aligned real finite Bernstein pairs are required.');
assert(isnumeric(cable_length_m)&&isscalar(cable_length_m)&& ...
    isfinite(cable_length_m)&&cable_length_m>0&& ...
    isnumeric(tolerance_m)&&isscalar(tolerance_m)&& ...
    isfinite(tolerance_m)&&tolerance_m>=0, ...
    'TRAJECTORY_CABLE_COMPATIBILITY:Authority', ...
    'External physical length and numerical tolerance required.');
D=P-U;
variation=max(sqrt(sum((D-D(:,1)).^2,1)));
length_error=abs(norm(D(:,1))-double(cable_length_m));
compatible=variation<=tolerance_m && length_error<=tolerance_m;
R=struct('polynomial_taut_length_compatible',compatible, ...
    'max_control_offset_variation_m',variation, ...
    'constant_offset_length_error_m',length_error, ...
    'safe_to_commit',false, ...
    'scope','REPRESENTATION_NECESSARY_CONDITION_NOT_DYNAMICS');
if compatible
    R.status='NUMERIC_STATIC_OFFSET_TAUT_COMPATIBLE__TENSION_UNPROVED';
else
    R.status='NONCONSTANT_POLYNOMIAL_OFFSET_CANNOT_BE_EXACT_TAUT_CABLE';
end
end
