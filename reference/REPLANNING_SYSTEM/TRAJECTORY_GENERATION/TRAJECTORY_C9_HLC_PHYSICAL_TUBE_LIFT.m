function R=TRAJECTORY_C9_HLC_PHYSICAL_TUBE_LIFT(virtual_tube, ...
    nominal_w_lower_mps2,vertical_acceleration_residual_mps2,cable_length_m)
%TRAJECTORY_C9_HLC_PHYSICAL_TUBE_LIFT  Conditional tube of 3 PHYSICAL bodies.
% Assumes the x,y,z virtual error states are respectively the actual
% payload position derivatives up to 5/5/1, including estimation errors.
% z acceleration is NOT part of the 2nd-order error state; for a held
% virtual z input, |e_z''| <= ||F1|| ||e_z(k)||+a_z_residual, where the
% certified residual explicitly includes ALL nonideal plant/HLC terms.
% To avoid incorrectly using an intersample e_z radius as an e_z(k)
% radius, the supplied bound max_virtual_feedback_2norm(1) is used.
%
% w=g-pL'', q=w/||w||, pU=pL-L*q in the ideal taut straight-cable model.
% If nominal ||w|| >= wmin > delta_a, the unit-vector derivative bound is
%   ||q_actual-q_nom|| <= delta_a/(wmin-delta_a).
% Thus payload error epsL=sqrt(e_x^2+e_y^2+e_z^2), UAV error <=
% epsL+L*eps_q, and cable position at fraction lambda is bounded by
% (1-lambda)*epsL+lambda*epsU. Separate radii, NOT one system sphere.
%
% This does NOT establish tautness of real plant, actual-HLC equivalence,
% EKF error bounds, or MATLAB directed-rounding guarantees. It is only a
% real-arithmetic CONDITIONAL composition lemma; NEVER grants COMMIT.
R=struct('status','UNKNOWN_PHYSICAL_TUBE_PRECONDITIONS', ...
    'safe_to_commit',false,'physical_tracking_certified',false, ...
    'actual_HLC_equivalence_proven',false, ...
    'uav_m',NaN,'cable_m',NaN,'payload_m',NaN, ...
    'payload_acceleration_error_mps2',NaN, ...
    'cable_direction_error_2norm',NaN, ...
    'nominal_w_lower_mps2',nominal_w_lower_mps2, ...
    'scope','CONDITIONAL_FULLBODY_GEOMETRY_FROM_VIRTUAL_ERRORS');
if ~isstruct(virtual_tube)|| ...
        ~isfield(virtual_tube,'status')|| ...
        ~strcmp(virtual_tube.status, ...
        'CONDITIONAL_SAMPLED_VIRTUAL_TUBE__REAL_HLC_MODEL_PENDING')|| ...
        ~isfield(virtual_tube,'max_intersample_error_2norm')|| ...
        ~isfield(virtual_tube,'max_virtual_feedback_2norm')|| ...
        ~(isnumeric(nominal_w_lower_mps2)&&isreal(nominal_w_lower_mps2)&& ...
          isscalar(nominal_w_lower_mps2)&& ...
          isfinite(nominal_w_lower_mps2)&&nominal_w_lower_mps2>0)|| ...
        ~(isnumeric(vertical_acceleration_residual_mps2)&& ...
          isreal(vertical_acceleration_residual_mps2)&& ...
          isscalar(vertical_acceleration_residual_mps2)&& ...
          isfinite(vertical_acceleration_residual_mps2)&& ...
          vertical_acceleration_residual_mps2>=0)|| ...
        ~(isnumeric(cable_length_m)&&isreal(cable_length_m)&& ...
          isscalar(cable_length_m)&&isfinite(cable_length_m)&&cable_length_m>0)
    return
end
rho=double(virtual_tube.max_intersample_error_2norm(:));
fb=double(virtual_tube.max_virtual_feedback_2norm(:));
if numel(rho)~=4||numel(fb)~=4|| ...
        any(~isfinite([rho;fb]))||any([rho;fb]<0)
    return
end
epsL=norm(rho(1:3));
% x/y high-order virtual states contain acceleration error directly.
epsa=norm([rho(2);rho(3); ...
    fb(1)+double(vertical_acceleration_residual_mps2)]);
R.payload_acceleration_error_mps2=epsa;
if epsa>=nominal_w_lower_mps2
    R.status='UNKNOWN_TAUT_DIRECTION_NORMALIZATION_NOT_PROVEN';return
end
epsq=min(2,epsa/(nominal_w_lower_mps2-epsa));
epsU=epsL+double(cable_length_m)*epsq;
R.payload_m=epsL;
R.uav_m=epsU;
R.cable_m=max(epsL,epsU);
R.cable_direction_error_2norm=epsq;
if all(isfinite([epsL;epsU;epsq;R.cable_m]))
    R.status='CONDITIONAL_SEPARATE_UAV_CABLE_PAYLOAD_TUBE__EXECUTION_UNPROVEN';
else
    R.status='UNKNOWN_NONFINITE_PHYSICAL_TUBE';
end
end
