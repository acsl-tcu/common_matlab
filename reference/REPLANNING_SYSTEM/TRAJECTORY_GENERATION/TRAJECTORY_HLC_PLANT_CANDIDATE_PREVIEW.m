function R=TRAJECTORY_HLC_PLANT_CANDIDATE_PREVIEW(req)
%TRAJECTORY_HLC_PLANT_CANDIDATE_PREVIEW Evaluate proposed C7 UAV reference
% with the EXISTING, preflight-pinned HLC + suspended-load plant predictor.
%
% Unlike a pair of independently optimized polynomials, this obtains the
% payload motion from the actual model (initial EKF state and latest mL).
% Input/mass/cable/tracking checks are SAMPLED NECESSARY CONDITIONS, not
% a continuous-time ODE/tension/robust tracking certificate. The swept
% geometry proof is for the piecewise-linear model samples ONLY.
% This function NEVER commits a reference and NEVER changes HLC / plant.
%
% REQUIRED fields are all caller-authoritative (no hidden fallback):
% piece, time_s, ekf_now, latest_payload_mass_kg, native_binding,
% relative_sample_times_s, numeric_tolerances, yaw_anchor_rad,
% input_limits (.lower/.upper 4x1), physical_parameters
% (.cable_length_m), tolerances (.cable_length_abs_m,
% .input_abs, .tracking_abs_m, .initial_position_abs_m),
% heading_options, derivative_limits, kinematic_options,
% observed, physical_radii, proof_options.
% Optional predictor_function @(native_request,native_binding) -- audit
% adapter only; default runs TRIGGER_HLC_PLANT_PREDICTOR.predict with its
% mandatory native parity gate. No synthetic predictor is used by default.
clock=tic;
mandatory={'piece','time_s','ekf_now','latest_payload_mass_kg', ...
    'native_binding','relative_sample_times_s','numeric_tolerances', ...
    'yaw_anchor_rad','input_limits','physical_parameters','tolerances', ...
    'heading_options','derivative_limits','kinematic_options', ...
    'observed','physical_radii','proof_options'};
assert(isstruct(req)&&isscalar(req)&&all(isfield(req,mandatory)), ...
    'TRAJECTORY_MODEL_PREVIEW:Request','Missing caller-owned authority.');
p=req.piece;
assert(isstruct(p)&&isscalar(p)&& ...
    all(isfield(p,{'t0_s','duration_s','control_points_m','derivative_controls'}))&& ...
    isequal(size(p.control_points_m),[3 24])&& ...
    isfinite(p.t0_s)&&p.duration_s>0&&isfinite(p.duration_s)&& ...
    isequal(double(req.time_s),double(p.t0_s)), ...
    'TRAJECTORY_MODEL_PREVIEW:Piece','Expected active C7 candidate beginning now.');
assert(isstruct(req.ekf_now)&& ...
    all(isfield(req.ekf_now,{'p','q','v','w','pL','vL','pT','wL'})), ...
    'TRAJECTORY_MODEL_PREVIEW:EKF','Full current 24-state EKF required.');
for field={'p','q','v','w','pL','vL','pT','wL'}
    v=req.ekf_now.(field{1});
    assert(isnumeric(v)&&isequal(size(v),[3 1])&&all(isfinite(v)), ...
        'TRAJECTORY_MODEL_PREVIEW:EKF','Invalid EKF state field.');
end
assert(isnumeric(req.latest_payload_mass_kg)&& ...
    isscalar(req.latest_payload_mass_kg)&& ...
    isfinite(req.latest_payload_mass_kg)&&req.latest_payload_mass_kg>0, ...
    'TRAJECTORY_MODEL_PREVIEW:Mass','Use current estimator mass.');
assert(isstruct(req.native_binding)&&isscalar(req.native_binding), ...
    'TRAJECTORY_MODEL_PREVIEW:Native','Live flight binding required.');
assert(isnumeric(req.yaw_anchor_rad)&&isscalar(req.yaw_anchor_rad)&& ...
    isfinite(req.yaw_anchor_rad), ...
    'TRAJECTORY_MODEL_PREVIEW:Yaw','Current yaw branch anchor required.');
t=reshape(double(req.relative_sample_times_s),1,[]);
assert(numel(t)>=2&&all(isfinite(t))&&t(1)==0&& ...
    all(diff(t)>0)&&abs(t(end)-p.duration_s)<= ...
    16*eps(max(1,abs(p.duration_s))), ...
    'TRAJECTORY_MODEL_PREVIEW:Times', ...
    'Caller must cover full candidate duration, starting at zero.');
t(end)=p.duration_s; % remove only roundoff at exact caller-owned endpoint
assert(isnumeric(req.numeric_tolerances)&& ...
    numel(req.numeric_tolerances)==2&& ...
    all(isfinite(req.numeric_tolerances(:)))&& ...
    all(req.numeric_tolerances(:)>0), ...
    'TRAJECTORY_MODEL_PREVIEW:Numerics', ...
    'Live [AbsTol,RelTol] required.');
assert(isstruct(req.physical_parameters)&& ...
    isfield(req.physical_parameters,'cable_length_m')&& ...
    isnumeric(req.physical_parameters.cable_length_m)&& ...
    isscalar(req.physical_parameters.cable_length_m)&& ...
    isfinite(req.physical_parameters.cable_length_m)&& ...
    req.physical_parameters.cable_length_m>0, ...
    'TRAJECTORY_MODEL_PREVIEW:Cable','Live cable length required.');
assert(isstruct(req.input_limits)&& ...
    all(isfield(req.input_limits,{'lower','upper'})), ...
    'TRAJECTORY_MODEL_PREVIEW:Input','Live force/torque limits required.');
lo=double(req.input_limits.lower(:));hi=double(req.input_limits.upper(:));
assert(numel(lo)==4&&numel(hi)==4&&all(isfinite([lo;hi]))&& ...
    all(lo<=hi), ...
    'TRAJECTORY_MODEL_PREVIEW:Input','Require four actuator intervals.');
fields={'cable_length_abs_m','input_abs','tracking_abs_m', ...
    'initial_position_abs_m'};
assert(isstruct(req.tolerances)&&all(isfield(req.tolerances,fields)), ...
    'TRAJECTORY_MODEL_PREVIEW:Tolerances', ...
    'Every numerical/physical acceptance tolerance is external.');
for k=1:numel(fields)
    a=req.tolerances.(fields{k});
    assert(isnumeric(a)&&isscalar(a)&&isfinite(a)&&a>=0, ...
        'TRAJECTORY_MODEL_PREVIEW:Tolerances','Invalid tolerance.');
end
assert(isstruct(req.observed), ...
    'TRAJECTORY_MODEL_PREVIEW:Observed','Use retained observed obstacles only.');
R=struct('status','UNKNOWN_NOT_EVALUATED','screen_pass',false, ...
    'safe_to_commit',false,'physical_continuous_time_certified',false, ...
    'prediction_complete',false,'reference_times_s',p.t0_s+t(1:end-1), ...
    'reference_matrix_28',zeros(28,0), ...
    'input_thrust_torque',zeros(4,0),'predicted_uav_m',zeros(3,0), ...
    'predicted_payload_m',zeros(3,0),'time_grid_s',p.t0_s+t, ...
    'tracking_error_max_m',NaN,'cable_length_error_max_m',NaN, ...
    'max_actuator_violation',NaN,'initial_position_error_m',NaN, ...
    'predicted_interpolant_geometry',struct(), ...
    'kinematic_certificate',struct(),'heading_certificate',struct(), ...
    'reference_build_ms',NaN,'native_prediction_ms',NaN, ...
    'total_ms',NaN,'reason','Not evaluated');
R.heading_certificate=TRAJECTORY_HEADING_CERTIFICATE(p,req.heading_options);
if ~R.heading_certificate.certified
    R.status='UNKNOWN_HEADING_SINGULARITY';
    R.reason='Horizontal tangent direction not certified for all times';
    R.total_ms=1000*toc(clock);return
end
R.kinematic_certificate=TRAJECTORY_KINEMATIC_CERTIFICATE( ...
    p,req.derivative_limits,req.kinematic_options);
if ~R.kinematic_certificate.certified
    R.status='REJECT_UNCERTIFIED_REFERENCE_KINEMATICS';
    R.reason='Entire reference polynomial does not pass derivative limits';
    R.total_ms=1000*toc(clock);return
end
initial_error=norm(double(req.ekf_now.p)-p.start_jets(:,1));
R.initial_position_error_m=initial_error;
if initial_error>req.tolerances.initial_position_abs_m
    R.status='REJECT_NOT_CURRENT_EKF_POSITION';
    R.reason='Candidate does not start at the present EKF position';
    R.total_ms=1000*toc(clock);return
end
refclock=tic;
ref=zeros(28,numel(t)-1);
yaw=double(req.yaw_anchor_rad);
for k=1:numel(t)-1
    [ref(:,k),yjets]=TRAJECTORY_C7_FREE_BERNSTEIN.reference28( ...
        p,p.t0_s+t(k),yaw);
    yaw=yjets(1); % phase continuity across all actually sent HLC samples
end
R.reference_matrix_28=ref;
R.reference_build_ms=1000*toc(refclock);
% The exact real-flight input interface from the pinned trigger predictor.
native=struct('time_s',double(p.t0_s),'sample_times_s',t, ...
    'reference_matrix',ref,'reference_at', ...
    @(time)reference_at(p,time,req.yaw_anchor_rad), ...
    'ekf_now',req.ekf_now, ...
    'payload_mass_kg',double(req.latest_payload_mass_kg), ...
    'numeric_tolerances',double(req.numeric_tolerances(:)));
try
    nclock=tic;
    if isfield(req,'predictor_function')
        assert(isa(req.predictor_function,'function_handle'), ...
            'TRAJECTORY_MODEL_PREVIEW:Adapter', ...
            'Optional predictor adapter must be a function handle.');
        P=req.predictor_function(native,req.native_binding);
    else
        P=TRIGGER_HLC_PLANT_PREDICTOR.predict(native,req.native_binding);
    end
    R.native_prediction_ms=1000*toc(nclock);
catch ME
    R.status='UNKNOWN_PINNED_HLC_PLANT_PREDICTION_FAILED';
    R.reason=['No unverified model fallback: ' ME.identifier];
    R.total_ms=1000*toc(clock);return
end
required_pred={'uav_m','payload_m','input_thrust_torque', ...
    'sample_times_s','prediction_complete'};
if ~(isstruct(P)&&isscalar(P)&&all(isfield(P,required_pred))&& ...
        isequal(P.prediction_complete,true)&& ...
        isequal(size(P.uav_m),[3 numel(t)])&& ...
        isequal(size(P.payload_m),[3 numel(t)])&& ...
        isequal(size(P.input_thrust_torque),[4 numel(t)-1])&& ...
        isequal(reshape(double(P.sample_times_s),1,[]),t)&& ...
        all(isfinite([P.uav_m(:);P.payload_m(:);P.input_thrust_torque(:)])))
    R.status='UNKNOWN_INCOMPLETE_NATIVE_MODEL_PREVIEW';
    R.reason='Predictor output missing or inconsistent';
    R.total_ms=1000*toc(clock);return
end
R.prediction_complete=true;
R.predicted_uav_m=double(P.uav_m);
R.predicted_payload_m=double(P.payload_m);
R.input_thrust_torque=double(P.input_thrust_torque);
R.max_actuator_violation=max([0;max(lo-R.input_thrust_torque,[],2); ...
    max(R.input_thrust_torque-hi,[],2)]);
D=R.predicted_uav_m-R.predicted_payload_m;
R.cable_length_error_max_m=max(abs(sqrt(sum(D.^2,1))- ...
    double(req.physical_parameters.cable_length_m)));
Pnom=zeros(3,numel(t));
Pnom(:,1)=p.start_jets(:,1);
Pnom(:,end)=p.end_jets(:,1);
for k=2:numel(t)-1
    J=TRAJECTORY_C7_FREE_BERNSTEIN.evaluate(p,p.t0_s+t(k));
    Pnom(:,k)=J(:,1);
end
R.tracking_error_max_m=max(sqrt(sum((Pnom-R.predicted_uav_m).^2,1)));
% Independent swept proof of the LINEAR INTERPOLANT of numeric model
% samples. This is NOT an error bound on the continuous ODE trajectory.
segments=repmat(struct('uav',struct(),'payload',struct()),1,numel(t)-1);
for k=1:numel(t)-1
    U=struct('control_points_m',R.predicted_uav_m(:,k:k+1), ...
        't0_s',p.t0_s+t(k),'duration_s',t(k+1)-t(k));
    L=struct('control_points_m',R.predicted_payload_m(:,k:k+1), ...
        't0_s',p.t0_s+t(k),'duration_s',t(k+1)-t(k));
    segments(k)=struct('uav',U,'payload',L);
end
try
    G=TRAJECTORY_CONTINUOUS_GEOMETRY_CERTIFICATE(segments, ...
        req.observed,req.physical_radii,req.proof_options);
catch ME
    R.status='UNKNOWN_MODEL_INTERPOLANT_GEOMETRY_EXCEPTION';
    R.reason=['Observed geometry check: ' ME.identifier];
    R.total_ms=1000*toc(clock);return
end
R.predicted_interpolant_geometry=G;
if ~G.certified
    R.status='REJECT_UNCERTIFIED_MODEL_INTERPOLANT_GEOMETRY';
    R.reason='Predicted UAV/cable/load swept interval cannot be separated';
elseif R.max_actuator_violation>req.tolerances.input_abs
    R.status='REJECT_SAMPLED_ACTUATOR_LIMIT';
    R.reason='Pinned HLC input exceeds live thrust/torque constraints';
elseif R.cable_length_error_max_m>req.tolerances.cable_length_abs_m
    R.status='REJECT_SAMPLED_CABLE_LENGTH';
    R.reason='Pinned plant violates caller-owned taut-length tolerance';
elseif R.tracking_error_max_m>req.tolerances.tracking_abs_m
    R.status='REJECT_SAMPLED_REFERENCE_TRACKING';
    R.reason='Pinned plant deviates from proposed UAV reference';
else
    R.screen_pass=true;
    R.status='PASS_PINNED_MODEL_SAMPLED_SCREEN__NOT_PHYSICAL_CERTIFICATE';
    R.reason='Necessary model checks pass; ODE bounds/tension/uncertainty still unproved';
end
R.total_ms=1000*toc(clock);
end

function r=reference_at(piece,time,branch_anchor)
% Read-only fallback for native request contract; production reuses the
% explicitly constructed full 28-row reference_matrix.
r=TRAJECTORY_C7_FREE_BERNSTEIN.reference28(piece,time,branch_anchor);
end
