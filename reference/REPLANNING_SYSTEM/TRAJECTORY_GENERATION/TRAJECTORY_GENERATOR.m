classdef TRAJECTORY_GENERATOR < handle
    % New single-online-solve trajectory generator boundary.
    % Geometry and kinematic certificate primitives are now available.
    % No full-body dynamics-certified online solver or HLC switch yet.
    properties (SetAccess=private)
        ROBUST_TUBE_ENABLED = true
        FAILURE_BACKUP_ENABLED = true
        committed_plan_revision = uint64(0)
        last_proposal_status = 'NOT_REQUESTED'
    end
    methods
        function obj=TRAJECTORY_GENERATOR(options)
            if nargin<1,options=struct();end
            assert(isstruct(options)&&isscalar(options), ...
                'TRAJECTORY_GENERATOR:Options','Options must be a scalar struct.');
            keys=fieldnames(options);
            assert(all(ismember(keys,{'ROBUST_TUBE_ENABLED','FAILURE_BACKUP_ENABLED'})), ...
                'TRAJECTORY_GENERATOR:UnknownOption','Unknown generator option.');
            for k=1:numel(keys)
                x=options.(keys{k});
                assert((islogical(x)||isnumeric(x))&&isscalar(x)&& ...
                    (isequal(x,0)||isequal(x,1)), ...
                    'TRAJECTORY_GENERATOR:Flag','Flags must be 0 or 1.');
                obj.(keys{k})=logical(x);
            end
        end
        function result=propose(obj,request)
            % Fail-closed until all constraints are implemented and proven.
            % Do NOT synthesize any mass, geometry, derivative, margin, or time.
            mandatory={'time_s','ekf_now','observed_frame', ...
                'active_reference','latest_payload_mass_kg', ...
                'physical_parameters','collision_event'};
            assert(isstruct(request)&&isscalar(request)&& ...
                all(isfield(request,mandatory)), ...
                'TRAJECTORY_GENERATOR:Request', ...
                'Missing authoritative observed-state/physical inputs.');
            result=struct('status','NOT_IMPLEMENTED_NO_CANDIDATE', ...
                'candidate_available',false,'certified',false, ...
                'safe_to_commit',false,'request_time_s',request.time_s, ...
                'robust_tube_enabled',obj.ROBUST_TUBE_ENABLED, ...
                'failure_backup_enabled',obj.FAILURE_BACKUP_ENABLED, ...
                'obstacle_release_ids',zeros(1,0), ...
                'reason','Single-solve optimizer and continuous-time whole-body execution certificate not yet connected');
            obj.last_proposal_status=result.status;
        end
        function report=certify_geometry(obj,segments,observed_shapes,physical_radii,proof_options)
            % A useful PRODUCTION-SCOPE geometric certificate, not a
            % generator commit. It covers each polynomial's continuous
            % time, all currently observed IDs and all 3 body components.
            % A positive geometry result does NOT bypass the missing
            % yaw/actuator/tension/tracking/optimizer acceptance gates.
            assert(isstruct(proof_options)&&isfield(proof_options,'robust_tube_enabled')&& ...
                isequal(logical(proof_options.robust_tube_enabled),obj.ROBUST_TUBE_ENABLED), ...
                'TRAJECTORY_GENERATOR:TubeFlag', ...
                'Proof tube toggle must match the generator instance configuration.');
            report=TRAJECTORY_CONTINUOUS_GEOMETRY_CERTIFICATE( ...
                segments,observed_shapes,physical_radii,proof_options);
            assert(~report.safe_to_commit, ...
                'TRAJECTORY_GENERATOR:UnsafeCommit','Geometry alone cannot permit a commit.');
        end
        function corridor=build_corridor(obj,guide_segments,observed_shapes,physical_radii,proof_options)
            % Corridor is a certified LINEAR feasible region for a supplied
            % guide. It is not an automatically discovered detour and does
            % NOT authorize a change of the HLC reference by itself.
            assert(isstruct(proof_options)&&isscalar(proof_options)&& ...
                isfield(proof_options,'robust_tube_enabled')&& ...
                isequal(logical(proof_options.robust_tube_enabled), ...
                obj.ROBUST_TUBE_ENABLED), ...
                'TRAJECTORY_GENERATOR:TubeFlag', ...
                'Corridor tube toggle must agree with the generator.');
            corridor=TRAJECTORY_SAFE_CORRIDOR( ...
                guide_segments,observed_shapes,physical_radii,proof_options);
            assert(~corridor.safe_to_commit, ...
                'TRAJECTORY_GENERATOR:UnsafeCommit', ...
                'Geometry-only corridor cannot authorize HLC commit.');
        end
        function result=search_geometric_candidate(obj,request)
            % One simultaneous NLP for ALL retained observed obstacles.
            % The optimizer is allowed to move through a colliding original
            % guide: obstacle separation normals are decision variables.
            % This remains GEOMETRIC-ONLY and must NEVER change HLC output.
            assert(isstruct(request)&&isscalar(request)&& ...
                isfield(request,'proof_options')&& ...
                isfield(request.proof_options,'robust_tube_enabled')&& ...
                isequal(logical(request.proof_options.robust_tube_enabled), ...
                    obj.ROBUST_TUBE_ENABLED), ...
                'TRAJECTORY_GENERATOR:TubeFlag', ...
                'Search robust tube mode must match the generator.');
            result=TRAJECTORY_SIMULTANEOUS_C7_SEARCH(request);
            assert(~result.safe_to_commit, ...
                'TRAJECTORY_GENERATOR:UnsafeCommit', ...
                'Nominal geometry alone must never authorize HLC commit.');
            obj.last_proposal_status=result.status;
        end
        function result=search_reference_feasible_candidate(obj,request)
            % The physically authoritative derivative limits and EKF-now
            % entry checks are imposed INSIDE the SAME NLP. Geometry and
            % C7/yaw checks are independent. The HLC+plant full dynamics
            % are NOT represented by these necessary reference constraints.
            assert(isstruct(request)&&isscalar(request)&& ...
                isfield(request,'candidate_feasibility'), ...
                'TRAJECTORY_GENERATOR:LiveFeasibility', ...
                'Cannot certify reference feasibility without live bounds.');
            result=obj.search_geometric_candidate(request);
            assert(result.candidate_kinematics_enforced && ...
                ~result.safe_to_commit, ...
                'TRAJECTORY_GENERATOR:CommitGuard', ...
                'Feasibility constraints must never authorize HLC commit.');
        end
        function preview=preview_c7_with_existing_model(obj,request)
            % Only the UAV polynomial is sent to the pinned HLC/plant.
            % The load follows the existing model, not a fabricated second
            % independent polynomial. NO physical continuous-time claim.
            assert(isstruct(request)&&isfield(request,'proof_options')&& ...
                isstruct(request.proof_options)&& ...
                isfield(request.proof_options,'robust_tube_enabled')&& ...
                isequal(logical(request.proof_options.robust_tube_enabled), ...
                    obj.ROBUST_TUBE_ENABLED), ...
                'TRAJECTORY_GENERATOR:TubeFlag', ...
                'Model preview must use generator-selected tube mode.');
            preview=TRAJECTORY_HLC_PLANT_CANDIDATE_PREVIEW(request);
            assert(~preview.safe_to_commit, ...
                'TRAJECTORY_GENERATOR:UnsafeCommit', ...
                'A sampled physical model screen cannot authorize HLC commit.');
            obj.last_proposal_status=preview.status;
        end
        function preview=preview_load_flatness_reference(obj,request)
            % New physically COUPLED candidate representation. Unlike the
            % legacy independent polynomial payload, q and UAV position
            % are derived from load acceleration by exact ideal-taut
            % equations. Positive tension has a whole-time Bernstein
            % proof; thrust is checked at reference samples only.
            % This is NOT collision safety, HLC tracking, actuator torque
            % certification, or authorization to change the HLC reference.
            needed={'load_piece','relative_sample_times_s', ...
                'physical_authority','flatness_proof_options', ...
                'yaw_anchor_rad','robust_tube_enabled'};
            assert(isstruct(request)&&isscalar(request)&& ...
                all(isfield(request,needed))&& ...
                isequal(logical(request.robust_tube_enabled), ...
                    obj.ROBUST_TUBE_ENABLED), ...
                'TRAJECTORY_GENERATOR:FlatnessRequest', ...
                'Explicit flat-output authority and matching robust mode required.');
            preview=TRAJECTORY_TAUT_FLATNESS.reference_window( ...
                request.load_piece,request.relative_sample_times_s, ...
                request.physical_authority, ...
                request.flatness_proof_options,request.yaw_anchor_rad);
            assert(~preview.safe_to_commit, ...
                'TRAJECTORY_GENERATOR:UnsafeCommit', ...
                'Ideal taut-load flatness cannot alone approve HLC commit.');
            obj.last_proposal_status=preview.status;
        end
        function report=certify_taut_fullbody(obj,load_pieces,observed, ...
                radii,authority,proof_options)
            % Non-polynomial UAV/cable geometry derived from C9 load output.
