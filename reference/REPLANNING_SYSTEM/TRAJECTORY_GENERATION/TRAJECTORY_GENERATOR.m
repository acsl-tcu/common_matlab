        function result=search_then_preview_model(obj,geometry_request,model_request)
            % One NLP with explicitly supplied constraints; the HLC/plant
            % preview runs ONCE on the final candidate, not at every
            % expensive optimizer iteration. This is still a necessary
            % sampled screen, not a full time-domain physical certificate.
            result=struct('status','UNKNOWN_NOT_STARTED', ...
                'geometry',struct(),'model_preview',struct(), ...
                'candidate_screen_pass',false,'safe_to_commit',false);
            if ~(isstruct(geometry_request)&&isscalar(geometry_request)&& ...
                    isfield(geometry_request,'candidate_feasibility'))
                result.status='UNKNOWN_MISSING_IN_SOLVE_REFERENCE_LIMITS';
                return
            end
            if ~(isstruct(model_request)&&isscalar(model_request)&& ...
                    isfield(model_request,'observed')&& ...
                    isfield(model_request,'proof_options')&& ...
                    isfield(geometry_request,'observed')&& ...
                    isfield(geometry_request,'proof_options')&& ...
                    isequaln(model_request.observed,geometry_request.observed)&& ...
                    isequaln(model_request.proof_options,geometry_request.proof_options))
                result.status='UNKNOWN_STALE_GEOMETRY_OR_TUBE_SNAPSHOT';
                return
            end
            g=obj.search_reference_feasible_candidate(geometry_request);
            result.geometry=g;
            if ~g.certified_geometry || ~g.candidate_available
                result.status='NO_REFERENCE_FEASIBLE_CANDIDATE';
                return
            end
            model_request.piece=g.pieces.uav;
            p=obj.preview_c7_with_existing_model(model_request);
            result.model_preview=p;
            result.candidate_screen_pass=p.screen_pass;
            if p.screen_pass
                result.status='IN_SOLVE_KINEMATICS_AND_MODEL_SCREEN_PASS__COMMIT_FORBIDDEN';
            else
                result.status=['REFERENCE_FEASIBILITY_PASS_MODEL_' p.status];
            end
        end
        function commit(~,varargin) %#ok<INUSD>
            error('TRAJECTORY_GENERATOR:CommitNotCertified', ...
                'No certified generator candidate is implemented: HLC reference must stay unchanged.');
        end
        function status=get_status(obj)
            status=struct('robust_tube_enabled',obj.ROBUST_TUBE_ENABLED,...
                'failure_backup_enabled',obj.FAILURE_BACKUP_ENABLED,...
                'plan_revision',obj.committed_plan_revision,...
                'last_proposal_status',obj.last_proposal_status,...
                'allow_uncertified_commit',false);
        end
