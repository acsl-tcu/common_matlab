            % A trace match cannot certify continuous closed-loop tracking.
            report=TRAJECTORY_C9_HLC_TICK_AUDIT( ...
                piece,authority,log_input);
            assert(~report.safe_to_commit&& ...
                ~report.physical_continuous_time_certified, ...
