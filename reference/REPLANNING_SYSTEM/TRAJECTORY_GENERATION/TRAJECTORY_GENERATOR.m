            % physically coupled UAV/payload/cable, never independent paths.
            assert(isstruct(proof_options)&&isfield(proof_options, ...
                'robust_tube_enabled')&& ...
                isequal(logical(proof_options.robust_tube_enabled), ...
                    obj.ROBUST_TUBE_ENABLED), ...
