function R=TRIGGER_SIM_INITIAL_TAUT_SOURCE()
% Simulation-only deterministic initial 24-state enclosure.
% Read the ACTUALLY ACTIVE runner, Model_Suspended_Load, MODEL_CLASS, EKF.
% Only supports the explicitly observed common_matlab original initialization
% contract. It NEVER reads future plant truth, never edits the runner/plant,
% and is not a real hardware EKF uncertainty theorem.
%
% This source contract proves: at simulation t=0 BEFORE plant stepping,
% plant initial 24-state and EKF posterior first 24 states are identical,
% even though the 25th EKF parameter mL is initialized differently.
% If ANY structural condition changes, the result is UNKNOWN (not zero error).
R=struct('status','UNKNOWN_SIM_INITIAL_SOURCE','reason','', ...
    'source_contract_match',false,'model_class_source_pinned',false, ...
    'sim_initial_taut_exact',false,'initial_ekf_first24_equal_plant',false, ...
    'simulation_initial_set_proven',false, ...
    'initial_time_s',NaN,'initial_lower',zeros(24,0), ...
    'initial_upper',zeros(24,0),'cable_length_m',NaN, ...
    'true_payload_mass_kg',NaN,'ekf_initial_mass_kg',NaN, ...
    'sim_plant_parameter_snapshot_source',false, ...
    'sim_true_mass_rate_bound_kg_s',NaN, ...
    'flight_current_ekf_true_set_proven',false, ...
    'full_4s_physical_safety_proven',false,'safe_to_commit',false);
try
    runner=which('run_flight_headless');
    model=which('Model_Suspended_Load');
    modelclass=which('MODEL_CLASS');
    ekf=which('EKF');
    assert(~isempty(runner)&&isfile(runner)&& ...
        ~isempty(model)&&isfile(model)&& ...
        ~isempty(modelclass)&&isfile(modelclass)&& ...
        ~isempty(ekf)&&isfile(ekf), ...
        'TRIGGER_SIM_INITIAL_TAUT_SOURCE:Missing', ...
        'The actual runner, Model_Suspended_Load, MODEL_CLASS and EKF are required.');
    % Source match is intentionally strict; regex-normalized whitespace only.
    a=clean_source(fileread(runner));
    b=clean_source(fileread(model));
    c=clean_source(fileread(modelclass));
    d=clean_source(fileread(ekf));
    required_runner={ ...
        'ts=0;', ...
        'initial_state.q=[0;0;0];', ...
        'initial_state.w=[0;0;0];', ...
        'initial_state.vL=[0;0;0];', ...
        'initial_state.p=[0;0;0];', ...
        'initial_state.pT=[0;0;-1];', ...
        'initial_state.wL=[0;0;0];', ...
        'initial_state.pL=initial_state.p+initial_state.pT*agent.parameter.cableL;', ...
        'initial_state.v=[0;0;0];', ...
        'agent.plant=MODEL_CLASS(agent,Model_Suspended_Load(dt,initial_state,1,agent));', ...
        'MODEL_CLASS(agent,Model_Suspended_Load(dt,initial_state,1,agent,"Load_mL_HL"))', ...
        'motive.getData(agent);', ...
        'agent.estimator.set_function_class("ekf",'};
    for k=1:numel(required_runner)
        assert(contains(a,required_runner{k}), ...
            'TRIGGER_SIM_INITIAL_TAUT_SOURCE:RunnerContract', ...
            'Required source initialization token missing: %s',required_runner{k});
    end
    assert(contains(b,'Setting.initial=initial;')&& ...
        contains(b,'Setting.initial.vL=[0;0;0];')&& ...
        contains(b,'Setting.initial.wL=[0;0;0];')&& ...
        contains(b,'Setting.initial.mL=agent.parameter.loadmass;')&& ...
        contains(b,'Setting.dim=[24,4,21];')&& ...
        contains(b,'Setting.dim=[25,4,21];'), ...
        'TRIGGER_SIM_INITIAL_TAUT_SOURCE:ModelContract', ...
        'Original 24-state plant/25-state estimator shared initial model changed.');
    assert(contains(c,'obj.state=STATE_CLASS(param);')&& ...
        contains(c,'obj.set_state(param.initial);')&& ...
        contains(c,'if(cha==''q''||cha==''s''||cha==''a'')')&& ...
        contains(c,'obj.param=obj.self.parameter.get("all","row");')&& ...
        contains(c,'ifisempty(obj.param)')&& ...
        contains(d,'obj.result.state=state_copy(obj.model.state);')&& ...
        contains(d,'ifvarargin{1}.t~=0'), ...
        'TRIGGER_SIM_INITIAL_TAUT_SOURCE:Construction', ...
        'Plant/estimator initial state equality or no-step-at-t=0 contract changed.');
    R.model_class_source_pinned=sha_matches(modelclass, ...
        '77a32dad0bdf62a35a8448e8ed1c66d11a1184f33bd07a57794f1ff86f1515f3');
    assert(R.model_class_source_pinned, ...
        'TRIGGER_SIM_INITIAL_TAUT_SOURCE:ModelClassPin', ...
        'MODEL_CLASS must match the previously audited implementation.');
    % Extract, NEVER guess, the simulation parameter literals. This module
    % does not invent fallback mass/length or copy estimator mL into truth.
    mass_positions=strfind(a,'agent.parameter.set("loadmass",');
    cable_positions=strfind(a,'agent.parameter.set("cableL",');
    plant_positions=strfind(a, ...
        'agent.plant=MODEL_CLASS(agent,Model_Suspended_Load(dt,initial_state,1,agent));');
    ekf_positions=strfind(a,'agent.estimator.set_function_class("ekf",');
    assert(numel(mass_positions)>=2 && numel(cable_positions)>=1 && ...
        numel(plant_positions)==1 && numel(ekf_positions)==1 && ...
        mass_positions(1)<plant_positions(1) && ...
        cable_positions(1)<plant_positions(1) && ...
        plant_positions(1)<mass_positions(2) && ...
        mass_positions(2)<ekf_positions(1), ...
        'TRIGGER_SIM_INITIAL_TAUT_SOURCE:ParameterOrder', ...
        ['True plant mass/cable must be set before plant construction, ' ...
        'and estimator mass only AFTER it.']);
    L=single_assignment(a,'agent.parameter.set("cableL",',');');
    mtrue=single_assignment(a,'agent.parameter.set("loadmass",',');');
    mest=single_assignment(a(mass_positions(2):end), ...
        'agent.parameter.set("loadmass",',');');
    % Block an unnoticed reassignment to any initial component before
    % plant construction. Matching one old literal elsewhere is not enough.
    preamble=a(1:plant_positions(1)-1);
    fields={'p','q','v','w','pL','vL','pT','wL'};
    for j=1:numel(fields)
        token=['initial_state.' fields{j} '='];
        assert(numel(strfind(preamble,token))==1, ...
            'TRIGGER_SIM_INITIAL_TAUT_SOURCE:InitialReassignment', ...
            'The initial state field %s is not assigned uniquely.',fields{j});
    end
    R.cable_length_m=L;R.true_payload_mass_kg=mtrue;
    R.ekf_initial_mass_kg=mest;
    % The live model constructor snapshots plant parameters BEFORE the
    % runner changes the estimator-side loadmass. MODEL_CLASS.do only
    % reloads parameters if the stored snapshot is empty. This is a
    % SIMULATION-SOURCE conclusion, not a general mass-transfer law.
    assert(~contains(a,'agent.plant.param='), ...
        'TRIGGER_SIM_INITIAL_TAUT_SOURCE:PlantParamMutation', ...
        'A runner-side plant parameter rewrite invalidates this witness.');
    R.sim_plant_parameter_snapshot_source=true;
    R.sim_true_mass_rate_bound_kg_s=0;

    assert(L>0&&mtrue>0, ...
        'TRIGGER_SIM_INITIAL_TAUT_SOURCE:PhysicalInit', ...
        'True initial cable length and load mass must be finite positive literals.');
    % The SOURCE initializes the 24-vector in this exact order.
    x=zeros(24,1);
    x(19:21)=[0;0;-1];
    x(13:15)=x(1:3)+L*x(19:21);
    R.initial_time_s=0;
    R.initial_lower=x;R.initial_upper=x;
    % No unproved interpolation: source equalities are exact at t=0 in
    % the ideal deterministic MATLAB Sim initialization (before stepping).
    R.source_contract_match=true;
    R.sim_initial_taut_exact=isequal(sum(x(19:21).^2),1) && ...
        isequal(x(13:15),x(1:3)+L*x(19:21)) && ...
        isequal(x(16:18),x(7:9)+L*cross(x(22:24),x(19:21)));
    R.initial_ekf_first24_equal_plant=R.sim_initial_taut_exact;
    R.simulation_initial_set_proven=R.initial_ekf_first24_equal_plant;
    R.status='SIM_T0_DETERMINISTIC_TRUE_24_STATE_SEEDED__NOT_FUTURE_FLIGHT_PROOF';
    R.reason=['The unchanged runner/model/EKF construction pins the same initial ' ...
        '24 state for plant and EKF at Sim t=0, and the joint taut constraint ' ...
        'holds at that instant. The separate 25th EKF mL differs from physical ' ...
        'mL. No present-time error bound after t=0 is inferred without plant ' ...
        'set propagation; hardware initial errors remain unproved.'];
catch ME
    R.reason=[ME.identifier ' | ' ME.message];
end
end
function s=clean_source(s)
% Remove MATLAB comments only in source-audit text; this is a lexical
% cross-check, not arbitrary MATLAB source interpretation.
s=regexprep(s,'(?m)%[^\n]*','');
s=regexprep(s,'\s+','');
s=strrep(s,'...','');
end
function val=single_assignment(source,marker,stopmark)
start=strfind(source,marker);
assert(~isempty(start), ...
    'TRIGGER_SIM_INITIAL_TAUT_SOURCE:AssignmentMissing', ...
    'Required original runner parameter assignment is absent.');
% At the runner initial state preamble, this must be a unique literal.
start=start(1)+numel(marker);
fin=strfind(source(start:end),stopmark);
assert(~isempty(fin), ...
    'TRIGGER_SIM_INITIAL_TAUT_SOURCE:AssignmentEnd');
raw=source(start:start+fin(1)-2);
assert(~isempty(regexp(raw,'^[+]?[0-9]+(\.[0-9]*)?([eE][-+]?[0-9]+)?$', 'once')), ...
    'TRIGGER_SIM_INITIAL_TAUT_SOURCE:Literal', ...
    'Parameter source must be a finite literal, not a dynamic expression.');
val=str2double(raw);
assert(isscalar(val)&&isfinite(val), ...
    'TRIGGER_SIM_INITIAL_TAUT_SOURCE:Finite');
end
function yes=sha_matches(path,expected)
yes=false;
f=fopen(path,'rb');
if f<0,return;end
q=onCleanup(@()fclose(f)); %#ok<NASGU>
bytes=fread(f,inf,'*uint8');
md=java.security.MessageDigest.getInstance('SHA-256');
md.update(typecast(bytes,'int8'));
raw=typecast(int8(md.digest()),'uint8');
yes=strcmp(lower(reshape(dec2hex(raw,2).',1,[])),expected);
end
