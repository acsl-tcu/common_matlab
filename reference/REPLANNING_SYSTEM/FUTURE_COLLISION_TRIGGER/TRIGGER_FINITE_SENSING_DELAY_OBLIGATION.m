function R=TRIGGER_FINITE_SENSING_DELAY_OBLIGATION(C)
% TRIGGER_FINITE_SENSING_DELAY_OBLIGATION
% A necessary piece of the observed-only real-time safety argument:
% conditional, conservative FIRST-RESPONSE clearance after a last complete
% sensor scan. It is NOT a whole-flight viability / replanning proof.
%
% For a taut, CONSTANT-length straight cable of length L, the entire
% swept UAV sphere, cable capsule and load sphere is contained in a ball
% around the CURRENT UAV of radius
%       B=max(ru, L+rc, L+rL).
% With original d_dot=wL x d, ||d||=1, and certified all-time bounds
%       ||vQ|| <= V, ||wL|| <= Omega,
% any material point of the combined body moves at speed <= V+L*Omega.
% At a successful complete true-solid range-R scan, any STILL-UNOBSERVED
% static obstacle O must be farther than R from the current UAV centre.
% Therefore it cannot contact the full body before elapsed delay Delta if
%       R-B-Delta*(V+L*Omega) > 0.
%
% This statement is CONDITIONAL on independently established sensor
% visibility/completeness, true-state velocity/rotation bounds, the taut
% mode, static obstacles, an upper bound on time to the effective reaction,
% and SOUND arithmetic. It does not prove that a recovery exists AFTER
% Delta, nor is it valid for occluded obstacles or an unproved EKF tube.
% Every numerical value must be provided by the real external authority.
% A boolean claim of completeness is NOT itself a proof.
R=struct('status','UNKNOWN_FINITE_SENSING_OBLIGATION','reason','', ...
    'body_extent_m',NaN,'full_body_speed_bound_mps',NaN, ...
    'unseen_initial_clearance_lower_m',NaN, ...
    'worst_reaction_travel_upper_m',NaN,'remaining_clearance_m',NaN, ...
    'conditional_no_contact_until_reaction',false, ...
    'complete_sensor_theorem_proven',false, ...
    'true_reach_speed_theorem_proven',false, ...
    'taut_hybrid_mode_proven',false,'wcet_bound_proven',false, ...
    'outward_rounding_proven',false, ...
    'future_avoidance_feasible_proven',false, ...
    'full_flight_safety_proven',false,'safe_to_commit',false);
try
    required={'sensor_range_m','cable_length_upper_m', ...
        'uav_radius_m','cable_radius_m','payload_radius_m', ...
        'true_uav_speed_upper_mps', ...
        'true_cable_angular_speed_upper_radps', ...
        'elapsed_since_last_complete_scan_upper_s', ...
        'compute_and_actuation_delay_upper_s'};
    assert(isstruct(C)&&isscalar(C)&&all(isfield(C,required)), ...
        'TRIGGER_FINITE_SENSING_DELAY_OBLIGATION:MissingBounds', ...
        'All actual range, body, speed and delay bounds are mandatory.');
    b=zeros(1,numel(required));
    for k=1:numel(required)
        v=C.(required{k});
        assert(isnumeric(v)&&isreal(v)&&isscalar(v)&&isfinite(v), ...
            'TRIGGER_FINITE_SENSING_DELAY_OBLIGATION:InvalidBound', ...
            '%s must be a real finite scalar.',required{k});
        b(k)=double(v);
    end
    assert(all(b>=0) && b(1)>0 && b(2)>0, ...
        'TRIGGER_FINITE_SENSING_DELAY_OBLIGATION:InvalidPhysics', ...
        'Radius, upper speed and time bounds must be nonnegative; range and cable length positive.');
    if ~isfield(C,'sensor_complete_without_occlusion') || ...
            ~isequal(C.sensor_complete_without_occlusion,true)
        R.status='UNKNOWN_OCCLUSION_OR_SENSOR_COMPLETENESS';
        R.reason=['In-range occlusion suppression/missed detections prevent ' ...
            'any guarantee for the still-unobserved world.'];
        return
    end
    R.body_extent_m=max([b(3),b(2)+b(4),b(2)+b(5)]);
    R.full_body_speed_bound_mps=b(6)+b(2)*b(7);
    delta=b(8)+b(9);
    R.unseen_initial_clearance_lower_m=b(1)-R.body_extent_m;
    R.worst_reaction_travel_upper_m=delta*R.full_body_speed_bound_mps;
    R.remaining_clearance_m=R.unseen_initial_clearance_lower_m- ...
        R.worst_reaction_travel_upper_m;
    if R.remaining_clearance_m>0
        R.conditional_no_contact_until_reaction=true;
        R.status='CONDITIONAL_RANGE_DELAY_CLEARANCE__NOT_FLIGHT_SAFETY';
        R.reason=['A still-unseen static solid is conditionally disjoint ' ...
            'from the entire taut body until the specified response time. ' ...
            'Proven speed/latency/sensing provenance, roundoff and future ' ...
            'avoidance feasibility are NOT supplied by this calculation.'];
    else
        R.status='UNKNOWN_RANGE_TOO_SHORT_FOR_SUPPLIED_BOUNDS';
        R.reason=['Finite range and supplied true-body speed/latency ' ...
            'bounds do not certify clearance until reaction.'];
    end
catch ME
    R.reason=[ME.identifier ' | ' ME.message];
end
end
