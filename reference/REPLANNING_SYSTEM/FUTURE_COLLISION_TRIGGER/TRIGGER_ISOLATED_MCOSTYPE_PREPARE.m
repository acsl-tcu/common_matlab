function [R,fixture]=TRIGGER_ISOLATED_MCOSTYPE_PREPARE(static_order, f)
% Pure software-only preflight probe of the actual MCOS access route.
% Runs TRIGGER_FLIGHT_AUTHORITY.current on THROWN-AWAY instances of the
% original TIME / DRONE / DRONE_PARAM_SUSPENDED_LOAD / STATE_CLASS classes.
%
% NOT read: original agent, real EKF, observed or unobserved obstacles,
% real reference values, future Flight starting time, or Sim LOGGER.
% NOT called: controller.do, plant model, sensor.observe, trigger.evaluate.
% NOT changed: physical authority, real agent, sensor memory, real caches.
% Never grants collision safety, warm JIT state, or event/adoption permission.
fixture=struct();
R=struct('status','NOT_RUN','calls',0,'same_mcos_classes',false, ...
    'used_live_state',false,'used_obstacle_definitions',false, ...
    'used_flight_epoch',false,'published_events',false, ...
    'safe_to_commit',false,'reason','');
try
    must_have={'sample_dt_s','model_parameters','loadmass_index', ...
        'cable_length_m','plant_rhs','plant_solver','hlc_param', ...
        'r_uav_m','r_payload_m','r_cable_m'};
    assert(isstruct(f)&&isscalar(f)&&all(isfield(f,must_have)), ...
        'TRIGGER_MCOS:StaticBinding','A verified static plant/HLC binding is required.');
    names=reshape(string(static_order),1,[]);
    nums=reshape(double(f.model_parameters),1,[]);
    assert(numel(names)==numel(nums)&&all(isfinite(nums))&& ...
        numel(unique(names))==numel(names)&&all(strlength(names)>0), ...
        'TRIGGER_MCOS:StaticOrder','Static parameter names/values mismatch.');
    % The original parameter class has a fixed model-authoritative order.
    % Never guess a different plant layout or silently remap parameters.
    required=["mass","Lx","Ly","lx","ly","jx","jy","jz", ...
        "gravity","km1","km2","km3","km4","k1","k2", ...
        "k3","k4","rotor_r","Length","loadmass","cableL"];
    assert(isequal(names,required), ...
        'TRIGGER_MCOS:StaticOrder','Unexpected parameter layout; skip fixture.');
    p=struct();
    for i=1:numel(names)
        p.(char(names(i)))=nums(i);
    end
    % Only in this disposable synthetic object: require positive toy mL
    % even when the real pre-arm estimator mass has not been initialized.
    % This value is NEVER a fallback for real Flight or a proof hypothesis.
    if ~(isfinite(p.loadmass)&&p.loadmass>0)
        p.loadmass=1;
    end
    dt=double(f.sample_dt_s);
    L=double(f.cable_length_m);
    assert(all(isfinite([dt L]))&&dt>0&&L>0, ...
        'TRIGGER_MCOS:StaticTime','Expected positive static dt and cable length.');
    synthetic_time=TIME(0,dt,10);
    synthetic_agent=DRONE(struct('type',"sim"));
    % DRONE_PARAM_SUSPENDED_LOAD uses param.NAME name-value arguments.
    % The previous positional ("row", p) call is NOT supported by this
    % MATLAB version: it fails with invalid name "row" before any MCOS
    % current() call. Supply EACH model-authoritative name/value by name.
    nv=cell(1,2*numel(names));
    for j=1:numel(names)
        nv{2*j-1}=char(names(j));
        nv{2*j}=p.(char(names(j)));
    end
    synthetic_agent.parameter=DRONE_PARAM_SUSPENDED_LOAD( ...
        "TRIGGER_SYNTHETIC_MCOSTYPE",nv{:});
    assert(isequal(reshape(string(synthetic_agent.parameter.parameter_order),1,[]),names), ...
        'TRIGGER_MCOS:ParameterClass','Synthetic parameter layout mismatch.');
    sparam=struct('state_list', ...
        ["p","q","v","w","pL","vL","pT","wL","mL"], ...
        'num_list',[3 3 3 3 3 3 3 3 1]);
    s=STATE_CLASS(sparam);
    s.p=zeros(3,1);s.q=zeros(3,1);s.v=zeros(3,1);
    s.w=zeros(3,1);s.pL=[0;0;-L];s.vL=zeros(3,1);
    s.pT=[0;0;-1];s.wL=zeros(3,1);s.mL=p.loadmass;
    synthetic_agent.estimator.result=struct('state',s);
    plant_state=STATE_CLASS(struct('state_list', ...
        ["p","q","v","w","pL","vL","pT","wL"], ...
        'num_list',3*ones(1,8)));
    synthetic_agent.plant=struct('method',f.plant_rhs, ...
        'solver',f.plant_solver,'dt',dt,'state',plant_state, ...
        'param',nums);
    synthetic_agent.controller.set_function_class( ...
        'hlc_suspended',HLC_SUSPENDED_LOAD(synthetic_agent,f.hlc_param));
    geom=struct('r_uav_m',double(f.r_uav_m), ...
        'r_payload_m',double(f.r_payload_m), ...
        'r_cable_m',double(f.r_cable_m));
    if isfield(f,'horizon_s'),geom.horizon_s=double(f.horizon_s);end
    % The closure below is never evaluated: it only matches the required
    % reference_at function-handle contract at current()'s call boundary.
    artificial_reference=@(t) zeros(28,1); %#ok<NASGU>
    b=TRIGGER_FLIGHT_AUTHORITY(synthetic_time,synthetic_agent, ...
        @()geom,artificial_reference);
    for k=1:8
        synthetic_time.t=(k-1)*dt;
        [ekf,authority]=b.current(synthetic_time,synthetic_agent,artificial_reference);
        assert(isstruct(ekf)&&isstruct(authority)&& ...
            isfield(authority,'verified_native_binding')&& ...
            numel(fieldnames(ekf))==8 && ...
            all(isfinite([ekf.p;ekf.pL;ekf.pT])) && ...
            authority.payload_mass_kg>0, ...
            'TRIGGER_MCOS:Current','The real MCOS current() path failed.');
        R.calls=k;
    end
    R.same_mcos_classes=isa(synthetic_time,'TIME')&& ...
        isa(synthetic_agent,'DRONE')&& ...
        isa(synthetic_agent.parameter,'DRONE_PARAM_SUSPENDED_LOAD')&& ...
        isa(s,'STATE_CLASS');
    assert(R.same_mcos_classes,'TRIGGER_MCOS:ClassMismatch', ...
        'Disposable instance classes do not match the original path.');
    fixture=struct('time',synthetic_time,'agent',synthetic_agent, ...
        'authority',b,'cable_length_m',L,'sample_dt_s',dt);
    R.status='PASS_SYNTHETIC_REAL_MCOSTYPE_CURRENT_8__NO_JIT_OR_SAFETY_PROOF';
catch ME
    R.status='NOT_COMPLETED_SYNTHETIC_REAL_MCOSTYPE';
    R.reason=[ME.identifier ' | ' ME.message];
end
end
