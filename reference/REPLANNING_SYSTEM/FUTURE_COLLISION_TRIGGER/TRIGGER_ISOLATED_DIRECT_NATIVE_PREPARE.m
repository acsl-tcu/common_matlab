function W=TRIGGER_ISOLATED_DIRECT_NATIVE_PREPARE(cfg)
% Throwaway PRE-ARM software exercise. Flight time, sensor world, EKF,
% obstacle count and actual reference epoch are never read in this function.
% The two->three fixture is CODE COVERAGE, never a preset detection mask.
% Every synthetic observation comes from the genuine simulated sensor, with
% EXACT same-tick synthetic EKF position and physically consistent taut d.
% No cache/state from this function can enter a live Flight.
W=struct('status','NOT_RUN_DISCARDED_SENSOR_TWO_TO_THREE', ...
    'pass',false,'first_acquisition_calls',0,'append_calls',0, ...
    'reuse_calls',0,'sensor_observation_calls',0, ...
    'verified_append_transitions',0,'outer_append_transitions',0, ...
    'actual_sensor_schema_used',false,'taut_fixture_correct',false, ...
    'reason','','safe_to_commit',false);
try
    names={'native_binding','numeric_tolerances','sample_dt_s', ...
        'horizon_s','cable_length_m','r_uav_m','r_payload_m','r_cable_m'};
    assert(isstruct(cfg)&&isscalar(cfg)&&all(isfield(cfg,names)), ...
        'TRIGGER_ISOLATED_DIRECT_NATIVE_PREPARE:Config', ...
        'A validated, source-pinned STATIC Flight model binding is required.');
    dt=double(cfg.sample_dt_s);L=double(cfg.cable_length_m);
    assert(isscalar(dt)&&isscalar(L)&&isfinite(dt)&&isfinite(L) && ...
        dt>0&&L>0, 'TRIGGER_ISOLATED_DIRECT_NATIVE_PREPARE:Physical');
    pin=TRIGGER_NATIVE_SOURCE_PIN_CACHE('get');
    assert(isstruct(pin)&&isfield(pin,'passed')&&isequal(pin.passed,true), ...
        'TRIGGER_ISOLATED_DIRECT_NATIVE_PREPARE:NativePin', ...
        'An independently source-pinned original HLC/plant MEX is required.');
    b=cfg.native_binding;
    assert(isstruct(b)&&isfield(b,'native_source_order_checked')&& ...
        isequal(b.native_source_order_checked,true), ...
        'TRIGGER_ISOLATED_DIRECT_NATIVE_PREPARE:Binding', ...
        'Original live-model parameter ordering must be verified.');
    % Explicitly SYNTHETIC positive load mass, no real/estimated load-mass
    % fallback; it is never written back to the source binding.
    b.model_parameters(20)=1;
    b.hlc_parameter_values(b.hlc_loadmass_index)=1;
    mock=struct('estimator',struct('result',struct('state',struct())));
    nominal=TIME_VARYING_REFERENCE(mock, ...
        {'TRIGGER_SOFTWARE_FIXTURE_REFERENCE_FACTORY',{}});
    nominal.t=0; % Disposable fixture clock, NOT Flight epoch.
    purity=TRIGGER_REFERENCE_WINDOW_CACHE();
    check=purity.audit_immutable_source(nominal.func);
    assert(check.eligible, ...
        'TRIGGER_ISOLATED_DIRECT_NATIVE_PREPARE:SourcePurity', ...
        'A pure mathematical fixture reference is required.');

    % Fictional geometry is used only in this discarded test. For range
    % 0.8 m: x=0 detects exactly two; x=1 newly detects the third while
    % the first disappears from *current* detection but remains observed.
    % These numerical coordinates and IDs do NOT encode runtime world data.
    o1=OBSTACLE_INFORMATION.define(70001,'sphere',[-0.5;0;0],0.15);
    o2=OBSTACLE_INFORMATION.define(70002,'cylinder',[0.5;0;0],[0.15 0.4]);
    o3=OBSTACLE_INFORMATION.define(70003,'box',[1.5;0;0],[0.3 0.3 0.3]);
    fiction=[o1 o2 o3];
    for k=1:8
        sensor=SIMULATED_OBSTACLE_SENSOR(fiction,0.8,false);
        memory=OBSERVED_OBSTACLE_MEMORY(fiction([]));
        core=FUTURE_COLLISION_TRIGGER(struct('horizon_s',cfg.horizon_s));
        core.prepare_static_timing(dt,cfg.horizon_s);
        cache=TRIGGER_REFERENCE_WINDOW_CACHE();
        cache.audit_immutable_source(nominal.func);
        a=struct('runtime',cfg,'payload_mass_kg',1, ...
            'reference_at',@(tt)[0;0;-L;zeros(25,1)], ...
            'predictor',[], ...
            'verified_native_binding',b, ...
            'current_time_s',0, ...
            'authority_binding_policy','DISCARDED_SYNTHETIC_NO_FLIGHT', ...
            'actual_hlc_mass_source_kg',1, ...
            'hlc_mass_matches_estimator',true, ...
            'model_authority','SYNTHETIC_ONLY_SOURCE_PINNED', ...
            'native_reference_cache',cache, ...
            'native_reference_source',nominal, ...
            'native_reference_contract', ...
                'VERIFIED_F_PHASE_NOMINAL_Z_MINUS_CABLEL', ...
            'native_validated_now_time_s',0, ...
            'native_validated_now_jet',[0;0;-L;zeros(25,1)], ...
            'numeric_tolerances',cfg.numeric_tolerances);
        t=0;
        sensor_position=[0;0;0];
        f=sensor.observe(t,sensor_position);
        W.sensor_observation_calls=W.sensor_observation_calls+1;
        assert(isequal(reshape(double(f.detected_ids),1,[]), ...
                [70001 70002]), ...
            'TRIGGER_ISOLATED_DIRECT_NATIVE_PREPARE:TwoObserved', ...
            'The synthetic real sensor must observe exactly two obstacles.');
        memory.update(f);
        known=memory.known_frame_for_trigger(f);
        first_shapes=sensor.observed_prepared_only([70001 70002]);
        assert(isstruct(first_shapes)&&numel(first_shapes)==2 && ...
            all(isfield(first_shapes,{'id','center0','bounding_radius_m'})));
        known.prepared_sensor_shapes=first_shapes;
        e=local_current_taut(sensor_position,L);
        assert(isequal(known.uav_position_ekf_m,e.p));
        a.native_validated_now_time_s=t;
        r=core.evaluate(t,e,known,a);
        assert(r.prediction_complete && ...
            strcmp(r.predictor_dispatch,'DIRECT_NATIVE_VERIFIED_BINDING')&& ...
            ~r.safe_to_commit, ...
            'TRIGGER_ISOLATED_DIRECT_NATIVE_PREPARE:InitialNative', ...
            'Real-schema initial two-solid native dispatch did not complete.');
        W.first_acquisition_calls=W.first_acquisition_calls+1;

        t=dt;
        sensor_position=[1;0;0];
        f=sensor.observe(t,sensor_position);
        W.sensor_observation_calls=W.sensor_observation_calls+1;
        assert(isequal(reshape(double(f.detected_ids),1,[]), ...
                [70002 70003]), ...
            'TRIGGER_ISOLATED_DIRECT_NATIVE_PREPARE:NewObserved', ...
            'The third synthetic solid must be newly detected while first leaves.');
        memory.update(f);
        known=memory.known_frame_for_trigger(f);
        assert(isequal(reshape(double(known.detected_ids),1,[]), ...
            [70001 70002 70003]));
        third_shape=sensor.observed_prepared_only(70003);
        known.prepared_sensor_shapes=[reshape(first_shapes,1,[]) ...
            reshape(third_shape,1,[])];
        e=local_current_taut(sensor_position,L);
        assert(isequal(known.uav_position_ekf_m,e.p));
        a.native_validated_now_time_s=t;
        r=core.evaluate(t,e,known,a);
        assert(r.prediction_complete && ...
            strcmp(r.predictor_dispatch,'DIRECT_NATIVE_VERIFIED_BINDING')&& ...
            ~r.safe_to_commit, ...
            'TRIGGER_ISOLATED_DIRECT_NATIVE_PREPARE:IncrementalNative', ...
            'Real-schema incremental native dispatch did not complete.');
        W.append_calls=W.append_calls+1;

        t=2*dt;
        f=sensor.observe(t,sensor_position);
        W.sensor_observation_calls=W.sensor_observation_calls+1;
        memory.update(f);
        known=memory.known_frame_for_trigger(f);
        known.prepared_sensor_shapes=[reshape(first_shapes,1,[]) ...
            reshape(third_shape,1,[])];
        assert(isequal(known.uav_position_ekf_m,e.p));
        a.native_validated_now_time_s=t;
        r=core.evaluate(t,e,known,a);
        assert(r.prediction_complete && ...
            strcmp(r.predictor_dispatch,'DIRECT_NATIVE_VERIFIED_BINDING')&& ...
            ~r.safe_to_commit, ...
            'TRIGGER_ISOLATED_DIRECT_NATIVE_PREPARE:ReuseNative', ...
            'Real-schema reuse native dispatch did not complete.');
        W.reuse_calls=W.reuse_calls+1;
        counts=core.static_preparation_status();
        W.verified_append_transitions=W.verified_append_transitions+ ...
            counts.incremental_verified_appends;
        W.outer_append_transitions=W.outer_append_transitions+ ...
            counts.incremental_outer_appends;
    end
    assert(W.first_acquisition_calls==8&&W.append_calls==8&& ...
        W.reuse_calls==8&&W.sensor_observation_calls==24&& ...
        W.verified_append_transitions==8&& ...
        W.outer_append_transitions==8, ...
        'TRIGGER_ISOLATED_DIRECT_NATIVE_PREPARE:Coverage', ...
        'Genuine synthetic two-to-three and reuse paths must each run 8 times.');
    W.actual_sensor_schema_used=true;
    W.taut_fixture_correct=true;
    W.pass=true;
    W.status='PASS_DISCARDED_TWO_TO_THREE_REAL_SENSOR_NATIVE__NO_JIT_GUARANTEE';
catch ME
    W.status=['NOT_COMPLETED_DISCARDED_TWO_TO_THREE_NATIVE__' ME.identifier];
    W.reason=[ME.identifier ' | ' ME.message];
end
end

function e=local_current_taut(p,L)
% Source-derived manifold pL-pQ-L*d=0; d points to the load.
% Previous +e3 with pL below UAV was physically inconsistent.
e=struct('p',double(p(:)), 'q',zeros(3,1), ...
    'v',zeros(3,1),'w',zeros(3,1), ...
    'pL',double(p(:))+[0;0;-L], 'vL',zeros(3,1), ...
    'pT',[0;0;-1], 'wL',zeros(3,1));
assert(norm(e.pL-e.p-L*e.pT,inf)==0 && ...
    norm(e.vL-e.v-L*cross(e.wL,e.pT),inf)==0);
end
