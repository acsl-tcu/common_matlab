function R=TRIGGER_EKF_ERROR_SET_RECURSION(C)
% TRIGGER_EKF_ERROR_SET_RECURSION  Deterministic outer error-set step.
%
% If, and ONLY if, the TRUE error of the original EKF satisfies
%   e_{k+1} = A_k*e_k + d_k
% with A_k in [A_lower,A_upper], d_k in [d_lower,d_upper]
% for every admissible true state/noise/mode, this interval computation
% encloses the TRUE next error. A_k may also describe a discrete reset;
% the bounds must cover that exact discrete event.
%
% The existence/validity of these matrices is NOT inferred from an EKF
% covariance, numerical samples or a user-declared Boolean. A Gaussian
% covariance alone never supplies a deterministic bounded-error theorem.
% No external authority, default noise bound, actual Flight data or
% trajectory is accessed here. This routine NEVER grants flight safety.
R=struct('status','UNKNOWN_EKF_ERROR_RECURSION','reason','', ...
    'conditional_enclosure',false,'rounding_backend_audited',false, ...
    'original_EKF_error_transition_audited',false, ...
    'next_error_lower',zeros(24,0), ...
    'next_error_upper',zeros(24,0), ...
    'safe_to_commit',false);
try
    required={'time_before_s','time_after_s', ...
        'error_lower','error_upper', ...
        'A_lower','A_upper','disturbance_lower','disturbance_upper'};
    assert(isstruct(C)&&isscalar(C)&&all(isfield(C,required)), ...
        'TRIGGER_EKF_ERROR_SET_RECURSION:Required', ...
        'True error-transition and explicit uncertainty bounds are mandatory.');
    t0=double(C.time_before_s);t1=double(C.time_after_s);
    assert(isscalar(t0)&&isscalar(t1)&&isfinite(t0)&& ...
        isfinite(t1)&&t1>t0, ...
        'TRIGGER_EKF_ERROR_SET_RECURSION:Time', ...
        'Time steps must be finite, strictly increasing and runtime supplied.');
    el=double(C.error_lower);eu=double(C.error_upper);
    al=double(C.A_lower);au=double(C.A_upper);
    dl=double(C.disturbance_lower);du=double(C.disturbance_upper);
    assert(isequal(size(el),[24,1])&&isequal(size(eu),[24,1]) && ...
        isequal(size(dl),[24,1])&&isequal(size(du),[24,1]) && ...
        isequal(size(al),[24,24])&&isequal(size(au),[24,24]) && ...
        all(isfinite([el;eu;dl;du])) && ...
        all(isfinite(al(:)))&&all(isfinite(au(:))) && ...
        all(el<=eu)&&all(dl<=du)&&all(al(:)<=au(:)), ...
        'TRIGGER_EKF_ERROR_SET_RECURSION:Bounds', ...
        'Finite ordered 24-state error and transition intervals are required.');
    lo=zeros(24,1);hi=zeros(24,1);
    for i=1:24
        z=TRIGGER_OUTWARD_INTERVAL(dl(i),du(i));
        for j=1:24
            z=z+TRIGGER_OUTWARD_INTERVAL(al(i,j),au(i,j)).* ...
                TRIGGER_OUTWARD_INTERVAL(el(j),eu(j));
        end
        lo(i)=z.lo;hi(i)=z.hi;
    end
    R.next_error_lower=lo;
    R.next_error_upper=hi;
    R.conditional_enclosure=true;
    R.status='CONDITIONAL_DISCRETE_EKF_ERROR_ENCLOSURE__SOURCE_NOT_PROVED';
    R.reason=['This recurrence encloses the original EKF error ONLY if ' ...
        'its exact original predictor/corrector/reset dynamics and all ' ...
        'disturbances are independently enclosed by the supplied A and d. ' ...
        'The current MATLAB interval arithmetic backend still requires ' ...
        'independent directed-rounding certification.'];
catch ME
    R.reason=[ME.identifier ' | ' ME.message];
end
end
