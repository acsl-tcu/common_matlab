function R=TRIGGER_EKF_TAUT_ANCHOR_ERROR(E)
% TRIGGER_EKF_TAUT_ANCHOR_ERROR  Whole straight taut cable, NO spherical sweep.
% Original 24-state model: UAV p=x(1:3), payload pL=x(13:15).
% For every cable coordinate s in [0,1]:
%   c_true(s)-c_nom(s)=(1-s)*e_Q+s*e_L.
% Consequently its Euclidean error is <= max(rho_Q,rho_L).
% Works for all obstacle shapes; does not assume where an obstacle lies.
R=struct('status','UNKNOWN_ERROR_SET_NOT_BOUND', ...
    'rho_uav_m',NaN,'rho_payload_m',NaN, ...
    'rho_full_cable_m',NaN,'safe_to_commit',false);
assert(isstruct(E)&&isscalar(E)&&isfield(E,'initialized')&& ...
    isequal(E.initialized,true)&&isfield(E,'error_lower')&& ...
    isfield(E,'error_upper'), ...
    'TRIGGER_EKF_TAUT_ANCHOR_ERROR:Unknown', ...
    'A live conditional EKF true-state enclosure is required.');
lo=double(E.error_lower(:));hi=double(E.error_upper(:));
assert(numel(lo)==24&&numel(hi)==24 && ...
    all(isfinite(lo))&&all(isfinite(hi))&&all(lo<=hi), ...
    'TRIGGER_EKF_TAUT_ANCHOR_ERROR:Box', ...
    '24-dimensional ordered error bounds required.');
a=max(abs(lo([1 2 3])),abs(hi([1 2 3])));
b=max(abs(lo([13 14 15])),abs(hi([13 14 15])));
ru=norm(a);rl=norm(b);
R.rho_uav_m=TRIGGER_FLOAT_OUTWARD_ONE_ULP(ru,+1);
R.rho_payload_m=TRIGGER_FLOAT_OUTWARD_ONE_ULP(rl,+1);
R.rho_full_cable_m=max(R.rho_uav_m,R.rho_payload_m);
R.status='CONDITIONAL_ENDPOINT_ERROR_TO_ALL_TAUT_CABLE';
end
