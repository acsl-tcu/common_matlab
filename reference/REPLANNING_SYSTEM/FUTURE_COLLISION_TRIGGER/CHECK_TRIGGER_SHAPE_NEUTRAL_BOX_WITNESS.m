function A=CHECK_TRIGGER_SHAPE_NEUTRAL_BOX_WITNESS()
% Disposable root-level conditional geometry audit; NO physical Flight proof.
root=fileparts(mfilename('fullpath'));
A=struct('status','FAIL_BOX_OUTER_MATH','cases',0,'failures',0, ...
    'positives',0,'negative_controls',0,'flight_safe_grants',0, ...
    'reason','');
prior=rng;
cleaner=onCleanup(@()rng(prior)); %#ok<NASGU>
rng(20261105,'twister');
try
    rad=[0.15 0.2 0.025];
    for j=1:500
        % Box center/width and original straight cable endpoints are drawn
        % independently; no fixed obstacle number or body orientation.
        x=2*randn(3,1);y=x+[0;0;-2]+0.2*randn(3,1);
        qlo=x-0.1*rand(3,1);qhi=x+0.1*rand(3,1);
        llo=y-0.1*rand(3,1);lhi=y+0.1*rand(3,1);
        c=x+[10+2*rand();rand();rand()]; R=1+rand();
        W=TRIGGER_SHAPE_NEUTRAL_INTERVAL_BOX_WITNESS( ...
            qlo,qhi,llo,lhi,c,R,rad);
        assert(W.all_parts_separated && ~W.safe_to_commit && ...
            ~W.source_outer_ball_verified_here, ...
            'CHECK_BOX_OUTER:Far','Conservative far-ball witness did not pass.');
        A.cases=A.cases+1;A.positives=A.positives+1;
        % A witness must prove separation for every point in both boxes and
        % every point on every corresponding taut segment. The test uses
        % the worst-case enclosing ball, not an ellipsoid model.
        for k=1:10
            q=qlo+(qhi-qlo).*rand(3,1);
            l=llo+(lhi-llo).*rand(3,1);
            a=rand();p=q+a*(l-q);
            assert(norm(q-c)>R+rad(1) && ...
                norm(l-c)>R+rad(2) && ...
                norm(p-c)>R+rad(3), ...
                'CHECK_BOX_OUTER:FalseClear', ...
                'The witness excluded a genuine ball material contact.');
        end
        % Near body: no positive claim is possible by an axis gap.
        B=TRIGGER_SHAPE_NEUTRAL_INTERVAL_BOX_WITNESS( ...
            qlo,qhi,llo,lhi,x,1,rad);
        assert(~B.all_parts_separated && ~B.safe_to_commit, ...
            'CHECK_BOX_OUTER:Near','Near obstacle was incorrectly excluded.');
        A.cases=A.cases+1;A.negative_controls=A.negative_controls+1;
    end
    bad=TRIGGER_SHAPE_NEUTRAL_INTERVAL_BOX_WITNESS( ...
        [0;0;0],[0;0;0],[0;0;-2],[0;0;-2],[20;0;0],NaN,rad);
    assert(~bad.all_parts_separated && ~bad.safe_to_commit, ...
        'CHECK_BOX_OUTER:NaN','Nonfinite authority must refuse.');
    A.cases=A.cases+1;A.negative_controls=A.negative_controls+1;
    % Integration regression: the only fast path in the conditional flowpipe
    % requires an explicit authenticated outer-ball certificate tag.
    q=[0;0;0];l=[0;0;-2];
    F=struct('conditional_chain_pass',true,'completed_intervals',2, ...
        'conditional_tension_positive_all_intervals',true, ...
        'manifold_compatible_intervals',true(1,2), ...
        'tube_lower',zeros(24,2),'tube_upper',zeros(24,2));
    % Each hold is a separate column: do not assign a 3x1 endpoint
    % into a 3x2 interval matrix (MATLAB forbids implicit expansion here).
    % Distinct hold endpoints also exercise K-column indexing explicitly.
    q_per_hold=[q, q+[0.2;0;0]];
    l_per_hold=[l, l+[0.2;0;0]];
    assert(isequal(size(q_per_hold),[3 2]) && ...
        isequal(size(l_per_hold),[3 2]), ...
        'CHECK_BOX_OUTER:HoldLayout','Expected two explicit 3-D hold columns.');
    F.tube_lower(1:3,:)=q_per_hold;
    F.tube_upper(1:3,:)=q_per_hold;
    F.tube_lower(13:15,:)=l_per_hold;
    F.tube_upper(13:15,:)=l_per_hold;
    S=struct('id',314,'center0',[20;0;0], ...
        'bounding_radius_m',1,'is_stationary',true, ...
        'rigorous_outer_ball_certified',true, ...
        'type','sphere','dimensions',1,'rotation',eye(3));
    C=struct('flowpipe',F,'time_grid_s',[0 2 4], ...
        'observed_prepared_shapes',S,'observed_ids',314, ...
        'body',struct('r_uav_m',rad(1), ...
           'r_payload_m',rad(2),'r_cable_m',rad(3)));
    Y=TRIGGER_TAUT_TRUE_SHAPE_FLOWPIPE_GATE(C);
    assert(Y.conditional_geometry_pass && ...
        Y.certified_outer_box_exclusions==2 && ...
        Y.distance_queries==0 && ~Y.safe_to_commit, ...
        'CHECK_BOX_OUTER:Integration', ...
        'Certified box gate did not short circuit two holds.');
    A.cases=A.cases+1;
    S.rigorous_outer_ball_certified=false;
    C.observed_prepared_shapes=S;
    Z=TRIGGER_TAUT_TRUE_SHAPE_FLOWPIPE_GATE(C);
    assert(Z.conditional_geometry_pass && ...
        Z.certified_outer_box_exclusions==0 && ...
        Z.distance_queries>=4 && ...
        isequal(Z.separated_intervals,true(1,2)) && ...
        ~Z.safe_to_commit, ...
        'CHECK_BOX_OUTER:Untrusted', ...
        'Unattested outer-ball geometry must follow the original oracle.');
    A.cases=A.cases+1;
    A.status='PASS_SHAPE_NEUTRAL_INTERVAL_BOX__CONDITIONAL';
catch ME
    A.failures=A.failures+1;
    A.reason=[ME.identifier ' | ' ME.message];
end
save(fullfile(root,'TRIGGER_SHAPE_NEUTRAL_BOX_RESULT.mat'),'A');
file=fopen(fullfile(root,'TRIGGER_SHAPE_NEUTRAL_BOX_RESULT.txt'),'w');
if file>=0
    fprintf(file,'status=%s\ncases=%d\nfailures=%d\npositives=%d\nnegative_controls=%d\nsafe_to_commit=0\nreason=%s\n', ...
        A.status,A.cases,A.failures,A.positives,A.negative_controls,A.reason);
    fclose(file);
end
end
