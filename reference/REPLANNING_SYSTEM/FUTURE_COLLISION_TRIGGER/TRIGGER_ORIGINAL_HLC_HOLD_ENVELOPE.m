function R=TRIGGER_ORIGINAL_HLC_HOLD_ENVELOPE(time_grid_s)
% Source-derived conservative 4-channel HLC input enclosure, one per
% mathematical interval of an ARBITRARY COMPUTATIONAL time partition.
% Source byte pin is independently read from original MODEL_CLASS/HLC.
% For ALL measurable input traces u(t) in the universal saturation box,
% the interval plant RHS f(Z,U,P) encloses the derivative even if HLC
% switches several times WITHIN one computed interval. The time grid is
% NOT required to match future HLC events; this removes an unnecessary
% scheduling proof obligation. It remains conditional on the actual
% applied input being finite and within source-pinned limits at ALL times.
R=struct('status','UNKNOWN_ACTUAL_HLC_HOLD_ENVELOPE', 'reason','', ...
    'conditional_saturated_hold',false, 'lower',zeros(4,0), ...
    'upper',zeros(4,0),'source',struct(), ...
    'finite_future_hlc_calls_proven',false, ...
    'physical_time_alignment_proven',false, ...
    'universal_input_valid_on_arbitrary_partition',false, ...
    'future_switching_instants_required',false, ...
    'safe_to_commit',false);
try
    assert(isnumeric(time_grid_s)&&isreal(time_grid_s), ...
        'TRIGGER_ORIGINAL_HLC_HOLD_ENVELOPE:ClockType', 'Numeric time grid required.');
    t=double(time_grid_s(:).'); K=numel(t)-1;
    assert(K>=1&&all(isfinite(t))&&all(diff(t)>0), ...
        'TRIGGER_ORIGINAL_HLC_HOLD_ENVELOPE:Clock', ...
        'Exact strictly increasing future hold time boundaries required.');
    S=TRIGGER_ORIGINAL_SIM_ZOH_SOURCE_SCOPE();R.source=S;
    if ~(S.hlc_source_pinned && S.model_source_pinned && ...
            S.sim_direct_controller_input && S.sim_zero_order_hold_source && ...
            S.conditional_applied_input_bounds)
        R.reason=['Original HLC/MODEL_CLASS source not pinned: ' S.reason];
        return
    end
    R.lower=repmat([0;-1;-1;-1],1,K);
    R.upper=repmat([20;1;1;1],1,K);
    R.conditional_saturated_hold=true;  % legacy name/API preserved
    R.universal_input_valid_on_arbitrary_partition=true;
    R.status='CONDITIONAL_ORIGINAL_HLC_ANYTIME_ENVELOPE__APPLIED_INPUT_UNPROVEN';
    R.reason=['For all times with a finite original saturated applied HLC ' ...
        'input, the universal 4-channel box encloses u(t), irrespective ' ...
        'of controller switching times. The Picard partition is numerical, ' ...
        'not the actual controller hold schedule. Source identity alone ' ...
        'does not prove all future inputs finite or physical application.'];
catch ME
    R.reason=[ME.identifier ' | ' ME.message];
end
end
