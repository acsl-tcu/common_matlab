classdef TRIGGER_SIM_TRUE_SET_CONTINUATION < handle
    % Simulation-only t=0 -> actual EKF posterior -> future 4 s bridge.
    %
    % Called AFTER original plant.do in run_flight_headless, but it NEVER
    % reads agent.plant.state. The controller input visible at this point
    % was just applied over [t,t+dt], so we STORE it and use it ONLY when
    % the next genuine EKF posterior at t+dt becomes available.
    %
    % This ordering prevents a one-step future-truth leak. No replanning
    % decision / controller command / source-world obstacle is modified.
    % A failed Picard/tension check invalidates the induction permanently;
    % it must NEVER silently reset at a later EKF sample.
    properties (SetAccess=private)
        initialized = false
        last_time_s = NaN
        last_input = zeros(4,0)
        plant_params = zeros(21,0)
        time_step_s = NaN
        sim_initial = struct()
        ekf_true_tracker = []
        source_scope = struct()
        original_runner_order = struct()
        completed_real_ticks = 0
        repeated_t0_calls = 0
        last_status = 'UNKNOWN_NOT_STARTED'
        last_reason = ''
        last_advance = struct()
        forecast_count = 0
        failure_latched = false
        % The FIRST failed physics/interval obligation is immutable for
        % this Flight. Later cycle calls must not overwrite its reason.
        first_failure_time_s = NaN
        first_failure_prior_time_s = NaN
        first_failure_reason = ''
        first_failure_stage = ''
        first_failure_advance_status = ''
        first_failure_advance_reason = ''
    end
    methods
        function R=observe(obj,t,agent)
            % Failure remains latched with the ORIGINAL evidence. Calling
            % this function again may not conceal the first bad interval.
            if obj.failure_latched
                R=obj.brief();
                return
            end
            R=obj.brief();
            try
                assert(~obj.failure_latched, ...
                    'TRIGGER_SIM_TRUE_SET_CONTINUATION:LatchedFailure', ...
                    'A failed true-set induction cannot be re-seeded inside this Flight.');
                assert(isnumeric(t) && isreal(t) && isscalar(t) && ...
                    isfinite(t), 'TRIGGER_SIM_TRUE_SET_CONTINUATION:Time', ...
                    'Finite scalar actual simulation time required.');
                t=double(t);
                current_post=obj.read_original_ekf_post(agent);
                current_u=obj.read_applied_input(agent);
                current_param=obj.read_original_params(agent);
                if ~obj.initialized
                    % Only the genuine zero-time SIM initialization can
                    % establish the induction anchor. No truth resync.
                    assert(t==0 && obj.completed_real_ticks==0, ...
                        'TRIGGER_SIM_TRUE_SET_CONTINUATION:Origin', ...
                        'Missed Sim t=0. Cannot synthesize a later true set.');
                    order=TRIGGER_SIM_RUNNER_ORDER_PROOF();
                    assert(order.previous_controller_input_alignment_proven && ...
                        order.physical_hold_duration_from_solver_proven, ...
                        'TRIGGER_SIM_TRUE_SET_CONTINUATION:RunnerOrder', ...
                        'The actual Sim run-loop ordering is unverified: %s',order.reason);
                    source=TRIGGER_SIM_INITIAL_TAUT_SOURCE();
                    assert(source.simulation_initial_set_proven && ...
                        source.sim_initial_taut_exact && ...
                        source.sim_plant_parameter_snapshot_source, ...
                        'TRIGGER_SIM_TRUE_SET_CONTINUATION:InitialSource', ...
                        'The original Sim zero-time seed has not been source-proven.');
                    scope=TRIGGER_ORIGINAL_SIM_ZOH_SOURCE_SCOPE();
                    assert(scope.hlc_source_pinned && ...
                        scope.sim_zero_order_hold_source, ...
                        'TRIGGER_SIM_TRUE_SET_CONTINUATION:ZOHSource', ...
                        'Original applied-input read / plant ZOH is not source-pinned.');
                    assert(strcmp(func2str(agent.plant.method), ...
                            'with_load_model_euler_for_HL'), ...
                        'TRIGGER_SIM_TRUE_SET_CONTINUATION:PlantRHS', ...
                        'Active plant RHS differs from original 24-state source.');
                    assert(isequal(current_param(20),source.true_payload_mass_kg) && ...
                        isequal(current_param(21),source.cable_length_m), ...
                        'TRIGGER_SIM_TRUE_SET_CONTINUATION:PlantParams', ...
                        'Actual numeric plant parameters differ from Sim t0 source.');
                    assert(isequal(current_post,source.initial_lower), ...
                        'TRIGGER_SIM_TRUE_SET_CONTINUATION:InitialPost', ...
                        'Actual initial 24-state EKF posterior differs from plant t0.');
                    obj.ekf_true_tracker=TRIGGER_EKF_TRUE_SET_TRACKER();
                    obj.ekf_true_tracker.seed(t,current_post, ...
                        [source.initial_lower source.initial_upper], ...
                        'SOURCE_VERIFIED_SIM_T0_PLANT_EKF_INITIAL_STATE');
                    obj.plant_params=current_param;
                    obj.time_step_s=double(agent.plant.dt);
                    assert(isscalar(obj.time_step_s) && ...
                        isfinite(obj.time_step_s) && obj.time_step_s>0, ...
                        'TRIGGER_SIM_TRUE_SET_CONTINUATION:PlantDt');
                    obj.source_scope=scope;
                    obj.original_runner_order=order;
                    obj.sim_initial=source;
                    obj.last_time_s=t;
                    obj.last_input=current_u;
                    obj.initialized=true;
                    obj.last_status='SIM_T0_TRUE_SET_AND_FIRST_APPLIED_INPUT_CAPTURED';
                    obj.last_reason='Seeded from original Sim t0 source, no future plant state read.';
                elseif t==obj.last_time_s
                    % The existing runner invokes update twice at t=0:
                    % Arming then the first Takeoff iteration. The second
                    % applied input is the one for the genuine 0->dt step.
                    assert(t==0 && obj.completed_real_ticks==0 && ...
                        isequal(current_post,obj.ekf_true_tracker.ekf_post), ...
                        'TRIGGER_SIM_TRUE_SET_CONTINUATION:DuplicateClock', ...
                        'Only original Sim double t0 is allowed.');
                    obj.last_input=current_u;
                    obj.repeated_t0_calls=obj.repeated_t0_calls+1;
                    obj.last_status='SIM_T0_ACTUAL_FIRST_HOLD_INPUT_REFRESHED';
                    obj.last_reason='Replaced Arming input with genuine first Takeoff input at same t0.';
                else
                    assert(t>obj.last_time_s && ...
                        isequal(current_param,obj.plant_params), ...
                        'TRIGGER_SIM_TRUE_SET_CONTINUATION:ClockOrPlantMutation', ...
                        'Out-of-order sample or mutable original plant parameters.');
                    % Reject a dropped EKF observation; no unobserved
                    % applied HLC inputs can be guessed or filled in.
                    h=TRIGGER_EXACT_BINARY64_TIME_SPAN(obj.last_time_s,t);
                    % The runner accumulates t=t+dt in binary64. A
                    % correctly adjacent sample can differ from dt by
                    % several ulps of the LARGE absolute timestamp; an
                    % eps(dt) tolerance would reject legitimate ticks.
                    % Distinguish one versus two+ observed ticks using
                    % the interval of the accumulated runner timestamp.
                    % The physical Picard duration instead uses the
                    % source-pinned MODEL_CLASS solver dt (see below).
                    assert(h.valid && ...
                        h.lower_s>obj.time_step_s/2 && ...
                        h.upper_s<obj.time_step_s*1.5, ...
                        'TRIGGER_SIM_TRUE_SET_CONTINUATION:MissingTick', ...
                        'Expected exactly one original plant dt between real EKF posteriors.');
                    % MODEL_CLASS.do integrates a physical hold of dt,
                    % independently of the accumulated runner clock.
                    % Fail closed if that source-pinned solver dt mutates.
                    assert(isequal(double(agent.plant.dt),obj.time_step_s), ...
                        'TRIGGER_SIM_TRUE_SET_CONTINUATION:PhysicalDtMutated', ...
                        'Original plant integration step changed during Flight.');
                    step=obj.ekf_true_tracker.advance_original_held_plant( ...
                        obj.last_time_s,t,current_post, ...
                        obj.last_input,obj.last_input, ...
                        obj.plant_params,obj.plant_params, ...
                        'ORIGINAL_SIM_PREVIOUS_ACTUALLY_APPLIED_INPUT', ...
                        obj.time_step_s);
                    obj.last_advance=step;
                    assert(step.conditional_advanced, ...
                        'TRIGGER_SIM_TRUE_SET_CONTINUATION:NoVerifiedTube', ...
                        'Original plant Picard/tension failed: %s',step.reason);
                    obj.completed_real_ticks=obj.completed_real_ticks+1;
                    obj.last_time_s=t;
                    obj.last_input=current_u;
                    obj.last_status='CONDITIONAL_ORIGINAL_T0_TO_ACTUAL_POSTERIOR_CHAIN';
                    obj.last_reason=['A real previous applied input and actual EKF posterior ' ...
                        'are linked by a conditional all-time Picard flowpipe.'];
                end
                R=obj.brief();
            catch ME
                % Preserve the very first failed interval, not the later
                % LatchedFailure error after thousands of Flight ticks.
                obj.first_failure_time_s=double(t);
                obj.first_failure_prior_time_s=obj.last_time_s;
                obj.first_failure_reason=[ME.identifier ' | ' ME.message];
                obj.first_failure_stage='OBSERVE_OR_POSTERIOR';
                if isstruct(obj.last_advance) && ...
                        isfield(obj.last_advance,'conditional_advanced') && ...
                        ~obj.last_advance.conditional_advanced
                    A=obj.last_advance;
                    obj.first_failure_stage='ORIGINAL_HELD_TRUE_SET_ADVANCE';
                    if isfield(A,'status')
                        obj.first_failure_advance_status=A.status;
                    end
                    if isfield(A,'reason')
                        obj.first_failure_advance_reason=A.reason;
                    end
                    if isfield(A,'plant_interval') && ...
                            isstruct(A.plant_interval) && ...
                            isfield(A.plant_interval,'first_failure_stage') && ...
                            ~isempty(A.plant_interval.first_failure_stage)
                        obj.first_failure_stage=A.plant_interval.first_failure_stage;
                    end
                end
                % This failure cannot be re-seeded from the EKF and cannot
                % become a safe clearance on future unknown steps.
                obj.initialized=false;
                obj.failure_latched=true;
                if ~isempty(obj.ekf_true_tracker)
                    obj.ekf_true_tracker.invalidate('UNKNOWN_SIM_CHAIN_INVALIDATED');
                end
                obj.last_status='UNKNOWN_SIM_TRUE_SET_CHAIN_FAIL_CLOSED';
                obj.last_reason=obj.first_failure_reason;
                R=obj.brief();
            end
        end
        function R=predict4s(obj,observed_prepared_shapes,body)
            R=struct('status','UNKNOWN_SIM_4S_CHAIN', ...
                'reason','','time_s',obj.last_time_s, ...
                'real_history_ticks',obj.completed_real_ticks, ...
                'covered_horizon_lower_s',NaN, ...
                't0_to_now_conditional',false, ...
                'future_conditional_chain_pass',false, ...
                'four_second_conditional_clearance',false, ...
                'observed_ids',zeros(1,0), ...
                'possible_risk_ids',zeros(1,0), ...
                'full_sim_physics_numerically_proven',false, ...
                'safe_to_commit',false);
            try
                assert(obj.initialized && ...
                    ~isempty(obj.ekf_true_tracker) && ...
                    obj.ekf_true_tracker.initialized, ...
                    'TRIGGER_SIM_TRUE_SET_CONTINUATION:History', ...
                    'A source-anchored unbroken true-state induction is required.');
                assert(isstruct(observed_prepared_shapes), ...
                    'TRIGGER_SIM_TRUE_SET_CONTINUATION:Observed', ...
                    'Pass only the prepared, genuinely observed static shapes.');
                if ~isempty(observed_prepared_shapes)
                    ids=reshape(double([observed_prepared_shapes.id]),1,[]);
                    assert(all(isfinite(ids)) && ...
                        numel(unique(ids))==numel(ids), ...
                        'TRIGGER_SIM_TRUE_SET_CONTINUATION:ObservedIDs');
                    R.observed_ids=ids;
                    R.possible_risk_ids=ids;
                end
                if isempty(R.observed_ids)
                    R.status='NO_KNOWN_OBSTACLES__UNKNOWN_OUTSIDE_SENSOR';
                    R.reason='No source-world obstacles are inserted into sensor history.';
                    return
                end
                assert(isstruct(body) && isscalar(body) && ...
                    all(isfield(body,{'r_uav_m','r_payload_m','r_cable_m'})), ...
                    'TRIGGER_SIM_TRUE_SET_CONTINUATION:PhysicalRadii', ...
                    'Real physical dimensions, not invented defaults, are mandatory.');
                N=ceil(4/obj.time_step_s);
                assert(N>=1&&N<=1000000, ...
                    'TRIGGER_SIM_TRUE_SET_CONTINUATION:GridLimit', ...
                    'Non-finite or infeasible original simulation grid.');
                t0=obj.last_time_s;
                % Computational slabs need not predict future HLC switch
                % times: universal actuator bounds cover arbitrary switching.
                grid=t0+(0:N)*(4/N);
                % Enforce mathematically >=4s in the exact interpretation
                % of binary64 timestamps (avoid a rounded-up 3.999... gap).
                for j=1:4
                    span=TRIGGER_EXACT_BINARY64_TIME_SPAN(t0,grid(end));
                    if span.valid && span.exact_ge_4s,break;end
                    grid(end)=TRIGGER_FLOAT_OUTWARD_ONE_ULP(grid(end),+1);
                end
                assert(all(diff(grid)>0), ...
                    'TRIGGER_SIM_TRUE_SET_CONTINUATION:GridOrder');
                span=TRIGGER_EXACT_BINARY64_TIME_SPAN(t0,grid(end));
                assert(span.valid&&span.exact_ge_4s, ...
                    'TRIGGER_SIM_TRUE_SET_CONTINUATION:FourSeconds');
                R.covered_horizon_lower_s=span.lower_s;
                n=numel(grid)-1;
                ekf=obj.ekf_true_tracker.ekf_post;
                names={'p','q','v','w','pL','vL','pT','wL'};
                state=struct();
                for j=1:8
                    state.(names{j})=ekf(3*j-2:3*j);
                end
                D=struct('time_grid_s',grid, ...
                    'observation_provenance','ACTUAL_SENSOR_HISTORY_ONLY', ...
                    'observed_prepared_shapes',observed_prepared_shapes, ...
                    'observed_ids',R.observed_ids, ...
                    'true_state_tracker',obj.ekf_true_tracker, ...
                    'ekf_now',state, ...
                    'true_mass_now_lower_kg',obj.plant_params(20), ...
                    'true_mass_now_upper_kg',obj.plant_params(20), ...
                    'true_mass_rate_bound_kg_s', ...
                         obj.sim_initial.sim_true_mass_rate_bound_kg_s, ...
                    'cable_length_lower_m',obj.plant_params(21), ...
                    'cable_length_upper_m',obj.plant_params(21), ...
                    'other_param_lower',repmat(obj.plant_params,1,n), ...
                    'other_param_upper',repmat(obj.plant_params,1,n), ...
                    'body',body);
                F=TRIGGER_CLOSED_LOOP_FROM_SOURCE_LIMITS(D);
                obj.forecast_count=obj.forecast_count+1;
                R.t0_to_now_conditional=true;
                if isfield(F,'chain') && isstruct(F.chain) && ...
                        isfield(F.chain,'conditional_chain_pass')
                    R.future_conditional_chain_pass=F.chain.conditional_chain_pass;
                end
                if isfield(F,'conditional_4s_observed_clearance')
                    R.four_second_conditional_clearance= ...
                        F.conditional_4s_observed_clearance;
                end
                if isfield(F,'possible_risk_ids')
                    R.possible_risk_ids=F.possible_risk_ids;
                end
                R.status=['SIM_SOURCE_CHAIN__' F.status];
                R.reason=F.reason;
                % Cannot certify ode15s numerical step error, all RHS
                % arithmetic and a physically real plant from byte pins.
                R.full_sim_physics_numerically_proven=false;
                R.safe_to_commit=false;
            catch ME
                R.status='UNKNOWN_SIM_4S_CHAIN_FAIL_CLOSED';
                R.reason=[ME.identifier ' | ' ME.message];
                R.possible_risk_ids=R.observed_ids;
            end
        end
        function R=brief(obj)
            R=struct('status',obj.last_status,'reason',obj.last_reason, ...
                'initialized',obj.initialized, ...
                'time_s',obj.last_time_s, ...
                'real_history_ticks',obj.completed_real_ticks, ...
                'duplicate_t0_calls',obj.repeated_t0_calls, ...
                'failure_latched',obj.failure_latched, ...
                'first_failure_time_s',obj.first_failure_time_s, ...
                'first_failure_prior_time_s',obj.first_failure_prior_time_s, ...
                'first_failure_stage',obj.first_failure_stage, ...
                'first_failure_reason',obj.first_failure_reason, ...
                'first_failure_advance_status',obj.first_failure_advance_status, ...
                'first_failure_advance_reason',obj.first_failure_advance_reason, ...
                'conditional_true_set_ready',false, ...
                'safe_to_commit',false);
            if obj.initialized && ~isempty(obj.ekf_true_tracker)
                R.conditional_true_set_ready=obj.ekf_true_tracker.initialized;
            end
        end
    end
    methods (Static,Access=private)
        function p=read_original_ekf_post(agent)
            assert(isprop(agent,'estimator') && ...
                isfield(agent.estimator.result,'state'), ...
                'TRIGGER_SIM_TRUE_SET_CONTINUATION:EKF', ...
                'The genuine original EKF posterior has not been published.');
            z=agent.estimator.result.state.get();
            assert(isnumeric(z)&&isreal(z) && numel(z)>=24 && ...
                all(isfinite(z(1:24))), ...
                'TRIGGER_SIM_TRUE_SET_CONTINUATION:EKF', ...
                'Original EKF posterior lacks its first 24 finite components.');
            p=double(z(1:24));p=p(:);
        end
        function u=read_applied_input(agent)
            assert(isfield(agent.controller.result,'input'), ...
                'TRIGGER_SIM_TRUE_SET_CONTINUATION:Input', ...
                'The original controller applied input is unavailable.');
            u=double(agent.controller.result.input(:));
            assert(isreal(u)&&isequal(size(u),[4 1])&& ...
                all(isfinite(u)) && u(1)>=0 && u(1)<=20 && ...
                all(u(2:4)>=-1) && all(u(2:4)<=1), ...
                'TRIGGER_SIM_TRUE_SET_CONTINUATION:InputRange', ...
                'Applied input must be finite and inside original HLC saturation.');
        end
        function p=read_original_params(agent)
            assert(isprop(agent,'plant') && ...
                isa(agent.plant,'MODEL_CLASS'), ...
                'TRIGGER_SIM_TRUE_SET_CONTINUATION:Plant');
            p=double(agent.plant.param(:));
            assert(isequal(size(p),[21 1])&&all(isfinite(p)) && ...
                p(20)>0&&p(21)>0, ...
                'TRIGGER_SIM_TRUE_SET_CONTINUATION:Params', ...
                'Original 21-param numeric model vector is required.');
        end
    end
