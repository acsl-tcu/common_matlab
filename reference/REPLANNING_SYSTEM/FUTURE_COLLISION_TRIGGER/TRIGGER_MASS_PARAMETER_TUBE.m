function R=TRIGGER_MASS_PARAMETER_TUBE(C)
% Build the ORIGINAL 21-parameter plant interval grid with a DIFFERENT
% externally justified true payload-mass interval for EACH future hold.
% Other 20 physical parameter bounds must be independently supplied.
% This is the PARAMETER input to TRIGGER_ORIGINAL_PLANT_AUTO_CHAIN, not a
% proof that the true physical payload mass belongs to the provided box.
% Index 20 is mL in the source-pinned with_load_model_euler_for_HL.m.
R=struct('status','UNKNOWN_MASS_PARAMETER_TUBE','reason','', ...
    'conditional_parameter_box',false, ...
    'parameter_lower',zeros(21,0), ...
    'parameter_upper',zeros(21,0), ...
    'true_mass_source_proven',false, ...
    'future_parameter_refresh_proven',false, ...
    'all_other_parameters_proven',false, ...
    'safe_to_commit',false);
try
    needed={'time_grid_s','true_mass_lower_kg','true_mass_upper_kg', ...
        'other_param_lower','other_param_upper'};
    assert(isstruct(C)&&isscalar(C)&&all(isfield(C,needed)), ...
        'TRIGGER_MASS_PARAMETER_TUBE:Inputs', ...
        'Per-hold true-mass bounds and all other physical bounds required.');
    t=double(C.time_grid_s(:).');
    assert(numel(t)>1&&all(isfinite(t))&&all(diff(t)>0), ...
        'TRIGGER_MASS_PARAMETER_TUBE:Clock', ...
        'Use actual monotonically increasing hold times, never assumed Flight start.');
    n=numel(t)-1;
    mlo=double(C.true_mass_lower_kg(:).');
    mhi=double(C.true_mass_upper_kg(:).');
    assert(numel(mlo)==n&&numel(mhi)==n&&all(isfinite([mlo mhi])) && ...
        all(mlo>0)&&all(mhi>=mlo), ...
        'TRIGGER_MASS_PARAMETER_TUBE:TrueMass', ...
        'Per-hold physical payload mass ranges are mandatory.');
    lo=double(C.other_param_lower);hi=double(C.other_param_upper);
    assert(isequal(size(lo),[21 n])&&isequal(size(hi),[21 n]), ...
        'TRIGGER_MASS_PARAMETER_TUBE:ParamSize', ...
        'Original plant has 21 parameter entries per hold.');
    other=[1:19 21];
    assert(all(isfinite(lo(other,:)),'all')&& ...
        all(isfinite(hi(other,:)),'all')&& ...
        all(lo(other,:)<=hi(other,:),'all'), ...
        'TRIGGER_MASS_PARAMETER_TUBE:OtherParameters', ...
        'Other 20 parameter ranges must come from actual physical authority.');
    physical_positive=[1 6 7 8 9 21]; % mass, inertia, gravity, cable length
    assert(all(lo(physical_positive,:)>0,'all'), ...
        'TRIGGER_MASS_PARAMETER_TUBE:PositivePhysical', ...
        'Mass/inertia/gravity/cable length need positive lower bounds.');
    % The true payload mass is NEVER copied from EKF mL, HLC loadmass or
    % the numeric plant snapshot. Their snapshots have separate roles.
    lo(20,:)=mlo;hi(20,:)=mhi;
    R.parameter_lower=lo;R.parameter_upper=hi;
    R.conditional_parameter_box=true;
    R.status='CONDITIONAL_PER_HOLD_TRUE_MASS_PARAMETER_BOX__NOT_TRUE_MASS_PROOF';
    R.reason=['Feed these source-indexed boxes to the original interval ' ...
        'plant Picard chain ONLY if an independent physical certificate ' ...
        'proves all true masses/other parameters throughout each hold. ' ...
        'This module never assumes the EKF estimate equals truth.'];
catch ME
    R.reason=[ME.identifier ' | ' ME.message];
end
end
