classdef TRIGGER_PICARD_TO_GENERIC_TUBE
    % Shape-independent link: original 24-state WHOLE-interval Picard boxes
    % -> q-box and taut-direction cone for all UAV/cable/payload material.
    % Plant state: q=x(1:3), pT=x(19:21), omega_L=x(22:24).
    % If pT's *whole-interval* interval box is already guaranteed, another
    % Omega*h angular inflation is unnecessary (and can be much larger).
    % This is only geometric set conversion; no source proof of reachability,
    % unit taut mode, estimator error, mass, or directed rounding is granted.
    methods(Static)
        function [T,R]=from_boxes(xlo,xhi,time_bounds_s,Llo,Lhi,ru,rc,rl)
            T=struct();
            R=struct('status','UNKNOWN_PICARD_INPUT', 'reason','', ...
                'intervals',0,'full_sphere_intervals',0, ...
                'safe_to_commit',false,'certifies_reachability',false);
            try
                assert(isnumeric(xlo)&&isreal(xlo)&& ...
                    isequal(size(xlo),size(xhi))&&size(xlo,1)==24&& ...
                    all(isfinite(xlo(:)))&&all(isfinite(xhi(:)))&& ...
                    all(xlo(:)<=xhi(:)),'InvalidOriginal24StateBox');
                K=size(xlo,2);
                assert(K>0&&isequal(size(time_bounds_s),[2 K])&& ...
                    all(isfinite(time_bounds_s(:)))&& ...
                    time_bounds_s(1,1)==0&& ...
                    all(time_bounds_s(1,:)<time_bounds_s(2,:))&& ...
                    all(time_bounds_s(1,2:end)==time_bounds_s(2,1:end-1)), ...
                    'InvalidWholeIntervalTimeCover');
                assert(isequal(size(Llo),[1 K])&& ...
                    isequal(size(Lhi),[1 K])&& ...
                    all(isfinite(Llo))&&all(isfinite(Lhi))&& ...
                    all(Llo>0)&&all(Llo<=Lhi)&& ...
                    all(isfinite([ru rc rl]))&&all([ru rc rl]>=0), ...
                    'InvalidLengthOrBodyRadii');
            catch ME
                R.reason=[ME.identifier ' | ' ME.message];return
            end
            if ~(isscalar(ru)&&isscalar(rc)&&isscalar(rl))
                R.reason='Body radii must be scalars';return
            end
            axis=zeros(3,K);alpha=zeros(1,K);full=0;
            for k=1:K
                dlo=xlo(19:21,k);dhi=xhi(19:21,k);
                mid=(dlo+dhi)/2;
                if norm(mid)==0
                    axis(:,k)=[1;0;0];alpha(k)=pi;full=full+1;
                else
                    a=mid/norm(mid);axis(:,k)=a;
                    lower=sum(min(a.*dlo,a.*dhi));
                    % Approximate outward guard; NEVER a proof of rounding.
                    lower=lower-128*eps(max([1;abs(dlo);abs(dhi)]));
                    alpha(k)=acos(max(-1,min(1,lower)));
                    if alpha(k)==pi,full=full+1;end
                end
            end
            T=struct('q_lo',xlo(1:3,:), ...
                'q_hi',xhi(1:3,:), 'axis',axis, ...
                'half_angle_rad',alpha, 'L_lo',Llo, 'L_hi',Lhi, ...
                'r_uav',ru,'r_cable',rc,'r_payload',rl, ...
                'interval_bounds_s',time_bounds_s, ...
                'horizon_s',time_bounds_s(2,end));
            R.intervals=K;R.full_sphere_intervals=full;
            R.status='CONDITIONAL_PICARD_DIRECTION_BOX_TO_CONE__NOT_REACHABILITY_PROOF';
            R.reason='Requires externally verified true-state enclosure, taut unit direction and outward rounding.';
        end
    end
end
