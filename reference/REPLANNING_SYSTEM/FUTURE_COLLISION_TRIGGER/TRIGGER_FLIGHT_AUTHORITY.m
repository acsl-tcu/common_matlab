classdef TRIGGER_FLIGHT_AUTHORITY < handle
    % All EXTERNAL parameters are bound once for EACH Flight from the LIVE
    % plant/controller/parameter provider and geometry source. Only EKF
    % state and mL are refreshed on every tick. No numerical fallbacks.
    % A separate instance must be constructed for the next Flight.
    %
    % Usage (before Flight, after Sim construction):
    %  B=TRIGGER_FLIGHT_AUTHORITY(time,agent,@geometry_from_live,...
    %                                             @existing_future_reference);
    % On each Flight tick AFTER EKF and sensor updates:
    %  [ekf,a]=B.current(time,agent);
    %  R=FUTURE_COLLISION_TRIGGER(struct()).evaluate(time.t,ekf,sensor,a);
    %
    % This class does NOT obtain source obstacle definitions or mutate agent.
    properties (SetAccess=private)
        flight
        live_agent
        reference_at
        snapshot_count=0
    end
    methods
        function obj=TRIGGER_FLIGHT_AUTHORITY(time,agent,geometry_getter,reference_at)
            % The optional empty reference is permitted ONLY when binding
            % the REAL static Flight model before arming. It is not a fake
            % future reference: current() requires a live handle later.
            prebound_static=isempty(reference_at);
            assert(isa(geometry_getter,'function_handle') && ...
                   (prebound_static || isa(reference_at,'function_handle')), ...
                'TRIGGER_FLIGHT_AUTHORITY:Sources', ...
                'Real geometry source and either live reference or explicit prebind required.');
            obj.live_agent=agent;
            obj.reference_at=reference_at;
            f=struct();
            f.sample_dt_s=TRIGGER_FLIGHT_AUTHORITY.positive( ...
                TRIGGER_FLIGHT_AUTHORITY.member(time,'dt'),'time.dt');
            P=TRIGGER_FLIGHT_AUTHORITY.member(agent,'parameter');
            order=string(TRIGGER_FLIGHT_AUTHORITY.member(P,'parameter_order'));
            assert(numel(order)>0 && all(strlength(order)>0) && ...
                numel(unique(order))==numel(order), ...
                'TRIGGER_FLIGHT_AUTHORITY:ParameterOrder', ...
                'An unambiguous live physical parameter order is required.');
            plant=TRIGGER_FLIGHT_AUTHORITY.member(agent,'plant');
            rhs=TRIGGER_FLIGHT_AUTHORITY.member(plant,'method');
            solver=TRIGGER_FLIGHT_AUTHORITY.member(plant,'solver');
            assert(isa(rhs,'function_handle') && isa(solver,'function_handle'), ...
                'TRIGGER_FLIGHT_AUTHORITY:Plant', ...
                'The active plant must expose its exact RHS and solver handles.');
            plant_dt=TRIGGER_FLIGHT_AUTHORITY.positive( ...
                TRIGGER_FLIGHT_AUTHORITY.member(plant,'dt'),'plant.dt');
            assert(isequal(plant_dt,f.sample_dt_s), ...
                'TRIGGER_FLIGHT_AUTHORITY:PlantDT', ...
                'Configured plant integration dt must equal Flight dt.');
            state=TRIGGER_FLIGHT_AUTHORITY.member(plant,'state');
            actual_names=string(TRIGGER_FLIGHT_AUTHORITY.member(state,'list'));
            actual_num=double(TRIGGER_FLIGHT_AUTHORITY.member(state,'num_list'));
            required_state=["p","q","v","w","pL","vL","pT","wL"];
            assert(isequal(actual_names(:).',required_state) && ...
                isequal(actual_num(:).',[3 3 3 3 3 3 3 3]), ...
                'TRIGGER_FLIGHT_AUTHORITY:PlantState', ...
                'Actual plant must use the 24-state suspended-load layout; no guessed mapping.');
            model_parameters=double(TRIGGER_FLIGHT_AUTHORITY.member(plant,'param'));
            assert(isreal(model_parameters) && isrow(model_parameters) && ...
                numel(model_parameters)==numel(order) && ...
                all(isfinite(model_parameters)), ...
                'TRIGGER_FLIGHT_AUTHORITY:PlantParameter', ...
                'Actual model parameter vector/order do not match.');
            idx_mass=find(order=="loadmass");
            idx_length=find(order=="cableL");
            assert(isscalar(idx_mass) && isscalar(idx_length), ...
                'TRIGGER_FLIGHT_AUTHORITY:PlantParameter', ...
                'Exact loadmass and cableL positions are needed from the live order.');
            f.model_parameters=model_parameters;
            f.loadmass_index=idx_mass;
            f.plant_rhs=rhs;
            f.plant_solver=solver;
            f.cable_length_m=TRIGGER_FLIGHT_AUTHORITY.positive( ...
                model_parameters(idx_length),'plant.param.cableL');
            % Refuse stale geometry/plant mismatch instead of inventing a length.
            current_length=TRIGGER_FLIGHT_AUTHORITY.positive( ...
                TRIGGER_FLIGHT_AUTHORITY.pget(P,"cableL"),'parameter.cableL');
            assert(isequal(f.cable_length_m,current_length), ...
                'TRIGGER_FLIGHT_AUTHORITY:CableBinding', ...
                'Plant cable length differs from live parameter.cableL; reinitialize the plant.');
            ctrl=TRIGGER_FLIGHT_AUTHORITY.member(agent,'controller');
            hlc=TRIGGER_FLIGHT_AUTHORITY.member(ctrl,'hlc_suspended');
            assert(isa(hlc,'HLC_SUSPENDED_LOAD'), ...
                'TRIGGER_FLIGHT_AUTHORITY:Controller', ...
                'The actual HLC_SUSPENDED_LOAD controller must be active.');
            gains=TRIGGER_FLIGHT_AUTHORITY.member(hlc,'param');
            for key=["F1","F2","F3","F4","dt"]
                x=TRIGGER_FLIGHT_AUTHORITY.member(gains,char(key));
                assert(isnumeric(x)&&isreal(x)&&~isempty(x)&&all(isfinite(x(:))), ...
                    'TRIGGER_FLIGHT_AUTHORITY:Gain','Invalid live HLC gain: %s',key);
            end
            assert(isequal(double(gains.dt),f.sample_dt_s), ...
                'TRIGGER_FLIGHT_AUTHORITY:ControlDT', ...
                'HLC dt and Flight dt mismatch; must rebind.');
            f.hlc_param=gains;
            % The unchanged HLC reads parameter.loadmass (not EKF.mL).
            % Preserve that controller behavior; the physical model alone
            % substitutes latest EKF.mL each evaluation.
            f.hlc_parameter_names=["mass","jx","jy","jz","gravity","loadmass","cableL"];
            v=TRIGGER_FLIGHT_AUTHORITY.pget(P,f.hlc_parameter_names);
            assert(isnumeric(v)&&isrow(v)&&numel(v)==numel(f.hlc_parameter_names) && ...
                all(isfinite(v)) && all(v([1 2 3 4 5 7])>0) && ...
                ((prebound_static && v(6)>=0) || (~prebound_static && v(6)>0)), ...
                'TRIGGER_FLIGHT_AUTHORITY:HLCParameters', ...
                'Live parameter mapping invalid (pre-arm loadmass may be zero).');
            f.hlc_parameter_values=double(v);
            f.hlc_mass_source_kg=double(v(6));
            geometry=geometry_getter();
            f.r_uav_m=TRIGGER_FLIGHT_AUTHORITY.positive( ...
                TRIGGER_FLIGHT_AUTHORITY.member(geometry,'r_uav_m'),'r_uav_m');
            f.r_payload_m=TRIGGER_FLIGHT_AUTHORITY.positive( ...
                TRIGGER_FLIGHT_AUTHORITY.member(geometry,'r_payload_m'),'r_payload_m');
            f.r_cable_m=TRIGGER_FLIGHT_AUTHORITY.nonnegative( ...
                TRIGGER_FLIGHT_AUTHORITY.member(geometry,'r_cable_m'),'r_cable_m');
            if TRIGGER_FLIGHT_AUTHORITY.exists(geometry,'horizon_s')
                f.horizon_s=TRIGGER_FLIGHT_AUTHORITY.positive( ...
                    TRIGGER_FLIGHT_AUTHORITY.member(geometry,'horizon_s'),'horizon_s');
            end
            % No horizon or physical parameter guessed here. Trigger itself
            % owns the intrinsic initial horizon of 4 seconds.
            obj.flight=f;
        end
        function [ekf,a]=current(obj,time,agent,reference_at)
            % Each LIVE tick supplies the REAL phase-specific reference.
            % No reference or EKF state is sampled during the prebind.
            if nargin<4, reference_at=obj.reference_at; end
            assert(isa(reference_at,'function_handle'), ...
                'TRIGGER_FLIGHT_AUTHORITY:CurrentReference', ...
                'Current live future reference must be bound before prediction.');
            if isobject(obj.live_agent)
                assert(isequal(agent,obj.live_agent), ...
                    'TRIGGER_FLIGHT_AUTHORITY:AgentChanged', ...
                    'A different Flight agent requires a new binding.');
            end
            % These are fixed members of the live TIME_CLASS previously
            % validated in the static binding. Direct access avoids per-tick
            % dynamic isprop/member lookup; missing members throw UNKNOWN.
            t=time.t;
            assert(isnumeric(t)&&isscalar(t)&&isfinite(t)&&isreal(t), ...
                'TRIGGER_FLIGHT_AUTHORITY:Time','Invalid time.t.');
            dt=TRIGGER_FLIGHT_AUTHORITY.positive(time.dt,'time.dt');
            assert(isequal(dt,obj.flight.sample_dt_s), ...
                'TRIGGER_FLIGHT_AUTHORITY:DTChanged', ...
                'Flight dt changed; rebind external model and HLC before use.');
            est=TRIGGER_FLIGHT_AUTHORITY.member(agent,'estimator');
            state=TRIGGER_FLIGHT_AUTHORITY.member( ...
                TRIGGER_FLIGHT_AUTHORITY.member(est,'result'),'state');
            % Fixed state schema, exactly the order used by the original
            % 24-state HLC/plant. Never substitute a nominal or previous state.
            ekf=struct('p',double(state.p),'q',double(state.q), ...
                'v',double(state.v),'w',double(state.w), ...
                'pL',double(state.pL),'vL',double(state.vL), ...
                'pT',double(state.pT),'wL',double(state.wL));
            live_fields={'p','q','v','w','pL','vL','pT','wL'};
            for i=1:8
                v=ekf.(live_fields{i});
                assert(isnumeric(v)&&isreal(v)&&isequal(size(v),[3 1]) && ...
                    all(isfinite(v)), 'TRIGGER_FLIGHT_AUTHORITY:EKF', ...
                    'Current EKF field %s is missing or invalid.',live_fields{i});
            end
            mL=TRIGGER_FLIGHT_AUTHORITY.positive(state.mL,'EKF.mL');
            cfg=struct('sample_dt_s',obj.flight.sample_dt_s, ...
                'cable_length_m',obj.flight.cable_length_m, ...
                'r_uav_m',obj.flight.r_uav_m, ...
                'r_payload_m',obj.flight.r_payload_m, ...
                'r_cable_m',obj.flight.r_cable_m);
            if isfield(obj.flight,'horizon_s'),cfg.horizon_s=obj.flight.horizon_s;end
            % The actual SUSPENDED_LOAD_STATE_MANAGER updates parameter.loadmass
            % EVERY TICK, including landing fade-to-zero. The original HLC
            % reads agent.parameter.loadmass, not a frozen preflight mass.
            % Refresh only this entry from the original live source, without
            % ever writing back to the Flight controller or estimator.
            current_hlc_mass=TRIGGER_FLIGHT_AUTHORITY.pget( ...
                TRIGGER_FLIGHT_AUTHORITY.member(agent,'parameter'),"loadmass");
            current_hlc_mass=TRIGGER_FLIGHT_AUTHORITY.positive( ...
                current_hlc_mass,'current HLC parameter.loadmass');
            binding=obj.flight;  % Copy; do not mutate Flight's nominal snapshot.
            mass_key=find(binding.hlc_parameter_names=="loadmass");
            assert(isscalar(mass_key),'TRIGGER_FLIGHT_AUTHORITY:HLCCurrentMass', ...
                'Flight HLC mass map is not unique.');
            binding.hlc_parameter_values(mass_key)=current_hlc_mass;
            binding.hlc_mass_source_kg=current_hlc_mass;
            a=struct('runtime',cfg,'payload_mass_kg',mL, ...
                'reference_at',reference_at, ...
                'predictor',[], ... % Real Flight uses verified direct native, no per-tick closure.
                'verified_native_binding',binding, ...
                'current_time_s',double(t), ...
                'authority_binding_policy','FLIGHT_VALUES__CURRENT_EKF_MASS', ...
                'actual_hlc_mass_source_kg',binding.hlc_mass_source_kg, ...
                'hlc_mass_matches_estimator',isequal(current_hlc_mass,mL), ...
                'model_authority','EXISTING_HLC_AND_MODEL__NOMINAL_ONLY');
            obj.snapshot_count=obj.snapshot_count+1;
        end
    end
    methods (Static,Access=private)
        function tf=exists(x,key)
            tf=(isstruct(x)&&isscalar(x)&&isfield(x,key)) || ...
                (isobject(x)&&isscalar(x)&&isprop(x,key));
        end
        function v=member(x,key)
            assert(TRIGGER_FLIGHT_AUTHORITY.exists(x,key), ...
                'TRIGGER_FLIGHT_AUTHORITY:Missing', ...
                'Required LIVE external member is unavailable: %s',key);
            v=x.(key);
        end
        function v=pget(p,keys)
            if isstruct(p)
                getter=TRIGGER_FLIGHT_AUTHORITY.member(p,'get');
                assert(isa(getter,'function_handle'), ...
                    'TRIGGER_FLIGHT_AUTHORITY:Getter','Parameter getter is not callable.');
                v=getter(keys);
            else
                v=p.get(keys);
            end
        end
        function v=positive(x,label)
            assert(isnumeric(x)&&isscalar(x)&&isfinite(x)&&isreal(x)&&x>0, ...
                'TRIGGER_FLIGHT_AUTHORITY:Value', ...
                'Missing or invalid physical value: %s',label);
            v=double(x);
        end
        function v=nonnegative(x,label)
            assert(isnumeric(x)&&isscalar(x)&&isfinite(x)&&isreal(x)&&x>=0, ...
                'TRIGGER_FLIGHT_AUTHORITY:Value', ...
                'Missing or invalid physical value: %s',label);
            v=double(x);
        end
    end
end
