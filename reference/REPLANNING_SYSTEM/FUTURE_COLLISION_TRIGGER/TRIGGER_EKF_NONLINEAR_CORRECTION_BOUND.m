function R=TRIGGER_EKF_NONLINEAR_CORRECTION_BOUND(C)
% TRIGGER_EKF_NONLINEAR_CORRECTION_BOUND  Exact-form EKF correction obligation.
%
% Original EKF source performs:
%    x_pre = estimator_model.do(...)
%    yh = output_func(x_pre,...)
%    G = (P_pre*C')/(C*P_pre*C'+R)
%    xhat_next = model.projection(x_pre + G*(y-yh))
%
% This function performs an interval extension of THE NONLINEAR INNOVATION
% CORRECTION, not an assumed affine error recursion e_next=A*e+d.
% All lower/upper bounds are EXTERNAL obligations, not synthesized from Q,
% R, covariance P or a nominal trajectory. The interval matrices must enclose
% every admissible actual EKF gain; they are not necessarily the nominal G.
% The projection enclosure must be proved separately for the real active
% model.projection and ALL corrected states. Caller-provided bounds alone
% do not constitute that proof. This is OFFLINE theory, not Flight code.
% The current floating-point interval engine still requires an independent
% directed-rounding audit. ALWAYS return safe_to_commit=false.
R=struct('status','UNKNOWN_EKF_NONLINEAR_UPDATE','reason','', ...
    'preprojection_lower',zeros(24,0), ...
    'preprojection_upper',zeros(24,0), ...
    'conditional_error_lower',zeros(24,0), ...
    'conditional_error_upper',zeros(24,0), ...
    'preprojection_enclosed',false, ...
    'projection_enclosed_by_source',false, ...
    'gain_enclosed_by_source',false, ...
    'observation_enclosed_by_source',false, ...
    'rounding_audited',false,'safe_to_commit',false);
try
    mandatory={'estimated_prediction_lower','estimated_prediction_upper', ...
        'measurement_lower','measurement_upper', ...
        'predicted_measurement_lower','predicted_measurement_upper', ...
        'gain_lower','gain_upper', ...
        'true_next_lower','true_next_upper'};
    assert(isstruct(C)&&isscalar(C)&&all(isfield(C,mandatory)), ...
        'TRIGGER_EKF_NONLINEAR_CORRECTION_BOUND:Inputs', ...
        'Original EKF prediction, gain, innovation and true-state bounds required.');
    a=double(C.estimated_prediction_lower(:));
    b=double(C.estimated_prediction_upper(:));
    ylo=double(C.measurement_lower(:));
    yhi=double(C.measurement_upper(:));
    hlo=double(C.predicted_measurement_lower(:));
    hhi=double(C.predicted_measurement_upper(:));
    gl=double(C.gain_lower);gh=double(C.gain_upper);
    xl=double(C.true_next_lower(:));xu=double(C.true_next_upper(:));
    m=numel(ylo);
    assert(numel(a)==24 && numel(b)==24 && m>=1 && ...
        numel(yhi)==m && numel(hlo)==m && numel(hhi)==m && ...
        numel(xl)==24 && numel(xu)==24 && ...
        isequal(size(gl),[24 m])&&isequal(size(gh),[24 m]) && ...
        all(isfinite([a;b;ylo;yhi;hlo;hhi;xl;xu])) && ...
        all(isfinite(gl(:)))&&all(isfinite(gh(:))) && ...
        all(a<=b)&&all(ylo<=yhi)&&all(hlo<=hhi) && ...
        all(xl<=xu)&&all(gl(:)<=gh(:)), ...
        'TRIGGER_EKF_NONLINEAR_CORRECTION_BOUND:Box', ...
        'All exact-form EKF correction boxes must be finite, ordered and dimensionally correct.');
    rawlo=zeros(24,1);rawhi=zeros(24,1);
    innovation=cell(m,1);
    for j=1:m
        innovation{j}=TRIGGER_OUTWARD_INTERVAL(ylo(j),yhi(j))- ...
            TRIGGER_OUTWARD_INTERVAL(hlo(j),hhi(j));
    end
    for i=1:24
        z=TRIGGER_OUTWARD_INTERVAL(a(i),b(i));
        for j=1:m
            z=z+TRIGGER_OUTWARD_INTERVAL(gl(i,j),gh(i,j)).*innovation{j};
        end
        rawlo(i)=z.lo;rawhi(i)=z.hi;
    end
    R.preprojection_lower=rawlo;
    R.preprojection_upper=rawhi;
    R.preprojection_enclosed=true;
    if ~all(isfield(C,{'projected_lower','projected_upper'}))
        R.status='UNKNOWN_REAL_EKF_PROJECTION_NOT_BOUNDED';
        R.reason=['Preprojection x_pre+G*(y-h(x_pre)) bounded, but actual ' ...
            'model.projection and its complete enclosure are mandatory.'];
        return
    end
    pl=double(C.projected_lower(:));pu=double(C.projected_upper(:));
    assert(numel(pl)==24&&numel(pu)==24 && ...
        all(isfinite(pl))&&all(isfinite(pu))&&all(pl<=pu), ...
        'TRIGGER_EKF_NONLINEAR_CORRECTION_BOUND:Projection', ...
        'Explicit finite 24-dimensional projection enclosure required.');
    el=zeros(24,1);eu=zeros(24,1);
    for i=1:24
        d=TRIGGER_OUTWARD_INTERVAL(xl(i),xu(i))- ...
            TRIGGER_OUTWARD_INTERVAL(pl(i),pu(i));
        el(i)=d.lo;eu(i)=d.hi;
    end
    R.conditional_error_lower=el;
    R.conditional_error_upper=eu;
    R.status='CONDITIONAL_EXACT_EKF_NONLINEAR_ERROR_STEP__NOT_ORIGINAL_EKF_PROOF';
    R.reason=['True next state, model prediction, measurement, nonlinear ' ...
        'innovation gain and model.projection must ALL have sound external ' ...
        'enclosures; actual EKF code/source order and interval rounding ' ...
        'remain to be audited. User-supplied projected box is not a proof.'];
catch ME
    R.status='UNKNOWN_EKF_NONLINEAR_UPDATE';
    R.reason=[ME.identifier ' | ' ME.message];
end
end
