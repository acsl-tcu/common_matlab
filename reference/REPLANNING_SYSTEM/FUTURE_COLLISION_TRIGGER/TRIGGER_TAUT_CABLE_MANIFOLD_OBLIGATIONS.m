function R=TRIGGER_TAUT_CABLE_MANIFOLD_OBLIGATIONS(X,P)
% Necessary INITIAL and CONTINUOUS taut-cable holonomic obligations.
% Original physical state order: [pQ, euler, vQ, wQ, pL, vL, pT, wL].
% For pT directed UAV -> load and cable length L:
%   c0 = pL-pQ-L*pT = 0,
%   c1 = vL-vQ-L*(wL CROSS pT) = 0,  |pT|=1.
% c1 is the exact time derivative of c0 when L is held constant.
% These are NECESSARY conditions, not a proof that 24-state plant flow
% preserves the manifold, or a proof of tension>0. Independent boxes
% cannot certify exact equalities merely because they CONTAIN zero.
% This tool only REJECTS contradictory boxes, never certifies Flight safety.
R=struct('status','UNKNOWN_CABLE_MANIFOLD','compatible',false, ...
    'position_residual_lower',nan(3,1), ...
    'position_residual_upper',nan(3,1), ...
    'velocity_residual_lower',nan(3,1), ...
    'velocity_residual_upper',nan(3,1), ...
    'unit_norm_squared_lower',NaN,'unit_norm_squared_upper',NaN, ...
    'position_zero_possible',false,'velocity_zero_possible',false, ...
    'unit_direction_possible',false,'exact_manifold_verified',false, ...
    'manifold_invariance_verified',false, ...
    'taut_tension_verified',false,'safe_to_commit',false,'reason','');
try
    assert(isstruct(X)&&isscalar(X)&& ...
        all(isfield(X,{'lower','upper'})) && ...
        isequal(size(X.lower),[24 1]) && isequal(size(X.upper),[24 1]) && ...
        isstruct(P)&&isscalar(P)&& ...
        all(isfield(P,{'lower','upper'})) && ...
        isequal(size(P.lower),[21 1])&&isequal(size(P.upper),[21 1]) && ...
        all(isfinite([X.lower;X.upper;P.lower;P.upper])) && ...
        all(X.lower<=X.upper)&&all(P.lower<=P.upper) && ...
        P.lower(21)>0, ...
        'TRIGGER_TAUT_CABLE_MANIFOLD_OBLIGATIONS:Input', ...
        'Valid 24-state and 21-parameter ordered boxes required.');
    I=cell(24,1);
    for k=1:24
        I{k}=TRIGGER_OUTWARD_INTERVAL(X.lower(k),X.upper(k));
    end
    L=TRIGGER_OUTWARD_INTERVAL(P.lower(21),P.upper(21));
    pt=I(19:21);w=I(22:24);
    cp=ixcross(w,pt);
    norm2=TRIGGER_OUTWARD_INTERVAL(0,0);
    for j=1:3
        r0=I{12+j}-I{j}-L.*pt{j};
        r1=I{15+j}-I{6+j}-L.*cp{j};
        R.position_residual_lower(j)=r0.lo;
        R.position_residual_upper(j)=r0.hi;
        R.velocity_residual_lower(j)=r1.lo;
        R.velocity_residual_upper(j)=r1.hi;
        norm2=norm2+pt{j}.*pt{j};
    end
    R.unit_norm_squared_lower=norm2.lo;
    R.unit_norm_squared_upper=norm2.hi;
    R.position_zero_possible=all(R.position_residual_lower<=0 & ...
        R.position_residual_upper>=0);
    R.velocity_zero_possible=all(R.velocity_residual_lower<=0 & ...
        R.velocity_residual_upper>=0);
    R.unit_direction_possible=norm2.lo<=1&&norm2.hi>=1;
    R.compatible=R.position_zero_possible && ...
        R.velocity_zero_possible && R.unit_direction_possible;
    if R.compatible
        R.status='NECESSARY_TAUT_CONSTRAINTS_COMPATIBLE__NOT_PROVED';
        R.reason=['Zero residual is POSSIBLE in each interval, not guaranteed. ' ...
            'Need a joint constrained initial set, invariance theorem, ' ...
            'nonzero cable tension and complete continuous-time tube.'];
    else
        R.status='REJECT_INCONSISTENT_TAUT_CABLE_STATE';
        R.reason='A necessary holonomic, derivative or unit-length condition excludes zero/one.';
    end
catch ME
    R.status='UNKNOWN_CABLE_MANIFOLD_EVALUATION';
    R.reason=[ME.identifier ' | ' ME.message];
end
end
function c=ixcross(a,b)
c={a{2}.*b{3}-a{3}.*b{2}; ...
   a{3}.*b{1}-a{1}.*b{3}; ...
   a{1}.*b{2}-a{2}.*b{1}};
end
