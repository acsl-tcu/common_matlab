function R=TRIGGER_ISOLATED_OUTER_AUTHORITY_PREPARE(cfg)
% Purely SYNTHETIC pre-arm exercise of the ACTUAL authority.current() path.
% Builds a throwaway agent-shaped struct around the original static source
% binding; it NEVER reads the real EKF, sensor, obstacle list, reference
% values, Flight epoch, or executes the real HLC/plant controller.
% This is optional JIT-path preparation, not a guarantee of compilation.
R=struct('status','NOT_COMPLETED_ISOLATED_OUTER_AUTHORITY', ...
    'calls',0,'reference_probes',0,'reason','', ...
    'read_real_flight',false,'safe_to_commit',false);
try
    assert(isstruct(cfg)&&isfield(cfg,'native_binding') && ...
        isfield(cfg,'sample_dt_s') && isfield(cfg,'horizon_s') && ...
        isfield(cfg,'cable_length_m') && isfield(cfg,'r_uav_m') && ...
        isfield(cfg,'r_payload_m') && isfield(cfg,'r_cable_m'), ...
        'TRIGGER_ISOLATED_OUTER_AUTHORITY_PREPARE:Cfg', ...
        'Static, preflight-verified numeric source binding is required.');
    b=cfg.native_binding;
    assert(b.native_source_order_checked && numel(b.model_parameters)==21 && ...
        isa(b.plant_rhs,'function_handle') && ...
        isa(b.plant_solver,'function_handle') && ...
        isstruct(b.hlc_param) && isfield(b.hlc_param,'dt'), ...
        'TRIGGER_ISOLATED_OUTER_AUTHORITY_PREPARE:Binding', ...
        'Original static HLC/plant source contract is not available.');
    % Unique synthetic names at unused indices, real required names at
    % the fixed indices verified by the original static source binding.
    order="unused_"+string(1:21);
    order(1)="mass";order(6)="jx";order(7)="jy";
    order(8)="jz";order(9)="gravity";
    order(20)="loadmass";order(21)="cableL";
    values=double(b.model_parameters(:).');
    values(20)=1; % SYNTHETIC positive payload mass, never a Flight fallback
    params=struct();
    params.parameter_order=order;
    params.get=@(keys)local_pget(keys,order,values);
    plant=struct();
    plant.method=b.plant_rhs;
    plant.solver=b.plant_solver;
    plant.dt=double(cfg.sample_dt_s);
    plant.state=struct('list', ...
        ["p","q","v","w","pL","vL","pT","wL"], ...
        'num_list',3*ones(1,8));
    plant.param=values;
    controller=struct('hlc_suspended',HLC_SUSPENDED_LOAD([],b.hlc_param));
    L=double(cfg.cable_length_m);
    state=struct('p',zeros(3,1),'q',zeros(3,1), ...
        'v',zeros(3,1),'w',zeros(3,1), ...
        'pL',[0;0;-L],'vL',zeros(3,1), ...
        'pT',[0;0;-1],'wL',zeros(3,1),'mL',1);
    agent=struct('parameter',params,'plant',plant, ...
        'controller',controller, ...
        'estimator',struct('result',struct('state',state)));
    time=struct('dt',double(cfg.sample_dt_s),'t',0);
    get_geometry=@()struct('r_uav_m',cfg.r_uav_m, ...
        'r_payload_m',cfg.r_payload_m,'r_cable_m',cfg.r_cable_m, ...
        'horizon_s',cfg.horizon_s);
    % Nominal time-only fixture: not the actual Flight reference handle.
    empty_estimator=struct('result',struct('state',struct()));
    fixture=struct('estimator',empty_estimator);
    nominal=TIME_VARYING_REFERENCE(fixture, ...
        {'TRIGGER_SOFTWARE_FIXTURE_REFERENCE_FACTORY',{}});
    nominal.t=0;
    ref=@(tt)REPLANNING_SYSTEM.software_probe_flight_reference(nominal,tt,L);
    B=TRIGGER_FLIGHT_AUTHORITY(time,agent,get_geometry,ref);
    for k=1:8
        time.t=(k-1)*time.dt;
        [ekf,a]=B.current(time,agent,ref);
        assert(isequal(size(ekf.p),[3 1]) && ...
            isequal(a.payload_mass_kg,1) && ...
            isequal(a.verified_native_binding.hlc_mass_source_kg,1), ...
            'TRIGGER_ISOLATED_OUTER_AUTHORITY_PREPARE:Current', ...
            'Actual current() method failed the isolated physical binding.');
        R.calls=k;
        xd=ref(time.t);
        assert(isnumeric(xd)&&iscolumn(xd)&&numel(xd)>=4 && ...
            all(isfinite(xd)), ...
            'TRIGGER_ISOLATED_OUTER_AUTHORITY_PREPARE:Reference', ...
            'Synthetic reference-only call returned invalid data.');
        R.reference_probes=k;
    end
    R.status='SYNTHETIC_ACTUAL_AUTHORITY_CURRENT_AND_REFERENCE_PATH_PASS';
catch ME
    R.reason=[ME.identifier ' | ' ME.message];
end
end

function values=local_pget(keys,order,p)
keys=string(keys);
values=zeros(1,numel(keys));
for k=1:numel(keys)
    ix=find(order==keys(k),1);
    assert(~isempty(ix), ...
        'TRIGGER_ISOLATED_OUTER_AUTHORITY_PREPARE:Parameter', ...
        'Unknown synthetic source parameter requested.');
    values(k)=p(ix);
end
end
