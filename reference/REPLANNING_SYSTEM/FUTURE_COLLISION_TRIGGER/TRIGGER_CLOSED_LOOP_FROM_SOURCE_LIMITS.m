function R=TRIGGER_CLOSED_LOOP_FROM_SOURCE_LIMITS(C)
% Single connected 24-state theoretical workflow:
% original HLC/MODEL_CLASS byte-pinned universal saturated ZOH image
% -> physically bounded future true mass from current interval + rate
% -> original EKF posterior signed-error box, original Picard plant RHS,
%    original tension/taut test, observed-only full-body shape geometry.
%
% C must include all original TRIGGER_CLOSED_LOOP_CONDITIONAL_ASSEMBLY
% requirements EXCEPT held_input_*/true_mass_* (derived here), plus:
% observation_provenance='ACTUAL_SENSOR_HISTORY_ONLY'
% true_mass_now_lower_kg, true_mass_now_upper_kg,
% true_mass_rate_bound_kg_s. These TRUE physical inputs MUST be supported
% by independently established deterministic measurement/rate bounds.
% Even if all conditional stages pass, this is NOT a Flight certificate.
R=struct('status','UNKNOWN_CLOSED_LOOP_SOURCE_LIMITS','reason','', ...
    'source_hlc',struct(),'mass_rate',struct(),'chain',struct(), ...
    'source_derived_geometry',struct(), ...
    'source_geometry_gate_executed',false, ...
    'required_horizon_s',4.0,'covered_horizon_s',NaN, ...
    'tracker_error_derived',false,'tracker_error_generation',uint64(0), ...
    'observed_ids',zeros(1,0),'possible_risk_ids',zeros(1,0), ...
    'genuine_ekf_error_bound_proven',false, ...
    'physical_mass_rate_proven',false, ...
    'finite_future_hlc_calls_proven',false, ...
    'actual_sample_hold_grid_proven',false, ...
    'numerical_rounding_entire_chain_proven',false, ...
    'full_physical_4s_safety_proven',false,'safe_to_commit',false);
try
    assert(isstruct(C)&&isscalar(C) && ...
        isfield(C,'observation_provenance') && ...
        strcmp(C.observation_provenance,'ACTUAL_SENSOR_HISTORY_ONLY'), ...
        'TRIGGER_CLOSED_LOOP_FROM_SOURCE_LIMITS:Observation', ...
        'Only the current sensor-observed and retained static shapes may enter.');
    assert(isfield(C,'observed_prepared_shapes')&& ...
        isstruct(C.observed_prepared_shapes), ...
        'TRIGGER_CLOSED_LOOP_FROM_SOURCE_LIMITS:Shapes', ...
        'Sensor-prepared real observations are mandatory.');
    if ~isempty(C.observed_prepared_shapes)
        R.observed_ids=reshape(double([C.observed_prepared_shapes.id]),1,[]);
    end
    assert(isfield(C,'time_grid_s'), ...
        'TRIGGER_CLOSED_LOOP_FROM_SOURCE_LIMITS:Clock', ...
        'The original controller hold grid is mandatory.');
    % This API serves the 4-second collision trigger, NOT an arbitrary
    % short theorem fixture.  Do not permit a conditional certificate over
    % a shorter supplied grid to be mistaken for a 4-second result.  This
    % checks COVERAGE only; it cannot establish actual future clock events.
    t=double(C.time_grid_s(:).');
    assert(isnumeric(C.time_grid_s) && isreal(C.time_grid_s) && ...
        numel(t)>=2 && all(isfinite(t)) && all(diff(t)>0), ...
        'TRIGGER_CLOSED_LOOP_FROM_SOURCE_LIMITS:Grid', ...
        'Actual future controller holds must have increasing finite times.');
    R.covered_horizon_s=t(end)-t(1);
    if ~(R.covered_horizon_s>=R.required_horizon_s)
        R.status='UNKNOWN_INCOMPLETE_FOUR_SECOND_HORIZON';
        R.reason='The supplied actual held-input grid does not cover the full 4 seconds.';
        R.possible_risk_ids=R.observed_ids;
        return
    end
    % Optional REAL ORIGINAL-EKF POSTERIOR linkage. This replaces the
    % previously HAND-FED signed-error bounds when a continuously updated
    % 24-state true-set tracker is supplied. The tracker itself must have
    % been seeded from an independently established deterministic true
    % initial set and advanced through conditional original-plant Picard.
    % This code NEVER upgrades the conditional recursion into a physical
    % measurement-error proof. Mismatch, stale time and mixed manual error
    % boxes all fail closed before any HLC/geometry calculations.
    tracked_error_lower=[];tracked_error_upper=[];
    if isfield(C,'true_state_tracker')
        assert(~isfield(C,'error_lower') && ~isfield(C,'error_upper'), ...
            'TRIGGER_CLOSED_LOOP_FROM_SOURCE_LIMITS:ErrorSourceConflict', ...
            'Use the actual tracker OR explicit signed error intervals, never both.');
        assert(isa(C.true_state_tracker,'TRIGGER_EKF_TRUE_SET_TRACKER'), ...
            'TRIGGER_CLOSED_LOOP_FROM_SOURCE_LIMITS:TrackerType', ...
            'Expected the actual stateful 24-state true-set tracker.');
        E=C.true_state_tracker.snapshot();
        assert(E.initialized && isequal(E.time_s,t(1)) && ...
            isequal(size(E.ekf_post),[24 1]) && ...
            isequal(size(E.error_lower),[24 1]) && ...
            isequal(size(E.error_upper),[24 1]), ...
            'TRIGGER_CLOSED_LOOP_FROM_SOURCE_LIMITS:TrackerStale', ...
            'Tracker must enclose the same actual posterior at the horizon start.');
        names={'p','q','v','w','pL','vL','pT','wL'};
        assert(isfield(C,'ekf_now') && isstruct(C.ekf_now) && ...
            isscalar(C.ekf_now) && all(isfield(C.ekf_now,names)), ...
            'TRIGGER_CLOSED_LOOP_FROM_SOURCE_LIMITS:EKFState', ...
            'Original 8x3 EKF posterior fields are mandatory.');
        post=zeros(24,1);
        for j=1:8
            x=C.ekf_now.(names{j});
            assert(isnumeric(x)&&isreal(x)&&isequal(size(x),[3 1]) && ...
                all(isfinite(x)), ...
                'TRIGGER_CLOSED_LOOP_FROM_SOURCE_LIMITS:EKFStateVector', ...
                'Each original EKF posterior part must be 3x1 finite.');
            post(3*j-2:3*j)=double(x);
        end
        assert(isequal(post,E.ekf_post), ...
            'TRIGGER_CLOSED_LOOP_FROM_SOURCE_LIMITS:EKFMismatch', ...
            'True-set recursion and the actual EKF posterior disagree.');
        tracked_error_lower=E.error_lower;
        tracked_error_upper=E.error_upper;
        R.tracker_error_derived=true;
        R.tracker_error_generation=E.generation;
    end
    % Reject conflicting manually supplied bounds, so this entry point
    % cannot silently skip the newly derived mass/HLC calculation.
    assert(~any(isfield(C,{'held_input_lower','held_input_upper', ...
        'true_mass_lower_kg','true_mass_upper_kg'})), ...
        'TRIGGER_CLOSED_LOOP_FROM_SOURCE_LIMITS:Bypass', ...
        'This entry point derives held inputs and future mass; no manual overriding.');
    H=TRIGGER_ORIGINAL_HLC_HOLD_ENVELOPE(C.time_grid_s);
    R.source_hlc=H;
    if ~H.conditional_saturated_hold
        R.status='UNKNOWN_ORIGINAL_HLC_SOURCE_OR_CLOCK';R.reason=H.reason;
        return
    end
    M=TRIGGER_FUTURE_MASS_RATE_ENCLOSURE(C);
    R.mass_rate=M;
    if ~M.conditional_enclosure
        R.status='UNKNOWN_PHYSICAL_MASS_FUTURE_BOUND';R.reason=M.reason;
        return
    end
    D=C;
    if R.tracker_error_derived
        D=rmfield(D,'true_state_tracker');
        D.error_lower=tracked_error_lower;
        D.error_upper=tracked_error_upper;
    end
    D.held_input_lower=H.lower;D.held_input_upper=H.upper;
    D.true_mass_lower_kg=M.true_mass_lower_kg;
    D.true_mass_upper_kg=M.true_mass_upper_kg;
    Q=TRIGGER_CLOSED_LOOP_CONDITIONAL_ASSEMBLY(D);
    R.chain=Q;
    R.possible_risk_ids=Q.possible_risk_ids;
    % Once the source-pinned original Picard/tension pipeline has actually
    % constructed a full-time tube, derive all obstacle outer balls from
    % the OBSERVED shape definitions here.  Never trust a caller's
    % rigorous_outer_ball_certified flag or its supplied bounding radius.
    % This is a second, independent geometric sufficient condition; it
    % does not override an UNKNOWN of the existing original-shape gate.
    if Q.conditional_chain_pass && Q.conditional_tension_positive && ...
            isfield(Q,'plant') && isstruct(Q.plant)
        G=TRIGGER_SOURCE_GEOMETRY_REACH_GATE(struct( ...
            'flowpipe',Q.plant, ...
            'time_grid_s',D.time_grid_s, ...
            'observed_ids',R.observed_ids, ...
            'observed_prepared_shapes',D.observed_prepared_shapes, ...
            'observation_provenance','ACTUAL_SENSOR_HISTORY_ONLY', ...
            'body',D.body));
        R.source_derived_geometry=G;
        R.source_geometry_gate_executed=true;
        R.possible_risk_ids=unique([reshape(R.possible_risk_ids,1,[]), ...
            reshape(G.possible_risk_ids,1,[])],'stable');
    end
    R.status=['CONDITIONAL_SOURCE_AND_RATE_LINK__' Q.status];
    R.reason=['HLC input bounds and per-hold future mass intervals were DERIVED, ' ...
        'then connected to original 24-state Picard and observed geometry. ' ...
        'Physical initial-EKF error, true mass/current rate validity, finite ' ...
        'future HLC, actual hold grid, mode and independent arithmetic proof ' ...
        'must still be established before any real Flight safety claim. ' Q.reason];
catch ME
    R.status='UNKNOWN_CLOSED_LOOP_SOURCE_LIMITS_EXCEPTION';
    R.reason=[ME.identifier ' | ' ME.message];
end
end
