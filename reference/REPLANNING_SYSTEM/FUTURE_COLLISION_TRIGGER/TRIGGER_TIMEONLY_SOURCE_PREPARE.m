function R=TRIGGER_TIMEONLY_SOURCE_PREPARE(fn,audit,cfg)
% Software-only PRE-ARM reference callsite preparation. All samples are
% locally synthetic mathematical source arguments. The REAL stateless
% reference function is allowed only after its independent purity audit.
% Uses a throwaway reference-cache instance with the ORIGINAL nominal
% object's CLASS and schema. Nothing is retained for Flight. No first
% Flight epoch, sensor/obstacle, EKF, controller or plant is inspected.
%
% A MATLAB JIT improvement is NOT guaranteed by executing this function.
% Failure has no authority to change the native parity or safety gate.
R=struct('status','NOT_ATTEMPTED','reason','', 'calls',0, ...
    'cache_windows',0,'cache_columns',0, ...
    'copied_live_nominal_ref_schema',false,'used_flight_start',false, ...
    'stored_reference_values',false,'safe_to_commit',false, ...
    'direct_exact_windows',0,'direct_source_calls',0, ...
    'contract_rejections',0,'reused_exact_columns',0, ...
    'live_epoch_accessed',false);
try
    assert(isa(fn,'function_handle') && isstruct(audit) && ...
        isscalar(audit) && isfield(audit,'eligible') && ...
        islogical(audit.eligible) && isscalar(audit.eligible), ...
        'TRIGGER_TIMEONLY_SOURCE_PREPARE:Audit', ...
        'An independently audited reference handle is mandatory.');
    if ~audit.eligible
        R.status='SKIPPED_UNAUDITED_SOURCE';return
    end
    for k=1:8
        v=fn(0); % Fixed synthetic ARGUMENT, not a Flight clock.
        assert(isnumeric(v)&&isreal(v)&&iscolumn(v) && ...
            numel(v)>=4&&numel(v)<=28&&all(isfinite(v)), ...
            'TRIGGER_TIMEONLY_SOURCE_PREPARE:Source', ...
            'The original source returned an invalid synthetic jet.');
        R.calls=k;
    end
    if nargin<3
        R.status='PASS_REFERENCE_SOURCE_ONLY__NO_JIT_GUARANTEE';return
    end
    mandatory={'nominal','sample_dt_s','horizon_s','cable_length_m'};
    assert(isstruct(cfg)&&isscalar(cfg)&&all(isfield(cfg,mandatory)), ...
        'TRIGGER_TIMEONLY_SOURCE_PREPARE:Config', ...
        'Nominal source and static dt/horizon/length are required.');
    real_nominal=cfg.nominal;
    assert(isa(real_nominal,'TIME_VARYING_REFERENCE') && ...
        isequal(real_nominal.func,fn), ...
        'TRIGGER_TIMEONLY_SOURCE_PREPARE:Nominal', ...
        'The original pre-Flight time-only source is required.');
    % The REAL nominal.t is intentionally [] until the first Flight tick.
    % Never set that field or invent its future value. Make an entirely
    % disposable instance of the SAME MATLAB class and copy only the
    % ORIGINAL, already-generated immutable reference SCHEMA and pure fn.
    mock=struct('estimator',struct('result',struct('state',struct())));
    nominal=TIME_VARYING_REFERENCE(mock, ...
        {'TRIGGER_SOFTWARE_FIXTURE_REFERENCE_FACTORY',{}});
    nominal.func=fn;
    nominal.ref=real_nominal.ref;
    nominal.t=0; % Only this local synthetic instance; not a Flight epoch.
    dt=double(cfg.sample_dt_s);H=double(cfg.horizon_s);
    L=double(cfg.cable_length_m);
    assert(all(isfinite([dt H L])) && all([dt H L]>0), ...
        'TRIGGER_TIMEONLY_SOURCE_PREPARE:Physical', ...
        'Physical model dt/horizon/cable length must be positive.');
    grid=(0:floor(H/dt))*dt;
    grid=grid(grid<H);
    grid=[grid,H];
    assert(numel(grid)>=2&&all(diff(grid)>0), ...
        'TRIGGER_TIMEONLY_SOURCE_PREPARE:Grid', ...
        'A strictly increasing source test grid is required.');
    % Important: FUTURE_COLLISION_TRIGGER.evaluate calls the cache with
    % *six explicit arguments* (seven including obj). The older fixture
    % supplied only four and therefore never entered the production
    % direct_exact/source-argument path. Exercise this actual signature.
    % Synthetic offsets are mathematical probes, not a guessed Flight t0.
    % All cache objects, jets and closures are discarded after this call.
    offsets=dt.*[0 0.125 0.25 0.5 0.75 0.875 1 0];
    reference_at=@(tt)REPLANNING_SYSTEM.software_probe_flight_reference( ...
        nominal,tt,L);
    for k=1:numel(offsets)
        scratch=TRIGGER_REFERENCE_WINDOW_CACHE();
        a=scratch.audit_immutable_source(fn);
        assert(a.eligible, ...
            'TRIGGER_TIMEONLY_SOURCE_PREPARE:CacheAudit', ...
            'Cache did not accept independently audited source.');
        test_times=double(offsets(k))+double(grid(1:end-1));
        now=reference_at(test_times(1));
        [one,first]=scratch.evaluate(nominal,test_times,L,reference_at, ...
            now,'VERIFIED_F_PHASE_NOMINAL_Z_MINUS_CABLEL');
        assert(size(one,2)==numel(test_times)&&all(isfinite(one(:))) && ...
            first.validated_now_used && first.source_cached, ...
            'TRIGGER_TIMEONLY_SOURCE_PREPARE:FullWindow', ...
            'Production-signature synthetic full window was not executed.');
        R.cache_windows=R.cache_windows+1;
        R.cache_columns=R.cache_columns+size(one,2);
        shifted_times=test_times+dt;
        shifted_now=reference_at(shifted_times(1));
        [two,second]=scratch.evaluate(nominal,shifted_times,L,reference_at, ...
            shifted_now,'VERIFIED_F_PHASE_NOMINAL_Z_MINUS_CABLEL');
        assert(size(two,2)==numel(test_times)&&all(isfinite(two(:))) && ...
            second.validated_now_used && second.source_cached, ...
            'TRIGGER_TIMEONLY_SOURCE_PREPARE:ShiftedWindow', ...
            'Production-signature shifted window was not computed.');
        R.cache_windows=R.cache_windows+1;
        R.cache_columns=R.cache_columns+size(two,2);
        stats=scratch.get_status();
        assert(stats.calls==2 && stats.validated_now_reuses==2 && ...
            stats.direct_source_evaluations>0 && ...
            stats.direct_source_rejected==0 && ...
            stats.exact_reuses>0, ...
            'TRIGGER_TIMEONLY_SOURCE_PREPARE:DirectPathNotCovered', ...
            'Did not reach the actual direct-source/exact-shift branch.');
        % Independent reference calls at mathematically chosen columns
        % check source-value parity. Neither is Flight data.
        test_idx=[1,size(two,2)];
        for q=test_idx
            expected=reference_at(shifted_times(q));
            expected_full=zeros(28,1);
            expected_full(1:numel(expected))=double(expected(:));
            assert(isequal(two(:,q),expected_full), ...
                'TRIGGER_TIMEONLY_SOURCE_PREPARE:SourceParity', ...
                'Synthetic direct cache differs from the audited source.');
        end
        R.direct_exact_windows=R.direct_exact_windows+2;
        R.direct_source_calls=R.direct_source_calls+ ...
            stats.direct_source_evaluations;
        R.contract_rejections=R.contract_rejections+ ...
            stats.direct_source_rejected;
        R.reused_exact_columns=R.reused_exact_columns+ ...
            stats.exact_reuses;
    end
    assert(R.direct_exact_windows==16 && R.direct_source_calls>0 && ...
        R.contract_rejections==0 && R.reused_exact_columns>0, ...
        'TRIGGER_TIMEONLY_SOURCE_PREPARE:Coverage', ...
        'Actual direct-exact source path was not fully covered.');
    R.copied_live_nominal_ref_schema=true;
    R.status='PASS_REAL_SOURCE_DIRECT_EXACT_CALLSITE_DISCARDED__NO_JIT_GUARANTEE';
    R.reason='Source/path preparation only; initial Flight and normal spikes unproven.';
catch ME
    R.status='SOURCE_CACHE_CALLSITE_PREPARE_INCOMPLETE';
    R.reason=[ME.identifier ' | ' ME.message];
end
end
