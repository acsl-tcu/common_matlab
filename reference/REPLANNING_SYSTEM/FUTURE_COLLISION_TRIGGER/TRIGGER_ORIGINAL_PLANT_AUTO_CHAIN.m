function R=TRIGGER_ORIGINAL_PLANT_AUTO_CHAIN(C)
% Conditional continuous-time flowpipe for the ORIGINAL 24-state plant.
% Construct a Picard tube and recursively propagate its ENDPOINT for each
% arbitrary COMPUTATIONAL time slab, without resetting to nominal samples.
%
% Input is only explicit uncertainty boxes. A universal applied-input box
% bounds arbitrary time-varying inputs, even with switching within a slab.
% No obstacle definition,
% sensor, actual EKF, future reference, Flight epoch, and no hidden world
% information are fetched. It is NOT invoked from the Flight loop.
%
% Required: time_grid_s 1x(N+1), initial_lower/upper 24x1,
%           held_input_lower/upper 4xN, param_lower/upper 21xN.
% Parameter intervals must contain every allowed time-varying mass in
% their WHOLE control interval. The interval input box must contain the actual
% applied controller output EVERYWHERE in that slab, not only samples.
%
% Optional: observed_prepared_shapes (only already-sensed geometry), body.
% All resulting geometry statuses remain conditional and never commit.
R=struct('status','UNKNOWN_ORIGINAL_PLANT_CHAIN', ...
    'conditional_chain_pass',false,'completed_intervals',0, ...
    'interval_pass',false(1,0),'iteration_counts',zeros(1,0), ...
    'tube_lower',zeros(24,0),'tube_upper',zeros(24,0), ...
    'endpoint_lower',zeros(24,0),'endpoint_upper',zeros(24,0), ...
    'conditional_reach',struct(),'swept_speed',struct(), ...
        'conditional_swept_speed_pass',false, ...
        'directional_geometry',struct(), ...
    'conditional_geometry_pass',false, ...
    'source_and_rounding_audited',false, ...
    'actual_EKF_error_proven',false, ...
    'actual_HLC_sample_hold_proven',false, ...
    'mass_tension_hybrid_proven',false, ...
    'conditional_tension_positive_all_intervals',false, ...
    'tension_lower_N',zeros(1,0), ...
    'tension_status',{{}}, ...
    'manifold_compatible_intervals',false(1,0), ...
    'manifold_exactly_verified',false, ...
    'taut_source_invariants',struct(), ...
    'original_ode_taut_manifold_invariance_verified',false, ...
    'safe_to_commit',false,'reason','');
try
    mandatory={'time_grid_s','initial_lower','initial_upper', ...
        'held_input_lower','held_input_upper','param_lower','param_upper'};
    assert(isstruct(C)&&isscalar(C)&&all(isfield(C,mandatory)), ...
        'TRIGGER_ORIGINAL_PLANT_AUTO_CHAIN:Fields', ...
        'Explicit initial, control-hold and parameter boxes required.');
    t=double(C.time_grid_s(:).');
    assert(isnumeric(C.time_grid_s)&&isreal(C.time_grid_s) && ...
        numel(t)>=2&&all(isfinite(t))&&all(diff(t)>0), ...
        'TRIGGER_ORIGINAL_PLANT_AUTO_CHAIN:Grid', ...
        'Monotone continuous-time grid required.');
    n=numel(t)-1;
    xlo=double(C.initial_lower(:));xhi=double(C.initial_upper(:));
    assert(isequal(size(xlo),[24 1]) && isequal(size(xhi),[24 1]) && ...
        all(isfinite([xlo;xhi]))&&all(xlo<=xhi), ...
        'TRIGGER_ORIGINAL_PLANT_AUTO_CHAIN:Initial', ...
        'Real initial physical 24-state enclosure required.');
    boxes={'held_input_lower','held_input_upper','param_lower','param_upper'};
    dims=[4,4,21,21];
    for j=1:4
        a=C.(boxes{j});
        assert(isnumeric(a)&&isreal(a)&&isequal(size(a),[dims(j) n]) && ...
            all(isfinite(a(:))), ...
            'TRIGGER_ORIGINAL_PLANT_AUTO_CHAIN:Box', ...
            '%s must be a %dx%d finite array.',boxes{j},dims(j),n);
    end
    ul=double(C.held_input_lower);uu=double(C.held_input_upper);
    pl=double(C.param_lower);pu=double(C.param_upper);
    assert(all(ul(:)<=uu(:))&&all(pl(:)<=pu(:)), ...
        'TRIGGER_ORIGINAL_PLANT_AUTO_CHAIN:Order', ...
        'All input/parameter boxes must be ordered.');
    % Discharge the STRUCTURAL invariance obligation on the exact original
    % symbolic ODE. This does NOT turn interval-box compatibility into
    % proof of the true INITIAL holonomic constraints or physical mode.
    R.taut_source_invariants=TRIGGER_TAUT_SOURCE_INVARIANTS();
    % The conservation proof uses dL/dt=0. Merely giving one positive
    % cable-length INTERVAL does not prove its time evolution. This
    % computational witness accepts only the same singleton L throughout
    % all slabs, and is STILL conditional on its physical provenance.
    pinned_constant_L=all(pl(21,:)==pu(21,:)) && ...
        all(pl(21,:)==pl(21,1));
    R.original_ode_taut_manifold_invariance_verified= ...
        R.taut_source_invariants.source_bound_invariance && pinned_constant_L;
    R.interval_pass=false(1,n);
    R.iteration_counts=zeros(1,n);
    R.tube_lower=nan(24,n);R.tube_upper=nan(24,n);
    R.tension_lower_N=nan(1,n);
    R.tension_status=cell(1,n);
    R.manifold_compatible_intervals=false(1,n);
    R.endpoint_lower=nan(24,n+1);R.endpoint_upper=nan(24,n+1);
    R.endpoint_lower(:,1)=xlo;R.endpoint_upper(:,1)=xhi;
    for k=1:n
        % The timestamps are binary64 values, but their exact real
        % difference need not be representable. Time uncertainty matters
        % even when all plant state arithmetic is directed outward.
        clock=TRIGGER_EXACT_BINARY64_TIME_SPAN(t(k),t(k+1));
        if ~clock.valid
            R.status='UNKNOWN_BINARY64_TIME_SPAN';
            R.reason=sprintf('Interval %d: %s',k,clock.reason);
            return
        end
        D=struct('x0_lower',xlo,'x0_upper',xhi, ...
            'u_lower',ul(:,k),'u_upper',uu(:,k), ...
            'param_lower',pl(:,k),'param_upper',pu(:,k), ...
            'h_s',clock.upper_s,'h_lower_s',clock.lower_s);
        step=TRIGGER_ORIGINAL_PLANT_AUTO_PICARD(D);
        R.iteration_counts(k)=step.iterations;
        if ~step.conditional_strict_inclusion
            R.status='UNKNOWN_INTERVAL_NO_VERIFIED_PICARD_TUBE';
            R.reason=sprintf('Hold interval %d: %s | %s', ...
                k,step.status,step.reason);
            return
        end
        R.interval_pass(k)=true;
        R.completed_intervals=k;
        R.tube_lower(:,k)=step.tube_lower;
        R.tube_upper(:,k)=step.tube_upper;
        % Necessary physical cable constraints: a shape-independent
        % guard. Merely containing zero does not certify exact manifold
        % invariance; never turn this into safe_to_commit.
        M=TRIGGER_TAUT_CABLE_MANIFOLD_OBLIGATIONS( ...
            struct('lower',step.tube_lower,'upper',step.tube_upper), ...
            struct('lower',pl(:,k),'upper',pu(:,k)));
        R.manifold_compatible_intervals(k)=M.compatible;
        if ~M.compatible
            R.status='UNKNOWN_INCONSISTENT_TAUT_CABLE_REACH_TUBE';
            R.reason=sprintf('Interval %d: %s',k,M.reason);
            return
        end
        % All-time tension range on this very same Picard tube, not a
        % sampled nominal tension. A positive result is conditional on
        % the original taut-cable model and audited interval operations.
        tension=TRIGGER_ORIGINAL_TENSION_INTERVAL( ...
            struct('lower',step.tube_lower,'upper',step.tube_upper), ...
            struct('lower',ul(:,k),'upper',uu(:,k)), ...
            struct('lower',pl(:,k),'upper',pu(:,k)));
        R.tension_lower_N(k)=tension.tension_lower_N;
        R.tension_status{k}=tension.status;
        xlo=step.endpoint_lower;
        xhi=step.endpoint_upper;
        R.endpoint_lower(:,k+1)=xlo;
        R.endpoint_upper(:,k+1)=xhi;
    end
    R.conditional_chain_pass=true;
    R.conditional_tension_positive_all_intervals= ...
        all(isfinite(R.tension_lower_N) & R.tension_lower_N>0);
    R.conditional_reach=struct('time_grid_s',t, ...
        'uav_lower_m',R.tube_lower(1:3,:), ...
        'uav_upper_m',R.tube_upper(1:3,:), ...
        'payload_lower_m',R.tube_lower(13:15,:), ...
        'payload_upper_m',R.tube_upper(13:15,:));
    % The same original 24-state ALL-TIME tubes also bound the speed of
    % the UAV ball, complete straight cable capsule, and payload ball.
    % This replaces any guessed/nominal speed in CONDITIONAL gate inputs.
    R.swept_speed=TRIGGER_TAUT_TRUE_BODY_SPEED_FROM_TUBE( ...
        R.tube_lower,R.tube_upper);
    if ~R.swept_speed.conditional_bound
        R.conditional_chain_pass=false;
        R.status='UNKNOWN_TRUE_BODY_SWEEP_SPEED';
        R.reason=R.swept_speed.reason;
        return
    end
    R.conditional_swept_speed_pass=true;
    R.conditional_reach.whole_body_speed_upper_mps= ...
        R.swept_speed.whole_body_speed_upper_mps;
    if isfield(C,'observed_prepared_shapes') && isfield(C,'body')
        R.directional_geometry=TRIGGER_DIRECTIONAL_REACH_CERT( ...
            R.conditional_reach,C.observed_prepared_shapes,C.body);
        R.conditional_geometry_pass= ...
            R.directional_geometry.conditional_geometry_pass && ...
            ~isempty(C.observed_prepared_shapes);
    end
    R.status='CONDITIONAL_ORIGINAL_PLANT_AUTO_FLOWPIPE__NO_FLIGHT_PROOF';
    R.reason=['Original source interval-RHS / Picard chain constructed for ' ...
        'EXTERNALLY GIVEN boxes only. Need audited rounding and source equivalence, ' ...
        'actual EKF error, actual finite HLC held inputs, mass/tension/hybrid ' ...
        'model, and interval-safe obstacle support before safety clearance.'];
catch ME
    R.status='UNKNOWN_ORIGINAL_PLANT_CHAIN_ERROR';
    R.reason=[ME.identifier ' | ' ME.message];
end
end
