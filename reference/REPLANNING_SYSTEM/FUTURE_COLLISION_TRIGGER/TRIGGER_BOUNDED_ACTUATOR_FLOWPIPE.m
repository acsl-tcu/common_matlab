function R=TRIGGER_BOUNDED_ACTUATOR_FLOWPIPE(C)
% Conditional sampled-data reachability, ORIGINAL HLC saturation + 24-state RHS.
% Independent of trajectory-generation, live Flight and obstacle truth.
%
% Exact conditional theorem (NOT yet discharged on the real closed loop):
% If every HLC raw result is finite, the byte-pinned saturated output is
% exactly the input applied to the plant, the original 24-state RHS applies
% with taut cable, and supplied X0 / P boxes contain the actual initial
% state and all parameter variations, THEN the plant obeys the universal
% U=[0,20]x[-1,1]^3 AT EVERY INSTANT. The Picard partition need not
% align with real HLC switching/hold instants: arbitrary switching within
% the universal box is mathematically included by the interval RHS.
% TRIGGER_ORIGINAL_PLANT_AUTO_CHAIN can consequently enclose the entire
% state evolution without evaluating the nonlinear HLC on future samples.
% The box is broad and may fail Picard inclusion; failure is UNKNOWN.
% All obligations, particularly estimator error, timing and plant wiring,
% remain outstanding. This file NEVER authorizes safe_to_commit.
R=struct('status','UNKNOWN_NOT_EVALUATED','reason','', ...
    'hlc_source_pinned',false,'conditional_actuator_box',false, ...
    'applied_held_input_proven',false,'finite_raw_hlc_proven',false, ...
    'initial_EKF_error_proven',false,'time_varying_mass_proven',false, ...
    'tension_mode_proven',false,'rounding_proven',false, ...
    'trajectory_clearance_proven',false,'safe_to_commit',false, ...
    'u_lower',zeros(4,0),'u_upper',zeros(4,0), ...
    'conditional_flowpipe',struct(), ...
    'required_witnesses',{{'finite HLC evaluation on every admissible EKF/ref state', ...
    'controller -> input_transform -> plant identity and saturation ordering', ...
    'zero-order-hold or verified actual applied-input waveform', ...
    'EKF error bounds mapped to original 24-state plant state', ...
    'time-varying payload mass and all plant parameter bounds over 4 s', ...
    'taut cable, nonzero tension, valid chart and all hybrid modes', ...
    'audited directed-rounding interval RHS and interval geometry'}});
try
    required={'time_grid_s','initial_lower','initial_upper','param_lower','param_upper'};
    assert(isstruct(C)&&isscalar(C)&&all(isfield(C,required)), ...
        'TRIGGER_BOUNDED_ACTUATOR_FLOWPIPE:Inputs', ...
        'Explicit grid, initial physical 24-state box and 21-parameter boxes required.');
    times=double(C.time_grid_s(:).');
    assert(numel(times)>=2 && all(isfinite(times)) && all(diff(times)>0), ...
        'TRIGGER_BOUNDED_ACTUATOR_FLOWPIPE:Times', ...
        'Computational partition times must be strictly increasing.');
    n=numel(times)-1;
    assert(isequal(size(C.initial_lower),[24 1]) && ...
        isequal(size(C.initial_upper),[24 1]) && ...
        isequal(size(C.param_lower),[21 n]) && ...
        isequal(size(C.param_upper),[21 n]) && ...
        all(isfinite(C.initial_lower)) && all(isfinite(C.initial_upper)) && ...
        all(C.initial_lower<=C.initial_upper) && ...
        all(isfinite(C.param_lower(:))) && all(isfinite(C.param_upper(:))) && ...
        all(C.param_lower(:)<=C.param_upper(:)), ...
        'TRIGGER_BOUNDED_ACTUATOR_FLOWPIPE:Boxes', ...
        'Initial/parameter boxes must be finite and ordered.');
    S=TRIGGER_ORIGINAL_HLC_ACTUATOR_SCOPE();
    R.hlc_source_pinned=S.source_verified;
    if ~S.source_verified
        R.status='UNKNOWN_ORIGINAL_HLC_SOURCE_NOT_PINNED';
        R.reason=S.reason;
        return
    end
    assert(isequal(S.lower,[0;-1;-1;-1]) && ...
        isequal(S.upper,[20;1;1;1]), ...
        'TRIGGER_BOUNDED_ACTUATOR_FLOWPIPE:ActuatorContract', ...
        'The source-audited saturated actuator range changed.');
    R.u_lower=repmat(S.lower,1,n);
    R.u_upper=repmat(S.upper,1,n);
    R.conditional_actuator_box=true;
    D=struct('time_grid_s',times, ...
        'initial_lower',double(C.initial_lower), ...
        'initial_upper',double(C.initial_upper), ...
        'held_input_lower',R.u_lower,'held_input_upper',R.u_upper, ...
        'param_lower',double(C.param_lower), ...
        'param_upper',double(C.param_upper));
    % These boxes are conditional input assumptions: source-level HLC
    % saturation does not prove application by input_transform or plant.
    if isfield(C,'observed_prepared_shapes') && isfield(C,'body')
        D.observed_prepared_shapes=C.observed_prepared_shapes;
        D.body=C.body;
    end
    T=TRIGGER_ORIGINAL_PLANT_AUTO_CHAIN(D);
    R.conditional_flowpipe=T;
    if T.conditional_chain_pass
        R.status='CONDITIONAL_BOUNDED_INPUT_PLANT_TUBE__NOT_CLOSED_LOOP_PROOF';
        R.trajectory_clearance_proven=false;
        R.reason=['24-state Picard tube exists for the universal saturated-input ' ...
            'box only. Controller-to-plant, EKF, modes and audited rounding ' ...
            'are still unproven.'];
    else
        R.status='UNKNOWN_BOUNDED_INPUT_PICARD_NOT_ESTABLISHED';
        R.reason=T.reason;
    end
catch ME
    R.status='UNKNOWN_BOUNDED_INPUT_BRIDGE';
    R.reason=[ME.identifier ' | ' ME.message];
end
end
