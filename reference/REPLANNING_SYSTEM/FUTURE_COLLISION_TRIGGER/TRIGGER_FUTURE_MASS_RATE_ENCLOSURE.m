function R=TRIGGER_FUTURE_MASS_RATE_ENCLOSURE(D)
% Each true physical payload mass m(t) lies in the returned whole-hold box
% IF m(t0) in [m0_lower,m0_upper] and |dm/dt| <= rate_bound_kg_s
% holds for all t in [t0,t_end], including any pickup/release events.
% A current EKF mass estimate alone establishes NEITHER premise.
% Source-provenance booleans cannot establish a physical bound.
% Every arithmetic interval uses TRIGGER_OUTWARD_INTERVAL; missing premises
% and a non-positive resulting lower mass fail closed. No guessed limits.
R=struct('status','UNKNOWN_FUTURE_TRUE_MASS','reason','', ...
    'conditional_enclosure',false,'true_mass_lower_kg',zeros(1,0), ...
    'true_mass_upper_kg',zeros(1,0),'true_mass_proven',false, ...
    'rate_bound_proven',false,'time_alignment_proven',false, ...
    'safe_to_commit',false);
try
    needed={'time_grid_s','true_mass_now_lower_kg', ...
        'true_mass_now_upper_kg','true_mass_rate_bound_kg_s'};
    assert(isstruct(D)&&isscalar(D)&&all(isfield(D,needed)), ...
        'TRIGGER_FUTURE_MASS_RATE_ENCLOSURE:Inputs', ...
        'True initial mass interval and physical rate bound are required.');
    t=double(D.time_grid_s(:).'); n=numel(t)-1;
    assert(n>=1&&all(isfinite(t))&&all(diff(t)>0), ...
        'TRIGGER_FUTURE_MASS_RATE_ENCLOSURE:Grid', ...
        'Strictly increasing actual hold-grid times are required.');
    a=double(D.true_mass_now_lower_kg);
    b=double(D.true_mass_now_upper_kg);
    beta=double(D.true_mass_rate_bound_kg_s);
    assert(isscalar(a)&&isscalar(b)&&isscalar(beta)&& ...
        isreal(a)&&isreal(b)&&isreal(beta)&& ...
        isfinite(a)&&isfinite(b)&&isfinite(beta)&& ...
        0<a&&a<=b&&beta>=0, ...
        'TRIGGER_FUTURE_MASS_RATE_ENCLOSURE:PhysicalBound', ...
        'Positive ordered true mass interval and nonnegative finite true rate bound required.');
    m0=TRIGGER_OUTWARD_INTERVAL(a,b);
    v=TRIGGER_OUTWARD_INTERVAL(beta,beta);
    lo=zeros(1,n);hi=zeros(1,n);
    for k=1:n
        % Covers EVERY time within [t(k),t(k+1)]: the entire hold lies
        % no further than t(k+1)-t(1) from the genuine initial state.
        delta=TRIGGER_OUTWARD_INTERVAL(t(k+1),t(k+1)) - ...
              TRIGGER_OUTWARD_INTERVAL(t(1),t(1));
        assert(delta.lo>=0 && isfinite(delta.hi), ...
            'TRIGGER_FUTURE_MASS_RATE_ENCLOSURE:Clock', ...
            'Outward time calculation must be finite and nonnegative.');
        excursion=v.*delta;
        whole=m0 + TRIGGER_OUTWARD_INTERVAL(-excursion.hi,excursion.hi);
        assert(isfinite(whole.lo)&&isfinite(whole.hi)&&whole.lo>0, ...
            'TRIGGER_FUTURE_MASS_RATE_ENCLOSURE:MayReachZero', ...
            'Given data cannot certify strictly positive mass for the entire hold.');
        lo(k)=whole.lo;hi(k)=whole.hi;
    end
    R.true_mass_lower_kg=lo;R.true_mass_upper_kg=hi;
    R.conditional_enclosure=true;
    R.status='CONDITIONAL_RATE_ENCLOSED_EVERY_HOLD__NOT_TRUE_MASS_PROOF';
    R.reason=['All future true masses are enclosed IF the provided current TRUE mass ' ...
        'interval, continuous-time physical rate bound, event behavior and actual time ' ...
        'grid are independently justified. EKF mL variance is not such evidence.'];
catch ME
    R.reason=[ME.identifier ' | ' ME.message];
end
end
