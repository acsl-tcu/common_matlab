function [next_shapes,next_ids]=TRIGGER_OBSERVED_PREPARED_APPEND( ...
    previous_shapes,previous_ids,new_shapes,new_ids)
% TRIGGER_OBSERVED_PREPARED_APPEND
% Append only geometry that the ACTUAL sensor has JUST disclosed.
% No future/synthetic observation, obstacle-count cap, fixed slots, or
% precomputed detection-mask subsets. This function is called ONLY when
% OBSERVED_OBSTACLE_MEMORY.update has returned newly_acquired_ids.
%
% Inductive invariant: the private REPLANNING_SYSTEM cache was empty at
% construction and every prior append was verified here. Therefore
% previous_shapes(i).id == previous_ids(i) for all previous rows.
% Check ONLY the new shape-ID pairs rather than extracting the IDs from
% the entire grown struct array again. The calling update independently
% compares the resulting NUMERIC ID vector with the sensor-derived
% memory_result.known_obstacle_ids before publishing the cache.
%
% This is a performance candidate, not a safety or WCET claim. Invalid
% event inputs fail closed before either output is published by caller.
assert((isstruct(previous_shapes)||isequal(previous_shapes,[])) && ...
    isnumeric(previous_ids) && isreal(previous_ids) && ...
    (isempty(previous_ids)||isvector(previous_ids)) && ...
    numel(previous_shapes)==numel(previous_ids) && ...
    isstruct(new_shapes) && ~isempty(new_shapes) && ...
    isfield(new_shapes,'id') && ...
    isnumeric(new_ids) && isreal(new_ids) && ...
    isvector(new_ids) && ~isempty(new_ids), ...
    'TRIGGER_OBSERVED_PREPARED_APPEND:Contract', ...
    'An existing verified cache and a nonempty real acquisition are required.');
previous_ids=reshape(double(previous_ids),1,[]);
new_ids=reshape(double(new_ids),1,[]);
assert(all(isfinite(new_ids)) && all(new_ids>0) && ...
    all(new_ids==fix(new_ids)) && ...
    numel(unique(new_ids))==numel(new_ids) && ...
    numel(new_shapes)==numel(new_ids) && ...
    isequal(reshape(double([new_shapes.id]),1,[]),new_ids) && ...
    ~any(ismember(new_ids,previous_ids)), ...
    'TRIGGER_OBSERVED_PREPARED_APPEND:ObservedIDMismatch', ...
    'Only newly sensed, correctly ordered and disjoint shape IDs are appendable.');
% Exactly one struct concatenation on a real new-observation event.
next_shapes=OBSERVED_OBSTACLE_MEMORY.append_row_structs( ...
    previous_shapes,new_shapes);
next_ids=[previous_ids new_ids];
assert(numel(next_shapes)==numel(next_ids), ...
    'TRIGGER_OBSERVED_PREPARED_APPEND:Length', ...
    'The newly assembled observation arrays disagree in length.');
end
