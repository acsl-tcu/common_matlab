classdef CHECK_TRIGGER_ORIGINAL_NUMERIC_ORACLE
    % Experimental nominal rollout using the EXISTING HLC and plant RHS.
    % Never invokes HLC.do() on the real Flight agent; a separate HLC instance
    % and separate STATE_CLASS instances are used for each evaluation.
    % Does not model future EKF error, reachability, cable slack, or provide
    % interval bounds. Thus NEVER proves continuous-time safety.
    methods (Static)
        function prediction=predict(request,binding)
            required={'sample_times_s','time_s','ekf_now','payload_mass_kg','reference_at'};
            assert(isstruct(request)&&isscalar(request)&&all(isfield(request,required)), ...
                'TRIGGER_HLC_PLANT_PREDICTOR:Request','Incomplete model request.');
            assert(isstruct(binding)&&isscalar(binding)&& ...
                all(isfield(binding,{'plant_rhs','plant_solver', ...
                    'model_parameters','loadmass_index','hlc_param', ...
                    'hlc_parameter_names','hlc_parameter_values'})), ...
                'TRIGGER_HLC_PLANT_PREDICTOR:FlightBinding', ...
                'Flight-bound model/controller authorities are missing.');
            assert(exist('HLC_SUSPENDED_LOAD','class')==8 && ...
                exist('STATE_CLASS','class')==8, ...
                'TRIGGER_HLC_PLANT_PREDICTOR:Classes', ...
                'Actual HLC_SUSPENDED_LOAD and STATE_CLASS must be on the path.');
            clock=tic;
            % Pure CPU/compute effort limit (not a prediction horizon).
            % The declared 4 s horizon never changes. An unfinished
            % calculation is reported UNKNOWN, never called safe.
            budget=Inf;
            if isfield(request,'compute_budget_ms')
                budget=request.compute_budget_ms;
                assert(isnumeric(budget)&&isscalar(budget)&&isreal(budget)&& ...
                    (isfinite(budget)&&budget>0 || isinf(budget)&&budget>0), ...
                    'TRIGGER_HLC_PLANT_PREDICTOR:ComputeBudget', ...
                    'Computation budget must be positive milliseconds or Inf.');
            end
            grid=double(request.sample_times_s(:).');
            assert(numel(grid)>=2 && grid(1)==0 && ...
                all(isfinite(grid)) && all(diff(grid)>0), ...
                'TRIGGER_HLC_PLANT_PREDICTOR:Grid','Invalid future sample grid.');
            assert(isnumeric(request.payload_mass_kg) && ...
                isscalar(request.payload_mass_kg) && isfinite(request.payload_mass_kg) && ...
                request.payload_mass_kg>0, ...
                'TRIGGER_HLC_PLANT_PREDICTOR:Mass','Current EKF mass is invalid.');
            assert(isa(request.reference_at,'function_handle'), ...
                'TRIGGER_HLC_PLANT_PREDICTOR:Reference', ...
                'Future reference from the existing reference must be bound.');
            e=request.ekf_now;
            names={'p','q','v','w','pL','vL','pT','wL'};
            x=zeros(24,1);
            for j=1:8
                v=e.(names{j});
                assert(isnumeric(v)&&isreal(v)&&isequal(size(v),[3 1]) && ...
                    all(isfinite(v)), 'TRIGGER_HLC_PLANT_PREDICTOR:EKF', ...
                    'Current EKF field %s is invalid.',names{j});
                x((3*j-2):(3*j))=double(v);
            end
            % Same state layout as the active Model_Suspended_Load and HLC.
            state=STATE_CLASS(struct('state_list', ...
                ["p","q","v","w","pL","vL","pT","wL","mL"], ...
                'num_list',[3,3,3,3,3,3,3,3,1]));
            refstate=STATE_CLASS(struct('state_list',"xd",'num_list',28));
            params=TRIGGER_SHADOW_PARAMETER( ...
                binding.hlc_parameter_names,binding.hlc_parameter_values);
            shadow=TRIGGER_SHADOW_AGENT(state,refstate,params);
            % Instantiate the REAL HLC class with a shadow agent and the
            % FLIGHT-snapshotted gains. HLC.do's own saturations are retained.
            hlc=HLC_SUSPENDED_LOAD(shadow,binding.hlc_param);
            hlc.result=struct();
            physical=double(binding.model_parameters(:).');
            physical(binding.loadmass_index)=double(request.payload_mass_kg);
            n=numel(grid);
            uav=zeros(3,n); payload=zeros(3,n);
            controls=zeros(4,n-1);
            uav(:,1)=e.p; payload(:,1)=e.pL;
            completed=1;
            controller_ms=0;integrator_ms=0;
            setup_ms=1000*toc(clock);
            for k=1:n-1
                ref=double(request.reference_at(request.time_s+grid(k)));
                assert(isreal(ref)&&iscolumn(ref)&&numel(ref)>=4 && ...
                    numel(ref)<=28 && all(isfinite(ref)), ...
                    'TRIGGER_HLC_PLANT_PREDICTOR:Reference', ...
                    'The actual phase-adjusted reference must return finite 4..28x1 jets.');
                state.set_state(struct('p',x(1:3),'q',x(4:6), ...
                    'v',x(7:9),'w',x(10:12), ...
                    'pL',x(13:15),'vL',x(16:18), ...
                    'pT',x(19:21),'wL',x(22:24), ...
                    'mL',double(request.payload_mass_kg)));
                refstate.set_state('xd',ref);
                phase_clock=tic;
                out=hlc.do();
                controller_ms=controller_ms+1000*toc(phase_clock);
                u=out.input;
                assert(isnumeric(u)&&isreal(u)&&isequal(size(u),[4 1]) && ...
                    all(isfinite(u)), ...
                    'TRIGGER_HLC_PLANT_PREDICTOR:HLC', ...
                    'Unmodified HLC returned an invalid control input.');
                controls(:,k)=u;
                % The exact configured plant RHS and solver are used, with
                % controller input held for one configured controller tick.
                h=grid(k+1)-grid(k);
                phase_clock=tic;
                [~,sol]=binding.plant_solver( ...
                    @(tau,y) binding.plant_rhs(y,u,physical),[0,h],x);
                integrator_ms=integrator_ms+1000*toc(phase_clock);
                assert(isnumeric(sol)&&size(sol,2)==24 && ...
                    ~isempty(sol)&&all(isfinite(sol(end,:))), ...
                    'TRIGGER_HLC_PLANT_PREDICTOR:Plant', ...
                    'The actual suspended-load plant solver failed.');
                x=double(sol(end,:).');
                uav(:,k+1)=x(1:3);payload(:,k+1)=x(13:15);
                completed=k+1;
            end
            complete=(completed==n);
            prediction=struct('sample_times_s',grid(1:completed), ...
                'uav_m',uav(:,1:completed),'payload_m',payload(:,1:completed), ...
                'input_thrust_torque',controls(:,1:max(0,completed-1)), ...
                'prediction_complete',complete, ...
                'compute_budget_ms',double(budget), ...
                'controller_total_ms',controller_ms, ...
                'integrator_total_ms',integrator_ms, ...
                'setup_total_ms',setup_ms, ...
                'model_description', ...
                'EXISTING_HLC_AND_PLANT_RHS__NOMINAL_ESTIMATOR_PROXY__NOT_CERTIFIED', ...
                'nominal_only',true,'continuous_bounds_provided',false, ...
                'hlc_mass_source_kg',params.get("loadmass"), ...
                'plant_mass_source_kg',double(request.payload_mass_kg), ...
                'plant_rhs_authority',func2str(binding.plant_rhs), ...
                'plant_solver_authority',func2str(binding.plant_solver));
            % DO NOT claim interval excursions / tracking/estimator error
            % bounds / taut cable. The trigger must fail closed for SAFE.
        end
    end
end
