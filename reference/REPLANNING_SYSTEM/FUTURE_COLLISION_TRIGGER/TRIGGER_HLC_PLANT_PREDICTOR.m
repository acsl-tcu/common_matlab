classdef TRIGGER_HLC_PLANT_PREDICTOR
    % Candidate native numeric HLC+full 24-state plant nominal rollout.
    % The original MATLAB HLC and original plant are NOT changed.
    % Full 4 s prediction in one call; no time budget, no partial prefix.
    % Source SHA and A/B HLC/ODE parity are mandatory before use.
    % IMPORTANT: Nominal samples DO NOT establish continuous-time safety,
    % estimator-error/tension guarantee, or future phase correctness.
    methods (Static)
        function P = predict(req,b)
            start=tic;
            assert(isstruct(req)&&isstruct(b)&&...
                isfield(req,'reference_at')&&isfield(req,'sample_times_s')&&...
                isfield(req,'ekf_now')&&isfield(req,'payload_mass_kg')&&...
                isfield(req,'numeric_tolerances'),...
                'TRIGGER_HLC_PLANT_PREDICTOR:Request',...
                'Flight source, future reference and numeric tolerances required.');
            assert(isfield(b,'model_parameters')&&isfield(b,'loadmass_index')&&...
                isfield(b,'hlc_parameter_values')&&isfield(b,'hlc_param')&&...
                isfield(b,'plant_rhs')&&isfield(b,'plant_solver'),...
                'TRIGGER_HLC_PLANT_PREDICTOR:Binding',...
                'Incomplete actual HLC / plant binding.');
            % Do not make the Flight slow again if the candidate fails
            % verification: return UNKNOWN via the caller's catch branch.
            % Preflight performs read-only SHA/parity pinning once for each
            % Flight. This hot path MUST NOT hash files/load MAT/build sources.
            % If preflight was not executed, fail closed rather than
            % silently moving that cold-start work into the Flight loop.
            readiness=TRIGGER_NATIVE_SOURCE_PIN_CACHE('get');
            if ~readiness.passed
                error('TRIGGER_HLC_PLANT_PREDICTOR:NotReady','%s',readiness.status);
            end
            % Strictly require exact source order and active solver.
            if isfield(b,'native_source_order_checked') && ...
                    isequal(b.native_source_order_checked,true) && ...
                    isfield(b,'plant_rhs_name') && isfield(b,'plant_solver_name')
                % Real preflight binding already verified the original
                % function handles and parameter order. No func2str in Flight.
                source_names_ok=strcmp(b.plant_rhs_name, ...
                    'with_load_model_euler_for_HL') && ...
                    strcmp(b.plant_solver_name,'ode15s');
                rhs_label=b.plant_rhs_name;
                solver_label=b.plant_solver_name;
            else
                % Synthetic/offline callers retain the original hot check.
                rhs_label=func2str(b.plant_rhs);
                solver_label=func2str(b.plant_solver);
                source_names_ok=strcmp(rhs_label, ...
                    'with_load_model_euler_for_HL') && ...
                    strcmp(solver_label,'ode15s');
            end
            assert(isequal(b.loadmass_index,20) && source_names_ok,...
                'TRIGGER_HLC_PLANT_PREDICTOR:SourceOrder',...
                'Native kernel not pinned to this live RHS/solver/parameter order.');
            e=req.ekf_now;
            % The original complete 24-state order. The core has already
            % checked all eight fields; retain the 24-element finite guard.
            x=double([e.p;e.q;e.v;e.w;e.pL;e.vL;e.pT;e.wL]);
            assert(isreal(x)&&isequal(size(x),[24 1])&&all(isfinite(x)),...
                'TRIGGER_HLC_PLANT_PREDICTOR:EKF',...
                'Invalid current EKF 24-vector.');
            mass=double(req.payload_mass_kg);
            assert(isscalar(mass)&&isfinite(mass)&&mass>0,...
                'TRIGGER_HLC_PLANT_PREDICTOR:Mass','Invalid current estimator mL.');
            pp=double(b.model_parameters(:));pp(20)=mass;
            hp=double(b.hlc_parameter_values(:));
            gain=b.hlc_param;
            ts=reshape(double(req.sample_times_s),1,[]);
            n=numel(ts);
            assert(n>=2&&ts(1)==0&&all(isfinite(ts))&&all(diff(ts)>0),...
                'TRIGGER_HLC_PLANT_PREDICTOR:TimeGrid','Invalid complete horizon.');
            if isfield(req,'reference_matrix')
                % Reuse is allowed only from the original source at EXACTLY
                % identical absolute times; cache owns validation/invalidation.
                ref=double(req.reference_matrix);
                assert(isreal(ref)&&isequal(size(ref),[28,n-1])&& ...
                    all(isfinite(ref(:))), ...
                    'TRIGGER_HLC_PLANT_PREDICTOR:ReferenceMatrix', ...
                    'Cached future reference samples are missing or invalid.');
            else
                % Original uncached path for offline regression and audits.
                ref=zeros(28,n-1);
                for i=1:n-1
                    r=double(req.reference_at(req.time_s+ts(i)));
                    assert(iscolumn(r)&&isreal(r)&&numel(r)>=4&&numel(r)<=28&&...
                        all(isfinite(r)),...
                        'TRIGGER_HLC_PLANT_PREDICTOR:Reference',...
                        'Future reference must be actual 4..28x1 jets.');
                    ref(1:numel(r),i)=r;
                end
            end
            tol=double(req.numeric_tolerances(:));
            assert(numel(tol)==2 && all(isfinite(tol)) && all(tol>0),...
                'TRIGGER_HLC_PLANT_PREDICTOR:Tolerance',...
                'Flight must supply finite positive [AbsTol, RelTol].');
            setup_ms=1000*toc(start);
            fused=false; sampled_excluded=false(1,0);
            trace_first=isfield(req,'first_use_trace') && ...
                isequal(req.first_use_trace,true);
            if trace_first, native_call_clock=tic; end
            if isfield(req,'native_sampled_outer_balls') && ...
                    isfield(req,'native_sampled_body_radii') && ...
                    isfield(req,'native_sampled_outer_ids')
                bballs=double(req.native_sampled_outer_balls);
                rad=double(req.native_sampled_body_radii(:));
                b_ids=double(req.native_sampled_outer_ids(:)).';
                assert(isreal(bballs)&&size(bballs,1)==5 && ...
                    numel(b_ids)==size(bballs,2) && ...
                    isreal(rad)&&isequal(size(rad),[3 1]) && ...
                    all(isfinite(rad))&&all(rad>=0) && ...
                    all(isfinite(bballs(:))) && ...
                    all(bballs(4,:)>=0) && ...
                    all(ismember(bballs(5,:),[0 1])), ...
                    'TRIGGER_HLC_PLANT_PREDICTOR:OuterBalls', ...
                    'All outer balls must come from validated observed solids.');
                [q,l,u,stats,sampled_excluded]=TRIGGER_SYMBOLIC_NATIVE_CORE(...
                    x,ts,ref,pp,hp,gain.F1(:),gain.F2(:),gain.F3(:),...
                    gain.F4(:),double(gain.dt),tol,bballs,rad);
                fused=true;
            else
                [q,l,u,stats]=TRIGGER_SYMBOLIC_NATIVE_CORE(...
                    x,ts,ref,pp,hp,gain.F1(:),gain.F2(:),gain.F3(:),...
                    gain.F4(:),double(gain.dt),tol);
            end
            if trace_first
                native_call_wall_ms=1000*toc(native_call_clock);
            end
            assert(isequal(size(q),[3 n])&&isequal(size(l),[3 n])&&...
                isequal(size(u),[4 n-1])&&all(isfinite([q(:);l(:);u(:)])),...
                'TRIGGER_HLC_PLANT_PREDICTOR:Output','Native numeric output invalid.');
            P=struct('sample_times_s',ts,'uav_m',q,'payload_m',l,...
                'input_thrust_torque',u,'prediction_complete',true,...
                'model_description',...
                'PINNED_ORIGINAL_HLC_SYMBOLIC_AND_PLANT_RHS__NATIVE_NUMERIC_ONLY',...
                'nominal_only',true,'continuous_bounds_provided',false,...
                'controller_total_ms',stats(3),'integrator_total_ms',stats(4),...
                'setup_total_ms',setup_ms,'rhs_evaluations',stats(1),...
                'rejected_numeric_steps',stats(2),...
                'hlc_mass_source_kg',hp(6),'plant_mass_source_kg',mass,...
                'plant_rhs_authority',rhs_label,...
                'plant_solver_authority',solver_label);
            if trace_first
                P.native_call_wall_ms=native_call_wall_ms;
                P.first_predictor_total_wall_ms=1000*toc(start);
            end
            if fused
                P.native_sampled_outer_excluded=logical(sampled_excluded);
                P.native_sampled_outer_ids=b_ids;
                P.native_sampled_outer_only=true;
            end
        end
    end
end
