function R=TRIGGER_SIM_RUNNER_ORDER_PROOF()
% Verify the actual live Sim runner's EKF/HLC/plant/replanner call order.
% Lexical source pin is intentionally narrow; an edited runner fails closed.
% This does not read plant.state or inspect future EKF measurements.
R=struct('status','UNKNOWN_SIM_RUNNER_ORDER','reason','', ...
    'source_order_verified',false,'arming_then_t0_duplicate',false, ...
    'previous_controller_input_alignment_proven',false, ...
    'actual_closed_loop_physical_certified',false,'safe_to_commit',false);
try
    path=which('run_flight_headless');
    assert(~isempty(path)&&isfile(path), ...
        'TRIGGER_SIM_RUNNER_ORDER_PROOF:Missing', ...
        'Actual run_flight_headless.m source not on MATLAB path.');
    s=fileread(path);
    % Only comments/whitespace are removed; the ORIGINAL runner is not
    % executed, changed, or replaced by a synthetic trajectory.
    s=regexprep(s,'(?m)%[^\n]*','');
    s=regexprep(s,'\s+','');
    s=strrep(s,'"','''');
    start=strfind(s,'whiletime.t<=time.te');
    assert(numel(start)==1, ...
        'TRIGGER_SIM_RUNNER_ORDER_PROOF:FlightLoop', ...
        'Expected exactly one original monotone Flight loop.');
    prefix=s(1:start);
    A=strfind(prefix,'replanner_instance.update(time,agent);');
    assert(~isempty(A) && contains(prefix,'time.t=0;'), ...
        'TRIGGER_SIM_RUNNER_ORDER_PROOF:Arming', ...
        'Sim t0 Arming must call the same replanner before the loop.');
    tail=s(start:end);
    token_time='time.t=time.t+dt;';
    e=strfind(tail,token_time);
    assert(~isempty(e), ...
        'TRIGGER_SIM_RUNNER_ORDER_PROOF:TimeIncrement', ...
        'Original increment after the plant/replanner loop is missing.');
    flight=tail(1:e(1)+numel(token_time)-1);
    required={ ...
        'motive.getData(agent);', ...
        'do_prop_local(time,cha,cha,logger,env,agent,''sensor'',1);', ...
        'do_prop_local(time,cha,cha,logger,env,agent,''estimator'',1);', ...
        'do_prop_local(time,cha,cha,logger,env,agent,''reference'',1);', ...
        'do_prop_local(time,cha,cha,logger,env,agent,''controller'',1);', ...
        'do_prop_local(time,cha,cha,logger,env,agent,''input_transform'',1);', ...
        'do_prop_local(time,cha,cha,logger,env,agent,''plant'',1);', ...
        'replanner_instance.update(time,agent);', ...
        'logger.logging(time,cha,agent,[]);', ...
        token_time};
    offsets=zeros(1,numel(required));
    for i=1:numel(required)
        hits=strfind(flight,required{i});
        assert(numel(hits)==1, ...
            'TRIGGER_SIM_RUNNER_ORDER_PROOF:MissingOrDuplicate', ...
            'Required Sim loop call missing or duplicated: %s',required{i});
        offsets(i)=hits;
    end
    assert(all(diff(offsets)>0), ...
        'TRIGGER_SIM_RUNNER_ORDER_PROOF:Ordering', ...
        'Current EKF, HLC input, ORIGINAL plant.do and replanner ordering differs.');
    % Critical distinction: the runner's accumulated time.t is NOT the
    % time interval that MODEL_CLASS actually integrates. MODEL_CLASS.do
    % reuses [obj.ts, obj.ts+obj.dt] for each autonomous held-input step.
    % Thus a proof interval for the original Sim plant must use obj.dt,
    % not the rounded subtraction of adjacent accumulated timestamps.
    model_path=which('MODEL_CLASS');
    assert(~isempty(model_path)&&isfile(model_path), ...
        'TRIGGER_SIM_RUNNER_ORDER_PROOF:ModelClassMissing', ...
        'Cannot pin the actual MODEL_CLASS solver time integration.');
    model_text=fileread(model_path);
    model_text=regexprep(model_text,'(?m)%[^\n]*','');
    model_text=regexprep(model_text,'\s+','');
    assert(contains(model_text,'obj.dt=varargin{1}.dt;') && ...
        contains(model_text,'[obj.tsobj.ts+obj.dt],obj.state.get()') && ...
        contains(model_text,'u=obj.self.controller.result.input;'), ...
        'TRIGGER_SIM_RUNNER_ORDER_PROOF:ModelClassHoldMismatch', ...
        'Original numeric plant does not integrate with the documented held input and solver dt.');
    R.physical_hold_duration_from_solver_proven=true;
    R.source_order_verified=true;
    R.arming_then_t0_duplicate=true;
    R.previous_controller_input_alignment_proven=true;
    R.status='SOURCE_PINNED_SIM_T0_AND_ACTUAL_PREVIOUS_HOLD_ORDER';
    R.reason=['Original Flight loop is EKF->HLC->plant->replanner and ' ...
        'only then t+=dt. Current controller input applied by plant is ' ...
        'stored now and propagated to the NEXT actual EKF posterior; no future ' ...
        'plant state read. Physical integration interval is MODEL_CLASS dt, ' ...
        'not the cumulative runner timestamp difference. Solver numerical error ' ...
        'and true physical-system equivalence remain separate.'];
catch ME
    R.reason=[ME.identifier ' | ' ME.message];
end
end
