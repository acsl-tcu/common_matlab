function R=TRIGGER_TAUT_CONE_FLOWPIPE_GATE(C)
% CONDITIONAL full-time geometry of a straight, taut UAV-cable-payload.
% Connects the ORIGINAL 24-state Picard chain with the independently
% derived sphere-direction cap of d_dot=omega_L x d. The initial cap is
% constructed from each interval's endpoint direction BOX, not an ad-hoc
% swing-angle bound. Angular speed comes from its ALL-TIME Picard BOX.
%
% C.flowpipe: output of TRIGGER_ORIGINAL_PLANT_AUTO_CHAIN, including
%  tube_lower/upper 24xK and endpoint_lower/upper 24x(K+1).
% C.time_grid_s: corresponding real time grid 1x(K+1), no phase time guess.
% C.param_lower/upper: all-time 21xK physical parameter enclosures;
%  row 21 is cable length, supplied from actual model, not a fallback.
% C.observed_prepared_shapes: already-sensed static geometry ONLY.
% C.body: physical radii r_uav_m, r_cable_m, r_payload_m.
%
% If a single common normal separates the ENTIRE taut body from each
% obstacle on each interval, the ideal REAL-ARITHMETIC geometry is
% conditionally separated. NO autonomous safety permission is provided.
% This does NOT prove EKF error, HLC held-input image, mass evolution,
% taut hybrid mode, rigorously rounded trigonometry or real-time runtime.
R=struct('status','UNKNOWN_CONE_FLOWPIPE_GATE','reason','', ...
    'conditional_geometry_pass',false,'safe_to_commit',false, ...
    'continuous_closed_loop_safe_certified',false, ...
    'interval_count',0,'observed_count',0, ...
    'direction_cap_upper_rad',zeros(1,0), ...
    'angular_speed_upper_rad_s',zeros(1,0), ...
    'separated_intervals',false(0,0), ...
    'possible_risk_ids',zeros(1,0), ...
    'earliest_possible_event',struct(), ...
    'smallest_conditional_clearance',NaN, ...
    'requires',{{'verified_EKF_error_tube','actual_HLC_input_hold', ...
         'true_mass_interval','strict_tension_and_taut_mode', ...
         'observed_only_provenance','outward_rounding_and_source_parity'}});
try
    assert(isstruct(C)&&isscalar(C)&&all(isfield(C, ...
        {'flowpipe','time_grid_s','param_lower','param_upper', ...
         'observed_prepared_shapes','body'})), ...
        'TRIGGER_CONE_GATE:Fields','All explicit conditional inputs required.');
    F=C.flowpipe;
    assert(isstruct(F)&&isscalar(F)&& ...
        isfield(F,'conditional_chain_pass') && isequal(F.conditional_chain_pass,true) && ...
        isfield(F,'tube_lower')&&isfield(F,'tube_upper') && ...
        isfield(F,'endpoint_lower')&&isfield(F,'endpoint_upper') && ...
        isfield(F,'conditional_tension_positive_all_intervals') && ...
        isequal(F.conditional_tension_positive_all_intervals,true) && ...
        isfield(F,'manifold_compatible_intervals') && ...
        all(F.manifold_compatible_intervals(:)), ...
        'TRIGGER_CONE_GATE:Flowpipe', ...
        'Only a completed, positive-tension and manifold-compatible chain is admissible.');
    t=double(C.time_grid_s(:).');K=numel(t)-1;
    assert(K>=1&&all(isfinite(t))&&all(diff(t)>0), ...
        'TRIGGER_CONE_GATE:Time','Monotone actual interval grid required.');
    assert(isfield(F,'completed_intervals') && ...
        isequal(double(F.completed_intervals),double(K)) && ...
        numel(F.manifold_compatible_intervals)==K && ...
        isfield(F,'tension_lower_N') && ...
        numel(F.tension_lower_N)==K && ...
        all(isfinite(F.tension_lower_N(:))) && ...
        all(F.tension_lower_N(:)>0), ...
        'TRIGGER_CONE_GATE:ChainWitness', ...
        'Every time interval needs a positive-tension, taut-chain witness.');
    xlo=double(F.tube_lower);xhi=double(F.tube_upper);
    elo=double(F.endpoint_lower);ehi=double(F.endpoint_upper);
    pl=double(C.param_lower);pu=double(C.param_upper);
    assert(isequal(size(xlo),[24 K])&&isequal(size(xhi),[24 K]) && ...
        isequal(size(elo),[24 K+1])&&isequal(size(ehi),[24 K+1]) && ...
        isequal(size(pl),[21 K])&&isequal(size(pu),[21 K]) && ...
        all(isfinite([xlo(:);xhi(:);elo(:);ehi(:);pl(:);pu(:)])) && ...
        all(xlo(:)<=xhi(:))&&all(elo(:)<=ehi(:))&&all(pl(:)<=pu(:)), ...
        'TRIGGER_CONE_GATE:Bounds','Exact interval dimensions and order required.');
    assert(all(pl(20,:)>0) && all(pl(21,:)>0), ...
        'TRIGGER_CONE_GATE:MassAndLength', ...
        'Actual payload mass and taut cable length intervals must be positive.');
    B=C.body;
    assert(isstruct(B)&&isscalar(B) && ...
        all(isfield(B,{'r_uav_m','r_cable_m','r_payload_m'})), ...
        'TRIGGER_CONE_GATE:Body','Actual physical body radii required.');
    radii=[B.r_uav_m B.r_cable_m B.r_payload_m];
    assert(isnumeric(radii)&&isreal(radii)&&all(isfinite(radii)) && all(radii>=0), ...
        'TRIGGER_CONE_GATE:Radii','All physical radii must be nonnegative.');
    S=C.observed_prepared_shapes;
    assert(isstruct(S)&&~isempty(S) && ...
        all(isfield(S,{'id','center0','rotation','dimensions', ...
                       'type','is_stationary'})) && ...
        all([S.is_stationary]), ...
        'TRIGGER_CONE_GATE:Observed', ...
        'Only source-validated already-sensed STATIC solids are admitted.');
    ids=reshape(double([S.id]),1,[]);
    assert(all(isfinite(ids))&&all(ids>=1)&&all(ids==fix(ids)) && ...
        numel(unique(ids))==numel(ids), ...
        'TRIGGER_CONE_GATE:Ids','Unique real observed IDs required.');
    if isfield(C,'observed_ids')
        assert(isequal(reshape(double(C.observed_ids),1,[]),ids), ...
            'TRIGGER_CONE_GATE:Ids', ...
            'Prepared shapes must match cumulative observed ID order.');
    end
    nS=numel(S);R.interval_count=K;R.observed_count=nS;
    separated=false(nS,K);
    caps=nan(1,K);rates=nan(1,K);minimum=inf;
    for j=1:nS
        sh=S(j);
        assert(isequal(size(sh.center0),[3 1]) && ...
            isequal(size(sh.rotation),[3 3]) && ...
            all(isfinite([double(sh.center0(:));double(sh.rotation(:))])), ...
            'TRIGGER_CONE_GATE:Shape','Invalid oriented sensed solid.');
        RR=double(sh.rotation);
        assert(norm(RR.'*RR-eye(3),'fro')<=1e-8 && det(RR)>0, ...
            'TRIGGER_CONE_GATE:SO3','Shape rotation must lie in SO(3).');
    end
    for k=1:K
        dlo=elo(19:21,k);dhi=ehi(19:21,k);
        % Necessary consistency with the UNIT S2 sphere, not a proof of
        % exact physical taut mode. That is an upstream obligation.
        nearest=max(0,max(dlo,-dhi));
        farthest=max(abs(dlo),abs(dhi));
        if ~(sum(nearest.^2)<=1 && sum(farthest.^2)>=1)
            R.status='UNKNOWN_ENDPOINT_DIRECTION_NOT_UNIT_COMPATIBLE';
            R.reason=sprintf('Interval %d initial direction box misses S2.',k);
            return
        end
        center=(dlo+dhi)/2;
        if norm(center)>0
            axis=center/norm(center);
        else
            axis=[0;0;-1]; % Arbitrary search axis; no assumed direction.
        end
        min_projection=sum(max(axis,0).*dlo + min(axis,0).*dhi);
        alpha0=acos(max(-1,min(1,min_projection)));
        wmax=max(abs(xlo(22:24,k)),abs(xhi(22:24,k)));
        omega=sqrt(sum(wmax.^2));
        rates(k)=omega;
        caps(k)=min(pi,alpha0+omega*(t(k+1)-t(k)));
        qlo=xlo(1:3,k);qhi=xhi(1:3,k);
        qmid=(qlo+qhi)/2;
        for j=1:nS
            sh=S(j);sc=double(sh.center0(:));
            % Normals are only SEARCH HINTS. For every chosen normal we
            % evaluate support of the true prepared observed solid.
            normals=[sc-qmid,eye(3),-eye(3), ...
                     double(sh.rotation),-double(sh.rotation)];
            norms=sqrt(sum(normals.^2,1));
            normals=normals(:,isfinite(norms)&norms>0);
            D=struct('uav_lower',qlo,'uav_upper',qhi, ...
                'initial_direction_axis',axis, ...
                'initial_direction_angle_upper_rad',alpha0, ...
                'angular_speed_upper_rad_s',omega, ...
                'interval_duration_s',t(k+1)-t(k), ...
                'cable_length_lower_m',pl(21,k), ...
                'cable_length_upper_m',pu(21,k), ...
                'r_uav_m',radii(1),'r_cable_m',radii(2), ...
                'r_payload_m',radii(3),'normals',normals);
            Z=TRIGGER_TAUT_DIRECTION_CONE_SUPPORT(D);
            if ~Z.conditional_enclosure
                R.status='UNKNOWN_CAP_SUPPORT_NOT_AVAILABLE';
                R.reason=Z.reason;
                return
            end
            obs_min=sc.'*normals - ...
                TRIGGER_GEOMETRY_CERTIFICATE.support_radial_many(sh,-normals);
            margin=obs_min-Z.union_support_upper;
            margin=margin(isfinite(margin));
            if ~isempty(margin)
                best=max(margin);
                minimum=min(minimum,best);
                separated(j,k)=best>0;
            end
        end
    end
    R.direction_cap_upper_rad=caps;
    R.angular_speed_upper_rad_s=rates;
    R.separated_intervals=separated;
    R.possible_risk_ids=ids(any(~separated,2).');
    % Return the FIRST unproved interval, preserving simultaneous IDs.
    % This is not a contact time and does not imply actual Flight safety.
    R.earliest_possible_event=TRIGGER_FIRST_UNPROVED_INTERVAL( ...
        t,ids,separated);
    if isfinite(minimum),R.smallest_conditional_clearance=minimum;end
    R.conditional_geometry_pass=all(separated(:));
    if R.conditional_geometry_pass
        R.status='CONDITIONAL_FULL_TIME_CONE_SEPARATION__NOT_FLIGHT_SAFETY';
        R.reason=['Every given time tube separates in real arithmetic. ' ...
            'Actual EKF/HLC/taut/mass provenance and rigorous rounding missing.'];
    else
        R.status='UNKNOWN_UNSEPARATED_CONE_INTERVAL';
        R.reason='No witness plane for some interval; this is NOT a contact proof.';
    end
catch ME
    R.status='UNKNOWN_CONE_FLOWPIPE_INPUT_OR_NUMERIC_ERROR';
    R.reason=[ME.identifier ' | ' ME.message];
end
end
