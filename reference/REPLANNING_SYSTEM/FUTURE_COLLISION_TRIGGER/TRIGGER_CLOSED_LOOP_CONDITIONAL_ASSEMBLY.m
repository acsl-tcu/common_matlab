function R=TRIGGER_CLOSED_LOOP_CONDITIONAL_ASSEMBLY(C)
% Assemble the ORIGINAL EKF-taut->mass->plant->tension->cone->observed
% geometry chain, with no hidden error/mass/control budgets. This is a
% CONDITIONAL mathematical inclusion result, NOT a physical proof or a
% Flight trigger. No real Flight, sensors or source-world information is
% queried here. Missing, inconsistent, or unproved inputs fail closed.
%
% Required:
%   ekf_now (8 original 3x1 fields), error_lower/upper (signed true-EKF),
%   cable_length_lower_m/upper_m, time_grid_s (actual arbitrary hold grid),
%   true_mass_lower_kg/upper_kg (valid for each WHOLE hold),
%   other_param_lower/upper (21xK, non-mass rows supplied independently),
%   held_input_lower/upper (4xK, includes EVERY actual applied HLC output),
%   observed_prepared_shapes (actually sensor-known STATIC shapes), body.
%
% The caller is responsible for independent PROOF of: true EKF-error
% bounds, applied HLC output image, model/held-input equivalence, physical
% mass bounds and updates, taut tension/hybrid mode, and directed rounding.
% Boolean declarations from this caller are NOT treated as mathematical
% evidence. NEVER enable safe_to_commit from this function.
R=struct('status','UNKNOWN_CONDITIONAL_CLOSED_LOOP_ASSEMBLY', ...
    'reason','','completed_stage','NONE','conditional_chain_pass',false, ...
    'conditional_tension_positive',false,'conditional_geometry_pass',false, ...
    'initial',struct(),'mass',struct(),'plant',struct(),'cone',struct(), ...
    'shape_neutral_fast_witness',struct(), ...
    'source_scope',struct(),'original_hlc_pinned',false, ...
    'original_sim_zoh_pinned',false, ...
    'observer_error_proven',false,'real_HLC_input_image_proven',false, ...
    'applied_sample_hold_proven',false,'physical_mass_evolution_proven',false, ...
    'taut_hybrid_mode_proven',false,'outward_rounding_proven',false, ...
    'full_4s_continuous_safety_proven',false,'safe_to_commit',false, ...
    'observed_ids',zeros(1,0),'possible_risk_ids',zeros(1,0), ...
    'earliest_possible_event',struct(), ...
    'conditional_all_intervals_clear',false);
try
    needed={'ekf_now','error_lower','error_upper', ...
        'cable_length_lower_m','cable_length_upper_m', ...
        'time_grid_s','true_mass_lower_kg','true_mass_upper_kg', ...
        'other_param_lower','other_param_upper', ...
        'held_input_lower','held_input_upper', ...
        'observed_prepared_shapes','body'};
    assert(isstruct(C)&&isscalar(C)&&all(isfield(C,needed)), ...
        'TRIGGER_CLOSED_LOOP_CONDITIONAL_ASSEMBLY:Inputs', ...
        'Every external physical interval and observed geometry is mandatory.');
    t=double(C.time_grid_s(:).');K=numel(t)-1;
    assert(K>=1&&all(isfinite(t))&&all(diff(t)>0), ...
        'TRIGGER_CLOSED_LOOP_CONDITIONAL_ASSEMBLY:Clock', ...
        'An arbitrary monotone real sample-hold time grid is required.');
    assert(isstruct(C.observed_prepared_shapes)&& ...
        ~isempty(C.observed_prepared_shapes) && ...
        all(isfield(C.observed_prepared_shapes,{'id'})), ...
        'TRIGGER_CLOSED_LOOP_CONDITIONAL_ASSEMBLY:Observed', ...
        'There must be observed, provenance-checked static shapes.');
    ids=reshape(double([C.observed_prepared_shapes.id]),1,[]);
    assert(isnumeric([C.observed_prepared_shapes.id]) && ...
        all(isfinite(ids)) && all(ids>0) && ...
        all(ids==fix(ids)) && numel(unique(ids))==numel(ids), ...
        'TRIGGER_CLOSED_LOOP_CONDITIONAL_ASSEMBLY:ObservedIDs', ...
        'Observed IDs must be unique positive finite integers.');
    R.observed_ids=ids;
    % Before true-state/physical-input proof exists, EVERY observed shape
    % is conservatively unresolved from the first interval. This is not a
    % proven collision or permission to replace the HLC/trajectory.
    R.possible_risk_ids=ids;
    R.earliest_possible_event=TRIGGER_FIRST_UNPROVED_INTERVAL( ...
        t,ids,false(numel(ids),K));
    assert(isequal(size(C.held_input_lower),[4 K]) && ...
        isequal(size(C.held_input_upper),[4 K]), ...
        'TRIGGER_CLOSED_LOOP_CONDITIONAL_ASSEMBLY:HeldInputs', ...
        'Actual applied input inclusion must be 4xK, one box per hold.');
    % Audit the EXACT source-scoped Sim HLC/plant wiring before treating
    % supplied held-input boxes as the original actuator variables.
    W=TRIGGER_ORIGINAL_SIM_ZOH_SOURCE_SCOPE();R.source_scope=W;
    R.original_hlc_pinned=W.hlc_source_pinned;
    R.original_sim_zoh_pinned=W.sim_zero_order_hold_source;
    if ~(R.original_hlc_pinned && R.original_sim_zoh_pinned)
        R.status='UNKNOWN_ORIGINAL_HLC_PLANT_SOURCE';R.reason=W.reason;
        return
    end
    fixed_lower=[0;-1;-1;-1];fixed_upper=[20;1;1;1];
    ul=double(C.held_input_lower);uu=double(C.held_input_upper);
    assert(all(isfinite(ul(:)))&&all(isfinite(uu(:))) && ...
        all(ul(:)<=uu(:)) && ...
        all(all(ul>=repmat(fixed_lower,1,K))) && ...
        all(all(uu<=repmat(fixed_upper,1,K))), ...
        'TRIGGER_CLOSED_LOOP_CONDITIONAL_ASSEMBLY:Actuator', ...
        'Each externally enclosed applied input must obey the original finite HLC saturation.');
    % Guard the plant cable length against the SAME physical length used
    % in the taut manifold. Differing sources cannot be mixed silently.
    other_lo=double(C.other_param_lower);
    other_hi=double(C.other_param_upper);
    assert(isequal(size(other_lo),[21 K]) && ...
        isequal(size(other_hi),[21 K]) && ...
        all(other_lo(21,:)>=double(C.cable_length_lower_m)) && ...
        all(other_hi(21,:)<=double(C.cable_length_upper_m)), ...
        'TRIGGER_CLOSED_LOOP_CONDITIONAL_ASSEMBLY:LengthMismatch', ...
        'Plant length interval must be included in taut initial length interval.');
    D=struct('ekf_now',C.ekf_now, ...
        'error_lower',C.error_lower,'error_upper',C.error_upper, ...
        'cable_length_lower_m',C.cable_length_lower_m, ...
        'cable_length_upper_m',C.cable_length_upper_m);
    X=TRIGGER_EKF_TAUT_INITIAL_ENCLOSURE(D);R.initial=X;
    if ~X.conditional_enclosure
        R.status='UNKNOWN_EKF_TAUT_INITIAL';R.reason=X.reason;return
    end
    R.completed_stage='INITIAL';
    M=TRIGGER_MASS_PARAMETER_TUBE(struct('time_grid_s',t, ...
        'true_mass_lower_kg',C.true_mass_lower_kg, ...
        'true_mass_upper_kg',C.true_mass_upper_kg, ...
        'other_param_lower',C.other_param_lower, ...
        'other_param_upper',C.other_param_upper));
    R.mass=M;
    if ~M.conditional_parameter_box
        R.status='UNKNOWN_MASS_PARAMETER';R.reason=M.reason;return
    end
    R.completed_stage='MASS';
    F=TRIGGER_ORIGINAL_PLANT_AUTO_CHAIN(struct('time_grid_s',t, ...
        'initial_lower',X.initial_lower, ...
        'initial_upper',X.initial_upper, ...
        'held_input_lower',C.held_input_lower, ...
        'held_input_upper',C.held_input_upper, ...
        'param_lower',M.parameter_lower, ...
        'param_upper',M.parameter_upper));
    R.plant=F;
    if ~F.conditional_chain_pass
        R.status='UNKNOWN_PICARD_TUBE';R.reason=F.reason;return
    end
    R.completed_stage='PLANT';R.conditional_chain_pass=true;
    R.conditional_tension_positive= ...
        F.conditional_tension_positive_all_intervals;
    if ~R.conditional_tension_positive
        R.status='UNKNOWN_POSITIVE_TENSION';
        R.reason='The supplied reach tube does not certify positive tension.';
        return
    end
    if ~all(F.manifold_compatible_intervals(:))
        R.status='UNKNOWN_TAUT_CONSTRAINT';
        R.reason='Original plant reach tube is not compatible with taut constraints.';
        return
    end
    R.completed_stage='TAUT_TENSION';
    % FIRST try a 3-axis whole-time outer-solid separator. It is a
    % SUFFICIENT certificate for arbitrary STATIC occupied shapes, but only
    % when the external geometry source has itself established each outer
    % sphere as rigorous. No unseen ID is constructed or introduced here.
    % All unresolved/uncertified cases retain the ORIGINAL shape-specific
    % directional-cone path, with precisely the existing failure semantics.
    if all(isfield(C.observed_prepared_shapes,{'id'}))
        batch=TRIGGER_BATCH_SHAPE_NEUTRAL_REACH(struct( ...
            'flowpipe',F,'time_grid_s',t, ...
            'observed_ids',reshape(double([C.observed_prepared_shapes.id]),1,[]), ...
            'observed_prepared_shapes',C.observed_prepared_shapes, ...
            'body',C.body));
        R.shape_neutral_fast_witness=batch;
        if batch.conditional_all_intervals_separated
            R.conditional_geometry_pass=true;
            R.conditional_all_intervals_clear=true;
            R.possible_risk_ids=batch.possible_risk_ids;
            R.earliest_possible_event=batch.earliest_possible_event;
            R.completed_stage='GEOMETRY';
            R.status='CONDITIONAL_END_TO_END_TAUT_REACH__NOT_FLIGHT_SAFETY';
            R.reason=['Original 24-state continuous-time tube, conditional ' ...
                'positive tension and independently certified shape outer bounds ' ...
                'suffice for all-time separation. The EKF/HLC/physical/rounding ' ...
                'premises are NOT currently established for actual Flight.'];
            return
        end
    end
    G=TRIGGER_TAUT_CONE_FLOWPIPE_GATE(struct('flowpipe',F, ...
        'time_grid_s',t,'param_lower',M.parameter_lower, ...
        'param_upper',M.parameter_upper, ...
        'observed_prepared_shapes',C.observed_prepared_shapes, ...
        'body',C.body));
    R.cone=G;
    % Even if the cone engine exits early or reports UNKNOWN, the shared
    % theoretical risk interface retains ALL witnessed-unresolved IDs.
    % A false separator means UNKNOWN, not a demonstrated collision.
    if isfield(G,'separated_intervals') && ...
            islogical(G.separated_intervals) && ...
            isequal(size(G.separated_intervals),[numel(ids) K])
        sep=G.separated_intervals;
    else
        sep=false(numel(ids),K);
    end
    R.possible_risk_ids=ids(any(~sep,2).');
    R.earliest_possible_event=TRIGGER_FIRST_UNPROVED_INTERVAL(t,ids,sep);
    % Unknown/incomplete matrices can never be promoted to a clearance.
    R.conditional_geometry_pass=isequal(G.conditional_geometry_pass,true) && ...
        all(sep(:));
    R.conditional_all_intervals_clear=R.conditional_geometry_pass;
    if ~G.conditional_geometry_pass
        R.status='UNKNOWN_CONTINUOUS_GEOMETRY';R.reason=G.reason;return
    end
    R.completed_stage='GEOMETRY';
    R.status='CONDITIONAL_END_TO_END_TAUT_REACH__NOT_FLIGHT_SAFETY';
    R.reason=['A continuous-time chain was computed for GIVEN enclosures. ' ...
        'No original HLC interval-image, actual EKF-error theorem, future ' ...
        'physical mass/hybrid guarantee or independently verified rounding ' ...
        'has been supplied. This cannot authorize a Flight trajectory.'];
catch ME
    R.status='UNKNOWN_CLOSED_LOOP_ASSEMBLY_EXCEPTION';
    R.reason=[ME.identifier ' | ' ME.message];
end
end
