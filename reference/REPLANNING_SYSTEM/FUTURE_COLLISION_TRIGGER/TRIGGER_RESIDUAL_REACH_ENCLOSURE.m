classdef TRIGGER_RESIDUAL_REACH_ENCLOSURE
    % CONDITIONAL nonlinear ODE error-tube propagation; no guessed bounds.
    % Consider the actual (possibly time-dependent) closed-loop ODE
    %   x' = f(t,x),
    % a differentiable numerical nominal trajectory xbar(t), residual
    %   ||xbar' - f(t,xbar)||_W <= rho_k,
    % and one-sided Lipschitz inequality, valid on the WHOLE enclosure,
    %   <x-y,f(t,x)-f(t,y)>_W <= mu_k ||x-y||_W^2.
    % Then e'(t)<=mu_k*e(t)+rho_k, so e(t) is bounded by the exact scalar
    % comparison solution below. This requires VERIFIED bounds for rho, mu,
    % initial state error and continuous nominal position excursions. A
    % sampled RK result or a pointwise Jacobian is NOT such verification.
    % Projection gains gammaU,gammaL ensure ||p-pbar||_2<=gamma*||x-xbar||_W.
    % With the nominal position excursions dU,dL relative to LEFT samples,
    % a whole-time interval positional enclosure is dU+gammaU*max(e0,e1)
    % and dL+gammaL*max(e0,e1), respectively.
    % Status is always CONDITIONAL; the caller MUST independently check
    % proof provenance, phase switches, taut-cable and rounding, and the
    % class NEVER certifies actual-flight safety.
    methods (Static)
        function T=evaluate(grid,initial_error_norm,rho,mu,nominal_uav_excursion_m, ...
                nominal_payload_excursion_m,gamma_u_m_per_norm,gamma_l_m_per_norm)
            assert(isnumeric(grid)&&isrow(grid)&&numel(grid)>=2 && ...
                all(isfinite(grid))&&all(diff(grid)>0), ...
                'TRIGGER_RESIDUAL_REACH_ENCLOSURE:Grid','Strictly increasing grid required.');
            n=numel(grid)-1;
            assert(isnumeric(initial_error_norm)&&isscalar(initial_error_norm)&& ...
                isfinite(initial_error_norm)&&initial_error_norm>=0 && ...
                isscalar(gamma_u_m_per_norm)&&isfinite(gamma_u_m_per_norm)&& ...
                gamma_u_m_per_norm>=0&&isscalar(gamma_l_m_per_norm)&& ...
                isfinite(gamma_l_m_per_norm)&&gamma_l_m_per_norm>=0, ...
                'TRIGGER_RESIDUAL_REACH_ENCLOSURE:Initial', ...
                'Only externally verified initial error and projection gains are allowed.');
            input={rho,mu,nominal_uav_excursion_m,nominal_payload_excursion_m};
            for j=1:numel(input)
                v=input{j};
                assert(isnumeric(v)&&isrow(v)&&numel(v)==n && ...
                    isreal(v)&&all(isfinite(v)), ...
                    'TRIGGER_RESIDUAL_REACH_ENCLOSURE:Bounds', ...
                    'A certified finite per-interval model/nominal bound is required.');
            end
            assert(all(rho>=0)&&all(nominal_uav_excursion_m>=0)&& ...
                all(nominal_payload_excursion_m>=0), ...
                'TRIGGER_RESIDUAL_REACH_ENCLOSURE:Bounds', ...
                'Residual and excursion upper bounds must be nonnegative.');
            E=zeros(1,n+1); E(1)=double(initial_error_norm);
            sup=zeros(1,n); dU=zeros(1,n);dL=zeros(1,n);
            for k=1:n
                h=double(grid(k+1)-grid(k)); z=double(mu(k))*h;
                % Stable (exp(z)-1)/z near z=0; the z=0 limit is 1.
                if z==0
                    phi=1;
                else
                    phi=expm1(z)/z;
                end
                E(k+1)=exp(z)*E(k)+double(rho(k))*h*phi;
                assert(isfinite(E(k+1))&&E(k+1)>=0, ...
                    'TRIGGER_RESIDUAL_REACH_ENCLOSURE:Overflow', ...
                    'Scalar comparison bound overflowed; no clearance can be inferred.');
                % The comparison solution with constant mu,rho is monotone
                % within the interval for nonnegative e,rho. Its maximum
                % is attained at one of the two endpoints.
                sup(k)=max(E(k),E(k+1));
                dU(k)=double(nominal_uav_excursion_m(k))+ ...
                    double(gamma_u_m_per_norm)*sup(k);
                dL(k)=double(nominal_payload_excursion_m(k))+ ...
                    double(gamma_l_m_per_norm)*sup(k);
            end
            assert(all(isfinite(dU))&&all(isfinite(dL)), ...
                'TRIGGER_RESIDUAL_REACH_ENCLOSURE:Overflow', ...
                'Positional enclosure overflow; fail closed.');
            T=struct('status','CONDITIONAL_COMPARISON_TUBE_NOT_FLIGHT_CERTIFICATE', ...
                'state_error_at_knots',E,'state_error_supremum',sup, ...
                'interval_uav_excursion_m',dU, ...
                'interval_payload_excursion_m',dL, ...
                'requires_verified_initial_set',true, ...
                'requires_certified_closed_loop_residual',true, ...
                'requires_certified_one_sided_lipschitz_bound',true, ...
                'requires_certified_nominal_excursion',true, ...
                'requires_verified_mass_tension_phase_and_tracking',true, ...
                'requires_directed_rounding',true, ...
                'continuous_closed_loop_safe_certified',false);
        end
    end
end
