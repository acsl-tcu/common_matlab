function R=CHECK_TRIGGER_TAUT_EKF_INITIAL_SUPPORT()
% Synthetic fixture: no actual EKF error theorem or safety authorization.
R=struct('status','NOT_COMPLETED_TAUT_EKF_INITIAL_SUPPORT', ...
    'reason','','tested_normals',0,'expected_exact_body',false, ...
    'wide_box_rejected',false,'safe_to_commit',false);
try
    L=2;z=zeros(3,1);
    ekf=struct('p',z,'q',z,'v',z,'w',z, ...
        'pL',[0;0;-L],'vL',z,'pT',[0;0;-1],'wL',z);
    E=TRIGGER_EKF_TAUT_INITIAL_ENCLOSURE(struct( ...
        'ekf_now',ekf,'error_lower',zeros(24,1), ...
        'error_upper',zeros(24,1), ...
        'cable_length_lower_m',L,'cable_length_upper_m',L));
    assert(E.conditional_enclosure, ...
        'CHECK_TRIGGER_TAUT_EKF_INITIAL_SUPPORT:Initial',E.reason);
    N=[eye(3),-eye(3)];
    D=struct('initial',E,'cable_length_lower_m',L, ...
        'cable_length_upper_m',L,'r_uav_m',0.1, ...
        'r_cable_m',0.05,'r_payload_m',0.12,'normals',N);
    F=TRIGGER_TAUT_EKF_INITIAL_SUPPORT(D);
    assert(F.conditional_enclosure && ~F.safe_to_commit && ...
        all(isfinite(F.union_support_upper)) && ...
        numel(F.union_support_upper)==size(N,2), ...
        'CHECK_TRIGGER_TAUT_EKF_INITIAL_SUPPORT:Support',F.reason);
    % Exact full-body support for point initial state in real arithmetic.
    wanted=zeros(1,size(N,2));
    for j=1:size(N,2)
        n=N(:,j);a=dot(n,[0;0;-1]);
        wanted(j)=max([0.1,0.05+max(0,L*a),0.12+L*a]);
    end
    assert(all(F.union_support_upper>=wanted-1e-10) && ...
        all(F.union_support_upper<wanted+1e-8), ...
        'CHECK_TRIGGER_TAUT_EKF_INITIAL_SUPPORT:Enclosure', ...
        'Initial full-body directional support should match the exact taut configuration.');
    R.tested_normals=size(N,2);R.expected_exact_body=true;
    E2=E;E2.conditional_enclosure=false;D.initial=E2;
    bad=TRIGGER_TAUT_EKF_INITIAL_SUPPORT(D);
    R.wide_box_rejected=~bad.conditional_enclosure;
    assert(R.wide_box_rejected && ~bad.safe_to_commit);
    R.status='PASS_CONDITIONAL_EKF_TO_FULL_TAUT_BODY__NO_SAFETY_PROOF';
catch ME
    R.reason=[ME.identifier ' | ' ME.message];
end
save('TRIGGER_TAUT_EKF_INITIAL_SUPPORT_RESULT.mat','R');
fid=fopen('TRIGGER_TAUT_EKF_INITIAL_SUPPORT_RESULT.txt','w');
if fid>=0
    fprintf(fid,'status=%s\nnormals=%d\nexact_body=%d\nmissing_input_rejected=%d\nreason=%s\n', ...
        R.status,R.tested_normals,R.expected_exact_body,R.wide_box_rejected,R.reason);
    fclose(fid);
end
end
