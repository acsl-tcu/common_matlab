function R=TRIGGER_TAUT_TRUE_SHAPE_FLOWPIPE_GATE(C)
% CONDITIONAL full-time true-occupied-shape fallback to the cone plane gate.
% This is NOT a new independent true-state predictor or a Flight authority.
% The ORIGINAL plant flowpipe must enclose the true Q and load centers at
% EVERY instant (not just timestamps), and the cable must be straight and
% taut throughout the whole physical interval. Each 3D interval box is
% bounded by its center plus its exact corner radius, WITHOUT replacing
% the directional cable by a large surrounding sphere.
%
% The nonconvex-capable 1-Lipschitz true-shape oracle is evaluated for the
% complete finite material cable, not only its endpoints. Every obstacle
% is sourced from the already OBSERVED/retained list; no obstacle is read
% from source-world geometry. Failure or unavailable distance => UNKNOWN.
%
% Critical: the current OBSTACLE_GEOMETRY_QUERY.distance() is NOT an
% independently verified directed-rounding lower-bound oracle; actual
% EKF errors, future applied HLC inputs, variable mass, taut hybrid mode,
% and worst-case runtime still need rigorous physical witnesses.
R=struct('status','UNKNOWN_TRUE_SHAPE_FLOWPIPE', ...
    'conditional_geometry_pass',false,'safe_to_commit',false, ...
    'continuous_closed_loop_safe_certified',false, ...
    'interval_count',0,'observed_count',0,'distance_queries',0, ...
    'certified_outer_box_exclusions',0, ...
    'separated_intervals',false(0,0), ...
    'possible_risk_ids',zeros(1,0), ...
    'earliest_possible_event',struct(), ...
    'unproved_interval_count',0,'exhausted_query_intervals',0, ...
    'reason','');
try
    assert(isstruct(C)&&isscalar(C)&& ...
        all(isfield(C,{'flowpipe','time_grid_s', ...
            'observed_prepared_shapes','body'})), ...
        'TRIGGER_TRUE_SHAPE_GATE:Fields','Explicit original tubes required.');
    F=C.flowpipe;t=double(C.time_grid_s(:).');K=numel(t)-1;
    assert(K>=1 && all(isfinite(t)) && all(diff(t)>0), ...
        'TRIGGER_TRUE_SHAPE_GATE:Time','Real monotone time grid required.');
    assert(isstruct(F)&&isscalar(F) && ...
        isfield(F,'conditional_chain_pass') && ...
        isequal(F.conditional_chain_pass,true) && ...
        isfield(F,'completed_intervals') && ...
        isequal(double(F.completed_intervals),double(K)) && ...
        isfield(F,'conditional_tension_positive_all_intervals') && ...
        isequal(F.conditional_tension_positive_all_intervals,true) && ...
        isfield(F,'manifold_compatible_intervals') && ...
        isequal(size(F.manifold_compatible_intervals),[1 K]) && ...
        all(F.manifold_compatible_intervals), ...
        'TRIGGER_TRUE_SHAPE_GATE:PhysicalTube', ...
        'Each original hold must have a taut-compatible positive-tension Picard tube.');
    lo=double(F.tube_lower);hi=double(F.tube_upper);
    assert(isequal(size(lo),[24 K])&&isequal(size(hi),[24 K]) && ...
        all(isfinite(lo(:)))&&all(isfinite(hi(:))) && ...
        all(lo(:)<=hi(:)), ...
        'TRIGGER_TRUE_SHAPE_GATE:Tube', ...
        'All-time original 24-state boxes are required.');
    b=C.body;
    assert(isstruct(b)&&isscalar(b) && ...
        all(isfield(b,{'r_uav_m','r_payload_m','r_cable_m'})), ...
        'TRIGGER_TRUE_SHAPE_GATE:Body','Actual material radii required.');
    r=[double(b.r_uav_m),double(b.r_payload_m),double(b.r_cable_m)];
    assert(isreal(r)&&all(isfinite(r))&&all(r>=0), ...
        'TRIGGER_TRUE_SHAPE_GATE:Radii','Finite nonnegative physical radii needed.');
    S=C.observed_prepared_shapes;
    assert(isstruct(S)&&~isempty(S) && ...
        all(isfield(S,{'id','center0','is_stationary'})) && ...
        all([S.is_stationary]), ...
        'TRIGGER_TRUE_SHAPE_GATE:Observed', ...
        'A nonempty, observed-only stationary geometry snapshot is required.');
    ids=reshape(double([S.id]),1,[]);
    assert(all(isfinite(ids))&&all(ids>0)&&all(ids==fix(ids)) && ...
        numel(unique(ids))==numel(ids), ...
        'TRIGGER_TRUE_SHAPE_GATE:IDs','IDs must be unique positive integers.');
    if isfield(C,'observed_ids')
        assert(isequal(reshape(double(C.observed_ids),1,[]),ids), ...
            'TRIGGER_TRUE_SHAPE_GATE:Provenance', ...
            'The explicitly observed IDs must be identical to prepared shapes.');
    end
    M=numel(S);separated=false(M,K);
    R.interval_count=K;R.observed_count=M;
    % Each interval's full-time Q,Load box is enclosed by its center and
    % Euclidean half-diagonal. Distances are not sampled at a guessed path.
    for k=1:K
        qlo=lo(1:3,k);qhi=hi(1:3,k);
        llo=lo(13:15,k);lhi=hi(13:15,k);
        q=qlo+0.5*(qhi-qlo);l=llo+0.5*(lhi-llo);
        eq=norm(max(abs(q-qlo),abs(qhi-q)));
        el=norm(max(abs(l-llo),abs(lhi-l)));
        % Conventional double arithmetic guard, NOT a formal real-number
        % outward-rounding certificate; never authorize Flight from it.
        magnitude=max([1;abs(qlo);abs(qhi);abs(llo);abs(lhi);eq;el]);
        pad=4096*eps(magnitude);
        eq=eq+pad;el=el+pad;
        if ~all(isfinite([q;l;eq;el]))
            R.status='UNKNOWN_NONFINITE_TRUE_ENDPOINT_BOX';return
        end
        for j=1:M
            % Exact-grid-time-free sufficient separation. This path is
            % enabled ONLY for an OBSERVED shape whose preparation has
            % independently attested a rigorous outer enclosing ball.
            % A normal sensor bounding_radius_m alone is NOT such a proof.
            % No trust flag -> unchanged original true-shape fallback.
            if isfield(S,'rigorous_outer_ball_certified') && ...
                    isequal(S(j).rigorous_outer_ball_certified,true)
                W=TRIGGER_SHAPE_NEUTRAL_INTERVAL_BOX_WITNESS( ...
                    qlo,qhi,llo,lhi,S(j).center0, ...
                    S(j).bounding_radius_m,r);
                if W.all_parts_separated
                    separated(j,k)=true;
                    R.certified_outer_box_exclusions= ...
                        R.certified_outer_box_exclusions+1;
                    continue
                end
            end
            D=TRIGGER_TAUT_DISTANCE_INTERVAL_GATE(q,l,S(j), ...
                r(1),r(2),r(3),eq,el,t(k));
            separated(j,k)=D.conditionally_separated;
            R.distance_queries=R.distance_queries+D.distance_queries;
            R.exhausted_query_intervals=R.exhausted_query_intervals+ ...
                double(D.exhausted_budget);
        end
    end
    R.separated_intervals=separated;
    R.possible_risk_ids=ids(any(~separated,2).');
    R.unproved_interval_count=nnz(any(~separated,1));
    R.earliest_possible_event=TRIGGER_FIRST_UNPROVED_INTERVAL( ...
        t,ids,separated);
    R.conditional_geometry_pass=all(separated(:));
    if R.conditional_geometry_pass
        R.status='CONDITIONAL_TRUE_SHAPE_ALL_TIME_CLEAR__NOT_FLIGHT_SAFETY';
        R.reason=['Whole-time taut-body distance witnesses exist for GIVEN ' ...
            'original plant tubes. Actual closed-loop provenance, shape ' ...
            'distance lower rounding and hybrid physical proof remain separate.'];
    else
        R.status='UNKNOWN_TRUE_SHAPE_UNSEPARATED_TIME_INTERVAL';
        R.reason=['Some observed shape/hold interval lacks an all-time ' ...
            'distance witness. This is not a collision or clearance proof.'];
    end
catch ME
    R.status='UNKNOWN_TRUE_SHAPE_CONTRACT_OR_DISTANCE_ERROR';
    R.reason=[ME.identifier ' | ' ME.message];
end
end
