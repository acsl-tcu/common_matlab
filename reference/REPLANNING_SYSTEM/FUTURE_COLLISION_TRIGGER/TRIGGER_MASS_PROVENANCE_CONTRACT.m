function R=TRIGGER_MASS_PROVENANCE_CONTRACT(C)
% Explicit separate mass authorities for a source-pinned suspended-load
% closed-loop reachability argument. Do NOT substitute EKF mL for TRUE
% mass, controller loadmass, or the original numerical plant parameter.
%
% Inputs: actual monotone sample grid (no Flight-start assumption), an
% EXTERNALLY JUSTIFIED true mass interval valid throughout EACH hold,
% latest EKF/HLC mass snapshots and current numerical plant snapshot.
% This function checks necessary consistency ONLY. The interval itself
% has not been verified against physical truth by this function.
%
% Crucial: a wrong EKF/HLC estimate MAY lie outside the true mass range;
% that is not a contradiction and must remain visible to a rigorous HLC
% interval analysis. Only original numerical plant/true-model alignment
% of the CURRENT hold is checked here. Future plant refresh is UNKNOWN.
R=struct('status','UNKNOWN_MASS_PROVENANCE','reason','', ...
    'conditional_current_snapshot_consistent',false, ...
    'true_mass_interval_supplied',false, ...
    'current_plant_mass_in_declared_true_interval',false, ...
    'estimator_mass_in_current_true_interval',false, ...
    'hlc_mass_in_current_true_interval',false, ...
    'estimator_matches_plant_mass',false, ...
    'time_grid_s',zeros(1,0), ...
    'true_mass_lower_kg',zeros(1,0), ...
    'true_mass_upper_kg',zeros(1,0), ...
    'estimator_mass_kg',NaN,'hlc_mass_kg',NaN, ...
    'sim_plant_mass_kg',NaN, ...
    'true_mass_evolution_proven',false, ...
    'estimator_error_proven',false, ...
    'future_plant_parameter_refresh_proven',false, ...
    'hlc_interval_image_proven',false, ...
    'safe_to_commit',false);
try
    required={'time_grid_s','true_mass_lower_kg','true_mass_upper_kg', ...
        'estimator_mass_kg','hlc_parameter_mass_kg', ...
        'sim_plant_parameter_mass_kg'};
    assert(isstruct(C)&&isscalar(C)&&all(isfield(C,required)), ...
        'TRIGGER_MASS_PROVENANCE_CONTRACT:Inputs', ...
        'Provide three distinct mass authorities and per-hold true-mass ranges.');
    t=double(C.time_grid_s(:).');
    assert(numel(t)>=2&&all(isfinite(t))&&all(diff(t)>0), ...
        'TRIGGER_MASS_PROVENANCE_CONTRACT:Clock', ...
        'The real hold times must be monotone, with no assumed Flight epoch.');
    n=numel(t)-1;
    lo=double(C.true_mass_lower_kg(:).');
    hi=double(C.true_mass_upper_kg(:).');
    assert(numel(lo)==n&&numel(hi)==n&&all(isfinite([lo hi]))&& ...
        all(lo>0)&&all(hi>=lo), ...
        'TRIGGER_MASS_PROVENANCE_CONTRACT:TrueBounds', ...
        'All-time true-mass bounds must be positive on every hold.');
    mE=double(C.estimator_mass_kg);
    mH=double(C.hlc_parameter_mass_kg);
    mP=double(C.sim_plant_parameter_mass_kg);
    assert(all(isfinite([mE mH mP]))&& ...
        all([mE mH mP]>0)&&isscalar(mE)&&isscalar(mH)&&isscalar(mP), ...
        'TRIGGER_MASS_PROVENANCE_CONTRACT:SourceMass', ...
        'All three live mass snapshots must be positive finite scalars.');
    R.time_grid_s=t;
    R.true_mass_lower_kg=lo;R.true_mass_upper_kg=hi;
    R.estimator_mass_kg=mE;R.hlc_mass_kg=mH;
    R.sim_plant_mass_kg=mP;
    R.true_mass_interval_supplied=true;
    R.estimator_mass_in_current_true_interval=lo(1)<=mE&&mE<=hi(1);
    R.hlc_mass_in_current_true_interval=lo(1)<=mH&&mH<=hi(1);
    R.estimator_matches_plant_mass=isequal(mE,mP);
    R.current_plant_mass_in_declared_true_interval= ...
        lo(1)<=mP && mP<=hi(1);
    if ~R.current_plant_mass_in_declared_true_interval
        R.status='UNKNOWN_CURRENT_SIM_PLANT_VS_DECLARED_TRUE_MASS';
        R.reason=['Current original plant mass snapshot is outside ' ...
          'the declared true physical mass interval. Do not claim that ' ...
          'the original numerical plant is the current physical plant.'];
        return
    end
    R.conditional_current_snapshot_consistent=true;
    R.status='CONDITIONAL_DISTINCT_MASS_AUTHORITIES__NO_FUTURE_MASS_PROOF';
    R.reason=['The plant snapshot is compatible with the first declared ' ...
        'mass hold. EKF and HLC estimates are allowed to differ from ' ...
        'physical mass; their uncertainty must be propagated through ' ...
        'the sampled HLC. Independently certify the true all-time mass ' ...
        'intervals and plant-parameter refresh at every future hold.'];
catch ME
    R.reason=[ME.identifier ' | ' ME.message];
end
end
