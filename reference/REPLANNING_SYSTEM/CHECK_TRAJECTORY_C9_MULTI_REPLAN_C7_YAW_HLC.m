function R=CHECK_TRAJECTORY_C9_MULTI_REPLAN_C7_YAW_HLC()
% CHECK_TRAJECTORY_C9_MULTI_REPLAN_C7_YAW_HLC
% Deterministic, general 3D multi-obstacle geometries (no pattern-specific
% production code); actual simultaneous joint C9 generator in every case.
% A certified candidate MUST pass the independent all-time C9 proof.
% UNKNOWN is recorded, NEVER counted as safety. C7/yaw C6 checks include
% off-clock replanning continuity and all-time nonzero UAV horizontal speed.
% HLC tick comparison uses a CLEARLY LABELED synthetic log test here; real
% HLC/plant tracking & torque remain explicitly UNVERIFIED in this CHECK.
root=fileparts(mfilename('fullpath'));
module=fullfile(root,'reference','REPLANNING_SYSTEM');
addpath(fullfile(module,'TRAJECTORY_GENERATION'), ...
    fullfile(module,'OBSTACLE_INFORMATION'),'-begin');
R=struct('status','FAIL_NOT_RUN','error_identifier','','error_message','', ...
    'case_count',0,'case_labels',{{}},'case_obstacle_counts',[], ...
    'case_status',{{}},'case_certified',[],'case_initial_proved',[], ...
    'case_joints_all_ids',[],'case_no_unsafe_commit',[], ...
    'case_geometry_tension_thrust_independent',[], ...
    'case_elapsed_ms',[],'case_proof_ms',[], ...
    'case_plane_ms',[],'case_qp_ms',[], ...
    'case_proof_calls',[],'case_qp_pivots',[], ...
    'case_robust_tube',[],'case_payload_mass_kg',[], ...
    'case_heading_certified',[],'case_heading_status',{{}}, ...
    'case_unresolved_obstacle_ids',{{}}, ...
    'case_unresolved_time_interval_s',zeros(2,0), ...
    'case_final_proof_nodes',[],'case_final_support_calls',[], ...
    'number_full_time_certified',0,'number_unknown',0, ...
    'baseline_single_certified',false, ...
    'baseline_C7_yaw_C6_regular',false, ...
    'zero_planar_speed_rejected',false, ...
    'offclock_replan_attempted',false, ...
    'offclock_replan_has_no_catchup',false, ...
    'offclock_replan_initial_join_C7_C6',false, ...
    'offclock_replan_candidate_certified',false, ...
    'offclock_replan_candidate_C7_C6',false, ...
    'offclock_replan_status','', ...
    'replan_new_obstacle_retained_with_old',false, ...
    'replan_modified_initial_jet_rejected',false, ...
    'replan_search_elapsed_ms',NaN, ...
    'fixture_tick_log_correct_pass',false, ...
    'fixture_tick_log_corruption_rejected',false, ...
    'fixture_tick_log_cannot_certify_HLC',false, ...
    'real_HLC_tracking_certified',false, ...
    'real_torque_certified',false, ...
    'overall_median_ms',NaN,'overall_p95_ms',NaN, ...
    'overall_max_ms',NaN,'results_file','TRAJECTORY_C9_MULTI_REPLAN_C7_YAW_HLC_RESULT');
try
    A=struct('cable_length_m',2,'payload_mass_kg',0.2, ...
        'uav_mass_kg',1.0,'gravity_world_mps2',[0;0;-9.80665], ...
        'thrust_limits_N',[0 30],'minimum_tension_N',0, ...
        'acceleration_guard_mps2',0);
    radii=struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1);
    geo=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'numerical_guard_m',0,'robust_tube_enabled',false, ...
        'trajectory_phase','f');
    force=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'force_guard_N',0);
    opt=struct('probe_count',13,'max_outer_iterations',4, ...
        'max_projection_sweeps',100, ...
        'projection_tolerance_m',1e-8,'min_separation_m',1e-5);
    J0=zeros(3,10);J0(:,1)=[-2;0;3];J0(1,2)=0.4;
    J1=zeros(3,10);J1(:,1)=[2;0;3];J1(1,2)=0.4;
    nom=TRAJECTORY_C9_FLAT_BERNSTEIN.build(0,10,J0,J1, ...
        repmat([0;0;3],1,4));
    req=struct('t0_s',0,'duration_s',10,'flight_interval_s',[0 30], ...
        'start_jets',J0,'end_jets',J1, ...
        'nominal_free',nom.control_points_m(:,11:14), ...
        'observed',OBSTACLE_INFORMATION.define(21,'sphere',[0 0.1 3],0.2), ...
        'radii',radii,'authority',A,'geometry_options',geo, ...
        'force_options',force,'search_options',opt);
    joinopt=struct('max_subdivision_depth',8, ...
        'max_node_count',511,'horizontal_velocity_guard_mps',0, ...
        'w_guard_mps2',0,'payload_jet_tolerance',1e-7*ones(3,10), ...
        'uav_jet_tolerance',1e-7*ones(3,8), ...
        'yaw_jet_tolerance',1e-7*ones(1,7));
    baseline=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(req);
    R.baseline_single_certified=baseline.candidate_available&& ...
        baseline.final_certificate.certified&&~baseline.safe_to_commit;
    assert(R.baseline_single_certified, 'CHECK_C9_MULTI:Baseline', ...
        'Previously solved collision-start sphere case must remain certified.');
    generator=TRAJECTORY_GENERATOR(struct( ...
        'ROBUST_TUBE_ENABLED',false,'FAILURE_BACKUP_ENABLED',true));
    one=generator.audit_c9_C7_yaw_C6( ...
        baseline.candidate_piece,A,joinopt);
    R.baseline_C7_yaw_C6_regular=one.certified&& ...
        one.continuous_horizontal_heading_proven&& ...
        one.derived_uav_C7_regular&&one.derived_yaw_C6_regular;
    % Pure hover has undefined tangent yaw, regardless of collision safety.
    hover=zeros(3,10);hover(3,1)=3;
    still=TRAJECTORY_C9_FLAT_BERNSTEIN.build(0,10,hover,hover, ...
        repmat([0;0;3],1,4));
    sr=TRAJECTORY_C9_UAV_C7_YAW_C6_AUDIT(still,A,joinopt);
    R.zero_planar_speed_rejected=~sr.certified&& ...
        ~sr.continuous_horizontal_heading_proven;
    assert(R.zero_planar_speed_rejected, 'CHECK_C9_MULTI:Singularity', ...
        'The zero-speed heading singularity must never be certified.');

    % SO(3) orientations include coupled roll/pitch/yaw, NOT yaw only.
    poses={rotation3(0.34,-0.26,0.21), ...
        rotation3(-0.61,0.48,-0.37), ...
        rotation3(1.03,0.37,0.56)};
    s1=OBSTACLE_INFORMATION.define(21,'sphere',[0 0.1 3],0.2);
    e1=OBSTACLE_INFORMATION.define(24,'ellipsoid', ...
        [0.55 -0.15 3],[0.32 0.18 0.47],'rotation',poses{1});
    e2=OBSTACLE_INFORMATION.define(32,'ellipsoid', ...
        [-0.6 0.31 3.1],[0.38 0.13 0.24],'rotation',poses{2});
    b1=OBSTACLE_INFORMATION.define(33,'box', ...
        [0.9 0.34 3.15],[0.32 0.25 0.45],'rotation',poses{3});
    s2=OBSTACLE_INFORMATION.define(34,'sphere',[-1 -0.26 2.95],0.15);
    s3=OBSTACLE_INFORMATION.define(35,'sphere',[1.3 0.21 3.04],0.17);
    e3=OBSTACLE_INFORMATION.define(36,'ellipsoid', ...
        [-1.25 0.42 3.3],[0.19 0.31 0.22],'rotation',poses{1});
    e4=OBSTACLE_INFORMATION.define(37,'ellipsoid', ...
        [1.62 -0.3 2.9],[0.21 0.15 0.32],'rotation',poses{2});
    patterns={ ...
        struct('label','sphere_ellipsoid_roll_pitch_yaw','obs',[s1 e1]), ...
        struct('label','two_ellipsoids_different_SO3','obs',[e1 e2]), ...
        struct('label','three_shapes_reordered','obs',[b1 s1 e2]), ...
        struct('label','four_shapes_symmetric_opposition','obs',[s1 s2 e1 e2]), ...
        struct('label','six_mixed_positions','obs',[s1 e1 e2 b1 s2 s3]), ...
        struct('label','eight_mixed_positions','obs',[s1 e1 e2 b1 s2 s3 e3 e4]), ...
        struct('label','rotated_translated_pair','obs',[e3 e4]), ...
        struct('label','reverse_of_eight','obs',[e4 e3 s3 s2 b1 e2 e1 s1]) ...
        };
    count=numel(patterns);R.case_count=count;
    R.case_labels=cell(1,count);R.case_status=cell(1,count);
    R.case_heading_status=cell(1,count);
    scalarfields={'case_obstacle_counts','case_certified','case_initial_proved', ...
        'case_joints_all_ids','case_no_unsafe_commit', ...
        'case_geometry_tension_thrust_independent','case_elapsed_ms', ...
        'case_proof_ms','case_plane_ms','case_qp_ms','case_proof_calls', ...
        'case_qp_pivots','case_robust_tube','case_payload_mass_kg', ...
        'case_final_proof_nodes','case_final_support_calls', ...
        'case_heading_certified'};
    for n=1:numel(scalarfields)
        R.(scalarfields{n})=zeros(1,count);
    end
    R.case_unresolved_obstacle_ids=cell(1,count);
    R.case_unresolved_time_interval_s=NaN(2,count);
    for k=1:count
        v=req;v.observed=patterns{k}.obs;
        % Different LIVE mass and robust mode; no instance-specific code.
        v.authority.payload_mass_kg=A.payload_mass_kg*(1+0.1*(k-1));
        if mod(k,2)==0
            v.geometry_options.robust_tube_enabled=true;
            v.geometry_options.uncertainty_bounds_m= ...
                struct('uav_m',0.03,'cable_m',0.02,'payload_m',0.04);
        end
        out=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(v);
        R.case_labels{k}=patterns{k}.label;
        R.case_obstacle_counts(k)=numel(v.observed);
        R.case_status{k}=out.status;
        R.case_certified(k)=out.candidate_available;
        R.case_initial_proved(k)=out.initial_certificate.certified;
        R.case_no_unsafe_commit(k)=~out.safe_to_commit;
        R.case_robust_tube(k)=v.geometry_options.robust_tube_enabled;
        R.case_payload_mass_kg(k)=v.authority.payload_mass_kg;
        R.case_elapsed_ms(k)=out.elapsed_ms;
        R.case_proof_ms(k)=out.independent_proof_time_total_ms;
        R.case_plane_ms(k)=out.plane_construction_time_total_ms;
        R.case_qp_ms(k)=out.joint_qp_time_total_ms;
        R.case_proof_calls(k)=out.independent_proof_calls;
        R.case_qp_pivots(k)=out.projection_sweeps;
        R.case_final_proof_nodes(k)=out.final_certificate.checked_node_count;
        R.case_final_support_calls(k)=out.final_certificate.shape_support_calls;
        R.case_unresolved_obstacle_ids{k}=out.final_certificate.unresolved_obstacle_ids;
        R.case_unresolved_time_interval_s(:,k)= ...
            reshape(out.final_certificate.unresolved_time_interval_s,2,1);
        R.case_joints_all_ids(k)=isequal( ...
            out.considered_obstacle_ids,[v.observed.id]);
        if out.candidate_available
            proof=TRAJECTORY_C9_JOINT_FAST_CERTIFICATE( ...
                out.candidate_piece,v.observed,v.radii,v.authority, ...
                v.geometry_options,v.force_options);
            R.case_geometry_tension_thrust_independent(k)= ...
                proof.certified&&proof.certified_continuous_geometry&& ...
                proof.certified_continuous_tension&& ...
                proof.certified_continuous_thrust;
            heading=TRAJECTORY_C9_UAV_C7_YAW_C6_AUDIT( ...
                out.candidate_piece,v.authority,joinopt);
            R.case_heading_certified(k)=heading.certified;
            R.case_heading_status{k}=heading.status;
        else
            R.case_geometry_tension_thrust_independent(k)=true;
            R.case_heading_status{k}='NOT_EVALUATED_NO_PROVED_CANDIDATE';
        end
        assert(R.case_no_unsafe_commit(k)&&R.case_joints_all_ids(k)&& ...
            R.case_geometry_tension_thrust_independent(k), ...
            'CHECK_C9_MULTI:SafetyInvariant', ...
            'Every accepted scenario must be independently proven, all IDs retained.');
    end
    R.number_full_time_certified=sum(R.case_certified);
    R.number_unknown=count-R.number_full_time_certified;
    sorted=sort(R.case_elapsed_ms);
    R.overall_median_ms=median(sorted);
    R.overall_p95_ms=sorted(ceil(0.95*count));
    R.overall_max_ms=max(sorted);

    % Real replan at an off-clock event on the VALID first avoidance.
    % Keep all old observed obstacles and add a newly sensed obstacle.
    prev=baseline.candidate_piece;
    replan_tau=0.43;
    now=prev.t0_s+prev.duration_s*replan_tau;
    [~,old_tail]=split_bernstein(prev.control_points_m,replan_tau);
    newL=TRAJECTORY_C9_FLAT_BERNSTEIN.evaluate(prev,now);
    old_remaining=prev.duration_s*(1-replan_tau);
    % Deliberately choose a different duration: no original-time catch-up.
    requested_duration=old_remaining*1.27;
    candidate=TRAJECTORY_C9_FLAT_BERNSTEIN.build( ...
        now,requested_duration,newL,prev.end_jets,old_tail(:,11:14));
    jo=joinopt;jo.previous_piece=prev;
    rejoin=TRAJECTORY_C9_UAV_C7_YAW_C6_AUDIT(candidate,A,jo);
    R.offclock_replan_attempted=true;
    R.offclock_replan_has_no_catchup= ...
        abs(requested_duration-old_remaining)>0&& ...
        candidate.t0_s==now;
    R.offclock_replan_initial_join_C7_C6= ...
        rejoin.strict_C9_load_join&&rejoin.strict_C7_uav_join&& ...
        rejoin.strict_C6_yaw_join;
    assert(R.offclock_replan_initial_join_C7_C6, ...
        'CHECK_C9_MULTI:Rejoin','Replan at current instant must retain C7/yaw C6 jets.');
    broken=newL;broken(1,2)=broken(1,2)+0.02;
    bad=TRAJECTORY_C9_FLAT_BERNSTEIN.build( ...
        now,requested_duration,broken,prev.end_jets,old_tail(:,11:14));
    bad_check=TRAJECTORY_C9_UAV_C7_YAW_C6_AUDIT(bad,A,jo);
    R.replan_modified_initial_jet_rejected=~bad_check.certified;
    assert(R.replan_modified_initial_jet_rejected, ...
        'CHECK_C9_MULTI:Rejoin','Mismatched initial velocity may not be accepted.');
    near=TRAJECTORY_C9_FLAT_BERNSTEIN.evaluate( ...
        candidate,now+0.57*requested_duration);
    newly=OBSTACLE_INFORMATION.define(55,'sphere', ...
        near(:,1).'+[0 0.09 0],0.17);
    newer=req;newer.t0_s=now;newer.duration_s=requested_duration;
    newer.flight_interval_s=[0 30];newer.start_jets=newL;
    newer.end_jets=prev.end_jets;
    newer.nominal_free=old_tail(:,11:14);
    newer.observed=[req.observed,newly];
    replan_result=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(newer);
    R.offclock_replan_status=replan_result.status;
    R.replan_search_elapsed_ms=replan_result.elapsed_ms;
    R.replan_new_obstacle_retained_with_old=isequal( ...
        replan_result.considered_obstacle_ids,[21 55]);
    R.offclock_replan_candidate_certified= ...
        replan_result.candidate_available&&replan_result.final_certificate.certified;
    if replan_result.candidate_available
        check=TRAJECTORY_C9_UAV_C7_YAW_C6_AUDIT( ...
            replan_result.candidate_piece,A,jo);
        R.offclock_replan_candidate_C7_C6=check.certified&& ...
            check.strict_C7_uav_join&&check.strict_C6_yaw_join;
    end
    assert(R.replan_new_obstacle_retained_with_old&& ...
        ~replan_result.safe_to_commit&& ...
        (~replan_result.candidate_available|| ...
            replan_result.final_certificate.certified), ...
        'CHECK_C9_MULTI:Replan','Replan cannot discard known obstacles or commit.');

    % API-level 28xN delivery audit: synthetic fixture ONLY, NOT actual HLC.
    times=prev.t0_s+prev.duration_s*[0.1 0.3 0.5 0.7 0.9];
    expected=zeros(28,numel(times));yaw=0;
    for k=1:numel(times)
        [expected(:,k),j]=TRAJECTORY_TAUT_FLATNESS.reference28( ...
            prev,times(k),A,yaw);yaw=j(1);
    end
    tlog=struct('time_s',times,'actual_controller_ref28',expected, ...
        'yaw_anchor_rad',0,'reference_tolerance28',1e-9*ones(28,1));
    correct=generator.audit_c9_actual_HLC_ticks(prev,A,tlog);
    R.fixture_tick_log_correct_pass=correct.sampled_reference_match&& ...
        ~correct.safe_to_commit;
    R.fixture_tick_log_cannot_certify_HLC= ...
        ~correct.physical_continuous_time_certified&&~correct.safe_to_commit;
    tlog.actual_controller_ref28(4,3)= ...
        tlog.actual_controller_ref28(4,3)+0.1;
    corrupt=generator.audit_c9_actual_HLC_ticks(prev,A,tlog);
    R.fixture_tick_log_corruption_rejected= ...
        ~corrupt.sampled_reference_match&&corrupt.first_mismatch_index==3;
    assert(R.fixture_tick_log_correct_pass&& ...
        R.fixture_tick_log_corruption_rejected&& ...
        R.fixture_tick_log_cannot_certify_HLC, ...
        'CHECK_C9_MULTI:Trace','28-channel logged reference comparison must be exact.');
    if R.offclock_replan_candidate_certified && ...
            ~R.offclock_replan_candidate_C7_C6
        R.status='PASS_GEOMETRY_ONLY__REPLAN_YAW_C7_UNKNOWN__HLC_UNCERTIFIED';
    elseif R.baseline_C7_yaw_C6_regular
        R.status='PASS_MULTI_CASE_SAFETY_AUDIT_AND_REPLAN_JOIN__HLC_UNCERTIFIED';
    else
        R.status='PASS_MULTI_CASE_SAFETY_AUDIT__HEADING_UNPROVEN__HLC_UNCERTIFIED';
    end
catch ME
    R.status='FAIL_C9_MULTI_REPLAN_AUDIT';
    R.error_identifier=ME.identifier;R.error_message=ME.message;
    write_results(root,R);
    rethrow(ME);
end
write_results(root,R);
end

function M=rotation3(a,b,c)
Rx=[1 0 0;0 cos(a) -sin(a);0 sin(a) cos(a)];
Ry=[cos(b) 0 sin(b);0 1 0;-sin(b) 0 cos(b)];
Rz=[cos(c) -sin(c) 0;sin(c) cos(c) 0;0 0 1];
M=Rz*Ry*Rx;
end

function [A,B]=split_bernstein(P,u)
n=size(P,2);A=zeros(size(P));B=A;Q=P;
A(:,1)=P(:,1);B(:,end)=P(:,end);
for k=2:n
    Q=(1-u)*Q(:,1:end-1)+u*Q(:,2:end);
    A(:,k)=Q(:,1);B(:,n-k+1)=Q(:,end);
end
end

function write_results(root,R)
name='TRAJECTORY_C9_MULTI_REPLAN_C7_YAW_HLC_RESULT';
save(fullfile(root,[name '.mat']),'R');
fid=fopen(fullfile(root,[name '.txt']),'wt');
if fid<0,error('CHECK_C9_MULTI:IO','Failed to open result file.');end
c=onCleanup(@()fclose(fid));
fprintf(fid,'status=%s\n',R.status);
for k=1:min([R.case_count,numel(R.case_labels),numel(R.case_status)])
    fprintf(fid,['case=%d label=%s obstacles=%d status=%s ' ...
        'certified=%d heading=%d mass=%.4f tube=%d ' ...
        'total_ms=%.5f proof_ms=%.5f plane_ms=%.5f qp_ms=%.5f\n'], ...
        k,R.case_labels{k},R.case_obstacle_counts(k),R.case_status{k}, ...
        R.case_certified(k),R.case_heading_certified(k), ...
        R.case_payload_mass_kg(k),R.case_robust_tube(k), ...
        R.case_elapsed_ms(k),R.case_proof_ms(k), ...
        R.case_plane_ms(k),R.case_qp_ms(k));
    fprintf(fid,'    proof_nodes=%d support_calls=%d unresolved_ids=%s interval_s=[%.9g %.9g]\n', ...
        R.case_final_proof_nodes(k),R.case_final_support_calls(k), ...
        mat2str(R.case_unresolved_obstacle_ids{k}), ...
        R.case_unresolved_time_interval_s(1,k), ...
        R.case_unresolved_time_interval_s(2,k));
end
fields=fieldnames(R);
for i=1:numel(fields)
    name=fields{i};val=R.(name);
    if islogical(val)&&isscalar(val)
        fprintf(fid,'%s=%d\n',name,val);
    elseif isnumeric(val)&&isscalar(val)
        fprintf(fid,'%s=%.14g\n',name,val);
    elseif ischar(val)&&~isempty(val)
        fprintf(fid,'%s=%s\n',name,val);
    end
end
clear c;
try
    name='TRAJECTORY_C9_MULTI_REPLAN_C7_YAW_HLC_RESULT';
    zip(fullfile(root,[name '_FOR_CHATGPT.zip']), ...
        {[name '.mat'],[name '.txt']},root);
catch ME
    warning('CHECK_C9_MULTI:Zip','Results saved but ZIP failed: %s',ME.message);
end
end
