function OUT=AF7R36_FAMILY_DIAG_OBSTACLE_PLOT_R24B_INSTALL()
% AF7R36_FAMILY_DIAG_OBSTACLE_PLOT_R24B_INSTALL
% Diagnostic + visualization only.
% Does not change C7, speed, rejoin, or whole-body acceptance mathematics.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 FAMILY-DIAGNOSTIC + OBSTACLE-PLOT R24B INSTALL\n');
fprintf(' planner mathematics modified                = 0\n');
fprintf(' hard safety gates modified                  = 0\n');
fprintf(' exact-C7 gate modified                      = 0\n');
fprintf(' family-resolved rejection diagnostics       = 1\n');
fprintf(' 3-D raw-obstacle rendering                  = 1\n');
fprintf(' local equal-scale obstacle view             = Figure 12\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir)&&isfolder(refDir),'[R24B] Cannot resolve reference directory.');
hpp=fullfile(refDir,'af7r36_core.hpp');
cpp=fullfile(refDir,'af7r36_single_core_mex.cpp');
rps=fullfile(refDir,'REPLANNING_SYSTEM.m');
runner=which('run_flight_headless');
assert(isfile(hpp)&&isfile(cpp)&&isfile(rps),'[R24B] Production sources missing.');
assert(~isempty(runner)&&isfile(runner),'[R24B] run_flight_headless.m missing.');

hpp0=normlf(fileread(hpp)); cpp0=normlf(fileread(cpp));
rps0=normlf(fileread(rps)); run0=normlf(fileread(runner));
hppNew=hpp0; cppNew=cpp0; rpsNew=rps0; runNew=run0;

assert(contains(hpp0,'AF7_EXACT_C7_DYADIC_LATTICE_R22C'), ...
    '[R24B] R22C exact-C7 source is not installed.');
assert(contains(hpp0,'if(!cand.exact_c7)continue;'), ...
    '[R24B] R22C exact-C7 hard gate not found.');
assert(contains(cpp0,'"stored_c7_exact"'), ...
    '[R24B] R22C serializer not found.');
assert(contains(rps0,'staged_replan_predeadline_c7_exact'), ...
    '[R24B] R22C predeadline latch not found.');
assert(contains(run0,'AF7R36 R23 partial-plot-on-error'), ...
    '[R24B] R23 runner patch not found.');
assert(~contains(hpp0,'AF7R24B_FAMILY_DIAGNOSTICS'), ...
    '[R24B] R24B already installed.');

try
    %% 1. Diagnostic counters only.
    old=[ ...
        '    int fallback_rejoin_pass=0;' sprintf('\n') ...
        '    int fallback_geom_tests=0;'];
    new=[old sprintf('\n') ...
        '' sprintf('\n') ...
        '    // AF7R24B_FAMILY_DIAGNOSTICS -- diagnostic only.' sprintf('\n') ...
        '    std::array<int,8> r24b_family_seen{};' sprintf('\n') ...
        '    std::array<int,8> r24b_family_exact{};' sprintf('\n') ...
        '    std::array<int,8> r24b_family_exact_reject{};' sprintf('\n') ...
        '    std::array<int,8> r24b_family_speed_pass{};' sprintf('\n') ...
        '    std::array<int,8> r24b_family_speed_fail{};' sprintf('\n') ...
        '    int r24b_split_representability_reject=0;'];
    hppNew=replace_once(hppNew,old,new,'PlanResult diagnostics');

    %% 2. R22C split representability rejection counter.
    old='                    if(m.rfind("R22C ",0)==0)return;';
    new=[ ...
        '                    if(m.rfind("R22C ",0)==0){' sprintf('\n') ...
        '                        ++R.r24b_split_representability_reject;' sprintf('\n') ...
        '                        return;' sprintf('\n') ...
        '                    }'];
    hppNew=replace_once(hppNew,old,new,'split diagnostic');

    %% 3. Instrument exact-C7 gate inside certify_candidates region only.
    exactOld='        if(!cand.exact_c7)continue;';
    exactNew=[ ...
        '        const int r24bfi=(cand.family>=0&&cand.family<8)?cand.family:0;' sprintf('\n') ...
        '        ++R.r24b_family_seen[r24bfi];' sprintf('\n') ...
        '        if(cand.exact_c7)++R.r24b_family_exact[r24bfi];' sprintf('\n') ...
        '        else{' sprintf('\n') ...
        '            ++R.r24b_family_exact_reject[r24bfi];' sprintf('\n') ...
        '            continue;' sprintf('\n') ...
        '        }'];
    hppNew=replace_once_in_region(hppNew, ...
        'auto certify_candidates=[&]','return false;', ...
        exactOld,exactNew,'family exact gate');

    %% 4. Instrument speed result without assuming Stage-B source formatting.
    speedOld='            if(!sc.certified) continue;';
    speedNew=[ ...
        '            if(!sc.certified){' sprintf('\n') ...
        '                ++R.r24b_family_speed_fail[r24bfi];' sprintf('\n') ...
        '                continue;' sprintf('\n') ...
        '            }' sprintf('\n') ...
        '            ++R.r24b_family_speed_pass[r24bfi];'];
    hppNew=replace_once_in_region(hppNew, ...
        'auto certify_candidates=[&]','return false;', ...
        speedOld,speedNew,'family speed result');

    %% 5. MEX serializer.
    old='"spatial_envelope_priority","compact_constant_translation","stored_c7_exact","minimum_deviation_primary",';
    new=[ ...
        '"spatial_envelope_priority","compact_constant_translation","stored_c7_exact",' ...
        '"r24b_family_seen","r24b_family_exact","r24b_family_exact_reject",' ...
        '"r24b_family_speed_pass","r24b_family_speed_fail",' ...
        '"r24b_split_representability_reject","minimum_deviation_primary",'];
    cppNew=replace_once(cppNew,old,new,'MEX field list');

    old='    set("stored_c7_exact",logicalScalar(R.cand.exact_c7));';
    new=[old sprintf('\n') ...
        '    std::vector<int> r24bs(R.r24b_family_seen.begin(),R.r24b_family_seen.end());' sprintf('\n') ...
        '    std::vector<int> r24be(R.r24b_family_exact.begin(),R.r24b_family_exact.end());' sprintf('\n') ...
        '    std::vector<int> r24bx(R.r24b_family_exact_reject.begin(),R.r24b_family_exact_reject.end());' sprintf('\n') ...
        '    std::vector<int> r24bp(R.r24b_family_speed_pass.begin(),R.r24b_family_speed_pass.end());' sprintf('\n') ...
        '    std::vector<int> r24bf(R.r24b_family_speed_fail.begin(),R.r24b_family_speed_fail.end());' sprintf('\n') ...
        '    set("r24b_family_seen",ivecrow(r24bs));' sprintf('\n') ...
        '    set("r24b_family_exact",ivecrow(r24be));' sprintf('\n') ...
        '    set("r24b_family_exact_reject",ivecrow(r24bx));' sprintf('\n') ...
        '    set("r24b_family_speed_pass",ivecrow(r24bp));' sprintf('\n') ...
        '    set("r24b_family_speed_fail",ivecrow(r24bf));' sprintf('\n') ...
        '    set("r24b_split_representability_reject",dscalar(R.r24b_split_representability_reject));'];
    cppNew=replace_once(cppNew,old,new,'MEX field values');

    %% 6. MATLAB latch/status.
    old='        staged_replan_predeadline_c7_exact = false;';
    new=[old sprintf('\n') ...
        '        % R24B diagnostic-only family decomposition.' sprintf('\n') ...
        '        staged_replan_predeadline_r24b_family_seen = nan(1,8);' sprintf('\n') ...
        '        staged_replan_predeadline_r24b_family_exact = nan(1,8);' sprintf('\n') ...
        '        staged_replan_predeadline_r24b_family_exact_reject = nan(1,8);' sprintf('\n') ...
        '        staged_replan_predeadline_r24b_family_speed_pass = nan(1,8);' sprintf('\n') ...
        '        staged_replan_predeadline_r24b_family_speed_fail = nan(1,8);' sprintf('\n') ...
        '        staged_replan_predeadline_r24b_split_representability_reject = NaN;'];
    rpsNew=replace_once(rpsNew,old,new,'MATLAB properties');

    old=[ ...
        '                if isfield(NR16,''stored_c7_exact'')' sprintf('\n') ...
        '                    obj.staged_replan_predeadline_c7_exact=logical(NR16.stored_c7_exact);' sprintf('\n') ...
        '                end'];
    new=[old sprintf('\n') ...
        '                if isfield(NR16,''r24b_family_seen''),obj.staged_replan_predeadline_r24b_family_seen=double(NR16.r24b_family_seen(:).'');end' sprintf('\n') ...
        '                if isfield(NR16,''r24b_family_exact''),obj.staged_replan_predeadline_r24b_family_exact=double(NR16.r24b_family_exact(:).'');end' sprintf('\n') ...
        '                if isfield(NR16,''r24b_family_exact_reject''),obj.staged_replan_predeadline_r24b_family_exact_reject=double(NR16.r24b_family_exact_reject(:).'');end' sprintf('\n') ...
        '                if isfield(NR16,''r24b_family_speed_pass''),obj.staged_replan_predeadline_r24b_family_speed_pass=double(NR16.r24b_family_speed_pass(:).'');end' sprintf('\n') ...
        '                if isfield(NR16,''r24b_family_speed_fail''),obj.staged_replan_predeadline_r24b_family_speed_fail=double(NR16.r24b_family_speed_fail(:).'');end' sprintf('\n') ...
        '                if isfield(NR16,''r24b_split_representability_reject''),obj.staged_replan_predeadline_r24b_split_representability_reject=double(NR16.r24b_split_representability_reject);end'];
    rpsNew=replace_once(rpsNew,old,new,'MATLAB native latch');

    old='            S.predeadline_c7_exact=logical(obj.staged_replan_predeadline_c7_exact);';
    new=[old sprintf('\n') ...
        '            S.r24b_family_seen=double(obj.staged_replan_predeadline_r24b_family_seen);' sprintf('\n') ...
        '            S.r24b_family_exact=double(obj.staged_replan_predeadline_r24b_family_exact);' sprintf('\n') ...
        '            S.r24b_family_exact_reject=double(obj.staged_replan_predeadline_r24b_family_exact_reject);' sprintf('\n') ...
        '            S.r24b_family_speed_pass=double(obj.staged_replan_predeadline_r24b_family_speed_pass);' sprintf('\n') ...
        '            S.r24b_family_speed_fail=double(obj.staged_replan_predeadline_r24b_family_speed_fail);' sprintf('\n') ...
        '            S.r24b_split_representability_reject=double(obj.staged_replan_predeadline_r24b_split_representability_reject);'];
    rpsNew=replace_once(rpsNew,old,new,'MATLAB status');

    %% 7. 3-D obstacle visualization.
    old=[ ...
        'plot_suspended_load_trajectory(logger,dt, ...' sprintf('\n') ...
        '    "figure_number",6, ...' sprintf('\n') ...
        '    "phase","f", ...' sprintf('\n') ...
        '    "title_text","UAV / Suspended Load / Reference Trajectory — Flight");'];
    new=[old sprintf('\n') ...
        '' sprintf('\n') ...
        '% AF7R24B obstacle-aware 3-D visualization.' sprintf('\n') ...
        'figure(5); af7r24b_overlay_obstacles(gca,replanner_instance.static_obstacle_map);' sprintf('\n') ...
        'figure(6); af7r24b_overlay_obstacles(gca,replanner_instance.static_obstacle_map);' sprintf('\n') ...
        'plot_suspended_load_trajectory(logger,dt, ...' sprintf('\n') ...
        '    "figure_number",12, ...' sprintf('\n') ...
        '    "phase","f", ...' sprintf('\n') ...
        '    "title_text","Obstacle-local 3-D: UAV / Load / Reference");' sprintf('\n') ...
        'figure(12); af7r24b_overlay_obstacles(gca,replanner_instance.static_obstacle_map);' sprintf('\n') ...
        'af7r24b_local_limits(gca,replanner_instance.static_obstacle_map);' sprintf('\n') ...
        'view(3); grid on; box on; daspect([1 1 1]);'];
    runNew=replace_once(runNew,old,new,'3-D plot calls');

    anchor='function y = motive_output(obj,data)';
    helper=[ ...
        'function af7r24b_overlay_obstacles(ax,obs)' sprintf('\n') ...
        'if isempty(obs),return;end;hold(ax,''on'');' sprintf('\n') ...
        'for ii=1:numel(obs)' sprintf('\n') ...
        ' o=obs(ii);if ~isfield(o,''p_center''),continue;end;c=double(o.p_center(:));' sprintf('\n') ...
        ' if numel(c)~=3||any(~isfinite(c)),continue;end;R=eye(3);' sprintf('\n') ...
        ' if isfield(o,''R_obs'')&&isequal(size(o.R_obs),[3 3]),R=double(o.R_obs);end' sprintf('\n') ...
        ' typ='''';if isfield(o,''type''),typ=lower(char(o.type));end;rp=[];' sprintf('\n') ...
        ' if isfield(o,''raw_param''),rp=double(o.raw_param(:));end' sprintf('\n') ...
        ' if strcmp(typ,''cylinder'')&&numel(rp)>=2,af7r24b_cylinder(ax,c,R,rp(1),rp(2));' sprintf('\n') ...
        ' elseif strcmp(typ,''sphere'')&&~isempty(rp),af7r24b_ellipsoid(ax,c,R,rp(1)*ones(3,1));' sprintf('\n') ...
        ' elseif strcmp(typ,''ellipsoid'')&&numel(rp)>=3,af7r24b_ellipsoid(ax,c,R,rp(1:3));end' sprintf('\n') ...
        ' id=ii;if isfield(o,''id''),id=double(o.id);end;text(ax,c(1),c(2),c(3),sprintf('' Obs %g'',id),''FontWeight'',''bold'');' sprintf('\n') ...
        'end;hold(ax,''off'');' sprintf('\n') ...
        'end' sprintf('\n') ...
        'function af7r24b_cylinder(ax,c,R,r,h)' sprintf('\n') ...
        '[X,Y,Z]=cylinder(r,48);Z=(Z-0.5)*h;[X,Y,Z]=af7r24b_xform(X,Y,Z,c,R);' sprintf('\n') ...
        'surf(ax,X,Y,Z,''FaceAlpha'',0.22,''EdgeAlpha'',0.18,''HandleVisibility'',''off'');' sprintf('\n') ...
        'end' sprintf('\n') ...
        'function af7r24b_ellipsoid(ax,c,R,a)' sprintf('\n') ...
        '[X,Y,Z]=sphere(36);a=double(a(:));X=a(1)*X;Y=a(2)*Y;Z=a(3)*Z;[X,Y,Z]=af7r24b_xform(X,Y,Z,c,R);' sprintf('\n') ...
        'surf(ax,X,Y,Z,''FaceAlpha'',0.18,''EdgeAlpha'',0.12,''HandleVisibility'',''off'');' sprintf('\n') ...
        'end' sprintf('\n') ...
        'function [X,Y,Z]=af7r24b_xform(X,Y,Z,c,R)' sprintf('\n') ...
        'sz=size(X);V=R*[X(:)'';Y(:)'';Z(:)'']+c;X=reshape(V(1,:),sz);Y=reshape(V(2,:),sz);Z=reshape(V(3,:),sz);' sprintf('\n') ...
        'end' sprintf('\n') ...
        'function af7r24b_local_limits(ax,obs)' sprintf('\n') ...
        'if isempty(obs),return;end;lo=[inf;inf;inf];hi=[-inf;-inf;-inf];' sprintf('\n') ...
        'for ii=1:numel(obs),o=obs(ii);if ~isfield(o,''p_center''),continue;end;c=double(o.p_center(:));' sprintf('\n') ...
        'if numel(c)~=3||any(~isfinite(c)),continue;end;R=eye(3);if isfield(o,''R_obs'')&&isequal(size(o.R_obs),[3 3]),R=double(o.R_obs);end' sprintf('\n') ...
        'typ='''';if isfield(o,''type''),typ=lower(char(o.type));end;rp=[];if isfield(o,''raw_param''),rp=double(o.raw_param(:));end;e=[1;1;1];' sprintf('\n') ...
        'if strcmp(typ,''cylinder'')&&numel(rp)>=2,e=abs(R)*[rp(1);rp(1);rp(2)/2];elseif strcmp(typ,''sphere'')&&~isempty(rp),e=rp(1)*ones(3,1);elseif strcmp(typ,''ellipsoid'')&&numel(rp)>=3,e=abs(R)*rp(1:3);end' sprintf('\n') ...
        'lo=min(lo,c-e);hi=max(hi,c+e);end;if any(~isfinite([lo;hi])),return;end' sprintf('\n') ...
        'span=max(hi-lo);pad=max(2,0.35*max(span,1));xlim(ax,[lo(1)-pad hi(1)+pad]);ylim(ax,[lo(2)-pad hi(2)+pad]);zlim(ax,[lo(3)-pad hi(3)+pad]);' sprintf('\n') ...
        'end' sprintf('\n') ...
        anchor];
    runNew=replace_once(runNew,anchor,helper,'plot helpers');

    %% Static invariants.
    assert(count_exact(hppNew,'AF7R24B_FAMILY_DIAGNOSTICS')==1);
    assert(contains(hppNew,'r24b_family_speed_fail'));
    assert(contains(cppNew,'"r24b_family_seen"'));
    assert(contains(rpsNew,'S.r24b_family_seen='));
    assert(count_exact(runNew,'AF7R24B obstacle-aware 3-D visualization.')==1);

    %% Stage compile MEX.
    stage=tempname;[ok,msg]=mkdir(stage);assert(ok,'%s',msg);
    cleanup=onCleanup(@()cleanup_stage(stage)); %#ok<NASGU>
    sh=fullfile(stage,'af7r36_core.hpp');sc=fullfile(stage,'af7r36_single_core_mex.cpp');
    write_text(sh,hppNew);write_text(sc,cppNew);
    oldDir=pwd;cdguard=onCleanup(@()cd(oldDir)); %#ok<NASGU>
    cd(stage);clear mex
    fprintf('[R24B] Compiling staged MEX...\n');
    mex('-R2018a','-O','COMPFLAGS="$COMPFLAGS /std:c++17"', ...
        ['-I' stage],'-output','af7r36_single_core_mex','-outdir',stage,sc);
    sm=fullfile(stage,['af7r36_single_core_mex.' mexext]);assert(isfile(sm));

    %% Transactional install.
    dstMex=fullfile(refDir,['af7r36_single_core_mex.' mexext]);
    oldMex=fullfile(stage,['af7r36_single_core_mex_OLD.' mexext]);
    hadMex=isfile(dstMex);if hadMex,[ok,msg]=copyfile(dstMex,oldMex,'f');assert(ok,'%s',msg);end
    cd(oldDir);clear mex
    wroteH=false;wroteC=false;wroteR=false;wroteRun=false;installed=false;
    try
        write_text(hpp,hppNew);wroteH=true;
        write_text(cpp,cppNew);wroteC=true;
        write_text(rps,rpsNew);wroteR=true;
        write_text(runner,runNew);wroteRun=true;
        [ok,msg]=copyfile(sm,dstMex,'f');assert(ok,'%s',msg);installed=true;
        clear mex;rehash
    catch ME2
        if wroteH,try,write_text(hpp,hpp0);catch,end,end
        if wroteC,try,write_text(cpp,cpp0);catch,end,end
        if wroteR,try,write_text(rps,rps0);catch,end,end
        if wroteRun,try,write_text(runner,run0);catch,end,end
        if installed&&hadMex,try,copyfile(oldMex,dstMex,'f');catch,end,end
        clear mex;rehash;rethrow(ME2);
    end

    fprintf('[R24B] PASS.\n');
    fprintf('  family exact/speed decomposition installed = 1\n');
    fprintf('  Figure 5/6 raw obstacles overlaid          = 1\n');
    fprintf('  Figure 12 obstacle-local equal-scale view  = 1\n');
    fprintf('  hard acceptance behavior changed           = 0\n');
    OUT=struct('pass',true,'revision','AF7_FAMILY_DIAG_OBSTACLE_PLOT_R24B');

catch ME
    clear mex;rehash
    fprintf(2,'[R24B] FAILED: %s | %s\n',ME.identifier,ME.message);
    rethrow(ME);
end
end

function txt=replace_once_in_region(txt,regionStart,regionEnd,old,new,label)
p0=strfind(txt,regionStart);assert(numel(p0)==1,'[R24B] region start "%s" count=%d.',label,numel(p0));
tail=txt(p0:end);p1=strfind(tail,regionEnd);assert(~isempty(p1),'[R24B] region end "%s" missing.',label);
stop=p0+p1(1)-2;
sub=txt(p0:stop);q=strfind(sub,old);
assert(numel(q)==1,'[R24B] anchor "%s" count=%d in certify region.',label,numel(q));
a=p0+q(1)-1;txt=[txt(1:a-1) new txt(a+numel(old):end)];
end
function txt=replace_once(txt,old,new,label)
p=strfind(txt,old);assert(numel(p)==1,'[R24B] Anchor "%s" count=%d; expected 1.',label,numel(p));
txt=[txt(1:p-1) new txt(p+numel(old):end)];
end
function n=count_exact(txt,pat),n=numel(strfind(txt,pat));end
function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));s=strrep(s,sprintf('\r'),sprintf('\n'));
end
function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');assert(f>=0,'[R24B] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end
function cleanup_stage(d)
if isfolder(d),try,rmdir(d,'s');catch,end,end
end
