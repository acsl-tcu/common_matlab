function OUT = AF7R36_TOWING_WITNESS_TIME_MAP_R4C_INSTALL()
% AF7R36_TOWING_WITNESS_TIME_MAP_R4C_INSTALL
% Diagnostic-only, compatible with the already-installed AF7_TOWING_DIAG_V1.
%
% Key difference from R4:
%   R4B does NOT edit any stageB_speed call site. Existing &wmax diagnostics
%   remain untouched. The exact finite-witness rejection point is recorded
%   inside stageB_speed itself.
%
% No trajectory generation/order/acceptance/commit rule is changed.
% No README and no persistent backup file is created.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 TOWING WITNESS + TIME MAP R4C INSTALL\n');
fprintf(' existing AF7_TOWING_DIAG_V1 compatible     = 1\n');
fprintf(' trajectory generation modified             = 0\n');
fprintf(' hard certificate semantics modified        = 0\n');
fprintf(' stageB call sites modified                  = 0\n');
fprintf(' insertion-index arithmetic used             = 0\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir) && isfolder(refDir), ...
    '[TOWMAP-R4C] Cannot resolve current reference directory.');

hpp=fullfile(refDir,'af7r36_core.hpp');
cpp=fullfile(refDir,'af7r36_single_core_mex.cpp');
assert(isfile(hpp),'[TOWMAP-R4C] Missing %s',hpp);
assert(isfile(cpp),'[TOWMAP-R4C] Missing %s',cpp);

hpp0=normlf(fileread(hpp));
cpp0=normlf(fileread(cpp));
hppNew=hpp0;
cppNew=cpp0;

assert(contains(hpp0,'TOWING-SPECIFIC SECONDARY FAMILY') || ...
       contains(hpp0,'AF7_TOWING_CONSTANT_V1'), ...
    '[TOWMAP-R4C] Towing constant branch not found. No edit made.');
assert(contains(cpp0,'TOWING_CONSTANT_TRANSLATION'), ...
    '[TOWMAP-R4C] Towing family wrapper output not found. No edit made.');
assert(contains(cpp0, ...
    'static const char* PLANNER_REV="AF7_REPLANNER_MIN_DEVIATION_V4_FIXED_T1";'), ...
    '[TOWMAP-R4C] Legacy planner identity is not restored. No edit made.');
assert(~contains(hpp0,'AF7_TOWMAP_R4C_CORE_WITNESS'), ...
    '[TOWMAP-R4C] Core witness instrumentation already installed.');
assert(~contains(cpp0,'AF7_TOWMAP_R4C_RING'), ...
    '[TOWMAP-R4C] MEX ring instrumentation already installed.');

try
    %% 1) Core witness accumulator. Does not affect acceptance.
    anchor='struct VLeaf {';
    witnessBlock=[ ...
        '// AF7_TOWMAP_R4C_CORE_WITNESS -- rejection-only diagnostics.' sprintf('\n') ...
        '// class: 1 ENTRY_C7, 2 UNSAFE_AFFINE, 3 INTER_C7, 4 EXIT_REJOIN_C7.' sprintf('\n') ...
        'struct TowMapWitnessSummary {' sprintf('\n') ...
        '    int count=0;' sprintf('\n') ...
        '    double min_vq=std::numeric_limits<double>::infinity();' sprintf('\n') ...
        '    double min_t=std::numeric_limits<double>::quiet_NaN();' sprintf('\n') ...
        '    int min_seg=-1,min_class=0;' sprintf('\n') ...
        '    double max_vq=-std::numeric_limits<double>::infinity();' sprintf('\n') ...
        '    double max_t=std::numeric_limits<double>::quiet_NaN();' sprintf('\n') ...
        '    int max_seg=-1,max_class=0;' sprintf('\n') ...
        '};' sprintf('\n') ...
        'static TowMapWitnessSummary G_towmap_primary_witness;' sprintf('\n') ...
        'static TowMapWitnessSummary G_towmap_towing_witness;' sprintf('\n') ...
        'static inline void towmap_core_reset_witness(){' sprintf('\n') ...
        '    G_towmap_primary_witness=TowMapWitnessSummary{};' sprintf('\n') ...
        '    G_towmap_towing_witness=TowMapWitnessSummary{};' sprintf('\n') ...
        '}' sprintf('\n') ...
        'static inline void towmap_core_record_witness(int family,int seg,int nseg,double t,double vq){' sprintf('\n') ...
        '    if(!(fin(t)&&fin(vq))||nseg<1)return;' sprintf('\n') ...
        '    TowMapWitnessSummary* W=nullptr;' sprintf('\n') ...
        '    if(family==1)W=&G_towmap_primary_witness;' sprintf('\n') ...
        '    else if(family==3)W=&G_towmap_towing_witness;' sprintf('\n') ...
        '    else return;' sprintf('\n') ...
        '    int cls=0;' sprintf('\n') ...
        '    if(seg==0)cls=1;' sprintf('\n') ...
        '    else if(seg==nseg-1)cls=4;' sprintf('\n') ...
        '    else if((seg&1)==1)cls=2;' sprintf('\n') ...
        '    else cls=3;' sprintf('\n') ...
        '    ++W->count;' sprintf('\n') ...
        '    if(vq<W->min_vq){W->min_vq=vq;W->min_t=t;W->min_seg=seg;W->min_class=cls;}' sprintf('\n') ...
        '    if(vq>W->max_vq){W->max_vq=vq;W->max_t=t;W->max_seg=seg;W->max_class=cls;}' sprintf('\n') ...
        '}' sprintf('\n') ...
        anchor];
    hppNew=replace_once(hppNew,anchor,witnessBlock,'VLeaf declaration');

    %% 2) Insert one diagnostic record at the exact finite-witness reject.
    % Work only inside stageB_speed, so existing AF7_TOWING_DIAG_V1
    % witnessMaxOut logic and its call sites remain unchanged.
    stageStart='static inline SpeedCert stageB_speed';
    stageEnd='// -------------------------- corrected candidate eval';
    if ~contains(hppNew,stageEnd)
        % AF7_TOWING_DIAG_V1 may insert StageBTrace before candidate_eval.
        stageEnd='struct StageBTrace';
    end
    oldStageToken='finiteWitness=true;';
    newStageToken=[oldStageToken sprintf('\n') ...
        '            towmap_core_record_witness(C.family,f.seg,(int)C.cp.size(),0.5*(f.ta+f.tb),f.wit);'];
    hppNew=replace_once_between(hppNew,stageStart,stageEnd, ...
        oldStageToken,newStageToken,'finite witness record');

    % Structural self-audit: instrumentation must not split or remove return.
    assert(count_exact(hppNew,'return {};')==count_exact(hpp0,'return {};'), ...
        '[TOWMAP-R4C] C++ return-token count changed; refusing staged compile.');
    assert(count_exact(hppNew,'stageB_speed(ref,L,base,cand,lim')== ...
           count_exact(hpp0,'stageB_speed(ref,L,base,cand,lim'), ...
        '[TOWMAP-R4C] Stage-B call-site count changed unexpectedly.');
    assert(count_exact(hppNew,'towmap_core_record_witness(C.family')==1, ...
        '[TOWMAP-R4C] Witness recorder insertion count is not exactly one.');

    %% 3) Bounded MEX call ring.
    anchor='static bool G_compiled=false;';
    ringBlock=[anchor sprintf('\n') sprintf('\n') ...
        '// AF7_TOWMAP_R4C_RING -- diagnostic only.' sprintf('\n') ...
        'struct TowMapEntry {' sprintf('\n') ...
        '    double seq=0,t0=NAN,tm=NAN,t1=NAN,limit=NAN,success=0,reason=0,family=0;' sprintf('\n') ...
        '    double envelope=NAN,VQ=NAN,VL=NAN,A=NAN,J=NAN,sigma=NAN,qdot=NAN,total_ms=NAN;' sprintf('\n') ...
        '    double pc=0,ps=0,pr=0,pg=0,tc=0,ts=0,tr=0,tg=0,fc=0,fs=0,fr=0,fg=0;' sprintf('\n') ...
        '    double pwc=0,pwmin=NAN,pwmint=NAN,pwmins=NAN,pwminc=NAN,pwmax=NAN,pwmaxt=NAN,pwmaxs=NAN,pwmaxc=NAN;' sprintf('\n') ...
        '    double twc=0,twmin=NAN,twmint=NAN,twmins=NAN,twminc=NAN,twmax=NAN,twmaxt=NAN,twmaxs=NAN,twmaxc=NAN;' sprintf('\n') ...
        '};' sprintf('\n') ...
        'static std::vector<TowMapEntry> G_towmap;' sprintf('\n') ...
        'static double G_towmap_seq=0;' sprintf('\n') ...
        'static inline double towmap_finite_or_nan(double x){return std::isfinite(x)?x:NAN;}' sprintf('\n') ...
        'static void towmap_push(const PlanResult&Q,const Live&L,double t0,double tm,double t1){' sprintf('\n') ...
        '    TowMapEntry d;d.seq=++G_towmap_seq;d.t0=t0;d.tm=tm;d.t1=t1;' sprintf('\n') ...
        '    double rho=std::max({L.rQ,L.L+L.rL,L.L+L.rC});d.limit=(L.sensor_range-rho)/(L.horizon+L.dt);' sprintf('\n') ...
        '    d.success=Q.success?1.0:0.0;d.reason=Q.reason;d.family=(double)Q.cand.family;' sprintf('\n') ...
        '    if(Q.success){d.envelope=Q.cand.max_ctrl;d.VQ=Q.speed.VQ;d.VL=Q.speed.VL;d.A=Q.speed.A;d.J=Q.speed.J;d.sigma=Q.speed.sigma;d.qdot=Q.speed.qdot;}' sprintf('\n') ...
        '    d.total_ms=Q.tim.total;' sprintf('\n') ...
        '    d.pc=Q.primary_candidate_count;d.ps=Q.primary_speed_pass;d.pr=Q.primary_rejoin_pass;d.pg=Q.primary_geom_tests;' sprintf('\n') ...
        '    d.tc=Q.towing_candidate_count;d.ts=Q.towing_speed_pass;d.tr=Q.towing_rejoin_pass;d.tg=Q.towing_geom_tests;' sprintf('\n') ...
        '    d.fc=Q.fallback_candidate_count;d.fs=Q.fallback_speed_pass;d.fr=Q.fallback_rejoin_pass;d.fg=Q.fallback_geom_tests;' sprintf('\n') ...
        '    const auto&P=G_towmap_primary_witness;const auto&T=G_towmap_towing_witness;' sprintf('\n') ...
        '    d.pwc=P.count;d.pwmin=towmap_finite_or_nan(P.min_vq);d.pwmint=P.min_t;d.pwmins=P.min_seg;d.pwminc=P.min_class;' sprintf('\n') ...
        '    d.pwmax=towmap_finite_or_nan(P.max_vq);d.pwmaxt=P.max_t;d.pwmaxs=P.max_seg;d.pwmaxc=P.max_class;' sprintf('\n') ...
        '    d.twc=T.count;d.twmin=towmap_finite_or_nan(T.min_vq);d.twmint=T.min_t;d.twmins=T.min_seg;d.twminc=T.min_class;' sprintf('\n') ...
        '    d.twmax=towmap_finite_or_nan(T.max_vq);d.twmaxt=T.max_t;d.twmaxs=T.max_seg;d.twmaxc=T.max_class;' sprintf('\n') ...
        '    if(G_towmap.size()>=512)G_towmap.erase(G_towmap.begin());' sprintf('\n') ...
        '    G_towmap.push_back(d);' sprintf('\n') ...
        '}' sprintf('\n') ...
        'static mxArray* towmap_matrix(){' sprintf('\n') ...
        '    const mwSize N=(mwSize)G_towmap.size(),C=46;' sprintf('\n') ...
        '    mxArray*M=mxCreateDoubleMatrix(N,C,mxREAL);double*p=mxGetPr(M);' sprintf('\n') ...
        '    for(mwSize i=0;i<N;++i){const auto&d=G_towmap[i];double v[C]={' sprintf('\n') ...
        '        d.seq,d.t0,d.tm,d.t1,d.limit,d.success,d.reason,d.family,d.envelope,d.VQ,d.VL,d.A,d.J,d.sigma,d.qdot,d.total_ms,' sprintf('\n') ...
        '        d.pc,d.ps,d.pr,d.pg,d.tc,d.ts,d.tr,d.tg,d.fc,d.fs,d.fr,d.fg,' sprintf('\n') ...
        '        d.pwc,d.pwmin,d.pwmint,d.pwmins,d.pwminc,d.pwmax,d.pwmaxt,d.pwmaxs,d.pwmaxc,' sprintf('\n') ...
        '        d.twc,d.twmin,d.twmint,d.twmins,d.twminc,d.twmax,d.twmaxt,d.twmaxs,d.twmaxc};' sprintf('\n') ...
        '        for(mwSize j=0;j<C;++j)p[i+N*j]=v[j];' sprintf('\n') ...
        '    }return M;' sprintf('\n') ...
        '}'];
    cppNew=replace_once(cppNew,anchor,ringBlock,'MEX ring globals');

    %% 4) Reset core witness immediately before each fixed-t1 plan call,
    % then append the result to the ring. Existing planner call is unchanged.
    old='            PlanResult Q=plan(R,L,B,O,t0,tm,searchEnd);';
    new=[ ...
        '            towmap_core_reset_witness();' sprintf('\n') ...
        old sprintf('\n') ...
        '            towmap_push(Q,L,t0,tm,searchEnd);'];
    cppNew=replace_once(cppNew,old,new,'op1 plan capture');

    %% 5) Add diagnostic-only MEX ops 6(read) and 7(clear).
    anchor='        if(op==3){';
    block=[ ...
        '        if(op==6){' sprintf('\n') ...
        '            if(nrhs!=1||nlhs!=1) mexErrMsgIdAndTxt("AF7TOWMAP:Arity","diag op: op -> matrix.");' sprintf('\n') ...
        '            plhs[0]=towmap_matrix();return;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '        if(op==7){' sprintf('\n') ...
        '            if(nrhs!=1||nlhs>1) mexErrMsgIdAndTxt("AF7TOWMAP:Arity","clear diag op: op.");' sprintf('\n') ...
        '            G_towmap.clear();G_towmap_seq=0;towmap_core_reset_witness();' sprintf('\n') ...
        '            if(nlhs>0)plhs[0]=logicalScalar(true);return;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        anchor];
    cppNew=replace_once(cppNew,anchor,block,'diagnostic ops');

    %% 6) Compatibility invariants.
    assert(contains(cppNew, ...
        'static const char* PLANNER_REV="AF7_REPLANNER_MIN_DEVIATION_V4_FIXED_T1";'), ...
        '[TOWMAP-R4C] planner_native_revision changed unexpectedly.');
    assert(contains(cppNew, ...
        'set("compact_constant_translation",logicalScalar(false));'), ...
        '[TOWMAP-R4C] compact build-contract flag changed unexpectedly.');
    assert(contains(cppNew,'TOWING_CONSTANT_TRANSLATION'), ...
        '[TOWMAP-R4C] towing family output disappeared.');

    %% 7) Stage compile before production write.
    stageDir=tempname;
    [ok,msg]=mkdir(stageDir);
    assert(ok,'[TOWMAP-R4C] Cannot create staging directory: %s',msg);
    stageCleanup=onCleanup(@()cleanup_stage(stageDir)); %#ok<NASGU>

    stagedHpp=fullfile(stageDir,'af7r36_core.hpp');
    stagedCpp=fullfile(stageDir,'af7r36_single_core_mex.cpp');
    write_text(stagedHpp,hppNew);
    write_text(stagedCpp,cppNew);

    fprintf('[TOWMAP-R4C] Compiling staged diagnostic MEX...\n');
    oldDir=pwd;
    cwdCleanup=onCleanup(@()cd(oldDir)); %#ok<NASGU>
    cd(stageDir);
    clear mex;
    mex('-R2018a','-O', ...
        'COMPFLAGS="$COMPFLAGS /std:c++17"', ...
        ['-I' stageDir], ...
        '-output','af7r36_single_core_mex', ...
        '-outdir',stageDir, ...
        stagedCpp);

    stagedMex=fullfile(stageDir,['af7r36_single_core_mex.' mexext]);
    assert(isfile(stagedMex),'[TOWMAP-R4C] Staged MEX binary missing.');

    % Temporary rollback copy only inside temp directory; never persisted.
    dstMex=fullfile(refDir,['af7r36_single_core_mex.' mexext]);
    oldMexTmp=fullfile(stageDir,['af7r36_single_core_mex_OLD.' mexext]);
    hadOldMex=isfile(dstMex);
    if hadOldMex
        [ok,msg]=copyfile(dstMex,oldMexTmp,'f');
        assert(ok,'[TOWMAP-R4C] Cannot stage old MEX rollback image: %s',msg);
    end

    cd(oldDir);
    clear mex;

    wroteH=false;wroteC=false;installedMex=false;
    try
        write_text(hpp,hppNew);wroteH=true;
        write_text(cpp,cppNew);wroteC=true;
        [ok,msg]=copyfile(stagedMex,dstMex,'f');
        assert(ok,'[TOWMAP-R4C] Cannot install staged MEX: %s',msg);
        installedMex=true;

        clear mex;
        rehash;
        assert(exist('af7r36_single_core_mex','file')==3, ...
            '[TOWMAP-R4C] Installed MEX not visible.');
        af7r36_single_core_mex(7);

    catch ME2
        if wroteH, try, write_text(hpp,hpp0); catch, end, end
        if wroteC, try, write_text(cpp,cpp0); catch, end, end
        if installedMex && hadOldMex
            try, copyfile(oldMexTmp,dstMex,'f'); catch, end
        end
        clear mex;rehash;
        rethrow(ME2);
    end

    fprintf('[TOWMAP-R4C] PASS.\n');
    fprintf('  existing &wmax Stage-B diagnostic kept    = 1\n');
    fprintf('  witness time/segment capture               = 1\n');
    fprintf('  fixed-t1 call ring capacity                = 512\n');
    fprintf('  trajectory generation modified             = 0\n');
    fprintf('  hard certificate semantics modified        = 0\n');
    fprintf('  planner build identity modified             = 0\n');
    fprintf('  README created                              = 0\n');
    fprintf('  persistent backup files created             = 0\n');
    fprintf('  NOTE: R4C timing is diagnostic, not production timing.\n');

    OUT=struct();
    OUT.pass=true;
    OUT.reference_dir=refDir;
    OUT.revision='AF7_TOWMAP_R4C';
    OUT.ring_capacity=512;
    OUT.trajectory_generation_modified=false;
    OUT.hard_certificate_semantics_modified=false;
    OUT.stageB_call_sites_modified=false;
    OUT.readme_created=false;
    OUT.persistent_backup_created=false;

catch ME
    clear mex;rehash;
    fprintf(2,'[TOWMAP-R4C] FAILED. No successful production install completed.\n');
    rethrow(ME);
end
end

function txt=replace_once_between(txt,startPat,endPat,old,new,label)
a=strfind(txt,startPat);
assert(numel(a)==1,'[TOWMAP-R4C] %s start count=%d; expected 1.',label,numel(a));
bAll=strfind(txt,endPat);
b=bAll(find(bAll>a,1,'first'));
assert(~isempty(b),'[TOWMAP-R4C] %s end anchor not found after start.',label);

chunk=txt(a:b-1);
h=strfind(chunk,old);
assert(numel(h)==1, ...
    '[TOWMAP-R4C] %s target count=%d inside stageB_speed; expected 1.',label,numel(h));

% Exact replacement inside the bounded function body. No insertion-index arithmetic.
chunk=[chunk(1:h-1) new chunk(h+numel(old):end)];
txt=[txt(1:a-1) chunk txt(b:end)];
end

function n=count_exact(txt,pat)
n=numel(strfind(txt,pat));
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1, ...
    '[TOWMAP-R4C] Anchor "%s" count=%d; expected exactly 1.',label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end

function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));
s=strrep(s,sprintf('\r'),sprintf('\n'));
end

function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');
assert(f>=0,'[TOWMAP-R4C] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end

function cleanup_stage(d)
if isfolder(d)
    try, rmdir(d,'s'); catch, end
end
end
