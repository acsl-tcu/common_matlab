function T=AF7R58R115_MEX_TEST(mexName)
% Execute REAL op27 compiled entry, in isolation. No hidden fallbacks.
if nargin<1, mexName='af7r36_single_core_mex'; end
assert(exist(mexName,'file')==3,'R115:MexNotFound', ...
    'An actual compiled MEX with op27 is required.');
C=zeros(3,1); Rot=reshape(eye(3),9,1);
A=[0.35;0.35;0.35]; D=[0.15;0.15;0.08]; ids=42;
[h,id,comp,margin]=feval(mexName,27,[3;0;1],[3;0;-1], ...
    C,Rot,A,D,ids,true);
assert(~h && isnan(id) && isnan(comp) && margin>0, ...
    'R115:SafeFail','Fully separated bodies were rejected.');
% Endpoints independently safe; the full cable crosses the ellipsoid.
[h,id,comp,margin]=feval(mexName,27,[-2;0;0],[2;0;0], ...
    C,Rot,A,D,ids,true);
assert(h && id==42 && comp==3 && margin<=0, ...
    'R115:CableFail','Crossing cable segment was not classified as CABLE.');
[h,id,comp]=feval(mexName,27,[2;0;0],[0;0;0], ...
    C,Rot,A,D,ids,true);
assert(h && id==42 && comp==1, ...
    'R115:PayloadFail','Payload sphere risk must be detected.');
[h,id,comp]=feval(mexName,27,[0;0;0],[2;0;0], ...
    C,Rot,A,D,ids,true);
assert(h && id==42 && comp==2, ...
    'R115:UAVFail','UAV sphere risk must be detected.');
[h,id,comp]=feval(mexName,27,[-2;0;0],[2;0;0], ...
    C,Rot,A,D,ids,false);
assert(~h && isnan(id) && isnan(comp), ...
    'R115:UnknownMaskFail','Unobserved obstacles must remain UNKNOWN.');
% Native current-EKF geometry accepts finite endpoints without fabricating
% a cable-direction unit vector, even if their estimated spacing differs.
[h,id,comp]=feval(mexName,27,[-3;0;0],[2;0;0], ...
    C,Rot,A,D,ids,true);
assert(h && id==42 && comp==3, ...
    'R115:MismatchFail','Long estimated endpoint separation should not suppress a cable warning.');
% Check exact source test is still reachable in this binary.
G=feval(mexName,26);
assert(isstruct(G) && strcmp(char(G.status), ...
    'PASS_R114_COMPILED_REAL_CORE_GEOMETRY'), ...
    'R115:R114Regression','R114 real native core regression failed.');
T=struct('status','PASS_R115_REAL_MEX_EKF_ENDPOINTS_AND_THREE_BODIES', ...
    'safe_pass',true,'cable_crossing_rejected',true, ...
    'payload_collision_rejected',true,'uav_collision_rejected',true, ...
    'unknown_mask_ignored',true,'length_mismatch_not_hidden',true, ...
    'r114_core_pass',true);
end
