function OUT = AF7R36_SELECTED_MOTION_AUDIT_R11_INSTALL()
% AF7R36_SELECTED_MOTION_AUDIT_R11_INSTALL
%
% Lightweight diagnostic to answer one question first:
%   "Is the selected trajectory actually moving inside [t0,t1]?"
%
% For each fixed-t1 production result, evaluate 65 deterministic diagnostic
% nodes and compare:
%   base reference            = ref.eval(t)
%   selected full reference   = candidate_eval(ref,Q.cand,t)
%   new correction            = full - base
%
% Records position extent, speed extent, correction extent, midpoint values,
% and moving-node count. This is diagnostic sampling only; it does NOT grant
% any safety or smoothness acceptance.
%
% The R10B per-call heading topology hook is disabled to remove unnecessary
% diagnostic work while motion authority is being checked.
%
% Production candidate selection and all safety/C7 certificates are unchanged.

fprintf('\n====================================================================================================\n');
fprintf(' AF7R36 SELECTED MOTION AUDIT R11 INSTALL\n');
fprintf(' production selection modified              = 0\n');
fprintf(' hard safety/C7 semantics modified           = 0\n');
fprintf(' R10B runtime heading hook disabled          = 1\n');
fprintf(' selected full/base/correction motion audit  = 1\n');
fprintf('====================================================================================================\n');

refDir=fileparts(which('af7r34_make_core_packet'));
assert(~isempty(refDir)&&isfolder(refDir), ...
    '[MOTION-R11] Cannot resolve current reference directory.');

hpp=fullfile(refDir,'af7r36_core.hpp');
cpp=fullfile(refDir,'af7r36_single_core_mex.cpp');
assert(isfile(hpp),'[MOTION-R11] Missing %s',hpp);
assert(isfile(cpp),'[MOTION-R11] Missing %s',cpp);

hpp0=normlf(fileread(hpp));
cpp0=normlf(fileread(cpp));
hppNew=hpp0;cppNew=cpp0;

assert(contains(cpp0,'headtopo10b_push(Q,R,t0,tm,searchEnd);'), ...
    '[MOTION-R11] Active R10B hook not found.');
assert(contains(cpp0,'phr9_push(Q,Q7,R,L,t0,tm,searchEnd);'), ...
    '[MOTION-R11] Current production diagnostic call site not found.');
assert(~contains(cpp0,'AF7_SELECTED_MOTION_AUDIT_R11_RING'), ...
    '[MOTION-R11] R11 already installed.');

try
    %% --------------------------------------------------------------------
    % 1) Add a self-contained wrapper motion ring.
    % ---------------------------------------------------------------------
    anchor='static bool G_compiled=false;';
    ring=[anchor sprintf('\n') sprintf('\n') ...
        '// AF7_SELECTED_MOTION_AUDIT_R11_RING -- sampled diagnostic only.' sprintf('\n') ...
        'struct MotionR11Row {' sprintf('\n') ...
        '    double seq=0,t0=NAN,tm=NAN,t1=NAN,ok=0,family=0;' sprintf('\n') ...
        '    double full3=0,fullxy=0,base3=0,corr3=0,end3=0;' sprintf('\n') ...
        '    double vmax=0,vxymax=0,vbase=0,vcorr=0,moving=0,env=NAN;' sprintf('\n') ...
        '    double p0x=NAN,p0y=NAN,p0z=NAN,pmx=NAN,pmy=NAN,pmz=NAN,p1x=NAN,p1y=NAN,p1z=NAN;' sprintf('\n') ...
        '    double cmx=NAN,cmy=NAN,cmz=NAN;' sprintf('\n') ...
        '};' sprintf('\n') ...
        'static std::vector<MotionR11Row> G_motion11;' sprintf('\n') ...
        'static double G_motion11_seq=0;' sprintf('\n') ...
        'static void motion11_push(const PlanResult&Q,const ActiveReference&R,double t0,double tm,double t1){' sprintf('\n') ...
        '    MotionR11Row d;d.seq=++G_motion11_seq;d.t0=t0;d.tm=tm;d.t1=t1;d.ok=Q.success?1:0;' sprintf('\n') ...
        '    if(Q.success){' sprintf('\n') ...
        '        d.family=Q.cand.family;d.env=Q.cand.max_ctrl;' sprintf('\n') ...
        '        const int N=65;auto F0=candidate_eval(R,Q.cand,t0);auto B0=R.eval(t0);Vec3 p0=F0[0];' sprintf('\n') ...
        '        d.p0x=p0.x;d.p0y=p0.y;d.p0z=p0.z;' sprintf('\n') ...
        '        for(int k=0;k<N;++k){' sprintf('\n') ...
        '            double u=double(k)/double(N-1),t=t0+(t1-t0)*u;auto F=candidate_eval(R,Q.cand,t);auto B=R.eval(t);' sprintf('\n') ...
        '            Vec3 df=F[0]-p0,db=B[0]-B0[0],dc=F[0]-B[0],dv=F[1]-B[1];' sprintf('\n') ...
        '            d.full3=std::max(d.full3,norm(df));d.fullxy=std::max(d.fullxy,std::hypot(df.x,df.y));' sprintf('\n') ...
        '            d.base3=std::max(d.base3,norm(db));d.corr3=std::max(d.corr3,norm(dc));' sprintf('\n') ...
        '            d.vmax=std::max(d.vmax,norm(F[1]));d.vxymax=std::max(d.vxymax,std::hypot(F[1].x,F[1].y));' sprintf('\n') ...
        '            d.vbase=std::max(d.vbase,norm(B[1]));d.vcorr=std::max(d.vcorr,norm(dv));' sprintf('\n') ...
        '            if(norm(F[1])>1e-9)++d.moving;' sprintf('\n') ...
        '            if(k==(N-1)/2){d.pmx=F[0].x;d.pmy=F[0].y;d.pmz=F[0].z;d.cmx=dc.x;d.cmy=dc.y;d.cmz=dc.z;}' sprintf('\n') ...
        '            if(k==N-1){d.p1x=F[0].x;d.p1y=F[0].y;d.p1z=F[0].z;d.end3=norm(F[0]-p0);}' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '    }' sprintf('\n') ...
        '    if(G_motion11.size()>=512)G_motion11.erase(G_motion11.begin());G_motion11.push_back(d);' sprintf('\n') ...
        '}' sprintf('\n') ...
        'static mxArray* motion11_matrix(){' sprintf('\n') ...
        '    const mwSize N=(mwSize)G_motion11.size(),C=29;mxArray*M=mxCreateDoubleMatrix(N,C,mxREAL);double*p=mxGetPr(M);' sprintf('\n') ...
        '    for(mwSize i=0;i<N;++i){const auto&d=G_motion11[i];double v[C]={' sprintf('\n') ...
        '        d.seq,d.t0,d.tm,d.t1,d.ok,d.family,d.full3,d.fullxy,d.base3,d.corr3,d.end3,' sprintf('\n') ...
        '        d.vmax,d.vxymax,d.vbase,d.vcorr,d.moving,d.env,' sprintf('\n') ...
        '        d.p0x,d.p0y,d.p0z,d.pmx,d.pmy,d.pmz,d.p1x,d.p1y,d.p1z,d.cmx,d.cmy,d.cmz};' sprintf('\n') ...
        '        for(mwSize j=0;j<C;++j)p[i+N*j]=v[j];}return M;' sprintf('\n') ...
        '}'];
    cppNew=replace_once(cppNew,anchor,ring,'R11 ring globals');

    %% --------------------------------------------------------------------
    % 2) Disable R10B runtime hook and add R11 sampled motion hook.
    % ---------------------------------------------------------------------
    cppNew=replace_once(cppNew, ...
        '            headtopo10b_push(Q,R,t0,tm,searchEnd);', ...
        ['            /* R11: R10B heading runtime hook disabled while motion authority is audited. */' sprintf('\n') ...
         '            motion11_push(Q,R,t0,tm,searchEnd);'], ...
        'replace R10B hook with R11 motion hook');

    %% --------------------------------------------------------------------
    % 3) op18 read / op19 clear.
    % ---------------------------------------------------------------------
    anchor='        if(op==3){';
    ops=[ ...
        '        if(op==18){' sprintf('\n') ...
        '            if(nrhs!=1||nlhs!=1)mexErrMsgIdAndTxt("AF7MOTION11:Arity","op18 -> matrix.");' sprintf('\n') ...
        '            plhs[0]=motion11_matrix();return;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        '        if(op==19){' sprintf('\n') ...
        '            if(nrhs!=1||nlhs>1)mexErrMsgIdAndTxt("AF7MOTION11:Arity","op19 clear.");' sprintf('\n') ...
        '            G_motion11.clear();G_motion11_seq=0;if(nlhs>0)plhs[0]=logicalScalar(true);return;' sprintf('\n') ...
        '        }' sprintf('\n') ...
        anchor];
    cppNew=replace_once(cppNew,anchor,ops,'R11 diagnostic ops');

    %% --------------------------------------------------------------------
    % 4) Audits.
    % ---------------------------------------------------------------------
    assert(count_exact(cppNew,'headtopo10b_push(Q,R,t0,tm,searchEnd);')==0, ...
        '[MOTION-R11] R10B runtime hook still active.');
    assert(count_exact(cppNew,'motion11_push(Q,R,t0,tm,searchEnd);')==1, ...
        '[MOTION-R11] R11 runtime hook count invalid.');
    assert(count_exact(cppNew,'AF7_SELECTED_MOTION_AUDIT_R11_RING')==1, ...
        '[MOTION-R11] R11 ring marker count invalid.');
    assert(contains(cppNew, ...
        'static const char* PLANNER_REV="AF7_REPLANNER_MIN_DEVIATION_V4_FIXED_T1";'), ...
        '[MOTION-R11] Planner identity changed unexpectedly.');

    %% --------------------------------------------------------------------
    % 5) Stage compile and atomic install.
    % ---------------------------------------------------------------------
    stageDir=tempname;
    [ok,msg]=mkdir(stageDir);
    assert(ok,'[MOTION-R11] Cannot create staging directory: %s',msg);
    stageCleanup=onCleanup(@()cleanup_stage(stageDir)); %#ok<NASGU>
    stagedHpp=fullfile(stageDir,'af7r36_core.hpp');
    stagedCpp=fullfile(stageDir,'af7r36_single_core_mex.cpp');
    write_text(stagedHpp,hppNew);write_text(stagedCpp,cppNew);

    fprintf('[MOTION-R11] Compiling staged diagnostic MEX...\n');
    oldDir=pwd;
    cwdCleanup=onCleanup(@()cd(oldDir)); %#ok<NASGU>
    cd(stageDir);clear mex;
    mex('-R2018a','-O', ...
        'COMPFLAGS="$COMPFLAGS /std:c++17"', ...
        ['-I' stageDir], ...
        '-output','af7r36_single_core_mex', ...
        '-outdir',stageDir, ...
        stagedCpp);
    stagedMex=fullfile(stageDir,['af7r36_single_core_mex.' mexext]);
    assert(isfile(stagedMex),'[MOTION-R11] Staged MEX missing.');

    dstMex=fullfile(refDir,['af7r36_single_core_mex.' mexext]);
    oldMexTmp=fullfile(stageDir,['af7r36_single_core_mex_OLD.' mexext]);
    hadOldMex=isfile(dstMex);
    if hadOldMex
        [ok,msg]=copyfile(dstMex,oldMexTmp,'f');
        assert(ok,'[MOTION-R11] Cannot stage rollback MEX: %s',msg);
    end

    cd(oldDir);clear mex;
    wroteC=false;installedMex=false;
    try
        % hpp is unchanged by R11.
        write_text(cpp,cppNew);wroteC=true;
        [ok,msg]=copyfile(stagedMex,dstMex,'f');
        assert(ok,'[MOTION-R11] Cannot install staged MEX: %s',msg);
        installedMex=true;
        clear mex;rehash;
        assert(exist('af7r36_single_core_mex','file')==3, ...
            '[MOTION-R11] Installed MEX not visible.');
        try,af7r36_single_core_mex(7);catch,end
        try,af7r36_single_core_mex(11);catch,end
        try,af7r36_single_core_mex(13);catch,end
        try,af7r36_single_core_mex(15);catch,end
        try,af7r36_single_core_mex(17);catch,end
        af7r36_single_core_mex(19);
    catch ME2
        if wroteC,try,write_text(cpp,cpp0);catch,end,end
        if installedMex&&hadOldMex,try,copyfile(oldMexTmp,dstMex,'f');catch,end,end
        clear mex;rehash;rethrow(ME2);
    end

    fprintf('[MOTION-R11] PASS.\n');
    fprintf('  production selection unchanged             = 1\n');
    fprintf('  safety/C7 semantics unchanged              = 1\n');
    fprintf('  R10B runtime hook active                   = 0\n');
    fprintf('  R11 65-node motion audit active            = 1\n');
    fprintf('  NOTE: sampled motion data is diagnostic only.\n');

    OUT=struct('pass',true, ...
        'revision','AF7_SELECTED_MOTION_AUDIT_R11', ...
        'production_selection_modified',false, ...
        'hard_safety_modified',false, ...
        'C7_modified',false, ...
        'R10B_runtime_hook_active',false);
catch ME
    clear mex;rehash;
    fprintf(2,'[MOTION-R11] FAILED. No successful production install completed.\n');
    rethrow(ME);
end
end

function txt=replace_once(txt,old,new,label)
h=strfind(txt,old);
assert(numel(h)==1, ...
    '[MOTION-R11] Anchor "%s" count=%d; expected 1.',label,numel(h));
txt=[txt(1:h-1) new txt(h+numel(old):end)];
end
function n=count_exact(txt,pat),n=numel(strfind(txt,pat));end
function s=normlf(s)
s=strrep(s,sprintf('\r\n'),sprintf('\n'));s=strrep(s,sprintf('\r'),sprintf('\n'));
end
function write_text(path,txt)
f=fopen(path,'wt','n','UTF-8');assert(f>=0,'[MOTION-R11] Cannot open %s.',path);
c=onCleanup(@()fclose(f)); %#ok<NASGU>
fwrite(f,txt,'char');
end
function cleanup_stage(d)
if isfolder(d),try,rmdir(d,'s');catch,end,end
end
