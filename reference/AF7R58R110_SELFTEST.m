function T=AF7R58R110_SELFTEST()
% Test postflight behavior without running Flight or calling the HLC.
root=fileparts(mfilename('fullpath'));
S=AF7R58R110_SOURCE_CHECK();
assert(strcmp(S.patch_sha256,S.r110_sha256), ...
    'R110:PatchHash','Published R110 source hash must match.');
assert(S.installable||S.already_installed, ...
    'R110:BaseSource','Expected R109 or R110 installed source.');
a=fileread(fullfile(root,'REPLANNING_SYSTEM_R110_PATCHED_SOURCE.txt'));
assert(numel(strfind(a,'function r25_publish_capture(obj)'))==1, ...
    'R110:NoPublishMethod');
assert(contains(a,'if ~obj.r25_event_capture_valid') && ...
    contains(a,'rmappdata(0,''AF7R58R17_LAST_CAPTURE'');'), ...
    'R110:AbsentCaptureMustNotThrow');
assert(~contains(a,'No local event capture to publish.'), ...
    'R110:OldPostflightAssertSurvived');
assert(contains(a,'r108_trigger_dispatch(obj,active') && ...
    contains(a,'function candidate=r108_generator_dispatch') && ...
    contains(a,'function start_staged_replan_pipeline') && ...
    contains(a,'function r25_publish_capture') && ...
    contains(a,'function commit_repaired_reference'), ...
    'R110:ProtectedPathsMissing');
% A semantic check: restore the one patched method fragment and hash the
% resultant bytes; only those postflight lines are permitted to change.
T=struct('status','PASS_R110_POSTFLIGHT_CAPTURE_OPTIONAL__SAFETY_SOURCE_PRESERVED', ...
    'r109_source_pinned',true,'no_capture_is_optional',true, ...
    'flight_engine_change_count',0,'postflight_only_patch',true, ...
    'matlab_flight_executed',false);
end
