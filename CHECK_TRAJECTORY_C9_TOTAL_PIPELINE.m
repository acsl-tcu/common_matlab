function R=CHECK_TRAJECTORY_C9_TOTAL_PIPELINE()
% Test shared joint-proof -> corridor -> ray -> independent final joint.
% Only synthetic fixture parameters below; no defaults installed in flight.
% The HANDOFF_TRAJECTORY.txt is NOT required or read.
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'reference','REPLANNING_SYSTEM');
addpath(fullfile(base,'TRAJECTORY_GENERATION'), ...
    fullfile(base,'OBSTACLE_INFORMATION'));
A=struct('cable_length_m',2,'uav_mass_kg',1.5, ...
    'payload_mass_kg',1,'gravity_world_mps2',[0;0;-9.80665], ...
    'thrust_limits_N',[0;100],'minimum_tension_N',0, ...
    'acceleration_guard_mps2',1e-10);
r=struct('uav_m',0.02,'payload_m',0.02,'cable_m',0.005);
go=struct('robust_tube_enabled',false,'max_subdivision_depth',4, ...
    'max_node_count',63,'numerical_guard_m',1e-10);
fo=struct('max_subdivision_depth',4,'max_node_count',63, ...
    'force_guard_N',1e-10);
co=struct('min_separation_m',1e-6, ...
    'max_normal_iterations',20,'max_ray_iterations',12);
% Degree-elevated nonstraight load path x=t+0.1*t^3, z=4.
% Hovering UAV is at z=6, so body+load+straight cable all clear ground.
P=zeros(3,24);P(3,:)=4;
for k=0:23
    P(1,k+1)=k/23+0.1*k*(k-1)*(k-2)/(23*22*21);
end
start=zeros(3,10);start(3,1)=4;start(1,2)=1;start(1,4)=0.6;
finish=start;finish(1,1)=1.1;finish(1,2)=1.3;finish(1,3)=0.6;
X=TRAJECTORY_C9_FLAT_BERNSTEIN.build(0,1,start,finish,P(:,11:14));
assert(max(abs(X.control_points_m(:)-P(:)))<1e-9, ...
    'CHECK_C9_TOTAL:Piece','Incorrect synthetic C9 fixture.');
V=[0 0 0;1 0 0;0 1 0;0 0 1];
F=[1 3 2;1 2 4;1 4 3;2 3 4];
items={ ...
    OBSTACLE_INFORMATION.define(1,'sphere',[0 6 0],0.3), ...
    OBSTACLE_INFORMATION.define(2,'ellipsoid',[0 6 0],[.5 1 2], ...
       'euler_deg',[20 40 50]), ...
    OBSTACLE_INFORMATION.define(3,'box',[0 6 0],[1 .6 2], ...
       'euler_deg',[5 25 40]), ...
    OBSTACLE_INFORMATION.define(4,'cylinder',[0 6 0],[.5 2], ...
       'euler_deg',[20 20 15]), ...
    OBSTACLE_INFORMATION.define(5,'capsule',[0 6 0],[.3 1]), ...
    OBSTACLE_INFORMATION.define(6,'cone',[0 6 0],[.5 2], ...
       'euler_deg',[10 20 30]), ...
    OBSTACLE_INFORMATION.define(7,'frustum',[0 6 0],[.8 .3 1]), ...
    OBSTACLE_INFORMATION.define(8,'pyramid',[0 6 0],[1 2]), ...
    OBSTACLE_INFORMATION.define(9,'regular_prism',[0 6 0],[6 .7 1]), ...
    OBSTACLE_INFORMATION.define(10,'torus',[0 6 0],[1 .2]), ...
    OBSTACLE_INFORMATION.define(11,'polygon_prism',[0 6 0], ...
       struct('outline',[-1 -1;1 -1;1 1;-1 1],'height',2)), ...
    OBSTACLE_INFORMATION.define(12,'polyhedron',[0 6 0], ...
       struct('vertices',V,'faces',F))};
obs=[items{:}];
prepared=TRAJECTORY_OBSTACLE_SUPPORT.prepare(obs);
center=mean(X.control_points_m,2);ey=[0;1;0];
for j=1:numel(obs)
    neg_extent=TRAJECTORY_OBSTACLE_SUPPORT.value(prepared(j),-ey)+ ...
        prepared(j).center.'*ey;
    obs(j).position=center+[0;neg_extent+0.6;0];
end
obs24=obs;
for j=1:numel(obs24)
    obs24(j).id=obs24(j).id+100;
    obs24(j).position(1)=obs24(j).position(1)+0.02;
end
obs24=[obs obs24];
G=TRAJECTORY_GENERATOR(struct('ROBUST_TUBE_ENABLED',false));
target=X.control_points_m(:,11:14);
target(2,:)=target(2,:)+0.005;
% Test the entire pipeline, not just the final geometric gate.
Z12=G.refine_c9_certified_guide_fast(X,target,obs,r,A,go,fo,co);
Z24=G.refine_c9_certified_guide_fast(X,target,obs24,r,A,go,fo,co);
fullpass=Z12.candidate_available&&Z24.candidate_available&& ...
    ~Z12.safe_to_commit&&~Z24.safe_to_commit&& ...
    Z12.corridor.certified&&Z24.corridor.certified&& ...
    Z12.candidate.fullbody_certificate.certified&& ...
    Z24.candidate.fullbody_certificate.certified&& ...
    isequal(Z24.candidate.fullbody_certificate.considered_obstacle_ids, ...
      [obs24.id])&& ...
    Z24.corridor.shape_support_calls>=72;
if ~fullpass
    % Preserve detailed evidence BEFORE a test failure. No TXT dependency.
    R=struct('status','FAIL_C9_SHARED_PROOF_OR_CORRIDOR_OR_RAY', ...
        'near12_status',Z12.status,'near24_status',Z24.status, ...
        'near12_guide_proof_status',Z12.guide_proof_status, ...
        'near24_guide_proof_status',Z24.guide_proof_status, ...
        'near12_corridor_status',getstatus(Z12.corridor), ...
        'near24_corridor_status',getstatus(Z24.corridor), ...
        'near12_candidate_status',Z12.candidate_status, ...
        'near24_candidate_status',Z24.candidate_status, ...
        'near12_candidate_available',Z12.candidate_available, ...
        'near24_candidate_available',Z24.candidate_available, ...
        'near12_failed_obstacle_id',getfield_or(Z12.corridor,'failed_obstacle_id'), ...
        'near24_failed_obstacle_id',getfield_or(Z24.corridor,'failed_obstacle_id'), ...
        'near12_failed_body_id',getfield_or(Z12.corridor,'failed_body_id'), ...
        'near24_failed_body_id',getfield_or(Z24.corridor,'failed_body_id'), ...
        'near12_refinement_iterations',getfield_or(Z12.corridor,'plane_refinement_count'), ...
        'near24_refinement_iterations',getfield_or(Z24.corridor,'plane_refinement_count'), ...
        'near12_corridor_ms',Z12.corridor_ms, ...
        'near24_corridor_ms',Z24.corridor_ms, ...
        'near12_total_ms',Z12.total_ms, ...
        'near24_total_ms',Z24.total_ms, ...
        'safe_to_commit',false);
    save(fullfile(root,'TRAJECTORY_C9_TOTAL_PIPELINE_RESULT.mat'),'R');
    fp=fullfile(root,'TRAJECTORY_C9_TOTAL_PIPELINE_RESULT.txt');
    fid=fopen(fp,'w');
    if fid>0
        fprintf(fid,'%s\n',R.status);
        fprintf(fid,'12 guide/corridor/candidate: %s / %s / %s\n', ...
            R.near12_guide_proof_status,R.near12_corridor_status,R.near12_candidate_status);
        fprintf(fid,'24 guide/corridor/candidate: %s / %s / %s\n', ...
            R.near24_guide_proof_status,R.near24_corridor_status,R.near24_candidate_status);
        fprintf(fid,'failed obstacle IDs 12/24: %.0f / %.0f\n', ...
            R.near12_failed_obstacle_id,R.near24_failed_obstacle_id);
        fprintf(fid,'failed body IDs 12/24: %.0f / %.0f\n', ...
            R.near12_failed_body_id,R.near24_failed_body_id);
        fclose(fid);
        zip(fullfile(root,'TRAJECTORY_C9_TOTAL_PIPELINE_FOR_CHATGPT.zip'), ...
           {'TRAJECTORY_C9_TOTAL_PIPELINE_RESULT.mat', ...
            'TRAJECTORY_C9_TOTAL_PIPELINE_RESULT.txt'},root);
    end
    return
end
% Counterexample for a single centroid normal: a very tall but thin
% box is safely separated laterally from the whole cable. The UAV/cable
% centroid normal points partly along the long z dimension and can fail.
% The shape-support fallback MUST recover a valid non-world-fixed plane.
tall=OBSTACLE_INFORMATION.define(950,'box', ...
    (center+[0;0.7;0]).',[1 0.2 20]);
ZT=G.refine_c9_certified_guide_fast(X,target,tall,r,A,go,fo,co);
assert(ZT.candidate_available&&ZT.corridor.certified&& ...
    ZT.candidate.fullbody_certificate.certified&&~ZT.safe_to_commit, ...
    'CHECK_C9_TOTAL:Tall','Thin/tall obstacle needs a support-normal fallback.');
% Environment ground is ALWAYS known even with zero sensor obstacles.
ground=GROUND_INFORMATION.definition();
assert(strcmp(ground.type,'ground_halfspace')&&ground.height_m==0&& ...
    isequal(ground.normal_world,[0;0;1]), ...
    'CHECK_C9_TOTAL:GroundDefinition','Ground definition missing.');
assert(numel(OBSTACLE_INFORMATION.definitions())==3, ...
    'CHECK_C9_TOTAL:GroundSensor','Ground must not be an artificial finite sensor obstacle.');
noobs=obs([]);
Jabove=TRAJECTORY_C9_JOINT_FAST_CERTIFICATE( ...
    X,noobs,r,A,go,fo);
assert(Jabove.certified&&Jabove.ground_checked&& ...
    Jabove.ground_minimum_clearance_lower_bound_m>0, ...
    'CHECK_C9_TOTAL:AboveGround','Safe positive-altitude candidate rejected.');
% Shift the exact same C9 curve downward without changing its dynamics.
% At z=0.01 payload centre, 0.02 m payload sphere intersects z=0.
Pbelow=P;Pbelow(3,:)=0.01;
sbelow=start;sbelow(3,1)=0.01;
ebelow=finish;ebelow(3,1)=0.01;
Xbelow=TRAJECTORY_C9_FLAT_BERNSTEIN.build( ...
    0,1,sbelow,ebelow,Pbelow(:,11:14));
Jbelow=TRAJECTORY_C9_JOINT_FAST_CERTIFICATE( ...
    Xbelow,noobs,r,A,go,fo);
assert(~Jbelow.certified&&Jbelow.ground_checked, ...
    'CHECK_C9_TOTAL:GroundContact','Ground contact must be rejected even without obstacles.');
% Older geometric C7-candidate certificate must independently enforce the
% SAME ground, without trusting the C9-specific force certificate.
segmentAbove=struct('uav',struct('control_points_m',P+[0;0;2], ...
    't0_s',0,'duration_s',1), ...
    'payload',struct('control_points_m',P,'t0_s',0,'duration_s',1));
C7above=TRAJECTORY_CONTINUOUS_GEOMETRY_CERTIFICATE( ...
    segmentAbove,noobs,r,go);
segmentBelow=struct('uav',struct('control_points_m', ...
    Pbelow+[0;0;2],'t0_s',0,'duration_s',1), ...
    'payload',struct('control_points_m',Pbelow,'t0_s',0,'duration_s',1));
C7below=TRAJECTORY_CONTINUOUS_GEOMETRY_CERTIFICATE( ...
    segmentBelow,noobs,r,go);
assert(C7above.certified&&C7above.ground_certified&& ...
    ~C7below.certified&&~C7below.ground_certified, ...
    'CHECK_C9_TOTAL:C7Ground','Ground must also gate legacy C7 geometry.');
% End-to-end refinement must reject a guide below ground even without any
% finite obstacle input, and never grant a safe-to-commit flag.
Zbelow=G.refine_c9_certified_guide_fast( ...
    Xbelow,Xbelow.control_points_m(:,11:14),noobs,r,A,go,fo,co);
assert(~Zbelow.candidate_available&&~Zbelow.safe_to_commit, ...
    'CHECK_C9_TOTAL:EndToEndGround', ...
    'Unsafe below-ground guide unexpectedly entered the corridor.');
% A thick taut cable can hit the ground even when both endpoint spheres
% still have clearance. A cable is a capsule: a line segment + its radius.
Xlow=TRAJECTORY_C9_FLAT_BERNSTEIN.build( ...
    0,1,set_z(start,0.3),set_z(finish,0.3),set_z(P(:,11:14),0.3));
rCable=r;rCable.cable_m=0.4;
Jcable=TRAJECTORY_C9_JOINT_FAST_CERTIFICATE( ...
    Xlow,noobs,rCable,A,go,fo);
assert(~Jcable.certified, ...
    'CHECK_C9_TOTAL:GroundCable','The full cable radius must be included.');
% A large external tracking tube must also reduce ground clearance.
Gt=go;Gt.robust_tube_enabled=true;
Gt.uncertainty_bounds_m=struct('uav_m',0,'payload_m',0.4,'cable_m',0);
JgroundTube=TRAJECTORY_C9_JOINT_FAST_CERTIFICATE( ...
    Xlow,noobs,r,A,Gt,fo);
assert(~JgroundTube.certified, ...
    'CHECK_C9_TOTAL:GroundTube','Ground tracking tube was ignored.');
% Different obstacle ID order cannot alter validity.
ZR=G.refine_c9_certified_guide_fast( ...
    X,target,obs(end:-1:1),r,A,go,fo,co);
assert(ZR.candidate_available&&ZR.candidate.fullbody_certificate.certified, ...
    'CHECK_C9_TOTAL:Order','Order-invariant safety failed.');
% Obstacle at taut cable centre MUST prevent creating a corridor.
collider=OBSTACLE_INFORMATION.define(701,'sphere',[0.5 0 5],.15);
Zbad=G.refine_c9_certified_guide_fast( ...
    X,target,[obs collider],r,A,go,fo,co);
assert(~Zbad.candidate_available&&~Zbad.safe_to_commit, ...
    'CHECK_C9_TOTAL:Collision','Unsafe guide unexpectedly approved.');
% Safety authority must not be silently relaxed. Strong tube can only
% reject or retain a result, never approve a newly unsafe trajectory.
rob=go;rob.robust_tube_enabled=true;
rob.uncertainty_bounds_m=struct('uav_m',0.8, ...
    'payload_m',0.8,'cable_m',0.8);
GT=TRAJECTORY_GENERATOR(struct('ROBUST_TUBE_ENABLED',true));
Ztube=GT.refine_c9_certified_guide_fast(X,target,obs,r,A,rob,fo,co);
assert(~Ztube.candidate_available&&~Ztube.safe_to_commit, ...
    'CHECK_C9_TOTAL:Tube','Large tracking tube was not rejected.');
% Timings are NOT claimed WCET. Measure actual end-to-end, including the
% certificate, corridor construction, ray and independent final proof.
G.refine_c9_certified_guide_fast(X,target,obs,r,A,go,fo,co);
N=8;times12=zeros(1,N);times24=zeros(1,N);cc=zeros(1,N);
for i=1:N
    u=G.refine_c9_certified_guide_fast(X,target,obs,r,A,go,fo,co);
    v=G.refine_c9_certified_guide_fast(X,target,obs24,r,A,go,fo,co);
    assert(u.candidate_available&&v.candidate_available, ...
        'CHECK_C9_TOTAL:Repeat','Repeated pipeline result changed.');
    times12(i)=u.total_ms;times24(i)=v.total_ms;
    cc(i)=u.corridor_ms;
end
% Old implementation comparison: geometry-only corridor construction
% has a different force scope. Do not compare force guarantees as equal.
old=TRAJECTORY_C9_TAUT_COUPLED_CORRIDOR(X,obs,r,A,go,co);
old_ms=old.elapsed_ms;
R=struct('status','PASS_C9_SHARED_PROOF_CORRIDOR_AND_RAY__HLC_PENDING', ...
    'near12_median_total_ms',median(times12), ...
    'near24_median_total_ms',median(times24), ...
    'near12_max_total_ms',max(times12), ...
    'near24_max_total_ms',max(times24), ...
    'near12_median_corridor_ms',median(cc), ...
    'near12_first_joint_proof_ms',Z12.guide_joint_proof_ms, ...
    'near12_first_final_proof_ms',Z12.final_independent_joint_ms, ...
    'baseline_old_corridor_ms',old_ms, ...
    'baseline_old_corridor_status',old.status, ...
    'near12_ray_fraction',Z12.ray_fraction, ...
    'near24_ray_fraction',Z24.ray_fraction, ...
    'near12_samples_ms',times12,'near24_samples_ms',times24, ...
    'real_HLC_model_certified',false, ...
    'torque_certified',false,'collision_start_auto_guide',false, ...
    'safe_to_commit',false, ...
    'ground_certified',Jabove.certified, ...
    'below_ground_rejected',~Jbelow.certified, ...
    'ground_cable_rejected',~Jcable.certified, ...
    'ground_tube_rejected',~JgroundTube.certified, ...
    'C7_ground_rejected',~C7below.certified, ...
    'pipeline_ground_rejected',~Zbelow.candidate_available);
save(fullfile(root,'TRAJECTORY_C9_TOTAL_PIPELINE_RESULT.mat'),'R');
fp=fullfile(root,'TRAJECTORY_C9_TOTAL_PIPELINE_RESULT.txt');
fid=fopen(fp,'w');
assert(fid>0,'CHECK_C9_TOTAL:Output','Cannot open audit result.');
cl=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\n',R.status);
fprintf(fid,'near12 median/max total ms = %.5f / %.5f\n', ...
    R.near12_median_total_ms,R.near12_max_total_ms);
fprintf(fid,'near24 median/max total ms = %.5f / %.5f\n', ...
    R.near24_median_total_ms,R.near24_max_total_ms);
fprintf(fid,'near12 median corridor ms = %.5f\n', ...
    R.near12_median_corridor_ms);
fprintf(fid,'old corridor ms = %.5f (%s)\n', ...
    old_ms,old.status);
fprintf(fid,'ground z=0 above/contact/cable/tube/C7/pipeline = %d/%d/%d/%d/%d/%d\n', ...
    R.ground_certified,R.below_ground_rejected, ...
    R.ground_cable_rejected,R.ground_tube_rejected, ...
    R.C7_ground_rejected,R.pipeline_ground_rejected);
fprintf(fid,'ray fraction 12/24 = %.8f / %.8f\n', ...
    R.near12_ray_fraction,R.near24_ray_fraction);
fprintf(fid,'HLC torque/tracking = NOT_CERTIFIED; arbitrary collision-start guide=NOT_IMPLEMENTED\n');
clear cl
zip(fullfile(root,'TRAJECTORY_C9_TOTAL_PIPELINE_FOR_CHATGPT.zip'), ...
    {'TRAJECTORY_C9_TOTAL_PIPELINE_RESULT.mat', ...
     'TRAJECTORY_C9_TOTAL_PIPELINE_RESULT.txt'},root);
end

function s=getstatus(x)
s='UNKNOWN_NOT_RETURNED';
if isstruct(x)&&isfield(x,'status'),s=x.status;end
end

function v=getfield_or(x,name)
v=NaN;
if isstruct(x)&&isfield(x,name),v=x.(name);end
end

function X=set_z(X,z)
% Set only zeroth load-height jet or all free Bernstein controls.
if size(X,2)==10,X(3,1)=z;else,X(3,:)=z;end
end
