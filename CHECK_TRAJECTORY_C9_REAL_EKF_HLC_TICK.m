function R=CHECK_TRAJECTORY_C9_REAL_EKF_HLC_TICK(logger)
%CHECK_TRAJECTORY_C9_REAL_EKF_HLC_TICK
% Source-verified HLC limit binding, ideal taut start consistency, and
% actual-HLC-result *API* audits with ADVERSARIAL FIXTURE states/results.
% There is NO claim that this check operated a real Flight tick, nor that
% sampled inputs establish continuous-time torque/tracking safety.
% Stores MAT/TXT/ZIP in common_matlab regardless of pwd, including failures.
root=fileparts(mfilename('fullpath'));
assert(isfile(fullfile(root,'run_flight_headless.m')), ...
    'CHECK_C9_REAL_TICK:Root', ...
    'Place this CHECK at common_matlab, not inside reference/REPLANNING_SYSTEM.');
addpath(root,'-begin');
addpath(fullfile(root,'controller'),'-begin');
addpath(fullfile(root,'model'),'-begin');
addpath(fullfile(root,'reference','REPLANNING_SYSTEM', ...
    'TRAJECTORY_GENERATION'),'-begin');
base='TRAJECTORY_C9_REAL_EKF_HLC_TICK_RESULT';
R=struct('status','FAIL_NOT_EXECUTED','error_identifier','', ...
    'error_message','','real_HLC_source','', ...
    'source_lower',NaN(4,1),'source_upper',NaN(4,1), ...
    'live_EKF_join_fixture_pass',false, ...
    'wrong_EKF_position_rejected',false, ...
    'stale_EKF_mass_rejected',false, ...
    'production_entry_rejects_mismatched_start',false, ...
    'production_entry_rejects_missing_start_tolerances',false, ...
    'real_HLC_result_fixture_pass',false, ...
    'yaw_branch_lift_allowed',false, ...
    'preclamp_saturation_detected',false, ...
    'HLC_clamp_corruption_detected',false, ...
    'reference_corruption_detected',false, ...
    'internal_yaw_corruption_detected',false, ...
    'recorded_flight_fixture_pass',false, ...
    'recorded_flight_saturation_detected',false, ...
    'recorded_flight_plan_corruption_detected',false, ...
    'recorded_mass_updates_preserved',false, ...
    'actual_saved_flight_log_examined',false, ...
    'saved_flight_trace',struct(), ...
    'reference_non_yaw_channel_corruption_detected',false, ...
    'higher_order_C7_join_certified',false, ...
    'actual_Flight_HLC_tracking_certified',false, ...
    'actual_Flight_torque_continuous_certified',false, ...
    'fixture_only',true,'safe_to_commit',false);
try
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    P.set("loadmass",0.14);
    P.set("cableL",2.0);
    gains=struct('dt',0.025,'F1',zeros(1,2), ...
        'F2',zeros(1,6),'F3',zeros(1,6),'F4',zeros(1,2));
    hc=HLC_SUSPENDED_LOAD([],gains);
    ref28=zeros(28,1);
    loadp=[0;0;3];vL=[0.4;0;0];
    L=double(P.get("cableL"));
    ekf=struct('mL',0.14,'p',loadp+[0;0;L], ...
        'v',vL,'pL',loadp,'vL',vL,'pT',[0;0;-1]);
    agent=struct('cha','f','controller',struct('hlc_suspended',hc), ...
        'parameter',P,'estimator',struct('result',struct('state',ekf)), ...
        'reference',struct('result',struct('state',struct('xd',ref28))));
    time=struct('t',5,'dt',0.025);
    ext=struct('gravity_world_mps2',[0;0;-double(P.get("gravity"))], ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0);
    B=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.bind(agent,ext);
    R.real_HLC_source=B.source_file;
    R.source_lower=B.input_lower;R.source_upper=B.input_upper;
    left=zeros(3,10);left(:,1)=loadp;left(:,2)=vL;
    piece=TRAJECTORY_C9_FLAT_BERNSTEIN.build(5,3,left,left, ...
        repmat(loadp,1,4));
    tols=struct('uav_position_m',1e-10,'uav_velocity_mps',1e-10, ...
        'payload_position_m',1e-10,'payload_velocity_mps',1e-10, ...
        'cable_direction_unitless',1e-10,'cable_length_m',1e-10);
    J=TRAJECTORY_C9_LIVE_EKF_JOIN_GATE(piece,B,agent,time,tols);
    R.live_EKF_join_fixture_pass=J.necessary_start_pass&&~J.safe_to_commit&& ...
        ~J.full_C7_join_proven;
    agent.estimator.result.state.p(1)=1;
    Jbad=TRAJECTORY_C9_LIVE_EKF_JOIN_GATE(piece,B,agent,time,tols);
    R.wrong_EKF_position_rejected=~Jbad.necessary_start_pass&& ...
        strcmp(Jbad.status,'REJECT_C9_START_NOT_CURRENT_EKF_STATE');
    agent.estimator.result.state.p(1)=0;
    agent.estimator.result.state.mL=0.19;
    Jmass=TRAJECTORY_C9_LIVE_EKF_JOIN_GATE(piece,B,agent,time,tols);
    R.stale_EKF_mass_rejected=~Jmass.necessary_start_pass&& ...
        strcmp(Jmass.status,'UNKNOWN_EKF_HLC_MASS_MISMATCH');
    agent.estimator.result.state.mL=0.14;
    % The REAL search entry must reject a start mismatch BEFORE any QP or
    % obstacle proof. We intentionally omit search-specific fields, so
    % passing this test proves no planner was invoked on a rejected start.
    req=struct('t0_s',time.t,'duration_s',3, ...
        'start_jets',left,'end_jets',left, ...
        'nominal_free',repmat(loadp,1,4), ...
        'ekf_start_join_tolerances',tols);
    agent.estimator.result.state.p(1)=1;
    [X,~]=TRAJECTORY_C9_SEARCH_WITH_LIVE_AUTHORITY(req,B,time,agent);
    R.production_entry_rejects_mismatched_start= ...
        strcmp(X.status,'REJECT_C9_START_NOT_CURRENT_EKF_STATE')&& ...
        ~X.start_join_necessary_pass&&~X.candidate_available;
    agent.estimator.result.state.p(1)=0;
    req=rmfield(req,'ekf_start_join_tolerances');
    [Y,~]=TRAJECTORY_C9_SEARCH_WITH_LIVE_AUTHORITY(req,B,time,agent);
    R.production_entry_rejects_missing_start_tolerances= ...
        strcmp(Y.status,'UNKNOWN_REQUIRED_LIVE_EKF_JOIN_TOLERANCES_MISSING')&& ...
        ~Y.candidate_available;
    raw=0.5*(B.input_lower+B.input_upper);
    hc.result=struct('tmp',raw,'input',max(B.input_lower, ...
        min(B.input_upper,raw)),'xd',ref28);
    H=TRAJECTORY_C9_HLC_LIVE_ACTUATOR_TICK( ...
        B,agent,time,ref28,zeros(28,1));
    hc.result.xd(4)=ref28(4)+2*pi;
    Hbranch=TRAJECTORY_C9_HLC_LIVE_ACTUATOR_TICK( ...
        B,agent,time,ref28,zeros(28,1));
    R.yaw_branch_lift_allowed=Hbranch.sample_checked&& ...
        strcmp(Hbranch.status,H.status);
    hc.result.xd=ref28;
    hc.result.xd(4)=ref28(4)+0.25;
    Hyaw=TRAJECTORY_C9_HLC_LIVE_ACTUATOR_TICK( ...
        B,agent,time,ref28,zeros(28,1));
    R.internal_yaw_corruption_detected=~Hyaw.sample_checked&& ...
        strcmp(Hyaw.status,'REJECT_HLC_INTERNAL_YAW_NOT_EQUIVALENT');
    hc.result.xd=ref28;
    R.real_HLC_result_fixture_pass=H.sample_checked&&~H.saturated&& ...
        H.reference_match&&H.hlc_clamp_consistent&&~H.safe_to_commit;
    raw_over=raw;raw_over(1)=B.input_upper(1)+1;
    hc.result.tmp=raw_over;
    hc.result.input=max(B.input_lower,min(B.input_upper,raw_over));
    Hsat=TRAJECTORY_C9_HLC_LIVE_ACTUATOR_TICK( ...
        B,agent,time,ref28,zeros(28,1));
    R.preclamp_saturation_detected=Hsat.saturated&& ...
        ~Hsat.raw_input_feasible&&Hsat.hlc_clamp_consistent&& ...
        strcmp(Hsat.status,'REJECT_REAL_HLC_PRECLAMP_ACTUATOR_SATURATION');
    hc.result.input(1)=hc.result.input(1)-1;
    Hcor=TRAJECTORY_C9_HLC_LIVE_ACTUATOR_TICK( ...
        B,agent,time,ref28,zeros(28,1));
    R.HLC_clamp_corruption_detected=~Hcor.hlc_clamp_consistent&& ...
        strcmp(Hcor.status,'REJECT_ACTUAL_HLC_CLAMP_MISMATCH');
    hc.result.tmp=raw;
    hc.result.input=max(B.input_lower,min(B.input_upper,raw));
    agent.reference.result.state.xd(2)=0.1;
    Href=TRAJECTORY_C9_HLC_LIVE_ACTUATOR_TICK( ...
        B,agent,time,ref28,zeros(28,1));
    R.reference_corruption_detected=~Href.reference_match&& ...
        strcmp(Href.status,'REJECT_ACTUAL_HLC_REFERENCE_MISMATCH');
    agent.reference.result.state.xd=ref28;
    hc.result.xd(7)=1;
    Hint=TRAJECTORY_C9_HLC_LIVE_ACTUATOR_TICK( ...
        B,agent,time,ref28,zeros(28,1));
    R.reference_non_yaw_channel_corruption_detected= ...
        strcmp(Hint.status,'REJECT_HLC_INTERNAL_REFERENCE_CHANGED_OTHER_CHANNELS');
    % Sim LOGGER-compatible records, NOT a fabricated real flight.
    % The actual LOGGER stores controller/ref/EKF result cells per tick.
    row=struct('tmp',raw,'input',raw,'xd',ref28);
    rrow=struct('state',struct('xd',ref28));
    erow=struct('state',struct('mL',0.14));
    Data=struct('t',[0;5;5.025;47], ...
        'phase',double(['a';'f';'f';'l']));
    Data.agent=struct('controller',struct('result',{{row,row,row,row}}), ...
        'reference',struct('result',{{rrow,rrow,rrow,rrow}}), ...
        'estimator',struct('result',{{erow,erow,erow,erow}}));
    Data.agent(1).estimator.result{3}.state.mL=0.19;
    clean=TRAJECTORY_C9_RECORDED_FLIGHT_HLC_AUDIT(struct('Data',Data));
    R.recorded_flight_fixture_pass= ...
        strcmp(clean.status,'CHECKED_RECORDED_FLIGHT_SAMPLES__PLAN_NOT_CONNECTED')&& ...
        clean.checked_flight_records==2&&clean.failed_flight_records==0&& ...
        ~clean.safe_to_commit&&~clean.physical_continuous_time_certified;
    R.recorded_mass_updates_preserved= ...
        isequal(clean.estimated_payload_mass_kg,[0.14 0.19])&& ...
        ~clean.hlc_mass_consumed_each_tick_verified;
    changed=Data;
    changed.agent(1).controller.result{3}.tmp(1)=B.input_upper(1)+1;
    changed.agent(1).controller.result{3}.input(1)=B.input_upper(1);
    sat=TRAJECTORY_C9_RECORDED_FLIGHT_HLC_AUDIT(struct('Data',changed));
    R.recorded_flight_saturation_detected= ...
        sat.preclamp_saturation_count==1&&sat.failed_flight_records==1&& ...
        strcmp(sat.sample_status{2},'REJECT_REAL_HLC_PRECLAMP_ACTUATOR_SATURATION');
    changed=Data;
    changed.agent(1).reference.result{3}.state.xd(2)=0.125;
    plan=struct('planned_ref28',zeros(28,2), ...
        'reference_tolerance28',zeros(28,1));
    badplan=TRAJECTORY_C9_RECORDED_FLIGHT_HLC_AUDIT( ...
        struct('Data',changed),plan);
    R.recorded_flight_plan_corruption_detected= ...
        badplan.reference_mismatch_count==1&& ...
        strcmp(badplan.sample_status{2},'REJECT_ACTUAL_HLC_REFERENCE_MISMATCH');
    fields={'live_EKF_join_fixture_pass','wrong_EKF_position_rejected', ...
        'stale_EKF_mass_rejected','production_entry_rejects_mismatched_start', ...
        'production_entry_rejects_missing_start_tolerances', ...
        'real_HLC_result_fixture_pass','yaw_branch_lift_allowed', ...
        'preclamp_saturation_detected','HLC_clamp_corruption_detected', ...
        'reference_corruption_detected', ...
        'reference_non_yaw_channel_corruption_detected', ...
        'internal_yaw_corruption_detected', ...
        'recorded_flight_fixture_pass', ...
        'recorded_flight_saturation_detected', ...
        'recorded_flight_plan_corruption_detected', ...
        'recorded_mass_updates_preserved'};
    for k=1:numel(fields)
        assert(R.(fields{k}), 'CHECK_C9_REAL_TICK:Case', ...
            'Required fail-closed fixture test failed: %s',fields{k});
    end
    if nargin>=1 && ~isempty(logger)
        R.saved_flight_trace=TRAJECTORY_C9_RECORDED_FLIGHT_HLC_AUDIT(logger);
        R.actual_saved_flight_log_examined=true;
        R.fixture_only=false;
        R.status='CHECKED_REAL_FLIGHT_LOG__SAMPLED_DIAGNOSTIC_NO_COMMIT';
        if R.saved_flight_trace.failed_flight_records>0
            R.status='REAL_FLIGHT_LOG_HAS_REJECTED_OR_UNKNOWN_SAMPLES__NO_COMMIT';
        end
    else
        R.status='PASS_REAL_SOURCE_LIVE_EKF_JOIN_AND_HLC_PRECLAMP_API__FIXTURE_ONLY';
    end
catch ME
    R.status='FAIL_C9_REAL_EKF_HLC_TICK_AUDIT';
    R.error_identifier=ME.identifier;
    R.error_message=ME.message;
end
save(fullfile(root,[base '.mat']),'R');
fid=fopen(fullfile(root,[base '.txt']),'wt');
assert(fid>0,'CHECK_C9_REAL_TICK:Write','Cannot create TXT result.');
clean=onCleanup(@() fclose(fid));
fprintf(fid,'status=%s\nsource=%s\n',R.status,R.real_HLC_source);
fprintf(fid,'source_lower=%s\nsource_upper=%s\n', ...
    mat2str(R.source_lower.'),mat2str(R.source_upper.'));
fields={'live_EKF_join_fixture_pass','wrong_EKF_position_rejected', ...
    'stale_EKF_mass_rejected','production_entry_rejects_mismatched_start', ...
        'production_entry_rejects_missing_start_tolerances', ...
        'real_HLC_result_fixture_pass','yaw_branch_lift_allowed', ...
    'preclamp_saturation_detected','HLC_clamp_corruption_detected', ...
    'reference_corruption_detected', ...
    'reference_non_yaw_channel_corruption_detected', ...
    'internal_yaw_corruption_detected', ...
    'recorded_flight_fixture_pass', ...
    'recorded_flight_saturation_detected', ...
    'recorded_flight_plan_corruption_detected', ...
    'recorded_mass_updates_preserved', ...
    'actual_saved_flight_log_examined', ...
    'actual_Flight_HLC_tracking_certified', ...
    'actual_Flight_torque_continuous_certified', ...
    'fixture_only','safe_to_commit'};
for k=1:numel(fields)
    fprintf(fid,'%s=%d\n',fields{k},R.(fields{k}));
end
if R.actual_saved_flight_log_examined
    T=R.saved_flight_trace;
    fprintf(fid,'real_log_status=%s\nflight_samples=%d\nchecked_samples=%d\nfailed_samples=%d\n', ...
        T.status,T.flight_records,T.checked_flight_records,T.failed_flight_records);
    fprintf(fid,'preclamp_saturation_count=%d\nclamp_mismatch_count=%d\n', ...
        T.preclamp_saturation_count,T.clamp_mismatch_count);
    fprintf(fid,'yaw_lift_mismatch_count=%d\nmissing_or_invalid=%d\n', ...
        T.yaw_lift_mismatch_count,T.missing_or_invalid_record_count);
    fprintf(fid,'first_failed_logger_index=%g\nfirst_failed_time_s=%g\n', ...
        T.first_failed_record_index,T.first_failed_time_s);
    fprintf(fid,'estimated_load_mass_range_kg=%s\n', ...
        mat2str([min(T.estimated_payload_mass_kg), ...
                 max(T.estimated_payload_mass_kg)]));
    fprintf(fid,'hlc_mass_consumed_each_tick_verified=%d\n', ...
        T.hlc_mass_consumed_each_tick_verified);
end
fprintf(fid,'error_id=%s\nerror=%s\n',R.error_identifier,R.error_message);
clear clean;
archive=fullfile(root,[base '_FOR_CHATGPT.zip']);
if isfile(archive),delete(archive);end
zip(archive,{[base '.mat'],[base '.txt']},root);
meta=dir(archive);
assert(numel(meta)==1&&meta.bytes>100, ...
    'CHECK_C9_REAL_TICK:Export','Result ZIP was not created.');
fprintf('[C9 REAL TICK CHECK] %s\nResult ZIP: %s\n',R.status,archive);
end
