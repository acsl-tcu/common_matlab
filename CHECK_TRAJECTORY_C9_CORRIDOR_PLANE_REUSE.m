function R=CHECK_TRAJECTORY_C9_CORRIDOR_PLANE_REUSE()
% One development-only paired test for a multi-body, multi-obstacle safe
% CORRIDOR made from mathematically validated support halfspaces.
% The same independently certified guide is passed to both implementations.
% Timings include the original all-time guide proof in BOTH runs; this is
% NOT a whole Flight/HLC WCET nor an execution certificate.
root=fileparts(mfilename('fullpath'));
name='TRAJECTORY_C9_CORRIDOR_PLANE_REUSE_RESULT';
R=struct('status','FAIL_CORRIDOR_PLANE_REUSE', 'stage','START', ...
    'error_identifier','','error_message','','error_stack',{{}}, ...
    'obstacle_count',NaN,'body_count',3, ...
    'certified_off',false,'certified_on',false, ...
    'all_plane_inequalities_checked',false, ...
    'robust_mode_fixture_proved',false, ...
    'reused_planes',NaN,'fallback_searches_on',NaN, ...
    'fallback_searches_off',NaN, ...
    'support_calls_on',NaN,'support_calls_off',NaN, ...
    'plane_ms_on',NaN,'plane_ms_off',NaN, ...
    'joint_ms_on',NaN,'joint_ms_off',NaN, ...
    'median_ms_on',NaN,'median_ms_off',NaN, ...
    'p95_ms_on',NaN,'p95_ms_off',NaN, ...
    'max_ms_on',NaN,'max_ms_off',NaN, ...
    'repetitions',7, 'safe_to_commit',false, ...
    'scope','CERTIFIED_NOMINAL_GEOMETRY__NO_HLC_EXECUTION_PROOF', ...
    'zip_path',fullfile(root,[name '_FOR_CHATGPT.zip']));
try
    R.stage='LIVE_SOURCE_FIXTURE_INPUTS';
    addpath(fullfile(root,'controller'),fullfile(root,'model'),'-begin');
    addpath(fullfile(root,'reference','REPLANNING_SYSTEM', ...
        'TRAJECTORY_GENERATION'), ...
        fullfile(root,'reference','REPLANNING_SYSTEM', ...
        'OBSTACLE_INFORMATION'),'-begin');
    [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    P.set("loadmass",0.14);  % audit fixture only; no production constant
    d=double(P.get(["mass","jx","jy","jz","gravity", ...
        "cableL","loadmass"]));
    d=d(:);lo=double(lo(:));hi=double(hi(:));
    assert(numel(d)==7&&all(isfinite(d))&&all(d>0)&& ...
        numel(lo)==4&&numel(hi)==4&&all(hi>lo), ...
        'CHECK_C9_CORRIDOR:Authority','Actual source limits unavailable.');
    a=struct('uav_mass_kg',d(1),'payload_mass_kg',d(7), ...
        'cable_length_m',d(6),'uav_inertia_kgm2',d(2:4), ...
        'gravity_world_mps2',[0;0;-d(5)], ...
        'thrust_limits_N',[lo(1),hi(1)], ...
        'torque_limits_Nm',[lo(2:4),hi(2:4)], ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0);
    gopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'numerical_guard_m',0,'robust_tube_enabled',false, ...
        'trajectory_phase','f');
    fopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'force_guard_N',0);
    cop=struct('min_separation_m',1e-5, ...
        'max_normal_iterations',24,'max_ray_iterations',8);
    r=struct('uav_m',0.1,'payload_m',0.1,'cable_m',0.02);
    J0=zeros(3,10);J1=zeros(3,10);
    J0(:,1)=[0;0;3];J1(:,1)=J0(:,1);
    guide=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,10,J0,J1, ...
        repmat(J0(:,1),1,4));
    th=0.73;
    Q=[cos(th) -sin(th) 0;sin(th) cos(th) 0;0 0 1];
    o1=OBSTACLE_INFORMATION.define(21,'sphere',[2 0 3],0.25);
    o2=OBSTACLE_INFORMATION.define(33,'ellipsoid', ...
        [-2 0 3],[0.30 0.20 0.40],'rotation',Q);
    o3=OBSTACLE_INFORMATION.define(34,'box', ...
        [0 2 4],[0.40 0.55 0.60],'rotation',Q);
    o4=OBSTACLE_INFORMATION.define(35,'cylinder', ...
        [0 -2 4],[0.25 0.55],'rotation',Q);
    observed=[o1 o2 o3 o4];
    R.obstacle_count=numel(observed);
    R.stage='FULL_TIME_PROOF_AND_CORRIDOR_AB';
    off=cop;off.reuse_verified_body_normal=false;
    on=cop;on.reuse_verified_body_normal=true;
    A=TRAJECTORY_C9_FAST_SHARED_CORRIDOR(guide,observed,r, ...
        a,gopt,fopt,off);
    B=TRAJECTORY_C9_FAST_SHARED_CORRIDOR(guide,observed,r, ...
        a,gopt,fopt,on);
    R.certified_off=A.certified;R.certified_on=B.certified;
    assert(A.certified&&B.certified, ...
        'CHECK_C9_CORRIDOR:Proof', ...
        ['A/B nominal all-time proof did not pass; OFF=' A.status ...
         ', ON=' B.status]);
    assert(~A.safe_to_commit&&~B.safe_to_commit&& ...
        strcmp(A.joint_status,B.joint_status), ...
        'CHECK_C9_CORRIDOR:Commit', ...
        'Corridor may not bypass HLC/torque certification.');
    R.reused_planes=B.reused_body_separation_planes;
    R.fallback_searches_on=B.fallback_separator_searches;
    R.fallback_searches_off=A.fallback_separator_searches;
    R.support_calls_on=B.shape_support_calls;
    R.support_calls_off=A.shape_support_calls;
    R.plane_ms_on=B.plane_construction_ms;
    R.plane_ms_off=A.plane_construction_ms;
    R.joint_ms_on=B.joint_proof_ms;
    R.joint_ms_off=A.joint_proof_ms;
    assert(R.reused_planes>0 && ...
        R.fallback_searches_on<R.fallback_searches_off && ...
        R.support_calls_on<R.support_calls_off, ...
        'CHECK_C9_CORRIDOR:NoReuse', ...
        'Certified reuse did not eliminate any separator work.');
    R.stage='INDEPENDENT_ALL_BODY_ALL_OBSTACLE_PLANE_CHECK';
    shapes=TRAJECTORY_OBSTACLE_SUPPORT.prepare(observed);
    assert(numel(A.leaves)==numel(B.leaves)&& ...
        numel(B.leaves)>=1,'CHECK_C9_CORRIDOR:Leaves', ...
        'No equivalent independent proof leaves.');
    R.all_plane_inequalities_checked= ...
        local_check(A,guide,shapes,r,a,gopt,cop) && ...
        local_check(B,guide,shapes,r,a,gopt,cop);
    assert(R.all_plane_inequalities_checked, ...
        'CHECK_C9_CORRIDOR:Halfspaces', ...
        'An output plane failed a full-hull/true-support inequality.');
    R.stage='ROBUST_TUBE_FIXTURE_CONSISTENCY';
    rt=gopt;rt.robust_tube_enabled=true;
    rt.uncertainty_bounds_m=struct( ...
        'uav_m',0.01,'payload_m',0.01,'cable_m',0.01);
    Bt=TRAJECTORY_C9_FAST_SHARED_CORRIDOR(guide,observed,r, ...
        a,rt,fopt,on);
    R.robust_mode_fixture_proved=Bt.certified && ...
        ~Bt.safe_to_commit && ...
        local_check(Bt,guide,shapes,r,a,rt,cop);
    assert(R.robust_mode_fixture_proved, ...
        'CHECK_C9_CORRIDOR:Tube', ...
        'Synthetic ON tube is not safe or not fully validated.');
    R.stage='PAIRED_WHOLE_CORRIDOR_TIMING';
    tOn=zeros(1,R.repetitions);tOff=tOn;
    for k=1:R.repetitions
        if mod(k,2)==1
            ca=TRAJECTORY_C9_FAST_SHARED_CORRIDOR( ...
                guide,observed,r,a,gopt,fopt,on);
            cb=TRAJECTORY_C9_FAST_SHARED_CORRIDOR( ...
                guide,observed,r,a,gopt,fopt,off);
        else
            cb=TRAJECTORY_C9_FAST_SHARED_CORRIDOR( ...
                guide,observed,r,a,gopt,fopt,off);
            ca=TRAJECTORY_C9_FAST_SHARED_CORRIDOR( ...
                guide,observed,r,a,gopt,fopt,on);
        end
        assert(ca.certified&&cb.certified, ...
            'CHECK_C9_CORRIDOR:Nondeterminism','Corridor status changed.');
        tOn(k)=ca.elapsed_ms;tOff(k)=cb.elapsed_ms;
    end
    R.median_ms_on=median(tOn);R.median_ms_off=median(tOff);
    v=sort(tOn);R.p95_ms_on=v(ceil(0.95*numel(v)));
    v=sort(tOff);R.p95_ms_off=v(ceil(0.95*numel(v)));
    R.max_ms_on=max(tOn);R.max_ms_off=max(tOff);
    R.status='PASS_C9_CORRIDOR_HALFSPACE_REUSE__HLC_UNCERTIFIED';
    R.stage='COMPLETE';
catch ME
    R.error_identifier=ME.identifier;R.error_message=ME.message;
    R.error_stack=arrayfun(@(e)sprintf('%s:%d',e.name,e.line), ...
        ME.stack,'UniformOutput',false);
end
save(fullfile(root,[name '.mat']),'R');
fid=fopen(fullfile(root,[name '.txt']),'w');
if fid>=0
    fprintf(fid,'status=%s\nstage=%s\nerror=%s | %s\n', ...
        R.status,R.stage,R.error_identifier,R.error_message);
    for k=1:numel(R.error_stack)
        fprintf(fid,'stack_%d=%s\n',k,R.error_stack{k});
    end
    fprintf(fid,'certified_on_off=%d,%d | support_calls=%g,%g\n', ...
        R.certified_on,R.certified_off, ...
        R.support_calls_on,R.support_calls_off);
    fprintf(fid,'reused=%g | separator_searches=%g,%g\n', ...
        R.reused_planes,R.fallback_searches_on,R.fallback_searches_off);
    fprintf(fid,'plane_ms_on_off=%.6f,%.6f\n', ...
        R.plane_ms_on,R.plane_ms_off);
    fprintf(fid,'joint_ms_on_off=%.6f,%.6f\n', ...
        R.joint_ms_on,R.joint_ms_off);
    fprintf(fid,'full_corridor_median_ms_on_off=%.6f,%.6f\n', ...
        R.median_ms_on,R.median_ms_off);
    fprintf(fid,'full_corridor_p95_ms_on_off=%.6f,%.6f\n', ...
        R.p95_ms_on,R.p95_ms_off);
    fprintf(fid,'full_corridor_max_ms_on_off=%.6f,%.6f\n', ...
        R.max_ms_on,R.max_ms_off);
    fprintf(fid,'all_plane_inequalities=%d | tube_fixture=%d\n', ...
        R.all_plane_inequalities_checked,R.robust_mode_fixture_proved);
    fclose(fid);
end
zip(R.zip_path,{[name '.mat'],[name '.txt']},root);
fprintf('[C9 CORRIDOR] %s | %s\n',R.status,R.zip_path);
end

function ok=local_check(C,guide,shapes,r,a,gopt,cop)
% Re-evaluate every halfspace with the canonical true shape support,
% the current hull, AND its own radius/tube/cone margin on every leaf.
% This checks the corridor construction independently of plane reuse.
ok=false;
rad=[r.uav_m,r.payload_m,r.cable_m];
if gopt.robust_tube_enabled
    t=gopt.uncertainty_bounds_m;
    rad=rad+[t.uav_m,t.payload_m,t.cable_m];
end
margin0=cop.min_separation_m+gopt.numerical_guard_m;
L=a.cable_length_m;
P0=double(guide.control_points_m);
for k=1:numel(C.leaves)
    leaf=C.leaves(k);
    P=P0*leaf.map;
    U=P-L*leaf.q0;
    hulls={U,P,[P,U]};
    normals={leaf.uav_normals,leaf.payload_normals,leaf.cable_normals};
    offsets={leaf.uav_offsets,leaf.payload_offsets,leaf.cable_offsets};
    for j=1:numel(shapes)
        for b=1:3
            n=normals{b}(:,j);
            beta=offsets{b}(j);
            extra=double(b==1||b==3)*leaf.guide_cone_padding_m;
            required=TRAJECTORY_OBSTACLE_SUPPORT.value(shapes(j),n) + ...
                rad(b)+extra+margin0;
            numerical_guard=32*eps(max([1,abs(required),abs(beta)]));
            if ~all(isfinite(n)) || norm(n)==0 || ...
                    ~isfinite(beta) || beta+numerical_guard<required || ...
                    ~(min(n.'*hulls{b})>required+numerical_guard)
                return
            end
        end
    end
end
ok=true;
end
