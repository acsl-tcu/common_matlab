function R=CHECK_TRAJECTORY_C9_SYMMETRIC_UNIT_JET_AB()
% Development-only A/B. Verify that symmetric norm-jet arithmetic never
% downgrades a conditionally certified nominal torque reference.
% Diagnose the unknown midpoint separately from timing; never COMMIT.
root=fileparts(mfilename('fullpath'));
name='TRAJECTORY_C9_SYMMETRIC_UNIT_JET_AB_RESULT';
R=struct('status','FAIL_C9_SYMMETRIC_UNIT_JET_AB', ...
  'stage','START','error_identifier','','error_message','', ...
  'error_stack',{{}}, ...
  'scene_names',{{'SMOOTH_NOMINAL','SPHERE_ELLIPSOID_CERTIFIED_GUIDE'}}, ...
  'mode_names',{{'ORIGINAL_INTERVAL','SYMMETRIC_SQUARE_INTERVAL'}}, ...
  'status_by_mode',{{}}, ...
  'nodes_by_mode',NaN(2,2),'detailed_nodes_by_mode',NaN(2,2), ...
  'accepted_leaves_by_mode',NaN(2,2), ...
  'median_ms_by_mode',NaN(2,2), ...
  'p95_ms_by_mode',NaN(2,2),'max_ms_by_mode',NaN(2,2), ...
  'unknown_interval_s_by_mode',NaN(2,2), ...
  'unknown_bounds_Nm_by_mode',NaN(3,2,2), ...
  'midpoint_s',NaN,'midpoint_valid',false, ...
  'midpoint_torque_bounds_Nm',NaN(3,2), ...
  'midpoint_outside_limits_unrounded',false, ...
  'midpoint_inside_limits_unrounded',false, ...
  'midpoint_status','NOT_RUN', ...
  'random_interval_trials',0,'random_enclosure_pass',false, ...
  'search_status','NOT_CALLED','search_elapsed_ms',NaN, ...
  'search_independent_proof_calls',NaN, ...
  'safe_to_commit',false,'repetitions',7, ...
  'scope','REAL_ARITHMETIC_NOMINAL_ONLY__HLC_AND_ROUNDING_UNCERTIFIED', ...
  'zip_path',fullfile(root,[name '_FOR_CHATGPT.zip']));
try
    R.stage='SYMMETRIC_INTERVAL_DIAGONAL_INCLUSION';
    oldrng=rng;clean_rng=onCleanup(@()rng(oldrng));
    rng(628,'twister');
    for q=1:2000
        c=10*(rand(3,1)-0.5);
        h=2*rand(3,1);
        a=c-h;b=c+h;
        % Independent copies of a variable give a wider (or equal) box
        % than the exact diagonal square sum. All four products retained.
        P=[a.*a,a.*b,b.*a,b.*b];
        oldlo=sum(min(P,[],2));oldhi=sum(max(P,[],2));
        slo=min(a.^2,b.^2);slo(a<=0 & b>=0)=0;
        squlo=sum(slo);squhi=sum(max(a.^2,b.^2));
        tol=1e-12*max(1,max(abs([oldlo,oldhi,squlo,squhi])));
        assert(squlo>=oldlo-tol && squhi<=oldhi+tol, ...
          'C9_SYM:SquareInclusion','Exact diagonal square was not contained.');
    end
    R.random_interval_trials=2000;
    R.random_enclosure_pass=true;
    clear clean_rng
    R.stage='CURRENT_REAL_HLC_LIMITS_AND_C9_FIXTURES';
    addpath(fullfile(root,'controller'),fullfile(root,'model'),'-begin');
    addpath(fullfile(root,'reference','REPLANNING_SYSTEM', ...
      'TRAJECTORY_GENERATION'), ...
      fullfile(root,'reference','REPLANNING_SYSTEM', ...
      'OBSTACLE_INFORMATION'),'-begin');
    [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    P.set("loadmass",0.14); % CHECK fixture only; no production default.
    d=double(P.get(["mass","jx","jy","jz","gravity","cableL","loadmass"]));
    d=d(:);lo=double(lo(:));hi=double(hi(:));
    assert(numel(d)==7&&all(isfinite(d))&&all(d>0)&& ...
      numel(lo)==4&&numel(hi)==4&&all(hi>lo), ...
      'C9_INTERVAL_AB:Authority','Cannot read current HLC/plant bounds.');
    a=struct('uav_mass_kg',d(1),'payload_mass_kg',d(7), ...
      'cable_length_m',d(6),'uav_inertia_kgm2',d(2:4), ...
      'gravity_world_mps2',[0;0;-d(5)], ...
      'thrust_limits_N',[lo(1),hi(1)], ...
      'torque_limits_Nm',[lo(2:4),hi(2:4)], ...
      'minimum_tension_N',0,'acceleration_guard_mps2',0);
    opt=struct('max_subdivision_depth',8,'max_node_count',511, ...
      'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
      'torque_guard_Nm',zeros(3,1), ...
      'enable_fast_norm_sufficient_bound',true, ...
      'use_precomputed_binomial',true, ...
      'use_factored_diagonal_gyro',true, ...
      'enable_infeasible_leaf_early_exit',true);
    J0=zeros(3,10);J1=zeros(3,10);
    J0(:,1)=[-2;0;3];J1(:,1)=[2;0;3];
    J0(1,2)=0.4;J1(1,2)=0.4;
    nominal=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,10,J0,J1, ...
      repmat([0;0;3],1,4));
    R.stage='GENERATE_CERTIFIED_GUIDE_ONCE';
    theta=0.34;Q=[cos(theta) -sin(theta) 0; ...
                     sin(theta) cos(theta) 0;0 0 1];
    observed=[OBSTACLE_INFORMATION.define(21,'sphere',[0 0.1 3],0.2), ...
      OBSTACLE_INFORMATION.define(33,'ellipsoid',[0.6 -0.16 3], ...
      [0.32 0.19 0.4],'rotation',Q)];
    gopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
      'numerical_guard_m',0,'robust_tube_enabled',false, ...
      'trajectory_phase','f');
    fopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
      'force_guard_N',0);
    sopt=struct('probe_count',13,'max_outer_iterations',4, ...
      'max_projection_sweeps',100,'projection_tolerance_m',1e-8, ...
      'min_separation_m',1e-5, ...
      'lazy_initial_proof_on_violated_plane',false, ...
      'payload_hull_witness_policy','off', ...
      'embed_taut_bernstein_halfspaces',false, ...
      'accept_first_certified_minimum_qp',false, ...
      'enable_connected_group_topology',true, ...
      'enable_point_intersection_prefilter',true);
    req=struct('t0_s',8,'duration_s',10,'flight_interval_s',[8 30], ...
      'start_jets',J0,'end_jets',J1, ...
      'nominal_free',nominal.control_points_m(:,11:14), ...
      'observed',observed, ...
      'radii',struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1), ...
      'authority',a,'geometry_options',gopt, ...
      'force_options',fopt,'search_options',sopt);
    S=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(req);
    R.search_status=S.status;
    R.search_elapsed_ms=S.elapsed_ms;
    R.search_independent_proof_calls=S.independent_proof_calls;
    assert(S.candidate_available&&S.final_certificate.certified&& ...
      ~S.safe_to_commit, 'C9_INTERVAL_AB:Guide', ...
      ['No geometry-certified fixture: ' S.status]);
    pieces={nominal,S.candidate_piece};
    R.status_by_mode=cell(2,2);
    R.stage='CERTIFICATE_AB_7_REPEATS';
    for sc=1:2
        reference=cell(2,1);
        for mode=1:2
            o=opt;
            o.use_symmetric_unit_jet_kernel=(mode==2);
            Z=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL(pieces{sc},a,o);
            assert(~Z.safe_to_commit && ~Z.actual_HLC_tracking_proven && ...
              ~Z.numerically_directed_rounding_proven && ...
              Z.symmetric_unit_jet_enabled==(mode==2), ...
              'C9_SYM:NominalScope','HLC commit or mode semantics incorrect.');
            reference{mode}=Z;
            R.status_by_mode{mode,sc}=Z.status;
            R.nodes_by_mode(mode,sc)=Z.checked_nodes;
            R.detailed_nodes_by_mode(mode,sc)=Z.detailed_interval_checked_nodes;
            R.accepted_leaves_by_mode(mode,sc)=Z.accepted_leaves;
            if sc==2
                R.unknown_interval_s_by_mode(mode,:)=Z.unresolved_interval_s;
                R.unknown_bounds_Nm_by_mode(:,:,mode)= ...
                     Z.unresolved_torque_bounds_Nm;
            end
        end
        % A mathematically tighter sufficient enclosure must never make
        % an already proven candidate UNKNOWN. It CAN make UNKNOWN PASS.
        if reference{1}.conditional_nominal_all_time_torque_proven
            assert(reference{2}.conditional_nominal_all_time_torque_proven, ...
              'C9_SYM:ProofRegression','A prior nominal proof was lost.');
        end
        time_ms=NaN(2,R.repetitions);
        for rep=1:R.repetitions
            for position=1:2
                mode=mod(rep+position-2,2)+1;
                o=opt;
                o.use_symmetric_unit_jet_kernel=(mode==2);
                Z=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL(pieces{sc},a,o);
                assert(strcmp(Z.status,reference{mode}.status) && ...
                  Z.checked_nodes==reference{mode}.checked_nodes && ...
                  Z.detailed_interval_checked_nodes== ...
                      reference{mode}.detailed_interval_checked_nodes, ...
                  'C9_SYM:Determinism','Repeated certificate changed.');
                time_ms(mode,rep)=Z.elapsed_ms;
            end
        end
        for mode=1:2
            t=sort(time_ms(mode,:));
            R.median_ms_by_mode(mode,sc)=median(t);
            R.p95_ms_by_mode(mode,sc)=t(ceil(.95*numel(t)));
            R.max_ms_by_mode(mode,sc)=t(end);
        end
    end
    R.stage='UNKNOWN_POINT_DIAGNOSTIC_NONCERTIFYING';
    o=opt;
    o.use_symmetric_unit_jet_kernel=true;
    o.enable_unknown_midpoint_diagnostic=true;
    Z=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL(pieces{2},a,o);
    R.midpoint_status=Z.status;
    R.midpoint_s=Z.unresolved_midpoint_s;
    R.midpoint_valid=Z.unresolved_midpoint_valid;
    R.midpoint_torque_bounds_Nm=Z.unresolved_midpoint_torque_bounds_Nm;
    R.midpoint_outside_limits_unrounded= ...
      Z.unresolved_midpoint_outside_limits_unrounded;
    R.midpoint_inside_limits_unrounded= ...
      Z.unresolved_midpoint_inside_limits_unrounded;
    assert(~Z.safe_to_commit && ~Z.actual_HLC_tracking_proven, ...
      'C9_SYM:DiagnosticCommit','A point diagnostic changed safety scope.');
    R.status='PASS_C9_SYMMETRIC_UNIT_JET_AB__HLC_UNCERTIFIED';
    R.stage='COMPLETE';
catch ME
    R.error_identifier=ME.identifier;
    R.error_message=ME.message;
    R.error_stack=arrayfun(@(e)sprintf('%s:%d',e.name,e.line), ...
      ME.stack,'UniformOutput',false);
end
save(fullfile(root,[name '.mat']),'R');
fid=fopen(fullfile(root,[name '.txt']),'w');
if fid>=0
    fprintf(fid,'status=%s\nstage=%s\nerror=%s | %s\n', ...
      R.status,R.stage,R.error_identifier,R.error_message);
    for k=1:numel(R.error_stack)
        fprintf(fid,'stack_%d=%s\n',k,R.error_stack{k});
    end
    fprintf(fid,'random_square_tests=%d | pass=%d\n', ...
      R.random_interval_trials,R.random_enclosure_pass);
    fprintf(fid,'guide=%s | search_elapsed_ms=%.6f | proof_calls=%g\n', ...
      R.search_status,R.search_elapsed_ms,R.search_independent_proof_calls);
    for sc=1:2
      for m=1:2
        if numel(R.status_by_mode)<m+2*(sc-1),continue;end
        fprintf(fid,['scene=%s | mode=%s | status=%s | nodes=%g | detailed=%g ', ...
          '| median_ms=%.6f | p95_ms=%.6f | max_ms=%.6f\n'], ...
          R.scene_names{sc},R.mode_names{m},R.status_by_mode{m,sc}, ...
          R.nodes_by_mode(m,sc),R.detailed_nodes_by_mode(m,sc), ...
          R.median_ms_by_mode(m,sc),R.p95_ms_by_mode(m,sc),R.max_ms_by_mode(m,sc));
      end
    end
    fprintf(fid,'last_midpoint_s=%.12g | valid=%d | status=%s\n', ...
      R.midpoint_s,R.midpoint_valid,R.midpoint_status);
    fprintf(fid,['point_tau_box=[%.12g %.12g; %.12g %.12g; %.12g %.12g] ', ...
      '| outside_unrounded=%d | inside_unrounded=%d\n'], ...
      R.midpoint_torque_bounds_Nm.', ...
      R.midpoint_outside_limits_unrounded, ...
      R.midpoint_inside_limits_unrounded);
    fprintf(fid,'scope=%s | safe_to_commit=%d\n',R.scope,R.safe_to_commit);
    fclose(fid);
end
zip(R.zip_path,{[name '.mat'],[name '.txt']},root);
fprintf('[C9 SYMMETRIC UNIT JET] %s | %s\n',R.status,R.zip_path);
end
