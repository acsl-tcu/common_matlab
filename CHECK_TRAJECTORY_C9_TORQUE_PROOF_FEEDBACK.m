function R=CHECK_TRAJECTORY_C9_TORQUE_PROOF_FEEDBACK()
% CHECK only: full-time nominal torque oracle informs SAME C9 QP search.
% Torque point samples NEVER certify all-time feasibility. Final HLC
% tracking and directed-rounding guarantees remain false.
root=fileparts(mfilename('fullpath'));
name='TRAJECTORY_C9_TORQUE_PROOF_FEEDBACK_RESULT';
R=struct('status','FAIL_NOT_RUN','error_identifier','','error_message','', ...
    'error_stack',{{}},'baseline_status','NOT_RUN', ...
    'feedback_status','NOT_RUN','baseline_ms',NaN,'feedback_ms',NaN, ...
    'reference_nominal_torque','NOT_RUN','feedback_calls',NaN, ...
    'feedback_total_ms',NaN,'feedback_added_times',NaN, ...
    'feedback_nominal_conditionally_proven',false, ...
    'feedback_local_cuts',NaN,'feedback_oracle_proofs',NaN, ...
    'candidate_available',false,'helper_status','NOT_RUN', ...
    'helper_nominal_proven',false,'helper_witness_times_s',[], ...
    'helper_proof_interval_s',[NaN NaN], ...
    'helper_proof_ms',NaN,'helper_point_ms',NaN, ...
    'scope','NOMINAL_PROOF_GUIDED_SEARCH_ONLY__NOT_HLC', ...
    'safe_to_commit',false,'zip_path',fullfile(root,[name '_FOR_CHATGPT.zip']));
try
    addpath(fullfile(root,'controller'),fullfile(root,'model'),'-begin');
    addpath(fullfile(root,'reference','REPLANNING_SYSTEM', ...
        'TRAJECTORY_GENERATION'), ...
        fullfile(root,'reference','REPLANNING_SYSTEM', ...
        'OBSTACLE_INFORMATION'),'-begin');
    [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    P.set("loadmass",0.14); % CHECK-only fixture, never production fallback.
    d=double(P.get(["mass","jx","jy","jz", ...
         "gravity","cableL","loadmass"]));
    d=d(:);lo=double(lo(:));hi=double(hi(:));
    assert(numel(d)==7&&all(isfinite(d))&&all(d>0)&& ...
        numel(lo)==4&&numel(hi)==4&&all(hi>lo), ...
        'C9_INPUT_QP:Authority','HLC or physical authority unavailable');
    a=struct('uav_mass_kg',d(1),'payload_mass_kg',d(7), ...
      'cable_length_m',d(6),'uav_inertia_kgm2',d(2:4), ...
      'gravity_world_mps2',[0;0;-d(5)], ...
      'thrust_limits_N',[lo(1),hi(1)], ...
      'torque_limits_Nm',[lo(2:4),hi(2:4)], ...
      'minimum_tension_N',0,'acceleration_guard_mps2',0);
    topt=struct('max_subdivision_depth',8,'max_node_count',511, ...
      'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
      'torque_guard_Nm',zeros(3,1), ...
      'enable_fast_norm_sufficient_bound',true, ...
      'use_precomputed_binomial',true, ...
      'use_factored_diagonal_gyro',true, ...
      'enable_infeasible_leaf_early_exit',true, ...
      'use_symmetric_unit_jet_kernel',true, ...
      'use_cancellation_attitude_jet',true, ...
      'use_structural_torque_intersection',false);
    J0=zeros(3,10);J1=zeros(3,10);
    J0(:,1)=[-2;0;3];J1(:,1)=[2;0;3];
    J0(1,2)=0.4;J1(1,2)=0.4;
    nominal=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,10,J0,J1, ...
        repmat([0;0;3],1,4));
    theta=0.34;Q=[cos(theta) -sin(theta) 0; ...
                       sin(theta) cos(theta) 0;0 0 1];
    observed=[OBSTACLE_INFORMATION.define(21,'sphere',[0 0.1 3],0.2), ...
      OBSTACLE_INFORMATION.define(33,'ellipsoid',[0.6 -0.16 3], ...
      [0.32 0.19 0.4],'rotation',Q)];
    gopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
      'numerical_guard_m',0,'robust_tube_enabled',false, ...
      'trajectory_phase','f');
    fopt=struct('max_subdivision_depth',6,'max_node_count',127, ...
      'force_guard_N',0);
    sopt=struct('probe_count',13,'max_outer_iterations',4, ...
      'max_projection_sweeps',100,'projection_tolerance_m',1e-8, ...
      'min_separation_m',1e-5, ...
      'lazy_initial_proof_on_violated_plane',false, ...
      'payload_hull_witness_policy','off', ...
      'embed_taut_bernstein_halfspaces',false, ...
      'accept_first_certified_minimum_qp',false, ...
      'enable_connected_group_topology',true, ...
      'enable_point_intersection_prefilter',true);
    req=struct('t0_s',8,'duration_s',10,'flight_interval_s',[8 30], ...
      'start_jets',J0,'end_jets',J1, ...
      'nominal_free',nominal.control_points_m(:,11:14), ...
      'observed',observed, ...
      'radii',struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1), ...
      'authority',a,'geometry_options',gopt,'force_options',fopt, ...
      'search_options',sopt,'torque_options',topt);
    baseline=req;
    baseline.search_options.enable_torque_aware_joint_search=true;
    baseline.search_options.torque_probe_count=33; % CHECK-only collocation diagnostics, never proof.
    baseline.torque_options.use_forward_torque_jacobian=true;
    baseline.search_options.enable_nominal_torque_proof_feedback=false;
    guided=baseline;
    guided.search_options.enable_nominal_torque_proof_feedback=true;
    % The very same physical fixture and nominal segment for both cases.
    A=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(baseline);
    R.baseline_status=A.status;
    R.baseline_ms=A.elapsed_ms;
    if A.candidate_available
        tc=A.candidate_piece.t0_s + A.candidate_piece.duration_s*(0:32)/32;
        D=TRAJECTORY_C9_TORQUE_CERTIFICATE_FEEDBACK( ...
            A.candidate_piece,a,topt,tc);
        R.helper_status=D.status;
        R.helper_nominal_proven=D.nominal_all_time_conditional;
        R.helper_witness_times_s=D.witness_times_s;
        R.helper_proof_interval_s=D.proof_interval_s;
        R.helper_proof_ms=D.proof_elapsed_ms;
        R.helper_point_ms=D.point_elapsed_ms;
        R.reference_nominal_torque=D.proof_status;
        assert(~D.safe_to_commit, ...
            'C9_TORQUE_FEEDBACK:HelperCannotCommit', ...
            'The helper is never a closed-loop safety certificate');
        if D.can_reoptimize
            assert(numel(D.updated_times_s)>numel(unique(tc)) && ...
                ~isempty(D.witness_times_s), ...
                'C9_TORQUE_FEEDBACK:NewWitness', ...
                'Feedback must add a genuine point input witness');
            P1=TRAJECTORY_C9_TORQUE_POINT_EVALUATE( ...
                A.candidate_piece,a,topt,D.witness_times_s);
            assert(all(P1.valid)&&all(P1.outside_limits), ...
                'C9_TORQUE_FEEDBACK:WitnessValidity', ...
                'Feedback point must numerically violate live input limit');
        end
    end
    B=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(guided);
    R.feedback_status=B.status;
    R.feedback_ms=B.elapsed_ms;
    R.feedback_calls=B.nominal_torque_feedback_calls;
    R.feedback_total_ms=B.nominal_torque_feedback_ms;
    R.feedback_added_times=B.nominal_torque_witness_times_added;
    R.feedback_nominal_conditionally_proven= ...
        B.nominal_torque_conditional_proven;
    R.feedback_local_cuts=B.point_torque_local_cuts;
    R.feedback_oracle_proofs=B.independent_proof_calls;
    R.candidate_available=B.candidate_available;
    assert(B.nominal_torque_feedback_enabled && ...
        ~B.safe_to_commit && ...
        (~B.candidate_available || ...
         (B.final_certificate.certified && ...
          B.nominal_torque_conditional_proven)), ...
        'C9_TORQUE_FEEDBACK:CandidateGate', ...
        'A returned candidate must have BOTH nominal certificates');
    if B.candidate_available
        N=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL( ...
            B.candidate_piece,a,topt);
        assert(N.conditional_nominal_all_time_torque_proven && ...
            ~N.safe_to_commit, ...
            'C9_TORQUE_FEEDBACK:ReturnedNominalCertificate', ...
            'Returned candidate has no nominal full-time torque certificate');
    end
    R.status='PASS_PROOF_FEEDBACK_INVARIANTS__HLC_UNCERTIFIED';
catch ME
    R.status='FAIL_C9_TORQUE_PROOF_FEEDBACK';
    R.error_identifier=ME.identifier;
    R.error_message=ME.message;
    R.error_stack=arrayfun(@(s)sprintf('%s:%d',s.name,s.line), ...
        ME.stack,'UniformOutput',false);
end
save(fullfile(root,[name '.mat']),'R');
fid=fopen(fullfile(root,[name '.txt']),'w');
if fid>=0
    fprintf(fid,'status=%s error=%s %s\n',R.status,R.error_identifier,R.error_message);
    for k=1:numel(R.error_stack),fprintf(fid,'stack=%s\n',R.error_stack{k});end
    fprintf(fid,'baseline=%s elapsed_ms=%.6f\n',R.baseline_status,R.baseline_ms);
    fprintf(fid,'feedback=%s elapsed_ms=%.6f\n',R.feedback_status,R.feedback_ms);
    fprintf(fid,'helper=%s nominal_proven=%d proof=%s proof_ms=%.6f point_ms=%.6f\n', ...
        R.helper_status,R.helper_nominal_proven,R.reference_nominal_torque, ...
        R.helper_proof_ms,R.helper_point_ms);
    fprintf(fid,'helper_leaf=%.9f,%.9f witness_times_s=%s\n', ...
        R.helper_proof_interval_s,sprintf(' %.9f',R.helper_witness_times_s));
    fprintf(fid,'feedback_calls=%g extra_times=%g cuts=%g proof_calls=%g conditional_proven=%d candidate=%d safe_to_commit=%d\n', ...
        R.feedback_calls,R.feedback_added_times,R.feedback_local_cuts, ...
        R.feedback_oracle_proofs,R.feedback_nominal_conditionally_proven, ...
        R.candidate_available,R.safe_to_commit);
    fclose(fid);
end
zip(R.zip_path,{[name '.mat'],[name '.txt']},root);
fprintf('[C9 NOMINAL TORQUE PROOF FEEDBACK] %s\n',R.status);
end
