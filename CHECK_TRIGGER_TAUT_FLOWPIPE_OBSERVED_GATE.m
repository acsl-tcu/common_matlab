function T=CHECK_TRIGGER_TAUT_FLOWPIPE_OBSERVED_GATE()
% Disposable common_matlab-root synthetic test. No Flight or future truths.
T=struct('status','NOT_RUN','reason','', ...
    'intervals',0,'observed_shapes',0,'tension_checked',false, ...
    'outside_pass',false,'inside_rejected',false, ...
    'unprovided_obstacles_rejected',false,'never_commit',false);
try
    p=zeros(21,1);
    p(1)=1.4; p(6:8)=[0.05;0.06;0.08];
    p(9)=9.80665;p(20)=0.5;p(21)=2;
    x=zeros(24,1);
    x(13:15)=[0;0;-2];x(19:21)=[0;0;-1];
    u=[(p(1)+p(20))*p(9);0;0;0];
    delta=1e-8;
    P=struct('time_grid_s',[0,0.002,0.004], ...
        'initial_lower',x-delta,'initial_upper',x+delta, ...
        'held_input_lower',repmat(u-delta,1,2), ...
        'held_input_upper',repmat(u+delta,1,2), ...
        'param_lower',repmat(p,1,2),'param_upper',repmat(p,1,2));
    P.param_lower(20,:)=p(20)-delta;
    P.param_upper(20,:)=p(20)+delta;
    shape=struct('id',1,'type','ellipsoid','center0',[7;0;0], ...
        'rotation',eye(3),'dimensions',[0.4;0.7;0.9], ...
        'is_stationary',true);
    C=struct('flowpipe_inputs',P,'observed_prepared_shapes',shape, ...
        'body',struct('r_uav_m',0.15,'r_payload_m',0.12, ...
        'r_cable_m',0.01));
    good=TRIGGER_TAUT_FLOWPIPE_OBSERVED_GATE(C);
    assert(good.conditional_pass && ~good.safe_to_commit && ...
        all(good.separated_intervals(:)), ...
        'CHECK_TRIGGER_TAUT_FLOWPIPE:Exterior',good.reason);
    T.outside_pass=true;
    T.intervals=good.reach.completed_intervals;
    T.observed_shapes=numel(good.observed_ids);
    T.tension_checked=good.all_tensions_positive;
    bad=C;
    bad.observed_prepared_shapes.center0=[0;0;-1];
    blocked=TRIGGER_TAUT_FLOWPIPE_OBSERVED_GATE(bad);
    T.inside_rejected=~blocked.conditional_pass && ~blocked.safe_to_commit;
    assert(T.inside_rejected,'CHECK_TRIGGER_TAUT_FLOWPIPE:Interior', ...
        'Intersecting cable must not certify conditional separation.');
    empty=C;empty.observed_prepared_shapes=shape([]);
    missing=TRIGGER_TAUT_FLOWPIPE_OBSERVED_GATE(empty);
    T.unprovided_obstacles_rejected=~missing.conditional_pass && ...
        ~missing.safe_to_commit;
    assert(T.unprovided_obstacles_rejected, ...
        'CHECK_TRIGGER_TAUT_FLOWPIPE:Unknown', ...
        'No observed geometry must not produce a safety pass.');
    T.never_commit=~good.safe_to_commit && ~blocked.safe_to_commit && ...
        ~missing.safe_to_commit;
    T.status='PASS_CONDITIONAL_TAUT_FLOWPIPE_GEOMETRY_CHAIN__NOT_FLIGHT_SAFETY';
catch ME
    T.status='FAIL_TAUT_FLOWPIPE_CHAIN_FIXTURE';
    T.reason=[ME.identifier ' | ' ME.message];
end
save('TRIGGER_TAUT_FLOWPIPE_GATE_RESULT.mat','T');
f=fopen('TRIGGER_TAUT_FLOWPIPE_GATE_RESULT.txt','w');
if f>=0
    fprintf(f,'status=%s\nintervals=%d\nobserved=%d\n', ...
        T.status,T.intervals,T.observed_shapes);
    fprintf(f,'outside=%d\ninside_rejected=%d\nmissing_rejected=%d\nnever_commit=%d\nreason=%s\n', ...
        T.outside_pass,T.inside_rejected,T.unprovided_obstacles_rejected, ...
        T.never_commit,T.reason);
    fclose(f);
end
end
