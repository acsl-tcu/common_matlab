function S=CHECK_TRIGGER_CABLE_GEOMETRY()
% CHECK_TRIGGER_CABLE_GEOMETRY Read-only geometry regression, no Flight effects.
% Numerical constants below are SYNTHETIC TEST FIXTURES, not physical defaults.
center=[0;0;0];
sph=struct('type','sphere','rotation',eye(3),'dimensions',0.2, ...
    'center0',center);
ell=struct('type','ellipsoid','rotation', ...
    [cos(pi/4) -sin(pi/4) 0;sin(pi/4) cos(pi/4) 0;0 0 1], ...
    'dimensions',[0.7;0.2;0.3],'center0',center);
q=[-1;0;0];l=[1;0;0];
tests=struct();
tests.sphere_centerline_intersection= ...
    TRIGGER_GEOMETRY_CERTIFICATE.cable_centerline_hit(q,l,sph);
tests.ellipsoid_rotated_centerline_intersection= ...
    TRIGGER_GEOMETRY_CERTIFICATE.cable_centerline_hit(q,l,ell);
q=[-1;0.28;0];l=[1;0.28;0];
tests.thin_line_clear= ...
    TRIGGER_GEOMETRY_CERTIFICATE.separated_cable(q,l,0,sph,center);
tests.material_radius_proximity_not_certified_clear= ...
    ~TRIGGER_GEOMETRY_CERTIFICATE.separated_cable(q,l,0.1,sph,center);
tests.uav_sphere_clear= ...
    TRIGGER_GEOMETRY_CERTIFICATE.separated_point([0.71;0;0],0.5,sph,center);
tests.payload_sphere_overlap_possible= ...
    ~TRIGGER_GEOMETRY_CERTIFICATE.separated_point([0.69;0;0],0.5,sph,center);
tests.degenerate_zero_length_segment= ...
    TRIGGER_GEOMETRY_CERTIFICATE.separated_cable([1;0;0],[1;0;0],0,sph,center);
keys=fieldnames(tests);
passed=all(cellfun(@(key)isequal(tests.(key),true),keys));
if passed,status='PASS_SYNTHETIC_GEOMETRY_ONLY';
else,status='FAIL_SYNTHETIC_GEOMETRY';end
S=struct('status',status,'tests',tests,'passed_count',sum( ...
    cellfun(@(key)isequal(tests.(key),true),keys)),'total_count',numel(keys), ...
    'flight_tested',false,'continuous_time_certified',false);
disp(S);
assert(passed,'CHECK_TRIGGER_CABLE_GEOMETRY:Fail', ...
    'Finite segment/cable cross-section geometry failed the synthetic regression.');
end
