function R=CHECK_TRAJECTORY_C9_JOINT_FAST()
% CHECK_TRAJECTORY_C9_JOINT_FAST  One joint certificate + baseline timing.
% Put at common_matlab root. Results are archived there in one ZIP.
% HANDOFF_TRAJECTORY.txt is neither read nor required by this audit.
% All dimensions/masses/margins in this file are SYNTHETIC TEST INPUTS.
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'reference','REPLANNING_SYSTEM');
addpath(fullfile(base,'TRAJECTORY_GENERATION'), ...
    fullfile(base,'OBSTACLE_INFORMATION'));
A=struct('cable_length_m',2,'uav_mass_kg',1.5, ...
    'payload_mass_kg',1,'gravity_world_mps2',[0;0;-9.80665], ...
    'thrust_limits_N',[0;100],'minimum_tension_N',0, ...
    'acceleration_guard_mps2',1e-10);
r=struct('uav_m',0.02,'payload_m',0.02,'cable_m',0.005);
go=struct('robust_tube_enabled',false,'max_subdivision_depth',4, ...
    'max_node_count',63,'numerical_guard_m',1e-10);
fo=struct('max_subdivision_depth',4,'max_node_count',63, ...
    'force_guard_N',1e-10);
J=zeros(3,10);J(3,1)=-2;
H=TRAJECTORY_C9_FLAT_BERNSTEIN.build(0,1,J,J,repmat(J(:,1),1,4));
% An analytically exact degree-23 elevation of x=t+0.1*t^3.
P=zeros(3,24);P(3,:)=-2;
for i=0:23
    P(1,i+1)=i/23+0.1*i*(i-1)*(i-2)/(23*22*21);
end
start=J;start(1,2)=1;start(1,4)=0.6;
finish=start;finish(1,1)=1.1;finish(1,2)=1.3;
finish(1,3)=0.6;
X=TRAJECTORY_C9_FLAT_BERNSTEIN.build( ...
    0,1,start,finish,P(:,11:14));
assert(max(abs(X.control_points_m(:)-P(:)))<1e-9, ...
    'CHECK_C9_JOINT:Piece','The synthetic polynomial does not match.');
V=[0 0 0;1 0 0;0 1 0;0 0 1];
F=[1 3 2;1 2 4;1 4 3;2 3 4];
items={ ...
    OBSTACLE_INFORMATION.define(1,'sphere',[0 6 0],0.3), ...
    OBSTACLE_INFORMATION.define(2,'ellipsoid',[0 6 0],[.5 1 2], ...
        'euler_deg',[20 40 50]), ...
    OBSTACLE_INFORMATION.define(3,'box',[0 6 0],[1 .6 2], ...
        'euler_deg',[5 25 40]), ...
    OBSTACLE_INFORMATION.define(4,'cylinder',[0 6 0],[.5 2], ...
        'euler_deg',[20 20 15]), ...
    OBSTACLE_INFORMATION.define(5,'capsule',[0 6 0],[.3 1]), ...
    OBSTACLE_INFORMATION.define(6,'cone',[0 6 0],[.5 2], ...
        'euler_deg',[10 20 30]), ...
    OBSTACLE_INFORMATION.define(7,'frustum',[0 6 0],[.8 .3 1]), ...
    OBSTACLE_INFORMATION.define(8,'pyramid',[0 6 0],[1 2]), ...
    OBSTACLE_INFORMATION.define(9,'regular_prism',[0 6 0],[6 .7 1]), ...
    OBSTACLE_INFORMATION.define(10,'torus',[0 6 0],[1 .2]), ...
    OBSTACLE_INFORMATION.define(11,'polygon_prism',[0 6 0], ...
        struct('outline',[-1 -1;1 -1;1 1;-1 1],'height',2)), ...
    OBSTACLE_INFORMATION.define(12,'polyhedron',[0 6 0], ...
        struct('vertices',V,'faces',F))};
observed=[items{:}];
G=TRAJECTORY_GENERATOR(struct('ROBUST_TUBE_ENABLED',false));
% Pair the old independent certificates, then the new integrated one.
geom=TRAJECTORY_TAUT_FULLBODY_CERTIFICATE(X,observed,r,A,go);
force=TRAJECTORY_C9_CONTINUOUS_THRUST(X,A,fo);
fast=G.certify_c9_joint_fast(X,observed,r,A,go,fo);
assert(geom.certified&&force.certified&&fast.certified&& ...
    ~fast.safe_to_commit&&fast.checked_leaf_count>0 && ...
    isequal(fast.considered_obstacle_ids,[observed.id]), ...
    'CHECK_C9_JOINT:Clear','Joint 12-shape proof does not agree with baseline.');
assert(fast.minimum_tension_lower_bound_N<= ...
    geom.minimum_model_tension_lower_bound_N+1e-7 && ...
    fast.thrust_lower_bound_N<=force.thrust_upper_bound_N+1e-7 && ...
    fast.thrust_upper_bound_N>=force.thrust_lower_bound_N-1e-7, ...
    'CHECK_C9_JOINT:Force','Inconsistent model-bounded force/tension.');
% A nearby, but provably separate, shape MUST use directed support,
% not only broadphase balls. No world-axis avoidance direction is assumed.
near=OBSTACLE_INFORMATION.define(13,'sphere',[0 2.4 -1],.25);
nearR=G.certify_c9_joint_fast(X,near,r,A,go,fo);
assert(nearR.certified&&nearR.shape_support_calls>0 && ...
    ~nearR.safe_to_commit, ...
    'CHECK_C9_JOINT:Directed','Directional support path not certified.');
% Twelve DIFFERENT shapes close enough that the outer ball CANNOT reject
% them, all at once.  A distant 12-shape list alone does not establish
% multi-obstacle online feasibility or scaling.
prepared=TRAJECTORY_OBSTACLE_SUPPORT.prepare(observed);
close12=observed;
ey=[0;1;0]; centre=mean(X.control_points_m,2);
for j=1:numel(close12)
    % For arbitrary SO(3), exact negative-y extent from source support.
    negative_y_extent=TRAJECTORY_OBSTACLE_SUPPORT.value(prepared(j),-ey) ...
        +prepared(j).center.'*ey;
    % 0.6m is a SYNTHETIC test clearance, never a production fallback.
    close12(j).position=centre+[0;negative_y_extent+0.6;0];
end
many=G.certify_c9_joint_fast(X,close12,r,A,go,fo);
assert(many.certified && many.outer_rejections==0 && ...
    many.near_obstacle_leaf_checks>=12 && ...
    many.shape_support_calls>=12 && ...
    ~many.safe_to_commit && ...
    isequal(many.considered_obstacle_ids,[close12.id]), ...
    'CHECK_C9_JOINT:MultiNear', ...
    'All twelve close shapes must be checked using the common support path.');
reverse=G.certify_c9_joint_fast(X,close12(end:-1:1),r,A,go,fo);
assert(reverse.certified && ...
    reverse.near_obstacle_leaf_checks==many.near_obstacle_leaf_checks && ...
    isequal(sort(reverse.considered_obstacle_ids), ...
    sort(many.considered_obstacle_ids)), ...
    'CHECK_C9_JOINT:Order','Obstacle order changed the geometric proof.');
% The same shape functions must handle arbitrary new IDs and counts.
extra=close12;
for j=1:numel(extra)
    extra(j).id=extra(j).id+100;
    extra(j).position(1)=extra(j).position(1)+0.02;
end
close24=[close12 extra];
twentyfour=G.certify_c9_joint_fast(X,close24,r,A,go,fo);
assert(twentyfour.certified && twentyfour.outer_rejections==0 && ...
    twentyfour.near_obstacle_leaf_checks>=24 && ...
    twentyfour.shape_support_calls>=24 && ...
    isequal(twentyfour.considered_obstacle_ids,[close24.id]), ...
    'CHECK_C9_JOINT:Multi24', ...
    'Variable-count, close-range heterogeneous shapes were not proved.');
% One colliding shape hidden after 12 safe shapes must still reject.
mid_after=OBSTACLE_INFORMATION.define(501,'sphere',[0.5 0 -1],.05);
colliding_many=G.certify_c9_joint_fast(X,[close12 mid_after],r,A,go,fo);
assert(~colliding_many.certified && ~colliding_many.safe_to_commit ...
    && any(colliding_many.unresolved_obstacle_ids==501), ...
    'CHECK_C9_JOINT:MultiCollision', ...
    'A later colliding obstacle was incorrectly declared safe.');
% Warm measurements: not correctness criteria, no hard-coded time gate.
G.certify_c9_joint_fast(X,close12,r,A,go,fo);
G.certify_c9_joint_fast(X,close24,r,A,go,fo);
n_multi=15;close12_ms=zeros(1,n_multi);close24_ms=zeros(1,n_multi);
for k=1:n_multi
    tic12=tic;Z12=G.certify_c9_joint_fast(X,close12,r,A,go,fo);
    close12_ms(k)=toc(tic12)*1000;
    tic24=tic;Z24=G.certify_c9_joint_fast(X,close24,r,A,go,fo);
    close24_ms(k)=toc(tic24)*1000;
    assert(Z12.certified && Z24.certified, ...
        'CHECK_C9_JOINT:MultiRepeat','Repeated heterogeneous test changed.');
end
% Actual cable-intersecting obstacle must NEVER receive a safety proof.
mid=OBSTACLE_INFORMATION.define(14,'sphere',[0 0 -1],.05);
collision=G.certify_c9_joint_fast(H,mid,r,A,go,fo);
assert(~collision.certified && ~collision.safe_to_commit, ...
    'CHECK_C9_JOINT:Cable','Cable midpoint collision falsely certified.');
% Tube ON must not share a nominal result/cache or shrink radii.
side=OBSTACLE_INFORMATION.define(15,'sphere',[.6 0 -1],.05);
assert(G.certify_c9_joint_fast(H,side,r,A,go,fo).certified, ...
    'CHECK_C9_JOINT:Nominal','Nominal clearance unexpectedly rejected.');
rob=go;rob.robust_tube_enabled=true;
rob.uncertainty_bounds_m=struct('uav_m',.8,'cable_m',.8,'payload_m',.8);
Gt=TRAJECTORY_GENERATOR(struct('ROBUST_TUBE_ENABLED',true));
robR=Gt.certify_c9_joint_fast(H,side,r,A,rob,fo);
assert(~robR.certified&&~robR.safe_to_commit, ...
    'CHECK_C9_JOINT:Tube','Robust tube failed to reject close obstacle.');
% Force limit from live authority, and time-varying estimated load mass.
cap=A;cap.thrust_limits_N=[0;20];
capR=G.certify_c9_joint_fast(H,observed,r,cap,go,fo);
assert(~capR.certified,'CHECK_C9_JOINT:Actuator', ...
    'Nominal thrust limit is ignored.');
heavy=A;heavy.payload_mass_kg=2;
heavyR=G.certify_c9_joint_fast(H,observed,r,heavy,go,fo);
baseR=G.certify_c9_joint_fast(H,observed,r,A,go,fo);
assert(heavyR.certified&&baseR.certified && ...
    heavyR.thrust_lower_bound_N>baseR.thrust_lower_bound_N+5, ...
    'CHECK_C9_JOINT:Mass','Latest estimated load mass was not used.');
% A force-independent rejected freefall must fail even with no obstacles.
freeP=zeros(3,24);
for i=0:23
    freeP(:,i+1)=0.5*A.gravity_world_mps2*i*(i-1)/(23*22);
end
free=struct('control_points_m',freeP,'t0_s',0,'duration_s',1);
freeR=G.certify_c9_joint_fast(free,observed([]),r,A,go,fo);
assert(~freeR.certified, ...
    'CHECK_C9_JOINT:Freefall','Zero-tension freefall was approved.');
% All-time proof must be coordinate-equivariant, not a chosen world side.
a=.37;b=.61;
Q=[cos(a) -sin(a) 0;sin(a) cos(a) 0;0 0 1]* ...
    [cos(b) 0 sin(b);0 1 0;-sin(b) 0 cos(b)];
XR=X;XR.control_points_m=Q*X.control_points_m;
AR=A;AR.gravity_world_mps2=Q*A.gravity_world_mps2;
OR=observed;
for j=1:numel(OR)
    OR(j).position=Q*OR(j).position;
    OR(j).rotation=Q*OR(j).rotation;
end
rotR=G.certify_c9_joint_fast(XR,OR,r,AR,go,fo);
assert(rotR.certified && ...
    abs(rotR.thrust_upper_bound_N-fast.thrust_upper_bound_N)<1e-6, ...
    'CHECK_C9_JOINT:SO3','SO(3) coordinate covariance lost.');
% Warm timing: compare exactly one 12-shape C9 dynamic model task.
G.certify_c9_joint_fast(X,observed,r,A,go,fo);
TRAJECTORY_TAUT_FULLBODY_CERTIFICATE(X,observed,r,A,go);
TRAJECTORY_C9_CONTINUOUS_THRUST(X,A,fo);
nrun=5;times_new=zeros(1,nrun);times_old=zeros(1,nrun);
for k=1:nrun
    s=tic;
    Z=G.certify_c9_joint_fast(X,observed,r,A,go,fo);
    times_new(k)=toc(s)*1000;
    assert(Z.certified,'CHECK_C9_JOINT:Repeat','Joint result unstable.');
    s=tic;
    U=TRAJECTORY_TAUT_FULLBODY_CERTIFICATE(X,observed,r,A,go);
    T=TRAJECTORY_C9_CONTINUOUS_THRUST(X,A,fo);
    times_old(k)=toc(s)*1000;
    assert(U.certified&&T.certified, ...
        'CHECK_C9_JOINT:Repeat','Reference certificate unstable.');
end
R=struct('status', ...
    'PASS_C9_JOINT_FAST_MULTI_OBSTACLE_12_SHAPES__NO_TORQUE_HLC_COMMIT', ...
    'all_time_geometry',fast.certified_continuous_geometry, ...
    'all_time_thrust',fast.certified_continuous_thrust, ...
    'all_time_tension',fast.certified_continuous_tension, ...
    'shape_count',numel(observed), ...
    'near_shape_support_calls',nearR.shape_support_calls, ...
    'close12_support_calls',many.shape_support_calls, ...
    'close24_support_calls',twentyfour.shape_support_calls, ...
    'close12_near_checks',many.near_obstacle_leaf_checks, ...
    'close24_near_checks',twentyfour.near_obstacle_leaf_checks, ...
    'close12_median_ms',median(close12_ms), ...
    'close24_median_ms',median(close24_ms), ...
    'close12_max_ms',max(close12_ms), ...
    'close24_max_ms',max(close24_ms), ...
    'close12_samples_ms',close12_ms, ...
    'close24_samples_ms',close24_ms, ...
    'unsafe_cable_rejected',~collision.certified, ...
    'robust_tube_rejected',~robR.certified, ...
    'input_limit_rejected',~capR.certified, ...
    'SO3_invariance',rotR.certified, ...
    'median_joint_ms',median(times_new), ...
    'median_separate_ms',median(times_old), ...
    'joint_samples_ms',times_new,'separate_samples_ms',times_old, ...
    'native_hlc_certified',false,'torque_certified',false, ...
    'safe_to_commit',false);
save(fullfile(root,'TRAJECTORY_C9_JOINT_RESULT.mat'),'R');
fp=fopen(fullfile(root,'TRAJECTORY_C9_JOINT_RESULT.txt'),'wt');
assert(fp>0,'CHECK_C9_JOINT:Output','Cannot write results.');
cl=onCleanup(@()fclose(fp));
fprintf(fp,'%s\n',R.status);
fprintf(fp,'shapes=%d support_calls_near=%d tube=PASS mass=PASS SO3=PASS\n', ...
    R.shape_count,R.near_shape_support_calls);
fprintf(fp,'joint_median_ms=%.6f separate_median_ms=%.6f\n', ...
    R.median_joint_ms,R.median_separate_ms);
fprintf(fp,'joint_samples_ms=%s\n',mat2str(R.joint_samples_ms,8));
fprintf(fp,'separate_samples_ms=%s\n',mat2str(R.separate_samples_ms,8));
fprintf(fp,'close12: support=%d near_leaf_checks=%d median_ms=%.6f max_ms=%.6f\n', ...
    R.close12_support_calls,R.close12_near_checks, ...
    R.close12_median_ms,R.close12_max_ms);
fprintf(fp,'close24: support=%d near_leaf_checks=%d median_ms=%.6f max_ms=%.6f\n', ...
    R.close24_support_calls,R.close24_near_checks, ...
    R.close24_median_ms,R.close24_max_ms);
fprintf(fp,'close12_samples_ms=%s\n',mat2str(R.close12_samples_ms,8));
fprintf(fp,'close24_samples_ms=%s\n',mat2str(R.close24_samples_ms,8));
fprintf(fp,'torque/HLC/ODE tracking=NOT_CERTIFIED; commit=FORBIDDEN\n');
clear cl
zip(fullfile(root,'TRAJECTORY_C9_MULTI_OBSTACLE_RESULTS_FOR_CHATGPT.zip'), ...
    {'TRAJECTORY_C9_JOINT_RESULT.mat', ...
     'TRAJECTORY_C9_JOINT_RESULT.txt'},root);
delete(fullfile(root,'TRAJECTORY_C9_JOINT_RESULT.mat'));
delete(fullfile(root,'TRAJECTORY_C9_JOINT_RESULT.txt'));
end
