function A=CHECK_TRIGGER_SIM_CONTINUATION_SOURCE()
% Offline preflight test for the NEW live Sim t0->now->4s wiring.
% This proves source identity and fail-closed interfaces, NOT that a real
% 65-second trajectory has a successful Picard tube or true flight safety.
A=struct('status','FAIL_SIM_CONTINUATION_SOURCE_AUDIT', ...
    'reason','','cases',0,'failures',0, ...
    'initial_taut_source_pass',false, ...
    'original_hold_source_pass',false, ...
    'initial_predict_refused',false, ...
    'integration_opt_in_source',false, ...
    'actual_plant_state_peek_detected',false);
try
    A.cases=A.cases+1;
    S=TRIGGER_SIM_INITIAL_TAUT_SOURCE();
    assert(S.simulation_initial_set_proven && ...
        S.sim_true_mass_rate_bound_kg_s==0 && ...
        S.initial_ekf_first24_equal_plant && ...
        ~S.safe_to_commit,'CHECK_TRIGGER_SIM_CONTINUATION:SimSeed',S.reason);
    A.initial_taut_source_pass=true;
    A.cases=A.cases+1;
    B=TRIGGER_TAUT_SOURCE_INVARIANTS();
    assert(B.source_bound_invariance, ...
        'CHECK_TRIGGER_SIM_CONTINUATION:TautSource',B.reason);
    A.cases=A.cases+1;
    H=TRIGGER_ORIGINAL_SIM_ZOH_SOURCE_SCOPE();
    assert(H.hlc_source_pinned && H.sim_zero_order_hold_source, ...
        'CHECK_TRIGGER_SIM_CONTINUATION:InputHold',H.reason);
    A.original_hold_source_pass=true;
    A.cases=A.cases+1;
    OR=TRIGGER_SIM_RUNNER_ORDER_PROOF();
    assert(OR.previous_controller_input_alignment_proven, ...
        'CHECK_TRIGGER_SIM_CONTINUATION:RunnerOrder',OR.reason);
    A.cases=A.cases+1;
    obj=TRIGGER_SIM_TRUE_SET_CONTINUATION();
    R=obj.predict4s(struct([]),struct());
    assert(~R.safe_to_commit && ...
        strcmp(R.status,'UNKNOWN_SIM_4S_CHAIN_FAIL_CLOSED') && ...
        ~R.t0_to_now_conditional, ...
        'CHECK_TRIGGER_SIM_CONTINUATION:NoAnchor', ...
        'A future 4-second proof was accepted without a genuine t0 history.');
    A.initial_predict_refused=true;
    A.cases=A.cases+1;
    flow=fileread(which('TRIGGER_SIM_TRUE_SET_CONTINUATION'));
    % Only MATLAB executable lines: comments cannot satisfy the wiring.
    clean=regexprep(flow,'(?m)%[^\n]*','');
    assert(contains(clean,'advance_original_held_plant(') && ...
        contains(clean,'TRIGGER_CLOSED_LOOP_FROM_SOURCE_LIMITS(D)') && ...
        contains(clean,'TRIGGER_SIM_INITIAL_TAUT_SOURCE()') && ...
        contains(clean,'TRIGGER_SIM_RUNNER_ORDER_PROOF()') && ...
        contains(clean,'TRIGGER_EXACT_BINARY64_TIME_SPAN(') && ...
        contains(clean,'agent.controller.result.input') && ...
        ~contains(clean,'agent.plant.state'), ...
        'CHECK_TRIGGER_SIM_CONTINUATION:Wiring', ...
        'Missing original source connection or illegal future plant truth peek.');
    A.cases=A.cases+1;
    root=fileread(which('REPLANNING_SYSTEM'));
    assert(contains(root,'TRIGGER_SIM_TRUE_SET_CHAIN') && ...
        contains(root,'obj.sim_true_set_chain.observe(time_s,agent)') && ...
        contains(root,'obj.sim_true_set_chain.predict4s(') && ...
        contains(root,'trigger_result.true_set_4s_status=cert.status') && ...
        contains(root,'trigger_result.safe_to_commit=false;'), ...
        'CHECK_TRIGGER_SIM_CONTINUATION:ProductionWiring', ...
        'Optional live result wiring into original trigger is absent.');
    A.integration_opt_in_source=true;
    A.cases=A.cases+1;
    clk=TRIGGER_EXACT_BINARY64_TIME_SPAN(0,4);
    assert(clk.valid && clk.exact_ge_4s, ...
        'CHECK_TRIGGER_SIM_CONTINUATION:Duration');
    A.status='PASS_SOURCE_ANCHORED_T0_NOW_4S_WIRING__ACTUAL_FLIGHT_NOT_TESTED';
    A.reason=['Zero-time Sim seed and taut source pins hold; original input/hold ' ...
        'source checked; no plant state peek; both real-tick Picard and future 4s ' ...
        'interfaces are called by opt-in live replanner. Need real Flight test ' ...
        'and independent numerical solver error containment.'];
catch ME
    A.failures=1;
    A.reason=[ME.identifier ' | ' ME.message];
end
try
    save('TRIGGER_SIM_CONTINUATION_SOURCE_RESULT.mat','A');
    fid=fopen('TRIGGER_SIM_CONTINUATION_SOURCE_RESULT.txt','w');
    if fid>0
        fprintf(fid,'%s\ncases=%d failures=%d\n%s\n', ...
            A.status,A.cases,A.failures,A.reason);
        fclose(fid);
    end
catch
end
end
