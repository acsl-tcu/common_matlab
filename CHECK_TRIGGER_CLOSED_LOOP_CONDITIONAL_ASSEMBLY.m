function A=CHECK_TRIGGER_CLOSED_LOOP_CONDITIONAL_ASSEMBLY()
% Disposable common_matlab/ test of assembled conditional mathematical path.
% All fixture data are invented in THIS test; never publish as a bound on
% the real EKF, physical mass, HLC, or actual obstacle observations.
A=struct('status','NOT_RUN','reason','', ...
    'completed_stage','NONE','conditional_geometry_pass',false, ...
    'invalid_mass_rejected',false,'missing_bounds_rejected',false, ...
    'no_flight_safety_grant',false);
try
    p=zeros(21,1);p(1)=1.4;p(6:8)=[0.05;0.06;0.08];
    p(9)=9.80665;p(20)=0.5;p(21)=2;
    e=struct('p',zeros(3,1),'q',zeros(3,1), ...
        'v',zeros(3,1),'w',zeros(3,1), ...
        'pL',[0;0;-2],'vL',zeros(3,1), ...
        'pT',[0;0;-1],'wL',zeros(3,1));
    % The caller must independently prove these ranges; the numbers are
    % used only to test the matrix wiring and fail-closed logic.
    r=1e-9;times=[0 0.002 0.004];K=numel(times)-1;
    u=[(p(1)+p(20))*p(9);0;0;0];
    sh=struct('id',70001,'center0',[9;0;0], ...
        'rotation',eye(3),'dimensions',0.5, ...
        'type','sphere','is_stationary',true);
    C=struct('ekf_now',e,'error_lower',-r*ones(24,1), ...
        'error_upper',r*ones(24,1), ...
        'cable_length_lower_m',2,'cable_length_upper_m',2, ...
        'time_grid_s',times, ...
        'true_mass_lower_kg',repmat(p(20)-r,1,K), ...
        'true_mass_upper_kg',repmat(p(20)+r,1,K), ...
        'other_param_lower',repmat(p,1,K), ...
        'other_param_upper',repmat(p,1,K), ...
        'held_input_lower',repmat(u-r,1,K), ...
        'held_input_upper',repmat(u+r,1,K), ...
        'observed_prepared_shapes',sh, ...
        'body',struct('r_uav_m',0.2,'r_cable_m',0.02, ...
                      'r_payload_m',0.15));
    F=TRIGGER_CLOSED_LOOP_CONDITIONAL_ASSEMBLY(C);
    A.completed_stage=F.completed_stage;
    A.conditional_geometry_pass=F.conditional_geometry_pass;
    % A chain may be too wide for Picard/positive-tension to succeed.
    % Such failures are genuine UNKNOWN rather than fabricated PASS.
    assert(~F.safe_to_commit && ~F.full_4s_continuous_safety_proven, ...
        'CHECK_TRIGGER_CLOSED_LOOP_CONDITIONAL_ASSEMBLY:Unsafe', ...
        'The fixture must never authorize flight.');
    A.no_flight_safety_grant=true;
    invalid=C;invalid.true_mass_lower_kg(2)=-1;
    G=TRIGGER_CLOSED_LOOP_CONDITIONAL_ASSEMBLY(invalid);
    A.invalid_mass_rejected=~G.conditional_geometry_pass && ...
        ~G.safe_to_commit && ...
        any(strcmp(G.status,{'UNKNOWN_MASS_PARAMETER', ...
            'UNKNOWN_CLOSED_LOOP_ASSEMBLY_EXCEPTION'}));
    missing=rmfield(C,'error_lower');
    H=TRIGGER_CLOSED_LOOP_CONDITIONAL_ASSEMBLY(missing);
    A.missing_bounds_rejected=~H.conditional_geometry_pass && ...
        ~H.safe_to_commit;
    assert(A.invalid_mass_rejected&&A.missing_bounds_rejected, ...
        'CHECK_TRIGGER_CLOSED_LOOP_CONDITIONAL_ASSEMBLY:FailClosed', ...
        'Invalid or missing exogenous enclosure was accepted.');
    if F.conditional_geometry_pass
        A.status='PASS_SYNTHETIC_END_TO_END_CONDITIONAL_CHAIN__NOT_FLIGHT_PROOF';
    else
        A.status='PASS_FAIL_CLOSED_ASSEMBLY_WIRING__FULL_CHAIN_UNESTABLISHED';
        A.reason=['Fixture did not reach full geometric separation: ' ...
            F.status ' | ' F.reason];
    end
catch ME
    A.status='NOT_COMPLETED_CONDITIONAL_CHAIN_WIRING';
    A.reason=[ME.identifier ' | ' ME.message];
end
save('TRIGGER_CLOSED_LOOP_ASSEMBLY_RESULT.mat','A');
f=fopen('TRIGGER_CLOSED_LOOP_ASSEMBLY_RESULT.txt','w');
if f>=0
    fprintf(f,'status=%s\ncompleted_stage=%s\nconditional_geometry=%d\ninvalid_mass_rejected=%d\nmissing_bounds_rejected=%d\nno_flight_safety_grant=%d\nreason=%s\n', ...
        A.status,A.completed_stage,A.conditional_geometry_pass, ...
        A.invalid_mass_rejected,A.missing_bounds_rejected, ...
        A.no_flight_safety_grant,A.reason);
    fclose(f);
end
end
