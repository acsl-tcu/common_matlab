function R=CHECK_TRIGGER_THREE_RUN_WORKLOAD()
% Check recorded workload before and during the first REAL observation.
% Uses only saved Flight captures: no runner call, no replanner state change.
% Reports numeric workload separately from unproved scheduler/JIT/GC causes.
% All outputs are under common_matlab/ independent of pwd.
root=fileparts(mfilename('fullpath'));
R=struct('status','FAIL_THREE_RUN_WORKLOAD','runs',struct([]), ...
    'reason','','safe_to_commit',false, ...
    'mat_path',fullfile(root,'TRIGGER_THREE_RUN_WORKLOAD_RESULT.mat'), ...
    'txt_path',fullfile(root,'TRIGGER_THREE_RUN_WORKLOAD_RESULT.txt'));
try
    runstats=cell(1,3);
    for r=1:3
        file=fullfile(root,sprintf('TRIGGER_DIAG_RUN_%02d.mat',r));
        assert(exist(file,'file')==2, ...
            'CHECK_TRIGGER_THREE_RUN_WORKLOAD:Missing', ...
            'No saved capture for Run %d at %s',r,file);
        data=load(file,'C');
        assert(isfield(data,'C')&&isstruct(data.C)&&isscalar(data.C), ...
            'CHECK_TRIGGER_THREE_RUN_WORKLOAD:Capture', ...
            'Saved capture must have scalar struct C.');
        C=data.C;
        need={'replanner_ms','predicted','time_s','rhs_evals', ...
            'rejected_steps','acquired','new_count','predictor_ms', ...
            'sensor_ms','memory_ms','geometry_ms','reference_ms'};
        assert(all(isfield(C,need)), ...
            'CHECK_TRIGGER_THREE_RUN_WORKLOAD:Schema', ...
            'Capture has an incompatible workload schema.');
        y=double(C.replanner_ms(:).');
        pred=logical(C.predicted(:).');
        rhs=double(C.rhs_evals(:).');
        rej=double(C.rejected_steps(:).');
        tm=double(C.time_s(:).');
        acq=logical(C.acquired(:).');
        newly=double(C.new_count(:).');
        n=numel(y);
        assert(all(cellfun(@(s)numel(C.(s))==n,need)) && ...
            all(isfinite(y))&&all(y>=0)&&any(pred) && ...
            all(isfinite(rhs(pred))) && all(isfinite(rej(pred))), ...
            'CHECK_TRIGGER_THREE_RUN_WORKLOAD:Length', ...
            'Invalid or incomplete logged numeric workload.');
        normal_rhs=mode(rhs(pred)); % observed mode, NOT hard-coded 1120
        more_rhs=pred & rhs>normal_rhs;
        idx_first=find(pred,1,'first');
        idx_extra=find(more_rhs,1,'first');
        idx_acq=find(pred & acq & newly>0,1,'first');
        idx_spikes=find(pred & y>4); % 4 ms is a REPORT threshold, not runtime cap
        [~,peak_idx]=max(y);
        T=struct('run',r,'cycles',n,'prediction_cycles',nnz(pred), ...
            'modal_rhs',normal_rhs,'first_prediction_k',idx_first, ...
            'first_extra_rhs_k',NaN,'first_extra_rhs_time_s',NaN, ...
            'first_acquired_in_prediction_k',NaN, ...
            'first_acquired_in_prediction_time_s',NaN, ...
            'first_acquired_rhs',NaN,'first_acquired_rejected',NaN, ...
            'extra_rhs_precedes_acquisition',false, ...
            'prediction_tick_over_4_ms',numel(idx_spikes), ...
            'all_update_max_ms',y(peak_idx), ...
            'all_update_max_k',peak_idx, ...
            'spike_k',idx_spikes, ...
            'spike_rhs',rhs(idx_spikes), ...
            'spike_rejected',rej(idx_spikes), ...
            'spike_sensor_ms',double(C.sensor_ms(idx_spikes)), ...
            'spike_memory_ms',double(C.memory_ms(idx_spikes)), ...
            'spike_geometry_ms',double(C.geometry_ms(idx_spikes)), ...
            'spike_reference_ms',double(C.reference_ms(idx_spikes)), ...
            'spike_predictor_ms',double(C.predictor_ms(idx_spikes)));
        if ~isempty(idx_extra)
            T.first_extra_rhs_k=idx_extra;
            T.first_extra_rhs_time_s=tm(idx_extra);
        end
        if ~isempty(idx_acq)
            T.first_acquired_in_prediction_k=idx_acq;
            T.first_acquired_in_prediction_time_s=tm(idx_acq);
            T.first_acquired_rhs=rhs(idx_acq);
            T.first_acquired_rejected=rej(idx_acq);
        end
        T.extra_rhs_precedes_acquisition= ...
            ~isempty(idx_extra)&&~isempty(idx_acq)&&idx_extra<idx_acq;
        runstats{r}=T;
    end
    R.runs=[runstats{:}];
    R.status='PASS_RECORDED_WORKLOAD_SEPARATION__NO_CAUSAL_WCET_PROOF';
    R.reason=['First numeric integrator workload increase and first ' ...
        'genuine obstacle acquisition are logged independently. ' ...
        'Wall-clock stage spikes are not attributed to the OS/JIT/GC.'];
catch ME
    R.reason=[ME.identifier ' | ' ME.message];
end
try
    file=fopen(R.txt_path,'wt');
    assert(file>=0,'CHECK_TRIGGER_THREE_RUN_WORKLOAD:Write','Failed to open TXT.');
    close_guard=onCleanup(@()fclose(file));
    fprintf(file,'status=%s\nreason=%s\n',R.status,R.reason);
    for j=1:numel(R.runs)
        s=R.runs(j);
        fprintf(file,['run=%d cycles=%d predicted=%d modal_rhs=%d ' ...
            'first_predict_k=%d first_extra_rhs_k=%g first_extra_t=%g ' ...
            'first_acquire_k=%g first_acquire_t=%g ' ...
            'acquire_rhs=%g acquire_rejected=%g ' ...
            'extra_rhs_precedes_acquisition=%d ' ...
            'update_max_ms=%g update_max_k=%d over_4ms=%d\n'], ...
            s.run,s.cycles,s.prediction_cycles,s.modal_rhs, ...
            s.first_prediction_k,s.first_extra_rhs_k,s.first_extra_rhs_time_s, ...
            s.first_acquired_in_prediction_k, ...
            s.first_acquired_in_prediction_time_s, ...
            s.first_acquired_rhs,s.first_acquired_rejected, ...
            s.extra_rhs_precedes_acquisition,s.all_update_max_ms, ...
            s.all_update_max_k,s.prediction_tick_over_4_ms);
        for k=1:numel(s.spike_k)
            fprintf(file, ...
                '   k=%d rhs=%g rejects=%g sensor=%g memory=%g geometry=%g ref=%g predictor=%g\n', ...
                s.spike_k(k),s.spike_rhs(k),s.spike_rejected(k), ...
                s.spike_sensor_ms(k),s.spike_memory_ms(k), ...
                s.spike_geometry_ms(k),s.spike_reference_ms(k), ...
                s.spike_predictor_ms(k));
        end
    end
    clear close_guard
    save(R.mat_path,'R');
catch ME
    warning('CHECK_TRIGGER_THREE_RUN_WORKLOAD:Save','%s',ME.message);
end
end
