function R = CHECK_GROUND_INFORMATION_SEPARATE()
% CHECK_GROUND_INFORMATION_SEPARATE
% Independent, finite synthetic tests. NEVER touches the flight, EKF,
% trigger, HLC, sensor, memory or user-defined obstacle scenarios.
% Results are written in common_matlab/ regardless of current pwd.
% MATLAB run: cd(common_matlab); clear classes; rehash;
%             R=CHECK_GROUND_INFORMATION_SEPARATE(); disp(R.status)
root=fileparts(mfilename('fullpath'));
obdir=fullfile(root,'reference','REPLANNING_SYSTEM','OBSTACLE_INFORMATION');
trdir=fullfile(root,'reference','REPLANNING_SYSTEM','TRAJECTORY_GENERATION');
assert(isfile(fullfile(obdir,'GROUND_INFORMATION.m')) && ...
       isfile(fullfile(obdir,'OBSTACLE_INFORMATION.m')) && ...
       isfile(fullfile(trdir,'TRAJECTORY_C9_GROUND_LEAF.m')), ...
    'CHECK_GROUND:Layout','Ground must be a standalone module in OBSTACLE_INFORMATION/.');
addpath(obdir,trdir,'-begin');
R=struct('status','FAIL_NOT_RUN','separate_file',false, ...
    'ground_definition_correct',false, ...
    'finite_obstacle_definitions_unchanged',false, ...
    'above_ground_accepted',false,'ground_contact_rejected',false, ...
    'uav_cable_crossing_rejected',false, ...
    'tube_inflation_rejected',false, ...
    'polynomial_nominal_accepted',false, ...
    'polynomial_tube_rejected',false, ...
    'all_time_geometry_ground_checked',false, ...
    'error_identifier','','error_message','');
try
    path=which('GROUND_INFORMATION');
    R.separate_file=strcmpi(path,fullfile(obdir,'GROUND_INFORMATION.m'));
    assert(R.separate_file,'CHECK_GROUND:Shadowed','Wrong GROUND_INFORMATION class on MATLAB path.');

    G=GROUND_INFORMATION.definition();
    R.ground_definition_correct=isstruct(G)&&isscalar(G)&& ...
        isfield(G,'type')&&strcmp(G.type,'ground_halfspace')&& ...
        isfield(G,'normal_world')&&isequal(G.normal_world,[0;0;1])&& ...
        isfield(G,'height_m')&&isequal(G.height_m,0)&& ...
        isfield(G,'occupied_side')&&strcmp(G.occupied_side,'negative')&& ...
        isfield(G,'always_known')&&isequal(G.always_known,true);
    assert(R.ground_definition_correct,'CHECK_GROUND:Definition', ...
        'Ground must describe the known infinite z<=0 occupied halfspace.');

    O=OBSTACLE_INFORMATION.definitions();
    assert(isstruct(O),'CHECK_GROUND:FiniteObstacles','Bad obstacle definitions.');
    names=cell(1,numel(O));
    for j=1:numel(O)
        names{j}=char(O(j).geometry.type);
    end
    R.finite_obstacle_definitions_unchanged= ...
        ~any(strcmp(names,G.type))&& ...
        numel(unique([O.id]))==numel(O);
    assert(R.finite_obstacle_definitions_unchanged,'CHECK_GROUND:SensorLeak', ...
        'Always-known ground must not appear in finite obstacle definitions.');

    % Test the continuously enclosed taut configuration (not samples).
    % Coordinates and sizes below are ONLY local test fixtures.
    L=2; P=repmat([0;0;2],1,24); q=[0;0;-1];
    r=[0.5,0.5,0.0]; guard=0;
    [R.above_ground_accepted,clearance]= ...
        TRAJECTORY_C9_GROUND_LEAF(P,q,0,L,r,G,guard);
    assert(R.above_ground_accepted && all(clearance>0), ...
        'CHECK_GROUND:Above','Strict separation above ground must pass.');

    Pcontact=repmat([0;0;0.5],1,24);
    [accepted,clearance]=TRAJECTORY_C9_GROUND_LEAF( ...
        Pcontact,q,0,L,r,G,guard);
    R.ground_contact_rejected=~accepted&&clearance(2)==0;
    assert(R.ground_contact_rejected,'CHECK_GROUND:Contact', ...
        'A touching payload must not be certified.');

    qup=[0;0;1];
    [accepted,clearance]=TRAJECTORY_C9_GROUND_LEAF( ...
        P,qup,0,L,r,G,guard);
    R.uav_cable_crossing_rejected=~accepted&& ...
        clearance(1)<0&&clearance(3)<=0;
    assert(R.uav_cable_crossing_rejected,'CHECK_GROUND:Cable', ...
        'A UAV/cable reaching ground must not pass.');

    % Tube ON increases effective physical radii; not an invented margin.
    [accepted,clearance]=TRAJECTORY_C9_GROUND_LEAF( ...
        P,q,0,L,r+[0,1.5,0],G,guard);
    R.tube_inflation_rejected=~accepted&&clearance(2)==0;
    assert(R.tube_inflation_rejected,'CHECK_GROUND:Tube', ...
        'Uncertainty inflation touching the ground must not pass.');

    % Independent whole-time C7 polynomial geometry certificate.
    U=struct('control_points_m',repmat([0;0;4],1,16), ...
        't0_s',0,'duration_s',1);
    Q=struct('control_points_m',repmat([0;0;2],1,16), ...
        't0_s',0,'duration_s',1);
    segments=struct('uav',U,'payload',Q);
    radius=struct('uav_m',0.5,'payload_m',0.5,'cable_m',0);
    opt=struct('robust_tube_enabled',false,'max_subdivision_depth',0, ...
        'numerical_guard_m',0);
    ansnom=TRAJECTORY_CONTINUOUS_GEOMETRY_CERTIFICATE( ...
        segments,struct([]),radius,opt);
    R.polynomial_nominal_accepted=ansnom.certified && ...
        ansnom.ground_certified && ansnom.ground_checked && ...
        isempty(ansnom.considered_obstacle_ids);
    assert(R.polynomial_nominal_accepted,'CHECK_GROUND:PolynomialNominal', ...
        'Ground safety with no observed finite obstacles must be checked.');
    opt.robust_tube_enabled=true;
    opt.uncertainty_bounds_m=struct( ...
        'uav_m',0,'payload_m',1.5,'cable_m',0);
    anstube=TRAJECTORY_CONTINUOUS_GEOMETRY_CERTIFICATE( ...
        segments,struct([]),radius,opt);
    R.polynomial_tube_rejected=~anstube.certified && ...
        ~anstube.ground_certified && ...
        ~isempty(anstube.ground_unresolved_intervals_s);
    assert(R.polynomial_tube_rejected,'CHECK_GROUND:PolynomialTube', ...
        'Tube-on payload contact must not be certified by whole-time geometry.');
    R.all_time_geometry_ground_checked=true;
    R.status='PASS_GROUND_INFORMATION_SEPARATE_ALL_TIME_BODY_GEOMETRY';
catch ME
    R.status='FAIL_GROUND_INFORMATION_SEPARATE';
    R.error_identifier=ME.identifier;
    R.error_message=ME.message;
    write_result(root,R);
    rethrow(ME)
end
write_result(root,R);
end

function write_result(root,R)
save(fullfile(root,'GROUND_INFORMATION_SEPARATE_RESULT.mat'),'R');
fid=fopen(fullfile(root,'GROUND_INFORMATION_SEPARATE_RESULT.txt'),'wt');
if fid<0,error('CHECK_GROUND:IO','Cannot write audit summary.');end
closer=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\n',R.status);
keys={'separate_file','ground_definition_correct', ...
    'finite_obstacle_definitions_unchanged','above_ground_accepted', ...
    'ground_contact_rejected','uav_cable_crossing_rejected', ...
    'tube_inflation_rejected','polynomial_nominal_accepted', ...
    'polynomial_tube_rejected','all_time_geometry_ground_checked'};
for j=1:numel(keys)
    fprintf(fid,'%s=%d\n',keys{j},R.(keys{j}));
end
if ~isempty(R.error_identifier)
    fprintf(fid,'error_identifier=%s\n',R.error_identifier);
    fprintf(fid,'error_message=%s\n',R.error_message);
end
end
