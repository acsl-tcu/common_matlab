function R=CHECK_TRIGGER_SPIKE_HOTPATH()
% Fast standalone geometry/event-decision parity guard; NO Flight / MEX.
% Runs automatically before CHECK_TRIGGER_5RUN_SPIKE_CAUSES.
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'reference','REPLANNING_SYSTEM','FUTURE_COLLISION_TRIGGER');
addpath(base,'-begin');
core=fileread(fullfile(base,'FUTURE_COLLISION_TRIGGER.m'));
sweep_code=fileread(fullfile(base,'TRIGGER_NOMINAL_SWEPT_INTERVALS.m'));
assert(contains(core,'any_risk=~isempty(sweep.first_obstacle_ids)') && ...
    ~contains(core,'merged=TRIGGER_MERGE_EARLIEST_NOMINAL_RISK(') && ...
    contains(sweep_code,'frame_scale=max('), ...
    'CHECK_TRIGGER_SPIKE_HOTPATH:Wiring','Hot-path sources not installed.');
T=0:0.2:4; 
O=[-2+T;zeros(1,numel(T));zeros(1,numel(T))];
P=O-repmat([0;0;2],1,numel(T));
shapes=[ball(11,[0;0;-1],0.02) ball(12,[1;0;-1],0.02)];
configs={struct('u',O,'p',P,'obs',shapes,'old',[]), ...
    struct('u',O,'p',P,'obs',shapes,'old',11), ...
    struct('u',O,'p',P,'obs',shapes,'old',[11 12]), ...
    struct('u',O,'p',P,'obs',ball(13,[50;0;0],0.1),'old',[]), ...
    struct('u',repmat([0;0;0],1,numel(T)), ...
           'p',repmat([0;0;-2],1,numel(T)), ...
           'obs',ball(14,[0;0;-1],0.02),'old',[]), ...
    struct('u',repmat([0;0;0],1,numel(T)), ...
           'p',repmat([0;0;-2],1,numel(T)), ...
           'obs',ball(15,[1.414213562373095;0;0],0.03),'old',[])};
passed=0;
for i=1:numel(configs)
    z=configs{i};
    W=TRIGGER_NOMINAL_SWEPT_INTERVALS( ...
        z.u,z.p,T,z.obs,0.01,0.01,0.005,z.old,[]);
    empty_sample=struct('first_obstacle_ids',[], ...
        'first_ttc_s',NaN,'first_sample_index',NaN, ...
        'first_components',{{}},'new_obstacle_ids',[], ...
        'new_ttc_s',NaN,'new_sample_index',NaN,'new_components',{{}});
    M=TRIGGER_MERGE_EARLIEST_NOMINAL_RISK(empty_sample,W,T);
    assert(M.has_risk==~isempty(W.first_obstacle_ids) && ...
        M.has_new==~isempty(W.new_obstacle_ids), ...
        'CHECK_TRIGGER_SPIKE_HOTPATH:RiskParity','Risk presence mismatch.');
    if M.has_risk
        assert(isequal(M.first.ids,W.first_obstacle_ids) && ...
            isequal(M.first.bracket_s,W.first_time_bracket_s) && ...
            M.first.ttc_s==W.first_ttc_s, ...
            'CHECK_TRIGGER_SPIKE_HOTPATH:First','Earliest risk mismatch.');
        if M.has_new
            selected_ids=W.new_obstacle_ids;selected_ttc=W.new_ttc_s;
            selected_bracket=W.new_time_bracket_s;
            selected_part=W.new_parts{1};
        else
            selected_ids=W.first_obstacle_ids;selected_ttc=W.first_ttc_s;
            selected_bracket=W.first_time_bracket_s;
            selected_part=W.first_parts{1};
        end
        assert(isequal(M.selected.ids,selected_ids) && ...
            isequal(M.selected.bracket_s,selected_bracket) && ...
            M.selected.ttc_s==selected_ttc && ...
            strcmp(M.selected.component,selected_part) && ...
            strcmp(M.selected.kind,'POSSIBLE_INTERSAMPLE_CONTACT') && ...
            ~M.selected.sampled_confirmed && M.selected.intersample_possible, ...
            'CHECK_TRIGGER_SPIKE_HOTPATH:Selected','Selected new/old risk mismatch.');
    end
    passed=passed+1;
end
% Independent regression for the tilted-cable distant AABB corner.
u=repmat([0;0;0],1,2);
l=repmat([sqrt(2);0;-sqrt(2)],1,2);
x=TRIGGER_NOMINAL_SWEPT_INTERVALS(u,l,[0 0.1], ...
    ball(16,[sqrt(2);0;0],0.03),0.04,0.04,0.005,[],[]);
assert(~x.continuous_linear_interpolant_may_intersect, ...
    'CHECK_TRIGGER_SPIKE_HOTPATH:Overconservative', ...
    'Old diagonal-cable AABB false contact returned.');
passed=passed+1;
R=struct('status','PASS_SWEEP_HOTPATH_PARITY', ...
    'cases',passed,'failures',0,'flight_tested',false, ...
    'worst_case_time_proven',false);
end
function s=ball(id,c,r)
s=struct('id',id,'center0',c,'is_stationary',true, ...
    'bounding_radius_m',r,'rotation',eye(3), ...
    'dimensions',r,'type','sphere');
end
