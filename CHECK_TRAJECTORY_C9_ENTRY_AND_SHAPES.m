function R=CHECK_TRAJECTORY_C9_ENTRY_AND_SHAPES()
% One command/one upload ZIP for 12 shapes, entry necessary gate,
% and actual HLC four software input limits. Neither test commits a plan.
root=fileparts(mfilename('fullpath'));
R=struct('status','FAIL_NOT_STARTED', ...
    'error_identifier','','error_message','', ...
    'shape_status','NOT_EVALUATED', ...
    'shape_stage','NOT_EVALUATED', ...
    'shape_all12_joint','NOT_EVALUATED', ...
    'shape_near_family_count',0, ...
    'mixed_entry_shape_status','NOT_EVALUATED', ...
    'entry_status','NOT_EVALUATED', ...
    'EKF_entry_necessary_pass',false, ...
    'software_HLC_four_limits_read',false, ...
    'hlc_input_lower',NaN(4,1), ...
    'hlc_input_upper',NaN(4,1), ...
    'full_HLC_tracking_certified',false, ...
    'physical_motor_allocation_certified',false, ...
    'safe_to_commit',false,'elapsed_ms',NaN);
t0=tic;A=struct();B=struct();
try
    A=CHECK_TRAJECTORY_C9_ALL_SHAPES_HLC_SCOPE();
    R.shape_status=A.status;
    R.shape_stage=A.stage;
    R.shape_all12_joint=A.all_family_joint_geometry_status;
    R.shape_near_family_count=A.near_shape_family_checks;
    R.mixed_entry_shape_status=A.collision_mixed_shapes_status;
    B=CHECK_TRAJECTORY_C9_ENTRY_STATE_AND_HLC_LIMITS();
    R.entry_status=B.status;
    R.EKF_entry_necessary_pass=B.valid_entry_necessary_pass;
    R.software_HLC_four_limits_read=B.source_four_input_bounds_read;
    R.hlc_input_lower=B.software_lower;
    R.hlc_input_upper=B.software_upper;
    if startsWith(A.status,'PASS_12_SHAPE_')&& ...
            startsWith(B.status,'PASS_EKF_C9_ENTRY_NECESSARY_')&& ...
            A.all_family_joint_geometry_proven&& ...
            A.near_shape_family_checks==12&& ...
            ~A.safe_to_commit&&~B.hardware_motor_feasibility_proven
        R.status='PASS_12_SHAPES_EKF_ENTRY_AND_HLC_SOFTWARE_BOUNDS__HLC_PENDING';
    else
        R.status='FAIL_OR_UNKNOWN_12_SHAPE_ENTRY_COMBINED_AUDIT';
    end
catch ME
    R.status='FAIL_12_SHAPES_ENTRY_EXCEPTION';
    R.error_identifier=ME.identifier;
    R.error_message=ME.message;
end
R.elapsed_ms=1000*toc(t0);
name='TRAJECTORY_C9_ENTRY_AND_SHAPES_RESULT';
matfile=fullfile(root,[name '.mat']);
txtfile=fullfile(root,[name '.txt']);
zipfile=fullfile(root,[name '_FOR_CHATGPT.zip']);
save(matfile,'R','A','B');
fid=fopen(txtfile,'w');
if fid>=0
    fprintf(fid,'status=%s\nerror=%s | %s\n', ...
        R.status,R.error_identifier,R.error_message);
    fprintf(fid,'shape=%s\nstage=%s\nall12_joint=%s\n', ...
        R.shape_status,R.shape_stage,R.shape_all12_joint);
    fprintf(fid,'near_family_count=%d\nmixed=%s\nentry=%s\n', ...
        R.shape_near_family_count,R.mixed_entry_shape_status,R.entry_status);
    fprintf(fid,'HLC_LO=%s\nHLC_HI=%s\n', ...
        mat2str(R.hlc_input_lower.'),mat2str(R.hlc_input_upper.'));
    fprintf(fid,'HLC_CLOSED_LOOP_PROVEN=%d\nHW_MOTOR_FEASIBLE_PROVEN=%d\n', ...
        R.full_HLC_tracking_certified,R.physical_motor_allocation_certified);
    fprintf(fid,'safe_to_commit=%d\nelapsed_ms=%.5f\n', ...
        R.safe_to_commit,R.elapsed_ms);
    fclose(fid);
end
if isfile(zipfile),delete(zipfile);end
zip(zipfile,{matfile,txtfile});
fprintf('[C9 SHAPES+ENTRY+HLC] %s | %s\n',R.status,zipfile);
end
