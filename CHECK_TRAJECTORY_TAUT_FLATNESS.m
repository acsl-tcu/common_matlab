function R=CHECK_TRAJECTORY_TAUT_FLATNESS()
% CHECK_TRAJECTORY_TAUT_FLATNESS  One focused flat-output regression.
% Place this check at common_matlab root. No HLC/plant/trigger is changed.
% All masses, limits, durations below are SYNTHETIC TEST VALUES ONLY.
root=fileparts(mfilename('fullpath'));
addpath(fullfile(root,'reference','REPLANNING_SYSTEM','TRAJECTORY_GENERATION'));
A=struct('cable_length_m',2,'uav_mass_kg',1.5, ...
    'payload_mass_kg',1,'gravity_world_mps2',[0;0;-9.80665], ...
    'thrust_limits_N',[0;100],'minimum_tension_N',0, ...
    'acceleration_guard_mps2',1e-10);
opts=struct('max_subdivision_depth',3);
% Hover: exact constant-length downward cable, positive tension.
start=zeros(3,10);start(3,1)=-2;
H=TRAJECTORY_C9_FLAT_BERNSTEIN.build(0,1,start,start, ...
    repmat(start(:,1),1,4));
P=TRAJECTORY_TAUT_FLATNESS.certify_positive_tension(H,A,opts);
E=TRAJECTORY_TAUT_FLATNESS.evaluate(H,0.37,A);
assert(P.certified && E.valid && ...
    norm(E.cable_direction_jets(:,1)-[0;0;-1])<1e-12 && ...
    norm(E.uav_jets(:,1))<1e-12 && ...
    abs(E.tension_N-A.payload_mass_kg*9.80665)<1e-11 && ...
    abs(E.thrust_N-(A.uav_mass_kg+A.payload_mass_kg)*9.80665)<1e-10, ...
    'CHECK_TRAJECTORY_TAUT_FLATNESS:Hover','Incorrect load-flatness hover dynamics.');
% Cubic load pL(t)=[t+0.1*t^3;0;-2], 0<=t<=1.
% Construct the EXACT degree-23 elevated interior controls. The UAV is
% NOT a polynomial when q=(g-aL)/norm(g-aL) varies with time.
B=zeros(3,10);B(3,1)=-2;B(1,2)=1;B(1,4)=0.6;
C=B;C(1,1)=1.1;C(1,2)=1.3;C(1,3)=0.6;
n=23;all_controls=zeros(3,24);all_controls(3,:)=-2;
for i=0:n
    all_controls(1,i+1)=i/n + 0.1*i*(i-1)*(i-2)/(n*(n-1)*(n-2));
end
X=TRAJECTORY_C9_FLAT_BERNSTEIN.build(0,1,B,C,all_controls(:,11:14));
assert(max(abs(X.control_points_m(:)-all_controls(:)))<1e-9, ...
    'CHECK_TRAJECTORY_TAUT_FLATNESS:DegreeElevation', ...
    'Flat load polynomial controls are inconsistent.');
cert=TRAJECTORY_TAUT_FLATNESS.certify_positive_tension(X,A,opts);
assert(cert.certified && cert.minimum_model_tension_lower_bound_N>0, ...
    'CHECK_TRAJECTORY_TAUT_FLATNESS:Tension','Whole-time tension proof failed.');
for time=[0 0.2 0.5 0.8 1]
    F=TRAJECTORY_TAUT_FLATNESS.evaluate(X,time,A);
    assert(F.valid && abs(norm(F.load_jets(:,1)-F.uav_jets(:,1)) - ...
        A.cable_length_m)<3e-10 && ...
        abs(norm(F.cable_direction_jets(:,1))-1)<1e-12 && ...
        abs(dot(F.cable_direction_jets(:,1),F.cable_direction_jets(:,2)))<1e-8 && ...
        abs(dot(F.cable_direction_jets(:,1),F.cable_direction_jets(:,3))+ ...
            dot(F.cable_direction_jets(:,2),F.cable_direction_jets(:,2)))<1e-7, ...
        'CHECK_TRAJECTORY_TAUT_FLATNESS:Cable','Taut cable derivative identity failed.');
    residual=A.payload_mass_kg*(F.load_jets(:,3)-A.gravity_world_mps2)+ ...
        F.tension_N*F.cable_direction_jets(:,1);
    assert(norm(residual)<1e-9, ...
        'CHECK_TRAJECTORY_TAUT_FLATNESS:Newton','Payload Newton equation residual.');
end
[yawref,yaw,F]=TRAJECTORY_TAUT_FLATNESS.reference28(X,0.5,A,0);
assert(isequal(size(yawref),[28 1]) && all(isfinite(yawref)) && ...
    abs(wrap_pi(yaw(1)-atan2(F.uav_jets(2,2),F.uav_jets(1,2))))<1e-11, ...
    'CHECK_TRAJECTORY_TAUT_FLATNESS:Yaw','Heading-exact reference is invalid.');
W=TRAJECTORY_TAUT_FLATNESS.reference_window( ...
    X,[0 .25 .5 .75 1],A,opts,0);
assert(W.sampled_screen_pass && ~W.safe_to_commit && ...
    W.tension_certificate.certified && ...
    isequal(size(W.reference_matrix_28),[28 4]) && ...
    isequal(size(W.predicted_payload_m),[3 5]), ...
    'CHECK_TRAJECTORY_TAUT_FLATNESS:Window','Coupled reference bridge failed.');
% The preflight generator boundary exposes this ONLY as a read-only
% candidate preview; neither the numerical model nor HLC may be committed.
G=TRAJECTORY_GENERATOR(struct('ROBUST_TUBE_ENABLED',true));
req=struct('load_piece',X,'relative_sample_times_s',[0 .25 .5 .75 1], ...
    'physical_authority',A,'flatness_proof_options',opts, ...
    'yaw_anchor_rad',0,'robust_tube_enabled',true);
GB=G.preview_load_flatness_reference(req);
assert(GB.sampled_screen_pass && ~GB.safe_to_commit && ...
    isequal(GB.reference_matrix_28,W.reference_matrix_28), ...
    'CHECK_TRAJECTORY_TAUT_FLATNESS:Generator', ...
    'Read-only generator coupling bridge was not connected.');
% Rotational covariance (including a tilted gravity world frame).
phi=0.39;R3=[cos(phi) 0 sin(phi);0 1 0;-sin(phi) 0 cos(phi)];
Ar=A;Ar.gravity_world_mps2=R3*A.gravity_world_mps2;
Br=R3*B;Cr=R3*C;
Xr=TRAJECTORY_C9_FLAT_BERNSTEIN.build(0,1,Br,Cr, ...
    R3*all_controls(:,11:14));
Fr=TRAJECTORY_TAUT_FLATNESS.evaluate(Xr,0.5,Ar);
F0=TRAJECTORY_TAUT_FLATNESS.evaluate(X,0.5,A);
Pr=TRAJECTORY_TAUT_FLATNESS.certify_positive_tension(Xr,Ar,opts);
assert(Pr.certified && norm(Fr.uav_jets(:,1:3)-R3*F0.uav_jets(:,1:3),'fro')<1e-7 && ...
    abs(Fr.tension_N-F0.tension_N)<1e-10 && ...
    norm(Fr.thrust_force_world_N-R3*F0.thrust_force_world_N)<1e-8, ...
    'CHECK_TRAJECTORY_TAUT_FLATNESS:SO3', ...
    'Frame rotation changed the physical predictions.');
% Matching LOAD C9 jets guarantee UAV C7 jet continuity across joins.
Y=TRAJECTORY_C9_FLAT_BERNSTEIN.build(1,1,C,C, ...
    repmat(C(:,1),1,4));
Eleft=TRAJECTORY_TAUT_FLATNESS.evaluate(X,1,A);
Eright=TRAJECTORY_TAUT_FLATNESS.evaluate(Y,1,A);
assert(norm(Eleft.uav_jets-Eright.uav_jets,'fro')<1e-10, ...
    'CHECK_TRAJECTORY_TAUT_FLATNESS:Join','C9 load / C7 UAV join failed.');
% Freefall: g-aL=0 => normalized cable and tension are undefined.
Z0=zeros(3,10);Z1=Z0;
Z1(:,1)=A.gravity_world_mps2/2;
Z1(:,2)=A.gravity_world_mps2;
Z0(:,3)=A.gravity_world_mps2;Z1(:,3)=A.gravity_world_mps2;
freefall=zeros(3,24);
for i=0:n
    freefall(:,i+1)=A.gravity_world_mps2* ...
        (i*(i-1)/(2*n*(n-1)));
end
Z=TRAJECTORY_C9_FLAT_BERNSTEIN.build(0,1,Z0,Z1,freefall(:,11:14));
Pz=TRAJECTORY_TAUT_FLATNESS.certify_positive_tension(Z,A,opts);
Ez=TRAJECTORY_TAUT_FLATNESS.evaluate(Z,0,A);
assert(~Pz.certified && ~Ez.valid && ~Ez.safe_to_commit, ...
    'CHECK_TRAJECTORY_TAUT_FLATNESS:Singularity', ...
    'A freefall / zero-tension flat output must fail closed.');
R=struct('status','PASS_TAUT_FLATNESS_C9_TO_C7__HLC_DYNAMICS_PENDING', ...
    'whole_time_ideal_tension_proven',cert.certified, ...
    'rotated_world_consistent',true, ...
    'freefall_rejected',~Ez.valid, ...
    'sampled_reference_columns',size(W.reference_matrix_28,2), ...
    'load_flat_free_control_variables',12, ...
    'previous_independent_free_variables',48, ...
    'full_time_obstacle_certificate',false, ...
    'HLC_plant_physical_certificate',false,'safe_to_commit',false);
mat=fullfile(root,'TRAJECTORY_TAUT_FLATNESS_RESULT.mat');
txt=fullfile(root,'TRAJECTORY_TAUT_FLATNESS_RESULT.txt');
save(mat,'R');
fid=fopen(txt,'wt');
assert(fid>=0,'CHECK_TRAJECTORY_TAUT_FLATNESS:Save','Cannot write audit.');
clean=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',R.status);
fprintf(fid,'whole_time_ideal_tension=%d SO3=%d freefall_rejected=%d\n', ...
    R.whole_time_ideal_tension_proven,R.rotated_world_consistent,R.freefall_rejected);
fprintf(fid,'flat_load_free_variables=%d previous_geometric_variables=%d\n', ...
    R.load_flat_free_control_variables,R.previous_independent_free_variables);
fprintf(fid,'real_native_HLC_plant=NOT_TESTED whole_time_full_body_collision=NOT_CERTIFIED\n');
clear clean;
zip(fullfile(root,'TRAJECTORY_TAUT_FLATNESS_RESULTS_FOR_CHATGPT.zip'), ...
    {'TRAJECTORY_TAUT_FLATNESS_RESULT.mat', ...
    'TRAJECTORY_TAUT_FLATNESS_RESULT.txt'},root);
delete(mat);delete(txt);
end
function a=wrap_pi(a)
a=atan2(sin(a),cos(a));
end
