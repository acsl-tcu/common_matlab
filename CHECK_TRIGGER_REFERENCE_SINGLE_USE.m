function R=CHECK_TRIGGER_REFERENCE_SINGLE_USE(agent)
% Offline, after the original Flight. Does not write to agent or any logger.
% Confirms that a same-tick HLC-verified nominal sample is consumed by the
% reference window exactly once; evaluates the real reference function as
% a read-only postflight oracle, never during preflight.
% No safety or real-time performance claim.
assert(nargin==1&&isobject(agent)&&isscalar(agent), ...
    'CHECK_TRIGGER_REFERENCE_SINGLE_USE:Agent','Actual Flight agent required.');
nominal=agent.reference.timevarying;
assert(isa(nominal,'TIME_VARYING_REFERENCE') && ...
    ~isempty(nominal.t)&&isa(nominal.func,'function_handle'), ...
    'CHECK_TRIGGER_REFERENCE_SINGLE_USE:Nominal', ...
    'Real Flight nominal time source must already exist.');
L=double(agent.parameter.get("cableL"));
dt=double(agent.plant.dt);
assert(isscalar(dt)&&isfinite(dt)&&dt>0 && ...
    isscalar(L)&&isfinite(L)&&L>0, ...
    'CHECK_TRIGGER_REFERENCE_SINGLE_USE:External', ...
    'Live Flight dt and cable length must be positive.');
% Small postflight oracle window; the 4-second horizon is unrelated to this
% focused no-duplicate-re-evaluation test.
n=7;
times=double(nominal.t)+(0:n-1)*dt;
num_calls=0;
cache=TRIGGER_REFERENCE_WINDOW_CACHE();
verified_now=original_reference(times(1));
[W1,S1]=cache.evaluate(nominal,times,L,@counted_reference,verified_now);
expected1=zeros(28,n);
for k=1:n
    v=original_reference(times(k));
    expected1(1:numel(v),k)=v;
end
first_equal=isequal(W1,expected1);
first_expected_calls=num_calls==n-1;
% Force an EXACT shared set of binary64 times, without time snapping.
times2=[times(2:end),times(end)+dt];
verified_now2=original_reference(times2(1));
call_before=num_calls;
[W2,S2]=cache.evaluate(nominal,times2,L,@counted_reference,verified_now2);
expected2=zeros(28,n);
for k=1:n
    v=original_reference(times2(k));
    expected2(1:numel(v),k)=v;
end
second_equal=isequal(W2,expected2);
C=cache.get_status();
R=struct('status','FAIL', ...
    'first_jet_bitwise_equal',first_equal, ...
    'second_jet_bitwise_equal',second_equal, ...
    'first_real_source_evaluations',S1.fresh_generated, ...
    'first_counted_calls',call_before, ...
    'second_real_source_evaluations',S2.fresh_generated, ...
    'second_counted_calls',num_calls-call_before, ...
    'source_can_cache',C.active_source_cacheable, ...
    'validated_now_reuses',C.validated_now_reuses, ...
    'first_expected_n_minus_one',first_expected_calls, ...
    'proof_scope','Exact same-tick HLC verified jet reuse ONLY; not collision safety');
if first_equal&&second_equal&&first_expected_calls&& ...
        S1.validated_now_used&&S2.validated_now_used&& ...
        S1.fresh_generated==n-1&&C.validated_now_reuses==2
    R.status='PASS_EXACT_REFERENCE_NO_DUPLICATE_FIRST_JET';
end
save(fullfile(fileparts(mfilename('fullpath')), ...
    'TRIGGER_REFERENCE_SINGLE_USE_RESULT.mat'),'R');
fid=fopen(fullfile(fileparts(mfilename('fullpath')), ...
    'TRIGGER_REFERENCE_SINGLE_USE_RESULT.txt'),'wt');
if fid>=0
    fclose_guard=onCleanup(@()fclose(fid));
    fprintf(fid,'status=%s\nfirst_equal=%d second_equal=%d\n', ...
        R.status,R.first_jet_bitwise_equal,R.second_jet_bitwise_equal);
    fprintf(fid,'first_counted_calls=%d second_counted_calls=%d\n', ...
        R.first_counted_calls,R.second_counted_calls);
    fprintf(fid,'source_can_cache=%d validated_now_reuses=%d\n', ...
        R.source_can_cache,R.validated_now_reuses);
end
    function v=original_reference(t)
        v=double(nominal.func(double(t)-double(nominal.t)));
        assert(isreal(v)&&iscolumn(v)&&numel(v)>=4&& ...
            numel(v)<=28&&all(isfinite(v)), ...
            'CHECK_TRIGGER_REFERENCE_SINGLE_USE:Jet', ...
            'Original live reference did not return finite 4..28 jet.');
        v(3)=v(3)-L;
    end
    function v=counted_reference(t)
        num_calls=num_calls+1;
        v=original_reference(t);
    end
end
