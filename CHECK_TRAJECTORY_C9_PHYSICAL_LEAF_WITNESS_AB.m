function R=CHECK_TRAJECTORY_C9_PHYSICAL_LEAF_WITNESS_AB()
% One A/B across exact same 3 original observed-shape fixtures x 5 repeats.
% Five modes: shared only, legacy phase leaf, physical leaf,
% raw body-time focus, and body-time focus with exact CURRENT-geometry outer guard.
% Actual whole integrated nominal pipeline and ALL-TIME independent oracle.
% Do not read the numbers as hard WCET or real HLC tracking proof.
root=fileparts(mfilename('fullpath'));
mod=fullfile(root,'reference','REPLANNING_SYSTEM','TRAJECTORY_GENERATION');
addpath(fullfile(root,'controller'),fullfile(root,'model'),'-begin');
addpath(mod,fullfile(root,'reference','REPLANNING_SYSTEM','OBSTACLE_INFORMATION'),'-begin');
R=struct('status','NOT_RUN','error_message','','safe_to_commit',false, ...
    'actual_HLC_proven',false,'scenario_names',{{}}, ...
    'setup_stage','START','setup_completed',false, ...
    'completed_trials',zeros(3,5),'warmup_error_cells',{cell(3,5)}, ...
    'mode_names',{{'shared_only','shared_old_phase_leaf','shared_physical_leaf','shared_physical_leaf_body_time','guarded_body_time'}}, ...
    'total_ms',NaN(3,5,5),'geometry_ms',NaN(3,5,5), ...
    'planes_ms',NaN(3,5,5),'QP_ms',NaN(3,5,5), ...
    'torque_search_ms',NaN(3,5,5),'proof_calls',NaN(3,5,5), ...
    'shared_qp_uses',zeros(3,5,5),'leaf_cut_rows',zeros(3,5,5), ...
    'nominal_complete',false(3,5,5), ...
    'status_cells',{cell(3,5,5)}, 'error_cells',{cell(3,5,5)}, ...
    'failure_reasons',{cell(3,5,5)}, ...
    'body_time_qp_uses',zeros(3,5,5), ...
    'body_time_groups_avoided',zeros(3,5,5), ...
    'body_time_body_planes_avoided',zeros(3,5,5), ...
    'median_ms',NaN(3,5),'p95_ms',NaN(3,5), ...
    'max_ms',NaN(3,5),'jitter_ms',NaN(3,5), ...
    'success_by_mode',NaN(1,5), ...
    'regressions_vs_shared',NaN(1,5), ...
    'new_successes_vs_shared',NaN(1,5), ...
    'regressions_vs_physical_leaf',NaN(1,5), ...
    'guard_uses',zeros(3,5,5),'guard_rejections',zeros(3,5,5), ...
    'guard_far_body_checks',zeros(3,5,5), ...
    'guard_near_body_checks',zeros(3,5,5), ...
    'physical_leaf_test_count',0,'physical_leaf_tangent_max_scaled_error',NaN);
try
    R.setup_stage='LIVE_HLC_AUTHORITY_FIXTURE';
    [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    val=double(P.get(["mass","jx","jy","jz","gravity","cableL"]));
    val=val(:);lo=double(lo(:));hi=double(hi(:));
    assert(numel(val)==6&&numel(lo)==4&&numel(hi)==4&& ...
        all(isfinite([val;lo;hi]))&&all(val>0), ...
        'C9_AB:FixtureAuthority','Source physical values are required.');
    % Explicit CHECK mass fixture, NEVER a Flight/EKF estimator replacement.
    A=struct('uav_mass_kg',val(1),'payload_mass_kg',0.14, ...
        'cable_length_m',val(6),'uav_inertia_kgm2',val(2:4), ...
        'gravity_world_mps2',[0;0;-val(5)], ...
        'thrust_limits_N',[lo(1),hi(1)], ...
        'torque_limits_Nm',[lo(2:4),hi(2:4)], ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0);
    radii=struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1);
    geometry=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'numerical_guard_m',0,'robust_tube_enabled',false,'trajectory_phase','f');
    force=struct('max_subdivision_depth',6,'max_node_count',127,'force_guard_N',0);
    search=struct('probe_count',13,'max_outer_iterations',4, ...
        'max_projection_sweeps',100,'projection_tolerance_m',1e-8, ...
        'min_separation_m',1e-5, ...
        'enable_13d_variable_time_joint_search',1, ...
        'enable_13d_reuse_nominal_torque_certificate',1, ...
        'use_shared_13d_duration_cache',1);
    heading=struct('max_subdivision_depth',8,'max_node_count',511, ...
        'horizontal_velocity_guard_mps',0,'w_guard_mps2',0, ...
        'payload_jet_tolerance',1e-7*ones(3,10), ...
        'uav_jet_tolerance',1e-7*ones(3,8), ...
        'yaw_jet_tolerance',1e-7*ones(1,7));
    torque=struct('max_subdivision_depth',8,'max_node_count',511, ...
        'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
        'torque_guard_Nm',zeros(3,1), ...
        'enable_fast_norm_sufficient_bound',true);
    j0=zeros(3,10);j1=j0;
    j0(:,1)=[-2;0;3];j1(:,1)=[2;0;3];
    j0(1,2)=0.4;j1(1,2)=0.4;
    startPiece=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,10, ...
        j0,j1,repmat([0;0;3],1,4));
    req=struct('t0_s',8,'duration_s',10,'flight_interval_s',[8 30], ...
        'start_jets',j0,'end_jets',j1, ...
        'nominal_free',startPiece.control_points_m(:,11:14), ...
        'observed',struct([]),'radii',radii,'authority',A, ...
        'geometry_options',geometry,'force_options',force, ...
        'search_options',search,'heading_options',heading, ...
        'nominal_torque_options',torque,'torque_options',torque);
    s0=zeros(3,10);s1=s0;
    s0(:,1)=[0;0;3];s1(:,1)=[1;0;3];
    s0(1,2)=0.5;s1(1,2)=0.5;
    affineFree=repmat(s0(:,1),1,4)+s0(:,2)*((2/23)*(10:13));
    affine=TRAJECTORY_C9_FLAT_BERNSTEIN.build(8,2,s0,s1,affineFree);
    clearReq=req;clearReq.duration_s=2;
    clearReq.start_jets=s0;clearReq.end_jets=s1;
    clearReq.nominal_free=affine.control_points_m(:,11:14);
    sphere=OBSTACLE_INFORMATION.define(21,'sphere',[0 0.1 3],0.2);
    ax=0.34;ay=-0.26;az=0.4;
    Rx=[1 0 0;0 cos(ax) -sin(ax);0 sin(ax) cos(ax)];
    Ry=[cos(ay) 0 sin(ay);0 1 0;-sin(ay) 0 cos(ay)];
    Rz=[cos(az) -sin(az) 0;sin(az) cos(az) 0;0 0 1];
    ell=OBSTACLE_INFORMATION.define(33,'ellipsoid', ...
        [0.6 -0.16 3],[0.32 0.19 0.4],'rotation',Rz*Ry*Rx);
    observed={struct([]),sphere,[sphere ell]};
    R.scenario_names={'clear_affine','sphere_13D','sphere_ellipsoid_13D'};
    % Software-only constants and physical-leaf gradient independent test.
    R.setup_stage='STATIC_SOFTWARE_PREFLIGHT';
    TRAJECTORY_C9_STATIC_KERNEL_PREFLIGHT();
    R.setup_stage='PREPARED_SHAPE_PHYSICAL_LEAF_GRADIENT';
    [R.physical_leaf_test_count,R.physical_leaf_tangent_max_scaled_error]= ...
        c9_leaf_physical_gradient_test();
    if R.physical_leaf_test_count<20|| ...
            R.physical_leaf_tangent_max_scaled_error>5e-5
        error('C9_NEW_AB:PhysicalLeafGradientMismatch', ...
            'Fixed physical-time interval gradient not validated.');
    end
    R.setup_completed=true;
    R.setup_stage='COMPLETED_ENTER_PIPELINE_AB';
    for scene=1:3
        if scene==1,fixture=clearReq;else,fixture=req;end
        fixture.observed=observed{scene};
        for mode=1:5
            fixture.search_options.enable_13d_shared_jet_kernel=1;
            fixture.search_options.enable_13d_certificate_leaf_hull_cuts=double(mode>=2);
            fixture.search_options.enable_13d_physical_leaf_duration_tangent=double(mode>=3);
            fixture.search_options.enable_13d_oracle_body_time_qp_rows=double(mode>=4);
            fixture.search_options.enable_13d_oracle_body_time_outer_guard=double(mode==5);
            fixture.search_options.enable_13d_payload_witness_leaf_gate=double(mode>=3);
            % Warm each configuration ONCE before measured trials. This is
            % ordinary JIT warmup, not precomputing a Flight trajectory.
            try
                TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(fixture);
            catch MEwarm
                R.warmup_error_cells{scene,mode}= ...
                    [MEwarm.identifier ' | ' MEwarm.message];
                % Warmup failure does NOT conceal the per-trial exception.
                % Continue the independent measured trials, fail closed.
            end
            for trial=1:5
                t=tic;
                try
                    v=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(fixture);
                    R.total_ms(scene,mode,trial)=v.total_elapsed_ms;
                    R.geometry_ms(scene,mode,trial)=v.joint_geometry_force_proof_ms;
                    R.planes_ms(scene,mode,trial)=v.separation_planes_ms;
                    R.QP_ms(scene,mode,trial)=v.joint_QP_ms;
                    R.proof_calls(scene,mode,trial)=v.proof_calls;
                    R.shared_qp_uses(scene,mode,trial)=v.shared_jet_qp_uses;
                    R.leaf_cut_rows(scene,mode,trial)=v.certificate_leaf_qp_cuts;
                    R.body_time_qp_uses(scene,mode,trial)=v.body_time_focus_qp_uses;
                    R.guard_uses(scene,mode,trial)=v.body_time_outer_guard_uses;
                    R.guard_rejections(scene,mode,trial)=v.body_time_outer_guard_rejections;
                    R.guard_far_body_checks(scene,mode,trial)=v.body_time_outer_guard_far_checks;
                    R.guard_near_body_checks(scene,mode,trial)=v.body_time_outer_guard_near_checks;
                    R.body_time_groups_avoided(scene,mode,trial)= ...
                        v.body_time_focus_skipped_shape_phase_groups;
                    R.body_time_body_planes_avoided(scene,mode,trial)= ...
                        v.body_time_focus_skipped_body_planes;
                    if isfield(v.search_result,'failure_reason')
                        R.failure_reasons{scene,mode,trial}=v.search_result.failure_reason;
                    else
                        R.failure_reasons{scene,mode,trial}='';
                    end
                    R.nominal_complete(scene,mode,trial)=v.nominal_model_complete;
                    R.status_cells{scene,mode,trial}=v.status;
                    if isfield(v.search_result,'duration_13d_torque_ms')
                        R.torque_search_ms(scene,mode,trial)=v.search_result.duration_13d_torque_ms;
                    end
                    assert(~v.safe_to_commit&&~v.actual_HLC_tracking_proven, ...
                        'C9_AB:UnsafeCommit','A nominal A/B must never COMMIT.');
                    R.completed_trials(scene,mode)=R.completed_trials(scene,mode)+1;
                catch ME
                    R.total_ms(scene,mode,trial)=1000*toc(t);
                    R.error_cells{scene,mode,trial}= ...
                        [ME.identifier ' | ' ME.message];
                    R.status_cells{scene,mode,trial}='MATLAB_EXCEPTION_NOT_A_PROOF';
                end
            end
            t=reshape(R.total_ms(scene,mode,:),[],1);
            R.median_ms(scene,mode)=median(t);
            ordered=sort(t);
            R.p95_ms(scene,mode)=ordered(ceil(.95*numel(ordered)));
            R.max_ms(scene,mode)=max(t);
            R.jitter_ms(scene,mode)=max(t)-min(t);
        end
    end
    % A scene is successful only if ALL five trials completed and ALL
    % five independent nominal certificates agreed. Incomplete measurements
    % cannot become successful scenes or a speedup claim.
    complete=(R.completed_trials==5);
    successful=false(3,5);
    for scene=1:3
        for mode=1:5
            successful(scene,mode)=complete(scene,mode) && ...
                all(reshape(R.nominal_complete(scene,mode,:),[],1));
        end
    end
    R.success_by_mode=sum(successful,1);
    R.regressions_vs_shared=sum(successful(:,1) & ~successful,1);
    R.new_successes_vs_shared=sum(~successful(:,1) & successful,1);
    R.regressions_vs_physical_leaf=sum(successful(:,3) & ~successful,1);
    if any(~complete(:)) || ...
            any(~cellfun(@isempty,R.warmup_error_cells(:))) || ...
            any(~cellfun(@isempty,R.error_cells(:)))|| ...
            any(R.regressions_vs_shared>0) || ...
            R.regressions_vs_physical_leaf(5)>0
        R.status='DO_NOT_ENABLE__EXCEPTION_OR_NOMINAL_REGRESSION';
    else
        R.status='COMPLETED_GUARDED_BODY_TIME_AB__15_CASE_HLC_WCET_PENDING';
    end
catch ME
    R.status='FAIL_AUDIT_SETUP';
    R.error_message=ME.getReport('extended','hyperlinks','off');
end
base='TRAJECTORY_C9_PHYSICAL_LEAF_WITNESS_AB_RESULT';
matPath=fullfile(root,[base '.mat']);txtPath=fullfile(root,[base '.txt']);
zipPath=fullfile(root,[base '_FOR_CHATGPT.zip']);
save(matPath,'R');
fid=fopen(txtPath,'w');
if fid<0,error('C9_AB:CannotSave','Cannot open audit text.');end
fprintf(fid,'status=%s\nsetup_stage=%s setup_completed=%d\nerror=%s\n', ...
    R.status,R.setup_stage,R.setup_completed,R.error_message);
fprintf(fid,'completed_trials=%s\n',mat2str(R.completed_trials));
fprintf(fid,'nominal=%s regressions_vs_shared=%s new_vs_shared=%s\n', ...
    mat2str(R.success_by_mode),mat2str(R.regressions_vs_shared), ...
    mat2str(R.new_successes_vs_shared));
fprintf(fid,'regressions_vs_physical_leaf=%s\n', ...
    mat2str(R.regressions_vs_physical_leaf));
fprintf(fid,'fixed_physical_leaf_gradient_tests=%d max_scaled_error=%.12g\n', ...
    R.physical_leaf_test_count,R.physical_leaf_tangent_max_scaled_error);
for scene=1:3
    for mode=1:5
        if ~isempty(R.warmup_error_cells{scene,mode})
            fprintf(fid,' warmup_error scene=%s mode=%s error=%s\n', ...
                R.scenario_names{scene},R.mode_names{mode}, ...
                R.warmup_error_cells{scene,mode});
        end
        fprintf(fid,'scene=%s mode=%s median=%.7f p95=%.7f max=%.7f jitter=%.7f\n', ...
            R.scenario_names{scene},R.mode_names{mode}, ...
            R.median_ms(scene,mode),R.p95_ms(scene,mode), ...
            R.max_ms(scene,mode),R.jitter_ms(scene,mode));
        for trial=1:5
            fprintf(fid,' trial=%d status=%s total=%.7f geometry=%.7f planes=%.7f qp=%.7f torque=%.7f shared=%d leaf=%d focused=%d groups_skipped=%d body_skipped=%d guard_uses=%d guard_rejected=%d guard_far=%d guard_near=%d reason=%s error=%s\n', ...
                trial,R.status_cells{scene,mode,trial}, ...
                R.total_ms(scene,mode,trial),R.geometry_ms(scene,mode,trial), ...
                R.planes_ms(scene,mode,trial),R.QP_ms(scene,mode,trial), ...
                R.torque_search_ms(scene,mode,trial), ...
                R.shared_qp_uses(scene,mode,trial),R.leaf_cut_rows(scene,mode,trial), ...
                R.body_time_qp_uses(scene,mode,trial), ...
                R.body_time_groups_avoided(scene,mode,trial), ...
                R.body_time_body_planes_avoided(scene,mode,trial), ...
                R.guard_uses(scene,mode,trial), ...
                R.guard_rejections(scene,mode,trial), ...
                R.guard_far_body_checks(scene,mode,trial), ...
                R.guard_near_body_checks(scene,mode,trial), ...
                R.failure_reasons{scene,mode,trial}, ...
                R.error_cells{scene,mode,trial});
        end
    end
end
fprintf(fid,'safe_to_commit=0\nHLC_proven=0\n');fclose(fid);
if isfile(zipPath),delete(zipPath);end
zip(zipPath,{matPath,txtPath});
end


function [number,max_error]=c9_leaf_physical_gradient_test()
% Independent FROM SEARCH: finite differences of the SAME FIXED PHYSICAL
% failure leaf, with the actual degree-23 C9 endpoint physical jets fixed.
% Only verifies local 13D tangent; never labels any trajectory collision-free.
number=0;max_error=0;
rng(20261110,'twister');
for k=1:32
    T=2+0.05*k;t0=8;
    a=zeros(3,10);b=zeros(3,10);
    a(:,1)=[-1;0;3]+0.05*randn(3,1);
    b(:,1)=[+1;0;3]+0.05*randn(3,1);
    a(:,2)=0.1*randn(3,1);b(:,2)=0.1*randn(3,1);
    for j=3:10
        a(:,j)=0.005^(j-2)*randn(3,1);
        b(:,j)=0.005^(j-2)*randn(3,1);
    end
    free=repmat([0;0;3],1,4)+0.05*randn(3,4);
    S=TRAJECTORY_C9_DURATION_SENSITIVITY(t0,T,a,b,free);
    p=S.piece;
    tA=t0+0.15*T;tB=t0+0.45*T;
    u0=(tA-t0)/T;u1=(tB-t0)/T;
    H=TRAJECTORY_C9_BERNSTEIN_SUBINTERVAL_CONTROLS( ...
        p.control_points_m,u0,u1);
    center=mean(H,2)+[0;0.2;0];
    % OBSTACLE_INFORMATION.define produces a RAW obstacle with .position;
    % the local QP/search certificate helper accepts prepared shape
    % snapshots with .center/.kind/.dim/.R ONLY.  Prepare this diagnostic
    % fixture exactly as the production independent oracle does.
    raw_shape=OBSTACLE_INFORMATION.define(86,'sphere',center.',0.9);
    shape=TRAJECTORY_OBSTACLE_SUPPORT.prepare(raw_shape);
    assert(isscalar(shape) && isfield(shape,'center') && ...
        isequal(size(shape.center),[3,1]) && ...
        isequal(shape.center,center), ...
        'C9_NEW_AB:PreparedShapeMismatch', ...
        'CHECK fixture must use the canonical prepared world shape.');
    witness=struct('unresolved_time_interval_s',[tA tB], ...
        'unresolved_obstacle_ids',86);
    [A,bb,d]=TRAJECTORY_C9_13D_CERTIFICATE_LEAF_CUTS( ...
        p,S,shape,witness,0.1,0,true);
    assert(size(A,2)==1&&numel(bb)==1&& ...
        numel(d.selected_control_indices)==1&& ...
        d.physical_leaf_time_tangent, ...
        'C9_NEW_AB:LeafFixture','No leaf row was generated for test.');
    idx=d.selected_control_indices(1);
    n=(mean(H,2)-center);n=n/norm(n);
    h=1e-5*T;
    plus=TRAJECTORY_C9_FLAT_BERNSTEIN.build(t0,T+h,a,b,free);
    minus=TRAJECTORY_C9_FLAT_BERNSTEIN.build(t0,T-h,a,b,free);
    hp=TRAJECTORY_C9_BERNSTEIN_SUBINTERVAL_CONTROLS( ...
        plus.control_points_m,(tA-t0)/(T+h),(tB-t0)/(T+h));
    hm=TRAJECTORY_C9_BERNSTEIN_SUBINTERVAL_CONTROLS( ...
        minus.control_points_m,(tA-t0)/(T-h),(tB-t0)/(T-h));
    numerical=n.'*(hp(:,idx)-hm(:,idx))/(2*h);
    analytic=A(13,1);
    err=abs(numerical-analytic)/(1+abs(numerical)+abs(analytic));
    max_error=max(max_error,err);
    number=number+1;
    % Also check the independent free-Bernstein-control coordinate.
    j=mod(k-1,12)+1;fp=free;fm=free;
    fp(j)=fp(j)+h;fm(j)=fm(j)-h;
    pp=TRAJECTORY_C9_FLAT_BERNSTEIN.build(t0,T,a,b,fp);
    pm=TRAJECTORY_C9_FLAT_BERNSTEIN.build(t0,T,a,b,fm);
    Hplus=TRAJECTORY_C9_BERNSTEIN_SUBINTERVAL_CONTROLS( ...
        pp.control_points_m,u0,u1);
    Hminus=TRAJECTORY_C9_BERNSTEIN_SUBINTERVAL_CONTROLS( ...
        pm.control_points_m,u0,u1);
    numerical=n.'*(Hplus(:,idx)-Hminus(:,idx))/(2*h);
    analytic=A(j,1);
    err=abs(numerical-analytic)/(1+abs(numerical)+abs(analytic));
    max_error=max(max_error,err);
    number=number+1;
end
end
