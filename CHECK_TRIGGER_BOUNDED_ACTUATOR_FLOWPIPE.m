function T=CHECK_TRIGGER_BOUNDED_ACTUATOR_FLOWPIPE()
% Disposable fixture under common_matlab/; not an actual closed-loop proof.
T=struct('status','NOT_RUN','hlc_source_pinned',false, ...
    'actuator_box_correct',false,'never_commits',false, ...
    'invalid_mass_stays_unknown',false,'reason','');
try
    h=TRIGGER_ORIGINAL_HLC_ACTUATOR_SCOPE();
    T.hlc_source_pinned=h.source_verified;
    p=zeros(21,1);p(1)=1.4;p(6:8)=[0.05;0.06;0.08];
    p(9)=9.80665;p(20)=0.5;p(21)=2;
    x=zeros(24,1);x(13:15)=[0;0;-p(21)];x(19:21)=[0;0;-1];
    radius=1e-8;
    C=struct('time_grid_s',[0 0.0001], ...
        'initial_lower',x-radius,'initial_upper',x+radius, ...
        'param_lower',p,'param_upper',p);
    C.param_lower(20)=p(20)-radius;
    C.param_upper(20)=p(20)+radius;
    R=TRIGGER_BOUNDED_ACTUATOR_FLOWPIPE(C);
    T.actuator_box_correct=R.hlc_source_pinned && ...
        R.conditional_actuator_box && ...
        isequal(R.u_lower,[0;-1;-1;-1]) && ...
        isequal(R.u_upper,[20;1;1;1]);
    T.never_commits=~R.safe_to_commit && ...
        ~R.applied_held_input_proven && ...
        ~R.initial_EKF_error_proven;
    E=C;E.param_lower(20)=-1;
    U=TRIGGER_BOUNDED_ACTUATOR_FLOWPIPE(E);
    T.invalid_mass_stays_unknown=~U.safe_to_commit && ...
        ~(isfield(U.conditional_flowpipe,'conditional_chain_pass') && ...
          U.conditional_flowpipe.conditional_chain_pass);
    assert(T.actuator_box_correct && T.never_commits && ...
        T.invalid_mass_stays_unknown, ...
        'CHECK_TRIGGER_BOUNDED_ACTUATOR_FLOWPIPE:Audit', ...
        'HLC saturation enclosure, fail-closed status or mass rejection failed.');
    T.status='PASS_CONDITIONAL_ACTUATOR_TO_PLANT_FLOWPIPE__NOT_SAFETY';
catch ME
    T.reason=[ME.identifier ' | ' ME.message];
end
save('TRIGGER_BOUNDED_ACTUATOR_FLOWPIPE_RESULT.mat','T');
f=fopen('TRIGGER_BOUNDED_ACTUATOR_FLOWPIPE_RESULT.txt','w');
if f>=0
    fprintf(f,'status=%s\nhlc_pin=%d\ninput_box=%d\nnever_commit=%d\ninvalid_mass_rejected=%d\nreason=%s\n', ...
        T.status,T.hlc_source_pinned,T.actuator_box_correct, ...
        T.never_commits,T.invalid_mass_stays_unknown,T.reason);
    fclose(f);
end
end
