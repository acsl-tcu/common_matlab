function R=CHECK_TRAJECTORY_C9_FUSED_WITNESS_25D_AB()
% 3 search modes x 5 repetitions: baseline, canonical fallback, native proof-tree witness.
% 45 end-to-end trials. Records proof/build/solve breakdown; PASS is nominal only.
% A nominated native real-arithmetic certificate NEVER equals HLC execution
% or directed floating-point proof. Results stored in common_matlab root.
root=fileparts(mfilename('fullpath'));
R=struct('status','FAIL_FUSED_WITNESS_25D_AB', ...
  'error_message','','completed_trials',zeros(1,3), ...
  'modes',{{'canonical','fused_positive_with_canonical_witness', ...
            'fused_native_proof_tree_witness'}}, ...
  'scenes',{{'sphere_25d','sphere_ellipsoid_25d','clear_25d'}}, ...
  'nominal_success',false(3,3,5), ...
  'whole_ms',NaN(3,3,5),'proof_ms',NaN(3,3,5), ...
  'QP_ms',NaN(3,3,5),'QP_count',NaN(3,3,5), ...
  'fused_calls',zeros(3,3,5),'fused_positives',zeros(3,3,5), ...
  'canonical_fallbacks',zeros(3,3,5), ...
  'native_witness_qps',zeros(3,3,5), ...
  'native_ms',NaN(3,3,5), ...
  'generic_calls',zeros(3,3,5),'generic_positive',zeros(3,3,5), ...
  'generic_iterations',zeros(3,3,5), ...
  'torque_ms',NaN(3,3,5),'qp_solve_ms',NaN(3,3,5), ...
  'heading_ms',NaN(3,3,5), 'last_qp_status',{{}}, ...
  'statuses',{{}},'failure_reasons',{{}}, ...
  'median_ms',NaN(3,3),'p95_ms',NaN(3,3), ...
  'max_ms',NaN(3,3), 'native_12shape_checked',0, ...
  'native_positive_parity',false,'native_near_negative',false, ...
  'native_witness_parity',false, ...
  'regressions',NaN,'numerically_directed_rounding_proven',false, ...
  'HLC_B_proven',false,'safe_to_commit',false);
try
 K=TRAJECTORY_C9_FUSED_NATIVE_PREFLIGHT(false);
 assert(K.ready,['Native preflight: ' K.status ' ' K.message]);
 TK=TRAJECTORY_C9_TORQUE_WHOLE_27_PREFLIGHT(false);
 assert(TK.ready,['Torque preflight: ' TK.status]);
 g=[0;0;-9.80665];
 p=[zeros(1,28);linspace(0,27,28);3*ones(1,28)];
 packed=[1.1,.14,2,0,0,20,0,.3,.01,.2,0,8,900,1];
 R.native_12shape_checked=check_12_shape_prepared(p,g,packed);
 % The canonical oracle is independent of the native candidate, and
 % an apparent positive must NOT differ from the canonical mathematical
 % sufficient premise on simple affine witnesses.
 J0=zeros(3,10);J1=zeros(3,10);
 T=27;J0(:,1)=[0;0;3];J1(:,1)=[0;27;3];
 J0(:,2)=[0;1;0];J1(:,2)=[0;1;0];
 req=make_request(J0,J1,T);
 affine=TRAJECTORY_C9_FLAT_BERNSTEIN.build27( ...
     0,T,J0,J1,[zeros(1,8);10:17;3*ones(1,8)]);
 far=OBSTACLE_INFORMATION.define(2001,'ellipsoid', ...
      [4 13 3],[0.4 0.6 0.8],'euler_deg',[11 26 39]);
 [P,~]=TRAJECTORY_C9_FUSED_NOMINAL_ORACLE(affine,far, ...
      req.radii,req.authority,req.geometry_options,req.force_options);
 [Q,~]=TRAJECTORY_C9_JOINT_FAST_CERTIFICATE(affine,far, ...
      req.radii,req.authority,req.geometry_options,req.force_options);
 R.native_positive_parity=P.certified&&Q.certified&&P.checked_node_count>=1;
 assert(R.native_positive_parity, ...
       'C9_FUSED_WITNESS_AUDIT:BasicParity','Native positive/canonical proof disagreement.');
 near=OBSTACLE_INFORMATION.define(2002,'sphere',[0 13 3],0.8);
 [N,~]=TRAJECTORY_C9_FUSED_NOMINAL_ORACLE(affine,near, ...
      req.radii,req.authority,req.geometry_options,req.force_options);
 R.native_near_negative=~N.certified;
 assert(R.native_near_negative, ...
       'C9_FUSED_WITNESS_AUDIT:NearCollision','Near obstacle wrongly certified.');
 R.native_witness_parity=isfield(N,'unresolved_time_interval_s') && ...
      numel(N.unresolved_time_interval_s)==2 && ...
      all(isfinite(N.unresolved_time_interval_s)) && ...
      N.unresolved_time_interval_s(2)>N.unresolved_time_interval_s(1) && ...
      isfield(N,'unresolved_obstacle_ids') && ...
      any(N.unresolved_obstacle_ids==2002) && ...
      isfield(N,'unresolved_body_indices') && ...
      ~isempty(N.unresolved_body_indices);
 assert(R.native_witness_parity, ...
       'C9_FUSED_WITNESS_AUDIT:NativeWitness', ...
       'Near obstacle must produce native proof-tree shape/body/time witness.');
 first=OBSTACLE_INFORMATION.define(801,'sphere',[0.22 13 3],0.8);
 second=OBSTACLE_INFORMATION.define(802,'ellipsoid', ...
      [2.0 15 3],[0.6 0.8 0.9],'euler_deg',[17 29 43]);
 cases={first,[first second],struct([])};
 R.statuses=cell(3,3,5);R.failure_reasons=cell(3,3,5);
 R.last_qp_status=cell(3,3,5);
 for scene=1:3
   for trial=1:5
     order=1:3;if mod(trial,2)==0,order=3:-1:1;end
     for mode=order
       request=req;request.observed=cases{scene};
       request.search_options.enable_25d_certificate_driven_torque_rows=1;
       request.search_options.enable_25d_fused_native_alltime_oracle=double(mode>1);
       request.search_options.enable_25d_fused_native_witness_free_search=0;
       request.search_options.enable_25d_fused_native_witness_driven_search=double(mode==3);
       V=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(request);
       R.completed_trials(mode)=R.completed_trials(mode)+1;
       R.nominal_success(scene,mode,trial)=V.nominal_model_complete;
       R.whole_ms(scene,mode,trial)=V.total_elapsed_ms;
       R.statuses{scene,mode,trial}=V.status;
       R.failure_reasons{scene,mode,trial}=V.failure_detail;
       assert(~V.safe_to_commit && ~V.actual_HLC_tracking_proven, ...
          'C9_FUSED_WITNESS_AUDIT:InvalidCommit','Nominal proof cannot authorize Flight.');
       if isfield(V,'search_result')&&isstruct(V.search_result)
          S=V.search_result;
          R.proof_ms(scene,mode,trial)=getnum(S,'duration_25d_proof_ms');
          R.QP_ms(scene,mode,trial)=getnum(S,'duration_25d_plane_ms');
          R.QP_count(scene,mode,trial)=getnum(S,'duration_25d_qp_count');
          R.fused_calls(scene,mode,trial)=getnum(S,'duration_25d_fused_native_calls');
          R.fused_positives(scene,mode,trial)=getnum(S,'duration_25d_fused_native_positive');
          R.canonical_fallbacks(scene,mode,trial)=getnum(S,'duration_25d_fused_native_fallback_calls');
          R.native_witness_qps(scene,mode,trial)=getnum(S,'duration_25d_fused_native_witness_qps');
          R.native_ms(scene,mode,trial)=getnum(S,'duration_25d_fused_native_ms');
          R.generic_calls(scene,mode,trial)=getnum(S,'duration_25d_fused_generic_calls');
          R.generic_positive(scene,mode,trial)=getnum(S,'duration_25d_fused_generic_positives');
          R.generic_iterations(scene,mode,trial)=getnum(S,'duration_25d_fused_generic_iterations');
          R.torque_ms(scene,mode,trial)=getnum(S,'duration_25d_torque_ms');
          R.qp_solve_ms(scene,mode,trial)=getnum(S,'duration_25d_qp_ms');
          R.heading_ms(scene,mode,trial)=getnum(S,'duration_25d_heading_ms');
          if isfield(S,'duration_25d_last_qp_construction_status')
              R.last_qp_status{scene,mode,trial}=S.duration_25d_last_qp_construction_status;
          end
       end
     end
   end
 end
 for scene=1:3
   for mode=1:3
     a=sort(reshape(R.whole_ms(scene,mode,:),[],1));
     R.median_ms(scene,mode)=median(a);
     R.p95_ms(scene,mode)=interp1(1:5,a,4.8,'linear');
     R.max_ms(scene,mode)=max(a);
   end
 end
 R.regressions=0;
 for mode=2:3
   R.regressions=R.regressions+nnz( ...
       R.nominal_success(:,1,:)&~R.nominal_success(:,mode,:));
 end
 if R.regressions>0
   R.status='UNKNOWN_FUSED_WITNESS_25D_NOMINAL_REGRESSION__NO_ENABLE';
 elseif any(~R.nominal_success(1,2,:),'all')|| ...
        any(~R.nominal_success(1,3,:),'all')
   R.status='UNKNOWN_FUSED_WITNESS_25D_SPHERE_NOT_CERTIFIED__NO_ENABLE';
 else
   R.status='PASS_FUSED_WITNESS_25D_AB__HLC_B_AND_5MS_UNPROVEN';
 end
catch ME
 R.error_message=getReport(ME,'extended','hyperlinks','off');
end
try
 save(fullfile(root,'TRAJECTORY_C9_FUSED_WITNESS_25D_AB_RESULT.mat'),'R');
 fid=fopen(fullfile(root,'TRAJECTORY_C9_FUSED_WITNESS_25D_AB_RESULT.txt'),'w');
 if fid>=0
   fprintf(fid,'status=%s\nerror=%s\n',R.status,R.error_message);
   fprintf(fid,'tested_12_shapes=%d positive_parity=%d near_negative=%d witness_parity=%d\n', ...
       R.native_12shape_checked,R.native_positive_parity,R.native_near_negative, ...
       R.native_witness_parity);
   fprintf(fid,'completed=%s regressions=%g\n',mat2str(R.completed_trials),R.regressions);
   for s=1:3,for m=1:3
       fprintf(fid,'scene=%s mode=%s success=%s median=%.7g p95=%.7g max=%.7g\n', ...
           R.scenes{s},R.modes{m},mat2str(reshape(R.nominal_success(s,m,:),1,[])), ...
           R.median_ms(s,m),R.p95_ms(s,m),R.max_ms(s,m));
       fprintf(fid,'  native_calls=%s positives=%s fallback=%s native_witness_qps=%s\n', ...
          mat2str(reshape(R.fused_calls(s,m,:),1,[])), ...
          mat2str(reshape(R.fused_positives(s,m,:),1,[])), ...
          mat2str(reshape(R.canonical_fallbacks(s,m,:),1,[])), ...
          mat2str(reshape(R.native_witness_qps(s,m,:),1,[])));
   end,end
   fprintf(fid,'generic_calls=%s generic_positives=%s generic_iterations=%s\n', ...
       mat2str(sum(R.generic_calls,3)), ...
       mat2str(sum(R.generic_positive,3)), ...
       mat2str(sum(R.generic_iterations,3)));
   fprintf(fid,'HLC_B_proven=0 directed_rounding_proven=0 safe_to_commit=0\n');
   fprintf(fid,'NOTE native tree witness is an UNKNOWN locator, NOT a collision proof.\n');
   fprintf(fid,'NOTE native positives do not establish directed interval arithmetic.\n');
   fclose(fid);
 end
 if exist(fullfile(root,'TRAJECTORY_C9_FUSED_WITNESS_25D_AB_RESULT_FOR_CHATGPT.zip'),'file')
     delete(fullfile(root,'TRAJECTORY_C9_FUSED_WITNESS_25D_AB_RESULT_FOR_CHATGPT.zip'));
 end
 zip(fullfile(root,'TRAJECTORY_C9_FUSED_WITNESS_25D_AB_RESULT_FOR_CHATGPT.zip'), ...
    {'TRAJECTORY_C9_FUSED_WITNESS_25D_AB_RESULT.mat', ...
     'TRAJECTORY_C9_FUSED_WITNESS_25D_AB_RESULT.txt'},root);
catch
end
end

function q=getnum(a,f)
q=NaN;if isfield(a,f)&&isnumeric(a.(f))&&isscalar(a.(f)),q=double(a.(f));end
end

function req=make_request(J0,J1,T)
a=struct('cable_length_m',2,'payload_mass_kg',0.14, ...
 'uav_mass_kg',1.1,'gravity_world_mps2',[0;0;-9.80665], ...
 'thrust_limits_N',[0;20],'minimum_tension_N',0, ...
 'acceleration_guard_mps2',0, ...
 'uav_inertia_kgm2',[0.012;0.013;0.022], ...
 'torque_limits_Nm',[-1 1;-1 1;-1 1]);
rad=struct('uav_m',.3,'cable_m',.01,'payload_m',.2);
geo=struct('max_subdivision_depth',8,'max_node_count',900, ...
 'numerical_guard_m',0,'robust_tube_enabled',false, ...
 'trajectory_phase','f','use_exact_direction_cone_support',true, ...
 'use_native_support_separator',false);
force=struct('max_subdivision_depth',8,'max_node_count',900,'force_guard_N',0);
head=struct('max_subdivision_depth',8,'max_node_count',900, ...
 'horizontal_velocity_guard_mps',0,'w_guard_mps2',0, ...
 'payload_jet_tolerance',zeros(3,10), ...
 'uav_jet_tolerance',zeros(3,8), ...
 'yaw_jet_tolerance',zeros(1,7));
torque=struct('max_subdivision_depth',8,'max_node_count',900, ...
 'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
 'torque_guard_Nm',zeros(3,1),'use_native_whole_torque_kernel',true);
opt=struct('probe_count',5,'max_outer_iterations',2, ...
 'max_projection_sweeps',800,'projection_tolerance_m',1e-8, ...
 'min_separation_m',1e-3, ...
 'enable_degree27_25d_joint_search',1, ...
 'enable_25d_nominal_torque_local_rows',1, ...
 'enable_13d_variable_time_joint_search',0);
req=struct('t0_s',0,'duration_s',T,'flight_interval_s',[0 40], ...
 'start_jets',J0,'end_jets',J1, ...
 'nominal_free',[zeros(1,4);(10:13)*T/23;3*ones(1,4)], ...
 'nominal_free27',[zeros(1,8);10:17;3*ones(1,8)], ...
 'observed',struct([]),'radii',rad,'authority',a, ...
 'geometry_options',geo,'force_options',force, ...
 'heading_options',head,'torque_options',torque, ...
 'nominal_torque_options',torque,'search_options',opt);
end

function n=check_12_shape_prepared(p,g,packed)
kind={'sphere','ellipsoid','box','cylinder','capsule','cone', ...
      'frustum','torus','pyramid','regular_prism', ...
      'polygon_prism','polyhedron'};
Vpy=[.7 .7 -.6;.7 -.7 -.6;-.7 .7 -.6;-.7 -.7 -.6;0 0 .6];
theta=2*pi*(0:6).'/7;
Vring=[.9*cos(theta),.9*sin(theta)];
Vrp=[Vring,-.5*ones(7,1);Vring,.5*ones(7,1)];
Vpo=[-.7 -.1;.1 -.7;.8 -.2;.5 .7;-.6 .5];
Vpr=[Vpo,-.5*ones(5,1);Vpo,.5*ones(5,1)];
Vph=[0 0 .8;.7 0 0;0 .6 0;-.7 0 0;0 -.6 0;0 0 -.8];
D={.6,[.7 .8 .9],[.7 .8 .9],[.6 1.2], ...
 [.6 1.2],[.6 1.2],[.6 .2 1.2],[.6 .2], ...
 [1.4 1.2],[7 .9 1],struct('outline',Vpo,'height',1), ...
 struct('vertices',Vph)};
V={[],[],[],[],[],[],[],[],Vpy,Vrp,Vpr,Vph};
n=0;
for j=1:12
 ang=j*.09;
 Rx=[1 0 0;0 cos(ang) -sin(ang);0 sin(ang) cos(ang)];
 Ry=[cos(ang/2) 0 sin(ang/2);0 1 0;-sin(ang/2) 0 cos(ang/2)];
 Rz=[cos(ang/3) -sin(ang/3) 0;sin(ang/3) cos(ang/3) 0;0 0 1];
 verts=V{j};if isempty(verts),verts=zeros(0,3);end
 S=struct('id',j,'kind',kind{j},'dim',D{j}, ...
     'center',[4;13;3],'R',Rz*Ry*Rx,'local_vertices',verts);
 Z=TRAJECTORY_C9_FUSED_ALLTIME_CORE( ...
     p,27,g,packed,S,'C9_FUSED_V3_GENERAL_SEPARATOR_20261111');
 assert(Z.certified && Z.shape_support_calls>0, ...
     'C9_FUSED_WITNESS_AUDIT:Shape','Native direct 12-shape real-arithmetic proof failed at shape %d: %s',j,Z.status);
 n=n+1;
end
end
