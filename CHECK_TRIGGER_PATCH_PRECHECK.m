function S=CHECK_TRIGGER_PATCH_PRECHECK()
% Pre-flight check: verify exact class tree and required public interfaces.
% Never reads source-world obstacles, live EKF, or a real reference.
S=struct('status','NOT_READY','reason','', ...
  'replanner_file',which('REPLANNING_SYSTEM'), ...
  'trigger_file',which('FUTURE_COLLISION_TRIGGER'), ...
  'same_source_tree',false, ...
  'has_preparation_method',false,'has_status_method',false);
try
    assert(~isempty(S.replanner_file) && ~isempty(S.trigger_file), ...
      'CHECK_TRIGGER_PATCH_PRECHECK:MissingClass', ...
      'Cannot find current replanner and trigger sources on the MATLAB path.');
    replanner_dir=fileparts(S.replanner_file);
    trigger_repl_dir=fileparts(fileparts(S.trigger_file));
    S.same_source_tree=strcmpi(replanner_dir,trigger_repl_dir);
    assert(S.same_source_tree,'CHECK_TRIGGER_PATCH_PRECHECK:ClassTreeMismatch', ...
      'Different REPLANNING_SYSTEM source trees on the MATLAB path.');
    core=FUTURE_COLLISION_TRIGGER(struct('horizon_s',4));
    S.has_preparation_method=ismethod(core,'prepare_shadow_observed_static');
    S.has_status_method=ismethod(core,'shadow_observation_preparation_status');
    assert(S.has_preparation_method && S.has_status_method, ...
      'CHECK_TRIGGER_PATCH_PRECHECK:ClassInterfaceMismatch', ...
      'Production class interface is incomplete.');
    E=core.shadow_observation_preparation_status();
    assert(isstruct(E) && isfield(E,'status') && ...
       isfield(E,'verified_ids') && isfield(E,'outer_ids') && ...
       isfield(E,'pending_count'), ...
       'CHECK_TRIGGER_PATCH_PRECHECK:StatusSchema', ...
       'Shadow status must use the genuine expected schema.');
    S.status='PASS_CLASS_TREE_AND_SHADOW_API__NOT_FLIGHT_SAFETY';
catch ME
    S.reason=[ME.identifier ' | ' ME.message];
end
fid=fopen('TRIGGER_PATCH_PRECHECK_RESULT.txt','w');
if fid>=0
    fprintf(fid,'status=%s\nreason=%s\nreplanner=%s\ntrigger=%s\n', ...
       S.status,S.reason,S.replanner_file,S.trigger_file);
    fprintf(fid,'same_source_tree=%d\nshadow_prepare=%d\nshadow_status=%d\n', ...
       S.same_source_tree,S.has_preparation_method,S.has_status_method);
    fclose(fid);
end
end
