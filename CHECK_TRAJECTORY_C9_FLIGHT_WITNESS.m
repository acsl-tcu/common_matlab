function R = CHECK_TRAJECTORY_C9_FLIGHT_WITNESS(saved_result, logger)
%CHECK_TRAJECTORY_C9_FLIGHT_WITNESS  Offline, source-bound flight evidence.
% USAGE:
%   R = CHECK_TRAJECTORY_C9_FLIGHT_WITNESS();
%   R = CHECK_TRAJECTORY_C9_FLIGHT_WITNESS(previous_R);
%   R = CHECK_TRAJECTORY_C9_FLIGHT_WITNESS(previous_R,logger);
% Default input is the previous recorded HLC audit .mat in common_matlab.
% With raw Sim LOGGER, also audit HLC-CONSUMED payload pL/vL vs the
% ACTUAL reference at every logged Flight sample. No controller, estimator,
% plant, runner, or flight-time code is modified. NO continuous guarantee.
root=fileparts(mfilename('fullpath'));
assert(isfile(fullfile(root,'run_flight_headless.m')), ...
    'C9_FLIGHT_WITNESS:Root', ...
    'Place CHECK at common_matlab root where run_flight_headless.m exists.');
addpath(root,'-begin');
addpath(fullfile(root,'controller'),'-begin');
addpath(fullfile(root,'reference','REPLANNING_SYSTEM', ...
    'TRAJECTORY_GENERATION'),'-begin');
base='TRAJECTORY_C9_FLIGHT_WITNESS_RESULT';
R=struct('status','UNKNOWN_NOT_STARTED','error_id','', ...
    'error_message','','fixture_audit_pass',false, ...
    'tracking_fixture_audit_pass',false, ...
    'source_limits_checked',false,'archived_limits_agree_with_source',false, ...
    'archived_source_path_agrees_with_current',false, ...
    'estimated_payload_mass_range_kg',[NaN NaN], ...
    'hlc_source_file','', ...
    'sampled_actuator_witness',struct(), ...
    'raw_flight_logger_supplied',false, ...
    'sampled_payload_tracking',struct(), ...
    'actual_generated_C9_reference_selected',false, ...
    'C7_C6_all_time_certified',false, ...
    'HLC_tracking_tube_all_time_certified',false, ...
    'HLC_three_torque_all_time_certified',false, ...
    'safe_to_commit',false);
try
    % A true adversarial test, not merely printing the provided data.
    % The test intentionally has yaw-only saturation for four adjacent
    % ticks, one valid tick and an independent archive-count corruption.
    fixture=struct('time_s',[5 5.025 5.05 5.075 5.1], ...
        'logger_index',[202 203 204 205 206], ...
        'flight_records',5,'sample_status',{{'a','b','c','d','e'}}, ...
        'unclamped_input4',zeros(4,5), ...
        'clamped_input4',zeros(4,5), ...
        'preclamp_saturation_count',4,'clamp_mismatch_count',0);
    flow=[0;-1;-1;-1];fhigh=[20;1;1;1];
    fixture.unclamped_input4=repmat([10;0;0;0.1],1,5);
    fixture.unclamped_input4(4,1:4)=[2.04 1.75 1.44 1.12];
    fixture.clamped_input4=max(repmat(flow,1,5), ...
        min(repmat(fhigh,1,5),fixture.unclamped_input4));
    F=TRAJECTORY_C9_HLC_LIMIT_WITNESS(fixture,flow,fhigh);
    broken=fixture;
    broken.preclamp_saturation_count=3;
    B=TRAJECTORY_C9_HLC_LIMIT_WITNESS(broken,flow,fhigh);
    R.fixture_audit_pass= ...
        strcmp(F.status,'REJECT_RECORDED_HLC_INPUT_LIMIT_EXCEEDED')&& ...
        isequal(F.per_channel_violating_samples,[0;0;0;4])&& ...
        F.violating_any_input_samples==4&&F.event_count==1&& ...
        F.events(1).sample_count==4&& ...
        strcmp(B.status,'UNKNOWN_ARCHIVED_AUDIT_AND_RAW_INPUT_DISAGREE');
    assert(R.fixture_audit_pass,'C9_FLIGHT_WITNESS:Fixture', ...
        'Mathematical four-channel event/count adversarial test failed.');
    % Independent, real HLC x-layout tracking fixture. The previous
    % (takeoff) reference has yaw=0 and Flight yaw=pi/2, and the second
    % Flight sample deliberately introduces a 0.2m payload position error.
    base_x=[1;0;0;0;0;0;900;0;0;1;0;1;0;0;0;-1;0;0;0];
    assert(numel(base_x)==19,'C9_FLIGHT_WITNESS:FixtureLayout', ...
        'The actual HLC controller state must have 19 elements.');
    ref=zeros(28,1);ref(3)=1;ref(4)=pi/2;ref(6)=1;
    prev_ref=ref;prev_ref(4)=0;
    ex1=struct('x',base_x);
    ex2=struct('x',base_x);
    ex2.x(8)=ex2.x(8)+0.2;
    r0=struct('state',struct('xd',prev_ref));
    r1=struct('state',struct('xd',ref));
    sample=struct('t',[4.975;5;5.025], ...
        'phase',double(['t';'f';'f']));
    sample.agent=struct('controller',struct('result',{{ex1,ex1,ex2}}), ...
        'reference',struct('result',{{r0,r1,r1}}));
    T0=TRAJECTORY_C9_RECORDED_TRACKING_WITNESS(sample);
    R.tracking_fixture_audit_pass= ...
        strcmp(T0.status,'CHECKED_SAMPLED_HLC_PAYLOAD_TRACKING__NO_TUBE_PROOF')&& ...
        T0.valid_sample_count==2&& ...
        abs(T0.max_observed_payload_position_error_m-0.2)<1e-12&& ...
        abs(T0.adjacent_phase_yaw_difference_rad-pi/2)<1e-12&& ...
        ~T0.safe_to_commit&&~T0.continuous_time_tracking_certified;
    assert(R.tracking_fixture_audit_pass,'C9_FLIGHT_WITNESS:TrackingFixture', ...
        'Observed tracking and phase-boundary fixture failed.');
    broken_sample=sample;
    broken_sample.agent.controller.result{3}.x(1)=[];
    TB=TRAJECTORY_C9_RECORDED_TRACKING_WITNESS(broken_sample);
    assert(TB.invalid_sample_count==1 && ...
        strcmp(TB.status,'UNKNOWN_INCOMPLETE_HLC_CONSUMED_STATE_TRACE'), ...
        'C9_FLIGHT_WITNESS:WrongLayout', ...
        'Old 18-component HLC state must never pass a tracking audit.');
    if nargin<1||isempty(saved_result)
        inputfile=fullfile(root,'TRAJECTORY_C9_REAL_EKF_HLC_TICK_RESULT.mat');
        assert(isfile(inputfile),'C9_FLIGHT_WITNESS:PreviousResult', ...
            'The preceding real HLC tick result MAT is required.');
        prev=load(inputfile,'R');
        assert(isfield(prev,'R'),'C9_FLIGHT_WITNESS:ResultMAT', ...
            'The preceding MAT must contain variable R.');
        previous=prev.R;
    elseif ischar(saved_result)||isstring(saved_result)
        prev=load(char(saved_result),'R');
        assert(isfield(prev,'R'),'C9_FLIGHT_WITNESS:ResultMAT', ...
            'The preceding MAT must contain variable R.');
        previous=prev.R;
    else
        previous=saved_result;
    end
    assert(isstruct(previous)&&isscalar(previous)&& ...
        all(isfield(previous,{'saved_flight_trace', ...
         'source_lower','source_upper'})), ...
        'C9_FLIGHT_WITNESS:PreviousResult', ...
        'Recorded Flight summary and its HLC limits are required.');
    trace=previous.saved_flight_trace;
    [lo,hi,src]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    R.source_limits_checked=true;
    R.hlc_source_file=src;
    R.archived_limits_agree_with_source= ...
        isequal(lo,double(previous.source_lower(:)))&& ...
        isequal(hi,double(previous.source_upper(:)));
    if isfield(previous,'real_HLC_source')
        R.archived_source_path_agrees_with_current= ...
            strcmpi(char(previous.real_HLC_source),src);
    end
    if isfield(trace,'estimated_payload_mass_kg')
        masses=double(trace.estimated_payload_mass_kg(:));
        if ~isempty(masses)&&all(isfinite(masses))&&all(masses>0)
            R.estimated_payload_mass_range_kg=[min(masses) max(masses)];
        end
    end
    % Evaluate the raw recorded inputs even if source identity fails.
    % A changed source means no current-controller compatibility claim.
    R.sampled_actuator_witness= ...
        TRAJECTORY_C9_HLC_LIMIT_WITNESS(trace,lo,hi);
    if nargin>=2 && ~isempty(logger)
        R.raw_flight_logger_supplied=true;
        R.sampled_payload_tracking= ...
            TRAJECTORY_C9_RECORDED_TRACKING_WITNESS(logger);
    end
    if ~R.archived_limits_agree_with_source || ...
            ~R.archived_source_path_agrees_with_current
        R.status='UNKNOWN_ARCHIVED_AND_CURRENT_HLC_AUTHORITY_DIFFER__NO_COMMIT';
    elseif strncmp(R.sampled_actuator_witness.status,'UNKNOWN',7)
        R.status='UNKNOWN_RECORDED_HLC_WITNESS__NO_COMMIT';
    elseif ~isempty(strfind(R.sampled_actuator_witness.status,'REJECT')) %#ok<STREMP>
        R.status='REJECT_ACTUAL_RECORDED_HLC_SATURATION__NO_COMMIT';
    elseif R.raw_flight_logger_supplied&& ...
            strncmp(R.sampled_payload_tracking.status,'UNKNOWN',7)
        R.status='UNKNOWN_RECORDED_HLC_TRACKING_TRACE__NO_COMMIT';
    elseif R.raw_flight_logger_supplied
        R.status='CHECKED_RECORDED_HLC_ACTUATOR_AND_PAYLOAD_TRACKING__NO_PROOF';
    else
        R.status='CHECKED_RECORDED_HLC_ACTUATOR_ONLY__NO_TRACKING_LOG';
    end
catch ME
    R.status='FAIL_C9_FLIGHT_WITNESS_AUDIT';
    R.error_id=ME.identifier;
    R.error_message=ME.message;
end
save(fullfile(root,[base '.mat']),'R');
fid=fopen(fullfile(root,[base '.txt']),'wt');
assert(fid>0,'C9_FLIGHT_WITNESS:Write','Unable to save audit TXT.');
closer=onCleanup(@() fclose(fid));
fprintf(fid,'status=%s\n',R.status);
fprintf(fid,'fixture_audit_pass=%d\n',R.fixture_audit_pass);
fprintf(fid,'tracking_fixture_audit_pass=%d\n',R.tracking_fixture_audit_pass);
fprintf(fid,'hlc_source=%s\n',R.hlc_source_file);
fprintf(fid,'archived_limits_agree_with_source=%d\n', ...
    R.archived_limits_agree_with_source);
fprintf(fid,'archived_source_path_agrees_with_current=%d\n', ...
    R.archived_source_path_agrees_with_current);
fprintf(fid,'estimated_payload_mass_range_kg=%s\n', ...
    mat2str(R.estimated_payload_mass_range_kg,12));
if ~isempty(fieldnames(R.sampled_actuator_witness))
    W=R.sampled_actuator_witness;
    fprintf(fid,'actuator_status=%s\n',W.status);
    fprintf(fid,'flight_samples=%d\n',W.evaluated_sample_count);
    fprintf(fid,'violating_input_samples=%d\n', ...
        W.violating_any_input_samples);
    fprintf(fid,'violating_samples_by_channel_F_Mx_My_Mz=%s\n', ...
        mat2str(W.per_channel_violating_samples.'));
    fprintf(fid,'max_limit_excess_by_channel_F_Mx_My_Mz=%s\n', ...
        mat2str(W.maximum_excess_by_channel.',12));
    fprintf(fid,'raw_input_min_F_Mx_My_Mz=%s\n', ...
        mat2str(W.raw_input_min.',12));
    fprintf(fid,'raw_input_max_F_Mx_My_Mz=%s\n', ...
        mat2str(W.raw_input_max.',12));
    fprintf(fid,'number_sampled_saturation_episodes=%d\n',W.event_count);
    for k=1:W.event_count
        E=W.events(k);
        fprintf(fid,'episode_%d: logger=%d..%d, t=%.12g..%.12g, count=%d, channels=%s\n', ...
            k,E.first_logger_index,E.last_logger_index, ...
            E.first_time_s,E.last_time_s,E.sample_count, ...
            mat2str(E.violating_channels.'));
    end
end
fprintf(fid,'raw_flight_logger_supplied=%d\n',R.raw_flight_logger_supplied);
if ~isempty(fieldnames(R.sampled_payload_tracking))
    T=R.sampled_payload_tracking;
    fprintf(fid,'payload_tracking_status=%s\n',T.status);
    fprintf(fid,'valid_tracking_samples=%d/%d\n', ...
        T.valid_sample_count,T.sample_count);
    fprintf(fid,'max_sampled_payload_position_error_m=%.12g\n', ...
        T.max_observed_payload_position_error_m);
    fprintf(fid,'rms_sampled_payload_position_error_m=%.12g\n', ...
        T.rms_observed_payload_position_error_m);
    fprintf(fid,'max_sampled_payload_velocity_error_mps=%.12g\n', ...
        T.max_observed_payload_velocity_error_mps);
    fprintf(fid,'rms_sampled_payload_velocity_error_mps=%.12g\n', ...
        T.rms_observed_payload_velocity_error_mps);
    fprintf(fid,'adjacent_phase_yaw_ref_difference_rad=%.12g\n', ...
        T.adjacent_phase_yaw_difference_rad);
    fprintf(fid,'sampled_tube_necessary_radius_m=%.12g\n', ...
        T.sampled_payload_error_tube_necessary_radius_m);
end
fprintf(fid,'continuous_HLC_tracking_proven=0\n');
fprintf(fid,'continuous_3_torque_proven=0\n');
fprintf(fid,'safe_to_commit=0\n');
fprintf(fid,'error_id=%s\nerror_message=%s\n', ...
    R.error_id,R.error_message);
clear closer
archive=fullfile(root,[base '_FOR_CHATGPT.zip']);
if isfile(archive),delete(archive);end
zip(archive,{[base '.mat'],[base '.txt']},root);
info=dir(archive);
assert(numel(info)==1&&info.bytes>100, ...
    'C9_FLIGHT_WITNESS:ZIP','Result ZIP was not produced.');
fprintf('[C9 FLIGHT WITNESS] %s\n%s\n',R.status,archive);
end
