function R=CHECK_TRAJECTORY_C9_THREE_TIER_TENSION()
%CHECK_TRAJECTORY_C9_THREE_TIER_TENSION  Pure-math contract audit (no plant).
% Do not interpret fixture PASS as a flight safety COMMIT.
% All generated artifacts saved in common_matlab independently of pwd.
root=fileparts(mfilename('fullpath'));
name='TRAJECTORY_C9_THREE_TIER_TENSION_RESULT';
R=struct('status','FAIL_NOT_STARTED','error_message','', ...
    'nominal_tension_N',NaN,'model_tension_N',NaN, ...
    'physical_tension_N',NaN,'tension_monotonic',false, ...
    'zero_mass_rejected',false, ...
    'degenerate_direction_rejected',false, ...
    'physical_error_missing_rejected',false, ...
    'external_required_tension_rejected',false, ...
    'nominal_corridor',false,'model_corridor',false,'nominal_four_input',false, ...
    'corridor_nominal_w_lower_mps2',NaN, ...
    'projection_lower_nonworsening',false, ...
    'projection_bound_sample_valid',false, ...
    'safe_to_commit',false, ...
    'result_zip_path',fullfile(root,[name '_FOR_CHATGPT.zip']));
try
    module=fullfile(root,'reference','REPLANNING_SYSTEM','TRAJECTORY_GENERATION');
    assert(isfolder(module),'C9_TIER:Layout', ...
        'Place CHECK in the common_matlab root and production sources under reference.');
    addpath(module,'-begin');
    raw=[4.9 5.1;-.5 .5;-.5 .5;-.5 .5];
    ui=TRAJECTORY_C9_HLC_NOMINAL_FOUR_INPUT_GATE([0;-1;-1;-1], ...
        [20;1;1;1],raw);
    R.nominal_four_input=ui.conditional_headroom_all_positive;
    assert(R.nominal_four_input);
    g=9.80665;m=0.2;
    A=TRAJECTORY_C9_TAUT_TENSION_TIERS(g,m,'NOMINAL',[],[],[],0);
    B=TRAJECTORY_C9_TAUT_TENSION_TIERS(g,m,'MODEL_TUBE',0.6,[],[],0);
    C=TRAJECTORY_C9_TAUT_TENSION_TIERS(g,m,'PHYSICAL_ROBUST',0.6,0.3,0.02,0);
    assert(A.strict_tautness_proven_under_assumptions&& ...
        B.strict_tautness_proven_under_assumptions&& ...
        C.strict_tautness_proven_under_assumptions);
    assert(abs(A.tension_lower_N-m*g)<1e-12);
    assert(abs(B.tension_lower_N-m*(g-.6))<1e-12);
    assert(abs(C.tension_lower_N-(m-.02)*(g-.6-.3))<1e-12);
    R.nominal_tension_N=A.tension_lower_N;
    R.model_tension_N=B.tension_lower_N;
    R.physical_tension_N=C.tension_lower_N;
    R.tension_monotonic=A.tension_lower_N>=B.tension_lower_N && ...
        B.tension_lower_N>=C.tension_lower_N;
    bad=TRAJECTORY_C9_TAUT_TENSION_TIERS(g,0,'NOMINAL',[],[],[],0);
    R.zero_mass_rejected=~bad.strict_tautness_proven_under_assumptions;
    bad=TRAJECTORY_C9_TAUT_TENSION_TIERS(g,m,'MODEL_TUBE',g,[],[],0);
    R.degenerate_direction_rejected= ...
        strcmp(bad.status,'UNKNOWN_TAUT_DIRECTION_NOT_PROVEN');
    bad=TRAJECTORY_C9_TAUT_TENSION_TIERS(g,m,'PHYSICAL_ROBUST',0.6,[],[],0);
    R.physical_error_missing_rejected= ...
        strcmp(bad.status,'UNKNOWN_TENSION_TIER_INPUT');
    bad=TRAJECTORY_C9_TAUT_TENSION_TIERS(g,m,'NOMINAL',[],[],[],m*g+1);
    R.external_required_tension_rejected= ...
        strcmp(bad.status,'UNKNOWN_EXTERNAL_TENSION_REQUIREMENT');

    % Reuse the mathematically certified nominal corridor witness fixture.
    H=repmat([0;0;3],1,24);
    leaf=struct('time_interval_s',[0 1], 'map',eye(24), ...
        'q0',[0;0;-1],'guide_cone_padding_m',0, ...
        'uav_normals',[0;0;1],'payload_normals',[0;0;1], ...
        'cable_normals',[0;0;1], ...
        'uav_offsets',4.5,'payload_offsets',2.7,'cable_offsets',2.95);
    corridor=struct('certified',true,'leaves',leaf, ...
        'guide_piece',struct('control_points_m',H,'t0_s',0,'duration_s',1), ...
        'radii',struct('uav_m',.1,'payload_m',.1,'cable_m',.05), ...
        'authority',struct('cable_length_m',2, ...
            'gravity_world_mps2',[0;0;-g]), ...
        'obstacle_ids',11,'ground_applicable',true, ...
        'proof_options',struct('robust_tube_enabled',false, ...
            'use_affine_cable_execution_tube',true));
    p0=struct('status', ...
        'CONDITIONAL_SEPARATE_UAV_CABLE_PAYLOAD_TUBE__EXECUTION_UNPROVEN', ...
        'uav_m',0,'payload_m',0,'cable_m',0, ...
        'nominal_w_lower_mps2',0);
    nominal=TRAJECTORY_C9_HLC_CORRIDOR_TUBE_GATE(corridor,p0);
    p1=p0;p1.uav_m=.25;p1.payload_m=.02;p1.cable_m=.25;
    model=TRAJECTORY_C9_HLC_CORRIDOR_TUBE_GATE(corridor,p1);
    R.nominal_corridor=nominal.conditional_all_body_separated;
    R.model_corridor=model.conditional_all_body_separated;
    R.corridor_nominal_w_lower_mps2=nominal.recomputed_nominal_w_lower_mps2;
    assert(R.nominal_corridor&&R.model_corridor);
    assert(abs(R.corridor_nominal_w_lower_mps2-g)<1e-12);

    % Random convex combinations of Bernstein acceleration controls:
    % projection certificate is a rigorous ALL-TIME convex-hull bound,
    % random samples here only cross-check its implementation algebra.
    rng(314159);
    valid=true;nonworse=true;
    for k=1:2000
        w0=randn(3,1);w0=w0/max(norm(w0),eps);
        W=3*w0+.2*randn(3,22);
        center=mean(W,2);rad=max(sqrt(sum((W-center).^2,1)));
        old=norm(center)-rad;
        n=center/norm(center);projected=min(n.'*W);
        new=max(old,projected);
        weights=rand(22,1);weights=weights/sum(weights);
        valid=valid && norm(W*weights)>=new-1e-12;
        nonworse=nonworse&&new>=old-1e-12;
    end
    R.projection_lower_nonworsening=nonworse;
    R.projection_bound_sample_valid=valid;
    assert(R.nominal_four_input&&R.tension_monotonic&&R.zero_mass_rejected&& ...
        R.degenerate_direction_rejected&&R.physical_error_missing_rejected&& ...
        R.external_required_tension_rejected&&valid&&nonworse);
    R.status='PASS_THREE_TIER_TAUT_TENSION_AND_NOMINAL_CORRIDOR__NOT_FLIGHT_CERT';
catch ME
    R.status='FAIL_THREE_TIER_TENSION_AUDIT';
    R.error_message=[ME.identifier ': ' ME.message];
end
try
    save(fullfile(root,[name '.mat']),'R');
    fid=fopen(fullfile(root,[name '.txt']),'w');
    if fid>=0
        fprintf(fid,'status=%s\nerror=%s\n',R.status,R.error_message);
        fprintf(fid,'nominal=%.16g model_tube=%.16g physical_tube=%.16g\n', ...
            R.nominal_tension_N,R.model_tension_N,R.physical_tension_N);
        fprintf(fid,'nominal_corridor=%d model_corridor=%d w_lower=%.16g\n', ...
            R.nominal_corridor,R.model_corridor,R.corridor_nominal_w_lower_mps2);
        fprintf(fid,'zero_mass_rejected=%d degenerate_rejected=%d physical_missing_rejected=%d\n', ...
            R.zero_mass_rejected,R.degenerate_direction_rejected, ...
            R.physical_error_missing_rejected);
        fprintf(fid,'support_bound_nonworsening=%d support_bound_sample_valid=%d\n', ...
            R.projection_lower_nonworsening,R.projection_bound_sample_valid);
        fprintf(fid,'safe_to_commit=0\n');
        fclose(fid);
    end
    zip(R.result_zip_path,{[name '.mat'],[name '.txt']},root);
catch ME
    R.status=['FAIL_SAVE_' ME.identifier];
end
end
