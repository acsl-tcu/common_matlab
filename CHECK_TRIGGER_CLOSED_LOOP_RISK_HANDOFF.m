function R=CHECK_TRIGGER_CLOSED_LOOP_RISK_HANDOFF()
% Temporary common root audit of conditional risk handoff. Not Flight SAFE.
root=fileparts(mfilename('fullpath'));
R=struct('status','FAIL_CLOSED_LOOP_RISK_HANDOFF','reason','', ...
    'cases',0,'failures',0,'unproved_ids',0, ...
    'flight_safety_certified',false,'wcet_certified',false);
saved_rng=rng;cleanup=onCleanup(@()rng(saved_rng)); %#ok<NASGU>
try
    rng(7002,'twister');
    % End-to-end assembly must retain all sensed/retained IDs even if no
    % rigorous actual x0 / future HLC input enclosure is available.
    for M=[1 3 11]
        K=M+1;ids=7*(1:M)+100;
        S=repmat(struct('id',0,'is_stationary',true),1,M);
        for j=1:M,S(j).id=ids(j);end
        p=zeros(21,K);p(20,:)=1;p(21,:)=2;
        C=struct('ekf_now',struct(), ...
            'error_lower',zeros(24,1),'error_upper',zeros(24,1), ...
            'cable_length_lower_m',2,'cable_length_upper_m',2, ...
            'time_grid_s',(0:K)*.025, ...
            'true_mass_lower_kg',ones(1,K), ...
            'true_mass_upper_kg',ones(1,K), ...
            'other_param_lower',p,'other_param_upper',p, ...
            'held_input_lower',zeros(4,K), ...
            'held_input_upper',zeros(4,K), ...
            'observed_prepared_shapes',S, ...
            'body',struct('r_uav_m',.1,'r_payload_m',.1, ...
                          'r_cable_m',.01));
        A=TRIGGER_CLOSED_LOOP_CONDITIONAL_ASSEMBLY(C);
        assert(isequal(A.observed_ids,ids) && ...
               isequal(A.possible_risk_ids,ids) && ...
               isequal(A.earliest_possible_event.earliest_possible_ids,ids) && ...
               A.earliest_possible_event.first_interval_index==1 && ...
               ~A.safe_to_commit && ...
               ~A.full_4s_continuous_safety_proven, ...
               'CHECK_TRIGGER_HANDOFF:UnknownNotPreserved', ...
               'Unproved physics must not silently clear observed IDs.');
        R.cases=R.cases+1;
        R.unproved_ids=R.unproved_ids+M;
    end
    % Independent oracle for all simultaneous earliest unproved IDs; no
    % fixed number of obstacles or static detection-mask combinations.
    for trial=1:500
        M=randi([1 27]);K=randi([1 31]);
        ids=31+(1:M)*17;
        sep=rand(M,K)>0.2;
        first=find(any(~sep,1),1,'first');
        t=(0:K)*.025;
        A=TRIGGER_FIRST_UNPROVED_INTERVAL(t,ids,sep);
        if isempty(first)
            assert(~A.conditional_replan_required && ...
                   isempty(A.earliest_possible_ids) && ...
                   A.conditional_clear_intervals==K, ...
                   'CHECK_TRIGGER_HANDOFF:ClearWrong');
        else
            expected=ids(~sep(:,first).');
            assert(A.conditional_replan_required && ...
                   isequal(A.earliest_possible_ids,expected) && ...
                   A.first_interval_index==first && ...
                   A.first_possible_ttc_left_s==t(first)-t(1) && ...
                   A.first_possible_ttc_right_s==t(first+1)-t(1) && ...
                   ~A.safe_to_commit, ...
                   'CHECK_TRIGGER_HANDOFF:MultiIDWrong');
        end
        R.cases=R.cases+1;
    end
    R.status='PASS_CONDITIONAL_RISK_HANDOFF__PHYSICAL_PROOF_MISSING';
catch ME
    R.failures=R.failures+1;
    R.reason=[ME.identifier ' | ' ME.message];
end
save(fullfile(root,'TRIGGER_CLOSED_LOOP_RISK_HANDOFF_RESULT.mat'),'R');
f=fopen(fullfile(root,'TRIGGER_CLOSED_LOOP_RISK_HANDOFF_RESULT.txt'),'w');
if f>=0
    fprintf(f,'status=%s\ncases=%d\nfailures=%d\n' ...
        ,R.status,R.cases,R.failures);
    fprintf(f,'unproved_ids=%d\nreason=%s\n', ...
        R.unproved_ids,R.reason);
    fclose(f);
end
end
