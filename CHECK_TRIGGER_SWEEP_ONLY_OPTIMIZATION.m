function R=CHECK_TRIGGER_SWEEP_ONLY_OPTIMIZATION()
% A focused software regression: the swept-hull risk includes every sampled
% straight-cable/body contact, so the redundant sampled oracle cannot
% advance the earliest risk. Does NOT prove true ODE/WCET safety.
root=fileparts(mfilename('fullpath'));
base=fullfile(root,'reference','REPLANNING_SYSTEM');
assert(isfile(fullfile(base,'FUTURE_COLLISION_TRIGGER', ...
    'FUTURE_COLLISION_TRIGGER.m')), ...
    'CHECK_TRIGGER_SWEEP_ONLY_OPTIMIZATION:Location', ...
    'Extract the ZIP directly under common_matlab/.');
addpath(base,fullfile(base,'FUTURE_COLLISION_TRIGGER'), ...
    fullfile(base,'SIMULATED_OBSTACLE_SENSOR'), ...
    fullfile(base,'OBSTACLE_INFORMATION'));
source=fileread(fullfile(base,'FUTURE_COLLISION_TRIGGER','FUTURE_COLLISION_TRIGGER.m'));
assert(contains(source,'no_sample=struct(') && ...
    ~contains(source,'first=TRIGGER_EARLIEST_SAMPLED_CONTACT('), ...
    'CHECK_TRIGGER_SWEEP_ONLY_OPTIMIZATION:Production', ...
    'Swept-only production path not installed.');

% Test a stationary diagonal cable, continuous intersample crossing,
% repeated old ID, new ID and first contact on a later interval.
ru=.02;rl=.02;rc=.005;
t=[0 1 2];
U=[-1 0 1;0 0 0;0 0 0];
L=U-[0 0 0;0 0 0;2 2 2];
s1=fixture(901,[0;0;-1],.04);
s2=fixture(902,[1;0;-1],.04);
s3=fixture(903,[5;0;-1],.04);
cases=0;
for sh={[s1 s2],[s3 s2],[s1 s2 s3]}
    shapes=sh{1};
    for announced={[],901,902}
        ids=announced{1};
        sw=TRIGGER_NOMINAL_SWEPT_INTERVALS(U,L,t,shapes, ...
             ru,rl,rc,ids,[]);
        sampled=TRIGGER_EARLIEST_SAMPLED_CONTACT( ...
             U,L,t,shapes,ru,rl,rc,0, ...
             struct('diagnostic_timing_enabled',false, ...
                    'sampled_block_experiment_enabled',false),ids);
        old=TRIGGER_MERGE_EARLIEST_NOMINAL_RISK(sampled,sw,t);
        blank=struct('first_obstacle_ids',zeros(1,0), ...
            'first_ttc_s',NaN,'first_sample_index',NaN, ...
            'first_components',{{}}, ...
            'new_obstacle_ids',zeros(1,0), ...
            'new_ttc_s',NaN,'new_sample_index',NaN, ...
            'new_components',{{}});
        now=TRIGGER_MERGE_EARLIEST_NOMINAL_RISK(blank,sw,t);
        assert(isequal(old.has_risk,now.has_risk) && ...
            isequaln(old.first.ttc_s,now.first.ttc_s) && ...
            isequal(old.first.ids,now.first.ids) && ...
            isequaln(old.first_new.ttc_s,now.first_new.ttc_s) && ...
            isequal(old.first_new.ids,now.first_new.ids) && ...
            isequal(old.selected.ids,now.selected.ids) && ...
            isequaln(old.selected.ttc_s,now.selected.ttc_s), ...
            'CHECK_TRIGGER_SWEEP_ONLY_OPTIMIZATION:Equivalence', ...
            'A sampled contact advanced the earliest possible sweep risk.');
        cases=cases+1;
    end
end

% The revised production path must still detect, suppress duplicate IDs,
% and re-evaluate after the committed reference has changed.
z=zeros(3,1);
e=struct('p',z,'q',z,'v',z,'w',z,'pL',z-[0;0;2], ...
    'vL',z,'pT',[0;0;1],'wL',z);
o=OBSTACLE_INFORMATION.define(904,'sphere',[1 0 0],.04);
f=struct('time_s',0,'uav_position_ekf_m',z, ...
    'detected_obstacles',o,'detected_ids',904,'detected_count',1);
a=struct('runtime',struct('sample_dt_s',.2,'horizon_s',4, ...
     'r_uav_m',.01,'r_payload_m',.01,'r_cable_m',.005, ...
     'cable_length_m',2), ...
     'payload_mass_kg',1,'reference_at',@(tt)zeros(28,1), ...
     'predictor',@(req)line_prediction(req,1), ...
     'numeric_tolerances',[1e-7;1e-7]);
C=FUTURE_COLLISION_TRIGGER(struct('horizon_s',4));
x=C.evaluate(0,e,f,a);
assert(x.new_event && x.collision_predicted && ...
    ~x.sampled_collision && ~x.sampled_contact_checked && ...
    x.collision_obstacle_id==904 && ...
    abs(x.collision_ttc_s-.8)<1e-9 && ...
    abs(x.collision_time_bracket_s(1)-.8)<1e-9 && ...
    abs(x.collision_time_bracket_s(2)-1)<1e-9, ...
    'CHECK_TRIGGER_SWEEP_ONLY_OPTIMIZATION:Risk','Risk/interval changed.');
y=C.evaluate(0,e,f,a);
assert(~y.new_event && y.duplicate_suppressed, ...
    'CHECK_TRIGGER_SWEEP_ONLY_OPTIMIZATION:Repeat','Repeated ID fired again.');
C.set_committed_plan_revision(uint64(1));
a.predictor=@(req)line_prediction(req,-1);
z2=C.evaluate(0,e,f,a);
assert(z2.prediction_complete && ~z2.collision_risk_predicted && ...
    z2.nominal_interpolant_observed_clear, ...
    'CHECK_TRIGGER_SWEEP_ONLY_OPTIMIZATION:Revision', ...
    'The new committed reference did not re-evaluate clearance.');
cases=cases+3;
R=struct('status','PASS_SWEEP_ONLY_NOMINAL_TRIGGER_REGRESSION', ...
    'cases',cases,'failures',0, ...
    'sampled_oracle_in_flight',false, ...
    'certified_scope','nominal linear interpolant; not true ODE or WCET');
save(fullfile(root,'TRIGGER_SWEEP_ONLY_OPTIMIZATION_RESULT.mat'),'R');
fid=fopen(fullfile(root,'TRIGGER_SWEEP_ONLY_OPTIMIZATION_RESULT.txt'),'w');
assert(fid>0,'CHECK_TRIGGER_SWEEP_ONLY_OPTIMIZATION:Output','Cannot write log.');
c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\ncases=%d failures=%d\n',R.status,R.cases,R.failures);
end

function s=fixture(id,c,r)
s=struct('id',id,'center0',c,'is_stationary',true, ...
    'bounding_radius_m',r,'rotation',eye(3), ...
    'dimensions',r,'type','sphere');
end
function P=line_prediction(req,direction)
t=req.sample_times_s;
u=req.ekf_now.p+direction*[t;zeros(2,numel(t))];
l=u-[zeros(2,numel(t));repmat(req.cable_length_m,1,numel(t))];
P=struct('sample_times_s',t,'uav_m',u,'payload_m',l, ...
    'model_description','SYNTHETIC_ONLY');
end
