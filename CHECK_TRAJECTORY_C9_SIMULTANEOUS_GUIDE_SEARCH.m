function R=CHECK_TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH()
% CHECK_TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH
% Native MATLAB checks for the NEW *candidate search*; not an HLC flight.
% No CHANGE to REPLANNING_SYSTEM/Sim runner/EKF/sensor/trigger/controller.
% A successful CHECK does NOT imply arbitrary collision-start solves or
% torque, yaw C6, tracking, 5 ms, or free-time optimization are finished.
% The independent continuous-time joint proof is the only safety oracle.
% New revision tests POSITIVE avoidance, clearance continuation and the
% exact nonlinear cable-direction Jacobian, not just a safe UNKNOWN.
root=fileparts(mfilename('fullpath'));
mod=fullfile(root,'reference','REPLANNING_SYSTEM');
addpath(fullfile(root,'controller'),'-begin');
[hlc_force_limits,~]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_limits();
addpath(fullfile(mod,'TRAJECTORY_GENERATION'), ...
    fullfile(mod,'OBSTACLE_INFORMATION'),'-begin');
R=struct('status','FAIL_NOT_RUN', ...
    'previous_flight_ground_check_pass',false, ...
    'nominal_safe_independent_proof_pass',false, ...
    'stationary_center_collision_fail_closed',false, ...
    'interior_collision_initial_unproved',false, ...
    'interior_collision_search_exercised',false, ...
    'interior_collision_certified_by_solver',false, ...
    'interior_continuous_proof_status','', ...
    'interior_clearance_expansions',NaN, ...
    'interior_shortening_trials',NaN, ...
    'interior_acceleration_change_energy',NaN, ...
    'interior_position_change_energy',NaN, ...
    'interior_linear_constraints',NaN, ...
    'interior_independent_proof_calls',NaN, ...
    'interior_qp_pivots',NaN, ...
    'interior_joint_qp_status','', ...
    'interior_final_proof_nodes',NaN, ...
    'interior_final_support_calls',NaN, ...
    'interior_independent_proof_ms',NaN, ...
    'interior_search_plane_ms',NaN, ...
    'interior_joint_qp_ms',NaN, ...
    'multi_independent_proof_ms',NaN, ...
    'multi_search_plane_ms',NaN, ...
    'multi_joint_qp_ms',NaN, ...
    'multi_independent_proof_calls',NaN, ...
    'multi_qp_pivots',NaN, ...
    'nonlinear_cable_jacobian_checked',false, ...
    'qp_coordinate_transform_verified',false, ...
    'qp_coordinate_transform_max_error_m',NaN, ...
    'collision_not_relabelled_safe_by_probes',false, ...
    'ground_start_violation_rejected',false, ...
    'ground_endpoint_rejection_status','', ...
    'ground_endpoint_immovable_count',0, ...
    'ground_endpoint_deficit_m',NaN, ...
    'ground_interior_initial_unproved',false, ...
    'ground_interior_search_planes_generated',false, ...
    'ground_interior_no_commit',false, ...
    'ground_interior_search_status','', ...
    'multi_obstacle_both_ids_considered',false, ...
    'rotated_ellipsoid_support_checked',false, ...
    'different_obstacle_orders_no_false_commit',false, ...
    'robust_tube_on_off_exercised',false, ...
    'nonflight_is_excluded',false, ...
    'flight_phase_boundary_guard',false, ...
    'all_generated_candidates_independently_proved',false, ...
    'no_controller_commit',false, ...
    'unchanged_endpoint_jets_if_candidate',false, ...
    'interior_search_elapsed_ms',NaN, ...
    'multi_search_elapsed_ms',NaN, ...
    'benchmark_trials',0,'benchmark_median_ms',NaN, ...
    'benchmark_certified_count',0, ...
    'benchmark_proof_median_ms',NaN, ...
    'benchmark_plane_median_ms',NaN, ...
    'benchmark_qp_median_ms',NaN, ...
    'benchmark_p95_ms',NaN,'benchmark_max_ms',NaN, ...
    'generator_api_preserves_tube_and_no_commit',false, ...
    'multi_obstacle_certified_by_solver',false, ...
    'multi_solver_qp_status','', ...
    'joint_qp_regression_pass',false, ...
    'duration_not_trigger_fixed',false, ...
    'interior_search_status','', 'multi_search_status','', ...
    'error_identifier','','error_message','');
try
    old=fullfile(root,'TRAJECTORY_FLIGHT_GROUND_SPATIAL_RESULT.mat');
    if isfile(old)
        data=load(old,'R');
        R.previous_flight_ground_check_pass= ...
            isfield(data,'R')&&isfield(data.R,'status')&& ...
            strcmp(data.R.status, ...
            'PASS_FLIGHT_ONLY_GROUND_AND_TIME_FREE_SPATIAL_TARGET__HLC_PENDING');
    end
    auth=struct('cable_length_m',2,'payload_mass_kg',0.2, ...
        'uav_mass_kg',1.0,'gravity_world_mps2',[0;0;-9.80665], ...
        'thrust_limits_N',hlc_force_limits,'minimum_tension_N',0, ...
        'acceleration_guard_mps2',0);
    rad=struct('uav_m',0.1,'cable_m',0.02,'payload_m',0.1);
    g=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'numerical_guard_m',0,'robust_tube_enabled',false, ...
        'trajectory_phase','f');
    f=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'force_guard_N',0);
    search=struct('probe_count',13,'max_outer_iterations',4, ...
        'max_projection_sweeps',100, ...
        'projection_tolerance_m',1e-8,'min_separation_m',1e-5);
    % Physically valid hover: load z=3, UAV z=5, no obstacles.
    jets=zeros(3,10);jets(3,1)=3;
    free=repmat([0;0;3],1,4);
    req=struct('t0_s',0,'duration_s',10, ...
        'flight_interval_s',[0 20], ...
        'start_jets',jets,'end_jets',jets,'nominal_free',free, ...
        'observed',struct([]),'radii',rad,'authority',auth, ...
        'geometry_options',g,'force_options',f,'search_options',search);
    safe_req=req;
    safe=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(req);
    R.nominal_safe_independent_proof_pass= ...
        safe.candidate_available&&safe.final_certificate.certified&& ...
        safe.independent_proof_calls==1&& ...
        ~safe.safe_to_commit&&safe.ground_checked&& ...
        safe.integrated_squared_deviation_m2==0;
    assert(R.nominal_safe_independent_proof_pass, ...
        'CHECK_C9_GUIDE:Nominal','Pre-existing safe candidate must retain joint proof.');

    % Input symmetry: hover with a shape exactly at the load position.
    % Avoiding by hard-coded +x/+y/up is prohibited. No authority to pick
    % one orientation => UNKNOWN, never a manufactured safe candidate.
    centered=OBSTACLE_INFORMATION.define(11,'sphere',[0 0 3],0.3);
    req.observed=centered;
    blocked=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(req);
    R.stationary_center_collision_fail_closed= ...
        ~blocked.candidate_available&&~blocked.safe_to_commit&& ...
        ~blocked.initial_certificate.certified&& ...
        strcmp(blocked.status,'UNKNOWN_UNRESOLVED_GEOMETRIC_SYMMETRY');
    assert(R.stationary_center_collision_fail_closed, ...
        'CHECK_C9_GUIDE:Symmetry','Cannot manufacture a direction at symmetry.');

    % Verify the actual QP Cholesky coordinate mapping. This previously
    % contained a transpose bug which was invisible to the old CHECK.
    [R.qp_coordinate_transform_verified, ...
        R.qp_coordinate_transform_max_error_m]= ...
        check_qp_coordinates();
    R.joint_qp_regression_pass=check_joint_qp_solver();
    assert(R.joint_qp_regression_pass, ...
        'CHECK_C9_GUIDE:JointQP', ...
        'Joint QP must preserve satisfied constraints and report impossible pairs.');
    assert(R.qp_coordinate_transform_verified, ...
        'CHECK_C9_GUIDE:Whitening', ...
        'Whitened planes must equal actual physical linearized displacement.');

    % Actual colliding forward LINE is passed to the SAME generator. No
    % collision-specific manually supplied bypass curve or direction.
    v=0.4;
    left=zeros(3,10);left(:,1)=[-2;0;3];left(1,2)=v;
    right=zeros(3,10);right(:,1)=[2;0;3];right(1,2)=v;
    nominal=TRAJECTORY_C9_FLAT_BERNSTEIN.build( ...
        0,10,left,right,repmat([0;0;3],1,4));
    free=nominal.control_points_m(:,11:14);
    req.start_jets=left;req.end_jets=right;req.nominal_free=free;
    req.observed=OBSTACLE_INFORMATION.define(21,'sphere',[0 0.1 3],0.20);
    active=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(req);
    R.interior_collision_initial_unproved= ...
        ~active.initial_certificate.certified;
    R.interior_collision_search_exercised= ...
        active.search_iterations>=1&&active.independent_proof_calls>=1;
    R.interior_search_status=active.status;
    R.interior_search_elapsed_ms=active.elapsed_ms;
    R.interior_collision_certified_by_solver=active.candidate_available&& ...
        active.final_certificate.certified;
    R.interior_continuous_proof_status=active.final_certificate.status;
    R.interior_clearance_expansions=active.certificate_clearance_expansions;
    R.interior_shortening_trials=active.certified_shortening_trials;
    R.interior_acceleration_change_energy= ...
        active.integrated_squared_acceleration_change_m2ps3;
    R.interior_position_change_energy= ...
        active.integrated_squared_deviation_m2;
    R.interior_linear_constraints=active.linear_constraints_generated;
    R.interior_independent_proof_calls=active.independent_proof_calls;
    R.interior_qp_pivots=active.projection_sweeps;
    R.interior_joint_qp_status=active.joint_qp_status;
    R.interior_final_proof_nodes=active.final_certificate.checked_node_count;
    R.interior_final_support_calls=active.final_certificate.shape_support_calls;
    R.interior_independent_proof_ms=active.independent_proof_time_total_ms;
    R.interior_search_plane_ms=active.plane_construction_time_total_ms;
    R.interior_joint_qp_ms=active.joint_qp_time_total_ms;
    R.collision_not_relabelled_safe_by_probes= ...
        active.initial_certificate.certified==false&& ...
        active.final_certificate.certified==active.candidate_available;
    assert(R.interior_collision_certified_by_solver&& ...
        active.independent_proof_calls>=2&& ...
        isfinite(R.interior_acceleration_change_energy)&& ...
        isfinite(R.interior_position_change_energy)&& ...
        R.collision_not_relabelled_safe_by_probes, ...
        'CHECK_C9_GUIDE:PositiveCollisionAvoidance', ...
        ['The collision-start guide must obtain a strictly certified ' ...
         'full-time solution, not merely pass fail-closed gates.']);
    % Perturb one interior free control and compare the exact nonlinear
    % finite-difference cable center Jacobian to the analytic q derivative.
    R.nonlinear_cable_jacobian_checked=check_cable_jacobian(nominal,auth); 
    assert(R.nonlinear_cable_jacobian_checked, ...
        'CHECK_C9_GUIDE:CableJacobian', ...
        'Exact first-order cable-direction derivative did not agree.');
    R.duration_not_trigger_fixed=active.duration_s==10&& ...
        isempty(active.rejoin_time_s);
    assert(R.interior_collision_initial_unproved&& ...
        R.interior_collision_search_exercised, ...
        'CHECK_C9_GUIDE:CollisionStart', ...
        'The colliding input MUST enter the simultaneous C9 search.');

    % An already-in-ground endpoint is physically immutable under the
    % fixed 0..9 endpoint jets. Search MUST retain the ground in Flight,
    % never silently reclassify it as a finite/sensed obstacle.
    ground_case=req;
    ground_case.observed=struct([]);
    low=zeros(3,10);low(3,1)=0.05;
    ground_case.start_jets=low;ground_case.end_jets=low;
    ground_case.nominal_free=repmat([0;0;0.05],1,4);
    forbidden=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(ground_case);
    R.ground_endpoint_rejection_status=forbidden.status;
    R.ground_endpoint_immovable_count= ...
        forbidden.ground_immovable_violation_count;
    R.ground_endpoint_deficit_m= ...
        forbidden.ground_immovable_max_deficit_m;
    % A fixed endpoint has zero sensitivity to the 4 free controls. Its
    % violated ground inequality is REJECTED BEFORE it can be added as an
    % ordinary movable QP plane. Therefore ground_search_planes==0 is
    % expected here, NOT evidence that Flight ground was omitted.
    R.ground_start_violation_rejected= ...
        ~forbidden.candidate_available&&~forbidden.safe_to_commit&& ...
        forbidden.ground_checked&& ...
        ~forbidden.initial_certificate.certified&& ...
        strcmp(forbidden.status, ...
            'UNKNOWN_UNMOVABLE_ENDPOINT_OR_ZERO_FREE_BASIS')&& ...
        forbidden.ground_immovable_violation_count>=1&& ...
        forbidden.ground_immovable_max_deficit_m>0;
    % Separate regression: the same Flight ground is also part of the
    % ACTUAL joint QP when the fixed endpoint is clear but the trajectory
    % interior intersects z<=0. No shape/phase special case is introduced.
    ground_interior=ground_case;
    up=zeros(3,10);up(3,1)=0.3;
    ground_interior.start_jets=up;
    ground_interior.end_jets=up;
    ground_interior.nominal_free=repmat([0;0;-0.5],1,4);
    interior_ground=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(ground_interior);
    R.ground_interior_search_status=interior_ground.status;
    R.ground_interior_initial_unproved= ...
        ~interior_ground.initial_certificate.certified;
    R.ground_interior_search_planes_generated= ...
        interior_ground.ground_search_planes>0&& ...
        interior_ground.ground_checked&& ...
        strcmp(interior_ground.trajectory_phase,'f');
    R.ground_interior_no_commit=~interior_ground.safe_to_commit&& ...
        (~interior_ground.candidate_available|| ...
         interior_ground.final_certificate.certified);

    % Two near shapes (sphere and arbitrary SO(3) ellipsoid), 12 common
    % free variables. Reordering does not enable an unsafe HLC command.
    theta=0.38;phi=-0.29;
    Rz=[cos(theta) -sin(theta) 0;sin(theta) cos(theta) 0;0 0 1];
    Ry=[cos(phi) 0 sin(phi);0 1 0;-sin(phi) 0 cos(phi)];
    o2=OBSTACLE_INFORMATION.define(24,'ellipsoid', ...
        [0.55 -0.15 3],[0.32 0.18 0.47], ...
        'rotation',Rz*Ry);
    req.observed=[req.observed,o2];
    multi=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(req);
    R.multi_search_elapsed_ms=multi.elapsed_ms;
    R.multi_search_status=multi.status;
    R.multi_obstacle_certified_by_solver= ...
        multi.candidate_available&&multi.final_certificate.certified;
    R.multi_solver_qp_status=multi.joint_qp_status;
    R.multi_independent_proof_ms=multi.independent_proof_time_total_ms;
    R.multi_search_plane_ms=multi.plane_construction_time_total_ms;
    R.multi_joint_qp_ms=multi.joint_qp_time_total_ms;
    R.multi_independent_proof_calls=multi.independent_proof_calls;
    R.multi_qp_pivots=multi.projection_sweeps;
    R.multi_obstacle_both_ids_considered= ...
        isequal(multi.considered_obstacle_ids,[21 24]);
    S=TRAJECTORY_OBSTACLE_SUPPORT.prepare(req.observed);
    n=[1;2;3];n=n/norm(n);
    support1=TRAJECTORY_OBSTACLE_SUPPORT.value(S(2),n);
    expected=n.'*o2.position+norm( ...
        double(o2.geometry.dimensions(:)).*(o2.rotation.'*n));
    R.rotated_ellipsoid_support_checked=abs(support1-expected)<= ...
        64*eps(max(1,abs(expected)));
    rev=req;rev.observed=fliplr(req.observed);
    reversed=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(rev);
    R.different_obstacle_orders_no_false_commit= ...
        isequal(reversed.considered_obstacle_ids,[24 21])&& ...
        ~multi.safe_to_commit&&~reversed.safe_to_commit;

    robust=req;robust.geometry_options.robust_tube_enabled=true;
    robust.geometry_options.uncertainty_bounds_m=struct( ...
        'uav_m',0.03,'cable_m',0.02,'payload_m',0.04);
    tube=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(robust);
    R.robust_tube_on_off_exercised= ...
        ~tube.safe_to_commit&&tube.ground_checked&& ...
        isequal(tube.considered_obstacle_ids,[21 24]);
    outside=req;outside.geometry_options.trajectory_phase='l';
    other=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(outside);
    boundary=req;boundary.flight_interval_s=[0 5];
    clipped=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(boundary);
    R.flight_phase_boundary_guard= ...
        ~clipped.candidate_available&&~clipped.safe_to_commit&& ...
        strcmp(clipped.status, ...
        'UNKNOWN_CANDIDATE_CROSSES_NONFLIGHT_BOUNDARY');
    R.nonflight_is_excluded=~other.candidate_available&& ...
        ~other.safe_to_commit&&~other.ground_checked&& ...
        strcmp(other.status,'UNKNOWN_NOT_A_FLIGHT_PIECE');

    results={safe,blocked,active,multi,reversed,tube,other,clipped,interior_ground};
    R.all_generated_candidates_independently_proved=true;
    R.unchanged_endpoint_jets_if_candidate=true;
    R.no_controller_commit=true;
    for k=1:numel(results)
        x=results{k};
        R.no_controller_commit=R.no_controller_commit&&~x.safe_to_commit;
        if x.candidate_available
            R.all_generated_candidates_independently_proved= ...
                R.all_generated_candidates_independently_proved&& ...
                x.final_certificate.certified&& ...
                x.independent_proof_calls>=1;
            J0=TRAJECTORY_C9_FLAT_BERNSTEIN.evaluate( ...
                x.candidate_piece,x.candidate_piece.t0_s);
            J1=TRAJECTORY_C9_FLAT_BERNSTEIN.evaluate( ...
                x.candidate_piece,x.candidate_piece.t0_s+ ...
                x.candidate_piece.duration_s);
            if k==1
                exp0=jets;exp1=jets;
            elseif k==9
                exp0=up;exp1=up;
            else
                exp0=left;exp1=right;
            end
            R.unchanged_endpoint_jets_if_candidate= ...
                R.unchanged_endpoint_jets_if_candidate&& ...
                isequal(J0,exp0)&&isequal(J1,exp1);
        end
    end
    % Exercise the actual generator API instead of asserting an undefined
    % field. A mismatch in the instance robust-tube flag MUST throw;
    % neither generator API nor guide proof can commit to HLC.
    generator=TRAJECTORY_GENERATOR(struct( ...
        'ROBUST_TUBE_ENABLED',false, ...
        'FAILURE_BACKUP_ENABLED',true));
    via_api=generator.search_c9_simultaneous_guide(safe_req);
    invalid_api_req=safe_req;
    invalid_api_req.geometry_options.robust_tube_enabled=true;
    mismatch_rejected=false;
    try
        generator.search_c9_simultaneous_guide(invalid_api_req);
    catch ME
        mismatch_rejected=strcmp(ME.identifier,'TRAJECTORY_GENERATOR:TubeFlag');
    end
    commit_rejected=false;
    try
        generator.commit();
    catch ME
        commit_rejected=strcmp(ME.identifier, ...
            'TRAJECTORY_GENERATOR:CommitNotCertified');
    end
    current_generator=generator.get_status();
    R.generator_api_preserves_tube_and_no_commit= ...
        via_api.candidate_available&&via_api.final_certificate.certified&& ...
        ~via_api.safe_to_commit&&mismatch_rejected&&commit_rejected&& ...
        current_generator.plan_revision==0&& ...
        ~current_generator.robust_tube_enabled;
    % Raw full-pipeline cost is reported, not assumed to meet 5 ms.
    % This is a repeatable synthetic MATLAB benchmark, NOT an HLC runtime.
    timing=zeros(1,7);proof_t=zeros(1,7);plane_t=zeros(1,7);qp_t=zeros(1,7);
    count_certified=0;
    for i=1:numel(timing)
        bm=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(req);
        timing(i)=bm.elapsed_ms;
        proof_t(i)=bm.independent_proof_time_total_ms;
        plane_t(i)=bm.plane_construction_time_total_ms;
        qp_t(i)=bm.joint_qp_time_total_ms;
        count_certified=count_certified+double(bm.candidate_available&& ...
            bm.final_certificate.certified);
        assert(~bm.safe_to_commit, 'CHECK_C9_GUIDE:Benchmark', ...
            'Benchmark must never authorize controller output.');
    end
    sorted=sort(timing);
    R.benchmark_trials=numel(timing);
    R.benchmark_certified_count=count_certified;
    R.benchmark_proof_median_ms=median(proof_t);
    R.benchmark_plane_median_ms=median(plane_t);
    R.benchmark_qp_median_ms=median(qp_t);
    R.benchmark_median_ms=median(timing);
    R.benchmark_p95_ms=sorted(ceil(0.95*numel(timing)));
    R.benchmark_max_ms=max(timing);
    assert(R.all_generated_candidates_independently_proved&& ...
        R.no_controller_commit&&R.unchanged_endpoint_jets_if_candidate&& ...
        R.robust_tube_on_off_exercised&&R.nonflight_is_excluded&& ...
        R.duration_not_trigger_fixed&&R.flight_phase_boundary_guard&& ...
        R.generator_api_preserves_tube_and_no_commit&& ...
        R.interior_collision_certified_by_solver&& ...
        R.nonlinear_cable_jacobian_checked&& ...
        R.qp_coordinate_transform_verified&& ...
        R.ground_start_violation_rejected&& ...
        R.ground_interior_initial_unproved&& ...
        R.ground_interior_search_planes_generated&& ...
        R.ground_interior_no_commit&& ...
        R.multi_obstacle_both_ids_considered&& ...
        R.rotated_ellipsoid_support_checked&& ...
        R.different_obstacle_orders_no_false_commit, ...
        'CHECK_C9_GUIDE:Proof','At least one joint proof, ground, multi-geometry or generator invariant failed. See saved R fields.');
    if R.multi_obstacle_certified_by_solver
        R.status='PASS_C9_SINGLE_AND_MULTI_CERTIFIED_GUIDES__HLC_TORQUE_PENDING';
    else
        R.status='PASS_C9_SINGLE_CERTIFIED__MULTI_SAFETY_UNKNOWN__HLC_TORQUE_PENDING';
    end
catch ME
    R.status='FAIL_C9_SIMULTANEOUS_SEARCH';
    R.error_identifier=ME.identifier;
    R.error_message=ME.message;
    write_result(root,R);
    rethrow(ME)
end
write_result(root,R);
end

function write_result(root,R)
name='TRAJECTORY_C9_SIMULTANEOUS_GUIDE_RESULT';
save(fullfile(root,[name '.mat']),'R');
fid=fopen(fullfile(root,[name '.txt']),'wt');
if fid<0,error('CHECK_C9_GUIDE:IO','Could not write result TXT.');end
cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',R.status);
fields=fieldnames(R);
for k=1:numel(fields)
    key=fields{k};if strcmp(key,'status'),continue;end
    val=R.(key);
    if (islogical(val)||isnumeric(val))&&isscalar(val)
        if islogical(val),fmt='%d';else,fmt='%.8g';end
        fprintf(fid,['%s=' fmt '\n'],key,val);
    elseif ischar(val)&&~isempty(val)
        fprintf(fid,'%s=%s\n',key,val);
    end
end
clear cleanup
try
    zip(fullfile(root,[name '_FOR_CHATGPT.zip']), ...
        {[name '.mat'],[name '.txt']},root);
catch ME
    warning('CHECK_C9_GUIDE:ResultZIP', ...
        'MAT/TXT were saved but the result ZIP failed: %s',ME.message);
end
end

function [passed,maximum_error]=check_qp_coordinates()
% Independent algebraic identity test for the 4-free-control Cholesky map.
% The historical mistake was grad/U' rather than grad/U. Test 3-D
% arbitrary non-symmetric gradients and perturbations, not an x/y axis.
n=23; idx=10:13; G=zeros(4,4);
for i=1:4
    for j=1:4
        for a=0:2
            for b=0:2
                ii=idx(i)-a;jj=idx(j)-b;nn=n-2;
                if ii<0||jj<0||ii>nn||jj>nn,continue;end
                c1=gammaln(nn+1)-gammaln(ii+1)-gammaln(nn-ii+1);
                c2=gammaln(nn+1)-gammaln(jj+1)-gammaln(nn-jj+1);
                integral=exp(c1+c2+gammaln(ii+jj+1)+ ...
                    gammaln(2*nn-ii-jj+1)-gammaln(2*nn+2));
                G(i,j)=G(i,j)+(-1)^(a+b)*nchoosek(2,a)* ...
                    nchoosek(2,b)*integral;
            end
        end
    end
end
G=(n*(n-1))^2*0.5*(G+G.');
U=chol(G,'upper');
% Non-axis-aligned values prevent an accidental symmetry from passing.
grad=[0.53 -0.91 0.22 1.01; -0.43 0.13 0.77 -0.62; ...
    0.34 0.25 -1.11 0.47];
Delta=[0.81 -0.09 0.28 0.12; -0.17 0.67 -0.71 0.14; ...
    0.23 -0.48 0.61 0.05];
X=Delta*U.';
physical=sum(sum(grad.*Delta));
transformed=sum(sum((grad/U).*X));
maximum_error=abs(physical-transformed);
passed=isfinite(maximum_error)&& ...
    maximum_error<=2e-11*max(1,abs(physical));
end

function passed=check_cable_jacobian(piece,authority)
% This test is INDEPENDENT of the production make_local_planes() routine.
% It checks first-order sensitivity of the true taut load geometry.
T=double(piece.duration_s);u=0.37;
B=bernstein_vector_for_check(23,u);
B2=bernstein_vector_for_check(21,u);
j=2;eps0=1e-6;lam=0.61;
h=B(10+j);
a=(23*22/T^2)*(B2(8+j)-2*B2(9+j)+B2(10+j));
P=double(piece.control_points_m);
g=double(authority.gravity_world_mps2(:));L=double(authority.cable_length_m);
w=g-(23*22/T^2)*diff(P,2,2)*B2;
q=w/norm(w);sw=norm(w);
normal=[0.21;-0.59;0.47];normal=normal/norm(normal);
variable_direction=[0.43;0.70;-0.18];
analytic=normal.'*(variable_direction*h+ ...
    lam*L/sw*(variable_direction-q*(q.'*variable_direction))*a);
Qp=P;Qm=P;
Qp(:,10+j)=Qp(:,10+j)+eps0*variable_direction;
Qm(:,10+j)=Qm(:,10+j)-eps0*variable_direction;
pplus=Qp*B;pminus=Qm*B;
wp=g-(23*22/T^2)*diff(Qp,2,2)*B2;
wm=g-(23*22/T^2)*diff(Qm,2,2)*B2;
plus=pplus-lam*L*wp/norm(wp);
minus=pminus-lam*L*wm/norm(wm);
numeric=normal.'*(plus-minus)/(2*eps0);
passed=isfinite(analytic)&&isfinite(numeric)&& ...
    abs(analytic-numeric)<=2e-7*max(1,abs(analytic));
end

function b=bernstein_vector_for_check(n,u)
b=zeros(n+1,1);b(1)=(1-u)^n;
for k=1:n
    b(k+1)=b(k)*(n-k+1)/k*u/(1-u);
end
end

function passed=check_joint_qp_solver()
% A single QP must preserve initially satisfied, subsequently BINDING
% planes, including obstacles that are not initially penetrated.
A=zeros(12,4);
A(1,1)=1;A(1,2)=1;A(2,3)=1;A(1,4)=-1;
b=[1;0.5;2;-1.5];
[x,p]=TRAJECTORY_C9_JOINT_PROJECTION(A,b,100,1e-10);
known=p.solved&&norm(x-[1;2;zeros(10,1)],inf)<1e-8&& ...
    max(b-A.'*x)<=1e-10;
% Initially satisfied -x>=-0.5 becomes ACTIVE after x+y>=2.
% Optimal projection analytically: (x,y)=(0.5,1.5).
A2=zeros(12,2);A2(1,1)=1;A2(2,1)=1;A2(1,2)=-1;
b2=[2;-0.5];
[y,q]=TRAJECTORY_C9_JOINT_PROJECTION(A2,b2,100,1e-10);
held=q.solved&&norm(y(1:2)-[0.5;1.5],inf)<1e-8&& ...
    max(b2-A2.'*y)<=1e-10;
% Infeasible facing constraints cannot be mislabeled feasible.
A3=zeros(12,2);A3(1,:)=[1,-1];b3=[1;1];
[~,r]=TRAJECTORY_C9_JOINT_PROJECTION(A3,b3,100,1e-10);
passed=known&&held&&~r.solved&& ...
    strcmp(r.status,'UNKNOWN_QP_INFEASIBLE_LINEARIZATION');
end
