function R=CHECK_TRIGGER_EXACT_TIME_ANYTIME_THEOREM()
% Temporary root-level offline proof-obligation audit. No Flight run.
% This audit checks exact binary64 coverage, sign-correct endpoint
% propagation, arbitrary-switching universal saturation, and rejects
% uncertainty/observation omissions. An audit PASS is NOT physical proof.
root=fileparts(mfilename('fullpath'));
R=struct('status','FAIL_TIME_ANYTIME_THEOREM','reason','', ...
    'cases',0,'failures',0,'dyadic_exact_cases',0, ...
    'rounded_four_short_rejected',false, ...
    'rounded_four_long_accepted',false, ...
    'endpoint_interval_checked',false, ...
    'anytime_source_pinned',false, ...
    'missing_physics_rejected',false, ...
    'physical_safety_proven',false,'safe_to_commit',false);
try
    % Exactly four seconds, exact IEEE endpoint numbers.
    A=TRIGGER_EXACT_BINARY64_TIME_SPAN(0,4);
    assert(A.valid && A.exact_ge_4s && A.roundoff_error_s==0 && ...
        A.lower_s<=4 && A.upper_s>=4);
    R.cases=R.cases+1;
    % An exact duration of 4-2^-52 ROUNDS UP to binary64 4.
    % A test using only (t_end-t0)>=4 erroneously accepts it.
    short=TRIGGER_EXACT_BINARY64_TIME_SPAN(2^-52,4);
    assert(short.valid && short.nominal_s==4 && ...
        short.roundoff_error_s<0 && ~short.exact_ge_4s && ...
        short.lower_s<4 && short.upper_s>=4);
    R.rounded_four_short_rejected=true;R.cases=R.cases+1;
    % Opposite signed remainder: true duration >4 but rounds to 4.
    long=TRIGGER_EXACT_BINARY64_TIME_SPAN(-2^-52,4);
    assert(long.valid && long.nominal_s==4 && ...
        long.roundoff_error_s>0 && long.exact_ge_4s && ...
        long.lower_s<=4 && long.upper_s>4);
    R.rounded_four_long_accepted=true;R.cases=R.cases+1;
    % Check dyadic exact values with subtraction in a regime where exact
    % arithmetic is representable. No tolerance comparisons are needed.
    for k=1:1024
        a=double(randi([-1000 1000]))/16;
        b=a+double(randi([1 1000]))/16;
        T=TRIGGER_EXACT_BINARY64_TIME_SPAN(a,b);
        assert(T.valid && T.roundoff_error_s==0 && ...
            T.lower_s<=b-a && T.upper_s>=b-a && ...
            (T.exact_ge_4s==((b-a)>=4)));
        R.dyadic_exact_cases=R.dyadic_exact_cases+1;
        R.cases=R.cases+1;
    end
    % Numeric signs matter at an endpoint! For f=+1 on a true duration
    % [hminus,hplus], the next-state LOWER bound is hminus, not hplus.
    % Likewise for negative f, the next-state UPPER bound is -hminus.
    p=TRIGGER_OUTWARD_INTERVAL(short.lower_s,short.upper_s);
    vp=TRIGGER_OUTWARD_INTERVAL(1,1);
    vn=TRIGGER_OUTWARD_INTERVAL(-1,-1);
    a=p.*vp;b=p.*vn;
    assert(a.lo<=short.lower_s && a.hi>=short.upper_s && ...
        b.lo<=-short.upper_s && b.hi>=-short.lower_s && ...
        a.lo<short.upper_s && b.hi>-short.upper_s);
    R.endpoint_interval_checked=true;R.cases=R.cases+1;
    % HLC source bound is independent of future switching/grid edges.
    grid=[0 0.013 0.137 1.89 4];
    H=TRIGGER_ORIGINAL_HLC_HOLD_ENVELOPE(grid);
    assert(H.conditional_saturated_hold && ...
        H.universal_input_valid_on_arbitrary_partition && ...
        ~H.future_switching_instants_required && ...
        isequal(H.lower,repmat([0;-1;-1;-1],1,4)) && ...
        isequal(H.upper,repmat([20;1;1;1],1,4)) && ...
        ~H.safe_to_commit, ...
        'CHECK_TRIGGER_EXACT_TIME_ANYTIME_THEOREM:HLCSource', ...
        'Byte-pinned original HLC/MODEL_CLASS or universal input contract mismatch: %s',H.reason);
    R.anytime_source_pinned=true;R.cases=R.cases+1;
    % Reject a horizon whose rounded duration appears to equal four.
    D=struct('observation_provenance','ACTUAL_SENSOR_HISTORY_ONLY', ...
        'observed_prepared_shapes',struct('id',77), ...
        'time_grid_s',[2^-52 4]);
    C=TRIGGER_CLOSED_LOOP_FROM_SOURCE_LIMITS(D);
    assert(strcmp(C.status,'UNKNOWN_INCOMPLETE_FOUR_SECOND_HORIZON') && ...
        isequal(C.possible_risk_ids,77) && ~C.safe_to_commit, ...
        'CHECK_TRIGGER_EXACT_TIME_ANYTIME_THEOREM:Horizon', ...
        'Rounded-but-actually-short four-second horizon was accepted.');
    R.cases=R.cases+1;
    D.time_grid_s=[0 4];
    C=TRIGGER_CLOSED_LOOP_FROM_SOURCE_LIMITS(D);
    assert(~strcmp(C.status,'UNKNOWN_INCOMPLETE_FOUR_SECOND_HORIZON') && ...
        ~C.safe_to_commit && ~C.full_physical_4s_safety_proven, ...
        'CHECK_TRIGGER_EXACT_TIME_ANYTIME_THEOREM:NoPhysics', ...
        'Missing actual EKF/physics input incorrectly granted full safety.');
    R.missing_physics_rejected=true;R.cases=R.cases+1;
    % Check the REAL 24-state interval RHS/endpoint semantics at a very
    % short interval where the physical time uncertainty is testable.
    x=zeros(24,1);x(3)=2;x(7)=1;x(19:21)=[0;0;-1];
    p21=zeros(21,1);p21(1)=1;
    p21(6:8)=[0.05;0.05;0.08];
    p21(9)=9.80665;p21(20)=0.5;p21(21)=2;
    u=[14.709975;0;0;0];
    D=struct('h_s',0.0001,'h_lower_s',0.00005, ...
        'x0_lower',x,'x0_upper',x, ...
        'tube_lower',x-0.01,'tube_upper',x+0.01, ...
        'u_lower',u,'u_upper',u, ...
        'param_lower',p21,'param_upper',p21);
    V=TRIGGER_ORIGINAL_PLANT_PICARD_STEP(D);
    assert(isfield(V,'rhs')&&isstruct(V.rhs)&& ...
        V.rhs.outward_elementary_operations, ...
        'CHECK_TRIGGER_EXACT_TIME_ANYTIME_THEOREM:RHS', ...
        'Original 24-state outward RHS cannot be evaluated: %s',V.reason);
    d0=TRIGGER_OUTWARD_INTERVAL( ...
        V.rhs.rhs_lower(1),V.rhs.rhs_upper(1));
    expected=TRIGGER_OUTWARD_INTERVAL(x(1),x(1)) + ...
        TRIGGER_OUTWARD_INTERVAL(D.h_lower_s,D.h_s).*d0;
    assert(V.endpoint_lower(1)==expected.lo && ...
        V.endpoint_upper(1)==expected.hi && ...
        V.endpoint_lower(1)<V.endpoint_upper(1), ...
        'CHECK_TRIGGER_EXACT_TIME_ANYTIME_THEOREM:Endpoint', ...
        'Original physical Picard endpoint did not use FULL interval duration.');
    R.cases=R.cases+1;
    R.status='PASS_BINARY64_4S_AND_ANYTIME_INCLUSION__PHYSICAL_INITIAL_SET_UNPROVEN';
catch ME
    R.failures=R.failures+1;
    R.reason=[ME.identifier ' | ' ME.message];
end
save(fullfile(root,'TRIGGER_EXACT_TIME_ANYTIME_THEOREM_RESULT.mat'),'R');
f=fopen(fullfile(root,'TRIGGER_EXACT_TIME_ANYTIME_THEOREM_RESULT.txt'),'w');
if f>=0
    fprintf(f,'status=%s\ncases=%d\nfailures=%d\n', ...
        R.status,R.cases,R.failures);
    fprintf(f,'rounded_short_rejected=%d\nrounded_long_accepted=%d\n', ...
        R.rounded_four_short_rejected,R.rounded_four_long_accepted);
    fprintf(f,'endpoint_interval_checked=%d\nanytime_source_pinned=%d\n', ...
        R.endpoint_interval_checked,R.anytime_source_pinned);
    fprintf(f,'reason=%s\n',R.reason);fclose(f);
end
end
