function R=CHECK_TRAJECTORY_C9_25D_JOINT_NOMINAL()
% Research CHECK ONLY. Store all outputs directly under common_matlab/.
% Validates actual 25D tangent, nominal torque tangent, and a full
% integrated degree27 C9 nominal certificate. Does NOT prove B/HLC,
% 15-scene coverage, or 5-7ms real-time capability.
root=fileparts(mfilename('fullpath'));
R=struct('status','FAIL_C9_25D_JOINT_NOMINAL', ...
    'error_message','','degree27_preflight_status','NOT_RUN', ...
    'fullbody_25d_fd_error',NaN,'torque_25d_fd_error',NaN, ...
    'no_obstacle_nominal_pass',false,'two_obstacle_nominal_pass',false, ...
    'integrated_search_status','NOT_RUN', ...
    'integrated_pipeline_status','NOT_RUN', ...
    'integrated_total_ms',NaN, ...
    'integration_torque_evidence_reused',false, ...
    'integration_heading_evidence_reused',false, ...
    'degree23_to_27_elevation_max_error',NaN, ...
    'experiment_collision_search_status','NOT_RUN', ...
    'experiment_collision_qp_attempts',0, ...
    'experiment_collision_last_qp_status','NOT_RUN', ...
    'experiment_collision_failure_reason','NOT_RUN', ...
    'experiment_collision_optional_leaf_skips',0, ...
    'experiment_collision_optional_torque_skips',0, ...
    'experiment_collision_candidate_safe_to_commit',false, ...
    'safe_to_commit',false, ...
    'proven_HLC_B',false, ...
    'metric_gauss_gram_relative_error',NaN, ...
    'metric_qr_reconstruction_error',NaN, ...
    'metric_qr_min_diagonal',NaN, ...
    'nominal_chain_repeat_ms',NaN(1,5), ...
    'nominal_chain_median_ms',NaN, ...
    'nominal_chain_p95_ms',NaN, ...
    'nominal_chain_max_ms',NaN, ...
    'collision_qp_ready',false, ...
    'collision_stress_certified',false, ...
    'native_25d_preflight_status','NOT_RUN', ...
    'native_25d_torque_parity_error',NaN, ...
    'native_stress_completed_pairs',0, ...
    'native_stress_baseline_ms',NaN(1,5), ...
    'native_stress_native_ms',NaN(1,5), ...
    'native_stress_baseline_median_ms',NaN, ...
    'native_stress_native_median_ms',NaN, ...
    'native_stress_baseline_p95_ms',NaN, ...
    'native_stress_native_p95_ms',NaN, ...
    'native_stress_baseline_max_ms',NaN, ...
    'native_stress_native_max_ms',NaN, ...
    'native_25d_actual_kernel_calls',0);
try
    N=TRAJECTORY_C9_TORQUE_WHOLE_27_PREFLIGHT(false);
    R.degree27_preflight_status=N.status;
    NB=TRAJECTORY_C9_25D_TORQUE_BATCH_PREFLIGHT(false);
    R.native_25d_preflight_status=NB.status;
    assert(NB.ready, ...
        'The explicit 25D batch-torque MEX needs preflight build.');
    assert(N.ready,'The degree27 full-time torque MEX must be preflight-ready.');
    T=27;speed=1;
    J0=zeros(3,10);J1=zeros(3,10);
    J0(:,1)=[0;0;3];J1(:,1)=[0;T*speed;3];
    J0(:,2)=[0;speed;0];J1(:,2)=[0;speed;0];
    P23=[zeros(1,24);(0:23)*T*speed/23;3*ones(1,24)];
    free23=P23(:,11:14);
    obs=[OBSTACLE_INFORMATION.define(701,'sphere',[8,5,5],0.5), ...
        OBSTACLE_INFORMATION.define(702,'ellipsoid',[-8,12,5], ...
            [0.7,1.1,0.8],'euler_deg',[13,29,41])];
    a=struct('cable_length_m',2,'payload_mass_kg',0.14, ...
        'uav_mass_kg',1.1,'gravity_world_mps2',[0;0;-9.80665], ...
        'thrust_limits_N',[0;20], ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0, ...
        'uav_inertia_kgm2',[0.012;0.013;0.022], ...
        'torque_limits_Nm',[-1 1;-1 1;-1 1]);
    radius=struct('uav_m',0.3,'cable_m',0.01,'payload_m',0.2);
    geo=struct('max_subdivision_depth',8,'max_node_count',900, ...
        'numerical_guard_m',0,'robust_tube_enabled',false, ...
        'trajectory_phase','f','use_exact_direction_cone_support',true, ...
        'use_native_support_separator',false);
    force=struct('max_subdivision_depth',8,'max_node_count',900, ...
        'force_guard_N',0);
    heading=struct('max_subdivision_depth',8,'max_node_count',900, ...
        'horizontal_velocity_guard_mps',0,'w_guard_mps2',0, ...
        'payload_jet_tolerance',zeros(3,10), ...
        'uav_jet_tolerance',zeros(3,8), ...
        'yaw_jet_tolerance',zeros(1,7));
    torque=struct('max_subdivision_depth',8,'max_node_count',900, ...
        'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
        'torque_guard_Nm',zeros(3,1), ...
        'use_native_whole_torque_kernel',true);
    opt=struct('probe_count',5,'max_outer_iterations',2, ...
        'max_projection_sweeps',800, ...
        'projection_tolerance_m',1e-8,'min_separation_m',1e-3, ...
        'enable_degree27_25d_joint_search',1, ...
        'enable_25d_nominal_torque_local_rows',1, ...
        'enable_13d_variable_time_joint_search',0);
    req=struct('t0_s',0,'duration_s',T, ...
        'flight_interval_s',[0 40], ...
        'start_jets',J0,'end_jets',J1,'nominal_free',free23, ...
        'nominal_free27',[zeros(1,8);(10:17);3*ones(1,8)], ...
        'observed',obs,'radii',radius,'authority',a, ...
        'geometry_options',geo,'force_options',force, ...
        'heading_options',heading,'torque_options',torque, ...
        'nominal_torque_options',torque,'search_options',opt);
    % Test analytic 25D geometry tangents at a non-endpoint phase.
    old23=TRAJECTORY_C9_FLAT_BERNSTEIN.build(0,T,J0,J1,free23);
    P=old23.control_points_m;
    for deg=23:26
        Q=zeros(3,deg+2);Q(:,1)=P(:,1);Q(:,end)=P(:,end);
        for k=1:deg
            Q(:,k+1)=(k/(deg+1))*P(:,k)+ ...
                (1-k/(deg+1))*P(:,k+1);
        end
        P=Q;
    end
    F=[zeros(1,8);(10:17);3*ones(1,8)];u=0.37;
    Pexact=[zeros(1,28);(0:27);3*ones(1,28)];
    R.degree23_to_27_elevation_max_error=max(abs(P(:)-Pexact(:)));

    S=TRAJECTORY_C9_25D_FULLBODY_TANGENT( ...
        0,T,J0,J1,F,u,a.gravity_world_mps2,a.cable_length_m);
    assert(startsWith(S.status,'VALID_LOCAL_C9_25D_TANGENT'), ...
        '25D geometry tangent could not be constructed');
    Jp=S.payload_J_fixed_phase(:,:,1);
    Ju=S.uav_J_fixed_phase(:,:,1);
    max_error=0;
    for k=1:25
        plus=F;minus=F;Tp=T;Tm=T;
        h=1e-5;
        if k==25
            h=1e-4;Tp=T+h;Tm=T-h;
        else
            idx=ceil(k/3);axis=k-3*(idx-1);
            plus(axis,idx)=plus(axis,idx)+h;
            minus(axis,idx)=minus(axis,idx)-h;
        end
        A=TRAJECTORY_C9_25D_FULLBODY_TANGENT( ...
            0,Tp,J0,J1,plus,u,a.gravity_world_mps2,a.cable_length_m);
        B=TRAJECTORY_C9_25D_FULLBODY_TANGENT( ...
            0,Tm,J0,J1,minus,u,a.gravity_world_mps2,a.cable_length_m);
        dp=(A.payload_m(:,1)-B.payload_m(:,1))/(2*h);
        du=(A.uav_m(:,1)-B.uav_m(:,1))/(2*h);
        max_error=max([max_error,norm(dp-Jp(:,k))/(1+norm(dp)), ...
            norm(du-Ju(:,k))/(1+norm(du))]);
    end
    % Verify the exact degree-50 acceleration metric against the older
    % analytical Bernstein integral using the SAME tangent. Numerical
    % factorization is NOT a directed-rounded safety certificate.
    % The acceleration Jacobian is structurally sparse. The 24 physical
    % free coordinates influence only their own axis. Missing partials
    % are exact ZEROS; NaNs here previously stopped the whole audit before
    % any QP attempt (UNKNOWN_25D_METRIC_INVALID_JACOBIAN_OR_DURATION).
    assert(isequal(size(S.acceleration_control_J),[3 26 25]) && ...
        all(isfinite(S.acceleration_control_J(:))), ...
        '25D acceleration tensor must be finite, 3x26x25.');
    for cc=1:24
        aa=mod(cc-1,3)+1;
        others=setdiff(1:3,aa);
        assert(all(S.acceleration_control_J(others,:,cc)==0,'all'), ...
            '25D acceleration cross-axis partials must be exactly zero.');
    end
    M=TRAJECTORY_C9_25D_EXACT_ACCELERATION_QR( ...
        S.acceleration_control_J,T);
    assert(M.valid,M.status);
    G=TRAJECTORY_C9_13D_STATIC_GRAM(25,true);
    Href=zeros(25);
    for aa=1:3
        CC=reshape(S.acceleration_control_J(aa,:,:),26,25);
        Href=Href+T*(CC.'*G*CC);
    end
    Href=(Href+Href.')/2;
    R.metric_gauss_gram_relative_error= ...
        norm(M.H-Href,'fro')/max(1,norm(Href,'fro'));
    R.metric_qr_reconstruction_error=M.factorization_residual;
    R.metric_qr_min_diagonal=min(abs(diag(M.U)));
    assert(R.metric_gauss_gram_relative_error<1e-9 && ...
        R.metric_qr_reconstruction_error<1e-12 && ...
        R.metric_qr_min_diagonal>0, ...
        'The degree-27 exact acceleration QR metric failed parity.');
    R.fullbody_25d_fd_error=max_error;
    assert(max_error<5e-6,'25D body tangent mismatched finite differences.');
    % Compare all 25 torque tangent columns to an independent pointwise
    % nominal torque evaluator; both require NONDEGENERATE heading.
    piece=TRAJECTORY_C9_FLAT_BERNSTEIN.build27(0,T,J0,J1,F);
    Z=TRAJECTORY_C9_TORQUE_FORWARD_JACOBIAN_25D( ...
        piece,a,torque,u);
    assert(all(Z.valid),Z.status);
    max_tau=0;
    for k=1:25
        plus=F;minus=F;Tp=T;Tm=T;
        h=2e-5;
        if k==25
            h=1e-3;Tp=T+h;Tm=T-h;
        else
            idx=ceil(k/3);axis=k-3*(idx-1);
            plus(axis,idx)=plus(axis,idx)+h;
            minus(axis,idx)=minus(axis,idx)-h;
        end
        Ap=TRAJECTORY_C9_FLAT_BERNSTEIN.build27(0,Tp,J0,J1,plus);
        Am=TRAJECTORY_C9_FLAT_BERNSTEIN.build27(0,Tm,J0,J1,minus);
        vp=TRAJECTORY_C9_TORQUE_POINT_EVALUATE( ...
            Ap,a,torque,u*Tp);
        vm=TRAJECTORY_C9_TORQUE_POINT_EVALUATE( ...
            Am,a,torque,u*Tm);
        assert(all(vp.valid)&&all(vm.valid), ...
            'Independent finite-difference torque point evaluation invalid.');
        fd=(vp.torque_Nm(:,1)-vm.torque_Nm(:,1))/(2*h);
        analytic=Z.gradient_Nm_per_physical(:,k,1);
        max_tau=max(max_tau,norm(fd-analytic)/(1+norm(fd)));
    end
    % Same exact polynomial jets / live physics, two independent engines.
    % MEX computes pointwise local 25D sensitivities ONLY.
    native_options=torque;
    native_options.use_native_25d_torque_batch_kernel=1;
    compare_phases=[0,0.15,0.37,0.63,0.85,1];
    Zmat=TRAJECTORY_C9_TORQUE_FORWARD_JACOBIAN_25D( ...
        piece,a,torque,compare_phases);
    Zmex=TRAJECTORY_C9_TORQUE_FORWARD_JACOBIAN_25D( ...
        piece,a,native_options,compare_phases);
    assert(all(Zmat.valid)&&all(Zmex.valid)&& ...
        Zmex.native_executed, ...
        ['Native/MATLAB25D tangent not simultaneously valid: ' ...
         Zmat.status ' / ' Zmex.status]);
    R.native_25d_torque_parity_error=max([ ...
        max(abs(Zmat.torque_Nm(:)-Zmex.torque_Nm(:))), ...
        max(abs(Zmat.gradient_Nm_per_physical(:)- ...
                Zmex.gradient_Nm_per_physical(:)))]);
    assert(R.native_25d_torque_parity_error<1e-8, ...
        '25D native torque Jacobian differs from MATLAB on actual piece.');
    R.torque_25d_fd_error=max_tau;
    assert(max_tau<1e-4,'25D nominal torque tangent mismatched.');
    % Two independent integration calls: empty scene and two distant
    % observed shapes. Neither is claimed to cover the 15-case suite.
    req_clear=req;
    req_clear.observed=obs([]);
    clear_result=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(req_clear);
    R.no_obstacle_nominal_pass=clear_result.nominal_model_complete;
    assert(R.no_obstacle_nominal_pass, ...
        ['Degree27 nominal no-obstacle chain did not pass: ' ...
        clear_result.status]);
    result=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(req);
    R.integrated_search_status=result.search_status;
    R.integrated_pipeline_status=result.status;
    R.integrated_total_ms=result.total_elapsed_ms;
    R.two_obstacle_nominal_pass=result.nominal_model_complete&& ...
        result.obstacle_count==2&& ...
        isfield(result,'candidate_piece')&& ...
        isequal(size(result.candidate_piece.control_points_m),[3 28]);
    R.integration_torque_evidence_reused= ...
        result.nominal_torque_reused_from_same_search;
    R.integration_heading_evidence_reused= ...
        result.heading_reused_from_same_search;
    assert(R.two_obstacle_nominal_pass, ...
        ['The degree27 integrated nominal 25D route did not certify ' ...
        'the known clear fixture: ' result.status]);
    assert(R.integration_heading_evidence_reused, ...
        'The authenticated same-candidate C7/yaw proof was recomputed.');
    assert(R.integration_torque_evidence_reused, ...
        'The authenticated same-candidate 27D torque proof was recomputed.');
    assert(~result.safe_to_commit&&~result.actual_HLC_tracking_proven, ...
        'Nominal-only certificate must not authorize Flight execution.');
    % Five complete nominal-chain calls, not an isolated kernel benchmark.
    for rep=1:5
        Zrep=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(req);
        R.nominal_chain_repeat_ms(rep)=Zrep.total_elapsed_ms;
        assert(Zrep.nominal_model_complete&&~Zrep.safe_to_commit, ...
            'Repeat nominal certificate must not regress or authorize Flight.');
    end
    sorted_ms=sort(R.nominal_chain_repeat_ms);
    R.nominal_chain_median_ms=median(sorted_ms);
    R.nominal_chain_p95_ms=interp1(1:5,sorted_ms,4.8,'linear');
    R.nominal_chain_max_ms=sorted_ms(end);
    % Collision stress: test single-QP invocation and do not require a
    % PASS. Physical infeasibility or unresolved full-time proof is UNKNOWN.
    req.observed=OBSTACLE_INFORMATION.define(801,'sphere',[0.22,13,3],0.8);
    search=TRAJECTORY_C9_SIMULTANEOUS_GUIDE_SEARCH(req);
    R.experiment_collision_search_status=search.status;
    if isfield(search,'duration_25d_qp_count')
        R.experiment_collision_qp_attempts=search.duration_25d_qp_count;
    end
    R.experiment_collision_candidate_safe_to_commit=search.safe_to_commit;
    R.collision_qp_ready=R.experiment_collision_qp_attempts>0;
    R.collision_stress_certified=search.candidate_available && ...
        startsWith(search.status,'CONDITIONAL_C9_25D_DEGREE27_NOMINAL_FULLTIME');
    if isfield(search,'duration_25d_last_qp_construction_status')
        R.experiment_collision_last_qp_status= ...
            search.duration_25d_last_qp_construction_status;
    end
    if isfield(search,'failure_reason')
        R.experiment_collision_failure_reason=search.failure_reason;
    end
    if isfield(search,'duration_25d_optional_leaf_skips')
        R.experiment_collision_optional_leaf_skips= ...
            search.duration_25d_optional_leaf_skips;
    end
    if isfield(search,'duration_25d_optional_torque_skips')
        R.experiment_collision_optional_torque_skips= ...
            search.duration_25d_optional_torque_skips;
    end
    % Five paired WHOLE INTEGRATED collision-stress executions, including
    % the independent full-time oracle, local QP and torque if reached.
    % Do not mistake a skipped kernel for a measured MEX speedup.
    native_req=req;
    native_req.torque_options=native_options;
    for rep=1:5
        RB=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(req);
        RN=TRAJECTORY_C9_INTEGRATED_NOMINAL_PIPELINE(native_req);
        R.native_stress_baseline_ms(rep)=RB.total_elapsed_ms;
        R.native_stress_native_ms(rep)=RN.total_elapsed_ms;
        assert(~RB.safe_to_commit && ~RN.safe_to_commit, ...
            'The nominal-only integration must never authorize execution.');
        assert(isequal(RB.nominal_model_complete, ...
                RN.nominal_model_complete), ...
            '25D native torque caused a nominal-certificate regression.');
        if isfield(RN.search_result,'duration_25d_native_torque_calls')
            R.native_25d_actual_kernel_calls= ...
                R.native_25d_actual_kernel_calls+ ...
                RN.search_result.duration_25d_native_torque_calls;
        end
        R.native_stress_completed_pairs=rep;
    end
    v=sort(R.native_stress_baseline_ms);
    R.native_stress_baseline_median_ms=median(v);
    R.native_stress_baseline_p95_ms=interp1(1:5,v,4.8,'linear');
    R.native_stress_baseline_max_ms=v(end);
    v=sort(R.native_stress_native_ms);
    R.native_stress_native_median_ms=median(v);
    R.native_stress_native_p95_ms=interp1(1:5,v,4.8,'linear');
    R.native_stress_native_max_ms=v(end);
    assert(~search.safe_to_commit, ...
        'Research solver is forbidden from authorizing a Flight command.');
    if R.collision_stress_certified
        R.status='PASS_25D_COLLISION_STRESS_NOMINAL_ONLY__B_HLC_PENDING';
    elseif R.collision_qp_ready
        R.status='PASS_25D_NOMINAL_AND_QP_STARTED__COLLISION_CERTIFICATION_UNKNOWN';
    else
        R.status='PASS_25D_NOMINAL_ONLY__COLLISION_QP_NOT_STARTED';
    end
catch ME
    R.error_message=getReport(ME,'extended','hyperlinks','off');
end
% Always write results under common_matlab, independent of pwd.
matfile=fullfile(root,'TRAJECTORY_C9_25D_JOINT_NOMINAL_RESULT.mat');
txtfile=fullfile(root,'TRAJECTORY_C9_25D_JOINT_NOMINAL_RESULT.txt');
zipfile=fullfile(root,'TRAJECTORY_C9_25D_JOINT_NOMINAL_RESULT_FOR_CHATGPT.zip');
save(matfile,'R');
fid=fopen(txtfile,'w');
if fid>=0
    fprintf(fid,'status=%s\nerror_message=%s\n',R.status,R.error_message);
    fprintf(fid,'degree27_preflight=%s\n',R.degree27_preflight_status);
    fprintf(fid,'geometry_25d_fd_error=%.17g\n',R.fullbody_25d_fd_error);
    fprintf(fid,'torque_25d_fd_error=%.17g\n',R.torque_25d_fd_error);
    fprintf(fid,'no_obstacle_nominal=%d two_obstacle_nominal=%d\n', ...
        R.no_obstacle_nominal_pass,R.two_obstacle_nominal_pass);
    fprintf(fid,'degree23_to_27_elevation_max_error=%.17g\n', ...
        R.degree23_to_27_elevation_max_error);
    fprintf(fid,'search=%s pipeline=%s\n', ...
        R.integrated_search_status,R.integrated_pipeline_status);
    fprintf(fid,'nominal_torque_reused=%d heading_reused=%d\n', ...
        R.integration_torque_evidence_reused, ...
        R.integration_heading_evidence_reused);
    fprintf(fid,'integrated_total_ms=%.9g\n',R.integrated_total_ms);
    fprintf(fid,'collision_stress=%s QPs=%d\n', ...
        R.experiment_collision_search_status, ...
        R.experiment_collision_qp_attempts);
    fprintf(fid,'native_preflight=%s native_torque_parity=%.17g\n', ...
        R.native_25d_preflight_status,R.native_25d_torque_parity_error);
    fprintf(fid,'native_stress_pairs=%d native_actual_calls=%d\n', ...
        R.native_stress_completed_pairs,R.native_25d_actual_kernel_calls);
    fprintf(fid,'native_stress_base_median=%.9g p95=%.9g max=%.9g\n', ...
        R.native_stress_baseline_median_ms, ...
        R.native_stress_baseline_p95_ms,R.native_stress_baseline_max_ms);
    fprintf(fid,'native_stress_mex_median=%.9g p95=%.9g max=%.9g\n', ...
        R.native_stress_native_median_ms, ...
        R.native_stress_native_p95_ms,R.native_stress_native_max_ms);
    fprintf(fid,'metric_gauss_gram_relative_error=%.17g qr_residual=%.17g\n', ...
        R.metric_gauss_gram_relative_error,R.metric_qr_reconstruction_error);
    fprintf(fid,'nominal_chain_5_median=%.9g p95=%.9g max=%.9g\n', ...
        R.nominal_chain_median_ms,R.nominal_chain_p95_ms,R.nominal_chain_max_ms);
    fprintf(fid,'collision_qp_ready=%d collision_stress_certified=%d\n', ...
        R.collision_qp_ready,R.collision_stress_certified);
    fprintf(fid,'collision_last_qp_status=%s\n',R.experiment_collision_last_qp_status);
    fprintf(fid,'collision_failure_reason=%s\n',R.experiment_collision_failure_reason);
    fprintf(fid,'optional_leaf_skips=%d optional_torque_skips=%d\n', ...
        R.experiment_collision_optional_leaf_skips, ...
        R.experiment_collision_optional_torque_skips);
    fprintf(fid,'actual_HLC_B_proven=%d safe_to_commit=%d\n', ...
        R.proven_HLC_B,R.safe_to_commit);
    fclose(fid);
end
try
    if exist(zipfile,'file'),delete(zipfile);end
    zip(zipfile,{'TRAJECTORY_C9_25D_JOINT_NOMINAL_RESULT.mat', ...
        'TRAJECTORY_C9_25D_JOINT_NOMINAL_RESULT.txt'},root);
catch
end
end
