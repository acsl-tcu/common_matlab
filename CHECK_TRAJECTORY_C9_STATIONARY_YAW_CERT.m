function R=CHECK_TRAJECTORY_C9_STATIONARY_YAW_CERT()
% CHECK-only. Whole-piece rest proof, yaw hold and nominal torque identity.
% Does NOT prove actual HLC tracking, floating-point outward rounding,
% autonomous yaw choice, or an isolated zero-speed heading extension.
root=fileparts(mfilename('fullpath'));
name='TRAJECTORY_C9_STATIONARY_YAW_CERT_RESULT';
R=struct('status','FAIL_STATIONARY_YAW_CERT', ...
    'stage','INIT','error_identifier','','error_message','', ...
    'error_stack',{{}},'stationary_heading','NOT_RUN', ...
    'stationary_nominal_torque','NOT_RUN', ...
    'ordinary_heading','NOT_RUN', ...
    'no_anchor_status','NOT_RUN', ...
    'isolated_zero_status','NOT_RUN', ...
    'stationary_join_status','NOT_RUN', ...
    'nominal_torque_bounds_Nm',NaN(3,2), ...
    'normal_reference_yaw_jets',NaN(1,7), ...
    'reference_hold_max_error',NaN, ...
    'heading_elapsed_ms',NaN,'torque_elapsed_ms',NaN, ...
    'safe_to_commit',false,'actual_HLC_tracking_proven',false, ...
    'scope','REAL_ARITHMETIC_IDEAL_TAUT_ONLY__NO_HLC_OR_ROUNDING', ...
    'zip_path',fullfile(root,[name '_FOR_CHATGPT.zip']));
try
    addpath(fullfile(root,'controller'),fullfile(root,'model'),'-begin');
    addpath(fullfile(root,'reference','REPLANNING_SYSTEM', ...
        'TRAJECTORY_GENERATION'),'-begin');
    R.stage='LIVE_PARAMETER_FIXTURE';
    [lo,hi]=TRAJECTORY_C9_HLC_FORCE_AUTHORITY.source_input_limits();
    P=DRONE_PARAM_SUSPENDED_LOAD("DIATONE");
    P.set("loadmass",0.14); % CHECK fixture; never a production default.
    d=double(P.get(["mass","jx","jy","jz", ...
        "gravity","cableL","loadmass"]));
    d=d(:);lo=double(lo(:));hi=double(hi(:));
    assert(numel(d)==7&&all(isfinite(d))&&all(d>0)&& ...
        numel(lo)==4&&numel(hi)==4&&all(hi>lo), ...
        'C9_STATIONARY:Authority','Fixture authority unavailable.');
    A=struct('uav_mass_kg',d(1),'payload_mass_kg',d(7), ...
        'cable_length_m',d(6),'uav_inertia_kgm2',d(2:4), ...
        'gravity_world_mps2',[0;0;-d(5)], ...
        'thrust_limits_N',[lo(1),hi(1)], ...
        'torque_limits_Nm',[lo(2:4),hi(2:4)], ...
        'minimum_tension_N',0,'acceleration_guard_mps2',0);
    heading=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'horizontal_velocity_guard_mps',0,'w_guard_mps2',0, ...
        'payload_jet_tolerance',zeros(3,10), ...
        'uav_jet_tolerance',zeros(3,8), ...
        'yaw_jet_tolerance',zeros(1,7), ...
        'stationary_yaw_anchor_rad',0.73);
    torque=struct('max_subdivision_depth',6,'max_node_count',127, ...
        'minimum_force_z_N',0,'minimum_planar_speed_mps',0, ...
        'torque_guard_Nm',zeros(3,1), ...
        'stationary_yaw_anchor_rad',heading.stationary_yaw_anchor_rad);
    J=zeros(3,10);J(:,1)=[0;0;3];
    piece=TRAJECTORY_C9_FLAT_BERNSTEIN.build(0,2,J,J, ...
        repmat([0;0;3],1,4));
    R.stage='WHOLE_TIME_STATIONARY_HEADING';
    H=TRAJECTORY_C9_UAV_C7_YAW_C6_AUDIT(piece,A,heading);
    R.stationary_heading=H.status;R.heading_elapsed_ms=H.elapsed_ms;
    assert(H.certified&&H.certified_stationary_yaw_hold&& ...
        H.all_time_yaw_C6_defined_proven&& ...
        ~H.continuous_horizontal_heading_proven&& ...
        isequal(H.start_yaw_jets,[heading.stationary_yaw_anchor_rad zeros(1,6)])&& ...
        isequal(H.end_yaw_jets,H.start_yaw_jets)&& ...
        ~H.safe_to_commit, 'C9_STATIONARY:Hold', ...
        'Strict whole-time stationary C6 reference not proved.');
    R.stage='REFERENCES_AT_THREE_TIMES';
    samples=[0,0.5,2];err=0;
    for k=1:numel(samples)
        [ref,yj]=TRAJECTORY_TAUT_FLATNESS.reference28( ...
            piece,samples(k),A,heading.stationary_yaw_anchor_rad);
        err=max(err,max(abs(yj-[heading.stationary_yaw_anchor_rad zeros(1,6)])));
        assert(isequal(size(ref),[28,1])&&all(isfinite(ref)), ...
            'C9_STATIONARY:Reference','Held yaw reference is malformed.');
    end
    R.reference_hold_max_error=err;
    assert(err==0,'C9_STATIONARY:ReferenceHold','Yaw did not remain constant.');
    R.stage='WHOLE_TIME_STATIONARY_NOMINAL_TORQUE';
    Q=TRAJECTORY_C9_NOMINAL_TORQUE_INTERVAL(piece,A,torque);
    R.stationary_nominal_torque=Q.status;
    R.torque_elapsed_ms=Q.elapsed_ms;
    R.nominal_torque_bounds_Nm=Q.torque_bounds_Nm;
    assert(Q.conditional_nominal_all_time_torque_proven && ...
        Q.certified_exact_stationary_yaw_hold&& ...
        isequal(Q.torque_bounds_Nm,zeros(3,2)) && ...
        ~Q.safe_to_commit && ~Q.actual_HLC_tracking_proven && ...
        ~Q.numerically_directed_rounding_proven, ...
        'C9_STATIONARY:Torque','Exact stationary nominal torque was not proven.');
    R.stage='EXPLICIT_YAW_ANCHOR_REQUIRED';
    h2=rmfield(heading,'stationary_yaw_anchor_rad');
    Z=TRAJECTORY_C9_UAV_C7_YAW_C6_AUDIT(piece,A,h2);
    R.no_anchor_status=Z.status;
    assert(~Z.certified&&strcmp(Z.status,'UNKNOWN_STATIONARY_YAW_ANCHOR_REQUIRED'), ...
        'C9_STATIONARY:Anchor','Yaw must never be invented.');
    R.stage='STATIONARY_TO_STATIONARY_C7_YAW_C6_JOIN';
    next=piece;next.t0_s=piece.t0_s+piece.duration_s;
    hjoin=heading;hjoin.previous_piece=piece;
    S=TRAJECTORY_C9_UAV_C7_YAW_C6_AUDIT(next,A,hjoin);
    R.stationary_join_status=S.status;
    assert(S.certified&&S.strict_C7_uav_join&&S.strict_C6_yaw_join, ...
        'C9_STATIONARY:Join','Stationary-to-stationary C7/C6 join not proved.');
    R.stage='MOVING_HEADING_NO_REGRESSION';
    left=J;right=J;left(1,1)=-2;right(1,1)=2;
    left(1,2)=0.5;right(1,2)=0.5;
    free=[-2+(10:13)*4/23;zeros(1,4);3*ones(1,4)];
    moving=TRAJECTORY_C9_FLAT_BERNSTEIN.build(4,8,left,right,free);
    Mh=TRAJECTORY_C9_UAV_C7_YAW_C6_AUDIT(moving,A,h2);
    R.ordinary_heading=Mh.status;
    assert(Mh.certified&&Mh.continuous_horizontal_heading_proven&& ...
        ~Mh.certified_stationary_yaw_hold&&~Mh.safe_to_commit, ...
        'C9_STATIONARY:MovingRegression', ...
        'Ordinary heading certificate changed.');
    R.stage='ISOLATED_ZERO_MUST_NOT_BE_HELD';
    jets=zeros(3,8);jets(1,3)=2; % vx=0 but its first derivative !=0
    thrown=false;
    try
        TRAJECTORY_TAUT_FLATNESS.yaw_from_uav_jets(jets,0.1);
    catch ME
        thrown=strcmp(ME.identifier, ...
            'TRAJECTORY_TAUT_FLATNESS:HeadingZeroNotStationaryJet');
    end
    assert(thrown,'C9_STATIONARY:Reversal', ...
        'Isolated zero must not be treated as stationary yaw hold.');
    R.isolated_zero_status='UNKNOWN_REJECT_ISOLATED_ZERO';
    R.status='PASS_EXACT_STATIONARY_YAW_AND_NOMINAL_TORQUE__HLC_UNCERTIFIED';
catch ME
    R.error_identifier=ME.identifier;R.error_message=ME.message;
    R.error_stack=arrayfun(@(x)sprintf('%s:%d',x.name,x.line), ...
        ME.stack,'UniformOutput',false);
end
save(fullfile(root,[name '.mat']),'R');
fid=fopen(fullfile(root,[name '.txt']),'w');
if fid>=0
    fprintf(fid,'status=%s stage=%s error=%s %s\n', ...
        R.status,R.stage,R.error_identifier,R.error_message);
    for k=1:numel(R.error_stack)
        fprintf(fid,'stack=%s\n',R.error_stack{k});
    end
    fprintf(fid,'stationary_heading=%s, heading_ms=%.6f\n', ...
        R.stationary_heading,R.heading_elapsed_ms);
    fprintf(fid,'stationary_nominal_torque=%s, torque_ms=%.6f\n', ...
        R.stationary_nominal_torque,R.torque_elapsed_ms);
    fprintf(fid,'torque_bounds=%s\n',mat2str(R.nominal_torque_bounds_Nm));
    fprintf(fid,'reference_hold_error=%.12g\n',R.reference_hold_max_error);
    fprintf(fid,'no_anchor=%s isolated_zero=%s stationary_join=%s moving=%s\n', ...
        R.no_anchor_status,R.isolated_zero_status, ...
        R.stationary_join_status,R.ordinary_heading);
    fprintf(fid,'safe_to_commit=%d actual_hlc_tracking_proven=%d\n', ...
        R.safe_to_commit,R.actual_HLC_tracking_proven);
    fclose(fid);
end
zip(R.zip_path,{[name '.mat'],[name '.txt']},root);
fprintf('[C9 STATIONARY YAW CERT] %s\n',R.status);
end
